#!/usr/bin/env python3
"""PreToolUse на запуск помощника: скил о работе с агентами обязан быть позван.

СЛУЧАЙ (Ф3 ревизии харнеса, §5, замер 28.09.2026). По журналу `skills.jsonl`
(241 запись) два скила не были позваны НИ РАЗУ за всё время его существования:
`работа-субагентами` и `агенты-параллельно`. При этом помощников смена запускала
— значит правила «роли, выбор модели под роль, круги правок с предохранителем,
одна ветка, прогон фоном» каждый раз держались на памяти, а не на носителе.
Спека прямо говорит: «Назвать условие» исходом не считается — это мёртвая
запись; либо скил зовёт КОД, либо он сливается или удаляется.

Здесь код и зовёт: попытка запустить помощника без свежего вызова скила
отменяется с подсказкой, какой именно скил позвать. Отказ мягкий — он не
запрещает работу, а требует прочитать правила ОДИН раз за смену.

Что считается свежим: запись в `$LOG_DIR/skills.jsonl` об этом скиле, сделанная
ХУКОМ (`"источник":"хук"`) в текущей сессии. Записи руками не считаются — гейты
проекта считают только машинные (CLAUDE.md, «журнал никогда не ведётся рукой»).

Вход — JSON события PreToolUse на stdin. Отказ: код 2 и причина в stderr
(конвенция хуков оболочки, как у `guard_bash.py`).
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(КОРЕНЬ / "scripts" / "lib"))
import config as конф                                    # noqa: E402

# Инструменты запуска помощника: имя у разных оболочек своё, поэтому список —
# данные, а не одно имя. Task — прежнее имя того же инструмента.
ИНСТРУМЕНТЫ = ("Agent", "Task")
# Какой скил чему отвечает. Параллельный запуск судится отдельно: у него свои
# правила (независимость задач, приём работы), и они в другом скиле.
СКИЛ_ОДИН = "работа-субагентами"
СКИЛ_ПАРАЛЛЕЛЬНО = "агенты-параллельно"


def журнал_скилов() -> Path:
    return Path(конф.log_dir()) / "skills.jsonl"


def позван(скил: str, сессия: str | None, журнал: Path | None = None) -> bool:
    """Скил позван ХУКОМ в этой сессии? Пустая сессия — считаем по журналу целиком.

    Сессия важна: правила читаются один раз за смену, а не один раз за всё время
    существования харнеса — иначе носитель умирает вместе с первой сменой.
    """
    путь = журнал or журнал_скилов()
    try:
        строки = путь.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        # «Журнал не прочли» и «скил не звали» — разные ответы. Не прочли — не
        # мешаем работе: иначе сломанный журнал остановит смену целиком.
        return True
    for строка in строки:
        строка = строка.strip()
        if not строка:
            continue
        try:
            запись = json.loads(строка)
        except ValueError:
            continue
        if запись.get("skill") != скил or запись.get("источник") != "хук":
            continue
        if сессия and запись.get("сессия") and запись["сессия"] != сессия:
            continue
        return True
    return False


def сколько_агентов(вход: dict) -> int:
    """Сколько помощников запускается этим вызовом."""
    п = вход.get("tool_input") or {}
    # Оболочка присылает один вызов на одного помощника; параллельность видна
    # по числу вызовов в одном сообщении, чего хук не знает. Поэтому признак
    # параллельности — явное поле, если оно есть.
    for ключ in ("parallel_count", "agents", "count"):
        значение = п.get(ключ)
        if isinstance(значение, list):
            return len(значение)
        if isinstance(значение, int) and значение > 0:
            return значение
    return 1


def решение(вход: dict, журнал: Path | None = None) -> tuple[int, str]:
    """(код возврата, сообщение). 0 — пропускаем, 2 — отменяем с причиной."""
    инструмент = вход.get("tool_name") or ""
    if инструмент not in ИНСТРУМЕНТЫ:
        return 0, ""
    сессия = вход.get("session_id") or os.environ.get("CLAUDE_SESSION_ID") or ""
    нужен = (СКИЛ_ПАРАЛЛЕЛЬНО if сколько_агентов(вход) > 1 else СКИЛ_ОДИН)
    if позван(нужен, сессия, журнал):
        return 0, ""
    return 2, (
        f"Помощник запускается без скила «{нужен}» — правила работы с агентами "
        f"в этой смене ни разу не прочитаны.\n"
        f"Позови скил «{нужен}» (инструмент Skill) и повтори запуск: там роли, "
        f"выбор модели под роль, круги правок с предохранителем, наши запреты "
        f"(одна ветка, выкат только deploy.sh, прогон фоном).\n"
        f"Носитель заведён 28.09.2026: по журналу skills.jsonl этот скил не был "
        f"позван НИ РАЗУ, а помощников смена запускала — правила держались на "
        f"памяти (Ф3 ревизии, §5).")


def самотест() -> int:
    import tempfile
    путей = неудач = 0

    def проба(имя: str, ждём, факт):
        nonlocal путей, неудач
        путей += 1
        if факт == ждём:
            print(f"  ок    {имя}")
        else:
            неудач += 1
            print(f"  ПЛОХО {имя}: ждали «{ждём}», вышло «{факт}»")

    with tempfile.TemporaryDirectory() as врем:
        журнал = Path(врем) / "skills.jsonl"
        журнал.write_text("", encoding="utf-8")
        # БОЛЬНОЙ СЛУЧАЙ: помощник запускается, скил не позван — отказ.
        код, текст = решение({"tool_name": "Agent", "session_id": "с1"}, журнал)
        проба("БОЛЬНОЙ СЛУЧАЙ: агент без скила отменён", 2, код)
        проба("в отказе назван нужный скил", True, СКИЛ_ОДИН in текст)
        # Чужой инструмент не трогаем.
        проба("Bash пропускается", 0,
              решение({"tool_name": "Bash", "session_id": "с1"}, журнал)[0])
        # Запись РУКОЙ не считается: гейты проекта считают только машинные.
        журнал.write_text(
            json.dumps({"skill": СКИЛ_ОДИН, "сессия": "с1"}, ensure_ascii=False) + "\n",
            encoding="utf-8")
        проба("запись без «источник»:«хук» не считается", 2,
              решение({"tool_name": "Agent", "session_id": "с1"}, журнал)[0])
        # Машинная запись ЭТОЙ сессии — пропускаем.
        журнал.write_text(
            json.dumps({"skill": СКИЛ_ОДИН, "источник": "хук", "сессия": "с1"},
                       ensure_ascii=False) + "\n", encoding="utf-8")
        проба("машинная запись этой сессии пропускает", 0,
              решение({"tool_name": "Agent", "session_id": "с1"}, журнал)[0])
        # Запись ЧУЖОЙ сессии не считается: правила читаются раз за смену.
        проба("машинная запись чужой сессии не считается", 2,
              решение({"tool_name": "Agent", "session_id": "с2"}, журнал)[0])
        # Параллельный запуск требует своего скила.
        проба("двум помощникам нужен скил про параллельность", 2,
              решение({"tool_name": "Agent", "session_id": "с1",
                       "tool_input": {"agents": ["a", "b"]}}, журнал)[0])
        журнал.write_text(
            json.dumps({"skill": СКИЛ_ПАРАЛЛЕЛЬНО, "источник": "хук",
                        "сессия": "с1"}, ensure_ascii=False) + "\n",
            encoding="utf-8")
        проба("позванный скил про параллельность пропускает", 0,
              решение({"tool_name": "Agent", "session_id": "с1",
                       "tool_input": {"agents": ["a", "b"]}}, журнал)[0])
        # Журнал не прочли — работу не останавливаем.
        проба("нечитаемый журнал не мешает работе", 0,
              решение({"tool_name": "Agent", "session_id": "с1"},
                      Path(врем) / "нет-такого.jsonl")[0])

    print(f"SELFTEST: {'зелёный' if not неудач else 'КРАСНЫЙ'} ({путей} путей; "
          "больной первый — «агент без скила»)")
    return 1 if неудач else 0


def главная() -> int:
    if "--selftest" in sys.argv:
        return самотест()
    try:
        вход = json.load(sys.stdin)
    except (ValueError, OSError):
        return 0            # не разобрали событие — не мешаем работе
    код, текст = решение(вход)
    if код:
        print(текст, file=sys.stderr)
    return код


if __name__ == "__main__":
    sys.exit(главная())
