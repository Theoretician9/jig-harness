#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Сборка одностраничника из глав пакета.

Руками одностраничник не склеивать: ручная склейка отстаёт от пакета и молча
теряет главы. Скрипт включает каждый документ ДОСЛОВНО и сам проверяет
полноту в обе стороны: (1) каждая глава и каждый шаблон вошли в выгрузку,
(2) в выгрузке нет файла, которого нет в пакете. Несоответствие — отказ записи.

Запуск: python3 SBORKA.py  (из корня пакета)
Результат: ХАРНЕС-ОДНИМ-ФАЙЛОМ.md
"""

import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent
ВЫХОД = КОРЕНЬ / "ХАРНЕС-ОДНИМ-ФАЙЛОМ.md"

ШАПКА = """# Единый харнес — выгрузка одним файлом

Собрано скриптом `SBORKA.py` из пакета глав. Не редактируйте этот файл руками:
источник истины — отдельные главы, правки вносятся туда, файл пересобирается.

---
"""


def главы() -> list[Path]:
    файлы = sorted(p for p in КОРЕНЬ.glob("[0-9][0-9]-*.md"))
    if not файлы:
        sys.exit("Не найдено ни одной главы NN-*.md рядом со скриптом.")
    return файлы


def шаблоны() -> list[Path]:
    каталог = КОРЕНЬ / "templates"
    if not каталог.is_dir():
        return []
    return sorted(p for p in каталог.rglob("*") if p.is_file())


def прочитать(ф: Path) -> str:
    """Двоичный файл в пакете — отказ сборки: что нельзя прочитать, нельзя и
    вычистить (в реальном случае наружу уехал скомпилированный байткод)."""
    сырьё = ф.read_bytes()
    if b"\x00" in сырьё:
        sys.exit(f"Сборка НЕ записана: двоичный файл в пакете: "
                 f"{ф.relative_to(КОРЕНЬ)} — уберите его или добавьте в исключения осознанно.")
    try:
        return сырьё.decode("utf-8")
    except UnicodeDecodeError:
        sys.exit(f"Сборка НЕ записана: двоичный файл в пакете: "
                 f"{ф.relative_to(КОРЕНЬ)} — уберите его или добавьте в исключения осознанно.")


def собрать() -> str:
    куски = [ШАПКА]
    for гл in главы():
        куски.append(f"\n<!-- ФАЙЛ: {гл.name} -->\n\n")
        куски.append(прочитать(гл).rstrip() + "\n")
        куски.append("\n---\n")
    куски.append("\n# ПРИЛОЖЕНИЕ: templates/ — исходники шаблонов и скриптов\n")
    for ш in шаблоны():
        отн = ш.relative_to(КОРЕНЬ)
        расш = ш.suffix.lstrip(".") or "text"
        текст = прочитать(ш)
        куски.append(f"\n<!-- ФАЙЛ: {отн} -->\n\n")
        if расш == "md":
            куски.append(текст.rstrip() + "\n")
        else:
            # Ограда из большего числа обратных кавычек, чем есть в тексте.
            макс = 0
            for hit in re.finditer(r"`+", текст):
                макс = max(макс, len(hit.group()))
            огр = "`" * max(4, макс + 1)
            куски.append(f"{огр}{расш}\n{текст.rstrip()}\n{огр}\n")
        куски.append("\n---\n")
    return "".join(куски)


def проверить(текст: str) -> None:
    ошибки = []
    # 1. Каждый файл пакета вошёл, и вошёл дословно.
    for ф in главы() + шаблоны():
        отн = str(ф.relative_to(КОРЕНЬ))
        маркер = f"<!-- ФАЙЛ: {отн} -->"
        if маркер not in текст:
            ошибки.append(f"не вошёл: {отн}")
            continue
        тело = прочитать(ф).rstrip()
        if тело and тело not in текст:
            ошибки.append(f"вошёл не дословно: {отн}")
    # 2. В выгрузке нет файла, которого нет в пакете.
    есть = {str(ф.relative_to(КОРЕНЬ)) for ф in главы() + шаблоны()}
    for имя in re.findall(r"<!-- ФАЙЛ: (.+?) -->", текст):
        if имя not in есть:
            ошибки.append(f"в выгрузке лишний файл: {имя}")
    if ошибки:
        sys.exit("Сборка НЕ записана:\n  " + "\n  ".join(ошибки))


def main() -> None:
    текст = собрать()
    проверить(текст)
    ВЫХОД.write_text(текст, encoding="utf-8")
    n_гл, n_ш = len(главы()), len(шаблоны())
    print(f"OK: {ВЫХОД.name} — {n_гл} глав, {n_ш} файлов templates/, "
          f"{len(текст.splitlines())} строк.")


if __name__ == "__main__":
    main()
