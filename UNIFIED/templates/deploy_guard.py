#!/usr/bin/env python3
"""Не выкатывать, пока идёт долгая задача ИЛИ чужой деплой.

04.08 выкат в 09:28 перезапустил воркер и убил чужую сборку, шедшую с 08:59.
Повторной попытки у задач конвейера нет (`max_retries=0`): строка осталась
висеть «выполняется», владелец сорок минут ждал того, чего уже не было.

Проверять занятость руками я в тот раз забыл. Ручная проверка, которую можно
забыть, — не защита, поэтому она здесь.

05.08 добавлена вторая причина ждать: пуш в главную ветку запускает автодеплой
в CI, который делает тот же `docker compose up -d --build`. Два одновременных
выката по одному проекту пересоздали контейнеры под временными именами, часть
осталась не поднятой, и API лёг на минуту.

    scripts/deploy_guard.py          # проверить и сказать, можно ли
    scripts/deploy_guard.py --силой  # выкатить всё равно, назвав цену

Код возврата: 0 — можно, 1 — занято.

ЧТО ПОДОГНАТЬ ПОД СЕБЯ — всё в блоке «НАСТРОЙКИ» ниже. Переносится здесь не
код, а три проверки; запросы к базе и имена контейнеров у всех свои.
"""
from __future__ import annotations

import hashlib
import pathlib
import subprocess
import sys

# --- НАСТРОЙКИ ----------------------------------------------------------------
# Корень проекта берётся ОТНОСИТЕЛЬНО скрипта, а не абсолютным путём: тот же
# сторож запускается на машине CI, где вашего сервера нет, и абсолютный путь
# заворачивал бы вливание на пустом месте.
КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent

# 1. Где спросить про идущие долгие задачи. У нас это контейнер с базой задач.
КОНТЕЙНЕР_БАЗЫ = "<контейнер вашей базы задач>"
ПОЛЬЗОВАТЕЛЬ_БД = "<пользователь>"
ИМЯ_БД = "<база>"
# Запрос обязан вернуть по строке на КАЖДУЮ идущую задачу, с человеческим
# описанием: владельцу потом читать, что именно он чуть не убил.
ЗАПРОС = """
select left(j.id::text,8) || ' (' ||
       coalesce(j.name,'без имени') || ', ' ||
       round(extract(epoch from (now()-coalesce(j.started_at,j.created_at)))/60)::int || ' мин)'
from jobs j where j.status in ('running','queued') order by j.created_at
"""

# 2. Где спросить про чужой выкат. Пусто — проверка просто молчит.
РЕПОЗИТОРИЙ = "<владелец>/<репозиторий>"
ФАЙЛ_ТОКЕНА = pathlib.Path.home() / ".config" / "gh-token"

# 3. Чем поймать выкат, который уже в пути. Часто меняющийся файл кода: его
# содержимое в рабочем дереве сравнивается с содержимым внутри контейнера.
КОНТЕЙНЕР_ВОРКЕРА = "<контейнер вашего воркера>"
КОД_В_ДЕРЕВЕ = "backend/<сервис>"      # путь от корня проекта
КОД_В_ОБРАЗЕ = "/app"                  # тот же код внутри контейнера
ФАЙЛ_СВЕРКИ = "<часто меняющийся файл>.py"
# ------------------------------------------------------------------------------

БАЗА = ("docker", "exec", КОНТЕЙНЕР_БАЗЫ, "psql", "-U", ПОЛЬЗОВАТЕЛЬ_БД,
        "-d", ИМЯ_БД, "-tAc")


def идущие_задачи() -> list:
    out = subprocess.run(БАЗА + (ЗАПРОС,), capture_output=True, text=True)
    if out.returncode != 0:
        # Не смогли спросить — считаем, что заняты: ошибиться в эту сторону
        # дешевле, чем убить чужую работу.
        return ["(база недоступна — считаем стек занятым)"]
    return [ln.strip() for ln in out.stdout.splitlines() if ln.strip()]


def идущий_деплой() -> list:
    """Идёт ли прямо сейчас автодеплой в CI.

    Нет токена или сети — молчим: выдумывать занятость на пустом месте хуже,
    чем пропустить редкий случай, а про задачи мы всё равно спросим базу.
    """
    try:
        токен = ФАЙЛ_ТОКЕНА.read_text(encoding="utf-8").strip()
        if not токен:
            return []
        out = subprocess.run(
            ("curl", "-fsS", "-H", f"Authorization: Bearer {токен}",
             "-H", "Accept: application/vnd.github+json",
             f"https://api.github.com/repos/{РЕПОЗИТОРИЙ}/actions/runs"
             "?status=in_progress&per_page=5"),
            capture_output=True, text=True, timeout=15)
        if out.returncode != 0:
            return []
        import json as _json
        данные = _json.loads(out.stdout or "{}")
        return [f"деплой «{r.get('name') or '?'}» ({r.get('status')})"
                for r in (данные.get("workflow_runs") or [])]
    except Exception:                                   # noqa: BLE001
        return []


def выкат_в_пути() -> list:
    """Пуш уже сделан, а деплой ещё не доехал — стек вот-вот перезапустится.

    07.08 я потерял на этом две сборки: ворота сказали «свободно» (прогон в CI
    ещё не числился идущим), я запустил сборки в 22:04, а контейнеры
    перезапустились в 22:05.

    Спрашиваем не CI, а СВОЙ стек: тот ли код внутри воркера, что лежит в
    рабочем дереве. Сравниваем содержимое одного часто меняющегося файла. Если
    в дереве есть НЕЗАКОММИЧЕННЫЕ правки — молчим: расхождение тогда законно,
    это текущая работа, а не едущий выкат.
    """
    в_дереве = f"{КОД_В_ДЕРЕВЕ}/{ФАЙЛ_СВЕРКИ}"
    try:
        грязно = subprocess.run(("git", "-C", str(КОРЕНЬ), "status", "--porcelain",
                                 в_дереве),
                                capture_output=True, text=True, timeout=10).stdout.strip()
        if грязно:
            return []
        свой = (КОРЕНЬ / в_дереве).read_bytes()
        в_образе = subprocess.run(
            ("docker", "exec", КОНТЕЙНЕР_ВОРКЕРА, "python", "-c",
             f"import hashlib,pathlib;print(hashlib.sha256("
             f"pathlib.Path('{КОД_В_ОБРАЗЕ}/{ФАЙЛ_СВЕРКИ}').read_bytes()).hexdigest())"),
            capture_output=True, text=True, timeout=20).stdout.strip()
        if not в_образе:
            return []
        if в_образе != hashlib.sha256(свой).hexdigest():
            return ["выкат в пути: код в воркере старше рабочего дерева"]
        return []
    except Exception:                                   # noqa: BLE001
        return []


def решение(занятость, силой: bool = False) -> dict:
    """Можно ли выкатывать прямо сейчас."""
    if not занятость:
        return {"можно": True, "почему": "идущих задач нет — выкат безопасен"}
    список = "; ".join(занятость)
    if силой:
        return {"можно": True,
                "почему": (f"выкат убьёт идущую работу: {список}. "
                           "Перезапускать придётся вручную")}
    return {"можно": False,
            "почему": (f"занято: {список}. Перезапуск воркера убьёт идущие задачи "
                       "(повторной попытки у них нет), а второй одновременный выкат "
                       "оставляет контейнеры не поднятыми. Дождаться или «--силой», "
                       "понимая цену")}


def main() -> int:
    итог = решение(идущие_задачи() + идущий_деплой() + выкат_в_пути(),
                   силой="--силой" in sys.argv)
    print(итог["почему"])
    return 0 if итог["можно"] else 1


if __name__ == "__main__":
    sys.exit(main())
