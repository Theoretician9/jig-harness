#!/usr/bin/env bash
# Пропуск в карте разработки чинится сам.
#
# Сверка находит коммиты, которые прошли мимо карты, и вместо доклада человеку
# запускает агента с одной узкой задачей: завести пропущенную работу в манифест.
# Показывать пропуск владельцу — значит перекладывать на него мою забывчивость;
# правило должно держаться механикой, а не вниманием.
#
# Область агента намеренно узкая: он правит ТОЛЬКО dev-map.yaml и коммитит
# только его. Никакого кода, никаких других файлов.
#
# ВАЖНО: агент запускается БЕЗ MCP-серверов (--strict-mcp-config с пустым
# набором). Иначе он поднимает telegram-плагин, а Telegram допускает ровно
# одного потребителя getUpdates на токен: плагин убивает «устаревшего
# держателя» — то есть живой рабочий сеанс — и забирает канал себе. Один такой
# запуск оборвал переписку с владельцем; по расписанию он обрывал бы её каждый
# час. Фоновая починка не должна трогать канал связи.
#
# Той же граблёй бьёт `claude mcp list`: проверка здоровья MCP тоже поднимает
# плагин и тоже отбирает канал. Смотреть состав серверов — только чтением
# конфигов, health-check-командами нельзя.
#
# Запуск: scripts/devmap-selfheal.sh [дней]
set -euo pipefail

cd "$(dirname "$0")/.."
DAYS="${1:-14}"
AUDIT_JSON="/opt/<проект>/devmap/audit.json"
# Водораздел: SHA прошлой сверки. Без него каждый час пересматривалась бы одна
# и та же старая история — коммиты до введения правила трейлеров его не несут и
# понести не могут (история опубликована). Разобранное считается разобранным.
CURSOR="/opt/<проект>/devmap/audit.cursor"
AGENT_LOG="/opt/<проект>/devmap/selfheal-agent.log"
mkdir -p "$(dirname "$AGENT_LOG")"

python3 backend/scripts/devmap_audit.py --days "$DAYS" --out "$AUDIT_JSON" --cursor "$CURSOR" >/dev/null

# Водораздел двигаем ТОЛЬКО после того, как пропуск заведён в карту. Пока сверка
# двигала его сама (до запуска агента), упавший агент означал потерю работы
# навсегда: коммит уезжал за водораздел и больше не всплывал. Механизм против
# забывчивости не должен зависеть от того, повезло ли агенту.
HEAD_AT_AUDIT=$(python3 -c "import json;print(json.load(open('$AUDIT_JSON'))['head'])")
advance() { mkdir -p "$(dirname "$CURSOR")"; echo "$HEAD_AT_AUDIT" > "$CURSOR"; }

UNLINKED=$(python3 -c "import json;print(json.load(open('$AUDIT_JSON'))['unlinked'])")
if [ "$UNLINKED" -eq 0 ]; then
  advance
  echo "карта полна: мимо неё за $DAYS дн. — 0 коммитов"
  exit 0
fi

echo "мимо карты: $UNLINKED коммит(ов) — запускаю починку"
ITEMS=$(python3 -c "
import json
d=json.load(open('$AUDIT_JSON'))
for i in d['items']:
    print('- ' + i['subject'] + '  [' + i['reason'] + ']')
")

# Агент работает без вопросов (некому отвечать) и с узким набором инструментов.
claude -p "Ты дежурный по карте разработки проекта <ПРОЕКТ> (/opt/<проект>).

Сверка нашла работу, которая прошла мимо карты:

$ITEMS

Задача: завести эту работу в манифест backend/app/modules/dev_map/dev-map.yaml так,
чтобы она появилась на дашборде. Для каждого пропуска:
1. Найди коммит (git log --oneline --all | grep) и посмотри его диффом, что реально сделано.
2. Если работа подходит к существующей задаче манифеста — дополни её чек-лист пунктом
   с summary и done_at (дата коммита), не меняя чужие поля.
2а. Причина «работа без следа в карте» означает: ссылка на задачу есть, но за тот день
   её запись не менялась — значит на дашборде дня нет. Лечится ровно пунктом чек-листа
   у названной задачи с датой из причины (или сменой её статуса, если работа его меняет).
   Даже если задача стоит «ждёт теста» или «готово» — пункт всё равно нужен: иначе
   дневной работе негде оказаться.
3. Если это самостоятельная работа — заведи новую задачу в подходящем направлении:
   id, title, summary, status (done только если протестировано пользователем, иначе test),
   volume (loc по диффу, complexity и tokens_k — оценка), when с датами.
4. Summary пиши по-русски, для владельца продукта: что изменилось и почему это было нужно,
   без технического жаргона и без имён файлов.

Требования:
- Правь ТОЛЬКО dev-map.yaml. Никаких других файлов.
- Проверь гейт: docker compose exec -T backend python -m pytest tests/test_dev_map_manifest.py -q
  (перед этим: docker cp backend/app/modules/dev_map/dev-map.yaml <контейнер-бэкенда>:/app/app/modules/dev_map/)
- Закоммить только манифест с трейлером Dev-Map: <id задачи про карту разработки> и запушь в main.
- Если работа уже есть в карте — ничего не меняй и скажи об этом." \
  --allowedTools "Read,Edit,Bash,Grep,Glob" \
  --mcp-config '{"mcpServers":{}}' --strict-mcp-config \
  --output-format text > "$AGENT_LOG" 2>&1 || AGENT_RC=$?

tail -20 "$AGENT_LOG"

if [ "${AGENT_RC:-0}" -ne 0 ]; then
  echo "починка НЕ удалась (код $AGENT_RC) — водораздел на месте, попробую в следующий раз"
  exit 1
fi

advance
echo "починка завершена"
