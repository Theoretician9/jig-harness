#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Сторож модели: важный шаг делается той моделью, которую назвала таблица.

Владелец 18.10.2026: «получается смена сонет, а нужные шаги нужными моделями.
мы можем добиться того, чтобы это не скилами, а строго кодом контролировалось?
чтобы сонет случайно важный шаг сам не сделал, типа написания спеки или её
ревью, а строго опусом. чтобы та таблица очень строго выполнялась».

Почему признак шага — АРТЕФАКТ, а не вызов скила. Раскладку «работа → модель»
исполнял только хук вызова скила: позвали скил — переключил модель. Шаг без
скила (дописать спеку, поправить пробу) шёл на какой угодно модели, и правило
держалось вниманием. Путь файла подделать нельзя, а скил можно не позвать —
поэтому судится то, ЧТО пишется.

Модель берётся из ТРАНСКРИПТА того, кто пишет: у смены — `transcript_path`
из входа, у помощника — его собственный транскрипт по `agent_id` (см.
`транскрипт_пишущего`). Не из конфига: конфиг знает команду запуска, а не
живую модель — её меняет и «/model», и хук шага.

Три исхода, и третий назван вслух:
  0 — можно (модель та, шаг неважный, причина названа дверью);
  2 — отказ с объяснением и законным ходом;
  0 + след в журнале — модель узнать НЕ УДАЛОСЬ: запрещать, не зная, с чем
      сравнивать, значит останавливать смену на ровном месте (fail-open, как у
      соседнего сторожа команд).

Законная дверь: HARNESS_MODEL_GUARD_WHY='причина' — отказ без двери
обходят, а не исполняют. Причина уходит в журнал.

Прогон: python3 scripts/hooks/test_model_guard.py
"""
from __future__ import annotations

import datetime
import fnmatch
import json
import re
import os
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "lib"))
import config as конф                                     # noqa: E402

КОРЕНЬ = Path(__file__).resolve().parent.parent.parent
ТАБЛИЦА = Path(os.environ.get("MODELS_CONF") or (КОРЕНЬ / "harness" / "config" / "models.yaml"))
АРТЕФАКТЫ = Path(os.environ.get("MODEL_ARTIFACTS_CONF")
                 or (КОРЕНЬ / "harness" / "config" / "model-artifacts.yaml"))
ПРИЧИНА_МИН = 20


def журнал(запись: dict) -> None:
    try:
        # Время ставит запись, а не вызывающий: семь веток решения, один формат
        # (как `date -Is` у guard_bash) и ни одна ветка не забудет поле.
        запись = {"ts": datetime.datetime.now().astimezone().isoformat(timespec="seconds"), **запись}
        путь = Path(os.environ.get("LOG_DIR") or конф.log_dir()) / "model-guard.jsonl"
        путь.parent.mkdir(parents=True, exist_ok=True)
        with open(путь, "a", encoding="utf-8") as fh:
            fh.write(json.dumps(запись, ensure_ascii=False) + "\n")
    except Exception:
        pass


def данные() -> dict:
    try:
        import yaml
        return yaml.safe_load(ТАБЛИЦА.read_text(encoding="utf-8")) or {}
    except Exception:
        return {}


def маски_артефактов() -> dict | None:
    """Маски «путь → (вид, кто)» из model-artifacts.yaml; None — не прочитан.
    models.yaml для масок не читается: там они устарели."""
    try:
        import yaml
        карта = (yaml.safe_load(АРТЕФАКТЫ.read_text(encoding="utf-8")) or {}).get("артефакты")
    except Exception:
        return None
    return карта if isinstance(карта, dict) and карта else None


def вид_по_пути(путь: str, карта: dict) -> tuple[str, str]:
    """(вид работы, кто её делает) по артефакту. Маски — ДАННЫЕ: первая
    подошедшая побеждает, поэтому частное («*-REVIEW.md») стоит в файле выше
    общего («docs/specs/*»). Значение маски — строка (только вид) или пара."""
    # Не `lstrip("./")`: он снимает ЛЮБЫЕ ведущие точки и слэши, и «.tasks/…»
    # превращался в «tasks/…», мимо маски «.tasks/*» (поймано пробой).
    чистый = путь
    for префикс in (str(КОРЕНЬ) + "/", "./"):
        if чистый.startswith(префикс):
            чистый = чистый[len(префикс):]
    for маска, значение in (карта or {}).items():
        if fnmatch.fnmatch(чистый, маска) or fnmatch.fnmatch("/" + чистый, маска):
            if isinstance(значение, dict):
                return str(значение.get("вид") or ""), str(значение.get("кто") or "")
            return str(значение), ""
    return "", ""


def печать_по_пути(путь: str, карта: dict) -> bool:
    """True — маска файла просит печать хуком (`печать: true`).

    Отдельная функция, а не третье поле в паре `вид_по_пути`: у пары читателей
    много, и меняющаяся длина кортежа ломает их молча. Порядок масок тот же —
    побеждает первая подошедшая."""
    чистый = путь
    for префикс in (str(КОРЕНЬ) + "/", "./"):
        if чистый.startswith(префикс):
            чистый = чистый[len(префикс):]
    for маска, значение in (карта or {}).items():
        if fnmatch.fnmatch(чистый, маска) or fnmatch.fnmatch("/" + чистый, маска):
            return isinstance(значение, dict) and значение.get("печать") is True
    return False


def род(имя: str) -> str:
    """Род модели: «claude-opus-5-5» и «opus» — одно и то же, «sonnet» — другое."""
    имя = (имя or "").lower()
    for р in ("opus", "sonnet", "haiku", "fable"):
        if р in имя:
            return р
    return имя


def пишет_сама_смена(payload: dict) -> bool:
    """True — пишет основная смена, False — помощник.

    Признак — поле `agent_id` во ВХОДЕ хука: оболочка кладёт его только в
    вызовы инструментов помощника. Транскрипт для этого не годится —
    `transcript_path` у помощника указывает на транскрипт ОСНОВНОЙ сессии, где
    isSidechain=false. Судится запись оболочки, а не слово агента о себе.
    """
    return not payload.get("agent_id")


def транскрипт_пишущего(payload: dict) -> Path:
    """Транскрипт того, кто делает запись: смены или помощника.

    `transcript_path` во входе помощника — транскрипт СМЕНЫ, и модель в нём
    смены. Свой транскрипт помощника оболочка кладёт рядом:
    `<каталог>/<session_id>/subagents/agent-<agent_id>.jsonl`. Нет файла —
    модель не прочитана, а не модель смены.
    """
    смена = Path(str(payload.get("transcript_path") or ""))
    помощник = payload.get("agent_id")
    if not помощник:
        return смена
    return (смена.parent / str(payload.get("session_id") or "") / "subagents"
            / f"agent-{помощник}.jsonl")


def модель_сессии(транскрипт: Path) -> str:
    """Модель последнего ответа в транскрипте; «» — прочитать не удалось."""
    try:
        строки = Path(транскрипт).read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return ""
    for строка in reversed(строки[-400:]):
        try:
            запись = json.loads(строка)
        except Exception:
            continue
        имя = ((запись.get("message") or {}).get("model")
               or запись.get("model") or "")
        if имя and имя != "<synthetic>":
            return str(имя)
    return ""


def причина_двери() -> str:
    """Причина обхода: из ФАЙЛА двери, а не из переменной окружения команды.

    Больной случай 18.10.2026, пойман через минуту после включения сторожа:
    дверью была переменная `HARNESS_MODEL_GUARD_WHY`, но хук запускает
    ОБОЛОЧКА — её окружение не то, в котором агент набрал команду, и дверь не
    открывалась никогда. Правило без достижимой двери не обходят, а отключают
    ([[a-guard-without-a-legal-door]]).

    Переменная осталась вторым ходом: её видят помощники, запущенные с ней.
    """
    из_среды = (os.environ.get("HARNESS_MODEL_GUARD_WHY") or "").strip()
    if len(из_среды) >= ПРИЧИНА_МИН:
        return из_среды
    try:
        путь = Path(os.environ.get("LOG_DIR") or конф.log_dir()) / "model-guard.дверь"
        запись = json.loads(путь.read_text(encoding="utf-8"))
    except Exception:
        return ""
    if int(запись.get("до") or 0) < int(time.time()):
        return ""                      # дверь со сроком: иначе она вечная
    return str(запись.get("почему") or "").strip()


def deny_kto(вид: str, путь: str) -> int:
    журнал({"исход": "отказ: шаг трубы из самой смены", "вид": вид, "файл": путь})
    print(
        f"Запись остановлена хуком: шаг «{вид}» делает ПОМОЩНИК, а не сама смена.\n\n"
        "Решение владельца 18.10.2026: «сессия в первую очередь должна работать "
        "как оркестратор, общаться со мной, работать с картой задач, решать там "
        "разные вопросы общие, контролить всё, но именно работу по пайплайну "
        "должны делать сабы».\n\n"
        "Законный ход — позвать помощника на этот шаг (инструмент Agent), дав ему "
        "абсолютные пути и текст задачи; модель помощнику выбирает таблица:\n"
        f"  bash scripts/model-for.sh {вид}\n"
        "Если помощника позвать нельзя, открой дверь с причиной на 15 минут:\n"
        "  python3 scripts/model-guard-door.py --почему 'почему именно сам'\n"
        "Причина уходит в журнал, дверь закрывается сама.",
        file=sys.stderr,
    )
    return 2


def deny(вид: str, нужна: str, сейчас: str, путь: str) -> int:
    журнал({"исход": "отказ", "вид": вид, "нужна": нужна, "сейчас": сейчас, "файл": путь})
    print(
        f"Запись остановлена хуком: шаг «{вид}» делается моделью {нужна}, "
        f"а сейчас в панели {сейчас}.\n\n"
        "Таблица «работа → модель» — данные (harness/config/models.yaml), и это "
        "решение владельца от 18.10.2026: важный шаг чужой моделью не делается "
        "даже случайно.\n\n"
        "Законный ход — переключить модель и повторить:\n"
        f"  bash scripts/model.sh --только-сессия {нужна}\n"
        "Если переключиться нельзя (лимит на нужной модели), открой дверь:\n"
        "  python3 scripts/model-guard-door.py --почему 'почему именно так'\n"
        "Причина уходит в журнал, дверь закрывается сама через 15 минут.",
        file=sys.stderr,
    )
    return 2


# Признаки ЗАПИСИ в команде оболочки. Правило, закрытое на одном пути из
# двух, обходят, а не исполняют ([[a-rule-covering-one-path-of-two]]): эта
# смена пишет файлы и инструментом записи, и командой оболочки.
#
# Граница честная и узкая: судится строка команды, а значит обойти её можно
# (переменная вместо пути, кодировка, свой скрипт). Это первый рубеж, а не
# замок: второй — ревью кода и прогон ворот, где видно, кто и что менял.
ЗАПИСЬ_В_ОБОЛОЧКЕ = (
    ">", ">>", "tee ", "sed -i", "cp ", "mv ", "install ", "os.replace",
    "write_text", "truncate", "dd ", "patch ",
)


def путь_из_команды(cmd: str, карта: dict) -> str:
    """Путь артефакта, в который команда ПИШЕТ; «» — записи не видно.

    Ищется ЦЕЛЬ записи, а не любое упоминание пути: «python3 scripts/x.py 2>&1»
    — это прогон, а не правка, и прямолинейный признак «есть > и есть путь»
    отменял бы каждый прогон проверки (поймано случаем пробы).
    """
    цели: list[str] = []
    # Перенаправление: цель — слово сразу после > или >>, но не «&1» и не
    # дескриптор («2>»): их пишет оболочка, а не мы.
    цели += re.findall(r"(?<![0-9&])>>?\s*([\w./*-]+)", cmd)
    цели += re.findall(r"\btee\s+(?:-a\s+)?([\w./*-]+)", cmd)
    # Правка на месте — ТОЛЬКО то, что стоит рядом с признаком записи. Первая
    # редакция собирала все пути из текста команды и через минуту после
    # включения отменила правку КАРТЫ за то, что в тексте карточки упомянут
    # путь пробы. Окно узкое и названо явно.
    for м in re.finditer(r"\bsed\s+(?:-[a-zA-Z]*\s+)*-i\b", cmd):
        цели += re.findall(r"[\w./*-]+", cmd[м.end(): м.end() + 200])
    for м in re.finditer(r"os\.replace\(|write_text\(|open\(|truncate\(", cmd):
        окно = cmd[м.start(): м.end() + 160]
        цели += re.findall(r"['\"]([\w./*-]+)['\"]", окно)
    for слово in re.findall(r"\b(?:cp|mv|install)\s+([^|;&]+)", cmd):
        части = слово.split()
        if len(части) >= 2:
            цели.append(части[-1])
    for цель in цели:
        вид, _ = вид_по_пути(цель.strip(), карта)
        if вид:
            return цель.strip()
    return ""


def судить(payload: dict) -> int:
    инструмент = payload.get("tool_name")
    d_карта = маски_артефактов()
    if d_карта is None:
        журнал({"исход": "файл масок не прочитан", "файл": str(АРТЕФАКТЫ),
                "слово": "model-artifacts"})
        return 0
    if инструмент == "Bash":
        путь = путь_из_команды(str((payload.get("tool_input") or {}).get("command") or ""),
                               d_карта)
        if not путь:
            return 0
    elif инструмент in ("Write", "Edit", "MultiEdit", "NotebookEdit"):
        путь = str((payload.get("tool_input") or {}).get("file_path") or "")
    else:
        return 0
    if not путь:
        return 0
    d = данные()
    вид, кто = вид_по_пути(путь, d_карта)
    if not вид:
        return 0
    причина = причина_двери()
    дверь = len(причина) >= ПРИЧИНА_МИН
    if кто == "помощник" and not дверь:
        if пишет_сама_смена(payload):
            return deny_kto(вид, путь)
    нужна = str((d.get("модели") or {}).get(вид) or d.get("умолчание") or "")
    if not нужна:
        return 0
    сейчас = модель_сессии(транскрипт_пишущего(payload))
    if not сейчас:
        журнал({"исход": "модель не прочитана", "вид": вид, "файл": путь})
        return 0
    if род(сейчас) == род(нужна):
        return 0
    if дверь:
        журнал({"исход": "дверь", "вид": вид, "нужна": нужна, "сейчас": сейчас,
                "почему": причина, "файл": путь})
        return 0
    return deny(вид, нужна, сейчас, путь)


def main() -> int:
    raw = sys.stdin.read()
    try:
        payload = json.loads(raw)
    except Exception as e:
        журнал({"исход": "битый вход", "ошибка": repr(e), "байт": len(raw)})
        return 0
    try:
        return судить(payload)
    except Exception as e:
        журнал({"исход": "упал сам сторож", "ошибка": repr(e)})
        return 0


if __name__ == "__main__":
    sys.exit(main())
