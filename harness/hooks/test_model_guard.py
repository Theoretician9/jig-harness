ВИД_TS = re.compile(r"^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d[+-]\d\d:\d\d$")


def пояс_машины() -> str:
    """Пояс в окружении сторожа (TZ не передаётся — пояс самой машины)."""
    with tempfile.TemporaryDirectory() as врем:
        return subprocess.run(["date", "+%:z"], capture_output=True, text=True,
                              env=окружение_сторожа(врем)).stdout.strip()


ПОЯС = пояс_машины()


def сторож_на_стенде(врем: str, вход: str, среда: dict | None = None) -> int:
    """Зовёт сторожа с журналом в `врем` (дверь LOG_DIR, не боевой журнал)."""
    окружение = окружение_сторожа(врем)
    окружение.update(среда or {})
    return subprocess.run([sys.executable, str(СТОРОЖ)], input=вход,
                          capture_output=True, text=True, env=окружение).returncode


