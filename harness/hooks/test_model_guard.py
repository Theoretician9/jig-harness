def окружение_сторожа(врем: str) -> dict:
    """Окружение сторожа: свой HOME и LOG_DIR (иначе открытая живая дверь
    красит каждый отказ) и СВОИ таблицы — MODELS_CONF и MODEL_ARTIFACTS_CONF
    извне сюда не доходят."""
    return {"PATH": "/usr/bin:/bin", "HOME": врем, "LC_ALL": "C.UTF-8",
            "LOG_DIR": врем, "MODELS_CONF": str(ТАБЛИЦА_ПРОБЫ),
            "MODEL_ARTIFACTS_CONF": str(АРТЕФАКТЫ_ПРОБЫ)}

