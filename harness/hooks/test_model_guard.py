# с двоеточием, как `date -Is` (так пишет guard_bash.py; «Z» skill_log.sh —
# не канон). Время ставит ЗАПИСЬ: проба судит, что оно попадает в окно вызова,
# иначе зеленела бы и постоянная строка. Каждая ветка — свой случай: ts,
