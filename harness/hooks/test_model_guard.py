def суд_времени(строки: list[str], исход: str, до: float, после: float) -> list[str]:
    """Беды записей журнала; пусто — годно. Нет записи с нужным исходом —
    тоже беда: иначе случай зеленел бы на ЧУЖОЙ ветке."""
    беды = []
    if not строки:
        return ["журнал не вырос — судить нечего"]
    записи = [json.loads(с) for с in строки]
    if not any(з.get("исход") == исход for з in записи):
        беды.append(f"нет записи с исходом «{исход}»: {[з.get('исход') for з in записи]}")
    for з in записи:
        ts = з.get("ts")
        if not isinstance(ts, str) or not ВИД_TS.match(ts):
            беды.append(f"ts не канона «ГГГГ-ММ-ДДTЧЧ:ММ:СС±ЧЧ:ММ»: {ts!r}")
            continue
        if ts[-6:] != ПОЯС:
            беды.append(f"пояс {ts[-6:]}, а у машины {ПОЯС}: {ts}")
        момент = datetime.datetime.fromisoformat(ts).timestamp()
        if not (до - 2 <= момент <= после + 2):
            беды.append(f"ts не время записи: {ts}, вызов в окне "
                        f"{datetime.datetime.fromtimestamp(до).astimezone().isoformat(timespec='seconds')}")
    return беды


def ветка(имя: str, исход: str, вход_от, среда: dict | None = None) -> list[dict]:
    """Один случай на ветку записи; отдаёт записи для соседних случаев."""
    with tempfile.TemporaryDirectory() as врем:
        до = time.time()
        сторож_на_стенде(врем, вход_от(врем), среда)
        после = time.time()
        след = Path(врем) / "model-guard.jsonl"
        строки = след.read_text(encoding="utf-8").splitlines() if след.exists() else []
    случай(f"{имя}: каждая запись с ts ISO, секунды, пояс машины {ПОЯС}",
           [], суд_времени(строки, исход, до, после))
    return [json.loads(с) for с in строки]


