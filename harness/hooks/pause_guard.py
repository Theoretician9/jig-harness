# Разрешённое на паузе. Здесь не защита от злоумышленника, а дисциплина смены,
# поэтому сверка простая — но НЕ «содержит pause.py»: первая редакция этим
# разрешала и `pause.py --снять`, то есть агент своей же командой снимал паузу
# владельца (находка ревью спеки 21.09.2026, CRITICAL 1). Паузу снимает ТОЛЬКО
# владелец — бот и панель, а они отдельные процессы и через этот хук не ходят.
ЧИТАТЬ_ПАУЗУ = re.compile(r"pause\.py(?!\S)(?:\s+--(?:идёт-ли|почему)\b)?\s*$")
# Снятие СВОЕЙ паузы. Паузу владельца агент снять не вправе (CRITICAL 1), но
# 26.09.2026 смена поставила паузу собственной пробой, сторож подписал её
# владельцем по умолчанию — и смена встала до его слова из-за своей ошибки.
# Теперь автор пишется по факту (pause.py, «--кто»), и чужая остаётся чужой,
# а свою смена вправе снять сама: ловушка, из которой нет выхода своими
# руками, — не дисциплина, а простой.
СНЯТЬ_ПАУЗУ = re.compile(r"pause\.py\s+--снять\s*$")
# Очередь входящих — ПУТЬ, а не подстрока: «grep /inbox-старое» или файл с
# таким именем в чужом каталоге проходили бы наравне с чтением очереди
# (находка ревью остановки M2). Сверяем по каталогу очереди с границей.
РАЗРЕШЕНО = ("tg_send.sh",)
# Конец имени — только разделитель или конец строки: «\b» тут не годится,
# после «inbox» в «/tmp/inbox-старое» стоит дефис, и это тоже граница слова.
ОЧЕРЕДЬ = re.compile(r"(?:^|[\s\"'=])/[^\s\"']*/inbox(?:/|[\s\"']|$)")

# Инструменты, которые НИЧЕГО не меняют: читать на паузе можно — иначе нечем
# прочесть сообщение владельца, ради которого он и остановил работу.
ТОЛЬКО_ЧТЕНИЕ = {"Read", "Glob", "Grep", "TodoWrite", "ListAgents", "ToolSearch"}

