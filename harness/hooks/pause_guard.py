            проба("БОЛЬНОЙ СЛУЧАЙ: на паузе обычная команда отменена", 2,
                  реш("Bash", {"command": "bash scripts/gates.sh"})[0])
            проба("на паузе правка файла отменена — не только Bash", 2,
                  реш("Edit", {"file_path": "/tmp/x", "old_string": "a"})[0])
            проба("причина называет владельца и его слово", True,
                  "владелец остановил работу" in реш("Bash", {"command": "ls"})[1])
            проба("канал разрешён: ответить «стою» можно", 0,
                  реш("Bash", {"command": 'bash scripts/tg_send.sh "стою"'})[0])
            проба("спросить паузу можно: иначе о ней нечем узнать", 0,
                  реш("Bash", {"command": "python3 scripts/pause.py --идёт-ли"})[0])
            # БОЛЬНОЙ СЛУЧАЙ (ревью 21.09, CRITICAL 1): сверка по подстроке
            # «pause.py» разрешала и СНЯТИЕ — агент своей же командой снимал
            # паузу владельца. Снимает её только он, бот и панель идут мимо хука.
            проба("БОЛЬНОЙ СЛУЧАЙ: снять паузу агенту нельзя", 2,
                  реш("Bash", {"command": "python3 scripts/pause.py --снять"})[0])
            проба("и поставить свою — тоже нельзя", 2,
                  реш("Bash", {"command": "python3 scripts/pause.py --поставить моя"})[0])
            # БОЛЬНОЙ СЛУЧАЙ 26.09.2026: паузу поставила проба смены, а сторож
            # подписал её владельцем и запер смену до его слова. Чужая пауза
            # остаётся чужой, СВОЯ снимается своими руками.
            файл.write_text('{"почему": "проба смены", "кто": "смена"}',
                            encoding="utf-8")
