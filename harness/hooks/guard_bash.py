# ЖИВОЙ УЧЁТ ЗАКАЗЧИКА — ТОЛЬКО ЧТЕНИЕ. Слово владельца 29.09.2026: «мой склад
# который прямо сейчас работает <…> сделай прибор который тебе лично запрещает
# какие либо удаления или правки, к живому учёту заказчика у агента только чтение, а удаление и правки
# только через код crm и только для тестовых данных».
#
# ЧТО ОХРАНЯЕТСЯ. В учёте живёт РАБОЧАЯ база заказчика: товары, заказы,
# покупатели, остатки. Один PUT по ошибочному id перепишет карточку, которую
# ведёт человек, а DELETE снесёт её вовсе — и восстановить это нам нечем: чужая
# система, чужие резервные копии, чужой аудит. Правило «я буду аккуратен» здесь
# не носитель: оно держится вниманием, а внимание кончается на третьем часу
# смены.
#
# ЧТО ИМЕННО ОТМЕНЯЕТСЯ: любая команда, которая несёт адрес учёта и метод
# ЗАПИСИ (POST/PUT/PATCH/DELETE — в явном виде или через `-d`, который в curl
# сам означает POST). Чтение не трогается вовсе: GET к тому же адресу проходит.
#
# ЧЕГО ЭТО ПРАВИЛО НЕ ЗАКРЫВАЕТ, И ЭТО НАЗВАНО ВСЛУХ: хук видит только КОМАНДЫ
# оболочки. Запись из кода службы закрывает второй носитель — `pushEnabled` у
# транспорта адаптера (`transport.ts`: при выключенной выгрузке клиент
# ФИЗИЧЕСКИ умеет только GET), и его проба. Два пути — два носителя; один общий
# был бы либо дырявым, либо неработающим.
# Рассказ о записи — не запись. Правило ищет в ПОЛНОМ тексте команды (адрес и
# метод почти всегда стоят в кавычках, а «видимое» их гасит), и без этой
# прополки под запрет попадали бы две законные вещи: печать строки о запрете
# (`echo`) и ЗАПИСЬ ФАЙЛА с текстом правила через heredoc — на второй правило
