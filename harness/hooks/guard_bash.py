# Признак СТЕНДА: только с ним путь к данным продукта берётся из окружения.
# Без признака одна переменная в профиле или в живой оболочке снимала бы правила
# живого учёта на КАЖДОМ вызове хука — и молча (ревью кода 13.10.2026). Тот же
# приём, что у двери необратимого (`HARNESS_OWNER_WORD_STEND`).
КЛЮЧ_СТЕНДА_ПРОДУКТА = "HARNESS_PRODUCT_CONF_STEND"


def _данные_продукта() -> dict:
    """Данные ЭТОЙ установки о продукте. Путь из окружения — только на стенде."""
    путь = (os.environ.get("HARNESS_PRODUCT_CONF")
            if os.environ.get(КЛЮЧ_СТЕНДА_ПРОДУКТА) == "1" else "")
    if not путь:
        корень = (read_conf().get("PROJECT_DIR") or "").strip()
        путь = os.path.join(корень, "product-local.conf") if корень else ""
    if not путь:
        return {}
    данные = read_conf(путь)
    # read_conf подмешивает свои умолчания (AUTONOMY и каталоги) — здесь нужны
    # только ключи учёта, остальное пришло бы чужими значениями.
    return {к: v for к, v in данные.items() if к.startswith("ERP_")}


