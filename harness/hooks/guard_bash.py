def _каталог_перед(текст: str, поз: int) -> str | None:
    """Каталог последнего cd перед позицией, если он назван абсолютно."""
    cd = [m for m in CD_CMD.finditer(текст) if m.end() <= поз]
    доводы = _strip_comment(cd[-1].group(1)).split() if cd else []
    каталог = os.path.expandvars(доводы[0].strip("'\"")) if доводы else ""
    return каталог if каталог.startswith("/") else None


def _путь_цели(довод: str, текст: str, поз: int) -> str | None:
    """Путь, который увидит оболочка: $VAR раскрыт, относительный — от cd, // и .. сняты."""
    путь = os.path.expandvars(довод)
    if not путь.startswith("/"):
        база = _каталог_перед(текст, поз)
        if база is None:
            return None
        путь = база + "/" + путь
    return "/" + os.path.normpath(путь).lstrip("/")


def _живые_сокеты() -> set[str]:
    """Пути unix-сокетов, у которых сейчас есть живой владелец (/proc/net/unix)."""
    живые = set()
    try:
        with open("/proc/net/unix", encoding="utf-8", errors="replace") as f:
            for строка in f.readlines()[1:]:
                поля = строка.split(None, 7)
                if len(поля) == 8:
                    живые.add(поля[7].strip())
    except OSError:
        return set()
    return живые


def _гнездо_живое(путь: str) -> bool:
    """Держит ли кто-то живой сокет на этом пути или под ним."""
    цели = {os.path.normpath(путь), os.path.realpath(путь)}
    for сокет in _живые_сокеты():
        if any(сокет == ц or сокет.startswith(ц + "/") for ц in цели):
            return True
    return False


