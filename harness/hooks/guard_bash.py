# ([[heredoc-with-deploy-name-cancelled]]). Ложный запрет хуже пропуска: от него
# избавляются обходом всей защиты.
ПЕЧАТЬ_ТЕКСТА = re.compile(r"(?:^|[;|&]|\n)\s*(?:echo|printf)\b[^\n;|&]*", re.I)


