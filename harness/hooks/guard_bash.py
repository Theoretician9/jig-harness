# ── Учёт заказчика: правила ДАННЫЕ, и лежат они ВНЕ пакета ─────────────────
# Адрес учётной системы, имя файла рабочего ключа, пути заглушки и числа снятой
# копии — информация о ПРОДУКТЕ владельца, а харнес отдают другим людям (его
# слово 13.10.2026: публичная сборка уезжает без сведений о продукте). Поэтому
# значения живут в `product-local.conf` рядом с проектом: он в гите установки и
