- Правь ТОЛЬКО файл $TON — именно по этому пути и с этим именем. Это ДОКУМЕНТ,
  а не код: русское имя файла здесь правильное, переименовывать его нельзя
  (правило про латиницу в проекте касается только файлов кода: .py, .sh, .ts,
