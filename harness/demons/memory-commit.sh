#!/usr/bin/env bash
# memory-commit.sh — правки памяти, сделанные с панели, попадают в репозиторий.
#
# Что держит: память — часть кода, а не база. Владелец правит запись в браузере
# (11.09.2026: «Нужна возможность работать с памятью»), файл меняется сразу, но
# без коммита он живёт только на этой машине и исчезнет при первой же раскладке
# пакета. Решение, требующее «чтобы агент потом не забыл закоммитить», решением
# не является — поэтому коммит делает демон.
#
# Почему `git commit -o`: коммитятся ТОЛЬКО пути памяти, минуя индекс. Агент в
# этот момент может собирать свой коммит, и общий индекс увёл бы в него чужие
# файлы (грабля «параллельный стейджинг при идущем коммите»).
#
# Чем доказывается: `bash scripts/test_memory_commit.sh` — свой репозиторий,
# свой канал, своя доска. Судья ОДИН: второй самотест внутри демона мерил бы то
# же самое своей меркой, и через месяц они разошлись бы в правилах.
#
# Гейты pre-commit работают как обычно: правка памяти проходит те же ворота,
# что и любая другая. Не прошла — демон говорит об этом в лог и в канал, а не
# пытается обойти.
set -euo pipefail


# Путь к загрузчику — от САМОГО файла, а не через $PROJECT_DIR: его демон
# читает ИЗ КОНФИГА ниже, а cron окружения не даёт, и под `set -u` строка
# роняла демона каждые десять минут (поймано живым прогоном 21.09.2026 —
# в журнале три подряд «PROJECT_DIR: unbound variable»).
# shellcheck disable=SC1091
. "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/../../scripts/lib/config.sh"
CONF="${HARNESS_INSTALL_CONF:-$(konf_koren)/install.conf}"
# Пороги — из общего загрузчика, а не числом в коде (находка ревью M-09).
# Окружение СТАРШЕ файла: так проба задаёт свой порог, не трогая боевой.
konf_zagruzit MEMORY_COMMIT_FAILS_MAX
# Значение конфига — до комментария: строка «PROJECT_DIR="…"   # каталог кода»
# без этой обрезки приезжала в cd целиком (поймано первым же прогоном).
znachenie() { grep -E "^$1=" "$CONF" 2>/dev/null | head -1 | cut -d= -f2- \
    | sed 's/[[:space:]]*#.*$//' | tr -d '"' | xargs || true; }
PROJECT_DIR="$(znachenie PROJECT_DIR)"
PROJECT_DIR="${PROJECT_DIR:?пуст PROJECT_DIR — не прочитан паспорт установки}"
LOG_DIR="$(znachenie LOG_DIR)"
# Места, не названные паспортом, берутся ОТ КОРНЯ установки — общим загрузчиком,
# а не зашитым «/var/log/harness»: на чужой машине его нет.
KOREN="$(konf_koren)"
STATE_DIR="${STATE_DIR:-$(znachenie STATE_DIR)}"
STATE_DIR="${STATE_DIR:-$KOREN/state}"
LOG_DIR="${LOG_DIR:-$KOREN/log}"
HEARTBEAT_DIR="${HEARTBEAT_DIR:-$(znachenie HEARTBEAT_DIR)}"
HEARTBEAT_DIR="${HEARTBEAT_DIR:-$STATE_DIR/heartbeat}"
MEMORY_SUBDIR="память"


say() { printf '%s  %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$*"; }

# «Коммитить нечего» — отдельное РЕШЕНИЕ, и судится оно пробой (находка ревью
# M-08: инвариант «нечего коммитить — владельцу не писать» был без пробы, и
# мутация «if false» оставляла стенд зелёным). Отличать это от красного гейта
# обязательно: 13.09.2026 владелец получил тревогу «не прошли проверки», когда
# файл пробы исчез между обходом и коммитом, а все гейты прошли.
nechego_kommitit() {  # $1 — вывод git commit
    printf '%s' "${1:-}" | grep -q \
        "no changes added to commit\|nothing to commit\|nothing added to commit"
}

# Файл вывода коммита — в СВОЁМ каталоге журналов, а не в общем /tmp (ревью
# 27.09, M-06): прежний путь был зашит буквой, и прогон стенда затирал его под
# боевым сторожем — совпади он с обходом cron, владелец услышал бы про
# «красный гейт проба_гейта», которого нет.
VYVOD="${MEMORY_COMMIT_OUT:-$LOG_DIR/pamyat-kommit.вывод}"
# Счёт неудач подряд: ОДИН литерал на все пути (M-10) и объявление ВЫШЕ всех
# веток выхода — функция, вызванная до своего определения, в bash молча
# пустеет (память: функция-вызвана-до-определения).
FAILS_FILE="$LOG_DIR/pamyat-kommit.неудач"
zabyt_neudachi() { rm -f "$FAILS_FILE" || say "счёт неудач не снят: $FAILS_FILE"; }

# ── пауза владельца: демон, который ПИШЕТ, на паузе молчит ──────────────────
# Ревью спеки остановки 21.09.2026 (CRITICAL 4): владелец нажал «стоп», а
# фоновая механика продолжала менять репозиторий — коммитить память и заводить
# карточки чужой рукой. Пауза обязана останавливать не только смену.
if python3 "$PROJECT_DIR/scripts/pause.py" --идёт-ли 2>/dev/null; then
    say "владелец поставил паузу — не трогаю репозиторий"
    # Метка — про ПРОГОН, а не про работу: демон проснулся и принял решение.
    # 23–26.09.2026 владелец стоял на паузе, демон честно выходил здесь — и
    # сводка четверо суток звала мёртвым живого ([[a-sign-true-while-work-stands-still]]).
    mkdir -p "$HEARTBEAT_DIR" && : > "$HEARTBEAT_DIR/pamyat-kommit"
    exit 0
fi

cd "$PROJECT_DIR"

# Прополка указаний — ПЕРЕД сверкой изменений: она сама может их создать.
# Файл указаний упирался в потолок (7888 из 8000 знаков 13.09.2026), а
# держался ручной прополкой посреди другой работы — вниманием, а не
# механизмом. Прополка работает только при переполнении и ничего не теряет:
# длинная цитата уезжает в свою запись памяти, в указаниях остаётся начало и
# ссылка. Отказ прополки не мешает коммиту: память важнее её объёма.
if [ -x "$PROJECT_DIR/scripts/weed-the-orders.py" ]; then
    python3 "$PROJECT_DIR/scripts/weed-the-orders.py" 2>&1 | sed 's/^/    /' || \
        say "прополка указаний отказала — продолжаю коммит"
fi

# Что изменилось в памяти: и правки, и новые записи.
# Тот же quotepath: без него имя записи кириллицей приезжает в кавычках и
# октальными escape'ами — и сообщение коммита называло бы «\320\277…md»
# вместо имени записи, а сверка состава не нашла бы названного файла.
CHANGED="$(git -c core.quotepath=false status --porcelain -- "$MEMORY_SUBDIR" 2>/dev/null || true)"
if [ -z "$CHANGED" ]; then
    say "правок памяти нет"
    zabyt_neudachi        # не отказ гейта — счёт начинается заново (M-02)
    mkdir -p "$HEARTBEAT_DIR"
    : > "$HEARTBEAT_DIR/pamyat-kommit"
    exit 0
fi

COUNT="$(printf '%s\n' "$CHANGED" | grep -c . || true)"
say "правок памяти: $COUNT"
printf '%s\n' "$CHANGED" | sed 's/^/    /'

# НОВАЯ запись памяти в коммит сама не попадёт: `git commit --only <путь>`
# берёт только ОТСЛЕЖИВАЕМЫЕ пути, а неотслеженный файл остаётся снаружи —
# молча. Живой случай 28.09.2026: коммит bf91834 назвал в сообщении MEMORY.md
# и editing-a-running-bash-script.md, а внёс один MEMORY.md. Ссылка в индексе
# памяти была, файла в гите не было — преемник по [[…]] не нашёл бы ничего.
# Индекс трогаем ТОЛЬКО путями памяти: чужие staged-файлы смены остаются как
# есть, их коммитит она сама.
# `core.quotepath=false` обязателен: имена записей кириллицей git иначе отдаёт
# в октальных escape-последовательностях и в кавычках — `git add` такого пути не
# находит, и правка тихо остаётся снаружи (та же грабля дала 27.09 ложные 246
# расхождений при сверке продукта с гитом).
NOVYE="$(git -c core.quotepath=false ls-files --others --exclude-standard \
    -- "$MEMORY_SUBDIR" 2>/dev/null || true)"
if [ -n "$NOVYE" ]; then
    say "новых записей: $(printf '%s\n' "$NOVYE" | grep -c . || true) — беру в индекс"
    # Построчно: имя записи бывает из двух слов, и `for` порвал бы его по пробелу.
    printf '%s\n' "$NOVYE" | while IFS= read -r fajl; do
        [ -n "$fajl" ] || continue
        git add -- "$fajl" || say "не взялся в индекс: $fajl"
    done
fi

# Сообщение коммита называет ИМЕНА записей: по журналу панели потом видно, кто
# и когда правил, а по истории — что именно менялось.
NAMES="$(printf '%s\n' "$CHANGED" | awk '{print $NF}' | xargs -n1 basename 2>/dev/null | paste -sd', ' - || true)"
MSG="Правка памяти с панели: ${NAMES:-записи}

Записи изменены владельцем через веб-панель; демон pamyat-kommit переносит их
в репозиторий, потому что память — часть кода, а не база.

Co-Authored-By: Claude Opus 5 <noreply@anthropic.com>"

if git commit -o "$MEMORY_SUBDIR" -m "$MSG" >"$VYVOD" 2>&1; then
    say "закоммичено: $(git log --oneline -1)"
    # И-4 на своём же коммите: сообщение НАЗЫВАЕТ файлы, и они обязаны в нём
    # быть. Молчаливое расхождение и было бедой bf91834 — имя в истории,
    # файла нет. Судим по составу коммита, а не по своему списку.
    V_KOMMITE="$(git -c core.quotepath=false show --name-only --format= HEAD 2>/dev/null \
        | while IFS= read -r fajl; do [ -n "$fajl" ] && basename "$fajl"; done)"
    POTERYANO=""
    printf '%s\n' "$NAMES" | tr ',' '\n' | while IFS= read -r imya; do
        imya="$(printf '%s' "$imya" | xargs || true)"
        [ -n "$imya" ] || continue
        printf '%s\n' "$V_KOMMITE" | grep -qxF "$imya" || printf '%s\n' "$imya"
    done > "$VYVOD.назвал-не-внёс"
    # `grep -c` при нуле ПЕЧАТАЕТ 0 и выходит единицей: с «|| echo 0» в
    # переменной оказывалось «0\n0», и сверка жаловалась на здоровом коммите.
    POTERYANO="$(grep -c . "$VYVOD.назвал-не-внёс" 2>/dev/null || true)"
    case "$POTERYANO" in ""|*[!0-9]*) POTERYANO=0 ;; esac
    if [ "$POTERYANO" != 0 ]; then
        say "БЕДА: коммит назвал файлы, которых в нём нет ($POTERYANO):"
        sed 's/^/    /' "$VYVOD.назвал-не-внёс"
        mkdir -p "$HEARTBEAT_DIR" && : > "$HEARTBEAT_DIR/pamyat-kommit"
        exit 1
    fi
    # Счёт неудач подряд обнуляется, долг с доски снимается: висящая запись о
    # беде, которой больше нет, стоит внимания смены столько же, сколько
    # настоящая. Обе уборки НЕ роняют сторожа (M-04): отказ `rm` под set -e
    # обрывал его после успешного коммита, метка пульса не ставилась, и сторож
    # пульса называл живого мёртвым.
    zabyt_neudachi
    python3 "$PROJECT_DIR/scripts/board.py" --снять память-не-коммитится >/dev/null 2>&1 || true
else
    # «Коммитить нечего» и «гейты покраснели» — РАЗНЫЕ вещи, и владельцу их
    # нельзя называть одинаково. Живой случай 13.09.2026 в 00:20: демон увидел
    # временный файл пробы, взялся его коммитить, файл к тому моменту убрали —
    # и владелец получил тревогу «не прошли проверки», хотя все гейты прошли.
    # Его внимание — расходуемый ресурс (правило владельца 12.09), и тратить
    # его на исчезнувший файл нельзя.
    if nechego_kommitit "$(cat "$VYVOD" 2>/dev/null || true)"; then
        say "коммитить нечего: правка исчезла между обходом и коммитом — владельцу не пишу"
        # Счёт обнуляется и здесь (ревью 27.09, M-02): он копился только в
        # ветке отказа, а снимался только в ветке удачи. Любой другой выход
        # оставлял счёт выше порога, и о СЛЕДУЮЩЕМ, совсем новом отказе
        # владелец не узнавал никогда: ни «первое сообщение», ни «уже час».
        zabyt_neudachi
        sed 's/^/    /' $VYVOD | tail -5
        mkdir -p "$HEARTBEAT_DIR"
        : > "$HEARTBEAT_DIR/pamyat-kommit"
        exit 0
    fi
    say "коммит НЕ прошёл (гейты) — подробности ниже"
    sed 's/^/    /' $VYVOD | tail -20
    # Причина в сообщении владельцу — та, что видна в выводе: имя красного
    # гейта. «Не прошли проверки» без имени заставляет его спрашивать меня.
    GATE_NAME=$(grep -m1 "GATE FAIL" $VYVOD | sed 's/.*GATE FAIL: //')

    # Счёт неудач ПОДРЯД. Владелец 27.09.2026 о прежнем тексте: «И написано
    # "разберусь". В итоге это доходит то того что разбираешься?» — не
    # доходило: за словом не стояло ни задачи в карте, ни второй попытки, и
    # если смена не читала канал, не разбирался никто.
    #
    # Правда в том, что вторая попытка ЕСТЬ: демон ходит каждые десять минут и
    # повторит сам, правка никуда не делась. Про это и говорим. А вот отказ,
    # который держится дольше порога, — уже беда: он виден смене на доске и
    # назван владельцу ОДИН раз, а не каждые десять минут (13 отказов за месяц
    # по журналу — редкость, но час красного гейта дал бы шесть сообщений).
    # Форма счёта проверяется ДО арифметики (M-03): `$(( "1 2" + 1 ))` — не
    # ошибка значения, а синтаксическая ошибка bash: она обрывает весь
    # составной if, сторож проскакивает свой exit 1, ставит метку пульса и
    # выходит нулём. Правка памяти при этом не в гите, а по метке и коду
    # возврата сторож выглядит здоровым — каждые десять минут.
    FAILS_ROW=$(cat "$FAILS_FILE" 2>/dev/null || echo 0)
    case "$FAILS_ROW" in ""|*[!0-9]*) FAILS_ROW=0 ;; esac
    FAILS_ROW=$((FAILS_ROW + 1))
    # Умолчание НИЖЕ загрузчика: стоя выше, оно сделало бы ключ мёртвым
    # ([[default-above-loader-kills-setting]]).
    FAILS_MAX="${MEMORY_COMMIT_FAILS_MAX:-6}"
    # Запись счёта не должна вставать МЕЖДУ отказом и словом владельцу:
    # нечитаемый файл (скажем, созданный однажды из-под root) ронял сторожа
    # под set -e до отправки, и владелец молчал обход за обходом (M-03).
    printf '%s\n' "$FAILS_ROW" > "$FAILS_FILE" || say "счёт неудач не записался"

    if [ "$FAILS_ROW" = 1 ] && [ -x "$PROJECT_DIR/scripts/tg_send.sh" ]; then
        bash "$PROJECT_DIR/scripts/tg_send.sh" \
            "Правку памяти с панели пока не сохранил в хранилище кода: красный гейт${GATE_NAME:+ «$GATE_NAME»}. Файл цел, повторю сам на следующем обходе — делать ничего не нужно." >/dev/null 2>&1 || true
    fi

    if [ "$FAILS_ROW" -ge "$FAILS_MAX" ]; then
        # Долг на доску: стартовый отчёт смены её читает, и преемник увидит
        # беду, даже если канал никто не открывал.
        python3 "$PROJECT_DIR/scripts/board.py" --сказать память-не-коммитится \
            "правка памяти не уходит в гит ${FAILS_ROW} обходов подряд, красный гейт${GATE_NAME:+ «$GATE_NAME»}" \
            >/dev/null 2>&1 || say "доска не приняла запись о долге"
        if [ "$FAILS_ROW" = "$FAILS_MAX" ] && [ -x "$PROJECT_DIR/scripts/tg_send.sh" ]; then
            bash "$PROJECT_DIR/scripts/tg_send.sh" \
                "Правка памяти не уходит в код уже ${FAILS_ROW} обходов подряд: красный гейт${GATE_NAME:+ «$GATE_NAME»} сам не чинится. Это уже не ожидание — долг записан смене на доску." >/dev/null 2>&1 || true
        fi
    fi
    # Метка — про ПРОГОН, а не про удачу (M-05): обход состоялся и решение
    # принято. Без неё сторож пульса объявлял мёртвым живого сторожа уже на
    # двадцатой минуте красного гейта, и владелец получал два противоположных
    # сообщения об одном и том же.
    mkdir -p "$HEARTBEAT_DIR" && : > "$HEARTBEAT_DIR/pamyat-kommit"
    exit 1
fi

mkdir -p "$HEARTBEAT_DIR"
: > "$HEARTBEAT_DIR/pamyat-kommit"
