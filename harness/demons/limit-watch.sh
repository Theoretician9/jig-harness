#!/usr/bin/env bash
# Лимит подписки — владельцу СРАЗУ, а не на ближайшем обходе сторожа.
#
# Владелец 13.09.2026: «Ну вот опять мы сейчас упёрлись в лимит а я никаких
# сообщений об этом не вижу, почему это сразу не ловится как только появляется
# сообщение о лимите? Как сделать срабатывание мгновенным?»
#
# Замер той же ночи: сообщение дошло за 5 минут (его слова: «Сообщение пришло
# через 5 минут»), и это не задержка порога — порог доказанного лимита
# LIMIT_SAY_MIN=3 минуты, — а ожидание обхода: session-warden ходит раз в
# десять минут, и в худшем случае владелец узнаёт через 13.
#
# Этот сторож ходит РАЗ В МИНУТУ и делает ровно одно: смотрит, есть ли в
# журнале сессии свежий отказ 429. Больше ничего: тяжёлые ветки (ротация,
# пульс, приёмка) остаются у session-warden, иначе ежеминутный обход стоил бы
# как десятиминутный.
#
# Метка LIMIT_STATE — ОБЩАЯ с session-warden: у факта «о лимите владельцу
# сказано» один судья, и два сторожа не пишут владельцу дважды.
set -euo pipefail
export LC_ALL=C.UTF-8

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck disable=SC1091
source "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/../../scripts/lib/config.sh"
# Нажатия в панель агента — общей дверью (scripts/lib/pane.sh): те же семь
# строк уже лежали двумя копиями у сторожа сессий и диспетчера канала.
source "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/../../scripts/lib/pane.sh"
konf_zagruzit

# Каталог проекта — из паспорта установки: умолчание с чужим путём молча
# уводит установку нового владельца в несуществующий каталог.
PROJECT_DIR="${PROJECT_DIR:?пуст PROJECT_DIR — не прочитан паспорт установки}"
HEARTBEAT_DIR="${HEARTBEAT_DIR:-$LOG_DIR/heartbeat}"
SERVICE_LOCKS_SUBDIR="${SERVICE_LOCKS_SUBDIR:-services}"
WATCH_LOG="$LOG_DIR/limit-watch.log"

say() { printf '%s  %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$*" >>"$WATCH_LOG"; }

# Свой лок: ежеминутный обход не должен ни ждать десятиминутного, ни мешать
# ему. Занят своим же прошлым запуском — молча уступаем, через минуту придёт
# следующий.
mkdir -p "$LOG_DIR/locks/$SERVICE_LOCKS_SUBDIR" "$HEARTBEAT_DIR"
exec 9>>"$LOG_DIR/locks/$SERVICE_LOCKS_SUBDIR/limit-watch.lock"
flock -n 9 || exit 0

# Транскрипт текущей сессии ищется так же, как у session-warden: каталог
# проекта в ~/.claude/projects, самый свежий .jsonl.
PROJECTS_DIR="${CLAUDE_PROJECTS_DIR:-$HOME/.claude/projects}"
PROJECT_TRANSCRIPTS=""
for enc in "${PROJECT_DIR//\//-}" "$(printf '%s' "$PROJECT_DIR" | sed 's/[^a-zA-Z0-9]/-/g')"; do
    if [ -d "$PROJECTS_DIR/$enc" ]; then PROJECT_TRANSCRIPTS="$PROJECTS_DIR/$enc"; break; fi
done
[ -n "$PROJECT_TRANSCRIPTS" ] || { : >"$HEARTBEAT_DIR/limit-watch"; exit 0; }

TRANSCRIPT=$(find "$PROJECT_TRANSCRIPTS" -mindepth 1 -maxdepth 1 -name '*.jsonl' -type f \
             -printf '%T@ %p\n' 2>/dev/null | sort -nr | head -1 | cut -d' ' -f2- || true)
[ -n "$TRANSCRIPT" ] || { : >"$HEARTBEAT_DIR/limit-watch"; exit 0; }

# Факт берётся общим прибором — тем же, что зовёт session-warden.
LIMIT_MIN=$(python3 "$PROJECT_DIR/scripts/limit-in-log.py" "$TRANSCRIPT" 2>/dev/null || true)
: >"$HEARTBEAT_DIR/limit-watch"

# Пауза владельца гасит и этот прибор: он шлёт владельцу «работа встала» и
# «работа возобновилась», а на паузе стоять — норма, а не беда.
if python3 "$PROJECT_DIR/scripts/pause.py" --идёт-ли 2>/dev/null; then
    exit 0
fi

# Имя метки знает ОДИН судья (scripts/limit_mark.py) — здесь его нет вовсе:
# имя, собранное в трёх местах, разъезжается молча (ревью 27.09, F-lim-05).
MARK="python3 $PROJECT_DIR/scripts/limit_mark.py"
# Немота — тем же прибором, что у десятиминутного сторожа (scripts/stall-in-log.py).
# Раньше здесь стоял mtime транскрипта, и это была ВТОРАЯ мерка одной величины:
# файл обновляет любая строка — отказ 429, пинок сторожа, — а работой считается
# только успешный ответ. Улика 26.09.2026 (ревью 27.09, F-01): 21:20 сторож
# пишет «тишина 25 мин — пробую разбудить смену», 21:21 этот демон пишет
# владельцу «работа пошла снова, простой 0 мин». Таких «простой 0 мин» в
# журнале пять.
#
# Пусто — успешных ответов в журнале нет вовсе: работа НЕ доказана, и
# возобновления быть не может. Ставим заведомо большое число вместо тихого
# нуля: «не прочитали» не равно «только что работала».
LIMIT_SAY_MIN="${LIMIT_SAY_MIN:-3}"
WORK_AGE_MIN=$(python3 "$PROJECT_DIR/scripts/stall-in-log.py" "$TRANSCRIPT" 2>/dev/null || true)
# Успешных ответов в журнале нет вовсе — работа НЕ доказана. Берём заведомо
# большую немоту: молчание длиной в неделю честнее тихого нуля, который
# означал бы «только что работала».
[ -n "$WORK_AGE_MIN" ] || WORK_AGE_MIN=10080
LIMIT_FRESH_MIN="${LIMIT_FRESH_MIN:-5}"

# Свежий ли отказ. Пусто — отказов в журнале нет вовсе.
SVEZHIJ_OTKAZ=0
[ -n "$LIMIT_MIN" ] && [ "$LIMIT_MIN" -le "$LIMIT_FRESH_MIN" ] && SVEZHIJ_OTKAZ=1

# ── возобновление: тоже СРАЗУ, а не на ближайшем десятиминутном обходе ──────
# Симметрия обязательна: сказать «работа встала» за минуту и молчать десять
# минут о том, что она пошла, — значит держать владельца в тревоге дольше,
# чем длился простой. Метка общая, поэтому дважды о возобновлении не скажут:
# кто первый её снял, тот и говорит.
#
# НО свежесть транскрипта сама по себе возобновлением НЕ является: пока сессия
# стоит в лимите, каждая её попытка дописывает в журнал запись об ОТКАЗЕ и
# обновляет mtime файла. 13.09.2026 это дало владельцу цикл сообщений
# «встала → возобновилась → встала» с простоем «0 мин», и он написал: «Не
# верно определяет что работа вознобновилась и шлёт мне эти сообщения пока
# она стоит… Зачем мне этот спам». Тот же класс, что и
# [[api-failures-counted-as-work]]: отказ выглядит работой, только смотрели
# тогда на записи, а здесь — на время файла.
#
# Поэтому возобновление требует ДВУХ условий: журнал свеж И свежего отказа в
# нём нет.
if $MARK --стоит-ли && [ "$WORK_AGE_MIN" -lt "$LIMIT_SAY_MIN" ] \
   && [ "$SVEZHIJ_OTKAZ" -eq 0 ]; then
    # Метку читает, снимает и облекает в слова ОДИН судья — limit_mark.py.
    # 27.09.2026 знание о её двух полях жило в двух демонах, и этот писал одно
    # поле вместо двух: повод терялся, а читатель по отсутствующему полю
    # утверждал «признака лимита не было» сразу после «упёрся в лимит».
    SNYATO=$(python3 "$PROJECT_DIR/scripts/limit_mark.py" --снять 2>/dev/null) || SNYATO=""
    # Пусто — метки не было или судья не ответил. Своей вести здесь нет и быть
    # не должно: четвёртая формулировка вне судьи — это четвёртый источник
    # правды (ревью 27.09, F-lim-07), а «возобновилась» без метки — дубль с
    # ложным «0 мин» (F-lim-03).
    if [ -z "$SNYATO" ]; then
        say "метку снять не вышло или её не было — о возобновлении молчу"
        exit 0
    fi
    DOWN_MIN=$(printf '%s' "$SNYATO" | cut -f1)
    POVOD=$(printf '%s' "$SNYATO" | cut -f2)
    VEST=$(printf '%s' "$SNYATO" | cut -f3)
    # Пустая весть — метка устарела (её ставила уже другая смена) или смена
    # стояла у приглашения без работы (повод blocked): не новость владельцу.
    if [ -z "$VEST" ]; then
        say "весть пуста (простой ${DOWN_MIN:-?} мин, повод ${POVOD:-неизвестен}) — снял молча, владельцу не пишу"
        exit 0
    fi
    say "работа пошла снова (простой ${DOWN_MIN:-?} мин, повод ${POVOD:-неизвестен}) — говорю владельцу"
    bash "$PROJECT_DIR/scripts/tg_send.sh" --несмотря-на-лимит \
        "$VEST Продолжаю с того места, где остановился." \
        >/dev/null 2>&1 || say "о возобновлении сказать не удалось"
    exit 0
fi

# ── подъём РОВНО в момент обновления ───────────────────────────────────────
# Владелец 17.10.2026: «дернуть он должен ровно в тот момент когда лимит
# обновится, чтобы работа началась прям сразу. Ну пусть там с задержкой в 10
# секунд, на всякий случай, вдруг там рассинхрон будет небольшой».
#
# Раньше смену будил только десятиминутный session-warden, и его пинок приходил
# когда угодно в пределах десяти минут после обновления. Час обновления лежит В
# МЕТКЕ числом, поэтому ждать обхода незачем: ежеминутный сторож досыпает до
# этой секунды сам.
#
# ПИНОК ОДИН НА ОДИН СБРОС, и это не кулдаун по времени. Час приходит из ЧУЖОГО
# поля (resetsAt печатает CLI), и ревью 17.10.2026 замерило цену ошибки в нём:
# час в прошлом давал пинок каждые десять минут в ЖИВОЙ лимит — тридцать за
# окно, каждый ценой полного шага агента, — и писал в журнал «лимит обновился»
# про сброс суточной давности. Поэтому в метке пинка лежит САМО ЧИСЛО сброса:
# тот же сброс второй раз не будит, а новый сброс (новый лимит) будит снова.
# Предохранитель от часа «завтра» остаётся у десятиминутного сторожа: у него
# есть LIMIT_KICK_MAX_MIN, который будит смену в любом случае.
LIMIT_KICK_DELAY_SEC="${LIMIT_KICK_DELAY_SEC:-10}"
LIMIT_SAY_MIN="${LIMIT_SAY_MIN:-3}"
if $MARK --стоит-ли; then
    SBROS_STOYASHCHEJ=$(python3 "$PROJECT_DIR/scripts/limit_mark.py" --сброс-стоящей 2>/dev/null) || SBROS_STOYASHCHEJ=""
    KICK_DONE="$LOG_DIR/лимит-подписки.пинок-сброса"
    SBROS_RAZBUZHEN=$(cat "$KICK_DONE" 2>/dev/null || true)
    if [ -n "$SBROS_STOYASHCHEJ" ] && [ "$SBROS_RAZBUZHEN" != "$SBROS_STOYASHCHEJ" ]; then
        SEJCHAS=$(date +%s)
        ZHDAT=$(( SBROS_STOYASHCHEJ + LIMIT_KICK_DELAY_SEC - SEJCHAS ))
        if [ "$ZHDAT" -gt 70 ]; then
            : # до обновления далеко — панель не трогаем: пинок стоит полного шага агента
        elif [ "$WORK_AGE_MIN" -lt "$LIMIT_SAY_MIN" ]; then
            # Смена уже пишет в журнал — будить нечего, и пинок перебил бы её ход.
            say "сброс прошёл, но смена работает (последний ответ ${WORK_AGE_MIN} мин назад) — не бужу"
            printf '%s' "$SBROS_STOYASHCHEJ" > "$KICK_DONE"
        else
            # Доспать до самой секунды обновления: обход приходит в начале
            # минуты, а сброс может быть в её середине.
            [ "$ZHDAT" -gt 0 ] && sleep "$ZHDAT"
            printf '%s' "$SBROS_STOYASHCHEJ" > "$KICK_DONE"
            date +%s > "$LOG_DIR/лимит-подписки.пинок"   # общая метка кулдауна сторожей
            # Пинок НЕ поручает говорить владельцу: о возобновлении скажет тот,
            # кто снимет метку, а первое слово смены дверь всё равно придержит,
            # пока метка стоит (ревью 17.10.2026).
            if pane_kick "[сторож лимита] Лимит подписки обновился — продолжай текущий шаг с того места, где он оборвался: сверься с STATE.md и docs/handover/ и проверь \$LOG_DIR/inbox/."; then
                say "пинок отдан: сброс $SBROS_STOYASHCHEJ, ждали ${ZHDAT}с, смена молчала ${WORK_AGE_MIN} мин"
            else
                say "пора будить (сброс $SBROS_STOYASHCHEJ), но пинок не отдан: ${PANE_REFUSAL:-причина не названа}"
            fi
        fi
    fi
fi

[ -n "$LIMIT_MIN" ] || exit 0

# Отказ должен быть СВЕЖИМ: прошедший лимит («был час назад», а смена уже
# работает) поднял бы тревогу на ровном месте — сигнал без различения
# здорового и больного состояния (память: signal-without-distinction).
[ "$SVEZHIJ_OTKAZ" -eq 1 ] || exit 0

# И смена должна МОЛЧАТЬ: отказ субагента при живой работе смены — не остановка.
[ "$WORK_AGE_MIN" -ge "$LIMIT_SAY_MIN" ] || exit 0
# if, а не «[ ... ] && exit 0»: под set -e ложное условие в конце команды
# роняет скрипт — и сообщение владельцу не ушло бы НИКОГДА, ровно в том
# случае, ради которого этот сторож написан (память: падение-под-set-e-молчит).
# Повод пишется ВМЕСТЕ со временем и тем же судьёй, что читает: здесь он
# доказан свежим отказом 429, и потерять его — значит потом сказать владельцу
# «признака лимита не было» (его снимок 27.09.2026).
# Отказ судьи НЕ гасится: метка не поставлена — значит завтра же этот сторож
# скажет владельцу то же самое, и так каждую минуту. Ревью 27.09 (F-lim-01)
# воспроизвело это стендом без судьи: два сообщения за два обхода.
# Час обновления берётся ЧИСЛОМ из журнала (его печатает сам CLI полем
# resetsAt) и кладётся В МЕТКУ: слова владельцу собирает её судья, поэтому у
# двух сторожей не может быть двух разных первых сообщений. 17.10.2026 первым
# проснулся этот, ежеминутный, и владелец получил сообщение БЕЗ времени.
SBROS_UNIX=$(python3 "$PROJECT_DIR/scripts/limit-in-log.py" --сброс-числом "$TRANSCRIPT" 2>/dev/null) || SBROS_UNIX=""
POSTAVLENO=0
python3 "$PROJECT_DIR/scripts/limit_mark.py" --поставить limit ${SBROS_UNIX:+--сброс "$SBROS_UNIX"} || POSTAVLENO=$?
if [ "$POSTAVLENO" -eq 1 ]; then
    exit 0        # метка уже стоит — о лимите сказано, повторять нечего
fi
if [ "$POSTAVLENO" -ne 0 ]; then
    say "метку лимита поставить не вышло (код $POSTAVLENO) — владельцу не пишу: иначе скажу то же самое через минуту"
    exit 1
fi
say "лимит доказан: отказ 429 ${LIMIT_MIN} мин назад, смена молчит ${WORK_AGE_MIN} мин, сброс ${SBROS_UNIX:-неизвестен} — говорю владельцу"
# Слова — у судьи метки: владельцу нужен час обновления, а не признак отказа.
# Ключ «--несмотря-на-лимит» обязателен: метка уже стоит, и дверь канала
# придержала бы ровно то единственное сообщение, которое владелец ждёт.
VEST_O_LIMITE=$(python3 "$PROJECT_DIR/scripts/limit_mark.py" --весть-о-лимите 2>/dev/null) \
    || VEST_O_LIMITE="Упёрся в лимит подписки. Скажу, как только работа пойдёт."
bash "$PROJECT_DIR/scripts/tg_send.sh" --несмотря-на-лимит "$VEST_O_LIMITE" \
    >/dev/null 2>&1 || say "о лимите сказать не удалось"
