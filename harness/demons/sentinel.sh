# Сторож сессий бежит раз в 10 минут; 25 — два периода с запасом на долгую ротацию.
CRON_STALE_MIN="${CRON_STALE_MIN:-25}"
# Сторож сессий держит лок весь свой прогон: ротация — до 24 мин, досмотр
# позднего выхода — до 30. Наблюдаемый максимум возраста метки успеха при
# ЗДОРОВОЙ работе — 38 мин (замер по sentinel.log за 04–10.09.2026); 60 —
# выше него и выше досмотра.
WARDEN_STUCK_MIN="${WARDEN_STUCK_MIN:-60}"
