#!/usr/bin/env bash
#
# sentinel.sh — сторож систем: подъём после любого падения и проверка при старте.
#
# Что держит: правило владельца 11.08.2026 — «если сессия завершилась и не
# перезапустилась, или tmux слетел целиком, или сервер перезагрузился, должен
# точно произойти запуск и проверка всех систем».
#
# Почему отдельный носитель, а не ещё одна строка в session-warden: тот бежит
# из cron, и cron — единственная точка отказа всей механики присмотра. Умер
# cron — некому запустить и сторожа сессий, а узнать об этом можно было только
# из утренней сводки, которую тоже запускает cron. Sentinel живёт на systemd:
# два независимых носителя не отказывают одинаково.
#
# Три роли, три вызова:
#   sentinel.sh            — прогон по таймеру: юниты живы? cron бежит?
#   sentinel.sh --boot     — после загрузки: дождаться агента, проверить всё,
#                            доложить владельцу одним сообщением
#   sentinel.sh --selftest — больные случаи решений (без сервера и systemd)
#
# Чем доказывается: селфтест на чистых функциях (первым — больной случай) и
# живой тестовый ребут (раздел А чек-листа приёмки).
set -uo pipefail

# Пишем и в journald (юнит), и в файл рядом с логами прочих демонов: владельцу
# в сообщениях назван именно файл, а путь в отчёте обязан существовать.
say() {
    local line; line="$(date '+%Y-%m-%d %H:%M:%S')  $*"
    printf '%s\n' "$line"
    [ -n "${LOG_DIR:-}" ] && [ -d "${LOG_DIR:-}" ] && printf '%s\n' "$line" >> "$LOG_DIR/sentinel.log" 2>/dev/null
    return 0
}

# ── Решения — чистыми функциями, чтобы гонять их без systemd и без сервера ──

# Метка heartbeat протухла = демона никто не запускает. Печатает: ок | чинить
решение_по_метке() { # $1=возраст метки в минутах (-1 = метки нет)  $2=порог  $3=окно в минутах
    # Улика 01.09.2026: сервер перезагрузился, метка была 32 мин при пороге 25 —
    # сторож объявил «cron не запускает демонов», отправил владельцу ложную
    # тревогу и вышел с кодом 1 (юнит harness-sentinel-boot повис в failed).
    # Простой выключенного сервера — не вина cron: считается только то время,
    # когда cron МОГ бежать (окно — см. окно_cron_мин).
    # Отсутствие метки — не частный случай, а бесконечный возраст: окно режет
    # и его, иначе первые минуты после ребута или раскладки, когда метки ещё
    # неоткуда взяться, читались как остановка присмотра (ревью 10.09, ops-15).
    local age="$1" limit="$2" window="$3"
    { [ "$age" -lt 0 ] || [ "$age" -gt "$window" ]; } && age="$window"
    [ "$age" -ge "$limit" ] && printf 'чинить\n' || printf 'ок\n'
}

# Состояние юнита. Печатает: ок | поднять
решение_по_юниту() { # $1=вывод systemctl is-active
    case "$1" in
        active) printf 'ок\n' ;;
        *)      printf 'поднять\n' ;;
    esac
}

# Из вывода systemd-analyze verify — только замечания про НАШ файл. verify
# тянет зависимости и жалуется на чужие юниты системы (на этой машине —
# вечное «pure-ftpd: PIDFile ... legacy directory»); без отбора сторож кричал
# бы всегда и научил бы себя не слушать. Печатает пусто = юнит здоров.
замечания_по_юниту() { # $1=путь файла юнита  $2=вывод verify
    printf '%s\n' "$2" | grep -F "$1:" || true
}

if [ "${1:-}" = "--selftest" ]; then
    ok_flag=1
    проба() { # $1=ожидание $2=функция $3..=аргументы  (последний — имя случая)
        local want="$1" fn="$2" name="${!#}" got
        got=$("$fn" "${@:3:$#-3}")
        if [ "$got" = "$want" ]; then printf '  ок    %s\n' "$name"
        else printf '  ПЛОХО %s: ждали «%s», получили «%s»\n' "$name" "$want" "$got"; ok_flag=0; fi
    }
    # БОЛЬНОЙ СЛУЧАЙ: cron перестал запускать сторожа сессий. До этого сторожа
    # такое состояние не замечал никто: и присмотр, и утренняя сводка, которая
    # могла бы о нём рассказать, запускаются тем же самым cron.
    проба чинить решение_по_метке 30 25 1000 "метка сторожа сессий протухла (30 ≥ 25) — cron не бежит, чиним"
    проба чинить решение_по_метке -1 25 1000 "метки нет вовсе — демон не запускался ни разу"
    проба ок     решение_по_метке 12 25 1000 "метка свежая (12 < 25) — cron жив, не вмешиваемся"
    проба ок     решение_по_метке 24 25 1000 "порог не достигнут (24 < 25) — граница принадлежит здоровью"
    # БОЛЬНОЙ СЛУЧАЙ 01.09.2026: сервер только что загрузился, простой — не вина cron.
    проба ок     решение_по_метке 32 25 1    "после ребута (аптайм 1 мин) метка 32 мин — cron ещё не мог бежать"
    проба чинить решение_по_метке 40 25 30   "аптайм 30 ≥ порога: cron успел бы, а метка стоит — чиним"
    # БОЛЬНОЙ СЛУЧАЙ ревью 10.09.2026 (ops-15): метки нет и взяться ей неоткуда —
    # харнес разложен минуту назад, cron тикает раз в десять. Прежняя редакция
    # звала это остановкой присмотра: отсутствие метки било мимо окна.
    проба ок     решение_по_метке -1 25 1    "метки нет, но и окно 1 мин — раскладка свежее первого тика cron"
    проба чинить решение_по_метке -1 25 26   "метки нет, а окно 26 мин переросло порог — присмотр правда стоит"
    # БОЛЬНОЙ СЛУЧАЙ 04–10.09.2026: 59 ложных тревог подряд. Метка успеха
    # стоит всю ротацию (лок), cron при этом жив — теперь о cron судит метка
    # ЗАПУСКА, а о зависании прогона — своя проба с порогом WARDEN_STUCK_MIN.
    проба ок     решение_по_метке 38 60 1000 "ротация держала лок 38 мин — прогон идёт, тревоги нет"
    проба чинить решение_по_метке 61 60 1000 "прогон не завершается больше часа — лок держит мертвец, говорим"
    # БОЛЬНОЙ СЛУЧАЙ 10.09.2026 (мутационная проба по замечанию владельца М-2):
    # порог WARDEN_STUCK_MIN подняли до 999999 — самотест остался ЗЕЛЁНЫМ, потому
    # что пороги он получал аргументами и боевого значения не видел вовсе.
    # Проверка читает СВОЙ ЖЕ исходник: сигнал с невозможным порогом не сигнал.
    дефолт_порога() { # $1 = имя переменной → её значение по умолчанию из этого файла
        sed -n "s/^$1=\"\${$1:-\([0-9]*\)}\"/\1/p" "$0" | head -1
    }
    в_пределах() { # $1=имя $2=мин $3=макс $4=имя случая
        local v; v=$(дефолт_порога "$1")
        if [ -n "$v" ] && [ "$v" -ge "$2" ] && [ "$v" -le "$3" ]; then
            printf '  ок    %s\n' "$4"
        else
            printf '  ПЛОХО %s: %s = «%s», ждали число в [%s..%s]\n' "$4" "$1" "${v:-нет}" "$2" "$3"
            ok_flag=0
        fi
    }
    в_пределах CRON_STALE_MIN 10 60 "боевой порог метки cron осмыслен (10–60 мин)"
    в_пределах WARDEN_STUCK_MIN 40 240 "боевой порог зависшего прогона осмыслен (40–240 мин)"
    if [ "$(дефолт_порога WARDEN_STUCK_MIN)" -gt "$(дефолт_порога CRON_STALE_MIN)" ] 2>/dev/null; then
        printf '  ок    порог зависания выше порога cron — иначе первый сигнал глушил бы второй\n'
    else
        printf '  ПЛОХО пороги перепутаны: зависание должно ловиться позже, чем стоящий cron\n'; ok_flag=0
    fi
    проба поднять решение_по_юниту inactive "юнит остановлен — поднять"
    проба поднять решение_по_юниту failed   "юнит упал — поднять"
    проба поднять решение_по_юниту activating "юнит завис в запуске — поднять (следующий прогон увидит active)"
    проба ок      решение_по_юниту active   "юнит работает — не трогаем"
    # БОЛЬНОЙ СЛУЧАЙ 12.08.2026: StartLimitIntervalSec стоял в секции [Service]
    # юнита harness-agent. systemd такой ключ молча игнорирует — «не сдавайся
    # после серии падений» не действовало, лимит оставался дефолтным 10s/5.
    alien="/etc/systemd/system/pure-ftpd.service:11: PIDFile= references a path below legacy directory /var/run/"
    mine="/etc/systemd/system/harness-agent.service:19: Unknown key name 'StartLimitIntervalSec' in section 'Service', ignoring."
    проба "$mine" замечания_по_юниту /etc/systemd/system/harness-agent.service \
        "$mine"$'\n'"$alien" "ключ в неверной секции — замечание про наш юнит найдено среди чужого шума"
    проба "" замечания_по_юниту /etc/systemd/system/harness-agent.service "$alien" \
        "жалоба на чужой юнит системы — не наша беда, молчим"
    проба "" замечания_по_юниту /etc/systemd/system/harness-agent.service "" \
        "verify промолчал — юнит здоров"
    (( ok_flag )) && { echo "SELFTEST: зелёный (7 путей по метке cron + 2 по метке успеха + 3 пути боевых порогов + 4 по юниту + 3 по выверке, первым — больной случай «cron не бежит»)"; exit 0; }
    echo "SELFTEST: КРАСНЫЙ"; exit 1
fi

