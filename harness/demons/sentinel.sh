UNITS="${SENTINEL_UNITS:-harness-agent harness-dispatcher}"

tg_send() {
    if [ -x "$PROJECT_DIR/scripts/tg_send.sh" ]; then
        "$PROJECT_DIR/scripts/tg_send.sh" "$1" >/dev/null && return 0
    fi
    say "сообщение владельцу НЕ ушло: $1"
    return 1
}

# Сигнал с кулдауном по виду беды: чинить можно каждые 5 минут, говорить — нет.
сказать_раз() { # $1=ключ беды  $2=текст
    local stamp="$LOG_DIR/sentinel.$1.told" age
    if [ -f "$stamp" ]; then
        age=$(( ( $(date +%s) - $(stat -c '%Y' "$stamp") ) / 60 ))
        [ "$age" -lt "$SENTINEL_COOLDOWN_MIN" ] && return 0
    fi
    tg_send "$2" && date +%s > "$stamp"
}

возраст_метки() { # $1=имя демона → минуты, или -1
    local f="$HEARTBEAT_DIR/$1"
    [ -f "$f" ] || { echo -1; return 0; }
    echo $(( ( $(date +%s) - $(stat -c '%Y' "$f") ) / 60 ))
}
аптайм_мин() { awk '{print int($1/60)}' /proc/uptime; }

# Сколько минут cron ВООБЩЕ мог запускать демонов: не дольше, чем работает
# машина, и не дольше, чем разложен харнес. Второе — улика ревью 10.09.2026
# (ops-15): сразу после раскладки меток ещё нет, cron тикает раз в 10 минут, а
# sentinel по boot-юниту успевает объявить только что поставленный присмотр
# стоящим.
#
# Возраст раскладки берётся по ВРЕМЕНИ СОЗДАНИЯ каталога установки, а не по
# mtime паспорта: замер 10.09.2026 — install.conf правился 50 минут назад и
# пересоздавался сегодня же, тогда как харнес стоит с 11.08. Окно по правкам
# конфига обнулялось бы при каждой из них и глушило настоящую тревогу на
# CRON_STALE_MIN минут — сторож, который выключается редактированием.
# Нет btime (файловая система без него) — окно равно аптайму, как раньше.
окно_cron_мин() {
    local up born inst
    up=$(аптайм_мин)
    born=$(stat -c '%W' "$(dirname "$INSTALL_CONF")" 2>/dev/null || echo 0)
    [[ "$born" =~ ^[0-9]+$ ]] && [ "$born" -gt 0 ] || { printf '%s\n' "$up"; return 0; }
    inst=$(( ( $(date +%s) - born ) / 60 ))
    [ "$inst" -lt "$up" ] && printf '%s\n' "$inst" || printf '%s\n' "$up"
}

состояние_юнита() { systemctl is-active "$1" 2>/dev/null || true; }

# Юнит-файлы харнеса глазами самого systemd. Гейт установщика бежит один раз,
# а юниты правятся руками и после установки — тогда неверная строка живёт
# молча: «active» она не ломает, видна только строкой в журнале при reload.
выверка_юнитов() { # печатает замечания; пусто = все выверены
    command -v systemd-analyze >/dev/null 2>&1 || return 0
    local unit path
    for unit in $UNITS; do
        path=$(systemctl show "$unit" -p FragmentPath --value 2>/dev/null)
        [ -n "$path" ] && [ -r "$path" ] || continue
        замечания_по_юниту "$path" "$(systemd-analyze verify "$path" 2>&1 || true)"
    done
}

в_панели() { tmux display-message -p -t "$TMUX_SESSION" '#{pane_current_command}' 2>/dev/null || echo "нет-сессии"; }

mkdir -p "$LOG_DIR" "$HEARTBEAT_DIR"
RC=0

# ── 1. Юниты: упавший поднять, о падении сказать ────────────────────────────
for unit in $UNITS; do
    state=$(состояние_юнита "$unit")
    [ -z "$state" ] && continue          # юнита нет в этой установке — не наша беда
    if [ "$(решение_по_юниту "$state")" = "поднять" ]; then
        say "юнит $unit в состоянии '$state' — поднимаю"
        if sudo -n systemctl restart "$unit" 2>/dev/null || systemctl restart "$unit" 2>/dev/null; then
            say "$unit перезапущен"
            сказать_раз "$unit" "Юнит $unit был в состоянии «$state» — перезапустил сам. Проверь, если это повторится."
        else
            say "$unit поднять НЕ удалось (нет прав или ошибка юнита)"
            сказать_раз "$unit" "Юнит $unit в состоянии «$state», перезапустить не смог. Нужны твои руки: sudo systemctl restart $unit"
            RC=1
        fi
    fi
done

# ── 2. Cron бежит? Иначе весь присмотр стоит, и сказать об этом некому ──────
# Метка сторожа сессий — самый частый демон (10 мин), по ней и видно. Читается
# метка ЗАПУСКА, а не успеха: успех при живом cron отстаёт на всю ротацию (до
# 24 мин лок держит один прогон, остальные выходят «лок занят»), и слитый
# признак дал 59 ложных тревог подряд — см. session-warden.sh, метка запуска.
age=$(возраст_метки session-warden.запуск)
if [ "$(решение_по_метке "$age" "$CRON_STALE_MIN" "$(окно_cron_мин)")" = "чинить" ]; then
    say "метка session-warden: ${age} мин (порог $CRON_STALE_MIN) — cron не запускает демонов"
    cron_state=$(состояние_юнита cron)
    [ -z "$cron_state" ] && cron_state=$(состояние_юнита crond)
    # Отчёт называет ТОЛЬКО сделанное (И-4): первая же редакция писала «поднял
    # cron» и при живом cron — владелец прочитал бы настоящий случай неверно.
    ACTIONS=""
    if [ "$cron_state" != "active" ]; then
        say "служба cron в состоянии '${cron_state:-нет}' — поднимаю"
        if sudo -n systemctl restart cron 2>/dev/null || systemctl restart cron 2>/dev/null; then
            ACTIONS="поднял cron"
        else
            ACTIONS="поднять cron НЕ смог"
        fi
    fi
    # Независимо от cron: прогнать сторожа сессий сейчас же, своими руками.
    if [ -x "$PROJECT_DIR/harness/demons/session-warden.sh" ]; then
        say "запускаю session-warden сам, не дожидаясь cron"
        SENTINEL_RESCUE=1 "$PROJECT_DIR/harness/demons/session-warden.sh" >> "$LOG_DIR/session-warden.log" 2>&1 || true
        ACTIONS="${ACTIONS:+$ACTIONS, }запустил сторожа сессий сам"
    fi
    сказать_раз cron "Демоны присмотра стояли: метка сторожа сессий была ${age} мин при пороге ${CRON_STALE_MIN} (служба cron: ${cron_state:-нет}). Сделал: ${ACTIONS:-ничего, чинить было нечем}. Если повторится — смотри $LOG_DIR/sentinel.log."
    RC=1
fi

# ── 2б. Сторож сессий ДОВОДИТ прогон до конца? ─────────────────────────────
# Второй вопрос второй меткой. Метка успеха стоит, пока лок держит живой
# прогон (ротация, досмотр выхода) — это норма до часа. Старше часа значит
# одно из двух: прогон завис или лок унаследовал чужой процесс и не отпустит
# никогда (улика 12.08.2026: tmux-сервер держал дескриптор, сторож был мёртв
# 40 минут и нашлось это случайно). Чинить отсюда нечего — пересоздаёт лок сам
# сторож при следующем прогоне; ценность блока в том, что молчание кончается.
stuck=$(возраст_метки session-warden)
if [ "$(решение_по_метке "$stuck" "$WARDEN_STUCK_MIN" "$(окно_cron_мин)")" = "чинить" ]; then
    say "метка успеха session-warden: ${stuck} мин (порог $WARDEN_STUCK_MIN) — прогон не доходит до конца"
    lock="$LOG_DIR/locks/${SERVICE_LOCKS_SUBDIR:-services}/session-warden.lock"
    holder=$(fuser "$lock" 2>/dev/null | tr -s ' ' '\n' | grep -m1 '[0-9]' || true)
    holder_cmd=$([ -n "$holder" ] && ps -o comm= -p "$holder" 2>/dev/null || echo "")
    say "лок $lock держит: ${holder:-никто}${holder_cmd:+ ($holder_cmd)}"
    сказать_раз warden_stuck "Сторож сессий не доводит прогон до конца: последний удачный был ${stuck} мин назад при пороге ${WARDEN_STUCK_MIN}. Лок держит ${holder:-никто}${holder_cmd:+ ($holder_cmd)}. Ротация сессий может не сработать — смотри $LOG_DIR/session-warden.log."
    RC=1
fi

# ── 3. Юнит-файлы выверены systemd? Молчащая строка не работает ─────────────
# Улика 12.08.2026: StartLimitIntervalSec стоял в [Service] юнита harness-agent
# — systemd ключ игнорировал, лимит перезапусков оставался дефолтным (10s/5)
# вместо снятого. Юнит при этом «active», сторож доволен, беда видна только
# строкой «Unknown key name» в журнале, которую никто не читает.
UNIT_NOTES=$(выверка_юнитов)
if [ -n "$UNIT_NOTES" ]; then
    say "systemd забраковал юнит-файлы харнеса:"
    say "$UNIT_NOTES"
    сказать_раз verify "systemd забраковал строку в юните харнеса — она молча не работает:
$UNIT_NOTES
Чинить: поправить файл, затем systemctl daemon-reload. Подробности в $LOG_DIR/sentinel.log."
    RC=1
fi

# ── 3б. Досыл того, что панель не смогла сказать при мёртвом канале ─────────
# Попытка запасного входа обязана дойти до владельца ДАЖЕ если в тот момент
# бот лежал: иначе единственный след чужого входа — строка в журнале, которую
# никто не читает.
QUEUE="$LOG_DIR/панель-недоставленное.jsonl"
if [ -s "$QUEUE" ]; then
    REST="$QUEUE.осталось"
    : > "$REST"
    while IFS= read -r line; do
        [ -n "$line" ] || continue
        msg=$(printf '%s' "$line" | python3 -c 'import json,sys; print(json.load(sys.stdin).get("текст",""))' 2>/dev/null || true)
        if [ -n "$msg" ] && tg_send "$msg"; then
            continue
        fi
        printf '%s\n' "$line" >> "$REST"
    done < "$QUEUE"
    mv "$REST" "$QUEUE"
    [ -s "$QUEUE" ] || rm -f "$QUEUE"
fi

# ── 4. Обычный прогон на этом заканчивается ─────────────────────────────────
if [ "${1:-}" != "--boot" ]; then
    touch "$HEARTBEAT_DIR/sentinel"
    exit "$RC"
fi

# ── 5. Режим загрузки: дождаться агента и проверить ВСЕ системы ─────────────
say "режим --boot: жду агента до ${BOOT_WAIT_SEC}с"
waited=0
while [ "$waited" -lt "$BOOT_WAIT_SEC" ]; do
    case "$(в_панели)" in claude|node) break ;; esac
    sleep 5; waited=$((waited + 5))
done
PANE=$(в_панели)
case "$PANE" in
    claude|node) AGENT_LINE="агент поднялся за ${waited}с (в панели: $PANE)" ;;
    нет-сессии)  AGENT_LINE="СЕССИИ НЕТ за ${BOOT_WAIT_SEC}с — поднимаю сам"
                 "$PROJECT_DIR/scripts/zapustit-agenta.sh" >> "$LOG_DIR/sentinel.log" 2>&1 \
                     && AGENT_LINE="сессии не было, поднял сам: $(в_панели)" || RC=1 ;;
    *)           AGENT_LINE="в панели '$PANE' — агента нет"; RC=1 ;;
esac
say "$AGENT_LINE"

# Сессию после перезагрузки поднимает юнит — и оставляет у пустого приглашения:
# пинок «подхвати работу» умеет только сторож сессий, а он в этот момент не
# при чём. Без этой строки после ребута агент жив и молчит, пока владелец не
# напишет первым, — то есть перезагрузка тихо останавливает работу.
case "$(в_панели)" in
    claude|node)
        if "$PROJECT_DIR/harness/demons/session-warden.sh" --kick >> "$LOG_DIR/sentinel.log" 2>&1; then
            AGENT_LINE="$AGENT_LINE; пинок «подхвати работу» отдан"
        else
            AGENT_LINE="$AGENT_LINE; ПИНОК НЕ ОТДАН — сессия стоит у пустого приглашения"
            RC=1
        fi ;;
esac

проверка() { # $1=имя  $2=команда  → строка отчёта
    # В канал уходит последняя строка (владельцу нужен вердикт), но красный
    # вердикт без подробностей нечинибелен: полный вывод — в лог, рядом.
    local out
    if out=$(eval "$2" 2>&1); then printf '%s: ок — %s' "$1" "$(printf '%s' "$out" | tail -1)"
    else
        RC=1
        say "ПОДРОБНОСТИ КРАСНОГО «$1»:"
        printf '%s\n' "$out" >> "$LOG_DIR/sentinel.log" 2>/dev/null
        printf '%s: КРАСНЫЙ — %s (подробности в %s)' "$1" "$(printf '%s' "$out" | tail -1)" "$LOG_DIR/sentinel.log"
    fi
}

REPORT="Сервер загрузился, проверяю системы.

$AGENT_LINE"
for unit in $UNITS; do
    REPORT="$REPORT
юнит $unit: $(состояние_юнита "$unit")"
done
REPORT="$REPORT
cron: $(состояние_юнита cron)
юнит-файлы: ${UNIT_NOTES:-выверены systemd, замечаний нет}
$(проверка "сторож команд" "cd '$PROJECT_DIR' && python3 scripts/hooks/test_guard_bash.py")
$(проверка "секреты (И-3)" "cd '$PROJECT_DIR' && bash scripts/check-secrets.sh")
$(проверка "сторож сессий" "cd '$PROJECT_DIR' && bash harness/demons/session-warden.sh --selftest")
$(проверка "срок входа" "cd '$PROJECT_DIR' && python3 scripts/check-srok-vhoda.py")
диск: $(df -h / | awk 'NR==2 {print $4" свободно из "$2}')
память: $(free -h | awk 'NR==2 {print $7" доступно из "$2}')
последний коммит: $(cd "$PROJECT_DIR" && git log --oneline -1 2>/dev/null)"

# Метки демонов: называем только протухшие — здоровые владельцу не новость.
# Порог у КАЖДОЙ метки свой — период из HEARTBEAT_PERIODS ×2, ровно как судит
# heartbeat-watch. Общие «1500 минут» здесь стояли своим правилом и врали в обе
# стороны: memory-revision ходит раз в месяц (44640 мин) и через сутки объявлялся
# бы протухшим ежедневно, а часовой task-closer мог опоздать в 24 раза незаметно
# (разбор кода 11.09.2026, пункт 9).
STALE=""
for f in "$HEARTBEAT_DIR"/*; do
    [ -f "$f" ] || continue
    n=$(basename "$f"); a=$(возраст_метки "$n")
    # Период метки из таблицы; метки вне таблицы (рабочие файлы демонов) не судим
    # вовсе — у них нет расписания, и «протухание» для них не определено.
    period=""
    for entry in ${HEARTBEAT_PERIODS:-}; do
        [ "${entry%%:*}" = "$n" ] && { period="${entry##*:}"; break; }
    done
    [ -n "$period" ] || continue
    [ "$a" -gt $((period * 2)) ] && STALE="$STALE $n(${a}м при периоде ${period})"
done
[ -n "$STALE" ] && REPORT="$REPORT
метки протухли (возраст больше периода ×2):$STALE"

say "$REPORT"
tg_send "$REPORT" || RC=1
touch "$HEARTBEAT_DIR/sentinel"
exit "$RC"
