def живые_контейнеры(запуск=subprocess.run) -> list[dict] | None:
    """Что РЕАЛЬНО работает на машине. None — docker не ответил.

    «Не спросили» и «ничего не запущено» — разные ответы: пустой список от
    упавшего docker означал бы «нарушений нет», и осмотр позеленел бы ровно
    тогда, когда машина больна сильнее всего.
    """
    import json
    try:
        имена = запуск(("docker", "ps", "--format", "{{.Names}}"),
                       capture_output=True, text=True, timeout=30)
        if имена.returncode != 0:
            return None
        список = [и for и in имена.stdout.split() if и]
        if not список:
            return []
        сырое = запуск(("docker", "inspect", *список),
                       capture_output=True, text=True, timeout=60)
        if сырое.returncode != 0:
            return None
        разбор = json.loads(сырое.stdout)
    except Exception:                                       # noqa: BLE001
        return None
    итог = []
    for к in разбор:
        хост = к.get("HostConfig") or {}
        образ = str((к.get("Config") or {}).get("Image", ""))
        порты = []
        for привязки in (хост.get("PortBindings") or {}).values():
            for п in привязки or []:
                порты.append((п.get("HostIp") or "", str(п.get("HostPort") or "")))
        итог.append({
            "имя": (к.get("Name") or "").lstrip("/"),
            "образ": образ,
            "основа": образ.rsplit("/", 1)[-1].split(":")[0],
            "потолок": int(хост.get("Memory") or 0),
            "перезапуск": ((хост.get("RestartPolicy") or {}).get("Name") or "no"),
            "порты": порты,
        })
    return итог


def запор_стоит(корень: Path, запуск=subprocess.run) -> tuple[bool | None, str]:
    """Стоит ли запор на порты контейнеров. None — спросить не вышло.

    Судит НЕ наш журнал и не метку, а сами правила ядра: метку пишет тот же,
    кого проверяют. Третий ответ обязателен — без прав на чтение правил
    «не прочёл» выглядело бы как «правил нет», и осмотр краснел бы зря.
    """
    путь = корень / ЗАПОР
    if not путь.exists():
        return None, f"нет {ЗАПОР}"
    try:
        из = запуск(("bash", str(путь), "--проверить"),
                    capture_output=True, text=True, timeout=30)
    except Exception as беда:                               # noqa: BLE001
        return None, f"запор не спросился: {беда}"
    if из.returncode == 0:
        return True, "правила стоят"
    if из.returncode == 1:
        return False, из.stdout.strip().splitlines()[0] if из.stdout.strip() else "правила не совпадают"
    return None, (из.stdout.strip().splitlines() or ["прав на чтение правил нет"])[0]


def наш(имя: str, наши: list[str] | None = None) -> bool:
    """Контейнер наш? Пустой список значит «все наши» — так ведёт себя
    установка без соседей, и молчать о своих же службах она не должна."""
    наши = НАШИ if наши is None else наши
    return not наши or any(имя.startswith(п) for п in наши)


def судить_контейнеры(контейнеры: list[dict], запор: tuple[bool | None, str],
                      наши: list[str] | None = None) -> list[str]:
    """Чистое суждение о живых контейнерах — его и судит самотест."""
    беды: list[str] = []
    наружу: list[str] = []
    чужие = [к["имя"] for к in контейнеры if not наш(к["имя"], наши)]
    if чужие:
        print(f"  (чужих контейнеров на машине {len(чужие)}: {', '.join(чужие)} — "
              "называю, но нашей бедой не считаю)")
    for к in контейнеры:
        # Потолок памяти и перезапуск — внутреннее хозяйство владельца
        # контейнера: за соседа мы это не чиним и бедой не считаем.
        if наш(к["имя"], наши):
            if not к["потолок"] and к["основа"] not in БЕЗ_ПОТОЛКА:
                беды.append(f"{к['имя']}: нет потолка памяти — утечка уйдёт в своп всей машины")
            if к["перезапуск"] == "no":
                беды.append(f"{к['имя']}: нет политики перезапуска — не встанет после перезагрузки")
        # А вот порт наружу судится у ВСЕХ: дыра в машине одна на всех, и
        # именно чужой контейнер отдал в интернет базу и хранилище (03.10).
        for адрес, порт in к["порты"]:
            if адрес.startswith("127.0.0.1") or порт in НАРУЖУ_МОЖНО:
                continue
            наружу.append(f"{к['имя']}:{порт} на {адрес or '0.0.0.0'}")
    if наружу:
        стоит, чем = запор
        if стоит is False:
            беды.append(f"порты опубликованы наружу и ЗАПОР НЕ СТОИТ ({чем}): {', '.join(наружу)}")
        elif стоит is None:
            беды.append(f"порты опубликованы наружу, а запор не спрошен ({чем}): {', '.join(наружу)}")
        else:
            print(f"  (наружу опубликовано портов {len(наружу)}, их закрывает запор: {', '.join(наружу)})")
    return беды


def _пики_за_неделю() -> dict:
    """Пик рабочего набора каждого контейнера за 7 дней, МБ. Пусто — если Prometheus молчит."""
    import json
    import urllib.parse
    import urllib.request
    if not ПРОМЕТЕЙ:
        return {}
    запрос = 'max_over_time(container_memory_working_set_bytes{name!=""}[7d])'
    url = f"{ПРОМЕТЕЙ}/api/v1/query?query=" + urllib.parse.quote(запрос)
    try:
        with urllib.request.urlopen(url, timeout=20) as о:
            ряды = json.loads(о.read().decode())["data"]["result"]
    except Exception:                                       # noqa: BLE001
        return {}
    из: dict = {}
    for р in ряды:
        имя = (р.get("metric") or {}).get("name", "")
        if not ПРЕФИКС_КОНТЕЙНЕРОВ or not имя.startswith(ПРЕФИКС_КОНТЕЙНЕРОВ):
            continue
        краткое = re.sub(r"-\d+$", "", re.sub(r"^" + re.escape(ПРЕФИКС_КОНТЕЙНЕРОВ) + r"[-_]", "", имя))
        из[краткое] = max(из.get(краткое, 0.0), float(р["value"][1]) / 1024 / 1024)
    return из


def проверить_границы(контейнеры: list[dict]) -> list[str]:
    """Не устарели ли потолки: сервис мог вырасти или, наоборот, усохнуть.

    Потолок берётся у ЖИВОГО контейнера, а не из файла описания: запущенное
    с `-m` мимо файла имело бы другой потолок, и сверка врала бы.
    """
    пики = _пики_за_неделю()
    if not пики or not контейнеры:
        return []
    беды: list[str] = []
    for к in контейнеры:
        потолок = к["потолок"] // 1024 // 1024
        краткое = re.sub(r"-\d+$", "", re.sub(
            r"^" + re.escape(ПРЕФИКС_КОНТЕЙНЕРОВ) + r"[-_]", "", к["имя"])
            if ПРЕФИКС_КОНТЕЙНЕРОВ else к["имя"])
        пик = пики.get(краткое)
        if not потолок or not пик:
            continue
        if пик > потолок * ТЕСНО:
            беды.append(f"{к['имя']}: пик за неделю {пик:.0f} МБ при потолке {потолок} МБ — "
                        "тесно, поднять потолок (сервис вырос)")
        elif пик < потолок * СЛИШКОМ_ШИРОКО and потолок > 512:
            беды.append(f"{к['имя']}: пик за неделю {пик:.0f} МБ при потолке {потолок} МБ — "
                        "потолок ни от чего не защищает, опустить")
    return беды


def проверить_машину() -> list[str]:
    беды: list[str] = []
    try:
        из = subprocess.run(("df", "--output=pcent", "/"), capture_output=True,
                            text=True, timeout=10).stdout.split()
        занято = int(из[-1].rstrip("%"))
        if занято >= ПОРОГ_ДИСКА:
            беды.append(f"диск занят на {занято}% (порог {ПОРОГ_ДИСКА}%)")
    except Exception:                                       # noqa: BLE001
        беды.append("диск: замерить не вышло")
    try:
        строки = Path("/proc/meminfo").read_text(encoding="utf-8")
        всего = int(re.search(r"SwapTotal:\s+(\d+)", строки).group(1))
        свободно = int(re.search(r"SwapFree:\s+(\d+)", строки).group(1))
        if всего:
            занято = round((всего - свободно) * 100 / всего)
            if занято >= ПОРОГ_СВОПА:
                беды.append(f"своп занят на {занято}% (порог {ПОРОГ_СВОПА}%)")
    except Exception:                                       # noqa: BLE001
        беды.append("своп: замерить не вышло")
    try:
        строки = Path("/proc/meminfo").read_text(encoding="utf-8")
        всего = int(re.search(r"MemTotal:\s+(\d+)", строки).group(1))
        доступно = int(re.search(r"MemAvailable:\s+(\d+)", строки).group(1))
        свободно = round(доступно * 100 / всего)
        if свободно < ПОРОГ_ПАМЯТИ:
            беды.append(f"свободной памяти {свободно}% (порог {ПОРОГ_ПАМЯТИ}%)")
    except Exception:                                       # noqa: BLE001
        беды.append("память: замерить не вышло")
    try:
        # Пятиминутное среднее, а не мгновенное: минутное скачет от любой
        # сборки и звало бы владельца на пустом месте.
        за_пять = float(Path("/proc/loadavg").read_text().split()[1])
        ядер = os.cpu_count() or 1
        if за_пять > ПОРОГ_НАГРУЗКИ * ядер:
            беды.append(f"нагрузка за 5 минут {за_пять:.2f} на {ядер} ядра "
                        f"(порог {ПОРОГ_НАГРУЗКИ} на ядро)")
    except Exception:                                       # noqa: BLE001
        беды.append("нагрузка: замерить не вышло")
    try:
        s = int(Path("/proc/sys/vm/swappiness").read_text().strip())
        if s > СВАППИНЕСС:
            беды.append(f"vm.swappiness={s} — ядро охотно выпихивает живые страницы; "
                        f"серверу нужно не выше {СВАППИНЕСС}")
    except Exception:                                       # noqa: BLE001
        pass
    return беды


# Имена сайтов, чей сертификат судится. ДАННЫЕ: пусто — проверять нечего.
САЙТЫ = [и for и in (КОНФИГ.get("CERT_HOSTS", "") or "").replace(" ", "").split(",") if и]


def срок_сертификата(имя: str, запуск=subprocess.run) -> tuple[int | None, str]:
    """Сколько суток осталось сертификату, который сайт ОТДАЁТ браузеру.

    Спрашивается живое рукопожатие, а не файл в /etc/letsencrypt: каталог
    закрыт на чтение всем, кроме root, и `is_dir()` под агентом отвечает
    «нет каталога» — осмотр зеленел бы молча. К тому же лежащий на диске
    свежий сертификат и отданный сайтом старый — разные факты, и человека
    бьёт второй.

    Возвращает (суток, причина). Суток нет — причину печатает САМ openssl:
    просроченный сертификат и недоступный сайт это разные беды, и назвать их
    одним «не прочиталось» значит угадывать ([[a-refusal-code-explained-from-memory]]).
    """
    from datetime import datetime, timezone
    try:
        из = запуск(("openssl", "s_client", "-servername", имя,
                     "-connect", f"{имя}:443", "-verify_return_error"),
                    input="", capture_output=True, text=True, timeout=25)
        дата = запуск(("openssl", "x509", "-enddate", "-noout"),
                      input=из.stdout, capture_output=True, text=True, timeout=15)
    except Exception as беда:                               # noqa: BLE001
        return None, f"openssl не запустился: {беда}"
    совпало = re.search(r"notAfter=(.+)", дата.stdout.strip()) if дата.returncode == 0 else None
    if not совпало:
        слова = [с for с in (из.stderr or из.stdout).splitlines() if "verify error" in с or "errno" in с]
        return None, (слова[0].strip() if слова else "рукопожатие не состоялось")
    try:
        конец = datetime.strptime(совпало.group(1).strip(), "%b %d %H:%M:%S %Y %Z")
    except ValueError:
        return None, f"непонятная дата: {совпало.group(1).strip()}"
    return (конец.replace(tzinfo=timezone.utc) - datetime.now(timezone.utc)).days, ""


def проверить_сертификаты(сайты: list[str] | None = None) -> list[str]:
    сайты = САЙТЫ if сайты is None else сайты
    if not сайты:
        print("  (сайты для проверки сертификата не объявлены — CERT_HOSTS пуст)")
        return []
    беды: list[str] = []
    for имя in сайты:
        осталось, почему = срок_сертификата(имя)
        if осталось is None:
            беды.append(f"сертификат {имя}: {почему} — это НЕ «срок в порядке»")
        elif осталось < ПОРОГ_СЕРТИФИКАТА:
            беды.append(f"сертификат {имя}: осталось {осталось} сут "
                        f"(порог {ПОРОГ_СЕРТИФИКАТА}) — обновление не прошло")
    print(f"  (сертификатов осмотрено: {len(сайты)})")
    return беды


def _самотест() -> int:
    """Пробы на подставных данных: машина не трогается.

    Самотест у осмотра был ОБЪЯВЛЕН в реестре и отсутствовал в коде: ключ
    `--selftest` молча проваливался в обычный прогон, ставил метку свежести и
    при находке написал бы владельцу — проба играла на боевом
    ([[the-probe-played-on-production]]).
    """
    плохо = 0

    def проба(имя, ждём, вышло):
        nonlocal плохо
        if ждём == вышло:
            print(f"  ок    {имя}")
        else:
            print(f"  ПЛОХО {имя}: ждали «{ждём}», вышло «{вышло}»")
            плохо += 1

    здоровый = {"имя": "целый", "образ": "nginx:1", "основа": "nginx",
                "потолок": 1 << 30, "перезапуск": "unless-stopped",
                "порты": [("127.0.0.1", "8080")]}
    проба("здоровый контейнер претензий не даёт", 0,
          len(судить_контейнеры([здоровый], (True, "правила стоят"), наши=[])))
    проба("нет потолка памяти — находка", 1,
          len(судить_контейнеры([{**здоровый, "потолок": 0}], (True, ""), наши=[])))
    # База — законное исключение, и оно НАЗВАНО списком, а не подразумевается.
    проба("базе потолок не обязателен", 0,
          len(судить_контейнеры([{**здоровый, "потолок": 0, "основа": "postgres"}], (True, ""), наши=[])))
    проба("нет политики перезапуска — находка", 1,
          len(судить_контейнеры([{**здоровый, "перезапуск": "no"}], (True, ""), наши=[])))

    наружу = {**здоровый, "порты": [("", "6380")]}
    # БОЛЬНОЙ: порт наружу при СТОЯЩЕМ запоре — не находка, иначе осмотр
    # краснел бы каждое утро на соседнем проекте, а краснящий зря отключают.
    проба("БОЛЬНОЙ: порт наружу при стоящем запоре — не находка", 0,
          len(судить_контейнеры([наружу], (True, "правила стоят"), наши=[])))
    # БОЛЬНОЙ: тот же порт при снятом запоре — находка С НАЗВАННЫМ портом.
    итог = судить_контейнеры([наружу], (False, "правила не совпадают"), наши=[])
    проба("БОЛЬНОЙ: запор снят — находка называет порт", "да",
          "да" if len(итог) == 1 and "6380" in итог[0] else f"нет: {итог}")
    # БОЛЬНОЙ: запор не спрошен — это НЕ «закрыто». Третий ответ обязан
    # доходить до владельца, а не растворяться в зелени.
    проба("БОЛЬНОЙ: запор не спрошен — находка, а не тишина", 1,
          len(судить_контейнеры([наружу], (None, "прав на чтение правил нет"), наши=[])))
    # 80 и 443 наружу законны — их отдаёт сам сайт.
    проба("порт 443 наружу законен", 0,
          len(судить_контейнеры([{**здоровый, "порты": [("", "443")]}], (False, ""), наши=[])))

    # БОЛЬНОЙ: docker не ответил. Пустой список значил бы «нарушений нет»
    # ровно в тот момент, когда машина больна сильнее всего.
    class _Отказ:
        returncode, stdout, stderr = 1, "", "Cannot connect to the Docker daemon"
    проба("БОЛЬНОЙ: docker не ответил — None, а не пустой список", None,
          живые_контейнеры(lambda *а, **к: _Отказ()))

    class _Пусто:
        returncode, stdout, stderr = 0, "", ""
    проба("docker ответил, но контейнеров нет — пустой список", [],
          живые_контейнеры(lambda *а, **к: _Пусто()))

    # БОЛЬНОЙ: запор отвечает 77 «не смог прочитать» — это None, не False.
    class _НеПрочёл:
        returncode, stdout, stderr = 77, "iptables: не смог прочитать правила", ""
    тут = Path(__file__).resolve().parents[2]
    проба("БОЛЬНОЙ: запор не прочитался — ответ «не знаю», а не «снят»", None,
          запор_стоит(тут, lambda *а, **к: _НеПрочёл())[0])

    # БОЛЬНОЙ: сосед по машине НАЗЫВАЕТСЯ, но нашей бедой не считается —
    # иначе осмотр краснел бы каждое утро на чужом проекте, который нам
    # править не велено, и его бы отключили.
    чужой = {**здоровый, "имя": "sosed-redis-1", "потолок": 0}
    проба("БОЛЬНОЙ: чужой контейнер без потолка — не наша беда", 0,
          len(судить_контейнеры([чужой], (True, ""), наши=["app"])))
    # БОЛЬНОЙ: а вот порт ЧУЖОГО контейнера наружу — наша беда: дыра в машине
    # одна на всех, и 03.10 в интернет её отдал именно сосед.
    проба("БОЛЬНОЙ: порт чужого контейнера наружу при снятом запоре — беда", 1,
          len(судить_контейнеры([{**чужой, "потолок": 1 << 30, "порты": [("", "6380")]}],
                                (False, "правила не совпадают"), наши=["app"])))
    проба("наш контейнер без потолка — беда", 1,
          len(судить_контейнеры([{**чужой, "имя": "app-api-1"}], (True, ""), наши=["app"])))
    # БОЛЬНОЙ: пустой список «наших» значит ВСЕ наши — установка без соседей
    # не должна молчать о собственных службах.
    проба("БОЛЬНОЙ: список наших пуст — судятся все", 1,
          len(судить_контейнеры([чужой], (True, ""), наши=[])))

    # БОЛЬНОЙ: отказ рукопожатия обязан нести СЛОВА openssl. «Просрочен» и
    # «сайт не отвечает» — разные беды, и одним словом их не назвать.
    class _Просрочен:
        returncode, stdout = 1, ""
        stderr = "verify error:num=10:certificate has expired\n"
    сутки, почему = срок_сертификата("проба", lambda *а, **к: _Просрочен())
    проба("БОЛЬНОЙ: причина отказа — словами openssl", "да",
          "да" if сутки is None and "has expired" in почему else f"нет: {сутки}, {почему}")

    # Сайты не объявлены — проверять нечего, и это сказано вслух.
    проба("сайты не объявлены — претензий нет", 0, len(проверить_сертификаты([])))

    print("самотест: всё зелено" if not плохо else f"самотест: красных {плохо}")
    return 1 if плохо else 0


def main() -> int:
    if "--selftest" in sys.argv:
        return _самотест()
    # `--только-compose` для CI: там другая машина, и её диск со свопом к нашему
    # серверу отношения не имеют — а правила compose проверить надо ДО вливания.
    корень = Path(КОНФИГ.get("PROJECT_DIR", "."))
    контейнеры = живые_контейнеры()
    if контейнеры is None:
        беды = ["docker не ответил — живые контейнеры не осмотрены, "
                "это НЕ «нарушений нет»"]
    else:
        print(f"  (осмотрено живых контейнеров: {len(контейнеры)})")
        беды = (судить_контейнеры(контейнеры, запор_стоит(корень))
                + проверить_границы(контейнеры))
    беды += проверить_машину() + проверить_сертификаты()
    if "--кратко" not in sys.argv:
        for б in беды:
            print("  •", б)
    print(f"гигиена сервера: нарушений {len(беды)}")
    return 1 if беды else 0


