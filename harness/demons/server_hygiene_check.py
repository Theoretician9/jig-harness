def _read_conf(path: Path, conf: dict) -> None:
    """KEY="value" / KEY=число; комментарии и пустые строки мимо.

    Подстановки $VAR разворачиваются по уже прочитанному — install.conf
    ссылается на $SECRETS_DIR в TG_TOKEN_FILE.

    Комментарий режется только ВНЕ кавычек (Д-3): прежняя резка по первому #
    обрубала значение вида KEY="пароль#42" посередине.
    """
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, raw = line.partition("=")
        raw = raw.strip()
        m = re.match(r'"([^"]*)"|\'([^\']*)\'', raw)
        if m:  # значение в кавычках — берём до закрывающей, # внутри законен
            value = m.group(1) if m.group(1) is not None else m.group(2)
        else:  # без кавычек # значению принадлежать не может — это комментарий
            value = raw.split("#", 1)[0].strip()
        for name, seen in conf.items():
            value = value.replace("${%s}" % name, seen).replace("$" + name, seen)
        conf[key.strip()] = value


def _сломана(причина: Exception) -> "SystemExit":
    """Проверка сломана ≠ нарушения найдены: traceback в stderr, код 2.

    Обёртка server-hygiene.sh различает по коду: 1 — нарушения (метка
    ставится), 2 — сломана сама проверка (метки НЕТ, сигнал владельцу).
    Без этого любой traceback выходил кодом 1 и сходил за «нарушения».
    """
    import traceback
    traceback.print_exc(file=sys.stderr)
    return SystemExit(2)


