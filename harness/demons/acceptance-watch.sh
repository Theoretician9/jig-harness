#!/usr/bin/env bash
#
# acceptance-watch.sh — приёмку задач делает механизм, а не список для владельца.
#
# Владелец 11.09.2026: «Нужен механизм фильтрации <…> там где большая
# уверенность, проверено тобой конкретно что точно работает, то там сам
# закрывай проверку»; «Я не хочу лично все проверять, в этом и смысл, надо
# только то, что не может проверить система».
#
# Модель здесь НЕ ЗОВЁТСЯ. Прогон команд из поля `проверка:` — работа скрипта
# (находка C6 ревью спеки: у харнеса нет способа поднять второго агента, а
# заводить его ради запуска команд — лишняя цена и лишний риск). Агент нужен
# только строителю проверок, и это отдельный демон.
#
# Что делает: зовёт acceptance.py --применить, кладёт отчёт в docs/приёмка/ и
# шлёт владельцу ЧИСЛА — закрыто, провалилось, доказать нечем, и отдельно —
# сколько задач ждут ЛИЧНО его. Ничего не чинит.
#
# Запуск: cron. Служебное: --selftest, --сухой (посчитать, ничего не менять).
set -uo pipefail

# shellcheck disable=SC1091
source "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/../../scripts/lib/config.sh"
INSTALL_CONF="${HARNESS_INSTALL_CONF:-$(konf_koren)/install.conf}"
HARNESS_CONF="${HARNESS_CONF:-$(konf_koren)/harness.conf}"
# Окружение старше конфига: общий загрузчик вместо голого source (улика
# 12.09.2026 — проба с TMUX_SESSION в окружении сменила модель в РАБОЧЕЙ панели).
konf_zagruzit

PROJECT_DIR="${PROJECT_DIR:?пуст PROJECT_DIR — не прочитан паспорт установки}"
OTCHET_DIR="$PROJECT_DIR/docs/приёмка"

say() { printf '%s priyomka-watch: %s\n' "$(date -Is)" "$*"; }

# Числа из вывода приёмки: первая строка — JSON со сводом.
chisla() {  # вывод приёмки на stdin → «принято=N провал=M нечем=K»
    # Программа идёт аргументом -c, а НЕ heredoc-ом: «python3 - <<PY» отдаёт
    # стандартный ввод под текст программы, и разбираемый вывод до неё не
    # доходит — самотест поймал это первой же пробой (11.09.2026).
    python3 -c '
import json, sys
свод = {}
for строка in sys.stdin.read().splitlines():
    if строка.startswith("{"):
        try:
            свод = json.loads(строка).get("итог", {})
        except ValueError:
            свод = {}
        break
print("принято=%d провал=%d нечем=%d врёт=%d владельцу=%d" % (
    свод.get("доказано", 0),
    свод.get("провал", 0),
    свод.get("доказать-нечем", 0),
    свод.get("проверка-врёт", 0),
    свод.get("ждёт-владельца", 0)))
'
}

# Число из строки чисел: «владельцу=7» → 7. Пустое значение — ноль, иначе
# арифметика ниже молча превратится в синтаксическую ошибку bash.
chislo_iz() {  # <имя> <строка чисел>
    local vyshlo
    vyshlo=$(printf '%s' "$2" | sed -n "s/.*$1=\([0-9]*\).*/\1/p")
    printf '%s' "${vyshlo:-0}"
}

if [ "${1:-}" = "--selftest" ]; then
    ok=1
    T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
    # БОЛЬНОЙ СЛУЧАЙ: пустой вывод не должен давать пустых чисел молча — все
    # три числа обязаны быть названы, иначе отчёт владельцу ни о чём.
    got=$(printf '' | chisla)
    if [ "$got" = "принято=0 провал=0 нечем=0 врёт=0 владельцу=0" ]; then
        echo "  ок    БОЛЬНОЙ СЛУЧАЙ: пустой вывод даёт нули, а не пустоту"
    else echo "  ПЛОХО пустой вывод дал «$got»"; ok=0; fi
    got=$(printf '{"задач в test": 3, "итог": {"доказано": 2, "провал": 1}}\n' | chisla)
    if [ "$got" = "принято=2 провал=1 нечем=0 врёт=0 владельцу=0" ]; then
        echo "  ок    числа берутся из свода"
    else echo "  ПЛОХО свод разобран как «$got»"; ok=0; fi
    # БОЛЬНОЙ СЛУЧАЙ 27.09.2026: очередь ВЛАДЕЛЬЦА не имела своего числа и
    # считалась вместе с долгом механизма — сказать ему «тебя ждут семь» было
    # нечем. Его слова: «надо именно мне их все проверять?».
    got=$(printf '{"итог": {"ждёт-владельца": 7, "доказать-нечем": 12, "проверка-врёт": 8}}\n' | chisla)
    if [ "$got" = "принято=0 провал=0 нечем=12 врёт=8 владельцу=7" ]; then
        echo "  ок    БОЛЬНОЙ СЛУЧАЙ: очередь владельца названа своим числом"
    else echo "  ПЛОХО очередь владельца разобрана как «$got»"; ok=0; fi
    # БОЛЬНОЙ СЛУЧАЙ 15–20.09.2026: при «принято=0 провал=0» демон не говорил
    # НИЧЕГО — семь дней молчания ровно там, где долг был наибольшим. Условие
    # обязано срабатывать и на непустую очередь владельца.
    # БОЛЬНОЙ СЛУЧАЙ 27.09.2026: владельцу уходило ЧИСЛО, а он просил список с
    # пояснениями «что проверить и как». Проба зовёт сборщик списка живьём.
    if [ "$(chislo_iz владельцу 'принято=0 провал=0 нечем=12 врёт=8 владельцу=7')" = "7" ] \
       && [ "$(chislo_iz принято 'мусор')" = "0" ]; then
        echo "  ок    число из строки берётся, а пустое даёт ноль"
    else echo "  ПЛОХО разбор числа из строки"; ok=0; fi
    got=$(printf 'мусор не json\n' | chisla)
    if [ "$got" = "принято=0 провал=0 нечем=0 врёт=0 владельцу=0" ]; then
        echo "  ок    битый вывод не валит демона"
    else echo "  ПЛОХО битый вывод дал «$got»"; ok=0; fi
    # ── СТЕНД: демон проходит БОЕВЫМ путём, и проба судит ФАКТ ──
    # Находка G-08 ревью 27.09.2026: шесть путей из тринадцати грепали текст
    # собственного файла, и три мутации (мёртвая ветка очереди, ослабленный
    # порог падения судьи, утёкший лок) оставались зелёными. Ни один путь не
    # проверял то, ради чего смена делалась: уходит ли владельцу сообщение и
    # уходит ли список.
    stend="$T/стенд"
    mkdir -p "$stend/scripts/lib" "$stend/docs/приёмка" "$T/лог" "$T/метки"
    cp "$PROJECT_DIR/scripts/acceptance.py" "$stend/scripts/"
    cp "$PROJECT_DIR/scripts/lib/"*.py "$stend/scripts/lib/"
    printf '#!/usr/bin/env bash\nexit 0\n' > "$stend/scripts/pre-commit-gate.sh"
    printf '#!/usr/bin/env python3\nprint("закрытых задач: 0")\n' \
        > "$stend/scripts/archive-map.py"
    # Подставной канал: пишет, ЧТО ушло, и слушается переключателя отказа.
    cat > "$stend/scripts/tg_send.sh" <<'KANAL'
#!/usr/bin/env bash
[ -n "${KANAL_OTKAZ:-}" ] && exit 1
printf '%s\n' "$*" >> "${OTPRAVLENO:?}"
exit 0
KANAL
    cat > "$stend/dev-map.yaml" <<'KARTA'
version: 1
lines:
  - id: harness
    layer: infra
    name: "Ядро"
    tasks:
      - id: t.первая-владельцу
        status: test
        title: "Первая для владельца"
        summary: "x"
        проверить_владельцу: "вид на экране"
        как_проверить: "открой панель и посмотри на карту"
      - id: t.вторая-владельцу
        status: test
        title: "Вторая для владельца"
        summary: "x"
        проверить_владельцу: "удобство"
        как_проверить: "нажми кнопку паузы и убедись, что смена встала"
KARTA
    OTPRAVLENO="$T/отправлено.log"
    : > "$OTPRAVLENO"
    # [1 — канал отказывает] [2 — свой каталог меток] [3 — режим: пусто = боевой]
    # Боевой режим нужен для проб про список очереди владельца: судья пишет его
    # только при `--применить`, и сухой прогон не мог отправить файл НИКОГДА
    # (две пробы были красными с 27.09.2026 и не видны обычным воротам —
    # самотест демона живёт за флагом `--всё`).
    stend_progon() {
        local metki="${2:-$T/метки}" rezhim="${3---сухой}"
        mkdir -p "$metki"
        env PROJECT_DIR="$stend" LOG_DIR="$T/лог" HEARTBEAT_DIR="$metki" \
            HARNESS_ACTIVE_LINE=harness OTPRAVLENO="$OTPRAVLENO" \
            KANAL_OTKAZ="${1:-}" bash "$0" $rezhim >> "$T/прогон.log" 2>&1
    }

    stend_progon
    if grep -q "владельцу=2" "$OTPRAVLENO"; then
        echo "  ок    БОЕВОЙ ПУТЬ: владельцу ушло число его очереди"
    else echo "  ПЛОХО сообщение с очередью владельца не ушло: «$(cat "$OTPRAVLENO")»"; ok=0; fi
    # БОЛЬНОЙ СЛУЧАЙ G-01 (critical): условие свежести сравнивало список с
    # отчётом, который пишется ПОЗЖЕ него, — список не уходил ни разу.
    # Прогон БОЕВОЙ: список пишет судья только при `--применить`. След прежнего
    # состава очереди уносим в свой каталог журнала: иначе второй прогон считает
    # очередь «не новой» и списка не отправляет — состав же не менялся.
    : > "$OTPRAVLENO"
    env LOG_DIR="$T/лог-боевой" stend_progon "" "$T/метки-боевой" "" || true
    stend_progon_boevoj() {
        mkdir -p "$T/лог-боевой" "$T/метки-боевой"
        env PROJECT_DIR="$stend" LOG_DIR="$T/лог-боевой" \
            HEARTBEAT_DIR="$T/метки-боевой" HARNESS_ACTIVE_LINE=harness \
            OTPRAVLENO="$OTPRAVLENO" bash "$0" >> "$T/прогон.log" 2>&1
    }
    : > "$OTPRAVLENO"
    stend_progon_boevoj
    if grep -q -- "--file" "$OTPRAVLENO" && grep -q "очередь-владельца.md" "$OTPRAVLENO"; then
        echo "  ок    БОЛЬНОЙ СЛУЧАЙ: список задач ушёл владельцу файлом"
    else echo "  ПЛОХО файл со списком владельцу не ушёл"; ok=0; fi
    if grep -q "Как проверить" "$stend/docs/приёмка/очередь-владельца.md" 2>/dev/null; then
        echo "  ок    список говорит владельцу, ЧТО открыть и что увидеть"
    else echo "  ПЛОХО список собран без шагов для владельца"; ok=0; fi

    # Второй прогон тем же составом: повтора быть не должно.
    : > "$OTPRAVLENO"
    stend_progon
    if [ ! -s "$OTPRAVLENO" ]; then
        echo "  ок    тот же состав очереди второй раз не шлётся"
    else echo "  ПЛОХО повтор: «$(cat "$OTPRAVLENO")»"; ok=0; fi

    # БОЛЬНОЙ СЛУЧАЙ G-03: состав сменился, а ЧИСЛО прежнее — прежняя метка по
    # длине очереди этого не замечала, и новая задача входила молча.
    sed -i 's/t.вторая-владельцу/t.третья-владельцу/' "$stend/dev-map.yaml"
    : > "$OTPRAVLENO"
    stend_progon
    if grep -q "владельцу=2" "$OTPRAVLENO"; then
        echo "  ок    БОЛЬНОЙ СЛУЧАЙ: подмена задачи при том же числе замечена"
    else echo "  ПЛОХО смена состава очереди прошла молча"; ok=0; fi

    # БОЛЬНОЙ СЛУЧАЙ G-02: канал отказал — состав НЕ запоминается, иначе
    # молчание навсегда при живой очереди.
    sed -i 's/t.третья-владельцу/t.четвёртая-владельцу/' "$stend/dev-map.yaml"
    : > "$OTPRAVLENO"
    stend_progon 1
    metka_posle_otkaza=$(cat "$T/лог/priyomka.последняя-очередь-владельцу" 2>/dev/null || echo "нет")
    : > "$OTPRAVLENO"
    stend_progon
    if grep -q "владельцу=2" "$OTPRAVLENO"; then
        echo "  ок    БОЛЬНОЙ СЛУЧАЙ: после отказа канала весть повторяется"
    else echo "  ПЛОХО отказ канала запомнился как сказанное: метка «$metka_posle_otkaza»"; ok=0; fi

    # Чистка — второй шаг того же действия: закрыл задачу, унеси её из карты.
    # Проба на то, что механизм переноса на месте и зелёный.
    # БОЛЬНОЙ СЛУЧАЙ ревью (I5): метка присмотра писалась даже когда судья
    # падал — сломанный механизм выглядел здоровым и молчал.
    # Судим ПОВЕДЕНИЕ, а не текст: до 28.09.2026 здесь стоял `grep` по своему же
    # файлу, и проба зеленела от наличия строки в коде — даже если условие
    # перевёрнуто (§6 ревизии, класс «проба судит текст своего файла»).
    # Больной случай: подставной судья падает кодом 3 (битая карта, нет yaml).
    mkdir -p "$stend/scripts"
    SUDYA_ZHIVOJ=""
    [ -f "$stend/scripts/acceptance.py" ] && SUDYA_ZHIVOJ=$(cat "$stend/scripts/acceptance.py")
    printf '%s\n' '#!/usr/bin/env python3' 'import sys' \
        'print("битая карта: судья упал")' 'sys.exit(3)' \
        > "$stend/scripts/acceptance.py"
    : > "$T/прогон-падение.log"
    PROGON_LOG_PREZHNIJ="$T/прогон.log"
    stend_progon "" "$T/метки-падение"
    if grep -q "ОТКАЗ: приёмка упала" "$PROGON_LOG_PREZHNIJ"; then
        echo "  ок    БОЛЬНОЙ СЛУЧАЙ: падение судьи названо словом «ОТКАЗ»"
    else echo "  ПЛОХО падение судьи (код 3) прошло как обычный прогон"; ok=0; fi
    if [ ! -e "$T/метки-падение/priyomka-watch" ]; then
        echo "  ок    БОЛЬНОЙ СЛУЧАЙ: при падении судьи метка присмотра НЕ ставится"
    else echo "  ПЛОХО метка поставлена при упавшем судье — сторож промолчит"; ok=0; fi
    if [ -n "$SUDYA_ZHIVOJ" ]; then
        printf '%s' "$SUDYA_ZHIVOJ" > "$stend/scripts/acceptance.py"
    else
        : > "$stend/scripts/acceptance.py"
    fi
    # БОЛЬНОЙ СЛУЧАЙ 12.09.2026: лок утекал в агента, тот держал его до 15
    # минут после нашего выхода, и следующий прогон уходил ни с чем — цикл
    # отработал шестнадцать кругов за секунду, все впустую.
    if grep -q '9>&-' "$PROJECT_DIR/harness/demons/check-builder.sh"; then
        echo "  ок    БОЛЬНОЙ СЛУЧАЙ: лок закрыт у потомков строителя"
    else echo "  ПЛОХО лок утечёт в агента строителя"; ok=0; fi
    if python3 "$PROJECT_DIR/scripts/archive-map.py" --selftest >/dev/null 2>&1; then
        echo "  ок    перенос в архив на месте и зелёный"
    else echo "  ПЛОХО механизм переноса в архив красный или не найден"; ok=0; fi
    # Валидатор карты доступен демону: без него дубль ключа прошёл бы молча.
    if bash "$PROJECT_DIR/scripts/pre-commit-gate.sh" --devmap-only "$PROJECT_DIR/dev-map.yaml" >/dev/null 2>&1; then
        echo "  ок    валидатор карты доступен демону и карта здорова"
    else echo "  ПЛОХО валидатор карты недоступен или карта больна"; ok=0; fi
    if python3 "$PROJECT_DIR/scripts/acceptance.py" --selftest >/dev/null 2>&1; then
        echo "  ок    судья приёмки на месте и зелёный"
    else echo "  ПЛОХО судья приёмки красный или не найден"; ok=0; fi
    [ "$ok" = 1 ] && { echo "SELFTEST: зелёный (16 путей, из них шесть — боевой путь на стенде)"; exit 0; }
    echo "SELFTEST: КРАСНЫЙ"; exit 1
fi

# Карту пишут ПЯТЬ сторон: живой агент, devmap-selfheal, проверщик, строитель
# и панель. Лок общий на карту, а не на демона: два писателя наперегонки
# затирают правки друг друга целиком (находка C4 ревью кода 11.09.2026).
LOK="$LOG_DIR/locks/${SERVICE_LOCKS_SUBDIR:-services}/dev-map.lock"
mkdir -p "$(dirname "$LOK")"
exec 9>"$LOK"
# Дескриптор 9 закрывается у КАЖДОГО потомка: иначе агент (он живёт до 15
# минут) наследует его и держит лок после нашего выхода — следующий прогон
# видит «карту правит кто-то другой» и уходит ни с чем. Улика 12.09.2026:
# цикл отработал шестнадцать кругов подряд за одну секунду, все впустую.
# Это те же грабли, что [[lock-leaked-into-a-child]].
if ! flock -n 9; then
    say "карту сейчас правит кто-то другой (лок $LOK) — выхожу, повторю по расписанию"
    exit 0
fi

mkdir -p "$LOG_DIR" "$HEARTBEAT_DIR" "$OTCHET_DIR"

REZHIM="--применить"
[ "${1:-}" = "--сухой" ] && REZHIM=""

NACHALO_PROGONA=$(date +%s)
VYVOD=$(cd "$PROJECT_DIR" && python3 scripts/acceptance.py $REZHIM 2>&1)
SUDYA_RC=$?
# Код 1 у судьи — это «есть провалы», работа состоялась. Всё, что больше, —
# сам судья упал: битая карта, нет yaml, любая беда. Тогда метку присмотра
# писать НЕЛЬЗЯ: сломанный механизм со свежей меткой неотличим от здорового и
# молчит (находка I5 ревью кода 11.09.2026).
if [ "$SUDYA_RC" -gt 1 ]; then
    say "ОТКАЗ: приёмка упала (код $SUDYA_RC) — метку не ставлю, зову владельца"
    printf '%s\n' "$VYVOD" | tail -5
    bash "$PROJECT_DIR/scripts/tg_send.sh" \
        "Приёмка задач упала и не отработала. Метка присмотра не обновлена — сторож это увидит." \
        >/dev/null 2>&1 || true
    exit "$SUDYA_RC"
fi
ITOG=$(printf '%s\n' "$VYVOD" | chisla)

OTCHET="$OTCHET_DIR/$(date +%Y-%m-%d).md"
{
    printf '# Приёмка задач: %s\n\n' "$(date '+%d.%m.%Y %H:%M')"
    printf 'Итог: %s\n\n' "$ITOG"
    printf 'Проверка идёт по полю `проверка:` в карточке задачи: команда и то,\n'
    printf 'что обязано быть в её выводе. Нет поля — «доказать нечем», и это\n'
    printf 'работа строителю проверок, а не повод закрыть задачу.\n\n'
    printf '```\n%s\n```\n' "$VYVOD"
} > "$OTCHET"

# Закрыл задачу — унеси её из карты. Владелец 11.09.2026: «Один агент пишет
# проверки, другой проверки делает и отмечает что задача проверена, разве он
# не может по логике чистить?» — может и должен: чистка это второй шаг того же
# действия, а не чужая работа. Карта и архив пишутся вместе (И-1).
UBRANO=0
if [ "$REZHIM" = "--применить" ]; then
    UBRANO=$(cd "$PROJECT_DIR" && python3 scripts/archive-map.py --перенести 2>&1 \
             | sed -n 's/.*закрытых задач: \([0-9]*\).*/\1/p')
    UBRANO="${UBRANO:-0}"
    if [ "$UBRANO" != "0" ] \
       && ! bash "$PROJECT_DIR/scripts/pre-commit-gate.sh" --devmap-only "$PROJECT_DIR/dev-map.yaml" >/dev/null 2>&1; then
        say "ТРЕВОГА: после переноса в архив карта не проходит валидатор"
        bash "$PROJECT_DIR/scripts/tg_send.sh" \
            "Приёмка убрала закрытые задачи в архив, и карта перестала проходить проверку. Работа остановлена — нужен разбор." \
            >/dev/null 2>&1 || true
        exit 1
    fi
fi

say "$ITOG убрано-в-архив=$UBRANO · отчёт: $OTCHET"

# Владельцу — числа, а не простыня: сам отчёт лежит файлом.
PROVAL=$(chislo_iz провал "$ITOG")
PRINYATO=$(chislo_iz принято "$ITOG")
VLADELCU=$(chislo_iz владельцу "$ITOG")
NECHEM=$(chislo_iz нечем "$ITOG")
VRYOT=$(chislo_iz врёт "$ITOG")

# БОЛЬНОЙ СЛУЧАЙ 15–20.09.2026: условие сообщения смотрело ТОЛЬКО на принято и
# провал, поэтому семь дней из шестнадцати канал молчал — ровно в те дни, когда
# «нечем» было 38, то есть долг перед владельцем был наибольшим. Он 27.09:
# «куча всего лежит в статусе тест а я даже об этом не знаю и не понимаю».
#
# Теперь поводов два, и очередь владельца среди них — но с анти-повтором по
# ЧИСЛУ: пока оно не изменилось, второй раз то же самое не шлётся (улика того
# же дня — 14 пар одинаковых сообщений за три часа).
SLED="$LOG_DIR/priyomka.последняя-очередь-владельцу"
BYLO=$(cat "$SLED" 2>/dev/null || echo "нет")
DVIZHENIE=0
{ [ "$PRINYATO" != "0" ] || [ "$PROVAL" != "0" ]; } && DVIZHENIE=1
# Метка — по СОСТАВУ очереди, а не по её длине: подмена одной задачи другой
# оставляет число прежним, и новая задача входила в очередь владельца молча
# (находка G-03 ревью 27.09.2026). Состав берётся из строк отчёта судьи.
SOSTAV=$(printf '%s\n' "$VYVOD" | awk '/^  ждёт-владельца/{print $2}' \
         | sort | sha1sum | cut -c1-12)
OCHERED_NOVA=0
{ [ "$VLADELCU" != "0" ] && [ "$SOSTAV" != "$BYLO" ]; } && OCHERED_NOVA=1

if [ "$DVIZHENIE" = 1 ] || [ "$OCHERED_NOVA" = 1 ]; then
    POTOLOK="${OWNER_QUEUE_MAX:-5}"
    # Сигнал обязан называть РАБОТУ, а не задавать владельцу вопрос: «нечем» —
    # это порция строителю проверок, и решать тут нечего
    # ([[early-signal-must-name-the-work]]).
    HVOST="Твоя очередь: $VLADELCU (доказать может только человек)."
    if [ "$VLADELCU" -gt "$POTOLOK" ]; then
        HVOST="$HVOST Это выше потолка $POTOLOK — сокращает её строитель проверок, не ты."
    fi
    [ "$NECHEM" != "0" ] && HVOST="$HVOST Без способа проверки: $NECHEM — работа строителя."
    # «Врёт» — команда прошла, а обещанного в выводе нет: механизм здоров,
    # неверно обещание. Владельцу тут решать нечего, это порция строителю.
    [ "$VRYOT" != "0" ] && HVOST="$HVOST Проверки обещают не то, что печатают: $VRYOT — их переписывает строитель."
    # Число запоминается ТОЛЬКО если сообщение УШЛО. Прежде метка писалась
    # безусловно, и один отказ канала (429, отказ сторожа канала, нет сети)
    # означал молчание навсегда — тот самый класс, который этот механизм и
    # чинит ([[api-failures-counted-as-work]], находка G-02 ревью 27.09.2026).
    if bash "$PROJECT_DIR/scripts/tg_send.sh" \
           "Приёмка: $ITOG. $HVOST Отчёт в docs/приёмка/." >/dev/null 2>&1; then
        printf '%s' "$SOSTAV" > "$SLED"
    else
        say "ОТКАЗ канала: состав очереди не запоминаю, скажу в следующий прогон"
    fi
    # Число мало: владелец 27.09.2026 — «Мне нужен конкретный список с
    # пояснениями что мне нужно проверит и как». Список уходит ФАЙЛОМ, потому
    # что семь задач с шагами не влезают в потолок сообщения, а путь в тексте
    # он не откроет (правило канала 4).
    if [ "$OCHERED_NOVA" = 1 ]; then
        # Файл пишет САМ прогон судьи из своих вердиктов (второй прибор на тот
        # же факт разъехался бы с числом в сообщении). Демон проверяет, что
        # файл написан ЭТИМ прогоном — не старше его начала.
        #
        # Сравнивать с отчётом нельзя: отчёт пишется ПОСЛЕ судьи, поэтому
        # «список новее отчёта» не выполнялось никогда и список не уходил ни
        # разу (находка G-01 ревью 27.09.2026, critical).
        SPISOK_FILE="$OTCHET_DIR/очередь-владельца.md"
        if [ -s "$SPISOK_FILE" ] \
           && [ "$(stat -c %Y "$SPISOK_FILE" 2>/dev/null || echo 0)" -ge "$NACHALO_PROGONA" ]; then
            bash "$PROJECT_DIR/scripts/tg_send.sh" --file "$SPISOK_FILE" \
                --caption "Список того, что проверить вам: $VLADELCU задач, у каждой написано как" \
                >/dev/null 2>&1 || true
        else
            say "ОТКАЗ: список очереди владельца не собран прогоном (файл пуст или старее отчёта) — владельцу не шлю"
        fi
    fi
fi

date -Is > "$HEARTBEAT_DIR/priyomka-watch"
exit 0
