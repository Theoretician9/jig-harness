#!/usr/bin/env python3
"""Гейт удержания: у каждого пишущего пути есть хозяин, потолок и срок.

Замечание владельца П-3 к ревизии 10.09.2026: «мусор — это один дефект, а не
семь». В таблице мусора у каждой строки в графе «кто убирает» стояло «никто»;
разовая прополка (или точечный logrotate) вернула бы тот же список через
месяц. Правило кодом, а не привычкой: путь, у которого нет объявленной
политики, красит ворота — значит завели запись, не решив, кто её убирает.

Что проверяется:
  1. каждый файл в $LOG_DIR подпадает под маску из harness/config/удержание.yaml;
  2. суммарный размер по маске не выше потолка;
  3. файлы старше срока называются числом (это не отказ, а работа для хозяина).

Запуск: python3 scripts/check-uderzhanie.py [--подробно] [--selftest]
"""
import os
import re
import sys
import time

import yaml

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "lib"))
from konf import log_dir, конфиг  # noqa: E402 — один парсер конфига на все гейты

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ДАННЫЕ = os.path.join(КОРЕНЬ, "harness", "config", "удержание.yaml")


def подходит(отн: str, маска: str) -> bool:
    """Маска — список через «|»; «*» НЕ переходит через «/».

    fnmatch считает «*» всеядной, и маска «inbox/*» съедала вложения из
    «inbox/файлы/» вместе с их собственной политикой — 60 МБ при потолке 5,
    отказ на ровном месте. Разделитель каталогов обязан оставаться границей.
    """
    for m in маска.split("|"):
        шаблон = "".join("[^/]*" if c == "*" else
                         "[^/]" if c == "?" else re.escape(c) for c in m)
        if re.fullmatch(шаблон, отн):
            return True
    return False


def обход(корень: str):
    for путь, _каталоги, файлы in os.walk(корень):
        for f in файлы:
            полный = os.path.join(путь, f)
            yield os.path.relpath(полный, корень), полный


def уборщик(политика: dict) -> str:
    """Команда, которой лечится превышение, или пусто — уборщика нет."""
    к = str(политика.get("уборщик", "нет")).strip()
    return "" if к in ("", "нет", "никто") else к


def красит(политика: dict) -> bool:
    """Превышение потолка красит ворота только там, где есть чем погасить.

    Ревью 10.09.2026: гейт краснел от вложений владельца (их агент удалять не
    вправе — И-1) и от случайного рабочего файла в каталоге. Красный гейт,
    который нечем погасить, выключают вместе с остальной защитой. Признак не
    объявляется отдельно, а следует из наличия команды уборки: два поля,
    обязанных сходиться, рано или поздно разойдутся (q-08).
    """
    return bool(уборщик(политика))


def посчитать(корень: str, политики: list) -> tuple:
    """Обход каталога → (размеры по маскам, счётчики старья, пути без политики).

    Считает и только считает: печать и решение «красный или нет» живут выше.
    Разделение — по ревью 10.09.2026 (q-17): прежняя функция мерила, судила и
    докладывала в одном теле длиннее экрана, и проверить её счёт отдельно от
    её печати было нечем.
    """
    размер = {p["маска"]: 0 for p in политики}
    старьё = {p["маска"]: 0 for p in политики}
    ничьи = []
    сейчас = time.time()
    for отн, полный in обход(корень):
        try:
            байт = os.path.getsize(полный)
            дней = (сейчас - os.path.getmtime(полный)) / 86400
        except OSError:
            continue
        for p in политики:
            if подходит(отн, p["маска"]):
                размер[p["маска"]] += байт
                if p["срок_дней"] and дней > p["срок_дней"]:
                    старьё[p["маска"]] += 1
                break
        else:
            ничьи.append(отн)
    return размер, старьё, ничьи


def проверить(корень: str, политики: list, подробно: bool) -> int:
    if not os.path.isdir(корень):
        # Отвалившийся том, опечатка в LOG_DIR, чужие права — всё это читалось
        # как здоровье: os.walk по пустоте молчит (ревью 10.09.2026).
        print(f"  [удержание] ✗ каталога журналов нет вовсе: {корень} — "
              f"проверять нечего, а значит и писать некуда")
        return 1
    размер, старьё, ничьи = посчитать(корень, политики)
    красных = 0
    for p in политики:
        мб = размер[p["маска"]] / 1024 / 1024
        плохо = мб > p["потолок_мб"]
        красных += плохо and красит(p)
        if плохо or подробно:
            метка = ("ПЕРЕПОЛНЕН" if плохо and красит(p)
                     else "ТЕСНО — убрать может только владелец" if плохо else "ок")
            print(f"  [удержание] {метка} {p['маска']}: {мб:.1f} МБ при потолке "
                  f"{p['потолок_мб']} МБ · хозяин: {p['хозяин']}")
            if плохо and красит(p):
                print(f"  [удержание] лечится: {уборщик(p)}")
        if старьё[p["маска"]]:
            print(f"  [удержание] под уборку: {старьё[p['маска']]} файлов старше "
                  f"{p['срок_дней']} дн по маске {p['маска']} — чистит {p['хозяин']}")
    if ничьи:
        # Предупреждение, не отказ: случайный рабочий файл не должен блокировать
        # коммит чужой работы (живой случай 10.09 — копия журнала на минуту).
        print(f"  [удержание] ⚠ путей без хозяина: {len(ничьи)} — "
              f"объяви политику в harness/config/удержание.yaml")
        for отн in ничьи[:5]:
            print(f"      • {отн}")
    if not красных:
        print("[удержание] у каждого пути есть хозяин и потолок")
    return красных


def самотест() -> int:
    import tempfile
    ok = True
    политики = [{"маска": "*.log", "хозяин": "проба", "потолок_мб": 0,
                 "срок_дней": 1, "уборщик": "bash уборка.sh"}]
    with tempfile.TemporaryDirectory() as tmp:
        # БОЛЬНОЙ СЛУЧАЙ: путь, не подпадающий ни под одну маску, обязан красить.
        open(os.path.join(tmp, "чужой.dat"), "w").close()
        красных = проверить(tmp, [{"маска": "*.log", "хозяин": "п", "потолок_мб": 10,
                                   "срок_дней": 0, "уборщик": "bash уборка.sh"}], False)
        ok = ok and красных == 0
        print(f"  {'ок   ' if красных == 0 else 'ПЛОХО'} файл без политики — предупреждение, не отказ")
    with tempfile.TemporaryDirectory() as tmp:
        with open(os.path.join(tmp, "толстый.log"), "w") as fh:
            fh.write("x" * 200_000)
        красных = проверить(tmp, политики, False)
        ok = ok and красных == 1
        print(f"  {'ок   ' if красных == 1 else 'ПЛОХО'} потолок превышен — красный")
    with tempfile.TemporaryDirectory() as tmp:
        open(os.path.join(tmp, "мелкий.log"), "w").close()
        красных = проверить(tmp, [{"маска": "*.log", "хозяин": "п", "потолок_мб": 10,
                                   "срок_дней": 0, "уборщик": "bash уборка.sh"}], False)
        ok = ok and красных == 0
        print(f"  {'ок   ' if красных == 0 else 'ПЛОХО'} всё в пределах — зелёный")
    # БОЛЬНЫЕ СЛУЧАИ ревью 10.09: пропавший каталог читался как здоровье, а
    # потолок без уборщика красил ворота, которые нечем погасить.
    красных = проверить("/нет-такого-каталога-харнеса", политики, False)
    ok = ok and красных == 1
    print(f"  {'ок   ' if красных == 1 else 'ПЛОХО'} БОЛЬНОЙ СЛУЧАЙ: каталога журналов нет — отказ, а не тишина")
    import tempfile as _t
    with _t.TemporaryDirectory() as tmp:
        with open(os.path.join(tmp, "толстый.log"), "w") as fh:
            fh.write("x" * 200_000)
        без_уборщика = [{"маска": "*.log", "хозяин": "ВЛАДЕЛЕЦ", "потолок_мб": 0,
                         "срок_дней": 0, "уборщик": "нет"}]
        красных = проверить(tmp, без_уборщика, False)
        ok = ok and красных == 0
        print(f"  {'ок   ' if красных == 0 else 'ПЛОХО'} БОЛЬНОЙ СЛУЧАЙ: потолок без уборщика — тесно, но не отказ")
    print("SELFTEST: зелёный (5 путей, два больных: пропавший каталог и потолок без уборщика)"
          if ok else "SELFTEST: КРАСНЫЙ")
    return 0 if ok else 1


def main() -> int:
    if "--selftest" in sys.argv:
        return самотест()
    with open(ДАННЫЕ, encoding="utf-8") as fh:
        политики = yaml.safe_load(fh)["пути"]
    return проверить(log_dir(), политики, "--подробно" in sys.argv)


if __name__ == "__main__":
    sys.exit(main())
