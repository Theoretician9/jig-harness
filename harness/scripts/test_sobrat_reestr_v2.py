print("── живые данные: приёмка задания владельца ──")
# Числа задания считаются ЗДЕСЬ своим счётом по входному файлу, и вывод
# сборщика обязан совпасть с ним. Чтение числа из вывода сборщика было бы
# пересказом; два независимых счётчика, сошедшихся на одном числе, — довод.
ЖИВЫЕ = json.loads(КАРТА_БОЕВАЯ.read_text(encoding="utf-8"))
СЕМЕЙСТВА = {}
for з in ЖИВЫЕ:
    СЕМЕЙСТВА[з["f"]] = СЕМЕЙСТВА.get(з["f"], 0) + 1
МЕХ = СЕМЕЙСТВА.get("mech", 0) + СЕМЕЙСТВА.get("promote", 0)
ПРАВ = СЕМЕЙСТВА.get("rule", 0)
СКИЛ = СЕМЕЙСТВА.get("skill", 0) + СЕМЕЙСТВА.get("skill-dom", 0)
СЛИТ = (СЕМЕЙСТВА.get("proof", 0) + СЕМЕЙСТВА.get("wrap", 0)
        + СЕМЕЙСТВА.get("part", 0))
ИМЕНА = {з["n"] for з in ЖИВЫЕ}
В_НИКУДА = [з for з in ЖИВЫЕ if з["t"] and з["t"] not in ИМЕНА]
ЦЕЛИ_В_НИКУДА = sorted({з["t"] for з in В_НИКУДА})
БЕЗ_КОНТУРА_ЖИВЫХ = [з["n"] for з in ЖИВЫЕ if not з["c"]]
print(f"     свой замер входа: записей {len(ЖИВЫЕ)} · механизмы {МЕХ} "
      f"(mech {СЕМЕЙСТВА.get('mech', 0)} + promote {СЕМЕЙСТВА.get('promote', 0)}) · "
      f"правила {ПРАВ} · скилы {СКИЛ} · слитые {СЛИТ} · "
      f"в никуда записей {len(В_НИКУДА)} / целей {len(ЦЕЛИ_В_НИКУДА)} · "
      f"без контура {len(БЕЗ_КОНТУРА_ЖИВЫХ)}")

# Это проверка ВХОДНОГО файла, а не машины: 127 = 55+31+19+22 задано снаружи
