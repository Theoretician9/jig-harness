#!/usr/bin/env python3
"""Проверка сборщика черновика реестра v2 — ДО того, как сборщик написан.

Откуда взято. Задание владельца из разбора устройства (файл 02) и спека
`docs/specs/2026-09-13-реестр-устройства-v2.md`, фаза 2; план
`docs/plans/hr.reestr-v2.md`, Task 2. Сборщик `scripts/sobrat-reestr-v2.py`
читает разбор (`docs/РАЗБОР-УСТРОЙСТВА-2026-09-12/karta-data.json`, 127 записей)
и живой реестр (`harness/config/устройство.yaml`) и собирает ЧЕРНОВИК паспортов
v2 — ничего не перезаписывая.

Почему пробы написаны раньше кода. Приёмка задания `127 = 55 + 31 + 19 + 22`
уже была посчитана неверно: формулировка «механизмы + правила + скилы + слитые»
без семейства `promote` даёт 121, и первая редакция плана эту потерю не
заметила. Требование, записанное только словами, теряет шесть записей молча;
записанное пробой — краснеет.

Каждая проба СОЗДАЁТ своё условие: свой временный двор со своим
`karta-data.json` и своим реестром. Пути подставляются переменными окружения,
боевые файлы сверяются по md5 до и после прогона ([[проба-играет-на-боевом]]).

Красный прогон до реализации обязан падать с ПРИЧИНОЙ. Отсутствие сборщика —
не причина: путь, зелёный от «команды нет», не проверяет ничего
([[кириллица-в-именах-bash]], абзац про rc=127). Поэтому «сборщика нет»
считается отдельным исходом и красным путём не засчитывается никогда.

Прогон:
    python3 scripts/test_sobrat_reestr_v2.py
Код возврата: 0 — все пути прошли, 1 — есть упавший.
"""
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

КОРЕНЬ = Path(__file__).resolve().parent.parent
СБОРЩИК = КОРЕНЬ / "scripts" / "sobrat-reestr-v2.py"
КАРТА_БОЕВАЯ = КОРЕНЬ / "docs" / "РАЗБОР-УСТРОЙСТВА-2026-09-12" / "karta-data.json"
РЕЕСТР_БОЕВОЙ = КОРЕНЬ / "harness" / "config" / "устройство.yaml"
ЧЕРНОВИК_В_БОЕВОМ = КОРЕНЬ / "harness" / "config" / "устройство-v2.draft.yaml"

# Ручки окружения — часть контракта сборщика. Имена продолжают уже живущие в
# проекте (HARNESS_USTROJSTVO читает harness/panel/sostoyanie.py,
# HARNESS_PASPORT — scripts/check-ustrojstvo.py): подставляются на КАЖДОМ
# вызове, без кэша при импорте ([[дефолт-до-загрузчика-убивает-настройку]]).
РУЧКА_КАРТА = "HARNESS_KARTA_DATA"
РУЧКА_РЕЕСТР = "HARNESS_USTROJSTVO"
РУЧКА_ЧЕРНОВИК = "HARNESS_CHERNOVIK"
РУЧКИ = (РУЧКА_КАРТА, РУЧКА_РЕЕСТР, РУЧКА_ЧЕРНОВИК)

# Не код возврата, а отдельный исход: файла сборщика ещё нет.
НЕТ_СБОРЩИКА = -1

# Следы падения, а не отказа. Сборщик, упавший трассировкой, причину НЕ назвал.
КРАХ = ("Traceback (most recent call last)",
        "can't open file",
        "No such file or directory",
        "ModuleNotFoundError")

ОК, УПАЛО = [], []


def проба(имя: str, условие: bool, подробность: str = "") -> None:
    (ОК if условие else УПАЛО).append(имя)
    знак = "✓" if условие else "✗"
    print(f"  {знак} {имя}" + (f" — {подробность}" if подробность and not условие else ""))


def _слепок_боевых() -> dict:
    """md5 всего, что сборщик читает или мог бы задеть."""
    слепок = {п.name: hashlib.md5(п.read_bytes()).hexdigest()
              for п in sorted((КОРЕНЬ / "harness" / "config").glob("*.yaml"))}
    слепок["karta-data.json"] = hashlib.md5(КАРТА_БОЕВАЯ.read_bytes()).hexdigest()
    return слепок


def _паспортов_в_боевом() -> int:
    данные = yaml.safe_load(РЕЕСТР_БОЕВОЙ.read_text(encoding="utf-8"))
    return len(данные["механизмы"])


СЛЕПОК_ДО = _слепок_боевых()
ПАСПОРТОВ_ДО = _паспортов_в_боевом()
ЧЕРНОВИК_В_БОЕВОМ_БЫЛ = ЧЕРНОВИК_В_БОЕВОМ.exists()


# ─── подставной вход: свои записи, свои числа ───────────────────────────────
def зап(номер: int, семейство: str, **прочее) -> dict:
    """Одна запись разбора. Поля односимвольные — как в karta-data.json."""
    основа = {
        "i": номер,
        "n": f"Механизм {номер}",
        "p": f"scripts/mehanizm-{номер}.py",
        "old": "Связь с владельцем",
        "f": семейство,
        "c": "К5 Смена",
        "k": "гейт",
        "b": "ложь",
        "t": "",
        "d": "Что делает этот механизм.",
        "bez": "Что сломается, если его убрать.",
        "kog": "когда срабатывает",
        "pr": f"python3 scripts/mehanizm-{номер}.py --selftest",
    }
    основа.update(прочее)
    return основа


ПАСПОРТ = {
    "файл": "harness/demons/backup.sh",
    "вид": "демон",
    "тема": "данные и сервер",
    "имя": "Резервные копии",
    "роль": "Каждую ночь снимает копию рабочих данных.",
    "когда": "каждые сутки в 03:10",
    "без_него": "Потерянные данные будет неоткуда вернуть.",
    "проверяется": "bash harness/demons/backup.sh --selftest",
    "пишет": "копии в /var/backups/harness",
}


def набор(**семейства) -> list:
    """Вход с заданным числом записей каждого семейства; имена сквозные.

    Ключ `skill_dom` — семейство `skill-dom`: в имени python дефис не живёт.
    """
    записи, номер = [], 0
    for ключ, сколько in семейства.items():
        семейство = ключ.replace("_", "-")
        for _ in range(сколько):
            записи.append(зап(номер, семейство))
            номер += 1
    return записи


def равенство(всего: int, мех: int, прав: int, скил: int, слит: int) -> str:
    """Строка приёмки задания. Форма фиксирована: её печатает отчёт владельцу."""
    return f"{всего} = {мех} + {прав} + {скил} + {слит}"


def двор(записи, паспорта=None) -> dict:
    """Временный двор: свой karta-data.json, свой реестр, свой путь черновика."""
    каталог = Path(tempfile.mkdtemp(prefix="reestr-v2-"))
    карта = каталог / "karta-data.json"
    карта.write_text(json.dumps(записи, ensure_ascii=False), encoding="utf-8")
    реестр = каталог / "устройство.yaml"
    реестр.write_text(
        yaml.safe_dump({"механизмы": [ПАСПОРТ] if паспорта is None else паспорта},
                       allow_unicode=True),
        encoding="utf-8")
    return {"каталог": каталог,
            РУЧКА_КАРТА: карта,
            РУЧКА_РЕЕСТР: реестр,
            РУЧКА_ЧЕРНОВИК: каталог / "устройство-v2.draft.yaml"}


def прогон(аргументы=(), ручки=None, предел: int = 120):
    """Боевой вызов отдельным процессом — так сборщика зовут ворота.

    Возвращает (rc, вывод). Если файла сборщика нет — rc = НЕТ_СБОРЩИКА:
    этот исход не годится ни в зелёный путь, ни в красный.
    """
    if not СБОРЩИК.exists():
        return НЕТ_СБОРЩИКА, f"СБОРЩИКА НЕТ: {СБОРЩИК} не создан"
    окружение = dict(os.environ)
    for ручка in РУЧКИ:
        окружение.pop(ручка, None)
    окружение.update({к: str(v) for к, v in (ручки or {}).items()})
    итог = subprocess.run([sys.executable, str(СБОРЩИК), *аргументы],
                          cwd=str(КОРЕНЬ), env=окружение,
                          capture_output=True, text=True, timeout=предел)
    return итог.returncode, (итог.stdout or "") + (итог.stderr or "")


def сверка(записи, аргументы=("--сверка",), паспорта=None):
    """(rc, вывод, черновик, имя_черновика) на подставном дворе; двор убирается."""
    д = двор(записи, паспорта)
    имя_черновика = д[РУЧКА_ЧЕРНОВИК].name
    try:
        rc, вывод = прогон(аргументы,
                           ручки={к: v for к, v in д.items() if к != "каталог"})
        черновик = None
        if д[РУЧКА_ЧЕРНОВИК].exists():
            черновик = yaml.safe_load(
                д[РУЧКА_ЧЕРНОВИК].read_text(encoding="utf-8"))
        return rc, вывод, черновик, имя_черновика
    finally:
        shutil.rmtree(д["каталог"], ignore_errors=True)


def _красный_годен(rc, вывод: str, слова) -> bool:
    """Красный путь засчитывается, ТОЛЬКО если сборщик назвал причину сам."""
    if rc in (0, НЕТ_СБОРЩИКА):
        return False
    if any(след in вывод for след in КРАХ):
        return False
    return all(слово in вывод for слово in слова)


def сошлось(имя, rc, вывод, *куски):
    нет = [к for к in куски if к not in вывод]
    проба(имя, rc == 0 and not нет,
          f"rc={rc}, не нашлось {нет}, вывод: {вывод[:300]!r}")


def красный_с_причиной(имя, rc, вывод, *слова):
    проба(имя, _красный_годен(rc, вывод, слова),
          f"rc={rc}, названо {[с for с in слова if с in вывод]} из {list(слова)}, "
          f"вывод: {вывод[:300]!r}")


print("── ловушка красного: «команды нет» зелёным не считается ──")
# Существует затем, что сборщика ещё НЕТ, и любой запуск даёт ненулевой код.
# Проба «ожидаю rc≠0» без требования причины была бы зелена весь красный
# прогон и осталась бы зелёной навсегда. Эти три пути охраняют сам разборщик
# исходов — они единственные, кто обязан быть зелёным ДО реализации.
проба("rc=127 с пустым выводом красным НЕ считается",
      not _красный_годен(127, "", ["без контура: 1"]))
проба("падение трассировкой красным НЕ считается",
      not _красный_годен(1, "Traceback (most recent call last)\nбез контура: 1",
                         ["без контура: 1"]))
проба("«сборщика нет» красным НЕ считается",
      not _красный_годен(НЕТ_СБОРЩИКА, "СБОРЩИКА НЕТ", ["без контура: 1"]))
проба("честный отказ с названной причиной — считается",
      _красный_годен(1, "без контура: 1 — Механизм 0", ["без контура: 1"]))

print("── сборщик существует ──")
# Отдельным путём, чтобы красный прогон не пришлось объяснять словами: строка
# ниже прямо называет, чего не хватает.
проба("файл scripts/sobrat-reestr-v2.py создан", СБОРЩИК.exists(),
      f"нет файла {СБОРЩИК}")

print("── разбивка входа: четыре группы задания ──")
# Охраняет приёмку З-2. Числа СВОИ, не 127: проба, требующая живого числа,
# совпадает с машиной, а не проверяет её ([[проверка-создаёт-условие]]).
# Вход 12 записей → 12 = 5 + 1 + 3 + 3, и каждая группа составная.
ВХОД_12 = набор(mech=2, promote=3, rule=1, skill=2, skill_dom=1,
                proof=1, wrap=1, part=1)
rc12, вывод12, _, _ = сверка(ВХОД_12)
сошлось("сверка на подставном входе печатает равенство 12 = 5 + 1 + 3 + 3",
        rc12, вывод12, равенство(12, 5, 1, 3, 3))
сошлось("группы названы словами задания: механизмы · правила · скилы · слитые",
        rc12, вывод12, "механизмы", "правила", "скилы", "слитые")
проба("сходящаяся сверка даёт rc=0", rc12 == 0,
      f"rc={rc12}, вывод: {вывод12[:300]!r}")

print("── семейство promote входит в механизмы (ловушка «121») ──")
# Улика: первая редакция плана написала «механизмы + правила + скилы + слитые»
# без promote и получила 121 вместо 127 — шесть записей исчезли молча.
# Вход ТОЛЬКО из promote: сборщик, забывший это семейство, напечатает «0 = 0…»
# и не сойдётся с общим числом.
rc_pr, вывод_pr, _, _ = сверка(набор(promote=3))
сошлось("вход из трёх promote даёт «3 = 3 + 0 + 0 + 0»",
        rc_pr, вывод_pr, равенство(3, 3, 0, 0, 0))

print("── skill-dom входит в скилы, wrap и part — в слитые ──")
rc_sk, вывод_sk, _, _ = сверка(набор(skill=1, skill_dom=2))
сошлось("skill 1 + skill-dom 2 даёт «3 = 0 + 0 + 3 + 0»",
        rc_sk, вывод_sk, равенство(3, 0, 0, 3, 0))
rc_sl, вывод_sl, _, _ = сверка(набор(proof=1, wrap=1, part=1))
сошлось("proof 1 + wrap 1 + part 1 даёт «3 = 0 + 0 + 0 + 3»",
        rc_sl, вывод_sl, равенство(3, 0, 0, 0, 3))

print("── незнакомое семейство не теряется молча ──")
# Без этого пути новое семейство в разборе просто выпадет из суммы, и приёмка
# окажется «сошлась» на неполных данных: ровно так теряются шесть promote.
rc_чужой, вывод_чужой, _, _ = сверка(набор(mech=1) + [зап(9, "выдумка")])
красный_с_причиной("семейство вне перечня — красный и НАЗВАНО поимённо",
                   rc_чужой, вывод_чужой, "выдумка")

print("── слитые в никуда: числом и поимённо ──")
# Охраняет ссылочную целостность слияния. «Слитых в никуда» — это записи,
# чья цель (поле t) не существует как запись разбора. Печатаются ДВА числа:
# записей и целей — они не равны (живой замер: 7 записей в 6 целей), и
# сборщик, печатающий одно, неотличим от сборщика, считающего другое.
ЦЕЛЬ_ЕСТЬ = [зап(0, "mech", n="Панель управления"),
             зап(1, "proof", t="Панель управления")]
rc_есть, вывод_есть, _, _ = сверка(ЦЕЛЬ_ЕСТЬ)
сошлось("все цели существуют — «слитых в никуда: 0 (целей 0)»",
        rc_есть, вывод_есть, "слитых в никуда: 0 (целей 0)")

ЦЕЛИ_НЕТ = [зап(0, "mech", n="Панель управления"),
            зап(1, "proof", n="Проверка входа в панель",
                t="Вход в панель по одноразовой ссылке")]
rc_нет, вывод_нет, _, _ = сверка(ЦЕЛИ_НЕТ)
сошлось("цель слияния не существует — «слитых в никуда: 1 (целей 1)»",
        rc_нет, вывод_нет, "слитых в никуда: 1 (целей 1)")
сошлось("несуществующая цель названа поимённо, вместе с записью",
        rc_нет, вывод_нет, "Вход в панель по одноразовой ссылке",
        "Проверка входа в панель")

ДВЕ_В_ОДНУ = [зап(0, "mech", n="Панель управления"),
              зап(1, "proof", n="Проверка писателя настроек",
                  t="Единственный писатель настроек"),
              зап(2, "promote", n="Проверка включателя шагов",
                  t="Единственный писатель настроек")]
rc_две, вывод_две, _, _ = сверка(ДВЕ_В_ОДНУ)
сошлось("две записи в одну отсутствующую цель — «слитых в никуда: 2 (целей 1)»",
        rc_две, вывод_две, "слитых в никуда: 2 (целей 1)")

# Слитые в никуда rc НЕ красят: спека фаза 2 прямо говорит, что это не дефект
# сборщика, а те же механизмы без паспорта, и ноль требуется ПОСЛЕ Task 5.
# Шаг 1 плана Task 2 требует здесь «и красный» — это расхождение с фазой 2 и
# с Шагом 4 того же Task 2 («на живых данных равенство сходится»): на живых
# данных слитых в никуда семь, и красный rc сделал бы Шаг 4 недостижимым.
проба("слитые в никуда печатаются, но rc не красят (сверка сошлась)",
      rc_нет == 0, f"rc={rc_нет}, вывод: {вывод_нет[:300]!r}")

print("── контур есть у каждой записи ──")
rc_к0, вывод_к0, _, _ = сверка(набор(mech=2))
сошлось("у всех записей контур — «без контура: 0»",
        rc_к0, вывод_к0, "без контура: 0")
БЕЗ_КОНТУРА = [зап(0, "mech"), зап(1, "mech", n="Безродный", c="")]
rc_бк, вывод_бк, _, _ = сверка(БЕЗ_КОНТУРА)
# Счётчик печатается и тогда, когда сверка красная: `сошлось` здесь требовало
# бы rc=0 одновременно с соседней пробой, требующей rc≠0 — один прогон не может
# дать оба. Проверяется то, ради чего путь заведён: число напечатано.
проба("запись с пустым контуром сосчитана — «без контура: 1»",
      "без контура: 1" in вывод_бк,
      f"rc={rc_бк}, вывод: {вывод_бк[:300]!r}")
красный_с_причиной("запись без контура красит сверку и названа поимённо",
                   rc_бк, вывод_бк, "без контура: 1", "Безродный")

print("── черновик: отдельный файл, боевой реестр не трогается ──")
# Охраняет главный запрет фазы 2: сборщик НИЧЕГО не перезаписывает.
ВХОД_ЧЕРНОВИКА = набор(mech=2, promote=1)
rc_ч, вывод_ч, черновик, имя_черновика = сверка(ВХОД_ЧЕРНОВИКА, аргументы=())
проба("без флагов сборщик пишет черновик по ручке окружения и даёт rc=0",
      rc_ч == 0 and черновик is not None,
      f"rc={rc_ч}, черновик: {черновик!r}, вывод: {вывод_ч[:300]!r}")
проба("черновик — YAML вида {механизмы: [...]} и не пуст",
      isinstance(черновик, dict) and isinstance(черновик.get("механизмы"), list)
      and черновик["механизмы"],
      f"черновик: {str(черновик)[:200]!r}")

записи_черновика = черновик.get("механизмы", []) if isinstance(черновик, dict) else []
пути_черновика = [з.get("файл") for з in записи_черновика if isinstance(з, dict)]
проба("каждый mech и promote входа получил паспорт в черновике",
      all(з["p"] in пути_черновика for з in ВХОД_ЧЕРНОВИКА),
      f"в черновике {пути_черновика}, ждали {[з['p'] for з in ВХОД_ЧЕРНОВИКА]}")
проба("паспорт живого реестра в черновике не потерян",
      ПАСПОРТ["файл"] in пути_черновика,
      f"в черновике {пути_черновика}")
# Тот самый инвариант, ради которого затеян реестр v2: у файла ровно один
# паспорт. Черновик, где путь встретился дважды, ломает его ещё до заведения.
