#!/usr/bin/env python3
"""Гейт: функция оболочки, званная выше своего определения, молчит.

Откуда взят. Улика 12.09.2026: в scripts/hooks/session_state.sh функция
«обрезать» вызывалась на строке 62, а определялась на 154. Каждый старт сессии
владелец видел «line 62: обрезать: command not found» и ПУСТОЕ поле «последний
коммит» — так с 11.08.2026, месяц. Ни один сторож не сработал: `bash -n` такой
файл считает законным, а у shellcheck правила на это нет вовсе (проверено на
образце — выдал только SC2005 про лишний echo).

Почему молчит. Оболочка читает файл сверху вниз: на момент вызова имени ещё
нет, вызов уходит в PATH, не находится и печатает ОДНУ строку в stderr.
Подстановка `$(…)` при этом не роняет скрипт — результат просто пустой, и
отказ выглядит как «данных нет», а не как «сломано».

Что ловим: вызов функции ВНЕ тела функций (на верхнем уровне) выше строки, где
она определена. Вызов из тела другой функции законен — тело исполняется
позже, когда определены уже все.

Прогон: python3 scripts/check-funkciya-do-opredeleniya.py [--selftest]
"""
import io
import os
import re
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
КАТАЛОГИ = ('scripts', 'harness')

# Отступ допускается: определение ВНУТРИ блока (например, заглушка канала в
# самотесте — `    tg_send() { … }`) — законный bash и именно то, что автор
# хотел: подменить настоящую функцию, определённую ниже. Прежняя редакция
# требовала начала строки и объявляла такую заглушку «вызовом выше
# определения» — краснела на честном коде (12.09.2026).
ОПРЕДЕЛЕНИЕ = re.compile(r'^\s*(?:function\s+)?([^\s()=]+)\s*\(\s*\)\s*\{')
КОНЕЦ_ТЕЛА = re.compile(r'^\s*\}')


def В_ПОЗИЦИИ_КОМАНДЫ(имя):
    """Имя запускается, а не упоминается: слово стоит там, где ждут команду.

    Без этого гейт краснел на здоровом коде — в pre-commit-hook.sh слово «гейт»
    девять раз встречается ВНУТРИ текста сообщений («прошло гейт»), а функция
    с тем же именем определена ниже. Краснящий зря гейт отключают.
    """
    return re.compile(r'(?:^|[;|&(){]|\$\(|`|\bthen\b|\bdo\b|\belse\b)\s*'
                      + re.escape(имя) + r'(?![\w./-])')


def разбор(текст):
    """(определения {имя: строка}, вызовы верхнего уровня [(имя, строка)])."""
    определения, вызовы, в_теле = {}, [], False
    for номер, строка in enumerate(текст.split('\n'), 1):
        без_отступа = строка.lstrip()
        if без_отступа.startswith('#'):
            continue
        начало = ОПРЕДЕЛЕНИЕ.match(строка)
        if начало:
            определения.setdefault(начало.group(1), номер)
            # Однострочное определение `f() { …; }` тело не открывает.
            в_теле = not строка.rstrip().endswith('}')
            continue
        if в_теле:
            if КОНЕЦ_ТЕЛА.match(строка):
                в_теле = False
            continue
        вызовы.append((номер, строка))
    return определения, вызовы


def находки_в(текст):
    определения, вызовы = разбор(текст)
    если_нет = []
    for номер, строка in вызовы:
        for имя, где in определения.items():
            if где <= номер:
                continue
            if В_ПОЗИЦИИ_КОМАНДЫ(имя).search(строка):
                если_нет.append((номер, имя, где, строка.strip()[:120]))
                break
    return если_нет


def файлы_репозитория():
    for каталог in КАТАЛОГИ:
        корень = os.path.join(КОРЕНЬ, каталог)
        if not os.path.isdir(корень):
            continue
        for путь, каталоги, имена in os.walk(корень):
            каталоги[:] = [d for d in каталоги if d not in ('.git', '__pycache__')]
            for имя in sorted(имена):
                if имя.endswith('.sh'):
                    yield os.path.join(путь, имя)


def самотест():
    случаи = [
        ('echo "$(обрезать 80)"\nобрезать() {\n  cat\n}\n', 1,
         'БОЛЬНОЙ СЛУЧАЙ: ровно session_state.sh — вызов на 1-й строке, определение на 2-й'),
        ('обрезать() {\n  cat\n}\necho "$(обрезать 80)"\n', 0,
         'определение выше вызова — здоровый код'),
        ('внешняя() {\n  поздняя 1\n}\nпоздняя() {\n  echo 1\n}\nвнешняя\n', 0,
         'вызов из ТЕЛА другой функции законен: тело исполняется позже'),
        ('say "привет"\nsay() { echo "$1"; }\n', 1,
         'однострочное определение ниже вызова — тот же отказ'),
        ('echo "функция обрезать описана ниже"\nобрезать() {\n  cat\n}\n', 0,
         'БОЛЬНОЙ СЛУЧАЙ 2: имя внутри ТЕКСТА сообщения — не вызов (девять таких в pre-commit-hook.sh)'),
        ('echo "$(git log -1 | обрезать 80)"\nобрезать() {\n  cat\n}\n', 1,
         'вызов за конвейером внутри подстановки — настоящий, ловим'),
        ('гейт "имена" python3 x.py\nгейт() { \"$@\"; }\n', 1,
         'вызов первым словом строки — настоящий'),
        ('вызов_потом() { echo 1; }\nвызов_потом\n', 0,
         'вызов сразу после определения — здоровый код'),
        ('if true; then\n    tg_send() { echo "$1"; }\n    tg_send "проба"\nfi\ntg_send() { curl -s x; }\n', 0,
         'ЛОЖНОЕ СРАБАТЫВАНИЕ: заглушка с отступом внутри блока — подмена, а не вызов выше определения'),
    ]
    ok = True
    for текст, ждём, зачем in случаи:
        было = len(находки_в(текст))
        if было != ждём:
            ok = False
        print('  %s %s (находок %d, ждали %d)' % ('ок   ' if было == ждём else 'ПЛОХО', зачем, было, ждём))
    print('САМОТЕСТ %s: %d путей, первым — больной случай'
          % ('ПРОЙДЕН' if ok else 'ПРОВАЛЕН', len(случаи)))
    return 0 if ok else 1


def main():
    if '--selftest' in sys.argv:
        return самотест()
    всего = 0
    for путь in файлы_репозитория():
        текст = io.open(путь, encoding='utf-8', errors='replace').read()
        for номер, имя, где, строка in находки_в(текст):
            всего += 1
            print('%s:%d  «%s» определена ниже, на строке %d:  %s'
                  % (os.path.relpath(путь, КОРЕНЬ), номер, имя, где, строка))
    if всего:
        print('[функция до определения] КРАСНЫЙ: %d вызов(ов) выше определения — оболочка '
              'напечатает «command not found» в stderr и вернёт ПУСТО, отказ выглядит как '
              '«данных нет». Перенесите определение выше первого вызова' % всего)
        return 1
    print('[функция до определения] чисто: функции определены выше своих вызовов')
    return 0


if __name__ == '__main__':
    sys.exit(main())
