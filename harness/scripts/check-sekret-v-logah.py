#!/usr/bin/env python3
"""Гейт: пароль из .env не лежит в логах харнеса.

СЛУЧАЙ, ради которого заведён (10.09.2026). Переустановка данных прода шла
через `make ... DSN_TARGET='$(DSN)'` фоном с логом в /var/log/harness. Make
печатает каждую команду рецепта ПЕРЕД выполнением, и DSN разворачивается в неё
целиком: в лог легла строка с паролем боевой базы. Замер после находки — 257
файлов логов содержали пароль, копилось месяцами.

Почему не поймал прежний сторож: `check-kirillica-v-imenah.py` завёлся под
похожий случай (значение переменной печаталось в ошибку), но стережёт ИМЕНА
переменных в скриптах. Здесь имя правильное, латиницей, а печатает значение
сам make — то есть путь утечки другой, и перекрывать его нужно отдельно
([[правило-перекрывает-один-путь-из-двух]]).

Гейт сравнивает ФАКТИЧЕСКИЕ пароли из .env-файлов с содержимым логов, а не
ищет «что-то похожее на пароль»: проверка обязана создавать своё условие, а не
совпадать с машиной ([[проверка-создаёт-условие]]).

Запуск: python3 scripts/check-sekret-v-logah.py [--чинить]
  --чинить  затирает найденные пароли на <СКРЫТО> вместо отказа

Код выхода: 0 — чисто, 1 — пароль найден в логах.
"""
from __future__ import annotations

import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
ЛОГИ = pathlib.Path("/var/log/harness")
# Короткие и словарные значения не ищем: «app», «postgres», «1234» встречаются
# в текстах логов сами по себе, и гейт на них краснел бы вечно (а краснеющий
# без причины гейт отключают). Восемь знаков — граница, ниже которой значение
# не является настоящим паролем установки.
МИН_ДЛИНА = 8
КЛЮЧИ = ("POSTGRES_PASSWORD", "TELEGRAM_TOKEN", "BOT_TOKEN", "SECRET_KEY")
ЗАМЕНА = "<СКРЫТО>"


def пароли(корень: pathlib.Path = КОРЕНЬ) -> set[str]:
    """Значения секретных ключей из всех .env продукта.

    Каталоги — аргументами (по умолчанию боевые): без этого гейт нельзя
    проверить иначе как на живой системе, где он зелёный всегда. Мутационная
    проба 10.09.2026 показала это прямо: у механизма не было ни одного
    больного случая, и обезврежен он был бы молча.
    """
    найдено: set[str] = set()
    for файл in корень.rglob(".env*"):
        if ".venv" in файл.parts or "node_modules" in файл.parts:
            continue
        try:
            строки = файл.read_text(encoding="utf-8", errors="ignore").splitlines()
        except OSError:
            continue
        for строка in строки:
            ключ, _, значение = строка.partition("=")
            значение = значение.strip().strip('"').strip("'")
            if ключ.strip() in КЛЮЧИ and len(значение) >= МИН_ДЛИНА:
                найдено.add(значение)
    return найдено


def проверить(чинить: bool, корень: pathlib.Path = КОРЕНЬ,
              логи: pathlib.Path = ЛОГИ) -> int:
    искомые = пароли(корень)
    if not искомые:
        print("[секрет-в-логах] в .env нет паролей длиннее "
              f"{МИН_ДЛИНА} знаков — проверять нечего")
        return 0
    if not логи.is_dir():
        print(f"[секрет-в-логах] каталога {логи} нет — проверять нечего")
        return 0

    образец = re.compile("|".join(re.escape(п) for п in искомые))
    грязные: list[pathlib.Path] = []
    for файл in логи.rglob("*"):
        if not файл.is_file():
            continue
        try:
            текст = файл.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue
        if not образец.search(текст):
            continue
        грязные.append(файл)
        if чинить:
            файл.write_text(образец.sub(ЗАМЕНА, текст), encoding="utf-8")

    if not грязные:
        print(f"[секрет-в-логах] паролей из .env в {логи} нет "
              f"(проверено значений: {len(искомые)})")
        return 0
    if чинить:
        print(f"[секрет-в-логах] затёрто в {len(грязные)} файл(ах)")
        return 0
    print(f"[секрет-в-логах] ПАРОЛЬ В ЛОГАХ: {len(грязные)} файл(ов)")
    for файл in грязные[:10]:
        print(f"  {файл}")
    if len(грязные) > 10:
        print(f"  … и ещё {len(грязные) - 10}")
    print("  Затереть: python3 scripts/check-sekret-v-logah.py --чинить")
    print("  Не допускать: make запускать с -s, либо export DATABASE_URL "
          "в Makefile вместо подстановки DSN в каждую строку рецепта")
    return 1


def самотест() -> int:
    """Больные случаи на подставных каталогах: живая система зелена всегда."""
    import tempfile
    ok = True

    def стенд(tmp: str, пароль: str, в_логе: str):
        корень, логи = pathlib.Path(tmp) / "repo", pathlib.Path(tmp) / "logs"
        (корень / "app").mkdir(parents=True)
        логи.mkdir()
        (корень / "app" / ".env").write_text(
            f"POSTGRES_PASSWORD={пароль}\nAPP_NAME=app\n", encoding="utf-8")
        (логи / "deploy.log").write_text(f"шаг сборки: {в_логе}\n", encoding="utf-8")
        return корень, логи

    def проба(имя: str, ждём: int, got: int):
        nonlocal ok
        if got == ждём:
            print(f"  ок    {имя}")
        else:
            print(f"  ПЛОХО {имя}: ждали rc={ждём}, получили rc={got}")
            ok = False

    # БОЛЬНОЙ СЛУЧАЙ 10.09.2026: пароль БОЕВОЙ базы уехал в 257 файлов логов,
    # потому что make печатает рецепт целиком. Гейт заведён ровно под него.
    with tempfile.TemporaryDirectory() as tmp:
        к, л = стенд(tmp, "пароль-прода-длинный", "psql пароль-прода-длинный@db")
        проба("БОЛЬНОЙ СЛУЧАЙ: пароль из .env лежит в логе — отказ", 1,
              проверить(False, к, л))
    with tempfile.TemporaryDirectory() as tmp:
        к, л = стенд(tmp, "пароль-прода-длинный", "psql <СКРЫТО>@db")
        проба("тот же пароль затёрт — чисто", 0, проверить(False, к, л))
    with tempfile.TemporaryDirectory() as tmp:
        к, л = стенд(tmp, "app123", "psql app123@db")
        проба("короткое значение — не пароль, гейт не краснеет впустую", 0,
              проверить(False, к, л))
    with tempfile.TemporaryDirectory() as tmp:
        к, л = стенд(tmp, "пароль-прода-длинный", "psql пароль-прода-длинный@db")
        проверить(True, к, л)
        текст = (л / "deploy.log").read_text(encoding="utf-8")
        got = 0 if "пароль-прода-длинный" not in текст and ЗАМЕНА in текст else 1
        проба("«--чинить» затирает значение в файле, а не только отчитывается", 0, got)
        проба("после починки гейт зелёный", 0, проверить(False, к, л))
    with tempfile.TemporaryDirectory() as tmp:
        логи = pathlib.Path(tmp) / "нет-таких-логов"
        проба("каталога логов нет — проверять нечего, но и не отказ", 0,
              проверить(False, pathlib.Path(tmp), логи))
    print("SELFTEST: зелёный (6 путей, первым — больной случай «пароль прода в логе»)"
          if ok else "SELFTEST: КРАСНЫЙ")
    return 0 if ok else 1


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        sys.exit(самотест())
    sys.exit(проверить("--чинить" in sys.argv))
