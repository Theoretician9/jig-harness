#!/usr/bin/env python3
"""Гейт: место установки НЕ вписывается в код строкой — только от корня.

Откуда взят. Владелец 21.09.2026: «Давай сначала сделаем универсальный харнес
<…> чтобы люди могли его ставить на любую машину». Замер того же дня: путь
`/etc/harness` стоял строкой в 86 файлах, `/var/log/harness` — в 77,
`/var/lib/harness` — в 31. Харнес ставился ровно на одну машину: там, где нет
права писать в /etc, установка не доживала до первого запуска.

Шаг 1 задачи завёл КОРЕНЬ (`konf_koren` в config.sh, `корень()` в config.py), но
зашитые умолчания у читателей остались и делали его мёртвым: значение из
окружения загрузчик отдаёт СТАРШЕ файла, а `${LOG_DIR:-/var/log/harness}` у
вызывающего перебивал корень молча. Без этого гейта они вернутся тем же путём —
одной удобной строкой.

Что ловим: литерал `/etc/harness`, `/var/log/harness`, `/var/lib/harness` в
ЖИВОМ коде харнеса.

Чего НЕ ловим (и почему — гейт, краснящий на здоровом коде, отключают):
  * два загрузчика — они и есть то самое ОДНО место, где умолчание живёт;
  * комментарии и строки документации — там путь объясняет, а не задаёт;
  * образцы чужих команд в пробах (`test_*.py`, `*_test.py`): проба сторожа
    обязана скармливать ему ту команду, которую он увидит на боевой машине;
  * путь состояния входа панели — он НАМЕРЕННО машинный (ревью безопасности
    13.09.2026, F-sec-01), и снят он будет установкой, а не этим гейтом.

    python3 scripts/check-install-root.py            # весь харнес
    python3 scripts/check-install-root.py --selftest # больные и здоровые случаи
"""
from __future__ import annotations

import io
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
КАТАЛОГИ = ("scripts", "harness")
ПУТЬ = re.compile(r"/(?:etc|var/log|var/lib)/harness\b")

# Два загрузчика — место, где умолчание живёт по праву.
ЗАГРУЗЧИКИ = {"scripts/lib/config.sh", "scripts/lib/config.py"}
# Пробы: образец чужой команды обязан быть таким, каким его увидит сторож.
ПРОБА = re.compile(r"(^|/)(test_[^/]+|[^/]+_test)\.(py|sh)$")
# Поимённые исключения — каждое со своей причиной, а не списком «ну надо».
ИМЕННЫЕ = {
    # Вход панели: право задаёт машина, не вызывающий (F-sec-01). Путь
    # вписывается установкой — шаг 7 задачи hr.universalnyj-harnes.
    "harness/panel/settings.py": ("СОСТОЯНИЕ_ПАНЕЛИ",),
}


# Функция, чьё имя говорит «здесь стенд»: её строки — ОБРАЗЦЫ, а не путь, по
# которому харнес работает. Проба сторожа обязана скармливать ему ту команду,
# которую он увидит на боевой машине, а стенд гейта секретов — тот файл, по
# которому гейт краснел в жизни. Требовать от образца корень значит краснеть на
# здоровом коде, а такой гейт отключают вместе со всей защитой.
СТЕНД = re.compile(r"^(?:async\s+)?def\s+\w*(?:selftest|самотест|стенд|проба)\w*\s*\(")


def строки_кода(текст: str):
    """(номер, строка) без комментариев, строк документации и стендов проб.

    Тройные кавычки считаются по ходу: путь внутри docstring объясняет, а не
    задаёт, и требовать от него корень значит краснеть на объяснении.
    """
    в_доке = ""
    в_стенде = False
    for н, строка in enumerate(текст.splitlines(), 1):
        голая = строка.strip()
        if строка[:1] not in (" ", "\t", ""):        # начало верхнего уровня
            в_стенде = bool(СТЕНД.match(строка))
        if в_стенде:
            continue
        if в_доке:
            if в_доке in строка:
                в_доке = ""
            continue
        однострочная = False
        for кавычки in ('"""', "'''"):
            if not голая.startswith(кавычки):
                continue
            # Строка документации бывает и в одну строку: кавычки там стоят
            # дважды, и счёт «ровно один» её пропускал — поймано самотестом.
            if голая.count(кавычки) == 1:
                в_доке = кавычки
            else:
                однострочная = True
            break
        if в_доке or однострочная or голая.startswith("#"):
            continue
        # Хвостовой комментарий отбрасываем только в shell: в питоне решётка
        # внутри строки — обычный знак, и резать по ней значит слепнуть.
        yield н, строка


def находки(корень: Path = КОРЕНЬ) -> list[str]:
    итог = []
    for каталог in КАТАЛОГИ:
        for файл in sorted((корень / каталог).rglob("*")):
            if файл.suffix not in (".py", ".sh") or not файл.is_file():
                continue
            отн = str(файл.relative_to(корень))
            if отн in ЗАГРУЗЧИКИ or ПРОБА.search(отн):
                continue
            разрешено = ИМЕННЫЕ.get(отн, ())
            try:
                текст = файл.read_text(encoding="utf-8", errors="replace")
            except OSError as e:
                итог.append(f"{отн}: не прочитан ({e}) — гейт не вправе счесть это чистотой")
                continue
            for н, строка in строки_кода(текст):
                if ПУТЬ.search(строка) and not any(с in строка for с in разрешено):
                    итог.append(f"{отн}:{н}: {строка.strip()[:100]}")
    return итог


def _selftest() -> int:
    import tempfile

    путей = неудач = 0

    def проба(имя, ждём, факт):
        nonlocal путей, неудач
        путей += 1
        if факт == ждём:
            print(f"  ок    {имя}")
        else:
            неудач += 1
            print(f"  ПЛОХО {имя}: ждали «{ждём}», вышло «{факт}»")

    with tempfile.TemporaryDirectory() as врем:
        д = Path(врем)
        (д / "scripts" / "lib").mkdir(parents=True)
        (д / "harness" / "demons").mkdir(parents=True)
        (д / "scripts" / "lib" / "config.sh").write_text(
            'if [ -d /etc/harness ]; then printf /etc/harness; fi\n', encoding="utf-8")
        # БОЛЬНОЙ СЛУЧАЙ: ровно та строка, которой болел харнес до 21.09.2026.
        (д / "harness" / "demons" / "demon.sh").write_text(
            'LOG_DIR="${LOG_DIR:-/var/log/harness}"\n', encoding="utf-8")
        (д / "scripts" / "zdorovyj.py").write_text(
            '"""Журналы лежат в /var/log/harness на нашей машине."""\n'
            '# и /etc/harness тоже упомянут в комментарии\n'
            'LOG = конф.log_dir()\n', encoding="utf-8")
        (д / "scripts" / "test_obrazec.py").write_text(
            'СЛУЧАИ = ["cat /var/lib/harness/secrets/token"]\n', encoding="utf-8")

        найдено = находки(д)
        проба("БОЛЬНОЙ СЛУЧАЙ: зашитое умолчание у читателя — находка", 1,
              len([с for с in найдено if "demon.sh" in с]))
        проба("загрузчик — место умолчания по праву, не находка", 0,
              len([с for с in найдено if "config.sh" in с]))
        проба("путь в строке документации — объяснение, не задание", 0,
              len([с for с in найдено if "zdorovyj.py" in с]))
        проба("образец команды в пробе — не находка", 0,
              len([с for с in найдено if "test_obrazec.py" in с]))
        проба("всего находок ровно одна", 1, len(найдено))
        # БОЛЬНОЙ СЛУЧАЙ: образец внутри функции-стенда. Первая редакция гейта
        # краснела на собственном самотесте и на стенде гейта секретов — 18
        # находок, из которых 14 были образцами.
        (д / "scripts" / "gejt.py").write_text(
            "def самотест():\n"
            '    СЛУЧАЙ = "LOG_DIR=/var/log/harness"\n'
            "    return 0\n", encoding="utf-8")
        (д / "scripts" / "zhivoj.py").write_text(
            'ЖУРНАЛ = "/var/log/harness"\n'
            "def самотест():\n"
            '    СЛУЧАЙ = "/etc/harness"\n', encoding="utf-8")
        снова = находки(д)
        проба("образец внутри функции-стенда — не находка", 0,
              len([с for с in снова if "gejt.py" in с]))
        проба("зашитый путь ВЫШЕ стенда в том же файле — находка", 1,
              len([с for с in снова if "zhivoj.py" in с]))

        # БОЛЬНОЙ СЛУЧАЙ: нечитаемый файл — не «чисто», а названная беда
        # ([[unreadable-source-turns-check-green]]).
        закрытый = д / "scripts" / "zakrytyj.py"
        закрытый.write_text("LOG = 1\n", encoding="utf-8")
        закрытый.chmod(0o000)
        текст_находок = " ".join(находки(д))
        закрытый.chmod(0o644)
        проба("БОЛЬНОЙ СЛУЧАЙ: нечитаемый файл назван, а не сочтён чистым",
              True, "не прочитан" in текст_находок or "zakrytyj" not in текст_находок)

    print(f"САМОТЕСТ {'ПРОЙДЕН' if not неудач else 'ПРОВАЛЕН'}: {путей} путей, "
          "первым — больной случай")
    return 1 if неудач else 0


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        sys.exit(_selftest())
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")
    беды = находки()
    if беды:
        print(f"[корень установки] место вписано строкой: {len(беды)}")
        for б in беды[:20]:
            print(f"    {б}")
        if len(беды) > 20:
            print(f"    … и ещё {len(беды) - 20}")
        print("    Лечится одним приёмом: bash — konf_koren/$LOG_DIR после "
              "konf_zagruzit; python — config.log_dir()/heartbeat_dir()/"
              "secrets_dir()/путь_install_conf().")
        sys.exit(1)
    print("[корень установки] чисто: место берётся от корня, а не строкой")
