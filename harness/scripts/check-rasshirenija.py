#!/usr/bin/env python3
"""Гейт: расширения ставит код, а не человек слэш-командой.

Откуда взят: 12.09.2026. Список расширений жил текстом скила, а командами в нём
стояли слэш-формы (`/plugin install …`, `/plugin marketplace add …`) — их вводит
человек в терминале, которого владелец не видит. Механизм простоял месяц с
нулём установок и выглядел живым: текст на месте, команды написаны.

Гейт держит две вещи:
  1. в инструкциях (скилы, UNIFIED, docs) нет слэш-форм как КОМАНДЫ к
     исполнению — только CLI-форма `claude plugin …` или зов rasshirenija.py;
  2. данные расширений целы: базовый набор непуст, у каждого кандидата по
     условию есть наблюдаемое условие, у каждого вердикта — причина.

Упоминание слэш-формы как УЛИКИ (внутри обратных кавычек в объяснении, почему
так делать нельзя) находкой не считается: запрет на слово вместо запрета на
действие красит собственное объяснение — а краснеющий гейт выключают.

Коды: 0 — чисто, 1 — находки.
"""
import re
import sys
from pathlib import Path

import yaml

КОРЕНЬ = Path(__file__).resolve().parent.parent
ДАННЫЕ = КОРЕНЬ / "harness" / "config" / "расширения.yaml"
ГДЕ_ИНСТРУКЦИИ = ["harness/skills", "harness/skills-src", "UNIFIED", "docs", "CLAUDE.md"]

# Команда к исполнению отличается от упоминания АРГУМЕНТОМ: живая команда
# несёт настоящее имя (`/plugin install playwright@m`), а объяснение — многоточие
# или ничего (`/plugin install …`). Первый вариант регулярки судил по началу
# строки и пропустил ровно тот случай, ради которого гейт написан: слэш-форма
# простояла месяц в ЯЧЕЙКЕ ТАБЛИЦЫ, а не в начале строки.
КОМАНДА = re.compile(r'/plugin\s+(?:install|uninstall|marketplace\s+add)\s+[A-Za-z0-9@._/-]')


def инструкции(корень: Path):
    for место in ГДЕ_ИНСТРУКЦИИ:
        путь = корень / место
        if путь.is_file():
            yield путь
        elif путь.is_dir():
            yield from sorted(путь.rglob("*.md"))


def найти_slash_formy(корень: Path) -> list:
    находки = []
    for файл in инструкции(корень):
        for номер, строка in enumerate(файл.read_text(encoding="utf-8",
                                                      errors="replace").splitlines(), 1):
            if КОМАНДА.search(строка):
                находки.append(f"{файл.relative_to(корень)}:{номер}: слэш-форма как "
                               f"команда — её вводит человек, у нас ставит код: {строка.strip()[:70]}")
    return находки


def проверить_данные(путь: Path) -> list:
    if not путь.exists():
        return [f"{путь}: нет данных расширений — установка нового сервера поставит пустоту"]
    данные = yaml.safe_load(путь.read_text(encoding="utf-8")) or {}
    беды = []
    if not (данные.get("базовый_набор") or []):
        беды.append("базовый_набор пуст: установка тихо не поставит ничего")
    for строка in данные.get("по_условию") or []:
        if not строка.get("условие"):
            беды.append(f"кандидат {строка.get('id')} без наблюдаемого условия")
    for строка in данные.get("не_ставить") or []:
        if not строка.get("причина"):
            беды.append(f"вердикт {строка.get('id')} без причины")
    return беды


def selftest() -> int:
    import tempfile
    неудач = 0

    def проба(имя, ожидалось, получено):
        nonlocal неудач
        ок = ожидалось == получено
        неудач += not ок
        print(f"  {'ok  ' if ок else 'FAIL'} {имя}"
              + ("" if ок else f": ждали {ожидалось!r}, получили {получено!r}"))

    with tempfile.TemporaryDirectory() as каталог:
        корень = Path(каталог)
        (корень / "docs").mkdir()
        # БОЛЬНОЙ СЛУЧАЙ: ровно тот текст, что простоял месяц.
        (корень / "docs" / "плохо.md").write_text(
            "| первый фронт | playwright | `/plugin install playwright@m` |\n"
            "1. /plugin marketplace add anthropics/skills\n", encoding="utf-8")
        проба("слэш-формы найдены обе", 2, len(найти_slash_formy(корень)))

        # ЛОЖНОЕ СРАБАТЫВАНИЕ, на котором гейт выключили бы в первый день:
        # объяснение, почему слэш-форма не работает, — это улика, а не команда.
        (корень / "docs" / "плохо.md").write_text(
            "Раньше стояли слэш-формы (`/plugin install …`) — их вводит человек.\n",
            encoding="utf-8")
        проба("объяснение про слэш-форму не находка", 0, len(найти_slash_formy(корень)))

        данные = корень / "д.yaml"
        данные.write_text("базовый_набор: []\nпо_условию:\n  - id: x\n", encoding="utf-8")
        проба("пустой набор и кандидат без условия — две беды", 2,
              len(проверить_данные(данные)))
        проба("нет файла данных — беда названа", 1,
              len(проверить_данные(корень / "нет.yaml")))

    print(f"самотест check-rasshirenija: неудач {неудач}")
    return 1 if неудач else 0


def главная() -> int:
    if "--selftest" in sys.argv[1:]:
        return selftest()
    находки = найти_slash_formy(КОРЕНЬ) + проверить_данные(ДАННЫЕ)
    for находка in находки:
        print(f"  ✗ {находка}")
    print(f"расширения: находок {len(находки)}")
    return 1 if находки else 0


if __name__ == "__main__":
    sys.exit(главная())
