#!/usr/bin/env python3
"""Обновление харнеса из публичного репозитория: сверка версий.

Владелец 11.09.2026: «А как сделать возможность ручного-автоматического
обновления после изменений в гите публичном где это будет лежать?»
Спека: docs/specs/2026-09-11-обновление-из-гита.md (итерация 2).

Главное решение спеки: обновляется ПАКЕТ (`$STARTER_DIR` — рабочая копия
публичной ветки), а в проект его разносит существующий раскладчик. Прямая
правка файлов проекта развела бы проект с пакетом: следующая раскладка молча
откатила бы обновление, а гейт сверки покраснел бы на первом коммите
(находка C6 разбора спеки).

Здесь — только сверка: на чём стоим и есть ли новее. Сверка НЕ трогает рабочее
дерево (`fetch`, не `pull`): узнать про обновление и поставить его — разные
действия, и второе требует копии, самопроверки и отката.

Прогон:
    python3 scripts/obnovlenie.py --сверить      # что нового в публичной ветке
    python3 scripts/obnovlenie.py --версия       # на чём стоит эта установка
Код возврата: 0 — ответ получен, 2 — спросить не удалось.
"""
import json
import os
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent


def файл_версии() -> Path:
    """Версия — состояние, которое пишет код, а не человек: ей не место в
    конфиге. Путь спрашивается в момент обращения, а не при импорте: проверка
    выставляет своё окружение уже после того, как модуль загружен."""
    return Path(os.environ.get("HARNESS_VERSION_FILE")
                or "/var/lib/harness/версия-харнеса")


def _конфиг(путь: str) -> dict:
    значения = {}
    try:
        текст = Path(путь).read_text(encoding="utf-8", errors="replace")
    except OSError:
        return значения
    for строка in текст.splitlines():
        строка = строка.strip()
        if строка and not строка.startswith("#") and "=" in строка:
            ключ, _, значение = строка.partition("=")
            значения[ключ.strip()] = значение.split("#")[0].strip().strip("\"'")
    return значения


def пакет() -> Path:
    """Рабочая копия публичной ветки. Её путь — данные установки."""
    из_окружения = os.environ.get("HARNESS_STARTER")
    if из_окружения:
        return Path(из_окружения)
    конф = _конфиг(os.environ.get("HARNESS_CONF", "/etc/harness/harness.conf"))
    агент = _конфиг("/etc/harness/install.conf").get("AGENT_USER") or "agent"
    return Path(конф.get("STARTER_DIR") or f"/home/{агент}/starter/STARTER-PACKAGE")


def ветка() -> str:
    """Публичная ветка: данные, а не догадка кода."""
    из_окружения = os.environ.get("HARNESS_PUBLIC_BRANCH")
    if из_окружения:
        return из_окружения
    конф = _конфиг(os.environ.get("HARNESS_CONF", "/etc/harness/harness.conf"))
    return конф.get("PUBLIC_BRANCH") or "master"


def удалённый(каталог: Path) -> str:
    """Как зовут публичный источник. Имя — ДАННЫЕ: в живом пакете удалённый
    называется «harness», а не «origin», и вшитое имя ломало сверку на нём же
    (живая проверка 11.09.2026)."""
    из_окружения = os.environ.get("HARNESS_PUBLIC_REMOTE")
    if из_окружения:
        return из_окружения
    есть = _гит("remote", где=каталог).stdout.split()
    конф = _конфиг(os.environ.get("HARNESS_CONF", "/etc/harness/harness.conf"))
    названный = конф.get("PUBLIC_REMOTE") or ""
    for имя in (названный, "origin"):
        if имя and имя in есть:
            return имя
    return есть[0] if есть else "origin"


def _гит(*доводы, где: Path) -> subprocess.CompletedProcess:
    """Git с выключенным экранированием путей: без core.quotepath=false он
    отдаёт кириллические имена восьмеричными байтами, и сравнение путей молча
    не совпадает ни с чем (поймано первым же прогоном разбора 11.09.2026)."""
    return subprocess.run(["git", "-c", "core.quotepath=false", *доводы],
                          cwd=str(где), capture_output=True, text=True, timeout=120)


def версия_установки() -> dict:
    """На чём стоит эта установка. Пусто — значит ещё не записывали."""
    try:
        return json.loads(файл_версии().read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def записать_версию(коммит: str) -> None:
    файл = файл_версии()
    файл.parent.mkdir(parents=True, exist_ok=True)
    врем = файл.with_suffix(".tmp")
    врем.write_text(json.dumps({"коммит": коммит,
                                "дата": time.strftime("%Y-%m-%d %H:%M:%S")},
                               ensure_ascii=False), encoding="utf-8")
    os.replace(врем, файл)


def бытие_из_своего_пакета(каталог) -> bool:
    """Публичный коммит собран из коммита, который уже лежит в этом пакете?

    Контракт с publikaciya.sh: первая строка сообщения сборки — «версия от
    ГГГГ-ММ-ДД, пакет <хэш>». Хэша нет (коммит не наш, старая схема) — обычный
    разбор по предкам.
    """
    # ПЕРВАЯ строка целиком, а не поиск по всему телу: прежняя редакция брала
    # `%B` и искала «пакет <хэш>» где угодно, поэтому любой коммит, в теле
    # которого встретилось это слово и семь hex-символов, признавался своей
    # сборкой — и извещение об обновлении гасло (ревью кода 12.09.2026, №13).
    заголовок = _гит("log", "-1", "--format=%s", "FETCH_HEAD", где=каталог).stdout.strip()
    совпало = re.fullmatch(r"версия от \d{4}-\d{2}-\d{2}, пакет ([0-9a-f]{7,40})",
                           заголовок)
    if not совпало:
        return False
    return _гит("merge-base", "--is-ancestor", совпало.group(1), "HEAD",
                где=каталог).returncode == 0


def спросить_обновления() -> dict:
    """Что в публичной ветке против того, что лежит в пакете.

    Ответ всегда называет СОСТОЯНИЕ: «нового нет», «есть новое <коммит>» или
    «спросить не удалось: <причина>». Молчание и ноль — разные вещи, и на
    экране владельца они не должны выглядеть одинаково.
    """
    каталог = пакет()
    if not (каталог / ".git").is_dir():
        return {"есть новое": False, "коммит": "",
                "беда": f"пакета нет или он не репозиторий: {каталог}"}
    добыто = _гит("fetch", "--quiet", удалённый(каталог), ветка(), где=каталог)
    if добыто.returncode != 0:
        строки = [с.strip() for с in (добыто.stderr or добыто.stdout).splitlines()
                  if с.strip()]
        # Первая значимая строка, а не последняя: git заканчивает подсказкой
        # «and the repository exists», из которой причина не видна.
        причина = next((с for с in строки if "fatal" in с.lower()), строки[0] if строки else "?")
        return {"есть новое": False, "коммит": "",
                "беда": f"репозиторий не отвечает: {причина}"}
    свой = _гит("rev-parse", "HEAD", где=каталог).stdout.strip()
    чужой = _гит("rev-parse", "FETCH_HEAD", где=каталог).stdout.strip()
    дата = _гит("log", "-1", "--format=%ci", "FETCH_HEAD", где=каталог).stdout.strip()
    # «Не равны» — неверный признак: на рабочей машине в пакет коммитят раньше
    # публикации, и сверка кричала «есть новая версия», предлагая откатиться
    # назад (живая проверка 11.09.2026). Новое есть тогда, когда публичный
    # коммит НЕ является предком нашего.
    предок = _гит("merge-base", "--is-ancestor", чужой, свой,
                  где=каталог).returncode == 0 if чужой and свой else False
    # Своя сборка — не новая версия. Публичный коммит собирается ИЗ пакета и
    # ложится потомком публичной ветки, то есть предком нашего HEAD он не
    # станет никогда: на машине-источнике сверка отвечала бы «есть новое»
    # вечно, а сторож обновлений будил бы владельца каждые сутки вестью о том,
    # что он сам и опубликовал. Хэш пакета стоит в сообщении коммита сборки.
    if бытие_из_своего_пакета(каталог):
        return {"есть новое": False, "источник": "свой пакет",
                "коммит": чужой or свой, "свой коммит": свой, "дата": дата,
                "беда": None}
    return {"есть новое": bool(чужой) and not предок,
            "коммит": чужой or свой, "свой коммит": свой, "дата": дата,
            "беда": None}


def _содержимое(коммит: str, путь: str, каталог: Path):
    """Файл на указанной ревизии или None, если его там не было."""
    готово = _гит("show", f"{коммит}:{путь}", где=каталог)
    return готово.stdout if готово.returncode == 0 else None


def разбор(эталон: str, новый: str) -> dict:
    """Что делать с каждым файлом: таблица §1 спеки.

    Сравниваются ТРИ стороны: файл на прежней публичной версии (эталон), файл
    на машине сейчас (наш) и файл в обновлении (новый). Затирать молча можно
    только то, чего здесь не трогали, — владелец 11.09.2026 просил, чтобы
    расхождение показывалось, а не исчезало.
    """
    каталог = пакет()
    итог = {"обновить": [], "не трогать": [], "расхождения": [],
            "добавить": [], "удалить": []}
    названные = _гит("diff", "--name-only", эталон, новый, где=каталог).stdout.split("\n")
    for путь in sorted(п.strip() for п in названные if п.strip()):
        если_эталон = _содержимое(эталон, путь, каталог)
        если_новый = _содержимое(новый, путь, каталог)
        живой = каталог / путь
        наш = живой.read_text(encoding="utf-8", errors="replace") if живой.is_file() else None
        if если_эталон is None and если_новый is not None:
            итог["добавить" if наш is None else "расхождения"].append(путь)
        elif если_новый is None:
            # Файл исчез в обновлении. Удаляем только если здесь его не трогали:
            # иначе это правка владельца, и она переживает обновление.
            итог["удалить" if наш == если_эталон else "расхождения"].append(путь)
        elif наш == если_эталон:
            итог["обновить"].append(путь)
        elif наш == если_новый:
            итог["не трогать"].append(путь)
        else:
            итог["расхождения"].append(путь)
    # Файлы, которых обновление не касалось, но которые правлены здесь, в
    # список не попадают вовсе: их никто не собирался трогать.
    for путь in sorted(_гит("diff", "--name-only", где=каталог).stdout.split("\n")):
        путь = путь.strip()
        if путь and путь not in названные:
            итог["не трогать"].append(путь)
    return итог


def _сказать_владельцу(текст: str) -> None:
    """Сообщение в канал. Молчаливое обновление — худший вид обновления."""
    отправка = КОРЕНЬ / "scripts" / "tg_send.sh"
    if not отправка.exists() or os.environ.get("HARNESS_TG_SEND") == "":
        return
    try:
        subprocess.run(["bash", str(отправка), текст], timeout=60,
                       capture_output=True)
    except (OSError, subprocess.SubprocessError):
        pass


def каталог_копий() -> Path:
    return Path(os.environ.get("HARNESS_BACKUP_DIR") or "/var/backups/harness")


def _снять_копию(каталог: Path) -> Path | None:
    """Копия пакета ДО установки. Без неё установка не начинается (И-1).

    Имя с датой И временем: два обновления за сутки затирали бы копию друг
    друга (находка I10 разбора спеки).
    """
    основа = каталог_копий() / time.strftime("обновление-%Y%m%d-%H%M%S")
    # Два обновления в одну секунду — не выдумка: так идут проверки, и второе
    # падало на «каталог уже есть», то есть отказывалось ставиться молча.
    цель, номер = основа, 1
    while цель.exists():
        номер += 1
        цель = основа.with_name(f"{основа.name}-{номер}")
    try:
        цель.parent.mkdir(parents=True, exist_ok=True)
        shutil.copytree(каталог, цель, symlinks=True,
                        ignore=shutil.ignore_patterns("__pycache__"))
        return цель
    except (OSError, shutil.Error):
        return None


def _вернуть_из_копии(копия: Path, каталог: Path, пути: list) -> None:
    """Правки владельца переживают обновление: их возвращают из копии.

    Владелец 11.09.2026 (карточка задачи): «расхождение должно показываться,
    а не затираться молча». Показ — это отчёт; здесь — вторая половина: файл
    остаётся тем, каким его сделали здесь.
    """
    for путь in пути:
        откуда, куда = копия / путь, каталог / путь
        try:
            if откуда.is_file():
                куда.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(откуда, куда)
        except (OSError, shutil.Error):
            continue


def _занят_выкат() -> bool:
    """Идёт ли выкат. Спрашиваем ЛОК, а не возраст файла: deploy.lock не метка
    свежести и после выката остаётся лежать (находка I6)."""
    лок = Path(os.environ.get("LOG_DIR", "/var/log/harness")) / "locks" / "deploy.lock"
    if not лок.exists():
        return False
    готово = subprocess.run(["flock", "-n", str(лок), "-c", "true"],
                            capture_output=True, timeout=30)
    return готово.returncode != 0


def прогнать_ворота() -> tuple:
    """Самопроверка обновлённого харнеса. Итог — по строке ворот, а не по коду
    возврата: жёлтые проверки в код не входят (находка M3)."""
    готово = subprocess.run(["bash", str(КОРЕНЬ / "scripts" / "vorota.sh")],
                            capture_output=True, text=True, timeout=1800)
    строки = [с for с in готово.stdout.splitlines() if с.startswith("=== итог:")]
    строка = строки[-1] if строки else "итоговой строки нет"
    return ("красных 0" in строка, строка)


def поставить(*, разложить=None, перезапустить=None, проверить=None,
              сказать=None) -> dict:
    """Поставить обновление: копия → пакет вперёд → раскладка → проверка.

    Не прошло — откат на прежний коммит, версия НЕ меняется, владельцу сказано
    словами. Внешние действия приходят доводами: так их подменяет проверка, а
    живая установка получает умолчания.
    """
    разложить = разложить or _разложить_пакет
    перезапустить = перезапустить or _перезапустить_службы
    проверить = проверить or прогнать_ворота
    сказать = сказать or (lambda текст: None)

    каталог = пакет()

    def отказ(причина: str, **ещё) -> dict:
        """Любой отказ доходит до владельца: молчаливо не поставленное
        обновление выглядит как «всё хорошо» (И-4)."""
        сказать(f"Обновление не поставлено: {причина}")
        return {"поставлено": False, "беда": причина, **ещё}

    ответ = спросить_обновления()
    if ответ.get("беда"):
        return отказ(ответ["беда"])
    if not ответ["есть новое"]:
        return {"поставлено": False, "беда": "нового нет"}   # это не беда, молчим
    if _занят_выкат():
        return отказ("идёт выкат — обновление подождёт")

    копия = _снять_копию(каталог)
    if копия is None:
        return отказ("копия не снята — установка не начата")

    прежний = _гит("rev-parse", "HEAD", где=каталог).stdout.strip()
    # Что здесь правили — знаем ДО слияния: после него отличить правку
    # владельца от пришедшей строки уже нечем.
    исходы = разбор(прежний, ответ["коммит"])
    сберечь = исходы["не трогать"] + исходы["расхождения"]

    # Слияние не смеет спотыкаться о правки владельца: дерево сбрасывается до
    # HEAD (копия уже снята), а сбережённые файлы возвращаются из копии после.
    # Живая проверка 11.09.2026: без этого merge --ff-only отказывался словами
    # «your local changes would be overwritten», и обновление не шло вовсе.
    _гит("checkout", "--", ".", где=каталог)
    вперёд = _гит("merge", "--ff-only", ответ["коммит"], где=каталог)
    if вперёд.returncode != 0:
        причина = (вперёд.stderr or вперёд.stdout).strip().splitlines()
        _вернуть_из_копии(копия, каталог, сберечь)
        return отказ(f"пакет разошёлся с публичной веткой: "
                     f"{причина[0] if причина else '?'}")
    _вернуть_из_копии(копия, каталог, сберечь)

    разложить()
    перезапустить()
    прошло, строка = проверить()
    if прошло:
        записать_версию(ответ["коммит"])
        хвост = ("" if not исходы["расхождения"] else
                 f" Не тронуто (правлено здесь и в обновлении): "
                 f"{', '.join(исходы['расхождения'][:5])}")
        сказать(f"Харнес обновлён до {ответ['коммит'][:7]}. Проверки: {строка}.{хвост}")
        return {"поставлено": True, "коммит": ответ["коммит"], "проверки": строка,
                "копия": str(копия), "расхождения": исходы["расхождения"]}

    _гит("reset", "--hard", прежний, где=каталог)
    разложить()
    перезапустить()
    сказать(f"Обновление не прошло проверку ({строка}) — сделан откат на "
            f"{прежний[:7]}. Копия: {копия}")
    return {"поставлено": False, "беда": f"самопроверка не прошла: {строка}",
            "откат": прежний, "копия": str(копия)}


def _разложить_пакет() -> bool:
    """Раскладка пакета в проект И пересборка производных.

    Пересборка обязательна: документ устройства собирается из реестра, и без
    неё гейт `check-ustrojstvo.py` краснеет побайтно — то есть КАЖДОЕ
    обновление откатывалось бы самопроверкой (находка C1 разбора спеки).
    """
    готово = subprocess.run(["bash", str(пакет() / "harness" / "razlozhit-harnes.sh")],
                            capture_output=True, text=True, timeout=900)
    if готово.returncode != 0:
        return False
    собрано = subprocess.run(
        [sys.executable, str(КОРЕНЬ / "scripts" / "sobrat-ustrojstvo.py")],
        capture_output=True, text=True, timeout=300)
    if собрано.returncode != 0:
        return False
    # Новый демон без строки cron и без периода метки мёртв и незаметен
    # (находка C7): доустановка добавляет недостающее и ничего не удаляет.
    доставлено = subprocess.run(
        [sys.executable, str(КОРЕНЬ / "scripts" / "ustanovit-novoe.py")],
        capture_output=True, text=True, timeout=300)
    return доставлено.returncode == 0


def _перезапустить_службы() -> bool:
    """Носители обновлённого кода. Диспетчер ПОСЛЕДНИМ: он держит канал с
    владельцем, и его перезапуск обрывает разговор (находка C4)."""
    ок = True
