def main(argv: list) -> int:
    if "--поставить" in argv:
        итог = поставить(сказать=_сказать_владельцу)
        if итог.get("поставлено"):
            print(f"[обновление] поставлено: {итог['коммит'][:7]}; "
                  f"проверки: {итог['проверки']}")
            return 0
        print(f"[обновление] не поставлено: {итог.get('беда')}", file=sys.stderr)
        return 1
    if "--версия" in argv:
        версия = версия_установки()
        print(json.dumps(версия or {"нет данных": "версия ещё не записана"},
                         ensure_ascii=False))
        return 0
    ответ = спросить_обновления()
    if ответ.get("беда"):
        print(f"[обновление] спросить не удалось: {ответ['беда']}", file=sys.stderr)
        return 2
    if ответ["есть новое"]:
        print(f"[обновление] есть новая версия: {ответ['коммит'][:7]} "
              f"от {ответ['дата']}")
    else:
        print(f"[обновление] стоит последняя версия: {ответ['коммит'][:7]}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
