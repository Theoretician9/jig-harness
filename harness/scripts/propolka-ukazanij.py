#!/usr/bin/env python3
"""Прополка указаний: длинная цитата уезжает в запись памяти, суть остаётся.

Откуда взят. Замер 13.09.2026: `память/УКАЗАНИЯ.md` — 7888 из 8000 знаков,
99 % потолка. Снимать указание вправе только владелец, а прибавляются они
каждую смену, и объём держался ручной прополкой посреди другой работы — то
есть вниманием сессии. Механизм, который требует, чтобы кто-то помнил, — не
механизм ([[механизм-для-человека-мёртв]]).

Что делает и чего НЕ делает. Смысл не сжимает и слов владельца не выдумывает:
берёт абзац, где есть и ДОСЛОВНАЯ цитата, и ссылка на запись памяти, дописывает
цитату в ту запись (если её там нет) и оставляет в указаниях начало цитаты со
ссылкой. Ничего не пропадает: цитата переезжает, а не исчезает, и всё видно в
git. Абзац без ссылки не трогается вовсе — туда указание попало без своей
записи, и куда его девать, решает не код.

Работает ТОЛЬКО при переполнении: пока файл ниже порога, прополка не нужна, а
лишняя правка слов владельца — сама по себе вред.

Прогон:
    python3 scripts/propolka-ukazanij.py            # прополоть, если нужно
    python3 scripts/propolka-ukazanij.py --проверить # только сказать, нужно ли
    python3 scripts/propolka-ukazanij.py --selftest
Код возврата: 0 — сделано или не требовалось; 1 — переполнение, а прополоть
нечем (нет ни одного абзаца со ссылкой) — это случай для владельца.
"""
import os
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
ПАМЯТЬ = Path(os.environ.get("HARNESS_PAMYAT") or КОРЕНЬ / "память")
ПОТОЛОК = int(os.environ.get("UKAZANIYA_POTOLOK", "8000"))
# Прополка начинается ДО потолка: упереться в него — значит покрасить ворота
# посреди чужой работы. Доля, а не число: потолок задаётся отдельно.
НАЧИНАТЬ_С = float(os.environ.get("UKAZANIYA_PROPOLKA_S", "0.92"))
# Цитата короче этого — уже суть, её выносить незачем.
ЦИТАТА_ОТ = 60
# Сколько знаков цитаты остаётся в указаниях: начало фразы и есть её суть.
ОСТАВИТЬ = 40


def абзацы(текст: str) -> list[str]:
    return [а for а in re.split(r"\n\s*\n", текст)]


def кандидат(абзац: str) -> tuple[str, str] | None:
    """(ссылка, длинная цитата) — или None, если абзац трогать нельзя."""
    ссылки = re.findall(r"\[\[([^\]]+)\]\]", абзац)
    цитаты = [ц for ц in re.findall(r"«([^»]+)»", абзац) if len(ц) >= ЦИТАТА_ОТ]
    if not ссылки or not цитаты:
        return None
    return ссылки[0], max(цитаты, key=len)


def обрезать(цитата: str) -> str:
    """Начало цитаты по границе слова: обрыв на полуслове — не суть, а мусор."""
    если_целиком = цитата[:ОСТАВИТЬ]
    пробел = если_целиком.rfind(" ")
    return (если_целиком[:пробел] if пробел > ОСТАВИТЬ // 2 else если_целиком).rstrip(" ,.;:—-")


def дописать_в_запись(запись: Path, цитата: str) -> bool:
    """Цитата попадает в запись, если её там ещё нет. → дописали ли."""
    if not запись.exists():
        return False
    текст = запись.read_text(encoding="utf-8")
    if цитата[:ЦИТАТА_ОТ] in текст:
        return True
    текст = текст.rstrip() + f"\n\n**Дословно (перенесено прополкой указаний):**\n\n> «{цитата}»\n"
    запись.write_text(текст, encoding="utf-8")
    return True


def прополоть(указания: Path, память: Path, потолок: int = ПОТОЛОК) -> dict:
    """Один проход: сокращает столько абзацев, сколько нужно до порога."""
    текст = указания.read_text(encoding="utf-8")
    было = len(текст)
    цель = int(потолок * НАЧИНАТЬ_С)
    if было <= цель:
        return {"нужно": False, "было": было, "стало": было, "перенесено": []}
    куски = абзацы(текст)
    порядок = sorted(range(len(куски)), key=lambda и: len(куски[и]), reverse=True)
    перенесено = []
    for и in порядок:
        if len("\n\n".join(куски)) <= цель:
            break
        пара = кандидат(куски[и])
        if not пара:
            continue
        ссылка, цитата = пара
        if not дописать_в_запись(память / f"{ссылка}.md", цитата):
            continue
        # Ссылка в абзаце уже есть — второй раз её не пишем: «дословно в
        # [[X]] — [[X]]» читается как сбой, а не как забота о месте.
        хвост = "" if f"[[{ссылка}]]" in куски[и] else f" — дословно в [[{ссылка}]]"
        новый = куски[и].replace(f"«{цитата}»", f"«{обрезать(цитата)}…»{хвост}")
        # Замена, которая не короче, — просто порча слов владельца.
        if len(новый) >= len(куски[и]):
            continue
        куски[и] = новый
        перенесено.append(ссылка)
    стало_текст = "\n\n".join(куски)
    if перенесено:
        указания.write_text(стало_текст, encoding="utf-8")
    return {"нужно": True, "было": было, "стало": len(стало_текст),
            "перенесено": перенесено}


def самотест() -> int:
    import shutil
    import tempfile
    неудач = 0

    def проба(имя, условие, подробность=""):
        nonlocal неудач
        неудач += not условие
        print(("  ок    " if условие else "  ПЛОХО ") + имя
              + ("" if условие else f" — {подробность}"))

    двор = Path(tempfile.mkdtemp(prefix="прополка-указаний-"))
    (двор / "память").mkdir()
    запись = двор / "память" / "длинное-указание.md"
    запись.write_text("---\nname: длинное-указание\n---\n\nтело записи\n", encoding="utf-8")
    длинная = "это очень длинная дословная цитата владельца, которая занимает много места " * 3
    указания = двор / "память" / "УКАЗАНИЯ.md"
    указания.write_text(
        "# УКАЗАНИЯ\n\n"
        f"**13.09:** «{длинная}» — суть в [[длинное-указание]].\n\n"
        "**12.09:** короткое указание без цитаты и без ссылки.\n",
        encoding="utf-8")

    # Ниже порога прополка не трогает НИЧЕГО: лишняя правка слов владельца вредна.
    итог = прополоть(указания, двор / "память", потолок=100000)
    проба("ниже порога — файл не тронут", итог["нужно"] is False and итог["было"] == итог["стало"],
          str(итог))

    было = len(указания.read_text(encoding="utf-8"))
    итог = прополоть(указания, двор / "память", потолок=200)
    стало = указания.read_text(encoding="utf-8")
    проба("БОЛЬНОЙ СЛУЧАЙ: переполнение — цитата уехала, файл короче",
          итог["перенесено"] == ["длинное-указание"] and len(стало) < было, str(итог))
    проба("в указаниях осталось НАЧАЛО цитаты и ссылка",
          "это очень длинная дословная цитата" in стало and "[[длинное-указание]]" in стало,
          стало[:200])
    проба("цитата целиком переехала в запись",
          длинная[:ЦИТАТА_ОТ] in запись.read_text(encoding="utf-8"),
          запись.read_text(encoding="utf-8")[:160])
    проба("абзац без ссылки не тронут", "короткое указание без цитаты" in стало, стало[-120:])
    проба("БОЛЬНОЙ СЛУЧАЙ: ссылка не задвоена",
          стало.count("[[длинное-указание]]") == 1, стало[:200])
    проба("обрезано по границе слова, а не на полуслове",
          not re.search(r"[а-яё]…»", стало) or "цитата…" in стало, стало[:160])

    # БОЛЬНОЙ СЛУЧАЙ: ссылка есть, а записи нет — тогда трогать нечего, и
    # прополка честно ничего не делает, а не роняет цитату в никуда.
    сирота = двор / "память" / "УКАЗАНИЯ2.md"
    сирота.write_text(f"**13.09:** «{длинная}» — [[записи-такой-нет]].\n", encoding="utf-8")
    итог2 = прополоть(сирота, двор / "память", потолок=200)
    проба("ссылка без записи — цитата остаётся на месте",
          итог2["перенесено"] == [] and длинная[:40] in сирота.read_text(encoding="utf-8"),
          str(итог2))

    shutil.rmtree(двор, ignore_errors=True)
    print(f"САМОТЕСТ propolka-ukazanij: неудач {неудач}")
    return 1 if неудач else 0


def main() -> int:
    if "--selftest" in sys.argv:
        return самотест()
    указания = ПАМЯТЬ / "УКАЗАНИЯ.md"
    if not указания.exists():
        print(f"[прополка указаний] файла нет: {указания}")
        return 0
    размер = len(указания.read_text(encoding="utf-8"))
    цель = int(ПОТОЛОК * НАЧИНАТЬ_С)
    if "--проверить" in sys.argv:
        нужно = размер > цель
        print(f"[прополка указаний] {размер} из {ПОТОЛОК} знаков; "
              f"порог прополки {цель} — {'нужна' if нужно else 'не нужна'}")
        return 0
    итог = прополоть(указания, ПАМЯТЬ)
    if not итог["нужно"]:
        print(f"[прополка указаний] {итог['было']} знаков — ниже порога {цель}, не трогаю")
        return 0
    if not итог["перенесено"]:
        print(f"[прополка указаний] {итог['было']} знаков при потолке {ПОТОЛОК}, "
              f"а прополоть нечем: нет абзаца с цитатой и ссылкой на запись. "
              f"Это случай для владельца — снять указание вправе только он.")
        return 1
    print(f"[прополка указаний] {итог['было']} → {итог['стало']} знаков; "
          f"цитаты уехали в записи: {', '.join(итог['перенесено'])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
