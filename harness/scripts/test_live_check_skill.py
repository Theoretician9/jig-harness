#!/usr/bin/env python3
"""Проверка носителя живой проверки скилов (scripts/live-check-skill.py).

Откуда взято. Спека `docs/specs/2026-10-15-живая-проверка-механизмов.md` §3.1,
класс E: «вызов в ЭТОЙ задаче — запись журнала скилов с `ts` позже начала задачи,
судится разбором JSON, — и артефакт, который скил обязан оставить». Носителя
этому предикату в коде не было, и 18 скилов оставались непроверенными.

Что охраняется сверх буквы спеки:

1. **Запись считается только МАШИННАЯ.** `"источник":"хук"` — её пишет оболочка,
   а не я; запись рукой была бы моим же словом, и правило харнеса «журнал
   никогда не ведётся рукой» существует ровно поэтому.
2. **Вызов, кончившийся отказом, работой не считается.** `"успех":false` — это
   попытка, а не доказательство ([[a-sign-true-while-work-stands-still]]).
3. **Вызов ДО начала задачи не годится.** Иначе «проверено живьём» закрывалось
   бы чужой давней работой.
4. **Артефакт — не моё слово, а файл.** Он назван МАСКОЙ в данных и обязан быть
   не старше начала задачи: скил, оставивший файл год назад, в этой задаче не
   работал. Скил без артефакта объявляется в данных с причиной, а не молчанием.

Проба создаёт свой двор: свой журнал скилов, свои данные артефактов, своё
состояние. Боевой журнал и боевые данные не трогаются.

Прогон: python3 scripts/test_live_check_skill.py
Код возврата: 0 — все случаи зелёные, 1 — хоть один плохой.
"""
from __future__ import annotations

import hashlib
import json
import os
import pathlib
import subprocess
import sys
import tempfile
import time

import yaml

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
ПРОГОН = КОРЕНЬ / "scripts" / "live-check-skill.py"
БОЕВЫЕ = (КОРЕНЬ / "harness" / "config" / "live-check-state.yaml",)

хорошо = 0
плохо = 0


def случай(имя: str, условие: bool, пояснение: str = "") -> None:
    global хорошо, плохо
    if условие:
        хорошо += 1
        print(f"  ок    {имя}")
    else:
        плохо += 1
        print(f"  ПЛОХО {имя}{(': ' + пояснение) if пояснение else ''}")


def двор(записи: list[dict], артефакты: dict, *,
         начата: str = "2026-10-15", артефакт_есть: bool = True) -> pathlib.Path:
    """Двор пробы: журнал скилов, данные артефактов, карта и состояние."""
    путь = pathlib.Path(tempfile.mkdtemp(prefix="скил-живьём-"))
    (путь / "следы").mkdir()
    (путь / "артефакты").mkdir()
    журнал = путь / "skills.jsonl"
    журнал.write_text(
        "".join(json.dumps(з, ensure_ascii=False) + "\n" for з in записи),
        encoding="utf-8")
    if артефакт_есть:
        (путь / "артефакты" / "спека.md").write_text("спека\n", encoding="utf-8")
    (путь / "артефакты-данные.yaml").write_text(
        yaml.dump({"скилы": артефакты}, allow_unicode=True), encoding="utf-8")
    (путь / "карта.yaml").write_text(
        "lines:\n  - id: harness\n    tasks:\n"
        f"      - id: задача-двора\n        status: wip\n"
        f"        when: {{ started: '{начата}' }}\n", encoding="utf-8")
    (путь / "состояние.yaml").write_text("версия: 1\nпроверено: {}\n", encoding="utf-8")
    return путь


def прогон(путь: pathlib.Path, *доводы: str) -> tuple[int, str]:
    среда = dict(os.environ)
    среда.update({
        "HARNESS_LIVE_CHECK_SKILL_LOG": str(путь / "skills.jsonl"),
        "HARNESS_LIVE_CHECK_SKILL_ARTIFACTS": str(путь / "артефакты-данные.yaml"),
        "HARNESS_LIVE_CHECK_SKILL_TRACE_DIR": str(путь / "следы"),
        "HARNESS_LIVE_CHECK_STATE": str(путь / "состояние.yaml"),
        "HARNESS_LIVE_CHECK_MAP": str(путь / "карта.yaml"),
        "HARNESS_LIVE_CHECK_REPO": str(путь),
    })
    готово = subprocess.run([sys.executable, str(ПРОГОН), *доводы],
                            capture_output=True, text=True, env=среда, timeout=120)
    return готово.returncode, готово.stdout + готово.stderr


ЗАПИСЬ_ХОРОШАЯ = {"ts": "2026-10-16T09:14:17Z", "skill": "spec-writing",
                  "task": "задача-двора", "источник": "хук", "успех": True}
АРТЕФАКТЫ = {"spec-writing": {"артефакт": "артефакты/*.md",
                              "почему": "скил обязан оставить файл спеки"}}


def main() -> int:
    было = {п: hashlib.md5(п.read_bytes()).hexdigest() for п in БОЕВЫЕ if п.exists()}

    # ── БОЛЬНЫМ СЛУЧАЕМ ПЕРВЫМ: вызова в ЭТОЙ задаче нет ─────────────────
    # Это и есть дыра, ради которой носитель написан: скил, позванный когда-то
    # и кем-то, выглядел бы проверенным в любой задаче.
    д = двор([dict(ЗАПИСЬ_ХОРОШАЯ, task="другая-задача")], АРТЕФАКТЫ)
    код, вывод = прогон(д, "spec-writing", "--задача", "задача-двора")
    случай("БОЛЬНОЙ СЛУЧАЙ: вызова в этой задаче нет — отказ",
           код == 1 and "вызова в этой задаче нет" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    # ── Запись рукой: источник не «хук» ──────────────────────────────────
    д = двор([dict(ЗАПИСЬ_ХОРОШАЯ, **{"источник": "рука"})], АРТЕФАКТЫ)
    код, вывод = прогон(д, "spec-writing", "--задача", "задача-двора")
    случай("запись не машинная (источник не «хук») — отказ",
           код == 1 and "вызова в этой задаче нет" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    # ── Вызов кончился отказом ───────────────────────────────────────────
    д = двор([dict(ЗАПИСЬ_ХОРОШАЯ, успех=False)], АРТЕФАКТЫ)
    код, вывод = прогон(д, "spec-writing", "--задача", "задача-двора")
    случай("вызов с отказом работой не считается — отказ",
           код == 1 and "вызова в этой задаче нет" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    # ── Вызов РАНЬШЕ начала задачи ───────────────────────────────────────
    д = двор([dict(ЗАПИСЬ_ХОРОШАЯ, ts="2026-09-01T10:00:00Z")], АРТЕФАКТЫ)
    код, вывод = прогон(д, "spec-writing", "--задача", "задача-двора")
    случай("вызов раньше начала задачи — отказ с датами",
           код == 1 and "раньше начала задачи" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    # ── Артефакта нет на диске ───────────────────────────────────────────
    д = двор([ЗАПИСЬ_ХОРОШАЯ], АРТЕФАКТЫ, артефакт_есть=False)
    код, вывод = прогон(д, "spec-writing", "--задача", "задача-двора")
    случай("артефакта по маске нет — отказ с маской",
           код == 1 and "артефакта по маске" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    # ── Артефакт СТАРШЕ начала задачи: работал не в этой задаче ──────────
    д = двор([ЗАПИСЬ_ХОРОШАЯ], АРТЕФАКТЫ)
    старое = time.time() - 365 * 24 * 60 * 60
    os.utime(д / "артефакты" / "спека.md", (старое, старое))
    код, вывод = прогон(д, "spec-writing", "--задача", "задача-двора")
    случай("артефакт старше начала задачи — отказ",
           код == 1 and "старше начала задачи" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    # ── Скила нет в данных артефактов ────────────────────────────────────
    д = двор([ЗАПИСЬ_ХОРОШАЯ], {})
    код, вывод = прогон(д, "spec-writing", "--задача", "задача-двора")
    случай("артефакт скила не назван в данных — отказ своей причиной",
           код == 1 and "не назван в данных" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    # ── ЗДОРОВЫЙ ПУТЬ ────────────────────────────────────────────────────
    д = двор([ЗАПИСЬ_ХОРОШАЯ], АРТЕФАКТЫ)
    код, вывод = прогон(д, "spec-writing", "--задача", "задача-двора", "--записать")
    случай("здоровый путь: вызов в задаче доказан, код 0",
           код == 0 and "вызов в этой задаче доказан" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")
    состояние = yaml.safe_load((д / "состояние.yaml").read_text()) or {}
    # Ключ записи — ПУТЬ механизма, как он назван в реестре
    # (harness/skills/<скил>/SKILL.md), а не имя скила: по имени запись никем не
    # считается, и гейт говорит «в состоянии есть механизмы, которых нет в
    # реестре» (поймано живым прогоном 17.10.2026 на семи скилах).
    запись = (состояние.get("проверено") or {}).get(
        "harness/skills/spec-writing/SKILL.md") or {}
    случай("ключ записи — путь механизма из реестра, а не имя скила",
           bool(запись), str(list((состояние.get("проверено") or {}).keys())))
    случай("в запись легли «живьём», «увидели», «след» и «когда»",
           all(запись.get(п) for п in ("живьём", "увидели", "след", "когда")),
           str(запись))
    случай("«увидели» цитирует СТРОКУ ЖУРНАЛА, которую написал хук",
           '"skill": "spec-writing"' in (запись.get("увидели") or "")
           or '"skill":"spec-writing"' in (запись.get("увидели") or ""),
           str(запись.get("увидели")))
    случай("«живьём» называет артефакт и его маску",
           "артефакты/" in (запись.get("живьём") or ""),
           str(запись.get("живьём")))
    след = д / "следы" / "spec-writing.log"
    случай("след написан прибором и несёт строку журнала",
           след.is_file() and "spec-writing" in след.read_text(),
           str(след))

    # ── Маска с «{задача}»: подстановка id, иначе glob ищет буквальный путь ─
    # Живой прогон 17.10.2026: три скила из семи отказали «артефакта по маске
    # .tasks/{задача}/review/*.md нет», потому что подстановки в коде не было —
    # данные обещали её, а прибор искал каталог с фигурными скобками в имени.
    д = двор([ЗАПИСЬ_ХОРОШАЯ],
             {"spec-writing": {"артефакт": "задачи/{задача}/*.md",
                               "почему": "артефакт лежит в каталоге ЭТОЙ задачи"}},
             артефакт_есть=False)
    (д / "задачи" / "задача-двора").mkdir(parents=True)
    (д / "задачи" / "задача-двора" / "разбор.md").write_text("разбор\n", encoding="utf-8")
    код, вывод = прогон(д, "spec-writing", "--задача", "задача-двора", "--записать")
    случай("маска с «{задача}» подставляет id задачи",
           код == 0 and "вызов в этой задаче доказан" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")
    состояние = yaml.safe_load((д / "состояние.yaml").read_text()) or {}
    запись = (состояние.get("проверено") or {}).get(
        "harness/skills/spec-writing/SKILL.md") or {}
    случай("и в записи стоит ПОДСТАВЛЕННЫЙ путь, а не маска со скобками",
           "задачи/задача-двора/разбор.md" in (запись.get("живьём") or ""),
           str(запись.get("живьём")))

    # ── Скил без артефакта: объявлен в данных с причиной ─────────────────
    д = двор([dict(ЗАПИСЬ_ХОРОШАЯ, skill="claude-api")],
             {"claude-api": {"артефакт": "-",
                             "почему": "справочный скил: знание уходит в работу, файла не создаёт"}})
    код, вывод = прогон(д, "claude-api", "--задача", "задача-двора")
    случай("скил без артефакта объявлен в данных — доказан записью журнала",
           код == 0 and "вызов в этой задаче доказан" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    # ── Без «--записать» состояние не трогается ──────────────────────────
    д = двор([ЗАПИСЬ_ХОРОШАЯ], АРТЕФАКТЫ)
    прогон(д, "spec-writing", "--задача", "задача-двора")
    состояние = yaml.safe_load((д / "состояние.yaml").read_text()) or {}
    случай("без «--записать» состояние не меняется",
           not (состояние.get("проверено") or {}), str(состояние))

    стало = {п: hashlib.md5(п.read_bytes()).hexdigest() for п in БОЕВЫЕ if п.exists()}
    случай("боевые файлы не тронуты", было == стало, "проба сыграла на производстве")

    print(f"ИТОГ: хороших {хорошо}, плохих {плохо}")
    return 1 if плохо else 0


if __name__ == "__main__":
    sys.exit(main())
