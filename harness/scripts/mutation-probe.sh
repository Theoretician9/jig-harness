if [ -n "${MUT_ONLY_LINES:-}" ] && [ "$SCOPED" -gt 0 ] && [ "$((OK + BAD + SKIPPED + DROPPED))" -eq 0 ] \
   && [ "${MECH_FILTER:-}" = "${MECH_FILTER#harness/config/}" ]; then
