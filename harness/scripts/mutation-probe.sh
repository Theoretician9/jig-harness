def образец(выражение: str):
    """Текст «до» и флаги из выражения sed → (образец, флаги, причина отказа).

    Разбирается ТОЛЬКО форма s<разделитель>образец<разделитель>замена: у «3d» и
    адресных форм образца нет вовсе, и угадать его — то же, что объяснять чужой
    код по памяти. Нераспознанное НАЗЫВАЕТСЯ, а не пропускается.
    """
    в = (выражение or "").strip()
    if len(в) < 4 or not в.startswith("s"):
        return None, "", "не форма s/образец/замена/"
    р = в[1]
    if р.isalnum() or р.isspace() or р == "\\":
        return None, "", f"разделитель «{р}» не годится"
    части = [""]
    н = 2
    while н < len(в):
        знак = в[н]
        if знак == "\\" and н + 1 < len(в):
            # Экранированный разделитель в sed означает САМ разделитель:
            # grep получит его без обратной косой.
            части[-1] += в[н + 1] if в[н + 1] == р else в[н:н + 2]
            н += 2
            continue
        if знак == р:
            части.append("")
            н += 1
            if len(части) == 3:
                break
            continue
        части[-1] += знак
        н += 1
    if len(части) < 2:
        return None, "", "разделителей меньше, чем нужно"
    if not части[0]:
        return None, "", "образец пуст"
    # Судья грамматики — САМ sed, а не наш разбор: выражение s|…||…|…| наш
    # разбор принимает (берёт усечённый образец), sed отказывается, файл не
    # меняется — и беда читается как «текст отстал от кода», то есть наоборот
    # (находка помощника 17.10.2026). Отказ печатает тот, кто отказывает.
    # --sandbox: выражение приходит ИЗ ДАННЫХ, и прогон sed — НЕ разбор. У s///
    # есть ключ «w ФАЙЛ» (файл открывается на запись при компиляции выражения и
    # усекается до нуля даже на пустом входе) и ключ «e» (замена исполняется
    # оболочкой). Замер ревью 17.10.2026: victim.txt 46 → 0 байт прямо в судье
    # грамматики. В песочнице sed отказывает своими словами «e/r/w disabled».
    готово = subprocess.run(["sed", "--sandbox", "-e", в, "/dev/null"],
                            capture_output=True, text=True)
    if готово.returncode != 0:
        причина = (готово.stderr or "").strip().splitlines()[-1:] or ["причины не назвал"]
        return None, "", f"sed не принимает выражение: {причина[0]}"
    return части[0], в[н:], ""


def сколько_раз(файл: str, текст: str):
    """Сколько раз образец встречается в файле → (число, причина отказа).

    Считает ВХОЖДЕНИЯ, а не строки: подстрока с отступом встречается дважды в
    одной строке, и мутация тогда садится не туда. Судья — тот же grep с тем же
    разбором выражения (BRE), что и у sed: свой разбор разошёлся бы молча.
    """
    готово = subprocess.run(["grep", "-o", "-e", текст, файл],
                            capture_output=True, text=True)
    if готово.returncode == 0:
        return len([с for с in готово.stdout.splitlines()]), ""
    if готово.returncode == 1:
        return 0, ""
    return None, (готово.stderr.strip().splitlines() or ["grep отказал"])[0]


