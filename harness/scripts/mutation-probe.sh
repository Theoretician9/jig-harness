CACHE_FILE="$LOG_DIR/mutations-cache.tsv"
NOW=$(date +%s)
SELF_SHA=$(sha256sum < "${BASH_SOURCE[0]}" | cut -c1-64)
if [ "$MUT_CACHE_DAYS" -gt 0 ] 2>/dev/null; then
    CACHE_ON=1
    CACHE_MIN=$((NOW - MUT_CACHE_DAYS * 86400))
    if [ -r "$CACHE_FILE" ]; then
        while IFS=$'\t' read -r ckey cwhen _ chole; do
            [[ "$cwhen" =~ ^[0-9]+$ ]] && [ "$cwhen" -ge "$CACHE_MIN" ] || continue
            [ "$cwhen" -gt "${CACHE_WHEN[$ckey]:-0}" ] || continue
            CACHE_WHEN[$ckey]=$cwhen; CACHE_HOLE[$ckey]=$chole
        done < "$CACHE_FILE"
    fi
fi

# Таблица мутаций — в harness/config/invariants.yaml рядом с самими правилами
# (ревью 10.09.2026, q-18): вшитая в скрипт, она не отвечала на главный вопрос
# «какие механизмы мутацией ещё НЕ проверены». Теперь непокрытые названы.
# Имена ЛАТИНИЦЕЙ: `read -r файл` — не идентификатор, bash отвечает ошибкой на
# каждой строке, и проба выходила «0 поймано, 0 дыр» с кодом 0 — зелёная, не
# проверив ничего (поймано прогоном 10.09.2026).
# Пустое поле в середине строки НЕ доживает до read: табуляция — пробельный
# разделитель, и два подряд схлопываются в один, сдвигая имя случая в подмену
# (отчёт печатал «мутация поймана: » без имени). Отсутствие подмены называется
# прочерком — признаком, а не пустотой.
# Читатель пишет таблицу в файл, а не в подстановку процесса: код выхода
# подстановки теряется, и упавший читатель давал зелёный итог по огрызку.
