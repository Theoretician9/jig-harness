# Кэш — в LOG_DIR рядом с мутации.log: это состояние прибора, а не код; в
# дереве его снесла бы уборка и увидел бы git. Строка: ключ, время, имя,
# причина дыры (пусто или нет поля в старых строках — зелёный прогон).
