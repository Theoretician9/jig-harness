python3 - > "$TABLE" <<'PYEOF'
import io, os, sys, yaml

# Пути носителей — из окружения, иначе боевые: без этого ни проба ключа, ни
# точечная сверка новых строк не могут не играть на производстве.
ИНВАРИАНТЫ = os.environ.get("HARNESS_INVARIANTS") or "harness/config/invariants.yaml"
ПРОБЫ = os.environ.get("HARNESS_PROBE_MUTATIONS") or "harness/config/probe-mutations.yaml"

МЕХ_ПАКЕТ = os.environ.get("MECH_STARTER", "")


def путь_механизма(путь):
    return путь.replace("${STARTER_DIR}", МЕХ_ПАКЕТ, 1) if isinstance(путь, str) else путь


ФИЛЬТР = os.environ.get("MECH_FILTER") or ""
d = yaml.safe_load(io.open(ИНВАРИАНТЫ, encoding="utf-8"))["инварианты"]
класс_d = {}
if os.path.exists(ПРОБЫ):
    класс_d = (yaml.safe_load(io.open(ПРОБЫ, encoding="utf-8")) or {}).get("пробы") or {}
for з in класс_d.values():
    if з and з.get("механизм"):
        з["механизм"] = путь_механизма(з["механизм"])
# Корни берутся ДО отбора: проверки механизма читают СОСЕДНИЙ корень
# (scripts/ → harness/config, harness/ → scripts/lib), и копия, собранная по
# одному отобранному механизму, краснела бы «чистой копией» без вины механизма.
корни = {и["файл"].split("/")[0] for и in d if и.get("мутация")}
корни |= {(з or {}).get("механизм", "").split("/")[0]
          for з in класс_d.values() if (з or {}).get("мутация")}
# Корень САМОЙ ПРОБЫ: при подмене «из-копии» из копии зовётся она, и её каталог
# обязан быть в копии целиком — иначе зов упадёт раньше любой мутации.
корни |= {проба.split("/")[0] for проба, з in класс_d.items()
          if (з or {}).get("мутация") and (з or {}).get("подмена") == "из-копии"}
# Проба и механизм из scripts/ читают harness/config, и наоборот: пара корней
# ходит вместе, иначе выборка записей зависит от порядка в таблице.
if "scripts" in корни or "harness" in корни:
    корни |= {"scripts", "harness"}
корни.discard("")
if ФИЛЬТР:
    # Отбор по механизму: пустота называется отдельной строкой, а не «0 из 0».
    d = [и for и in d if и.get("файл") == ФИЛЬТР]
    класс_d = {п: з for п, з in класс_d.items() if (з or {}).get("механизм") == ФИЛЬТР}
    if not any(и.get("мутация") for и in d) and not any((з or {}).get("мутация") for з in класс_d.values()):
        sys.stdout.write("\t".join(["#ПУСТО", ФИЛЬТР, "-", "-", "-", "-"]) + "\n")
        sys.exit(0)
sys.stdout.write("\t".join(["#КОРНИ", " ".join(sorted(корни)), "-", "-", "-", "-"]) + "\n")
без = []
def потеря(имя, сколько):
    """Запись не разобрана: названная потеря идёт в итог, а не молчаливый
    выход читателя, после которого прибор отчитывался зелёным по огрызку."""
    sys.stdout.write("\t".join(["#ВЫПАЛА", str(сколько), "-", "-", "-", имя]) + "\n")
def список(значение):
    """Поле «мутация»/«мутация_случай» — строка или список: у механизма бывает
    несколько мест, где ложь остаётся незаметной. 28.09.2026 у пробы копий их
    оказалось восемь, и одна строка в данных заставляла выбирать одну из них."""
    if значение is None:
        return []
    return значение if isinstance(значение, list) else [значение]


for и in d:
    выражения = список(и.get("мутация"))
    случаи = список(и.get("мутация_случай"))
    if выражения:
        if len(случаи) != len(выражения):
            sys.stderr.write(f"  ПЛОХО {и['id']}: мутаций {len(выражения)}, "
                             f"названных случаев {len(случаи)} — данные не парны\n")
            потеря(и["id"], len(выражения))
            continue
        # Доказательство инварианта бывает тяжёлым (поднимает базу) или живым
        # (прогон по боевым логам, зелёный всегда). Тогда мутацию проверяет
        # названный в данных лёгкий самотест — иначе механизм остаётся вовсе
        # без мутации, а это худший исход (10.09.2026).
        for выражение, случай in zip(выражения, случаи):
            sys.stdout.write("\t".join([и["файл"], выражение,
                                        и.get("мутация_доказательство") or и["доказательство"],
                                        и.get("мутация_подмена") or "-", "-",
                                        f"{и['id']}: {случай}"]) + "\n")
    elif и.get("доказательство"):
        без.append(и["id"])

# Класс D: мутация ставится в МЕХАНИЗМ, а краснеть обязана ПРОБА — поэтому
# файл и доказательство приходят из разных полей, а не из одного.
for проба, з in класс_d.items():
    з = з or {}
    выражения = список(з.get("мутация"))
    случаи = список(з.get("мутация_случай"))
    if not выражения:
        continue
    if len(случаи) != len(выражения):
        sys.stderr.write(f"  ПЛОХО {проба}: мутаций {len(выражения)}, "
                         f"названных случаев {len(случаи)} — данные не парны\n")
        потеря(проба, len(выражения))
        continue
    for выражение, случай in zip(выражения, случаи):
        sys.stdout.write("\t".join([з["механизм"], выражение,
                                    з["доказательство"], з.get("подмена") or "-",
                                    # Суффикс после # различает записи одной пробы, к пути не относится.
                                    проба.split("#")[0], f"{проба}: {случай}"]) + "\n")
sys.stderr.write(f"  без мутации ({len(без)}): {', '.join(без)}\n")
