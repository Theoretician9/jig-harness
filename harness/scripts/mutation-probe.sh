    ITOG2="$(date '+%Y-%m-%d %H:%M:%S')  === мутационная проба НЕДОГНАНА: не прогнано $NOT_RUN из $((OK + BAD + NOT_RUN)) (по сроку $SKIPPED, выпало $DROPPED) ==="
    echo "$ITOG2"; printf '%s\n' "$ITOG2" >> "$MUT_LOG" 2>/dev/null || true
fi
# Прополка кэша после полного набора: по ключу — свежайшая строка, просроченные
