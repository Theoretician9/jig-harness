            части.append("")
            н += 1
            if len(части) == 3:
                break
            continue
        части[-1] += знак
        н += 1
    if len(части) < 2:
        return None, "", "разделителей меньше, чем нужно"
    if not части[0]:
        return None, "", "образец пуст"
