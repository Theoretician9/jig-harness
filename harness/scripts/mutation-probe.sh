#!/usr/bin/env bash
#
# mutation-probe.sh — проверка самих проверок: портим одну строку в КОПИИ
# механизма и требуем, чтобы его самотест покраснел.
#
# Зачем. «Самотест зелёный» доказывает, что код согласован с собственным
# тестом, написанным тем же автором. Оно не доказывает, что тест ловит
# нарушение. Замечание владельца 10.09.2026 (М-2 к ревизии харнеса): ни одна
# проверка ревизии не подсовывала сломанный вход и не показывала красное.
#
# Улика, ради которой инструмент и остался: первая же проба нашла дыру —
# у sentinel пороги приходили в проверяемую функцию АРГУМЕНТАМИ, и мутация
# «WARDEN_STUCK_MIN=999999» оставила самотест зелёным. Сигнал с невозможным
# порогом не сигнал, а самотест этого не видел.
#
# Каждая строка таблицы: файл | выражение sed | команда самотеста | имя случая.
# Команда самотеста задаётся ЯВНО: у guard_bash проверка лежит в отдельном
# файле, и запуск «сам себя с --selftest» покраснел бы от синтаксической
# ошибки, а не от пойманной мутации — ложное доказательство хуже никакого.
#
# Запуск: bash scripts/mutation-probe.sh (входит в ворота --всё).
#         bash scripts/mutation-probe.sh --сверить-тексты — тексты мутаций ещё
#         стоят в коде? Прогонять после каждого круга правок на ЧИСТОМ дереве.
set -uo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.." || exit 1
# Защита от вложенности стоит ВЫШЕ загрузки конфига и журнала: отказ не должен
# ни читать боевую таблицу, ни писать в боевой мутации.log. Прибор сам ставит
# детям глубину+1 (см. `прогнать`): запись таблицы о самом приборе иначе плодила
# копию за копией (ночь 27.10: 38 уровней). Дверь HARNESS_MUTPROBE_SELFTEST_INNER
# ставит только самотест; --selftest на глубине ≥1 она всё равно не открывает,
# потому что именно этот путь и был рекурсией.
MUTPROBE_DEPTH="${HARNESS_MUTPROBE_DEPTH:-0}"
if [ "$MUTPROBE_DEPTH" -ge 2 ] 2>/dev/null \
   || { [ "$MUTPROBE_DEPTH" -ge 1 ] 2>/dev/null \
        && { [ "${HARNESS_MUTPROBE_SELFTEST_INNER:-}" != 1 ] || [ "${1:-}" = "--selftest" ]; }; }; then
    echo "mutation-probe: отказ — вложенный запуск прибора (HARNESS_MUTPROBE_DEPTH=$MUTPROBE_DEPTH)" >&2
    exit 2
fi
# Тяжёлый прогон идёт под потолок среза harness-checks.slice, а не в cgroup
# сессии. Метку ставит дверь; в срезе (служба проверок) она exec-ит прямо.
# Режимы без прогона проб (сверка текстов, самотест) и вложенные запуски самотеста
# дверь и очередь не берут: они дёшевы, а очередь занята часами.
case "${1:-}" in
    --сверить-тексты|--selftest) ;;
    *)  [ "$MUTPROBE_DEPTH" -ge 1 ] || [ -n "${HARNESS_IN_CHECKS_SLICE:-}" ] \
            || exec bash "$PWD/scripts/run-in-checks-slice.sh" bash "$PWD/scripts/mutation-probe.sh" "$@" ;;
esac
# След прогона — в СВОЙ журнал, а не только в вывод вызывающего: покрытие
# инвариантов ищет признак в мутации.log, и 28.09.2026 инвариант
# «проверки-ловят» стоял «БЕЗ СЛЕДА 18 дн», хотя проба гонялась воротами.
# Место журнала берётся общим загрузчиком: зашитый путь работает на одной машине.
# shellcheck disable=SC1091
. "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/lib/config.sh"
konf_zagruzit
# Механизм вне дерева проекта (установщик) в данных назван от пакета: `${STARTER_DIR}/USTANOVIT.sh`.
# Абсолютный путь в данных уезжает в публичную сборку с чужим домашним каталогом и ломает её.
MECH_STARTER="${MECH_STARTER:-$(python3 -I -c 'import sys; sys.path.insert(0, sys.argv[1]); import config; print(config.katalog_paketa())' \
    "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/lib" 2>/dev/null || true)}"
export MECH_STARTER
# Значения по умолчанию — ПОСЛЕ загрузчика, иначе они глушат файл конфига.
# Предел одного запуска: зависшая проба иначе съедает всю ночь.
MUTATION_RUN_TIMEOUT_S="${MUTATION_RUN_TIMEOUT_S:-180}"
# Крайний срок мягкой остановки (эпоха) ставит демон: прибор сам кончает за
# запас до жёсткого предела, чтобы итог напечатался, а не был убит на полпути.
# Пусто — без срока (ручной запуск).
MUTATION_DEADLINE_TS="${MUTATION_DEADLINE_TS:-}"
MUT_LOG="$LOG_DIR/мутации.log"
# Префикс harness-run-: голый mktemp проб внутри наследует TMPDIR, и уборка /tmp его опознаёт.
TMP=$(mktemp -d -t harness-run-XXXXXX); trap 'rm -rf "$TMP"' EXIT
export TMPDIR="$TMP"
# mktemp даёт 0700: проба, зовущая копию от второго пользователя группы, иначе её не откроет.
chmod 0755 "$TMP"
OK=0; BAD=0; SKIPPED=0; DROPPED=0
# Кэш включает только полный путь ниже разбора ключей: самотест и сверка
# текстов гоняют пробы по-настоящему. Флаг ставится здесь, а не берётся из
# среды, чтобы чужое окружение не включило кэш самотесту.
CACHE_ON=0; CACHE_HITS=0
declare -A CACHE_WHEN=() CACHE_HOLE=()

# Копия механизма проверяется ЕГО ЖЕ доказательством из инвариантов.yaml: путь
# оригинала в команде подменяется путём копии. Где тест берёт файл не из
# аргументов, а из окружения (guard_bash), имя переменной названо в данных
# полем «мутация_подмена» — запуск «сам себя с --selftest» покраснел бы от
# синтаксической ошибки, а не от пойманной мутации, и это ложное доказательство.
#
# Команда разбирается в МАССИВ слов, без eval: первая редакция звала
# eval "${runner//%s/$copy}", и путь с пробелом (TMPDIR) рвался по словам —
# bash отвечал rc=127, а проба печатала «ок, мутация поймана». Пять строк «ок»
# при нулевой проверке — ровно та ложная зелень, ради которой инструмент и
# написан (ревью 10.09.2026).
прогнать() { # $1=команда доказательства (с путём копии) $2=подмена или «-» $3=копия
    local -a words; read -ra words <<< "$1"
    # «Нет подмены» разбирается ЗДЕСЬ, а не у читателя данных: иначе всякий
    # другой вызывающий (самотест) обязан помнить про прочерк — и не помнит.
    local subst="$2"; [ "$subst" = "-" ] && subst=""
    # PYTHONDONTWRITEBYTECODE: свежий .pyc, написанный ЧИСТЫМ прогоном, гасит
    # мутацию той же байтовой длины (см. `корень_в_копию`).
    if [ -n "$subst" ]; then
        timeout -k 10 "$MUTATION_RUN_TIMEOUT_S" env -u MUT_ONLY_LINES PYTHONDONTWRITEBYTECODE=1 HARNESS_MUTPROBE_DEPTH=$((MUTPROBE_DEPTH+1)) "$subst=$3" "${words[@]}" >/dev/null 2>&1
    else
        timeout -k 10 "$MUTATION_RUN_TIMEOUT_S" env -u MUT_ONLY_LINES PYTHONDONTWRITEBYTECODE=1 HARNESS_MUTPROBE_DEPTH=$((MUTPROBE_DEPTH+1)) "${words[@]}" >/dev/null 2>&1
    fi
}

# Код 124/137 у `timeout` — зависание, а не «красная проба»: смешать их значило
# бы засчитать повисшую пробу как пойманную мутацию.
RC_TIMEOUT=124
прогнать_rc() { # как `прогнать`, но 137 (добито -k) сведено к 124
    прогнать "$@"; local rc=$?
    [ "$rc" = 137 ] && rc=$RC_TIMEOUT
    return "$rc"
}

дыра_таймаут() { # $1=имя случая; в кэш не пишется: перегруженная машина не повод держать дыру неделю
    дыра "таймаут: запуск пробы дольше ${MUTATION_RUN_TIMEOUT_S} с" "" "$1"
}

# Копия механизма обязана лежать СРЕДИ СОСЕДЕЙ. Скрипты харнеса сорсят общий
# загрузчик по своему пути (scripts/lib/config.sh), и одинокая копия в /tmp
# падает на строке source ещё до самотеста: 12.09.2026 пять проверок из
# восемнадцати отвечали «чистая копия уже красная» и не доказывали ничего.
# Копируется КОРНЕВОЙ каталог проверяемого файла — списка каталогов нет.
# Копия корня освежается из боевого дерева ОДИН раз на ключ (FRESH сбрасывает
# `проба`): за ночь механизмы правятся, и снимок начала прогона расходится с
# оригиналом — проба тогда красна на «чистой» копии. К началу ключа мутаций в
# копии нет (restore_mutated), так что сносить каталог корня безопасно.
declare -A FRESH=()
declare -A CLEAN_RC=()
корень_в_копию() { # $1 = первый сегмент пути (scripts, харнес…)
    [ -n "${FRESH[$1]:-}" ] && return 0
    FRESH[$1]=1
    rm -rf "${TMP:?}/дерево/$1"
    mkdir -p "$TMP/дерево"
    cp -a "$1" "$TMP/дерево/$1"
    # Старый байткод в копии ГАСИТ мутацию: питон сличает исходник с .pyc по
    # mtime-в-СЕКУНДАХ и РАЗМЕРУ, а мутация вида «обменять два слова» ни того,
    # ни другого не меняет — импортируемый модуль тогда берётся из кэша, и
    # прибор отвечает «самотест ЗЕЛЁН на испорченном коде» (замер 17.10.2026:
    # scripts/lib/selftest_cases.py, «дыр 1» без ключа и «дыр 0» с
    # PYTHONDONTWRITEBYTECODE=1). Два носителя: кэш из копии убираем здесь,
    # новый писать запрещаем при зове (см. `прогнать`).
    find "$TMP/дерево/$1" -type d -name __pycache__ -prune -exec rm -rf {} + 2>/dev/null || true
    # Пробы механизмов scripts/ читают СОСЕДА harness/config/* (паспорт,
    # system-jobs, tmp-sweep); без него чистая копия красна ещё до мутации.
    # harness ~5 МБ — копия целиком дешевле списка нужных файлов.
    if [ "$1" = scripts ] && [ -d harness ]; then корень_в_копию harness; fi
    if [ "$1" = scripts ] && [ -f dev-map.yaml ]; then cp -a dev-map.yaml "$TMP/дерево/"; fi
}

# Какие копии уже испорчены мутациями: «оригинал<TAB>копия» по строке.
#
# ЗАЧЕМ. Копия дерева ОДНА на весь прогон (`корень_в_копию` копирует корень
# только если его там ещё нет), и мутация, поставленная в ОБЩИЙ файл, остаётся
# в нём для всех следующих случаев. Пока мутации правили только свои файлы
# механизмов, это не стреляло; 13.10.2026 правило о слове владельца переехало в
# библиотеку `scripts/lib/owner_word.py`, её мутация осталась в копии — и
# СЛЕДУЮЩИЙ случай (сторож команд, который эту библиотеку читает) ответил
# «чистая копия уже красная». Испорченный сосед выглядел дефектом механизма, а
# не мусором прибора.
#
# Имя ЛАТИНИЦЕЙ: кириллическое имя переменной bash не берёт вовсе —
# присваивание становится КОМАНДОЙ и роняет разбор всего файла.
MUTATED=()

restore_mutated() {
    local para orig kopiya
    for para in "${MUTATED[@]:-}"; do
        [ -n "$para" ] || continue
        orig="${para%%$'\t'*}"; kopiya="${para##*$'\t'}"
        cp "$orig" "$kopiya"
    done
    MUTATED=()
}

# ── Кэш мутаций ────────────────────────────────────────────────────────────
# Ночной полный набор (~1520 мутаций × ~37 с) не укладывается в ночь, а почти
# все механизмы за сутки не меняются. Мутация пропускается, если ключ совпал с
# зелёным прогоном не старше MUT_CACHE_DAYS суток. Ключ — хеши файла механизма,
# каждого файла из команды доказательства (там проба), файла пробы класса D и
# самого прибора плюс текст мутации, команда и подмена: смена ЛЮБОГО из них —
# другой ключ. Соседи вне ключа (общие библиотеки, конфиги) ловятся сроком:
# каждая мутация раз в N суток гоняется по-настоящему. Дыра, найденная прогоном
# пробы, тоже кэшируется со своей причиной: повтор известной дыры ночь платила
# ~6 ч, а вердикт от кэша не меняется — дыра считается в BAD и называется.
cache_key() { # $1=файл $2=выражение $3=доказательство $4=подмена $5=путь пробы
    local -a files=("$1") words; local w hashes
    read -ra words <<< "$3"
    for w in "${words[@]}"; do [ -f "$w" ] && files+=("$w"); done
    [ -n "$5" ] && [ "$5" != "-" ] && files+=("$5")
    # Нечитаемый файл — нет ключа, а не ключ без него: иначе кэш врёт.
    hashes=$(sha256sum -- "${files[@]}" 2>/dev/null) || return 1
    printf '%s\n' "$SELF_SHA" "$2" "$3" "$4" "$5" "$hashes" | sha256sum | cut -c1-64
}

cache_put() { # $1=ключ $2=имя случая $3=причина дыры (пусто — зелёная)
    local hole="${3:-}"
    printf '%s\t%s\t%s\t%s\n' "$1" "$NOW" "${2//$'\t'/ }" "${hole//$'\t'/ }" >> "$CACHE_FILE" \
        || echo "mutation-probe: кэш не записан: $CACHE_FILE" >&2
}

дыра() { # $1=причина $2=ключ $3=имя случая
    printf '  ПЛОХО %s: %s\n' "$1" "$3"; BAD=$((BAD+1))
    [ -n "$2" ] && cache_put "$2" "$3" "$1"
}

# Шаг задачи сужает набор: MUT_ONLY_LINES — номера строк механизма, изменённых
# задачей (через запятую). Мутация, чьё выражение не трогает ни одной из них,
# в прогон не входит; мутация, не меняющая файл, входит (она сама дыра).
SCOPED=0
line_ranges() { # $1=номера через запятую; печатает «10–12,40–40»
    tr ',' '\n' <<< "$1" | sort -n -u | awk '
        NR == 1 { a = b = $1; next }
        $1 == b + 1 { b = $1; next }
        { out = out (out ? "," : "") a "–" b; a = b = $1 }
        END { print out (out ? "," : "") a "–" b }'
}

outside_task_edits() { # $1=файл $2=выражение
    [ -n "${MUT_ONLY_LINES:-}" ] || return 1
    local changed line
    changed=$(diff --unchanged-line-format= --old-line-format='%dn'$'\n' --new-line-format= \
        "$1" <(sed --sandbox "$2" "$1" 2>/dev/null)) || true
    [ -n "$changed" ] || return 1
    for line in $changed; do
        case ",$MUT_ONLY_LINES," in *",$line,"*) return 1 ;; esac
    done
    return 0
}

tree_hash() { # $1=файл $2=его копия; хеш содержимого того, что увидит чистый прогон
    case "$1" in
        /*) sha256sum < "$2" | cut -c1-64 ;;
        *)  (cd "$TMP/дерево" && find . -type f -print0 | sort -z | xargs -0 sha256sum | sha256sum | cut -c1-64) ;;
    esac
}

проба() { # $1=файл $2=выражение $3=доказательство $4=подмена $5=имя $6=путь пробы
    local src="$1" expr="$2" proof="$3" subst="$4" name="$5" probe="${6:-}"
    if outside_task_edits "$src" "$expr"; then SCOPED=$((SCOPED+1)); return; fi
    # Чужие мутации снимаются ДО своей: иначе «чистая копия» чистая только на
    # словах, и красный ответ ничего не доказывает.
    restore_mutated
    FRESH=()
    local key=""
    if [ "$CACHE_ON" = 1 ]; then
        key=$(cache_key "$src" "$expr" "$proof" "$subst" "$probe") || key=""
        if [ -n "$key" ] && [ -n "${CACHE_WHEN[$key]:-}" ]; then
            CACHE_HITS=$((CACHE_HITS+1))
            if [ -n "${CACHE_HOLE[$key]}" ]; then
                printf '  ПЛОХО (известная, из кэша, прогон %s) %s: %s\n' \
                    "$(date -d "@${CACHE_WHEN[$key]}" '+%d.%m %H:%M')" "${CACHE_HOLE[$key]}" "$name"
                BAD=$((BAD+1)); return
            fi
            printf '  ок    из кэша (те же файлы и мутация, зелёный прогон %s): %s\n' \
                "$(date -d "@${CACHE_WHEN[$key]}" '+%d.%m %H:%M')" "$name"
            OK=$((OK+1)); return
        fi
    fi
    # Срок проверяется только перед НАСТОЯЩИМ прогоном: ответ из кэша дёшев, и
    # его продолжаем отдавать, а непрогнанное добьёт следующий запуск через кэш.
    if [ -n "$MUTATION_DEADLINE_TS" ] && [ "$(date +%s)" -ge "$MUTATION_DEADLINE_TS" ]; then
        SKIPPED=$((SKIPPED+1)); return
    fi
    local copy
    case "$src" in
        /*) copy="$TMP/$(basename "$src")"   # одинокий файл стенда
            # Установщик пакета отказывает без harness/ рядом с собой: соседние
            # каталоги оригинала кладутся ссылками, мутируется только копия файла.
            for sibling in "$(dirname "$src")"/*/; do
                [ -d "$sibling" ] && ln -sfn "${sibling%/}" "$TMP/$(basename "$sibling")"
            done ;;
        *)  корень_в_копию "${src%%/*}" || { printf '  ПЛОХО не скопировать окружение: %s\n' "$name"; BAD=$((BAD+1)); return; }
            copy="$TMP/дерево/$src" ;;
    esac
    mkdir -p "$(dirname "$copy")"
    cp "$src" "$copy"
    local cmd="${proof//$src/$copy}"
    # Третий ответ на «чем испорченная копия доедет до пробы»: у пробы нет двери
    # среды, и механизм она находит РЯДОМ С СОБОЙ по своему пути — значит, из
    # копии дерева надо звать САМУ ПРОБУ. Путь пробы приходит шестым доводом;
    # без подстановки пути отказ ниже скажет «некуда подставить».
    if [ "$subst" = "из-копии" ]; then
        subst=""
        if [ -n "$probe" ] && [ "${cmd/$probe/}" != "$cmd" ]; then
            корень_в_копию "${probe%%/*}" || { printf '  ПЛОХО не скопировать окружение пробы: %s\n' "$name"; BAD=$((BAD+1)); return; }
            cmd="${cmd//$probe/$TMP/дерево/$probe}"
        fi
    fi
    if [ "$cmd" = "$proof" ] && [ -z "$subst" ]; then
        printf '  ПЛОХО мутацию некуда подставить (в доказательстве нет пути и нет подмены): %s\n' "$name"
        BAD=$((BAD+1)); return
    fi
    # Чистая копия ОБЯЗАНА быть зелёной: без этого «красное» ничего не доказывает —
    # оно могло прийти от сломанного окружения, а не от пойманной мутации.
    # Результат чистой копии один для всех мутаций одной пробы, пока не менялось
    # СОДЕРЖИМОЕ дерева копии (исходник, проба, соседи) и исполняемая команда:
    # другой помощник правит живое дерево между мутациями. Таймаут не запоминается.
    local ckey rc
    ckey="$cmd"$'\t'"$subst"$'\t'"$(tree_hash "$src" "$copy")"
    if [ -n "${CLEAN_RC[$ckey]:-}" ]; then
        rc="${CLEAN_RC[$ckey]}"
    else
        прогнать_rc "$cmd" "$subst" "$copy"; rc=$?
        [ "$rc" = "$RC_TIMEOUT" ] || CLEAN_RC[$ckey]=$rc
    fi
    if [ "$rc" = "$RC_TIMEOUT" ]; then дыра_таймаут "$name"; return; fi
    if [ "$rc" != 0 ]; then
        дыра 'чистая копия уже красная — проверка ничего не доказывает' "$key" "$name"; return
    fi
