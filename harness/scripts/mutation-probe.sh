ITOG="$(date '+%Y-%m-%d %H:%M:%S')  === мутационная проба: покраснели как надо $OK, дыр $BAD, из кэша $CACHE_HITS ==="
echo "$ITOG"; printf '%s\n' "$ITOG" >> "$MUT_LOG" 2>/dev/null || true
[ "$SCOPED" -gt 0 ] && echo "  вне правок задачи (в шаг не вошло): $SCOPED"
# Отдельная строка без «мутационная проба:» после «===»: демон берёт вердикт
# по дырам из первой, а недогон — из этой, и одна не затирает другую.
NOT_RUN=$((SKIPPED + DROPPED))
