    # (ревью 17.10.2026, F-sec-02). Наши мутации — только s///.
    sed --sandbox -i "$expr" "$copy"
    MUTATED+=("$src"$'\t'"$copy")
    if cmp -s "$src" "$copy"; then
        дыра 'мутация не изменила файл' "$key" "$name"; return
    fi
    прогнать_rc "$cmd" "$subst" "$copy"; rc=$?
    if [ "$rc" = "$RC_TIMEOUT" ]; then
        дыра_таймаут "$name"
    elif [ "$rc" = 0 ]; then
        дыра 'самотест ЗЕЛЁН на испорченном коде' "$key" "$name"
    else
        printf '  ок    чистая копия зелёная, мутация поймана: %s\n' "$name"; OK=$((OK+1))
        [ -n "$key" ] && cache_put "$key" "$name"
    fi
}

