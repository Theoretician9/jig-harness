            printf '  ок    копия без отказа пустого отбора с глубины 0: кончилась за %s с, копий копии %s\n' "$waited" "$launches"
        else
            printf '  ПЛОХО рекурсия копий с глубины 0: код %s, копий копии %s (ждали ≤1), за %s с\n' \
                "$rc" "$launches" "$waited"
            bad=1
        fi

