# -*- coding: utf-8 -*-
"""Пауза работы смены: владелец остановил — присмотр молчит.

Владелец 14.09.2026 в канал: «Нужен переключатель, можно прям в меню сделать.
Чтобы я остановил работу и больше лишней активности в виде сторожа которой
тебя пинает больше не было».

Что это чинит. Остановка смены была только словом в чат: сторожа о ней не
знали и продолжали делать своё — будили агента каждые десять минут и слали
владельцу «работа встала». Его же ночь 14.09: смена стояла по его решению, а
он получил и пинки, и ложное «Лимит обновился» (лимита не было вовсе).

Где живёт состояние. В общем каталоге состояния панели. Писатель сегодня ОДИН —
диспетчер бота (под пользователем агента); в `harness/panel/` про паузу нет ни
строки, и «панель тоже пишет» было обоснованием на будущее, выданным за факт
(находка ревью остановки I3, проверено `grep` по всем файлам панели). Каталог
общий именно поэтому: когда писатель появится, он пишет туда же. Ключом
в /etc/harness паузу держать нельзя: писать туда вправе только единственный
писатель настроек через sudo, и дать это право агенту значило бы дать ему
право менять ЛЮБУЮ развилку, включая «спрашивать ли владельца перед выкатом»
(И-2). Один файл — один источник истины, новых прав root не нужно.

Пауза БЕЗ СРОКА намеренно: её ставит и снимает владелец. Но любое его
сообщение снимает её само — иначе снять паузу было бы нечем, кроме панели, а
он пишет в чат (см. [[a-removal-mark-outlives-its-reason]]: у пометки должен
быть тот, кто её снимет).

Прогон:
    pause.py --поставить "почему" [--кто владелец]   # 0 — поставлена
    pause.py --снять                # 0 — снята (и когда её не было)
    pause.py --идёт-ли              # 0 — пауза стоит, 1 — работа идёт
    pause.py --почему               # печатает причину и когда поставлена
    pause.py --selftest
"""
from __future__ import annotations

import json
import os
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))
import config as конф                                     # noqa: E402

КАТАЛОГ = Path(os.environ.get("HARNESS_PANEL_STATE") or конф.panel_state_dir())
ФАЙЛ = КАТАЛОГ / "пауза.json"


def состояние() -> tuple[str, dict]:
    """ТРИ ответа, а не два: «нет» | «пауза» | «битый».

    Ревью спеки остановки 21.09.2026 нашло двух судей одного факта: этот модуль
    считал нечитаемый файл «паузы нет» (чтобы присмотр не замолчал навсегда от
    оборванной записи), а сторож паузы — «пауза» (чтобы смена не работала на
    непрочитанном стопе). Оба довода верны для СВОЕГО потребителя, и спор
    решается не выбором стороны, а третьим ответом: судья один, а политику по
    «битому» каждый выбирает сам ([[segment-state-three-answers]]).
    """
    try:
        сырое = ФАЙЛ.read_text(encoding="utf-8")
    except FileNotFoundError:
        return "нет", {}
    except OSError as беда:
        return "битый", {"почему": f"файл паузы не прочитан: {беда}"}
    try:
        запись = json.loads(сырое)
    except ValueError:
        return "битый", {"почему": "файл паузы не разбирается как JSON"}
    if not isinstance(запись, dict):
        return "битый", {"почему": "в файле паузы не запись, а " + type(запись).__name__}
    return "пауза", запись


def стоит() -> dict | None:
    """Запись о паузе, либо None — работа идёт.

    Битый файл здесь — НЕ пауза: этим ответом пользуется присмотр, и оборванная
    запись не вправе заставить сторожа замолчать навсегда. Тому, кто решает про
    СВОЮ работу (сторож паузы), нужен `состояние()` с тремя ответами.
    """
    вид, запись = состояние()
    return запись if вид == "пауза" else None


def поставить(почему: str, кто: str = "смена") -> int:
    """Поставить паузу. По умолчанию автор — СМЕНА, а не владелец.

    СЛУЧАЙ 26.09.2026. Проверяя ветку «на паузе демон всё равно отмечается», я
    поставил паузу своей же рукой — и сторож напечатал «Поставил: владелец.
    Причина: проба метки на паузе», после чего заперся: паузу владельца агенту
    снимать нельзя. Подпись была умолчанием, а не фактом, и смена встала до
    слова владельца из-за собственной пробы.

    Владельцем подписывает только тот, кто им и является: бот по кнопке меню и
    панель передают «--кто владелец» явно.
    """
    запись = {"почему": почему.strip() or "владелец остановил работу",
              "кто": кто, "ts": int(time.time())}
    try:
        КАТАЛОГ.mkdir(parents=True, exist_ok=True)
        # Атомарно: сторож читает этот файл каждую минуту и не должен увидеть
        # половину записи.
        врем = ФАЙЛ.with_suffix(".tmp")
        врем.write_text(json.dumps(запись, ensure_ascii=False), encoding="utf-8")
        врем.replace(ФАЙЛ)
    except OSError as беда:
        print(f"паузу не поставить: {беда}", file=sys.stderr)
        return 1
    return 0


def снять() -> int:
    """Снять паузу. Её отсутствие — не ошибка: снимать нечего, значит идём.

    Вместе с паузой снимаются метки «владельцу про неё сказано»
    (`пауза-сказано-*`, их ставит сторож паузы): у пометки должен быть тот, кто
    её снимет, иначе метка переживает свою причину
    ([[a-removal-mark-outlives-its-reason]]).
    """
    for метка in КАТАЛОГ.glob("пауза-сказано-*"):
        try:
            метка.unlink()
        except OSError:
            pass
    try:
        ФАЙЛ.unlink()
    except FileNotFoundError:
        return 0
    except OSError as беда:
        print(f"паузу не снять: {беда}", file=sys.stderr)
        return 1
    return 0


def словами() -> str:
    запись = стоит()
    if not запись:
        return "работа идёт"
    минут = max(0, int((time.time() - int(запись.get("ts") or 0)) // 60))
    return f"на паузе {минут} мин: {запись.get('почему')}"


def _selftest() -> int:
    import tempfile
    плохо = 0
    путей = 0

    def проба(имя: str, вышло, ждём) -> None:
        nonlocal плохо, путей
        путей += 1
        if вышло == ждём:
            print(f"  ок    {имя}")
        else:
            print(f"  ПЛОХО {имя}: вышло {вышло!r}, ждали {ждём!r}")
            плохо = 1

    global КАТАЛОГ, ФАЙЛ
    прежний_каталог, прежний_файл = КАТАЛОГ, ФАЙЛ
    with tempfile.TemporaryDirectory() as тмп:
        КАТАЛОГ = Path(тмп) / "состояние"
        ФАЙЛ = КАТАЛОГ / "пауза.json"
        # БОЛЬНОЙ СЛУЧАЙ 14.09.2026: смена стояла по решению владельца, а
        # сторож этого не знал и пинал её каждые десять минут.
        проба("БОЛЬНОЙ СЛУЧАЙ: паузы нет — работа идёт", стоит(), None)
        проба("поставить удалось", поставить("владелец сказал остановиться"), 0)
        проба("пауза видна", (стоит() or {}).get("почему"),
              "владелец сказал остановиться")
        проба("причина читается словами", "на паузе" in словами(), True)
        # БОЛЬНОЙ СЛУЧАЙ 26.09.2026: подпись «владелец» была умолчанием, и
        # пауза, поставленная пробой смены, заперла смену до его слова.
        проба("БОЛЬНОЙ СЛУЧАЙ: по умолчанию автор паузы — смена, не владелец",
              (стоит() or {}).get("кто"), "смена")
        поставить("владелец нажал кнопку", кто="владелец")
        проба("владельцем подписывает тот, кто назвался явно",
              (стоит() or {}).get("кто"), "владелец")
        # Метку «владельцу про эту паузу сказано» ставит сторож паузы, а снимать
        # её обязан тот, кто снимает саму паузу: иначе пометка переживает свою
        # причину и новая пауза молчит ([[a-removal-mark-outlives-its-reason]]).
        (КАТАЛОГ / "пауза-сказано-12345").write_text("", encoding="utf-8")
        проба("снять удалось", снять(), 0)
        проба("вместе с паузой снята метка «владельцу сказано»",
              list(КАТАЛОГ.glob("пауза-сказано-*")), [])
        проба("после снятия работа идёт", стоит(), None)
        # Снимать нечего — это не отказ: иначе бот отвечал бы владельцу ошибкой
        # на «продолжай», когда паузы и не было.
        проба("снять несуществующую паузу — не ошибка", снять(), 0)
        # Битый файл не должен выглядеть паузой: иначе сторож замолчит навсегда
        # из-за оборванной записи.
        КАТАЛОГ.mkdir(parents=True, exist_ok=True)
        ФАЙЛ.write_text("{не json", encoding="utf-8")
        проба("БОЛЬНОЙ СЛУЧАЙ: битый файл — не пауза, присмотр работает",
              стоит(), None)
        ФАЙЛ.write_text('"строка"', encoding="utf-8")
        проба("не-словарь в файле — тоже не пауза", стоит(), None)
        # ...но СУДЬЯ об этом знает: третий ответ есть, и сторож паузы возьмёт
        # именно его (ревью спеки остановки 21.09 — два судьи одного факта).
        проба("БОЛЬНОЙ СЛУЧАЙ: у битого файла свой ответ, а не «нет»",
              состояние()[0], "битый")
        ФАЙЛ.write_text("{не json", encoding="utf-8")
        проба("нечитаемый JSON — тоже «битый», а не «нет»", состояние()[0], "битый")
        # M1 ревью остановки: «битость» проверялась ОДНОЙ формой, а остальные
        # выводились чтением кода. Пустой файл появляется сам — обрыв записи на
        # нуле байт, — и по имени случая его не проверял никто.
        for вид, содержимое in (("пустой файл", ""),
                                ("файл из пробелов", "  \n\t "),
                                ("JSON-список", "[]"),
                                ("JSON-число", "17")):
            ФАЙЛ.write_text(содержимое, encoding="utf-8")
            проба(f"{вид} — «битый» для судьи", состояние()[0], "битый")
            проба(f"{вид} — не пауза для присмотра", стоит(), None)
        ФАЙЛ.unlink()
        проба("файла нет — ответ «нет»", состояние()[0], "нет")
        поставить("проба судьи")
        проба("файл на месте — ответ «пауза»", состояние()[0], "пауза")
        снять()
    КАТАЛОГ, ФАЙЛ = прежний_каталог, прежний_файл
    if плохо:
        print("САМОТЕСТ ПРОВАЛЕН")
        return 1
    print(f"САМОТЕСТ ПРОЙДЕН: {путей} путей, больной случай первым")
    return 0


def main() -> int:
    аргументы = sys.argv[1:]
    if "--selftest" in аргументы:
        return _selftest()
    if "--поставить" in аргументы:
        место = аргументы.index("--поставить") + 1
        почему = аргументы[место] if место < len(аргументы) else ""
        кто = "смена"
        if "--кто" in аргументы:
            где = аргументы.index("--кто") + 1
            кто = аргументы[где] if где < len(аргументы) else кто
        return поставить(почему, кто)
    if "--снять" in аргументы:
        return снять()
    if "--идёт-ли" in аргументы:
        return 0 if стоит() else 1
    if "--почему" in аргументы:
        print(словами())
        return 0
    print(__doc__.strip().splitlines()[0])
    return 2


if __name__ == "__main__":
    sys.exit(main())
