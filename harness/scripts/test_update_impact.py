def задачи_карты(с):
    данные = yaml.safe_load(с.devmap.read_text(encoding="utf-8")) or {}
    return {з["id"]: з for линия in данные.get("lines") or [] for з in линия.get("tasks") or []}


def карточки_части(с, часть):
    return {ид: з for ид, з in задачи_карты(с).items() if з.get("источник") == f"update_impact:{часть}"}


def статус_карточки(с, ид, статус):
    """Перевести карточку стенда в статус — правкой текста её блока, как правит карту человек."""
    текст = с.devmap.read_text(encoding="utf-8")
    начало = текст.index(f"- id: {ид}\n")
    конец = текст.index("status: plan", начало)
    с.devmap.write_text(текст[:конец] + f"status: {статус}" + текст[конец + len("status: plan"):], encoding="utf-8")


def строки_отчёта(с, **доп):
    _, первая, текст = с.отчёт(**доп)
    return текст if первая.startswith("шлю") else ""


def суточный_прогон(номер):
    """Часы N-го суточного прогона: переходы §6 судят «второй СУТОЧНЫЙ прогон подряд»."""
    return f"2026-11-{21 + номер}T07:12:00+05:00"


