    с.записать_реестр([с_перезапуском(часть_apt(пакет), перезапуск)])
    с.записать_замер([ряд_замера(пакет, БЫЛО_APT, СТАЛО_APT)])
    с.записать("apt-cache-policy.txt", блок_policy_карманы(пакет, БЫЛО_APT, СТАЛО_APT, источники) + общий_policy(общий))
    строки = ["* SECURITY UPDATE: overflow in parser", "  - CVE-2026-4444"] if безопасность else ["* Fix crash (LP: #2100100)"]
    с.записать(f"apt-changelog-{пакет}.txt",
               запись_changelog(пакет, СТАЛО_APT, "noble-updates", строки, "Mon, 02 Jun 2025 10:00:00 -0400")
               + запись_changelog(пакет, БЫЛО_APT, "noble", ["* Rebuild."], "Thu, 04 Apr 2024 10:00:00 -0400"))
