# -*- coding: utf-8 -*-
"""Пробы разбора обновлений сервера, фазы Р1–Р3.

Что судится. `update_impact.py` читает `$HARNESS_LOG_DIR/stack/замер.json`, берёт
тексты изменений из источников (§3.1 спеки), вырезает записи СТРОГО новее текущей
и не новее свежей, раскладывает их по классам кодом (§3.2) и пишет
`$HARNESS_LOG_DIR/stack/разбор.json` без модели. Отдельно (К-18а) замер
`stack_freshness.py` меряет пакет интерпретатора `python3.{минор}`, а не метапакет.
Р2 (§3.3–3.4): затронутость нашего кода по полю реестра `использование`, пункты записи,
модель только на пункты с нашими именами, сверка её ответа, кэш записей.
Р3 (§3.5, §3.5.1, §5, §7): класс рекомендации по таблице §3.5, ночной карман по
`Allowed-Origins` unattended-upgrades, отчёт владельцу `--отчёт` (≤ 700 знаков, пауза, «молчу»).

Стенд. Общий со стендом свежести стека (`test_stack_freshness.Стенд`): свой
каталог, окружение собрано с нуля, записанные ответы источников
(`HARNESS_STACK_SOURCES`), свой реестр (`HARNESS_STACK_REGISTRY`), свои часы.
Сверх него: `HARNESS_LOG_DIR` стенда, дерево `PROJECT_DIR` с `git init`, подставной
`claude` в PATH (пишет $PWD и счётчик вызовов, печатает ответ из файла стенда),
свои `HARNESS_UU_CONF` и `HARNESS_OS_RELEASE` (умолчание — как живая машина 21.11), заглушки
`scripts/pause.py` и `scripts/limit_mark.py` в `PROJECT_DIR` стенда (код из файла стенда).
Механизм проба зовёт РЯДОМ С СОБОЙ (подмена мутаций — «из-копии»): копия дерева
со сломанным `update_impact.py` или `stack_freshness.py` судится этой же пробой.

Записанные ответы (метки `recorded_or_live`):
  apt-changelog-<пакет>.txt                        — `apt-get changelog <пакет>`
  github-releases-<владелец>-<хранилище>-<N>.json  — страница N выпусков GitHub
  github-release-<владелец>-<хранилище>-<тег>.json — выпуск по тегу
  nodejs-dist-index.json, pypi-<пакет>.json, apt-cache-policy.txt — как у замера
  npm-<имя без области>-<версия>-engines.json      — `npm view <пакет>@<версия> engines --json`

Прогон (только фоном, через пул):
    python3 scripts/test_update_impact.py
"""
