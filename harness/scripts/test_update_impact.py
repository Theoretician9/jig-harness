def main() -> int:
    неудач = падений = 0
    for имя, функция in СЛУЧАИ:
        try:
            функция()
            print(f"  ок       {имя}")
        except AssertionError as ошибка:
            неудач += 1
            print(f"  НЕУДАЧА  {имя}: {ошибка}")
        except Exception:  # noqa: BLE001 — падение самой пробы называется отдельно от неудачи механизма
            падений += 1
            print(f"  ПАДЕНИЕ  {имя}:")
            traceback.print_exc(file=sys.stdout)
    print(f"РАЗБОР ОБНОВЛЕНИЙ Р1–Р3: случаев {len(СЛУЧАИ)}, неудач {неудач}, падений {падений}")
    return 1 if неудач or падений else 0


