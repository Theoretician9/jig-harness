#!/usr/bin/env python3
"""Проверка доски состояния: живёт ли запись ровно столько, сколько обещано.

Откуда взято. Владелец 12.09.2026: «Нужен какое то место для обмена данными,
чтобы код умел туда обращаться». Главная опасность такого места — вечная
правда: «жду ответа», записанное однажды, оправдывало бы молчание всегда
([[пометка-снятия-не-снимается-сама]]). Поэтому центральная проба здесь —
протухание.

Прогон:
    python3 scripts/test_doska.py
Код возврата: 0 — все пути прошли, 1 — есть упавший.
"""
import importlib.util
import os
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
двор = Path(tempfile.mkdtemp(prefix="доска-"))
os.environ["HARNESS_DOSKA"] = str(двор / "доска.json")

спец = importlib.util.spec_from_file_location("доска", КОРЕНЬ / "scripts" / "doska.py")
доска = importlib.util.module_from_spec(спец)
спец.loader.exec_module(доска)

путей = неудач = 0


def путь_ок(текст: str) -> None:
    global путей
    путей += 1
    print("ок  · " + текст)


def путь_плохо(текст: str) -> None:
    global путей, неудач
    путей += 1
    неудач += 1
    print("ПЛОХО · " + текст)


try:
    print("── сказать и прочитать ──")
    доска.сказать("лимит", "упёрся в лимит, сброс в 22:50", минут=30)
    запись = доска.читать("лимит")
    if запись and "22:50" in запись["что"]:
        путь_ок(f"записанное читается: {запись['что']}")
    else:
        путь_плохо(f"запись не прочиталась: {запись}")

    print("── БОЛЬНОЙ: протухшая запись не считается правдой ──")
    доска.сказать("жду", "жду ответа владельца", минут=0)
    time.sleep(1)
    if доска.читать("жду") is None:
        путь_ок("срок вышел — записи нет, хотя файл её ещё помнил")
    else:
        путь_плохо("протухшая запись выдана как живая")
    if "жду" not in доска.прочитать():
        путь_ок("протухшая запись снята с доски, а не копится")
    else:
        путь_плохо("протухшая запись осталась в файле")

    print("── чужая запись не затирает соседнюю ──")
    доска.сказать("делаю", "правлю панель", минут=30)
    if set(доска.живые()) == {"лимит", "делаю"}:
        путь_ок("на доске обе записи: лимит и делаю")
    else:
        путь_плохо(f"доска потеряла записи: {sorted(доска.живые())}")

    print("── снять ──")
    if доска.снять("делаю") and доска.читать("делаю") is None:
        путь_ок("снятая запись исчезает")
    else:
        путь_плохо("снятие не сработало")

    print("── БОЛЬНОЙ: битый файл не роняет читателя ──")
    Path(os.environ["HARNESS_DOSKA"]).write_text("{это не json", encoding="utf-8")
    if доска.прочитать() == {} and доска.читать("лимит") is None:
        путь_ок("битая доска читается как пустая, без исключения")
    else:
        путь_плохо("битый файл не обработан")

    print("── боевой путь: та же команда, что зовут демоны ──")
    среда = dict(os.environ)
    готово = subprocess.run(
        [sys.executable, str(КОРЕНЬ / "scripts" / "doska.py"),
         "--сказать", "лимит", "сброс в 22:50", "--на", "30"],
        capture_output=True, text=True, timeout=60, env=среда)
    читка = subprocess.run(
        [sys.executable, str(КОРЕНЬ / "scripts" / "doska.py"), "--читать", "лимит"],
        capture_output=True, text=True, timeout=60, env=среда)
    if готово.returncode == 0 and читка.returncode == 0 and "22:50" in читка.stdout:
        путь_ок("команда пишет и читает: код 0 и текст на выходе")
    else:
        путь_плохо(f"команда: запись {готово.returncode}, чтение {читка.returncode}, {читка.stdout[:60]}")

    пусто = subprocess.run(
        [sys.executable, str(КОРЕНЬ / "scripts" / "doska.py"), "--читать", "нет-такого"],
        capture_output=True, text=True, timeout=60, env=среда)
    if пусто.returncode == 1:
        путь_ок("нет записи — код 1: скрипт решает по коду возврата")
    else:
        путь_плохо(f"чтение пустого ключа дало код {пусто.returncode}")
finally:
    shutil.rmtree(двор, ignore_errors=True)

print(f"\nитого путей {путей}, неудач {неудач}")
sys.exit(1 if неудач else 0)
