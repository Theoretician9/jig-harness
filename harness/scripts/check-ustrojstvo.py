СХЕМА_ПУТЬ = "harness/config/паспорт.yaml"
КЛЮЧИ_СХЕМЫ = ("обязательные", "виды", "носители", "носитель_в_вид",
               "необязательные")
# Имя, начинающееся с этих слов, называет ПРОВЕРКУ, а не механизм: у такой
# записи обязан быть хозяин в поле «доказательство» (правило П-А задания
# владельца 13.09.2026). Пока только считаем — красить будем, когда хозяева
# появятся у всех 24.
ПРЕФИКСЫ_ПРОВЕРОК = ("Проверка", "Проба")
def прочитать_схему(корень: Path = КОРЕНЬ) -> dict:
    """Схема паспорта из данных. Читается на КАЖДЫЙ вызов: закэшированная при
    импорте схема сделала бы правку данных недействующей до перезапуска.

    Корень здесь — корень УСТАНОВКИ, а не проверяемого дерева: схема
    принадлежит харнесу, а дерево механизмов у проб бывает подставным. Поэтому
    `проверить()` свой корень сюда не передаёт.

    Файла нет или он битый — падаем ВСЛУХ, называя путь. Подставить вшитый
    список здесь нельзя: умолчание выше загрузчика превращает настройку в
    мёртвую, и гейт молча судил бы по коду, делая вид, что судит по данным.
    """
    import os
    путь = Path(os.environ.get("HARNESS_PASPORT") or (корень / СХЕМА_ПУТЬ))
    try:
        схема = yaml.safe_load(путь.read_text(encoding="utf-8"))
    except OSError as беда:
        raise SystemExit(f"схема паспорта не прочитана: {путь} — {беда}")
    except yaml.YAMLError as беда:
        raise SystemExit(f"схема паспорта не разобрана: {путь} — {беда}")
    if not isinstance(схема, dict) or not set(КЛЮЧИ_СХЕМЫ) <= set(схема):
        raise SystemExit(f"схема паспорта неполна: {путь} — нужны ключи "
                         f"{', '.join(КЛЮЧИ_СХЕМЫ)}")
    return схема


def имена_без_хозяина(записи: list) -> list:
    """Записи, чьё ИМЯ называет проверку, а хозяина в «доказательство» нет.

    Правило счёта — ПРЕФИКС «Проверка»/«Проба». По подстроке «роверк» вышло бы
    33 вместо 24: число ходит вместе с правилом, поэтому правило названо в
    коде и печатается владельцу вместе с числом.
    """
    return [з.get("имя", "") for з in записи
            if str(з.get("имя", "")).startswith(ПРЕФИКСЫ_ПРОВЕРОК)
            and not str(з.get("доказательство", "")).strip()]


# Фраза короче этого — не объяснение, а отписка («Копирует.»).
МИНИМУМ_РОЛИ = 25
ДОКУМЕНТ = Path("docs") / "УСТРОЙСТВО-ХАРНЕСА.md"


def _модуль(имя: str, файл: str):
    """Загрузить соседний скрипт как модуль — ССЫЛКОЙ, а не копией значений.

    Копия (`from … import СООТВЕТСТВИЯ`) неотличима от своего списка: подменить
    её у судьи нельзя, и «один судья» превращается в обещание вместо свойства.
    """
    спец = importlib.util.spec_from_file_location(имя, КОРЕНЬ / "scripts" / файл)
    модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(модуль)
    return модуль


# Кто судит факт «файл принадлежит харнесу» — ОДИН на весь проект. Свой обход
# дерева здесь был бы вторым судьёй того же факта: ровно это запрещает
# harness/config/признаки.yaml, заведённый этой же сменой.
СУДЬЯ = _модуль("сверка_с_пакетом", "sverit-s-paketom.py")
# Расширения, которые считаются кодом харнеса, и документ скила.
ДОМЕН_КОД = (".py", ".sh")
ДОМЕН_ДОКУМЕНТ = ("SKILL.md",)
# Потолок-ХРАПОВИК: сколько файлов домена сегодня живут без паспорта. Гейт стоит
# в воротах и краснеет на ПРЕВЫШЕНИИ, а не на самой дыре: заводить 39 паспортов
# одним коммитом с расширением домена значило бы держать ворота красными всю
# работу, а выключать домен ключом — усыпить механизм и оставить его живым на
# вид. Храповик ловит регресс с первого дня: новый файл без паспорта даёт 40
# при потолке 39 и красит ворота сразу. Потолок опускается до нуля тем же
# коммитом, которым заводятся паспорта (Task 5 плана hr.reestr-v2).
КЛЮЧ_ПОТОЛКА = "USTROJSTVO_BEZ_PASPORTA_POTOLOK"
# Второй храповик — на имена, называющие проверку вместо механизма. Счётчик без
# потолка растёт молча: ревью кода 13.09.2026 спросило прямо, кто заметит 25-е
# такое имя. Никто — поэтому потолок, и он тоже только опускается.
КЛЮЧ_ИМЁН = "USTROJSTVO_IMEN_PROVEROK_POTOLOK"


def потолок(ключ: str) -> int:
    """Сколько дыр домена терпится. Данные: harness.conf, ключ — выше.

    Читается СТРОГО из файла: `конфиг()` ставит окружение выше файла, и тогда
    потолок снимался бы там же, где запускаются ворота — сторож, который
    отключается одной переменной рядом с собой, не сторож (ревью кода
    13.09.2026). Путь конфига подставить можно: это нужно пробам, а вот
    ЗНАЧЕНИЕ приходит только из названного файла.
    """
    import os
    sys.path.insert(0, str(КОРЕНЬ / "scripts" / "lib"))
    from konf import из_файла, ПУТЬ_HARNESS_CONF
    путь = os.environ.get("HARNESS_CONF") or ПУТЬ_HARNESS_CONF
    try:
        return int(из_файла(путь).get(ключ, "0"))
    except ValueError:
        return 0


def _глубокие_термины():
    """Словарь берётся у уровня языка: два списка разойдутся, один — нет."""
    спец = importlib.util.spec_from_file_location(
        "уровень_языка", КОРЕНЬ / "scripts" / "uroven-yazyka.py")
    модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(модуль)
    return модуль.ГЛУБОКИЕ


ГЛУБОКИЕ = _глубокие_термины()


# ─── что есть в репозитории ─────────────────────────────────────────────────
def _хуки(корень: Path) -> dict:
    """Хуки — то, что зовёт оболочка: список берётся из её настроек."""
    настройки = корень / ".claude" / "settings.json"
    try:
        данные = json.loads(настройки.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    найдено = {}
    for группы in данные.get("hooks", {}).values():
        for группа in группы:
            for хук in группа.get("hooks", []):
                for путь in _пути_команды(хук.get("command", ""), корень):
                    найдено[путь] = "хук"
    return найдено


def _пути_команды(команда: str, корень: Path) -> list:
    """Пути к существующим файлам проекта внутри командной строки."""
    пути = []
    for кусок in re.findall(r'[\w./Ѐ-ӿ-]+\.(?:py|sh)', команда):
        относительный = re.sub(r'^\$?CLAUDE_PROJECT_DIR/', "", кусок).lstrip("./")
        if (корень / относительный).is_file():
            пути.append(относительный)
    return пути


def _гейты(корень: Path) -> dict:
    """Гейты — то, что зовут ворота: первый существующий файл в строке."""
    try:
        текст = (корень / "scripts" / "vorota.sh").read_text(encoding="utf-8")
    except OSError:
        return {}
    найдено = {}
    for строка in текст.splitlines():
        совпало = re.match(r'\s*проверка\s+"[^"]+"\s+(.*)', строка)
        if not совпало:
            continue
        пути = _пути_команды(совпало.group(1), корень)
        if пути:
            найдено[пути[0]] = "гейт"
    return найдено


def в_домене(путь: Path) -> bool:
    """Принадлежит ли файл харнесу. Судья один — таблица СООТВЕТСТВИЯ.

    `ЖИВЫЕ` вычитается: это то, что принадлежит серверу, а не харнесу
    (`STATE.md`, `dev-map.yaml`, `память/`, настройки, которые владелец крутит
    с панели). Без вычитания домен захватил бы чужое.
    """
    строка = str(путь)
    if "__pycache__" in строка:
        return False
    if any(строка == ж or строка.startswith(ж) for ж in СУДЬЯ.ЖИВЫЕ):
        return False
    if not any(строка == к or строка.startswith(к) for к in СУДЬЯ.СООТВЕТСТВИЯ):
        return False
    return путь.suffix in ДОМЕН_КОД or путь.name in ДОМЕН_ДОКУМЕНТ


def файлы_домена(корень: Path) -> set:
    """Все файлы харнеса на диске — по единственному судье."""
    найдено = set()
    for ключ in СУДЬЯ.СООТВЕТСТВИЯ:
        начало = корень / ключ
        кандидаты = [начало] if not ключ.endswith("/") else начало.rglob("*")
        for файл in кандидаты:
            if файл.is_file() and в_домене(файл.relative_to(корень)):
                найдено.add(str(файл.relative_to(корень)))
    return найдено


def числа_домена(корень: Path, записи: list | None = None) -> dict:
    """Три числа одной ручкой: домен, без паспорта, паспортов вне домена."""
    записи = прочитать_реестр(корень) if записи is None else записи
    файлы = файлы_домена(корень)
    паспорта = {з.get("файл") for з in записи}
    return {"домен": len(файлы),
            "без паспорта": len(файлы - паспорта),
            "паспортов вне домена": len(паспорта - файлы)}


def механизмы_репозитория(корень: Path) -> dict:
    """Все механизмы харнеса: путь → вид. Списки берутся из живых источников."""
    найдено = {}
    for файл in sorted((корень / "harness" / "demons").glob("*")):
        if файл.is_file():
            найдено[str(файл.relative_to(корень))] = "демон"
    for каталог in sorted((корень / "harness" / "skills").glob("*")):
        скил = каталог / "SKILL.md"
        if скил.is_file():
            найдено[str(скил.relative_to(корень))] = "скил"
    # Гейты раньше хуков: файл, служащий обоим, описывается как гейт —
    # проверкой он работает всегда, а хуком лишь при записи файла.
    найдено.update(_гейты(корень))
    for путь, вид in _хуки(корень).items():
        найдено.setdefault(путь, вид)
    # Файл, известный только по домену, вида НЕ заявляет: вид знает лишь тот,
    # кто видел механизм в работе (ворота зовут гейт, оболочка — хук). Пустой
    # вид значит «паспорт нужен, а каким он назовётся — скажет автор паспорта»;
    # заявленный наугад покрасил бы 134 живых паспорта сверкой видов.
    for путь in файлы_домена(корень):
        найдено.setdefault(путь, "")
    return найдено


# ─── что написано в реестре ─────────────────────────────────────────────────
def прочитать_реестр(корень: Path) -> list:
    путь = корень / "harness" / "config" / "устройство.yaml"
    данные = yaml.safe_load(путь.read_text(encoding="utf-8")) or {}
    return данные.get("механизмы") or []


def _термин_без_расшифровки(текст: str) -> str | None:
    """Глубокое слово без расшифровки рядом. Расшифровка — скобки в той же фразе."""
    for фраза in re.split(r'(?<=[.!?])\s+', текст):
        найдено = ГЛУБОКИЕ.search(фраза)
        if найдено and "(" not in фраза:
            return найдено.group(0)
    return None


def ждёт_возможности(запись: dict, корень: Path) -> bool:
    """Механизм приезжает не с базовой установкой, а с возможностью, и та ещё
    не поставлена. Тогда «файла нет» — норма, а не дыра.

    Живой прогон ворот ВНУТРИ свежей установки 13.09.2026: три скила мобильной
    разработки описаны в реестре, а файлов в пакете нет — и ворота новой машины
    красные с первого дня. Скилы возможности собираются при её установке, так
    и задумано; краснеть должен только случай «возможность стоит, файла нет».
    """
    имя = (запись.get("приезжает_с") or "").strip()
    if not имя:
        return False
    return not (корень / "harness" / "vozmozhnosti" / имя / ".установлено").exists()


def _больных_не_названо(запись: dict) -> bool:
    """«больных: 0» у механизма, заведённого ПОСЛЕ перехода на схему v2.

    Проверка, ни разу не падавшая, ничего не проверяет — поэтому ноль красный.
    Водораздел — наличие поля «заведён»: у прежних 134 паспортов его нет, и
    число больных путей им взять неоткуда; требовать его значит приглашать
    выдумать, а выдуманное число делает гейт зелёным именно тогда, когда он
    обязан краснеть.
    """
    if not str(запись.get("заведён", "")).strip():
        return False
    доказательство = запись.get("доказательство")
    if not isinstance(доказательство, dict):
        return False
    return доказательство.get("больных") == 0


def проверить(записи: list, найденные: dict, корень: Path,
              схема: dict | None = None) -> list:
    """Список претензий. Пусто — реестр сходится с репозиторием."""
    схема = схема if схема is not None else прочитать_схему()
    обязательные = tuple(схема["обязательные"])
    виды = tuple(схема["виды"])
    претензии = []
    описаны = {}
    for номер, запись in enumerate(записи, 1):
        файл = запись.get("файл", f"<запись {номер}>")
        нет = [поле for поле in обязательные if not str(запись.get(поле, "")).strip()]
        if нет:
            претензии.append(f"{файл}: нет обязательных полей: {', '.join(нет)}")
            continue
        if файл in описаны:
            претензии.append(f"{файл}: описан дважды")
            continue
        описаны[файл] = запись
        if _больных_не_названо(запись):
            претензии.append(
                f"{файл}: «больных: 0» у механизма, заведённого после перехода — "
                f"проверка, ни разу не падавшая, ничего не проверяет")
        if запись["вид"] not in виды:
            претензии.append(
                f"{файл}: вид «{запись['вид']}» не из перечня ({', '.join(виды)})")
        if not (корень / файл).exists() and not ждёт_возможности(запись, корень):
            претензии.append(f"{файл}: описание есть, а файла нет")
        elif (файл in найденные and найденные[файл]
              and найденные[файл] != запись["вид"]):
            претензии.append(
                f"{файл}: в репозитории это «{найденные[файл]}», "
                f"а в реестре «{запись['вид']}»")
        if len(запись["роль"].strip()) < МИНИМУМ_РОЛИ:
            претензии.append(f"{файл}: роль короче внятной фразы — это отписка")
        for поле in ("роль", "без_него"):
            термин = _термин_без_расшифровки(запись[поле])
            if термин:
                претензии.append(
                    f"{файл}: в поле «{поле}» термин «{термин}» без расшифровки "
                    f"в той же фразе — владелец читает это без подготовки")
    for путь in sorted(набор for набор in найденные if набор not in описаны):
        претензии.append(f"{путь}: механизм есть, а описания в реестре нет")
    return претензии


def документ_разошёлся(корень: Path) -> str | None:
    """Документ обязан быть ровно тем, что собирается из реестра."""
    спец = importlib.util.spec_from_file_location(
        "сборщик", КОРЕНЬ / "scripts" / "sobrat-ustrojstvo.py")
    сборщик = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(сборщик)
    ожидается = сборщик.собрать(прочитать_реестр(корень))
    путь = корень / ДОКУМЕНТ
    try:
        на_диске = путь.read_text(encoding="utf-8")
    except OSError:
        return f"{ДОКУМЕНТ}: документа нет — собрать: python3 scripts/sobrat-ustrojstvo.py"
    if на_диске != ожидается:
        return (f"{ДОКУМЕНТ}: разошёлся с реестром (правили руками?) — "
                f"пересобрать: python3 scripts/sobrat-ustrojstvo.py")
    return None


ДЫРА = ": механизм есть, а описания в реестре нет"


def main() -> int:
    записи = прочитать_реестр(КОРЕНЬ)
    претензии = проверить(записи, механизмы_репозитория(КОРЕНЬ), КОРЕНЬ)
    безхозяйных = имена_без_хозяина(записи)
    числа = числа_домена(КОРЕНЬ, записи)
    потолок_дыр = потолок(КЛЮЧ_ПОТОЛКА)
    # Дыры домена судит храповик, всё остальное — как прежде, поимённо.
    потолок_имён = потолок(КЛЮЧ_ИМЁН)
    if len(безхозяйных) > потолок_имён:
        претензии.append(
            f"имён-проверок без хозяина {len(безхозяйных)} при потолке "
            f"{потолок_имён}: {', '.join(sorted(безхозяйных)[:3])}… — "
            f"потолок опускается, а не поднимается")
    дыры = [п for п in претензии if п.endswith(ДЫРА)]
    претензии = [п for п in претензии if not п.endswith(ДЫРА)]
    print(f"домен: {числа['домен']} · без паспорта: {числа['без паспорта']}"
          f" · паспортов вне домена: {числа['паспортов вне домена']}"
          f" (потолок дыр {потолок_дыр})")
    if len(дыры) > потолок_дыр:
        претензии.extend(дыры)
        претензии.append(
            f"файлов домена без паспорта {len(дыры)} при потолке {потолок_дыр} — "
            f"потолок опускается, а не поднимается")
    расхождение = документ_разошёлся(КОРЕНЬ)
    if расхождение:
        претензии.append(расхождение)
    if претензии:
        print("устройство харнеса: реестр разошёлся с репозиторием")
        for строка in претензии:
            print(f"  ✗ {строка}")
        print(f"\nописано {len(записи)}, претензий {len(претензии)}")
        print("реестр: harness/config/устройство.yaml")
        return 1
    print(f"устройство: описано механизмов {len(записи)}, расхождений нет")
    print(f"  имён-проверок без хозяина в «доказательство»: {len(безхозяйных)} "
          f"(правило счёта — префикс «Проверка»/«Проба», потолок {потолок_имён})")
    return 0


