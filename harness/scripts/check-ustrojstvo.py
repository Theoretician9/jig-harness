"""Гейт: у каждого механизма харнеса есть описание, и описание не врёт.

Откуда взят. Владелец 11.09.2026: «Нужно прописать как работает всё в харнесе,
отдельно детально что делает каждый демон хук и тд». Спека панели §9.

Документ о том, как всё устроено, стареет быстрее любого другого: механизмы
заводятся каждую смену (11.09 прибавилось шесть проверок и демон коммита
памяти), а документ правят раз в месяц. Устаревшее описание опаснее пустого —
оно врёт с видом истины. Поэтому источник ОДИН — `harness/config/устройство.yaml`,
а сверка идёт в обе стороны:

  • механизм в репозитории без строки в реестре — красный (иначе новый демон
    живёт незамеченным, и владелец о нём не узнает);
  • строка реестра без файла — красный (описание пережило свой механизм);
  • вид в реестре разошёлся с местом файла — красный.

Плюс язык. Пояснения пишутся для человека без подготовки (владелец: «чтобы
бабушка поняла»), поэтому глубокий термин допускается только с расшифровкой в
той же фразе. Словарь терминов — общий с `scripts/uroven-yazyka.py`: два места
с разными списками разойдутся.

Прогон:
    python3 scripts/check-ustrojstvo.py
Код возврата: 0 — реестр сходится с репозиторием, 1 — расхождение.
"""
