КОРЕНЬ = Path(__file__).resolve().parent.parent
# Схема паспорта — ДАННЫЕ (harness/config/паспорт.yaml), а не кортежи здесь.
# Прежде добавить поле было нельзя без правки сторожа: две разные причины
