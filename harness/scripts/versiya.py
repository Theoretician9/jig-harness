#!/usr/bin/env python3
"""Номер следующего релиза харнеса и заметки к нему — счётом, а не на глаз.

Откуда взято. Владелец 12.09.2026: «Какие есть стандарты для релизов в гит.
Вот эти всякие другие харнесы например, что как должно быть стандарты
индустрии». Стандарт: SemVer, тег vX.Y.Z, заметки, собранные машиной.

Прибор ничего не меняет: отдаёт ДАННЫЕ, а тег и CHANGELOG пишет
publikaciya.sh — после того, как ветка уехала.

Три решения, каждое под свою улику:

* **Прошлая версия — из ТЕГА публичной сборки**, а не из файла VERSION. Файл
  едет в чужие руки, его правят; тег ставит только публикация.
* **Диапазон — из заголовка релизного коммита** («версия от ГГГГ-ММ-ДД, пакет
  <хэш>»). Тот же шаблон читает obnovlenie.py: заголовок — договор двух
  механизмов, а не украшение.
* **Минор — по ДОБАВЛЕННЫМ файлам механизмов** (git diff -M, признак A).
  Сравнивать содержимое реестра между ревизиями нельзя: 12.09.2026 реестр на
  прошлом релизе лежал по пути «харнес/config/…», и git show падал.

Прогон:
    python3 scripts/versiya.py --следующая [--пакет DIR] [--сборка DIR] [--мажор]
    python3 scripts/versiya.py --оформить --пакет DIR --сборка DIR [--удалённый ИМЯ]
    python3 scripts/versiya.py --selftest
Код возврата: 0 — посчитано, 1 — посчитать нечем.
"""
import fnmatch
import json
import re
import subprocess
import sys
import time
from pathlib import Path

import yaml

КОРЕНЬ = Path(__file__).resolve().parent.parent
ДАННЫЕ_ПО_УМОЛЧАНИЮ = КОРЕНЬ / "harness" / "config" / "релиз.yaml"
# Договор с publikaciya.sh и obnovlenie.py: первая строка релизного коммита.
ЗАГОЛОВОК_РЕЛИЗА = re.compile(r"версия от \d{4}-\d{2}-\d{2}, пакет ([0-9a-f]{7,40})")
ТЕГ = re.compile(r"^v(\d+)\.(\d+)\.(\d+)$")


class Отказ(Exception):
    """Посчитать нечем: об этом говорят словом, а не пустым ответом."""


def _гит(*доводы, где) -> subprocess.CompletedProcess:
    # core.quotepath=false: без него git отдаёт кириллические пути
    # экранированными байтами, и fnmatch по ним не совпадает никогда.
    return subprocess.run(["git", "-c", "core.quotepath=false", *доводы],
                          cwd=str(где), capture_output=True, text=True, timeout=120)


def данные(путь=ДАННЫЕ_ПО_УМОЛЧАНИЮ) -> dict:
    """Данные релиза. Нет файла или нет ключа — отказ словом: traceback
    уехал бы владельцу в канал строкой «ОТКАЗ: … Traceback (most recent…)»."""
    try:
        дано = yaml.safe_load(Path(путь).read_text(encoding="utf-8"))
    except (OSError, yaml.YAMLError) as беда:
        raise Отказ(f"данные релиза не прочитаны ({путь}): {беда}") from беда
    обязательные = ("начальная_версия", "минор_если_добавлен")
    нет = [к for к in обязательные if not isinstance(дано, dict) or к not in дано]
    if нет:
        raise Отказ(f"в данных релиза {путь} нет ключей: {', '.join(нет)}")
    return дано


def прошлый_тег(сборка: Path, удалённый: str = "") -> str:
    """Последний ОПУБЛИКОВАННЫЙ тег vX.Y.Z. Пусто — релизов ещё не было.

    Спрашивается удалённый, а не локальные теги: тег, который не уехал наружу,
    для человека не существует. Улика 12.09.2026 (ревью кода, R-2): после
    упавшей отправки тега локальный тег оставался, счёт уходил на следующий
    номер — опубликованный коммит навсегда оставался без метки, а версия
    пропускалась. Удалённого нет или он молчит — судим по локальным: на стенде
    и при первом релизе иначе не с чем сравнивать.
    """
    вывод = ""
    if удалённый:
        ответ = _гит("ls-remote", "--tags", удалённый, где=сборка)
        if ответ.returncode == 0:
            # refs/tags/v1.2.3 и refs/tags/v1.2.3^{} — берём имя без хвоста.
            вывод = "\n".join(строка.split("refs/tags/")[-1].replace("^{}", "")
                              for строка in ответ.stdout.splitlines() if "refs/tags/" in строка)
    if not вывод:
        вывод = _гит("tag", "--list", "v*", "--sort=-v:refname", где=сборка).stdout
    теги = [с.strip() for с in вывод.splitlines() if ТЕГ.fullmatch(с.strip())]
    # Сортировка своя: ls-remote отдаёт теги в порядке строк, и v0.9.0
    # оказался бы старше v0.10.0.
    теги.sort(key=lambda т: tuple(int(ч) for ч in ТЕГ.fullmatch(т).groups()), reverse=True)
    return теги[0] if теги else ""


def хэш_пакета_релиза(сборка: Path, тег: str) -> str:
    """Из какого состояния пакета собран релиз, помеченный тегом."""
    заголовок = _гит("log", "-1", "--format=%s", тег, где=сборка).stdout.strip()
    совпало = ЗАГОЛОВОК_РЕЛИЗА.fullmatch(заголовок)
    return совпало.group(1) if совпало else ""


def _есть_коммит(пакет: Path, хэш: str) -> bool:
    return bool(хэш) and _гит("cat-file", "-e", f"{хэш}^{{commit}}", где=пакет).returncode == 0


def заметки(пакет: Path, от: str) -> list:
    """Заголовки коммитов пакета за диапазон, новые сверху."""
    диапазон = [f"{от}..HEAD"] if от else []
    вывод = _гит("log", "--format=%s", *диапазон, где=пакет).stdout
    return [с.strip() for с in вывод.splitlines() if с.strip()]


def добавленные_механизмы(пакет: Path, от: str, шаблоны: list) -> list:
    """Новые файлы-механизмы за диапазон. Переименование сюда не попадает."""
    if not от:
        return []
    вывод = _гит("diff", "--name-status", "-M", f"{от}..HEAD", где=пакет).stdout
    новые = []
    for строка in вывод.splitlines():
        части = строка.split("\t")
        if len(части) < 2 or части[0] != "A":
            continue
        путь = части[1]
        if any(fnmatch.fnmatch(путь, ш) for ш in шаблоны):
            новые.append(путь)
    return новые


def поднять(версия: str, шаг: str) -> str:
    мажор, минор, патч = (int(ч) for ч in версия.split("."))
    if шаг == "мажор":
        return f"{мажор + 1}.0.0"
    if шаг == "минор":
        return f"{мажор}.{минор + 1}.0"
    return f"{мажор}.{минор}.{патч + 1}"


def следующая(пакет: Path, сборка: Path, дано: dict, мажор: bool = False,
              удалённый: str = "") -> dict:
    """Номер следующего релиза и всё, чем он обоснован."""
    пакет, сборка = Path(пакет), Path(сборка)
    if not (пакет / ".git").is_dir():
        raise Отказ(f"пакет {пакет} — не репозиторий, считать нечего")
    тег = прошлый_тег(сборка, удалённый) if (сборка / ".git").is_dir() else ""
    голова = _гит("rev-parse", "--short", "HEAD", где=пакет).stdout.strip()

    if not тег:
        # Первый релиз не поднимают: начальная версия и есть номер.
        итог = dict(прошлая="", следующая=дано["начальная_версия"],
                    почему="первый релиз: тегов ещё нет")
        от = ""
    else:
        прошлая = тег[1:]
        от = хэш_пакета_релиза(сборка, тег)
        оговорка = ""
        if от and not _есть_коммит(пакет, от):
            оговорка = f"; коммита {от} в пакете нет — заметки за всю историю"
            от = ""
        elif not от:
            оговорка = "; заголовок прошлого релиза не разобран — заметки за всю историю"
        новые = добавленные_механизмы(пакет, от, дано["минор_если_добавлен"])
        шаг = "мажор" if мажор else ("минор" if новые else "патч")
        почему = {"мажор": "довод --мажор: релиз ломает существующую установку",
                  "минор": f"новых механизмов: {len(новые)} ({', '.join(новые[:3])})",
                  "патч": "новых механизмов нет — только правки"}[шаг]
        итог = dict(прошлая=прошлая, следующая=поднять(прошлая, шаг),
                    почему=почему + оговорка)

    if мажор and not тег:
        итог.update(следующая=поднять(дано["начальная_версия"], "мажор"),
                    почему="довод --мажор на первом релизе")
    все_заметки = заметки(пакет, от)
    потолок = int(дано.get("потолок_заметок", 0)) or len(все_заметки)
    итог.update(пакет=голова, от=от, коммитов=len(все_заметки),
                заметки=все_заметки[:потолок],
                снято=max(0, len(все_заметки) - потолок))
    return итог


ШАПКА = """# Журнал изменений

Все заметные изменения харнеса. Формат — [Keep a Changelog](https://keepachangelog.com/ru/1.1.0/),
номера версий — [SemVer](https://semver.org/lang/ru/): мажор ломает существующую
установку, минор добавляет возможность, патч чинит.

Каждая секция собрана машиной из заголовков коммитов пакета, из которого
собран релиз. Полная история — в этом же репозитории, `git log`.
"""


def секция(итог: dict, дата: str) -> str:
    """Одна секция журнала: версия, дата, чем собрано, что изменилось."""
    строки = [f"## [{итог['следующая']}] — {дата}", "",
              f"Собрано из пакета `{итог['пакет']}`. Изменений: {итог['коммитов']}.", ""]
    строки += [f"- {з}" for з in итог["заметки"]]
    if итог["снято"]:
        # Снятое кодом называется вслух: молча срезанный список неотличим от
        # полного, и «изменений 216» рядом с десятью строками выглядит ложью.
        строки.append(f"- …и ещё {итог['снято']} изменений — см. `git log` пакета")
    return "\n".join(строки) + "\n"


def _из_истории(сборка: Path) -> str:
    """Прежний журнал — из последнего коммита сборки, а не только с диска.

    Сборщик публичного дерева зовёт `rsync -a --delete`, и артефакты релиза
    (VERSION, CHANGELOG.md) лежат в сборке, но не в пакете — значит перед
    КАЖДОЙ публикацией они сносятся. Замер 12.09.2026: без этого после второго
    релиза в журнале оставалась одна секция, история версий пропадала.
    """
    готово = _гит("show", "HEAD:CHANGELOG.md", где=сборка)
    return готово.stdout if готово.returncode == 0 and готово.stdout.strip() else ШАПКА


def оформить(пакет: Path, сборка: Path, дано: dict, мажор: bool = False,
             дата: str = "", удалённый: str = "") -> dict:
    """Записать в сборку VERSION и секцию CHANGELOG.md. Коммит — не здесь.

    Повторный вызов с той же версией ничего не двоит: секция ищется по
    заголовку. Иначе упавший push и повтор публикации оставили бы в журнале
    две одинаковые секции.
    """
    сборка = Path(сборка)
    итог = следующая(пакет, сборка, дано, мажор=мажор, удалённый=удалённый)
    дата = дата or time.strftime("%Y-%m-%d")
    (сборка / "VERSION").write_text(итог["следующая"] + "\n", encoding="utf-8")

    журнал = сборка / "CHANGELOG.md"
    было = журнал.read_text(encoding="utf-8") if журнал.exists() else _из_истории(сборка)
    заголовок = f"## [{итог['следующая']}]"
    if заголовок not in было:
        # Новое сверху, под шапкой: человек читает журнал с последней версии.
        граница = было.find("\n## ")
        шапка, хвост = (было[:граница + 1], было[граница + 1:]) if граница >= 0 else (было, "")
        было = шапка.rstrip("\n") + "\n\n" + секция(итог, дата) + ("\n" + хвост if хвост else "")
    # Файл пишется ВСЕГДА, даже когда секция уже была: на диске его могло не
    # остаться вовсе (сборщик сносит всё, чего нет в пакете), и повторный
    # прогон уехал бы в публичную ветку без журнала.
    журнал.write_text(было, encoding="utf-8")
    return итог


def _selftest() -> int:
    проба = КОРЕНЬ / "scripts" / "test_versiya.py"
    if not проба.exists():
        print(f"[версия] пробы нет: {проба}")
        return 1
    готово = subprocess.run([sys.executable, str(проба)], timeout=300)
    return готово.returncode


def главная(argv: list) -> int:
    if "--selftest" in argv:
        return _selftest()

    def довод(имя, умолчание=None):
        return argv[argv.index(имя) + 1] if имя in argv else умолчание

    пакет = довод("--пакет")
    сборка = довод("--сборка")
    if not пакет or not сборка:
        print("нужны --пакет DIR и --сборка DIR", file=sys.stderr)
        return 1
    try:
        дано = данные(довод("--данные") or ДАННЫЕ_ПО_УМОЛЧАНИЮ)
        работа = оформить if "--оформить" in argv else следующая
        итог = работа(Path(пакет), Path(сборка), дано, мажор="--мажор" in argv,
                      удалённый=довод("--удалённый") or "")
    except Отказ as беда:
        print(f"ОТКАЗ: {беда}", file=sys.stderr)
        return 1
    print(json.dumps(итог, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(главная(sys.argv[1:]))
