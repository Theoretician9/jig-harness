#!/usr/bin/env python3
"""Проверка прибора «кто на порту»: он обязан назвать процесс, а не «занят».

Проба поднимает слушающий сокет СВОИМ процессом и на СВОЁМ порту: чужой
экземпляр на общем порту ответил бы вместо нас и покрасил пробу зелёным на
чужой работе (память: проба-поднимает-службу-на-своём-порту). Порт занят
кем-то — проба падает вслух, а не переезжает молча.

    python3 scripts/test_kto_na_portu.py
Код возврата: 0 — все пути прошли, 1 — есть упавший.
"""
from __future__ import annotations

import os
import socket
import subprocess
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
ПРИБОР = str(КОРЕНЬ / "scripts" / "kto-na-portu.py")
ПОРТ = 59187
путей = неудач = 0


def итог(имя: str, ждём, факт) -> None:
    global путей, неудач
    путей += 1
    if факт == ждём:
        print(f"ок  · {имя}")
    else:
        неудач += 1
        print(f"ПЛОХО · {имя}: ждали «{ждём}», вышло «{факт}»")


def позвать(порт: int):
    вышло = subprocess.run([sys.executable, ПРИБОР, str(порт)],
                           capture_output=True, text=True, timeout=60)
    return вышло.returncode, вышло.stdout.strip()


print("── свободный порт назван свободным ──")
код, текст = позвать(ПОРТ)
итог("свободный порт: код 1", 1, код)
итог("свободный порт: сказано словом", True, "свободен" in текст)

print("── БОЛЬНОЙ СЛУЧАЙ: порт занят, хозяина надо назвать ──")
# Ровно этот случай шаг установки печатал как «занят» и молчал о том, кто
# занял (ревью кода 13.09.2026, F-22).
гнездо = socket.socket()
try:
    гнездо.bind(("127.0.0.1", ПОРТ))
except OSError as беда:
    print(f"ПЛОХО · порт пробы {ПОРТ} занят посторонним ({беда}) — "
          "проба не играет на чужом процессе, чини порт")
    sys.exit(1)
гнездо.listen(1)
try:
    код, текст = позвать(ПОРТ)
    итог("занятый порт: код 0", 0, код)
    итог("назван PID нашего процесса", True, f"PID {os.getpid()}" in текст)
    итог("названа команда процесса", True, "python" in текст.lower())
    итог("назван пользователь", True, Path(f"/proc/{os.getpid()}").owner() in текст)
finally:
    гнездо.close()

print("── аргумент не числом: прибор не гадает ──")
вышло = subprocess.run([sys.executable, ПРИБОР, "восемь"],
                       capture_output=True, text=True, timeout=60)
итог("нечисловой порт: код 2", 2, вышло.returncode)

print(f"\nитого путей {путей}, неудач {неудач}")
sys.exit(1 if неудач else 0)
