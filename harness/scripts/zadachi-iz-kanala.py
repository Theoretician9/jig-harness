#!/usr/bin/env python3
"""Гейт: задача, сказанная владельцем в канал, доходит до карты разработки.

Владелец 11.09.2026: «Я периодически пишу тебе задачи в то время когда ты
выполняешь задачи, у тебя должны быть конкретная фиксация и конкретные рельсы,
вне зависимости сколько когда и что я тебе пишу, все должно быть зафиксировано
в нужных местах чтобы если что всегда иметь карту».

Улика: в очереди 940 сообщений, 170 из них с признаком работы, и связи между
сообщением и задачей карты НЕ БЫЛО ни одной — задача заводилась руками и
держалась памятью сессии. Ровно так 11.09 потерялось указание про автоприёмку:
владельцу пришлось повторить его вторым сообщением.

Устройство — то же, что у сторожа указаний (`ukazaniya.py`), и нарочно: приём
уже доказан. Сообщение с признаком работы обязано получить ИСХОД:
  • задача заведена  — в её карточке dev-map.yaml стоит `источник: inbox:<id>`;
  • это не задача    — `zadachi-iz-kanala.py --не-задача <id>` (спутник);
  • сделано сразу    — тот же спутник с пометкой (исход всё равно записан).

Запуск:
    python3 scripts/zadachi-iz-kanala.py              # гейт (ворота, pre-commit)
    python3 scripts/zadachi-iz-kanala.py --не-задача ID
    python3 scripts/zadachi-iz-kanala.py --архив      # разовый разбор всего архива
    python3 scripts/zadachi-iz-kanala.py --selftest
Код возврата: 0 — всё разобрано, 1 — есть неразобранное.
"""
from __future__ import annotations

import json
import pathlib
import re
import sys

# Слова, которыми владелец ДАЁТ РАБОТУ. Список узкий нарочно: ложная тревога
# стоит одной команды `--не-задача`, а потерянная задача стоит повтора от
# владельца и его недоверия к карте.
#
# Живут в ДАННЫХ (harness/config/очередь.yaml, ключ «слова_работы») — там же,
# где слова внимания, которые читает прибор очереди. Два списка в двух
# носителях разъезжаются молча: так разошлись формы команд приёмки, и цикл
# крутился впустую пять кругов. Значение ниже — умолчание для свежей
# установки, где файла данных ещё нет.
МАРКЕРЫ_ПО_УМОЛЧАНИЮ = ("надо", "нужно", "сделай", "добавь", "почини", "исправь",
                        "переделай", "реализуй", "хочу чтобы", "не работает",
                        "сломал", "должно быть", "должен быть", "займись",
                        "давай сделаем")


def маркеры(конфиг: pathlib.Path | str | None = None) -> tuple:
    """Слова работы из данных; нет файла или ключа — умолчание."""
    файл = pathlib.Path(конфиг) if конфиг else (
        pathlib.Path(__file__).resolve().parent.parent
        / "harness" / "config" / "очередь.yaml")
    try:
        import yaml
        свои = (yaml.safe_load(файл.read_text(encoding="utf-8")) or {}).get("слова_работы")
    except Exception:
        свои = None
    return tuple(свои) if свои else МАРКЕРЫ_ПО_УМОЛЧАНИЮ


МАРКЕРЫ = маркеры()

СПУТНИК = "память/.задачи-разобрано"
КАРТА = "dev-map.yaml"
ИСТОЧНИК = re.compile(r"inbox:([0-9.]+)")


def текст_сообщения(файл: pathlib.Path) -> str:
    """Текст владельца. Старая очередь хранила сырой апдейт Telegram —
    признак работы искался бы в служебных полях, а не в словах владельца."""
    сырое = файл.read_text(encoding="utf-8", errors="replace").strip()
    if not сырое.startswith("{"):
        return сырое
    try:
        апдейт = json.loads(сырое)
    except ValueError:
        return ""
    # ПОДПИСЬ К СНИМКУ — тоже слова владельца. Замер 12.09.2026: из 972
    # сообщений архива 68 пришли фотографией с подписью, и все они пролетали
    # мимо разбора — ни задачей, ни пометкой «не задача». Среди них
    # «Вот так сейчас выглядит карта в приложении, займись как все остальные
    # задачи закроешь»: прямое указание, которого гейт не видел.
    return str(апдейт.get("text") or апдейт.get("caption") or "").strip()


def рабочее(текст: str) -> bool:
    низ = текст.lower()
    return any(м in низ for м in МАРКЕРЫ)


def сообщения(обработано: pathlib.Path) -> list[tuple[float, str, pathlib.Path]]:
    файлы = sorted(обработано.glob("*.txt"), key=lambda ф: ф.stat().st_mtime)
    return [(ф.stat().st_mtime, ф.stem, ф) for ф in файлы]


def разобранные(корень: pathlib.Path) -> str:
    """Что считается получившим исход: карта (источник: inbox:<id>) и спутник."""
    куски = []
    карта = корень / КАРТА
    if карта.exists():
        куски.append(карта.read_text(encoding="utf-8"))
    спутник = корень / СПУТНИК
    if спутник.exists():
        куски.append(спутник.read_text(encoding="utf-8"))
    return "\n".join(куски)


def водораздел(курсор: pathlib.Path, все: list, разобрано: str) -> float:
    """С какого момента спрашивать. Первый запуск встаёт на последнее
    разобранное сообщение: требовать разбора 940 старых — гейт, который никто
    не сможет позеленить, а такой гейт отключают. Прошлое разбирается командой
    `--архив`, и это работа, а не условие коммита."""
    try:
        return float(курсор.read_text(encoding="utf-8").strip())
    except (OSError, ValueError):
        есть = [когда for когда, ид, _ in все if ид in разобрано]
        return max(есть) if есть else (все[-1][0] if все else 0.0)


def без_исхода(все: list, с_какого: float, разобрано: str) -> list[tuple[str, str]]:
    итог = []
    for когда, ид, файл in все:
        if когда <= с_какого or ид in разобрано:
            continue
        текст = текст_сообщения(файл)
        if текст and рабочее(текст):
            итог.append((ид, текст.replace("\n", " ")[:110]))
    return итог


def пометить(корень: pathlib.Path, ид: str, почему: str) -> int:
    спутник = корень / СПУТНИК
    было = спутник.read_text(encoding="utf-8") if спутник.exists() else ""
    if ид in было:
        print(f"{ид} уже помечен")
        return 0
    спутник.parent.mkdir(parents=True, exist_ok=True)
    спутник.write_text(f"{было}{ид} {почему}\n", encoding="utf-8")
    print(f"{ид}: исход записан — {почему}")
    return 0


def архив(корень: pathlib.Path, обработано: pathlib.Path) -> int:
    """Разовый разбор: всё, что похоже на работу и не имеет исхода."""
    все = сообщения(обработано)
    список = без_исхода(все, 0.0, разобранные(корень))
    print(f"сообщений в архиве: {len(все)} · без исхода с признаком работы: {len(список)}")
    for ид, кусок in список:
        print(f"  {ид}  {кусок}")
    return 0


def проверить(корень: pathlib.Path, обработано: pathlib.Path,
              курсор: pathlib.Path) -> int:
    все = сообщения(обработано)
    if not все:
        print("[задачи из канала] очередь пуста — сверять нечего")
        return 0
    разобрано = разобранные(корень)
    с_какого = водораздел(курсор, все, разобрано)
    висят = без_исхода(все, с_какого, разобрано)
    if not висят:
        # Автопочинка: разобрано всё — курсор едет вперёд сам, иначе гейт
        # каждый раз перечитывает то, по чему исход уже есть.
        курсор.parent.mkdir(parents=True, exist_ok=True)
        курсор.write_text(str(все[-1][0]), encoding="utf-8")
        print("[задачи из канала] у каждой задачи владельца есть исход")
        return 0
    print(f"\n[задачи из канала] БЕЗ ИСХОДА: {len(висят)} сообщени(й) с работой")
    for ид, кусок in висят[:10]:
        print(f"    {ид}  {кусок}")
    if len(висят) > 10:
        print(f"    … и ещё {len(висят) - 10}")
    print("\nИсход — одно из двух: завести задачу в dev-map.yaml с полем")
    print("`источник: inbox:<id>` в её карточке, либо, если работы в сообщении")
    print("нет, сказать это вслух: zadachi-iz-kanala.py --не-задача <id>.")
    print("Владелец 11.09.2026: «всё должно быть зафиксировано в нужных местах»")
    return 1


def _selftest(корень: pathlib.Path) -> int:
    import tempfile
    плохо = 0

    def проба(имя: str, ждём, вышло) -> None:
        nonlocal плохо
        if вышло == ждём:
            print(f"  ок    {имя}")
        else:
            print(f"  ПЛОХО {имя}: ждали {ждём}, вышло {вышло}")
            плохо = 1

    with tempfile.TemporaryDirectory() as врем:
        т = pathlib.Path(врем)
        (т / "обработано").mkdir()
        (т / "память").mkdir()
        обр = т / "обработано"
        import time
        def положить(ид: str, текст: str, сдвиг: float) -> None:
            ф = обр / f"{ид}.txt"
            ф.write_text(текст, encoding="utf-8")
            момент = time.time() + сдвиг
            import os
            os.utime(ф, (момент, момент))

        положить("1.0", "Надо добавить экран памяти", -300)
        положить("2.0", "да", -200)
        положить("3.0", '{"text": "нужно починить карту", "message_id": 5}', -100)
        (т / КАРТА).write_text("tasks:\n  - id: hr.проба\n    источник: inbox:1.0\n",
                               encoding="utf-8")
        курсор = т / "курсор"
        курсор.write_text("0", encoding="utf-8")

        # БОЛЬНОЙ СЛУЧАЙ: задача владельца не дошла до карты — красный.
        проба("БОЛЬНОЙ СЛУЧАЙ: задача без исхода красит гейт",
              1, проверить(т, обр, курсор))
        # Сырой апдейт Telegram разбирается: признак ищется в словах владельца.
        все = сообщения(обр)
        проба("старый формат очереди разобран (текст из JSON)",
              True, any(ид == "3.0" for ид, _ in без_исхода(все, 0.0, разобранные(т))))
        # Согласие задачей не считается.
        проба("«да» задачей не считается",
              False, any(ид == "2.0" for ид, _ in без_исхода(все, 0.0, разобранные(т))))
        # Задача с источником в карте исхода уже имеет.
        проба("сообщение с источником в карте не висит",
              False, any(ид == "1.0" for ид, _ in без_исхода(все, 0.0, разобранные(т))))
        # БОЛЬНОЙ СЛУЧАЙ 12.09.2026: снимок с подписью. Владелец присылает
        # задачи фотографиями, а разбор читал только поле «text» — 68 из 972
        # сообщений архива пролетали мимо гейта вовсе, среди них прямое
        # указание «займись как все остальные задачи закроешь».
        положить("4.0", '{"caption": "надо переделать экран карты", "photo": [1]}', -50)
        все = сообщения(обр)
        проба("БОЛЬНОЙ СЛУЧАЙ: подпись к снимку — тоже слова владельца",
              True, any(ид == "4.0" for ид, _ in без_исхода(все, 0.0, разобранные(т))))
        # Снимок без подписи разбирать нечего — и это не беда, а пустота.
        положить("5.0", '{"photo": [1], "message_id": 7}', -40)
        все = сообщения(обр)
        проба("снимок без подписи задачей не считается",
              False, any(ид == "5.0" for ид, _ in без_исхода(все, 0.0, разобранные(т))))
        # Пометка «не задача» закрывает исход.
        пометить(т, "3.0", "не-задача")
        пометить(т, "4.0", "не-задача")
        проба("пометка «не задача» закрывает исход",
              0, проверить(т, обр, курсор))
    if плохо:
        print("САМОТЕСТ ПРОВАЛЕН")
        return 1
    print("САМОТЕСТ ПРОЙДЕН: 7 путей, первым — больной случай")
    return 0


def main() -> int:
    корень = pathlib.Path(__file__).resolve().parent.parent
    конф = {}
    for путь in ("/etc/harness/install.conf",):
        try:
            for строка in pathlib.Path(путь).read_text(encoding="utf-8").splitlines():
                если = re.match(r'^\s*([A-Z_][A-Z0-9_]*)\s*=\s*"?([^"#]*)"?', строка)
                if если:
                    конф[если.group(1)] = если.group(2).strip()
        except OSError:
            pass
    лог = pathlib.Path(конф.get("LOG_DIR") or "/var/log/harness")
    обработано = лог / "inbox" / "обработано"
    курсор = лог / "задачи-из-канала.cursor"

    if "--selftest" in sys.argv:
        return _selftest(корень)
    if "--не-задача" in sys.argv:
        ид = sys.argv[sys.argv.index("--не-задача") + 1]
        return пометить(корень, ид, "не-задача")
    if "--сделано" in sys.argv:
        ид = sys.argv[sys.argv.index("--сделано") + 1]
        return пометить(корень, ид, "сделано-без-карточки")
    if "--архив" in sys.argv:
        return архив(корень, обработано)
    if not обработано.exists():
        print("[задачи из канала] очереди нет — сверять нечего")
        return 0
    return проверить(корень, обработано, курсор)


if __name__ == "__main__":
    sys.exit(main())
