#!/usr/bin/env python3
"""Слово владельца: единственный источник разрешения на необратимое.

Зачем библиотека. Дверей, исполняющих его слово, стало три: удаление файла в
защищённом каталоге (`protected-delete.py`), снос образа отката
(`guard_bash.py`) и снятие среды (`/var/www/<имя>/scripts/teardown.sh`). Один
класс действий обязан иметь один порог, поэтому распознавание живёт здесь, а
не копией в каждой двери.

НОСИТЕЛЬ — МАШИННЫЙ ЖУРНАЛ ДИСПЕТЧЕРА, а не файлы очереди (ревью кода
28.09.2026, C-1). Прежняя редакция читала `$LOG_DIR/inbox/*.txt`: в этих файлах
нет ни одного признака авторства, а каталог — рабочий каталог самого агента (он
же переносит файлы в `обработано/`), то есть проверяемый писал доказательство
своей правоты — [[a-trace-is-evidence-only-if-someone-else-wrote-it]]. Ревьюер
прогнал распознаватель по 1197 настоящим файлам: единственное совпадение
пришлось на ТЕКСТ БОТА внутри файла. Теперь читается `$LOG_DIR/inbox.jsonl` —
его строку пишет tg-dispatcher.sh на каждое входящее владельца, и в ней есть
`message_id` телеграма: поля нет — это не слово владельца.

ТРИ ИСХОДА, А НЕ ДВА:
  * запись        — разрешение найдено;
  * None          — журнал прочитан, разрешения в окне нет;
  * НетНосителя   — журнала нет, он нечитаем или битый. «Прочитать не смогли»
                    ≠ «слова нет»: вызывающая дверь обязана ОТКАЗАТЬ
                    ([[unreadable-source-turns-check-green]]).

ОДИН КЛЮЧ СТЕНДА ВМЕСТО ТРЁХ РУЧЕК (ревью кода 28.09.2026, C-2). Каталог
журнала и окно свежести берутся у МАШИНЫ (`config.корень_машины()` — мимо
HARNESS_HOME и HARNESS_INSTALL_CONF), а не у вызывающего. Подмена разрешена
только при `HARNESS_OWNER_WORD_STEND=1`; без ключа любая подмена — `НетНосителя`
с названной причиной. Боевой путь ключа не выставляет.

Что считается разрешением: ГЛАГОЛ удаления И названный ПРЕДМЕТ в одном
сообщении, не старше окна свежести. Голого «да» мало: оно могло относиться к
выкату — ровно та дыра, которую закрыли у ворот выката 11.09.2026. Отказ
(«не», «погоди», «позже») в любом месте сообщения отменяет разрешение целиком.
"""
from __future__ import annotations

import datetime as _dt
import json
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import config as конф                                      # noqa: E402

# Имя журнала — ДАННЫЕ обеих сторон: его пишет tg-dispatcher.sh той же строкой.
ЖУРНАЛ_ВХОДЯЩИХ = "inbox.jsonl"
КЛЮЧ_СТЕНДА = "HARNESS_OWNER_WORD_STEND"
ОКНО_ПО_УМОЛЧАНИЮ = 60

# Предмет — то, что владелец МОЖЕТ назвать своими словами, а не имя ключа в
# коде. 28.09.2026 его «Удали дамп ктэка из копии» дверь не приняла: в словаре
# не было ни дампа, ни копии, и его прямое слово осталось неисполненным. То же
# 10.10.2026: на просьбу убрать ключ чужой подписки он ответил «Удали ключ» —
# предмет назван прямо, а в словаре стоял только «токен», его синоним.
ГЛАГОЛ = re.compile(r"удал|снеси|убер|вычист|очист|мусор")
ПРЕДМЕТ = re.compile(r"секрет|токен|ключ|снимок|файл|env|bak|мусор|дамп|копи|образ|том\b|сервер")
ОТКАЗ = re.compile(r"\b(не|нет|стоп|погоди|подожди|позже|рано)\b")

# РАЗРЕШЕНИЕ НА ЧТЕНИЕ — СВОИ СЛОВА, а не слова удаления.
#
# Живой случай 29.09.2026: дверь к учёту заказчика взяла проверку у двери
# удаления, и открыть её было НЕЛЬЗЯ ничем. Владелец выбрал вариант («2»),
# потом написал «читай статусы и типы цен» — оба раза сторож отменил чтение,
# потому что искал в его словах «удали» и «токен». Разрешение на чтение звучит
# иначе, и один класс действий не может брать словарь другого: читать — не
# удалять ([[a-guard-without-a-legal-door]]).
# Словари УЖЕ, чем у удаления, и нарочно. Владелец говорит про товары и заказы
# каждый день; «да» и «давай» в глаголах плюс «товар» в предметах означали бы, что
# обычный разговор о каталоге открывает дверь к живому учёту. Предмет здесь — сам
# УЧЁТ и его справочники, а не то, что в них лежит.
ГЛАГОЛ_ЧТЕНИЯ = re.compile(r"читай|прочит|смотр|посмотр|глян|сними|снимай|разреш|можно")
ПРЕДМЕТ_ЧТЕНИЯ = re.compile(
    r"склад|учёт|учет|статус|тип цен|справочник|остат")


class НетНосителя(Exception):
    """Журнал входящих прочитать не удалось — дверь обязана ОТКАЗАТЬ.

    Отдельный исход от «разрешения нет»: молчащий носитель и молчащий владелец
    выглядят одинаково только для того, кто их не различает.
    """


def стенд() -> bool:
    """Идёт ли проба на своём стенде (единственный ключ подмены)."""
    return os.environ.get(КЛЮЧ_СТЕНДА, "") == "1"


def _машинный_конфиг(имя: str) -> dict:
    """Значения из конфига МАШИНЫ, мимо окружения вызывающего.

    `корень_машины()` заведён ровно для тех, кто решает про право: подставленная
    переменная увела бы «где лежит слово владельца» в чужой каталог (ревью
    безопасности 13.09.2026, F-sec-01).
    """
    return конф.из_файла(f"{конф.корень_машины()}/{имя}")


def боевой_каталог_логов() -> Path | None:
    """LOG_DIR машины. None — паспорт установки прочитать не удалось."""
    значения = _машинный_конфиг("install.conf")
    if not значения:
        return None
    значение = (значения.get("LOG_DIR") or "").strip()
    return Path(значение) if значение else Path(конф.корень_машины()) / "log"


def окно_свежести() -> int:
    """Окно свежести в минутах — ТОЛЬКО из harness.conf машины.

    Окружение слушается лишь на стенде: `CONFIRM_MAX_AGE_MIN=999999` в
    окружении вызывающего открывало дверь словом двухлетней давности.
    """
    if стенд():
        из_окружения = (os.environ.get("CONFIRM_MAX_AGE_MIN")
                        or os.environ.get("SECRET_DELETE_FRESH_MIN") or "").strip()
        if из_окружения.isdigit():
            return int(из_окружения)
    значение = (_машинный_конфиг("harness.conf").get("CONFIRM_MAX_AGE_MIN") or "").strip()
    return int(значение) if значение.isdigit() else ОКНО_ПО_УМОЛЧАНИЮ


def _сверить_со_стендом(окно_мин: int, каталог_логов: Path) -> Path:
    """Каталог журнала для чтения — или НетНосителя с названной причиной."""
    каталог = Path(каталог_логов)
    if стенд():
        return каталог
    боевой = боевой_каталог_логов()
    if боевой is None:
        raise НетНосителя(
            f"паспорт установки {конф.корень_машины()}/install.conf не прочитан — "
            f"где лежит журнал входящих владельца, неизвестно; без ключа "
            f"{КЛЮЧ_СТЕНДА}=1 подменять его каталог нельзя")
    if каталог.resolve() != боевой.resolve():
        raise НетНосителя(
            f"каталог журнала подменён: спрашивают «{каталог}», у машины "
            f"«{боевой}». Подмена разрешена только ключом стенда "
            f"{КЛЮЧ_СТЕНДА}=1, и боевой путь его не выставляет")
    боевое_окно = окно_свежести()
    if int(окно_мин) != боевое_окно:
        raise НетНосителя(
            f"окно свежести подменено: спрашивают {окно_мин} мин, у машины "
            f"{боевое_окно} мин (CONFIRM_MAX_AGE_MIN в harness.conf). Подмена "
            f"разрешена только ключом стенда {КЛЮЧ_СТЕНДА}=1")
    return каталог


def _время(значение: str) -> float | None:
    """`date -Is` → секунды. None — разобрать не удалось."""
    try:
        return _dt.datetime.fromisoformat(str(значение)).timestamp()
    except (TypeError, ValueError):
        return None


def слова_владельца(окно_мин: int, каталог_логов: Path) -> list[dict]:
    """Его сообщения за последние N минут — из журнала ДИСПЕТЧЕРА.

    Журнал пишет не агент: строку кладёт tg-dispatcher.sh там же, где кладёт
    файл в inbox. Запись без `message_id` словом владельца не считается —
    поле проставляет телеграм, и его отсутствие значит, что строку написал
    кто-то другой.

    Исключение НетНосителя — журнала нет, он нечитаем или битый.
    """
    каталог = _сверить_со_стендом(окно_мин, каталог_логов)
    журнал = каталог / ЖУРНАЛ_ВХОДЯЩИХ
    try:
        текст = журнал.read_text(encoding="utf-8", errors="replace")
    except OSError as беда:
        raise НетНосителя(f"журнал входящих {журнал} не прочитан: {беда}") from беда

    найдено: list[dict] = []
    порог = _dt.datetime.now().timestamp() - int(окно_мин) * 60
    for номер, строка in enumerate(текст.splitlines(), 1):
        строка = строка.strip()
        if not строка:
            continue
        try:
            запись = json.loads(строка)
        except ValueError as беда:
            raise НетНосителя(
                f"журнал входящих {журнал} битый: строка {номер} не разобрана "
                f"({беда}); «прочитать не смогли» — это не «слова владельца нет»")
        if not isinstance(запись, dict):
            raise НетНосителя(
                f"журнал входящих {журнал} битый: строка {номер} не запись")
        # Признак авторства обязателен: его ставит телеграм, а не агент.
        if not str(запись.get("message_id") or "").strip():
            continue
        когда = _время(запись.get("ts"))
        слова = str(запись.get("текст") or запись.get("text") or "").strip()
        if когда is None or not слова or когда < порог:
            continue
        найдено.append({"когда": когда, "текст": слова,
                        "message_id": str(запись["message_id"]),
                        "файл": f"{ЖУРНАЛ_ВХОДЯЩИХ}:message_id={запись['message_id']}"})
    найдено.sort(key=lambda з: з["когда"])
    return найдено


def это_разрешение(текст: str) -> bool:
    """Слова владельца означают «удали это»?"""
    return _это_слово(текст, ГЛАГОЛ, ПРЕДМЕТ)


def это_разрешение_чтения(текст: str) -> bool:
    """Слова владельца означают «читай это»?

    Отдельный словарь, а не расширение прежнего: «удали токен» не должно
    открывать дверь чтения учёта, а «читай статусы» — дверь удаления секрета.
    """
    return _это_слово(текст, ГЛАГОЛ_ЧТЕНИЯ, ПРЕДМЕТ_ЧТЕНИЯ)


def _это_слово(текст: str, глагол: re.Pattern, предмет: re.Pattern) -> bool:
    """Общее правило: есть действие, есть предмет, и нет отказа рядом."""
    строка = " ".join((текст or "").lower().split())
    if not строка:
        return False
    if ОТКАЗ.search(f" {строка} ") and not re.search(r"если.*уверен", строка):
        return False
    return bool(глагол.search(строка) and предмет.search(строка))


def разрешение(окно_мин: int, каталог_логов: Path, признак=это_разрешение) -> dict | None:
    """Самое свежее его сообщение, означающее разрешение, — или None.

    `признак` — КАКОЕ разрешение искать: удаления (по умолчанию) или чтения.
    Дверь называет его сама: словарь разрешения зависит от действия, и дверь,
    взявшая чужой словарь, не открывается ни на что (живой случай 29.09.2026).

    Исключение НетНосителя пробрасывается наверх нарочно: дверь, поймавшая его,
    обязана отказать, а не считать, что владелец промолчал.
    """
    for запись in reversed(слова_владельца(окно_мин, каталог_логов)):
        if признак(запись["текст"]):
            return запись
    return None


# ── Самотест правила о слове владельца ──────────────────────────────────────
#
# ЗАЧЕМ ОН ЗДЕСЬ. Правило «разрешение = глагол И предмет, и отказ его снимает»
# переехало в эту библиотеку из `protected-delete.py` — а проба правила осталась
# там, где правила больше нет. Замер 13.10.2026 (полные ворота): две мутации
# инварианта И-1 не вставали вовсе, потому что их текст искали в файле двери.
# Проба живёт с ПРАВИЛОМ, иначе дверь зелена, а правило не охраняет ничего.
def _самотест() -> int:
    """Больные случаи первыми: отказ рядом и голое согласие."""
    неудач = 0

    def проба(имя: str, вышло, ждём) -> None:
        nonlocal неудач
        if вышло == ждём:
            print(f"  ок    {имя}")
        else:
            неудач += 1
            print(f"  ПЛОХО {имя}: вышло {вышло!r}, ждали {ждём!r}")

    # БОЛЬНОЙ СЛУЧАЙ: отказ в сообщении СНИМАЕТ разрешение. Без этого «не
    # удаляй секреты» открыло бы дверь удаления секретов.
    проба("«не удаляй секреты» — не разрешение", это_разрешение("не удаляй секреты"), False)
    проба("«стоп, не трогай ключи» — не разрешение",
          это_разрешение("стоп, не трогай ключи"), False)
    # БОЛЬНОЙ СЛУЧАЙ: голое согласие. Оно могло относиться к выкату — ровно та
    # дыра, которую закрыли у ворот выката 11.09.2026.
    проба("голое «да» — не разрешение", это_разрешение("да"), False)
    проба("«давай» — не разрешение", это_разрешение("давай"), False)
    # Глагол без предмета и предмет без глагола — тоже не разрешение.
    проба("«удали» без предмета — не разрешение", это_разрешение("удали"), False)
    проба("«секреты» без глагола — не разрешение", это_разрешение("секреты"), False)
    # Законное разрешение.
    проба("«удали старые секреты» — разрешение",
          это_разрешение("удали старые секреты"), True)
    # Оговорка «если уверен» отказом НЕ считается: владелец разрешает с условием.
    проба("«удали копии, если уверен» — разрешение",
          это_разрешение("удали копии, если уверен"), True)
    # Два словаря не подменяют друг друга: слово об удалении не открывает
    # дверь чтения, слово о чтении — дверь удаления.
    проба("«удали токен» не открывает дверь ЧТЕНИЯ",
          это_разрешение_чтения("удали токен"), False)
    проба("«посмотри остатки склада» не открывает дверь УДАЛЕНИЯ",
          это_разрешение("посмотри остатки склада"), False)
    проба("«посмотри остатки склада» открывает дверь чтения",
          это_разрешение_чтения("посмотри остатки склада"), True)
    # Пустое и None — не разрешение (дверь зовут и так).
    проба("пустая строка — не разрешение", это_разрешение(""), False)

    print("SELFTEST: " + ("зелёный (12 путей, больные первыми)" if неудач == 0
                          else f"КРАСНЫЙ, неудач {неудач}"))
    return 1 if неудач else 0


if __name__ == "__main__":
    import sys as _sys
    if "--selftest" in _sys.argv:
        raise SystemExit(_самотест())
    print("owner_word.py — библиотека правила о слове владельца; "
          "проверка: python3 scripts/lib/owner_word.py --selftest")
