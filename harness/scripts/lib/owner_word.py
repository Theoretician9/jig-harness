class НетНосителя(Exception):
    """Журнал входящих прочитать не удалось — дверь обязана ОТКАЗАТЬ.

    Отдельный исход от «разрешения нет»: молчащий носитель и молчащий владелец
    выглядят одинаково только для того, кто их не различает.
    """


@dataclasses.dataclass(frozen=True)
class Носитель:
    """Где лежит слово владельца и чем его судят: всё, что судья иначе взял бы у вызывающего.

    У машины его строит `носитель()`; проба на своём стенде строит свой и отдаёт судье
    аргументом. `граница` — до какого каталога вверх проверяются родители папки (проверка
    владения подключается позже, пока поле только хранится). `срок_кнопки_мин` None — срок
    общий машины. `ручки` — harness.conf, по которому дверь решает, нужен ли владелец.
    """
    папка: Path
    uid: int | None
    паспорт: dict
    граница: Path
    окно_мин: int
    срок_кнопки_мин: int | None
    ручки: dict = dataclasses.field(default_factory=dict)


# Полная карта uid: процесс в своём пользовательском пространстве имён мог бы подложить
# свой /etc/harness (unshare -rm + mount --bind) и судить по чужому паспорту.
ПОЛНАЯ_КАРТА_UID = "0 0 4294967295"


def _сверить_пространство_имён() -> None:
    try:
        карта = " ".join(Path("/proc/self/uid_map").read_text(encoding="utf-8").split())
    except OSError as беда:
        raise НетНосителя(f"карта uid процесса не прочитана: {беда}") from беда
    if карта != ПОЛНАЯ_КАРТА_UID:
        raise НетНосителя(
            f"процесс в чужом пространстве имён пользователей (uid_map «{карта}»): паспорт "
            f"машины в нём мог быть подменён, слову владельца верить нельзя")


def носитель() -> Носитель:
    """Носитель МАШИНЫ: папка — LOG_DIR её паспорта, граница — корень, окно и срок — её харнес-конфиг.

    Окружение не слушает ни при каком ключе. Звать только внутри суда, не на уровне
    модуля: беда носителя у сторожа команд на импорте была бы тихим пропуском всего.
    """
    _сверить_пространство_имён()
    паспорт = _машинный_конфиг("install.conf")
    папка = боевой_каталог_логов()
    if папка is None:
        raise НетНосителя(
            f"паспорт установки {конф.корень_машины()}/install.conf не прочитан — "
            f"где лежит журнал входящих владельца, неизвестно")
    return Носитель(папка=папка, uid=None, паспорт=паспорт, граница=Path("/"),
                    окно_мин=окно_свежести(), срок_кнопки_мин=_срок_машины(),
                    ручки=_машинный_конфиг("harness.conf"))


def _взять(заданный: Носитель | None) -> Носитель:
    """Носитель судьи: переданный пробой или машины."""
    return заданный if заданный is not None else носитель()


def _машинный_конфиг(имя: str) -> dict:
    """Значения из конфига МАШИНЫ, мимо окружения вызывающего.

    `корень_машины()` заведён ровно для тех, кто решает про право: подставленная
    переменная увела бы «где лежит слово владельца» в чужой каталог (ревью
    безопасности 13.09.2026, F-sec-01).
    """
    return конф.из_файла(f"{конф.корень_машины()}/{имя}")


def конфиг_права(имя: str, носитель: Носитель | None = None) -> dict:
    """Конфиг, по которому судят право: из носителя — install.conf это его паспорт, harness.conf его ручки.

    Ключи `*_NEEDS_OWNER`, `DEPLOY_CONSENT_STANDING`, `AUTONOMY` открывают дверь, и
    `HARNESS_CONF=/tmp/c ./scripts/deploy.sh` не вправе их подменять.
    """
    держатель = _взять(носитель)
    return держатель.паспорт if имя == "install.conf" else держатель.ручки


def боевой_каталог_логов() -> Path | None:
    """LOG_DIR машины. None — паспорт установки прочитать не удалось."""
    значения = _машинный_конфиг("install.conf")
    if not значения:
        return None
    значение = (значения.get("LOG_DIR") or "").strip()
    return Path(значение) if значение else Path(конф.корень_машины()) / "log"


def окно_свежести() -> int:
    """Окно свежести в минутах — ТОЛЬКО из harness.conf машины.

    Окружение не слушается: `CONFIRM_MAX_AGE_MIN=999999` в окружении
    вызывающего открывало дверь словом двухлетней давности.
    """
    значение = (_машинный_конфиг("harness.conf").get("CONFIRM_MAX_AGE_MIN") or "").strip()
    return int(значение) if значение.isdigit() else ОКНО_ПО_УМОЛЧАНИЮ


def _время(значение: str) -> float | None:
    """`date -Is` → секунды. None — разобрать не удалось."""
    try:
        return _dt.datetime.fromisoformat(str(значение)).timestamp()
    except (TypeError, ValueError):
        return None


def слова_владельца(носитель: Носитель | None = None) -> list[dict]:
    """Его сообщения за окно свежести носителя — из журнала ДИСПЕТЧЕРА.

    Журнал пишет не агент: строку кладёт tg-dispatcher.sh там же, где кладёт
    файл в inbox. Запись без `message_id` словом владельца не считается —
    поле проставляет телеграм, и его отсутствие значит, что строку написал
    кто-то другой.

    Исключение НетНосителя — журнала нет, он нечитаем или битый.
    """
    держатель = _взять(носитель)
    return _слова_с(держатель.папка, _dt.datetime.now().timestamp() - int(держатель.окно_мин) * 60)


def слова_владельца_с(момент: float, носитель: Носитель | None = None) -> list[dict]:
    """Его сообщения, сказанные не раньше момента (секунды эпохи), без окна свежести.

    Отзыв читается от нажатия «Да»: окно в 60 минут не прочло бы отзыв к «Да» старше часа.
    """
    return _слова_с(_взять(носитель).папка, момент)


def _слова_с(каталог: Path, порог: float) -> list[dict]:
    журнал = каталог / ЖУРНАЛ_ВХОДЯЩИХ
    try:
        текст = журнал.read_text(encoding="utf-8", errors="replace")
    except OSError as беда:
        raise НетНосителя(f"журнал входящих {журнал} не прочитан: {беда}") from беда

    найдено: list[dict] = []
    for номер, строка in enumerate(текст.splitlines(), 1):
        строка = строка.strip()
        if not строка:
            continue
        try:
            запись = json.loads(строка)
        except ValueError as беда:
            raise НетНосителя(
                f"журнал входящих {журнал} битый: строка {номер} не разобрана "
                f"({беда}); «прочитать не смогли» — это не «слова владельца нет»")
        if not isinstance(запись, dict):
            raise НетНосителя(
                f"журнал входящих {журнал} битый: строка {номер} не запись")
        # Признак авторства обязателен: его ставит телеграм, а не агент.
        if not str(запись.get("message_id") or "").strip():
            continue
        когда = _время(запись.get("ts"))
        слова = str(запись.get("текст") or запись.get("text") or "").strip()
        if когда is None or not слова or когда < порог:
            continue
        найдено.append({"когда": когда, "текст": слова,
                        "message_id": str(запись["message_id"]),
                        "файл": f"{ЖУРНАЛ_ВХОДЯЩИХ}:message_id={запись['message_id']}"})
    найдено.sort(key=lambda з: з["когда"])
    return найдено


def _срок_машины() -> int:
    значение = (_машинный_конфиг("harness.conf").get("CONSENT_BUTTON_TTL_MIN") or "").strip()
    return int(значение) if значение.isdigit() else СРОК_КНОПКИ_ПО_УМОЛЧАНИЮ


def срок_кнопки_мин(вид: str | None = None, носитель: Носитель | None = None) -> int:
    """Срок кнопки согласия: у вида из СРОК_ВИДА_МИН — он, иначе общий носителя.

    Общий — у носителя (у машины — из harness.conf), окружение не слушается. Без носителя
    общий срок читается у машины прямо: диспетчер каналa судит им нажатие и носителя не строит.
    Своя ручка, а не окно слова: слово живёт час, а нажатие привязано к одному предмету и
    должно протухать быстро.
    """
    if вид in СРОК_ВИДА_МИН:
        ручки = носитель.ручки if носитель is not None else _машинный_конфиг("harness.conf")
        значение = str(ручки.get(КЛЮЧ_СРОКА_ВИДА.get(вид, ""), "")).strip()
        return int(значение) if значение.isdigit() else СРОК_ВИДА_МИН[вид]
    if носитель is not None and носитель.срок_кнопки_мин is not None:
        return int(носитель.срок_кнопки_мин)
    return _срок_машины()


def _строки_журнала(журнал: Path, что: str) -> list[dict]:
    """Записи jsonl-журнала. Нет файла — пусто; нечитаемое или битое — НетНосителя."""
    try:
        текст = журнал.read_text(encoding="utf-8")
    except FileNotFoundError:
        return []
    except OSError as беда:
        raise НетНосителя(f"{что} {журнал} не прочитан: {беда}") from беда
    записи = []
    for номер, строка in enumerate(текст.splitlines(), 1):
        if not строка.strip():
            continue
        try:
            запись = json.loads(строка)
        except ValueError as беда:
            raise НетНосителя(
                f"{что} {журнал} битый: строка {номер} не разобрана ({беда})") from беда
        if not isinstance(запись, dict):
            raise НетНосителя(f"{что} {журнал} битый: строка {номер} не запись")
        записи.append(запись)
    return записи


def плоская_запись(строка: dict) -> dict | None:
    """Конверт emit → прежняя плоская запись {ts, событие, nonce, цель, …}; не конверт — None.

    ts берётся из конверта (время записи писателем), одноимённое поле data его не
    перекрывает.
    """
    событие = СОБЫТИЯ_СОГЛАСИЯ.get(строка.get("event"))
    данные = строка.get("data")
    if строка.get("v") != 1 or событие is None or not isinstance(данные, dict):
        return None
    return {**данные, "ts": строка.get("ts"), "событие": событие}


def _решения_кнопок(журнал: Path) -> list[dict]:
    """Решения «да»/«нет». Строка не по форме конверта — НетНосителя: молчаливый пропуск
    не гасил бы «нет», то есть ошибка читателя открывала бы дверь."""
    решения = []
    for строка in _строки_журнала(журнал, "журнал кнопок"):
        запись = плоская_запись(строка)
        if запись is None:
            raise НетНосителя(f"журнал кнопок {журнал} битый: строка не конверт согласия")
        if запись["событие"] in ("да", "нет"):
            решения.append(запись)
    return решения


def _время_следа(каталог: Path, путь: str) -> list[float]:
    """Времена удалений ЭТОГО пути из следа protected-delete.py.

    Непонятная дата у строки этого пути — НетНосителя, а не пропуск: пропущенная
    строка не гасит согласие, то есть ошибка читателя открывала бы дверь.
    """
    журнал = каталог / ЖУРНАЛ_УДАЛЕНИЙ
    времена = []
    for запись in _строки_журнала(журнал, "след удалений"):
        if запись.get("файл") != путь:
            continue
        когда = _время(запись.get("ts"))
        if когда is None:
            raise НетНосителя(f"след удалений {журнал} битый: у удаления {путь} нет читаемого ts")
        времена.append(когда)
    return времена


def _погашено_удалением(каталог: Path, цель: str, когда: float) -> bool:
    return any(удалено >= когда for удалено in _время_следа(каталог, цель))


def _погашено_предметом(каталог: Path, цель: str, когда: float) -> bool:
    # Пуш и публикация: прошли — вершина удалённого стала другой, предмет уже
    # другой; упали — тот же предмет открывает повтор в пределах срока.
    # Спека: одобрение — не действие, его записывают, а не тратят.
    return False


def _погашено_выкатом(каталог: Path, цель: str, когда: float) -> bool:
    """Выкат этого sha в этом дереве начат (конверт журнала выкатов, data.цель = «sha дерево») не раньше «Да».

    Упавший после записи выкат просит нового нажатия: «одно да — одно действие».
    Нечитаемая строка — НетНосителя, а не пропуск: пропущенная строка не гасила бы «Да».
    """
    журнал = каталог / ЖУРНАЛ_ВЫКАТОВ
    for строка in _строки_журнала(журнал, "журнал выкатов"):
        данные = строка.get("data")
        if строка.get("v") != 1 or строка.get("event") != "deploy.release" or not isinstance(данные, dict):
            raise НетНосителя(f"журнал выкатов {журнал} битый: строка не конверт выката")
        if данные.get("цель") != цель:
            continue
        начат = _время(строка.get("ts"))
        if начат is None:
            raise НетНосителя(f"журнал выкатов {журнал} битый: у выката нет читаемого ts")
        if начат >= когда:
            return True
    return False


def _погашено_сносом(каталог: Path, цель: str, когда: float) -> bool:
    """База с этим именем снесена (след drop-database.sh, поле «база») не раньше «Да».

    Нечитаемая строка этой базы — НетНосителя: пропущенная не гасила бы «Да».
    """
    журнал = каталог / ЖУРНАЛ_СНОСОВ
    for запись in _строки_журнала(журнал, "след сносов"):
        if запись.get("база") != цель:
            continue
        снесена = _время(запись.get("ts"))
        if снесена is None:
            raise НетНосителя(f"след сносов {журнал} битый: у сноса {цель} нет читаемого ts")
        if снесена >= когда:
            return True
    return False


def _погашено_записью_слоя(каталог: Path, цель: str, когда: float) -> bool:
    """Поле «поле=значение» записано дверью слоя человека (состояние «да») не раньше нажатия.

    Нечитаемая строка — НетНосителя: пропущенная не гасила бы «Да».
    """
    журнал = каталог / ЖУРНАЛ_СЛОЯ_ЧЕЛОВЕКА
    for строка in _строки_журнала(журнал, "журнал слоя человека"):
        данные = строка.get("data")
        if not isinstance(данные, dict) or данные.get("состояние") != "да":
            continue
        if f"{данные.get('поле')}={данные.get('значение')}" != цель:
            continue
        записано = _время(строка.get("ts"))
        if записано is None:
            raise НетНосителя(f"журнал слоя человека {журнал} битый: у записи нет читаемого ts")
        if записано >= когда:
            return True
    return False


# Погашение «Да» по виду: что считается фактом, что действие уже состоялось.
# Перепись гасится предметом: после неё вершина и ссылки удалённого другие.
ПОГАШЕНИЕ = {"удаление": _погашено_удалением, "пуш": _погашено_предметом,
             "выкат": _погашено_выкатом, "публикация": _погашено_предметом,
             "спека": _погашено_предметом, "снос-базы": _погашено_сносом,
             "перепись": _погашено_предметом, "слой-человека": _погашено_записью_слоя}


def _id_владельца(держатель: Носитель) -> str:
    """id владельца — TG_CHAT_ID паспорта носителя (у машины — тот же, по которому диспетчер судит нажатие)."""
    return str(держатель.паспорт.get("TG_CHAT_ID") or "").strip()


def _времена_просьб(каталог: Path, вид: str, цель: str) -> list[float]:
    """Времена просьб ask-consent на ЭТУ дверь. Нет файла — пусто (парной просьбы нет, «Да» не засчитается)."""
    журнал = каталог / ЖУРНАЛ_ЗАПРОСОВ
    времена = []
    for строка in _строки_журнала(журнал, "журнал просьб"):
        запись = плоская_запись(строка)
        if запись is None or запись["событие"] != "запрос":
            continue
        if запись.get("вид") != вид or запись.get("цель") != цель:
            continue
        когда = _время(запись.get("ts"))
        if когда is not None:
            времена.append(когда)
    return времена


def _да_подлинное(запись: dict, когда: float, владелец: str, просьбы: list[float]) -> bool:
    """«Да» засчитывается, только если его нажал владелец (from_id) и не позже него была просьба этой двери.

    Журнал кнопок сессия могла бы дописать руками; id отправителя ставит диспетчер из ответа
    Telegram, просьбу пишет ask-consent. Запись без id (старая) не засчитывается — fail-closed.
    """
    отправитель = str(запись.get("from_id") or "").strip()
    if not владелец or отправитель != владелец:
        return False
    # Метки обоих журналов — до секунды: просьба, «отправлено» и нажатие бывают в одной
    # секунде, а «просьба раньше кнопки» и так держит диспетчер (нет просьбы — нет кнопки).
    return any(просьба <= когда for просьба in просьбы)


def последнее_решение(вид: str, цель: str, носитель: Носитель | None = None) -> dict | None:
    """Последнее нажатие «Да»/«Нет» владельца об этом виде и этой цели — без срока.

    «Нет» не стареет: по нему закрывается более старое текстовое «да». В записи
    добавлено «когда» — секунды эпохи. НетНосителя — журнал нечитаем или битый.
    """
    держатель = _взять(носитель)
    каталог = держатель.папка
    журнал = каталог / ЖУРНАЛ_КНОПОК
    последнее = None
    просьбы = _времена_просьб(каталог, вид, цель)
    владелец = _id_владельца(держатель)
    for запись in _решения_кнопок(журнал):
        if запись.get("вид", ВИД_ПО_УМОЛЧАНИЮ) != вид or запись.get("цель") != цель:
            continue
        когда = _время(запись.get("ts"))
        if когда is None:
            raise НетНосителя(f"журнал кнопок {журнал} битый: у решения нет читаемого ts")
        if запись["событие"] == "да" and not _да_подлинное(запись, когда, владелец, просьбы):
            continue
        if последнее is None or когда >= последнее["когда"]:
            последнее = {**запись, "когда": когда}
    return последнее


def последнее_нет(вид: str, начало_цели: str = "", носитель: Носитель | None = None) -> float | None:
    """Когда владелец в последний раз нажал «Нет» на ЛЮБОЙ предмет этого вида, иначе None.

    Не по предмету: предмет выката и публикации — sha, и обычный новый коммит
    снял бы «Нет», а более старое текстовое «да» открыло бы дверь. Для вида с
    общей частью цели (спека: «<id> <хэш>») начало_цели сужает до неё.
    НетНосителя — журнал нечитаем или битый.
    """
    журнал = _взять(носитель).папка / ЖУРНАЛ_КНОПОК
    последнее = None
    for запись in _решения_кнопок(журнал):
        if (запись.get("вид", ВИД_ПО_УМОЛЧАНИЮ) != вид or запись["событие"] != "нет"
                or not str(запись.get("цель")).startswith(начало_цели)):
            continue
        когда = _время(запись.get("ts"))
        if когда is None:
            raise НетНосителя(f"журнал кнопок {журнал} битый: у решения нет читаемого ts")
        последнее = когда if последнее is None else max(последнее, когда)
    return последнее


def _слова_публикации() -> str:
    """Слова про публикацию в речи владельца; имя публичного удалённого — данные установки.

    Читается при загрузке модуля, поэтому у машины прямо, а не через носитель().
    """
    свои = ["публик", "публичн", "publish", "опубликов", "витрин", "stable", "релиз", "наружу"]
    удалённый = (_машинный_конфиг("harness.conf").get("PUBLIC_REMOTE") or "").strip().lower()
    # Имя короче трёх знаков в предмет не берём: однобуквенное совпало бы с половиной слов его речи.
    if len(удалённый) >= 3:
        свои.append(re.escape(удалённый))
    return "|".join(свои)


def _слова_переписи() -> str:
    удалённый = (_машинный_конфиг("harness.conf").get("PUBLIC_REMOTE") or "").strip().lower()
    return "истори|перепи[сш]" + (f"|{re.escape(удалённый)}" if len(удалённый) >= 3 else "")


# Предмет отзыва по виду: о чём должно быть сказано рядом с отказом, чтобы «Да» кнопкой закрылось.
ПРЕДМЕТ_ОТЗЫВА = {"выкат": re.compile(r"выкат|деплой|deploy"),
                  "пуш": формы.ПРЕДМЕТ_ОТПРАВКИ,
                  "публикация": re.compile(_слова_публикации()),
                  "перепись": re.compile(_слова_переписи()),
                  "снос-базы": re.compile(r"баз|дроп|drop"),
                  "удаление": ПРЕДМЕТ}
ОТМЕНА_СЛОВОМ = re.compile(r"(?<!\w)отмен\w*")


def _это_отзыв(текст: str, вид: str, цель: str) -> bool:
    """Отменил ли владелец согласие ИМЕННО на это действие.

    Две дороги: строка НАЧАТА самостоятельным отказом («Стоп. Я передумал…») — это ответ
    на вопрос, предмет назван в нём самом; либо назван предмет вида И есть слово отказа.
    Голое «не» без предмета отзывом не считается: «не забудь дописать карту» — напоминание.
    Длина сообщения правила не решает.
    """
    текст = текст.lower()
    if формы.СТРОКА_САМОСТОЯТЕЛЬНОГО_ОТКАЗА.search(текст):
        return True
    отказ = ОТКАЗ.search(текст) or (вид == "перепись" and ОТМЕНА_СЛОВОМ.search(текст))
    названо = ПРЕДМЕТ_ОТЗЫВА[вид].search(текст) or (вид == "удаление" and цель_названа(текст, цель))
    return bool(отказ and названо)


def отзыв_после(вид: str, цель: str, когда: float, носитель: Носитель | None = None) -> str | None:
    """Слова владельца после нажатия «Да», отменяющие это действие, — или None.

    Читается ТОЛЬКО `слова_владельца_с(когда)`: окно свежести отзыв к старому «Да» не прочло бы.
    """
    for слово in reversed(слова_владельца_с(когда, носитель)):
        if _это_отзыв(слово["текст"], вид, цель):
            return f"отозвано словами «{слово['текст']}»"
    return None


def время_чм(когда: float) -> str:
    return _dt.datetime.fromtimestamp(когда).strftime("%H:%M")


def _почему_закрыто(решение: dict | None, вид: str, цель: str, держатель: Носитель,
                    на: float, без_срока: bool) -> str | None:
    """Причина, по которой нажатие не открывает дверь, — или None (открывает)."""
    if решение is None:
        return "кнопки «Да» на этот предмет нет"
    if решение["событие"] != "да":
        return f"владелец нажал „Нет“ в {время_чм(решение['когда'])}"
    срок = срок_кнопки_мин(вид, держатель)
    if not без_срока and решение["когда"] < на - срок * 60:
        return f"кнопка истекла: «Да» в {время_чм(решение['когда'])} старше {срок} мин"
    if ПОГАШЕНИЕ[вид](держатель.папка, цель, решение["когда"]):
        return "уже использовано: «Да» одно — действие одно"
    return None


def судить_кнопкой(вид: str, цель: str, на: float | None = None,
                   носитель: Носитель | None = None) -> tuple[bool, str]:
    """ЕДИНСТВЕННЫЙ суд необратимых дверей: открыта ли дверь «Да» кнопкой на (вид, цель).

    Текст владельца дверь не открывает никогда, только закрывает (отзыв). `на` — момент, на
    который судится срок кнопки (по умолчанию сейчас). НетНосителя — закрыто, с причиной.
    """
    на = _dt.datetime.now().timestamp() if на is None else на
    try:
        держатель = _взять(носитель)
        решение = последнее_решение(вид, цель, держатель)
        причина = _почему_закрыто(решение, вид, цель, держатель, на, без_срока=False)
        if причина is None:
            причина = отзыв_после(вид, цель, решение["когда"], держатель)
    except НетНосителя as беда:
        return False, f"журнал кнопок не прочитан: {беда}"
    if причина:
        return False, причина
    return True, f"кнопка «Да» в Telegram, {решение.get('ts')}"


def открытый_запрос(вид: str, цель: str, носитель: Носитель | None = None) -> dict | None:
    """Последний запрос кнопки на (вид, цель) моложе срока вида и без нажатия — иначе None.

    Из него ask-consent берёт «кнопка уже ушла в ЧЧ:ММ»: одна кнопка на предмет за срок вида.
    НетНосителя — журнал нажатий или запросов нечитаем.
    """
    держатель = _взять(носитель)
    каталог = держатель.папка
    решено = {запись.get("nonce") for запись in _решения_кнопок(каталог / ЖУРНАЛ_КНОПОК)}
    начало = _dt.datetime.now().timestamp() - срок_кнопки_мин(вид, держатель) * 60
    найден = None
    for строка in _строки_журнала(каталог / ЖУРНАЛ_ЗАПРОСОВ, "журнал запросов"):
        запись = плоская_запись(строка)
        if запись is None or запись["событие"] != "запрос" or запись.get("nonce") in решено:
            continue
        когда = _время(запись.get("ts"))
        if (запись.get("вид", ВИД_ПО_УМОЛЧАНИЮ) == вид and запись.get("цель") == цель
                and когда is not None and когда >= начало):
            найден = {**запись, "когда": когда}
    return найден


ЗАПРОС_КНОПКИ = Path(__file__).resolve().parent.parent / "ask-consent.py"
КОД_ПОВТОРА = 3          # ask-consent: запроса не записал — «Нет» моложе суток либо кнопка уже ушла
_КОД_ЗАПРОСА = re.compile(r"[A-Za-z0-9_-]{22}")
# Закрытие, после которого дверь кнопку не просит: отзыв закрывает кнопку, новой сам не просит;
# журнал не прочитан — просить можно было бы не туда.
НЕ_ПРОСИТЬ_ПОСЛЕ = ("отозвано", "журнал кнопок не прочитан")


def просить_ли(причина: str) -> bool:
    """Просит ли дверь кнопку после закрытия по этой причине судьи."""
    return not причина.startswith(НЕ_ПРОСИТЬ_ПОСЛЕ)


def попросить_кнопку(вид: str, цель: str, почему: str, носитель: Носитель | None = None,
                     репо: str | None = None, журнал_просьбы: Path | None = None) -> tuple[int, str]:
    """ЕДИНСТВЕННАЯ просьба кнопки у необратимых дверей: зовёт scripts/ask-consent.py (единственного
    писателя журнала запросов). → (код ask-consent, строка для вывода двери).

    Журнал ПРОСЬБЫ — не слово: дверь передаёт свой (`журнал_просьбы`), в бою он равен папке
    носителя, на стенде это стенд. Без него — папка носителя. Иначе просьба стенда легла бы в
    журнал по умолчанию. `ЗАПРОС_КНОПКИ` читается в момент зова: проба подменяет его обёрткой.
    Отправку шлёт диспетчер по журналу запросов, сеть здесь не трогается.
    """
    папка = журнал_просьбы if журнал_просьбы is not None else _взять(носитель).папка
    команда = [sys.executable, "-I", str(ЗАПРОС_КНОПКИ), "--вид", вид, "--предмет-двери", цель,
               "--почему", почему[:200]]
    if репо:
        команда += ["--репо", репо]
    try:
        готово = subprocess.run(команда, capture_output=True, text=True, timeout=30,
                                stdin=subprocess.DEVNULL, env=dict(os.environ, HARNESS_LOG_DIR=str(папка)))
    except (OSError, subprocess.TimeoutExpired) as беда:
        return 2, f"кнопку не попросил: {type(беда).__name__}"
    строки = [л.strip() for л in (готово.stdout + готово.stderr).splitlines() if л.strip()]
    if готово.returncode == 0:
        код = next((л for л in строки if _КОД_ЗАПРОСА.fullmatch(л)), "")
        return 0, f"текст не засчитывается — нужна кнопка «Да»; кнопку прислал(а), код {код[:8]}"
    return готово.returncode, (строки[-1] if строки else "ask-consent промолчал")


def согласие_кнопкой(вид: str, цель: str, без_срока: bool = False,
                     носитель: Носитель | None = None) -> dict | None:
    """Нажатое «Да» владельца об ИМЕННО этой цели этого вида — или None (без отзыва текстом).

    Цель сверяется в точности, без родителя и соседа: кнопка названа одним
    предметом (realpath файла считает вызывающий). Судится ПОСЛЕДНЕЕ решение,
    поэтому позднее «Нет» закрывает; «Да» старше срока вида не открывает. Отметку
    «использовано» не пишет никто: согласие погашено, если действие этого вида
    уже состоялось не раньше «да» (ПОГАШЕНИЕ).

    без_срока — для записи, которая сама фиксирует нажатие (спека): срок тогда
    держит диспетчер при нажатии, а не «сейчас − срок» при каждой проверке.
    Необратимые двери спрашивают судить_кнопкой, эту зовёт только обратимая «спека».

    Исключение НетНосителя — журнал нечитаем или битый; дверь обязана отказать.
    """
    держатель = _взять(носитель)
    решение = последнее_решение(вид, цель, держатель)
    if _почему_закрыто(решение, вид, цель, держатель, _dt.datetime.now().timestamp(), без_срока):
        return None
    return {"текст": f"кнопка «Да» в Telegram, {решение.get('ts')}",
            "message_id": str(решение.get("message_id") or ""),
            "файл": f"{ЖУРНАЛ_КНОПОК}:nonce={str(решение.get('nonce'))[:8]}",
            "когда": решение["когда"]}


def это_разрешение(текст: str) -> bool:
    """Слова владельца означают «удали это»?"""
    return _это_слово(текст, ГЛАГОЛ, ПРЕДМЕТ)


def это_разрешение_чтения(текст: str) -> bool:
    """Слова владельца означают «читай это»?

    Отдельный словарь, а не расширение прежнего: «удали токен» не должно
    открывать дверь чтения учёта, а «читай статусы» — дверь удаления секрета.
    """
    return _это_слово(текст, ГЛАГОЛ_ЧТЕНИЯ, ПРЕДМЕТ_ЧТЕНИЯ)


def это_разрешение_перезапуска(текст: str) -> bool:
    """Слова владельца означают «перезапусти агента / машину сейчас»?"""
    строка = " ".join((текст or "").lower().split())
    if not строка or _ОТКАЗ_САМОСТОЯТЕЛЬНЫЙ.search(строка):
        return False
    if _НЕ.search(_НЕ_ЖАЛКО.sub(" ", строка)) or формы.СЛОВА_ПОТОМ.search(строка) or _ПОКА.search(строка):
        return False
    return bool(ГЛАГОЛ_ПЕРЕЗАПУСКА.search(строка) and ПРЕДМЕТ_ПЕРЕЗАПУСКА.search(строка))


def _это_слово(текст: str, глагол: re.Pattern, предмет: re.Pattern) -> bool:
    """Общее правило: есть действие, есть предмет, и нет отказа рядом."""
    строка = " ".join((текст or "").lower().split())
    if not строка:
        return False
    if ОТКАЗ.search(f" {строка} ") and not re.search(r"если.*уверен", строка):
        return False
    return bool(глагол.search(строка) and предмет.search(строка))


def цель_названа(текст: str, цель: str) -> bool:
    """Назван ли в слове владельца путь, под которым лежит ЦЕЛЬ действия.

    Находка ревью безопасности 15.10.2026 (critical): «глагол + предмет» —
    признак РАЗГОВОРА об удалении, а не разрешения на конкретную цель. Его
    бытовые фразы про «удаленный доступ» и «мусор» открывали удаление ключей
    канала. Путь в сообщении случайно не появляется, и владелец называет его
    сам: «Удали секреты и копии базы из /var/www/<продукт>».

    Сверяется ВХОЖДЕНИЕ: названный путь — родитель цели или сама цель. Так
    «/var/www/<продукт>» разрешает «/var/www/<продукт>/secrets», а он же в
    слове НЕ разрешает «/var/lib/harness/secrets».
    """
    # «..» и симлинки схлопываются до сверки: «A/data/../../b» не лежит под A/data
    цель_путь = PurePosixPath(os.path.realpath(цель))
    for кусок in re.findall(r"~?/[^\s'\"]+", текст):
        # «~» раскрывается в HOME процесса, как и в самой команде
        названный = PurePosixPath(os.path.realpath(
            os.path.expanduser(кусок.rstrip("/.,;:!?»)"))))
        if len(названный.parts) < 3:
            continue          # «/» и «/var» целями не управляют
        if цель_путь == названный or названный in цель_путь.parents:
            return True
    return False


def разрешение(признак=это_разрешение, носитель: Носитель | None = None) -> dict | None:
    """Самое свежее его сообщение, означающее разрешение, — или None.

    `признак` — КАКОЕ разрешение искать: удаления (по умолчанию) или чтения.
    Дверь называет его сама: словарь разрешения зависит от действия, и дверь,
    взявшая чужой словарь, не открывается ни на что (живой случай 29.09.2026).

    Исключение НетНосителя пробрасывается наверх нарочно: дверь, поймавшая его,
    обязана отказать, а не считать, что владелец промолчал.
    """
    for запись in reversed(слова_владельца(носитель)):
        if признак(запись["текст"]):
            return запись
    return None


# ── Самотест правила о слове владельца ──────────────────────────────────────
#
# ЗАЧЕМ ОН ЗДЕСЬ. Правило «разрешение = глагол И предмет, и отказ его снимает»
# переехало в эту библиотеку из `protected-delete.py` — а проба правила осталась
# там, где правила больше нет. Замер 13.10.2026 (полные ворота): две мутации
# инварианта И-1 не вставали вовсе, потому что их текст искали в файле двери.
# Проба живёт с ПРАВИЛОМ, иначе дверь зелена, а правило не охраняет ничего.
def _самотест_судьи(проба) -> None:
    """Судья кнопки: «Да» открывает, текст не открывает, «Нет», срок, погашение и отзыв закрывают."""
    import tempfile
    import time as _time

    # Цель дозаписи приходит параметром: ворота журналов не судят стенд во временном каталоге.
    def дописать(путь: Path, строка: dict) -> None:
        with open(путь, "a", encoding="utf-8") as fh:
            fh.write(json.dumps(строка, ensure_ascii=False) + "\n")

    # Владелец стенда: TG_CHAT_ID его паспорта; «Да» без него и без просьбы не засчитывается.
    владелец = "4242"
    # Одна точка отсчёта: равные «назад» дают равные метки — так судится просьба в секунду нажатия.
    сейчас = int(_time.time())

    def запись(каталог: Path, событие: str, вид: str, цель: str, назад_с: float,
               от: str | None = владелец, журнал: str = ЖУРНАЛ_КНОПОК) -> None:
        данные = {"nonce": "n" + str(назад_с), "вид": вид, "цель": цель, "message_id": 4242}
        if от is not None:
            данные["from_id"] = int(от)
        строка = {"v": 1, "ts": _dt.datetime.fromtimestamp(сейчас - назад_с).astimezone()
                  .isoformat(timespec="seconds"), "src": "самотест", "event": событие, "outcome": "ok",
                  "data": данные}
        дописать(каталог / журнал, строка)

    def просьба(каталог: Path, цель: str, назад_с: float) -> None:
        запись(каталог, "consent.request", "выкат", цель, назад_с, от=None, журнал=ЖУРНАЛ_ЗАПРОСОВ)

    def да(каталог: Path, цель: str, назад_с: float, **как) -> None:
        """Живой порядок: просьба ask-consent раньше нажатия."""
        просьба(каталог, цель, назад_с + 30)
        запись(каталог, "consent.yes", "выкат", цель, назад_с, **как)

    def слово(каталог: Path, текст: str, назад_с: float) -> None:
        строка = {"ts": _dt.datetime.fromtimestamp(_time.time() - назад_с).astimezone().isoformat(timespec="seconds"),
                  "message_id": "9", "text": текст}
        дописать(каталог / ЖУРНАЛ_ВХОДЯЩИХ, строка)

    def носитель_пробы(каталог: Path) -> Носитель:
        return Носитель(папка=каталог, uid=None, паспорт={"TG_CHAT_ID": владелец}, граница=каталог,
                        окно_мин=60, срок_кнопки_мин=15, ручки={})

    for название, подготовка, ждали in (
            ("судья: «Да» кнопкой открывает", lambda к: да(к, "t", 60), True),
            ("судья: текст без кнопки не открывает", lambda к: слово(к, "выкатывай", 10), False),
            ("судья: «Да» старше срока закрыто", lambda к: да(к, "t", 3600), False),
            ("судья: «Нет» после «Да» закрывает",
             lambda к: (да(к, "t", 120), запись(к, "consent.no", "выкат", "t", 60)), False),
            ("судья: «Да» на другой предмет не открывает", lambda к: да(к, "другой", 60), False),
            ("судья: отзыв текстом после «Да» закрывает",
             lambda к: (да(к, "t", 120), слово(к, "стоп, не выкатывай", 60)), False),
            ("судья: слово ДО «Да» не отзывает",
             lambda к: (слово(к, "стоп, не выкатывай", 300), да(к, "t", 60)), True),
            ("судья: «Да» без from_id не открывает", lambda к: да(к, "t", 60, от=None), False),
            ("судья: «Да» с чужим from_id не открывает", lambda к: да(к, "t", 60, от="777"), False),
            ("судья: «Да» без просьбы не открывает",
             lambda к: запись(к, "consent.yes", "выкат", "t", 60), False),
            ("судья: просьба ПОСЛЕ «Да» не открывает",
             lambda к: (запись(к, "consent.yes", "выкат", "t", 60), просьба(к, "t", 30)), False),
            ("судья: просьба на другой предмет не парная",
             lambda к: (просьба(к, "другой", 90), запись(к, "consent.yes", "выкат", "t", 60)), False),
            ("судья: просьба в ту же секунду, что «Да», — парная (живой путь без задержки)",
             lambda к: (просьба(к, "t", 60), запись(к, "consent.yes", "выкат", "t", 60)), True)):
        with tempfile.TemporaryDirectory() as временный:
            каталог = Path(временный)
            (каталог / ЖУРНАЛ_ВХОДЯЩИХ).write_text("", encoding="utf-8")
            подготовка(каталог)
            проба(название, ждали, судить_кнопкой("выкат", "t", носитель=носитель_пробы(каталог))[0])
    with tempfile.TemporaryDirectory() as временный:
        проба("судья: нет журнала кнопок — закрыто без исключения", False,
              судить_кнопкой("выкат", "t", носитель=носитель_пробы(Path(временный) / "нет"))[0])


def _самотест() -> int:
    """Больные случаи первыми: отказ рядом и голое согласие."""
    from selftest_cases import Cases
    случаи = Cases()
    проба = случаи.check

    # БОЛЬНОЙ СЛУЧАЙ: отказ в сообщении СНИМАЕТ разрешение. Без этого «не
    # удаляй секреты» открыло бы дверь удаления секретов.
    проба("«не удаляй секреты» — не разрешение", False, это_разрешение("не удаляй секреты"))
    # БОЛЬНОЙ СЛУЧАЙ: слово отказа из общего словаря. «отмена» есть в
    # patterns.СЛОВА_ОТКАЗА, и дверь удаления обязана его знать.
    проба("«отмена, удали токен» — не разрешение", False, это_разрешение("отмена, удали токен"))
    # БОЛЬНОЙ СЛУЧАЙ: отказ рядом с типографикой телефона (ёлочки, многоточие,
    # тире) — всё ещё отказ: граница слова — любой не-буквенный знак.
    проба("«удали токен…нет» — не разрешение", False, это_разрешение("удали токен…нет"))
    проба("«удали токен—нет» — не разрешение", False, это_разрешение("удали токен—нет"))
    проба("ёлочки: «не удаляй токен» — не разрешение", False, это_разрешение("«не удаляй токен»"))
    проба("«стоп, не трогай ключи» — не разрешение", False,
          это_разрешение("стоп, не трогай ключи"))
    # БОЛЬНОЙ СЛУЧАЙ: голое согласие. Оно могло относиться к выкату — ровно та
    # дыра, которую закрыли у ворот выката 11.09.2026.
    проба("голое «да» — не разрешение", False, это_разрешение("да"))
    проба("«давай» — не разрешение", False, это_разрешение("давай"))
    # Глагол без предмета и предмет без глагола — тоже не разрешение.
    проба("«удали» без предмета — не разрешение", False, это_разрешение("удали"))
    проба("«секреты» без глагола — не разрешение", False, это_разрешение("секреты"))
    # Законное разрешение.
    проба("«удали старые секреты» — разрешение", True,
          это_разрешение("удали старые секреты"))
    # Оговорка «если уверен» отказом НЕ считается: владелец разрешает с условием.
    проба("«удали копии, если уверен» — разрешение", True,
          это_разрешение("удали копии, если уверен"))
    # Два словаря не подменяют друг друга: слово об удалении не открывает
    # дверь чтения, слово о чтении — дверь удаления.
    проба("«удали токен» не открывает дверь ЧТЕНИЯ", False,
          это_разрешение_чтения("удали токен"))
    проба("«посмотри остатки склада» не открывает дверь УДАЛЕНИЯ", False,
          это_разрешение("посмотри остатки склада"))
    проба("«посмотри остатки склада» открывает дверь чтения", True,
          это_разрешение_чтения("посмотри остатки склада"))
    # Названный путь — предмет отзыва удаления; «~» раскрывается в HOME.
    проба("«снеси проект <путь>» называет путь цели", True,
          цель_названа("снеси проект /var/www/chuzhoj", "/var/www/chuzhoj/a"))
    проба("«снеси проект» без пути цель не называет", False,
          цель_названа("снеси проект", "/var/www/chuzhoj"))
    проба("«снеси проект <путь>» не называет ЧУЖОЙ путь", False,
          цель_названа("снеси проект /var/www/chuzhoj", "/var/www/other"))
    проба("«~/x» в слове раскрывается в HOME", True,
          цель_названа("удали ключ ~/.ssh/k", os.path.expanduser("~/.ssh/k")))
    # Дверь перезапуска: глагол И предмет, голое «да» мимо, «не» открывает не всё.
    проба("«перезапусти агента, помощников не жалко» — разрешение", True,
          это_разрешение_перезапуска("перезапусти агента, помощников не жалко"))
    проба("голое «да» не открывает дверь перезапуска", False, это_разрешение_перезапуска("да"))
    проба("«не перезапусти агента» — не разрешение", False,
          это_разрешение_перезапуска("не перезапусти агента"))
    проба("«стоп, перезапусти агента» — не разрешение", False,
          это_разрешение_перезапуска("стоп, перезапусти агента"))
    for фраза, ждали in (("перезапусти агента потом, когда помощники закончат", False),
                         ("ребут пока не делай, агент занят", False),
                         ("ребут сервера не нужен", False),
                         ("перезапусти агента завтра", False),
                         ("перезапусти агента", True),
                         ("перезапусти, помощников не жалко", True),
                         ("перезапусти что-нибудь в смене кода", False)):
        проба(f"дверь перезапуска: «{фраза}»", ждали, это_разрешение_перезапуска(фраза))
    _самотест_судьи(проба)
    # Пустое и None — не разрешение (дверь зовут и так).
    проба("пустая строка — не разрешение", False, это_разрешение(""))

    print("SELFTEST: " + (f"зелёный ({случаи.paths} путей, больные первыми)" if случаи.ok
                          else f"КРАСНЫЙ, неудач {случаи.failures}"))
    return 0 if случаи.ok else 1


