"""Сосед по каталогу scripts/ с дефисом в имени — ОДНО место на всех.

Имена файлов кода латиницей и через дефис (правило проекта), а дефис в имени
модуля Python недопустим: `import zadachi-iz-kanala` — синтаксическая ошибка.
Копировать чужие списки слов и признаков к себе нельзя (разошедшийся список
молчит ровно тогда, когда нужен), значит сосед берётся загрузчиком.

Ревью 10.09.2026 уже ловило это на чтении паспорта: одна и та же функция была
скопирована за смену четыре раза, и копии разошлись. Здесь она одна.

    from sosed import модуль
    гейт = модуль("zadachi-iz-kanala")
    гейт.рабочее("надо переделать карту")
"""
import importlib.util
from pathlib import Path

СКРИПТЫ = Path(__file__).resolve().parent.parent


def модуль(имя: str, каталог: Path | None = None):
    """Загружает scripts/<имя>.py и возвращает его как модуль."""
    путь = (каталог or СКРИПТЫ) / f"{имя}.py"
    спец = importlib.util.spec_from_file_location(имя.replace("-", "_"), путь)
    если_нет = спец is None or спец.loader is None
    if если_нет:
        raise ImportError(f"соседа {путь} не загрузить")
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м
