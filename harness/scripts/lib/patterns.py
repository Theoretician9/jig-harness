#!/usr/bin/env python3
"""Формы значений, по которым механизмы судят ОДИН И ТОТ ЖЕ факт.

СЛУЧАЙ (Ф2 ревизии харнеса, §4.3, замер 28.09.2026). Разведка нашла пять форм,
каждая из которых жила ДВУМЯ копиями в разных файлах:

| форма | копии были в |
|---|---|
| отрицание владельца («не», «нет», «стоп»…) | `deploy_guard.py`, `spec_approval.py` |
| граница слова в его сообщении | там же |
| имя записи памяти (`<имя>.md`) | `write-memory.py`, `memory-to-package.py` |
| не-латиница в имени файла | `check-file-names.py`, `rename-to-latin.py` |
| источник задачи (`inbox:<метка>`) | `tasks-from-channel.py`, `work-queue.py` |
| заголовок релизного коммита | `update.py`, `version.py` |

Почему это не мелочь. Класс уже стоил смены: 27.09 строитель проверок мерил
«поле есть», а судья — «форма годная», и 18 задач залегли между двумя мерками
([[two-writers-one-mark-different-thresholds]]). С отрицанием цена выше: стоит
кому-то добавить «не сейчас» в один список, и второй механизм засчитает такое
сообщение согласием — то есть выкат или работа по неодобренной спеке.

Здесь — один судья на форму. Списки слов и границы лежат ДАННЫМИ этого модуля,
а не повторяются у потребителей; гейт `scripts/check-one-judge.py` не даёт
копии вернуться.

    python3 scripts/lib/patterns.py --selftest
"""
from __future__ import annotations

import re
import sys

# Граница слова в сообщении владельца. `\b` не годится: дефис для него граница,
# и «claude-demon» совпадал с «claude» (улика deploy_guard, ревью 12.09.2026).
ГРАНИЦА_СЛЕВА = r"(?:^|[\s,.;:!?()\"-])"
ГРАНИЦА_СПРАВА = r"(?:$|[\s,.;:!?()\"-])"

# Слова, которыми владелец ОТКАЗЫВАЕТ. Список — данные: добавленное слово должно
# действовать сразу у всех, кто судит его согласие.
СЛОВА_ОТКАЗА = ("не", "нет", "стоп", "отмена", "погоди", "подожди", "позже", "рано")

ОТРИЦАНИЕ = re.compile(
    ГРАНИЦА_СЛЕВА + r"(?:" + "|".join(СЛОВА_ОТКАЗА) + r")" + ГРАНИЦА_СПРАВА)

# Согласие словом «да» — отдельная форма: голое «да» засчитывается не всегда, и
# решает это потребитель, а не форма.
СЛОВО_ДА = re.compile(ГРАНИЦА_СЛЕВА + r"да" + ГРАНИЦА_СПРАВА)

# Слова, которыми владелец соглашается БЕЗ названного предмета. Наборы разные по
# строгости, и разница названа здесь, а не рассыпана по трём файлам (замер
# 28.09.2026: у сторожа выката 4 слова, у согласования спеки 9, у диспетчера 7).
СОГЛАСИЕ_БАЗОВОЕ = ("да", "ок", "окей", "подтверждаю")
# Одобрение спеки принимает больше форм: спека — не выкат, цена ошибки ниже, а
# владелец отвечает на неё свободнее («согласен», «давай»).
СОГЛАСИЕ_СПЕКА_ДОП = ("одобряю", "согласен", "утверждаю", "да, одобряю", "давай")
# Диспетчер записывает в журнал согласий и то, что названо предметом прямо в
# слове: «ротация ок», «выкатывай».
СОГЛАСИЕ_КАНАЛ_ДОП = ("ротация ок", "ротация да", "выкатывай")


# Имя записи памяти: латиница или кириллица, дефисы, обязательное `.md`.
ИМЯ_ЗАПИСИ_ПАМЯТИ = re.compile(r"^[A-Za-zА-Яа-яЁё0-9][A-Za-zА-Яа-яЁё0-9-]{0,80}\.md$")

# Не-латиница в имени файла кода: правило владельца 11.09.2026.
НЕ_ЛАТИНИЦА = re.compile(r"[^\x00-\x7F]")

# Источник задачи в карте: «inbox:<метка времени файла>».
ИСТОЧНИК_INBOX = re.compile(r"inbox:([0-9.]+)")

# Договор с publish.sh: ПЕРВАЯ строка релизного коммита.
ЗАГОЛОВОК_РЕЛИЗА = re.compile(r"версия от \d{4}-\d{2}-\d{2}, пакет ([0-9a-f]{7,40})")


# Литералы, которых не должно быть НИГДЕ, кроме этого файла: их ищет гейт
# scripts/check-one-judge.py. Без него копия возвращается тихо — она и появилась
# так: сначала форма была написана в одном механизме, потом скопирована во второй.
ОХРАНЯЕМЫЕ_ЛИТЕРАЛЫ = {
    "граница слова в сообщении владельца": ГРАНИЦА_СЛЕВА,
    "имя записи памяти": r"^[A-Za-zА-Яа-яЁё0-9][A-Za-zА-Яа-яЁё0-9-]{0,80}\.md$",
    "не-латиница в имени файла": r"[^\x00-\x7F]",
    "источник задачи в карте": r"inbox:([0-9.]+)",
    "заголовок релизного коммита": r"версия от \d{4}-\d{2}-\d{2}, пакет ([0-9a-f]{7,40})",
    "слова отказа владельца": "|".join(СЛОВА_ОТКАЗА),
    # Наборы голого согласия: охраняем характерную пару слов (в прозе кода она не
    # встречается) и готовый шаблон для оболочки.
    "набор голого согласия, питон": '"ок", "окей"',
    "набор голого согласия, оболочка": "|".join(СОГЛАСИЕ_БАЗОВОЕ),
}


def _selftest() -> int:
    путей = неудач = 0

    def проба(имя: str, ждём, факт):
        nonlocal путей, неудач
        путей += 1
        if факт == ждём:
            print(f"  ок    {имя}")
        else:
            неудач += 1
            print(f"  ПЛОХО {имя}: ждали «{ждём}», вышло «{факт}»")

    # БОЛЬНОЙ СЛУЧАЙ: «да» внутри другого слова — не согласие, а дефис не должен
    # работать границей слова так, как это делает `\b`.
    проба("«да» отдельным словом — согласие", True, bool(СЛОВО_ДА.search("ну да")))
    проба("«да» внутри слова согласием не считается", False,
          bool(СЛОВО_ДА.search("выдача готова")))
    проба("отрицание найдено", True, bool(ОТРИЦАНИЕ.search("нет, погоди")))
    проба("«нет» внутри слова отрицанием не считается", False,
          bool(ОТРИЦАНИЕ.search("монета")))
    проба("список отказа — данные, а не текст регулярки", True,
          all(ОТРИЦАНИЕ.search(f"ответ {слово} тут") for слово in СЛОВА_ОТКАЗА))

    # БОЛЬНОЙ СЛУЧАЙ: наборы согласия расходились молча. Базовый — строгий, и
    # расширения ОБЯЗАНЫ его содержать: иначе сторож выката принял бы слово,
    # которого не знает согласование спеки, и наоборот.
    # Прежние две пробы сравнивали набор с объединением, куда он сам и входит, —
    # тавтология, истинная при любых данных ([[comparing-two-implementations-turns-tautological]]).
    # Мутационный прогон 28.09.2026: удаление «да» из базового набора и обнуление
    # границы слова оставляли самотест ЗЕЛЁНЫМ. Судим сами данные.
    проба("главное слово согласия в базовом наборе есть", True,
          "да" in СОГЛАСИЕ_БАЗОВОЕ)
    проба("набор спеки шире базового, а не равен ему", True,
          bool(set(СОГЛАСИЕ_СПЕКА_ДОП) - set(СОГЛАСИЕ_БАЗОВОЕ)))
    проба("набор канала шире базового", True,
          bool(set(СОГЛАСИЕ_КАНАЛ_ДОП) - set(СОГЛАСИЕ_БАЗОВОЕ)))
    проба("граница слева работает: «когда готово» — не согласие", False,
          bool(СЛОВО_ДА.search("когда готово")))
    проба("расширения не пересекаются с базовым", set(),
          set(СОГЛАСИЕ_СПЕКА_ДОП) & set(СОГЛАСИЕ_БАЗОВОЕ))
    проба("выкат не принимает «согласен» — набор строже", False,
          "согласен" in СОГЛАСИЕ_БАЗОВОЕ)

    проба("имя записи памяти принято", True,
          bool(ИМЯ_ЗАПИСИ_ПАМЯТИ.match("a-mutation-behind-the-code.md")))
    проба("имя записи с кириллицей принято", True,
          bool(ИМЯ_ЗАПИСИ_ПАМЯТИ.match("проба-восстановления.md")))
    проба("имя без .md отвергнуто", False,
          bool(ИМЯ_ЗАПИСИ_ПАМЯТИ.match("запись")))
    проба("путь вместо имени отвергнут", False,
          bool(ИМЯ_ЗАПИСИ_ПАМЯТИ.match("память/запись.md")))

    проба("кириллица в имени файла видна", True,
          bool(НЕ_ЛАТИНИЦА.search("проба.py")))
    проба("латинское имя чисто", False, bool(НЕ_ЛАТИНИЦА.search("probe.py")))

    проба("источник задачи разобран", ["1790535297.864288768"],
          ИСТОЧНИК_INBOX.findall("inbox:1790535297.864288768"))
    проба("два источника у одной задачи", 2,
          len(ИСТОЧНИК_INBOX.findall("inbox:1.1 и inbox:2.2")))

    проба("заголовок релиза разобран", "abc1234",
          (ЗАГОЛОВОК_РЕЛИЗА.fullmatch("версия от 2026-09-28, пакет abc1234")
           or type("", (), {"group": lambda *_: None})()).group(1))
    # БОЛЬНОЙ СЛУЧАЙ 12.09.2026: искали «пакет <хэш>» в любом месте тела, и любой
    # коммит со этими словами объявлялся своей сборкой — извещение об обновлении
    # гасло. Форма держит ПЕРВУЮ строку целиком.
    проба("слова в середине сообщения релизом не считаются", None,
          ЗАГОЛОВОК_РЕЛИЗА.fullmatch("правка: версия от 2026-09-28, пакет abc1234"))

    print(f"SELFTEST: {'зелёный' if not неудач else 'КРАСНЫЙ'} ({путей} путей; "
          "больной первый — «да» внутри другого слова)")
    return 1 if неудач else 0


def _печать_для_оболочки(ключ: str) -> int:
    """Форма для `grep -E` из оболочки: у bash нет импорта, но судья один.

    Улика 28.09.2026: `tg-dispatcher.sh` держал ТРЕТЬЮ копию списка слов отказа,
    и это точка приёма сообщений владельца — расхождение здесь стоит согласия.
    Пустой вывод недопустим: `grep -qE ""` совпадает со ВСЕМ, то есть согласие
    не было бы принято никогда; поэтому неизвестный ключ — отказ с кодом 2.
    """
    формы_для_оболочки = {
        "--слова-отказа": "(" + "|".join(СЛОВА_ОТКАЗА) + ")",
        # Для `case` в оболочке: набор через «|», без скобок.
        "--согласие-канала": "|".join(СОГЛАСИЕ_БАЗОВОЕ + СОГЛАСИЕ_КАНАЛ_ДОП),
        "--граница-слева": "[ ,.;:!?()\"-]",
        "--граница-справа": "[ ,.;:!?()\"-]",
    }
    значение = формы_для_оболочки.get(ключ)
    if not значение:
        print(f"patterns: неизвестная форма «{ключ}»", file=sys.stderr)
        return 2
    print(значение)
    return 0


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] != "--selftest":
        sys.exit(_печать_для_оболочки(sys.argv[1]))
    sys.exit(_selftest())
