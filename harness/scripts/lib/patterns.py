#!/usr/bin/env python3
"""Формы значений, по которым механизмы судят ОДИН И ТОТ ЖЕ факт.

СЛУЧАЙ (Ф2 ревизии харнеса, §4.3, замер 28.09.2026). Разведка нашла пять форм,
каждая из которых жила ДВУМЯ копиями в разных файлах:

| форма | копии были в |
|---|---|
| отрицание владельца («не», «нет», «стоп»…) | `deploy_guard.py`, `spec_approval.py` |
| граница слова в его сообщении | там же |
| имя записи памяти (`<имя>.md`) | `write-memory.py`, `memory-to-package.py` |
| не-латиница в имени файла | `check-file-names.py`, `rename-to-latin.py` |
| источник задачи (`inbox:<метка>`) | `tasks-from-channel.py`, `work-queue.py` |
| заголовок релизного коммита | `update.py`, `version.py` |

Почему это не мелочь. Класс уже стоил смены: 27.09 строитель проверок мерил
«поле есть», а судья — «форма годная», и 18 задач залегли между двумя мерками
([[two-writers-one-mark-different-thresholds]]). С отрицанием цена выше: стоит
кому-то добавить «не сейчас» в один список, и второй механизм засчитает такое
сообщение согласием — то есть выкат или работа по неодобренной спеке.

Здесь — один судья на форму. Списки слов и границы лежат ДАННЫМИ этого модуля,
а не повторяются у потребителей; гейт `scripts/check-one-judge.py` не даёт
копии вернуться.

    python3 scripts/lib/patterns.py --selftest
"""
from __future__ import annotations

import re
import sys

# Граница слова в сообщении владельца. `\b` не годится: дефис для него граница,
# и «claude-demon» совпадал с «claude» (улика deploy_guard, ревью 12.09.2026).
ГРАНИЦА_СЛЕВА = r"(?:^|[\s,.;:!?()\"-])"
ГРАНИЦА_СПРАВА = r"(?:$|[\s,.;:!?()\"-])"

# Слова, которыми владелец ОТКАЗЫВАЕТ. Список — данные: добавленное слово должно
# действовать сразу у всех, кто судит его согласие.
СЛОВА_ОТКАЗА = ("не", "нет", "стоп", "отмена", "погоди", "подожди", "позже", "рано",
                "нельзя", "отбой", "передумал", "отставить", "повремени")

# Граница отказа — ЛЮБОЙ не-буквенный знак, а не список знаков: телефон ставит
# многоточие, тире и ёлочки автозаменой, и «удали токен…нет» с узкой границей
# читалось разрешением. Для отказа шире — значит строже.
ОТРИЦАНИЕ = re.compile(r"(?<!\w)(?:" + "|".join(СЛОВА_ОТКАЗА) + r")(?!\w)")

# Отказ РЯДОМ с приказом — окно в СЛОВАХ по обе стороны: «не выкатывай» и
# «выкатывай, нет, погоди». Окно в знаках резало слово пополам («подожди» →
# «пог»), а в «публикуй как есть, проверю — обновим если что-то не так» отказ
# далеко от приказа, и это согласие (живая форма 11.09.2026).
ОКНО_ОТКАЗА_СЛОВ = 3
_СЛОВО = re.compile(r"\w+")


def отказ_рядом(текст: str, начало: int, конец: int) -> bool:
    слева = _СЛОВО.findall(текст[:начало])[-ОКНО_ОТКАЗА_СЛОВ:]
    справа = _СЛОВО.findall(текст[конец:])[:ОКНО_ОТКАЗА_СЛОВ]
    return any(слово in СЛОВА_ОТКАЗА for слово in слева + справа)


# Строка, НАЧАТАЯ отказом («нет, погоди», «стоп»), снимает согласие всего
# сообщения: владелец пишет приказ и отказ разными строками.
СТРОКА_ОТКАЗА = re.compile(r"^\W*(?:" + "|".join(СЛОВА_ОТКАЗА) + r")(?!\w)", re.M)

# Согласие словом «да» — отдельная форма: голое «да» засчитывается не всегда, и
# решает это потребитель, а не форма.
СЛОВО_ДА = re.compile(ГРАНИЦА_СЛЕВА + r"да" + ГРАНИЦА_СПРАВА)

# Слова, которыми владелец соглашается БЕЗ названного предмета. Наборы разные по
# строгости, и разница названа здесь, а не рассыпана по трём файлам (замер
# 28.09.2026: у сторожа выката 4 слова, у согласования спеки 9, у диспетчера 7).
СОГЛАСИЕ_БАЗОВОЕ = ("да", "ок", "окей", "подтверждаю")
# Одобрение спеки принимает больше форм: спека — не выкат, цена ошибки ниже, а
# владелец отвечает на неё свободнее («согласен», «давай»).
СОГЛАСИЕ_СПЕКА_ДОП = ("одобряю", "согласен", "утверждаю", "да, одобряю", "давай")
# Диспетчер записывает в журнал согласий и то, что названо предметом прямо в
# слове: «ротация ок», «выкатывай».
СОГЛАСИЕ_КАНАЛ_ДОП = ("ротация ок", "ротация да", "выкатывай")

# ПРЕДМЕТЫ СОГЛАСИЯ: о чём владелец может сказать «да». Данные, а не ветки —
# прежде диспетчер держал по ветке на предмет (выкат, отправка в гит), и ветки
# отличались только списком слов. Новый предмет требовал копии ветки, то есть
# пятого места, где написано одно и то же правило (ревизия 01.10.2026).
ПРЕДМЕТЫ_СОГЛАСИЯ = {
    # «Да для выката» и «По выкату пишу да» — обе формы за одни сутки,
    # 21.08.2026: перечислять точные фразы оказалось тупиком, судится ПРЕДМЕТ.
    "выкат": ("выкат", "деплой", "deploy"),
    # Отправка в чужой репозиторий — тоже наружу. Улика 03.09.2026: «на гит
    # отправляй, да» не подошло ни под одно правило, и push встал при данном
    # разрешении.
    "отправка в гит": ("гит", "git", "пуш", "push", "отправляй", "отправь", "отправить"),
}

# ПРЯМОЕ РАСПОРЯЖЕНИЕ — согласие без слова «да». Улика 11.09.2026: на вопрос с
# нумерованными вариантами владелец ответил «1 публикуй как есть, проверю»;
# слова «да» нет, строка длиннее трёх слов — распознаватель промолчал, и
# распоряжение осталось неисполненным.
ГЛАГОЛЫ_РАСПОРЯЖЕНИЯ = (
    "публикуй", "опубликуй", "выкатывай", "выкати", "отправляй", "отправь",
)

# Признак отправки в репозиторий: по нему ворота выката открывают push, а судья
# согласия не ставит вид any — «да, гит» без вопроса push не открывает.
ПРЕДМЕТ_ОТПРАВКИ = re.compile(r"гит|git|пуш|push|отправ")
_ГЛАГОЛ = re.compile("|".join(ГЛАГОЛЫ_РАСПОРЯЖЕНИЯ))


def _согласие_ли(строка: str) -> bool:
    if строка in СОГЛАСИЕ_БАЗОВОЕ + СОГЛАСИЕ_КАНАЛ_ДОП:
        return True
    # Распоряжение — согласие любой длины («1 публикуй как есть»), если ни
    # одно вхождение глагола не снято отказом рядом.
    глаголы = list(_ГЛАГОЛ.finditer(строка))
    if глаголы and not any(отказ_рядом(строка, г.start(), г.end()) for г in глаголы):
        return True
    if not СЛОВО_ДА.search(строка) or ОТРИЦАНИЕ.search(строка):
        return False
    # Короткое «да» — ответ на вопрос агента, предмет назван в вопросе.
    if len(строка.split()) <= 3:
        return True
    return any(слово in строка for слова in ПРЕДМЕТЫ_СОГЛАСИЯ.values() for слово in слова)


def вердикт_согласия(строка: str) -> str:
    """Строка владельца → «deploy» / «any» / «текст» (согласие этого вида) или «нет».

    Вид не зависит от правила, которым согласие признано: «выкат» в строке —
    deploy; короткая строка без признака отправки — any; иначе текст, и ворота
    разбирают его сами."""
    строка = строка.lower().strip()
    if not _согласие_ли(строка):
        return "нет"
    if "выкат" in строка:
        return "deploy"
    if len(строка.split()) <= 3 and not ПРЕДМЕТ_ОТПРАВКИ.search(строка):
        return "any"
    return "текст"


# Имя записи памяти: латиница или кириллица, дефисы, обязательное `.md`.
ИМЯ_ЗАПИСИ_ПАМЯТИ = re.compile(r"^[A-Za-zА-Яа-яЁё0-9][A-Za-zА-Яа-яЁё0-9-]{0,80}\.md$")

# Не-латиница в имени файла кода: правило владельца 11.09.2026.
НЕ_ЛАТИНИЦА = re.compile(r"[^\x00-\x7F]")

# Источник задачи в карте: «inbox:<метка времени файла>».
ИСТОЧНИК_INBOX = re.compile(r"inbox:([0-9.]+)")

# Договор с publish.sh: ПЕРВАЯ строка релизного коммита.
ЗАГОЛОВОК_РЕЛИЗА = re.compile(r"версия от \d{4}-\d{2}-\d{2}, пакет ([0-9a-f]{7,40})")


# Литералы, которых не должно быть НИГДЕ, кроме этого файла: их ищет гейт
# scripts/check-one-judge.py. Без него копия возвращается тихо — она и появилась
# так: сначала форма была написана в одном механизме, потом скопирована во второй.
ОХРАНЯЕМЫЕ_ЛИТЕРАЛЫ = {
    "граница слова в сообщении владельца": ГРАНИЦА_СЛЕВА,
    "имя записи памяти": r"^[A-Za-zА-Яа-яЁё0-9][A-Za-zА-Яа-яЁё0-9-]{0,80}\.md$",
    "не-латиница в имени файла": r"[^\x00-\x7F]",
    "источник задачи в карте": r"inbox:([0-9.]+)",
    "заголовок релизного коммита": r"версия от \d{4}-\d{2}-\d{2}, пакет ([0-9a-f]{7,40})",
    "слова отказа владельца": "|".join(СЛОВА_ОТКАЗА),
    # Наборы голого согласия: охраняем характерную пару слов (в прозе кода она не
    # встречается) и готовый шаблон для оболочки.
    "набор голого согласия, питон": '"ок", "окей"',
    "набор голого согласия, оболочка": "|".join(СОГЛАСИЕ_БАЗОВОЕ),
    # Согласие судит вердикт_согласия; у оболочки — только его ответ. Граница
    # слова в shell пишется двумя записями (в '' и в "" с экраном).
    "граница слова в оболочке": ',.;:!?()"-]',
    "граница слова в оболочке, с экраном": ',.;:!?()\\"-]',
    "вид согласия «выкат» в оболочке": "*выкат*",
    "признак отправки": ПРЕДМЕТ_ОТПРАВКИ.pattern,
}


def _selftest() -> int:
    from selftest_cases import Cases
    случаи = Cases()
    проба = случаи.check

    # БОЛЬНОЙ СЛУЧАЙ: «да» внутри другого слова — не согласие, а дефис не должен
    # работать границей слова так, как это делает `\b`.
    проба("«да» отдельным словом — согласие", True, bool(СЛОВО_ДА.search("ну да")))
    проба("«да» внутри слова согласием не считается", False,
          bool(СЛОВО_ДА.search("выдача готова")))
    проба("отрицание найдено", True, bool(ОТРИЦАНИЕ.search("нет, погоди")))
    # БОЛЬНОЙ СЛУЧАЙ: отказ за типографикой телефона — многоточие, тире,
    # ёлочки. Узкая граница-список его не видела, и «удали токен…нет» было
    # разрешением на удаление секрета.
    for строка in ("удали токен…нет", "выкат—нет", "«не» трогай", "отбой"):
        проба(f"отказ за типографикой: «{строка}»", True, bool(ОТРИЦАНИЕ.search(строка)))
    проба("«нет» внутри слова отрицанием не считается", False,
          bool(ОТРИЦАНИЕ.search("монета")))
    проба("список отказа — данные, а не текст регулярки", True,
          all(ОТРИЦАНИЕ.search(f"ответ {слово} тут") for слово in СЛОВА_ОТКАЗА))

    # БОЛЬНОЙ СЛУЧАЙ: наборы согласия расходились молча. Базовый — строгий, и
    # расширения ОБЯЗАНЫ его содержать: иначе сторож выката принял бы слово,
    # которого не знает согласование спеки, и наоборот.
    # Прежние две пробы сравнивали набор с объединением, куда он сам и входит, —
    # тавтология, истинная при любых данных ([[comparing-two-implementations-turns-tautological]]).
    # Мутационный прогон 28.09.2026: удаление «да» из базового набора и обнуление
    # границы слова оставляли самотест ЗЕЛЁНЫМ. Судим сами данные.
    проба("главное слово согласия в базовом наборе есть", True,
          "да" in СОГЛАСИЕ_БАЗОВОЕ)
    проба("набор спеки шире базового, а не равен ему", True,
          bool(set(СОГЛАСИЕ_СПЕКА_ДОП) - set(СОГЛАСИЕ_БАЗОВОЕ)))
    проба("набор канала шире базового", True,
          bool(set(СОГЛАСИЕ_КАНАЛ_ДОП) - set(СОГЛАСИЕ_БАЗОВОЕ)))
    проба("граница слева работает: «когда готово» — не согласие", False,
          bool(СЛОВО_ДА.search("когда готово")))
    проба("расширения не пересекаются с базовым", set(),
          set(СОГЛАСИЕ_СПЕКА_ДОП) & set(СОГЛАСИЕ_БАЗОВОЕ))
    проба("выкат не принимает «согласен» — набор строже", False,
          "согласен" in СОГЛАСИЕ_БАЗОВОЕ)

    проба("имя записи памяти принято", True,
          bool(ИМЯ_ЗАПИСИ_ПАМЯТИ.match("a-mutation-behind-the-code.md")))
    проба("имя записи с кириллицей принято", True,
          bool(ИМЯ_ЗАПИСИ_ПАМЯТИ.match("проба-восстановления.md")))
    проба("имя без .md отвергнуто", False,
          bool(ИМЯ_ЗАПИСИ_ПАМЯТИ.match("запись")))
    проба("путь вместо имени отвергнут", False,
          bool(ИМЯ_ЗАПИСИ_ПАМЯТИ.match("память/запись.md")))

    проба("кириллица в имени файла видна", True,
          bool(НЕ_ЛАТИНИЦА.search("проба.py")))
    проба("латинское имя чисто", False, bool(НЕ_ЛАТИНИЦА.search("probe.py")))

    проба("источник задачи разобран", ["1790535297.864288768"],
          ИСТОЧНИК_INBOX.findall("inbox:1790535297.864288768"))
    проба("два источника у одной задачи", 2,
          len(ИСТОЧНИК_INBOX.findall("inbox:1.1 и inbox:2.2")))

    проба("заголовок релиза разобран", "abc1234",
          (ЗАГОЛОВОК_РЕЛИЗА.fullmatch("версия от 2026-09-28, пакет abc1234")
           or type("", (), {"group": lambda *_: None})()).group(1))
    # БОЛЬНОЙ СЛУЧАЙ 12.09.2026: искали «пакет <хэш>» в любом месте тела, и любой
    # коммит со этими словами объявлялся своей сборкой — извещение об обновлении
    # гасло. Форма держит ПЕРВУЮ строку целиком.
    проба("слова в середине сообщения релизом не считаются", None,
          ЗАГОЛОВОК_РЕЛИЗА.fullmatch("правка: версия от 2026-09-28, пакет abc1234"))

    # Вердикт согласия по строке: эталон — формы владельца с видом записи,
    # которого ждут ворота выката.
    эталон = (
        ("1 публикуй как есть, проверю - обновим если чтото не так", "текст"),
        ("да", "any"),
        ("не публикуй пока", "нет"),
        ("публиковать пока рано", "нет"),
        ("а что будет если опубликовать?", "нет"),
        ("да и вообще не надо", "нет"),
        ("1 - но не надо подписи", "нет"),
        ("ПОДТВЕРЖДАЮ  ", "any"),
        ("нет", "нет"),
        ("Да для выката", "deploy"),
        ("По поводу калибровки, чтоб ты понимал", "нет"),
        ("да выкатывать не надо", "нет"),
        ("По выкату пишу да", "deploy"),
        ("Далее действуй без моих проверок", "нет"),
        ("по выкату пока подожди", "нет"),
        ("выкат не делай, да и вообще рано", "нет"),
        ("Да, отправляй на гит", "текст"),
        ("да, выкатывай на прод", "deploy"),
        ("и чтото еще осталось у тебя по задачам?", "нет"),
        ("", "нет"),
        ("Моё да", "any"),
        ("Делай как лучше", "нет"),
        ("да, конечно", "any"),
        ("да нет", "нет"),
        ("а данные откуда берутся", "нет"),
        ("Юбилейный 56 подключен. не задавай таких глупых вопросов", "нет"),
        ("ротация ок", "any"),
        ("выкатывай", "deploy"),
        # Граница «да» — любой пробельный символ, как у ворот; отказ перед
        # глаголом — целым словом («мне» — не «не»).
        ("по выкату\u00a0да", "deploy"),
        ("мне публикуй", "any"),
        # Границы правил: длина ответа на вопрос, нужен ли предмет, каждое
        # вхождение глагола.
        ("да, всё ок, давай", "нет"),
        ("да, давай про деплой", "текст"),
        ("отправляй на гит, но не публикуй", "нет"),
    )
    for строка, вид in эталон:
        проба(f"вердикт эталона: «{строка}» → {вид}", вид, вердикт_согласия(строка))
    # БОЛЬНЫЕ СЛУЧАИ: отказ за типографикой и справа от глагола снимает согласие.
    for строка in ("да, выкат…нет", "выкатывай? нет", "\"нет\" выкатывай"):
        проба(f"БОЛЬНОЙ СЛУЧАЙ: «{строка}» — не согласие", "нет", вердикт_согласия(строка))
    # Признак отправки снимает вид any: «да» про push не открывает выкат.
    проба("«да, гит» — вид текст, не any", "текст", вердикт_согласия("да, гит"))
    проба("«да, отправка» — вид текст, не any", "текст", вердикт_согласия("да, отправка"))

    print(f"SELFTEST: {'зелёный' if случаи.ok else 'КРАСНЫЙ'} ({случаи.paths} путей; "
          "больной первый — «да» внутри другого слова)")
    return 0 if случаи.ok else 1


def _вердикт_для_оболочки(доводы: list[str]) -> int:
    """`patterns.py --вердикт-согласия <строка>` → вердикт строкой, rc=0.

    Диспетчер судит согласие этим ответом, а не кусками регулярок: два судьи
    расходились молча. Неизвестный ключ — rc=2, и диспетчер не признаёт
    согласием ничего."""
    if len(доводы) != 2 or доводы[0] != "--вердикт-согласия":
        print(f"patterns: неизвестная форма «{' '.join(доводы)}»", file=sys.stderr)
        return 2
    print(вердикт_согласия(доводы[1]))
    return 0


