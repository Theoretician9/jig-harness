"""Чтение shell-конфига харнеса — ОДНО место на все гейты и приборы.

Ревью 10.09.2026: функция чтения LOG_DIR из install.conf была скопирована за
одну смену четыре раза (три копии байт в байт), и ни одна не понимала
HARNESS_INSTALL_CONF — из-за чего самотест журнала пропусков подменял свой же
глобал лямбдой, чтобы не писать в боевой каталог.

Не source: гейту нельзя исполнять чужой код, ему нужны только значения.
"""
import os
import re
from pathlib import Path

ПО_УМОЛЧАНИЮ = {
    "LOG_DIR": "/var/log/harness",
    "HEARTBEAT_DIR": "/var/lib/harness/heartbeat",
}
ПУТЬ_ПО_УМОЛЧАНИЮ = "/etc/harness/install.conf"
# Пороги механики — отдельный файл от паспорта установки.
ПУТЬ_HARNESS_CONF = "/etc/harness/harness.conf"


def корень_дерева(откуда: str | None = None):
    """Каталог, внутри которого лежит `harness/config` — корень установки.

    Зачем функция. Один и тот же скрипт живёт в ДВУХ раскладках: в пакете он в
    `harness/scripts/`, после раскладки — в `scripts/` корня проекта. Жёсткое
    `parent.parent` верно ровно в одной из них, и 12.09.2026 это выстрелило
    пять раз за смену: путь `harness/harness/config`, молча пропущенные пробы
    самотеста, красный гейт. Поиск вверх по дереву верен в обеих.
    """
    from pathlib import Path as _Path
    начало = _Path(откуда or __file__).resolve()
    for каталог in [начало, *начало.parents]:
        if (каталог / "harness" / "config").is_dir():
            return каталог
    return начало.parent.parent


def из_текста(текст: str) -> dict:
    """KEY="value" → словарь из уже прочитанного текста конфига.

    Отдельно от `из_файла`, потому что у некоторых читателей текст уже на
    руках: писатель ключей сравнивает прежнее значение с новым в том же
    содержимом, которое собирается переписать. Своя регулярка на этот случай
    была одной из десяти копий (ревизия лаконичности 12.09.2026).
    """
    итог: dict = {}
    for строка in текст.splitlines():
        m = re.match(r"""\s*([A-Z][A-Z0-9_]*)\s*=\s*("[^"]*"|'[^']*'|[^#\s]*)""", строка)
        if m:
            сырое = m.group(2)
            итог[m.group(1)] = сырое[1:-1] if сырое[:1] in "\"'" else сырое
    return итог


def из_файла(путь: str) -> dict:
    """KEY="value" → словарь СТРОГО из названного файла.

    Ни умолчаний, ни слоя окружения: тому, кто судит установку (сторож И-3,
    сборщик публичного дерева, гейт чистоты), окружение не хозяин — иначе
    подставленная переменная заставляет его судить не тот проект и отвечать
    «чисто» (правило смены 12.09.2026, см. konf.sh: konf_iz_fajla).
    """
    try:
        return из_текста(Path(путь).read_text(encoding="utf-8", errors="replace"))
    except OSError:
        return {}     # файла нет — пустой словарь (гейт не падает)


def конфиг(путь: str | None = None) -> dict:
    """KEY="value" → словарь. HARNESS_INSTALL_CONF переопределяет путь."""
    итог = dict(ПО_УМОЛЧАНИЮ)
    путь = путь or os.environ.get("HARNESS_INSTALL_CONF") or ПУТЬ_ПО_УМОЛЧАНИЮ
    итог.update(из_файла(путь))
    # ОКРУЖЕНИЕ СТАРШЕ ФАЙЛА — то же правило, что у konf.sh. Без этого проба,
    # задающая PROJECT_DIR или LOG_DIR, играла на боевом у девяти питоновских
    # гейтов: bash-половину правила закрыли, python-половину нет (ревью кода
    # 12.09.2026, F1-gen-07). Пустое значение окружения значит «не задано».
    for ключ in list(итог):
        if os.environ.get(ключ):
            итог[ключ] = os.environ[ключ]
    return итог


def активная_линия() -> str:
    """Над каким направлением карты работаем: харнес, продукт или пусто.

    Один судья на всех: то же чтение было скопировано дословно в приёмку,
    прибор очереди и страницу состояния — вместе с `import re as _re` внутри
    тела (ревизия лаконичности 12.09.2026). Пустая строка значит «над всем».
    Окружение старше файла — правило то же, что у остального конфига.
    """
    из_окружения = os.environ.get("HARNESS_ACTIVE_LINE")
    if из_окружения is not None:
        return из_окружения
    путь = os.environ.get("HARNESS_CONF") or ПУТЬ_HARNESS_CONF
    return из_файла(путь).get("ACTIVE_LINE", "")


def log_dir() -> str:
    return конфиг()["LOG_DIR"]


def heartbeat_dir() -> str:
    return конфиг()["HEARTBEAT_DIR"]

# Каталог кода продукта — ДАННЫЕ установки, а не знание харнеса о чужом
# проекте. Живёт в harness.conf (пороги механики), а не в install.conf
# (паспорт установки), поэтому путь отдельный.
#
# Владелец 12.09.2026 велел проверить, что харнес очищен от имени продукта.
# Имя чужого продукта в коде общего инструмента — и утечка, и поломка у того,
# у кого продукт называется иначе: гейт импортов искал корни по вшитому имени
# и на другой установке не нашёл бы ничего, промолчав.


def product_dir() -> str:
    """Каталог кода продукта, либо "" — продукта нет (первая установка)."""
    путь = os.environ.get("HARNESS_CONF") or ПУТЬ_HARNESS_CONF
    return конфиг(путь).get("PRODUCT_DIR", "")


# Каталог стартового пакета — ДАННЫЕ установки. Путь, вшитый по одной машине,
# у нового владельца ведёт в пустоту, и проверка, которая его читает, молча
# судит по несуществующему дереву — замок чистоты публичной сборки 14.09.2026
# назвал два таких места. Домашний каталог собирается из имени агента, взятого
# в паспорте: имя пользователя — тоже данные, а не знание кода.


def katalog_paketa() -> Path:
    """Пакет-источник: окружение → STARTER_DIR → конвенция по AGENT_USER."""
    из_окружения = os.environ.get("HARNESS_STARTER")
    if из_окружения:
        return Path(из_окружения)
    путь_конфига = os.environ.get("HARNESS_CONF") or ПУТЬ_HARNESS_CONF
    названный = конфиг(путь_конфига).get("STARTER_DIR", "").strip()
    if названный:
        return Path(названный)
    паспорт = os.environ.get("HARNESS_INSTALL_CONF") or ПУТЬ_ПО_УМОЛЧАНИЮ
    агент = из_файла(паспорт).get("AGENT_USER", "").strip() or "agent"
    return Path(f"/home/{агент}/starter/STARTER-PACKAGE")


def _selftest() -> int:
    """Больные случаи разбора. Модуль стал общим для всех читателей конфига
    (ревизия лаконичности 12.09.2026 свела сюда десять своих регулярок), и
    молчаливая ошибка здесь теперь молчит везде сразу."""
    import tempfile

    путей = неудач = 0

    def проба(имя: str, ждём, факт):
        nonlocal путей, неудач
        путей += 1
        if факт == ждём:
            print(f"  ок    {имя}")
        else:
            неудач += 1
            print(f"  ПЛОХО {имя}: ждали «{ждём}», вышло «{факт}»")

    проба("простая пара", {"A": "1"}, из_текста("A=1\n"))
    проба("значение в кавычках без них и есть значение", {"B": "два слова"},
          из_текста('B="два слова"\n'))
    проба("хвостовой комментарий отброшен", {"C": "3"}, из_текста("C=3   # почему\n"))
    проба("строка-комментарий не ключ", {}, из_текста("# A=1\n"))
    проба("нижний регистр не конфиг харнеса", {}, из_текста("abc=1\n"))
    проба("пробелы вокруг знака равенства", {"D": "4"}, из_текста("  D = 4\n"))
    # БОЛЬНОЙ СЛУЧАЙ: значение с решёткой ВНУТРИ кавычек — не комментарий.
    проба("решётка внутри кавычек уцелела", {"E": "цвет#1"}, из_текста('E="цвет#1"\n'))

    with tempfile.TemporaryDirectory() as врем:
        файл = Path(врем) / "install.conf"
        файл.write_text('LOG_DIR="/своё/лог"\nPROJECT_DIR=/своё/код\n', encoding="utf-8")
        проба("из_файла читает строго файл", "/своё/лог",
              из_файла(str(файл))["LOG_DIR"])
        проба("нет файла — пустой словарь, а не отказ", {},
              из_файла(str(Path(врем) / "нет-такого")))

        прежний = os.environ.get("LOG_DIR")
        try:
            os.environ["LOG_DIR"] = "/из/окружения"
            проба("окружение старше файла", "/из/окружения",
                  конфиг(str(файл))["LOG_DIR"])
            os.environ["LOG_DIR"] = ""
            проба("пустое окружение значит «не задано»", "/своё/лог",
                  конфиг(str(файл))["LOG_DIR"])
        finally:
            os.environ.pop("LOG_DIR", None)
            if прежний is not None:
                os.environ["LOG_DIR"] = прежний

        прежняя = os.environ.get("HARNESS_ACTIVE_LINE")
        try:
            os.environ["HARNESS_ACTIVE_LINE"] = "проба"
            проба("активная линия: окружение старше файла", "проба", активная_линия())
            os.environ["HARNESS_ACTIVE_LINE"] = ""
            проба("пустая линия — законный ответ «над всем»", "", активная_линия())
        finally:
            os.environ.pop("HARNESS_ACTIVE_LINE", None)
            if прежняя is not None:
                os.environ["HARNESS_ACTIVE_LINE"] = прежняя

    проба("корень дерева найден по harness/config", True,
          (Path(корень_дерева()) / "harness" / "config").is_dir())

    print(f"SELFTEST: {'зелёный' if not неудач else 'КРАСНЫЙ'} ({путей} путей; "
          "среди них больной случай «решётка внутри кавычек»)")
    return 1 if неудач else 0


if __name__ == "__main__":
    import sys
    sys.exit(_selftest() if "--selftest" in sys.argv else print(__doc__) or 0)
