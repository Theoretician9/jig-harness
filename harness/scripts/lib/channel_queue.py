#!/usr/bin/env python3
"""Обход очереди канала: один код на двух сторожей.

СЛУЧАЙ (ревизия лаконичности 12.09.2026). `tasks-from-channel.py` сам говорил:
«устройство то же, что у orders.py, и нарочно». Повторено было не
устройство, а КОД: список сообщений по mtime, водораздел и первый запуск,
«что считается разобранным», пометка в спутник, автопочинка курсора — пять
мест дословно. Дефект такого класса чинится в одной копии и остаётся во
второй, а расходятся копии молча.

Что здесь, а что у сторожа. Здесь — механика очереди: чтение каталога,
водораздел, фильтр, курсор, спутник. У сторожа — ЕГО смысл: что считать
признаком (указание или работа), где лежит запись об исходе (ORDERS.md или
dev-map.yaml) и что сказать владельцу.

    python3 scripts/lib/channel_queue.py --selftest
"""
from __future__ import annotations

import pathlib
import re
import sys


def сообщения(обработано: pathlib.Path) -> list[tuple[float, str, pathlib.Path]]:
    """Разобранные сообщения владельца: (когда, id, файл), от старых к новым."""
    файлы = sorted(обработано.glob("*.txt"), key=lambda ф: ф.stat().st_mtime)
    return [(ф.stat().st_mtime, ф.stem, ф) for ф in файлы]


def водораздел(курсор: pathlib.Path, все: list, разобрано: str,
               с_конца: bool = False) -> float:
    """С какого момента спрашивать.

    Курсор есть — берём его. Первого запуска два вида, и это единственная
    разница между сторожами: один встаёт на последнее УЖЕ разобранное
    сообщение (`с_конца=False` — прошлое разбиралось руками и след остался),
    другой — на самое свежее (`с_конца=True`), потому что требовать разбора
    940 старых значит завести гейт, который никто не сможет позеленить, а
    такой гейт отключают.
    """
    try:
        return float(курсор.read_text(encoding="utf-8").strip())
    except (OSError, ValueError):
        есть = [когда for когда, ид, _ in все if есть_исход(ид, разобрано)]
        if есть:
            return max(есть)
        return все[-1][0] if (с_конца and все) else 0.0


def есть_исход(ид: str, разобрано: str) -> bool:
    """Исход сообщения — ССЫЛКА на него, а не упоминание номера где-нибудь.

    Две законные формы: `inbox:<ид>` (карта, её архив, маркер в указаниях) и
    строка спутника, НАЧАТАЯ номером («<ид> не-задача»). Голая подстрока
    считала исходом любое упоминание пути файла в прозе: замер 17.10.2026 по
    1441 живому сообщению дал один ложный исход — «улика
    inbox/обработано/<номер>.txt» внутри описания чужой карточки закрыла
    сообщение, которого никто не разбирал (ревью, F-gen-02).
    """
    if f"inbox:{ид}" in разобрано:
        return True
    return re.search(rf"^{re.escape(ид)}(?!\d)", разобрано, re.M) is not None


def без_исхода(все: list, с_какого: float, разобрано: str, признак,
               текст_из=None) -> list[tuple[str, pathlib.Path, str]]:
    """Сообщения новее водораздела, без записи об исходе и с признаком.

    `признак(текст) -> bool` и `текст_из(файл) -> str` задаёт сторож: одному
    важно слово указания в сыром файле, другому — текст внутри JSON апдейта.
    """
    читать = текст_из or (lambda файл: файл.read_text(encoding="utf-8", errors="replace"))
    итог = []
    for когда, ид, файл in все:
        if когда <= с_какого or есть_исход(ид, разобрано):
            continue
        текст = читать(файл)
        if текст and признак(текст):
            итог.append((ид, файл, текст))
    return итог


def подвинуть_курсор(курсор: pathlib.Path, все: list) -> None:
    """Автопочинка: разобрано всё — курсор едет вперёд сам.

    Иначе гейт требовал бы ещё и «не забыть подвинуть курсор», то есть чтобы
    кто-то помнил, — а решение, которое держится памятью, не решение.
    """
    if not все:
        return
    курсор.parent.mkdir(parents=True, exist_ok=True)
    курсор.write_text(f"{все[-1][0]:.0f}\n", encoding="utf-8")


def пометить(спутник: pathlib.Path, ид: str, почему: str = "") -> bool:
    """Записать исход в спутник. False — уже был записан раньше."""
    было = спутник.read_text(encoding="utf-8") if спутник.exists() else ""
    if ид in было:
        return False
    спутник.parent.mkdir(parents=True, exist_ok=True)
    строка = f"{ид} {почему}".rstrip()
    спутник.write_text(f"{было}{строка}\n", encoding="utf-8")
    return True


def _selftest() -> int:
    import os
    import tempfile

    from selftest_cases import Cases
    случаи = Cases()
    проба = случаи.check

    with tempfile.TemporaryDirectory() as врем:
        очередь = pathlib.Path(врем) / "обработано"
        очередь.mkdir()
        курсор = pathlib.Path(врем) / "cursor"
        спутник = pathlib.Path(врем) / "спутник.txt"

        def сообщение(ид: str, текст: str, когда: int) -> None:
            ф = очередь / f"{ид}.txt"
            ф.write_text(текст, encoding="utf-8")
            os.utime(ф, (когда, когда))

        сообщение("100", "первое, оно разобрано", 1000)
        сообщение("200", "надо сделать карту", 2000)
        сообщение("300", "спасибо", 3000)
        все = сообщения(очередь)
        проба("очередь читается по времени, от старых к новым",
              ["100", "200", "300"], [ид for _, ид, _ in все])

        признак = lambda текст: "надо" in текст            # noqa: E731
        проба("первый запуск без следа: с начала (с_конца=False)", 0.0,
              водораздел(курсор, все, "", с_конца=False))
        проба("первый запуск без следа: с конца (с_конца=True)", 3000.0,
              водораздел(курсор, все, "", с_конца=True))
        проба("первый запуск встаёт на последнее разобранное", 1000.0,
              водораздел(курсор, все, "100"))

        # БОЛЬНОЙ СЛУЧАЙ «курсор отстал»: он показывает на старое сообщение, а
        # свежие с признаком уже разобраны — гейт обязан молчать и подвинуть
        # курсор сам, иначе он перечитывает разобранное вечно.
        курсор.write_text("500\n", encoding="utf-8")
        проба("курсор старше очереди — берётся как есть", 500.0,
              водораздел(курсор, все, ""))
        долги = без_исхода(все, 500.0, "200", признак)
        проба("сообщение с исходом долгом не считается", [], долги)
        подвинуть_курсор(курсор, все)
        проба("курсор подвинут на последнее сообщение", 3000.0,
              водораздел(курсор, все, ""))

        долги = без_исхода(все, 0.0, "", признак)
        проба("долг найден по признаку", ["200"], [ид for ид, _, _ in долги])
        проба("сообщение без признака в долги не попадает", 1, len(долги))

        проба("пометка записана", True, пометить(спутник, "200", "не задача"))
        проба("вторая пометка того же — нет", False, пометить(спутник, "200", "ещё раз"))
        проба("спутник держит исход", True, "200 не задача" in
              спутник.read_text(encoding="utf-8"))

        # Текст берётся способом сторожа: у одного сырой файл, у другого JSON.
        свой = без_исхода(все, 0.0, "", lambda т: т == "ПОДМЕНА",
                          текст_из=lambda ф: "ПОДМЕНА")
        проба("текст читается способом сторожа", 3, len(свой))

    print(f"SELFTEST: {'зелёный' if случаи.ok else 'КРАСНЫЙ'} ({случаи.paths} путей; "
          "среди них больной случай «курсор отстал»)")
    return 0 if случаи.ok else 1


if __name__ == "__main__":
    sys.exit(_selftest() if "--selftest" in sys.argv else print(__doc__) or 0)
