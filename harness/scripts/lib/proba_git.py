#!/usr/bin/env python3
"""Общая проба самотестов: гейт обязан краснеть, когда git не ответил.

Три гейта судят содержимое, взятое из git (кириллица в именах, пайплайн,
потеря задач). До 14.09.2026 все трое на отказе git печатали «чисто» и
возвращали 0 — «нечем судить» выглядело как «нарушений нет». Проба у них
одна: подменить git падающим и убедиться, что гейт отказывает КОДОМ и
называет причину. Копий этой пробы быть не должно — починка в одной из них
осталась бы незамеченной в двух других.

Судится боевой путь целиком, подпроцессом: чистые функции отказа git не
видят. Ожидается не просто «код не ноль» — код 1 И слово из СВОЕГО сообщения
гейта: 127 («команды нет») зеленит пробу впустую.
"""
from __future__ import annotations

import os
import subprocess
import sys
import tempfile
from pathlib import Path


def гейт_краснеет_без_git(гейт: str, ввод: str, слово: str,
                          окружение: dict[str, str] | None = None) -> int:
    """0 — гейт отказал как должно; 1 — прошёл как «нарушений нет».

    гейт — путь к файлу гейта, ввод — что подаётся ему на stdin (как в
    pre-commit), слово — кусок сообщения об отказе, по которому видно, что
    отказ ИМЕННО про непрочитанный git.
    """
    with tempfile.TemporaryDirectory() as тмп:
        падающий = Path(тмп) / "git"
        падающий.write_text("#!/bin/sh\necho 'fatal: проба отказа' >&2\nexit 1\n")
        падающий.chmod(0o755)
        среда = dict(os.environ, PATH=f"{тмп}:{os.environ.get('PATH', '')}")
        среда.update(окружение or {})
        итог = subprocess.run([sys.executable, гейт], input=ввод,
                              capture_output=True, text=True, env=среда)
    if итог.returncode == 1 and слово in итог.stdout:
        print("  ок    БОЛЬНОЙ СЛУЧАЙ: git не ответил — гейт красный и называет причину")
        return 0
    print(f"  ПЛОХО отказ git прошёл как «нарушений нет»: код {итог.returncode}, "
          f"вывод «{итог.stdout.strip()[:120]}»")
    return 1
