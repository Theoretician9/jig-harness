"""Заметки релиза простым языком: разбор файла, суд записи, выдержка для канала.

Файл ЧТО-НОВОГО.md лежит в корне пакета и едет в публичную сборку. Запись —
раздел `## дата — название`; новые сверху. Внутри три подраздела: «Исправлено»,
«Добавлено», «Что изменилось для вас». Читатель — человек, не разработчик:
номера правок, имена файлов и словарь смены в запись не пускаются.
"""
import re

ИМЯ_ФАЙЛА = "ЧТО-НОВОГО.md"
ДЛЯ_ВАС = "Что изменилось для вас"
СПИСКИ = ("Исправлено", "Добавлено")
КРАТКО_МАКС = 220

# Словарь смены — ДАННЫЕ: начало слова, регистр не важен (склонения ловятся).
ЖАРГОН = ("гейт", "коммит", "демон", "рефакторинг", "хэш", "dev-map", "мутаци",
          "pipeline", "тред", "ревью кода", "заглушк")
ФОРМЫ = (
    (re.compile(r"(?<![0-9a-f])(?=[0-9a-f]*[0-9])(?=[0-9a-f]*[a-f])[0-9a-f]{7,40}(?![0-9a-f])"), "номер правки"),
    (re.compile(r"\b(?:hr|pr|pb)\.[a-z0-9][a-z0-9.-]+"), "номер карточки"),
    (re.compile(r"\b[\w-]+\.(?:py|sh|yaml|yml|json|conf)\b"), "имя файла"),
    (re.compile(r"\bscripts/|\bharness/"), "путь"),
)


def записи(текст: str) -> list:
    """[(заголовок, {подраздел: [строки-пункты]})], в порядке файла (новые сверху)."""
    итог, подраздел = [], None
    for строка in текст.splitlines():
        if строка.startswith("## "):
            итог.append((строка[3:].strip(), {}))
            подраздел = None
        elif строка.startswith("### ") and итог:
            подраздел = строка[4:].strip()
            итог[-1][1][подраздел] = []
        elif итог and подраздел and re.match(r"\s*[-*] +\S", строка):
            итог[-1][1][подраздел].append(re.sub(r"^\s*[-*] +", "", строка).strip())
    return итог


def жаргон_в(текст: str) -> str | None:
    """Что в тексте не для человека: найденное слово или вид следа; чисто — None."""
    низ = текст.lower()
    for корень in ЖАРГОН:
        if re.search(r"(?<![а-яёa-z])" + re.escape(корень), низ):
            return корень
    for форма, вид in ФОРМЫ:
        найдено = форма.search(текст)
        if найдено:
            return f"{вид} «{найдено.group(0)}»"
    return None


def отказы(текст: str, вышедшие: set) -> list:
    """Причины, по которым ВЕРХНЯЯ запись не годится для выпуска; пусто — годится."""
    разобрано = записи(текст)
    if not разобрано:
        return ["в файле нет ни одной записи (раздел «## дата — название»)"]
    заголовок, части = разобрано[0]
    если = []
    if заголовок in вышедшие:
        return [f"запись «{заголовок}» уже выходила в прошлом выпуске: нужна новая сверху"]
    if not части.get(ДЛЯ_ВАС):
        если.append(f"раздел «{ДЛЯ_ВАС}» пуст или его нет")
    if not any(части.get(имя) for имя in СПИСКИ):
        если.append("ни «Исправлено», ни «Добавлено» не заполнено")
    for имя, пункты in части.items():
        for пункт in пункты:
            беда = жаргон_в(пункт)
            if беда:
                если.append(f"жаргон в «{имя}»: {беда}")
    return если


def кратко(текст: str) -> str:
    """Одна строка для сообщения владельцу; нет записи или жаргон — пустая."""
    разобрано = записи(текст)
    пункты = разобрано[0][1].get(ДЛЯ_ВАС) if разобрано else None
    if not пункты or жаргон_в(пункты[0]):
        return ""
    строка = пункты[0]
    if len(строка) > КРАТКО_МАКС:
        строка = строка[:КРАТКО_МАКС - 1].rsplit(" ", 1)[0].rstrip(" ,;:") + "…"
    return строка
