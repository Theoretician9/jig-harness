#!/usr/bin/env python3
"""Проверка носителя класса C2 — живого вызова инструмента или библиотеки.

Откуда взято. Спека `docs/specs/2026-10-15-живая-проверка-механизмов.md` §3.1,
класс C2: «вызван с настоящим входом, вывод прочитан и записан». Носителя этому
предикату в коде не было: 24 механизма класса C2 оставались непроверенными, и
доказательством служило бы слово проверяющего.

Что охраняется сверх буквы спеки — каждое правило из пережитого случая:

1. **Отказ механизма — не доказательство.** Инструмент, который на здоровой
   машине отвечает ненулевым кодом, это косяк, и называть его «ок» нельзя.
2. **Молчащему механизму цитировать нечего.** Если в выводе нет строки длиной
   от 12 знаков, запись доказывалась бы моим эхом, а не чужим текстом
   (находка 17.10.2026 — карточка `hr.mehanizm-otvechaet-tolko-kodom`).
3. **Команда берётся ИЗ ДАННЫХ, а не из паспорта.** В реестре поле
   «проверяется» смешано с прозой («python3 x.py (12 путей)»), и разбор прозы
   однажды позвал бы не то. Нет команды в данных — отказ со своим словом.
4. **Класс судится по данным.** Механизм другого класса этим носителем не
   доказывается: у каждого класса свой предикат.
5. **Без «--записать» состояние не меняется** — иначе проба играет на
   производстве.

Прогон: python3 scripts/test_live_check_tool.py
Код возврата: 0 — все случаи зелёные, 1 — хоть один плохой.
"""
from __future__ import annotations

import os
import pathlib
import subprocess
import sys
import tempfile

import yaml

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
# Путь прибора — из окружения, если задан: так мутационный прогон подсовывает
# ИСПОРЧЕННУЮ копию и требует красного ([[probe-loads-the-live-mechanism]]).
ПРИБОР = pathlib.Path(os.environ.get("HARNESS_LIVE_CHECK_C2_TOOL")
                      or КОРЕНЬ / "scripts" / "live-check-tool.py")

хорошо = 0
плохо = 0


def случай(имя: str, условие: bool, пояснение: str = "") -> None:
    global хорошо, плохо
    if условие:
        хорошо += 1
        print(f"  ок    {имя}")
    else:
        плохо += 1
        print(f"  ПЛОХО {имя}{(': ' + пояснение) if пояснение else ''}")


ГОВОРЛИВЫЙ = """#!/usr/bin/env bash
echo "инструмент ответил своим текстом о настоящем входе"
exit 0
"""
МОЛЧУН = """#!/usr/bin/env bash
echo "ок"
exit 0
"""
ОТКАЗНИК = """#!/usr/bin/env bash
echo "инструмент отказал на здоровой машине"
exit 3
"""
# Код 2 — тот же, которым обёртка отдаёт СВОИ отказы. Живой случай
# 18.10.2026: клиент панели на чужом номере отвечает «ссылка входа выдаётся
# только владельцу» и кодом 2, а прибор винил невиновную обёртку.
ОТКАЗНИК_КОД_2 = """#!/usr/bin/env bash
echo "служба отказала: номер не владельца"
exit 2
"""
# Сон короткий НАРОЧНО: предел обёртки в случае задаётся доводом (2 с), а
# тридцатисекундный сон делал мутационный прогон этой пробы втрое дороже
# ([[a-probe-must-not-sleep-the-production-ceiling]]).
ДОЛГИЙ = """#!/usr/bin/env bash
echo "долгий инструмент начал работу и говорит об этом"
sleep 6
"""


def двор(*, команды: dict | None = None, классы: dict | None = None) -> pathlib.Path:
    """Свой двор: три игрушечных механизма, реестр, классы и команды в данных."""
    путь = pathlib.Path(tempfile.mkdtemp(prefix="живая-c2-"))
    (путь / "scripts").mkdir()
    for имя, текст in (("govorlivyj.sh", ГОВОРЛИВЫЙ), ("molchun.sh", МОЛЧУН),
                       ("otkaznik.sh", ОТКАЗНИК), ("dolgij.sh", ДОЛГИЙ),
                       ("otkaznik2.sh", ОТКАЗНИК_КОД_2)):
        файл = путь / "scripts" / имя
        файл.write_text(текст, encoding="utf-8")
        файл.chmod(0o755)
    механизмы = [{"файл": f"scripts/{имя}", "вид": "гейт", "имя": имя,
                  "проверяется": f"bash scripts/{имя} --selftest (столько-то путей)"}
                 for имя in ("govorlivyj.sh", "molchun.sh", "otkaznik.sh",
                             "dolgij.sh", "otkaznik2.sh")]
    (путь / "mechanisms.yaml").write_text(
        yaml.dump(механизмы, allow_unicode=True), encoding="utf-8")
    (путь / "classes.yaml").write_text(yaml.dump(
        {"классы": классы if классы is not None else {
            "scripts/govorlivyj.sh": {"класс": "C2"},
            "scripts/molchun.sh": {"класс": "C2"},
            "scripts/otkaznik.sh": {"класс": "C2"},
            "scripts/dolgij.sh": {"класс": "C2"},
            "scripts/otkaznik2.sh": {"класс": "C2"}}},
        allow_unicode=True), encoding="utf-8")
    (путь / "state.yaml").write_text(
        yaml.dump({"проверено": {}}, allow_unicode=True), encoding="utf-8")
    (путь / "commands.yaml").write_text(yaml.dump(
        {"команды": команды if команды is not None else {
            "scripts/govorlivyj.sh": "bash scripts/govorlivyj.sh --живьём",
            "scripts/molchun.sh": "bash scripts/molchun.sh --живьём",
            "scripts/otkaznik.sh": "bash scripts/otkaznik.sh --живьём",
            "scripts/dolgij.sh": "bash scripts/dolgij.sh --живьём",
            "scripts/otkaznik2.sh": "bash scripts/otkaznik2.sh --живьём"}},
        allow_unicode=True), encoding="utf-8")
    # Обёртка следа нужна прибору настоящая: след пишет ОНА, и проба судит её
    # шапку. Копируется, а не подменяется заглушкой.
    (путь / "scripts" / "live-check.sh").write_bytes(
        (КОРЕНЬ / "scripts" / "live-check.sh").read_bytes())
    return путь


def прогон(двор_путь: pathlib.Path, *доводы: str,
           среда: dict | None = None) -> tuple[int, str]:
    свои = среда or {}
    среда = dict(os.environ)
    среда.update({
        "HARNESS_LIVE_CHECK_REPO": str(двор_путь),
        "HARNESS_MECHANISMS": str(двор_путь / "mechanisms.yaml"),
        "HARNESS_LIVE_CHECK_CLASSES": str(двор_путь / "classes.yaml"),
        "HARNESS_LIVE_CHECK_STATE": str(двор_путь / "state.yaml"),
        "HARNESS_LIVE_CHECK_COMMANDS": str(двор_путь / "commands.yaml"),
        "HARNESS_LIVE_CHECK_TOOL_TRACE_DIR": str(двор_путь / "следы"),
    })
    # Своё окружение случая — ПОСЛЕДНИМ: иначе двор затирает то, что случай
    # нарочно подменяет (предел времени, каталог следов).
    среда.update(свои)
    готово = subprocess.run([sys.executable, str(ПРИБОР), *доводы],
                            capture_output=True, text=True, env=среда, timeout=300)
    return готово.returncode, готово.stdout + готово.stderr


def состояние(двор_путь: pathlib.Path) -> dict:
    данные = yaml.safe_load((двор_путь / "state.yaml").read_text(encoding="utf-8")) or {}
    return данные.get("проверено") or {}


def main() -> int:
    боевые = {п: (КОРЕНЬ / п).read_bytes() for п in
              ("harness/config/live-check-state.yaml", "harness/config/live-check-classes.yaml")}

    # ── БОЛЬНОЙ СЛУЧАЙ ПЕРВЫМ: механизм отказал — это косяк, а не «ок» ──────
    д = двор()
    код, вывод = прогон(д, "scripts/otkaznik.sh", "--записать")
    случай("БОЛЬНОЙ СЛУЧАЙ: механизм отказал — отказ прибора, записи нет",
           код == 1 and "механизм отказал" in вывод
           and "scripts/otkaznik.sh" not in состояние(д),
           f"код {код}, вывод {вывод[:200]!r}")

    # ── Молчащий механизм: цитировать нечего ───────────────────────────────
    д = двор()
    код, вывод = прогон(д, "scripts/molchun.sh", "--записать")
    случай("БОЛЬНОЙ СЛУЧАЙ: в выводе нет строки от 12 знаков — цитировать нечего",
           код == 1 and "цитировать нечего" in вывод
           and "scripts/molchun.sh" not in состояние(д),
           f"код {код}, вывод {вывод[:200]!r}")

    # ── Команды в данных нет: паспорт разбирать нельзя ─────────────────────
    д = двор(команды={})
    код, вывод = прогон(д, "scripts/govorlivyj.sh", "--записать")
    случай("БОЛЬНОЙ СЛУЧАЙ: команды в данных нет — отказ, а не разбор паспорта",
           код == 1 and "команды в данных нет" in вывод
           and "scripts/govorlivyj.sh" not in состояние(д),
           f"код {код}, вывод {вывод[:200]!r}")

    # ── Чужой класс этим носителем не доказывается ─────────────────────────
    д = двор(классы={"scripts/govorlivyj.sh": {"класс": "C1"}})
    код, вывод = прогон(д, "scripts/govorlivyj.sh", "--записать")
    случай("БОЛЬНОЙ СЛУЧАЙ: механизм не класса C2 — отказ своим словом",
           код == 1 and "класс" in вывод
           and "scripts/govorlivyj.sh" not in состояние(д),
           f"код {код}, вывод {вывод[:200]!r}")

    # ── Здоровый случай: запись с цитатой ИЗ СЛЕДА и след с шапкой обёртки ──
    д = двор()
    код, вывод = прогон(д, "scripts/govorlivyj.sh", "--записать")
    запись = состояние(д).get("scripts/govorlivyj.sh") or {}
    след = д / "следы" / "scripts-govorlivyj.sh.log"
    текст_следа = след.read_text(encoding="utf-8") if след.is_file() else ""
    случай("здоровый случай: исход «ок», цитата из следа, след написан обёрткой",
           код == 0 and запись.get("исход") == "ок"
           and (запись.get("увидели") or "") in текст_следа
           and len(запись.get("увидели") or "") >= 12
           and "--- вывод механизма ---" in текст_следа
           and запись.get("след", "").endswith("scripts-govorlivyj.sh.log"),
           f"код {код}, запись {запись}, следа знаков {len(текст_следа)}")

    # ── Без «--записать» состояние не меняется ─────────────────────────────
    д = двор()
    код, вывод = прогон(д, "scripts/govorlivyj.sh")
    случай("без «--записать» состояние не меняется",
           код == 0 and состояние(д) == {},
           f"код {код}, состояние {состояние(д)}")

    # ── «--всё» берёт только C2 без исхода ─────────────────────────────────
    д = двор()
    код, вывод = прогон(д, "--всё")
    случай("«--всё» называет все три механизма класса C2",
           "scripts/govorlivyj.sh" in вывод and "scripts/molchun.sh" in вывод
           and "scripts/otkaznik.sh" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    # ── Находки ревью безопасности 17.10.2026 ──────────────────────────────
    # F-sec-01: команда из данных уходила в `bash -c` МИМО сторожа команд, и
    # ни одно правило И-1/И-2 к ней не применялось.
    д = двор(команды={"scripts/govorlivyj.sh": "dropdb --help"})
    код, вывод = прогон(д, "scripts/govorlivyj.sh", "--записать")
    случай("БОЛЬНОЙ СЛУЧАЙ: команду, которую отменяет сторож, прибор не зовёт",
           код == 1 and "сторож" in вывод
           and "scripts/govorlivyj.sh" not in состояние(д),
           f"код {код}, вывод {вывод[:200]!r}")

    # F-gen-01 (ревью общего профиля 17.10): все 35 боевых команд оказались
    # ПОБУКВЕННЫМ повтором поля «проверяется» из реестра, то есть живая проверка
    # доказывалась ПЕРЕСКАЗОМ САМОТЕСТА. Владелец 15.10: «проверить не просто
    # тестами, а именно наживую, в практике».
    д = двор(команды={"scripts/govorlivyj.sh": "bash scripts/govorlivyj.sh --selftest"})
    код, вывод = прогон(д, "scripts/govorlivyj.sh", "--записать")
    случай("БОЛЬНОЙ СЛУЧАЙ: команда — пересказ самотеста из паспорта — отказ",
           код == 1 and "самотест" in вывод
           and "scripts/govorlivyj.sh" not in состояние(д),
           f"код {код}, вывод {вывод[:200]!r}")

    # Законная дверь правила: команда БЕЗ ключа самотеста короче паспортной, и
    # это ДРУГОЙ вызов. Отказ ей закрыл бы живую проверку у всякого механизма,
    # чей живой вход — тот же файл без ключа.
    д = двор(команды={"scripts/govorlivyj.sh": "bash scripts/govorlivyj.sh"})
    код, вывод = прогон(д, "scripts/govorlivyj.sh", "--записать")
    случай("команда короче паспортной — живой вызов, а не пересказ",
           код == 0 and (состояние(д).get("scripts/govorlivyj.sh") or {}).get("исход") == "ок",
           f"код {код}, вывод {вывод[:200]!r}")

    # F-gen-02: запись обязана СЛИВАТЬСЯ с чужими записями, а не заменять раздел.
    д = двор()
    (д / "state.yaml").write_text(
        yaml.dump({"проверено": {"scripts/chuzhoj.sh": {"исход": "ок",
                                                        "живьём": "чужая работа"}}},
                  allow_unicode=True), encoding="utf-8")
    код, вывод = прогон(д, "scripts/govorlivyj.sh", "--записать")
    случай("БОЛЬНОЙ СЛУЧАЙ: чужая запись цела после записи своей",
           (состояние(д).get("scripts/chuzhoj.sh") or {}).get("исход") == "ок"
           and (состояние(д).get("scripts/govorlivyj.sh") or {}).get("исход") == "ок",
           f"код {код}, состояние {list(состояние(д))}")

    # F-gen-03: запись поверх ЧУЖОГО доказательства уносит его молча — за смену
    # так снесено четыре записи, у owner_word.py живое наблюдение владельца.
    д = двор()
    (д / "state.yaml").write_text(
        yaml.dump({"проверено": {"scripts/govorlivyj.sh": {
            "живьём": "живое наблюдение прошлой смены, не моя приставка"}}},
                  allow_unicode=True), encoding="utf-8")
    код, вывод = прогон(д, "scripts/govorlivyj.sh", "--записать")
    запись = состояние(д).get("scripts/govorlivyj.sh") or {}
    случай("БОЛЬНОЙ СЛУЧАЙ: прежнее доказательство не затирается молча",
           "живое наблюдение прошлой смены" in str(запись),
           f"код {код}, запись {str(запись)[:200]!r}")

    # F-gen-04: «--всё» обязано брать только НЕПРОВЕРЕННЫХ — иначе повторный зов
    # перезаписывает уже доказанное и его след.
    д = двор()
    (д / "state.yaml").write_text(
        yaml.dump({"проверено": {"scripts/molchun.sh": {"исход": "ок"}}},
                  allow_unicode=True), encoding="utf-8")
    код, вывод = прогон(д, "--всё")
    случай("БОЛЬНОЙ СЛУЧАЙ: «--всё» не зовёт механизм с готовым исходом",
           "scripts/molchun.sh" not in вывод and "scripts/govorlivyj.sh" in вывод,
           f"код {код}, вывод {вывод[:200]!r}")

    # F-sec-03: след читался ПО ИМЕНИ в ОБЩЕМ каталоге, и прогон соседа по тому
    # же механизму успевал подменить файл ВО ВРЕМЯ зова — цитатой «проверено
    # живьём» становился чужой текст. Случай воспроизводит именно гонку: сосед
    # пишет общий след через секунду после начала трёхсекундного зова.
    д = двор(команды={"scripts/govorlivyj.sh":
                      "sleep 2; bash scripts/govorlivyj.sh --живьём"})
    общий_след = д / "следы" / "scripts-govorlivyj.sh.log"
    чужой = ("время: 2026-10-17T01:00:00+05:00\nмеханизм: scripts/govorlivyj.sh\n"
             "команда: bash -c echo соседний прибор\nпользователь: agent\n"
             "--- вывод механизма ---\n"
             "ЧУЖОЙ текст соседнего прибора длиной больше двенадцати знаков\n")
    сосед = subprocess.Popen(
        ["bash", "-c", f'sleep 0.7; mkdir -p "{общий_след.parent}"; '
                       f'printf %s "$1" > "{общий_след}"', "_", чужой])
    код, вывод = прогон(д, "scripts/govorlivyj.sh", "--записать")
    сосед.wait(timeout=30)
    запись = состояние(д).get("scripts/govorlivyj.sh") or {}
    случай("БОЛЬНОЙ СЛУЧАЙ: след соседа по тому же механизму цитатой не становится",
           "ЧУЖОЙ" not in (запись.get("увидели") or ""),
           f"код {код}, увидели {запись.get('увидели')!r}")

    # F-sec-05: доказанное писалось ОДИН раз в конце, и обрыв уносил всё.
    д = двор()
    код, вывод = прогон(д, "scripts/govorlivyj.sh", "scripts/otkaznik.sh", "--записать")
    случай("доказанное записано, хотя следующий механизм отказал",
           код == 1 and (состояние(д).get("scripts/govorlivyj.sh") or {}).get("исход") == "ок",
           f"код {код}, состояние {list(состояние(д))}")

    # F-sec-05, второй путь: предел времени у прибора обязан быть БОЛЬШЕ предела
    # обёртки, иначе оборванным оказывается прибор, а не механизм.
    д = двор()
    среда_предел = {"HARNESS_LIVE_CHECK_TIMEOUT": "2"}
    код, вывод = прогон(д, "scripts/dolgij.sh", "--записать", среда=среда_предел)
    случай("механизм, оборванный пределом обёртки, назван ПРЕДЕЛОМ, а не отказом",
           код == 1 and "ПРЕДЕЛОМ" in вывод
           and "scripts/dolgij.sh" not in состояние(д),
           f"код {код}, вывод {вывод[:200]!r}")

    # F-gen-05: отказ ОБЁРТКИ (её код 2) выдавался за отказ механизма, и
    # проверяющего отправляли заводить карточку на невиновного.
    д = двор()
    код, вывод = прогон(д, "scripts/govorlivyj.sh", "--записать",
                        среда={"HARNESS_LIVE_CHECK_TOOL_TRACE_DIR": "/proc/нельзя-писать"})
    случай("БОЛЬНОЙ СЛУЧАЙ: отказ обёртки назван отказом ОБЁРТКИ",
           код == 1 and "ОБЁРТКА" in вывод
           and "scripts/govorlivyj.sh" not in состояние(д),
           f"код {код}, вывод {вывод[:250]!r}")

    # БОЛЬНОЙ СЛУЧАЙ 18.10.2026: механизм отказал СВОИМ кодом 2 — тем же, каким
    # обёртка отдаёт свои отказы. Прибор винил обёртку, и проверяющего отправляли
    # искать дефект в невиновном носителе.
    д = двор()
    код, вывод = прогон(д, "scripts/otkaznik2.sh", "--записать")
