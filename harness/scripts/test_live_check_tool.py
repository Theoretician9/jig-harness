#!/usr/bin/env python3
"""Проверка носителя класса C2 — живого вызова инструмента или библиотеки.

Откуда взято. Спека `docs/specs/2026-10-15-живая-проверка-механизмов.md` §3.1,
класс C2: «вызван с настоящим входом, вывод прочитан и записан». Носителя этому
предикату в коде не было: 24 механизма класса C2 оставались непроверенными, и
доказательством служило бы слово проверяющего.

Что охраняется сверх буквы спеки — каждое правило из пережитого случая:

1. **Отказ механизма — не доказательство.** Инструмент, который на здоровой
   машине отвечает ненулевым кодом, это косяк, и называть его «ок» нельзя.
2. **Молчащему механизму цитировать нечего.** Если в выводе нет строки длиной
   от 12 знаков, запись доказывалась бы моим эхом, а не чужим текстом
   (находка 17.10.2026 — карточка `hr.mehanizm-otvechaet-tolko-kodom`).
3. **Команда берётся ИЗ ДАННЫХ, а не из паспорта.** В реестре поле
   «проверяется» смешано с прозой («python3 x.py (12 путей)»), и разбор прозы
   однажды позвал бы не то. Нет команды в данных — отказ со своим словом.
4. **Класс судится по данным.** Механизм другого класса этим носителем не
   доказывается: у каждого класса свой предикат.
5. **Без «--записать» состояние не меняется** — иначе проба играет на
   производстве.
6. **Опасный механизм (C3) зовётся только своей командой стенда из данных**,
   а «не-проверяемо» и «ждёт» пишутся без вызова и только названному
   механизму: живой вызов опасного на производстве необратим (спека §3.1, C3).

Прогон: python3 scripts/test_live_check_tool.py
Код возврата: 0 — все случаи зелёные, 1 — хоть один плохой.
"""
from __future__ import annotations

import datetime
import json
import os
import pathlib
import re
import shutil
import subprocess
import sys
