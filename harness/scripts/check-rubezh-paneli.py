#!/usr/bin/env python3
"""Гейт: рубеж панели существует и не разошёлся с кодом, который на него оперся.

СЛУЧАЙ, ради которого заведён (13.09.2026, ревизия безопасности 12.09).
Защита панели в четырёх местах кода опирается на конфиг nginx: свой origin
(`server.py:20-21`), закрытые снаружи `/vnutr/*` (`:403-418`), адрес гостя из
`X-Real-IP` (`:284`), cookie с флагом `Secure` (`:526`). Самого конфига не
было ни в репозитории, ни в пакете — код считал данностью то, чего на чистой
установке не возникает вовсе.

ЖИВАЯ УЛИКА того же дня: `curl -sk -H 'Host: bogus.example' https://127.0.0.1/`
отдавал 200 и страницу панели. Явного `default_server` для 443 не было ни у
кого, nginx отвечал ПЕРВЫМ блоком по алфавиту — им оказалась панель. «Свой
origin» не выполнялся: панель жила под любым именем и по голому IP.

Три решения, каждое — из находки ревью спеки:

* граница по `PANEL_URL`, а не по наличию nginx (S-03): пусто — рубеж не
  требуется; непусто — ссылка владельцу выдана, и рубеж ОБЯЗАН быть;
* судится ЭФФЕКТИВНАЯ конфигурация (`nginx -T`), а не один файл (S-04): вывод
  панели вторым `proxy_pass` из конфига продукта — та самая беда общего
  origin, и по одному файлу она невидима;
* признак «nginx есть» — не PATH (S-02): под агентом `command -v nginx` пусто,
  бинарь лежит в `/usr/sbin`, а служба активна.

Запуск:
    python3 scripts/check-rubezh-paneli.py
    python3 scripts/check-rubezh-paneli.py --selftest
Код выхода: 0 — рубеж цел или не требуется, 1 — разошёлся с кодом.
"""
from __future__ import annotations

import os
import re
import shutil
import subprocess
import sys
from pathlib import Path
from urllib.parse import urlparse

_ЗДЕСЬ = Path(__file__).resolve().parent
sys.path.insert(0, str(_ЗДЕСЬ / "lib"))
from konf import из_файла, корень_дерева  # noqa: E402

# Корень ищется ВВЕРХ по дереву: один и тот же файл живёт в двух раскладках —
# в пакете рядом с panel/, после раскладки в scripts/ корня проекта. Жёсткий
# parent.parent верен ровно в одной, и живая проба в контейнере это показала.
КОРЕНЬ = Path(корень_дерева(__file__))

# Точки подстановки — из окружения: их задают и пробы, и сборщик, который
# зовёт этот гейт вместо собственной копии правил (ревью кода F-17).
КОНФИГ = Path(os.environ.get("HARNESS_CONF", "/etc/harness/harness.conf"))
# PANEL_URL читается из ОБОИХ файлов, как его читает сборщик (konf_iz_fajla):
# ключ, положенный установкой в install.conf, иначе прошёл бы мимо гейта, и он
# молчал бы при выведенной наружу панели (ревью кода 13.09.2026, F-10).
def _паспорт_установки() -> Path:
    """Путь читается В МОМЕНТ вызова, а не при импорте: иначе проба, задавшая
    окружение после загрузки модуля, судила бы боевой паспорт."""
    return Path(os.environ.get("HARNESS_INSTALL_CONF",
                               "/etc/harness/install.conf"))
NGINX_DIR = Path(os.environ.get("NGINX_DIR", "/etc/nginx"))
# Полным путём, а не именем: PATH агента не содержит /usr/sbin, и поиск по
# имени объявил бы исправную машину машиной без nginx (ревью спеки S-02).
NGINX_BIN = os.environ.get("NGINX_BIN", "/usr/sbin/nginx")
ЮНИТ = Path(os.environ.get("PANEL_UNIT", "/etc/systemd/system/harness-panel.service"))
ШАБЛОН = КОРЕНЬ / "harness" / "panel" / "nginx-panel.conf.in"

# Опоры кода: строка шаблона → чем она держится в server.py.
ОПОРЫ_ШАБЛОНА = {
    "/vnutr/": "внутренние маршруты закрыты снаружи (server.py:403-418)",
    "X-Real-IP": "адрес гостя ставит наш nginx (server.py:284)",
    "default_server": "чужое имя получает обрыв, а не панель (улика 13.09.2026)",
    "listen 443 ssl": "cookie пропуска идёт с Secure (server.py:526)",
    "@PANEL_HOST@": "свой origin, а не общий с продуктом (server.py:20-21)",
    "@PANEL_PORT@": "порт панели подставляется, а не вшит",
}


def шаблон_цел(путь: Path = ШАБЛОН) -> list[str]:
    """Опоры, которых в шаблоне НЕТ. Пустой список — шаблон целый."""
    try:
        текст = путь.read_text(encoding="utf-8")
    except OSError:
        return [f"шаблона нет: {путь}"]
    голый = _без_комментариев(текст)
    return [f"{опора} — {зачем}" for опора, зачем in ОПОРЫ_ШАБЛОНА.items()
            if опора not in голый]


def _без_комментариев(текст: str) -> str:
    """Комментарии снимаются ДО суда: закомментированная директива не работает,
    а подстрокой по файлу неотличима от живой (ревью спеки S-08)."""
    return "\n".join(re.sub(r"#.*$", "", строка) for строка in текст.splitlines())


def эффективная_конфигурация(nginx_bin: str) -> tuple[str, str]:
    """(дамп `nginx -T`, причина отказа). Ровно одно из двух непусто."""
    if not Path(nginx_bin).exists() and not shutil.which(nginx_bin):
        return "", f"nginx не найден по пути {nginx_bin}"
    готово = subprocess.run(["sudo", "-n", nginx_bin, "-T"],
                            capture_output=True, text=True, timeout=60)
    if готово.returncode != 0:
        беда = (готово.stderr or готово.stdout).strip().splitlines()
        return "", ("nginx -T отказал: "
                    + (беда[0] if беда else f"код {готово.returncode}"))
    return готово.stdout, ""


def блоки_server(дамп: str) -> list[tuple[str, str]]:
    """(файл, тело server-блока) из вывода `nginx -T`.

    Имя файла — то, каким его печатает nginx (путь из include, симлинк не
    разворачивается): именно его гейт называет в отказе.
    """
    файл = "?"
    найдено: list[tuple[str, str]] = []
    тело: list[str] = []
    глубина = 0
    for строка in дамп.splitlines():
        метка = re.match(r"#\s*configuration file (.+):\s*$", строка)
        if метка and глубина == 0:
            файл = метка.group(1)
            continue
        # Кавычки выбрасываются ДО подсчёта скобок: «add_header Set-Cookie
        # "a=}"» закрывал блок раньше времени, и гейт говорил «рубежа нет»
        # вместо правды (ревью кода 13.09.2026, F-15).
        голая = re.sub(r"'[^']*'|\"[^\"]*\"", "", re.sub(r"#.*$", "", строка))
        if глубина == 0:
            if re.match(r"\s*server\s*\{", голая):
                глубина = голая.count("{") - голая.count("}")
                тело = [голая]
                if глубина == 0:
                    найдено.append((файл, "\n".join(тело)))
            continue
        тело.append(голая)
        глубина += голая.count("{") - голая.count("}")
        if глубина == 0:
            найдено.append((файл, "\n".join(тело)))
    return найдено


def порт_панели(юнит: Path) -> int | None:
    """Порт РАБОТАЮЩЕЙ панели: сначала установленный юнит, потом его файл.

    Работает то, что стоит, а не то, что лежит в репозитории (ревью спеки
    S-07): юнит могли поставить раньше или править руками.
    """
    for источник in (_порт_из_systemd(), _порт_из_файла(юнит)):
        if источник:
            return источник
    return None


def _порт_из_systemd() -> int | None:
    try:
        готово = subprocess.run(
            ["systemctl", "show", "harness-panel", "-p", "ExecStart"],
            capture_output=True, text=True, timeout=20)
    except (OSError, subprocess.SubprocessError):
        return None
    найдено = re.search(r"--порт\s+(\d+)", готово.stdout)
    return int(найдено.group(1)) if найдено else None


def _порт_из_файла(юнит: Path) -> int | None:
    try:
        найдено = re.search(r"--порт\s+(\d+)", юнит.read_text(encoding="utf-8"))
    except OSError:
        return None
    return int(найдено.group(1)) if найдено else None


def _имена(тело: str) -> list[str]:
    """Имена из ВСЕХ директив server_name: nginx их накапливает, и имя панели
    во второй директиве терялось бы (ревью кода 13.09.2026, F-16)."""
    return [имя for кусок in re.findall(r"server_name\s+([^;]+);", тело)
            for имя in кусок.split()]


def _слушает(тело: str) -> list[str]:
    return re.findall(r"listen\s+([^;]+);", тело)


def _порты(тело: str) -> set[int]:
    """Порты из listen ЧИСЛОМ: «listen 8443» содержит подстроку «443», и суд
    по подстроке признавал рубеж на 8443 четыреста сорок третьим (F-05)."""
    найдено = set()
    for строка in _слушает(тело):
        первый = строка.split()[0] if строка.split() else ""
        число = re.match(r"(?:.*:)?(\d+)$", первый)
        if число:
            найдено.add(int(число.group(1)))
    return найдено


def _панель_выведена(конф: Path) -> str:
    """PANEL_URL из пары файлов, как его читает сборщик (konf_iz_fajla):
    install.conf, затем harness.conf — последний побеждает (F-10)."""
    значение = ""
    for файл in (_паспорт_установки(), конф):
        нашлось = из_файла(str(файл)).get("PANEL_URL", "").strip()
        if нашлось:
            значение = нашлось
    return значение


def проверить(конф: Path = КОНФИГ, nginx_dir: Path | None = None,
              nginx_bin: str = NGINX_BIN, unit: Path = ЮНИТ) -> int:
    """nginx_dir остаётся в подписи ради проб и читаемости вызова из ворот,
    но судится ЭФФЕКТИВНАЯ конфигурация: дерево файлов гейт не обходит."""
    претензии: list[str] = []
    претензии += [f"шаблон рубежа: нет опоры {что}" for что in шаблон_цел()]

    адрес = _панель_выведена(конф)
    if not адрес:
        print("[рубеж панели] PANEL_URL пуст — панель наружу не выведена, "
              "рубеж не требуется")
        return _итог(претензии, рубеж_нужен=False)

    хост = urlparse(адрес).hostname or ""
    порт = порт_панели(unit)
    if порт is None:
        претензии.append(f"порт панели неоткуда взять: в {unit} нет «--порт N»")

    дамп, беда = эффективная_конфигурация(nginx_bin)
    if беда:
        претензии.append(f"{беда}; при этом PANEL_URL={адрес} — ссылка "
                         "владельцу выдана, значит рубеж обязан быть")
        return _итог(претензии)

    блоки = блоки_server(дамп)
    # Блок панели — тот, что носит её ИМЯ и куда-то проксирует. Искать его по
    # порту нельзя: при разъехавшемся порте блок просто не нашёлся бы, и гейт
    # сказал бы «рубежа нет» вместо «порт разошёлся» (ревью спеки S-07).
    свои = [(файл, тело) for файл, тело in блоки
            if хост in _имена(тело) and "proxy_pass" in тело]
    if not свои:
        претензии.append(f"рубежа нет: ни один server-блок с именем {хост} не "
                         f"проксирует панель, а PANEL_URL={адрес}")
        return _итог(претензии)

    претензии += _чужие_входы(дамп, блоки, свои, порт)
    # Судятся ВСЕ блоки с именем панели, а не первый: оставленный рядом старый
    # блок открывал бы /vnutr/ наружу при зелёном гейте (F-06).
    for файл, тело in свои:
        претензии += _опоры_блока(файл, тело, порт)
    претензии += _заглушка(блоки)
    return _итог(претензии)


def _опоры_блока(файл: str, тело: str, порт: int | None) -> list[str]:
    """Претензии к одному блоку панели: то, на что опирается код server.py."""
    найдено: list[str] = []
    if any("default_server" in строка for строка in _слушает(тело)):
        найдено.append(f"{файл}: блок панели объявлен default_server — "
                       "она отвечает на ЛЮБОЕ имя")
    if 443 not in _порты(тело):
        найдено.append(f"{файл}: панель проксируется не из 443-блока, "
                       "а cookie пропуска идёт с Secure — вход не сработает")
    if not re.search(r"location\s+/vnutr/\s*\{[^}]*return\s+404", тело):
        найдено.append(f"{файл}: нет запрета /vnutr/ — внутренние маршруты "
                       "панели открыты снаружи")
    if "X-Real-IP" not in тело:
        найдено.append(f"{файл}: нет X-Real-IP — панели неоткуда взять "
                       "адрес гостя")
    шлёт = re.search(r"proxy_pass\s+http://127\.0\.0\.1:(\d+)", тело)
    если_порт = int(шлёт.group(1)) if шлёт else None
    if если_порт and порт and если_порт != порт:
        найдено.append(f"{файл}: рубеж шлёт на порт {если_порт}, а панель "
                       f"слушает порт {порт}")
    return найдено


def _чужие_входы(дамп: str, блоки: list[tuple[str, str]],
                 свои: list[tuple[str, str]], порт: int | None) -> list[str]:
    """Кто ЕЩЁ проксирует порт панели.

    Считается ПО ФАЙЛАМ: сколько раз порт встречается в дампе файла против
    того, сколько раз он встречается в блоках самой панели. Сравнивать строки
    текстом нельзя — строка `proxy_pass …:8787;` у чужого сайта побайтно та
    же. Искать надо по всему дампу, а не по server-блокам: `nginx -T` печатает
    include-сниппет отдельным файлом, и вынесенный туда proxy_pass не лежит
    внутри какого-либо блока (ревью кода 13.09.2026, F-07).
    """
    if not порт:
        return []
    образец = re.compile(rf"proxy_pass\s+http://127\.0\.0\.1:{порт}\b")
    свои_счёт: dict[str, int] = {}
    for файл, тело in свои:
        свои_счёт[файл] = свои_счёт.get(файл, 0) + len(образец.findall(тело))

    всего: dict[str, int] = {}
    файл = "?"
    for строка in дамп.splitlines():
        метка = re.match(r"#\s*configuration file (.+):\s*$", строка)
        if метка:
            файл = метка.group(1)
            continue
        if образец.search(re.sub(r"#.*$", "", строка)):
            всего[файл] = всего.get(файл, 0) + 1

    лишние = sorted(ф for ф, сколько in всего.items()
                    if сколько > свои_счёт.get(ф, 0))
    if not лишние:
        return []
    return [f"порт панели проксирует ещё и {', '.join(лишние)}: общий origin "
            "с чужим сайтом отдаёт панель его скриптам (proxy_pass)"]


def _заглушка(блоки: list[tuple[str, str]]) -> list[str]:
    """Ответ по умолчанию для 443 обязан быть объявлен ЯВНО.

    Проверяется пара «443 и default_server в ОДНОЙ строке listen»: заглушка на
    :80 соседнего сайта дыру 13.09.2026 не закрывает (ревью кода F-04).
    """
    for _, тело in блоки:
        for строка in _слушает(тело):
            if "default_server" in строка and 443 in _порты(f"listen {строка};"):
                return []
    return ["для 443 никто не объявлен default_server: ответом на неизвестное "
            "имя станет ПЕРВЫЙ блок по алфавиту (улика 13.09.2026 — им была "
            "панель)"]


def _итог(претензии: list[str], рубеж_нужен: bool = True) -> int:
    if not претензии and not рубеж_нужен:
        print("[рубеж панели] шаблон рубежа цел — собрать его будет из чего")
        return 0
    if not претензии:
        print("[рубеж панели] рубеж на месте: панель отвечает только по своему "
              "имени, /vnutr/ закрыт, X-Real-IP ставится")
        return 0
    print(f"[рубеж панели] РУБЕЖ РАЗОШЁЛСЯ С КОДОМ: претензий {len(претензии)}")
    for строка in претензии:
        print(f"  ✗ {строка}")
    print("  Собрать рубеж: bash scripts/nginx-paneli.sh")
    return 1


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        пробы = _ЗДЕСЬ / "test_rubezh_paneli.py"
        sys.exit(subprocess.run([sys.executable, str(пробы)]).returncode)
    sys.exit(проверить())
