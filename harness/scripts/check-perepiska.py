#!/usr/bin/env python3
"""Сторож правил переписки с владельцем: ёмко, без разбора своих ошибок.

Откуда взят. Владелец 11.09.2026: «Мне не нравится что ты мне вываливаешь кучу
своих рассуждений, которые мне приходится читать, кучу своих комментариев, где
ты что ошибся, что исправил, это все лишняя информация, тебе ее надо сохранять
в какие то логи <…> мне нужна ёмкая, лаконичная, но регулярная отчетность, как
пульс по регулярности, и с очень высокой эффективностью по каждому написанному
слову и контроль тоже должен быть системный».

Пороги — ИЗ ЗАМЕРА моих же сообщений (380 штук за смену 11.09), а не из головы:
медиана 724 знака, 31 % длиннее 1000, максимум 3215, в 6 % — разбор своих
ошибок. Отсюда: предупреждение с 900 (чуть выше медианы — половина сообщений
уже укладывается), отказ с 1800 (верхние проценты, где простыни).

Отказ — именно отказ, а не совет: сторож, который советует, — это снова
внимание модели, а его владелец и просил убрать из носителей правила.

Что НЕ трогаем: документы (`--file`), они читаются иначе; и короткий ack,
который обязан уйти за 30 секунд, под пороги не попадает по определению.

Прогон:
    python3 scripts/check-perepiska.py --текст "…"    # код 1 = отказ
    python3 scripts/check-perepiska.py --selftest
"""
import re
import sys
from pathlib import Path

# Потолки — ЗАПАСНЫЕ. Главный носитель тона с 11.09.2026 — документ
# `память/ТОН.md`, который пишет агент по замеру речи владельца («предлагаю
# убрать тот механизм, и сделать другой — тон оф войс <…> и использовать его
# для общения»). Числа берутся ИЗ НЕГО: сколько знаков считать нормой, решает
# замер живой речи, а не литерал в коде.
МЯГКИЙ_ПО_УМОЛЧАНИЮ = 900
ЖЁСТКИЙ_ПО_УМОЛЧАНИЮ = 1800
ТОН = "память/ТОН.md"



sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "scripts" / "lib"))
from konf import из_файла  # noqa: E402 — один парсер паспорта на весь харнес


def _iz_pasporta(ключ: str, умолчание: str = "") -> str:
    """Значение ключа паспорта установки. Вшитый путь — след чужой установки.

    Читает ОБЩАЯ функция: за смену 12.09.2026 та же выборка была скопирована
    руками четырежды, и копии разошлись в ответе (ревью кода, №7).
    """
    return из_файла("/etc/harness/install.conf").get(ключ) or умолчание

def потолки(корень=None) -> tuple[int, int]:
    """Потолки из документа тона; нет документа или строки — запасные числа.

    Читается МАШИННАЯ строка, а не проза:

        <!-- потолки: мягкий=700 жёсткий=1500 -->

    Разбирать прозу пробовал: выражение «стремимся к N знакам» поймало из
    текста «61 % сообщений короче 100 знаков» — и потолок стал 100, то есть
    канал отказал бы почти на всём. Число, от которого зависит поведение,
    обязано стоять как число, а не быть выужено из фразы.
    """
    import os
    import re as _re
    корень = корень or os.environ.get("PROJECT_DIR") or _iz_pasporta("PROJECT_DIR")
    try:
        текст = (Path(корень) / ТОН).read_text(encoding="utf-8")
    except OSError:
        return МЯГКИЙ_ПО_УМОЛЧАНИЮ, ЖЁСТКИЙ_ПО_УМОЛЧАНИЮ
    строка = _re.search(
        r"<!--\s*потолки:\s*мягкий=(\d{3,5})\s+жёсткий=(\d{3,5})\s*-->", текст)
    if not строка:
        return МЯГКИЙ_ПО_УМОЛЧАНИЮ, ЖЁСТКИЙ_ПО_УМОЛЧАНИЮ
    мягкий, жёсткий = int(строка.group(1)), int(строка.group(2))
    return мягкий, max(жёсткий, мягкий + 100)


МЯГКИЙ, ЖЁСТКИЙ = потолки()

# Разбор СВОИХ действий: владельцу он не нужен, его место — журнал.
# Формулировки взяты из моих же сообщений, где сторож и должен был сработать.
САМОКОММЕНТАРИЙ = re.compile(
    r'\bя ошиб|\bмоя ошибка|\bошибся\b|\bпоправил себя|\bпризнаю\b'
    r'|\bкак я (?:писал|говорил|сказал)|\bнаступил на\b|\bмоей лен'
    r'|\bчестно про (?:одну|мою)\b|\bэто моя (?:ошибка|вина|лень)'
    r'|\bя сначала написал|\bсам написал дефект|\bпойман до включения'
    r'|\bурок\b|\bгра[бп]ли\b',
    re.I)

# ПОСЛЕДСТВИЕ: признание, которое владельцу НУЖНО. Правило «отказ на разборе
# своих ошибок всегда» сталкивалось с И-4 («упавшее — показать»): сторож
# отклонял сообщение «Выкат откатился: я ошибся в пороге, прод вернул тег…»,
# и единственным путём честного «я сломал» оставался обход сторожа.
# Признак разводится по НАЛИЧИЮ ПОСЛЕДСТВИЯ: есть откат, прод, потеря, тег,
# число — это факт для владельца; нет — это разбор себя, ему в журнал.
ПОСЛЕДСТВИЕ = re.compile(
    r'\bоткат|\bпрод\b|\bпотер|\bне сделан|\bне рабо|\bсломал|\bупал'
    r'|\bтег\b|\bвернул|\bостанов|\bпропал|\bждёт твоей проверки'
    r'|\bпересчит|\bпочинено\b|\bзакрыт|\bзелён'
    r'|\b\d+[.,]?\d*\s*(?:строк|файл|мин|сек|шт|с|ч|%)\b',
    re.I)

# Вода: обороты, которые не несут факта. Не запрещаем, но считаем — если их
# больше трети предложений, сообщение мягкое, а не ёмкое.
ВОДА = re.compile(
    r'\bв целом\b|\bкак я уже\b|\bстоит отметить\b|\bхочу сказать\b'
    r'|\bдумаю,? что\b|\bкажется,?\b|\bпо сути\b|\bна самом деле\b'
    r'|\bтак сказать\b|\bнаверное\b',
    re.I)


def _уровень_владельца():
    """Текущий уровень языка. Не смогли узнать — «обычный»: середина безопаснее
    крайности, а сторож не вправе ронять отправку из-за своего незнания."""
    try:
        import importlib.util
        import os
        путь = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                            'uroven-yazyka.py')
        спец = importlib.util.spec_from_file_location('уровень_языка', путь)
        модуль = importlib.util.module_from_spec(спец)
        спец.loader.exec_module(модуль)
        return модуль.прочитать_уровень(), модуль.ГЛУБОКИЕ
    except Exception:
        return 'обычный', None


def _бросок(термин: str, текст: str) -> bool:
    """Термин брошен без расшифровки? Расшифровка — тире или скобка во фразе."""
    for фраза in re.split(r'(?<=[.!?\n])\s+', текст):
        if термин.lower() in фраза.lower():
            if "(" in фраза or " — " in фраза or " - " in фраза:
                return False
    return True


def проверить_язык(текст, уровень=None, глубокие=None):
    """[замечания] — соответствует ли МОЙ текст уровню владельца."""
    if уровень is None:
        уровень, глубокие = _уровень_владельца()
    if глубокие is None or not текст.strip():
        return []
    # Считаются НЕОБЪЯСНЁННЫЕ термины. Правило уровня «обычный» — «термин
    # можно, но при первом появлении объясняется» (uroven-yazyka.py), значит
    # словарь, где каждое слово раскрыто, обязан проходить. Улика 12.09.2026:
    # сообщение «гейт — проверка, которая не пропускает; хук — перехватчик…»
    # получило замечание «терминов многовато» ровно за то, что их объясняло.
    # Признак расшифровки тот же, что у гейта устройства: тире или скобка в
    # той же фразе.
    термины = sorted({м.lower() for м in глубокие.findall(текст)
                      if _бросок(м, текст)})
    if not термины:
        return []
    if уровень == 'простой':
        return [f'уровень владельца «простой», а в сообщении термины: '
                f'{", ".join(термины[:5])}. Скажи то же обиходными словами']
    if уровень == 'обычный' and len(термины) > 3:
        return [f'уровень владельца «обычный», терминов многовато '
                f'({len(термины)}: {", ".join(термины[:5])}) — поясни или упрости']
    return []


def проверить(текст, мягкий=МЯГКИЙ, жёсткий=ЖЁСТКИЙ):
    """(код, [замечания]). Код: 0 — можно, 1 — отказ."""
    замечания = []
    отказ = False

    длина = len(текст)
    if длина > жёсткий:
        отказ = True
        замечания.append(
            f'{длина} знаков при потолке {жёсткий}: это простыня. '
            f'Оставь вывод и числа, подробности — в журнал или вложением')
    elif длина > мягкий:
        замечания.append(f'{длина} знаков — длинновато (мягкий потолок {мягкий})')

    свои = САМОКОММЕНТАРИЙ.findall(текст)
    if свои and ПОСЛЕДСТВИЕ.search(текст):
        свои = []          # признание с последствием — это И-4, а не самокомментарий
    if свои:
        отказ = True
        найдено = ', '.join(sorted({(с if isinstance(с, str) else с[0]).lower()
                                    for с in свои})[:4])
        замечания.append(
            f'разбор своих ошибок ({найдено}) — владельцу он не нужен: '
            f'в канал идёт итог, разбор пиши в память и журнал')

    вода = len(ВОДА.findall(текст))
    if вода >= 3:
        замечания.append(f'слов-наполнителей: {вода} — на каждое слово должен приходиться факт')

    # Язык — замечание, а не отказ: перевести термин на обиходный язык я могу,
    # а вот отказ на каждом техническом слове остановил бы работу целиком.
    замечания.extend(проверить_язык(текст))

    return (1 if отказ else 0), замечания


def самотест():
    случаи = [
        # (текст, ждём отказ, чем случай важен)
        ('Ворота 13 зелёных, прод жив. Беру следующую задачу.', False,
         'короткий отчёт с числами — проходит'),
        ('Честно про одну вещь: это моя ошибка, я сначала написал дефектный гейт, '
         'наступил на те же грабли.', True,
         'БОЛЬНОЙ СЛУЧАЙ: разбор своих ошибок — отказ (ровно так я и писал 11.09)'),
        ('x' * (ЖЁСТКИЙ + 1), True, 'простыня длиннее жёсткого потолка — отказ'),
        ('x' * (МЯГКИЙ + 10), False, 'длинновато, но не отказ — только замечание'),
        ('В целом, думаю что по сути на самом деле всё неплохо.', False,
         'вода замечена, но сама по себе не отказ'),
        ('', False, 'пустой текст сторожу не интересен'),
        # Разведение признания и самокомментария (находка ревью C-8): сторож
        # отклонял честное «я сломал, откатил» — это прямое столкновение с И-4
        # («упавшее — показать»), и единственной дверью оставался обход.
        ('Выкат откатился: я ошибся в пороге, прод вернул тег deploy-20260910. '
         'Прод жив.', False,
         'БОЛЬНОЙ СЛУЧАЙ: признание С ПОСЛЕДСТВИЕМ для владельца — проходит'),
        ('Грабли: сторож искал «>», живой CLI печатает «❯». Починено, '
         'закрытие сессии 8 с.', False,
         'разбор с числом и исходом — это факт, а не самокомментарий'),
        ('Признаю, был неаккуратен, урок на будущее — буду внимательнее.', True,
         'БОЛЬНОЙ СЛУЧАЙ: признание БЕЗ последствия — по-прежнему отказ'),
    ]
    ok = True
    for текст, ждём_отказ, зачем in случаи:
        код, замечания = проверить(текст)
        if bool(код) is not ждём_отказ:
            ok = False
            print(f'  ПЛОХО {зачем}: код {код}, замечания {замечания}')
        else:
            print(f'  ок    {зачем}')
    # Язык: тот же текст при разных уровнях владельца.
    import re as _re
    глубокие = _re.compile(r'\b(пайплайн\w*|гейт\w*|ротаци\w*)\b', _re.I)
    техничный = 'Гейт в пайплайне краснеет, ротация прошла.'
    # БОЛЬНОЙ СЛУЧАЙ 12.09.2026: словарь, где каждый термин раскрыт, получал
    # замечание «терминов многовато» — ровно за то, что их объяснял.
    словарь = ('Гейт — проверка, которая не пропускает. Хук — перехватчик '
               'внутри работы. Ротация — смена рабочего окна.')
    if not проверить_язык(словарь, 'обычный', глубокие):
        print('  ок    БОЛЬНОЙ СЛУЧАЙ: раскрытые термины замечания не дают')
    else:
        ok = False
        print('  ПЛОХО объяснённые термины сочтены брошенными')
    if проверить_язык(техничный, 'простой', глубокие):
        print('  ок    БОЛЬНОЙ СЛУЧАЙ: термины при «простом» владельце — замечание')
    else:
        ok = False
        print('  ПЛОХО термины при простом уровне не замечены')
    if not проверить_язык(техничный, 'технический', глубокие):
        print('  ок    те же термины при «техническом» — молчим')
    else:
        ok = False
        print('  ПЛОХО термины при техническом уровне вызвали замечание')
    if not проверить_язык('Прод жив, ворота зелёные.', 'простой', глубокие):
        print('  ок    обиходный текст при «простом» проходит')
    else:
        ok = False
        print('  ПЛОХО обиходный текст получил замечание')

    # Замечание обязано НАЗЫВАТЬ причину, иначе его нельзя исполнить.
    _, зам = проверить('x' * (ЖЁСТКИЙ + 1))
    if зам and str(ЖЁСТКИЙ) in зам[0]:
        print('  ок    отказ называет потолок числом')
    else:
        ok = False
        print(f'  ПЛОХО отказ без числа: {зам}')
    # БОЛЬНОЙ СЛУЧАЙ 11.09.2026: потолок выуживался из прозы тона и поймал
    # фразу «61 % сообщений короче 100 знаков» — норма стала 100, и канал
    # отказал бы почти на всём. Число берётся машинной строкой.
    import tempfile as _tf
    with _tf.TemporaryDirectory() as _врем:
        _корень = Path(_врем)
        (_корень / 'память').mkdir()
        (_корень / ТОН).write_text(
            '61 % сообщений короче 100 знаков — стремимся к 700 знакам.\n',
            encoding='utf-8')
        if потолки(str(_корень)) == (МЯГКИЙ_ПО_УМОЛЧАНИЮ, ЖЁСТКИЙ_ПО_УМОЛЧАНИЮ):
            print('  ок    БОЛЬНОЙ СЛУЧАЙ: проза тона потолком не становится')
        else:
            ok = False
            print(f'  ПЛОХО проза дала потолок {потолки(str(_корень))}')
        (_корень / ТОН).write_text(
            '<!-- потолки: мягкий=700 жёсткий=1500 -->\n', encoding='utf-8')
        if потолки(str(_корень)) == (700, 1500):
            print('  ок    машинная строка тона задаёт потолки')
        else:
            ok = False
            print(f'  ПЛОХО машинная строка дала {потолки(str(_корень))}')
        (_корень / ТОН).unlink()
        if потолки(str(_корень)) == (МЯГКИЙ_ПО_УМОЛЧАНИЮ, ЖЁСТКИЙ_ПО_УМОЛЧАНИЮ):
            print('  ок    нет документа тона — запасные потолки')
        else:
            ok = False
            print('  ПЛОХО без документа потолки не запасные')

    print('САМОТЕСТ %s: %d путей, вторым — больной случай'
          % ('ПРОЙДЕН' if ok else 'ПРОВАЛЕН', len(случаи) + 7))
    return 0 if ok else 1


def main():
    if '--selftest' in sys.argv:
        return самотест()
    if '--текст' in sys.argv:
        текст = sys.argv[sys.argv.index('--текст') + 1]
    else:
        текст = sys.stdin.read()
    код, замечания = проверить(текст)
    for з in замечания:
        print(f'[переписка] {з}')
    return код


if __name__ == '__main__':
    sys.exit(main())
