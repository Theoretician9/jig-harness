#!/usr/bin/env python3
"""Гейт: у одной формы — один судья. Копия формы в другом файле — красный.

СЛУЧАЙ (Ф2 ревизии харнеса, §4.3, 28.09.2026). Пять форм жили двумя копиями:
отрицание владельца и граница слова в его сообщении (`deploy_guard.py` и
`spec_approval.py`), имя записи памяти, не-латиница в имени файла, источник
задачи `inbox:<метка>`, заголовок релизного коммита. Копии совпадали дословно —
и это худший вид дубля: он выглядит согласованным, пока кто-нибудь не поправит
ОДНУ из них. С отрицанием цена прямая: добавленное в один список слово «не
сейчас» второй механизм не увидит и засчитает сообщение согласием на выкат.

Судим не «похожесть кода», а КОНКРЕТНЫЕ литералы: их перечисляет сам общий
судья (`ОХРАНЯЕМЫЕ_ЛИТЕРАЛЫ` в `scripts/lib/patterns.py`), потому что список
форм — его дело, а не знание гейта о чужом файле.

    python3 scripts/check-one-judge.py
    python3 scripts/check-one-judge.py --selftest
Код возврата: 0 — у каждой формы один судья, 1 — копия найдена.
"""
from __future__ import annotations

import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "scripts" / "lib"))
import patterns as формы                          # noqa: E402

# Судье литералы положены, и гейту — в его собственном самотесте (там они
# образцы больного случая, а не вторая реализация). Список форм гейт не держит:
# он читает его из данных модуля-судьи.
СВОИ = ("scripts/lib/patterns.py", "scripts/check-one-judge.py")
ОСМАТРИВАЕМ = ("scripts", "harness/demons", "harness/panel")


def файлы(корень: Path) -> list[Path]:
    итог = []
    for каталог in ОСМАТРИВАЕМ:
        основа = корень / каталог
        if not основа.is_dir():
            continue
        итог += [п for п in основа.rglob("*")
                 if п.suffix in (".py", ".sh") and "__pycache__" not in п.parts]
    return sorted(итог)


def копии(корень: Path = КОРЕНЬ,
          литералы: dict[str, str] | None = None) -> list[tuple[str, str, str]]:
    """[(файл, имя формы, литерал)] — где форма написана второй раз."""
    литералы = литералы if литералы is not None else формы.ОХРАНЯЕМЫЕ_ЛИТЕРАЛЫ
    найдено = []
    for путь in файлы(корень):
        свой = str(путь.relative_to(корень))
        if свой in СВОИ:
            continue
        try:
            текст = путь.read_text(encoding="utf-8", errors="replace")
        except OSError:
            # «Не прочли» и «чисто» — разные ответы: закрытый файл не должен
            # выглядеть отсутствием копии ([[unreadable-source-turns-check-green]]).
            найдено.append((свой, "файл не прочитан", ""))
            continue
        for имя, литерал in литералы.items():
            if литерал and литерал in текст:
                найдено.append((свой, имя, литерал))
    return найдено


def проверить(корень: Path = КОРЕНЬ) -> int:
    найдено = копии(корень)
    if найдено:
        print(f"[один судья] КОПИЯ ФОРМЫ: {len(найдено)}")
        for файл, имя, литерал in найдено:
            print(f"  ✗ {файл}: {имя} — {литерал[:60]!r}")
        print("  Формы живут в scripts/lib/patterns.py: импортируй оттуда, "
              "иначе правка одной копии разойдётся с другой.")
        return 1
    print(f"[один судья] чисто: {len(формы.ОХРАНЯЕМЫЕ_ЛИТЕРАЛЫ)} форм — "
          f"по одному судье у каждой")
    return 0


def самотест() -> int:
    import tempfile
    путей = неудач = 0

    def проба(имя: str, ждём, факт):
        nonlocal путей, неудач
        путей += 1
        if факт == ждём:
            print(f"  ок    {имя}")
        else:
            неудач += 1
            print(f"  ПЛОХО {имя}: ждали «{ждём}», вышло «{факт}»")

    with tempfile.TemporaryDirectory() as врем:
        стенд = Path(врем)
        (стенд / "scripts" / "lib").mkdir(parents=True)
        (стенд / "scripts" / "lib" / "patterns.py").write_text(
            'ФОРМА = "inbox:([0-9.]+)"\n', encoding="utf-8")
        # БОЛЬНОЙ СЛУЧАЙ: механизм написал форму у себя вместо импорта.
        (стенд / "scripts" / "свой-разбор.py").write_text(
            'import re\nМОЁ = re.compile(r"inbox:([0-9.]+)")\n', encoding="utf-8")
        свои = {"источник задачи": "inbox:([0-9.]+)"}
        найдено = копии(стенд, свои)
        проба("БОЛЬНОЙ СЛУЧАЙ: копия формы названа с файлом",
              [("scripts/свой-разбор.py", "источник задачи")],
              [(ф, и) for ф, и, _ in найдено])
        # Судье своя форма позволена.
        проба("судья не считается копией себя", 0,
              len([ф for ф, _, _ in найдено if ф == "scripts/lib/patterns.py"]))
        # Импорт вместо копии — чисто.
        (стенд / "scripts" / "свой-разбор.py").write_text(
            "import patterns as формы\nМОЁ = формы.ФОРМА\n", encoding="utf-8")
        проба("импорт вместо копии — чисто", [], копии(стенд, свои))
        # Пустой литерал не ищется: иначе он совпал бы с каждым файлом.
        проба("пустая форма никого не красит", [], копии(стенд, {"пусто": ""}))

    print(f"SELFTEST: {'зелёный' if not неудач else 'КРАСНЫЙ'} ({путей} путей; "
          "больной первый — «форма написана второй раз»)")
    return 1 if неудач else 0


if __name__ == "__main__":
    sys.exit(самотест() if "--selftest" in sys.argv else проверить())
