#!/usr/bin/env python3
"""Приём секрета из канала: значение — в своё хранилище, в журналы — пометка.

Слова владельца читают демоны, панель, разборщик карточек (он зовёт модель) и
передачи между сменами — ключ, присланный в канал, не должен дойти ни до
одного из них. Диспетчер отдаёт сюда слова через stdin (argv виден в ps) и
дальше работает только с тем, что вернулось. Секрет ли — решает общий судья
форм (`lib/patterns.py`, `секреты_в_речи`), здесь только раскладка:

  * значения — в $LOG_DIR/inbox/секреты/<метка>, по строке на значение,
    файл 600, каталог 700;
  * в stdout — тот же текст, где каждое значение заменено пометкой с путём и
    командой переноса. Без секретов текст возвращается как был;
  * хранилище не записалось — значение всё равно не уходит дальше: пометка
    «секрет не принят», причина — в stderr без значения.

Агент значение в сессию не читает (оно осело бы в стенограмме и в argv
следующей команды): `--переложить` копирует файл в место назначения с правами
600 и удаляет копию из хранилища. Забытое в хранилище убирает disk-cleanup по
сроку из retention.yaml.

    python3 secret-intake.py --журналы <LOG_DIR> --метка <метка> < текст
    python3 secret-intake.py --переложить <файл хранилища> <куда> [номер строки]
    python3 secret-intake.py --selftest
"""
from __future__ import annotations

import os
import stat
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))
import patterns as формы                          # noqa: E402

СЕБЯ = Path(__file__).resolve()
НЕ_ПРИНЯТ = "[секрет не принят: {причина} — пришли заново]"


def _новый_файл(путь: Path, данные: str) -> None:
    """Файл 600, только новый и не по ссылке: подложенный файл или ссылка
    на месте метки — отказ, а не запись поверх."""
    дескриптор = os.open(путь, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    with os.fdopen(дескриптор, "w", encoding="utf-8") as ф:
        ф.write(данные)


def _своё_хранилище(журналы: Path) -> Path:
    каталог = журналы / формы.КАТАЛОГ_СЕКРЕТОВ_КАНАЛА
    каталог.mkdir(mode=0o700, parents=True, exist_ok=True)
    сведения = os.lstat(каталог)
    if stat.S_ISLNK(сведения.st_mode) or сведения.st_uid != os.geteuid():
        raise PermissionError(0, "хранилище — ссылка или чужой каталог")
    os.chmod(каталог, 0o700)          # mkdir подчиняется umask, каталог мог быть
    return каталог


def отделить(текст: str, журналы: Path, метка: str) -> str:
    значения = формы.секреты_в_речи(текст)
    if not значения:
        return текст
    try:
        файл = _своё_хранилище(журналы) / метка
        _новый_файл(файл, "\n".join(значения) + "\n")
        пометка = (f"[секрет из канала: {файл} — в сессию не читать, не cat; "
                   f"переложить: python3 {СЕБЯ} --переложить {файл} <куда>]")
    except OSError as беда:
        причина = f"хранилище не записано ({беда.strerror})"
        print(f"secret-intake: {причина} — значение отброшено", file=sys.stderr)
        пометка = НЕ_ПРИНЯТ.format(причина=причина)
    # Длинные первыми: значение, вложенное в другое (КЛЮЧ=значение и само
    # значение), не должно оставить хвост.
    for значение in sorted(значения, key=len, reverse=True):
        текст = текст.replace(значение, пометка)
    return текст


def переложить(откуда: Path, куда: Path, номер: int | None, хранилище: Path) -> int:
    """Значение — в место назначения (600, только новый файл), копия в
    хранилище удаляется. Значение в вывод не попадает.

    Источник — только файл прямо в хранилище канала и не ссылка: команда
    удаляет и переписывает источник, и ошибка в пути иначе портила бы любой
    файл мимо сторожа удаления."""
    if (откуда.is_symlink() or not откуда.is_file()
            or откуда.resolve().parent != хранилище.resolve()):
        print(f"secret-intake: {откуда} — не файл хранилища {хранилище}; не трогаю",
              file=sys.stderr)
        return 2
    дескриптор = os.open(откуда, os.O_RDONLY | os.O_NOFOLLOW)
    with os.fdopen(дескриптор, encoding="utf-8") as ф:
        строки = [с for с in ф.read().splitlines() if с]
    if номер is None and len(строки) != 1:
        print(f"secret-intake: в {откуда} значений {len(строки)} — укажи номер строки "
              f"(1…{len(строки)})", file=sys.stderr)
        return 2
    if номер is not None and not 1 <= номер <= len(строки):
        print(f"secret-intake: в {откуда} нет строки {номер} (всего {len(строки)})",
              file=sys.stderr)
        return 2
    try:
        _новый_файл(куда, строки[(номер or 1) - 1] + "\n")
    except FileExistsError:
        print(f"secret-intake: {куда} уже есть — поверх не пишу (решает владелец)",
              file=sys.stderr)
        return 2
    осталось = [с for н, с in enumerate(строки, 1) if н != (номер or 1)]
    os.unlink(откуда)
    if осталось:
        _новый_файл(откуда, "\n".join(осталось) + "\n")
    print(f"переложено: {куда} (600); в {откуда} осталось значений: {len(осталось)}")
    return 0


def самотест() -> int:
    import hashlib
    import tempfile
    from selftest_cases import Cases
    случаи = Cases()
    проба = случаи.check
    ключ = hashlib.sha256(b"intake").hexdigest()[:40]
    with tempfile.TemporaryDirectory() as tmp:
        журналы = Path(tmp)
        вышло = отделить(f"ключ склада: {ключ}", журналы, "1.5")
        файл = журналы / формы.КАТАЛОГ_СЕКРЕТОВ_КАНАЛА / "1.5"
        проба("БОЛЬНОЙ СЛУЧАЙ: в выходе значения нет", False, ключ in вышло)
        проба("пометка с путём и запретом читать", True,
              f"[секрет из канала: {файл} — в сессию не читать" in вышло)
        проба("значение в файле хранилища", ключ, файл.read_text().strip() if файл.exists() else "")
        проба("права файла", "0o600", oct(stat.S_IMODE(файл.stat().st_mode)) if файл.exists() else "")
        проба("права каталога", "0o700", oct(stat.S_IMODE(файл.parent.stat().st_mode)))
        обычное = "Посмотри коммит 65a59df и подними диспетчер"
        проба("обычное сообщение не тронуто", обычное, отделить(обычное, журналы, "2.5"))
        проба("на обычное файл не заводится", False, (файл.parent / "2.5").exists())
        # Подложенная ссылка на месте метки: запись по ней — отказ.
        (файл.parent / "3.5").symlink_to(журналы / "чужой")
        вышло = отделить(ключ, журналы, "3.5")
        проба("ссылка на месте метки — значения в выходе нет", False, ключ in вышло)
        проба("ссылка на месте метки — пометка «не принят»", True, "[секрет не принят:" in вышло)
        проба("по ссылке ничего не записано", False, (журналы / "чужой").exists())
        хранилище = файл.parent
        # БОЛЬНОЙ СЛУЧАЙ: источник вне хранилища — команда переписала бы и
        # удалила чужой файл. Отказ, файл цел.
        чужой = журналы / "чужой-файл"
        чужой.write_text("первая\n\nвторая\nтретья\n", encoding="utf-8")
        проба("БОЛЬНОЙ СЛУЧАЙ: переложить файл вне хранилища — отказ", 2,
              переложить(чужой, журналы / "куда-1", 2, хранилище))
        проба("файл вне хранилища цел", "первая\n\nвторая\nтретья\n", чужой.read_text())
        ссылка = хранилище / "4.5"
        ссылка.symlink_to(чужой)
        проба("переложить ссылку из хранилища на чужой файл — отказ", 2,
              переложить(ссылка, журналы / "куда-2", None, хранилище))
        проба("путь с «..» мимо хранилища — отказ", 2,
              переложить(хранилище / ".." / ".." / "чужой-файл", журналы / "куда-3", 2, хранилище))
        куда = журналы / "warehouse-key"
        проба("переложить: код", 0, переложить(файл, куда, None, хранилище))
        проба("переложить: значение на месте", ключ, куда.read_text().strip())
        проба("переложить: права 600", "0o600", oct(stat.S_IMODE(куда.stat().st_mode)))
        проба("переложить: копия в хранилище удалена", False, файл.exists())
        _новый_файл(файл, f"{ключ}\n")
        проба("переложить поверх существующего — отказ", 2, переложить(файл, куда, None, хранилище))
    print(f"SELFTEST: {'зелёный' if случаи.ok else 'КРАСНЫЙ'} ({случаи.paths} путей; "
          "больной первый — ключ в сообщении)")
    return 0 if случаи.ok else 1


def main(доводы: list[str]) -> int:
    if доводы == ["--selftest"]:
        return самотест()
    if доводы[:1] == ["--переложить"] and len(доводы) in (3, 4):
        номер = int(доводы[3]) if len(доводы) == 4 else None
        from config import log_dir
        хранилище = Path(log_dir()) / формы.КАТАЛОГ_СЕКРЕТОВ_КАНАЛА
        return переложить(Path(доводы[1]), Path(доводы[2]), номер, хранилище)
    if len(доводы) != 4 or доводы[0] != "--журналы" or доводы[2] != "--метка":
        print("secret-intake: --журналы <LOG_DIR> --метка <метка> < текст | "
              "--переложить <файл> <куда> [номер]", file=sys.stderr)
        return 2
    sys.stdout.write(отделить(sys.stdin.read(), Path(доводы[1]), доводы[3]))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
