#!/usr/bin/env python3
"""Сроки присмотра из реестра устройства — сверка с живым конфигом.

Откуда взят. За демонами следит сторож пульса: каждый механизм с расписанием
обновляет свою метку, и если метка старше срока вдвое — сторож называет демона
мёртвым. Сроки живут строкой `HEARTBEAT_PERIODS` в `harness.conf`, а механизмы
описаны в реестре. Два списка ведутся врозь и расходятся МОЛЧА: 13.09.2026
нашёлся сторож срока входа по подписке, стоявший в кроне без присмотра вовсе —
его смерть тихо сняла бы предупреждение, а работа встала бы на восемь часов.

Сборщик ничего не пишет: ни в реестр, ни в конфиг. Писатель настроек в проекте
один — `write-key.py`, и второй сделал бы потерянную правку неотличимой
от несработавшей настройки. Здесь только сверка, а её вывод — руководство к
правке, поэтому расхождение называется ПОИМЁННО в обе стороны: «множества не
равны» не говорит, что чинить.

Прогон:
    python3 scripts/build-watch-periods.py --проверить
Код возврата: 0 — реестр и конфиг сошлись, 1 — расхождение названо поимённо.
"""
import os
import re
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))
from config import корень_дерева, путь_harness_conf  # noqa: E402

КОРЕНЬ = корень_дерева(__file__)
РЕЕСТР = "harness/config/устройство.yaml"
КОНФИГ = путь_harness_conf()
КЛЮЧ = "HEARTBEAT_PERIODS"
# Кого заводит расписание — тому и метка пульса.
ПРИСМОТР_ПОЛОЖЕН = ("крон", "таймер")


def путь_реестра() -> Path:
    return Path(os.environ.get("HARNESS_USTROJSTVO") or (КОРЕНЬ / РЕЕСТР))


def путь_конфига() -> Path:
    return Path(os.environ.get("HARNESS_CONF") or КОНФИГ)


def сроки_конфига(источник: Path) -> dict:
    """`имя: минуты` из HEARTBEAT_PERIODS.

    Строка берётся НЕ первым совпадением: закомментированная строка выше
    боевой увела бы сверку на выдумку, а гейт остался бы внешне исправным.
    """
    итог = {}
    try:
        текст = источник.read_text(encoding="utf-8")
    except OSError as беда:
        raise SystemExit(f"конфиг сроков не прочитан: {источник} — {беда}")
    for строка in текст.splitlines():
        if строка.lstrip().startswith("#"):
            continue
        найдено = re.match(rf'\s*{КЛЮЧ}\s*=\s*"([^"]*)"', строка)
        if найдено:
            итог = {пара.split(":")[0]: int(пара.split(":")[1])
                    for пара in найдено.group(1).split() if ":" in пара}
    return итог


def сроки_реестра(источник: Path) -> tuple[dict, list]:
    """(`имя метки: минуты` из поля `повод`, механизмы с расписанием без меток).

    Второе — отдельный ответ, а не пустое место: механизм, у которого есть
    расписание и нет ни одной метки, не попадёт НИ в одно множество, сверка
    «сойдётся», а демон останется без присмотра. Ровно эта дыра и завела всю
    работу, поэтому она называется вслух, а не тонет в равенстве множеств.
    """
    try:
        данные = yaml.safe_load(источник.read_text(encoding="utf-8")) or {}
    except OSError as беда:
        raise SystemExit(f"реестр не прочитан: {источник} — {беда}")
    сроки, безнадзорные = {}, []
    for запись in данные.get("механизмы") or []:
        повод = запись.get("повод")
        if not isinstance(повод, dict):
            continue
        метки = повод.get("метки") or []
        # Метка пульса положена тому, кого заводит расписание: он молчит, и
        # молчание надо отличить от смерти. У службы присмотр другой — её юнит
        # смотрит сторож пульса отдельной веткой; у заводимого вызовом хозяин
        # и есть тот, кто его зовёт. Требовать метку от них значило бы завести
        # красноту, которую нечем погасить, — и гейт отключили бы (ревью К-4).
        if повод.get("источник") in ПРИСМОТР_ПОЛОЖЕН and not метки:
            безнадзорные.append((запись.get("файл"), запись.get("имя")))
        for метка in метки:
            сроки[метка["имя"]] = int(метка["молчание_считать_поломкой"])
    return сроки, безнадзорные


def расхождения(реестр: dict, конфиг: dict) -> list:
    """Строки-претензии. Пусто — списки сошлись именами И числами."""
    беды = []
    нет_в_конфиге = sorted(set(реестр) - set(конфиг))
    нет_в_реестре = sorted(set(конфиг) - set(реестр))
    if нет_в_конфиге:
        беды.append(f"в реестре есть, в конфиге нет: {', '.join(нет_в_конфиге)}")
    if нет_в_реестре:
        беды.append(f"в конфиге есть, в реестре нет: {', '.join(нет_в_реестре)}")
    # Равенство ИМЁН при разных числах — сверка «сошлась», а сторож ждёт
    # протухшую метку вшестеро дольше положенного. Молчать об этом нельзя.
    for имя in sorted(set(реестр) & set(конфиг)):
        if реестр[имя] != конфиг[имя]:
            беды.append(f"срок разошёлся: {имя} — в реестре {реестр[имя]}, "
                        f"в конфиге {конфиг[имя]}")
    return беды


def метки_без_срока(каталог: Path, конфиг: dict) -> list:
    """Метки, которые КТО-ТО ПИШЕТ, а сроки о них не знают.

    СЛУЧАЙ 21–26.09.2026. Демонам перевели имена меток на латиницу
    (`memory-commit` → `pamyat-kommit`, `acceptance-watch` → `priyomka-watch`
    и ещё шесть), а реестр и конфиг остались со старыми. Обе сверяемые стороны
    ДАННЫЕ и написаны одной рукой — они сошлись, гейт сказал «сошлось — имён
    23», и четверо суток сводка звала мёртвыми шесть живых демонов. Хуже
    второе: восемь работающих демонов не сторожил НИКТО.

    Третья сторона — не ещё один список, а ФАКТ: файл метки на диске. Его
    пишет код в момент успешного прогона, подделать его нечем, и он не зависит
    от того, какой формой имя записано в исходнике (строкой, переменной,
    константой питона) — регулярка по коду на трёх из них уже промахнулась.
    Мерить надо там, где явление ЖИВЁТ ([[a-check-creates-its-own-condition]]).
    """
    try:
        имена = sorted(п.name for п in каталог.iterdir() if п.is_file())
    except OSError:
        return []          # каталога нет — свежая установка, сторожить нечего
    # Точка в начале — служебный флаг механизма (.полный-перезапуск), не метка.
    чужие = [и for и in имена if not и.startswith(".") and и not in конфиг]
    return [f"метку пишут, а срока для неё нет: {и} — этого демона "
            f"не сторожит никто" for и in чужие]


def главная() -> int:
    реестр, безнадзорные = сроки_реестра(путь_реестра())
    конфиг = сроки_конфига(путь_конфига())
    беды = расхождения(реестр, конфиг)
    sys.path.insert(0, str(КОРЕНЬ / "scripts" / "lib"))
    import config as конф_модуль
    # Стенд пробы подменяет реестр и конфиг, но каталог меток — ОБЩИЙ с боевой
    # машиной: без этой оговорки сверка стенда с двумя именами объявляла
    # сиротами двадцать живых боевых меток ([[narrowing-missed-shared-carriers]]).
    свой_стенд = os.environ.get("HARNESS_USTROJSTVO") or os.environ.get("HARNESS_CONF")
    свой_каталог_меток = os.environ.get("HEARTBEAT_DIR")
    if свой_каталог_меток or not свой_стенд:
        беды += метки_без_срока(
            Path(свой_каталог_меток or конф_модуль.heartbeat_dir()), конфиг)
    for файл, имя in безнадзорные:
        беды.append(f"с расписанием, но без присмотра: {файл} ({имя})")

    # Тот же счёт по ОБРАЗЦУ конфига из пакета: он уезжает на новую машину, и
    # демон, чьего срока там нет, живёт без присмотра с первого дня. Живой
    # прогон ворот внутри свежей установки 13.09.2026: в реестре 22 имени,
    # в образце было 17 — пять демонов без сторожа, и никто бы не заметил.
    sys.path.insert(0, str(КОРЕНЬ / "scripts" / "lib"))
    from config import katalog_paketa
    образец = katalog_paketa() / "harness" / "config" / "harness.conf"
    # Только на БОЕВОЙ сверке: когда реестр или конфиг подменены (это делает
    # проба своим стендом), образец пакета к их содержимому отношения не имеет
    # и красил бы чужой стенд — так самотест и покраснел при первой правке.
    if образец.exists() and not свой_стенд:
        в_образце = сроки_конфига(образец)
        беды += [f"ОБРАЗЕЦ ПАКЕТА: {б}" for б in расхождения(реестр, в_образце)]

    if беды:
        print("сроки присмотра: РАЗОШЛИСЬ")
        # Без значка-украшения в начале: строка машиночитаемая, и читатель
        # ищет её по маркеру («в реестре есть, в конфиге нет:»), а не по месту.
        for строка in беды:
            print(f"  {строка}")
        print(f"\nимён в реестре {len(реестр)}, в конфиге {len(конфиг)}")
        return 1
    print(f"сроки присмотра: сошлось — имён {len(реестр)}")
    return 0


if __name__ == "__main__":
    sys.exit(главная())
