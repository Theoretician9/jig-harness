#!/usr/bin/env bash
#
# test_live_check_sh.sh — проверка обёртки живой проверки ДО того, как обёртка
# написана.
#
# Откуда взято. Спека `docs/specs/2026-10-15-живая-проверка-механизмов.md` §3.2
# и план `docs/plans/2026-10-16-носители-живой-проверки.md`, Task 1.
#
# Зачем обёртка нужна. Запись «проверено живьём» доказывалась моими же словами,
# и гейт судил ФОРМУ записи: «2026-10-15: работает» и пересказ самотеста
# проходили (ревью спеки 15.10, CRITICAL 5). Мерой может быть только ЧУЖОЙ
# текст — вывод самого механизма. Обёртка зовёт механизм, кладёт его вывод в
# файл со своей шапкой и возвращает код механизма как есть; гейт потом требует
# дословную подстроку из этого файла.
#
# ЧТО ОХРАНЯЕТСЯ СВЕРХ БУКВЫ ПЛАНА
# 1. **Код возврата не глотать.** Если обёртка вернёт 0 на упавшем механизме,
#    поломка превратится в «проверено» — самый дорогой из возможных дефектов
#    этого носителя. Случай стоит ПЕРВЫМ.
# 2. **Вывод в след попадает ДОСЛОВНО**, включая stderr: гейт ищет подстроку
#    из следа, и потерянный stderr сделал бы недоказуемой ровно ту проверку,
#    где механизм ругается.
# 3. **Имя следа из пути механизма** (`scripts/hooks/guard_bash.py` →
#    `scripts-hooks-guard_bash.py.log`): косая черта в имени файла создала бы
#    каталоги вне `живьём/`, а то и записала бы файл чужому механизму.
# 4. **Пустая команда — отказ, а не пустой след.** Файл следа без вывода
#    выглядит как проверенный механизм, который ничего не сказал.
#
# Прогон: bash scripts/test_live_check_sh.sh
# Код возврата: 0 — все случаи зелёные, 1 — хоть один плохой.
set -uo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.." || exit 1

OBERTKA="scripts/live-check.sh"
OK=0
BAD=0

sluchaj() {  # $1=имя случая $2=условие (0 — верно)
    if [ "$2" = 0 ]; then
        OK=$((OK + 1)); echo "  ок    $1"
    else
        BAD=$((BAD + 1)); echo "  ПЛОХО $1"
    fi
}

DVOR=$(mktemp -d)
trap 'rm -rf "$DVOR"' EXIT
export HARNESS_LIVE_CHECK_TRACE_DIR="$DVOR/живьём"

# БОЛЬНОЙ СЛУЧАЙ ПЕРВЫМ: механизм упал — обёртка обязана вернуть его код.
bash "$OBERTKA" "scripts/проба-механизм.sh" -- bash -c 'echo "начал"; echo "сломался" >&2; exit 7' \
    >/dev/null 2>&1
kod=$?
sluchaj "БОЛЬНОЙ СЛУЧАЙ: код упавшего механизма возвращён как есть (ждём 7, вышло $kod)" \
    "$([ "$kod" = 7 ] && echo 0 || echo 1)"

SLED="$DVOR/живьём/scripts-проба-механизм.sh.log"
sluchaj "след создан по имени механизма без каталогов" \
    "$([ -f "$SLED" ] && echo 0 || echo 1)"

sluchaj "в следе есть шапка обёртки: механизм, команда, время" \
    "$(grep -q 'механизм: scripts/проба-механизм.sh' "$SLED" 2>/dev/null \
       && grep -q 'команда: ' "$SLED" 2>/dev/null \
       && grep -qE 'время: [0-9]{4}-[0-9]{2}-[0-9]{2}T' "$SLED" 2>/dev/null \
       && echo 0 || echo 1)"

sluchaj "вывод механизма в следе ДОСЛОВНО, вместе с stderr" \
    "$(grep -q '^начал$' "$SLED" 2>/dev/null && grep -q '^сломался$' "$SLED" 2>/dev/null \
       && echo 0 || echo 1)"

sluchaj "код механизма записан в след" \
    "$(grep -q 'код возврата: 7' "$SLED" 2>/dev/null && echo 0 || echo 1)"

# НАХОДКИ РЕВЬЮ 17.10 (F-gen-04): проба судила шапку только по имени механизма.
# Мутации «команда стала пустой» и «строки пользователя нет» были ЗЕЛЁНЫМИ на
# девяти случаях — то есть две трети шапки не сторожил никто, а шапка и есть
# доказательство: по ней видно, ЧТО звали и КЕМ.
sluchaj "в шапке стоит сама команда механизма" \
    "$(grep -qF 'команда: bash -c echo "начал"; echo "сломался" >&2; exit 7' "$SLED" 2>/dev/null \
       && echo 0 || echo 1)"

sluchaj "в шапке назван пользователь, под которым звали" \
    "$(grep -qE "^пользователь: $(id -un)\$" "$SLED" 2>/dev/null && echo 0 || echo 1)"

# НАХОДКА РЕВЬЮ 17.10 (F-gen-03): механизм, читающий stdin, висел вечно — в
# следе уже лежала шапка, и это выглядело как начатая проверка. Обёртка обязана
# закрыть stdin и иметь предел времени.
nachalo=$(date +%s)
timeout 60 bash "$OBERTKA" "scripts/проба-стдин.sh" -- cat >/dev/null 2>&1
kod=$?
proshlo=$(( $(date +%s) - nachalo ))
sluchaj "механизм, читающий stdin, не висит (код $kod, $proshlo с)" \
    "$([ "$kod" != 124 ] && [ "$proshlo" -lt 20 ] && echo 0 || echo 1)"

# Предел времени: механизм, который не кончается сам, обрывается обёрткой, и
# это видно в следе — «проверено» из вечного ожидания не получается.
HARNESS_LIVE_CHECK_TIMEOUT=2 timeout 60 bash "$OBERTKA" "scripts/проба-вечная.sh" \
    -- bash -c 'sleep 30' >/dev/null 2>&1
kod=$?
SLED3="$DVOR/живьём/scripts-проба-вечная.sh.log"
sluchaj "вечный механизм обрывается пределом, и предел назван в следе (код $kod)" \
    "$([ "$kod" != 0 ] && grep -q 'предел' "$SLED3" 2>/dev/null && echo 0 || echo 1)"

# Здоровый механизм: код 0 и вывод на месте.
bash "$OBERTKA" "scripts/проба-здоровый.py" -- bash -c 'echo "ИТОГ: плохих 0"' >/dev/null 2>&1
kod=$?
SLED2="$DVOR/живьём/scripts-проба-здоровый.py.log"
sluchaj "здоровый механизм: код 0 и его слова в следе" \
    "$([ "$kod" = 0 ] && grep -q 'ИТОГ: плохих 0' "$SLED2" 2>/dev/null && echo 0 || echo 1)"

# Команды нет — отказ, а не пустой след, который выглядит как проверка.
# Отказ судится ПО СЛОВУ обёртки, а не по «код не 0»: отсутствующий скрипт
# даёт 127, и такой случай зелен ни от чего (память: «проба, ждущая ненулевого
# кода, зеленеет от 127»).
otkaz=$(bash "$OBERTKA" "scripts/проба-пустая.sh" -- 2>&1); kod=$?
sluchaj "пустая команда — отказ со СВОИМ словом (код $kod)" \
    "$([ "$kod" != 0 ] && printf '%s' "$otkaz" | grep -q 'нечего звать' && echo 0 || echo 1)"

# Разделителя нет — тоже отказ: иначе имя механизма уедет в команду.
otkaz=$(bash "$OBERTKA" "scripts/проба-без-разделителя.sh" echo привет 2>&1); kod=$?
sluchaj "без разделителя «--» — отказ со СВОИМ словом (код $kod)" \
    "$([ "$kod" != 0 ] && printf '%s' "$otkaz" | grep -q 'разделител' && echo 0 || echo 1)"

# Каталог следа берётся из окружения: иначе проба пишет в рабочий .tasks и
# засоряет задачу чужими файлами (своё условие — своя подстилка).
sluchaj "след лёг в каталог из окружения, а не в .tasks проекта" \
    "$([ ! -e ".tasks/hr.zhivaya-proverka-vseh-mehanizmov/живьём/scripts-проба-механизм.sh.log" ] \
       && echo 0 || echo 1)"

echo "ИТОГ: хороших $OK, плохих $BAD"
[ "$BAD" = 0 ] || exit 1
exit 0
