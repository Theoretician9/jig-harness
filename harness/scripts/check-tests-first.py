#!/usr/bin/env python3
"""Гейт: новый модуль приходит вместе с тестом на него.

Откуда взят. Второй пункт владельца 11.09.2026: «Тесты до кода проверять по
истории — тестовый файл в коммитах появился раньше файла реализации. Машинно
проверяется, тут даже думать не надо».

Думать пришлось: adversarial-ревью спеки замерило, во что превращается правило
«парный тест по имени» на этом репозитории (находка I-3).

| замер | число |
|---|---|
| файлов `.py` реализации | 334 |
| у скольких есть одноимённый `test_<имя>.py` | 58 (17 %) |
| файлов `ts/tsx` | 124, из них тестов 8 |
| файлов без записи о добавлении (git видит переименование) | 210 из 1439 |
| находок при прогоне правила по всей истории | 1 |

Правило по одноимённым файлам сторожило бы одну шестую кода, а датирование по
истории рвалось бы на каждом переименовании. Поэтому гейт сужен честно и
граница названа вслух:

**Судятся только файлы, ДОБАВЛЯЕМЫЕ этим коммитом.** Там история не нужна
вовсе: новый модуль без теста виден прямо в индексе. Парность ищется по
УПОМИНАНИЮ имени модуля внутри теста (импорт, путь, строка), а не по имени
файла — тесты продукта названы по сценариям («test_дом_без_реестра.py»), и
поиск по имени их не находит.

Прогон:
    python3 scripts/check-tests-first.py            # судит текущий индекс
    python3 scripts/check-tests-first.py --selftest
Код возврата: 0 — чисто, 1 — новый модуль без теста, 77 — жёлтый (обкатка).
"""
import os
import subprocess
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
# Умолчания, если пульта нет. Замер истории (1192 коммита): без сужения правило
# даёт 135 коммитов с находками, и почти все ложные — тест на миграцию, на
# shell-скрипт и на React-компонент не пишут ни здесь, ни где-либо ещё.
РАСШИРЕНИЯ_КОДА = (".py", ".ts")
ПРОПУСКАТЬ = ("__init__.py", "alembic/versions/")
ЖЁЛТЫЙ = 77
# Признак теста в пути: имя или каталог. Языки разные, привычки тоже.
ПРИЗНАКИ_ТЕСТА = ("test_", "_test.", ".test.", ".spec.", "/tests/", "/test/",
                  "conftest", "selftest")


def конфиг():
    """(исключения путей, расширения, пропускать, строгость) — с пульта владельца."""
    данные = {}
    try:
        import yaml
        with open(КОРЕНЬ / "harness" / "config" / "пайплайн.yaml", encoding="utf-8") as fh:
            данные = yaml.safe_load(fh) or {}
    except (OSError, ValueError, ImportError):
        данные = {}
    свои = данные.get("тесты_до_кода") or {}
    return (данные.get("исключения_путей") or ["scripts/", "harness/"],
            tuple(свои.get("расширения") or РАСШИРЕНИЯ_КОДА),
            tuple(свои.get("пропускать") or ПРОПУСКАТЬ),
            свои.get("строгость") or "жёлтый")


def это_тест(путь: str) -> bool:
    return any(признак in путь for признак in ПРИЗНАКИ_ТЕСТА)


def без_теста(добавленные, содержимое, исключения,
              расширения=РАСШИРЕНИЯ_КОДА, пропускать=ПРОПУСКАТЬ):
    """Новые модули, на которые в этом же коммите нет ни одного теста.

    `содержимое` — словарь путь → текст (для тестов коммита). Чистая функция:
    её и проверяет самотест, без git и без файловой системы.
    """
    тесты = {п: т for п, т in содержимое.items() if это_тест(п)}
    сироты = []
    for путь in добавленные:
        if это_тест(путь) or not путь.endswith(расширения):
            continue
        if any(путь.startswith(искл) for искл in исключения):
            continue
        if any(кусок in путь for кусок in пропускать):
            continue
        имя = Path(путь).stem
        if any(имя in текст for текст in тесты.values()):
            continue
        сироты.append(путь)
    return сироты


def _индекс(флаг):
    """Пути из индекса — или None, если git не ответил.

    Пустой список означал и «в индексе ничего», и «git молчит»: на отказе
    гейт печатал «новых модулей без теста нет» и пропускал коммит
    (14.09.2026, тот же класс, что у трёх гейтов, читавших отказ как
    «нарушений нет»). Код возврата здесь не проверялся вовсе.
    """
    команда = ["git", "-C", str(КОРЕНЬ), "-c", "core.quotepath=false",
               "diff", "--cached", "--name-only", f"--diff-filter={флаг}"]
    try:
        готово = subprocess.run(команда, capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.SubprocessError):
        return None
    if готово.returncode != 0:
        return None
    return [с for с in готово.stdout.splitlines() if с.strip()]


def _staged_текст(путь):
    try:
        # errors="replace": в коммит попадает и двоичное (снимки экрана), а
        # упавший на декодировании гейт молча не проверит ничего.
        return subprocess.run(["git", "-C", str(КОРЕНЬ), "-c", "core.quotepath=false",
                               "show", f":{путь}"],
                              capture_output=True, text=True, errors="replace",
                              timeout=30).stdout
    except (OSError, subprocess.SubprocessError):
        return ""


def самотест():
    случаи = [
        (["app/lib/насос.py"], {}, 1,
         "БОЛЬНОЙ СЛУЧАЙ: новый модуль без единого теста в коммите — находка"),
        (["app/lib/насос.py", "app/tests/test_подача.py"],
         {"app/tests/test_подача.py": "from app.lib.насос import расход"}, 0,
         "тест назван по сценарию, но модуль в нём упомянут — засчитан"),
        (["app/lib/насос.py", "app/tests/test_чужое.py"],
         {"app/tests/test_чужое.py": "from app.lib.труба import длина"}, 1,
         "БОЛЬНОЙ СЛУЧАЙ: тест есть, но про другой модуль — не засчитан"),
        (["scripts/новый-гейт.py"], {}, 0,
         "харнес исключён: самотесты живут внутри скриптов"),
        (["docs/спека.md", "data/район.yaml"], {}, 0,
         "документы и данные — не код, молчим"),
        (["app/tests/test_новый.py"], {}, 0, "сам тест тестом не требует"),
        ([], {}, 0, "пустой коммит — чисто"),
        (["app/db/alembic/versions/0051_журнал.py", "app/api/схемы/__init__.py",
          "app/web/src/Панель.tsx", "app/scripts/сборка.sh"], {}, 0,
         "БОЛЬНОЙ СЛУЧАЙ: миграция, __init__, компонент и скрипт — теста не просим"),
    ]
    ok = True
    исключения = ["scripts/", "harness/"]
    for добавленные, содержимое, ждём, зачем in случаи:
        вышло = len(без_теста(добавленные, содержимое, исключения))
        if вышло != ждём:
            ok = False
            print(f"  ПЛОХО {зачем}: находок {вышло}, ждали {ждём}")
        else:
            print(f"  ок    {зачем}")
    # БОЛЬНОЙ СЛУЧАЙ 14.09.2026: git молчит, индекс выглядит пустым, и гейт
    # печатает «новых модулей без теста нет». Судится боевой путь целиком.
    sys.path.insert(0, str(КОРЕНЬ / "scripts" / "lib"))
    from proba_git import гейт_краснеет_без_git
    if гейт_краснеет_без_git(__file__, "", "индекс не прочитан") != 0:
        ok = False
    print("САМОТЕСТ %s: %d путей, первым — больной случай"
          % ("ПРОЙДЕН" if ok else "ПРОВАЛЕН", len(случаи) + 1))
    return 0 if ok else 1


def _строгость_из_состояния(находок, строгость_конфига):
    """Строгость: конфиг задаёт пол, состояние поднимает. Гейт взрослеет сам."""
    try:
        import importlib.util
        спец = importlib.util.spec_from_file_location(
            "пайплайн", КОРЕНЬ / "scripts" / "pajplajn.py")
        модуль = importlib.util.module_from_spec(спец)
        спец.loader.exec_module(модуль)
        строгость, сменилась = модуль.отметить_прогон("тесты_до_кода", находок)
    except Exception:
        return строгость_конфига, False
    if строгость_конфига == "красный":
        return "красный", False
    return строгость, сменилась


def main():
    if "--selftest" in sys.argv:
        return самотест()
    исключения, расширения, пропускать, строгость = конфиг()
    добавленные, изменённые = _индекс("A"), _индекс("M")
    if добавленные is None or изменённые is None:
        print("[тесты до кода] индекс не прочитан: git не отдал состав коммита — "
              "судить нечем. «Нечем судить» это не «новых модулей нет».")
        return 1
    все_в_коммите = добавленные + изменённые
    содержимое = {п: _staged_текст(п) for п in все_в_коммите if это_тест(п)}
    сироты = без_теста(добавленные, содержимое, исключения, расширения, пропускать)
    строгость, сменилась = _строгость_из_состояния(сироты, строгость)
    if сменилась:
        print("[тесты до кода] обкатка закончена: гейт стал КРАСНЫМ — "
              "дальше новый модуль без теста коммит не пройдёт")
    if not сироты:
        print(f"[тесты до кода] новых модулей без теста нет "
              f"(добавлено файлов: {len(добавленные)})")
        return 0
    if os.environ.get("HARNESS_PIPELINE_FORCE"):
        причина = (os.environ.get("HARNESS_PIPELINE_WHY") or "").strip()
        if причина:
            print(f"[тесты до кода] обход разрешён: {причина}")
            return 0
    print("[тесты до кода] новый модуль приходит без теста:")
    for путь in сироты:
        print(f"    {путь}")
    print("    Тест на модуль — в ТОМ ЖЕ коммите. Имя теста любое: гейт ищет")
    print("    упоминание модуля внутри теста, а не одноимённый файл.")
    # Жёлтый на обкатке: правило новое, база ненулевая (75 коммитов истории),
    # а краснящий с первого дня гейт отключают вместе с пользой.
    return 1 if строгость == "красный" else ЖЁЛТЫЙ


if __name__ == "__main__":
    sys.exit(main())
