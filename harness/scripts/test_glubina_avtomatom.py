print(f"  карточек всего {len(живые)}, заведённых автоматом (источник inbox:) "
      f"{len(из_очереди)}, из них без поля «глубина» {len(без_глубины)}")
print(f"  из безглубинных в статусе test: "
      f"{sum(1 for к in без_глубины if к.get('status') == 'test')} — "
      f"работа шла, а глубина не назначалась никогда")

# ─── подставной двор: копия дерева, своя карта, своя очередь ────────────────
МАРКЕР = "зюзюк"          # слова нет ни в одном списке живого судьи
ПОДМЕНА_ХАРАКТЕРА = "механическая"   # имя настоящее, но по тексту пробы недостижимо
СООБЩЕНИЕ = ("Надо сделать зюзюку в панели состояния, сейчас её нет "
             "и владелец не видит статус смены")
НОВЫЕ_ПРАВИЛА = (f'СЛОВА_ХАРАКТЕРА = (\n'
                 f'    ("{ПОДМЕНА_ХАРАКТЕРА}", ("{МАРКЕР}",)),\n'
                 f')\n')


def двор(подменить_судью: bool) -> dict:
    """Своё дерево: копия scripts/ и harness/config/, карта, очередь, LOG_DIR.

    Копия, а не симлинк: скрипты берут соседей через Path(__file__).resolve(),
    и симлинк вернул бы их в боевой каталог — подмена судьи не состоялась бы,
    а путь позеленел бы впустую.
    """
    корень = Path(tempfile.mkdtemp(prefix="глубина-автоматом-"))
    ДВОРЫ.append(корень)
    shutil.copytree(КОРЕНЬ / "scripts", корень / "scripts",
                    ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    shutil.copytree(КОРЕНЬ / "harness" / "config", корень / "harness" / "config")

    (корень / "inbox" / "обработано").mkdir(parents=True)
    (корень / "inbox" / "7.1.txt").write_text(СООБЩЕНИЕ, encoding="utf-8")
    карта = корень / "dev-map.yaml"
    карта.write_text(
        "version: 1\nqueue: []\nlayers:\n  - { id: infra, label: И, color: \"#1\" }\n"
        "lines:\n  - id: core\n    layer: infra\n    name: Ядро\n    tasks:\n\n"
        "      - id: hr.первая\n        status: plan\n        title: Первая\n"
        "        summary: была\n", encoding="utf-8")

    # Вход модели подменён: реальный sprosit-model.py в пробе звать нельзя.
    # Стаб отмечается в файле (значит, автомат прошёл именно этим входом) и
    # выходит кодом 3 — «модель молчит», путь, который автомат уже умеет.
    маркер_модели = корень / "модель-звали.txt"
    (корень / "fake-model.py").write_text(
        "import sys\n"
        f"open({str(маркер_модели)!r}, 'a', encoding='utf-8').write(' '.join(sys.argv[1:]) + chr(10))\n"
        "sys.exit(3)\n", encoding="utf-8")

    (корень / "install.conf").write_text(
        f'LOG_DIR="{корень / "log"}"\nPROJECT_DIR="{корень}"\n', encoding="utf-8")
    (корень / "harness.conf").write_text('ACTIVE_LINE="core"\n', encoding="utf-8")

    судья = корень / "scripts" / "pajplajn.py"
    заменено = 0
    if подменить_судью:
        текст = судья.read_text(encoding="utf-8")
        текст, заменено = re.subn(r"^СЛОВА_ХАРАКТЕРА = \(.*?^\)\n", НОВЫЕ_ПРАВИЛА,
                                  текст, flags=re.S | re.M)
        судья.write_text(текст, encoding="utf-8")
        compile(текст, str(судья), "exec")   # подмена не имеет права ломать судью

    return {"корень": корень, "карта": карта, "инбокс": корень / "inbox",
            "судья": судья, "маркер_модели": маркер_модели, "замен": заменено,
            "окружение": {**os.environ,
                          "HARNESS_INSTALL_CONF": str(корень / "install.conf"),
                          "HARNESS_CONF": str(корень / "harness.conf"),
                          "LOG_DIR": str(корень / "log"),
                          "HARNESS_SPROSIT_MODEL": str(корень / "fake-model.py")}}


def автомат(д: dict, *ещё: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["python3", str(д["корень"] / "scripts" / "karta-iz-soobshcheniya.py"),
         "--сообщение", "7.1", "--карта", str(д["карта"]),
         "--инбокс", str(д["инбокс"]), "--линия", "core", *ещё],
        capture_output=True, text=True, timeout=180, env=д["окружение"])


def новая_карточка(карта: Path) -> dict:
    задачи = [з for з in _карточки(yaml.safe_load(карта.read_text(encoding="utf-8")) or {})
              if str(з.get("источник") or "").startswith("inbox:")]
    return задачи[0] if len(задачи) == 1 else {}


