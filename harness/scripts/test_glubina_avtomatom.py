карточка = новая_карточка(чистый["карта"])
все_задачи = list(_карточки(yaml.safe_load(
    чистый["карта"].read_text(encoding="utf-8")) or {}))
проба("карта выросла ровно на одну карточку, прежняя цела",
      len(все_задачи) == 2 and any(з["id"] == "hr.первая" for з in все_задачи),
      f"задач в карте {len(все_задачи)}: {[з.get('id') for з in все_задачи]}")

глубина = карточка.get("глубина")
