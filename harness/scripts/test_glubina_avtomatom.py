#!/usr/bin/env python3
"""Глубина у карточки, которую завёл АВТОМАТ, — и кто её подтверждает.

Откуда взята проба. Владелец 13.09.2026: «это должно быть не просто памятью,
должен работать чёткий механизм» — про своё же правило «пересмотр карты сразу
ставит задаче статус и глубину».

УЛИКА (замер живой карты, печатается при каждом прогоне): карточки заводит код
`scripts/karta-iz-soobshcheniya.py`, а поле «глубина» он не пишет вовсе. На
13.09.2026 в карте 21 карточка с «источник: inbox:», из них без глубины 16 в
коммите 71f40c4 и 15 сейчас — разница ровно в тех, куда поле вписали РУКАМИ,
когда гейт покраснел. Механизм, который держится на внимании смены, — не
механизм.

Что закрепляют пути ниже:

1. автомат пишет «глубина» с четырьмя ключами и «кем: автомат» — заготовку, а
   не решение. Вычислять глубину формулой нельзя (ревью спеки 13.09, C-2/C-5:
   volume самоотчётен), поэтому автомат заполняет, а решает смена;
2. значения берутся у ЕДИНСТВЕННОГО судьи — scripts/pajplajn.py. Своя копия
   правил внутри автомата = второй судья того же факта (harness/config/
   признаки.yaml, гейт check-priznaki.py). Ловится подменой: у копии дерева
   правила характера заменены, и вывод автомата обязан пойти следом;
3. гейт пайплайна при переходе plan → wip/test требует ПОДТВЕРЖДЁННОЙ глубины
   («кем: смена»); заготовка автомата в работу не пропускается;
4. карточки без поля «глубина» краснеют как прежде: заготовка не закрывает
   молча существующую дыру.

Каждый путь создаёт СВОЁ условие: свой двор (копия scripts/ и harness/config/),
своя карта, своя очередь, свой LOG_DIR, подставной вход модели. Боевые
dev-map.yaml, scripts/*.py и $LOG_DIR не трогаются — это проверяется md5 до и
после прогона.

Прогон:
    python3 scripts/test_glubina_avtomatom.py
Код возврата: 0 — все пути прошли, 1 — есть упавший.
"""
