ОК, УПАЛО = [], []
ДВОРЫ = []


def проба(имя: str, условие: bool, подробность: str = "") -> None:
    (ОК if условие else УПАЛО).append(имя)
    знак = "✓" if условие else "✗"
    print(f"  {знак} {имя}" + (f" — {подробность}" if подробность and not условие else ""))


def _модуль(имя_файла: str, имя_модуля: str, откуда: Path | None = None):
    """Импорт по пути: имена с дефисом обычным import не берутся."""
    спец = importlib.util.spec_from_file_location(
        имя_модуля, (откуда or (КОРЕНЬ / "scripts")) / имя_файла)
    модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(модуль)
    return модуль


def md5(путь: Path) -> str:
    return hashlib.md5(путь.read_bytes()).hexdigest() if путь.exists() else "НЕТ"


# ─── слепок боевого: проба не имеет права играть на живом ────────────────────
БОЕВАЯ_КАРТА = КОРЕНЬ / "dev-map.yaml"
БОЕВЫЕ_ИСХОДНИКИ = [КОРЕНЬ / "scripts" / имя for имя in
                    ("karta-iz-soobshcheniya.py", "pajplajn.py", "check-pipeline.py")]
БОЕВОЙ_LOG_DIR = Path(из_файла("/etc/harness/install.conf").get("LOG_DIR")
                      or "/var/log/harness")
БОЕВОЙ_ЛОК = БОЕВОЙ_LOG_DIR / "locks" / "services" / "dev-map.lock"


def _слепок_боевого() -> dict:
    слепок = {"карта": md5(БОЕВАЯ_КАРТА)}
    for путь in БОЕВЫЕ_ИСХОДНИКИ:
        слепок[путь.name] = md5(путь)
    слепок["лок"] = (f"{БОЕВОЙ_ЛОК.stat().st_mtime_ns}/{БОЕВОЙ_ЛОК.stat().st_size}"
                     if БОЕВОЙ_ЛОК.exists() else "НЕТ")
    return слепок


СЛЕПОК_ДО = _слепок_боевого()

# ─── УЛИКА: замер живой карты (только чтение) ───────────────────────────────
def _карточки(дерево):
    if isinstance(дерево, dict):
        if "id" in дерево and "status" in дерево:
            yield дерево
        for значение in дерево.values():
            yield from _карточки(значение)
    elif isinstance(дерево, list):
        for значение in дерево:
            yield from _карточки(значение)


