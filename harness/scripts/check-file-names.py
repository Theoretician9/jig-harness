def почему(путь, контекст=None):
    """Причина отказа — та, что верна для ЭТОГО пути.

    Один текст на две области врал бы половине случаев: запись памяти это не
    «файл с кодом», и человек, прочитав про импорты, искал бы несуществующий
    дефект.
    """
    контекст = КОНТЕКСТ_ПО_УМОЛЧАНИЮ if контекст is None else контекст
    return ПОЧЕМУ_КОНТЕКСТ if путь.startswith(tuple(контекст)) else ПОЧЕМУ_КОД


def режим_хука():
    """PreToolUse на Write/Edit: отказать В МОМЕНТ создания файла, а не на коммите.

    Два носителя у одного правила — не роскошь: гейт видит только коммит, и до
    него успевает появиться модуль с сотней строк и импортами. Правило,
    перекрытое одним путём из двух, обходится вторым — это уже случалось.
    Отказ хука — код 2 и причина в stderr (так же устроен guard_bash).
    """
    try:
        нагрузка = json.loads(sys.stdin.read())
    except ValueError:
        return 0                      # не разобрали — не мешаем работать
    путь = (нагрузка.get("tool_input") or {}).get("file_path") or ""
    if not путь or not находки([путь], расширения_кода()):
        return 0
    print(f"Нелатинское имя: {путь}\n{почему(путь)}", file=sys.stderr)
    return 2


def main():
    if "--selftest" in sys.argv:
        return самотест()
    if "--hook" in sys.argv:
        return режим_хука()
    пути = sys.stdin.read().splitlines()
    плохие = находки(пути, расширения_кода(), пути_контекста())
    транслитные = транслитные_имена(пути, расширения_кода(), пути_контекста())
    if not плохие and not транслитные:
        print("[имена файлов] новые имена — латиница, английские слова")
        return 0
    if плохие:
        print("[имена файлов] нелатинское имя у нового файла:")
        for путь in плохие:
            print(f"    {путь}")
        for причина in dict.fromkeys(почему(п, пути_контекста()) for п in плохие):
            print(f"    {причина}")
    if транслитные:
        print("[имена файлов] транслит вместо английского слова:")
        for путь, слова in транслитные:
            print(f"    {путь} — не английские слова: {', '.join(слова)}")
