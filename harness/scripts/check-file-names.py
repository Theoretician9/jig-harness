def английские_слова(словарь=None, исключения=None) -> set:
    """Словарь + технические исключения. Нет файлов — суда о транслите нет."""
    слова = set()
    try:
        with gzip.open(словарь or СЛОВАРЬ_АНГЛИЙСКОГО, "rt", encoding="utf-8") as fh:
            слова = {с.strip() for с in fh if с.strip()}
    except OSError:
        return set()
    try:
        for строка in (исключения or СЛОВАРЬ_ИСКЛЮЧЕНИЙ).read_text(encoding="utf-8").splitlines():
            слово = строка.split("#")[0].strip().lower()
            if слово:
                слова.add(слово)
    except OSError:
        pass
    return слова


def транслит_в_имени(путь: str, словарь: set) -> list:
    """Слова имени, которых нет ни в словаре, ни в исключениях.

    Судится ИМЯ без расширения, разбитое по дефисам, точкам и подчёркиваниям.
    Цифры и односимвольные куски пропускаются: «etap-2», «v-2» законны.
    """
    if not словарь:
        return []
    # Расширения снимаются С КОНЦА и все: «english-words.txt.gz» иначе оставит
    # «txt» отдельным словом, и гейт покраснеет на собственном словаре.
    имя = Path(путь).name
    while Path(имя).suffix:
        имя = имя[: -len(Path(имя).suffix)]
    # Кириллическое слово судит ПЕРВОЕ правило (НЕ_ЛАТИНИЦА); здесь оно дало бы
    # вторую жалобу на ту же беду и увело бы отчёт от настоящей причины.
    чужие = [с for с in re.split(r"[-_.]+", имя.lower())
             if len(с) >= 2 and с.isascii() and not any(з.isdigit() for з in с)
             and not знакомое(с, словарь)]
    return чужие


def знакомое(слово: str, словарь: set) -> bool:
    """Слово или любая его словарная форма.

    Словарь держит основы: «played» и «kills» в нём отсутствуют, хотя оба
    английские. Отсечение окончаний дешевле и честнее, чем второй словарь: не
    узнав формы, гейт краснел бы на здоровых именах, а краснеющий гейт
    отключают.
    """
    if слово in словарь:
        return True
    for окончание in ("s", "es", "ed", "d", "ing", "er", "ers", "ly"):
        if слово.endswith(окончание):
            основа = слово[: -len(окончание)]
            if основа in словарь or основа + "e" in словарь:
                return True
            # «running» → «run»: удвоенная согласная перед окончанием.
            if len(основа) > 2 and основа[-1] == основа[-2] and основа[:-1] in словарь:
                return True
    return False


def расширения_кода(путь=HARNESS_CONF):
    """Что на этой установке считается кодом. Нет ключа — вшитый список."""
    try:
        текст = Path(путь).read_text(encoding="utf-8")
    except OSError:
        return КОД_ПО_УМОЛЧАНИЮ
    найдено = re.search(r'^CODE_NAME_EXTS="?([^"#\n]*)"?', текст, re.M)
    если_задано = (найдено.group(1).strip() if найдено else "")
    if not если_задано:
        return КОД_ПО_УМОЛЧАНИЮ
    return tuple(ч if ч.startswith(".") else "." + ч for ч in если_задано.split())


def пути_контекста(путь=HARNESS_CONF):
    """Каталоги, чьё содержимое грузится модели. Нет ключа — вшитый список."""
    try:
        текст = Path(путь).read_text(encoding="utf-8")
    except OSError:
        return КОНТЕКСТ_ПО_УМОЛЧАНИЮ
    найдено = re.search(r'^MODEL_CONTEXT_PATHS="?([^"#\n]*)"?', текст, re.M)
    если_задано = найдено.group(1).strip() if найдено else ""
    if not если_задано:
        return КОНТЕКСТ_ПО_УМОЛЧАНИЮ
    return tuple(ч if ч.endswith("/") else ч + "/" for ч in если_задано.split())


def находки(пути, код=None, контекст=None):
    """Новые файлы с нелатинским именем — код или контекст модели.

    Чистая функция — её и проверяем. Две области, одно правило: имя файла,
    которое станет именем модуля ИЛИ уедет в контекст модели, пишется
    латиницей.
    """
    код = код or КОД_ПО_УМОЛЧАНИЮ
    контекст = КОНТЕКСТ_ПО_УМОЛЧАНИЮ if контекст is None else контекст
    плохие = []
    for путь in пути:
        путь = путь.strip().strip('"')
        if not путь:
            continue
        корень = next((к for к in контекст if путь.startswith(к)), None)
        # Две области судятся РАЗНОЙ мерой, и это не прихоть.
        #   * код: только ИМЯ файла — оно становится именем модуля; кириллица
        #     в каталоге кода решается владельцем отдельно (правило 11.09);
        #   * контекст модели: путь ВНУТРИ области — модель видит и каталог.
        #     Имя скила это имя его КАТАЛОГА, и `.claude/skills/приём-задачи/
        #     SKILL.md` по имени файла выглядел бы чистым, оставаясь
        #     кириллицей в глазах модели.
        #
        # Сам корень области из суда исключён: `память/` кириллическая, и без
        # этого гейт краснел бы на КАЖДОЙ новой записи, то есть на здоровой
        # работе. Переименование самих корней — шаг миграции, а не повод
        # держать ворота красными (краснеющий гейт отключают).
        судим = путь[len(корень):] if корень else Path(путь).name
        if (корень or путь.endswith(код)) and НЕ_ЛАТИНИЦА.search(судим):
            плохие.append(путь)
    return плохие


def транслитные_имена(пути, код=None, контекст=None, словарь=None):
    """Пары (путь, чужие слова) для тех же областей, что судит правило латиницы.

    Область та же не ради симметрии: имя файла кода становится именем модуля, а
    имя внутри контекста модели уезжает в каждую сессию — платится и тем, и
    другим. Документ, который читает человек, не судится вовсе.
    """
    код = код or КОД_ПО_УМОЛЧАНИЮ
    контекст = КОНТЕКСТ_ПО_УМОЛЧАНИЮ if контекст is None else контекст
    словарь = английские_слова() if словарь is None else словарь
    найдено = []
    for путь in пути:
        путь = путь.strip().strip('"')
        if not путь:
            continue
        в_контексте = any(путь.startswith(к) for к in контекст)
        if not (в_контексте or путь.endswith(код)):
            continue
        чужие = транслит_в_имени(путь, словарь)
        if чужие:
            найдено.append((путь, чужие))
    return найдено


