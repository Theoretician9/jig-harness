#!/usr/bin/env python3
"""Проверка носителя живой проверки демонов (scripts/live-check-daemon.py).

Откуда взято. Спека `docs/specs/2026-10-15-живая-проверка-механизмов.md` §3.1,
класс A1: «прочитан журнал ПОСЛЕДНЕГО кронового прогона — путь берётся из
`crontab -l`, не из реестра — либо вызов в среде крона». Носителя этому
предикату в коде не было, и 22 демона в расписании оставались непроверенными:
проверяющий мог написать «работает» своим словом, а гейт судил только общий
след.

Что охраняется сверх буквы спеки:

1. **Путь журнала — ИЗ РАСПИСАНИЯ.** Реестр говорит, чем механизм проверяется,
   а не куда он пишет под кроном; журнал, названный в реестре, может вообще не
   быть тем файлом, в который крон перенаправляет вывод.
2. **Свежесть судится ПЕРИОДОМ своего расписания.** Демон раз в десять минут и
   демон раз в месяц молчат по-разному, и один потолок врал бы одному из них
   ([[server-downtime-is-not-the-daemons-fault]] — та же беда с другой стороны).
3. **Пустой журнал — не доказательство.** Файл есть, прогона в нём нет: это
   «не прочитали», а не «работает» ([[unreadable-source-turns-check-green]]).
4. **Нет в расписании — предикат неприменим.** Демон без строки крона (A2,
   служба) судится другим способом, и молчать об этом нельзя.

Проба создаёт свой двор: файл расписания, журналы и своё состояние. Живое
расписание и боевые данные не трогаются.

Прогон: python3 scripts/test_live_check_daemon.py
Код возврата: 0 — все случаи зелёные, 1 — хоть один плохой.
"""
from __future__ import annotations

import hashlib
import os
import pathlib
import re
import subprocess
import sys
import tempfile
import time

import yaml

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
# Путь прибора — через окружение, иначе мутационная проба судит боевой
# файл и зелена на любой поломке (поймано прогоном 17.10.2026: четыре
# мутации из четырёх не покраснели).
ПРОГОН = pathlib.Path(os.environ.get("HARNESS_LIVE_CHECK_DAEMON_TOOL")
                      or КОРЕНЬ / "scripts" / "live-check-daemon.py")
БОЕВЫЕ = (КОРЕНЬ / "harness" / "config" / "live-check-state.yaml",)

хорошо = 0
плохо = 0


def случай(имя: str, условие: bool, пояснение: str = "") -> None:
    global хорошо, плохо
    if условие:
        хорошо += 1
        print(f"  ок    {имя}")
    else:
        плохо += 1
        print(f"  ПЛОХО {имя}{(': ' + пояснение) if пояснение else ''}")


def двор(расписание: str, журналы: dict[str, tuple[str, float]]) -> pathlib.Path:
    """Двор пробы: файл расписания и журналы с заданным возрастом.

    `журналы`: имя файла → (содержимое, сколько минут назад записан).
    """
    путь = pathlib.Path(tempfile.mkdtemp(prefix="демон-живьём-"))
    (путь / "журналы").mkdir()
    (путь / "следы").mkdir()
    (путь / "расписание").write_text(расписание, encoding="utf-8")
    for имя, (текст, минут_назад) in журналы.items():
        файл = путь / "журналы" / имя
        файл.write_text(текст, encoding="utf-8")
        когда = time.time() - минут_назад * 60
        os.utime(файл, (когда, когда))
    (путь / "состояние.yaml").write_text("версия: 1\nпроверено: {}\n", encoding="utf-8")
    return путь


def прогон(путь: pathlib.Path, *доводы: str,
           среда: dict | None = None) -> tuple[int, str]:
    среда_прогона = dict(os.environ)
    среда_прогона.update({
        "HARNESS_LIVE_CHECK_CRON": str(путь / "расписание"),
        "HARNESS_LIVE_CHECK_STATE": str(путь / "состояние.yaml"),
        "HARNESS_LIVE_CHECK_DAEMON_TRACE_DIR": str(путь / "следы"),
        "HARNESS_LIVE_CHECK_REPO": str(КОРЕНЬ),
        # Данные о демонах — СВОИ у стенда: боевой файл юнитов называл бы
        # стенду чужое «как пишет журнал», и проба судила бы производство.
        "HARNESS_LIVE_CHECK_UNITS": str(путь / "юниты.yaml"),
    })
    # Своё СТАРШЕ общего: случаю про молчуна нужен свой корень с механизмом,
    # а общая раскладка ставила боевой — и прибор звал боевой файл.
    среда_прогона.update(среда or {})
    среда = среда_прогона
    готово = subprocess.run([sys.executable, str(ПРОГОН), *доводы],
                            capture_output=True, text=True, env=среда, timeout=120)
    return готово.returncode, готово.stdout + готово.stderr


def пишет(путь: pathlib.Path, механизм: str, как: str) -> None:
    """Поле данных стенда «как демон пишет журнал»: каждый-прогон, по-событию
    или молчит-при-успехе. Прибор берёт его из данных и не угадывает по
    журналу: кроновый журнал непуст и у того, кто пишет его на каждом прогоне,
    и у того, кто молчит при успехе и наследует старые ошибки (улика 11.11.2026:
    speed_mode и process-dispatcher живы, а журналы молчат с 06.11 и 07.11)."""
    файл = путь / "юниты.yaml"
    данные = yaml.safe_load(файл.read_text(encoding="utf-8")) if файл.is_file() else None
    данные = данные or {}
    данные.setdefault("как_пишет_журнал", {})[механизм] = как
    файл.write_text(yaml.safe_dump(данные, allow_unicode=True), encoding="utf-8")


def расписание_двора(путь: pathlib.Path, период: str = "*/10 * * * *",
                     журнал: str = "сторож.log") -> str:
    return (f"# свой двор\n"
            f"{период}  /путь/harness/demons/сторож.sh >>{путь}/журналы/{журнал} 2>&1\n")


def main() -> int:
    было = {п: hashlib.md5(п.read_bytes()).hexdigest() for п in БОЕВЫЕ if п.exists()}

    # ── БОЛЬНЫМ СЛУЧАЕМ ПЕРВЫМ: журнал СТАРШЕ своего расписания ───────────
    # Это и есть дыра, ради которой носитель написан: «демон есть, журнал есть»
    # выглядит работой, пока не спросить, когда он писал последний раз.
    д = двор("", {})
    д_расписание = расписание_двора(д)
    (д / "расписание").write_text(д_расписание, encoding="utf-8")
    пишет(д, "harness/demons/сторож.sh", "каждый-прогон")
    (д / "журналы" / "сторож.log").write_text(
        "2026-10-01 03:00:01  сторож: обошёл 5 задач\n", encoding="utf-8")
    старое = time.time() - 300 * 60
    os.utime(д / "журналы" / "сторож.log", (старое, старое))
    код, вывод = прогон(д, "harness/demons/сторож.sh")
    случай("БОЛЬНОЙ СЛУЧАЙ: журнал старше своего расписания — отказ",
           код == 1 and "старше своего расписания" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    # ── Нет строки в расписании: предикат A1 неприменим, и это говорится ──
    д = двор("# пусто\n", {})
    код, вывод = прогон(д, "harness/demons/сторож.sh")
    случай("нет в расписании — предикат неприменим, сказано вслух",
           код == 1 and "в расписании его нет" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    # ── Журнала нет на диске ──────────────────────────────────────────────
    д = двор("", {})
    (д / "расписание").write_text(расписание_двора(д), encoding="utf-8")
    пишет(д, "harness/demons/сторож.sh", "каждый-прогон")
    код, вывод = прогон(д, "harness/demons/сторож.sh")
    случай("журнала нет на диске — отказ с путём",
           код == 1 and "журнал кронового прогона не найден" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    # ── Журнал пуст: файл есть, прогона в нём нет ────────────────────────
    д = двор("", {"сторож.log": ("", 1)})
    (д / "расписание").write_text(расписание_двора(д), encoding="utf-8")
    пишет(д, "harness/demons/сторож.sh", "каждый-прогон")
    код, вывод = прогон(д, "harness/demons/сторож.sh")
    случай("пустой журнал — отказ, а не зачёт",
           код == 1 and "журнал пуст" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    # ── ЗДОРОВЫЙ ПУТЬ: свежий журнал со строкой прогона ──────────────────
    д = двор("", {"сторож.log": (
        "2026-10-17 07:20:01  сторож: обошёл 5 задач, разбудил 0\n", 3)})
    (д / "расписание").write_text(расписание_двора(д), encoding="utf-8")
    пишет(д, "harness/demons/сторож.sh", "каждый-прогон")
    код, вывод = прогон(д, "harness/demons/сторож.sh", "--записать")
    случай("здоровый путь: кроновый прогон доказан, код 0",
           код == 0 and "кроновый прогон доказан" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")
    состояние = yaml.safe_load((д / "состояние.yaml").read_text()) or {}
    запись = (состояние.get("проверено") or {}).get("harness/demons/сторож.sh") or {}
    случай("в запись легли «живьём», «увидели», «след» и «когда»",
           all(запись.get(п) for п in ("живьём", "увидели", "след", "когда")),
           str(запись))
    случай("«увидели» цитирует ЖУРНАЛ ДЕМОНА дословно",
           "обошёл 5 задач, разбудил 0" in (запись.get("увидели") or ""),
           str(запись.get("увидели")))
    случай("«живьём» называет расписание и путь журнала ИЗ РАСПИСАНИЯ",
           "*/10" in (запись.get("живьём") or "")
           and "журналы/сторож.log" in (запись.get("живьём") or ""),
           str(запись.get("живьём")))
    след = д / "следы" / "harness-demons-сторож.sh.log"
    случай("след написан прибором и несёт хвост журнала",
           след.is_file() and "обошёл 5 задач" in след.read_text(),
           str(след))

    # ── Период из расписания: суточный демон молчит сутки законно ────────
    д = двор("", {"ночной.log": ("2026-10-17 03:00:01  уборка: снесено 3\n", 600)})
    (д / "расписание").write_text(
        расписание_двора(д, период="0 3 * * *", журнал="ночной.log")
        .replace("сторож.sh", "ночной.sh"), encoding="utf-8")
    пишет(д, "harness/demons/ночной.sh", "каждый-прогон")
    код, вывод = прогон(д, "harness/demons/ночной.sh")
    случай("суточному демону десять часов молчания — законно",
           код == 0 and "кроновый прогон доказан" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    # ── Крон-журнал пуст, а СВОЙ журнал демона свеж ─────────────────────
    # Живой случай 17.10.2026: ежеминутные limit-watch и panel-tunnel в stdout
    # молчат нарочно (иначе крон-журнал растёт на 1440 строк в сутки), а пишут
    # в свой файл. «Журнал пуст» для них — правда о крон-журнале и ложь о
    # работе, поэтому прибор смотрит соседний <имя>.log и ГОВОРИТ ВСЛУХ, что
    # кроновый был пуст.
    д = двор("", {"ежеминутный.cron.log": ("", 1),
                  "ежеминутный.log": (
                      "2026-10-17 07:30:01  ежеминутный: лимита нет, работа идёт\n", 2)})
    (д / "расписание").write_text(
        f"* * * * *  /путь/harness/demons/ежеминутный.sh "
        f">>{д}/журналы/ежеминутный.cron.log 2>&1\n", encoding="utf-8")
    пишет(д, "harness/demons/ежеминутный.sh", "каждый-прогон")
    код, вывод = прогон(д, "harness/demons/ежеминутный.sh", "--записать")
    случай("пустой кроновый при свежем своём журнале — доказано по своему",
           код == 0 and "кроновый прогон доказан" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")
    состояние = yaml.safe_load((д / "состояние.yaml").read_text()) or {}
    запись = (состояние.get("проверено") or {}).get("harness/demons/ежеминутный.sh") or {}
    случай("и сказано вслух, что кроновый журнал ПУСТ",
           "кроновый журнал пуст" in (запись.get("живьём") or ""),
           str(запись.get("живьём")))
    случай("цитата — из СВОЕГО журнала демона",
           "лимита нет, работа идёт" in (запись.get("увидели") or ""),
           str(запись.get("увидели")))

    # Оба журнала пусты — отказ остаётся отказом: иначе ветка «свой журнал»
    # превратила бы молчание в доказательство.
    д = двор("", {"тихий.cron.log": ("", 1), "тихий.log": ("", 1)})
    (д / "расписание").write_text(
        f"* * * * *  /путь/harness/demons/тихий.sh "
        f">>{д}/журналы/тихий.cron.log 2>&1\n", encoding="utf-8")
    пишет(д, "harness/demons/тихий.sh", "каждый-прогон")
    код, вывод = прогон(д, "harness/demons/тихий.sh")
    случай("БОЛЬНОЙ СЛУЧАЙ: оба журнала пусты — отказ",
           код == 1 and "журнал пуст" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    # ── Журнал пишется ТОЛЬКО ПО СОБЫТИЮ, а метка свежа ─────────────────
    # Живой случай 17.10.2026: limit-watch бегает каждую минуту и пишет в журнал
    # лишь когда лимит встал или работа пошла — его журналу было 138 минут при
    # периоде 1 мин, а метка обновлена 3 минуты назад. «Демон не бегал» о таком
    # демоне — ложь; доказательством служит метка, которую он ставит каждый
    # прогон, и в записи это сказано вслух.
    д = двор("", {"событийный.cron.log": ("", 1),
                  "событийный.log": (
                      "2026-10-17 05:12:01  работа пошла снова (простой 56 мин)\n", 140)})
    (д / "метки").mkdir()
    метка = д / "метки" / "событийный"
    метка.write_text("", encoding="utf-8")
    (д / "расписание").write_text(
        f"* * * * *  /путь/harness/demons/событийный.sh "
        f">>{д}/журналы/событийный.cron.log 2>&1\n", encoding="utf-8")
    пишет(д, "harness/demons/событийный.sh", "по-событию")
    среда_метки = {"HARNESS_LIVE_CHECK_HEARTBEAT": str(д / "метки")}
    код, вывод = прогон(д, "harness/demons/событийный.sh", "--записать",
                        среда=среда_метки)
    случай("журнал по событию + свежая метка — жив, названо последнее событие",
           код == 0 and "последнее событие" in вывод
           and "кроновый прогон доказан" not in вывод,
           f"код {код}, вывод {вывод[:300]!r}")
    состояние = yaml.safe_load((д / "состояние.yaml").read_text()) or {}
    запись = (состояние.get("проверено") or {}).get("harness/demons/событийный.sh") or {}
    случай("и сказано вслух, что свежесть доказана МЕТКОЙ",
           "МЕТКОЙ" in (запись.get("живьём") or ""), str(запись.get("живьём")))

    # Метка тоже стара — отказ: иначе ветка метки превратила бы мёртвого
    # демона в живого.
    д = двор("", {"мёртвый.cron.log": ("", 200)})
    (д / "метки").mkdir()
    старая = д / "метки" / "мёртвый"
    старая.write_text("", encoding="utf-8")
    когда = time.time() - 300 * 60
    os.utime(старая, (когда, когда))
    (д / "расписание").write_text(
        f"* * * * *  /путь/harness/demons/мёртвый.sh "
        f">>{д}/журналы/мёртвый.cron.log 2>&1\n", encoding="utf-8")
    пишет(д, "harness/demons/мёртвый.sh", "по-событию")
    код, вывод = прогон(д, "harness/demons/мёртвый.sh", среда=среда_метки)
    случай("БОЛЬНОЙ СЛУЧАЙ: и журнал, и метка стары — отказ",
           код == 1, f"код {код}, вывод {вывод[:300]!r}")

    # ── Без «--записать» состояние не трогается ──────────────────────────
    д = двор("", {"сторож.log": ("2026-10-17 07:20:01  сторож: обошёл 5 задач\n", 3)})
    (д / "расписание").write_text(расписание_двора(д), encoding="utf-8")
    пишет(д, "harness/demons/сторож.sh", "каждый-прогон")
    прогон(д, "harness/demons/сторож.sh")
    состояние = yaml.safe_load((д / "состояние.yaml").read_text()) or {}
    случай("без «--записать» состояние не меняется",
           not (состояние.get("проверено") or {}), str(состояние))

    # Сухой прогон не оставляет СЛЕДОВ: след — доказательство для записи, и
    # прогон «посмотреть» без своего каталога переписывал живые следы чужих
    # записей (замер 11.11.2026: следы диспетчера и speed_mode переписаны в
    # 07:2x и 07:38) — «увидели» записи перестаёт быть подстрокой следа.
    следы = д / "следы"
    до = sorted((ф.name, ф.stat().st_mtime_ns, ф.read_bytes()) for ф in следы.iterdir())
    прогон(д, "harness/demons/сторож.sh")
    после = sorted((ф.name, ф.stat().st_mtime_ns, ф.read_bytes()) for ф in следы.iterdir())
    случай("БОЛЬНОЙ СЛУЧАЙ: сухой прогон по расписанию не пишет следа",
           до == после, f"было {[и for и, *_ in до]}, стало {[и for и, *_ in после]}")

    # ── ДЕМОН ПО РАСПИСАНИЮ, журнал которого пишется КАЖДЫЙ прогон ────────
    # Улика 11.11.2026: диспетчер под кроном «каждую минуту» молчал четверо
    # суток, метка свежая — и прибор сказал «кроновый прогон доказан —
    # IndexError»: свежесть взял у метки, а цитату у журнала любой давности.
    # Журнал, который пишется на каждом прогоне, старше потолка — значит
