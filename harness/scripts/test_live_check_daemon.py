    (д / "юниты.yaml").write_text(
        "юниты:\n  harness/demons/помощник.py:\n"
        "    зовёт: harness/demons/обёртка.sh (крон)\n"
        "    журнал: обёртка.log\n    признак: 'гигиена сервера:'\n"
        "    потолок_минут: 60\n", encoding="utf-8")
    среда = {"HARNESS_LIVE_CHECK_UNITS": str(д / "юниты.yaml"),
             "HARNESS_LOG_DIR": str(д / "журналы")}
    код, вывод = прогон(д, "harness/demons/помощник.py", среда=среда)
    случай("БОЛЬНОЙ СЛУЧАЙ: журнала зовущего нет — не звал ни разу",
           код == 1, вывод[:160])

    журнал_о = д / "журналы" / "обёртка.log"
    журнал_о.write_text("обёртка: начала\nгигиена сервера: нарушений 0\n", encoding="utf-8")
    старо = time.time() - 120 * 60
    os.utime(журнал_о, (старо, старо))
    код, вывод = прогон(д, "harness/demons/помощник.py", среда=среда)
    случай("БОЛЬНОЙ СЛУЧАЙ: журнал зовущего старше потолка", код == 1, вывод[:160])
    случай("и сказано, что давно не бегал зовущий",
           "давно не бегал" in вывод, вывод[:160])

    свежо = time.time() - 5 * 60
    os.utime(журнал_о, (свежо, свежо))
    код, вывод = прогон(д, "harness/demons/помощник.py", среда=среда)
    случай("свежий журнал зовущего со строкой помощника — доказано",
           код == 0, вывод[:160])
    случай("цитата — строка помощника, а не обёртки",
           "гигиена сервера: нарушений 0" in вывод, вывод[:160])

    журнал_о.write_text("обёртка: начала\nобёртка: кончила\n", encoding="utf-8")
    os.utime(журнал_о, (свежо, свежо))
    код, вывод = прогон(д, "harness/demons/помощник.py", среда=среда)
    случай("БОЛЬНОЙ СЛУЧАЙ: в журнале только строки обёртки — не доказано",
           код == 1, вывод[:160])

    # Зовущий пишет не в файл, а в журнал своего юнита: признак тогда
    # ОБЯЗАТЕЛЕН, иначе цитатой станет любая строка зовущего.
    (д / "юниты.yaml").write_text(
        "юниты:\n  scripts/судья.py:\n    зовёт: обёртка\n"
        "    юнит: проба-юнит.service\n    потолок_минут: 60\n", encoding="utf-8")
    среда = системные("ActiveState=active\nActiveEnterTimestamp=",
                      "Oct 17 19:15:12 стенд обёртка[1]: срочное (ответ владельца)")
    код, вывод = прогон(д, "scripts/судья.py", среда=среда)
    случай("БОЛЬНОЙ СЛУЧАЙ: журнал юнита без признака — не доказано",
           код == 1, вывод[:160])
    случай("и сказано про строку соседа", "соседа" in вывод, вывод[:160])

    (д / "юниты.yaml").write_text(
        "юниты:\n  scripts/судья.py:\n    зовёт: обёртка\n"
        "    юнит: проба-юнит.service\n    признак: 'срочное ('\n"
        "    потолок_минут: 60\n", encoding="utf-8")
    код, вывод = прогон(д, "scripts/судья.py", среда=среда)
    случай("его строка в журнале юнита зовущего — доказано", код == 0, вывод[:160])

    среда = системные("ActiveState=active\nActiveEnterTimestamp=",
                      "Oct 17 19:15:12 стенд обёртка[1]: круг прошёл, нового нет")
    код, вывод = прогон(д, "scripts/судья.py", среда=среда)
    случай("БОЛЬНОЙ СЛУЧАЙ: в окне только чужие строки — его не звали",
           код == 1, вывод[:160])

    # ── МОЛЧУН: демон, которому молчать ЗАКОННО по состоянию данных ──────
    # Улика 18.10.2026: panel-tunnel при панели, выведенной через nginx, не
    # печатает НИЧЕГО — ни в кроновый журнал, ни в свой, — и прежний предикат
    # отказывал ему словами «цитировать нечего». Его работа видна только в
    # МЕТКЕ, которую он ставит каждый прогон, а молчание законно не «потому что
    # так вышло», а по значению ключа конфига. Улику о метке пишет ПРИБОР (mtime
    # до и после зова), и это не слова проверяемого о себе.
    д2 = двор("* * * * *  /х/harness/demons/молчун.sh >>журналы/молчун.log 2>&1\n",
              {"молчун.log": ("", 0)})
    (д2 / "harness" / "demons").mkdir(parents=True)
    метка2 = д2 / "метки"
    метка2.mkdir()
    (д2 / "harness" / "demons" / "молчун.sh").write_text(
        '#!/usr/bin/env bash\ntouch "$HARNESS_LIVE_CHECK_HEARTBEAT/молчун"\n',
        encoding="utf-8")
    (д2 / "конфиг").write_text('PANEL_URL="https://harness.свой.домен"\n', encoding="utf-8")
    (д2 / "юниты.yaml").write_text(
        "молчат_нарочно:\n  harness/demons/молчун.sh:\n"
        "    почему: панель выведена через nginx — туннель не нужен\n"
        "    условие: { ключ: PANEL_URL, не_содержит: trycloudflare.com }\n",
        encoding="utf-8")
    среда2 = {"HARNESS_LIVE_CHECK_UNITS": str(д2 / "юниты.yaml"),
              "HARNESS_LIVE_CHECK_HEARTBEAT": str(метка2),
              "HARNESS_LIVE_CHECK_REPO": str(д2),
              "HARNESS_CONF": str(д2 / "конфиг"),
              "HARNESS_LOG_DIR": str(д2 / "журналы")}
    код, вывод = прогон(д2, "harness/demons/молчун.sh", среда=среда2)
    случай("молчун с обновлённой меткой доказан", код == 0, вывод[:200])
    случай("и сказано, что доказательство — метка, а не цитата",
           "молчит нарочно" in вывод, вывод[:200])
    # Сухой прогон молчуна не пишет следов и обёрткой: её след без «--записать»
    # уходит во временный каталог (Р3, 11.11.2026).
    до = sorted((ф.name, ф.stat().st_mtime_ns) for ф in (д2 / "следы").iterdir())
    прогон(д2, "harness/demons/молчун.sh", среда=среда2)
    после = sorted((ф.name, ф.stat().st_mtime_ns) for ф in (д2 / "следы").iterdir())
    случай("БОЛЬНОЙ СЛУЧАЙ: сухой прогон молчуна не пишет следа", до == после,
           f"было {[и for и, *_ in до]}, стало {[и for и, *_ in после]}")


    # БОЛЬНОЙ: метку не трогает — значит прогона не было, и молчание ничего
    # не доказывает.
    (д2 / "harness" / "demons" / "молчун.sh").write_text(
        '#!/usr/bin/env bash\nexit 0\n', encoding="utf-8")
    код, вывод = прогон(д2, "harness/demons/молчун.sh", среда=среда2)
    случай("БОЛЬНОЙ СЛУЧАЙ: молчун не обновил метку — не доказано",
           код == 1, вывод[:200])
    случай("и причина названа меткой, а не молчанием",
           "метк" in вывод, вывод[:200])

    # БОЛЬНОЙ: обещано молчание, а демон заговорил — это находка о НЁМ, и
    # зачесть её за «молчит нарочно» нельзя.
    (д2 / "harness" / "demons" / "молчун.sh").write_text(
        '#!/usr/bin/env bash\ntouch "$HARNESS_LIVE_CHECK_HEARTBEAT/молчун"\n'
        'echo "поднимаю туннель: адрес сменился"\n', encoding="utf-8")
    код, вывод = прогон(д2, "harness/demons/молчун.sh", среда=среда2)
    случай("БОЛЬНОЙ СЛУЧАЙ: обещан молчуном, а сказал — не доказано",
           код == 1, вывод[:200])
    случай("и сказано, ЧТО он сказал",
           "поднимаю туннель" in вывод, вывод[:200])

    # БОЛЬНОЙ: условие молчания в конфиге НЕ стоит — молчание незаконно, и
    # прибор не вправе его прощать (иначе ветвь стала бы отмазкой для любого).
    (д2 / "harness" / "demons" / "молчун.sh").write_text(
        '#!/usr/bin/env bash\ntouch "$HARNESS_LIVE_CHECK_HEARTBEAT/молчун"\n',
        encoding="utf-8")
    (д2 / "конфиг").write_text(
        'PANEL_URL="https://веселый-туннель.trycloudflare.com"\n', encoding="utf-8")
    код, вывод = прогон(д2, "harness/demons/молчун.sh", среда=среда2)
    случай("БОЛЬНОЙ СЛУЧАЙ: условия молчания в конфиге нет — молчание незаконно",
           код == 1, вывод[:200])
    случай("и названы ключ и его значение",
           "PANEL_URL" in вывод, вывод[:200])

    стало = {п: hashlib.md5(п.read_bytes()).hexdigest() for п in БОЕВЫЕ if п.exists()}
    случай("боевые файлы не тронуты", было == стало, "проба сыграла на производстве")

    print(f"ИТОГ: хороших {хорошо}, плохих {плохо}")
    return 1 if плохо else 0


