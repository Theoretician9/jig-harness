#!/usr/bin/env python3
"""Данные публичной сборки означают то, что обещает спека.

Почему тест на файл данных: сборщик верит ему без разбора. Ключ обезличивания,
которого нет в паспорте, — молчаливая пустая замена; путь в «оставить», которого
нет в пакете, — отказ на каждой сборке; литерал нашей установки внутри файла —
красный гейт навсегда (файл сам едет в сборку, ревью спеки №2).

Прогон: python3 scripts/test_public_build.py
"""
import os
import re
import sys
from pathlib import Path

import yaml

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "scripts" / "lib"))
from config import из_файла, конфиг, корень_дерева, путь_harness_conf, путь_install_conf  # noqa: E402

ДАННЫЕ = корень_дерева(__file__) / "harness" / "config" / "public-build.yaml"
путей = неудач = 0


def путь(ок: bool, текст: str) -> None:
    global путей, неудач
    путей += 1
    неудач += 0 if ок else 1
    print(("  ок    " if ок else "  ПЛОХО ") + текст)


# Паспорт читается СТРОГО из файла установки, как его читает сам сборщик:
# конфиг() накладывает слой окружения, и проба судила бы не тот проект, что
# боевой путь (ревью кода 12.09.2026, №9).
паспорт = из_файла(путь_install_conf())
паспорт.update(из_файла(путь_harness_conf()))
ПАКЕТ = Path(os.environ.get("HARNESS_STARTER")
             or f"/home/{паспорт['AGENT_USER']}/starter/STARTER-PACKAGE")

if not ДАННЫЕ.is_file():
    print(f"  ПЛОХО файла данных нет: {ДАННЫЕ}")
    print("ДАННЫЕ СБОРКИ: путей 1, неудач 1")
    sys.exit(1)

текст = ДАННЫЕ.read_text(encoding="utf-8")
данные = yaml.safe_load(текст) or {}

# БОЛЬНОЙ СЛУЧАЙ первым: значение любого ключа паспорта внутри файла данных —
# гейт чистоты найдёт его в сборке на каждой публикации, и красным он будет
# всегда, потому что файл данных едет в сборку вместе со сборщиком.
литералы = [к for к in ("PROJECT_DIR", "PROJECT_NAME", "TG_CHAT_ID", "PRODUCT_DIR")
            if паспорт.get(к) and паспорт[к] in текст]
путь(not литералы, f"в файле данных нет значений паспорта {литералы or ''}")

for раздел in ("исключить", "заменить_шаблоном", "обезличить_ключи", "оставить"):
    путь(раздел in данные, f"раздел «{раздел}» объявлен")

# Состояние живой проверки — записи ЭТОЙ установки: что трогали руками, что
# увидели, какие нашли косяки и где они заведены. Установщик копирует дерево
# пакета целиком, поэтому с записями наружу уехали бы и чужие пути (замер
# 17.10.2026: гейт чистоты нашёл в сборке домашний каталог второго харнеса
# владельца), и ложная зелень приёмки — новая установка получила бы «проверено
# живьём 65» про механизмы, которых там никто не касался.
СОСТОЯНИЕ_ЖИВОЙ_ПРОВЕРКИ = "harness/config/live-check-state.yaml"
укрыто = (СОСТОЯНИЕ_ЖИВОЙ_ПРОВЕРКИ in (данные.get("исключить") or [])
          or СОСТОЯНИЕ_ЖИВОЙ_ПРОВЕРКИ in (данные.get("заменить_шаблоном") or {}))
путь(укрыто, f"{СОСТОЯНИЕ_ЖИВОЙ_ПРОВЕРКИ} наружу не едет с нашими записями "
             "(стоит в «исключить» или в «заменить_шаблоном»)")

# Ключ, известный паспорту, но ПУСТОЙ, — законное состояние: сам сборщик его
# пропускает (замены() не строит пары из пустого значения). Требовать
# непустоты значило бы краснеть на свежей установке, где PRODUCT_DIR ещё пуст.
ИЗВЕСТНЫЕ_ПАСПОРТУ = set(из_файла(путь_install_conf())) | {
    "PROJECT_DIR", "PROJECT_NAME", "PRODUCT_DIR", "TG_CHAT_ID", "AGENT_USER"}
for ключ in данные.get("обезличить_ключи") or []:
    путь(ключ in ИЗВЕСТНЫЕ_ПАСПОРТУ, f"ключ {ключ} известен паспорту установки")

for файл, шаблон in (данные.get("заменить_шаблоном") or {}).items():
    есть = (ПАКЕТ / шаблон).is_file()
    путь(есть, f"шаблон {шаблон} лежит в пакете")
    текст_шаблона = (ПАКЕТ / шаблон).read_text(encoding="utf-8") if есть else ""
    # Чего требовать от шаблона — зависит от его ЧИТАТЕЛЯ, и это разные правила.
    # Машинную строку потолков читает сторож канала (check-channel-messages.py)
    # ИЗ ДОКУМЕНТА ТОНА: без неё он берёт запасные числа молча, а @-импорт
    # CLAUDE.md остаётся битым. Требовать ту же строку от ЛЮБОГО шаблона значит
    # судить одно правило на чужом файле — так эта проверка покраснела
    # 13.10.2026 на заготовке списка цитат, у которой потолков нет и быть не
    # может.
    if файл.endswith("TONE.md"):
        путь(bool(re.search(r"<!--\s*потолки:\s*мягкий=\d+\s+жёсткий=\d+\s*-->",
                            текст_шаблона)),
             f"в шаблоне {шаблон} есть машинная строка потолков")
    elif шаблон.endswith((".yaml", ".yml")):
        # Шаблон, заменяющий данные, обязан РАЗБИРАТЬСЯ и объявлять те же
        # разделы верхнего уровня: пустышка оставила бы читателя без ключей, и
        # он молча взял бы умолчания.
        свои = чужие = None
        try:
            свои = set(yaml.safe_load(текст_шаблона) or {})
            чужие = set(yaml.safe_load((ПАКЕТ / файл).read_text(encoding="utf-8")) or {})
        except Exception as беда:                     # noqa: BLE001 — причина важнее типа
            путь(False, f"шаблон {шаблон} не разобран: {беда}")
        if свои is not None and чужие is not None:
            путь(свои == чужие,
                 f"шаблон {шаблон} объявляет те же разделы, что {файл}"
                 + (f" (разница {свои ^ чужие})" if свои != чужие else ""))
    путь((ПАКЕТ / файл).exists(), f"заменяемый {файл} существует в пакете")

def до_переноса(путь_в_сборке: str) -> str:
    """Путь в СБОРКЕ → путь в ПАКЕТЕ. «оставить» перечисляет то, что обязано
    быть в собранном дереве, а часть каталогов сборщик по дороге переносит
    (`перенести`): проверять их в пакете по новому имени — краснеть всегда
    (поймано этим же тестом 12.09.2026 после переноса UNIFIED)."""
    for откуда, куда in (данные.get("перенести") or {}).items():
        if путь_в_сборке == куда or путь_в_сборке.startswith(куда + "/"):
            return откуда + путь_в_сборке[len(куда):]
    return путь_в_сборке


# Пакет бывает мастерской (UNIFIED в корне) и опубликованной сборкой
# (sluzhebnoe/UNIFIED): установка ставится из сборки, и в ней перенос уже сделан.
for файл in данные.get("оставить") or []:
    в_пакете = до_переноса(файл)
    путь((ПАКЕТ / в_пакете).exists() or (ПАКЕТ / файл).exists(),
         f"«оставить» {файл} существует в пакете ({в_пакете} или {файл})")

# «@STATE.md» и «@./память/TONE.md» — обе законные формы: regex с обязательной
# точкой терял первую, и битый импорт STATE.md тест бы не заметил.
импорты = re.findall(r"^@(?:\./)?(.+)$",
                     (ПАКЕТ / "harness" / "CLAUDE.md").read_text(encoding="utf-8"), re.M)
оставить = данные.get("оставить") or []
битые = [и for и in импорты if f"harness/{и}" not in оставить]
путь(not битые, f"каждый @-импорт CLAUDE.md пакета стоит в «оставить» ({len(импорты)}) {битые or ''}")

print(f"ДАННЫЕ СБОРКИ: путей {путей}, неудач {неудач}")
sys.exit(1 if неудач else 0)
