#!/usr/bin/env python3
"""Обе половины живой проверки: гейт краснеет на сломанном дереве и молчит на целом.

Откуда взято. Спека `docs/specs/2026-10-15-живая-проверка-механизмов.md` §3.1,
класс C1: «Больной случай в КОПИИ дерева → красный с названной причиной; затем
здоровый → зелёный. **Одного зелёного мало**».

Зачем прогон, а не руки. 17.10.2026 за одну смену 48 гейтов-судей были записаны
по ОДНОМУ зелёному прогону: предикат класса не судил никто. Больная половина по
гейту руками — решение, которое требует помнить, то есть не решение.

Три решения, каждое против пережитого случая:

* **Чистая копия обязана быть ЗЕЛЁНОЙ.** Красное на сломанном дереве ничего не
  доказывает, если то же красное даёт и целое: оно могло прийти от сломанного
  окружения копии. Это правило спасло мутационную пробу 12.09.2026, когда пять
  проверок из восемнадцати отвечали «чистая копия уже красная».
* **Отказ судится СЛОВОМ, а не кодом.** Один код возврата служит целому классу
  бед, и 127 «нет такой команды» зеленит случай ни за что: ждём подстроку,
  которую может напечатать ТОЛЬКО судимое правило.
* **Поломка обязана изменить дерево.** Команда, не тронувшая ни одного файла, —
  промах данных, а не успех: иначе «гейт покраснел» означало бы «краснеет всегда».

Здоровая половина — после доказанной больной, тем же «команда» случая, но на
ЖИВОМ дереве (cwd = КОРЕНЬ): клон не несёт незакоммиченного, и копия, зелёная
при красном живом дереве, поставила бы «ок» сломанному механизму. Ждём слово
из «ждём_в_здоровом» в ВЫВОДЕ механизма (ниже разделителя следа): шапка несёт
команду, и слово в ней закрыло бы половину эхом собственной команды. «ок»
(исход, живьём, увидели, след, когда) ставит только прибор, когда доказаны обе;
нет «ждём_в_здоровом» — пишется одна больная, и прибор говорит об этом вслух.

Копия дерева — `git clone --local` (1,3 с на этом репозитории), ОДНА на прогон;
между случаями она возвращается к коммиту. `git checkout -- .` законен только
здесь, в выбрасываемой копии: в живом дереве он стирает несохранённую работу.

Запуск:
    python3 scripts/live-check-sick.py <механизм> [<механизм>…] [--записать]
    python3 scripts/live-check-sick.py --всё [--записать]
Код возврата: 0 — все больные половины доказаны, 1 — хоть одна нет.
Чем доказан: scripts/test_live_check_sick.py (больной случай первым — гейт,
зелёный на сломанном дереве).
"""
from __future__ import annotations

import datetime
import fcntl
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile

import yaml

КОРЕНЬ = pathlib.Path(os.environ.get("HARNESS_LIVE_CHECK_REPO")
                      or pathlib.Path(__file__).resolve().parent.parent)
СЛУЧАИ = pathlib.Path(os.environ.get("HARNESS_LIVE_CHECK_SICK_CASES")
                      or КОРЕНЬ / "harness" / "config" / "live-check-sick-cases.yaml")
СОСТОЯНИЕ = pathlib.Path(os.environ.get("HARNESS_LIVE_CHECK_STATE")
                         or КОРЕНЬ / "harness" / "config" / "live-check-state.yaml")
def _корень_следов() -> pathlib.Path:
    """Корень следов — у общего загрузчика: умолчание внутри репозитория
    отдавало весь вывод произвольной команды гиту."""
    sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent / "lib"))
    import config as конф                                 # noqa: PLC0415
    return pathlib.Path(конф.live_check_trace_root())


СЛЕДЫ = pathlib.Path(os.environ.get("HARNESS_LIVE_CHECK_SICK_TRACE_DIR")
                     or _корень_следов() / "hr.zhivaya-proverka-vseh-mehanizmov"
                     / "живьём-больные")
# След здоровой половины: она идёт из корня, и её след не должен затирать след
# больной, поэтому каталог свой.
СЛЕДЫ_ЖИВЬЁМ = pathlib.Path(os.environ.get("HARNESS_LIVE_CHECK_SICK_LIVE_TRACE_DIR")
                            or _корень_следов() / "hr.zhivaya-proverka-vseh-mehanizmov"
                            / "живьём")
РАЗДЕЛИТЕЛЬ_ВЫВОДА = "--- вывод механизма ---"
# След, которому в гите не место. Гейты секретов доказываются ТЕМ, что они
# запрещают: вывод несёт значение, похожее на ключ, и гейт секретов отказывает
# коммиту — правильно отказывает. Подчищать чужой вывод руками нельзя, он тогда
# перестаёт быть чужим; значит такой след живёт вне дерева, и случай говорит об
# этом ключом «след_наружу».
СЛЕДЫ_НАРУЖУ = pathlib.Path(os.environ.get("HARNESS_LIVE_CHECK_SICK_TRACE_OUT")
                            or _корень_следов())


def больные_случаи() -> dict:
    if not СЛУЧАИ.exists():
        return {}
    данные = yaml.safe_load(СЛУЧАИ.read_text(encoding="utf-8")) or {}
    return данные.get("больные_случаи") or {}


def _git(копия: pathlib.Path, *доводы: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", *доводы], cwd=копия,
                          capture_output=True, text=True)


def копия_дерева(куда: pathlib.Path) -> pathlib.Path:
    """Клон живого дерева. Клон, а не cp: гейты судят индекс и историю."""
    копия = куда / "дерево"
    готово = subprocess.run(["git", "clone", "--local", "-q",
                             str(КОРЕНЬ), str(копия)],
                            capture_output=True, text=True)
    if готово.returncode != 0:
        raise SystemExit(f"[больная половина] копию дерева не сделать: "
                         f"{(готово.stderr or '').strip()[:200]}")
    return копия


def вернуть(копия: pathlib.Path) -> None:
    """Копия — к коммиту. Законно ТОЛЬКО здесь: это выбрасываемый клон.

    `reset --hard`, а не `checkout -- .`: поломка бывает и в ИНДЕКСЕ («git rm
    --cached» у случая реестра), а checkout восстанавливает рабочее дерево ИЗ
    индекса — то есть не восстанавливает ничего. 17.10.2026 из-за этого грязь
    предыдущего случая прошла за поломку следующего, и «гейт зелён на сломанном
    дереве» было сказано о дереве, сломанном не тем случаем.
    """
    _git(копия, "reset", "-q", "--hard", "HEAD")
    _git(копия, "clean", "-fdq")


def прогнать(копия: pathlib.Path, команда: str) -> tuple[int, str]:
    готово = subprocess.run(команда, shell=True, cwd=копия,
                            capture_output=True, text=True, timeout=600)
    return готово.returncode, (готово.stdout or "") + (готово.stderr or "")


def позвать_обёрткой(где: pathlib.Path, механизм: str, команда: str,
                     следы: pathlib.Path) -> tuple[int, str, pathlib.Path]:
    """Гейт зовётся обёрткой ИЗ `где` (копия или корень): след пишет сам
    механизм, в каталог `следы`."""
    след = следы / (механизм.replace("/", "-") + ".log")
    # Старый след остался бы свидетельством, если обёртка в этот раз не писала.
    след.unlink(missing_ok=True)
    среда = dict(os.environ)
    среда["HARNESS_LIVE_CHECK_TRACE_DIR"] = str(следы)
    готово = subprocess.run(["bash", "scripts/live-check.sh", механизм, "--",
                             "bash", "-c", команда],
                            cwd=где, capture_output=True, text=True,
                            env=среда, timeout=900)
    текст = след.read_text(errors="replace") if след.is_file() else ""
    return готово.returncode, текст, след


def вывод_механизма(текст_следа: str) -> str:
    """Только то, что напечатал сам механизм: без шапки «команда: …» (она несёт
    слово эхом команды) и без хвоста обёртки (код возврата, «ОБОРВАНО…»)."""
    вывод = текст_следа.partition(РАЗДЕЛИТЕЛЬ_ВЫВОДА)[2]
    строки = вывод.splitlines()
    for номер in range(len(строки) - 1, -1, -1):
        if строки[номер].startswith("код возврата:"):
            строки = строки[:номер]
            break
    return "\n".join(с for с in строки if not с.startswith("ОБОРВАНО ОБЁРТКОЙ"))


def строка_со_словом(текст_следа: str, слово: str, обрезать: bool = False) -> str:
    """Строка следа, несущая ожидаемое слово, — она и станет цитатой.

    `обрезать` оставляет строку ТОЛЬКО до конца ожидаемого слова. Нужно там, где
    след уведён из дерева: сам он в гит не попадает, а цитата попадает — и
    17.10.2026 она принесла в запись то самое значение, похожее на ключ, из-за
    которого след и уводили. Гейт секретов отказал коммиту, и правильно отказал.
    Цитата остаётся ДОСЛОВНОЙ подстрокой следа — просто короче.
    """
    for строка in текст_следа.splitlines():
        if слово in строка:
            плотно = " ".join(строка.split())
            if обрезать:
                конец = плотно.find(слово) + len(слово)
                return плотно[:конец]
            return плотно
    return ""


def _путь_следа(след: pathlib.Path) -> str:
    """Относительный от КОРНЯ, если след внутри него, иначе абсолютный."""
    if след.is_relative_to(КОРЕНЬ):
        return str(след.relative_to(КОРЕНЬ))
    return str(след)


def _красный_со_словом(копия: pathlib.Path, механизм: str, зов: str, слово: str,
                       случай: dict, зелёный: str, как_сломано: str
                       ) -> tuple[bool, str, dict]:
    """Общий хвост обоих родов: гейт зовётся обёрткой и обязан покраснеть СЛОВОМ.

    Род случая решает, ЧЕМ создано нарушение (поломка дерева или больной довод);
    доказательство у обоих одно — чужой текст в следе, и писать его дважды
    значило бы развести две копии одного правила.
    """
    код_гейта, текст_следа, след = позвать_обёрткой(
        копия, механизм, зов,
        СЛЕДЫ_НАРУЖУ if случай.get("след_наружу") else СЛЕДЫ)
    if код_гейта == 0:
        return False, f"{механизм}: {зелёный}", {}
    строка = строка_со_словом(вывод_механизма(текст_следа), слово,
                              bool(случай.get("след_наружу")))
    if not строка:
        return False, (f"{механизм}: в отказе нет ожидаемого слова «{слово}» — "
                       f"красный пришёл по другой причине"), {}

    поля = {
        "больной": f"{как_сломано} → гейт покраснел: {строка}",
        "след_больного": _путь_следа(след),
    }
    return True, f"{механизм}: больная половина доказана — {строка[:90]}", поля


def судить(копия: pathlib.Path, механизм: str, случай: dict) -> tuple[bool, str, dict]:
    """(доказано, что сказать, поля записи) для одного механизма.

    Два рода случаев, и род задают ДАННЫЕ, а не догадка прибора:
    «чем_ломать» — предмет гейта лежит в дереве, его и ломаем; «больной_довод» —
    предмет приходит ДОВОДОМ (текст сообщения, команда, путь журнала), и поломка
    дерева такой гейт не красит вовсе. Замер 17.10.2026: из 63 непроверенных
    гейтов-судей 24 второго рода.
    """
    команда = str(случай.get("команда") or "").strip()
    чем_ломать = str(случай.get("чем_ломать") or "").strip()
    больной_довод = str(случай.get("больной_довод") or "").strip()
    слово = str(случай.get("ждём_в_отказе") or "").strip()
    if чем_ломать and больной_довод:
        return False, (f"{механизм}: названы ОБА способа, а нужно одно из двух — "
                       f"«чем_ломать» (предмет в дереве) или «больной_довод» "
                       f"(предмет приходит доводом)"), {}
    if not (команда and слово and (чем_ломать or больной_довод)):
        return False, (f"{механизм}: больной случай неполон — нужны «команда», "
                       f"«ждём_в_отказе» и один способ: «чем_ломать» или "
                       f"«больной_довод»"), {}
    # Здоровая команда судится вместе с полнотой случая: отказ после клона и
    # больной половины оставил бы следы от прогона, который ничего не доказал.
    # Пустая не равна отсутствующей: молча упасть на «команду» значило бы судить
    # не то, что названо в данных.
    if "здоровая_команда" in случай:
        if not str(случай["здоровая_команда"] or "").strip():
            return False, f"{механизм}: «здоровая_команда» пуста — уберите поле или впишите команду", {}
        if not str(случай.get("ждём_в_здоровом") or "").strip():
            return False, (f"{механизм}: «здоровая_команда» без «ждём_в_здоровом» — "
                           f"здоровую половину нечем судить"), {}

    вернуть(копия)
    код, вывод = прогнать(копия, команда)
    if код != 0:
        return False, (f"{механизм}: чистая копия уже красная — доказывать нечем: "
                       f"{' '.join(вывод.split())[:120]}"), {}

    if больной_довод:
        return _красный_со_словом(
            копия, механизм, больной_довод, слово, случай,
            зелёный=("гейт ЗЕЛЁН на больном доводе — он не ловит нарушение, "
                     "которое охраняет"),
            как_сломано=f"позван больным доводом: {больной_довод}")

    код_ломки, вывод_ломки = прогнать(копия, чем_ломать)
    if код_ломки != 0:
        return False, (f"{механизм}: команда поломки отказала: "
                       f"{' '.join(вывод_ломки.split())[:120]}"), {}
    if not _git(копия, "status", "--porcelain").stdout.strip():
        return False, (f"{механизм}: поломка не изменила дерево — промах данных, "
                       f"а не успех: {чем_ломать}"), {}
    # Индекс тоже: часть гейтов судит staged-файлы, а не рабочее дерево.
    _git(копия, "add", "-A")

    return _красный_со_словом(
        копия, механизм, команда, слово, случай,
        зелёный=("гейт ЗЕЛЁН на сломанном дереве — он не ловит нарушение, "
                 "которое охраняет"),
        как_сломано=f"сломано в копии дерева: {чем_ломать}")


# Беда здоровой снимает прежнее «ок»: поля здоровой половины приходят со
# значением None, а запись снимает такое поле.
_ПОЛЯ_ЗДОРОВОЙ = ("исход", "живьём", "увидели", "след", "когда")


def здоровая_половина(механизм: str, случай: dict) -> tuple[bool, str, dict]:
    """Та же команда на ЖИВОМ дереве: зелёная и со словом в выводе механизма.

    Зовётся только после доказанной больной. Слово ищется ниже разделителя
    следа, не в шапке с «команда: …».
    """
    # Больная команда бывает самотестом или полным кругом на часы; здоровая —
    # узкий прогон на настоящих воротах. Нет поля — зовём «команду».
    команда = (str(случай.get("здоровая_команда") or "").strip()
               or str(случай.get("команда") or "").strip())
    слово = str(случай.get("ждём_в_здоровом") or "").strip()
    снять = dict.fromkeys(_ПОЛЯ_ЗДОРОВОЙ)
    код, текст_следа, след = позвать_обёрткой(КОРЕНЬ, механизм, команда,
                                              СЛЕДЫ_ЖИВЬЁМ)
    if код != 0:
        return False, (f"{механизм}: здоровая половина красная на живом дереве "
                       f"(код {код}), а ждали зелёный со словом «{слово}»"), снять
    строка = строка_со_словом(вывод_механизма(текст_следа), слово,
                              bool(случай.get("след_наружу")))
    if not строка:
        return False, (f"{механизм}: здоровая половина зелёная, но слова "
                       f"«{слово}» нет в выводе механизма"), снять
    return True, f"{механизм}: здоровая половина доказана — {строка[:90]}", {
        "живьём": f"позван здоровым: {команда}",
        "увидели": строка,
        "след": _путь_следа(след),
        "когда": datetime.date.today().isoformat(),
        "исход": "ок",
    }


def судить_обе(копия: pathlib.Path, механизм: str,
               случай: dict) -> tuple[bool, str, dict]:
    """Больная, затем здоровая; здоровая не зовётся, пока больная не доказана.

    Больная половина остаётся в полях, даже если здоровая упала: она доказана
    сама по себе, а беда названа отдельно.
    """
    доказано, слово, поля = судить(копия, механизм, случай)
    if not доказано:
        return False, слово, поля
    if not str(случай.get("ждём_в_здоровом") or "").strip():
        print(f"  --    {механизм}: слова «ждём_в_здоровом» в данных нет — "
              f"здоровая не звалась, записана одна больная")
        return True, слово, поля
    здорово, сказано, добавка = здоровая_половина(механизм, случай)
    return здорово, f"{слово}; {сказано}", {**поля, **добавка}


def записать(поля_по_механизму: dict) -> None:
    # замок по соседнему файлу: сам yaml заменяется через replace, на нём замок бы терялся
    with open(СОСТОЯНИЕ.with_name(СОСТОЯНИЕ.name + ".lock"), "w") as замок:
        fcntl.flock(замок, fcntl.LOCK_EX)
        данные = yaml.safe_load(СОСТОЯНИЕ.read_text(encoding="utf-8")) or {}
        сост = данные.setdefault("проверено", {})
        for механизм, поля in поля_по_механизму.items():
            запись = сост.setdefault(механизм, {})
            for поле, значение in поля.items():
                if значение is None:
                    запись.pop(поле, None)
                else:
                    запись[поле] = значение
        # временный файл рядом + replace: читатель без замка не увидит половину файла
        врем = СОСТОЯНИЕ.with_name(f"{СОСТОЯНИЕ.name}.{os.getpid()}.tmp")
        врем.write_text(
            yaml.dump(данные, allow_unicode=True, sort_keys=False, width=100),
            encoding="utf-8")
        os.replace(врем, СОСТОЯНИЕ)


def main() -> int:
    доводы = [д for д in sys.argv[1:] if not д.startswith("--")]
    писать = "--записать" in sys.argv
    случаи = больные_случаи()
    кого = sorted(случаи) if "--всё" in sys.argv else доводы
    if not кого:
        print("[больная половина] нечего судить: назовите механизм или «--всё»",
              file=sys.stderr)
        return 1

    двор = pathlib.Path(tempfile.mkdtemp(prefix="больная-половина-"))
    поля_по_механизму: dict = {}
    беды: list[str] = []
    try:
        копия = копия_дерева(двор)
        for механизм in кого:
            случай = случаи.get(механизм)
            if not случай:
                беды.append(f"{механизм}: больного случая нет в данных "
                            f"({СЛУЧАИ.name}) — судить нечем")
                continue
            доказано, слово, поля = судить_обе(копия, механизм, случай)
            print(("  ок    " if доказано else "  ПЛОХО ") + слово)
            if поля:
                поля_по_механизму[механизм] = поля
            if not доказано:
                беды.append(слово)
    finally:
        shutil.rmtree(двор, ignore_errors=True)

    if писать and поля_по_механизму:
        записать(поля_по_механизму)
        print(f"[больная половина] записано механизмов: {len(поля_по_механизму)}")
    if беды:
        print(f"[больная половина] ✗ не доказано: {len(беды)} из {len(кого)}",
              file=sys.stderr)
        for б in беды:
            print(f"    {б}", file=sys.stderr)
        return 1
    print(f"[больная половина] доказано все {len(кого)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
