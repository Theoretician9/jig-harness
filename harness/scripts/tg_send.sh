# Неизвестный флаг — отказ, а не отправка его текстом. Улика 12.08.2026: агент
# позвал `--файл` (флаг называется --file), и владелец получил два сообщения из
# одного слова «--файл», а снимки экрана не ушли вовсе. Молчаливая подмена
# «команда → текст» здесь всегда ошибка: настоящее сообщение владельцу с
# двух дефисов не начинается, а вот опечатка в флаге — начинается.
case "$TEXT" in
    --*) refuse "неизвестный флаг «${TEXT%% *}»; известны: --file /путь [--caption «подпись»] (по-русски тоже: --файл, --вложение, --подпись)" \
                "текст отправляется первым аргументом без флагов" ;;
esac

# Хеш коммита в отчёте владельцу обязан существовать. Улика 12.08.2026: агент
# дважды подряд назвал число и хеш «по памяти» — сначала «1568 шагов» при
# замере 1389, потом коммит 5eb0f79 вместо cb9d430. Владелец видит только
# канал: неверный номер он проверить не может и поверит. Гейт смотрит лишь на
# хеши, названные словом «коммит», — остальной hex (uuid, токены) не трогаем.
# Деревьев два: харнес и репозиторий продукта (ключ PRODUCT_REPO) — отчёт о
# коммите продукта иначе был бы отвергнут как выдуманный.
TREES=()
[ -d "${PROJECT_DIR:?пуст PROJECT_DIR — не прочитан паспорт установки}/.git" ] && TREES+=("$PROJECT_DIR")
[ -n "${PRODUCT_REPO:-}" ] && [ -d "$PRODUCT_REPO/.git" ] && TREES+=("$PRODUCT_REPO")
if [ "${#TREES[@]}" -gt 0 ]; then
    while read -r HASH; do
        [ -n "$HASH" ] || continue
        FOUND=0
        for tree in "${TREES[@]}"; do
            git -C "$tree" cat-file -e "${HASH}^{commit}" 2>/dev/null && { FOUND=1; break; }
        done
        [ "$FOUND" = 1 ] \
            || refuse "в тексте назван коммит $HASH, которого нет в репозитории (искал в: ${TREES[*]})" \
                      "проверьте git log и вставьте настоящий хеш"
    done < <(printf '%s' "$TEXT" | grep -oiE '(коммит|commit)[^0-9a-f]{0,4}[0-9a-f]{7,40}' \
             | grep -oE '[0-9a-f]{7,40}$')
fi

