# ОЧЕРЕДЬ ДОСЫЛА — та же, что у панели: её обходит sentinel раз в пять минут и
# снимает строку ТОЛЬКО при доставке.
RESEND_QUEUE="$LOG_DIR/панель-недоставленное.jsonl"
придержать() {  # $1 = что не ушло
    mkdir -p "$LOG_DIR" 2>/dev/null || true
    jq -cn --arg ts "$(date -Is)" --arg text "$1" --arg sbros "${SBROS_CHAS:-}" \
           --argjson dosyl "$([ "$NE_DOSYLAT" = 1 ] && echo false || echo true)" \
        '{ts:$ts, script:"tg_send", why:"держится лимит подписки — владельцу молчим до обновления", sbros:$sbros, "досыл":$dosyl, text:$text}' \
        >> "$LOG_DIR/придержано-лимитом.jsonl" 2>/dev/null || true
    if [ "$NE_DOSYLAT" = 1 ] || [ "$JA_DOSYL" = 1 ]; then
        echo "tg_send: ПРИДЕРЖАНО — держится лимит подписки${SBROS_CHAS:+ (обновится в $SBROS_CHAS)}; досыла не будет (так позвали)." >&2
        exit 3
    fi
    jq -cn --arg ts "$(date -Is)" --arg text "$1" '{"ts":$ts, "текст":$text}' \
        >> "$RESEND_QUEUE" 2>/dev/null \
        || { echo "tg_send: ОТКАЗ — придержанное не легло в очередь досыла, сообщение потеряно" >&2; exit 1; }
    echo "tg_send: ПРИДЕРЖАНО — держится лимит подписки${SBROS_CHAS:+ (обновится в $SBROS_CHAS)}; уйдёт досылом после обновления." >&2
    exit 0
}

