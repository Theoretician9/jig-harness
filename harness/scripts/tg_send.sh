#!/usr/bin/env bash
#
# tg_send.sh — отправка текста или файла владельцу в Telegram.
#
# Откуда взят: написан для стартового пакета, шаблона в UNIFIED нет; норма —
# 01-SPEC §7 и 02-КАРТА («лог „отправлено" без разбора ответа успехом не
# считается»): успех ТОЛЬКО при ok:true И наличии message_id в ответе Bot API.
# Всё остальное — отказ: ненулевой код + строка JSONL в $LOG_DIR/tg_failures.log,
# чтобы недоставленное было видно демонам, а не только в момент отправки.
#
# Запуск:
#   tg_send.sh "текст"                       # текст >4000 знаков режется на части
#   tg_send.sh --file /путь [--caption "подпись"]
#   tg_send.sh --несмотря-на-лимит "текст"   # о лимите, об обновлении, о смене сессии
#
# Коды возврата: 0 — доставлено; 1 — сбой связи/API, неподтверждённая доставка
# или ошибка вызова; 3 — придержано лимитом без досыла; 4 — отказ правил
# переписки (текст не годится). Звонящий должен отличить «перепиши текст» от
# «канал лёг, повтори»; отказ правил пишет строку и в tg_failures.log.
#
# Токен — из файла TG_TOKEN_FILE (install.conf), в командной строке не светится.
# Чем доказывается на живом: отправка при принятии канала (01-SPEC §7) и
# больной случай — испортить токен → скрипт обязан выйти ненулевым и оставить
# строку в tg_failures.log.
set -euo pipefail

# Резка по СИМВОЛАМ, не байтам: без UTF-8-локали ${#строка} и ${строка:0:N}
# считают байты и режут посреди многобайтной кириллической буквы — Telegram
# такой кусок отверг бы. C.UTF-8 есть на любом Ubuntu. Поймано прогоном при
# сборке пакета 08.08.2026: 9500 знаков кириллицы уехали пятью частями вместо трёх.
export LC_ALL=C.UTF-8

source "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/lib/config.sh"
INSTALL_CONF="${HARNESS_INSTALL_CONF:-$(konf_koren)/install.conf}"
[ -r "$INSTALL_CONF" ] || { echo "tg_send: нет $INSTALL_CONF — установка не завершена (01-SPEC §0)"; exit 1; }
# shellcheck disable=SC1090
# Конфиги грузятся так, чтобы ОКРУЖЕНИЕ было старше файла: иначе проба с
# подставным путём судит БОЕВУЮ установку (улика 12.09.2026).
# shellcheck disable=SC1091
# Путь берётся по РЕАЛЬНОМУ файлу (readlink -f): pre-commit подключён в
# .git/hooks симлинком, и dirname дал бы .git/hooks, где библиотеки нет.
# Поймано первым же коммитом после правки, 12.09.2026.
konf_zagruzit PROJECT_DIR LOG_DIR TMUX_SESSION SECRETS_DIR AGENT_START_CMD

# Метка ПУЛЬСА отчётности: по ней сторож сессий видит, что владелец слышал меня
# в последние полчаса. Владелец 11.09.2026: «мне нужна ёмкая, лаконичная, но
# регулярная отчетность, как пульс по регулярности».
#
# Метку ставит ТОЛЬКО мой отчёт. Раньше её обновляла любая доставка, а через
# этот скрипт шлют восемь демонов: тревога sentinel или уборка диска гасила
# пульс, и сторож считал, что владелец только что получил статус (находка
# ревью I-7). Признак вызова из сессии — переменные окружения CLAUDE_*, их
# ставит сама оболочка агента; демону из cron их взять неоткуда. Это код, а не
# моя память о флаге.
отметить_отчёт() {
    if [ -n "${HARNESS_REPORT:-}" ] || [ -n "${CLAUDE_CODE_SESSION_ID:-}" ]; then
        date +%s > "$LOG_DIR/last_report" 2>/dev/null || true
    fi
}

FAIL_LOG="$LOG_DIR/tg_failures.log"
OUT_LOG="$LOG_DIR/tg_out.jsonl"

# Журнал ИСХОДЯЩИХ. Заведён 29.09.2026 по слову владельца: «я поменял стиль
# твоего текста в панели на самый простой, но не вижу, что чтото изменилось».
# Разбор показал, что проверить это было НЕЧЕМ: входящие диспетчер пишет в
# inbox.jsonl, а из исходящих хранились только ОТКАЗЫ. Совпадает ли язык смены
# с уровнем владельца — вопрос к замеру, а замерять было не по чему.
#
# Пишется ПОСЛЕ доставки: строка в журнале означает, что текст ушёл, а не что
# его собирались отправить. Уровень языка кладётся рядом с текстом — иначе
# следующий замер не отличит «написано сложно при простом уровне» от
# «написано сложно, когда простого ещё не просили».
zapisat_ishodyashchee() {
    mkdir -p "$LOG_DIR" 2>/dev/null || true
    LANG_LEVEL_NOW=$(python3 "$PROJECT_DIR/scripts/language-level.py" 2>/dev/null || echo "")
    jq -cn --arg ts "$(date -Is)" --arg text "$1" --arg uroven "$LANG_LEVEL_NOW" \
           --arg iz_sessii "$([ -n "${CLAUDE_CODE_SESSION_ID:-}" ] && echo 1 || echo 0)" \
           '{ts: $ts, uroven: $uroven, iz_sessii: ($iz_sessii == "1"), text: $text}' \
        >> "$OUT_LOG" 2>/dev/null || true
}

# jq проверяется ДО работы: без него ответ API нечем разобрать, и отказ был бы
# ложным «не доставлено» уже после ухода запроса. Строка в FAIL_LOG — руками
# (jq-то и нет), текст фиксированный, кавычек внутри не бывает.
command -v jq >/dev/null 2>&1 || {
    mkdir -p "$LOG_DIR" 2>/dev/null || true
    printf '{"ts":"%s","script":"tg_send","why":"нет jq — ответ API нечем разобрать, отправка не начиналась"}\n' \
        "$(date -Is)" >> "$FAIL_LOG" 2>/dev/null || true
    echo "tg_send: ОТКАЗ — нет jq, ответ API нечем разобрать (поставьте: apt-get install -y jq); отправка НЕ начиналась" >&2
    exit 1
}

# Сколько частей уже реально ушло — для честного отказа посреди длинного
# сообщения: владелец видит начало и должен знать, что хвоста не было.
SENT_PARTS=0
TOTAL_PARTS=1

# Отказ: строка JSONL + ненулевой выход. jq собирает JSON сам — ручная склейка
# ломается на первой кавычке в тексте ошибки.
refuse() {  # причина, хвост-ответа-api
    mkdir -p "$LOG_DIR" 2>/dev/null || true
    jq -cn --arg ts "$(date -Is)" --arg why "$1" --arg api "${2:-}" \
        --argjson sent "${SENT_PARTS:-0}" --argjson total "${TOTAL_PARTS:-1}" \
        '{ts:$ts, script:"tg_send", why:$why, api:$api, sent_parts:$sent, total_parts:$total}' \
        >> "$FAIL_LOG" 2>/dev/null \
        || echo "tg_send: даже $FAIL_LOG недоступен" >&2
    echo "tg_send: ОТКАЗ — $1 (частей уже ушло: ${SENT_PARTS:-0} из ${TOTAL_PARTS:-1})" >&2
    exit 1
}

[ -n "${TG_CHAT_ID:-}" ] || refuse "TG_CHAT_ID пуст в install.conf"
[ -n "${TG_TOKEN_FILE:-}" ] && [ -s "$TG_TOKEN_FILE" ] || refuse "TG_TOKEN_FILE пуст или файла нет: ${TG_TOKEN_FILE:-«не задан»}"
TOKEN=$(tr -d '[:space:]' < "$TG_TOKEN_FILE")
API="https://api.telegram.org/bot$TOKEN"

# Признак успеха — ОТДЕЛЬНОЙ функцией, чтобы его можно было проверить без сети.
# Мутационная проба 10.09.2026: подменённый на «.ok != null» признак остался
# незамеченным самотестом — тот мерил резку текста и флаги, а главное правило
# канала («лог „отправлено" без разбора ответа успехом не считается», 01-SPEC §7)
# не проверял никто. Слепая проверка доставки хуже отсутствующей: она обещает.
ответ_успешен() {  # $1 = тело ответа Bot API → rc=0 только при ok:true и message_id
    printf '%s' "$1" | jq -e '.ok == true and (.result.message_id != null)' >/dev/null 2>&1
}

# Успех только при ok:true и message_id — иначе отказ с ответом API в логе.
verdict() {  # ответ-api, что-отправляли
    local resp="$1" what="$2"
    ответ_успешен "$resp" && return 0
    refuse "API не подтвердил доставку ($what)" "$(printf '%.300s' "$resp")"
}

# ── правила переписки: ёмко, без разбора своих ошибок ───────────────────────
# Владелец 11.09.2026: «мне нужна ёмкая, лаконичная, но регулярная отчетность
# <…> и контроль тоже должен быть системный такого способа взаимоотношений».
# Пороги — из замера 380 моих сообщений за смену (медиана 724 знака).
# Проверка стоит ДО резки на части: резать простыню и слать её кусками — то же
# самое вываливание, только в несколько сообщений.
проверить_правила() {  # $1 = текст целиком
    [ "${HARNESS_TG_FORCE:-0}" = 1 ] && {
        printf '{"ts":"%s","script":"tg_send","why":"правила переписки обойдены HARNESS_TG_FORCE"}\n' \
            "$(date -Is)" >> "$FAIL_LOG" 2>/dev/null || true
        return 0
    }
    local GUARD="${PROJECT_DIR:?пуст PROJECT_DIR — не прочитан паспорт установки}/scripts/check-channel-messages.py"
    [ -r "$GUARD" ] || return 0          # сторожа нет — не мешаем каналу работать
    local REMARKS rc=0 GUARD_ARGS=()
    [ "${STATUS_DOOR:-0}" = 1 ] && GUARD_ARGS=(--статус)
    REMARKS=$(printf '%s' "$1" | python3 "$GUARD" "${GUARD_ARGS[@]}") || rc=$?
    [ -n "$REMARKS" ] && printf '%s\n' "$REMARKS" >&2
    if [ "$rc" != 0 ]; then
        echo "tg_send: ОТКАЗ — сообщение нарушает правила переписки (владелец 11.09.2026)." >&2
        echo "  Перепиши: итог и числа в канал, разбор своих действий — в память и журнал." >&2
        echo "  Документ длиннее потолка отправляй вложением ВМЕСТЕ с подписью:" >&2
        echo "  tg_send.sh --file <путь> --caption «о чём документ одной строкой»" >&2
        return 1
    fi
    return 0
}

send_text() {  # кусок текста
    local resp
    # URL с токеном — через stdin (curl -K -), не в argv: argv виден любому в ps.
    resp=$(printf 'url = "%s/sendMessage"\n' "$API" \
        | curl -sS --max-time 30 -K - -X POST \
        --data-urlencode "chat_id=$TG_CHAT_ID" \
        --data-urlencode "text=$1" 2>&1) || refuse "curl не дошёл до API" "$(printf '%.300s' "$resp")"
    verdict "$resp" "текст ${#1} зн."
}

# Потолок Telegram — 4096 знаков на сообщение; режем по 4000, по возможности по
# переводу строки, чтобы не рвать посреди фразы. Части нумеруются: владелец
# видит, что это одно сообщение. Ничего не теряется — предел есть у сообщения,
# у текста его нет.
отправить_текст_частями() {  # $1=текст целиком
    local rest="$1" piece trimmed n=0
    local -a chunks=()
    while [ ${#rest} -gt 4000 ]; do
        piece="${rest:0:4000}"
        trimmed="${piece%$'\n'*}"
        if [ -n "$trimmed" ] && [ "$trimmed" != "$piece" ]; then
            piece="$trimmed"
        fi
        chunks+=("$piece")
        rest="${rest:${#piece}}"
        rest="${rest#$'\n'}"
    done
    [ -n "$rest" ] && chunks+=("$rest")

    TOTAL_PARTS=${#chunks[@]}
    for piece in "${chunks[@]}"; do
        n=$((n + 1))
        if [ "$TOTAL_PARTS" -gt 1 ]; then
            send_text "[$n/$TOTAL_PARTS] $piece"
        else
            send_text "$piece"
        fi
        SENT_PARTS=$n   # часть подтверждена — отказ на следующей назовёт это число
    done
}

# Потолок подписи к файлу в Bot API — 1024 знака, и поднять его нельзя. Раньше
# хвост подписи отрезался: владелец получал снимок с недописанным текстом и
# сказал прямо (13.08.2026) — «твои сообщения обрезаются, а они вообще не
# должны иметь лимита». Теперь под файлом остаётся начало, а подпись целиком
# уходит следом обычным сообщением, где потолка на текст нет.
CAPTION_MAX=1000
# Нижняя граница подписи. Ревью 27.09 (F-05): «непустая подпись» обходится
# одним словом — «ответ», — и файл-ответ уходит владельцу снова. Замер живых
# подписей: единственный боевой отправитель файлов (scripts/spec_approval.py)
# пишет «Спека задачи <id> целиком» — 26 знаков и больше; отписки, которыми
# правило обходят, укладываются в десять. Порог 20 режет вторые и пропускает
# первые. Восемьдесят знаков брать нельзя: столько требует ОПИСАНИЕ спеки —
# отдельное ТЕКСТОВОЕ сообщение, а не подпись под файлом.
CAPTION_MIN=20
подпись_под_файл() {  # $1=подпись целиком
    local head="${1:0:900}"
    printf '%s… (подпись целиком — сообщением следом)' "${head% *}"
}

# ── самотест: деление и подпись проверяются без сети ────────────────────────
# Гоняется воротами. Больной случай первым: подпись длиннее потолка Bot API —
# та самая, хвост которой владелец не получил 13.08.2026.
# Флаг на двух языках. Треть отказов доставки за месяц (38 из 116) — не сбои
# канала, а кривые вызовы: «--файл» вместо «--file». Замечание владельца В-2 к
# ревизии 10.09.2026: прибор, в котором ошибаются в трети вызовов, — дефект
# прибора. Неизвестный флаг по-прежнему отказ, молчаливой подмены нет.
канон_флаг() {
    case "$1" in
        --файл|--вложение) printf '%s\n' "--file" ;;
        --подпись)         printf '%s\n' "--caption" ;;
        *)                 printf '%s\n' "$1" ;;
    esac
}

# Голый файл — не сообщение владельцу.
#
# Владелец 27.08.2026: «отчёт текстом, файлом — только документ» — отчёт
# идёт ТЕКСТОМ, вложение только для документа. 26.09.2026 он же о спеке:
# «присылать спеку описанием, а не голым файлом» — голый файл отправкой не считается. 27.09.2026 он
# спросил снова: «Ты мне зачем файлами ответы шлёшь» — два моих ответа ушли
# документами, потому что правило держалось только моим вниманием.
#
# Признак — ПОДПИСЬ, а не каталог и не расширение: документ, который стоит
# посылать, всегда можно описать одной строкой, а ответ, описанный строкой,
# и есть текст сообщения. Единственный боевой отправитель файлов
# (scripts/spec_approval.py) подпись даёт всегда.
голый_файл() {  # $1 = подпись; 0 — подписи нет или она отписка
    local TIGHT
    TIGHT=$(printf '%s' "${1:-}" | tr -s '[:space:]' ' ')
    TIGHT="${TIGHT# }"; TIGHT="${TIGHT% }"
    [ "${#TIGHT}" -lt "${CAPTION_MIN:-20}" ]
}

if [ "${1:-}" = "--selftest" ]; then
    OK=1
    PARTS_FILE=$(mktemp)
    send_text() { printf '%s\n' "$1" >> "$PARTS_FILE"; }   # без сети: части копим в файл

    проба() {  # $1=что проверяем $2=1/0
        if [ "$2" = 1 ]; then printf '  ок    %s\n' "$1"; else printf '  ПЛОХО %s\n' "$1"; OK=0; fi
    }

    LINE=$(printf 'я%.0s' $(seq 1 99))
    LONG=$(for _ in $(seq 1 95); do printf '%s\n' "$LINE"; done)
    LONG="${LONG%$'\n'}"

    : > "$PARTS_FILE"; отправить_текст_частями "$LONG"
    GLUED=$(sed 's/^\[[0-9]*\/[0-9]*\] //' "$PARTS_FILE")
    проба "текст ${#LONG} зн. ушёл частями ($TOTAL_PARTS), а не обрезком" \
          "$([ "$TOTAL_PARTS" -ge 3 ] && echo 1 || echo 0)"
    проба "БОЛЬНОЙ СЛУЧАЙ: склейка частей знак в знак равна исходному тексту" \
          "$([ "$GLUED" = "$LONG" ] && echo 1 || echo 0)"

    : > "$PARTS_FILE"; отправить_текст_частями "короткий"
    проба "короткий текст идёт одной частью без нумерации" \
          "$([ "$(cat "$PARTS_FILE")" = "короткий" ] && echo 1 || echo 0)"

    CAP=$(printf 'слово %.0s' $(seq 1 500))
    SHORT=$(подпись_под_файл "$CAP")
    проба "БОЛЬНОЙ СЛУЧАЙ: подпись ${#CAP} зн. под файлом влезает в потолок Bot API (1024)" \
          "$([ ${#SHORT} -le 1024 ] && echo 1 || echo 0)"
    case "$SHORT" in
        *"… (подпись целиком — сообщением следом)") проба "укороченная подпись называет себя и обещает хвост" 1 ;;
        *) проба "укороченная подпись называет себя и обещает хвост" 0 ;;
    esac
    проба "укороченная подпись не рвёт слово посреди" \
          "$(case "$SHORT" in *"слов… "*) echo 0 ;; *) echo 1 ;; esac)"
    : > "$PARTS_FILE"; отправить_текст_частями "$CAP"
    проба "хвост подписи уходит следом целиком, знак в знак" \
          "$([ "$(cat "$PARTS_FILE")" = "$CAP" ] && echo 1 || echo 0)"

    EXACT=$(printf 'a%.0s' $(seq 1 "$CAPTION_MAX"))
    проба "подпись ровно в потолок ($CAPTION_MAX) идёт как есть, хвоста нет" \
          "$([ ${#EXACT} -le "$CAPTION_MAX" ] && echo 1 || echo 0)"

    # БОЛЬНЫЕ СЛУЧАИ признака доставки (мутационная проба 10.09.2026): без них
    # самотест не замечал, что успехом стал считаться ЛЮБОЙ ответ API.
    проба "БОЛЬНОЙ СЛУЧАЙ: ok:false («Unauthorized») — это отказ, а не доставка" \
          "$(ответ_успешен '{"ok":false,"description":"Unauthorized"}' && echo 0 || echo 1)"
    проба "БОЛЬНОЙ СЛУЧАЙ: ok:true без message_id — доставку никто не подтвердил" \
          "$(ответ_успешен '{"ok":true}' && echo 0 || echo 1)"
    проба "пустой ответ (сеть оборвалась) — отказ" \
          "$(ответ_успешен '' && echo 0 || echo 1)"
    проба "не-JSON от прокси или заглушки — отказ" \
          "$(ответ_успешен '<html>502 Bad Gateway</html>' && echo 0 || echo 1)"
    проба "ok:true с message_id — единственная форма успеха" \
          "$(ответ_успешен '{"ok":true,"result":{"message_id":4219}}' && echo 1 || echo 0)"
    # Метка пульса: ставится за МОЙ отчёт и не ставится за сообщение демона —
    # иначе тревога sentinel гасила бы пульс, и сторож считал бы, что владелец
    # только что получил статус (находка ревью I-7).
    PULSE_TMP=$(mktemp -d)
    ( LOG_DIR="$PULSE_TMP" CLAUDE_CODE_SESSION_ID="" HARNESS_REPORT="" \
      bash -c 'source <(sed -n "/^отметить_отчёт()/,/^}/p" '"$0"'); отметить_отчёт' )
    проба "БОЛЬНОЙ СЛУЧАЙ: сообщение демона пульс не двигает" \
          "$([ ! -f "$PULSE_TMP/last_report" ] && echo 1 || echo 0)"
    ( LOG_DIR="$PULSE_TMP" CLAUDE_CODE_SESSION_ID="проба" \
      bash -c 'source <(sed -n "/^отметить_отчёт()/,/^}/p" '"$0"'); отметить_отчёт' )
    проба "мой отчёт пульс двигает" \
          "$([ -f "$PULSE_TMP/last_report" ] && echo 1 || echo 0)"
    rm -rf "$PULSE_TMP"

    проба "БОЛЬНОЙ СЛУЧАЙ: «--файл» понимается как --file (12.08 владелец получил вместо снимков слово «--файл»)" \
