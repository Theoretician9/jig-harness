_ПРОПУСК_КАТАЛОГОВ = {".git", "node_modules", "__pycache__", ".venv", "venv"}


def _метка() -> Path:
    """Файл-водораздел: его mtime — «когда смотрели в прошлый раз».

    Метка СВОЯ у каждой сессии (находка ревью F-gen-02). Владелец 12.09.2026
    разрешил параллельные сессии, и хук срабатывает ещё у субагентов: с одной
    меткой на машину чужой прогон сдвигал водораздел, и правка, сделанная до
    него, не находилась НИ У КОГО — проверено живым прогоном двух деревьев.
    """
    sys.path.insert(0, str(КОРЕНЬ / "lib"))
    from config import log_dir
    сессия = (os.environ.get("CLAUDE_CODE_SESSION_ID")
              or str(os.getppid()))
    каталог = Path(log_dir()) / "имена"
    _подмести(каталог)
    return каталог / f"осмотр-{re.sub(r'[^A-Za-z0-9_-]', '_', сессия)[:64]}"


def _подмести(каталог: Path, суток: int = 7) -> None:
    """Метки мёртвых сессий: по файлу на сессию, а сессии ротируются часто."""
    предел = time.time() - суток * 86400
    for метка in каталог.glob("осмотр-*"):
        try:
            if метка.stat().st_mtime < предел:
                метка.unlink()
        except OSError:
            continue


def корни_осмотра() -> list[Path]:
    """Проект и ПАКЕТ: у пакета есть свои файлы, которых в проекте нет.

    13.09.2026 `local строка` в `USTANOVIT.sh` уронил живой шаг установки, а
    установщик живёт только в пакете (см. файлы_пакета). Для остальных файлов
    харнеса пара «пакет + проект» спасает сама: копия в проекте меняется тем же
    ходом. Обход пакета замерен 28.09.2026 — 351 файл, 1 мс.
    """
    из_окружения = os.environ.get("CLAUDE_PROJECT_DIR")
    проект = Path(из_окружения) if из_окружения else РЕПО
    sys.path.insert(0, str(КОРЕНЬ / "lib"))
    from config import katalog_paketa
    пакет = katalog_paketa()
    корни = [к for к in (проект, пакет) if к.is_dir()]
    # Пакета на чужой машине может не быть законно, а вот отсутствие ПРОЕКТА
    # значит, что осмотр вечно зелен и ничего не осматривает — такое молчание
    # и есть дефект (находка ревью F-gen-03,
    # [[unreadable-source-turns-check-green]]).
    if not проект.is_dir():
        print(f"[кириллица] корень осмотра не найден: {проект}", file=sys.stderr)
    return корни if проект != пакет else корни[:1]


def скрипты_свежее(корень: Path, порог: float) -> list[Path]:
    """Файлы .sh, изменённые после порога. Обход дерева — 8 мс на 1837 файлов."""
    итог = []
    for каталог, подкаталоги, файлы in os.walk(корень):
        подкаталоги[:] = [к for к in подкаталоги if к not in _ПРОПУСК_КАТАЛОГОВ]
        for имя in файлы:
            if not имя.endswith(".sh"):
                continue
            путь = Path(каталог) / имя
            try:
                # lstat, а не stat: битая ссылка с именем .sh иначе исчезает
                # молча, а «не прочитали» это не «нарушений нет».
                if путь.lstat().st_mtime > порог:
                    итог.append(путь)
            except OSError:
                continue
    return sorted(итог)


def режим_после_команды() -> int:
    """PostToolUse на Bash: третий путь записи — оболочка.

    Судим не команду, а ФАКТ: какие .sh изменились с прошлого осмотра. Разбор
    команды закрыл бы только heredoc, а пять пропусков смены 27–28.09.2026
    пришли разными формами, в том числе питоном внутри `python3 - <<PY`,
    который пишет файл — такую запись из командной строки не вычитать.

    Отказать поздно (файл уже записан), но сказать НЕМЕДЛЕННО ещё можно: код 2
    отдаёт текст агенту тем же ходом, что и хук записи. Метка сдвигается всегда
    — о находке говорим один раз, дальше её держит гейт на коммите.

    Область носителя — файлы `.sh` в двух корнях (проект и пакет). Запись
    оболочкой в чужой каталог или в bash-файл без расширения им не видна, и
    гейт коммита её тоже не видит: файла нет в индексе (находка ревью F-gen-08).
    """
    находки, непрочитанные = [], []
    try:
        метка = _метка()
        метка.parent.mkdir(parents=True, exist_ok=True)
        порог = метка.stat().st_mtime if метка.exists() else None
        метка.touch()
        if порог is None:
            return 0     # первый запуск: водораздела не было, судить не от чего
        свежие = [путь for корень in корни_осмотра()
                  for путь in скрипты_свежее(корень, порог)]
        if not свежие:
            return 0     # правило грузится ПОСЛЕ обхода: 0,039 с из 0,106 с
        правило = _правило()
        for путь in свежие:
            # Отдельный except на файл: иначе один нечитаемый .sh глотал ВСЕ
            # находки прогона, а метка уже сдвинута — про больной файл носитель
            # не сказал бы никогда (находка ревью F-gen-01).
            try:
                текст = путь.read_text(encoding="utf-8", errors="replace")
            except OSError:
                непрочитанные.append(путь)
                continue
            находки += [(путь, номер, имя)
                        for номер, имя in беды_в_тексте(текст, правило)]
    except Exception as беда:        # прибор не смеет ронять работу (гл. 08, п. 4)
        print(f"[кириллица] осмотр после команды не состоялся: {беда}",
              file=sys.stderr)
        return 0
    if непрочитанные:
        print(f"[кириллица] не прочитано файлов: {len(непрочитанные)} "
              f"({непрочитанные[0]}…) — судить по ним нечем", file=sys.stderr)
    if not находки:
        return 0
    for путь, номер, имя in находки[:4]:
        print(f"{путь}:{номер}: имя переменной кириллицей — «{имя}»",
              file=sys.stderr)
    if len(находки) > 4:
        print(f"…и ещё {len(находки) - 4}: молча отброшенное неотличимо от "
              f"несделанного", file=sys.stderr)
    print("Файл записан ОБОЛОЧКОЙ, мимо хука записи. Bash такие идентификаторы "
          "не берёт и печатает в ошибку САМО ЗНАЧЕНИЕ — 09.09.2026 так утёк "
          "пароль. Переименуй латиницей; кириллица законна в тексте.",
          file=sys.stderr)
    return 2


def режим_хука() -> int:
    """PreToolUse на запись файла: отказать В МОМЕНТ правки, а не на коммите.

    Гейт видит только индекс, а правки .sh идут через запись файла и через
    скрипты во временных каталогах — за одну смену 11.09.2026 кириллическое имя
    переменной всплывало семь раз, и каждый раз ловилось запуском, а не
    правилом. Второй носитель закрывает второй путь: правило, перекрытое одним
    путём из двух, обходится вторым.
    """
    import json
    try:
        нагрузка = json.loads(sys.stdin.read())
    except ValueError:
        return 0
    вход = нагрузка.get("tool_input") or {}
    путь = вход.get("file_path") or ""
    if not путь.endswith(".sh"):
        return 0
    текст = вход.get("content") or вход.get("new_string") or ""
    if not текст:
        return 0
    беды = беды_в_тексте(текст, _правило())
    if not беды:
        return 0
    имена = ", ".join(f"«{имя}»" for _, имя in беды[:4])
    print(f"Имя переменной кириллицей: {имена}. Bash такие идентификаторы не "
          f"берёт и печатает в ошибку САМО ЗНАЧЕНИЕ — так утекал токен. "
          f"Переименуй латиницей; кириллица законна в тексте и комментариях.",
          file=sys.stderr)
    return 2


