def состарить_node(с, дата):
    путь = с.src / "nodejs-dist-index.json"
    данные = json.loads(путь.read_text(encoding="utf-8"))
    for запись in данные:
        if запись["version"].startswith("v22.") and Ф1.кортеж(запись["version"]) > (22, 20, 0):
            запись["date"] = дата
    путь.write_text(json.dumps(данные), encoding="utf-8")


def новая_заплатка_node(с, версия, дата):
    путь = с.src / "nodejs-dist-index.json"
    данные = json.loads(путь.read_text(encoding="utf-8"))
