def путь_демона() -> Path:
    if os.environ.get("HARNESS_STACK_WATCH"):
        return Path(os.environ["HARNESS_STACK_WATCH"])
    # Рабочий каталог — последний кандидат: прибор мутаций зовёт пробу из копии, где может быть только scripts/.
    for кандидат in (ЗДЕСЬ.parent / "harness" / "demons" / "stack-watch.sh", ЗДЕСЬ.parent / "demons" / "stack-watch.sh",
                     Path.cwd() / "harness" / "demons" / "stack-watch.sh"):
        if кандидат.is_file():
            return кандидат
    return ЗДЕСЬ.parent / "harness" / "demons" / "stack-watch.sh"


class Стенд2(Ф1.Стенд):
    def __init__(self):
        super().__init__()
        self.скрипты = self.корень / "scripts"
        self.скрипты.mkdir()
        (self.скрипты / "stack_freshness.py").symlink_to(Ф1.ИНСТРУМЕНТ)
        self.канал = self.корень / "канал.txt"
        self.inbox = self.log / "inbox.jsonl"
        self.заглушки()
        self.код("tg", 0)
        self.код("pause", 1)
        self.код("limit", 1)

    def заглушки(self):
        tg = self.скрипты / "tg_send.sh"
        tg.write_text(f'#!/bin/sh\nprintf "%s\\n" "$*" >> "{self.корень}/tg.argv"\n'
                      f'for a in "$@"; do case "$a" in --*) ;; *) printf "%s\\n---\\n" "$a" >> "{self.канал}";; esac; done\n'
                      f'exit $(cat "{self.корень}/tg.rc")\n', encoding="utf-8")
        tg.chmod(0o755)
        for имя, файл in (("pause.py", "pause.rc"), ("limit_mark.py", "limit.rc")):
            (self.скрипты / имя).write_text(
                f'import sys\nsys.exit(int(open("{self.корень}/{файл}").read()))\n', encoding="utf-8")

    def strict_channel(self):
        """tg_send, который, как боевой, судит каждое сообщение сторожем канала и отказывает кодом 1.

        Потолки сторож берёт из памяти/TONE.md в PROJECT_DIR — кладём стенду строку живого документа."""
        live_tone = ЗДЕСЬ.parent / "память" / "TONE.md"
        line = next((s for s in live_tone.read_text(encoding="utf-8").split("\n") if "потолки:" in s), None) \
            if live_tone.is_file() else None
        (self.корень / "память").mkdir(exist_ok=True)
        (self.корень / "память" / "TONE.md").write_text(
            (line or "<!-- потолки: мягкий=700 жёсткий=1400 -->") + "\n", encoding="utf-8")
        tg = self.скрипты / "tg_send.sh"
        tg.write_text(f'#!/bin/sh\nprintf "%s\\n" "$*" >> "{self.корень}/tg.argv"\n'
                      f'for a in "$@"; do case "$a" in --*) ;; *)\n'
                      f'  printf "%s" "$a" | PROJECT_DIR="{self.корень}" python3 "{ПРОВЕРКА_КАНАЛА}" >/dev/null 2>&1 '
                      f'|| {{ printf "%s\\n---\\n" "$a" >> "{self.корень}/отказано.txt"; exit 1; }}\n'
                      f'  printf "%s\\n---\\n" "$a" >> "{self.канал}";; esac; done\n'
                      f'exit $(cat "{self.корень}/tg.rc")\n', encoding="utf-8")
        tg.chmod(0o755)

    def refused(self):
        файл = self.корень / "отказано.txt"
        return [s for s in файл.read_text(encoding="utf-8").split("\n---\n") if s.strip()] if файл.exists() else []

    def код(self, что, значение):
        файл = {"tg": "tg.rc", "pause": "pause.rc", "limit": "limit.rc"}[что]
        (self.корень / файл).write_text(str(значение), encoding="utf-8")

    def сообщения(self):
        if not self.канал.exists():
            return []
        return [s for s in self.канал.read_text(encoding="utf-8").split("\n---\n") if s.strip()]

    def вопросы(self):
        файл = self.log / "stack-вопросы.jsonl"
        if not файл.exists():
            return []
        return [json.loads(s) for s in файл.read_text(encoding="utf-8").split("\n") if s.strip()]

    def входящее(self, текст, ts, номер):
        строка = {"chat_id": 1, "message_id": номер, "text": текст, "ts": ts}
        with open(self.inbox, "a", encoding="utf-8") as out:
            out.write(json.dumps(строка, ensure_ascii=False) + "\n")

    def убедиться_что_двери_в_стенде(self):
        загрузчик = ЗДЕСЬ / "lib" / "config.sh"
        готово = subprocess.run(["bash", "-c", f'source "{загрузчик}"; konf_zagruzit; printf %s "$PROJECT_DIR"'],
                                env=self.окружение(), capture_output=True, text=True)
        Ф1.проверить(готово.stdout == str(self.корень), f"PROJECT_DIR демона не стенд: {готово.stdout!r}")

    def демон(self, *args, **доп):
        self.убедиться_что_двери_в_стенде()
        готово = subprocess.run(["bash", str(путь_демона()), *args], cwd=self.корень,
                                env=self.окружение(**доп), capture_output=True, text=True, timeout=180)
        return готово.returncode, готово.stdout + готово.stderr

    def сводка(self, now):
        код, вывод, _ = self.запустить("--сводка", HARNESS_STACK_NOW=now)
        return код, вывод.split("\n")[0], "\n".join(вывод.split("\n")[1:])

    def замерить(self, now=Ф1.СЕЙЧАС):
        return self.запустить("--замер", HARNESS_STACK_NOW=now)


