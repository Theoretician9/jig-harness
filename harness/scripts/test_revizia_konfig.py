#!/usr/bin/env python3
"""Данные ревизии читаются и означают то, что обещает спека.

Почему тест на файл данных: демон и модуль порций верят этому файлу без
разбора. Область без масок читала бы пустоту и молча отчитывалась «находок
нет»; порог не-числом уронил бы арифметику потолка внутри bash. Ловим это
здесь, а не в 09:00 первого числа.

Прогон: python3 scripts/test_revizia_konfig.py
"""
import glob
import sys
from pathlib import Path

import yaml

КОРЕНЬ = Path(__file__).resolve().parent.parent
ДАННЫЕ = КОРЕНЬ / "harness" / "config" / "ревизия.yaml"
ПОРОГИ = ("знаков_на_порцию", "потолок_минут", "максимум_находок",
          "максимум_знаков_карточки", "срок_находки_суток")
путей = неудач = 0


def путь(ок: bool, текст: str) -> None:
    global путей, неудач
    путей += 1
    неудач += 0 if ок else 1
    print(("ок  · " if ок else "ПЛОХО · ") + текст)


данные = yaml.safe_load(ДАННЫЕ.read_text(encoding="utf-8"))
области = данные.get("области") or []
пороги = данные.get("пороги") or {}

путь(len(области) == 5, f"областей пять (сейчас {len(области)})")
for область in области:
    имя = область.get("имя", "?")
    маски = область.get("пути") or []
    путь(bool(маски) and bool(область.get("вопрос")),
         f"{имя}: есть пути и вопрос")
    # БОЛЬНОЙ СЛУЧАЙ: маска, под которую не попадает ни один файл, — область
    # читала бы пустоту и отчитывалась «находок нет».
    пустые = [м for м in маски if not glob.glob(str(КОРЕНЬ / м))]
    путь(not пустые, f"{имя}: каждая маска находит хотя бы один файл {пустые or ''}")
for ключ in ПОРОГИ:
    путь(isinstance(пороги.get(ключ), int) and пороги[ключ] > 0,
         f"порог {ключ} — целое положительное ({пороги.get(ключ)!r})")

print(f"КОНФИГ РЕВИЗИИ: путей {путей}, неудач {неудач}")
sys.exit(1 if неудач else 0)
