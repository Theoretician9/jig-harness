#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Гейт: в коде харнеса нет имени продукта — ни каталога, ни написаний.

Откуда взят. Владелец 12.09.2026 велел проверить, что харнес хорошенько
очищен от всего, что относится к продукту. Харнес — общий инструмент, его
ставят другие люди. Имя чужого продукта в его коде — это и утечка (кому-то достаётся имя
нашего заказчика), и ПОЛОМКА у того, чей продукт называется иначе.

Что поломка не выдумана, показал замер того же дня: гейт импортов искал корни
по вшитому имени продукта, а гейт гигиены — файлы памяти с ним же в названии.
На другой установке оба нашли бы ноль и промолчали бы: зелёный гейт, не
проверяющий ничего. Всего имя встречалось 124 раза в 20 файлах харнеса.

Что считается ХАРНЕСОМ — не свой список, а тот же, по которому сверяется
пакет (`sverit-s-paketom.py`, СООТВЕТСТВИЯ): два списка разъехались бы молча,
и разошедшаяся половина молчала бы ровно тогда, когда нужна.

Что считается ИМЕНЕМ ПРОДУКТА — данные установки, а не список в коде:
`PRODUCT_DIR` (каталог) и `PRODUCT_ALIASES` (прочие написания, например
кириллическое) из harness.conf. Нет продукта — гейту нечего искать, он молчит.

Живые данные — карта, память, журналы, спеки, передачи смен — не судятся:
там имя продукта законно, это наша мастерская, а не инструмент.

    check-harnes-chist.py            # весь харнес
    check-harnes-chist.py --список   # список staged-файлов на stdin
    check-harnes-chist.py --selftest
Код возврата: 0 — чисто, 1 — имя продукта найдено.
"""
from __future__ import annotations

import importlib.util
import os
import re
import subprocess
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))
from konf import конфиг                       # noqa: E402


def имена_продукта(конф: str | None = None) -> list[str]:
    """Как зовут продукт: каталог плюс прочие написания. Пусто — продукта нет."""
    путь = конф or os.environ.get("HARNESS_CONF") or "/etc/harness/harness.conf"
    данные = конфиг(путь)
    имена = [данные.get("PRODUCT_DIR", "").strip("/")]
    имена += данные.get("PRODUCT_ALIASES", "").split()
    # Короткое имя ловит слишком много («db», «app»): три знака — граница, ниже
    # которой совпадение почти наверняка случайно.
    return sorted({и for и in имена if len(и) >= 3})


def _место_в_пакете():
    """Функция из гейта сверки с пакетом — ОДИН источник списка «что харнес».

    Импорт по пути: имя файла с дефисами модулем не зовётся.
    """
    путь = Path(__file__).resolve().with_name("sverit-s-paketom.py")
    спец = importlib.util.spec_from_file_location("_sverka", путь)
    модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(модуль)
    return модуль.место_в_пакете


def файлы_харнеса(корень: Path | None = None) -> list[str]:
    """Пути репозитория, которые принадлежат харнесу (а не проекту)."""
    корень = корень or КОРЕНЬ
    место = _место_в_пакете()
    вывод = subprocess.run(
        ["git", "-C", str(корень), "-c", "core.quotepath=false", "ls-files"],
        capture_output=True, text=True, check=True).stdout
    # Скилы генерируются из UNIFIED, а UNIFIED — живой текст глав: судить их
    # тут значило бы красить то, что правится в другом месте.
    пропуск = ("harness/skills/", "UNIFIED/")
    return [п for п in вывод.splitlines()
            if п and not п.startswith(пропуск) and место(п)]


def находки(пути, имена, корень: Path | None = None) -> list[tuple[str, int, str]]:
    """(файл, строка, имя) для каждого вхождения имени продукта."""
    корень = корень or КОРЕНЬ
    if not имена:
        return []
    правило = re.compile("|".join(re.escape(и) for и in имена), re.IGNORECASE)
    итог = []
    for путь in пути:
        файл = корень / путь
        if not файл.is_file():
            continue
        try:
            текст = файл.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        for номер, строка in enumerate(текст.splitlines(), 1):
            найдено = правило.search(строка)
            if найдено:
                итог.append((путь, номер, найдено.group(0)))
    return итог


def отчёт(итог) -> str:
    if not итог:
        return "[харнес чист] имени продукта в коде харнеса нет"
    файлов = len({ф for ф, _, _ in итог})
    строки = [f"[харнес чист] ИМЯ ПРОДУКТА В ХАРНЕСЕ: {len(итог)} вхождений "
              f"в {файлов} файлах — у другого проекта это поломка или утечка"]
    for ф, н, и in итог[:12]:
        строки.append(f"    {ф}:{н} — «{и}»")
    if len(итог) > 12:
        строки.append(f"    … ещё {len(итог) - 12}")
    строки.append("    Имя продукта берут из данных (PRODUCT_DIR), образцы в "
                  "самотестах — нейтральные («app», «продукт»).")
    return "\n".join(строки)


def самотест() -> int:
    import tempfile
    ok = True

    def проба(зачем, ждём, вышло):
        nonlocal ok
        if вышло != ждём:
            ok = False
            print(f"  ПЛОХО {зачем}: вышло {вышло}, ждали {ждём}")
        else:
            print(f"  ок    {зачем}")

    with tempfile.TemporaryDirectory() as tmp:
        корень = Path(tmp)
        (корень / "конф").write_text('PRODUCT_DIR="mojprodukt"\n'
                                     'PRODUCT_ALIASES="МОЙПРОДУКТ Mojik"\n',
                                     encoding="utf-8")
        проба("имена берутся из данных и сортируются",
              ["Mojik", "mojprodukt", "МОЙПРОДУКТ"],
              имена_продукта(str(корень / "конф")))
        (корень / "пусто").write_text("LOG_DIR=/var/log\n", encoding="utf-8")
        проба("продукта нет — искать нечего", [], имена_продукта(str(корень / "пусто")))
        (корень / "короткое").write_text('PRODUCT_DIR="db"\n', encoding="utf-8")
        проба("имя короче трёх знаков не берём: совпадёт где угодно",
              [], имена_продукта(str(корень / "короткое")))

        # БОЛЬНОЙ СЛУЧАЙ 12.09.2026: имя продукта в коде гейта. Так гейт
        # импортов искал корни по вшитому имени и на чужой установке молчал бы.
        (корень / "гейт.py").write_text(
            'КОРНИ = ("mojprodukt", ".")\n# образец: mojprodukt/lib/x.py\n',
            encoding="utf-8")
        найдено = находки(["гейт.py"], ["mojprodukt"], корень)
        проба("БОЛЬНОЙ СЛУЧАЙ: имя продукта в коде — две находки",
              2, len(найдено))
        проба("отчёт называет файл и строку", True,
              "гейт.py:1" in отчёт(найдено))

        (корень / "чистый.py").write_text(
            'КОРНИ = (product_dir(), ".")\n# образец: app/lib/x.py\n',
            encoding="utf-8")
        проба("тот же гейт на данных — чисто", [],
              находки(["чистый.py"], ["mojprodukt"], корень))

        # Регистр: кириллическое написание ловится независимо от него.
        (корень / "текст.md").write_text("Задача МойПродукт закрыта\n", encoding="utf-8")
        проба("написание ловится без учёта регистра", 1,
              len(находки(["текст.md"], ["МОЙПРОДУКТ"], корень)))

        проба("пустой список имён — молчание, а не падение", [],
              находки(["гейт.py"], [], корень))

    print("САМОТЕСТ %s: 8 путей, первым — больной случай"
          % ("ПРОЙДЕН" if ok else "ПРОВАЛЕН"))
    return 0 if ok else 1


def main() -> int:
    if "--selftest" in sys.argv:
        return самотест()
    имена = имена_продукта()
    if not имена:
        print("[харнес чист] продукт не задан (PRODUCT_DIR пуст) — проверять нечего")
        return 0
    if "--список" in sys.argv:
        место = _место_в_пакете()
        пути = [п.strip() for п in sys.stdin.read().splitlines() if п.strip()]
        пути = [п for п in пути
                if место(п) and not п.startswith(("harness/skills/", "UNIFIED/"))]
    else:
        пути = файлы_харнеса()
    итог = находки(пути, имена)
    print(отчёт(итог))
    return 1 if итог else 0


if __name__ == "__main__":
    sys.exit(main())
