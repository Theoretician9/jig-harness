#!/usr/bin/env python3
"""Гейт: у каждого задания расписания есть период метки, у каждой метки — хозяин.

СЛУЧАЙ (ревизия архитектуры 12.09.2026). Файл `системные-задания.yaml` заведён
ровно против отказа «новый демон без строки расписания и без периода метки
мёртв и незаметен» — и сам от него не был защищён: три помощника (строитель
проверок, сторож приёмки, замер речи) стояли в расписании, писали метку, а
периода не имели. Сторож меток судит ТОЛЬКО по списку периодов — их молчание
не разбудило бы никого.

Что судим:

  • задание без периода метки — красный. Исключение одно и считается кодом:
    два задания одного демона (обычный прогон и прогон по порогу) делят одну
    метку, и имя метки берётся из КОМАНДЫ, а не из имени задания;
  • метка без задания — красный, если она не названа в `метки_без_задания`
    с причиной: таймер systemd, отдельная строка установки, вторая метка того
    же сторожа. Причина обязана быть словами, а не пустой строкой.

    python3 scripts/check-zadanie-i-metka.py
    python3 scripts/check-zadanie-i-metka.py --selftest
Код возврата: 0 — сходится, 1 — есть расхождение.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

КОРЕНЬ = Path(__file__).resolve().parent.parent
ДАННЫЕ = КОРЕНЬ / "harness" / "config" / "системные-задания.yaml"


def данные(путь: Path = ДАННЫЕ) -> dict:
    return yaml.safe_load(путь.read_text(encoding="utf-8")) or {}


def имя_метки(задание: dict) -> str:
    """Метка, которую пишет это задание: имя демона из команды.

    Два задания одного демона («memory-revision» и «memory-revision-порог»)
    пишут ОДНУ метку — брать имя задания было бы требованием завести вторую.
    """
    команда = str(задание.get("команда", ""))
    основа = Path(команда.split()[0]).name if команда.split() else ""
    return re.sub(r"\.(sh|py)$", "", основа) or str(задание.get("имя", ""))


def расхождения(дано: dict) -> list[str]:
    задания = дано.get("задания") or []
    метки = дано.get("метки") or {}
    объяснённые = дано.get("метки_без_задания") or {}
    беды = []

    for задание in задания:
        метка = имя_метки(задание)
        if метка not in метки:
            беды.append(f"задание «{задание.get('имя')}» пишет метку «{метка}», "
                        f"а периода у неё нет — сторож меток его не ждёт")

    от_заданий = {имя_метки(з) for з in задания}
    for метка in метки:
        if метка in от_заданий:
            continue
        причина = str(объяснённые.get(метка, "")).strip()
        if not причина:
            беды.append(f"метка «{метка}» без задания и без причины: кто её пишет? "
                        f"впиши в «метки_без_задания» словами")

    for метка in объяснённые:
        if метка not in метки:
            беды.append(f"метка «{метка}» объяснена, но периода у неё нет — "
                        f"объяснение без метки ничего не сторожит")
    return беды


def проверить(путь: Path = ДАННЫЕ) -> int:
    дано = данные(путь)
    беды = расхождения(дано)
    if беды:
        print(f"[задание и метка] РАСХОЖДЕНИЕ: {len(беды)}")
        for беда in беды:
            print(f"  ✗ {беда}")
        print(f"  Файл: {путь}")
        return 1
    print(f"[задание и метка] сходится: заданий {len(дано.get('задания') or [])}, "
          f"периодов меток {len(дано.get('метки') or {})}")
    return 0


def самотест() -> int:
    путей = неудач = 0

    def проба(имя: str, ждём, факт):
        nonlocal путей, неудач
        путей += 1
        if факт == ждём:
            print(f"  ок    {имя}")
        else:
            неудач += 1
            print(f"  ПЛОХО {имя}: ждали «{ждём}», вышло «{факт}»")

    здоровые = {
        "задания": [{"имя": "сторож", "команда": "harness/demons/сторож.sh"}],
        "метки": {"сторож": 10},
    }
    проба("здоровая пара задание↔метка", [], расхождения(здоровые))

    # БОЛЬНОЙ СЛУЧАЙ 12.09.2026: три демона в расписании без периода метки.
    без_метки = {"задания": [{"имя": "строитель",
                              "команда": "harness/demons/stroitel-proverok.sh"}],
                 "метки": {}}
    беды = расхождения(без_метки)
    проба("задание без периода метки названо", 1, len(беды))
    проба("претензия говорит, чем это грозит", True,
          "не ждёт" in (беды[0] if беды else ""))

    сирота = {"задания": [], "метки": {"ничья": 5}}
    проба("метка без задания и без причины — претензия", 1, len(расхождения(сирота)))
    объяснена = {"задания": [], "метки": {"ничья": 5},
                 "метки_без_задания": {"ничья": "её пишет таймер systemd"}}
    проба("объяснённая метка претензии не даёт", [], расхождения(объяснена))
    пустая = {"задания": [], "метки": {"ничья": 5},
              "метки_без_задания": {"ничья": "   "}}
    проба("пустая причина причиной не считается", 1, len(расхождения(пустая)))
    лишняя = {"задания": [], "метки": {},
              "метки_без_задания": {"нет-такой": "почему-то"}}
    проба("объяснение без метки названо", 1, len(расхождения(лишняя)))

    два_режима = {
        "задания": [{"имя": "память", "команда": "harness/demons/memory-revision.sh"},
                    {"имя": "память-порог",
                     "команда": "harness/demons/memory-revision.sh --по-порогу"}],
        "метки": {"memory-revision": 1440},
    }
    проба("два режима одного демона делят метку", [], расхождения(два_режима))

    проба("живые данные сходятся", 0, проверить())
    print(f"SELFTEST: {'зелёный' if not неудач else 'КРАСНЫЙ'} ({путей} путей; "
          "больной первый — задание в расписании без периода метки)")
    return 1 if неудач else 0


if __name__ == "__main__":
    sys.exit(самотест() if "--selftest" in sys.argv else проверить())
