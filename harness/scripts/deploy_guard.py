# Слово владельца 05.11.2026: «все вопросы по поводу моего Да должны приходить
# кнопками в телегу», «нужно не как правило, а кодом». Текст дверь не открывает
# никогда, только закрывает (отзыв); судит owner_word.судить_кнопкой — один судья
# на все двери. Кнопка не тратится: гасит её само действие (owner_word.ПОГАШЕНИЕ).

# Кого спрашивать: своя ручка на каждое действие (спека панели §4). Ключи читаются
# у МАШИНЫ (owner_word.конфиг_права): `HARNESS_CONF=/tmp/c ./scripts/deploy.sh` их
# не подменяет, окружение слушается лишь на стенде.
КЛЮЧ_ДЕЙСТВИЯ = {
    "push": "PUSH_NEEDS_OWNER",
    "deploy": "DEPLOY_NEEDS_OWNER",
    "публикация": "PUBLISH_NEEDS_OWNER",
}
# Согласие, данное ЗАРАНЕЕ (слово владельца 10.10.2026 «Выкат - да»): ключ в harness.conf
# машины, действует ТОЛЬКО на выкат и пуш; необратимое остальное его не знает.
СТОЯЩЕЕ_СОГЛАСИЕ_ДЕЙСТВИЯ = {"deploy", "push"}
# Действия без ручки: ни ключ, ни AUTONOMY их не открывают (необратимые данные, И-1).
БЕЗ_РУЧКИ = {"dropdb", "перепись"}


def _ключ_права(имя: str) -> str:
    return (слово_вл.конфиг_права("harness.conf").get(имя) or "").strip()


def нужно_согласие(действие: str = "deploy") -> bool:
    """Спрашивать ли владельца про это действие.

    Ключа нет — спрашиваем: конфиг старой установки не смеет молча открывать
    выкат. Действие без ключа (`dropdb`) спрашивает всегда.
    """
    ключ = КЛЮЧ_ДЕЙСТВИЯ.get(действие)
    if ключ is None:
        return True
    return (_ключ_права(ключ) or "1") != "0"


# ── Кнопка «Да» на выкат, пуш, публикацию (предмет считают door_subjects и push_subject) ──
# Вид кнопки по действию ворот.
ВИД_ДЕЙСТВИЯ = {"push": "пуш", "deploy": "выкат", "публикация": "публикация",
                "dropdb": "снос-базы", "перепись": "перепись"}
# Ключи предмета от зовущего. --пуш даёт сторож ТОЛЬКО для команды из одного звена
# `git push <удалённый> <40-hex>:refs/heads/<ветка>`; --выкат и --публикация даёт
# сам скрипт: что он выкатывает и публикует, ворота сверяют со своим подсчётом.
ПУШ: tuple[str, str, str] | None = None
ВЫКАТ: tuple[str, str] | None = None
ПУБЛИКАЦИЯ: str | None = None
БАЗА: str | None = None
ПЕРЕПИСЬ: str | None = None
# Просит кнопку только зов с явным --просить: его ставят скрипты-двери (deploy.sh, publish.sh,
# drop-database.sh). Хук, stop_reminder и проверки сеть не трогают и не просят никогда.
ПРОСИТЬ = False
# Предмет считается один раз за запуск: main зовёт нет_согласия дважды, а ls-remote
# по сети не должен идти дважды. Неудача тоже кэшируется.
_ПРЕДМЕТ: dict = {}
REFSPEC_ХЭША = re.compile(r"([0-9a-f]{40}):refs/heads/(.+)")


def _предмет_пуша() -> str | None:
    if ПУШ is None:
        raise push_subject.PushSubjectError("ключ --пуш не передан: хэш пуша ворота не знают")
    удалённый, refspec, репо = ПУШ
    найдено = REFSPEC_ХЭША.fullmatch(refspec)
    if not найдено:
        raise push_subject.PushSubjectError("refspec не <40-hex>:refs/heads/<ветка>")
    head, ветка = найдено.groups()
    # Хук без сети: вершина удалённого — по локальной ссылке; пуш не force, git отвергнет не-ff.
    return push_subject.push_subject(репо, удалённый, head, ветка,
                                     base=f"refs/remotes/{удалённый}/{ветка}")


def _предмет_выката() -> str:
    """Предмет считается из дерева КОНФИГА МАШИНЫ; deploy.sh, назвав своё дерево и sha, обязан с ним сойтись."""
    предмет = door_subjects.deploy_subject(door_subjects.deploy_tree(
        слово_вл.конфиг_права("install.conf"), слово_вл.конфиг_права("harness.conf")))
    if ВЫКАТ is not None and предмет != f"{ВЫКАТ[1]} {os.path.realpath(ВЫКАТ[0])}":
        raise push_subject.PushSubjectError(
            f"выкат идёт не тот, что видят ворота (скрипт: {ВЫКАТ[1][:8]} в {ВЫКАТ[0]}; "
            f"ворота: {предмет[:8]}...)")
    return предмет


def _предмет_публикации() -> str:
    if ПУБЛИКАЦИЯ is None:
        raise push_subject.PushSubjectError("ключ --публикация <пакет> не передан")
    return door_subjects.publish_subject(
        ПУБЛИКАЦИЯ, *door_subjects.publish_settings(слово_вл.конфиг_права("harness.conf")))


def _предмет_сноса() -> str:
    if БАЗА is None:
        raise push_subject.PushSubjectError("ключ --база <имя> не передан")
    return БАЗА


def _предмет_переписи() -> str:
    """Предмет переписи: вершина удалённого ДО входит в строку — повторный force-push прежним «Да» закрыт."""
    if ПЕРЕПИСЬ is None:
        raise push_subject.PushSubjectError("ключ --перепись <копия> не передан")
    _сборка, удалённый, ветка = door_subjects.publish_settings(слово_вл.конфиг_права("harness.conf"))
    адрес = door_subjects.rewrite_address(str(конф.katalog_paketa()), удалённый)
    return door_subjects.rewrite_subject(ПЕРЕПИСЬ, адрес, ветка)


ПРЕДМЕТЫ = {"push": _предмет_пуша, "deploy": _предмет_выката, "публикация": _предмет_публикации,
            "dropdb": _предмет_сноса, "перепись": _предмет_переписи}


def _предмет(действие: str) -> tuple[str | None, str | None]:
    """→ (предмет, причина): ровно одно из двух. Причину печатает отказ двери."""
    if действие not in _ПРЕДМЕТ:
        try:
            _ПРЕДМЕТ[действие] = (ПРЕДМЕТЫ[действие](), None)
        except push_subject.PushSubjectError as беда:
            _ПРЕДМЕТ[действие] = (None, str(беда))
        if _ПРЕДМЕТ[действие][0]:
            # Строку читает publish.sh: перед пушем он пересчитывает предмет и сверяет с ней.
            print(f"предмет: {_ПРЕДМЕТ[действие][0]}")
    return _ПРЕДМЕТ[действие]


def _просьба(вид: str, предмет: str | None) -> str:
    """Готовая команда просьбы — хук-двери кнопку сами не просят."""
    if предмет is None:
        return ""
    return (f" Попросить кнопку: python3 scripts/ask-consent.py --вид {вид} "
            f"--предмет-двери \"{предмет}\" --почему …")


def нет_согласия(действие: str) -> str | None:
    """Причина «нет согласия владельца» или None — кнопка «Да» есть либо согласие не требуется.

    Ключи ручек, DEPLOY_CONSENT_STANDING и AUTONOMY — с машины (см. КЛЮЧ_ДЕЙСТВИЯ).
    Предмет не посчитан — отказ с его причиной («в дереве не закоммичено N», «git fetch»).
    """
    if not нужно_согласие(действие):
        print(f"(ручка «{КЛЮЧ_ДЕЙСТВИЯ.get(действие)}» отпущена — "
              f"согласие владельца на «{действие}» не спрашивается)")
        return None
    if _ключ_права("DEPLOY_CONSENT_STANDING") == "1" and действие in СТОЯЩЕЕ_СОГЛАСИЕ_ДЕЙСТВИЯ:
        print(f"(согласие на «{действие}» дано владельцем ЗАРАНЕЕ — ключ "
              f"DEPLOY_CONSENT_STANDING в harness.conf, его слово 10.10.2026 "
              f"«согласие на выкат дано заранее, на всю работу»; не расходуется. "
              f"Необратимое его слова по-прежнему требует)")
        return None
    режим = (слово_вл.конфиг_права("install.conf").get("AUTONOMY") or "semi").strip().lower()
    if режим != "semi" and действие not in БЕЗ_РУЧКИ:
        print(f"(AUTONOMY={режим} — согласие владельца на «{действие}» не проверяется)")
        return None
    вид = ВИД_ДЕЙСТВИЯ.get(действие)
    if вид is None:
        return f"действие «{действие}» воротам незнакомо — кнопки на него нет, дверь закрыта"
    предмет, причина = _предмет(действие)
    что = {"push": "отправку в репозиторий", "dropdb": "удаление базы",
           "публикация": "публикацию проверенного",
           "перепись": "перепись публичной истории"}.get(действие, "выкат")
    если_пуш = (" Предмет посчитан по локальной refs/remotes без сети: если удалённый ушёл вперёд — "
                "git fetch и новая кнопка.") if действие == "push" else ""
    if предмет is None:
        # Хэша пуша ворота не знают: ask-consent сам посчитает его и выдаст кнопку.
        как = (" Попросить кнопку: python3 scripts/ask-consent.py --вид пуш "
               '--предмет "<удалённый> <ветка>" --почему …') if действие == "push" else ""
        return f"нет согласия владельца на {что}: кнопки нет — {причина}.{если_пуш}{как}"
    на = МОМЕНТ_СВЕЖЕСТИ if МОМЕНТ_СВЕЖЕСТИ is not None else time.time()
    открыто, причина = слово_вл.судить_кнопкой(вид, предмет, LOG_DIR, на=на)
    if открыто:
        print(f"(согласие кнопкой: {причина}; не расходуется — гасит его само действие «{вид}»)")
        return None
    отказ = (f"нет согласия владельца на {что} (полуавтомат): {причина}. Текст владельца дверь не "
             f"открывает — нужна кнопка «Да» в Telegram.{если_пуш}")
    if not ПРОСИТЬ:
        return отказ + _просьба(вид, предмет)
    if not слово_вл.просить_ли(причина):
        return отказ
    # Журналы просьбы — каталог этой двери, явно: просьба стенда в машинный журнал не ляжет.
    _код, итог = слово_вл.попросить_кнопку(вид, предмет, f"скрипт просит: {что}", LOG_DIR, репо=ПЕРЕПИСЬ or ПУБЛИКАЦИЯ)
    return f"{отказ} {итог}"


def две_смены() -> str | None:
    """Причина отказа, если живьём работают два и более основных агента.

    Считает библиотека по дереву процессов, а не признак сторожа
    two-agents.state: признак устаревает, а выкат поверх двух смен выкатывает
    неизвестно чью работу. «--силой» снимает только занятость и этого запрета
    не касается.
    """
    pids = агенты.main_agents()
    if len(pids) < 2:
        return None
    return (f"работают два агента: pids {' '.join(map(str, pids))}. Выкат поверх двух "
            "смен выкатывает неизвестно чью работу, «--силой» это не снимает. "
            "Оставить одну смену: bash scripts/one-shift.sh")


def решение(занятость: list, силой: bool = False) -> dict:
    """Можно ли выкатывать прямо сейчас. Логика — из шаблона; --силой печатает
    каждую жертву отдельной строкой."""
    if not занятость:
        return {"можно": True, "почему": "идущих работ нет — выкат безопасен"}
    if силой:
        return {"можно": True,
                "почему": ("выкат «--силой» пойдёт по живому:\n  "
                           + "\n  ".join(занятость)
                           + "\nПерезапускать убитое придётся вручную")}
    return {"можно": False,
            "почему": (f"занято: {'; '.join(занятость)}. Выкат перезапускает стек "
                       "и убивает идущую работу (повторной попытки у неё нет), а "
                       "второй одновременный выкат оставляет контейнеры не "
                       "поднятыми. Дождаться или «--силой», понимая цену")}


# Кнопка не тратится зовущим (гасит её само действие), поэтому ключей возврата и «не тратить» нет.
# «--не-тратить» и «--вернуть-согласие» — тихие пустышки: их ещё зовут старые вызовы в живых конфигах.
ФЛАГИ = ("--силой", "--только-согласие", "--просить", "--не-тратить", "--вернуть-согласие")
# Ключи со значениями: сколько значений следует за ключом.
КЛЮЧИ_СО_ЗНАЧЕНИЯМИ = {"--пуш": 3, "--выкат": 2, "--публикация": 1, "--база": 1, "--перепись": 1,
                       "--свежесть-на": 1}
ИЗВЕСТНЫЕ_КЛЮЧИ = ("--действие <значение>", "--пуш <удалённый> <refspec> <репо>",
                   "--выкат <дерево> <sha>", "--публикация <пакет>", "--база <имя>",
                   "--перепись <копия>", "--свежесть-на <epoch>", *ФЛАГИ)


def разобрать_ключи(ключи: list[str]) -> tuple[str, str | None]:
    """→ (действие, отказ). Незнакомый ключ отказывает ДО чтения журнала и
    состояния: прежде он шёл боевой проверкой и жёг «да» владельца."""
    действие = "deploy"
    очередь = iter(ключи)
    for ключ in очередь:
        if ключ == "--действие":
            действие = next(очередь, "-")
            if действие.startswith("-"):
                return действие, "незнакомый ключ --действие без значения"
        elif ключ in КЛЮЧИ_СО_ЗНАЧЕНИЯМИ:
            if None in [next(очередь, None) for _ in range(КЛЮЧИ_СО_ЗНАЧЕНИЯМИ[ключ])]:
                return действие, f"ключ {ключ} требует значений: {КЛЮЧИ_СО_ЗНАЧЕНИЯМИ[ключ]}"
        elif ключ not in ФЛАГИ:
            return действие, f"незнакомый ключ {ключ}"
    return действие, None


def main() -> int:
    # Действие названо зовущим: у выката, отправки в репозиторий и удаления
    # базы разные предметы согласия, и «да» про одно не разрешает другого.
    действие, отказ = разобрать_ключи(sys.argv[1:])
    if отказ:
        print(f"{отказ}; известны: {', '.join(ИЗВЕСТНЫЕ_КЛЮЧИ)}")
        return 2
    global ПУШ, ВЫКАТ, ПУБЛИКАЦИЯ, БАЗА, ПЕРЕПИСЬ, ПРОСИТЬ, МОМЕНТ_СВЕЖЕСТИ

    def значения(ключ: str) -> tuple | None:
        at = sys.argv.index(ключ) + 1 if ключ in sys.argv else None
        return tuple(sys.argv[at:at + КЛЮЧИ_СО_ЗНАЧЕНИЯМИ[ключ]]) if at else None
    ПУШ, ВЫКАТ = значения("--пуш"), значения("--выкат")
    ПУБЛИКАЦИЯ = (значения("--публикация") or (None,))[0]
    БАЗА = (значения("--база") or (None,))[0]
    ПЕРЕПИСЬ = (значения("--перепись") or (None,))[0]
    ПРОСИТЬ = "--просить" in sys.argv
    момент = значения("--свежесть-на")
    if момент and действие not in ("публикация", "перепись"):
        print("--свежесть-на: ключ только для --действие публикация и перепись; выкату и пушу "
              "момент не нужен")
        return 2
    if момент:
        # float() пропускает nan, а сравнения с NaN ложны: потолок бы снялся.
        if not (момент[0].isascii() and момент[0].isdigit()):
            print(f"--свежесть-на: «{момент[0]}» не целое число секунд epoch")
            return 2
        МОМЕНТ_СВЕЖЕСТИ = int(момент[0])
        возраст_момента = (time.time() - МОМЕНТ_СВЕЖЕСТИ) / 60
        if возраст_момента < -1:
            print("--свежесть-на: момент попытки в будущем — спроси согласие заново")
            return 1
        if возраст_момента > ПОТОЛОК_СВЕЖЕСТИ_МИН:
            print(f"--свежесть-на: момент попытки {int(возраст_момента)} мин назад старше "
                  f"допустимых {ПОТОЛОК_СВЕЖЕСТИ_МИН} мин — спроси согласие заново")
            return 1
    # «--только-согласие»: зовущему нужны именно ворота согласия, а не
    # занятость выката. Так спрашивает дверь удаления базы: чужой идущий
    # прогон ей не помеха, а вот слово владельца — обязательно.
    if "--только-согласие" in sys.argv:
        просрочка = нет_согласия(действие)
        print(просрочка or "согласие владельца есть")
        return 1 if просрочка else 0
    смены = две_смены()
    if смены:
        print(смены)
        return 1
    # Отсутствие кнопки — не занятость: «--силой» снимает только занятость
    # и согласия владельца не заменяет.
    просрочка = нет_согласия(действие)
    if просрочка:
        print(просрочка)
        return 1
    занятость = лок_файлы() + долгие_процессы()
    итог = решение(занятость, силой="--силой" in sys.argv)
    print(итог["почему"])
    return 0 if итог["можно"] else 1


if __name__ == "__main__":
    sys.exit(main())
