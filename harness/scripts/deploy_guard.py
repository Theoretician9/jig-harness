def _под_нашим_деревом(каталог: pathlib.Path) -> bool:
    """Работа идёт в НАШЕМ дереве: рабочий каталог процесса или его бинарь лежат
    под проектом харнеса или под продуктом. Пути — ДАННЫЕ (PROJECT_DIR,
    PRODUCT_PATH): вшитые сюда, они были бы следом нашей установки."""
    корни = [p.strip() for p in (КОНФИГ.get("PROJECT_DIR"), МЕХАНИКА.get("PRODUCT_PATH"))
             if p and p.strip()]
    if not корни:
        return False
    for имя in ("cwd", "exe"):
        try:
            цель = str(pathlib.Path(каталог, имя).resolve())
        except OSError:
            continue
        if any(цель == к or цель.startswith(к.rstrip("/") + "/") for к in корни):
            return True
    return False


def _в_нашем_контейнере(каталог: pathlib.Path) -> bool:
    """Процесс живёт в контейнере НАШЕГО стека: имя проекта compose стоит в его
    cgroup. Имя — данные (PRODUCT_DIR), и пустое значит «продукта здесь нет», а
    не «подходит любой контейнер»."""
    имя = (МЕХАНИКА.get("PRODUCT_DIR") or "").strip()
    if not имя:
        return False
    try:
        return имя in pathlib.Path(каталог, "cgroup").read_text()
    except OSError:
        return False


def _свой_процесс(каталог: pathlib.Path, свой_uid: int) -> bool:
    """Наша ли это работа. Признаков ТРИ, и довольно одного.

    Улика 15.10.2026: на одной машине с харнесом может стоять ВТОРОЙ харнес под
    другим пользователем, и такая установка на этой машине есть. Его
    агент работает постоянно, а ворота обходили весь /proc по имени бинаря — и
    назвали чужую работу нашей занятостью: отправка в гит отменена словами
    «занято: процесс 280436». Вечный отказ учит ходить «--силой» — ровно то,
    против чего замок.
    Одного uid, однако, НЕ ХВАТИЛО (ревью безопасности того же дня, major):
    работа в контейнере идёт под uid 0/70/999, работа под `sudo` — под root, и
    ворота перестали видеть их вовсе, то есть выкат пошёл бы поверх идущего
    прогона. Поэтому своим считается процесс того же владельца ЛИБО работающий
    в нашем дереве ЛИБО в контейнере нашего стека: лишний отказ здесь дешевле
    пропуска, и это уже решено веткой «терминалы неизвестны — НЕ исключаем».
    Каталог недоступен (процесс умер) — не наш: судить нечего.
    """
    try:
        if каталог.stat().st_uid == свой_uid:
            return True
    except OSError:
        return False
    return _под_нашим_деревом(каталог) or _в_нашем_контейнере(каталог)


def _процесс_агента(pid: str, терминалы: set | None) -> bool:
    """claude, чей терминал — панель tmux-сессии агента: интерактивная сессия,
    а не «долгая работа» (Б-1: она блокировала бы ворота всё время жизни агента).
    Терминалы неизвестны (tmux недоступен) — НЕ исключаем: честнее лишний отказ
    с внятной строкой, чем молчаливый пропуск проверки."""
    if not терминалы:
        return False
    tty = _tty_процесса(pid)
    return tty is not None and tty in терминалы


def долгие_процессы() -> list:
    """Живые долгие процессы claude/тестов, кроме собственных предков
    и интерактивного claude в tmux-сессии агента (Б-1)."""
    свои = _предки()
    свой_uid = _свой_uid()
    терминалы = _tmux_терминалы(TMUX_SESSION)
    if терминалы is None:
        print(f"(tmux-сессия «{TMUX_SESSION}» недоступна — интерактивный claude агента "
              "не исключается из занятости)")
    занято = []
    try:
        uptime = time.clock_gettime(time.CLOCK_BOOTTIME)   # почему не /proc/uptime — в _процесс_моложе
        hz = os.sysconf("SC_CLK_TCK")
    except (OSError, ValueError):
        return занято
    for p in pathlib.Path("/proc").iterdir():
        if not p.name.isdigit() or int(p.name) in свои:
            continue
        if not _свой_процесс(p, свой_uid):
            continue
        try:
            токены = [t for t in p.joinpath("cmdline").read_bytes().decode(errors="replace").split("\0") if t]
            имя = _имя_работы(токены) if токены else None
            if not имя:
                continue
            cmdline = " ".join(токены)
            starttime = int(pathlib.Path(p, "stat").read_text().rsplit(")", 1)[1].split()[19])
            возраст = uptime - starttime / hz
        except (OSError, ValueError, IndexError):
            continue
        if возраст < ДОЛГО_СЕК:
            continue
        if имя == "claude" and _процесс_агента(p.name, терминалы):
            print(f"(процесс {p.name}: claude на терминале tmux-сессии «{TMUX_SESSION}» — "
                  "интерактивная сессия агента, не занятость)")
            continue
        занято.append(f"процесс {p.name}: {cmdline[:80]} ({int(возраст // 60)} мин)")
    return занято


