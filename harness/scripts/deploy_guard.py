def read_conf(path: str = CONF_PATH) -> dict:
    """Мини-парсер shell-конфига. Не source: воротам нельзя исполнять чужой код."""
    conf: dict[str, str] = {}
    try:
        with open(path, encoding="utf-8") as fh:
            for line in fh:
                m = re.match(r"""\s*([A-Z][A-Z0-9_]*)=("[^"]*"|'[^']*'|[^#\s]*)""", line)
                if m:
                    raw = m.group(2)
                    val = raw[1:-1] if raw[:1] in "\"'" else raw
                    for name, seen in conf.items():
                        val = val.replace("${%s}" % name, seen).replace("$" + name, seen)
                    conf[m.group(1)] = val
    except OSError:
        pass
    return conf


