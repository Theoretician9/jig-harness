ДОЛГО_СЕК = 120
# Что считается долгой работой: headless-агенты claude и прогоны тестов.
ИМЕНА_РАБОТЫ = {"claude", "pytest", "vitest"}


def _имя_работы(токены: list) -> str | None:
    """Имя опознанной долгой работы («claude», «pytest», …) или None.

    Работа опознаётся по ИМЕНИ запущенного бинаря, не поиском подстроки:
    поиск по подстроке ловил чужое — путь /opt/claude-code в аргументах любого
    процесса выглядел как «claude» (дефис — граница слова для \\b), и ворота
    видели занятость там, где её нет. Ложный запрет хуже пропуска: от него
    избавляются обходом всей защиты (улика guard_bash.py). Поймано прогоном
    при сборке пакета 08.08.2026.
    """
    базы = [pathlib.PurePath(t).name for t in токены[:4]]
    for б in базы:
        if б in ИМЕНА_РАБОТЫ:
            return б  # claude/pytest/vitest сам или через python -m
    if базы and базы[0] in ("npm", "npx") and any(t == "test" for t in токены[1:4]):
        return "npm test"
    # bash -c 'claude -p ...' — смотрим первое слово нагрузки -c
    for i, t in enumerate(токены[:-1]):
        if t == "-c":
            нагрузка = токены[i + 1].strip().split()
            if нагрузка and pathlib.PurePath(нагрузка[0]).name in ИМЕНА_РАБОТЫ:
                return pathlib.PurePath(нагрузка[0]).name
    return None


def _pid_жив(pid: int) -> bool:
    try:
        os.kill(pid, 0)
        return True
    except ProcessLookupError:
        return False
    except PermissionError:
        return True


def лок_файлы() -> list:
    """Живые операционные lock-файлы. Мёртвый PID называется протухшим, но не блокирует.

    Б-1: смотрим ТОЛЬКО $LOG_DIR/locks/*.lock — glob не спускается в подкаталоги,
    и это поведение здесь закон: сервисные локи (locks/services/, см.
    SERVICE_LOCKS_SUBDIR в harness.conf) живут вечно и занятостью не являются.
    Лок, который держит собственный предок ворот (deploy.sh берёт свой лок ДО
    ворот, К-3), — тоже не занятость: иначе выкат блокировал бы сам себя.
    """
    занято = []
    if not LOCKS.is_dir():
        return занято
    свои = _предки()
    for lock in sorted(LOCKS.glob("*.lock")):
        if not lock.is_file() or lock.parent != LOCKS:
            continue  # подкаталоги (services/) — не операционные локи
        try:
            строки = lock.read_text(encoding="utf-8").splitlines()
        except OSError:
            continue
        pid = int(строки[0]) if строки and строки[0].strip().isdigit() else 0
        описание = строки[1].strip() if len(строки) > 1 else "без описания"
        if pid and pid in свои:
            print(f"(лок {lock.name} держит сам вызвавший процесс — не блокирует)")
        elif pid and _pid_жив(pid):
            занято.append(f"лок {lock.name}: {описание} (PID {pid})")
        else:
            print(f"(протухший лок {lock.name} — держатель мёртв, не блокирует)")
    return занято


def _предки() -> set:
    """Свои процессы вверх по дереву.

    Без этого проверка ловит саму себя: ворота зовутся из сессии claude, и
    поиск по имени находит родительскую оболочку (улика в guard_bash.py).
    """
    свои, pid = set(), os.getpid()
    while pid > 1 and pid not in свои:
        свои.add(pid)
        try:
            stat = pathlib.Path(f"/proc/{pid}/stat").read_text()
            pid = int(stat.rsplit(")", 1)[1].split()[1])
        except (OSError, ValueError, IndexError):
            break
    return свои


def _tmux_терминалы(сессия: str) -> set | None:
    """tty всех панелей tmux-сессии агента; None = tmux/сессия недоступны."""
    try:
        p = subprocess.run(
            ["tmux", "list-panes", "-s", "-t", сессия, "-F", "#{pane_tty}"],
            capture_output=True, text=True, timeout=5,
        )
    except Exception:
        return None
    if p.returncode != 0:
        return None
    return {с.strip() for с in p.stdout.splitlines() if с.strip()} or None


def _tty_процесса(pid: str) -> str | None:
    """Управляющий терминал процесса из tty_nr в /proc/<pid>/stat (кодировка proc(5))."""
    try:
        tty_nr = int(pathlib.Path(f"/proc/{pid}/stat").read_text().rsplit(")", 1)[1].split()[4])
    except (OSError, ValueError, IndexError):
        return None
    if tty_nr <= 0:
        return None
    major = (tty_nr >> 8) & 0xFF
    minor = (tty_nr & 0xFF) | (((tty_nr >> 20) & 0xFFF) << 8)
    if 136 <= major <= 143:
        return f"/dev/pts/{(major - 136) * 256 + minor}"
    if major == 4:
        return f"/dev/tty{minor}"
    return None


def _процесс_агента(pid: str, терминалы: set | None) -> bool:
    """claude, чей терминал — панель tmux-сессии агента: интерактивная сессия,
    а не «долгая работа» (Б-1: она блокировала бы ворота всё время жизни агента).
    Терминалы неизвестны (tmux недоступен) — НЕ исключаем: честнее лишний отказ
    с внятной строкой, чем молчаливый пропуск проверки."""
    if not терминалы:
        return False
    tty = _tty_процесса(pid)
    return tty is not None and tty in терминалы


def долгие_процессы() -> list:
    """Живые долгие процессы claude/тестов, кроме собственных предков
    и интерактивного claude в tmux-сессии агента (Б-1)."""
    свои = _предки()
    терминалы = _tmux_терминалы(TMUX_SESSION)
    if терминалы is None:
        print(f"(tmux-сессия «{TMUX_SESSION}» недоступна — интерактивный claude агента "
              "не исключается из занятости)")
    занято = []
    try:
        uptime = float(pathlib.Path("/proc/uptime").read_text().split()[0])
        hz = os.sysconf("SC_CLK_TCK")
    except (OSError, ValueError):
        return занято
    for p in pathlib.Path("/proc").iterdir():
        if not p.name.isdigit() or int(p.name) in свои:
            continue
        try:
            токены = [t for t in p.joinpath("cmdline").read_bytes().decode(errors="replace").split("\0") if t]
            имя = _имя_работы(токены) if токены else None
            if not имя:
                continue
            cmdline = " ".join(токены)
            starttime = int(pathlib.Path(p, "stat").read_text().rsplit(")", 1)[1].split()[19])
            возраст = uptime - starttime / hz
        except (OSError, ValueError, IndexError):
            continue
        if возраст < ДОЛГО_СЕК:
            continue
        if имя == "claude" and _процесс_агента(p.name, терминалы):
            print(f"(процесс {p.name}: claude на терминале tmux-сессии «{TMUX_SESSION}» — "
                  "интерактивная сессия агента, не занятость)")
            continue
        занято.append(f"процесс {p.name}: {cmdline[:80]} ({int(возраст // 60)} мин)")
    return занято


# ── В-7: согласие владельца на выкат в полуавтомате ─────────────────────────
# Формат записи — то, что реально пишет tg-dispatcher.sh (его ветка confirmations):
#   {"ts":"2026-08-09T12:34:56+00:00","text":"да","message_id":"123"}
# text — нормализованный ответ владельца; выкат разрешают общие подтверждения,
# «ротация ок»/«ротация да» — согласие на РОТАЦИЮ, выкат ими не разрешён.
# Запись с "kind":"deploy" (будущий адресный формат) тоже считается согласием.
# Голые формы: предмет НЕ назван, он был в вопросе агента. Годятся только
# тому действию, о котором спрашивали (см. _согласие) — иначе «да» про одно
# открывает другое, и правило владельца «одно да — одно действие» держится
# на памяти агента, а не на механизме (замер 11.09.2026).
СОГЛАСИЕ_БЕЗ_ПРЕДМЕТА = {"да", "ок", "окей", "подтверждаю"}
# Точные формы с НАЗВАННЫМ предметом выката (случай 20.08.2026: «Да для
# выката» первой строкой длинного сообщения). Их привязывать не к чему —
# предмет в них уже есть.
ПОДТВЕРЖДЕНИЯ_ВЫКАТА = {"выкатывай", "да для выката", "да выкатывай",
                        "да, выкатывай"}


def _секунды_ts(ts) -> float | None:
    if isinstance(ts, (int, float)):
        return float(ts)
    try:
        return datetime.datetime.fromisoformat(str(ts)).timestamp()
    except ValueError:
        return None


# Согласие с НАЗВАННЫМ ПРЕДМЕТОМ — признаком, а не списком форм. Список
# оказался тупиком дважды: 20.08.2026 «Да для выката» и «По выкату пишу да»,
# 25.08.2026 «Делай деплой, да» — все три раза согласие БЫЛО, а выкат стоял.
# Тот же признак давно живёт в tg-dispatcher.sh (его `согласие_владельца`), и
# именно расхождение двух списков ловило нас каждый раз: диспетчер согласие
# записывал, ворота его не признавали. Теперь правило одно на оба места.
ПРЕДМЕТ_ВЫКАТА = re.compile(r"выкат|деплой|deploy")
# Отправка в чужой репозиторий — тоже действие наружу, и согласие на неё
# владелец даёт своими словами. Улика 03.09.2026: «на гит отправляй, да» —
# согласие названо, предмет назван, а ворота его не признали: предметом они
# знали только выкат, и push встал при данном разрешении. Правило то же, что
# у выката, и живёт рядом с ним, чтобы не разошлось.
ПРЕДМЕТ_ОТПРАВКИ = re.compile(r"гит|git|пуш|push|отправ")
# Удаление базы — третье действие наружу (дверь scripts/ubrat-bazu.sh). До
# 11.09.2026 у неё было СВОЁ правило согласия без предмета: любое «да» за час
# открывало снос базы. Предмет назван здесь, рядом с двумя другими, чтобы не
# разошлось снова.
ПРЕДМЕТ_БАЗЫ = re.compile(r"баз|дроп|drop|удал|снес|снос")
# Публикация — четвёртое действие наружу: перенос проверенного в ветку, которую
# владелец показывает людям. Предмет назван здесь же, рядом с тремя другими.
ПРЕДМЕТ_ПУБЛИКАЦИИ = re.compile(r"публик|publish|опубликов|витрин|stable|релиз")
# Прямое распоряжение сильнее слова «да»: «публикуй как есть» — согласие, хотя
# слова «да» в нём нет. 11.09.2026 владелец ответил цифрой на вопрос с
# вариантами («1 публикуй как есть»), сторож не признал, и распоряжение
# владельца осталось неисполненным. Форма повелительная и по предмету —
# спутать её с обсуждением нельзя.
РАСПОРЯЖЕНИЕ = {
    "публикация": re.compile(r"публикуй|опубликуй"),
    "deploy": re.compile(r"выкатывай|выкати|деплой(?:ь|те)?\b"),
    "push": re.compile(r"отправляй|отправь|запуш"),
}
СЛОВО_ДА = re.compile(r"(?:^|[\s,.;:!?()\"-])да(?:$|[\s,.;:!?()\"-])")
ОТРИЦАНИЕ = re.compile(
    r"(?:^|[\s,.;:!?()\"-])(?:не|нет|стоп|отмена|погоди|подожди|позже|рано)"
    r"(?:$|[\s,.;:!?()\"-])")


def _согласие(запись: dict, действие: str, ожидаемое: str | None = None) -> bool:
    """Согласен ли владелец на ЭТО действие. `действие` — deploy либо push.

    `ожидаемое` — действие, в котором ворота отказали последними, то есть то,
    о чём агент спрашивал. Для согласия БЕЗ названного предмета это
    единственный якорь: без него «да», сказанное про что угодно, открывало
    любое действие наружу (замер 11.09.2026 — «да» про репозиторий харнеса
    45 минут спустя разрешало и push, и ВЫКАТ В ПРОД).
    """
    if запись.get("kind") == "deploy":
        # Публикация сюда НЕ попадает: «выкатывай, да» не разрешает показать
        # людям непроверенное — у этой двери свой предмет.
        if действие == "публикация":
            return bool(ПРЕДМЕТ_ПУБЛИКАЦИИ.search(str(запись.get("text", "")).lower()))
        return действие == "deploy" or bool(ПРЕДМЕТ_ОТПРАВКИ.search(
            str(запись.get("text", "")).lower()))
    # `any` — согласие БЕЗ названного предмета, распознанное диспетчером
    # («моё да», «да, конечно»): предмет назван в вопросе агента, а не в
    # ответе владельца. Улика 09.09.2026: на вопрос «поднимать ли упавший
    # прод» владелец ответил «Моё да» — диспетчер согласие признал, ворота
    # своим списком форм не признали. Признак сохранён, но привязан к
    # предмету ВОПРОСА: правило владельца «одно да — одно действие» иначе
    # держится только на памяти агента, а не на механизме.
    if запись.get("kind") == "any":
        return ожидаемое == действие
    текст = str(запись.get("text", "")).strip().lower()
    if текст in ПОДТВЕРЖДЕНИЯ_ВЫКАТА:
        return действие == "deploy"
    # Голое «да»/«ок» — тот же смысл, что и kind=any: предмет назван в вопросе.
    if текст in СОГЛАСИЕ_БЕЗ_ПРЕДМЕТА:
        return ожидаемое == действие
    # «выкат не делай, да и вообще рано» согласием не станет: отрицание
    # перевешивает. «ротация да» — тоже: предмета выката в ней нет.
    предмет = {"push": ПРЕДМЕТ_ОТПРАВКИ,
               "dropdb": ПРЕДМЕТ_БАЗЫ,
               "публикация": ПРЕДМЕТ_ПУБЛИКАЦИИ}.get(действие, ПРЕДМЕТ_ВЫКАТА)
    приказ = РАСПОРЯЖЕНИЕ.get(действие)
    попадание = приказ.search(текст) if приказ is not None else None
    if попадание is not None:
        # Отрицание считается ТОЛЬКО рядом с приказом: «не публикуй» — отказ,
        # а «публикуй как есть, проверю — обновим если что-то не так» согласие,
        # хотя слово «не» в нём есть (живая форма 11.09.2026).
        слева = текст[max(0, попадание.start() - 12):попадание.start()]
        return not ОТРИЦАНИЕ.search(слева)
    if ОТРИЦАНИЕ.search(текст):
        return False
    return bool(СЛОВО_ДА.search(текст) and предмет.search(текст))


def _из_очереди(сейчас: float, уже: list) -> list:
    """Слова владельца из $LOG_DIR/inbox — первичная запись, журнал вторичен.

    Распознаватель диспетчера знает свой список форм, и форма вне списка в
    confirmations.jsonl не попадает вовсе: 11.09.2026 «1 публикуй как есть»
    (ответ цифрой на вопрос с вариантами) потерялся целиком, и распоряжение
    владельца осталось неисполненным. Правила разбора у ворот свои и полнее —
    пусть они видят и то, что распознаватель пропустил.

    Дубли отсекаются по минуте и началу текста: одно сообщение попадает и
    сюда, и в журнал, а потратиться оно должно один раз.
    """
    каталог = LOG_DIR / "inbox"
    было = {(int((_секунды_ts(з.get("ts")) or 0) // 60),
             str(з.get("text", ""))[:40].strip().lower()) for з in уже}
    найдено = []
    for подкаталог in (каталог, каталог / "обработано"):
        try:
            файлы = sorted(подкаталог.glob("*.txt"))
        except OSError:
            continue
        for файл in файлы:
            try:
                когда = файл.stat().st_mtime
            except OSError:
                continue
            if (сейчас - когда) / 60 > CONFIRM_MAX_AGE_MIN:
                continue
            try:
                текст = файл.read_text(encoding="utf-8", errors="replace").strip()
            except OSError:
                continue
            ключ = (int(когда // 60), текст[:40].strip().lower())
            if not текст or ключ in было:
                continue
            было.add(ключ)
            найдено.append({"ts": datetime.datetime.fromtimestamp(когда).isoformat(),
                            "text": текст, "message_id": файл.stem})
    return найдено


def _состояние_согласия() -> dict:
    """Что ворота помнят о согласиях: чего ждали и что уже израсходовали."""
    try:
        return json.loads((LOG_DIR / "согласие.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def _записать_состояние(данные: dict) -> None:
    """Атомарно: временный файл и переименование — иначе смерть посреди записи
    оставит ворота без памяти о согласиях (тот же приём, что у журналов)."""
    путь = LOG_DIR / "согласие.json"
    врем = путь.with_suffix(".json.tmp")
    try:
        врем.write_text(json.dumps(данные, ensure_ascii=False), encoding="utf-8")
        os.replace(врем, путь)
    except OSError:
        pass


# Кого спрашивать: своя ручка на каждое действие (спека панели §4).
# Прежде решал один AUTONOMY, и «автомат» снимал согласие разом с выката,
# отправки, публикации И СНОСА БАЗЫ: проверка режима стояла первой строкой и
# выходила до разбора действия (находки ревью C1/C2 11.09.2026). Снос базы
# ручки не имеет вовсе — это необратимая операция над данными, И-1.
КЛЮЧ_ДЕЙСТВИЯ = {
    "push": "PUSH_NEEDS_OWNER",
    "deploy": "DEPLOY_NEEDS_OWNER",
    "публикация": "PUBLISH_NEEDS_OWNER",
}


def нужно_согласие(действие: str = "deploy") -> bool:
    """Спрашивать ли владельца про это действие.

    Ключа нет — спрашиваем: конфиг старой установки не смеет молча открывать
    выкат. Действие без ключа (`dropdb`) спрашивает всегда.
    """
    ключ = КЛЮЧ_ДЕЙСТВИЯ.get(действие)
    if ключ is None:
        return True
    return (МЕХАНИКА.get(ключ) or "1").strip() != "0"


def нет_согласия(действие: str = "deploy", тратить: bool = True) -> str | None:
    """Причина «нет согласия владельца» (AUTONOMY=semi) или None — согласие есть
    либо не требуется. Нет записи — нет действия (решение владельца 08.08.2026).

    Три правила, каждое под свой замер 11.09.2026:
      • предмет: «да» без названного предмета годится ТОЛЬКО для действия, в
        котором ворота отказали последними, — оно и есть вопрос агента;
      • расход: разрешение тратится. Одно «да» — одно действие (правило
        владельца); прежде им можно было выкатить дважды подряд;
      • отзыв: отрицание ПОСЛЕ согласия отменяет его. Прежде цикл шёл к
        последнему «да» и «стоп» минутой позже не видел вовсе.
    """
    if not нужно_согласие(действие):
        print(f"(ручка «{КЛЮЧ_ДЕЙСТВИЯ.get(действие)}» отпущена — "
              f"согласие владельца на «{действие}» не спрашивается)")
        return None
    режим = (КОНФИГ.get("AUTONOMY") or "semi").strip().lower()
    if режим != "semi" and действие != "dropdb":
        print(f"(AUTONOMY={режим} — согласие владельца на «{действие}» не проверяется)")
        return None
    журнал = LOG_DIR / "confirmations.jsonl"
    сейчас = time.time()
    состояние = _состояние_согласия()
    ожидание = состояние.get("ожидание") or {}
    ожидаемое = ожидание.get("действие") if (
        _секунды_ts(ожидание.get("ts")) or 0) > сейчас - CONFIRM_MAX_AGE_MIN * 60 else None
    израсходованы = set(состояние.get("израсходованы") or [])
    # «Одно да — одно ДЕЙСТВИЕ», а не одна проверка. Перед выкатом ворота
    # спрашивают дважды: сперва сторож команд, потом сам deploy.sh, — и второму
    # разрешения уже не доставалось (улика 11.09.2026: два «да» владельца
    # подряд сгорели на проверках, выкат так и не пошёл). Повтор ТОГО ЖЕ
    # действия в пределах окна — продолжение той же попытки.
    потрачено_когда = max(
        (к for п, к in (состояние.get("потрачено") or {}).items()
         if п.endswith(f"|{действие}")), default=None)
    if (потрачено_когда is not None
            and сейчас - потрачено_когда <= ПОВТОР_ПРОВЕРКИ_СЕК):
        print(f"(та же попытка «{действие}»: разрешение засчитано "
              f"{int((сейчас - потрачено_когда) / 60)} мин назад)")
        return None
    try:
        строки = журнал.read_text(encoding="utf-8").splitlines()
    except OSError:
        строки = []
    записи = []
    for строка in строки:
        try:
            запись = json.loads(строка)
        except ValueError:
            continue
        if isinstance(запись, dict):
            записи.append(запись)
    записи += _из_очереди(сейчас, записи)
    записи.sort(key=lambda з: _секунды_ts(з.get("ts")) or 0)
    for запись in reversed(записи):
        когда = _секунды_ts(запись.get("ts"))
        if когда is None or (сейчас - когда) / 60 > CONFIRM_MAX_AGE_MIN:
            break                      # дальше только старее — читать нечего
        # Отзыв: «стоп» после «да» встречается РАНЬШЕ при обходе с конца.
        текст = str(запись.get("text", "")).lower()
        if ОТРИЦАНИЕ.search(текст) and not _согласие(запись, действие, ожидаемое):
            return (f"владелец отменил согласие словами «{запись.get('text')}» — "
                    f"спроси заново")
        if not _согласие(запись, действие, ожидаемое):
            continue
        ключ = f"{запись.get('ts')}|{действие}"
        if ключ in израсходованы:
            continue                   # это «да» уже сработало один раз
        возраст_мин = (сейчас - когда) / 60
        if not тратить:
            # Проверка — не действие. Раньше «публикация --проверка» съедала
            # согласие, и настоящая публикация минутой позже упиралась в
            # «нет записи свежее 60 мин» (случилось 11.09.2026).
            print(f"(согласие владельца есть: «{запись.get('text', 'kind=any')}», "
                  f"{int(возраст_мин)} мин назад — не израсходовано, это только проверка)")
            return None
        израсходованы.add(ключ)
        состояние["израсходованы"] = sorted(израсходованы)[-50:]
        состояние.setdefault("потрачено", {})[ключ] = сейчас
        состояние["потрачено"] = dict(sorted(
            состояние["потрачено"].items(), key=lambda п: п[1])[-50:])
        состояние.pop("ожидание", None)
        _записать_состояние(состояние)
        print(f"(согласие владельца: «{запись.get('text', 'kind=deploy')}», "
              f"{int(возраст_мин)} мин назад — свежее, порог {CONFIRM_MAX_AGE_MIN} мин; "
              f"разрешение израсходовано: следующее действие потребует нового «да»)")
        return None
    # Отказ — это и есть вопрос агента владельцу: запоминаем предмет, чтобы
    # засчитать ответ «да» без названного предмета именно ему.
    состояние["ожидание"] = {"действие": действие, "ts": сейчас}
    _записать_состояние(состояние)
    что = {"push": "отправку в репозиторий",
           "dropdb": "удаление базы",
           "публикация": "публикацию проверенного"}.get(действие, "выкат")
    return (f"нет согласия владельца на {что} (полуавтомат): в {журнал} нет записи "
            f"свежее {CONFIRM_MAX_AGE_MIN} мин — анонсируй в канал и дождись «да»")


def решение(занятость: list, силой: bool = False) -> dict:
    """Можно ли выкатывать прямо сейчас. Логика — из шаблона; --силой печатает
    каждую жертву отдельной строкой (В-7: отсутствие согласия — тоже строка)."""
    if not занятость:
        return {"можно": True, "почему": "идущих работ нет — выкат безопасен"}
    if силой:
        return {"можно": True,
                "почему": ("выкат «--силой» пойдёт по живому:\n  "
                           + "\n  ".join(занятость)
                           + "\nПерезапускать убитое придётся вручную")}
    return {"можно": False,
            "почему": (f"занято: {'; '.join(занятость)}. Выкат перезапускает стек "
                       "и убивает идущую работу (повторной попытки у неё нет), а "
                       "второй одновременный выкат оставляет контейнеры не "
                       "поднятыми. Дождаться или «--силой», понимая цену")}


def main() -> int:
    # Действие названо зовущим: у выката, отправки в репозиторий и удаления
    # базы разные предметы согласия, и «да» про одно не разрешает другого.
    действие = "deploy"
    if "--действие" in sys.argv:
        действие = sys.argv[sys.argv.index("--действие") + 1]
    # «--только-согласие»: зовущему нужны именно ворота согласия, а не
    # занятость выката. Так спрашивает дверь удаления базы: чужой идущий
    # прогон ей не помеха, а вот слово владельца — обязательно.
    if "--только-согласие" in sys.argv:
        просрочка = нет_согласия(действие, тратить="--не-тратить" not in sys.argv)
        print(просрочка or "согласие владельца есть")
        return 1 if просрочка else 0
    занятость = лок_файлы() + долгие_процессы()
    просрочка = нет_согласия(действие)
    if просрочка:
        занятость.append(просрочка)
    итог = решение(занятость, силой="--силой" in sys.argv)
    print(итог["почему"])
    return 0 if итог["можно"] else 1


if __name__ == "__main__":
    sys.exit(main())
