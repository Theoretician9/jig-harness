def текст_сообщения(файл: pathlib.Path) -> str:
    """Текст владельца. Старая очередь хранила сырой апдейт Telegram —
    признак работы искался бы в служебных полях, а не в словах владельца."""
    сырое = файл.read_text(encoding="utf-8", errors="replace").strip()
    if not сырое.startswith("{"):
        return сырое
    try:
        апдейт = json.loads(сырое)
    except ValueError:
        return ""
    # ПОДПИСЬ К СНИМКУ — тоже слова владельца. Замер 12.09.2026: из 972
    # сообщений архива 68 пришли фотографией с подписью, и все они пролетали
    # мимо разбора — ни задачей, ни пометкой «не задача». Среди них
    # «Вот так сейчас выглядит карта в приложении, займись как все остальные
    # задачи закроешь»: прямое указание, которого гейт не видел.
    return str(апдейт.get("text") or апдейт.get("caption") or "").strip()


# Чужой текст внутри сообщения владельца: пересланные слова бота, вставленный
# экран терминала агента (строки интерфейса Claude Code и поданные агенту
# промпты — «❯ …»), итоговая сводка установщика. Владелец вставляет их, чтобы
# ПОКАЗАТЬ, что было; поручением они не являются, но глаголы работы в них есть
# («ПРОДОЛЖАЙ ТЕКУЩИЙ ШАГ», «назови владельцу…»), и разбор заводил по ним
# карточки, а сторож требовал их делать.
ЧУЖАЯ_СТРОКА = re.compile(
    r"^(\[\d{2}\.\d{2}\.\d{4}[^\]]*\]\s*\S+:"     # пересылка: «[дата] Бот:»
    r"|[❯⎿✻⏺●]"                                  # строки экрана Claude Code
    r"|Ran \d+ \w+ commands?\b"                  # «Ran 4 shell commands»
    r"|.*\b(?:run|Please run|Switch anytime with) /\w+)")  # подвал экрана
# Сводка установщика — блок до конца сообщения: строки внутри неё ничем не
# помечены, отличает её только рамка заголовка.
НАЧАЛО_СВОДКИ = re.compile(r"^=+\s*[A-ZА-ЯЁ][A-ZА-ЯЁ ]*\s*=+$")


# Цитата НАШЕГО сообщения: форма строк обычная, узнать её можно только по
# журналу отправок — и знание о нём приносит ЗОВУЩИЙ, второго признака внутри
# судьи нет. Два порога против случайного совпадения: строка короче
# МИН_ДЛИНА_ЦИТАТЫ («Да», «Пишу») встречается у обоих, а единственная совпавшая
# строка — это его задание моими словами («сделай как писал про крошки»),
# вырезав её, потеряли бы саму задачу.
МИН_ДЛИНА_ЦИТАТЫ = 12
МИН_СТРОК_ЦИТАТЫ = 2


def ровно(строка: str) -> str:
    """Строка для сравнения: пробелы схлопнуты, края сняты."""
    return re.sub(r"\s+", " ", строка).strip()


def слова_владельца(текст: str, наши_строки: set | None = None) -> str:
    """Текст без вставленного чужого: только то, что владелец написал сам.

    `наши_строки` — нормализованные строки наших сообщений владельцу
    (`_ровно`); их блок в его сообщении есть ЦИТАТА, а не задание.
    """
    свои = []
    for строка in текст.splitlines():
        голая = строка.strip()
        if НАЧАЛО_СВОДКИ.match(голая):
            break
        if not ЧУЖАЯ_СТРОКА.match(голая):
            свои.append(строка)
    if наши_строки:
        # Цитата — НЕПРЕРЫВНАЯ группа наших строк, в которой не меньше
        # МИН_СТРОК_ЦИТАТЫ длинных. Длина судит доверие к факту цитирования
        # (короткие «Да», «Пишу спеку.» совпадают у обоих), непрерывность —
        # границы: его собственное поручение, случайно повторившее нашу строку
        # в другом месте письма, лежит в СВОЕЙ группе и остаётся
        # (ревью 14.10.2026, F-gen-04; обе ошибки до этого — срез по всему
        # сообщению и расширение через пустую строку — найдены мутацией).
        группа: list = []
        к_выбросу: set = set()

        def закрыть_группу() -> None:
            длинных = sum(1 for н in группа
                          if len(ровно(свои[н])) >= МИН_ДЛИНА_ЦИТАТЫ)
            if длинных >= МИН_СТРОК_ЦИТАТЫ:
                к_выбросу.update(группа)
            группа.clear()

        for н, строка in enumerate(свои):
            if ровно(строка) in наши_строки:
                группа.append(н)
            else:
                закрыть_группу()
        закрыть_группу()
        свои = [с for н, с in enumerate(свои) if н not in к_выбросу]

    # Вырезанные строки оставляют за собой пустые — схлопнуть до одной.
    return re.sub(r"\n\s*\n(\s*\n)+", "\n\n", "\n".join(свои)).strip()


def рабочее(текст: str, наши_строки: set | None = None) -> bool:
    низ = слова_владельца(текст, наши_строки).lower()
    return any(м in низ for м in МАРКЕРЫ)


def разобранные(корень: pathlib.Path) -> str:
    """Что считается получившим исход: карта (источник: inbox:<id>) и спутник."""
    куски = []
    for имя in (КАРТА, АРХИВ):
        файл = корень / имя
        if файл.exists():
            куски.append(файл.read_text(encoding="utf-8"))
    спутник = корень / СПУТНИК
    if спутник.exists():
        куски.append(спутник.read_text(encoding="utf-8"))
    return "\n".join(куски)


# Механика очереди — общая со сторожем указаний (scripts/lib/channel_queue.py):
# пять мест было написано дважды, и дефект чинился бы в одной копии (ревизия
# лаконичности 12.09.2026). Здесь остаётся СМЫСЛ: что считать работой, где
# лежит исход и что показать владельцу.
def без_исхода(все: list, с_какого: float, разобрано: str) -> list[tuple[str, str]]:
    return [(ид, текст.replace("\n", " ")[:110]) for ид, _, текст in
            очередь.без_исхода(все, с_какого, разобрано, рабочее,
                               текст_из=текст_сообщения)]


def пометить(корень: pathlib.Path, ид: str, почему: str) -> int:
    if not очередь.пометить(корень / СПУТНИК, ид, почему):
        print(f"{ид} уже помечен")
        return 0
    print(f"{ид}: исход записан — {почему}")
    return 0


def архив(корень: pathlib.Path, обработано: pathlib.Path) -> int:
    """Разовый разбор: всё, что похоже на работу и не имеет исхода."""
    все = очередь.сообщения(обработано)
    список = без_исхода(все, 0.0, разобранные(корень))
    print(f"сообщений в архиве: {len(все)} · без исхода с признаком работы: {len(список)}")
    for ид, кусок in список:
        print(f"  {ид}  {кусок}")
    return 0


def проверить(корень: pathlib.Path, обработано: pathlib.Path,
              курсор: pathlib.Path) -> int:
    все = очередь.сообщения(обработано)
    if not все:
        print("[задачи из канала] очередь пуста — сверять нечего")
        return 0
    разобрано = разобранные(корень)
    # с_конца: первый запуск встаёт на самое свежее сообщение — требовать
    # разбора 940 старых значит завести гейт, который никто не позеленит, а
    # такой гейт отключают. Прошлое разбирает `--архив`, и это работа.
    с_какого = очередь.водораздел(курсор, все, разобрано, с_конца=True)
    висят = без_исхода(все, с_какого, разобрано)
    if not висят:
        очередь.подвинуть_курсор(курсор, все)
        print("[задачи из канала] у каждой задачи владельца есть исход")
        return 0
    print(f"\n[задачи из канала] БЕЗ ИСХОДА: {len(висят)} сообщени(й) с работой")
    for ид, кусок in висят[:10]:
        print(f"    {ид}  {кусок}")
    if len(висят) > 10:
        print(f"    … и ещё {len(висят) - 10}")
    print("\nИсход — одно из двух: завести задачу в dev-map.yaml с полем")
    print("`источник: inbox:<id>` в её карточке, либо, если работы в сообщении")
    print("нет, сказать это вслух: tasks-from-channel.py --не-задача <id>.")
    print("Владелец 11.09.2026: «всё должно быть зафиксировано в нужных местах»")
    return 1


def _selftest(корень: pathlib.Path) -> int:
    import tempfile
    плохо = 0

    # Число путей СЧИТАЕТСЯ, а не пишется литералом: «7 путей» в итоге при 17
    # прогнанных пробах ушло в довод карточки как доказательство
    # (ревью 14.10.2026, F-gen-07) — [[cap-in-chars-price-in-tokens]] про то же:
    # число в отчёте обязано мериться тем же, чем живёт.
    путей = [0]

    def проба(имя: str, ждём, вышло) -> None:
        nonlocal плохо
        путей[0] += 1
        if вышло == ждём:
            print(f"  ок    {имя}")
        else:
            print(f"  ПЛОХО {имя}: ждали {ждём}, вышло {вышло}")
            плохо = 1

    with tempfile.TemporaryDirectory() as врем:
        т = pathlib.Path(врем)
        (т / "обработано").mkdir()
        (т / "память").mkdir()
        обр = т / "обработано"
        import time
        def положить(ид: str, текст: str, сдвиг: float) -> None:
            ф = обр / f"{ид}.txt"
            ф.write_text(текст, encoding="utf-8")
            момент = time.time() + сдвиг
            import os
            os.utime(ф, (момент, момент))

        положить("1.0", "Надо добавить экран памяти", -300)
        положить("2.0", "да", -200)
        положить("3.0", '{"text": "нужно починить карту", "message_id": 5}', -100)
        (т / КАРТА).write_text("tasks:\n  - id: hr.проба\n    источник: inbox:1.0\n",
                               encoding="utf-8")
        курсор = т / "курсор"
        курсор.write_text("0", encoding="utf-8")

        # БОЛЬНОЙ СЛУЧАЙ: задача владельца не дошла до карты — красный.
        проба("БОЛЬНОЙ СЛУЧАЙ: задача без исхода красит гейт",
              1, проверить(т, обр, курсор))
        # Сырой апдейт Telegram разбирается: признак ищется в словах владельца.
        все = очередь.сообщения(обр)
        проба("старый формат очереди разобран (текст из JSON)",
              True, any(ид == "3.0" for ид, _ in без_исхода(все, 0.0, разобранные(т))))
        # Согласие задачей не считается.
        проба("«да» задачей не считается",
              False, any(ид == "2.0" for ид, _ in без_исхода(все, 0.0, разобранные(т))))

        # БОЛЬНОЙ СЛУЧАЙ 17.10.2026: карточка уехала в АРХИВ карты — законным
        # путём, которым её переносит и прибор архивации, и гейт потери задач.
        # Исходом считалась только живая карта, и сообщение владельца снова
        # оказывалось «без исхода»: гейт требовал разбирать сделанную работу
        # заново.
        положить("9.0", "сделай кнопку на сайте", -50)
        (т / "docs").mkdir(exist_ok=True)
        (т / АРХИВ).write_text(
            "lines:\n  - id: снятые\n    tasks:\n      - id: hr.ушла\n"
            "        источник: inbox:9.0\n", encoding="utf-8")
        все = очередь.сообщения(обр)
        проба("БОЛЬНОЙ: карточка в архиве карты — это исход",
              False, any(ид == "9.0" for ид, _ in без_исхода(все, 0.0, разобранные(т))))

        # БОЛЬНОЙ СЛУЧАЙ 17.10.2026 (ревью, F-gen-02): исход искался ГОЛОЙ
        # подстрокой номера, и упоминание пути файла в прозе карточки («улика
        # inbox/обработано/<номер>.txt») закрывало исход сообщению, которого
        # никто не разбирал. Замер по 1441 живому сообщению: такой ложный исход
        # был один — и он был.
        положить("8.0", "надо поправить панель", -40)
        (т / КАРТА).write_text(
            "tasks:\n  - id: hr.проба\n    источник: inbox:1.0\n"
            "  - id: hr.чужая\n    summary: 'улика inbox/обработано/8.0.txt'\n",
            encoding="utf-8")
        все = очередь.сообщения(обр)
        проба("БОЛЬНОЙ: упоминание пути файла в прозе исходом не считается",
              True, any(ид == "8.0" for ид, _ in без_исхода(все, 0.0, разобранные(т))))
        # И обратно: законная ссылка `inbox:<номер>` исход закрывает.
        (т / КАРТА).write_text(
            "tasks:\n  - id: hr.проба\n    источник: inbox:1.0\n"
            "  - id: hr.своя\n    источник: inbox:8.0\n", encoding="utf-8")
        проба("законная ссылка inbox:<номер> закрывает исход",
              False, any(ид == "8.0" for ид, _ in без_исхода(все, 0.0, разобранные(т))))
        # БОЛЬНЫЕ СЛУЧАИ: владелец вставил экран терминала агента и сводку
        # установщика — из цитат выросли карточки «ПРОДОЛЖАЙ ТЕКУЩИЙ ШАГ…».
        экран = ("смотри что было. ты работал:\n\n"
                 "7 MCP servers need authentication · run /mcp\n"
                 "  Get to finished work sooner with Opus 5.5. Switch anytime with /model.\n"
                 "❯ Ты — новая сессия. ПРОДОЛЖАЙ ТЕКУЩИЙ ШАГ, назови владельцу задачу\n"
                 "  Ran 4 shell commands\n"
                 "Not logged in · Please run /login\n"
                 "✻ Cooked for 0s · done 8:44 PM\n"
                 "  ⎿  Login interrupted\n\n"
                 "и потом логин слетел. надо такое поправить")
        проба("БОЛЬНОЙ СЛУЧАЙ: из экрана терминала остались только слова владельца",
              "смотри что было. ты работал:\n\nи потом логин слетел. надо такое поправить",
              слова_владельца(экран))
        проба("работа владельца под экраном терминала видна", True, рабочее(экран))
        сводка = ("==================== ИТОГОВАЯ СВОДКА ====================\n\n"
                  "Поставлено:\n  - панель владельца: служба harness-panel\n"
                  "Осталось: надо починить упавших демонов")
        проба("БОЛЬНОЙ СЛУЧАЙ: сводка установщика задачей не считается",
              False, рабочее(сводка))
        проба("слова перед сводкой сохранены",
              "вот на этом остановился", слова_владельца("вот на этом остановился\n" + сводка))
        # БОЛЬНОЙ СЛУЧАЙ 12.10.2026: владелец переслал МОЁ сообщение со
        # словами «Я не понял» — разборщик увидел в цитате список работ и
        # завёл ТРИ задачи от моего имени, выданных за его слова. Форма строк
        # тут обычная: ни экрана, ни рамки сводки — узнать цитату можно только
        # по журналу отправок, и знание о нём приносит ЗОВУЩИЙ.
        цитата = ("Я не понял\n"
                  "Ты же ранее мне написал\n\n"
                  "Главное, чего нет НИ НА ОДНОЙ нашей странице: хлебные крошки\n"
                  "Блог брать не буду: в админке нет механизма блога\n"
                  "Пишу спеку.")
        наши = {"Главное, чего нет НИ НА ОДНОЙ нашей странице: хлебные крошки",
                "Блог брать не буду: в админке нет механизма блога",
                "Пишу спеку."}
        проба("БОЛЬНОЙ СЛУЧАЙ: цитата нашего же сообщения снята",
              "Я не понял\nТы же ранее мне написал",
              слова_владельца(цитата, наши))
        проба("БОЛЬНОЙ СЛУЧАЙ: в цитате работы нет — она не его слова",
              False, рабочее(цитата, наши))
        # Без журнала отправок судья слеп по-прежнему — и это honest: знание
        # приносит зовущий, а не второй признак внутри судьи.
        проба("без наших строк текст не трогается",
              True, "Блог брать не буду" in слова_владельца(цитата))
        # БОЛЬНОЙ СЛУЧАЙ: одна совпавшая строка — не цитата. Владелец часто
        # повторяет одну мою фразу СВОИМИ словами задания: «сделай как писал
        # про крошки». Вырезав её, мы потеряли бы саму задачу.
        # Совпасть обязана ДЛИННАЯ строка, иначе проба слепа к самому порогу:
        # короткая не опорная ни при каком его значении (поймано мутацией
        # МИН_СТРОК_ЦИТАТЫ=1 — она не покраснела ни одной пробой).
        одна = ("сделай как писал\n"
                "Блог брать не буду: в админке нет механизма блога")
        проба("одиночное совпадение цитатой не считается", одна,
              слова_владельца(одна, наши))
        # Порог ДЛИНЫ тоже обязан иметь пробу: без неё число 12 не охраняет
        # никто (поймано мутацией МИН_ДЛИНА_ЦИТАТЫ=1 — ни одной красной).
        # Короткие строки совпадают у обоих: «Да», «Готово», «Пишу спеку.».
        короткие = "Да\nПишу спеку.\nсделай крошки"
        проба("короткие совпадения опорными не считаются", короткие,
              слова_владельца(короткие, наши | {"Да"}))

        # БОЛЬНОЙ СЛУЧАЙ (ревью 14.10.2026, F-gen-04): его поручение стоит
        # ОТДЕЛЬНО от цитаты и случайно повторяет одну нашу строку. Срез по
        # всему сообщению съел бы это поручение молча; срез по блоку — нет.
        # Его строка СОВПАДАЕТ с нашей (мы писали ему это в отчёте раньше) и
        # стоит ОТДЕЛЬНО от цитаты. Срез по всему сообщению съел бы её молча.
        вне_блока = ("Главное, чего нет НИ НА ОДНОЙ нашей странице: хлебные крошки\n"
                     "Блог брать не буду: в админке нет механизма блога\n"
                     "\n"
                     "Надо переделать экран карты")
        проба("БОЛЬНОЙ СЛУЧАЙ: поручение вне блока цитаты уцелело",
              "Надо переделать экран карты",
              слова_владельца(вне_блока, наши | {"Надо переделать экран карты"}))
        проба("работа владельца вне блока цитаты видна", True,
              рабочее(вне_блока, наши | {"Надо переделать экран карты"}))

        # Здоровый случай: настоящее задание не трогается вовсе.
        задание = "Надо переделать экран карты, он не читается"
        проба("настоящее задание не тронуто", задание,
              слова_владельца(задание, наши))

        # Задача с источником в карте исхода уже имеет.
        проба("сообщение с источником в карте не висит",
              False, any(ид == "1.0" for ид, _ in без_исхода(все, 0.0, разобранные(т))))
        # БОЛЬНОЙ СЛУЧАЙ 12.09.2026: снимок с подписью. Владелец присылает
        # задачи фотографиями, а разбор читал только поле «text» — 68 из 972
        # сообщений архива пролетали мимо гейта вовсе, среди них прямое
        # указание «займись как все остальные задачи закроешь».
        положить("4.0", '{"caption": "надо переделать экран карты", "photo": [1]}', -50)
        все = очередь.сообщения(обр)
        проба("БОЛЬНОЙ СЛУЧАЙ: подпись к снимку — тоже слова владельца",
              True, any(ид == "4.0" for ид, _ in без_исхода(все, 0.0, разобранные(т))))
        # Снимок без подписи разбирать нечего — и это не беда, а пустота.
        положить("5.0", '{"photo": [1], "message_id": 7}', -40)
        все = очередь.сообщения(обр)
        проба("снимок без подписи задачей не считается",
              False, any(ид == "5.0" for ид, _ in без_исхода(все, 0.0, разобранные(т))))
        # Пометка «не задача» закрывает исход.
        пометить(т, "3.0", "не-задача")
        пометить(т, "4.0", "не-задача")
        проба("пометка «не задача» закрывает исход",
              0, проверить(т, обр, курсор))
    if плохо:
        print("САМОТЕСТ ПРОВАЛЕН")
        return 1
    print(f"САМОТЕСТ ПРОЙДЕН: {путей[0]} путей, первым — больной случай")
    return 0


