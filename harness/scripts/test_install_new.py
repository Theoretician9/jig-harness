def git_стенда(каталог: Path, *доводы: str) -> None:
    """git ВРЕМЕННОГО репозитория стенда: свои имя/почта, без чужих хуков."""
    subprocess.run(["git", "-C", str(каталог), "-c", "user.name=проба",
                    "-c", "user.email=проба@стенд", "-c", "commit.gpgsign=false",
                    "-c", f"core.hooksPath={каталог / '.нет-хуков'}", *доводы],
                   check=True, capture_output=True, text=True, timeout=60)


ГЕЙТ_ГИГИЕНЫ = КОРЕНЬ / "scripts" / "check-context-hygiene.py"
СТРОКА_СИРОТ = re.compile(r"^\[гигиена\] ✗ записи памяти нет ни в одном указателе"
                          r" \(найти их будет нечем\): (.+)$", re.M)


def сироты_гигиены(проект: Path) -> tuple:
    """Сироты по гейту гигиены на стенде; пакет машины отведён в сторону.

    Строка «память пакета: …» к проекту не относится и в разбор не идёт.
    """
    окружение = dict(os.environ, HARNESS_STARTER=str(проект.parent / "нет-пакета"))
    готово = subprocess.run([sys.executable, str(ГЕЙТ_ГИГИЕНЫ), "--repo", str(проект)],
                            capture_output=True, text=True, timeout=60, env=окружение)
    найдено = СТРОКА_СИРОТ.search(готово.stdout + готово.stderr)
    return (set(найдено.group(1).rstrip("…").split(", ")) if найдено else set(),
            готово.stdout + готово.stderr)


