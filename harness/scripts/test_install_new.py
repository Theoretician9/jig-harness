# Сбой судится в процессе пробы: io.open подменён так, что запись в каталог
# памяти под любым именем, кроме донесённой записи, роняет write() ПОСЛЕ
# открытия и половины байтов (диск полон). Так ломаются и write_bytes, и
# временный файл любого вида (mkstemp+fdopen, NamedTemporaryFile — путь int).
import errno
import io

ДОНОСИМЫЕ = {"новая-запись.md"}


class ПолДиска:
    """Файл, у которого write() пишет половину и бросает ENOSPC."""

    def __init__(self, настоящий):
        self._ф = настоящий

    def write(self, данные):
        self._ф.write(данные[:len(данные) // 2])
        self._ф.flush()
        raise OSError(errno.ENOSPC, "проба: нет места на диске")

    def __enter__(self):
        return self

    def __exit__(self, *_):
        self._ф.close()

    def __getattr__(self, имя):
        return getattr(self._ф, имя)


def с_полным_диском(память: Path, действие):
    настоящий_open = io.open

    def open_проба(путь, mode="r", *доводы, **ключи):
        ф = настоящий_open(путь, mode, *доводы, **ключи)
        пишет = any(з in mode for з in "wax+")
        своё_имя = not isinstance(путь, int) and Path(путь).parent == память \
            and Path(путь).name in ДОНОСИМЫЕ
        return ПолДиска(ф) if пишет and not своё_имя else ф

    io.open = open_проба
    try:
        действие()
        return None
    except OSError as ошибка:
        return ошибка
    finally:
        io.open = настоящий_open


