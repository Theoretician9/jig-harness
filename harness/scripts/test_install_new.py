# main(): договор вывода и --показать на уровне скрипта. Расписание, конфиг и
# метки подменены своими — проба не трогает машину.
def прогон_main(пакет: Path, проект: Path, доводы: list, конфиг: str = "") -> tuple:
    import contextlib
    import io

    class Принято:
        returncode = 0
        stdout = stderr = ""

    было_run = доустановка.subprocess.run
    было_hb = доустановка.конф_модуль.heartbeat_dir
    было_конф = доустановка.HARNESS_CONF
    было_расписание = доустановка._расписание_сейчас
    было_окружение = {к: os.environ.get(к) for к in ("HARNESS_STARTER", "PROJECT_DIR")}
    пустой_конф = проект.parent / "harness.conf"
    пустой_конф.write_text(конфиг, encoding="utf-8")
    (проект.parent / "heartbeat").mkdir(exist_ok=True)

    def run_без_машины(команда, *доводы_, **ключи_):
        if list(команда[:2]) == ["crontab", "-"]:
            return Принято()
        return было_run(команда, *доводы_, **ключи_)

    доустановка.subprocess.run = run_без_машины
    доустановка.конф_модуль.heartbeat_dir = lambda: проект.parent / "heartbeat"
    доустановка.HARNESS_CONF = str(пустой_конф)
    доустановка._расписание_сейчас = lambda: ""
    os.environ["HARNESS_STARTER"] = str(пакет)
    os.environ["PROJECT_DIR"] = str(проект)
    вывод = io.StringIO()
    try:
        # stderr в тот же вывод: отказ («пакет не прочитан») вправе идти в любой поток.
        with contextlib.redirect_stdout(вывод), contextlib.redirect_stderr(вывод):
            код = доустановка.main(доводы)
    finally:
        доустановка.subprocess.run = было_run
        доустановка.конф_модуль.heartbeat_dir = было_hb
        доустановка.HARNESS_CONF = было_конф
        доустановка._расписание_сейчас = было_расписание
        for к, з in было_окружение.items():
            if з is None:
                os.environ.pop(к, None)
            else:
                os.environ[к] = з
    return код, вывод.getvalue()


