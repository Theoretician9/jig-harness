#!/usr/bin/env python3
"""Законная дверь: удалить файл в ЗАЩИЩЁННОМ каталоге по слову владельца.

СЛУЧАЙ (27–28.09.2026). Владелец увидел в секретах снимок настроек продукта и
сказал «Удаляй». Смена не смогла: `guard_bash.py` отменяет всякое `rm` в
`SECRETS_DIR` (И-1 — данные, бэкапы и секреты из сессии не удаляются) и не
различает решение ВЛАДЕЛЬЦА от решения агента. Файл провисел сутки, а его слово
осталось неисполненным — сторож без законной двери превращается в тупик.

Дверь узкая:
  • удаляется ОДИН файл внутри SECRETS_DIR (каталоги — нет, маски — нет);
  • перед удалением делается копия в BACKUP_DIR/секреты-удалённые/ с датой:
    И-1 — «не терять данные», а не «не удалять файлы»;
  • требуется СЛОВО владельца: разрешение с названным предметом в МАШИННОМ
    журнале входящих `$LOG_DIR/inbox.jsonl` (его пишет tg-dispatcher.sh, и
    признак авторства — `message_id` телеграма), не старше срока свежести.
    Распознаватель ОДИН на все двери — `scripts/lib/owner_word.py`: своя копия
    правила здесь разъехалась бы с соседней дверью молча (ревью кода
    28.09.2026, C-1);
  • каждое удаление оставляет след в `$LOG_DIR/удаления-секретов.jsonl`: что,
    когда, по какому сообщению и куда положена копия.

Защищённых корней два: каталог секретов (SECRETS_DIR) и каталог копий
(BACKUP_DIR). Для секретов копия перед удалением обязательна; для копий её не
делают — копия копии бессмысленна, поэтому там дверь требует, чтобы файл был
старше порога (SECRET_DELETE_MIN_AGE_DAYS, по умолчанию 14) и лежал ФАЙЛОМ в
корне каталога копий, а не внутри ежесуточного каталога.

    python3 scripts/protected-delete.py <имя файла или путь>
    python3 scripts/protected-delete.py <путь> --спросить # спросить владельца и запомнить вопрос
    python3 scripts/protected-delete.py <путь> --сухо   # что будет сделано
    python3 scripts/protected-delete.py --selftest
Код возврата: 0 — удалено (или сухой прогон), 1 — слова владельца нет, 2 — путь
не годится, 77 — каталога секретов нет (мерить нечем).
"""
from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "scripts" / "lib"))
import config as конф                                      # noqa: E402
import owner_word as слово_вл                              # noqa: E402

НЕ_ПРИМЕНИМО = 77
# Копию копии не делают: в каталоге копий дверь вместо этого требует возраст —
# свежая копия может быть единственной, из которой можно встать.
МИН_ВОЗРАСТ_ДНЕЙ = int(os.environ.get("SECRET_DELETE_MIN_AGE_DAYS", "14"))
# Сколько живёт слово владельца — у БИБЛИОТЕКИ, а не у окружения: ручка
# SECRET_DELETE_FRESH_MIN в окружении вызывающего открывала дверь словом
# двухлетней давности (ревью кода 28.09.2026, C-2). Окно берётся из
# harness.conf машины, а подмена разрешена только ключом стенда.
СВЕЖЕСТЬ_МИН = слово_вл.окно_свежести()

# Разрешение = глагол удаления И названный предмет. Одного «да» мало: голое
# согласие могло относиться к выкату — ровно та дыра, которую закрыли у ворот
# выката 11.09.2026. Правило ОДНО на все двери и живёт в библиотеке: имена
# здесь — ссылки на неё, а не вторая копия, которая разойдётся молча.
ГЛАГОЛ = слово_вл.ГЛАГОЛ
ПРЕДМЕТ = слово_вл.ПРЕДМЕТ
ОТКАЗ = слово_вл.ОТКАЗ
слова_владельца = слово_вл.слова_владельца
это_разрешение = слово_вл.это_разрешение
разрешение = слово_вл.разрешение
НетНосителя = слово_вл.НетНосителя


# Журнал СВОИХ вопросов. Предмет владелец называет в ОТВЕТЕ редко: он отвечает
# коротко — «Сноси», «Если не нужны удаляй», — а файл назвал я в вопросе
# (17.10.2026, дважды за сутки). Голое согласие годится ТОЛЬКО тому файлу, о
# котором дверь спросила САМА и чей вопрос ушёл владельцу в канал; у двери
# согласия на выкат это правило стоит с 11.09.2026.
ЖУРНАЛ_ВОПРОСОВ = "удаления-спрошено.jsonl"


def спросить_владельца(пути: list[Path], логи: Path) -> int:
    """Отправить ОДИН вопрос об удалении файлов и записать его. 0 — ушёл, 1 — нет.

    Нескольких файлов нарочно: четыре вопроса подряд — это четыре сообщения
    владельцу, ровно тот шум, против которого он высказался 17.10.2026.
    Удаление при этом остаётся по одному файлу за вызов.
    """
    строки = []
    for путь in пути:
        возраст = (time.time() - путь.stat().st_mtime) / 86400
        строки.append(f"{путь} — {путь.stat().st_size} байт, правка {возраст:.0f} дн назад")
    перечень = "\n".join(строки)
    хвост = "эти файлы" if len(пути) > 1 else "этот файл"
    текст = (f"Удалить {хвост}?\n{перечень}\nОтветь «удаляй» или «не надо».")
    отправка = КОРЕНЬ / "scripts" / "tg_send.sh"
    готово = subprocess.run(["bash", str(отправка), текст],
                            capture_output=True, text=True)
    if готово.returncode != 0:
        print(f"[удаление секрета] вопрос владельцу НЕ ушёл: "
              f"{(готово.stderr or готово.stdout).strip()[:160]}")
        return 1
    логи.mkdir(parents=True, exist_ok=True)
    когда = time.time()
    with open(логи / ЖУРНАЛ_ВОПРОСОВ, "a", encoding="utf-8") as поток:
        for путь in пути:
            поток.write(json.dumps({"ts": когда, "файл": str(путь),
                                    "вопрос": текст}, ensure_ascii=False) + "\n")
    print(f"[удаление секрета] спросил владельца про {len(пути)} файл(ов) — жду его слова")
    return 0


def когда_спросили(путь: Path, логи: Path) -> float | None:
    """Когда дверь последний раз спрашивала про ЭТОТ файл; None — не спрашивала."""
    журнал = логи / ЖУРНАЛ_ВОПРОСОВ
    последний = None
    try:
        for строка in журнал.read_text(encoding="utf-8").splitlines():
            строка = строка.strip()
            if not строка:
                continue
            try:
                запись = json.loads(строка)
            except ValueError:
                continue                      # битая строка вопросом не считается
            if str(запись.get("файл")) == str(путь):
                когда = запись.get("ts")
                if isinstance(когда, (int, float)):
                    последний = max(последний or 0, float(когда))
    except OSError:
        return None
    return последний


def слово_по_своему_вопросу(путь: Path, логи: Path) -> dict | None:
    """Короткое согласие владельца, сказанное ПОСЛЕ нашего вопроса об этом файле.

    Два условия, и ни одно не лишнее: вопрос об ИМЕННО ЭТОМ файле ушёл в канал
    (иначе «да» про другое удаляло бы то, о чём владелец не слышал), и его
    слово НОВЕЕ вопроса.
    """
    спрошено = когда_спросили(путь, логи)
    if спрошено is None:
        return None
    for запись in reversed(слова_владельца(СВЕЖЕСТЬ_МИН, логи)):
        if запись["когда"] <= спрошено:
            break
        if слово_вл.это_голое_согласие(запись["текст"]):
            return запись
    return None


def живые_базы_копий() -> set[str] | None:
    """Имена баз, которые ещё снимаются в копии (ключи BACKUP_DBS).

    Три ответа, а не два: множество имён, пустое множество («список прочитан и
    пуст») и None («ПРОЧЕСТЬ НЕ УДАЛОСЬ»). Последний — отказ двери: «не смогли
    прочесть» ≠ «живых баз нет» ([[unreadable-source-turns-check-green]]).

    Значение читается ТЕМ ЖЕ способом, каким его пишут: в harness.conf ключ
    многострочный (одна строка = одна база), а построчный разбор конфига видел
    бы только первую — и все остальные базы стали бы «снятыми» (ревью кода
    28.09.2026, C-2). Поэтому здесь свой разбор значения в кавычках.
    """
    путь = Path(конф.путь_harness_conf()) if hasattr(конф, "путь_harness_conf") else None
    if путь is None:
        return None
    try:
        текст = путь.read_text(encoding="utf-8")
    except OSError:
        return None
    совпало = re.search(r'^\s*BACKUP_DBS=(?:"([^"]*)"|\'([^\']*)\'|([^\n#]*))',
                        текст, re.MULTILINE)
    if not совпало:
        return set()          # ключа нет вовсе — баз не снимают, это прочитано
    значение = next((г for г in совпало.groups() if г is not None), "")
    имена = set()
    for строка in значение.splitlines():
        строка = строка.strip()
        if строка and "=" in строка:
            имена.add(строка.split("=", 1)[0].strip())
    return имена


def каталог_копий() -> Path | None:
    значение = конф.из_файла(конф.путь_install_conf()).get("BACKUP_DIR", "") \
        or "/var/backups/harness"
    return Path(значение) if Path(значение).is_dir() else None


def каталог_секретов() -> Path | None:
    путь = конф.secrets_dir() if hasattr(конф, "secrets_dir") else None
    if not путь:
        значение = конф.из_файла(конф.путь_install_conf()).get("SECRETS_DIR", "")
        путь = значение or None
    return Path(путь) if путь and Path(путь).is_dir() else None


def цель(имя: str, секреты: Path | None,
         копии: Path | None = None,
         по_слову_владельца: bool = False) -> tuple[Path | None, str, str]:
    """(путь, вид корня, причина отказа). Вид — «секреты» или «копии».

    Два защищённых корня, и правила у них РАЗНЫЕ: у секретов перед удалением
    снимается копия, у копий — проверяется возраст. Одна функция вместо двух
    дверей: иначе вторая дверь через месяц разойдётся с первой в правилах.

    `по_слову_владельца` снимает ТОЛЬКО порог возраста. Порог защищает от
    решения АГЕНТА («вдруг эта копия единственная, из которой можно встать»);
    против прямого слова владельца с названным предметом он становится тупиком,
    а тупик обходят, не соблюдают (17.10.2026: его «Снеси копию базы» про копию
    базы уехавшего продукта, ей два дня). Всё остальное дверь судит как прежде:
    каталогом вместо файла, путём наружу, файлом внутри ежесуточной копии его
    слово не делает ничего.
    """
    if not имя or имя.startswith("-"):
        return None, "", "не назван файл"
    корни = [(секреты, "секреты"), (копии, "копии")]
    путь = Path(имя) if "/" in имя else None
    if путь is None:
        for корень, вид in корни:
            if корень and (корень / имя).exists():
                путь = корень / имя
                break
        if путь is None:
            return None, "", f"файла «{имя}» нет ни в секретах, ни в копиях"
    try:
        путь = путь.resolve()
    except (OSError, ValueError):
        return None, "", f"путь не разобран: {имя}"
    вид = ""
    for корень, имя_корня in корни:
        try:
            if корень and путь.is_relative_to(корень.resolve()):
                вид = имя_корня
                break
        except (OSError, ValueError):
            continue
    if not вид:
        return None, "", f"{путь} вне защищённых каталогов — эта дверь только для них"
    if путь.is_dir():
        return None, вид, f"{путь} — каталог: дверь удаляет ОДИН файл, не дерево"
    if not путь.exists():
        return None, вид, f"{путь} не существует"
    if вид == "копии":
        корень_копий = копии.resolve() if копии else None
        # Слепок, снятый ЭТОЙ ЖЕ дверью при удалении секрета. Порог возраста на
        # него не распространяется: он защищает «свежая копия может быть
        # единственной», а здесь оригинал уже удалён по слову владельца, и
        # слепок — след того удаления, а не источник восстановления. Случай
        # 28.09.2026: владелец велел убрать продукт с машины целиком и получил
        # ключ подписи себе в канал, а его слепки оставались на сервере, и
        # убрать их было нечем.
        свой_слепок = путь.parent.name == "секреты-удалённые" and (
            корень_копий is not None and путь.parent.parent.resolve() == корень_копий)
        # Файл ФАЙЛОМ в корне каталога копий: внутри ежесуточных каталогов лежат
        # рабочие копии, и открывать к ним дверь нельзя.
        # Дамп базы, которую больше не снимают: имя базы взято из BACKUP_DBS,
        # а не из имени продукта — вшитое имя увело бы правило на чужой
        # установке. Сирота внутри ежесуточной копии балласт: восстанавливать
        # ею нечего, а копию харнеса она не составляет.
        сирота = False
        совпало_дамп = re.fullmatch(r"db-(.+)\.dump", путь.name)
        if совпало_дамп and корень_копий is not None \
                and путь.parent.parent.resolve() == корень_копий:
            живые = живые_базы_копий()
            # None — список прочесть не удалось. Тогда дверь НЕ открывается:
            # иначе нечитаемый конфиг делал бы сиротой любой дамп, включая
            # единственную свежую копию рабочей базы.
            сирота = живые is not None and совпало_дамп.group(1) not in живые
        if not свой_слепок and not сирота and путь.parent.resolve() != корень_копий:
            return None, вид, (f"{путь} лежит внутри каталога копий — дверь открыта "
                               "только для отдельных файлов в его корне и для "
                               "слепков удалённых секретов")
        возраст_дней = (time.time() - путь.stat().st_mtime) / 86400
        if (not свой_слепок and not сирота and not по_слову_владельца
                and возраст_дней < МИН_ВОЗРАСТ_ДНЕЙ):
            return None, вид, (f"{путь.name} моложе {МИН_ВОЗРАСТ_ДНЕЙ} дн "
                               f"({возраст_дней:.0f}) — свежая копия может быть "
                               "единственной, из которой можно встать")
    return путь, вид, ""


def копия_перед_удалением(файл: Path, куда: Path) -> Path:
    """Копия с отметкой времени. И-1 — «не терять», а не «не удалять»."""
    куда.mkdir(parents=True, exist_ok=True)
    имя = f"{файл.name}.{time.strftime('%Y%m%d-%H%M%S')}"
    цель_копии = куда / имя
    shutil.copy2(файл, цель_копии)
    os.chmod(цель_копии, 0o600)
    return цель_копии


def след(запись: dict, каталог_логов: Path) -> None:
    журнал = каталог_логов / "удаления-секретов.jsonl"
    try:
        with open(журнал, "a", encoding="utf-8") as fh:
            fh.write(json.dumps(запись, ensure_ascii=False) + "\n")
    except OSError:
        pass                     # след важен, но не важнее самого действия


def селфтест_со_стендом() -> int:
    # Самотест сам подменяет LOG_DIR, а дверь подмены открыта только ключом стенда.
    ключ = слово_вл.КЛЮЧ_СТЕНДА
    было = os.environ.get(ключ)
    os.environ[ключ] = "1"
    try:
        return селфтест()
    finally:
        if было is None:
            os.environ.pop(ключ, None)
        else:
            os.environ[ключ] = было


def главная(аргументы: list[str]) -> int:
    if аргументы[:1] == ["--selftest"]:
        return селфтест_со_стендом()
    сухо = "--сухо" in аргументы
    спросить = "--спросить" in аргументы
    имена = [а for а in аргументы if not а.startswith("-")]
    секреты = каталог_секретов()
    if секреты is None:
        print("[удаление секрета] НЕ ПРИМЕНИМО: каталога секретов нет")
        return НЕ_ПРИМЕНИМО
    if len(имена) != 1 and not спросить:
        print("[удаление секрета] нужен ОДИН файл: "
              "python3 scripts/secret-delete.py <имя в секретах>")
        return 2
    if not имена:
        print("[удаление секрета] назови файл(ы), о которых спросить владельца")
        return 2
    логи = Path(конф.log_dir())
    # Слово владельца ищется ДО разбора цели: от него зависит, снимается ли
    # порог возраста у свежей копии (17.10.2026 — его «Снеси копию базы»).
    # Три исхода, а не два. «Журнал входящих прочитать не смогли» — это ОТКАЗ
    # двери, а не «владелец промолчал»: молчащий носитель и молчащий владелец
    # выглядят одинаково только для того, кто их не различает
    # ([[unreadable-source-turns-check-green]]).
    try:
        слово = разрешение(СВЕЖЕСТЬ_МИН, логи)
    except НетНосителя as беда:
        print(f"[удаление секрета] ОТКАЗ: слово владельца ПРОЧИТАТЬ НЕ СМОГЛИ — "
              f"дверь закрыта: {беда}")
        return 1
    путь, вид, беда = цель(имена[0], секреты, каталог_копий(),
                           по_слову_владельца=bool(слово) or спросить)
    if путь is None:
        print(f"[удаление секрета] ОТКАЗ: {беда}")
        return 2
    if спросить:
        цели = []
        for имя in имена:
            п, _вид, беда_ц = цель(имя, секреты, каталог_копий(), по_слову_владельца=True)
            if п is None:
                print(f"[удаление секрета] ОТКАЗ: {беда_ц}")
                return 2
            цели.append(п)
        return спросить_владельца(цели, логи)
    # Короткое слово владельца («Сноси», «Если не нужны удаляй») годится, когда
    # предмет назван в НАШЕМ вопросе и вопрос ушёл в канал раньше ответа.
    if not слово:
        слово = слово_по_своему_вопросу(путь, логи)
        if слово:
            print(f"[удаление секрета] слово короткое — «{слово['текст'][:60]}», "
                  f"предмет взят из моего вопроса об этом файле")
