#!/usr/bin/env python3
"""Законная дверь: удалить файл в ЗАЩИЩЁННОМ каталоге по слову владельца.

СЛУЧАЙ (27–28.09.2026). Владелец увидел в секретах снимок настроек продукта и
сказал «Удаляй». Смена не смогла: `guard_bash.py` отменяет всякое `rm` в
`SECRETS_DIR` (И-1 — данные, бэкапы и секреты из сессии не удаляются) и не
различает решение ВЛАДЕЛЬЦА от решения агента. Файл провисел сутки, а его слово
осталось неисполненным — сторож без законной двери превращается в тупик.

Дверь узкая:
  • удаляется ОДИН файл внутри SECRETS_DIR (каталоги — нет, маски — нет);
  • перед удалением делается копия в BACKUP_DIR/секреты-удалённые/ с датой:
    И-1 — «не терять данные», а не «не удалять файлы»;
  • требуется СЛОВО владельца: разрешение с названным предметом в его входящих
    (`$LOG_DIR/inbox`, включая обработанные) либо запись в confirmations.jsonj —
    не старше срока свежести;
  • каждое удаление оставляет след в `$LOG_DIR/удаления-секретов.jsonl`: что,
    когда, по какому сообщению и куда положена копия.

Защищённых корней два: каталог секретов (SECRETS_DIR) и каталог копий
(BACKUP_DIR). Для секретов копия перед удалением обязательна; для копий её не
делают — копия копии бессмысленна, поэтому там дверь требует, чтобы файл был
старше порога (SECRET_DELETE_MIN_AGE_DAYS, по умолчанию 14) и лежал ФАЙЛОМ в
корне каталога копий, а не внутри ежесуточного каталога.

    python3 scripts/protected-delete.py <имя файла или путь>
    python3 scripts/protected-delete.py <путь> --сухо   # что будет сделано
    python3 scripts/protected-delete.py --selftest
Код возврата: 0 — удалено (или сухой прогон), 1 — слова владельца нет, 2 — путь
не годится, 77 — каталога секретов нет (мерить нечем).
"""
from __future__ import annotations

import json
import os
import re
import shutil
import sys
import time
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "scripts" / "lib"))
import config as конф                                      # noqa: E402

НЕ_ПРИМЕНИМО = 77
# Копию копии не делают: в каталоге копий дверь вместо этого требует возраст —
# свежая копия может быть единственной, из которой можно встать.
МИН_ВОЗРАСТ_ДНЕЙ = int(os.environ.get("SECRET_DELETE_MIN_AGE_DAYS", "14"))
# Сколько живёт слово владельца. Час — как у согласия на выкат: разрешение,
# данное вчера, относилось к другому файлу и другому разговору.
СВЕЖЕСТЬ_МИН = int(os.environ.get("SECRET_DELETE_FRESH_MIN", "60"))

# Разрешение = глагол удаления И названный предмет. Одного «да» мало: голое
# согласие могло относиться к выкату — ровно та дыра, которую закрыли у ворот
# выката 11.09.2026.
ГЛАГОЛ = re.compile(r"удал|снеси|убер|вычист|мусор")
ПРЕДМЕТ = re.compile(r"секрет|токен|снимок|файл|env|bak|мусор")
ОТКАЗ = re.compile(r"\b(не|нет|стоп|погоди|подожди|позже|рано)\b")


def каталог_копий() -> Path | None:
    значение = конф.из_файла(конф.путь_install_conf()).get("BACKUP_DIR", "") \
        or "/var/backups/harness"
    return Path(значение) if Path(значение).is_dir() else None


def каталог_секретов() -> Path | None:
    путь = конф.secrets_dir() if hasattr(конф, "secrets_dir") else None
    if not путь:
        значение = конф.из_файла(конф.путь_install_conf()).get("SECRETS_DIR", "")
        путь = значение or None
    return Path(путь) if путь and Path(путь).is_dir() else None


def слова_владельца(окно_мин: int, каталог_логов: Path) -> list[dict]:
    """Его сообщения за последние N минут — из очереди и из обработанных.

    Первичный источник — файлы очереди, а не журнал согласий: распознаватель
    диспетчера знает формы про выкат и push, и «Удаляй» в согласия не попадает
    (та же причина, что у согласования спеки).
    """
    найдено = []
    порог = time.time() - окно_мин * 60
    for подкаталог in (каталог_логов / "inbox", каталог_логов / "inbox" / "обработано"):
        try:
            файлы = sorted(подкаталог.glob("*.txt"))
        except OSError:
            continue
        for файл in файлы:
            try:
                когда = файл.stat().st_mtime
                текст = файл.read_text(encoding="utf-8", errors="replace").strip()
            except OSError:
                continue
            if текст and когда >= порог:
                найдено.append({"когда": когда, "текст": текст, "файл": файл.name})
    найдено.sort(key=lambda з: з["когда"])
    return найдено


def это_разрешение(текст: str) -> bool:
    """Слова владельца означают «удали этот файл»?"""
    строка = " ".join(текст.lower().split())
    if not строка:
        return False
    # Отказ где-либо в сообщении отменяет разрешение целиком: «не удаляй пока».
    if ОТКАЗ.search(f" {строка} ") and not re.search(r"если.*уверен", строка):
        return False
    return bool(ГЛАГОЛ.search(строка) and ПРЕДМЕТ.search(строка))


def разрешение(окно_мин: int, каталог_логов: Path) -> dict | None:
    for запись in reversed(слова_владельца(окно_мин, каталог_логов)):
        if это_разрешение(запись["текст"]):
            return запись
    return None


def цель(имя: str, секреты: Path | None,
         копии: Path | None = None) -> tuple[Path | None, str, str]:
    """(путь, вид корня, причина отказа). Вид — «секреты» или «копии».

    Два защищённых корня, и правила у них РАЗНЫЕ: у секретов перед удалением
    снимается копия, у копий — проверяется возраст. Одна функция вместо двух
    дверей: иначе вторая дверь через месяц разойдётся с первой в правилах.
    """
    if not имя or имя.startswith("-"):
        return None, "", "не назван файл"
    корни = [(секреты, "секреты"), (копии, "копии")]
    путь = Path(имя) if "/" in имя else None
    if путь is None:
        for корень, вид in корни:
            if корень and (корень / имя).exists():
                путь = корень / имя
                break
        if путь is None:
            return None, "", f"файла «{имя}» нет ни в секретах, ни в копиях"
    try:
        путь = путь.resolve()
    except (OSError, ValueError):
        return None, "", f"путь не разобран: {имя}"
    вид = ""
    for корень, имя_корня in корни:
        try:
            if корень and путь.is_relative_to(корень.resolve()):
                вид = имя_корня
                break
        except (OSError, ValueError):
            continue
    if not вид:
        return None, "", f"{путь} вне защищённых каталогов — эта дверь только для них"
    if путь.is_dir():
        return None, вид, f"{путь} — каталог: дверь удаляет ОДИН файл, не дерево"
    if not путь.exists():
        return None, вид, f"{путь} не существует"
    if вид == "копии":
        # Файл ФАЙЛОМ в корне каталога копий: внутри ежесуточных каталогов лежат
        # рабочие копии, и открывать к ним дверь нельзя.
        if путь.parent.resolve() != (копии.resolve() if копии else None):
            return None, вид, (f"{путь} лежит внутри каталога копий — дверь открыта "
                               "только для отдельных файлов в его корне")
        возраст_дней = (time.time() - путь.stat().st_mtime) / 86400
        if возраст_дней < МИН_ВОЗРАСТ_ДНЕЙ:
            return None, вид, (f"{путь.name} моложе {МИН_ВОЗРАСТ_ДНЕЙ} дн "
                               f"({возраст_дней:.0f}) — свежая копия может быть "
                               "единственной, из которой можно встать")
    return путь, вид, ""


def копия_перед_удалением(файл: Path, куда: Path) -> Path:
    """Копия с отметкой времени. И-1 — «не терять», а не «не удалять»."""
    куда.mkdir(parents=True, exist_ok=True)
    имя = f"{файл.name}.{time.strftime('%Y%m%d-%H%M%S')}"
    цель_копии = куда / имя
    shutil.copy2(файл, цель_копии)
    os.chmod(цель_копии, 0o600)
    return цель_копии


def след(запись: dict, каталог_логов: Path) -> None:
    журнал = каталог_логов / "удаления-секретов.jsonl"
    try:
        with open(журнал, "a", encoding="utf-8") as fh:
            fh.write(json.dumps(запись, ensure_ascii=False) + "\n")
    except OSError:
        pass                     # след важен, но не важнее самого действия


def главная(аргументы: list[str]) -> int:
    if аргументы[:1] == ["--selftest"]:
        return селфтест()
    сухо = "--сухо" in аргументы
    имена = [а for а in аргументы if not а.startswith("-")]
    секреты = каталог_секретов()
    if секреты is None:
        print("[удаление секрета] НЕ ПРИМЕНИМО: каталога секретов нет")
        return НЕ_ПРИМЕНИМО
    if len(имена) != 1:
        print("[удаление секрета] нужен ОДИН файл: "
              "python3 scripts/secret-delete.py <имя в секретах>")
        return 2
    путь, вид, беда = цель(имена[0], секреты, каталог_копий())
    if путь is None:
        print(f"[удаление секрета] ОТКАЗ: {беда}")
        return 2
    логи = Path(конф.log_dir())
    слово = разрешение(СВЕЖЕСТЬ_МИН, логи)
    if not слово:
        print(f"[удаление секрета] ОТКАЗ: слова владельца за последние "
              f"{СВЕЖЕСТЬ_МИН} мин нет.\n"
              "  Спроси его в канале, назвав ФАЙЛ, и повтори после ответа —\n"
              "  разрешением считается слово об удалении с названным предметом.")
        return 1
    копия = конф.из_файла(конф.путь_install_conf()).get("BACKUP_DIR", "") \
        or "/var/backups/harness"
    куда = Path(копия) / "секреты-удалённые"
    if сухо:
        куда_текст = f"копия ушла бы в {куда}" if вид == "секреты" \
            else f"копии не делаю: это сам каталог копий, файл старше {МИН_ВОЗРАСТ_ДНЕЙ} дн"
        print(f"[удаление секрета] сухо: удалил бы {путь} ({вид}), {куда_текст}, "
              f"слово владельца — «{слово['текст'][:60]}» ({слово['файл']})")
        return 0
    сохранённая = копия_перед_удалением(путь, куда) if вид == "секреты" else None
    путь.unlink()
    след({"ts": time.strftime("%Y-%m-%dT%H:%M:%S%z"), "файл": str(путь),
          "вид": вид, "копия": str(сохранённая) if сохранённая else "",
          "слово": слово["текст"][:200], "источник": слово["файл"]}, логи)
    print(f"[удаление секрета] удалён {путь} ({вид}); "
          f"{'копия — ' + str(сохранённая) if сохранённая else 'копии нет: это каталог копий'}; "
          f"по слову владельца из {слово['файл']}")
    return 0


def селфтест() -> int:
    import tempfile
    ok = True
    путей = 0

    def проба(условие: bool, имя: str) -> None:
        nonlocal ok, путей
        путей += 1
        print(f"  {'ок   ' if условие else 'ПЛОХО'} {имя}")
        if not условие:
            ok = False

    # БОЛЬНОЙ СЛУЧАЙ: голое «да» — не разрешение на удаление секрета.
    проба(not это_разрешение("да"), "БОЛЬНОЙ СЛУЧАЙ: голое «да» разрешением не считается")
    проба(это_разрешение("Удаляй этот снимок из секретов"),
          "глагол с названным предметом — разрешение")
    проба(это_разрешение("Если ты точно уверен что это мусор, то удаляй"),
          "его живые слова 28.09 («если уверен — удаляй») — разрешение")
    проба(not это_разрешение("не удаляй пока этот файл"),
          "отказ в том же сообщении отменяет разрешение")
    проба(not это_разрешение("удали ветку в гите"),
          "удаление БЕЗ предмета из нашего списка — не разрешение")

    with tempfile.TemporaryDirectory() as врем:
        двор = Path(врем)
        секреты = двор / "secrets"
        секреты.mkdir()
        (секреты / "мусор.bak").write_text("старьё", encoding="utf-8")
        (секреты / "живой_токен").write_text("111:aaa", encoding="utf-8")
        (секреты / "подкаталог").mkdir()

        копии = двор / "backups"
        копии.mkdir()
        (копии / "старая.dump").write_text("x", encoding="utf-8")
        (копии / "свежая.dump").write_text("y", encoding="utf-8")
        сутки = копии / "2026-09-27_0400"
        сутки.mkdir()
        (сутки / "db.dump").write_text("z", encoding="utf-8")
        давно = time.time() - 40 * 86400
        import os as _os
        _os.utime(копии / "старая.dump", (давно, давно))
        # Файл внутри ежесуточного каталога делается СТАРЫМ нарочно. Молодой
        # отвергался порогом возраста, и проба каталога проходила по ЧУЖОЙ
        # причине: мутация «убрать проверку каталога» оставляла самотест
        # зелёным — дыра мутационной пробы 28.09.2026.
        _os.utime(сутки / "db.dump", (давно, давно))

        путь, вид, беда = цель("мусор.bak", секреты, копии)
        проба(путь is not None and вид == "секреты", "файл внутри секретов принят")
        проба(цель("подкаталог", секреты, копии)[0] is None, "каталог отвергнут")
        проба(цель("../наружу", секреты, копии)[0] is None,
              "БОЛЬНОЙ СЛУЧАЙ: путь наружу из защищённых каталогов отвергнут")
        проба(цель("нет-такого", секреты, копии)[0] is None, "несуществующий файл отвергнут")
        путь_к, вид_к, _ = цель("старая.dump", секреты, копии)
        проба(путь_к is not None and вид_к == "копии",
              "старый файл в корне каталога копий принят")
        проба(цель("свежая.dump", секреты, копии)[0] is None,
              f"БОЛЬНОЙ СЛУЧАЙ: копия моложе {МИН_ВОЗРАСТ_ДНЕЙ} дн не удаляется")
        путь_с, _вид_с, беда_с = цель(str(сутки / "db.dump"), секреты, копии)
        проба(путь_с is None and "внутри каталога копий" in беда_с,
              "файл ВНУТРИ ежесуточного каталога копий дверь не открывает — "
              "и отказывает ИМЕННО поэтому, а не по возрасту")

        # Копия делается ДО удаления и с правами 600.
        куда = двор / "backup" / "секреты-удалённые"
        копия = копия_перед_удалением(секреты / "мусор.bak", куда)
        проба(копия.exists() and копия.read_text(encoding="utf-8") == "старьё",
              "копия снята до удаления и содержит то же")
        проба(oct(копия.stat().st_mode)[-3:] == "600",
              "копия закрыта от чужих (600)")

        # Слово владельца ищется в очереди и в обработанных, и только свежее.
        логи = двор / "log"
        (логи / "inbox" / "обработано").mkdir(parents=True)
        свежее = логи / "inbox" / "обработано" / "1790000000.txt"
        свежее.write_text("Если ты точно уверен что это мусор, то удаляй",
                          encoding="utf-8")
        проба(разрешение(60, логи) is not None,
              "свежее слово из обработанных найдено")
        старо = time.time() - 3 * 3600
        os.utime(свежее, (старо, старо))
        проба(разрешение(60, логи) is None,
              "БОЛЬНОЙ СЛУЧАЙ: слово трёхчасовой давности не считается свежим")
        проба(разрешение(60 * 24, логи) is not None,
              "с большим окном то же слово снова годится — окно решает, не текст")

    print(f"SELFTEST: {'зелёный' if ok else 'КРАСНЫЙ'} ({путей} путей, "
          "первым — больной случай «голое да не разрешение»)")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(главная(sys.argv[1:]))
