#!/usr/bin/env python3
"""Пробы заметок релиза простым языком (слово владельца 24.10.2026: «в релизы
харнеса писать человеческим языком что было исправлено добавлено в новой версии»).

Судится два носителя: lib/release_notes.py (разбор и суд) и скрипт
check-release-notes.py (то, что зовёт публикация). Каждый случай СОЗДАЁТ своё
условие: свой каталог сборки с git-историей, своё содержимое заметок.

Прогон:  python3 scripts/test_release_notes.py
Код возврата: 0 — все пути прошли, 1 — есть упавший.
"""
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "scripts" / "lib"))
СКРИПТ = КОРЕНЬ / "scripts" / "check-release-notes.py"
ИМЯ = "ЧТО-НОВОГО.md"
ПРЕФИКС = "proba-zametki-"

путей = неудач = 0


def итог(условие: bool, текст: str) -> None:
    global путей, неудач
    путей += 1
    if not условие:
        неудач += 1
    print(("ок  · " if условие else "ПЛОХО · ") + текст)


def стенды() -> list[Path]:
    return sorted(Path(tempfile.gettempdir()).glob(ПРЕФИКС + "*"))


def убрать_стенды() -> int:
    """Убрать каталоги стендов по префиксу; вернуть число убранных.
    Симлинк и чужой каталог не трогаются: префикс в общем /tmp может занять другой."""
    убрано = 0
    не_убрано: list[str] = []
    for путь in стенды():
        if путь.is_symlink() or not путь.is_dir() or путь.stat().st_uid != os.getuid():
            continue
        try:
            shutil.rmtree(путь)
            убрано += 1
        except OSError as ошибка:
            не_убрано.append(f"{путь.name}: {ошибка}")
    if не_убрано:
        print(f"стенды: не убрано {len(не_убрано)} — " + "; ".join(не_убрано))
    return убрано


# 0. Стенд, брошенный прошлым прогоном (SIGKILL мимо уборки), убирается ДО работы.
# Зелен на поломке? «убирать только свои за этот прогон» — нет: подложенный каталог чужой;
# «уборка в конце, а не в начале» — нет: судится сразу после уборки начала.
брошенный = Path(tempfile.mkdtemp(prefix=ПРЕФИКС))
(брошенный / "след").write_text("x\n", encoding="utf-8")
убрано = убрать_стенды()
итог(not брошенный.exists() and убрано >= 1,
     f"стенды: брошенный прошлым прогоном {брошенный.name} убран до работы (убрано {убрано})")


def запись(дата="2026-10-24", название="Опись раскладки", исправлено="- Сессия больше не обрывается из-за нехватки памяти.",
           добавлено="- Харнес помнит, что положил в проект, и может убрать лишнее.",
           для_вас="- После обновления вам придёт вопрос, убирать ли старые файлы. Ответьте «да» или «нет».") -> str:
    return (f"## {дата} — {название}\n\n### Исправлено\n\n{исправлено}\n\n"
            f"### Добавлено\n\n{добавлено}\n\n### Что изменилось для вас\n\n{для_вас}\n")


ШАПКА = "# Что нового\n\nКоротко и простыми словами.\n\n"


def сборка(текст: str | None, опубликовано: str | None = None) -> Path:
    """Каталог сборки с историей: в HEAD лежит `опубликовано`, на диске — `текст`."""
    каталог = Path(tempfile.mkdtemp(prefix="proba-zametki-"))
    гит = ["git", "-C", str(каталог), "-c", "user.name=t", "-c", "user.email=t@t"]
    subprocess.run(["git", "init", "-q", "-b", "master", str(каталог)], check=True)
    (каталог / "README.md").write_text("x\n", encoding="utf-8")
    if опубликовано is not None:
        (каталог / ИМЯ).write_text(опубликовано, encoding="utf-8")
    subprocess.run([*гит, "add", "-A"], check=True)
    subprocess.run([*гит, "commit", "-qm", "прошлый"], check=True)
    if текст is not None:
        (каталог / ИМЯ).write_text(текст, encoding="utf-8")
    return каталог


def судить(каталог: Path) -> tuple[int, str]:
    готово = subprocess.run([sys.executable, str(СКРИПТ), str(каталог)],
                            capture_output=True, text=True, timeout=60)
    return готово.returncode, готово.stdout + готово.stderr


# 1. Здоровая запись, публикаций раньше не было — проходит.
код, вывод = судить(сборка(ШАПКА + запись()))
итог(код == 0, f"здоровая запись проходит (код {код}: {вывод.strip()[:80]})")

# 2. Файла заметок нет — отказ словом «нет файла».
код, вывод = судить(сборка(None))
итог(код == 1 and "нет файла" in вывод, f"нет файла заметок — отказ (код {код})")

# 3. Верхняя запись уже вышла в прошлом релизе — отказ: новой записи нет.
старое = ШАПКА + запись()
код, вывод = судить(сборка(старое, опубликовано=старое))
итог(код == 1 and "уже выходила" in вывод, f"запись прошлого релиза — отказ (код {код})")

# 4. Новая запись над старой — проходит, судится только верхняя.
код, вывод = судить(сборка(ШАПКА + запись(дата="2026-11-01", название="Другое") + "\n" + запись(), опубликовано=старое))
итог(код == 0, f"новая запись над прошлой проходит (код {код}: {вывод.strip()[:80]})")

# 5. Нет раздела «Что изменилось для вас».
без = (ШАПКА + "## 2026-10-24 — Х\n\n### Исправлено\n\n- Починили вход.\n")
код, вывод = судить(сборка(без))
итог(код == 1 and "Что изменилось для вас" in вывод, f"нет раздела для владельца — отказ (код {код})")

# 6. Раздел без строк.
код, вывод = судить(сборка(ШАПКА + запись(для_вас="")))
итог(код == 1 and "пуст" in вывод, f"пустой раздел — отказ (код {код})")

# 7. Ни «Исправлено», ни «Добавлено» не заполнено.
код, вывод = судить(сборка(ШАПКА + запись(исправлено="", добавлено="")))
итог(код == 1, f"нечего сказать об исправленном и добавленном — отказ (код {код})")

# 8. Жаргон: каждый из примеров ОБЯЗАН покраснить своим словом.
for плохое, слово in [
    ("- Правка номер adef4acd.", "adef4acd"),
    ("- Карточка hr.layout-manifest-removes-stale закрыта.", "hr.layout"),
    ("- Поправили scripts/update.py.", "update.py"),
    ("- Гейт теперь строже.", "гейт"),
    ("- Демон перезапускается.", "демон"),
    ("- Сделали рефакторинг.", "рефакторинг"),
]:
    код, вывод = судить(сборка(ШАПКА + запись(исправлено=плохое)))
    итог(код == 1 and слово.lower() in вывод.lower(), f"жаргон «{слово}» — отказ (код {код})")

# 9. Следы продукта — не дело этой проверки, но и не пропуск: слово не ловим,
#    поэтому здесь только убеждаемся, что обычный русский текст с цифрами проходит.
код, вывод = судить(сборка(ШАПКА + запись(исправлено="- Лимит сообщения теперь 900 знаков, а не 700.")))
итог(код == 0, f"обычные числа не жаргон (код {код}: {вывод.strip()[:80]})")

# 10. Краткая выдержка для сообщения «Харнес обновлён».
import release_notes as заметки  # noqa: E402

текст = ШАПКА + запись()
итог(заметки.кратко(текст).startswith("После обновления вам придёт вопрос"),
     "кратко: первая строка раздела «Что изменилось для вас» без маркера")
итог(заметки.кратко("") == "" and заметки.кратко("# Пусто\n") == "",
     "кратко: нет записи — пустая строка, а не выдумка")
длинное = ШАПКА + запись(для_вас="- " + "слово " * 200)
итог(0 < len(заметки.кратко(длинное)) <= заметки.КРАТКО_МАКС,
     f"кратко: длинная строка обрезана до {заметки.КРАТКО_МАКС} знаков ({len(заметки.кратко(длинное))})")
итог(заметки.кратко(ШАПКА + запись(для_вас="- Гейт стал строже.")) == "",
     "кратко: жаргонная строка в сообщение не идёт")

# 11. Свои стенды убраны в конце: каталогов с префиксом не осталось.
# Зелен на поломке? «убрать в /tmp, когда TMPDIR другой» — нет: и стенд, и счёт идут через
# tempfile.gettempdir(); «убрать без счёта» — нет: судится остаток на диске, не возврат.
до_уборки = len(стенды())
убрать_стенды()
осталось = стенды()
итог(до_уборки > 0 and not осталось,
     f"стенды: в конце убраны все {до_уборки}, осталось {len(осталось)}")

print(f"\nпутей {путей}, упавших {неудач}")
sys.exit(1 if неудач else 0)
