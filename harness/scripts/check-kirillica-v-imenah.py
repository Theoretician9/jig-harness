#!/usr/bin/env python3
"""Гейт: кириллическое имя переменной в bash-скрипте.

Почему отдельный гейт, когда правило уже держит `guard_bash.py`: сторож видит
КОМАНДЫ, которые агент набирает в оболочке, а файл пишется редактором — мимо
него. 09.09.2026 это стоило двух падений подряд в один вечер, и во второй раз
bash напечатал в сообщение об ошибке САМО ЗНАЧЕНИЕ — строку подключения к базе
вместе с паролем. Разница между путями и есть дыра: правило одно, а перекрыт
был только один путь из двух.

Правило берётся из guard_bash (`КИРИЛЛИЦА_В_ИМЕНИ`), а не переписывается:
два экземпляра одного правила разъезжаются молча.

Читает список staged-файлов со stdin (как прочие гейты pre-commit) либо
проверяет файлы, названные аргументами. Самотест — `--selftest`.
"""
from __future__ import annotations

import importlib.util
import re
import subprocess
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent


_ЦЕЛИКОМ_КОММЕНТАРИЙ = re.compile(r"^\s*#")
# Маркер heredoc — тот же, что у сторожа; здесь тело ГАСИТСЯ пустыми строками,
# а не вырезается: гейт называет номер строки, и нумерация обязана уцелеть.
_HEREDOC = re.compile(r"<<-?\s*[\"']?([A-Za-zА-Яа-яЁё_][A-Za-zА-Яа-яЁё0-9_]*)")


def _тела_heredoc_погашены(текст: str) -> list[str]:
    строки, ждём = [], None
    for строка in текст.splitlines():
        if ждём is None:
            строки.append(строка)
            найден = _HEREDOC.search(строка)
            if найден:
                ждём = найден.group(1)
        else:
            строки.append("")
            if строка.strip() == ждём:
                ждём = None
    return строки


def _кавычки_погашены(строки: list[str]) -> list[str]:
    """Содержимое кавычек → пробелы, СКВОЗЬ переводы строк.

    Построчного разбора мало: `python3 -c '…'` держит литерал открытым десяток
    строк, и питон внутри выглядел как bash с русскими именами (замер
    09.09.2026: session-warden.sh:275). Строка-комментарий целиком гасится и
    состояния кавычек не меняет — апостроф в русском тексте иначе открыл бы
    литерал до конца файла.
    """
    итог, кавычка = [], None
    for строка in строки:
        if кавычка is None and _ЦЕЛИКОМ_КОММЕНТАРИЙ.match(строка):
            итог.append("")
            continue
        буфер = []
        for символ in строка:
            if кавычка is None:
                буфер.append(символ)
                if символ in "\"'":
                    кавычка = символ
            else:
                буфер.append(символ if символ == кавычка else " ")
                if символ == кавычка:
                    кавычка = None
        итог.append("".join(буфер))
    return итог


def _сторож():
    """Модуль сторожа команд — единственный экземпляр правила и разбора heredoc."""
    путь = КОРЕНЬ / "hooks" / "guard_bash.py"
    спец = importlib.util.spec_from_file_location("guard_bash_правило", путь)
    модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(модуль)
    return модуль


def _правило():
    """Функция сторожа, знающая ОБА пути: присваивание и объявление."""
    return _сторож().имя_кириллицей


def беды_в_тексте(текст: str, правило) -> list[tuple[int, str]]:
    """Строки с кириллическим именем переменной: (номер, имя).

    Тела heredoc и содержимое кавычек не рассматриваются: в первых лежит не
    bash (питон с русскими именами законен), во вторых — текст сообщений.
    Замер 09.09.2026 по всем скриптам репозитория: без этого правило дало
    четыре находки, и все четыре — ложные (два питоновских heredoc и два
    текста вида «(гейты=$N)»). Гейт, кричащий на здоровый код, гасят, а не
    чинят.
    """
    беды = []
    строки = _кавычки_погашены(_тела_heredoc_погашены(текст))
    for номер, строка in enumerate(строки, 1):
        m = правило(строка.split("#", 1)[0])
        if m:
            беды.append((номер, m.group(1)))
    return беды


def _staged(путь: str) -> str:
    """Содержимое ИНДЕКСА, а не рабочего дерева: коммитится оно."""
    out = subprocess.run(["git", "show", f":{путь}"], capture_output=True)
    return out.stdout.decode("utf-8", "replace") if out.returncode == 0 else ""


def проверить(пути: list[str], из_индекса: bool) -> int:
    правило = _правило()
    всего = 0
    for путь in пути:
        if not путь.endswith(".sh"):
            continue
        текст = _staged(путь) if из_индекса else Path(путь).read_text(
            encoding="utf-8", errors="replace")
        for номер, имя in беды_в_тексте(текст, правило):
            print(f"{путь}:{номер}: имя переменной кириллицей — «{имя}»")
            всего += 1
    if всего:
        print(f"\n[кириллица] {всего} имён(и) переменных кириллицей в bash.")
        print("Bash такие идентификаторы НЕ берёт и печатает в ошибку САМО")
        print("ЗНАЧЕНИЕ — 09.09.2026 так утёк пароль тестовой базы в лог.")
        print("Переименовать латиницей; кириллица законна в тексте и комментариях.")
        return 1
    print("[кириллица] имена переменных в bash латиницей")
    return 0


def _selftest() -> int:
    правило = _правило()
    плохо = 0

    def проба(имя: str, ждём: int, текст: str) -> None:
        nonlocal плохо
        было = len(беды_в_тексте(текст, правило))
        if было == ждём:
            print(f"  ок    {имя}")
        else:
            print(f"  ПЛОХО {имя}: ждали {ждём}, нашли {было}")
            плохо = 1

    # БОЛЬНОЙ СЛУЧАЙ 09.09.2026: ровно эта строка напечатала пароль в лог.
    проба("БОЛЬНОЙ СЛУЧАЙ: присваивание кириллическим именем", 1,
          'DSN_СТЕНД="postgresql://app:пароль@localhost:5435/app"')
    проба("тот же случай в цикле for", 1, "for ФАЙЛ in a b; do echo $ФАЙЛ; done")
    проба("две беды в одном файле", 2, "СЕТЬ=/tmp/x.json\nВЫВОД=out.json")
    проба("латинское имя с кириллицей в ЗНАЧЕНИИ — законно", 0,
          'OUT_FILE="data/processed/эталон_район.json"')
    проба("кириллица в комментарии — законно", 0,
          "# СЕТЬ=/tmp/x.json — так писать нельзя\nNET=/tmp/x.json")
    проба("кириллица в тексте echo — законно", 0, 'echo "ВЫВОД записан"')
    проба("имя функции кириллицей — законно, bash их берёт", 0,
          "диалог_выхода_в() { grep -q x; }")
    # БОЛЬНЫЕ СЛУЧАИ 10.09.2026: имя приходит аргументом, без «=», и правило
    # присваивания его не видело — цикл не выполнился, проба осталась зелёной.
    проба("БОЛЬНОЙ СЛУЧАЙ: read -r с кириллическим именем", 1,
          "while IFS=$'\\t' read -r файл выражение; do echo x; done")
    проба("БОЛЬНОЙ СЛУЧАЙ: local -a с кириллическим именем", 1,
          "прогнать() { local -a слова; }")
    проба("кириллическое имя ТРЕТЬИМ в списке read", 1,
          "read -r src expr имя_случая")
    проба("read со списком латинских имён — законно", 0,
          "while IFS=$'\\t' read -r src expr proof subst name; do :; done")
    проба("local с латинскими именами и значениями — законно", 0,
          'local src="$1" expr="$2" name="Мутация поймана"')
    проба("declare -A латиницей — законно", 0, "declare -A MAP")
    # Все четыре ложняка ниже — замер 09.09.2026 по живым скриптам репозитория.
    проба("присваивание внутри ТЕКСТА сообщения — не команда", 0,
          'say "часовая сводка записана (гейты=$GATES_N скилы=$SKILLS_N)"')
    проба("то же в одинарных кавычках", 0,
          "echo 'прибор не ответил (работа=$WORK)'")
    проба("питон в heredoc: русские имена там законны", 0,
          "python3 - <<'PY'\nстроки = open(ф).read()\nfor строка in строки:\n    pass\nPY")
    проба("команда ПОСЛЕ heredoc проверяется как обычно", 1,
          "python3 - <<'PY'\nстроки = []\nPY\nСЕТЬ=/tmp/x.json")
    # session-warden.sh:275 — литерал живёт десяток строк, внутри питон.
    проба("многострочный python3 -c: питон внутри кавычек — не bash", 0,
          "tail -c 200 \"$1\" | python3 -c '\nimport json, sys\n"
          "последний = 0\nfor строка in sys.stdin:\n    pass\n'")
    проба("после закрытия литерала правило снова работает", 1,
          "python3 -c '\nимя = 1\n'\nВЫВОД=/tmp/x")
    # Нумерация обязана пережить гашение heredoc — иначе гейт покажет чужую строку.
    беды = беды_в_тексте(
        "python3 - <<'PY'\nстроки = []\nPY\nСЕТЬ=/tmp/x.json", правило)
    if беды and беды[0][0] == 4:
        print("  ок    номер строки после heredoc не съехал")
    else:
        print(f"  ПЛОХО номер строки после heredoc: ждали 4, получили {беды}")
        плохо = 1
    if плохо:
        print("САМОТЕСТ ПРОВАЛЕН")
        return 1
    # Второй носитель: хук на запись файла. Проверяется подпроцессом — иначе
    # проверялась бы функция, а не то, что увидит оболочка.
    import subprocess
    хук = [
        ('{"tool_input":{"file_path":"/tmp/x.sh","content":"ТЕСТ=1\\necho $ТЕСТ"}}', 2,
         "БОЛЬНОЙ СЛУЧАЙ: хук отказывает при записи .sh с кириллическим именем"),
        ('{"tool_input":{"file_path":"/tmp/x.sh","content":"OK=1\\necho $OK"}}', 0,
         "латинские имена — запись проходит"),
        ('{"tool_input":{"file_path":"/tmp/x.py","content":"ТЕСТ=1"}}', 0,
         "питон не судим: там кириллица в именах законна"),
        ("не json", 0, "битая нагрузка не мешает работать"),
    ]
    for нагрузка, ждём, зачем in хук:
        итог = subprocess.run([sys.executable, __file__, "--hook"],
                              input=нагрузка, capture_output=True, text=True)
        if итог.returncode != ждём:
            print(f"  ПЛОХО {зачем}: код {итог.returncode}, ждали {ждём}")
            return 1
        print(f"  ок    {зачем}")
    print("САМОТЕСТ ПРОЙДЕН: 24 пути, среди них больные: присваивание, read, local и хук записи")
    return 0


def режим_хука() -> int:
    """PreToolUse на запись файла: отказать В МОМЕНТ правки, а не на коммите.

    Гейт видит только индекс, а правки .sh идут через запись файла и через
    скрипты во временных каталогах — за одну смену 11.09.2026 кириллическое имя
    переменной всплывало семь раз, и каждый раз ловилось запуском, а не
    правилом. Второй носитель закрывает второй путь: правило, перекрытое одним
    путём из двух, обходится вторым.
    """
    import json
    try:
        нагрузка = json.loads(sys.stdin.read())
    except ValueError:
        return 0
    вход = нагрузка.get("tool_input") or {}
    путь = вход.get("file_path") or ""
    if not путь.endswith(".sh"):
        return 0
    текст = вход.get("content") or вход.get("new_string") or ""
    if not текст:
        return 0
    беды = беды_в_тексте(текст, _правило())
    if not беды:
        return 0
    имена = ", ".join(f"«{имя}»" for _, имя in беды[:4])
    print(f"Имя переменной кириллицей: {имена}. Bash такие идентификаторы не "
          f"берёт и печатает в ошибку САМО ЗНАЧЕНИЕ — так утекал токен. "
          f"Переименуй латиницей; кириллица законна в тексте и комментариях.",
          file=sys.stderr)
    return 2


def main() -> int:
    if "--selftest" in sys.argv[1:]:
        return _selftest()
    if "--hook" in sys.argv[1:]:
        return режим_хука()
    аргументы = [a for a in sys.argv[1:] if not a.startswith("--")]
    if аргументы:
        return проверить(аргументы, из_индекса=False)
    return проверить([с.strip() for с in sys.stdin if с.strip()], из_индекса=True)


if __name__ == "__main__":
    sys.exit(main())
