#!/usr/bin/env python3
"""Гейт: в публичной сборке нет следов ЭТОЙ установки.

Судит собранное дерево и его историю — то есть РЕЗУЛЬТАТ, а не источник.
Образцы берутся независимо от списка сборщика: сборщик, проверяющий сам
себя, зелен по построению («что заменил — того и нет»), и след, которого в
его данных нет, уехал бы наружу молча.

Источники образцов:
  * значения ключей паспорта установки (имя и путь проекта, номер чата
    владельца, имя продукта и его прозвища, домашний каталог агента);
  * адреса хранилищ, на которые смотрит пакет (git remote);
  * почты авторов коммитов проекта;
  * имя сервера.

Чего здесь нарочно НЕТ: имени пользователя самого по себе, режима работы,
каталога журналов. Замер дна 12.09.2026: «agent» встречается в дереве 199
раз, «semi» 68, /var/log/harness 93 — гейт с такими образцами был бы красным
всегда, а краснеющий без причины гейт отключают. Домашний путь /home/<имя>
ловится целиком — он и есть след.

В выводе — ИМЯ ключа, а не значение: вывод уезжает в журнал публикации и в
канал, и печатать там номер чата владельца незачем.

Запуск:
  python3 scripts/check-public-clean.py <каталог сборки>
  python3 scripts/check-public-clean.py --selftest
"""
import os
import re
import socket
import subprocess
import sys
import tempfile
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "scripts" / "lib"))
from config import из_файла, путь_harness_conf, путь_install_conf  # noqa: E402

ПАСПОРТ = путь_install_conf()
КОНФИГ = путь_harness_conf()
ОБРАЗЦЫ_ПАСПОРТА = ("PROJECT_NAME", "PROJECT_DIR", "TG_CHAT_ID", "PRODUCT_DIR")
# Метку ставит сборщик последним движением (build-public.py). Её отсутствие
# значит «сборки здесь нет»: 17.10.2026 сборщик отказал на полпути, а гейт
# на том каталоге ответил «следов установки нет» — зелень без предмета.
МЕТКА_СБОРКИ = ".публичная-сборка"
ДВОИЧНЫЕ = {".png", ".jpg", ".jpeg", ".gif", ".pdf", ".zip", ".gz", ".woff", ".woff2"}


def довод(имя: str, умолчание: str | None = None) -> str | None:
    if имя in sys.argv:
        место = sys.argv.index(имя) + 1
        if место < len(sys.argv):
            return sys.argv[место]
    return умолчание


def образцы(паспорт: dict, пакет: Path, проект: Path) -> list:
    """Пары «значение → имя образца». Пустые значения пропускаются.

    Пустое значение — не «совпало со всем», а «ключ не заполнен»: PRODUCT_DIR
    на свежей установке пуст, и поиск пустой строки нашёл бы каждый файл.
    """
    пары = []
    for ключ in ОБРАЗЦЫ_ПАСПОРТА:
        значение = (паспорт.get(ключ) or "").strip()
        if значение:
            пары.append((значение, ключ))
    for прозвище in (паспорт.get("PRODUCT_ALIASES") or "").split():
        if прозвище.strip():
            пары.append((прозвище.strip(), "PRODUCT_ALIASES"))
    пользователь = (паспорт.get("AGENT_USER") or "").strip()
    if пользователь:
        пары.append((f"/home/{пользователь}", "домашний каталог агента"))

    for каталог, имя in ((пакет, "адрес хранилища пакета"), (проект, "адрес хранилища проекта")):
        готово = subprocess.run(["git", "-C", str(каталог), "remote", "-v"],
                                capture_output=True, text=True, timeout=30)
        for строка in готово.stdout.splitlines():
            части = строка.split()
            if len(части) >= 2 and части[1]:
                пары.append((части[1], имя))

    почты = subprocess.run(["git", "-C", str(проект), "log", "--format=%ae"],
                           capture_output=True, text=True, timeout=60)
    for почта in sorted(set(почты.stdout.split())):
        # noreply-адреса не след установки: они одинаковы у всех и стоят в
        # публичной истории любого проекта.
        if почта and "noreply" not in почта:
            пары.append((почта, "почта автора коммитов"))

    # Список запретных слов живёт в harness.conf ЭТОЙ установки и в публичную
    # сборку не едет: вписать его в данные пакета значило бы опубликовать ровно
    # то, что он прячет.
    for слово in (паспорт.get("PUBLIC_FORBIDDEN_WORDS") or "").split():
        if слово.strip():
            пары.append((слово.strip(), "запретное слово"))

    хост = socket.gethostname().strip()
    if хост and хост not in ("localhost",):
        пары.append((хост, "имя сервера"))

    # Длинные образцы первыми: находка по пути важнее находки по имени внутри
    # него, и в отчёте должен стоять точный образец.
    пары.sort(key=lambda п: len(п[0]), reverse=True)
    return пары


def паспорт_прочитан(паспорт: dict) -> bool:
    """Хоть один опорный ключ заполнен?

    Пустой паспорт означает не «следов нет», а «судить нечем»: без значений
    гейт не имеет ни одного образца и отвечает «чисто» на любое дерево. Отказ
    чтения бывает живой — install.conf принадлежит root, а гейт зовут и демоны,
    и панель под своими пользователями (ревью кода 12.09.2026).
    """
    return any((паспорт.get(к) or "").strip()
               for к in ("PROJECT_NAME", "PROJECT_DIR", "AGENT_USER"))


def найти_в_дереве(сборка: Path, пары: list) -> list:
    # Образец ищется БЕЗ оглядки на регистр: имя проекта, написанное в
    # комментарии строчными, — то же имя, что и в паспорте с заглавной
    # (находка владельца 17.10.2026). Одно написание из двух равно ни одному.
    низкие = [(значение.lower(), имя) for значение, имя in пары]
    находки = []
    for файл in sorted(сборка.rglob("*")):
        if not файл.is_file() or ".git" in файл.parts:
            continue
        if файл.suffix.lower() in ДВОИЧНЫЕ:
            continue
        try:
            текст = файл.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue
        for номер, строка in enumerate(текст.splitlines(), 1):
            низкая = строка.lower()
            for значение, имя in низкие:
                if значение in низкая:
                    находки.append(f"{файл.relative_to(сборка)}:{номер}: образец={имя}")
                    break
    return находки


class ОтказGit(Exception):
    """git не ответил. «Не прочитали» и «ничего не нашли» — разные ответы:
    прежде любой отказ (нечитаемые объекты, чужой владелец каталога,
    повреждённый репозиторий) читался как «в истории ничего нет», и гейт
    печатал «следов установки нет» с кодом 0 (ревью 17.10, F-sec-06)."""


def _git(сборка: Path, *аргументы: str, годные: tuple = (0,),
         предел: int = 120) -> str:
    """Вывод git. Локаль задаётся ЯВНО: `git grep -i` гнёт не-ASCII только под
    UTF-8, а в кроне и в пустом окружении локали нет — половина истории слепла
    молча (ревью 17.10, F-sec-05). Код возврата вне `годные` — отказ."""
    среда = dict(os.environ, LC_ALL="C.UTF-8")
    готово = subprocess.run(["git", "-C", str(сборка), *аргументы],
                            capture_output=True, text=True, timeout=предел, env=среда)
    if готово.returncode not in годные:
        raise ОтказGit(f"git {' '.join(аргументы[:2])}: код {готово.returncode}, "
                       f"{готово.stderr.strip()[:200]}")
    return готово.stdout


def найти_в_истории(сборка: Path, пары: list) -> list:
    """История судится и по сообщениям, и по СОДЕРЖИМОМУ прошлых версий файлов.

    Убрать след из рабочего дерева мало: в истории он остаётся навсегда, и
    публичный репозиторий отдаёт его каждому, кто сделает клон. Обычный поиск
    по .git слеп — объекты сжаты, поэтому спрашиваем сам git (ревью 12.09.2026:
    прежняя редакция читала только тексты сообщений и отвечала «чисто»).
    """
    if not (сборка / ".git").exists():
        return []
    находки = []
    низкие = [(значение.lower(), имя) for значение, имя in пары]

    сообщения = _git(сборка, "log", "--all", "--format=%H%n%B")
    коммит = "?"
    for строка in сообщения.splitlines():
        if len(строка) == 40 and all(з in "0123456789abcdef" for з in строка):
            коммит = строка[:8]
            continue
        низкая = строка.lower()
        for значение, имя in низкие:
            if значение in низкая:
                находки.append(f"история {коммит}, сообщение: образец={имя}")
                break

    # Содержимое: git grep по всем коммитам. -I пропускает двоичное, -F берёт
    # образец буквально (в путях и адресах есть точки и слэши).
    коммиты = _git(сборка, "rev-list", "--all").split()
    if коммиты:
        for значение, имя in пары:
            # core.quotepath=false: иначе git отдаёт кириллические имена
            # экранированными байтами, и в отчёте владельцу нечитаемая строка.
            # Код 1 у grep законен — «не найдено»; всё остальное отказ.
            найдено = _git(сборка, "-c", "core.quotepath=false",
                           "grep", "-I", "-i", "-l", "-F", "-e", значение, *коммиты,
                           годные=(0, 1), предел=300)
            for строка in найдено.splitlines()[:5]:
                находки.append(f"история {строка.split(':')[0][:8]}, содержимое "
                               f"{строка.split(':', 1)[-1]}: образец={имя}")
    return находки


def _несвежая_сборка(сборка: Path, пакет: Path) -> str | None:
    """Причина, по которой судить эту сборку нельзя, — или None.

    Метка несёт хэш пакета, из которого собрано. Если он не совпадает с HEAD
    пакета, перед нами ОСТАТКИ прошлой сборки: гейт на них отвечал «следов
    установки нет», и зелень читалась как «публиковать можно» (ревью 17.10).
    Пакет недоступен (гейт зовут и демоны) — свежесть не судится: отказ без
    возможности его закрыть учит ходить мимо гейта.
    """
    текст = (сборка / МЕТКА_СБОРКИ).read_text(encoding="utf-8", errors="replace")
    из_метки = re.search(r"^пакет:\s*(\S+)", текст, re.M)
    if not из_метки:
        return (f"метка {МЕТКА_СБОРКИ} не называет пакет, из которого собрано — "
                "пересобрать: python3 scripts/build-public.py")
    if not (пакет / ".git").exists():
        return None
    готово = subprocess.run(["git", "-C", str(пакет), "rev-parse", "--short", "HEAD"],
                            capture_output=True, text=True, timeout=60)
    if готово.returncode != 0:
        return None
    сейчас = готово.stdout.strip()
    если_из_метки = из_метки.group(1)
    if сейчас and не_совпали(сейчас, если_из_метки):
        return (f"сборка от пакета {если_из_метки}, а пакет сейчас {сейчас} — "
                "это остатки прошлой сборки, судить нечем; пересобрать: "
                "python3 scripts/build-public.py")
    return None


def не_совпали(сейчас: str, из_метки: str) -> bool:
    """Хэши сравниваются по общей длине: `rev-parse --short` отдаёт 7 знаков,
    а в метке может лежать длинный."""
    длина = min(len(сейчас), len(из_метки))
    return сейчас[:длина] != из_метки[:длина]


def проверить(сборка: Path, пары: list) -> list:
    return найти_в_дереве(сборка, пары) + найти_в_истории(сборка, пары)


def main() -> int:
    свои = [д for д in sys.argv[1:] if not д.startswith("--")]
    паспорт = из_файла(довод("--паспорт", ПАСПОРТ))
    паспорт.update(из_файла(довод("--конфиг", КОНФИГ)))
    if not паспорт_прочитан(паспорт):
        print("[чистота] паспорт установки не прочитан — судить нечем, а не «чисто»",
              file=sys.stderr)
        return 2
    пакет = Path(довод("--пакет") or f"/home/{паспорт.get('AGENT_USER', 'agent')}/starter/STARTER-PACKAGE")
    сборка = Path(свои[0] if свои else паспорт.get("PUBLIC_BUILD_DIR", ""))
    if not str(сборка).strip() or not сборка.is_dir():
        print(f"[чистота] сборки нет: {сборка or '(путь не задан)'} — проверять нечего",
              file=sys.stderr)
        return 2
    if not (сборка / МЕТКА_СБОРКИ).exists():
        print(f"[чистота] в {сборка} нет метки {МЕТКА_СБОРКИ} — это не собранное "
              "дерево, судить нечем", file=sys.stderr)
        return 2
    беда_свежести = _несвежая_сборка(сборка, пакет)
    if беда_свежести:
        print(f"[чистота] {беда_свежести}", file=sys.stderr)
        return 2


    проект = Path(довод("--проект") or паспорт.get("PROJECT_DIR") or str(КОРЕНЬ))
    пары = образцы(паспорт, пакет, проект)
    try:
        находки = проверить(сборка, пары)
    except ОтказGit as отказ:
        # Молчание git не имеет права выглядеть чистотой: «судить нечем» —
        # это код 2, его же читает publish.sh как отказ публикации.
        print(f"[чистота] историю прочитать не удалось — {отказ}; судить нечем",
              file=sys.stderr)
        return 2
    # Число судимых образцов говорится ВСЛУХ: пустые данные уже делали
    # «проверять нечего» неотличимым от «следов нет» (ревью 17.10, F-gen-05).
    print(f"[чистота] судимых образцов: {len(пары)}")
    # ДЕРЕВО и ИСТОРИЯ судятся порознь. Дерево — то, что мы публикуем сейчас:
    # отказ. История — то, что УЖЕ опубликовано (14.10.2026: вторая машина
    # владельца увезла имя магазина 24 раза в своих коммитах), и убрать её можно
    # только перезаписью чужой публичной ветки, что запрещено отдельным правилом.
    # Отказ по истории делал дверь непроходимой навсегда — а дверь, которую
    # нельзя пройти, не охраняет, её обходят ([[a-guard-without-a-legal-door]]).
    в_дереве = [с for с in находки if not с.startswith("история ")]
    в_истории = [с for с in находки if с.startswith("история ")]
    if в_дереве:
        for строка in в_дереве[:50]:
            print(f"  {строка}")
        if len(в_дереве) > 50:
            print(f"  … и ещё {len(в_дереве) - 50}")
        print(f"[чистота] в публичной сборке следы установки: {len(в_дереве)}")
        return 1
    if в_истории:
        for строка in в_истории[:10]:
            print(f"  ⚠ {строка}")
        print(f"[чистота] дерево чистое, а в УЖЕ ОПУБЛИКОВАННОЙ истории следов "
              f"{len(в_истории)} — их убирает только перезапись публичной ветки, "
              f"и это решение владельца")
    print("[чистота] в публичной сборке следов установки нет")
    return 0


def _вердикт(сборка: Path, паспорт: dict, корень: Path,
             подменить_git: bool = False) -> tuple[int, list[str]]:
    """Код возврата main() и его печать на подставной сборке.

    Проба судит ВЕРДИКТ, а не только список находок: разделение «дерево — отказ,
    история — предупреждение» живёт именно в main, и без этого пути поломка там
    оставалась бы зелёной.

    `подменить_git` ставит в PATH отказывающий `git` — так воспроизводится
    живая беда: нечитаемые объекты, чужой владелец каталога, повреждённый
    репозиторий. Отказ подделывается ИМЕННО сломанной командой, а не правкой
    кода гейта: иначе случай судил бы свою же выдумку.
    """
    import contextlib
    import io

    прежний_путь = os.environ.get("PATH", "")
    if подменить_git:
        ломаный = корень / "ломаный-git"
        ломаный.mkdir(exist_ok=True)
        (ломаный / "git").write_text(
            "#!/bin/sh\necho 'fatal: detected dubious ownership' >&2\nexit 128\n",
            encoding="utf-8")
        (ломаный / "git").chmod(0o755)
        os.environ["PATH"] = f"{ломаный}:{прежний_путь}"

    файл_паспорта = корень / "паспорт-вердикта.conf"
    файл_паспорта.write_text(
        "".join(f'{к}="{з}"\n' for к, з in паспорт.items() if з), encoding="utf-8")
    поток = io.StringIO()
    было = sys.argv[:]
    sys.argv = ["check-public-clean.py", str(сборка), "--паспорт", str(файл_паспорта),
                "--конфиг", str(файл_паспорта), "--пакет", str(корень / "пакет"),
                "--проект", str(корень / "проект")]
    try:
        # И stderr: отказы гейта («судить нечем») печатаются туда, а случай
        # обязан судить ПРИЧИНУ, а не только код — иначе он зелен от любой
        # другой беды с тем же кодом.
        with contextlib.redirect_stdout(поток), contextlib.redirect_stderr(поток):
            код = main()
    finally:
        sys.argv = было
        os.environ["PATH"] = прежний_путь
    return код, поток.getvalue().splitlines()


# ── самотест: подставная сборка, девять путей ───────────────────────────────
def _подставная_сборка(корень: Path, паспорт: dict, хэш_пакета: str = "0000000") -> Path:
    сборка = корень / "сборка"
    (сборка / "harness").mkdir(parents=True)
    (сборка / МЕТКА_СБОРКИ).write_text(
        f"стенд самотеста\nпакет: {хэш_пакета}\n"
        "собрано: 2026-10-17T02:00:00+05:00\n", encoding="utf-8")
    (сборка / "README.md").write_text("Ставится куда угодно.\n", encoding="utf-8")
    (сборка / "harness" / "код.py").write_text("ПОРОГ = 15\n", encoding="utf-8")
    subprocess.run(["git", "-C", str(сборка), "init", "-q", "-b", "master"], check=True)
    subprocess.run(["git", "-C", str(сборка), "add", "-A"], check=True)
    subprocess.run(["git", "-C", str(сборка), "-c", "user.name=t", "-c", "user.email=t@t",
                    "commit", "-qm", "версия от 2026-09-12"], check=True)
    return сборка


def самотест() -> int:
    """Гейт обязан ловить то, чего сборщик не знает."""
    путей = неудач = 0

    def проба(ок: bool, текст: str) -> None:
        nonlocal путей, неудач
        путей += 1
        неудач += 0 if ок else 1
        print(("  ок    " if ок else "  ПЛОХО ") + текст)

    with tempfile.TemporaryDirectory(prefix="самотест-чистоты-") as врем:
        корень = Path(врем)
        пакет = корень / "пакет"
        пакет.mkdir()
        subprocess.run(["git", "-C", str(пакет), "init", "-q", "-b", "master"], check=True)
        subprocess.run(["git", "-C", str(пакет), "remote", "add", "jig",
                        "git@подставной-хост:кто-то/репо.git"], check=True)
        (пакет / "файл").write_text("пакет стенда\n", encoding="utf-8")
        subprocess.run(["git", "-C", str(пакет), "add", "-A"], check=True)
        subprocess.run(["git", "-C", str(пакет), "-c", "user.name=t", "-c", "user.email=t@t",
                        "commit", "-qm", "пакет"], check=True)
        хэш_пакета = subprocess.run(
            ["git", "-C", str(пакет), "rev-parse", "--short", "HEAD"],
            capture_output=True, text=True, check=True).stdout.strip()
        проект = корень / "проект"
        проект.mkdir()
        subprocess.run(["git", "-C", str(проект), "init", "-q", "-b", "master"], check=True)
        (проект / "ф").write_text("x\n", encoding="utf-8")
        subprocess.run(["git", "-C", str(проект), "add", "-A"], check=True)
        subprocess.run(["git", "-C", str(проект), "-c", "user.name=t",
                        "-c", "user.email=хозяин@подставной.рф", "commit", "-qm", "п"], check=True)

        паспорт = {"PROJECT_NAME": "Подставной", "PROJECT_DIR": "/srv/подставной",
                   "TG_CHAT_ID": "987654321", "PRODUCT_DIR": "", "AGENT_USER": "жилец",
                   "PRODUCT_ALIASES": "ПРОДУКТ продукт"}
        пары = образцы(паспорт, пакет, проект)
        сборка = _подставная_сборка(корень, паспорт, хэш_пакета)

        # БОЛЬНОЙ первым: след, которого в данных сборщика нет вовсе.
        (сборка / "harness" / "код.py").write_text(
            'CHAT = "987654321"\n', encoding="utf-8")
        находки = проверить(сборка, пары)
        проба(any("TG_CHAT_ID" in н for н in находки),
              "БОЛЬНОЙ: номер чата владельца в коде сборки — находка")
        проба(all("987654321" not in н for н in находки),
              "БОЛЬНОЙ: в выводе стоит ИМЯ образца, а не его значение")

        # Коммит с нашим путём в СООБЩЕНИИ: дерево при этом чистое. Файл меняем
        # на другое содержимое, иначе коммитить нечего и git отвечает отказом.
        (сборка / "harness" / "код.py").write_text("ПОРОГ = 16\n", encoding="utf-8")
        subprocess.run(["git", "-C", str(сборка), "add", "-A"], check=True)
        subprocess.run(["git", "-C", str(сборка), "-c", "user.name=t", "-c", "user.email=t@t",
                        "commit", "-qm", "правка в /srv/подставной"], check=True)
        находки = проверить(сборка, пары)
        проба(any(н.startswith("история") for н in находки),
              "БОЛЬНОЙ: след только в сообщении коммита — дерево чистое, а след назван")
        # ВЕРДИКТ: след ТОЛЬКО в истории не валит публикацию (убрать его можно
        # лишь перезаписью чужой публичной ветки — это решение владельца), но
        # обязан быть СКАЗАН числом (находка соседского ревью 14.10.2026).
        код, сказано = _вердикт(сборка, паспорт, корень)
        проба(код == 0 and any("УЖЕ ОПУБЛИКОВАННОЙ истории" in с for с in сказано),
              f"след только в истории: код {код}, предупреждение сказано "
              f"({[с for с in сказано if 'истории' in с][:1]})")

        subprocess.run(["git", "-C", str(сборка), "-c", "user.name=t", "-c", "user.email=t@t",
                        "commit", "-q", "--amend", "-m", "версия от 2026-09-12"], check=True)

        (сборка / "README.md").write_text(
            "git clone git@подставной-хост:кто-то/репо.git\n", encoding="utf-8")
        проба(any("адрес хранилища" in н for н in проверить(сборка, пары)),
              "БОЛЬНОЙ: адрес нашего хранилища в документе — находка")

        (сборка / "README.md").write_text("Ставится куда угодно.\n", encoding="utf-8")
        (сборка / "harness" / "код.py").write_text(
            'ПУТЬ = "/home/жилец/starter"\nИМЯ = "жилец пользователь"\n',
            encoding="utf-8")
        находки = проверить(сборка, пары)
        проба(any("домашний каталог" in н for н in находки),
              "БОЛЬНОЙ: домашний каталог агента — находка")
        проба(len([н for н in находки if "код.py" in н]) == 1,
              "имя пользователя само по себе находкой не считается")

        (сборка / "harness" / "код.py").write_text(
            f'СЕРВЕР = "{socket.gethostname()}"\n', encoding="utf-8")
        проба(any("имя сервера" in н for н in проверить(сборка, пары)),
              "БОЛЬНОЙ: имя сервера в файле — находка")

        # БОЛЬНОЙ СЛУЧАЙ 17.10.2026: имя проекта строчными буквами. Гейт искал
        # образец буква в букву, и строчное написание в комментарии пропускал,
        # хотя значение PROJECT_NAME знал. Одно написание из двух — то же, что
        # ни одного: владелец нашёл это сам, спросив «что только харнес».
        (сборка / "harness" / "код.py").write_text(
            "# про подставной проект — см. корень\n", encoding="utf-8")
        проба(any("PROJECT_NAME" in н for н in проверить(сборка, пары)),
              "БОЛЬНОЙ: имя проекта В ДРУГОМ РЕГИСТРЕ — находка")

        (сборка / "harness" / "код.py").write_text("ПОРОГ = 15\n", encoding="utf-8")
        проба(проверить(сборка, пары) == [],
              "здоровый: чистое дерево и чистая история — находок нет")

        # БОЛЬНОЙ СЛУЧАЙ 17.10.2026 (ревью, F-sec-07/F-gen-05): метка
        # свидетельствовала сама о себе. Каталог с ПРОШЛОЙ сборкой (метка от
        # другого хэша пакета) судился как свежая, и зелень читалась «можно
        # публиковать»: живой PUBLIC_BUILD_DIR нёс метку от 14.10 над деревом
        # от 15.10, в котором гейт находил 25 следов.
        метка = сборка / МЕТКА_СБОРКИ
        было_в_метке = метка.read_text(encoding="utf-8")
        метка.write_text("пакет: 0000000\nсобрано: 2026-01-01T00:00:00+05:00\n",
                         encoding="utf-8")
        код, сказано = _вердикт(сборка, паспорт, корень)
        проба(код == 2 and any("пакет" in с.lower() for с in сказано),
              f"БОЛЬНОЙ: метка от ЧУЖОГО хэша пакета — «судить нечем» (код {код})")
        метка.write_text(было_в_метке, encoding="utf-8")

        # БОЛЬНОЙ СЛУЧАЙ 17.10.2026: каталог ЕСТЬ, а сборки в нём нет. Сборщик
        # отказал на полпути (цитата без пары), и гейт на этом каталоге сказал
        # «следов установки нет» — то есть зелень означала «нечего смотреть».
        недособранный = корень / "недособранное"
        недособранный.mkdir()
        код, сказано = _вердикт(недособранный, паспорт, корень)
        проба(код == 2, f"БОЛЬНОЙ: каталог без метки сборки — «судить нечем», код {код}")

        # БОЛЬНОЙ СЛУЧАЙ 17.10.2026 (ревью, F-sec-05): кириллический образец,
        # оставшийся ТОЛЬКО в истории. Дерево складывает регистр питоном, а
        # историю — `git grep -i`, и он гнёт не-ASCII лишь под UTF-8 локалью:
        # под LC_ALL=C (крон, пустое окружение, свежий сервер) половина
        # истории слепла, а гейт печатал «следов установки нет».
        # Написание ТРЕТЬЕ: в образцах стоят «ПРОДУКТ» и «продукт», и
        # буквальное совпадение прошло бы без складывания регистра — случай
        # был бы зелен ни от чего (поймано на себе же).
        (сборка / "harness" / "старое.py").write_text(
            'ИМЯ = "Продукт"\n', encoding="utf-8")
        subprocess.run(["git", "-C", str(сборка), "add", "-A"], check=True)
        subprocess.run(["git", "-C", str(сборка), "-c", "user.name=t", "-c", "user.email=t@t",
                        "commit", "-qm", "правка"], check=True)
        (сборка / "harness" / "старое.py").unlink()
        subprocess.run(["git", "-C", str(сборка), "add", "-A"], check=True)
        subprocess.run(["git", "-C", str(сборка), "-c", "user.name=t", "-c", "user.email=t@t",
                        "commit", "-qm", "убрал"], check=True)
        прежняя_локаль = os.environ.get("LC_ALL")
        os.environ["LC_ALL"] = "C"
        находки = найти_в_истории(сборка, пары)
        if прежняя_локаль is None:
            os.environ.pop("LC_ALL", None)
        else:
            os.environ["LC_ALL"] = прежняя_локаль
        проба(any("содержимое" in н and "PRODUCT_ALIASES" in н for н in находки),
              "БОЛЬНОЙ: кириллический образец в ИСТОРИИ найден и под локалью C")

        # БОЛЬНОЙ СЛУЧАЙ 17.10.2026 (ревью, F-sec-06): отказ git читался как
        # «в истории ничего нет». Нечитаемые объекты, чужой владелец каталога,
        # повреждённый репозиторий — любая такая беда давала тихую зелень.
        код, сказано = _вердикт(сборка, паспорт, корень, подменить_git=True)
        проба(код == 2 and any("git" in с.lower() for с in сказано),
              f"БОЛЬНОЙ: отказ git — «судить нечем» (код {код}), а не чистота")

        # Пустой ключ не должен совпадать со всем подряд.
        проба(all(имя != "PRODUCT_DIR" for _, имя in пары),
              "пустой PRODUCT_DIR в образцы не попал")

        # Образцы из ФАЙЛА: подменённое окружение вердикта не меняет.
        образец_файла = корень / "паспорт.conf"
        образец_файла.write_text('PROJECT_DIR="/из-файла"\n', encoding="utf-8")
        os.environ["PROJECT_DIR"] = "/из-окружения"
        проба(из_файла(str(образец_файла))["PROJECT_DIR"] == "/из-файла",
              "образцы берутся из файла паспорта, а не из окружения")
        os.environ.pop("PROJECT_DIR", None)

    if неудач:
        print("САМОТЕСТ ПРОВАЛЕН")
        return 1
    print(f"САМОТЕСТ ПРОЙДЕН: {путей} путей, первым — больной случай")
    return 0


