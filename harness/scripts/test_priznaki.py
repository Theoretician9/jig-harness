#!/usr/bin/env python3
"""Проверка гейта «у факта один судья»: краснеет ли он на случившихся отказах.

Откуда взято. Владелец 12.09.2026 (ночь): «Реши системно все эти проблемы».
Гейт написан под три ночных отказа одного класса, и проба воспроизводит их:
файл судит о факте, но источник не спрашивает.

Проверять приходится на подставном дереве: на живом гейт зелёный — все три
случая уже починены, а «сегодня зелено» не доказывает, что он ловит.

Прогон:
    python3 scripts/test_priznaki.py
Код возврата: 0 — все пути прошли, 1 — есть упавший.
"""
import importlib.util
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
путей = неудач = 0


def путь_ок(текст: str) -> None:
    global путей
    путей += 1
    print("ок  · " + текст)


def путь_плохо(текст: str) -> None:
    global путей, неудач
    путей += 1
    неудач += 1
    print("ПЛОХО · " + текст)


спец = importlib.util.spec_from_file_location(
    "признаки", КОРЕНЬ / "scripts" / "check-priznaki.py")
гейт = importlib.util.module_from_spec(спец)
спец.loader.exec_module(гейт)

ДАНО = [{
    "факт": "согласие владельца на действие",
    "источник": "deploy_guard.py",
    "где": "scripts/deploy_guard.py",
    "маркеры": ["согласия владельца"],
    "знают_сами": [{"файл": "scripts/пересказчик.sh", "причина": "пересказывает чужое решение"}],
}]

двор = Path(tempfile.mkdtemp(prefix="признаки-"))
try:
    (двор / "scripts").mkdir(parents=True)
    (двор / "scripts" / "deploy_guard.py").write_text("# источник\n", encoding="utf-8")

    print("── БОЛЬНОЙ: судит, но источник не зовёт (случай 12.09) ──")
    (двор / "scripts" / "судья.sh").write_text(
        'echo "согласия владельца свежее 60 мин нет — не пушь"\n', encoding="utf-8")
    беды = гейт.претензии(двор, ДАНО)
    if any("судья.sh" in б for б in беды):
        путь_ок("файл со своим суждением пойман")
    else:
        путь_плохо(f"свой судья не пойман: {беды}")

    print("── здоровый: судит и зовёт источник ──")
    (двор / "scripts" / "судья.sh").write_text(
        'if python3 "$D/scripts/deploy_guard.py" --действие push; then\n'
        '  echo "согласия владельца хватает"\nfi\n', encoding="utf-8")
    беды = гейт.претензии(двор, ДАНО)
    if not any("судья.sh" in б for б in беды):
        путь_ок("зовёт источник — претензий нет")
    else:
        путь_плохо(f"вызов источника не зачтён: {беды}")

    print("── названный в «знают_сами» не краснеет ──")
    (двор / "scripts" / "пересказчик.sh").write_text(
        'echo "согласия владельца нет — так сказал сторож"\n', encoding="utf-8")
    беды = гейт.претензии(двор, ДАНО)
    if not any("пересказчик" in б for б in беды):
        путь_ок("пересказчик с причиной пропущен")
    else:
        путь_плохо(f"пересказчик покраснел: {беды}")

    print("── БОЛЬНОЙ: маркер в комментарии — не суждение ──")
    (двор / "scripts" / "объяснитель.py").write_text(
        '# согласия владельца тут нет, это пояснение к соседнему коду\n'
        'печать = 1\n', encoding="utf-8")
    беды = гейт.претензии(двор, ДАНО)
    if not any("объяснитель" in б for б in беды):
        путь_ок("комментарий объясняет, а не судит — гейт молчит")
    else:
        путь_плохо(f"комментарий сочтён суждением: {беды}")

    print("── БОЛЬНОЙ: маркер в строке документации — не суждение ──")
    # Улика 13.09.2026: гейт покраснел на scripts/srochnost.py за цитату
    # владельца в шапке модуля. Слово там пересказывает его просьбу.
    кавычки = chr(34) * 3
    (двор / "scripts" / "цитатник.py").write_text(
        f"{кавычки}Модуль про другое.\n\nВладелец писал: «согласия владельца жду».\n{кавычки}\n"
        "значение = 1\n", encoding="utf-8")
    беды = гейт.претензии(двор, ДАНО)
    if not any("цитатник" in б for б in беды):
        путь_ок("цитата в документации суждением не считается")
    else:
        путь_плохо(f"документация сочтена суждением: {беды}")

    print("── боевой путь: команда на живом дереве ──")
    готово = subprocess.run(
        [sys.executable, str(КОРЕНЬ / "scripts" / "check-priznaki.py")],
        capture_output=True, text=True, timeout=120)
    if готово.returncode == 0 and "один судья" in готово.stdout:
        путь_ок(f"живое дерево чисто: {готово.stdout.strip()[:70]}")
    else:
        путь_плохо(f"живой прогон: код {готово.returncode}, {готово.stdout[-160:]}")
finally:
    shutil.rmtree(двор, ignore_errors=True)

print(f"\nитого путей {путей}, неудач {неудач}")
sys.exit(1 if неудач else 0)
