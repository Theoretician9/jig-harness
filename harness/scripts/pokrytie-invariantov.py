#!/usr/bin/env python3
"""Покрытие инвариантов: у каждого правила — механизм, прибор и живой след.

Ревизия «снизу вверх» (осмотреть, что есть) не видит инварианта, у которого
механизма нет вовсе: осматривать нечего. Замечание владельца М-1 к ревизии
10.09.2026. Здесь обратный ход — от списка правил (harness/config/инварианты.yaml)
к их механизмам, и три вопроса по каждому:

  1. файл механизма существует?
  2. есть прибор — команда, которая покраснеет при нарушении?
  3. виден ли СЛЕД срабатывания в журнале и свежий ли он?

Третий вопрос — главный: механизм, который существует, но ни разу не
срабатывал, ничем не отличается от отсутствующего, пока не сломается что-то
важное. Ровно так 59 раз подряд врал сигнал про cron, и ровно так «бэкап есть»
означал «дамп, из которого никто не вставал».

Запуск:
    python3 scripts/pokrytie-invariantov.py            # таблица + итог
    python3 scripts/pokrytie-invariantov.py --приборы  # прогнать лёгкие приборы
    python3 scripts/pokrytie-invariantov.py --приборы --тяжёлые  # и живые пробы
    python3 scripts/pokrytie-invariantov.py --selftest

Код возврата = число строк без механизма или без свежего следа.
"""
import datetime
import os
import re
import shlex
import subprocess
import sys
import time

import yaml

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "lib"))
from konf import log_dir, конфиг  # noqa: E402 — один парсер конфига на все гейты

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ДАННЫЕ = os.path.join(КОРЕНЬ, "harness", "config", "инварианты.yaml")


ВРЕМЯ = re.compile(r'"ts"\s*:\s*"([0-9]{4}-[0-9]{2}-[0-9]{2}[T ][0-9:]{8})'
                   r'|^([0-9]{4}-[0-9]{2}-[0-9]{2} [0-9:]{8})')


def момент_строки(строка: str) -> float | None:
    """Время СОБЫТИЯ из самой строки: поле ts (JSONL) или дата в начале (лог)."""
    m = ВРЕМЯ.search(строка)
    if not m:
        return None
    текст = (m.group(1) or m.group(2)).replace(" ", "T", 1)
    try:
        return datetime.datetime.fromisoformat(текст).timestamp()
    except ValueError:
        return None


def возраст_следа(журнал: str, признак: str, log_dir: str) -> float | None:
    """Дни с последнего появления признака, посчитанные ПО САМОЙ СТРОКЕ.

    Первая редакция брала mtime ФАЙЛА: любая свежая запись в общий журнал
    объявляла живым механизм, который молчит неделю. Ревью 10.09.2026 поймало
    это на живом — шесть инвариантов делили признак «"gate":"pre-commit"», и
    один коммит объявлял живыми все шесть. Теперь время берётся из строки, а
    признак обязан быть СВОИМ (см. поле «признак» в инварианты.yaml).
    """
    # «heartbeat:<имя>» — след не в журнале, а в МЕТКЕ присмотра. Так живут
    # механизмы, которые в здоровом состоянии молчат: sentinel пишет в журнал
    # только когда что-то поднимает, и живой прогон 12.09.2026 объявил
    # инвариант «cron жив» непокрытым ровно потому, что два дня всё было
    # хорошо. Признак обязан быть у ЗДОРОВОГО состояния, иначе он ловит беду,
    # а не жизнь.
    if журнал.startswith("heartbeat:"):
        метка = os.path.join(
            os.environ.get("HEARTBEAT_DIR", "/var/lib/harness/heartbeat"),
            журнал.split(":", 1)[1])
        if not os.path.exists(метка):
            return None
        return (time.time() - os.path.getmtime(метка)) / 86400

    путь = os.path.join(log_dir, журнал)
    if not os.path.exists(путь):
        return None
    try:
        with open(путь, "rb") as fh:
            fh.seek(0, os.SEEK_END)
            размер = fh.tell()
            окно = min(размер, 4_000_000)
            fh.seek(размер - окно)
            хвост = fh.read().decode("utf-8", "replace")
    except OSError:
        return None
    for строка in reversed(хвост.splitlines()):
        if признак in строка:
            момент = момент_строки(строка)
            if момент is None:
                return None      # без времени события «свежесть» выдумана
            return (time.time() - момент) / 86400
    return None


ЗАПУСКАТЕЛИ = ("bash", "python3")


def разобрать_прибор(команда: str) -> list | None:
    """Команда прибора — из ФАЙЛА ДАННЫХ, поэтому не через оболочку.

    Ревью 10.09.2026: строка исполнялась `shell=True`, то есть таблица данных
    была каналом исполнения мимо сторожа команд — правка одной строки YAML
    запускала что угодно. Разрешены только «bash|python3 <путь внутри репозитория>»
    с флагами; всё остальное честно не запускается.
    """
    try:
        слова = shlex.split(команда)
    except ValueError:
        return None
    if len(слова) < 2 or слова[0] not in ЗАПУСКАТЕЛИ:
        return None
    цель = os.path.normpath(os.path.join(КОРЕНЬ, слова[1]))
    if not цель.startswith(КОРЕНЬ + os.sep) or not os.path.exists(цель):
        return None
    if any(с.startswith("-") is False and "/" in с and с != слова[1] for с in слова[2:]):
        return None                      # второй путь в аргументах — не наш случай
    return [слова[0], цель, *слова[2:]]


def оценить(и: dict, каталог: str) -> tuple:
    """Одна строка таблицы → (метка, текст следа, беда).

    Беда — пара (раздел, пояснение) или None. Чистая оценка, отделённая от
    печати и от запуска приборов (ревью 10.09.2026, q-17): прежде всё это
    жило в одном теле длиннее экрана, и судить о правилах отдельно от их
    вывода было нечем.
    """
    есть = os.path.exists(os.path.join(КОРЕНЬ, и["файл"]))
    прибор = и.get("доказательство") or ""
    срок = int(и.get("срок_дней") or 0)
    возраст = возраст_следа(и.get("журнал", ""), и.get("признак", ""), каталог)
    if возраст is None:
        след = "следа нет"
    elif срок and возраст > срок:
        след = f"{возраст:.0f} дн (порог {срок})"
    else:
        след = f"{возраст:.1f} дн"
    if not есть:
        return "НЕТ ", след, ("механизм", f"{и['id']}: файла {и['файл']} нет")
    if not прибор:
        return "БЕЗ ПРИБОРА", след, (
            "механизм", f"{и['id']}: прибора нет — нарушение никто не покрасит")
    if срок and (возраст is None or возраст > срок):
        return "БЕЗ СЛЕДА", след, ("след", f"{и['id']}: {след} в {и.get('журнал')}")
    return "ок  ", след, None


def прогнать_прибор(и: dict, тяжёлые: bool) -> str:
    """Запуск прибора инварианта → строка отчёта. Ничего не решает, только меряет."""
    прибор = и["доказательство"]
    слова = разобрать_прибор(прибор)
    if слова is None:
        return f"прибор НЕ ЗАПУЩЕН — команда не разобрана: {прибор}"
    if и.get("тяжёлый") and not тяжёлые:
        # Живая проба поднимает базу на сотни мегабайт и идёт минутами: такое не
        # запускают мимоходом, да и прогон внутри сессии запрещён указанием
        # владельца 23.08 (ревью 10.09.2026).
        return f"прибор ТЯЖЁЛЫЙ, пропущен — запусти сам: {прибор}"
    try:
        rc = subprocess.run(слова, cwd=КОРЕНЬ, capture_output=True,
                            text=True, timeout=120).returncode
        итог = "зелёный" if rc == 0 else f"КРАСНЫЙ (rc={rc})"
    except subprocess.TimeoutExpired:
        итог = "ЗАВИС (120 с) — прибор не отвечает"
    return f"прибор: {итог} — {прибор}"


def main() -> int:
    if "--selftest" in sys.argv:
        return самотест()
    with open(ДАННЫЕ, encoding="utf-8") as fh:
        строки = yaml.safe_load(fh)["инварианты"]
    каталог = log_dir()
    гнать = "--приборы" in sys.argv
    беды = {"механизм": [], "след": []}
    print(f"=== покрытие инвариантов: {len(строки)} правил ===")
    for и in строки:
        метка, след, беда = оценить(и, каталог)
        if беда:
            беды[беда[0]].append(беда[1])
        print(f"  {метка:<12} {и['id']:<26} {и['механизм'][:44]:<44} след: {след}")
        if гнать and и.get("доказательство") and os.path.exists(
                os.path.join(КОРЕНЬ, и["файл"])):
            print(f"      {прогнать_прибор(и, '--тяжёлые' in sys.argv)}")
    print()
    for заголовок, список in (("БЕЗ МЕХАНИЗМА ИЛИ ПРИБОРА", беды["механизм"]),
                              ("МЕХАНИЗМ ЕСТЬ, СВЕЖЕГО СЛЕДА НЕТ", беды["след"])):
        if список:
            print(f"{заголовок}:")
            for s in список:
                print(f"  • {s}")
    итог = len(беды["механизм"]) + len(беды["след"])
    print(f"=== итог: покрыто {len(строки) - итог} из {len(строки)}, "
          f"без прибора {len(беды['механизм'])}, без свежего следа {len(беды['след'])} ===")
    return итог


def самотест() -> int:
    """Больной случай первым: строка без прибора обязана попасть в находки."""
    import tempfile
    ok = True
    with tempfile.TemporaryDirectory() as tmp:
        лог = os.path.join(tmp, "проба.log")
        сейчас = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        старое = (datetime.datetime.now() - datetime.timedelta(days=10)).strftime("%Y-%m-%d %H:%M:%S")
        with open(лог, "w", encoding="utf-8") as fh:
            fh.write(f"{старое}  СОБЫТИЕ было давно\n{сейчас}  СОБЫТИЕ есть\n")
        без_времени = os.path.join(tmp, "безвремени.log")
        with open(без_времени, "w", encoding="utf-8") as fh:
            fh.write("СОБЫТИЕ есть, а когда — неизвестно\n")
        свежесть = возраст_следа("проба.log", "СОБЫТИЕ", tmp)
        случаи = [
            ("возраст берётся из ПОСЛЕДНЕЙ строки с признаком, а не из mtime файла",
             свежесть is not None and свежесть < 0.01),
            ("БОЛЬНОЙ СЛУЧАЙ: признака в журнале нет — след не выдуман",
             возраст_следа("проба.log", "ЧЕГО-ТО-НЕТ", tmp) is None),
            ("БОЛЬНОЙ СЛУЧАЙ: строка без времени — свежесть не выдумывается",
             возраст_следа("безвремени.log", "СОБЫТИЕ", tmp) is None),
            ("журнала нет вовсе — следа нет",
             возраст_следа("нет-такого.log", "СОБЫТИЕ", tmp) is None),
        ]
        with open(ДАННЫЕ, encoding="utf-8") as fh:
            строки = yaml.safe_load(fh)["инварианты"]
        случаи.append(("таблица читается и не пуста", len(строки) >= 10))
        случаи.append(("БОЛЬНОЙ СЛУЧАЙ: чужая команда из данных НЕ запускается",
                       разобрать_прибор("rm -rf /var/log/harness") is None
                       and разобрать_прибор("bash /etc/passwd") is None
                       and разобрать_прибор("bash ../вне-репозитория.sh") is None))
        случаи.append(("свой прибор разбирается в список аргументов",
                       (разобрать_прибор("bash scripts/mutacionnaya-proba.sh") or [None])[0] == "bash"))
        случаи.append(("у каждой строки есть id, файл и правило",
                       all(и.get("id") and и.get("файл") and и.get("правило") for и in строки)))
        for имя, годен in случаи:
            print(f"  {'ок   ' if годен else 'ПЛОХО'} {имя}")
            ok = ok and годен
    print("SELFTEST: зелёный (8 путей, среди них три больных: признака нет, строка без времени, чужая команда из данных)"
          if ok else "SELFTEST: КРАСНЫЙ")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
