#!/usr/bin/env bash
# Вызов модели ДЕМОНОМ: один вход для всех фоновых прогонов.
#
# СЛУЧАЙ 13.09.2026. Три демона получили «You've hit your weekly limit ·
# resets Sep 16, 6pm» и отчитались обычной неудачей: devmap-selfheal
# «попробую в следующий раз», ton-watch «повторим завтра», check-builder
# «агент строителя вернул 1». Карта не чинилась двое суток, и владелец не
# услышал ни слова. Сторож limit-watch тут не помощник: он судит по отказам
# 429 в журнале СМЕНЫ, а headless-прогон демона в тот журнал не пишет.
#
# Что делает обёртка:
#   • зовёт claude с переданными доводами (и всегда --strict-mcp-config:
#     без него headless-вызов отбирает канал у живой сессии владельца);
#   • распознаёт отказ ПО ЛИМИТУ и отдаёт его СВОИМ кодом 77 — демон больше
#     не путает «модель отказала» с «модель занята до среды»;
#   • говорит владельцу про ПОВТОРЯЮЩИЙСЯ отказ ЛЮБОГО вида — см. ниже;
#   • говорит владельцу ОДИН раз на период: состояние — файл с датой сброса,
#     второй демон в тот же период молчит;
#   • о снятии говорит ровно один раз, тем же файлом.
#
# СЛУЧАЙ 15–21.09.2026 — та же болезнь, другой класс отказа. Долгий токен
# перестали принимать: «Your organization has disabled Claude subscription
# access for Claude Code». Слова лимита в этом отказе нет, поэтому он прошёл
# мимо разбора выше и стал «обычной неудачей»: демоны шесть суток писали себе
# в лог «попробую в следующий раз», и владелец узнал об этом сам.
#
# Перечислить все тексты отказов нельзя — этого мы и не знали заранее. Признак
# берётся не из словаря, а из ПОВТОРА: обычная неудача задания случайна, отказ
# доступа приходит снова и снова одной и той же первой строкой. Второй
# одинаковый отказ подряд — у этого демона или у соседнего — доходит до
# владельца один раз, как лимит. Прекращение — тоже один раз.
#
#   bash scripts/claude-demon.sh <имя-демона> <доводы claude...>
# Код возврата: 77 — отказ по лимиту, иначе код самой модели.
set -uo pipefail
export LC_ALL=C.UTF-8

HERE="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" && pwd)"
# shellcheck disable=SC1091
source "$HERE/lib/config.sh"
konf_zagruzit

# Каталог проекта — из паспорта установки, без умолчания нашей машины.
PROJECT_DIR="${PROJECT_DIR:?пуст PROJECT_DIR — не прочитан паспорт установки}"
# Канал подменяем ТОЛЬКО переменной: проба ставит свой, боевой путь — по умолчанию.
TG_SEND="${TG_SEND:-$PROJECT_DIR/scripts/tg_send.sh}"
SOSTOYANIE="$LOG_DIR/лимит-демонов.состояние"
# Подпись повторяющегося отказа НЕ по лимиту и метка «владельцу сказано».
OTKAZ="$LOG_DIR/отказ-демонов.состояние"
OTKAZ_SKAZANO="$LOG_DIR/отказ-демонов.сказано"
ZHURNAL="$LOG_DIR/claude-demon.log"
KOD_LIMITA=77

DEMON="${1:?первым доводом — имя демона}"
shift

say() { printf '%s  %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$*" >>"$ZHURNAL"; }

skazat() {  # $1 = текст, $2 = ключ двери (необязателен); отказ канала не роняет демона
    # Код 3 двери канала — ПРИДЕРЖАНО: стоит метка лимита подписки, и о нём
    # владельцу уже сказано (его правило 17.10.2026 — одно сообщение о лимите).
    # Это не сбой: звонящему важно знать, что обещание «скажу, когда снимется»
    # он не давал, иначе о снятии он сообщит про то, о чём молчал.
    local rc=0
    bash "$TG_SEND" "$1" ${2:+"$2"} >/dev/null 2>&1 || rc=$?
    case "$rc" in
        0) return 0 ;;
        3) say "придержано дверью канала (стоит метка лимита): $1"; return 3 ;;
        *) say "сказать владельцу не удалось: $1"; return 1 ;;
    esac
}

# ── Пауза владельца: модель не зовём и владельцу не пишем ───────────────────
# СЛУЧАЙ 23–26.09.2026. Владелец стоял на паузе трое суток, а в канал ему
# приходило «Лимит подписки: фоновый демон „check-builder" не получил ответ
# модели». Его вопрос: «Почему писал о лимитах во время паузы». Упоминаний
# паузы в этом файле было НОЛЬ, а через него модель зовут ВСЕ демоны.
#
# Проверка стоит ЗДЕСЬ, а не в каждом демоне: правило, размазанное по двадцати
# файлам, держится вниманием — новый демон о нём просто не узнает
# ([[a-rule-the-agent-enforces-on-itself]]). Своих 77 и кодов модели не
# занимаем: 78 — «не звали», и это не отказ, поэтому счёт повторяющихся отказов
# не трогается.
#
# Заодно снимается расход в простое: 24–25.09 модель звала одна фоновая проба,
# по 21,0k контекста на вызов, и владелец за это платил, стоя на паузе.
KOD_PAUZY=78
if python3 "$PROJECT_DIR/scripts/pause.py" --идёт-ли 2>/dev/null; then
    say "$DEMON: владелец поставил паузу — модель не зову, владельцу не пишу"
    exit "$KOD_PAUZY"
fi

# Судью факта «лимит подписки» держит ОДИН прибор — limit-in-log.py:
# у него уже два потребителя (session-warden и limit-watch читают журнал
# сессии), и третья копия разбора разошлась бы с ними молча. Здесь у того же
# факта другой носитель: headless-прогон в журнал не пишет, отказ приходит
# ТЕКСТОМ на экран.
SUDYA="$PROJECT_DIR/scripts/limit-in-log.py"

# Формат вывода ставит обёртка, а не демон: в stream-json отказ API назван
# полями result, и слова ответа модели («429», «rate limit») больше не
# принимаются за лимит. Переданный демоном --output-format вырезается.
DOVODY=()
while [ $# -gt 0 ]; do
    case "$1" in
        --output-format) shift; [ $# -gt 0 ] && shift; continue ;;
        --output-format=*|--verbose) shift; continue ;;
    esac
    DOVODY+=("$1"); shift
done
DOVODY=(--strict-mcp-config --output-format stream-json --verbose "${DOVODY[@]}")

POTOK_KAT="$LOG_DIR/demon-stream"
RASHOD="$LOG_DIR/demon-spend.jsonl"
mkdir -p "$POTOK_KAT"

# Агент демона работает из пустого временного каталога: .claude/settings.json проекта
# у него не грузится. Сторож записи память/ORDERS.md подключается явно, абсолютным
# путём; признак демона HARNESS_DEMON он читает из окружения.
export HARNESS_DEMON="$DEMON"
ORDERS_HOOK_SETTINGS="$(jq -nc --arg c "python3 $PROJECT_DIR/scripts/hooks/orders_write_guard.py" \
    '{hooks: {PreToolUse: [{matcher: "Write|Edit|NotebookEdit|Bash", hooks: [{type: "command", command: $c, timeout: 5}]}]}}')"

VYVOD_FAJL="$(mktemp)"
OSHIBKI_FAJL="$(mktemp)"
SUD_FAJL="$(mktemp)"
TEKST_FAJL="$(mktemp)"
trap 'rm -f "$VYVOD_FAJL" "$OSHIBKI_FAJL" "$SUD_FAJL" "$TEKST_FAJL"' EXIT

# Сырой поток растёт на каждый вызов (tee -a): сверх потолка из данных остаётся
# хвост по границе строки — последний вызов цел, начало файла (может быть
# обрезано посреди строки) выбрасывается до первого перевода строки.
potok_urezat() {
    local fajl="$1" potolok=$(( ${DEMON_STREAM_MAX_KB:-4096} * 1024 ))
    [ "$(stat -c %s "$fajl" 2>/dev/null || echo 0)" -gt "$potolok" ] || return 0
    tail -c "$potolok" "$fajl" | sed '1d' >"$fajl.urezka" && mv "$fajl.urezka" "$fajl"
}
# Первая НЕПУСТАЯ строка текста — подпись отказа (из result, не из JSON).
# Пустая строка подписью быть не может: тогда любые два молчаливых отказа
# слились бы в один.
podpis() { grep -m1 -v '^[[:space:]]*$' "$TEKST_FAJL" 2>/dev/null | cut -c1-200; }

# Повторяющийся отказ НЕ по лимиту: та же дисциплина, что у лимита — один раз
# на период, под тем же локом. Первый отказ молчит: обычная неудача задания
# случайна, и крик на каждую сделал бы сообщения шумом, который не читают.
otkaz_povtoryayushchijsya() {
    local teper proshloe
    teper="$(podpis)"
    [ -n "$teper" ] || teper="отказ без текста (код $KOD)"

    mkdir -p "$LOG_DIR/locks"
    exec 9>>"$LOG_DIR/locks/лимит-демонов.lock"
    flock 9

    proshloe="$(cat "$OTKAZ" 2>/dev/null || true)"
    if [ "$proshloe" != "$teper" ]; then
        printf '%s' "$teper" >"$OTKAZ"
        rm -f "$OTKAZ_SKAZANO"
        say "$DEMON: отказ не по лимиту, вижу впервые — молчу до повтора: $teper"
        return
    fi
    [ -f "$OTKAZ_SKAZANO" ] && return      # об этом отказе уже сказано

    say "$DEMON: отказ не по лимиту повторился — говорю владельцу: $teper"
    # Метка ставится ПО ФАКТУ доставки: прежде она стояла раньше отправки, и
    # придержанная весть пропала бы навсегда — об этом отказе больше не
    # говорят. Весть идёт БЕЗ ключа: отказ не по лимиту обновлением не лечится,
    # и дверь при лимите положит её в очередь досыла.
    skazat "Демоны не получают ответ модели. Отказ повторился у «$DEMON», код $KOD: $teper — работа фоновых демонов пропускается. Скажу, когда пройдёт." \
        && : >"$OTKAZ_SKAZANO"
}

# Здоровый вызов снимает оба состояния — и говорит об этом один раз: «встали»
# без «пошли» держит владельца в тревоге дольше, чем длился простой.
otkaz_proshyol() {
    rm -f "$OTKAZ"
    [ -f "$OTKAZ_SKAZANO" ] || return
    rm -f "$OTKAZ_SKAZANO"
    say "отказ прекратился: $DEMON получил ответ модели — говорю владельцу"
    skazat "Прошло: фоновые демоны снова получают ответ модели (проверено демоном $DEMON)."
}

# Один вызов модели и разбор его вывода. Функция, а не скрипт сплошь: после
# автоперехода на другой ключ вызов повторяется, и каждому нужны свой id сессии
# (транскрипт головной сессии называется id) и своя строка demon.start до вызова —
# по ней разрешитель токенов узнаёт, чей это вызов. Печать ответа — после
# окончательного вызова: демон получает один ответ, а не отказ и ответ подряд.
vyzov_modeli() {
    SESSION_ID="$(cat /proc/sys/kernel/random/uuid)"
    local ZAPUSK=(--settings "$ORDERS_HOOK_SETTINGS" --session-id "$SESSION_ID" "${DOVODY[@]}")
    jq -nc --arg d "$DEMON" --arg s "$SESSION_ID" --arg w "$(date -Iseconds)" \
        '{event: "demon.start", "демон": $d, session_id: $s, "когда": $w}' >>"$RASHOD"

    # tee: сырой поток ложится в файл демона ПО ХОДУ, байт в байт; stderr отдельно,
    # чтобы его строки не попали в поток. Код берётся у первого звена конвейера.
    # Модель зовётся только через носитель: он собирает личность класса «демон» и
    # сам шлёт сигнал, если не собрал.
    bash "$PROJECT_DIR/scripts/claude-run.sh" --класс демон "${ZAPUSK[@]}" 2>"$OSHIBKI_FAJL" | tee -a "$POTOK_KAT/$DEMON.jsonl" >"$VYVOD_FAJL"
    KOD=${PIPESTATUS[0]}

    # 79: личность не собрана, модель не запускалась. Это не отказ API и не лимит:
    # судью и счёт повторяющихся отказов не трогаем, владельцу не пишем (сигнал
    # уже дал носитель), код отдаём вызывающему как есть.
    if [ "$KOD" -eq 79 ]; then
        say "$DEMON: личность не собрана (носитель вернул 79) — модель не звана"
        exit 79
    fi

    potok_urezat "$POTOK_KAT/$DEMON.jsonl"

    # Судье — stdout и stderr вместе: при выводе без JSON отказ CLI приходит
    # текстом на stderr, и прежний разбор по тексту обязан его видеть.
    cat "$VYVOD_FAJL" "$OSHIBKI_FAJL" >"$SUD_FAJL"

    SBROS="$(python3 "$SUDYA" --в-потоке "$SUD_FAJL" 2>/dev/null)"
    SUD_KOD=$?

    if [ "$SUD_KOD" -eq 2 ]; then
        # «Не смог прочитать» и «не лимит» — разные ответы: молчащий судья снова
        # сделал бы лимит невидимым ([[unreadable-source-turns-check-green]]).
        say "$DEMON: судья лимита не ответил ($SUDYA) — отказ разобран как обычный"
    fi

    if [ "$SUD_KOD" -eq 3 ]; then
        # Поток оборван: ни расхода, ни вердикта — слова в недописанном потоке
        # судить нельзя, а успехом обрыв быть не может. Подписью отказа служит
        # наша фраза, не текст модели: иначе её слова ушли бы владельцу.
        say "$DEMON: поток CLI оборван без итога (код $KOD) — отказ не по лимиту, не судим"
        echo "без итога: поток CLI оборван (код $KOD)" >&2
        echo "поток CLI оборван без итога" >"$TEKST_FAJL"
        [ "$KOD" -eq 0 ] && KOD=1
        otkaz_povtoryayushchijsya
        exit "$KOD"
    fi

    NET_ITOGA=1
    IS_ERROR=false
    if python3 "$SUDYA" --текст-итога "$SUD_FAJL" >"$TEKST_FAJL" 2>/dev/null \
       && python3 "$SUDYA" --расход "$SUD_FAJL" "$DEMON" "$(date -Iseconds)" >"$SUD_FAJL.rashod" 2>/dev/null; then
        NET_ITOGA=0
        cat "$SUD_FAJL.rashod" >>"$RASHOD"
        IS_ERROR="$(jq -r '.is_error' "$SUD_FAJL.rashod" 2>/dev/null || echo false)"
    fi
    rm -f "$SUD_FAJL.rashod"
}

pechat_otveta() {
    # Демону — только ответ модели. Вывод без JSON отдаётся целиком, как раньше.
    if [ "$NET_ITOGA" -eq 0 ]; then
        cat "$TEKST_FAJL"
    else
        cat "$SUD_FAJL" >"$TEKST_FAJL"
        cat "$TEKST_FAJL"
    fi
}

# Автопереход на другой аккаунт при отказе по лимиту (account-switch.py). Зовётся
# только когда аккаунты заведены. Лок — на время самого вызова двери: два демона
# в одну минуту получают её ответы по очереди (0, затем 5), а повтор модели идёт
# ВНЕ лока, иначе демоны ждали бы друг друга весь вызов. Код — в AUTO_RC, пусто — не звана.
avto_perehod() {
    AUTO_RC=""
    [ -f "${HARNESS_ACCOUNT_DIR:-${STATE_DIR:-}/account}/profiles.json" ] || return 0
    local out
    mkdir -p "$LOG_DIR/locks"
    exec 8>>"$LOG_DIR/locks/лимит-демонов.lock"
    flock 8
    AUTO_RC=0
    out=$(python3 "$PROJECT_DIR/scripts/account-switch.py" --авто --от демоны 2>&1) || AUTO_RC=$?
    flock -u 8
    say "$DEMON: авто: дверь автоперехода ответила кодом $AUTO_RC: $(printf '%s' "$out" | tr '\n' ' ' | head -c 300)"
}

vyzov_modeli
if [ "$SUD_KOD" -eq 0 ]; then
    avto_perehod
    case "$AUTO_RC" in
        0|5)
            say "$DEMON: авто: аккаунт сменён дверью, повторяю вызов модели"
            vyzov_modeli
            if [ "$SUD_KOD" -eq 0 ]; then
                say "$DEMON: авто: после перехода снова отказ по лимиту ($SBROS) — о лимите говорит дверь"
                pechat_otveta
                exit "$KOD_LIMITA"
            fi ;;
        4|6)
            say "$DEMON: авто: все аккаунты в лимите или предел неудач (код $AUTO_RC) — о лимите говорит дверь"
            pechat_otveta
            exit "$KOD_LIMITA" ;;
    esac
fi
pechat_otveta

if [ "$SUD_KOD" -ne 0 ]; then
    # Отказ API при коде CLI 0 успехом не считается (код при отказе не замерен).
    if [ "$IS_ERROR" = true ] && [ "$KOD" -eq 0 ]; then KOD=1; fi
    if [ "$KOD" -eq 0 ]; then
        if [ -f "$SOSTOYANIE" ]; then
            rm -f "$SOSTOYANIE"
            # О снятии говорим ТОЛЬКО тому, кому сказали о самом лимите.
            # 17.10.2026 владелец получил «Лимит снят» через 34 минуты после
            # «Лимит обновился» от смены — два сообщения об одном событии, а
            # его слово: «зачем потом столько сообщений слать об одном и том же».
            if [ -f "$SOSTOYANIE.сказано" ]; then
                rm -f "$SOSTOYANIE.сказано"
                say "лимит снят: $DEMON получил ответ модели — говорю владельцу"
                skazat "Лимит снят: фоновые демоны снова получают ответ модели (проверено демоном $DEMON)."
            else
                say "лимит снят: $DEMON получил ответ модели; о самом лимите владельцу не говорили — молчу и о снятии"
            fi
        fi
        otkaz_proshyol
    else
        otkaz_povtoryayushchijsya
    fi
    exit "$KOD"
fi

say "$DEMON: отказ по лимиту ($SBROS) — работа демона пропущена"

# Проверка и запись состояния — под локом: cron будит демонов В ОДНУ минуту
# (04:15, 05:15, 05:45 стоят рядом не случайно), и без лока каждый увидел бы
# «файла нет» и написал владельцу своё сообщение об одном и том же лимите.
mkdir -p "$LOG_DIR/locks"
exec 8>>"$LOG_DIR/locks/лимит-демонов.lock"
flock 8

if [ -f "$SOSTOYANIE" ] && [ "$(cat "$SOSTOYANIE" 2>/dev/null)" = "$SBROS" ]; then
    exit "$KOD_LIMITA"     # об этом периоде уже сказано — второй раз не пишем
fi

printf '%s' "$SBROS" >"$SOSTOYANIE"
# Час в тексте уже 24-часовой и по-русски: его переводит судья лимита
# (limit-in-log.py: в_24_часа), а не это сообщение — иначе переводов стало
# бы два. Сообщение идёт через дверь канала БЕЗ ключа: пока стоит метка
# лимита, владельцу о нём уже сказано, и дверь это придержит.
# «--не-досылать»: после обновления эта весть смысла не имеет — демон отработает
# сам, а залп устаревших сообщений и есть то, на что владелец пожаловался.
if skazat "Лимит подписки: фоновый демон «$DEMON» не получил ответ модели, $SBROS. Его работа на этот период пропускается — скажу, когда лимит снимется." --не-досылать; then
    : > "$SOSTOYANIE.сказано"       # обещание дано — о снятии скажем
fi
exit "$KOD_LIMITA"
