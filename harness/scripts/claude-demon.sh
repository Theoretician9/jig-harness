#!/usr/bin/env bash
# Вызов модели ДЕМОНОМ: один вход для всех фоновых прогонов.
#
# СЛУЧАЙ 13.09.2026. Три демона получили «You've hit your weekly limit ·
# resets Sep 16, 6pm» и отчитались обычной неудачей: devmap-selfheal
# «попробую в следующий раз», ton-watch «повторим завтра», stroitel-proverok
# «агент строителя вернул 1». Карта не чинилась двое суток, и владелец не
# услышал ни слова. Сторож limit-watch тут не помощник: он судит по отказам
# 429 в журнале СМЕНЫ, а headless-прогон демона в тот журнал не пишет.
#
# Что делает обёртка:
#   • зовёт claude с переданными доводами (и всегда --strict-mcp-config:
#     без него headless-вызов отбирает канал у живой сессии владельца);
#   • распознаёт отказ ПО ЛИМИТУ и отдаёт его СВОИМ кодом 77 — демон больше
#     не путает «модель отказала» с «модель занята до среды»;
#   • говорит владельцу про ПОВТОРЯЮЩИЙСЯ отказ ЛЮБОГО вида — см. ниже;
#   • говорит владельцу ОДИН раз на период: состояние — файл с датой сброса,
#     второй демон в тот же период молчит;
#   • о снятии говорит ровно один раз, тем же файлом.
#
# СЛУЧАЙ 15–21.09.2026 — та же болезнь, другой класс отказа. Долгий токен
# перестали принимать: «Your organization has disabled Claude subscription
# access for Claude Code». Слова лимита в этом отказе нет, поэтому он прошёл
# мимо разбора выше и стал «обычной неудачей»: демоны шесть суток писали себе
# в лог «попробую в следующий раз», и владелец узнал об этом сам.
#
# Перечислить все тексты отказов нельзя — этого мы и не знали заранее. Признак
# берётся не из словаря, а из ПОВТОРА: обычная неудача задания случайна, отказ
# доступа приходит снова и снова одной и той же первой строкой. Второй
# одинаковый отказ подряд — у этого демона или у соседнего — доходит до
# владельца один раз, как лимит. Прекращение — тоже один раз.
#
#   bash scripts/claude-demon.sh <имя-демона> <доводы claude...>
# Код возврата: 77 — отказ по лимиту, иначе код самой модели.
set -uo pipefail
export LC_ALL=C.UTF-8

HERE="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" && pwd)"
# shellcheck disable=SC1091
source "$HERE/lib/config.sh"
konf_zagruzit

# Каталог проекта — из паспорта установки, без умолчания нашей машины.
PROJECT_DIR="${PROJECT_DIR:?пуст PROJECT_DIR — не прочитан паспорт установки}"
# Канал подменяем ТОЛЬКО переменной: проба ставит свой, боевой путь — по умолчанию.
TG_SEND="${TG_SEND:-$PROJECT_DIR/scripts/tg_send.sh}"
SOSTOYANIE="$LOG_DIR/лимит-демонов.состояние"
# Подпись повторяющегося отказа НЕ по лимиту и метка «владельцу сказано».
OTKAZ="$LOG_DIR/отказ-демонов.состояние"
OTKAZ_SKAZANO="$LOG_DIR/отказ-демонов.сказано"
ZHURNAL="$LOG_DIR/claude-demon.log"
KOD_LIMITA=77

DEMON="${1:?первым доводом — имя демона}"
shift

say() { printf '%s  %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$*" >>"$ZHURNAL"; }

skazat() {  # одно сообщение владельцу; отказ канала не роняет демона
    bash "$TG_SEND" "$1" >/dev/null 2>&1 || say "сказать владельцу не удалось: $1"
}

# ── Пауза владельца: модель не зовём и владельцу не пишем ───────────────────
# СЛУЧАЙ 23–26.09.2026. Владелец стоял на паузе трое суток, а в канал ему
# приходило «Лимит подписки: фоновый демон „stroitel-proverok" не получил ответ
# модели». Его вопрос: «Почему писал о лимитах во время паузы». Упоминаний
# паузы в этом файле было НОЛЬ, а через него модель зовут ВСЕ демоны.
#
# Проверка стоит ЗДЕСЬ, а не в каждом демоне: правило, размазанное по двадцати
# файлам, держится вниманием — новый демон о нём просто не узнает
# ([[a-rule-the-agent-enforces-on-itself]]). Своих 77 и кодов модели не
# занимаем: 78 — «не звали», и это не отказ, поэтому счёт повторяющихся отказов
# не трогается.
#
# Заодно снимается расход в простое: 24–25.09 модель звала одна фоновая проба,
# по 21,0k контекста на вызов, и владелец за это платил, стоя на паузе.
KOD_PAUZY=78
if python3 "$PROJECT_DIR/scripts/pause.py" --идёт-ли 2>/dev/null; then
    say "$DEMON: владелец поставил паузу — модель не зову, владельцу не пишу"
    exit "$KOD_PAUZY"
fi

# Судью факта «лимит подписки» держит ОДИН прибор — limit-in-log.py:
# у него уже два потребителя (session-warden и limit-watch читают журнал
# сессии), и третья копия разбора разошлась бы с ними молча. Здесь у того же
# факта другой носитель: headless-прогон в журнал не пишет, отказ приходит
# ТЕКСТОМ на экран.
SUDYA="$PROJECT_DIR/scripts/limit-in-log.py"

DOVODY=("$@")
case " ${DOVODY[*]:-} " in
    *" --strict-mcp-config "*) ;;
    *) DOVODY=(--strict-mcp-config "${DOVODY[@]}") ;;
esac

VYVOD_FAJL="$(mktemp)"
trap 'rm -f "$VYVOD_FAJL"' EXIT
# tee, а не перенаправление: демон пишет вывод модели в свой лог ПО ХОДУ, и
# копить его до конца прогона значит потерять картину зависшего вызова. Код
# берётся у первого звена конвейера — код tee нам не интересен.
claude "${DOVODY[@]}" 2>&1 | tee "$VYVOD_FAJL"
KOD=${PIPESTATUS[0]}

SBROS="$(python3 "$SUDYA" --в-тексте "$VYVOD_FAJL" 2>/dev/null)"
SUD_KOD=$?

if [ "$SUD_KOD" -eq 2 ]; then
    # «Не смог прочитать» и «не лимит» — разные ответы: молчащий судья снова
    # сделал бы лимит невидимым ([[unreadable-source-turns-check-green]]).
    say "$DEMON: судья лимита не ответил ($SUDYA) — отказ разобран как обычный"
fi

# Первая НЕПУСТАЯ строка вывода — подпись отказа. Пустая строка подписью быть
# не может: тогда любые два молчаливых отказа слились бы в один.
podpis() { grep -m1 -v '^[[:space:]]*$' "$VYVOD_FAJL" 2>/dev/null | cut -c1-200; }

# Повторяющийся отказ НЕ по лимиту: та же дисциплина, что у лимита — один раз
# на период, под тем же локом. Первый отказ молчит: обычная неудача задания
# случайна, и крик на каждую сделал бы сообщения шумом, который не читают.
otkaz_povtoryayushchijsya() {
    local teper proshloe
    teper="$(podpis)"
    [ -n "$teper" ] || teper="отказ без текста (код $KOD)"

    mkdir -p "$LOG_DIR/locks"
    exec 9>>"$LOG_DIR/locks/лимит-демонов.lock"
    flock 9

    proshloe="$(cat "$OTKAZ" 2>/dev/null || true)"
    if [ "$proshloe" != "$teper" ]; then
        printf '%s' "$teper" >"$OTKAZ"
        rm -f "$OTKAZ_SKAZANO"
        say "$DEMON: отказ не по лимиту, вижу впервые — молчу до повтора: $teper"
        return
    fi
    [ -f "$OTKAZ_SKAZANO" ] && return      # об этом отказе уже сказано

    : >"$OTKAZ_SKAZANO"
    say "$DEMON: отказ не по лимиту повторился — говорю владельцу: $teper"
    skazat "Демоны не получают ответ модели. Отказ повторился у «$DEMON», код $KOD: $teper — работа фоновых демонов пропускается. Скажу, когда пройдёт."
}

# Здоровый вызов снимает оба состояния — и говорит об этом один раз: «встали»
# без «пошли» держит владельца в тревоге дольше, чем длился простой.
otkaz_proshyol() {
    rm -f "$OTKAZ"
    [ -f "$OTKAZ_SKAZANO" ] || return
    rm -f "$OTKAZ_SKAZANO"
    say "отказ прекратился: $DEMON получил ответ модели — говорю владельцу"
    skazat "Прошло: фоновые демоны снова получают ответ модели (проверено демоном $DEMON)."
}

if [ "$SUD_KOD" -ne 0 ]; then
    if [ "$KOD" -eq 0 ]; then
        if [ -f "$SOSTOYANIE" ]; then
            rm -f "$SOSTOYANIE"
            say "лимит снят: $DEMON получил ответ модели — говорю владельцу"
            skazat "Лимит снят: фоновые демоны снова получают ответ модели (проверено демоном $DEMON)."
        fi
        otkaz_proshyol
    else
        otkaz_povtoryayushchijsya
    fi
    exit "$KOD"
fi

say "$DEMON: отказ по лимиту ($SBROS) — работа демона пропущена"

# Проверка и запись состояния — под локом: cron будит демонов В ОДНУ минуту
# (04:15, 05:15, 05:45 стоят рядом не случайно), и без лока каждый увидел бы
# «файла нет» и написал владельцу своё сообщение об одном и том же лимите.
mkdir -p "$LOG_DIR/locks"
exec 8>>"$LOG_DIR/locks/лимит-демонов.lock"
flock 8

if [ -f "$SOSTOYANIE" ] && [ "$(cat "$SOSTOYANIE" 2>/dev/null)" = "$SBROS" ]; then
    exit "$KOD_LIMITA"     # об этом периоде уже сказано — второй раз не пишем
fi

printf '%s' "$SBROS" >"$SOSTOYANIE"
skazat "Лимит подписки: фоновый демон «$DEMON» не получил ответ модели ($SBROS). Его работа на этот период пропускается — скажу, когда лимит снимется."
exit "$KOD_LIMITA"
