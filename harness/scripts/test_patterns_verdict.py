def _загрузить_ворота(пустой_каталог: str):
    # Ключи ручек и паспорт ворота читают у носителя; стенд даёт его сам в каждом случае
    # (_открыто). Файл ручек — для своих ключей двери, судья окружение не слушает.
    конфиги = Path(пустой_каталог) / "конфиги"
    конфиги.mkdir()
    (конфиги / "harness.conf").write_text(
        "".join(f'{к}="{з}"\n' for к, з in РУЧКИ.items()), encoding="utf-8")
    os.environ["HARNESS_CONF"] = str(конфиги / "harness.conf")
    os.environ["HARNESS_LOG_DIR"] = пустой_каталог
    спец = importlib.util.spec_from_file_location("deploy_guard_под_пробой", ВОРОТА)
    ворота = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(ворота)
    return ворота


def _метка(секунд_назад: float) -> str:
    return (datetime.datetime.now().astimezone().replace(microsecond=0)
            - datetime.timedelta(seconds=секунд_назад)).isoformat()


def _записи_диспетчера(судья, сообщение: str, номер: str) -> list:
    """Что положит в журнал диспетчер (согласие_владельца + zapisat_soglasiya):
    строка в нижнем регистре без краевых пробелов, «нет» не пишется, «текст» —
    без kind, остальные виды — kind. Запись диспетчера держит его самотест (П7)."""
    записи = []
    for строка in сообщение.splitlines():
        строка = строка.lower().strip()
        вид = судья(строка) if строка else "нет"
        if вид == "нет":
            continue
        записи.append({"ts": _метка(60), "text": строка, "message_id": номер,
                       **({} if вид == "текст" else {"kind": вид})})
    return записи


def _открыто(ворота, действие: str, *, записи=(), очередь=None, сообщение=None, кнопка=False) -> bool:
    """Ворота на своём стенде. `очередь` — сырой файл inbox/*.txt, `сообщение` — inbox.jsonl по
    номеру 1, `кнопка` — «Да» кнопкой на предмет «S» (предмет ворот подменён: считать его нечем)."""
    with tempfile.TemporaryDirectory(prefix="verdict-gate-") as tmp:
        двор = Path(tmp)
        ворота.ПРЕДМЕТЫ[действие] = lambda: "S"
        ворота._ПРЕДМЕТ.clear()
        (двор / "inbox.jsonl").write_text("", encoding="utf-8")
        if кнопка:
            вид = ворота.ВИД_ДЕЙСТВИЯ[действие]
            # Живой порядок: просьба ask-consent раньше нажатия, нажатие — с from_id владельца.
            (двор / "consent-requests.jsonl").write_text(json.dumps(
                {"v": 1, "ts": _метка(90), "src": "scripts/ask-consent.py", "event": "consent.request",
                 "outcome": "ok", "data": {"nonce": "n", "вид": вид, "цель": "S", "почему": "проба"}},
                ensure_ascii=False) + "\n", encoding="utf-8")
            данные = {"nonce": "n", "вид": вид, "цель": "S", "message_id": 5, "from_id": ВЛАДЕЛЕЦ}
            (двор / "consent-buttons.jsonl").write_text(json.dumps(
                {"v": 1, "ts": _метка(60), "src": "проба", "event": "consent.yes", "outcome": "ok",
                 "data": данные}, ensure_ascii=False) + "\n", encoding="utf-8")
        (двор / "confirmations.jsonl").write_text(
            "".join(json.dumps(з, ensure_ascii=False) + "\n" for з in записи), encoding="utf-8")
        if очередь is not None:
            (двор / "inbox").mkdir()
            (двор / "inbox" / "1.txt").write_text(очередь, encoding="utf-8")
        if сообщение is not None:
            (двор / "inbox.jsonl").write_text(json.dumps(
                {"ts": datetime.datetime.now().astimezone().isoformat(timespec="seconds"),
                 "message_id": "1", "text": сообщение}, ensure_ascii=False) + "\n",
                encoding="utf-8")
        ворота.LOG_DIR = двор
        судья = ворота.слово_вл
        носитель = судья.Носитель(папка=двор, uid=None, паспорт=dict(ПАСПОРТ), граница=двор, окно_мин=60,
                                  срок_кнопки_мин=None, ручки=dict(РУЧКИ))
        судья.носитель = lambda: носитель
        with contextlib.redirect_stdout(io.StringIO()):
            return ворота.нет_согласия(действие) is None


def _формы_приказов(ворота, судья_модуль) -> set:
    """Формы приказов у ОБОИХ судей: глаголы судьи и таблица ворот, пока она у
    них своя (после переезда в patterns.py — общая). Таблица — регулярка с
    перечнем `(?:а|б)` или список слов. Перепись — своя дверь, см. таблицу."""
    формы = set(судья_модуль.ГЛАГОЛЫ_РАСПОРЯЖЕНИЯ)
    for таблица in (getattr(ворота, "РАСПОРЯЖЕНИЕ", {}), getattr(судья_модуль, "РАСПОРЯЖЕНИЯ", {})):
        for действие, слова in таблица.items():
            if действие == "перепись":
                continue
            образец = getattr(слова, "pattern", None)
            if образец is None:
                формы.update(слова)
                continue
            перечень = re.search(r"\(\?:([^()]*)\)", образец)
            формы.update(перечень.group(1).split("|") if перечень else [f"<не разобрано: {образец}>"])
    return формы


def _таблица_форм(путь_ок, путь_плохо) -> None:
    спец = importlib.util.spec_from_file_location("patterns_для_таблицы", СУДЬЯ)
    судья_модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(судья_модуль)
    # Судья в таблице зовётся функцией: форма вызова оболочкой доказана случаями
    # выше, а таблица — сотня строк на две дороги, и прогон обязан уложиться в
    # предел мутационной пробы (MUTATION_RUN_TIMEOUT_S).
    судья = судья_модуль.вердикт_согласия
    with tempfile.TemporaryDirectory(prefix="verdict-gate-empty-") as пусто:
        ворота = _загрузить_ворота(пусто)
        # Живость стенда: «Да» кнопкой открывает каждую дверь, слово «да» — ни одну.
        # Иначе таблица ниже мерила бы закрытую дверь, а не правило.
        живой = all(_открыто(ворота, д, кнопка=True)
                    and not _открыто(ворота, д, записи=_записи_диспетчера(судья, "да", "1"), очередь="да")
                    for д in ("deploy", "push", "публикация", "dropdb"))
        if not живой:
            путь_плохо("стенд ворот не годен: «Да» кнопкой не открывает или слово «да» открывает")
            return
        путь_ок("стенд ворот жив: «Да» кнопкой открывает, слово «да» не открывает")
        приказы = _формы_приказов(ворота, судья_модуль)
        без_строки = sorted(п for п in приказы
                            if not any(ф == п or ф.startswith(п + " ") for ф, _ in ФОРМЫ_РАСПОРЯЖЕНИЯ))
        if not приказы or без_строки:
            путь_плохо(f"приказов у судьи и ворот {len(приказы)}, без строки таблицы: {без_строки}")
        else:
            путь_ок(f"все {len(приказы)} приказов судьи и ворот стоят в таблице форм")
        for форма, действие in ФОРМЫ_РАСПОРЯЖЕНИЯ:
            for шаблон, ждём in ВАРИАНТЫ:
                сообщение = шаблон.format(форма)
                # Одна строка — её судит судья целиком; несколько — судья
                # видит их по одной, и за него отвечает дорога журнала.
                по_судье = (судья(сообщение.lower()) != "нет") if "\n" not in сообщение else "—"
                по_очереди = _открыто(ворота, действие, очередь=сообщение)
                по_журналу = _открыто(ворота, действие, сообщение=сообщение,
                                      записи=_записи_диспетчера(судья, сообщение, "1"))
                итог = (f"{действие} · «{сообщение.replace(chr(10), ' ⏎ ')}» · "
                        f"судья {по_судье}, очередь {по_очереди}, "
                        f"журнал {по_журналу}, ждём {ждём}; ворота текстом закрыты")
                if по_судье in (ждём, "—") and not по_очереди and not по_журналу:
                    путь_ок(итог)
                else:
                    путь_плохо(итог)
        # F2a: отказ после номера пункта другой строкой («2. не сегодня») гасит
        # согласие на любое действие. Ворота текстом закрыты и для «2. спасибо».
        for сообщение in ("выкатывай\n2. не сегодня", "выкатывай\n2) не надо", "да\n3. не сейчас",
                          "выкатывай\n2. спасибо"):
            for действие in ("deploy", "push", "публикация", "dropdb"):
                ждём = False
                по_очереди = _открыто(ворота, действие, очередь=сообщение)
                по_журналу = _открыто(ворота, действие, сообщение=сообщение,
                                      записи=_записи_диспетчера(судья, сообщение, "1"))
                итог = (f"F2a {действие} · «{сообщение.replace(chr(10), ' ⏎ ')}» · "
                        f"очередь {по_очереди}, журнал {по_журналу}, ждём {ждём}")
                (путь_ок if по_очереди == по_журналу == ждём else путь_плохо)(итог)
        # F2a после «Да» кнопкой: отказ про выкат другой строкой отзывает кнопку, «2. спасибо» — нет.
        for сообщение, открыто in (("выкатывай\n2. не сегодня", False), ("выкатывай\n2) не надо", False),
                                   ("выкатывай\n2. спасибо", True)):
            вышло = _открыто(ворота, "deploy", сообщение=сообщение, кнопка=True)
            (путь_ок if вышло == открыто else путь_плохо)(
                f"F2a кнопка · deploy · «Да», затем «{сообщение.replace(chr(10), ' ⏎ ')}» · "
                f"открыто {вышло}, ждём {открыто}")


def main() -> int:
    счёт = {"путей": 0, "неудач": 0}

    def путь_ок(текст):
        счёт["путей"] += 1
        print(f"  ок    {текст}")

    def путь_плохо(текст):
        счёт["путей"] += 1
        счёт["неудач"] += 1
        print(f"  ПЛОХО {текст}")

    глаголы = _глаголы_судьи()
    наши = {форма for форма, _ in ФОРМЫ_ПРИКАЗА}
    без_случая = [г for г in глаголы if г not in наши]
    if not глаголы or без_случая:
        путь_плохо(f"у судьи глаголов {len(глаголы)}, без случая здесь: {без_случая}")
    else:
        путь_ок(f"все {len(глаголы)} глаголов судьи судятся правилом вопроса и отсрочки")
    for строка, ждём, почему in СЛУЧАИ:
        код, вышло = вердикт(строка)
        if код == 0 and вышло == ждём:
            путь_ок(f"«{строка}» → {вышло} · {почему}")
        else:
            путь_плохо(f"«{строка}» → код {код}, «{вышло}», ждали «{ждём}» · {почему}")
    _таблица_форм(путь_ок, путь_плохо)
    print(f"ВЕРДИКТ-СОГЛАСИЯ: путей {счёт['путей']}, неудач {счёт['неудач']}")
    return 1 if счёт["неудач"] else 0


if __name__ == "__main__":
    sys.exit(main())
