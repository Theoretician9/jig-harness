#!/usr/bin/env python3
"""Проба судьи согласия: приказ на выкат словом «сделай деплой».

БОЛЬНОЙ СЛУЧАЙ: `patterns.py --вердикт-согласия "сделай деплой"` отвечал «нет», и так же
«задеплой» и «сделай выкат». Диспетчер судит согласие ЭТИМ ответом, так что
приказ владельца на выкат записью согласия не становился.

Согласие остаётся СЛОВОМ ([[consent-counts-only-as-a-word]]): цифра, вопрос,
существительное и приказ с отказом рядом — «нет».

Судья зовётся так же, как его зовёт диспетчер, — командой с ключом, и файл
берётся РЯДОМ с пробой: из копии дерева проба судит испорченную копию.
"""
import subprocess
import sys
from pathlib import Path

СУДЬЯ = Path(__file__).resolve().parent / "lib" / "patterns.py"

СЛУЧАИ = (
    # (строка владельца, вердикт, почему)
    ("сделай деплой", "deploy", "БОЛЬНОЙ СЛУЧАЙ: приказ «сделай» + предмет выката"),
    ("сделай выкат", "deploy", "БОЛЬНОЙ СЛУЧАЙ: тот же приказ своим словом"),
    ("задеплой", "deploy", "БОЛЬНОЙ СЛУЧАЙ: приказ одним глаголом"),
    ("Сделай деплой!", "deploy", "регистр и знак — та же форма"),
    ("деплой упал", "нет", "существительное — не приказ"),
    ("зачем ты сделал деплой?", "нет", "вопрос о прошлом — не приказ"),
    ("не делай деплой", "нет", "отказ перед приказом"),
    ("сделай деплой, нет", "нет", "отказ после приказа"),
    ("задеплоил?", "нет", "вопрос — не приказ"),
    ("сделай деплой?", "нет", "БОЛЬНОЙ СЛУЧАЙ: вопрос формой приказа — не согласие"),
    ("задеплой?", "нет", "БОЛЬНОЙ СЛУЧАЙ: вопрос одним глаголом — не согласие"),
    ("сделай деплой завтра", "нет", "БОЛЬНОЙ СЛУЧАЙ: приказ на потом — не согласие сейчас"),
    ("сделай деплой сейчас", "deploy", "контроль: слово времени «сейчас» приказа не гасит"),
    ("сделай отчёт", "нет", "«сделай» без предмета выката — не согласие"),
    ("1", "нет", "цифра согласием не считается"),
    ("выкатывай", "deploy", "контроль: прежняя форма не потеряна"),
    ("да, давай про деплой", "текст", "контроль: прежний вид из самотеста судьи"),
)


def вердикт(строка: str) -> tuple[int, str]:
    вышло = subprocess.run([sys.executable, str(СУДЬЯ), "--вердикт-согласия", строка],
                           capture_output=True, text=True, timeout=30)
    return вышло.returncode, вышло.stdout.strip()


def main() -> int:
    неудач = 0
    for строка, ждём, почему in СЛУЧАИ:
        код, вышло = вердикт(строка)
        if код == 0 and вышло == ждём:
            print(f"  ок    «{строка}» → {вышло} · {почему}")
        else:
            неудач += 1
            print(f"  ПЛОХО «{строка}» → код {код}, «{вышло}», ждали «{ждём}» · {почему}")
    print(f"ВЕРДИКТ-СОГЛАСИЯ: путей {len(СЛУЧАИ)}, неудач {неудач}")
    return 1 if неудач else 0


if __name__ == "__main__":
    sys.exit(main())
