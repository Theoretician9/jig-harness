#!/usr/bin/env python3
"""Проба судьи согласия: приказ на выкат словом «сделай деплой».

БОЛЬНОЙ СЛУЧАЙ: `patterns.py --вердикт-согласия "сделай деплой"` отвечал «нет», и так же
«задеплой» и «сделай выкат». Диспетчер судит согласие ЭТИМ ответом, так что
приказ владельца на выкат записью согласия не становился.

Согласие остаётся СЛОВОМ ([[consent-counts-only-as-a-word]]): цифра, вопрос,
существительное и приказ с отказом рядом — «нет».

Судья зовётся так же, как его зовёт диспетчер, — командой с ключом, и файл
берётся РЯДОМ с пробой: из копии дерева проба судит испорченную копию.
"""
import importlib.util
import subprocess
import sys
from pathlib import Path

СУДЬЯ = Path(__file__).resolve().parent / "lib" / "patterns.py"

# ОДНО ПРАВИЛО ДЛЯ ВСЕХ ФОРМ ПРИКАЗА: вопрос и отсрочка гасят любой приказ,
# «сейчас» — ни один. Формы и вид согласия выписаны АБСОЛЮТНО, а не взяты из
# судьи: мутация, урезавшая список судьи, урезала бы и пробу. Обратную сторону
# держит сверка ниже — глагол, добавленный в судью без случая здесь, красит пробу.
ФОРМЫ_ПРИКАЗА = (
    # (форма приказа, вид согласия на «форма сейчас»)
    ("выкатывай", "deploy"), ("выкати", "deploy"), ("задеплой", "deploy"),
    ("сделай деплой", "deploy"), ("сделай выкат", "deploy"),
    ("публикуй", "any"), ("опубликуй", "any"),
    ("отправляй", "текст"), ("отправь", "текст"),
)
ВОПРОСЫ = ("?", " ?", ", когда проверишь?")
# Отсрочка — не только слова из списка судьи: «вечером» и «через час» тоже
# переносят выкат с «сейчас» на потом.
ОТСРОЧКИ = (" завтра", " послезавтра", " потом", ", когда проверишь",
            " вечером", " утром", " через час", " после обеда", " в понедельник",
            " попозже")
СЕЙЧАС = (" сейчас", " прямо сейчас")


def _случаи_всех_форм() -> tuple:
    случаи = []
    for форма, вид in ФОРМЫ_ПРИКАЗА:
        случаи += [(форма + в, "нет", "БОЛЬНОЙ СЛУЧАЙ: вопрос формой приказа")
                   for в in ВОПРОСЫ]
        случаи += [(форма + о, "нет", "БОЛЬНОЙ СЛУЧАЙ: приказ на потом")
                   for о in ОТСРОЧКИ]
        случаи += [(форма + с, вид, "контроль: приказ сейчас — согласие")
                   for с in СЕЙЧАС]
    return tuple(случаи)


ЖИВЫЕ_ФОРМЫ = (
    ("можно выкатывать?", "нет", "вопрос-разрешение — не приказ"),
    ("выкатывай!", "deploy", "контроль: знак восклицания приказа не гасит"),
    ("да, выкатывай на прод", "deploy", "контроль: законное согласие"),
    ("отправляй позже", "нет", "контроль: «позже» — слово отказа"),
    ("выкатывай, проверю потом, если что не так — откатим", "deploy",
     "граница правила: «потом» про ПРОВЕРКУ, не про выкат — ворота это уже "
     "числят согласием (test_deploy_guard_consent.py), судья обязан так же"),
)


def _глаголы_судьи() -> tuple:
    спец = importlib.util.spec_from_file_location("patterns_под_пробой", СУДЬЯ)
    модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(модуль)
    return модуль.ГЛАГОЛЫ_РАСПОРЯЖЕНИЯ


СЛУЧАИ = _случаи_всех_форм() + ЖИВЫЕ_ФОРМЫ + (
    # (строка владельца, вердикт, почему)
    ("сделай деплой", "deploy", "БОЛЬНОЙ СЛУЧАЙ: приказ «сделай» + предмет выката"),
    ("сделай выкат", "deploy", "БОЛЬНОЙ СЛУЧАЙ: тот же приказ своим словом"),
    ("задеплой", "deploy", "БОЛЬНОЙ СЛУЧАЙ: приказ одним глаголом"),
    ("Сделай деплой!", "deploy", "регистр и знак — та же форма"),
    ("деплой упал", "нет", "существительное — не приказ"),
    ("зачем ты сделал деплой?", "нет", "вопрос о прошлом — не приказ"),
    ("не делай деплой", "нет", "отказ перед приказом"),
    ("сделай деплой, нет", "нет", "отказ после приказа"),
    ("задеплоил?", "нет", "вопрос — не приказ"),
    ("сделай деплой?", "нет", "БОЛЬНОЙ СЛУЧАЙ: вопрос формой приказа — не согласие"),
    ("задеплой?", "нет", "БОЛЬНОЙ СЛУЧАЙ: вопрос одним глаголом — не согласие"),
    ("сделай деплой завтра", "нет", "БОЛЬНОЙ СЛУЧАЙ: приказ на потом — не согласие сейчас"),
    ("сделай деплой сейчас", "deploy", "контроль: слово времени «сейчас» приказа не гасит"),
    ("сделай отчёт", "нет", "«сделай» без предмета выката — не согласие"),
    ("1", "нет", "цифра согласием не считается"),
    ("выкатывай", "deploy", "контроль: прежняя форма не потеряна"),
    ("да, давай про деплой", "текст", "контроль: прежний вид из самотеста судьи"),
)


def вердикт(строка: str) -> tuple[int, str]:
    вышло = subprocess.run([sys.executable, str(СУДЬЯ), "--вердикт-согласия", строка],
                           capture_output=True, text=True, timeout=30)
    return вышло.returncode, вышло.stdout.strip()


def main() -> int:
    неудач = 0
    глаголы = _глаголы_судьи()
    наши = {форма for форма, _ in ФОРМЫ_ПРИКАЗА}
    без_случая = [г for г in глаголы if г not in наши]
    if not глаголы or без_случая:
        неудач += 1
        print(f"  ПЛОХО у судьи глаголов {len(глаголы)}, без случая здесь: {без_случая}")
    else:
        print(f"  ок    все {len(глаголы)} глаголов судьи судятся правилом вопроса и отсрочки")
    for строка, ждём, почему in СЛУЧАИ:
        код, вышло = вердикт(строка)
        if код == 0 and вышло == ждём:
            print(f"  ок    «{строка}» → {вышло} · {почему}")
        else:
            неудач += 1
            print(f"  ПЛОХО «{строка}» → код {код}, «{вышло}», ждали «{ждём}» · {почему}")
    print(f"ВЕРДИКТ-СОГЛАСИЯ: путей {len(СЛУЧАИ)}, неудач {неудач}")
    return 1 if неудач else 0


if __name__ == "__main__":
    sys.exit(main())
