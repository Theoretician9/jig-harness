# Ворота, загрузка ключей и сверка секретов остаются здесь: их судят по тексту этого файла.
# shellcheck disable=SC1091
source "$SCRIPT_DIR/lib/door_stages.sh"

# ── 0. Продукт задан? Три ветви ─────────────────────────────────────────────
# Выкат судит ПРОДУКТ: его репозиторий PRODUCT_REPO — предмет тега, сверки секретов,
# манифестов и файла расписания. Каталог харнеса предметом не служит ни при каких
# ключах: тег deploy-* в его репозитории и сверка не того дерева были бы выкатом
# мимо продукта (спека эталонного выката §5.4, Г1, Г2).
# (а) Ничего не объявлено — продукта ещё нет. Честный выход нулём, а не имитация
#     выката: харнес ставится на чистый сервер раньше первой строки кода продукта.
# (б) Продукт ОБЪЯВЛЕН (PRODUCT_DIR, PRODUCT_REPO или PRODUCT_PATH — последний кладёт
#     установщик, находка bkb 10.11.2026), а STACK_BUILD_CMD пуст — не «нечего», а
#     выкат мимо ворот: нуль здесь читался как «выкачено» (И-2).
# (в) Сборка задана, а репозиторий продукта нет — отказ до ворот с именем ключа.
if [ -z "${STACK_BUILD_CMD:-}" ]; then
    if [ -z "${PRODUCT_DIR:-}${PRODUCT_REPO:-}${PRODUCT_PATH:-}" ]; then
        say "продукта нет (STACK_BUILD_CMD, PRODUCT_DIR, PRODUCT_REPO, PRODUCT_PATH пусты) — выкатывать нечего; заполни ключи продукта в $HARNESS_CONF с первой задачей продукта"
        exit 0
    fi
    say "ОШИБКА: продукт объявлен (PRODUCT_DIR=${PRODUCT_DIR:-}, PRODUCT_REPO=${PRODUCT_REPO:-}, PRODUCT_PATH=${PRODUCT_PATH:-}), а STACK_BUILD_CMD в $HARNESS_CONF пуст — заполни секцию STACK_*, деплой вслепую не выкатывает"
    say "  заготовка секции из compose продукта: python3 $SCRIPT_DIR/stack-template.py '${PRODUCT_PATH:-<каталог продукта>}' --в $HARNESS_CONF"
    exit 1
fi
if [ -z "${PRODUCT_REPO:-}" ]; then
    say "ОШИБКА: STACK_BUILD_CMD задан, а PRODUCT_REPO в $HARNESS_CONF пуст — выкату нужен репозиторий продукта (тег, сверка секретов, манифесты); каталог харнеса продуктом не служит, выкат отменён до ворот"
    exit 1
fi
PRODUCT_TREE="$PRODUCT_REPO"
cd "$PRODUCT_TREE"

# ── 0а. Ключи со значением: --ветка <имя> ───────────────────────────────────
# Разбираются отдельно от остальных: цикл ниже судит ключи по одному слову, а имя ветки
# он принял бы за незнакомый ключ.
BRANCH=""
WANT_PLAN=0
CHECK_ONLY=0
REST_KEYS=()
ARGV=("$@")
for ((i = 0; i < ${#ARGV[@]}; i++)); do
    case "${ARGV[i]}" in
        --ветка)
            i=$((i + 1))
            BRANCH="${ARGV[i]:-}"
            { [ -n "$BRANCH" ] && [ "${BRANCH:0:2}" != "--" ]; } \
                || { say "--ветка требует имя ветки — выкат отменён"; exit 1; } ;;
        --план) WANT_PLAN=1 ;;
        --проверка) CHECK_ONLY=1 ;;
        *) REST_KEYS+=("${ARGV[i]}") ;;
    esac
done

# ── 0б. Дамп базы: самотест ─────────────────────────────────────────────────
# Самотест стоит ДО лока и ворот: он ничего не выкатывает, а занимать ими выкат
# не имеет права. Проверяет оба исхода живьём, на временном каталоге.
if [ "${1:-}" = "--selftest-dump" ]; then
    TMP_DIR=$(mktemp -d)
    trap 'rm -rf "$TMP_DIR"' EXIT
    ERRORS=0

    STACK_DB_DUMP_CMD="head -c 4096 /dev/urandom"
    snapshot_db "$TMP_DIR/полный.dump" \
        && say "самотест 1/3: непустой дамп принят — ВЕРНО" \
        || { say "самотест 1/3: непустой дамп отвергнут — ОШИБКА"; ERRORS=$((ERRORS+1)); }

    STACK_DB_DUMP_CMD="true"
    if snapshot_db "$TMP_DIR/пустой.dump"; then
