# Свои ключи deploy.sh разбирает сам, ДО лока и ворот. Служебные ключи ворот
# (--только-согласие, --просить) ставит сам скрипт; пропусти их из командной строки, и
# просьба кнопки ушла бы от чужого имени.
GATE_FORCE=""
for key in ${REST_KEYS[@]+"${REST_KEYS[@]}"}; do
    [ "$key" = "--силой" ] || { say "незнакомый ключ $key; известны: --силой, --план, --проверка, --ветка <имя> — выкат отменён"; exit 1; }
    GATE_FORCE="--силой"
done
[ "$CHECK_ONLY" = 0 ] || [ -z "$GATE_FORCE" ] || { say "--проверка не берёт --силой: у неё нет ворот, которые можно обойти — отменено"; exit 1; }

if [ -n "$TREE_DIRTY" ]; then
    say "ОШИБКА: в $PRODUCT_TREE незакоммиченные правки — выкатывается только закоммиченное, выкат отменён до ворот:"
    printf '%s\n' "$TREE_DIRTY" | head -10 | sed 's/^/    /' | tee -a "$DEPLOY_LOG"
    exit 1
fi

# ── 0г1. Предусловия ДО сборки и тестов ──────────────────────────────────────
# Ключ, который всё равно откажет (STACK_RUN_AS = root, сборка с `up` без STACK_RELEASE_CMD,
# опечатка в потолках), не должен успеть собрать образ и прогнать наборы.
door_preflight || exit 1

# ── 0е. Docker доступен? ────────────────────────────────────────────────────
# Не виден docker — перезапуск под `sg docker` или отказ словами. Нужен и `--проверка`. Стоит ДО
# замка дерева: перезапуск под sg держал бы замок и упёрся бы в него сам.
ensure_docker "$@"

# ── 0г2. Замок дерева продукта и S: какой коммит выкатывается ───────────────
# Замок — до переключения дерева: второй проход с --ветка не должен сдвинуть HEAD под идущей
# сборкой первого. Ловушка выхода возвращает дерево при отказе и пишет итог оборванного выката.
take_tree_lock
trap door_on_exit EXIT
# Сигнал — выход с кодом сигнала, а не молчаливая смерть: ловушка выхода видит 143/129/130, пишет итог
# провалом и возвращает дерево, а `exit` без числа отдал бы ей код 0.
trap 'exit 143' TERM
trap 'exit 129' HUP
trap 'exit 130' INT
# S фиксируется ДО сборки, тестов и ворот: ворота судят кнопку по этому дереву и sha; тег, сборка,
# тесты и сверка ниже — по нему же. С --ветка дерево сначала встаёт на вершину ветки из хранилища.
door_subject "$BRANCH"
DEPLOY_SHA=""
GATE_SUBJECT=()
if git -C "$PRODUCT_TREE" rev-parse --git-dir >/dev/null 2>&1; then
    DEPLOY_SHA=$(GIT_NO_REPLACE_OBJECTS=1 git -C "$PRODUCT_TREE" rev-parse HEAD) \
        || { say "ОШИБКА: HEAD дерева $PRODUCT_TREE не прочитан — выкат отменён до ворот"; exit 1; }
    GATE_SUBJECT=(--выкат "$PRODUCT_TREE" "$DEPLOY_SHA")
fi
door_ff_ok
stage_done S

# ── 3а. X: секреты не едут в прод (И-3: check-secrets и в pre-commit, и здесь) ─
# Стоит ДО сборки и ворот: отказ на секретах не тратит ни сборку, ни «Да» (проба возврата согласия
# судит этот порядок). Судится диапазон «sha прошлого живого выката..DEPLOY_SHA»: то, что уже
# выкатывалось, судили тогда; нет живого выката или он вне истории — весь репозиторий, словами.
# Дубль pre-commit не лишний: тот можно обойти (--no-verify), деплой — нельзя. Через bash, а не по биту
# исполнения: в пакете файл лежит 644, и отказ «Permission denied» читался как «секреты найдены».
secrets_base
if [ -n "$RANGE_BASE" ]; then
    say "секреты: судится диапазон ${RANGE_BASE:0:8}..${DEPLOY_SHA:0:8} (от прошлого живого выката)"
else
    say "секреты: прошлого живого выката в истории нет — судится весь репозиторий"
fi
bash "$SCRIPT_DIR/check-secrets.sh" ${RANGE_BASE:+--range "$RANGE_BASE..$DEPLOY_SHA"} "$PRODUCT_TREE" || { say "секреты в репозитории — выкат отменён (И-3)"; exit 1; }
stage_done X

# ── 3. Снимок образов: точка отката ДО сборки ───────────────────────────────
# STACK_IMAGES — имена образов через пробел (данные). Пусто — отката не будет,
# и это говорится вслух, а не выясняется в момент аварии. Ставит ROLLBACK_READY.
# `--проверка` :previous не трогает: она ничего не выкатывает.
