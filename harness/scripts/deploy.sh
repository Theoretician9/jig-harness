    esac
    say "  дерево продукта: $TREE_NOTE"
    if [ -n "${STACK_REMOTE:-}" ]; then
        door_subject "$BRANCH" план
        say "  хранилище: $STACK_REMOTE, ветка ${STACK_BRANCH:-main} на ${SUBJ_MAIN:0:8}; пуш тега после ворот и дампа, ветки — только fast-forward"
        [ -z "$BRANCH" ] || say "  предмет: ветка $BRANCH, вершина ${SUBJ_TIP:0:8} (дерево переключается на неё при выкате)"
    elif [ -n "$BRANCH" ]; then
        door_subject "$BRANCH" план
    fi
    say "  образы: сборка получает IMAGE_TAG=<sha12>, :<sha12> продвигается в :latest; откат — на образ последнего живого выката"
    say "  образы для снимка :previous: ${STACK_IMAGES:-<пусто — отката не будет>}"
    say "  сборка: $STACK_BUILD_CMD"
    say "  сборка --no-cache (смена манифестов): ${STACK_BUILD_NOCACHE_CMD:-<пусто — обычная сборка>}"
    if [ -n "${STACK_CHECKS_FILE:-}" ]; then
        say "  тесты (этап T): $STACK_CHECKS_FILE — на образе :<sha12>, до лока и ворот"
    else
        say "  тесты (этап T): <пусто — пропущен: не задано STACK_CHECKS_FILE>"
    fi
    if [ -z "${STACK_DB_DUMP_CMD:-}" ] && [ -n "${BACKUP_DBS:-}" ]; then
        say "  дамп базы: все базы BACKUP_DBS через backup.sh --базы-в ${BACKUP_DIR:-/var/backups/harness}/перед-выкатом/<метка>-<sha8>"
    else
        say "  дамп базы: ${STACK_DB_DUMP_CMD:-<пусто — без дампа>}"
    fi
    say "  миграции: ${STACK_MIGRATE_CMD:-<пусто>}"
    say "  пересоздание служб: ${STACK_RELEASE_CMD:-<пусто — службы поднимает сборка>}"
    say "  живость: ${STACK_HEALTH_CMD:-${STACK_HEALTH_URL:-<пусто — выкат откажет>}}"
    say "  фронт (необязательный): ${STACK_FRONTEND_CMD:-<пусто>}"
    say "  подъём при откате: ${STACK_UP_CMD:-<пусто>}"
    say "  восстановление базы (руками): ${STACK_DB_RESTORE_HINT:-pg_restore по дампу}"
    say "  reload прокси: ${STACK_PROXY_RELOAD_CMD:-<пусто>}"
    say "  смоук (необязательный): ${STACK_SMOKE_CMD:-<пусто>}"
    exit 0
