    snapshot_images
fi

# ── 4. B: сборка (одна, :<sha12>); смена манифестов зависимостей → --no-cache ─
# CLAUDE.md §9: после изменения зависимостей — только --no-cache. Записка success и готовый
# образ делают сборку лишней (stage_build).
