#!/usr/bin/env bash
#
# deploy.sh — выкатка одной командой в гарантированном порядке.
#
# Откуда взят: UNIFIED/templates/deploy.sh — СЕМЯ первой установки, а не живой
# код: оно отстало и не обновляется (замер 27.09.2026).
# Что изменено: имена контейнеров и команды стека вынесены в /etc/harness/harness.conf
# (секция STACK_* — данные, не код); добавлены ворота deploy_guard.py, тег выката,
# снимок образов :previous и авто-откат на него при мёртвом health, пересборка
# --no-cache при смене манифестов зависимостей (CLAUDE.md §9), reload прокси;
# на чистом сервере без продукта скрипт честно говорит «выкатывать нечего» и
# выходит нулём — харнес ставится раньше продукта, и деплой не имеет права
# врать, будто что-то выкатил.
#
# Порядок (менять нельзя, каждый шаг стоит на случившемся отказе; стоимость отказа растёт слева
# направо, необратимое — после «Да», спека эталонного выката §5.1):
#   ЗАМОК ДЕРЕВА (flock, от выбора предмета до конца прохода; берёт и --проверка)
#   → предмет (S) → секреты по диапазону от живого выката (X) → снимок образов → сборка (B, одна, образы :<sha12>)
#   → тесты продукта (T) → скан образа (D/I)
#   → ЛОК (flock, до ворот — К-3) → ворота (G) → грязь прода → ДАМП БАЗЫ → тег и запись в журнал выкатов
#   → грязь прода под локом → пуш тега и ветки в хранилище → pull дерева прода → продвижение
#   :<sha12> в :latest → миграции → пересоздание служб → health циклом (при провале — откат на образ
#   прошлого живого выката) → фронт → расписание продукта → reload прокси → смоук.
# Сборка и тесты идут ДО лока и ворот: красные тесты не стоят «Да» владельца. Прод они не трогают:
# образ лежит под :<sha12>, :latest и службы двигаются только после ворот и дампа.
#
# Почему дамп именно здесь, а не в демоне бэкапа: откатить образы можно, а
# миграцию — нет. `alembic upgrade head` меняет схему необратимо, и при
# провале health авто-откат возвращает СТАРЫЙ код на НОВУЮ схему. До 02.09.2026
# в этом скрипте не было ни одного упоминания дампа: точка отката существовала
# только для образов (И-1).
#
# Граница: выкат продукта не судит и не пишет харнес (карта, ворота, автопамять) —
# ему принадлежит только репозиторий продукта (спека эталонного выката §5.4).
#
# Запуск: ./scripts/deploy.sh [--силой] [--ветка <имя>]   (--силой — единственный ключ, который уходит в ворота)
#         ./scripts/deploy.sh --план [--ветка <имя>]   что сделал бы: шаги и команды, без ворот и выката
#         ./scripts/deploy.sh --проверка [--ветка <имя>]   предмет, секреты, сборка, тесты: без лока, ворот, тега,
#                                                         пуша и служб; итог — записка deploy-checks.jsonl, выкат
#                                                         того же sha читает её и наборы не повторяет
# --ветка <имя>: предмет выката — вершина ветки в хранилище STACK_REMOTE, а не HEAD дерева.
set -euo pipefail

# ── конфиги ─────────────────────────────────────────────────────────────────
source "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/lib/config.sh"
