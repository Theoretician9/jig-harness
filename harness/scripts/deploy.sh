# HARNESS_ROOT нужен одному месту — предупреждению --план (Г7); предметом выката харнес не служит.
: "${PROJECT_DIR:?в install.conf пуст PROJECT_DIR}" "${LOG_DIR:?пуст LOG_DIR}"; HARNESS_ROOT=$(readlink -f -- "$PROJECT_DIR")

SCRIPT_DIR="$(cd "$(dirname "$(readlink -f "$0")")" && pwd)"
# Путь к себе считается ДО `cd "$PRODUCT_TREE"`: относительный `$0` после смены каталога
# указывал бы в дерево продукта, и перезапуск под sg звал бы несуществующий файл.
# shellcheck disable=SC2034  # читает ensure_docker из lib/door_stages.sh
DEPLOY_SELF="$(readlink -f "$0")"
