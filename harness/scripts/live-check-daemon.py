#!/usr/bin/env python3
"""Живая проверка демона: прочитан журнал его ПОСЛЕДНЕГО кронового прогона.

Откуда взято: спека `docs/specs/2026-10-15-живая-проверка-механизмов.md` §3.1,
класс A1. Носителя этому предикату в коде не было, и 22 демона в живом
расписании оставались непроверенными: доказательством служило бы слово
проверяющего, а гейт судил только общий след.

Почему путь журнала берётся ИЗ РАСПИСАНИЯ, а не из реестра: реестр говорит, чем
механизм проверяется, а крон решает, куда уходит его вывод. Эти два пути
расходятся молча, и тогда «журнал свежий» сказано о чужом файле.

Почему свежесть судится ПЕРИОДОМ своей строки крона: демон раз в десять минут и
демон раз в сутки молчат по-разному, и один потолок на всех врал бы одному из
них. Потолок — три периода: один пропуск бывает законным (машина была занята),
три подряд — это уже молчание.

Запуск:
    python3 scripts/live-check-daemon.py <механизм> [--записать]
    python3 scripts/live-check-daemon.py --всё [--записать]
Код возврата: 0 — кроновый прогон доказан у всех названных, 1 — хоть у одного
нет.

Чем доказан: scripts/test_live_check_daemon.py (больным случаем первым — журнал
старше своего расписания).
"""
