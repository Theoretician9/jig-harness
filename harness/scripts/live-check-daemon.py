def расписание() -> list[str]:
    """Строки живого расписания без пустых и закомментированных."""
    if РАСПИСАНИЕ_ФАЙЛ:
        текст = pathlib.Path(РАСПИСАНИЕ_ФАЙЛ).read_text(encoding="utf-8")
    else:
        готово = subprocess.run(["crontab", "-l"], capture_output=True, text=True)
        if готово.returncode != 0:
            raise SystemExit("[живая проверка демонов] расписание не прочитано: "
                             f"crontab -l вернул {готово.returncode}")
        текст = готово.stdout
    return [с for с in текст.splitlines()
            if с.strip() and not с.strip().startswith("#")]


def период_минут(поля: list[str]) -> int:
    """Период строки крона в минутах: по полям минут, часов и дня месяца.

    Разбор нарочно грубый и в одну сторону — ЗАВЫШАЕТ период. Занижение сделало
    бы живого демона мёртвым на ровном месте, а завышение лишь ослабляет
    потолок, и о нём говорится вслух в следе.
    """
    мин, час, день = поля[0], поля[1], поля[2]
    шаг_мин = re.fullmatch(r"\*/(\d+)", мин)
    if шаг_мин and час == "*":
        return int(шаг_мин.group(1))
    if мин == "*" and час == "*":
        return 1
    шаг_час = re.fullmatch(r"\*/(\d+)", час)
    if шаг_час:
        return 60 * int(шаг_час.group(1))
    if час == "*":
        return 60
    if день != "*":
        return 60 * 24 * 31
    return 60 * 24


def строка_демона(механизм: str) -> tuple[str, str, int] | None:
    """(строка расписания, путь журнала, период минут) или None, если его нет.

    Имя файла, а не целый путь: в расписании путь абсолютный и зависит от
    установки, а механизм назван относительно корня репозитория.
    """
    имя = pathlib.Path(механизм).name
    for строка in расписание():
        if имя not in строка:
            continue
        куда = re.search(r">>\s*(\S+)", строка)
        поля = строка.split()
        if not куда or len(поля) < 5:
            continue
        return строка.strip(), куда.group(1), период_минут(поля[:5])
    return None


def свежее_доказательство(механизм: str, журнал: str, потолок: int
                          ) -> tuple[pathlib.Path, str, float, str] | None:
    """Первый СВЕЖИЙ след прогона: (файл, путь, возраст в минутах, оговорка).

    Источников три, и порядок — от самого прямого к самому бедному. Это не три
    случая, а ЦЕПОЧКА кандидатов с одним судом «возраст не больше потолка»:
    ветвями они разъехались бы, и каждая получила бы свой потолок.

    1. Журнал кронового прогона — путь из расписания (спека §3.1).
    2. Свой журнал демона `<имя>.log`: ежеминутный демон в stdout молчит
       НАРОЧНО, иначе крон-журнал растёт на 1440 строк в сутки (живой случай
       17.10.2026 — limit-watch и panel-tunnel: кроновый 0 байт, свой 25 КБ).
    3. Метка демона в HEARTBEAT_DIR: её он ставит КАЖДЫЙ прогон, а в журнал
       пишет только по событию. У limit-watch журналу было 138 минут при периоде
       1 мин, а метке — 3 минуты: «демон не бегал» о таком демоне ложь.

    Оговорка — то, что обязано попасть в запись: откуда взята свежесть, если не
    из кронового журнала. Молча подменить источник нельзя, иначе запись скажет
    больше, чем доказано.
    """
    кроновый = pathlib.Path(журнал)
    свой = кроновый.with_name(pathlib.Path(механизм).stem + ".log")
    метка = pathlib.Path(КАТАЛОГ_МЕТОК) / pathlib.Path(механизм).stem
    кандидаты = [
        (кроновый, True, ""),
        (свой, True, f"кроновый журнал пуст или отстал ({журнал}) — демон в stdout "
                     f"молчит; свежесть взята из его своего журнала"),
        (метка, False, f"журнал пишется только по событию; свежесть прогона "
                       f"доказана МЕТКОЙ {метка}, её демон ставит каждый прогон"),
    ]
    for файл, нужно_содержимое, оговорка in кандидаты:
        if файл == кроновый and оговорка:
            continue
        if not файл.is_file():
            continue
        if нужно_содержимое and not файл.read_text(errors="replace").strip():
            continue
        возраст = (time.time() - файл.stat().st_mtime) / 60
        if возраст <= потолок:
            # Текст для цитаты берётся из ЖУРНАЛА даже тогда, когда свежесть
            # доказана меткой: метка пуста, а чужой текст в следе нужен.
            несущий = файл if файл != метка else (
                свой if свой.is_file() and свой.read_text(errors="replace").strip()
                else кроновый)
            return несущий, str(несущий), возраст, оговорка
    return None


def молчуны() -> dict:
    """Демоны, которым молчать ЗАКОННО, и условие их молчания — из данных.

    Данных нет — пусто: тогда прибор отказывает прежними словами, а не прощает
    молчание молча."""
    if not ЮНИТЫ.is_file():
        return {}
    прочтено = yaml.safe_load(ЮНИТЫ.read_text(encoding="utf-8")) or {}
    return прочтено.get("молчат_нарочно") or {}


def _условие_молчания(условие: dict) -> tuple[bool, str]:
    """Стоит ли в конфиге условие, при котором демону молчать законно.

    Иначе ветвь стала бы отмазкой для любого онемевшего демона: молчание
    законно по ЗНАЧЕНИЮ ключа, а не потому, что так вышло."""
    ключ = (условие or {}).get("ключ")
    не_содержит = (условие or {}).get("не_содержит")
    if not ключ or не_содержит is None:
        return False, ("в данных не названы ключ конфига и условие его значения "
                       "— придумывать их прибор не вправе")
    sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent / "lib"))
    import config as конф                                  # noqa: PLC0415
    # Условие молчания стоит в harness.conf (пороги и ключи механик), а не в
    # паспорте установки; окружение старше файла — правило общее.
    значение = (os.environ.get(ключ)
                or конф.из_файла(конф.путь_harness_conf()).get(ключ))
    if значение is None:
        return False, f"ключ {ключ} в конфиге не задан — молчание ничем не оправдано"
    if str(не_содержит) in str(значение):
        return False, (f"условие молчания не стоит: {ключ}={значение} содержит "
                       f"«{не_содержит}» — в этом состоянии демон обязан говорить")
    return True, f"{ключ}={значение} не содержит «{не_содержит}»"


def судить_молчуна(механизм: str, о_нём: dict) -> tuple[bool, str, dict]:
    """Демон, который в этом состоянии не печатает НИЧЕГО (улика 18.10.2026).

    panel-tunnel при панели, выведенной через nginx, молчит нарочно: ни
    кронового журнала, ни своего — и прежний предикат отказывал ему словами
    «цитировать нечего». Его работа видна в МЕТКЕ, которую он ставит каждый
    прогон, и измеряет её ПРИБОР (mtime до и после зова), а не проверяемый.

    Три разных отказа, и у каждого свои слова: условие молчания не стоит,
    метка не обновилась, демон заговорил (это находка о НЁМ).
    """
    почему = (о_нём.get("почему") or "").strip()
    законно, о_условии = _условие_молчания(о_нём.get("условие") or {})
    if not почему:
        return False, (f"{механизм}: в данных не сказано, ПОЧЕМУ ему молчать "
                       f"законно"), {}
    if not законно:
        return False, f"{механизм}: {о_условии}", {}

    метка = pathlib.Path(КАТАЛОГ_МЕТОК) / pathlib.Path(механизм).stem
    было = метка.stat().st_mtime if метка.exists() else 0.0
    СЛЕДЫ.mkdir(parents=True, exist_ok=True)
    след = СЛЕДЫ / (механизм.replace("/", "-") + ".log")
    # Обёртка берётся рядом с ПРИБОРОМ: в подменённом корне (стенд пробы) её
    # нет, и зов тогда падал бы молча — «демон молчит» выглядело бы правдой.
    обёртка = pathlib.Path(__file__).resolve().parent / "live-check.sh"
    готово = subprocess.run(
        ["bash", str(обёртка), механизм, "--", "bash", str(КОРЕНЬ / механизм)],
        capture_output=True, text=True, timeout=ПРЕДЕЛ_ЗОВА_СЕК, cwd=str(КОРЕНЬ),
        env=dict(os.environ, HARNESS_LIVE_CHECK_TRACE_DIR=str(СЛЕДЫ)))
    # Свой отказ обёртки (код 2) — не молчание демона: иначе её «не записать
    # след» читалось бы как доказанный прогон.
    if готово.returncode == 2:
        беда = " ".join((готово.stderr or готово.stdout or "").split())
        return False, (f"{механизм}: обёртка следа отказала — {беда[:160]}; "
                       f"позвать демона не удалось"), {}
    # Крон кладёт в журнал и stdout, и stderr: демон «сказал» и тем, и другим.
    сказал = " ".join(((готово.stdout or "") + (готово.stderr or "")).split())
    if сказал:
        return False, (f"{механизм}: обещан молчуном, а сказал: «{сказал[:120]}» "
                       f"— это находка о нём, а не доказательство"), {}
    стало = метка.stat().st_mtime if метка.exists() else 0.0
    if стало <= было:
        возраст = (time.time() - стало) / 60 if стало else -1
        return False, (f"{механизм}: позван, молчит — и метки {метка} не обновил "
                       f"({'её нет вовсе' if возраст < 0 else f'ей {возраст:.0f} мин'}): "
                       f"прогона не было, молчание ничего не доказывает"), {}

    измерение = (f"метка {метка}: обновлена зовом прибора "
                 f"({datetime.datetime.fromtimestamp(стало).isoformat(timespec='seconds')}, "
                 f"было {datetime.datetime.fromtimestamp(было).isoformat(timespec='seconds') if было else 'метки не было'})")
    with след.open("a", encoding="utf-8") as ф:
        ф.write(f"молчит нарочно: {почему}\n"
                f"условие молчания: {о_условии}\n"
                f"{измерение}\n")
    путь_следа = str(след)
    if след.is_relative_to(КОРЕНЬ):
        путь_следа = str(след.relative_to(КОРЕНЬ))
    поля = {
        "живьём": (f"позван так, как его зовёт крон; молчит нарочно — {почему} "
                   f"({о_условии}). Своего текста в этом состоянии он не печатает, "
                   f"и доказательство — обновление МЕТКИ, измеренное прибором "
                   f"(mtime до и после зова)"),
        "увидели": измерение,
        "след": путь_следа,
        "когда": datetime.date.today().isoformat(),
        "исход": "ок",
    }
    return True, f"{механизм}: молчит нарочно, прогон доказан меткой", поля


def юнит_механизма(механизм: str) -> dict:
    """Запись о юните systemd для механизма из данных: {юнит, журнал, признак}.

    Строка в данных — короткая форма (только имя юнита). Запись нужна там, где
    служба пишет не в журнал юнита, а в СВОЙ файл, и файл этот общий: панель
    делит `панель.jsonl` с писателями памяти, ключей и шагов, и цитата оттуда
    без признака доказывала бы работу СОСЕДА (замер 18.10.2026).
    """
    if not ЮНИТЫ.is_file():
        return {}
    данные = yaml.safe_load(ЮНИТЫ.read_text(encoding="utf-8")) or {}
    запись = (данные.get("юниты") or {}).get(механизм)
    if isinstance(запись, str):
        return {"юнит": запись.strip()} if запись.strip() else {}
    if isinstance(запись, dict) and str(запись.get("зовёт") or "").strip():
        return {"зовёт": str(запись["зовёт"]).strip(),
                "юнит": str(запись.get("юнит") or "").strip(),
                "журнал": str(запись.get("журнал") or "").strip(),
                "признак": str(запись.get("признак") or "").strip(),
                "потолок_минут": int(запись.get("потолок_минут") or 0)}
    if isinstance(запись, dict) and str(запись.get("юнит") or "").strip():
        return {"юнит": str(запись["юнит"]).strip(),
                "журнал": str(запись.get("журнал") or "").strip(),
                "признак": str(запись.get("признак") or "").strip(),
                "потолок_минут": int(запись.get("потолок_минут") or 0)}
    return {}


def строки_своего_журнала(имя: str, признак: str) -> tuple[list[str], str]:
    """(строки службы, причина отказа). Журнал берётся из LOG_DIR установки."""
    sys.path.insert(0, str(КОРЕНЬ / "scripts" / "lib"))
    import config as конф                                 # noqa: PLC0415
    путь = pathlib.Path(os.environ.get("HARNESS_LOG_DIR") or конф.log_dir()) / имя
    if not путь.is_file():
        return [], f"своего журнала {путь} нет — судить нечем"
    строки = [с for с in путь.read_text(encoding="utf-8",
                                        errors="replace").splitlines() if с.strip()]
    if признак:
        строки = [с for с in строки if признак in с]
        if not строки:
            return [], (f"в {путь} нет ни одной строки с признаком {признак} — "
                        f"журнал общий, и чужие строки её работой не считаются")
    return строки[-ХВОСТ_СТРОК:], ""


def _команда(довод: list[str]) -> tuple[int, str]:
    готово = subprocess.run(довод, capture_output=True, text=True, timeout=60)
    return готово.returncode, готово.stdout


def _записать_след_зовущего(механизм: str, зовёт: str, откуда: str,
                            хвост: list[str]) -> tuple[bool, str, dict]:
    """След и поля записи для механизма, которого зовёт другой. Одна функция на
    обе ветки (файл и юнит): разъехавшись, они дали бы разные следы одному
    предикату."""
    годные = [" ".join(с.split()) for с in reversed(хвост)
              if len(" ".join(с.split())) >= 12]
    if not годные:
        return False, (f"{механизм}: в {откуда} нет его строки длиннее 12 "
                       f"знаков — цитировать нечего"), {}
    СЛЕДЫ.mkdir(parents=True, exist_ok=True)
    след = СЛЕДЫ / (механизм.replace("/", "-") + ".log")
    когда = datetime.datetime.now().astimezone().isoformat(timespec="seconds")
    след.write_text(
        f"время: {когда}\n"
        f"механизм: {механизм}\n"
        f"его зовёт: {зовёт}; {откуда}\n"
        f"--- хвост журнала демона ---\n" + "\n".join(хвост) + "\n",
        encoding="utf-8")
    путь_следа = str(след)
    if след.is_relative_to(КОРЕНЬ):
        путь_следа = str(след.relative_to(КОРЕНЬ))
    поля = {
        "живьём": (f"в расписании его нет — в жизни его зовёт {зовёт}: прочитан "
                   f"{откуда}, строки взяты ЕГО признаком"),
        "увидели": годные[0],
        "след": путь_следа,
        "когда": datetime.date.today().isoformat(),
        "исход": "ок",
    }
    return True, f"{механизм}: его зовёт {зовёт} — {годные[0][:80]}", поля


def судить_по_зовущему(механизм: str, о_нём: dict) -> tuple[bool, str, dict]:
    """Предикат для механизма, которого зовёт ДРУГОЙ живой механизм.

    В расписании его нет и юнита у него нет: он помощник, и в жизни его зовёт
    обёртка под кроном. Доказательство — СВОИ строки помощника в журнале
    зовущего (признак из данных) и свежесть этого журнала: «журнал есть» и
    «журнал свежий» разные факты, а строка соседа доказывала бы работу соседа.
    """
    зовёт = о_нём["зовёт"]
    потолок = о_нём.get("потолок_минут") or 0
    журнал_имя = о_нём.get("журнал") or ""
    юнит_зовущего = о_нём.get("юнит") or ""
    признак = о_нём.get("признак") or ""
    if not потолок or (not журнал_имя and not юнит_зовущего):
        return False, (f"{механизм}: в данных не названы журнал зовущего (файл "
                       f"или юнит) и потолок свежести — судить нечем"), {}
    if юнит_зовущего:
        # Зовущий пишет не в файл, а в журнал своего юнита. Признак здесь
        # ОБЯЗАТЕЛЕН: без него цитатой станет любая строка зовущего.
        if not признак:
            return False, (f"{механизм}: зовущий пишет в журнал юнита "
                           f"{юнит_зовущего}, а признака его собственных строк "
                           f"в данных нет — цитатой стала бы строка соседа"), {}
        код, вывод = _команда([JOURNALCTL, "-u", юнит_зовущего, "--since",
                               f"-{потолок}min", "--no-pager"])
        if код != 0:
            return False, (f"{механизм}: журнал юнита {юнит_зовущего} не "
                           f"прочитан (код {код}) — «не прочитали» и «пусто» "
                           f"разные факты"), {}
        хвост_юнита = [с for с in вывод.splitlines()
                       if с.strip() and not с.strip().startswith("-- ")
                       and признак in с][-ХВОСТ_СТРОК:]
        if not хвост_юнита:
            return False, (f"{механизм}: за последние {потолок} мин в журнале "
                           f"{юнит_зовущего} нет ни одной его строки "
                           f"(признак {признак}) — {зовёт} его не звал"), {}
        return _записать_след_зовущего(механизм, зовёт,
                                       f"журнал юнита {юнит_зовущего}, окно "
                                       f"{потолок} мин", хвост_юнита)
    sys.path.insert(0, str(КОРЕНЬ / "scripts" / "lib"))
    import config as конф                                 # noqa: PLC0415
    путь = pathlib.Path(os.environ.get("HARNESS_LOG_DIR") or конф.log_dir()) / журнал_имя
    if not путь.is_file():
        return False, (f"{механизм}: журнала зовущего {путь} нет — "
                       f"{зовёт} его не звал ни разу"), {}
    возраст = (time.time() - путь.stat().st_mtime) / 60
    if возраст > потолок:
        return False, (f"{механизм}: журналу зовущего {путь} {возраст:.0f} мин "
                       f"при потолке {потолок} — {зовёт} давно не бегал, "
                       f"значит и он тоже"), {}
    хвост, беда = строки_своего_журнала(журнал_имя, признак)
    if беда:
        return False, f"{механизм}: {беда}", {}
    return _записать_след_зовущего(механизм, зовёт,
                                   f"журнал {журнал_имя}, возраст {возраст:.0f} "
                                   f"мин при потолке {потолок}", хвост)


def судить_по_юниту(механизм: str, о_юните: dict) -> tuple[bool, str, dict]:
    """Предикат класса A2 для демона, которого поднимает systemd.

    Крон его не зовёт, и «журнал последнего прогона» брать неоткуда: служба
    либо работает сейчас, либо нет. Поэтому доказательств два и оба чужие:
    systemd говорит, что она активна и с какого часа, а её журнал даёт строку,
    которую написала она сама.
    """
    юнит = о_юните["юнит"]
    код, состояние = _команда([SYSTEMCTL, "show", "-p", "ActiveState",
                               "-p", "ActiveEnterTimestamp", юнит])
    if код != 0:
        return False, (f"{механизм}: systemd не ответил о юните {юнит} "
                       f"(код {код}) — судить нечем"), {}
    поля = dict(с.split("=", 1) for с in состояние.splitlines() if "=" in с)
    если_активна = (поля.get("ActiveState") or "").strip()
    с_какого = (поля.get("ActiveEnterTimestamp") or "").strip()
    как_свеж = f"ActiveState=active, с {с_какого}"
    if если_активна != "active":
        потолок = о_юните.get("потолок_минут") or 0
        if not потолок:
            return False, (f"{механизм}: юнит {юнит} не работает — ActiveState="
                           f"{если_активна or 'пусто'}; служба, которой нет, "
                           f"живой проверки не проходит"), {}
        # РАЗОВАЯ служба (Type=oneshot по таймеру): «активна сейчас» о ней
        # ничего не говорит — она отработала и вышла. Свежесть берётся у её
        # МЕТКИ, как у демонов крона, а потолок назван в данных: период таймера
        # угадывать нельзя, разные таймеры молчат по-разному.
        метка = pathlib.Path(КАТАЛОГ_МЕТОК) / pathlib.Path(механизм).stem
        if not метка.exists():
            return False, (f"{механизм}: разовая служба {юнит} сейчас не "
                           f"работает, и метки {метка} нет — прогона не было"), {}
        возраст = (time.time() - метка.stat().st_mtime) / 60
        if возраст > потолок:
            return False, (f"{механизм}: разовая служба {юнит}, её метке "
                           f"{возраст:.0f} мин при потолке {потолок} — "
                           f"она не бегала"), {}
        как_свеж = (f"разовая служба по таймеру; её метке {возраст:.0f} мин "
                    f"при потолке {потолок}")

    свой_журнал = о_юните.get("журнал") or ""
    если_свой = ""
    if свой_журнал:
        # Служба пишет не в журнал юнита, а в свой файл: читаем его, и только
        # ЕЁ строки — по признаку из данных.
        хвост_свой, беда = строки_своего_журнала(свой_журнал,
                                                 о_юните.get("признак") or "")
        if беда:
            return False, f"{механизм}: юнит {юнит} работает, но {беда}", {}
        журнал = "\n".join(хвост_свой)
        если_свой = f"; строки взяты из её своего журнала {свой_журнал}"
    else:
        код, журнал = _команда([JOURNALCTL, "-u", юнит, "-n", str(ХВОСТ_СТРОК),
                                "--no-pager"])
        if код != 0:
            return False, (f"{механизм}: журнал юнита {юнит} не прочитан "
                           f"(код {код}) — «не прочитали» и «пусто» разные факты"), {}
    # Строки, начинающиеся с «-- », пишет САМ journalctl («-- No entries --»,
    # «-- Boot ... --»), и цитата из них доказывала бы работу журналиста, а не
    # службы. Замер 17.10.2026: юнит панели отдал ровно «-- No entries --», и
    # первая редакция приняла это за слова службы.
    хвост = [с for с in журнал.splitlines()
             if с.strip() and not с.strip().startswith("-- ")]
    годные = [" ".join(с.split()) for с in reversed(хвост)
              if len(" ".join(с.split())) >= 12]
    if not годные:
        return False, (f"{механизм}: юнит {юнит} работает, а в его журнале нет "
                       f"ни одной строки, написанной самой службой — "
                       f"цитировать нечего"), {}

    СЛЕДЫ.mkdir(parents=True, exist_ok=True)
    след = СЛЕДЫ / (механизм.replace("/", "-") + ".log")
    когда = datetime.datetime.now().astimezone().isoformat(timespec="seconds")
    след.write_text(
        f"время: {когда}\n"
        f"механизм: {механизм}\n"
        f"юнит systemd: {юнит} ({как_свеж}){если_свой}\n"
        f"--- хвост журнала демона ---\n" + "\n".join(хвост) + "\n",
        encoding="utf-8")
    путь_следа = str(след)
    if след.is_relative_to(КОРЕНЬ):
        путь_следа = str(след.relative_to(КОРЕНЬ))
    поля_записи = {
        "живьём": (f"его зовёт не крон, а systemd: юнит {юнит} — {как_свеж}; "
                   f"прочитан хвост журнала — строки писала сама "
                   f"служба{если_свой}"),
        "увидели": годные[0],
        "след": путь_следа,
        "когда": datetime.date.today().isoformat(),
        "исход": "ок",
    }
    return True, f"{механизм}: юнит {юнит} — {как_свеж} — {годные[0][:80]}", поля_записи


def судить(механизм: str) -> tuple[bool, str, dict]:
    """(доказано, что сказать, поля записи) для одного демона."""
    о_молчании = молчуны().get(механизм)
    if о_молчании:
        return судить_молчуна(механизм, о_молчании)
    найдено = строка_демона(механизм)
    if найдено is None:
        # Крон его не зовёт. Если он поднят юнитом systemd — это класс A2, и
        # предикат другой: служба работает сейчас, и строки в её журнале
        # написала она сама.
        о_юните = юнит_механизма(механизм)
        if о_юните.get("зовёт"):
            return судить_по_зовущему(механизм, о_юните)
        if о_юните:
            return судить_по_юниту(механизм, о_юните)
        return False, (f"{механизм}: в расписании его нет и юнита в данных ему "
                       f"не названо — судить надо вызовом тем способом, "
                       f"которым его зовут (класс A2)"), {}
    строка, журнал, период = найдено
    потолок = период * ЗАПАС_ПЕРИОДОВ
    свежий = свежее_доказательство(механизм, журнал, потолок)
    if свежий is None:
        кроновый = pathlib.Path(журнал)
        если_нет = ("журнал кронового прогона не найден" if not кроновый.is_file()
                    else "журнал пуст" if not кроновый.read_text(errors="replace").strip()
                    else "журнал старше своего расписания")
        return False, (f"{механизм}: {если_нет} — {журнал} (путь из расписания, "
                       f"не из реестра), потолок {потолок} мин при периоде "
                       f"{период} мин; свежего следа прогона нет ни в своём "
                       f"журнале, ни в метке: демон не бегал"), {}
    файл, журнал, возраст, оговорка = свежий
    текст = файл.read_text(errors="replace") if файл.is_file() else ""
    строки = [с for с in текст.splitlines() if с.strip()]
    хвост = строки[-ХВОСТ_СТРОК:]

    СЛЕДЫ.mkdir(parents=True, exist_ok=True)
    след = СЛЕДЫ / (механизм.replace("/", "-") + ".log")
    когда = datetime.datetime.now().astimezone().isoformat(timespec="seconds")
    след.write_text(
        f"время: {когда}\n"
        f"механизм: {механизм}\n"
        f"строка расписания: {строка}\n"
        f"журнал кронового прогона: {журнал}\n"
        f"возраст журнала: {возраст:.0f} мин при периоде {период} мин "
        f"(потолок {потолок})\n"
        f"--- хвост журнала демона ---\n" + "\n".join(хвост) + "\n",
        encoding="utf-8")

    путь_следа = str(след)
    if след.is_relative_to(КОРЕНЬ):
        путь_следа = str(след.relative_to(КОРЕНЬ))
    # Цитата — последняя СОДЕРЖАТЕЛЬНАЯ строка журнала: её написал сам демон под
    # кроном, и короче 12 знаков она гейту --проверить не годится.
    годные = [" ".join(с.split()) for с in reversed(хвост)
              if len(" ".join(с.split())) >= 12]
    if not годные:
        return False, (f"{механизм}: в хвосте журнала нет строки длиннее 12 "
                       f"знаков — цитировать нечего"), {}
    поля = {
        "живьём": (f"прочитан журнал ПОСЛЕДНЕГО кронового прогона: {журнал} "
                   f"(путь из расписания «{строка}»), возраст свежего следа "
                   f"{возраст:.0f} мин при периоде {период} мин"
                   + (f"; {оговорка}" if оговорка else "")),
        "увидели": годные[0],
        "след": путь_следа,
        "когда": datetime.date.today().isoformat(),
        "исход": "ок",
    }
    return True, (f"{механизм}: кроновый прогон доказан — {годные[0][:80]}"), поля


def демоны_класса() -> list[str]:
    """Механизмы класса A1 из данных классов."""
    данные = yaml.safe_load(КЛАССЫ.read_text(encoding="utf-8")) or {}
    классы = данные.get("классы") or {}
    итог = []
    for файл, запись in классы.items():
        класс = запись.get("класс") if isinstance(запись, dict) else запись
        if класс == "A1":
            итог.append(файл)
    return sorted(итог)


def записать(поля_по_механизму: dict) -> None:
    # замок по соседнему файлу: сам yaml заменяется через replace, на нём замок бы терялся
    with open(СОСТОЯНИЕ.with_name(СОСТОЯНИЕ.name + ".lock"), "w") as замок:
        fcntl.flock(замок, fcntl.LOCK_EX)
        данные = yaml.safe_load(СОСТОЯНИЕ.read_text(encoding="utf-8")) or {}
        сост = данные.setdefault("проверено", {})
        for механизм, поля in поля_по_механизму.items():
            сост.setdefault(механизм, {}).update(поля)
        # временный файл рядом + replace: читатель без замка не увидит половину файла
        врем = СОСТОЯНИЕ.with_name(f"{СОСТОЯНИЕ.name}.{os.getpid()}.tmp")
        врем.write_text(
            yaml.dump(данные, allow_unicode=True, sort_keys=False, width=100),
            encoding="utf-8")
        os.replace(врем, СОСТОЯНИЕ)


def main() -> int:
    доводы = [д for д in sys.argv[1:] if not д.startswith("--")]
    писать = "--записать" in sys.argv
    кого = демоны_класса() if "--всё" in sys.argv else доводы
    if not кого:
        print("[живая проверка демонов] нечего судить: назовите механизм или «--всё»",
              file=sys.stderr)
        return 1

    поля_по_механизму: dict = {}
    беды: list[str] = []
    for механизм in кого:
        доказано, слово, поля = судить(механизм)
        print(("  ок    " if доказано else "  ПЛОХО ") + слово)
        if доказано:
            поля_по_механизму[механизм] = поля
        else:
            беды.append(слово)

    if писать and поля_по_механизму:
        записать(поля_по_механизму)
        print(f"[живая проверка демонов] записано механизмов: {len(поля_по_механизму)}")
    if беды:
        print(f"[живая проверка демонов] ✗ не доказано: {len(беды)} из {len(кого)}",
              file=sys.stderr)
        for б in беды:
            print(f"    {б}", file=sys.stderr)
        return 1
    print(f"[живая проверка демонов] доказано все {len(кого)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
