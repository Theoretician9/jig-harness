#!/usr/bin/env python3
"""Проверка уровня вызова помощников: что разрешено на каждом уровне.

Откуда взято. Владелец 12.09.2026: «Надо сделать возможность выбирать уровень
когда вызывается агенты а когда нет <…> на максимальном мне бы не надо было
писать тебе „запусти агента на эту задачу“ а сам бы просто запустил, а на
минимальном только сам, кроме однозначно когда запускаются сабагенты».

Проверяется решение, а не оболочка: уровень читается из данных, ответ —
«зову» или «не зову» с причиной, и причина обязана называть уровень.

Прогон:
    python3 scripts/test_agent_level.py
Код возврата: 0 — все пути прошли, 1 — есть упавший.
"""
import importlib.util
import subprocess
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
путей = неудач = 0


def путь_ок(текст: str) -> None:
    global путей
    путей += 1
    print("ок  · " + текст)


def путь_плохо(текст: str) -> None:
    global путей, неудач
    путей += 1
    неудач += 1
    print("ПЛОХО · " + текст)


спец = importlib.util.spec_from_file_location(
    "уровень", КОРЕНЬ / "scripts" / "agent-level.py")
уровень = importlib.util.module_from_spec(спец)
спец.loader.exec_module(уровень)

ДАНО = уровень.данные()

print("── минимум: только то, без чего работа невозможна ──")
зову, почему = уровень.звать("harness-code-review", "минимум", ДАНО)
if зову:
    путь_ок(f"ревью кода зовётся даже на минимуме: {почему}")
else:
    путь_плохо(f"ревью кода не зовётся на минимуме: {почему}")

зову, почему = уровень.звать("независимые-задачи", "минимум", ДАНО)
if not зову and "максимум" in почему:
    путь_ок("параллельные задачи на минимуме не зовутся, причина называет уровень")
else:
    путь_плохо(f"на минимуме разрешены параллельные задачи: {зову}, {почему}")

print("── максимум: сам, без просьбы ──")
зову, почему = уровень.звать("независимые-задачи", "максимум", ДАНО)
if зову:
    путь_ок(f"на максимуме независимые задачи уходят помощникам: {почему}")
else:
    путь_плохо(f"на максимуме параллельные задачи запрещены: {почему}")

print("── средний: между ними ──")
зову_ср, _ = уровень.звать("долгий-поиск", "средний", ДАНО)
зову_мин, почему_мин = уровень.звать("долгий-поиск", "минимум", ДАНО)
if зову_ср and not зову_мин:
    путь_ок("долгий поиск: на среднем зовётся, на минимуме нет")
else:
    путь_плохо(f"долгий поиск ведёт себя одинаково: средний={зову_ср}, минимум={зову_мин}")

print("── БОЛЬНОЙ: неизвестный повод запрещён на любом уровне ──")
плохие = [у for у in ("минимум", "средний", "максимум")
          if уровень.звать("починить-прод-по-быстрому", у, ДАНО)[0]]
if not плохие:
    путь_ок("повода нет в данных — не зовётся нигде, включая максимум")
else:
    путь_плохо(f"неизвестный повод разрешён на уровнях: {плохие}")

print("── БОЛЬНОЙ: неизвестный уровень в настройке ──")
зову, почему = уровень.звать("harness-code-review", "суперавтомат", ДАНО)
if not зову and "суперавтомат" in почему:
    путь_ок("незнакомый уровень запрещает всё и называет себя в причине")
else:
    путь_плохо(f"незнакомый уровень: {зову}, {почему}")

print("── боевой путь: та же команда, что зовут скилы ──")
готово = subprocess.run(
    [sys.executable, str(КОРЕНЬ / "scripts" / "agent-level.py"),
     "--повод", "harness-code-review"],
    capture_output=True, text=True, timeout=60)
if готово.returncode == 0 and "зову" in готово.stdout:
    путь_ок(f"команда отвечает словом и кодом 0: {готово.stdout.strip()[:60]}")
else:
    путь_плохо(f"команда: код {готово.returncode}, {готово.stdout.strip()[:80]}")

готово = subprocess.run(
    [sys.executable, str(КОРЕНЬ / "scripts" / "agent-level.py"),
     "--повод", "независимые-задачи", "--уровень", "минимум"],
    capture_output=True, text=True, timeout=60)
if готово.returncode == 1 and "не зову" in готово.stdout:
    путь_ок("запрет отдаётся кодом 1 — скрипт может решать по коду возврата")
else:
    путь_плохо(f"запрет: код {готово.returncode}, {готово.stdout.strip()[:80]}")

print("── БОЛЬНОЙ п.7 (отчёт чужого сервера 25.10): уровень видит слово владельца ──")
# Владелец 25.10 03:00 написал в канал «запускай сабами, чтоб быстрее задачи
# доделать», а `agent-level.py --повод независимые-задачи` отвечал «не зову:
# … сейчас минимум» — ключ AGENT_LEVEL остался прежним, и смена пошла мимо
# прибора. Носитель (предложение, docs: карточка отчёта чужого сервера 25.10,
# mutations-p467-todo.md): слово владельца поднимает уровень до «максимум»,
# если оно (а) стоит в память/ORDERS.md — указание бессрочно, пока его не
# снимет владелец; или (б) пришло в канал не раньше AGENT_LEVEL_OWNER_WORD_FRESH_H
# часов назад — свежесть по метке в ИМЕНИ файла входящего (её пишет
# диспетчер, а не судимый). Причина обязана назвать «слово владельца» и
# источник. Фразы — дословные из ORDERS.md (24.10–25.10).
# Стенд: копия прибора, его lib и ЖИВЫХ данных agents.yaml в свой корень;
# свои ORDERS.md, harness.conf, LOG_DIR. Дверь для мутаций:
# AGENT_LEVEL_UNDER_TEST — путь к копии прибора.
import os
import shutil
import tempfile
import time

ПРИБОР = Path(os.environ.get("AGENT_LEVEL_UNDER_TEST")
              or КОРЕНЬ / "scripts" / "agent-level.py")
БАЗА_ORDERS = "# ORDERS.md — стенд\n\n**12.08:** «всё делать через ассистента, команд не давать».\n"


def стенд_зов(orders: str, входящие: list, свежесть_ч: str | None,
              повод: str = "независимые-задачи", доводы: tuple = ()) -> subprocess.CompletedProcess:
    """входящие — [(часов назад, текст)]; свежесть_ч None — ключа нет."""
    with tempfile.TemporaryDirectory(prefix="проба-уровня-") as корень:
        к = Path(корень)
        (к / "scripts").mkdir()
        shutil.copy(ПРИБОР, к / "scripts" / "agent-level.py")
        shutil.copytree(КОРЕНЬ / "scripts" / "lib", к / "scripts" / "lib")
        (к / "harness" / "config").mkdir(parents=True)
        shutil.copy(КОРЕНЬ / "harness" / "config" / "agents.yaml",
                    к / "harness" / "config" / "agents.yaml")
        (к / "память").mkdir()
        (к / "память" / "ORDERS.md").write_text(orders, encoding="utf-8")
        обработано = к / "log" / "inbox" / "обработано"
        обработано.mkdir(parents=True)
        сейчас = time.time()
        for часов, текст in входящие:
            (обработано / f"{сейчас - часов * 3600:.9f}.txt").write_text(текст, encoding="utf-8")
        конф = 'AGENT_LEVEL="минимум"\n'
        if свежесть_ч is not None:
            конф += f'AGENT_LEVEL_OWNER_WORD_FRESH_H="{свежесть_ч}"\n'
        (к / "harness.conf").write_text(конф, encoding="utf-8")
        (к / "install.conf").write_text(
            f'PROJECT_DIR="{к}"\nLOG_DIR="{к}/log"\n', encoding="utf-8")
        окружение = {kk: v for kk, v in os.environ.items() if kk != "AGENT_LEVEL"}
        окружение.update(HARNESS_CONF=str(к / "harness.conf"),
                         HARNESS_INSTALL_CONF=str(к / "install.conf"),
                         LOG_DIR=str(к / "log"), PROJECT_DIR=str(к))
        return subprocess.run(
            [sys.executable, str(к / "scripts" / "agent-level.py"), "--повод", повод, *доводы],
            capture_output=True, text=True, timeout=60, env=окружение, cwd=корень)


def судить(имя: str, готово, ждём_зову: bool, слова: tuple = ()) -> None:
    вывод = готово.stdout.strip()
    код_ок = готово.returncode == (0 if ждём_зову else 1)
    if код_ок and all(с in вывод for с in слова):
        путь_ок(f"{имя}: {вывод[:110]}")
    else:
        путь_плохо(f"{имя}: код {готово.returncode}, ждали {0 if ждём_зову else 1}"
                   f" и слова {слова}; вывод: {вывод[:160] or готово.stderr.strip()[:160]}")


СЛОВО_ORDERS = "**24.10 (ночь):** «Пользуйся сабами активно постоянно» — помощники параллельно.\n"
СЛОВО_КАНАЛА = "запускай сабами, чтоб быстрее задачи доделать"

судить("БОЛЬНОЙ п.7: указание в ORDERS.md «Пользуйся сабами» поднимает минимум",
       стенд_зов(БАЗА_ORDERS + СЛОВО_ORDERS, [], "48"), True,
       ("слово владельца", "ORDERS.md"))
судить("БОЛЬНОЙ п.7: «независимые шаги запускать параллельными помощниками» в ORDERS.md — то же",
       стенд_зов(БАЗА_ORDERS + "**24.10:** «независимые шаги запускать параллельными помощниками, чтобы"
                 " быстрее завершить».\n", [], "48"), True, ("слово владельца",))
судить("БОЛЬНОЙ п.7: свежее слово в канале (2 ч назад, предел 48 ч) поднимает минимум",
       стенд_зов(БАЗА_ORDERS, [(2, СЛОВО_КАНАЛА)], "48"), True, ("слово владельца",))
судить("предел свежести — данные: то же слово 100 ч назад при пределе 200 ч поднимает",
       стенд_зов(БАЗА_ORDERS, [(100, СЛОВО_КАНАЛА)], "200"), True, ("слово владельца",))
судить("сосед: слово в канале 100 ч назад при пределе 48 ч — не поднимает, минимум",
       стенд_зов(БАЗА_ORDERS, [(100, СЛОВО_КАНАЛА)], "48"), False, ("минимум",))
судить("сосед: слова владельца нет — минимум, не зову",
       стенд_зов(БАЗА_ORDERS, [(1, "как там прогон?")], "48"), False, ("минимум",))
судить("сосед: «не запускай сабов» — не поднимает",
       стенд_зов(БАЗА_ORDERS, [(1, "не запускай сабов, сам доделай")], "48"), False,
       ("минимум",))
судить("сосед: слово владельца не открывает повод вне закрытого списка",
       стенд_зов(БАЗА_ORDERS + СЛОВО_ORDERS, [], "48", повод="починить-прод-по-быстрому"),
       False, ("нет в данных",))

# Явный --уровень — решение звавшего: слово владельца его не перебивает. На
# стенде, а не боевым путём выше: там ответ зависел бы от живых ORDERS.md и
# входящих этой машины.
судить("сосед: явный --уровень минимум слово владельца в ORDERS.md не поднимает",
       стенд_зов(БАЗА_ORDERS + СЛОВО_ORDERS, [], "48", доводы=("--уровень", "минимум")),
       False, ("минимум",))

print(f"\nитого путей {путей}, неудач {неудач}")
sys.exit(1 if неудач else 0)
