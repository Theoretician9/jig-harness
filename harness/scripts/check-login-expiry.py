КОД_ЛИМИТА = 77


def вердикт_доступа(код, вывод=""):
    """(код, строка) по исходу боевого вызова. Чистая функция — её судит самотест.

    Лимит (77) доступа НЕ опровергает: ключ принят, модель занята до сброса, и
    об этом владельцу говорит сама обёртка. Красным делается только отказ,
    который чинится человеком: ключ не принят.
    """
    if код == 0:
        return 0, "доступ ЖИВОЙ: боевой путь демона получил ответ модели"
    if код == КОД_ЛИМИТА:
        return 0, ("лимит подписки: ключ принят, модель занята до сброса — "
                   "об этом говорит обёртка демона")
    первая = next((с.strip() for с in (вывод or "").splitlines() if с.strip()),
                  "без текста")
    return 1, (f"ДОСТУП НЕ РАБОТАЕТ: боевой путь демона не получил ответ модели "
               f"(код {код}): {первая[:200]}")


def проба_свежа(путь=ПРОБА_СОСТОЯНИЕ, период_ч=ПРОБА_ПЕРИОД_Ч, сейчас=None):
    """Возраст в часах и исход прошлой пробы, либо None — пробы не было.

    Зелёная проба держится период: вызов модели каждые полчаса стоит денег
    впустую. КРАСНАЯ не держится никогда — иначе починка заметится с опозданием
    на период, а именно её и ждут.
    """
    try:
        with open(путь, encoding="utf-8") as fh:
            запись = json.load(fh)
        было = datetime.datetime.fromisoformat(запись["ts"])
        код = int(запись["код"])
    except (OSError, ValueError, KeyError, TypeError):
        return None
    часов = ((сейчас or datetime.datetime.now()) - было).total_seconds() / 3600
    if код != 0 or часов >= период_ч:
        return None
    return часов, код


def запомнить_пробу(код, путь=ПРОБА_СОСТОЯНИЕ):
    try:
        with open(путь, "w", encoding="utf-8") as fh:
            json.dump({"ts": datetime.datetime.now().isoformat(timespec="seconds"),
                       "код": код}, fh, ensure_ascii=False)
    except OSError:
        pass          # журнал пробы не вправе ронять сторожа


def позвать_модель(обёртка=ОБЁРТКА_ДЕМОНА):
    """(код, вывод) боевого вызова из ПУСТОГО каталога. None — звать нечем."""
    if not os.access(обёртка, os.R_OK):
        return None
    import tempfile
    with tempfile.TemporaryDirectory() as пусто:
        try:
            прогон = subprocess.run(
                ["bash", обёртка, ИМЯ_МЕТКИ, "-p", "--model", "haiku",
                 "ответь одним словом: жив"],
                cwd=пусто, capture_output=True, text=True,
                timeout=ПРОБА_ТАЙМАУТ_С)
        except (OSError, subprocess.TimeoutExpired) as беда:
            return 1, f"вызов не состоялся: {беда}"
    return прогон.returncode, (прогон.stdout or "") + (прогон.stderr or "")


