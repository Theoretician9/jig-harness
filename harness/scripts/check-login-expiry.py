КОМАНДЫ_АГЕНТА = ("claude", "node")


def _дети(pid):
    """PID-ы детей процесса. Пусто — детей нет или читать нечем."""
    try:
        with open(f"/proc/{pid}/task/{pid}/children", encoding="utf-8") as fh:
            return fh.read().split()
    except OSError:
        return []


def процесс_смены(сессия=None):
    """PID агента в панели tmux, либо None — панели или агента в ней нет.

    Ищется обходом детей оболочки панели, а не поиском по имени во всей машине:
    совпасть с ЧУЖИМ claude (проба, фоновый вызов демона) значит судить не ту
    смену, а шаблон поиска по командной строке к тому же находит сам себя
    ([[the-wait-catches-itself]]).
    """
    сессия = сессия or конфиг(КОНФИГ_ДЕМОНОВ).get("TMUX_SESSION", "").strip() or "agent"
    панели = _значение(["tmux", "list-panes", "-t", сессия, "-F", "#{pane_pid}"])
    очередь = [p for p in (панели or "").splitlines() if p.isdigit()]
    while очередь:
        pid = очередь.pop(0)
        try:
            with open(f"/proc/{pid}/comm", encoding="utf-8") as fh:
                имя = fh.read().strip()
        except OSError:
            continue
        if имя in КОМАНДЫ_АГЕНТА:
            return pid
        очередь.extend(_дети(pid))
    return None


def оболочки_панелей(сессия=None) -> list:
    """PID оболочек панелей tmux — именно в них уходит команда подъёма смены.

    Пятый носитель, и его не спрашивал никто: ревью 13.10.2026 померило живьём —
    сервер tmux и процесс смены чисты, а в оболочке панели носитель ЖИВ (она
    поднята месяц назад, когда переменная ещё стояла в профиле). Снаружи
    окружение запущенного процесса не снять, поэтому лечит это пересоздание
    панели, то есть обычная ротация; подъём смены носитель срывает сам
    (`env -u` в команде), и аккаунт смены от этого не страдает.
    """
    сессия = сессия or конфиг(КОНФИГ_ДЕМОНОВ).get("TMUX_SESSION", "").strip() or "agent"
    панели = _значение(["tmux", "list-panes", "-t", сессия, "-F", "#{pane_pid}"])
    return [p for p in (панели or "").splitlines() if p.isdigit()]


def вердикт_оболочки(носители: list) -> tuple:
    """(код, строка) про носитель в оболочке панели. Красным НЕ горит.

    Почему не красным: решение о входе принимает команда подъёма, а она
    носитель срывает. Сторож, который кричит там, где работа не страдает,
    учит смену себе не верить — ровно там, где настоящая тревога стоила
    19 дней ([[owner-has-two-accounts]]). Но и молчать нельзя: это живой
    второй носитель, и он уйдёт только с пересозданием панели.
    """
    грязные = [pid for pid, ключ in носители if ключ]
    непрочитанные = [pid for pid, ключ in носители if ключ is None]
    if непрочитанные and not грязные:
        return 0, (f"окружение оболочки панели не прочитать (pid "
                   f"{', '.join(непрочитанные)}) — носитель там не померен")
    if not грязные:
        return 0, "в оболочке панели носителя нет"
    return 0, (f"в оболочке панели ЖИВ носитель {ПЕРЕМЕННАЯ} (pid "
               f"{', '.join(грязные)}): подъём смены его срывает, а уйдёт он "
               f"с пересозданием панели — обычной ротацией")


def ключ_процесса(pid):
    """Ключ входа из окружения процесса: пусто — носителя нет, None — не прочесть.

    «Не прочитать» и «чисто» — разные ответы: закрытый источник, принятый за
    чистоту, красит проверку зелёным ([[unreadable-source-turns-check-green]]).
    Значение живёт только в памяти, в вывод и журналы оно не попадает никогда.
    """
    try:
        with open(f"/proc/{pid}/environ", "rb") as fh:
            данные = fh.read()
    except OSError:
        return None
    голова = (ПЕРЕМЕННАЯ + "=").encode()
    for строка in данные.split(b"\0"):
        if строка.startswith(голова):
            return строка[len(голова):].decode("utf-8", "replace")
    return ""


# Слово, которым ребёнок самотеста говорит «я уже сменил программу».
ГОТОВ = "готов"


def ребёнок_с_окружением(окружение):
    """Живой процесс с НАЗВАННЫМ окружением, уже сменивший программу.

    ПОЧЕМУ НЕ ПРОСТО `Popen`: он возвращает управление после `fork`, а
    окружение нового процесса появляется в `/proc/<pid>/environ` только после
    `exec`. Чтение сразу после запуска — гонка: замер 12.10.2026 дал 3 красных
    прогона из 30 на ВЕРНОМ коде, «прочитано ''». Флейк в приборе, который
    зовут ворота, хуже стойкой красноты: он учит перезапускать, а не чинить.

    ПРИЗНАК ГОТОВНОСТИ — СЛОВО САМОГО РЕБЁНКА, а не имя программы в `comm` и
    не отмеренное время: напечатать его может только процесс, который УЖЕ
    исполняется с нашим окружением. Имя в `comm` этого не доказывает (замер
    12.10: с ожиданием по `comm` осталось 3 красных из 30).
    """
    ребёнок = subprocess.Popen(
        ["sh", "-c", f"echo {ГОТОВ}; sleep 5"],
        env=окружение, stdout=subprocess.PIPE, text=True)
    строка = ребёнок.stdout.readline() if ребёнок.stdout else ""
    return ребёнок, строка.strip() == ГОТОВ


def вердикт_смены(ключ, орг, ожидаемые, повод=""):
    """(код, строка) про идущую смену. Чистая функция — её судит самотест.

    `ожидаемые` — НАБОР организаций владельца (у него их две). Красным горит
    подписка, которой в наборе нет: смена тратит лимит, за который платит не
    владелец. Чинится она не руками и не правкой, а ротацией — поэтому в строке
    названа КОМАНДА, а не «разберись».
    """
    if ключ is None:
        return 2, "окружение процесса смены не прочитать — чем она вошла, не знаю"
    if ключ == "":
        return 0, f"идущая смена вошла по подписке: носителя {ПЕРЕМЕННАЯ} в её окружении нет"
    if not ожидаемые:
        return 2, (f"у идущей смены носитель {ПЕРЕМЕННАЯ}, а сверять не с чем: "
                   f"в {КОНФИГ_ДЕМОНОВ} нет LOGIN_EXPECTED_ORG")
    if not орг:
        return 2, (f"у идущей смены носитель {ПЕРЕМЕННАЯ}, организацию узнать "
                   f"не удалось: {повод}")
    if орг not in ожидаемые:
        return 1, (f"ИДУЩАЯ СМЕНА РАБОТАЕТ НА ЧУЖОЙ ПОДПИСКЕ: в её окружении "
                   f"носитель {ПЕРЕМЕННАЯ}, организация {орг}, у владельца "
                   f"{' и '.join(ожидаемые)}. Лечится ротацией — преемник "
                   f"поднимается без носителя: harness/demons/session-warden.sh --rotate-now")
    return 0, (f"идущая смена: носитель {ПЕРЕМЕННАЯ} в окружении есть, "
               f"но аккаунт тот ({орг})")


