#!/usr/bin/env python3
"""Проба имени спутника отказов у inbox-digest.py.

Беда (3.10 отчёта соседней установки, повтор класса их `7600c30`): спутник
отказов родства пишется в `память/.детали-разобрано`. Всё в `память/` едет в
контекст модели, а такие имена — латиницей (владелец 21.09.2026); гейт имён
этот файл отверг бы, но судит только НОВЫЕ пути в коммите, а файл рождает
демон. Тот же класс уже чинили: `.задачи-разобрано` → `.tasks-triaged`.

Проба судит ПОВЕДЕНИЕ, а не константу: зовёт настоящего писателя
(`отказать_в_родстве`) на стенде и судит гейтом имён КАЖДЫЙ файл, который он
родил. Прочитанное обратно (`отказы_родства`) обязано совпасть с записанным —
иначе переименование писателя без читателя прошло бы молча.

Двери для мутаций: INBOX_DIGEST_UNDER_TEST и CHECK_FILE_NAMES_UNDER_TEST.

    python3 scripts/test_inbox_digest.py
"""
from __future__ import annotations

import contextlib
import importlib.util
import io
import os
import sys
import tempfile
from pathlib import Path

ЗДЕСЬ = Path(__file__).resolve().parent
ПОДСУДНЫЙ = Path(os.environ.get("INBOX_DIGEST_UNDER_TEST") or ЗДЕСЬ / "inbox-digest.py")
ГЕЙТ_ИМЁН = Path(os.environ.get("CHECK_FILE_NAMES_UNDER_TEST") or ЗДЕСЬ / "check-file-names.py")


def загрузить(путь: Path, имя: str):
    спец = importlib.util.spec_from_file_location(имя, путь)
    модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(модуль)
    return модуль


def main() -> int:
    свод = загрузить(ПОДСУДНЫЙ, "inbox_digest_под_тестом")
    гейт = загрузить(ГЕЙТ_ИМЁН, "check_file_names_для_пробы")
    словарь = гейт.английские_слова()
    плохо, всего = 0, 0

    def итог(верно: bool, имя: str, подробно: str = "") -> None:
        nonlocal плохо, всего
        всего += 1
        if верно:
            print(f"  ок    {имя}")
        else:
            плохо += 1
            print(f"  ПЛОХО {имя}" + (f" — {подробно}" if подробно else ""))

    with tempfile.TemporaryDirectory() as стенд:
        корень = Path(стенд)
        with contextlib.redirect_stdout(io.StringIO()):
            свод.отказать_в_родстве("hr.проба-родства", корень)
        рождённые = sorted(str(п.relative_to(корень)) for п in корень.rglob("*") if п.is_file())
        итог(len(рождённые) == 1, "писатель отказа родил ровно один файл",
             f"файлы: {рождённые}")
        нелатинские = гейт.находки(рождённые)
        итог(not нелатинские,
             "БОЛЬНОЙ 3.10: имя спутника отказов — латиница (оно едет в контекст модели)",
             f"гейт имён отверг: {нелатинские}")
        транслит = гейт.транслитные_имена(рождённые, словарь=словарь)
        итог(not транслит, "имя спутника отказов — английские слова, не транслит",
             f"транслит: {транслит}")
        итог(all(р.startswith("память/") for р in рождённые),
             "спутник лежит в память/ — там его ищут писатель и читатель",
             f"файлы: {рождённые}")
        прочитано = свод.отказы_родства(корень)
        итог(прочитано == {"hr.проба-родства"},
             "читатель видит записанный отказ — писатель и читатель на одном имени",
             f"прочитано: {прочитано}")

    print(f"\nвсего путей: {всего}, неудач: {плохо}")
    return 1 if плохо else 0


if __name__ == "__main__":
    sys.exit(main())
