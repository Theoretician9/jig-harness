#!/usr/bin/env python3
"""Гейт: у каждого механизма реестра есть тот, кто его ЗОВЁТ.

СЛУЧАЙ (ревизия архитектуры 12.09.2026). Список гейтов вёлся руками в двух
местах: `vorota.sh` звал одни проверки, `pre-commit-hook.sh` — часть тех же, и
расхождение ничем не объяснялось, а от забытого вызова не отличалось. Реестр
несёт у каждого механизма поле «когда» («на воротах», «каждые сутки в 04:15»),
но гейт устройства требовал только НАЛИЧИЯ поля и ни разу не сверял его с
реальностью. Улика записана в самом файле: проверка из `vorota.sh:230`
написана 03.09 и до ревизии 10.09 её не запускал НИКТО.

Что судим. Поле «когда» говорит, ГДЕ механизм зовётся; здесь это проверяется
по носителям:

  • ворота          — `scripts/vorota.sh`;
  • запись в гит    — `scripts/pre-commit-hook.sh`;
  • расписание      — `harness/config/системные-задания.yaml` (крон и таймеры);
  • вызов из кода   — любой другой файл харнеса зовёт его по имени.

Механизм, которого не зовёт НИКТО, — красный: он мёртв и выглядит живым.

    python3 scripts/check-kto-zovyot.py
    python3 scripts/check-kto-zovyot.py --selftest
Код возврата: 0 — у каждого есть вызывающий, 1 — есть мёртвые.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

КОРЕНЬ = Path(__file__).resolve().parent.parent
РЕЕСТР = КОРЕНЬ / "harness" / "config" / "устройство.yaml"
ВОРОТА = КОРЕНЬ / "scripts" / "vorota.sh"
PRE_COMMIT = КОРЕНЬ / "scripts" / "pre-commit-hook.sh"
ЗАДАНИЯ = КОРЕНЬ / "harness" / "config" / "системные-задания.yaml"
НАСТРОЙКИ = КОРЕНЬ / ".claude" / "settings.json"
# Сторожа инвариантов названы в своих данных поимённо — это вызов.
ИНВАРИАНТЫ = КОРЕНЬ / "harness" / "config" / "инварианты.yaml"

# Виды, которые обязаны иметь вызывающего. Скил зовёт агент словом, документ
# читает человек — у них носителя в коде нет и быть не должно.
СУДИМЫЕ_ВИДЫ = {"гейт", "демон", "хук"}

# Механизмы, у которых вызывающий — ЧЕЛОВЕК или агент по случаю: так и написано
# в их поле «когда». Это не дыра, а честно названный носитель: инструмент
# разовой работы (переименование, запись пропуска, обход механизмов) не обязан
# стоять в воротах.
ЗОВУТ_РУКАМИ = ("вручную", "по запросу", "по случаю")

# Гейты установленных возможностей pre-commit перебирает КАТАЛОГОМ
# (harness/возможности/*/гейты/*.py), а не по имени — искать их имя в коде
# бесполезно.
КАТАЛОГОМ = ("vozmozhnosti/", "возможности/")


def механизмы(путь: Path = РЕЕСТР) -> list[dict]:
    дано = yaml.safe_load(путь.read_text(encoding="utf-8"))
    if isinstance(дано, dict):
        дано = дано.get("механизмы") or next(iter(дано.values()))
    return [м for м in дано if isinstance(м, dict) and м.get("файл")]


def кто_зовёт(файл: str, тексты: dict[str, str]) -> list[str]:
    """Имена носителей, в которых встречается вызов этого файла."""
    имя = Path(файл).name
    нашлись = []
    for носитель, текст in тексты.items():
        # Имя файла целиком. Слева допустим путь («scripts/имя.py»), поэтому
        # под запретом только буква и дефис — первая редакция запрещала и «/»,
        # то есть не видела НИ ОДНОГО вызова по пути. Справа запрещено и
        # продолжение расширения: «имя.py.bak» — другой файл.
        if re.search(rf"(?<![\w-]){re.escape(имя)}(?![\w-]|\.[A-Za-z])", текст):
            нашлись.append(носитель)
            continue
        # Библиотеку зовут ИМПОРТОМ, а не путём: «import konf», «from konf
        # import из_файла». Имя файла в коде при этом не встречается ни разу.
        if имя.endswith(".py"):
            модуль = имя[:-3]
            if re.search(rf"^\s*(?:from\s+{re.escape(модуль)}\s+import|"
                         rf"import\s+{re.escape(модуль)})\b", текст, re.M):
                нашлись.append(носитель)
    return нашлись


def тексты_носителей(корень: Path = КОРЕНЬ) -> dict[str, str]:
    """Носители вызовов: ворота, pre-commit, расписание, настройки и весь
    остальной код харнеса (механизм может звать другой механизм)."""
    итог = {}
    for имя, путь in (("ворота", ВОРОТА), ("запись в гит", PRE_COMMIT),
                      ("расписание", ЗАДАНИЯ), ("настройки оболочки", НАСТРОЙКИ),
                      ("инварианты", ИНВАРИАНТЫ)):
        полный = корень / Path(путь).relative_to(КОРЕНЬ)
        итог[имя] = полный.read_text(encoding="utf-8") if полный.exists() else ""
    куски = []
    for каталог in ("scripts", "harness"):
        основа = корень / каталог
        if not основа.is_dir():
            continue
        for путь in основа.rglob("*"):
            # Только ИСПОЛНЯЕМЫЙ код. Данные сюда не входят намеренно: в
            # реестре у каждого механизма стоит поле «проверяется: python3
            # <он сам>», и реестр «звал» бы каждого — гейт оказался слеп
            # (замер мутацией: убранный из ворот вызов остался незамеченным).
            if путь.suffix not in (".py", ".sh"):
                continue
            if "__pycache__" in путь.parts:
                continue
            куски.append(f"# <<{путь.relative_to(корень)}>>\n"
                         + путь.read_text(encoding="utf-8", errors="replace"))
    итог["код харнеса"] = "\n".join(куски)
    return итог


def мёртвые(реестр: list[dict], тексты: dict[str, str]) -> list[tuple[str, str]]:
    """[(файл, «когда» из реестра)] — механизмы без единого вызывающего."""
    итог = []
    for м in реестр:
        if str(м.get("вид", "")) not in СУДИМЫЕ_ВИДЫ:
            continue
        файл = str(м["файл"])
        когда = str(м.get("когда", "")).lower()
        if any(слово in когда for слово in ЗОВУТ_РУКАМИ):
            continue
        if any(кусок in файл for кусок in КАТАЛОГОМ):
            continue
        свои = {"ворота": ВОРОТА, "запись в гит": PRE_COMMIT,
                "расписание": ЗАДАНИЯ}
        # Свой же файл не считается вызывающим: гейт, который зовёт сам себя
        # в строке «Починка: python3 …», живым от этого не становится.
        без_себя = dict(тексты)
        без_себя["код харнеса"] = re.sub(
            rf"# <<{re.escape(файл)}>>\n(?:.|\n)*?(?=\n# <<|\Z)", "",
            тексты.get("код харнеса", ""))
        if not кто_зовёт(файл, без_себя):
            итог.append((файл, str(м.get("когда", "")).strip()))
    return итог


def проверить() -> int:
    реестр = механизмы()
    находки = мёртвые(реестр, тексты_носителей())
    if находки:
        print(f"[кто зовёт] МЕХАНИЗМ БЕЗ ВЫЗЫВАЮЩЕГО: {len(находки)}")
        for файл, когда in находки:
            print(f"  ✗ {файл} — в реестре «{когда}», а вызова нет нигде")
        print("  Либо позвать (ворота, pre-commit, расписание), либо снять "
              "паспорт: механизм без вызывающего мёртв и выглядит живым.")
        return 1
    судимых = sum(1 for м in реестр if str(м.get("вид", "")) in СУДИМЫЕ_ВИДЫ)
    print(f"[кто зовёт] чисто: у всех {судимых} проверок, помощников и "
          f"перехватчиков есть вызывающий")
    return 0


def самотест() -> int:
    путей = неудач = 0

    def проба(имя: str, ждём, факт):
        nonlocal путей, неудач
        путей += 1
        if факт == ждём:
            print(f"  ок    {имя}")
        else:
            неудач += 1
            print(f"  ПЛОХО {имя}: ждали «{ждём}», вышло «{факт}»")

    тексты = {"ворота": 'проверка "имя" python3 scripts/check-живой.py\n',
              "запись в гит": "", "расписание": "", "настройки оболочки": "",
              "код харнеса": "# <<scripts/check-мёртвый.py>>\nсам себя зову: check-мёртвый.py\n"}
    реестр = [
        {"файл": "scripts/check-живой.py", "вид": "гейт", "когда": "на воротах"},
        {"файл": "scripts/check-мёртвый.py", "вид": "гейт", "когда": "на воротах"},
        {"файл": "harness/skills/пишу-спеку/SKILL.md", "вид": "скил", "когда": "по задаче"},
    ]
    # БОЛЬНОЙ СЛУЧАЙ 12.09.2026: проверка написана, в реестре значится «на
    # воротах», а зовущей строки нет — и это неотличимо от забытого вызова.
    проба("мёртвый механизм назван", [("scripts/check-мёртвый.py", "на воротах")],
          мёртвые(реестр, тексты))
    проба("живой механизм претензии не даёт", [],
          мёртвые(реестр[:1], тексты))
    проба("скил не судится: его зовёт агент словом", [],
          мёртвые(реестр[2:], тексты))
    # Вызов из ДРУГОГО механизма — законный носитель.
    из_кода = dict(тексты)
    из_кода["код харнеса"] += "# <<harness/demons/сторож.sh>>\npython3 scripts/check-мёртвый.py\n"
    проба("вызов из кода харнеса считается", [], мёртвые(реестр[1:2], из_кода))
    # Имя как часть другого имени не считается вызовом.
    почти = dict(тексты)
    почти["ворота"] = 'проверка "x" python3 scripts/check-мёртвый.py.bak\n'
    проба("похожее имя вызовом не считается", 1, len(мёртвые(реестр[1:2], почти)))

    проба("живой реестр чист", 0, проверить())
    print(f"SELFTEST: {'зелёный' if not неудач else 'КРАСНЫЙ'} ({путей} путей; "
          "больной первый — «в реестре есть, а зовут его нигде»)")
    return 1 if неудач else 0


if __name__ == "__main__":
    sys.exit(самотест() if "--selftest" in sys.argv else проверить())
