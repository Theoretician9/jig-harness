    проба("и прибор называет ИМЕННО свободный пункт", True,
          "чинить соседний гейт" in (места[0]["почему"] if места else ""))

    # Обратная сторона: все незакрытые пункты заблокированы — работы нет.
    # Так стоит `hr.universalnyj-harnes`: шаги 3-8 ждут разрешения владельца, и
    # предложить их значило бы звать меня туда, куда он идти запретил.
    карта = {"queue": [], "lines": [{"id": "h", "tasks": [
        {"id": "весь-в-блокере", "status": "plan", "blocked": "ждёт разрешения",
         "checklist": [{"label": "шаг 3", "done": False, "blocked": "ждёт разрешения"},
                       {"label": "шаг 4", "done": False, "blocked": "ждёт разрешения"}]},
        {"id": "свободная", "status": "wip"}]}]}
    проба("все пункты заблокированы — карточка работой не считается",
          ["свободная"], [м["id"] for м in порядок(карта, направление="h",
                                                   настройки=настройки, внимание={})])

    # Блокер без чеклиста — судить не по чему, значит ждём (как и раньше).
    карта = {"queue": [], "lines": [{"id": "h", "tasks": [
        {"id": "голый-блокер", "status": "plan", "blocked": "ждёт владельца"},
        {"id": "свободная", "status": "wip"}]}]}
    проба("блокер без чеклиста по-прежнему прячет карточку",
          ["свободная"], [м["id"] for м in порядок(карта, направление="h",
                                                   настройки=настройки, внимание={})])

    # test без внимания владельца — не моя работа, она ждёт его.
