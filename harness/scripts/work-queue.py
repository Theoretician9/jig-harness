# Веса и слова — ДАННЫЕ (harness/config/очередь.yaml). Умолчания здесь нужны не
# «на всякий случай», а для свежей установки: файла данных ещё нет, а прибор
# уже зовут из осмотра сессии.
НАСТРОЙКИ_ПО_УМОЛЧАНИЮ = {
    "веса": {"внимание_владельца": 100, "провал_проверки": 40,
             "wip": 30, "queue": 20, "plan": 0, "почти_закончена": 10},
    "внимание_суток": 3,
    "почти_закончена_с_доли": 0.5,
    "свежесть_максимум": 9,
    "потолок_строк": 10,
}


def настройки(путь: str | Path | None = None) -> dict:
    """Данные порядка. Нет файла — умолчания, а не отказ: прибор не гейт."""
    файл = Path(путь) if путь else (Path(__file__).resolve().parent.parent
                                    / "harness" / "config" / "очередь.yaml")
    итог = dict(НАСТРОЙКИ_ПО_УМОЛЧАНИЮ)
    try:
        свои = yaml.safe_load(файл.read_text(encoding="utf-8")) or {}
    except (OSError, yaml.YAMLError):
        return итог
    итог.update({к: v for к, v in свои.items() if v is not None})
    итог["веса"] = {**НАСТРОЙКИ_ПО_УМОЛЧАНИЮ["веса"], **(свои.get("веса") or {})}
    return итог


def внимание_владельца(журнал: str | Path | None = None, суток: int = 3,
                       сейчас: float | None = None) -> dict:
    """{id сообщения: слово} по журналу, который ведёт ДИСПЕТЧЕР канала.

    Признак срочности ставит тот, чьи это слова, а не тот, кому он выгоден:
    агент этот файл только читает (находка ревью C-10 — та же, по которой
    отвергнуто поле priority в карточке).

    Просроченное не возвращается: у пометки обязан быть срок, иначе через
    неделю она поднимает наверх то, что владелец давно забыл.
    """
    import json
    import time
    файл = Path(журнал) if журнал else Path(
        конф.log_dir()) / "внимание.jsonl"
    сейчас = time.time() if сейчас is None else сейчас
    итог = {}
    try:
        строки = файл.read_text(encoding="utf-8").splitlines()
    except OSError:
        return итог
    for строка in строки:
        try:
            запись = json.loads(строка)
            ид = str(запись["id"])
            когда = float(запись.get("метка") or ид)
        except (ValueError, KeyError, TypeError):
            continue          # битую строку журнала пропускаем, но не падаем
        if сейчас - когда <= суток * 86400:
            итог[ид] = запись.get("слово") or "прямое слово владельца"
    return итог


def _источник_метка(задача: dict) -> float:
    """Метка времени сообщения, из которого заведена задача. Нет — 0."""
    сырое = str(задача.get("источник") or "")
    метки = формы.ИСТОЧНИК_INBOX.findall(сырое)
    значения = []
    for м in метки:
        try:
            значения.append(float(м))
        except ValueError:
            continue
    return max(значения) if значения else 0.0


def порядок(data: dict, направление: str | None = None, настройки: dict | None = None,
            внимание: dict | None = None) -> list[dict]:
    """Задачи в порядке работы: [{id, вес, почему}], первая — что делать сейчас.

    Правило источников то же, что у разобрать(), плюс хвост `plan`. Статус
    `test` в порядок не идёт: работа сделана и ждёт владельца, а не меня.
    Прямое слово владельца снимает ЛЮБОЕ исключение, кроме закрытых статусов:
    иначе «могу направить внимание на любую задачу» не выполняется.
    """
    напр = активное_направление() if направление is None else направление
    наст = настройки or НАСТРОЙКИ_ПО_УМОЛЧАНИЮ
    веса = dict(НАСТРОЙКИ_ПО_УМОЛЧАНИЮ["веса"], **(наст.get("веса") or {}))
    внимание = внимание or {}
    задачи = {t.get("id"): t
              for line in data.get("lines") or []
              if not напр or line.get("id") == напр
              for t in line.get("tasks") or []}
    # Задачи ВСЕЙ карты — чтобы отличить «карточки нет вовсе» (битая очередь,
    # её надо заметить) от «карточка в другом направлении» (над ним сейчас не
    # работаем). Живой случай 12.09.2026: в queue висели три задачи продукта,
    # и первой строкой «сейчас делаем» шла чужая задача без карточки.
    все_задачи = {t.get("id") for line in data.get("lines") or []
                  for t in line.get("tasks") or []}
    очередь = list(data.get("queue") or [])

    места = []
    for ид in dict.fromkeys(очередь + list(задачи)):
        задача = задачи.get(ид)
        if задача is None:
            if ид in все_задачи:
                continue      # карточка есть, но в другом направлении — не наше
            # Карточки нет НИГДЕ: битую очередь прибор не прощает — так же, как
            # разобрать(), иначе два вывода одного прибора разошлись бы.
            места.append({"id": ид, "вес": веса["queue"],
                          "почему": "в очереди, а карточки в карте нет"})
            continue
        слово = _слово_внимания(задача, внимание)
        статус = задача.get("status")
        блокер = задача.get("blocked")
        провал = задача.get("провал_проверки")
        if статус in ("done", "принято"):
            continue
        свободные = свободные_пункты(задача)
        # Блокер карточки прячет её ЦЕЛИКОМ только когда внутри нечего делать:
        # незаблокированный пункт — это «любая другая работа» из его слова.
        if not слово and блокер and not свободные:
            continue
        # Статус test — работа СДЕЛАНА и ждёт владельца. Его слово поднимает
        # и её (находки C-1, C-2: «займись» снимает любой фильтр), но только
        # если оно СВЕЖЕЕ закрытия: 27.09.2026 прибор ответил ему «В плане
        # следующей: Разбор отчётов харнеса» про задачу, закрытую накануне со
        # всеми пунктами, — слово «первым делом» было сказано ДО работы и к
        # сделанному уже не относилось. Он на это и написал: «по сути я не
        # имел информации что у тебя вообще есть эта задача».
        # Свободная работа видна В ЛЮБОМ статусе (находка ревью Q-05): в test
        # карточка уходила из порядка целиком, и её незаблокированные пункты
        # пропадали вместе с ней — тот же дефект, что чинили 27.09.2026 для
        # блокера у карточки. Слово владельца 26.09: «если у тебя блокер, но при
        # этом есть любая другая работа, она должна исполняться». Замер
        # 28.09.2026: так становятся видны 2 задачи из 36 в test.
        if (статус == "test" and not провал and not свободные_пункты(задача)
                and (not слово or слово_исполнено(задача))):
            continue
        вес, почему = 0, []
        if слово:
            вес += веса["внимание_владельца"]
            почему.append(f"внимание владельца: «{слово}»")
        if провал:
            вес += веса["провал_проверки"]
            почему.append("провалила проверку")
        if статус == "wip":
            вес += веса["wip"]
            почему.append("начата")
        if ид in очередь:
            вес += веса["queue"]
            почему.append("в очереди")
        доля = доля_закрытого(задача)
        if доля >= наст["почти_закончена_с_доли"]:
            вес += веса["почти_закончена"]
            почему.append(f"закрыто {int(доля * 100)} % пунктов")
        if not почему:
            почему.append("план")
        if блокер:
            почему.append(f"блокер: {блокер}")
            if свободные:
                почему.append(f"но свободен пункт: «{свободные[0].get('label')}»")
        места.append({"id": ид, "вес": вес, "почему": ", ".join(почему),
                      "метка": _источник_метка(задача)})

    # Свежесть источника разводит хвост: без неё девять задач из десяти
    # получают 0, и порядок вырождается в порядок строк в файле.
    с_меткой = sorted({м["метка"] for м in места if м.get("метка")})
    шаг = наст["свежесть_максимум"]
    for м in места:
        метка = м.pop("метка", 0.0)
        if метка and len(с_меткой) > 1:
            м["вес"] += round(шаг * с_меткой.index(метка) / (len(с_меткой) - 1))
        elif метка:
            м["вес"] += шаг
    места.sort(key=lambda м: -м["вес"])
    return места if напр else места[:наст["потолок_строк"]]


def следующая(data: dict, направление: str | None = None, настройки: dict | None = None,
              внимание: dict | None = None) -> dict | None:
    """Что брать СЕЙЧАС: первая задача порядка, либо None — всё заблокировано.

    Владелец 26.09.2026: «нужна иерархия, если у тебя блокер, но при этом есть
    любая другая работа, она должна исполняться, вплоть до следующего блокера.
    Это должен быть механизм».

    В тот день я трижды сказал «свободной работы нет», пока порядок держал
    четырёх кандидатов: число работ считалось по одному правилу (очередь плюс
    начатое), а порядок строился по другому — два вывода ОДНОГО прибора
    расходились молча, и верным оказывался тот, в который я не смотрел.
    Теперь судья один: и «работа: N», и «следующая» берутся из порядка.
    """
    места = порядок(data, направление, настройки, внимание)
    return места[0] if места else None


def свободные_пункты(задача: dict) -> list[dict]:
    """Незакрытые пункты чеклиста, у которых НЕТ своего блокера.

    Владелец 26.09.2026: «если у тебя блокер, но при этом есть любая другая
    работа, она должна исполняться, вплоть до следующего блокера». Прибор
    исполнял это между КАРТОЧКАМИ, но не внутри: блокер стоял у карточки, и
    вместе с ним из очереди пропадали её незаблокированные пункты.

    Улика 27.09.2026: у `hr.разобрать-находки-ревью` блокером был один вопрос
    владельцу (I-3), а пять находок ревью остановки, не ждавших никого, прибор
    не показывал — их пришлось выносить отдельной карточкой руками.
    """
    return [п for п in (задача.get("checklist") or [])
            if not п.get("done") and not п.get("blocked")]


def доля_закрытого(задача: dict) -> float:
    """Какая часть чеклиста закрыта. Нет чеклиста — 0, судить не по чему.

    Владелец 13.09.2026: порядок задаёт «эффективность и логичность
    разработки», а не свежесть его сообщений. Признаков эффективности в карте
    оказалось меньше, чем хотелось: поля зависимостей («что разблокирует
    другие») нет вовсе — 147 карточек, ни одной связи, — и придумывать его
    здесь значило бы считать по пустоте. Что есть честно: доведение начатого
    до конца дешевле начала нового, и это видно по чеклисту.
    """
    пункты = задача.get("checklist") or []
    if not пункты:
        return 0.0
    закрыто = sum(1 for п in пункты if п.get("done"))
    return закрыто / len(пункты)


def слово_исполнено(задача: dict) -> bool:
    """Всё, о чём просил владелец, уже сделано?

    Признак — ЗАКРЫТЫЕ ПУНКТЫ, а не дата: слово «первым делом» сказано
    26.09.2026 в 18:19, работа закрыта в тот же день позже, и сравнение по
    суткам считало слово свежим — ровно тот ответ, на который он и написал
    «по сути я не имел информации что у тебя вообще есть эта задача».
    Незакрытый пункт — работа есть, и слово владельца её поднимает; ни одного
    незакрытого — сделанному место в строке «ждёт вашей проверки».
    """
    пункты = задача.get("checklist") or []
    if not пункты:
        return False                  # чеклиста нет — судить нечем, не спорим
    # Судим ВСЕ незакрытые, а не только свободные (находка ревью Q-01): пункт с
    # собственным блокером — это незакрытая работа, и слово владельца её
    # поднимает. Прежний счёт объявлял исполненной карточку, у которой вся
    # оставшаяся работа заблокирована, — ровно наоборот смыслу.
    return not [п for п in пункты if not п.get("done")]


def _слово_внимания(задача: dict, внимание: dict) -> str:
    """Слово владельца по любому из источников задачи (их бывает несколько)."""
    for ид in формы.ИСТОЧНИК_INBOX.findall(str(задача.get("источник") or "")):
        if ид in внимание:
            return внимание[ид]
    return ""


def разобрать(data: dict, направление: str | None = None) -> tuple[int, list[str]]:
    """→ (сколько задач можно делать самому, список «id=причина» по остальным)."""
    направление = активное_направление() if направление is None else направление
    tasks = {
        t.get("id"): t
        for line in data.get("lines") or []
        if not направление or line.get("id") == направление
        for t in line.get("tasks") or []
    }
    # Задачи ДРУГОГО направления: карточка есть, но она не наша. Без этого
    # прибор считал их «карточки нет» и объявлял работой — 14.09.2026 очередь
    # из трёх задач отложенного направления будила смену по харнесу каждые
    # одиннадцать минут, хотя у всех трёх стоит blocked. Второй вывод прибора
    # (места()) такое различал: два вывода одного прибора разошлись молча.
    чужие = {t.get("id") for line in data.get("lines") or []
             for t in line.get("tasks") or []} - set(tasks)
    # Судья ОДИН. До 26.09.2026 «работа» считалась по очереди и начатому, а
    # порядок строился по всей карте: прибор отвечал «работа: 0», имея четырёх
    # кандидатов, и смена трижды за час встала со словами «свободной работы
    # нет». Владелец: «если у тебя блокер, но есть любая другая работа, она
    # должна исполняться, вплоть до следующего блокера».
    места = порядок(data, направление)
    берущиеся = [м for м in места
                 if "блокер:" not in м["почему"] and not м["почему"].startswith("внимание владельца")
                 or "провалила проверку" in м["почему"]]
    работа, ждут = len(берущиеся), []
    # Одним списком: очередь, начатое и ПРОВАЛИВШАЯ ПРОВЕРКУ. Провал — это
    # работа: приёмка его нашла, а починка за мной. Без этого провал виден
    # только в карточке, и я узнаю о нём, случайно открыв карту (вопрос
    # владельца 12.09.2026: «С провалом что? Куда уходит и как причина»).
    начатые = [и for и, з in tasks.items()
               if з.get("status") == "wip" or з.get("провал_проверки")]
    for qid in dict.fromkeys(list(data.get("queue") or []) + начатые):
        задача = tasks.get(qid)
        # Задачи нет в карте — это ловит валидатор pre-commit. Здесь считаем её
        # работой: прибор не должен молчаливо прощать битую очередь.
        if задача is None:
            continue          # битую очередь ловит валидатор схемы, не прибор
        причина = задача.get("blocked")
        if причина:
            ждут.append(f"{qid}={причина}")
    # Ждущие — по ВСЕЙ карте, а не только по очереди: блокер стоит у карточки,
    # и попала она в queue: или нет, владельца это не касается.
    for ид, задача in tasks.items():
        причина = задача.get("blocked")
        if (причина
                and задача.get("status") not in ("done", "принято")
                and not any(с.startswith(f"{ид}=") for с in ждут)):
            ждут.append(f"{ид}={причина}")
    return работа, ждут


def _коротко(задача: dict, предел: int = 58) -> str:
    """Заголовок задачи человеческими словами: id владельцу ничего не говорит."""
    имя = str(задача.get("title") or задача.get("id") or "").strip()
    return имя if len(имя) <= предел else имя[:предел - 1].rstrip() + "…"


def _сделано(часов: int = 12, сколько: int = 1) -> list[str]:
    """Заголовки коммитов смены. «Что сделал» — это git, а не моя память."""
    try:
        вывод = subprocess.run(
            ["git", "-C", str(Path(__file__).resolve().parent.parent),
             "log", f"--since={часов} hours ago", "--format=%s", f"-{сколько}"],
            capture_output=True, text=True, timeout=20).stdout
    except (OSError, subprocess.SubprocessError):
        return []
    return [с.strip() for с in вывод.splitlines() if с.strip()]


def для_владельца(data: dict, сделал: list[str] | None = None,
                  доска: str | None = None) -> list[str]:
    """Ответ на /status: что сделал, что делаю, что дальше — и ничего сверх.

    Владелец 13.09.2026, увидев прежний ответ: «ерунда какая то ответ. мне
    нужен понимать что ты делаешь, что сделал, что дальше». До этого ответ был
    дампом прибора (id, вес числом, первая задача дважды), а после первой
    правки «Делаю» показало ЕГО ЖЕ фразу: автомат карточек называет задачу
    первой строкой сообщения, и свежая карточка встаёт первой в очереди.

    Поэтому «делаю» берётся с ДОСКИ — там я пишу о себе своими словами
    (board.py, у записи обязательный срок). Очередь остаётся запасным ответом
    и честно помечается как план, а не как работа.
    """
    строки = []
    # «Сделал» и «делаю» приходят ДОВОДАМИ с боевым умолчанием (находка ревью
    # Q-07): прежде самотест звал настоящий git log и настоящую доску смены и
    # был зелёным лишь потому, что в репозитории есть свежие коммиты — проба
    # судила машину, а не прибор ([[a-test-that-depends-on-who-runs-it]]).
    сделал = _сделано() if сделал is None else сделал
    if сделал:
        строки.append("Сделал: " + _обрезать(сделал[0], 90))

    наст = настройки()
    места = порядок(data, направление=активное_направление(), настройки=наст,
                    внимание=внимание_владельца(суток=наст["внимание_суток"]))
    задачи = {t.get("id"): t
              for line in data.get("lines") or []
              for t in line.get("tasks") or []}
    доска = _доска_смены() if доска is None else доска
    if доска:
        строки.append("Делаю: " + _обрезать(доска, 90))
    elif места:
        строки.append("В плане следующей: "
                      + _коротко(задачи.get(места[0]["id"], {}), 70))
    else:
        строки.append("Делаю: очередь пуста — работы в карте нет.")

    дальше = [_коротко(задачи.get(м["id"], {}), 60) for м in места[1:2]]
    if доска and места:
        дальше = [_коротко(задачи.get(места[0]["id"], {}), 60)]
    if дальше:
        строки.append("Дальше: " + дальше[0])

    # Две строки про ЕГО долю. Владелец 27.09.2026: «ты мне назвал 4, но ту
    # что начал выполнять в списке не было и по сути я не имел информации что
    # у тебя вообще есть эта задача». Ответ собирался руками именно потому,
    # что прибор называл только работу и врал про неё; теперь он называет
    # ОБЕ доли — мою и его, — и собирать руками нечего.
    его = ждёт_владельца(data)
    if его["решений"]:
        строки.append(f"Ждут вашего слова: {его['решений']} — "
                      + "; ".join(его["имена"][:3]))
    if его["проверок"]:
        строки.append(f"Сделано, ждёт вашей проверки: {его['проверок']}")
    return строки


def ждёт_владельца(data: dict, направление: str | None = None) -> dict:
    """Сколько задач ждут ЕГО: решения (блокер) и проверки (статус test).

    Отдельной функцией, потому что проба обязана судить именно счёт: внутри
    печати мутация «считать и закрытые» осталась бы зелёной.
    """
    решений, имена, проверок = 0, [], 0
    # Направление — ДОВОД с тем же умолчанием, что у порядка работ: проба со
    # своим стендом обязана судить свой стенд, а не боевое направление машины
    # ([[the-probe-played-on-production]]).
    напр = активное_направление() if направление is None else направление
    for линия in data.get("lines") or []:
        # Направление судится ТАК ЖЕ, как в порядке работ (находка ревью Q-03):
        # иначе, как только в отложенном направлении появятся карточки, владельцу
        # начнут считать работу, которую он сам отложил.
        if напр and линия.get("id") and линия.get("id") != напр:
            continue
        for задача in линия.get("tasks") or []:
            статус = задача.get("status")
            if статус in ("done", "принято"):
                continue
            # Блокер РАНЬШЕ статуса (находка ревью Q-02): карточка в test с
            # блокером ждёт его ОТВЕТА, а не проверки, и прежний порядок
            # разводил два вывода прибора — «ждут» называл одно число,
            # «--владельцу» другое.
            if задача.get("blocked") and not свободные_пункты(задача):
                решений += 1
                имена.append(_обрезать(задача.get("title") or задача.get("id"), 45))
                continue
            # `owner_testable: false` значит «проверяет МЕХАНИЗМ» — такая
            # карточка ждёт прогона приёмки, а не его глаз. Замер 28.09.2026:
            # прибор называл ему 33 задачи, своих у него было 19, остальные 14
            # лежали в долге механизма (у 11 — готовая команда проверки).
            # Владелец 11.09: «оставлять ему только то, чего машина проверить не может».
            # Потолок OWNER_QUEUE_MAX держит НЕ этот счётчик, а демон приёмки
            # по своему разбору (acceptance-watch.sh, исход «ждёт-владельца»):
            # здесь мы лишь перестаём называть ему чужой долг.
            if статус == "test" and задача.get("owner_testable") is not False:
                проверок += 1
    return {"решений": решений, "имена": имена, "проверок": проверок}


def _обрезать(текст: str, предел: int) -> str:
    текст = str(текст or "").strip()
    return текст if len(текст) <= предел else текст[:предел - 1].rstrip() + "…"


def _доска_смены() -> str:
    """Что смена сказала о себе сама. Протухшую запись доска не отдаёт."""
    try:
        вышло = subprocess.run(
            [sys.executable,
             str(Path(__file__).resolve().parent / "board.py"), "--читать", "смена"],
            capture_output=True, text=True, timeout=20)
    except (OSError, subprocess.SubprocessError):
        return ""
    return вышло.stdout.strip() if вышло.returncode == 0 else ""


def напечатать(data: dict, с_порядком: bool = False) -> None:
    работа, ждут = разобрать(data)
    print(f"работа: {работа}")
    print("ждут: " + "; ".join(ждут))
    if not с_порядком:
        return
    # Старые две строки печатаются ВСЕГДА и первыми: их читают сторож сессий и
    # осмотр сессии. Порядок идёт следом одним и тем же разбором карты — иначе
    # осмотр разбирал бы файл в 390 КБ дважды.
    наст = настройки()
    напр = активное_направление()
    if not напр:
        print("порядок: направление не выбрано (ACTIVE_LINE пуст) — считаю по всей карте")
    места = порядок(data, направление=напр, настройки=наст,
                    внимание=внимание_владельца(суток=наст["внимание_суток"]))
    if not места:
        print("сейчас делаем: очередь пуста")
        return
    print(f"сейчас делаем: {места[0]['id']} — {места[0]['почему']}")
    for номер, м in enumerate(места[:наст["потолок_строк"]], 1):
        print(f"  {номер}. {м['id']} · {м['вес']} · {м['почему']}")


