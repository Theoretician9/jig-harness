ВЫПОЛНЕНА = ЗАКРЫТЫЕ + ("test",)


def зависимости_задачи(задача: dict) -> list[str]:
    """Поле `зависит_от` как список id: строка — один id, мусор не учитывается.

    Поле необязательное и пишется руками: прибор, который падает на опечатке
    в типе, стоит дороже, чем пропущенная зависимость.
    """
    поле = задача.get("зависит_от")
    if isinstance(поле, str):
        return [поле]
    if isinstance(поле, list):
        return [ид for ид in поле if isinstance(ид, str)]
    return []


def невыполненные(data: dict) -> dict[str, list[tuple[str, str]]]:
    """{карточка: [(предшественник, статус)]} по ВСЕЙ карте, только держащие.

    Предшественник ищется по всей карте, а не по активной линии: зависимость
    через линии — обычный случай. id вне карты не держит: опечатка не должна
    молча прятать карточку (её ловит `--готовые --битые`). Смотрим только
    прямой статус предшественника, без хода по цепочке, поэтому цикл не вешает
    прибор, а просто ждёт.
    """
    карточки = [t for line in data.get("lines") or [] for t in line.get("tasks") or []]
    статусы = {t.get("id"): t.get("status") for t in карточки}
    ждущие = {}
    for задача in карточки:
        держат = [(ид, статусы[ид]) for ид in dict.fromkeys(зависимости_задачи(задача))
                  if ид in статусы and статусы[ид] not in ВЫПОЛНЕНА]
        if держат:
            ждущие[задача.get("id")] = держат
    return ждущие


def цикл_зависимостей(ид: str, ждущие: dict) -> list[str]:
    """Цикл `ид → … → ид` по невыполненным зависимостям или [] — ид не в цикле.

    Обход в ширину с запоминанием посещённых и без рекурсии: рекурсия упала бы
    по глубине на длинной цепочке зависимостей, а цепочки в карте бывают длинные.
    """
    родитель, очередь = {ид: None}, [ид]
    for узел in очередь:
        for пред, _ in ждущие.get(узел, []):
            if пред == ид:
                путь = [узел]
                while родитель[путь[-1]] is not None:
                    путь.append(родитель[путь[-1]])
                return путь[::-1] + [ид]
            if пред not in родитель:
                родитель[пред] = узел
                очередь.append(пред)
    return []


ПРЕДЕЛ_ИМЁН_ЦИКЛА = 12


def циклы_ожидания(ждущие: dict) -> dict[str, list[str]]:
    """{член цикла: цикл `ид → … → ид`} за ОДИН проход по графу ждущих.

    Компоненты сильной связности (Тарьян, итеративно): член цикла — тот, чья
    компонента больше одной карточки или замкнута на себя. Цикл искать от
    каждой карточки отдельно значило бы обход всей цепочки на каждую — квадрат
    по числу карточек; здесь обход по компоненте идёт раз на компоненту, и
    лишний раз только для члена, не попавшего на найденный цикл (хорда).
    """
    граф = {к: [п for п, _ in держат if п in ждущие] for к, держат in ждущие.items()}
    номер, низ, на_стеке, стек, компоненты = {}, {}, set(), [], []
    for корень in граф:
        if корень in номер:
            continue
        номер[корень] = низ[корень] = len(номер)
        стек.append(корень)
        на_стеке.add(корень)
        вызовы = [(корень, iter(граф[корень]))]
        while вызовы:
            узел, соседи = вызовы[-1]
            for сосед in соседи:
                if сосед not in номер:
                    номер[сосед] = низ[сосед] = len(номер)
                    стек.append(сосед)
                    на_стеке.add(сосед)
                    вызовы.append((сосед, iter(граф[сосед])))
                    break
                if сосед in на_стеке:
                    низ[узел] = min(низ[узел], номер[сосед])
            else:
                вызовы.pop()
                if вызовы:
                    родитель = вызовы[-1][0]
                    низ[родитель] = min(низ[родитель], низ[узел])
                if низ[узел] == номер[узел]:
                    компонента = []
                    while True:
                        карточка = стек.pop()
                        на_стеке.discard(карточка)
                        компонента.append(карточка)
                        if карточка == узел:
                            break
                    компоненты.append(компонента)
    циклы = {}
    for компонента in компоненты:
        корень = компонента[-1]
        if len(компонента) == 1 and корень not in граф[корень]:
            continue
        члены = set(компонента)
        внутри = {к: [(п, с) for п, с in ждущие[к] if п in члены] for к in компонента}
        общий = цикл_зависимостей(корень, внутри)
        на_цикле = set(общий)
        for к in компонента:
            циклы[к] = общий if к in на_цикле else цикл_зависимостей(к, внутри)
    return циклы


def ждёт_зависимость(задача: dict, ждущие: dict) -> bool:
    """Карточка стоит из-за зависимости: держит невыполненная и она не отложена.

    Начатое не бросают (память queue-by-efficiency-owner-order, п. 1): wip
    не ждёт, зависимость лишь пишется в «почему». Сделанная test (ни провала,
    ни свободного пункта) не ждёт и без зависимости — её ждёт владелец.
    """
    if задача.get("id") not in ждущие:
        return False
    статус = задача.get("status")
    if статус in НЕ_РАБОТА or статус == "wip":
        return False
    return not (статус == "test" and not задача.get("провал_проверки")
                and not свободные_пункты(задача))


def причина_ожидания(ид: str, ждущие: dict, циклы: dict) -> str:
    """Почему карточка не идёт в работу: цикл с именами или первый предшественник."""
    цикл = циклы.get(ид)
    if цикл:
        # Длинный цикл в строке «ждут» не перечисляем целиком: каждый его член
        # несёт эту строку, и 2000 карточек дали бы 40 МБ вывода на «работа: N».
        if len(цикл) > ПРЕДЕЛ_ИМЁН_ЦИКЛА + 1:
            return ("цикл зависимостей: " + " → ".join(цикл[:ПРЕДЕЛ_ИМЁН_ЦИКЛА])
                    + f" → … (карточек в цикле: {len(цикл) - 1})")
        return "цикл зависимостей: " + " → ".join(цикл)
    пред, статус = ждущие[ид][0]
    return f"ждёт {пред} ({статус})"


