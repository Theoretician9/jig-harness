ЯРУС_НАЧАТОЙ = 0
ЯРУС_ОТКРЫТОЙ = 1
ЯРУС_СДЕЛАННОЙ = 2


def _ярус(статус: str | None, провал: object) -> int:
    """test с провалом приёмки — открытая работа: починка за сменой."""
    if статус == "wip":
        return ЯРУС_НАЧАТОЙ
    if статус == "test" and not провал:
        return ЯРУС_СДЕЛАННОЙ
    return ЯРУС_ОТКРЫТОЙ


def головные(места: list[dict]) -> list[dict]:
    """Места, которые можно брать в работу: без яруса сделанных."""
    return [м for м in места if м["ярус"] < ЯРУС_СДЕЛАННОЙ]


