def зависимости_самотест() -> bool:
    """Пути зависимостей задач: ждёт, выполнена, цикл, id вне карты."""
    ok = True

    def проба(имя, ждём, вышло):
        nonlocal ok
        if вышло == ждём:
            print(f"  ок    {имя}")
        else:
            ok = False
            print(f"  ПЛОХО {имя}: ждали {ждём}, вышло {вышло}")

    def ид_порядка(*задачи):
        карта = {"queue": [], "lines": [{"id": "h", "tasks": list(задачи)}]}
        return [м["id"] for м in порядок(карта, направление="h", внимание={})]

    проба("зависимость от начатой: карточка ждёт и в порядок не входит",
          ["п"], ид_порядка({"id": "п", "status": "wip"},
                            {"id": "х", "status": "plan", "зависит_от": ["п"]}))
    проба("предшественник в test — зависимость выполнена",
          ["х"], ид_порядка({"id": "п", "status": "test"},
                            {"id": "х", "status": "plan", "зависит_от": "п"}))
    проба("цикл не вешает: оба ждут, свободная идёт",
          ["з"], ид_порядка({"id": "а", "зависит_от": ["б"]},
                            {"id": "б", "зависит_от": ["а"]}, {"id": "з"}))
    проба("id вне карты зависимость не держит",
          ["х"], ид_порядка({"id": "х", "зависит_от": ["нет.такой", 5, None]}))
    карта_цикла = {"lines": [{"id": "h", "tasks": [
        {"id": "а", "зависит_от": ["б"]}, {"id": "б", "зависит_от": ["а"]}]}]}
    проба("причина цикла называет участников",
          "цикл зависимостей: а → б → а",
          причина_ожидания("а", невыполненные(карта_цикла),
                           циклы_ожидания(невыполненные(карта_цикла))))
    return ok


def порядок_самотест() -> bool:
    """Пути расчёта ПОРЯДКА. Первым — больной случай, ради которого он заведён."""
    ok = True

    def проба(имя, ждём, вышло):
        nonlocal ok
        if вышло == ждём:
            print(f"  ок    {имя}")
        else:
            ok = False
            print(f"  ПЛОХО {имя}: ждали {ждём}, вышло {вышло}")

    настройки = НАСТРОЙКИ_ПО_УМОЛЧАНИЮ

    # БОЛЬНОЙ СЛУЧАЙ 06.10.2026: пометка «срочно» переживала закрытие задачи.
    # Карточка лендинга закрыта статусом test с доводом в «чем_подтверждено», а
