def напечатать_готовые(data: dict, ждут: bool = False, битые: bool = False) -> None:
    """`--готовые`: «готовых: N» и id по строке в порядке порядок(), без потолка.

    Читают судья режимов и оркестратор, раздающий работу параллельно, поэтому
    список полный, а не первые десять, как у `--порядок`. `ждут` и `битые`
    добавляют объяснения после id — их строки с пробелами, id без пробелов.
    """
    наст = настройки()
    напр = активное_направление()
    места = порядок(data, направление=напр, настройки=наст,
                    внимание=внимание_владельца(суток=наст["внимание_суток"]),
                    тревоги=тревоги_сторожей(data), без_потолка=True)
    ид_готовых = [м["id"] for м in работа_из_порядка(места)]
    print(f"готовых: {len(ид_готовых)}")
    for ид in ид_готовых:
        print(ид)
    карточки = [t for line in data.get("lines") or [] for t in line.get("tasks") or []]
    if ждут:
        ждущие = невыполненные(data)
        циклы_членов = циклы_ожидания(ждущие)
        в_линии = [t for line in data.get("lines") or []
                   if not напр or line.get("id") == напр
                   for t in line.get("tasks") or []]
        циклы = {}
        for задача in в_линии:
            ид = задача.get("id")
            if not ждёт_зависимость(задача, ждущие):
                continue
            for пред, статус in ждущие[ид]:
                print(f"ждёт: {ид} ← {пред} ({статус})")
            if ид in циклы_членов:
                циклы.setdefault(id(циклы_членов[ид]), циклы_членов[ид])
        for цикл in циклы.values():
            print("цикл зависимостей: " + " → ".join(цикл))
    if битые:
        есть = {t.get("id") for t in карточки}
        всего = 0
        for задача in карточки:
            for пред in dict.fromkeys(зависимости_задачи(задача)):
                всего += 1
                if пред not in есть:
                    print(f"битая зависимость: {задача.get('id')} → {пред}")
        # Ноль пишем словами: молчание нельзя отличить от «прибор не смотрел».
        print(f"зависимостей в карте: {всего}")


def напечатать_проверки(data: dict) -> None:
    """`--проверки`: «проверок: N» и по строке «id ключ-тревоги» на открытую
    тревогу проверки, по всей карте. Читает поток проверок; очередь основной сессии их не видит."""
    места = порядок(data, направление="", настройки=настройки(), без_потолка=True,
                    проверки=True)
    карточки = {t.get("id"): t for line in data.get("lines") or []
                for t in line.get("tasks") or []}
    наст = настройки()
    print(f"проверок: {len(места)}")
    for м in места:
        print(f"{м['id']} {тревога_проверки(карточки[м['id']], наст)}")


