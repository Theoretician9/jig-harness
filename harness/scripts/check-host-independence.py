ПОДМЕНА = {"HOME": "/nonexistent-home", "HOSTNAME": "чужая-машина",
           "USER": "someone", "HARNESS_ACTIVE_LINE": "продукт"}
ЧИСТОЕ = {"PATH": "/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin",
          "HOME": "/nonexistent-home", "LC_ALL": "C.UTF-8"}


def проверки(путь_ворот: Path) -> list[tuple[str, list[str]]]:
    """Имя и команда каждой проверки ворот. Строки с подстановками пропускаем."""
    итог = []
    try:
        текст = путь_ворот.read_text(encoding="utf-8")
    except OSError:
        return []
    for строка in текст.splitlines():
        совпало = СТРОКА_ПРОВЕРКИ.match(строка)
        if not совпало:
            continue
        имя, команда = совпало.group(1), совпало.group(2)
        if "$" in команда:
            continue
        try:
            слова = shlex.split(команда)
        except ValueError:
            continue
        if слова:
            итог.append((имя, слова))
    return итог


def прогон(слова: list[str], окружение: dict | None, чистое: bool,
           потолок: int) -> int:
    """Код возврата команды. -9 — не дождались, -2 — запустить не удалось."""
    команда = (["env", "-i"] + [f"{к}={з}" for к, з in (окружение or {}).items()]
               + слова) if чистое else слова
    среда = None if чистое else {**os.environ, **(окружение or {})}
    try:
        итог = subprocess.run(команда, stdout=subprocess.DEVNULL,
                              stderr=subprocess.DEVNULL, timeout=потолок,
                              cwd=str(КОРЕНЬ), env=среда, stdin=subprocess.DEVNULL)
        return итог.returncode
    except subprocess.TimeoutExpired:
        return -9
    except OSError:
        return -2


def объявленное(путь_данных: Path) -> tuple[dict, dict, int, str]:
    """(судят_машину, тяжёлые, потолок_секунд, беда) из данных."""
    if not путь_данных.exists():
        return {}, {}, 0, f"нет файла данных {путь_данных.name}"
    try:
        import yaml
        д = yaml.safe_load(путь_данных.read_text(encoding="utf-8")) or {}
    except Exception as беда:                      # noqa: BLE001 — данные чужие
        return {}, {}, 0, f"{путь_данных.name} не разобран: {беда}"
    def словарь(ключ: str) -> dict:
        записи = д.get(ключ) or []
        return {з["проверка"]: з.get("причина", "") for з in записи
                if isinstance(з, dict) and з.get("проверка")}
    судят, тяжёлые = словарь("судят_машину"), словарь("тяжёлые")
    без_причины = [и for словарь_ in (судят, тяжёлые)
                   for и, п in словарь_.items() if not п]
    if без_причины:
        return {}, {}, 0, (f"{путь_данных.name}: записи без причины — "
                           f"{', '.join(без_причины)}")
    потолок = int(д.get("потолок_секунд") or 60)
    return судят, тяжёлые, потолок, ""


def последовательные(путь: Path) -> dict[str, str]:
    """Имя проверки → группа из gates-serial.yaml: те, что и в воротах разом не идут."""
    try:
        import yaml
        группы = (yaml.safe_load(путь.read_text(encoding="utf-8")) or {}).get("группы") or {}
    except Exception:                                    # noqa: BLE001 — данные чужие
        return {}
    return {имя: группа for группа, тело in группы.items() if isinstance(тело, dict)
            for имя in (тело.get("проверки") or [])}


def число_задач() -> int:
    """Сколько проверок гонять разом: HOST_INDEPENDENCE_JOBS из harness.conf, иначе 1."""
    сырое = конф.из_файла(конф.путь_harness_conf()).get("HOST_INDEPENDENCE_JOBS", "")
    try:
        задач = int(сырое)
    except ValueError:
        return 1
    return задач if задач > 0 else 1


def _расхождения(слова: list[str], потолок: int) -> list[str] | None:
    """Виды расхождения с прогоном «как обычно»; None — его не дождались.

    Не дождались «как обычно» — подменённые не гоняются: их тоже не дождались бы
    (-9 == -9), и проверка числилась бы чистой, не будучи измеренной.
    """
    как_обычно = прогон(слова, None, False, потолок)
    if как_обычно == -9:
        return None
    return [
        вид for вид, код in (
            ("под подменённым хозяином",
             прогон(слова, ПОДМЕНА, False, потолок)),
            ("из пустого окружения", прогон(слова, ЧИСТОЕ, True, потолок)))
        if код != как_обычно]


def _пачки(круг: list, группы: dict) -> tuple[list[list[int]], list[list[int]]]:
    """Номера проверок пачками для пула и пачки «одна» — после пула, по одной.

    Проверки одной группы — одна пачка: внутри неё по очереди, как в воротах.
    """
    пачки: list[list[int]] = []
    одни: list[list[int]] = []
    по_группе: dict[str, list[int]] = {}
    for номер, (имя, _) in enumerate(круг):
        группа = группы.get(имя)
        if группа == "одна":
            одни.append([номер])
        elif группа:
            if группа not in по_группе:
                по_группе[группа] = []
                пачки.append(по_группе[группа])
            по_группе[группа].append(номер)
        else:
            пачки.append([номер])
    return пачки, одни


def находки(путь_ворот: Path, судят: dict, тяжёлые: dict, потолок: int,
            круг: list | None = None, задач: int = 1,
            группы: dict | None = None) -> tuple[list[str], int, int, list[str]]:
    """Беды, число прогнанных, число законных расхождений и неизмеренные.

    Данные сверяются со ВСЕМИ воротами, а гоняется только `круг` (None — все):
    запись о проверке вне круга не устарела. `задач` проверок идут разом.
    """
    беды: list[str] = []
    законных = 0
    имена = {имя for имя, _ in проверки(путь_ворот)}
    for имя in sorted(судят) + sorted(тяжёлые):
        if имя not in имена:
            беды.append(f"{ДАННЫЕ.name}: запись устарела — проверки «{имя}» "
                        "в воротах нет")
    круг = [п for п in (проверки(путь_ворот) if круг is None else круг)
            if п[0] not in тяжёлые]
    исход: dict[int, list[str] | None] = {}
    счёт, замок = itertools.count(1), threading.Lock()

    def пачка(номера: list[int]) -> None:
        for номер in номера:
            имя, слова = круг[номер]
            with замок:
                по_счёту = next(счёт)
            # Голос в stderr: прогон идёт десятками минут, и молчащий прибор
            # неотличим от зависшего. stdout остаётся машинным — его читают ворота.
            print(f"  … {по_счёту}/{len(круг)} {имя}", file=sys.stderr, flush=True)
            исход[номер] = _расхождения(слова, потолок)

    пачки, одни = _пачки(круг, группы or {})
    with ThreadPoolExecutor(max_workers=max(1, задач)) as пул:
        list(пул.map(пачка, пачки))
    for номера in одни:
        пачка(номера)
    неизмерено: list[str] = []
    for номер, (имя, слова) in enumerate(круг):
        расходится = исход[номер]
        if расходится is None:
            неизмерено.append(имя)
            continue
        if not расходится:
            continue
        if имя in судят:
            законных += 1
            continue
        беды.append(f"«{имя}» ({' '.join(слова)}): исход меняется "
                    f"{' и '.join(расходится)} — проба судит машину, а не "
                    f"механизм; починить стенд или объявить с причиной в "
                    f"{ДАННЫЕ.name}")
    return беды, len(круг), законных, неизмерено


def _git(корень: Path, *аргументы: str) -> str | None:
    """Вывод git или None: любой сбой git толкуется как «считать нечем»."""
    try:
        итог = subprocess.run(["git", *аргументы], cwd=str(корень), capture_output=True,
                              timeout=60, stdin=subprocess.DEVNULL)
    except (OSError, subprocess.TimeoutExpired):
        return None
    return итог.stdout.decode("utf-8", "replace") if итог.returncode == 0 else None


def прочитать_метку(путь_метки: Path) -> tuple[str, float] | None:
    """(sha, ts) метки или None, если метки нет или она негодна."""
    try:
        метка = json.loads(Path(путь_метки).read_text(encoding="utf-8"))
        sha, ts = метка["sha"], метка["ts"]
    except (OSError, ValueError, KeyError, TypeError):
        return None
    # sha уходит аргументом git: только шестнадцатеричное, чтобы не стать опцией.
    if not isinstance(sha, str) or not re.fullmatch(r"[0-9a-f]{7,64}", sha):
        return None
    if isinstance(ts, bool) or not isinstance(ts, (int, float)):
        return None
    return sha, ts


def write_mark(путь_метки: Path, корень: Path, сейчас: float) -> bool:
    """Метка чистого полного круга: HEAD и время. False — HEAD узнать не удалось."""
    sha = _git(корень, "rev-parse", "HEAD")
    if not sha:
        return False
    путь_метки = Path(путь_метки)
    путь_метки.parent.mkdir(parents=True, exist_ok=True)
    # Через временный файл: оборванная запись оставила бы негодную метку.
    врем = путь_метки.with_name(путь_метки.name + ".tmp")
    врем.write_text(json.dumps({"sha": sha.strip(), "ts": сейчас}), encoding="utf-8")
    os.replace(врем, путь_метки)
    return True


def _изменённые_файлы(корень: Path, sha: str) -> set[str] | None:
    """Файлы, изменённые с коммита метки: коммиты, рабочее дерево и новые файлы."""
    правлено = _git(корень, "diff", "--name-only", "--no-renames", "-z", sha, "--")
    новые = _git(корень, "ls-files", "--others", "--exclude-standard", "-z")
    if правлено is None or новые is None:
        return None
    return {п for п in (правлено + новые).split("\0") if п}


def _замыкание(начало: set[str], корень: Path, по_имени: dict) -> set[str]:
    """Файлы, на которые проба опирается: упоминания в тексте, шаг за шагом.

    Ворота в замыкание не входят: их изменения ловятся по строкам проверок, а
    через них замыкание расползлось бы на каждую проверку.
    """
    увидели, очередь = set(начало), list(начало)
    while очередь:
        try:
            текст = (корень / очередь.pop()).read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        найденное: set[str] = set()
        for слово in УПОМИНАНИЕ.findall(текст):
            найденное |= ({слово} if (корень / слово).is_file()
                          else по_имени.get(слово.rsplit("/", 1)[-1], set()))
        for модуль in ИМПОРТ.findall(текст):
            найденное |= по_имени.get(f"{модуль}.py", set())
        for файл in найденное - увидели - {"scripts/gates.sh"}:
            увидели.add(файл)
            очередь.append(файл)
    return увидели


def _проверяется_у_изменённых(корень: Path, правлено: set[str]) -> str:
    """Тексты поля «проверяется» у механизмов реестра, чей файл изменён."""
    try:
        import yaml
        текст = (корень / "harness" / "config" / "mechanisms.yaml").read_text(encoding="utf-8")
        записи = (yaml.safe_load(текст) or {}).get("механизмы") or []
    except Exception:                                    # noqa: BLE001 — реестр чужой
        return ""
    return "\n".join(str(з.get("проверяется") or "") for з in записи
                     if isinstance(з, dict) and з.get("файл") in правлено)


def _строки_на_метке(корень: Path, sha: str, путь_ворот: Path) -> set | None:
    """Проверки ворот, какими они были на коммите метки; None — не прочитать."""
    прежние = _git(корень, "show", f"{sha}:{os.path.relpath(путь_ворот, корень)}")
    if прежние is None:
        return None
    with tempfile.TemporaryDirectory() as врем:
        копия = Path(врем) / "gates.sh"
        копия.write_text(прежние, encoding="utf-8")
        return {(имя, tuple(слова)) for имя, слова in проверки(копия)}


def choose_circle(путь_ворот: Path, путь_метки: Path, корень: Path, сейчас: float,
                  срок_суток: float) -> tuple[str, list, str]:
    """(режим, проверки, причина): полный круг или только изменённое с метки.

    Всякая неясность — полный круг: пропущенная проба молчит о зависимости от
    машины, а лишний прогон только стоит времени.
    """
    все = проверки(путь_ворот)
    метка = прочитать_метку(путь_метки)
    if метка is None:
        return ПОЛНЫЙ, все, "метки чистого полного круга нет или она негодна"
    sha, ts = метка
    if сейчас - ts >= срок_суток * СУТКИ:
        return ПОЛНЫЙ, все, f"полному кругу больше {срок_суток:g} сут."
    правлено = _изменённые_файлы(корень, sha)
    if правлено is None:
        return ПОЛНЫЙ, все, "git не назвал изменённого с метки"
    if ПРИБОР & правлено:
        return ПОЛНЫЙ, все, "изменился сам прибор или его данные"
    были = _строки_на_метке(корень, sha, путь_ворот)
    if были is None:
        return ПОЛНЫЙ, все, "ворот на метке не прочитать"
    файлы = _git(корень, "ls-files", "-z", "--cached", "--others", "--exclude-standard")
    по_имени: dict = {}
    for файл in filter(None, (файлы or "").split("\0")):
        по_имени.setdefault(файл.rsplit("/", 1)[-1], set()).add(файл)
    от_механизмов = _проверяется_у_изменённых(корень, правлено)
    круг = []
    for имя, слова in все:
        начало = {с for с in слова if (корень / с).is_file()}
        if ((имя, tuple(слова)) not in были
                or _замыкание(начало, корень, по_имени) & правлено
                or any(файл in от_механизмов for файл in начало)):
            круг.append((имя, слова))
    return ИЗМЕНЁННЫЕ, круг, f"с метки изменено файлов: {len(правлено)}"


def срок_полного_круга() -> float:
    """Срок из harness.conf СТРОГО: конфиг() без аргумента читает install.conf."""
    сырое = конф.из_файла(конф.путь_harness_conf()).get("HOST_INDEPENDENCE_FULL_DAYS", "")
    try:
        срок = float(сырое)
    except ValueError:
        return СРОК_ПО_УМОЛЧАНИЮ
    return срок if срок > 0 else СРОК_ПО_УМОЛЧАНИЮ


def путь_метки_по_умолчанию() -> Path:
    return Path(os.environ.get("HOST_INDEPENDENCE_MARK")
                or Path(конф.log_dir()) / ИМЯ_МЕТКИ)


def выборка(путь_ворот: Path, имена: list[str]) -> tuple[list, list[str]]:
    """(проверки с названными именами, имена, которых в воротах нет)."""
    все = проверки(путь_ворот)
    известные = {имя for имя, _ in все}
    return ([п for п in все if п[0] in имена],
            [имя for имя in имена if имя not in известные])


def отчёт(путь_ворот: Path, путь_данных: Path, путь_метки: Path | None = None,
          имена: list[str] | None = None) -> int:
    """Без пути метки круг всегда полный и метка не пишется (так зовёт самотест).

    `имена` — узкая выборка: метка не читается и не пишется, пустая выборка — отказ.
    """
    судят, тяжёлые, потолок, беда = объявленное(путь_данных)
    if беда:
        print(f"[хозяин машины] ПЛОХО {беда}")
        return 1
    все = проверки(путь_ворот)
    if not все:
        print(f"[хозяин машины] НЕ ПРИМЕНИМО: в {путь_ворот.name} "
              "не найдено ни одной проверки — мерить нечем")
        return НЕ_ПРИМЕНИМО
    режим, круг, причина = ПОЛНЫЙ, все, "метка не запрошена"
    if имена is not None:
        круг, чужие = выборка(путь_ворот, имена)
        лёгкие = [имя for имя, _ in круг if имя not in тяжёлые]
        if чужие or not лёгкие:
            print(f"[хозяин машины] ОТКАЗ: выборка {имена or 'пуста'} — "
                  f"{'в воротах нет ' + ', '.join(чужие) if чужие else 'лёгких проверок не нашлось'}")
            return ОТКАЗ
        режим, причина, путь_метки = "узкий", f"выбрано по имени: {len(круг)}", None
    elif путь_метки is not None:
        режим, круг, причина = choose_circle(
            путь_ворот, путь_метки, КОРЕНЬ, time.time(), срок_полного_круга())
    print(f"[хозяин машины] режим «{режим}»: {причина}; "
          f"проверок в круге {len(круг)} из {len(все)}")
    беды, проверено, законных, неизмерено = находки(
        путь_ворот, судят, тяжёлые, потолок, круг, число_задач(),
        последовательные(ГРУППЫ))
    if неизмерено:
        print(f"[хозяин машины] не измерено — прогон «как обычно» дольше потолка "
              f"{потолок} с: {len(неизмерено)} ({', '.join(неизмерено)})")
    if not беды:
        итог = "чисто" if круг else "изменённых нет"
        print(f"[хозяин машины] {итог}: прогнано {проверено} проверок, "
              f"необъявленных зависимостей 0, законных {законных}, "
              f"не измерено {len(неизмерено)}, тяжёлых пропущено {len(тяжёлые)}")
        if режим == ПОЛНЫЙ and путь_метки is not None:
            write_mark(путь_метки, КОРЕНЬ, time.time())
        return 0
    for б in беды:
        print(f"[хозяин машины] ПЛОХО {б}")
    print(f"[хозяин машины] находок {len(беды)} из {проверено} проверок")
    return 1


@contextlib.contextmanager
def свой_дом(путь):
    """HOME на время стенда — СВОЙ, и возвращается всегда.

    Прежде стенд брал дом хозяина как есть, и прибор попадал в свою же находку:
    «хозяин-самотест» гоняется трижды, как любая проверка ворот, и под
    подменённым HOME прогон «как обычно» тоже получал несуществующий дом —
    расхождения не возникало, больной случай переставал находиться. Проба
    обязана СОЗДАВАТЬ своё условие, а не наследовать его от машины.
    """
    прежний = os.environ.get("HOME")
    os.environ["HOME"] = str(путь)
    try:
        yield
    finally:
        if прежний is None:
            os.environ.pop("HOME", None)
        else:
            os.environ["HOME"] = прежний


def селфтест() -> int:
    import tempfile
    ok = True
    путей = 0

    def проба(условие: bool, имя: str) -> None:
        nonlocal ok, путей
        путей += 1
        print(f"  {'ок   ' if условие else 'ПЛОХО'} {имя}")
        if not условие:
            ok = False

    with tempfile.TemporaryDirectory() as врем, свой_дом(врем):
        двор = Path(врем)
        # ДОМ стенда — свой. Прежде проба брала дом хозяина как есть, и сам
        # прибор попадал в свою же находку: под подменённым HOME
        # («хозяин-самотест» гоняется трижды, как любая проверка ворот) прогон
        # «как обычно» получал несуществующий дом, расхождения не возникало —
        # и больной случай переставал находиться. Проба обязана СОЗДАВАТЬ своё
        # условие, а не наследовать его от машины.
        # БОЛЬНОЙ СЛУЧАЙ: проверка зеленеет только в доме хозяина.
        зависимая = двор / "zavisimaya.sh"
        зависимая.write_text('#!/bin/bash\n[ -d "$HOME" ] && exit 0\nexit 1\n',
                             encoding="utf-8")
        честная = двор / "chestnaya.sh"
        честная.write_text("#!/bin/bash\nexit 0\n", encoding="utf-8")
        ворота = двор / "gates.sh"
        ворота.write_text(
            f'проверка "зависимая" bash {зависимая}\n'
            f'проверка "честная" bash {честная}\n', encoding="utf-8")

        беды, проверено, законных, _ = находки(ворота, {}, {}, 20)
        проба(проверено == 2, "прогнаны все проверки стенда")
        проба(len(беды) == 1 and "зависимая" in беды[0],
              "БОЛЬНОЙ СЛУЧАЙ: проверка, зелёная только в доме хозяина — находка")
        проба(not any("честная" in б for б in беды),
              "проверка с одинаковым исходом претензии не получает")

        данные = двор / "host-independence.yaml"
        данные.write_text("судят_машину: []\nтяжёлые: []\n", encoding="utf-8")
        проба(отчёт(ворота, данные) == 1, "необъявленная зависимость краснит")

        данные.write_text(
            "судят_машину:\n  - проверка: зависимая\n"
            "    причина: «предмет этой проверки — дом хозяина»\n"
            "тяжёлые: []\n", encoding="utf-8")
        проба(отчёт(ворота, данные) == 0,
              "объявленная с причиной зависимость ворота не красит")

        данные.write_text(
            "судят_машину:\n  - проверка: зависимая\nтяжёлые: []\n",
            encoding="utf-8")
        проба(отчёт(ворота, данные) == 1, "запись без причины — красный")

        данные.write_text(
            "судят_машину: []\nтяжёлые:\n  - проверка: зависимая\n"
            "    причина: «идёт минутами»\n", encoding="utf-8")
        проба(отчёт(ворота, данные) == 0,
              "тяжёлая проверка пропускается по данным, а не молча")
        беды, проверено, _, _ = находки(
            ворота, {}, {"зависимая": "идёт минутами"}, 20)
        проба(проверено == 1, "пропущенная тяжёлая в счёт прогнанных не идёт")

        данные.write_text(
            "судят_машину:\n  - проверка: нет-такой\n"
            "    причина: «была когда-то»\nтяжёлые: []\n", encoding="utf-8")
        проба(отчёт(ворота, данные) == 1,
              "запись про несуществующую проверку — красный: данные не отстают")

        # УЗКИЙ РЕЖИМ: выборка по имени сужает круг, пустая или чужая — отказ.
        данные.write_text("судят_машину: []\nтяжёлые: []\n", encoding="utf-8")
        проба(отчёт(ворота, данные, None, ["честная"]) == 0,
              "узкий режим: выбрана здоровая проверка — чисто")
        проба(отчёт(ворота, данные, None, ["зависимая"]) == 1,
              "узкий режим: выбрана больная проверка — находка, код 1")
        круг, чужие = выборка(ворота, ["честная"])
        проба([и for и, _ in круг] == ["честная"] and not чужие,
              "выборка сужает круг до названной проверки")
        проба(отчёт(ворота, данные, None, ["нет-такой"]) == ОТКАЗ,
              "выборка с неизвестным именем — отказ (2), не «ок»")
        проба(отчёт(ворота, данные, None, []) == ОТКАЗ,
              "пустая выборка — отказ (2), не «ок»")
        проба(отчёт(ворота, данные, None, ["честная", "нет-такой"]) == 2,
              "одно неизвестное имя среди известных — отказ кодом 2, не выпадает молча")
        проба(ОТКАЗ == 2, "код отказа — литерал 2, на нём держится вызывающий")
        данные.write_text("судят_машину: []\nтяжёлые:\n  - проверка: зависимая\n"
                          "    причина: «идёт минутами»\n", encoding="utf-8")
        проба(отчёт(ворота, данные, None, ["зависимая"]) == 2,
              "выборка из одной тяжёлой — отказ (2), а не «чисто» при нуле прогнанных")
        данные.write_text("судят_машину: []\nтяжёлые: []\n", encoding="utf-8")
        # Командная строка судит СТЕНД, а не боевые ворота: поломка сужения
        # иначе гонит из самотеста полный боевой круг (часы, вместо красного).
        global ВОРОТА, ДАННЫЕ
        боевые = ВОРОТА, ДАННЫЕ
        ВОРОТА, ДАННЫЕ = ворота, данные
        try:
            проба(главная(["--только"]) == ОТКАЗ,
                  "--только без имён — отказ (2)")
            проба(главная(["--только", "честная"]) == 0,
                  "--только с именем гонит узкий круг стенда — чисто")
        finally:
            ВОРОТА, ДАННЫЕ = боевые
        global КОРЕНЬ
        репо = двор / "repo"; репо.mkdir()
        subprocess.run(["git", "init", "-q", str(репо)], check=True)
        subprocess.run(["git", "-C", str(репо), "-c", "user.name=t", "-c", "user.email=t@t",
                        "commit", "-q", "--allow-empty", "-m", "стенд"], check=True)
        данные.write_text("судят_машину:\n  - проверка: зависимая\n"
                          "    причина: «предмет этой проверки — дом хозяина»\n"
                          "тяжёлые: []\n", encoding="utf-8")
        боевой_корень, КОРЕНЬ = КОРЕНЬ, репо
        try:
            метка = двор / "mark.json"
            отчёт(ворота, данные, метка)
            проба(метка.exists(), "полный прогон на git-стенде пишет метку — проверка ниже зрячая")
            метка.unlink()
            отчёт(ворота, данные, метка, ["честная"])
            проба(not метка.exists(), "узкий прогон метку полного круга не пишет")
        finally:
            КОРЕНЬ = боевой_корень
        данные.write_text("судят_машину: []\nтяжёлые: []\n", encoding="utf-8")

        пустые = двор / "pustye.sh"
        пустые.write_text("# ни одной проверки\n", encoding="utf-8")
        проба(отчёт(пустые, данные) == НЕ_ПРИМЕНИМО,
              "проверок не найдено — код 77 «не применимо», не зелёный")
        проба(отчёт(ворота, двор / "нет-данных.yaml") == 1,
              "нет файла данных — красный, а не молчание")

        # Дольше потолка: прогон «как обычно» не дождались — подменённые два
        # дождались бы так же (-9 == -9), и проверка числилась бы чистой, не
        # будучи измеренной. Она идёт в «не измерено» и не гоняется ещё дважды.
        счёт = двор / "schyot.txt"
        медленная = двор / "medlennaya.sh"
        медленная.write_text('#!/bin/bash\necho x >> "$1"\nsleep 3\n', encoding="utf-8")
        ворота_медл = двор / "gates-slow.sh"
        ворота_медл.write_text(f'проверка "медленная" bash {медленная} {счёт}\n',
                               encoding="utf-8")
        итог = находки(ворота_медл, {}, {}, 1)
        запусков = len(счёт.read_text(encoding="utf-8").split()) if счёт.exists() else 0
        проба(запусков == 1, f"дольше потолка — подменённые прогоны не идут (запусков {запусков}, ждём 1)")
        проба(len(итог) == 4 and итог[3] == ["медленная"] and not итог[0],
              "дольше потолка — «не измерено», а не «чисто»")

        # Пул: разные проверки идут разом, одна группа gates-serial.yaml — по очереди.
        def перекрылись(задач: int, группы: dict) -> bool | None:
            следы = двор / "sledy.txt"
            следы.unlink(missing_ok=True)
            шаг = двор / "shag.sh"
            шаг.write_text('#!/bin/bash\necho + >> "$1"\nsleep 0.3\necho - >> "$1"\n',
                           encoding="utf-8")
            пара = двор / "gates-pair.sh"
            пара.write_text(f'проверка "раз" bash {шаг} {следы}\n'
                            f'проверка "два" bash {шаг} {следы}\n', encoding="utf-8")
            try:
                находки(пара, {}, {}, 20, None, задач, группы)
            except TypeError:
                return None
            return "+\n+\n" in следы.read_text(encoding="utf-8")
        проба(перекрылись(2, {}) is True, "пул из двух — разные проверки идут разом")
        проба(перекрылись(2, {"раз": "г", "два": "г"}) is False,
              "проверки одной последовательной группы разом не идут")
        проба(перекрылись(1, {}) is False, "пул из одной — по очереди, как прежде")
        проба(последовательные(двор / "нет.yaml") == {},
              "нет файла групп — групп нет, а не падение")

        # Таймаут: «не дождались» — это ответ, а не ноль.
        долгая = двор / "dolgaya.sh"
