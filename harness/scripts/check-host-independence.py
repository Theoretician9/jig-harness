#!/usr/bin/env python3
"""Проверки не должны зависеть от хозяина машины — а если зависят, то объявленно.

СЛУЧАЙ (Ф4 ревизии харнеса, §6 класс 2, 28.09.2026). Проба витрины панели строила
свой стенд — свою карту, свои журналы, свои метки, — и всё равно краснела под
`HARNESS_ACTIVE_LINE=«продукт»`: прибор очереди искал задачи в другом направлении
и отвечал «очередь пуста». Исход решало ОКРУЖЕНИЕ, а не поведение витрины.
Направление теперь задаёт стенд, а этот прибор не даёт классу вернуться.

Предикат: команда проверки гоняется трижды — как обычно, под подменёнными
`HOME`/`HOSTNAME`/`USER`/`HARNESS_ACTIVE_LINE` и из `env -i`. Разный код возврата
= исход зависит от машины.

Законные случаи есть: гейт срока входа по существу судит ЭТУ машину (профили
оболочки хозяина), и подменять ему `HOME` — всё равно что спрашивать о другой
машине. Такие проверки объявлены в данных
(`harness/config/host-independence.yaml`, ключ «судят_машину») с причиной. Там же
список тяжёлых: мутационный прогон идёт минутами, и трижды его не гоняют.

Замер 28.09.2026 по всем 128 проверкам ворот: расхождений 3 — витрина (дефект,
починен), срок входа (судит машину), мутационный прогон (тяжёлый, таймаут).

    python3 scripts/check-host-independence.py            # все объявленные лёгкие
    python3 scripts/check-host-independence.py --только "сроки-самотест" ...
    python3 scripts/check-host-independence.py --selftest

`--только` — узкий режим для живой проверки: гоняются лишь проверки с названными
ТОЧНЫМИ именами из ворот (полный круг идёт часами). Метку полного круга узкий
прогон не пишет и не читает: она свидетельствует только о полном круге.
Код возврата: 0 — чисто, 1 — необъявленная зависимость, 2 — отказ (пустая
выборка или имя, которого в воротах нет), 77 — мерить нечем.
"""
