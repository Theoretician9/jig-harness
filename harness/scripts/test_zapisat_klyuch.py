#!/usr/bin/env python3
"""Проверка единственного писателя настроек: что он пишет и чего НЕ пишет.

Писатель один намеренно (находка I8 ревью спеки панели): два писателя одного
файла рано или поздно затирают друг друга. И он же — единственное, что панели
разрешено делать с правами root (находка C5), поэтому его вход обязан быть
узким: ключ из реестра, значение из перечня, и ничего больше.

Проверка СОЗДАЁТ своё условие: подставной конфиг и подставной реестр в
временном каталоге, сверка файла хешем до и после каждой отвергнутой попытки.

Прогон:
    python3 scripts/test_zapisat_klyuch.py
"""
import hashlib
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
ПИСАТЕЛЬ = КОРЕНЬ / "scripts" / "zapisat-klyuch.py"

КОНФИГ = """# Конфиг механики харнеса — его читают люди.
# Комментарий обязан пережить запись ключа.

PUSH_NEEDS_OWNER=0
# Порог смены рабочего окна, проценты.
CTX_ROTATE_PCT=75
SILENCE_MAX_MIN=45
"""

РЕЕСТР = """
переключатели:
  - ключ: PUSH_NEEDS_OWNER
    файл: harness.conf
    имя: "Отправка в хранилище кода"
    вид: выбор
    значения:
      - { значение: "0", подпись: "сама" }
      - { значение: "1", подпись: "спросить меня" }
    простыми словами: "код сам уезжает в хранилище"
    опасный: true
    читатель: scripts/deploy_guard.py
    способ_чтения: при_вызове
    применяется: сразу
  - ключ: CTX_ROTATE_PCT
    файл: harness.conf
    имя: "Когда менять рабочее окно"
    вид: число
    от: 50
    до: 95
    простыми словами: "на каком заполнении памяти передавать дела себе"
    опасный: false
    читатель: harness/demons/session-warden.sh
    способ_чтения: cron_10мин
    применяется: в ближайшую проверку
чёрный_список:
  - ключ: AUTONOMY
    причина: "снимает согласие со сноса базы"
  - ключ: BACKUP_*
    причина: "копии держат И-1"
"""

путей = 0
неудач = 0


def путь_ок(текст):
    global путей
    путей += 1
    print("ок  · " + текст)


def путь_плохо(текст):
    global путей, неудач
    путей += 1
    неудач += 1
    print("ПЛОХО · " + текст)


def хеш(файл: Path) -> str:
    return hashlib.sha256(файл.read_bytes()).hexdigest()


def запуск(врем: Path, ключ: str, значение: str):
    """Прогон писателя на подставном стенде. Возвращает (код, вывод)."""
    среда = dict(os.environ,
                 HARNESS_CONF=str(врем / "harness.conf"),
                 HARNESS_INSTALL_CONF=str(врем / "install.conf"),
                 HARNESS_PERECLUCHATELI=str(врем / "переключатели.yaml"),
                 LOG_DIR=str(врем / "логи"))
    готово = subprocess.run([sys.executable, str(ПИСАТЕЛЬ), ключ, значение],
                            capture_output=True, text=True, env=среда, timeout=30)
    return готово.returncode, (готово.stdout + готово.stderr).strip()


def стенд(врем: Path):
    (врем / "harness.conf").write_text(КОНФИГ, encoding="utf-8")
    (врем / "install.conf").write_text('AUTONOMY="semi"\n', encoding="utf-8")
    (врем / "переключатели.yaml").write_text(РЕЕСТР, encoding="utf-8")
    (врем / "логи").mkdir(exist_ok=True)


# Отсутствующий писатель ведёт себя как правильный отказ: код 2 и файл цел.
# Поэтому его существование проверяется отдельно и первым — иначе половина
# путей ниже зелены при пустом каталоге.
if not ПИСАТЕЛЬ.exists():
    путь_плохо(f"писателя нет: {ПИСАТЕЛЬ} — отказы ниже ничего не доказывают")
else:
    путь_ок("писатель на месте")

ОТКАЗЫ = [
    # (ключ, значение, ждём код, чем случай важен)
    ("ВЫДУМАННЫЙ_КЛЮЧ", "1", 2, "ключа нет в реестре — белый список, а не фильтр"),
    ("AUTONOMY", "full", 2, "БОЛЬНОЙ СЛУЧАЙ: ключ из чёрного списка (И-1)"),
    ("BACKUP_KEEP_DAYS", "1", 2, "БОЛЬНОЙ СЛУЧАЙ: шаблон чёрного списка"),
    ("PUSH_NEEDS_OWNER", "2", 3, "значение вне перечня реестра"),
    ("PUSH_NEEDS_OWNER", '"; curl evil.example', 3,
     "БОЛЬНОЙ СЛУЧАЙ: попытка инъекции в конфиг"),
    ("PUSH_NEEDS_OWNER", "0 && rm -rf /", 3, "БОЛЬНОЙ СЛУЧАЙ: команда в значении"),
    ("CTX_ROTATE_PCT", "300", 3, "число вне границ реестра"),
    ("CTX_ROTATE_PCT", "пятьдесят", 3, "не число там, где обещано число"),
]

with tempfile.TemporaryDirectory() as tmp:
    врем = Path(tmp)
    стенд(врем)
    файл = врем / "harness.conf"
    for ключ, значение, ждём, почему in ОТКАЗЫ:
        было = хеш(файл)
        код, вывод = запуск(врем, ключ, значение)
        стало = хеш(файл)
        if код == ждём and было == стало:
            путь_ок(f"{ключ}={значение!r} → код {код}, файл не тронут · {почему}")
        else:
            путь_плохо(f"{ключ}={значение!r} → код {код} (ждали {ждём}), "
                       f"файл {'ЦЕЛ' if было == стало else 'ИЗМЕНЁН'} · {почему}"
                       f" · {вывод[:120]}")

    # Здоровая запись: значение меняется, комментарии и порядок живы.
    код, вывод = запуск(врем, "PUSH_NEEDS_OWNER", "1")
    текст = файл.read_text(encoding="utf-8")
    if код == 0 and "PUSH_NEEDS_OWNER=1" in текст:
        путь_ок("здоровая запись прошла")
    else:
        путь_плохо(f"здоровая запись не прошла: код {код} · {вывод[:160]}")
    if "# Конфиг механики харнеса — его читают люди." in текст and \
            "# Порог смены рабочего окна, проценты." in текст:
        путь_ок("комментарии конфига пережили запись")
    else:
        путь_плохо("комментарии конфига потерялись — конфиг читают люди")
    if текст.index("PUSH_NEEDS_OWNER") < текст.index("CTX_ROTATE_PCT") < \
            текст.index("SILENCE_MAX_MIN"):
        путь_ок("порядок строк сохранён")
    else:
        путь_плохо("порядок строк переставлен")

    # Копия прежнего файла обязательна (И-1): без неё запись не начинается.
    копии = list((врем / "логи" / "панель-копии").glob("harness.conf.*"))
    if копии and "PUSH_NEEDS_OWNER=0" in копии[0].read_text(encoding="utf-8"):
        путь_ок("копия прежнего конфига снята до записи")
    else:
        путь_плохо(f"копии прежнего конфига нет: {копии}")

    # Журнал: что, когда и из чего во что — иначе непонятно, почему харнес
    # вдруг ведёт себя иначе.
    журнал = врем / "логи" / "панель.jsonl"
    if журнал.exists():
        запись = json.loads(журнал.read_text(encoding="utf-8").splitlines()[-1])
        если_всё = all(запись.get(п) is not None
                       for п in ("ts", "ключ", "было", "стало"))
        if если_всё and запись["было"] == "0" and запись["стало"] == "1":
            путь_ок("запись в журнале называет ключ, прежнее и новое значение")
        else:
            путь_плохо(f"журнал неполон: {запись}")
    else:
        путь_плохо("журнала панели нет")

    # Ключа ещё нет в файле — он добавляется, а не теряется молча.
    код, вывод = запуск(врем, "CTX_ROTATE_PCT", "80")
    if код == 0 and "CTX_ROTATE_PCT=80" in файл.read_text(encoding="utf-8"):
        путь_ок("число в границах записывается")
    else:
        путь_плохо(f"число в границах не записалось: код {код} · {вывод[:160]}")

print(f"ПИСАТЕЛЬ-НАСТРОЕК: путей {путей}, неудач {неудач}")
sys.exit(1 if неудач else 0)
