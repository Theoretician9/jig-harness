# -*- coding: utf-8 -*-
"""Карточку задачи из сообщения владельца заводит КОД, а не модель.

Владелец 11.09.2026: «каждое сообщение с работой попадает в карту чтобы если
что всегда иметь карту»; 12.09.2026: «создать механизм, который не сбивая
модель сохраняет и распределяет задачи».

До этого связь «сообщение → карточка» держалась вниманием сессии: гейт
`tasks-from-channel.py` требовал исхода, а заводил карточку я руками, посреди
другой работы. Механизм, который держится на «чтобы кто-то помнил», — не
механизм: 11.09 так потерялось указание про автоприёмку.

Устройство:
  • текст берётся из очереди канала ($LOG_DIR/inbox/<id>.txt или обработано/);
  • признак работы — тот же, что у гейта (`tasks-from-channel.рабочее`);
  • смысл сообщения разбирает МОДЕЛЬ — но только через `ask-the-model.py`
    (повод «о-чём-сообщение-владельца»), то есть по схеме, с журналом и
    потолком. Модель отдаёт ДАННЫЕ (какие задачи названы), решение — здесь;
  • модель недоступна, молчит или уперлась в потолок — карточка всё равно
    заводится, по первой строке сообщения. Исход обязан быть всегда, иначе
    гейт красен, а задача владельца снова живёт только в памяти сессии;
  • карта правится под ОБЩИМ локом dev-map.lock (её пишут пять сторон), а
    результат сверяется разбором YAML: число задач выросло ровно на новые,
    ни один прежний id не пропал. Улика 09.09.2026: жадное регулярное
    выражение съело 88 задач, а YAML остался валидным.

    map-from-message.py --сообщение <id> [--карта П] [--инбокс К]
    map-from-message.py --все            # все накопленные без исхода
    map-from-message.py --сообщение <id> --сухой   # показать, не писать
    map-from-message.py --selftest
Код возврата: 0 — карточка заведена или исход уже был, 1 — отказ.
"""
