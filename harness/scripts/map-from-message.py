def main() -> int:
    разбор = argparse.ArgumentParser(add_help=True)
    разбор.add_argument("--сообщение")
    разбор.add_argument("--все", action="store_true")
    разбор.add_argument("--карта")
    разбор.add_argument("--инбокс")
    разбор.add_argument("--линия")
    разбор.add_argument("--сухой", action="store_true")
    разбор.add_argument("--selftest", action="store_true")
    аргументы = разбор.parse_args()

    if аргументы.selftest:
        return _selftest()

    наст = конфиг()
    лог = Path(наст["LOG_DIR"])
    карта = Path(аргументы.карта or (Path(наст.get("PROJECT_DIR")
                                          or корень_дерева(__file__)) / "dev-map.yaml"))
    инбокс = Path(аргументы.инбокс or (лог / "inbox"))
    лок = лог / "locks" / (наст.get("SERVICE_LOCKS_SUBDIR") or "services") / "dev-map.lock"
    # Направление работы живёт в harness.conf (ACTIVE_LINE), а конфиг() читает
    # паспорт установки: спрашиваем оба, иначе задача харнеса легла бы в линию
    # продукта только потому, что она первая в файле.
    из_порогов = из_файла(путь_harness_conf())
    линия = аргументы.линия or из_порогов.get("ACTIVE_LINE") or наст.get("ACTIVE_LINE") or None

    if аргументы.все:
        беда = 0
        for ид in накопленные(инбокс, карта):
            беда |= завести(ид, карта, инбокс, лок, линия, аргументы.сухой)
        return беда
    if not аргументы.сообщение:
        print(__doc__, file=sys.stderr)
        return 1
    return завести(аргументы.сообщение, карта, инбокс, лок, линия, аргументы.сухой)


if __name__ == "__main__":
    sys.exit(main())
