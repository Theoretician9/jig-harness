#!/usr/bin/env python3
"""Гейт: у факта один судья. Кто о факте говорит — тот его и спрашивает.

Владелец 12.09.2026 (ночь): «Реши системно все эти проблемы». За ночь их было
три, и корень один: два механизма судят об одном факте, каждый считает его сам
— и владелец получает два противоречащих сигнала.

  • сторож писал «с лимитом подписки это не связано», его же ветка видела 429;
  • напоминание требовало согласия на push, сторож выката говорил «не нужно»;
  • автомат карточек заводил задачу из вопроса, прибор срочности говорил
    «это не работа».

Правило: файл, в котором встретилось слово-маркер факта, обязан звать источник
истины — по имени функции или по имени скрипта. Не зовёт и не назван в
«знают_сами» с причиной — красный.

Чего гейт НЕ делает: не разбирает смысл. Он ловит ровно один признак — «судит,
но не спрашивает». Это дешёвая проверка под случившийся отказ, а не попытка
понять код.

Прогон:
    python3 scripts/check-priznaki.py            # весь харнес
    python3 scripts/check-priznaki.py --selftest
Код возврата: 0 — чисто, 1 — есть судья без источника.
"""
import os
import re
import subprocess
import sys
from pathlib import Path

import yaml

КОРЕНЬ = Path(__file__).resolve().parent.parent
ДАННЫЕ = КОРЕНЬ / "harness" / "config" / "признаки.yaml"
# Где ищем судей: код харнеса. Продукт и чужие деревья не наше дело.
ОБХОД = ("scripts", "harness/demons", "harness/hooks", "harness/panel")
РАСШИРЕНИЯ = (".py", ".sh")
# Кавычки собираются из кодов: литерал тройных кавычек в файле,
# который сам ищет слова в исходниках, читается хуже всего.
тройная_двойная = chr(34) * 3
тройная_одинарная = chr(39) * 3


def данные(путь=ДАННЫЕ) -> list:
    дано = yaml.safe_load(Path(путь).read_text(encoding="utf-8"))
    return (дано or {}).get("признаки") or []


def файлы(корень: Path) -> list:
    найдено = []
    for каталог in ОБХОД:
        основа = корень / каталог
        if not основа.is_dir():
            continue
        for путь in sorted(основа.rglob("*")):
            if путь.is_file() and путь.suffix in РАСШИРЕНИЯ:
                найдено.append(путь)
    return найдено


def судит(текст: str, маркеры: list) -> str:
    """Первый маркер ВНЕ комментария и ВНЕ строки документации.

    Комментарий и строка документации объясняют, а не судят: 13.09.2026 гейт
    покраснел на scripts/srochnost.py за цитату владельца в шапке модуля —
    слова «текущая задача» там пересказывают его просьбу, а не судят о факте.
    """
    в_документации = False
    for строка in текст.splitlines():
        голая = строка.strip()
        # Тройные кавычки открывают и закрывают блок документации. Нечётное
        # число в строке переключает состояние: у однострочной документации
        # их два, и состояние не меняется.
        троек = голая.count(тройная_двойная) + голая.count(тройная_одинарная)
        if троек % 2 == 1:
            в_документации = not в_документации
            continue
        if в_документации or голая.startswith("#"):
            continue
        for м in маркеры:
            if м.lower() in голая.lower():
                return м
    return ""


def спрашивает(текст: str, источник: str, где: str) -> bool:
    имя_файла = Path(где).name
    return источник in текст or имя_файла in текст


def претензии(корень: Path, признаки: list) -> list:
    беды = []
    for признак in признаки:
        маркеры = признак.get("маркеры") or []
        источник = str(признак.get("источник", ""))
        где = str(признак.get("где", ""))
        свои = {str(з.get("файл")) for з in (признак.get("знают_сами") or [])}
        свои.add(где)
        for путь in файлы(корень):
            относительный = str(путь.relative_to(корень))
            if относительный in свои:
                continue
            try:
                текст = путь.read_text(encoding="utf-8", errors="replace")
            except OSError:
                continue
            маркер = судит(текст, маркеры)
            if маркер and not спрашивает(текст, источник, где):
                беды.append(
                    f"{относительный}: судит о факте «{признак['факт']}» "
                    f"(слово «{маркер}»), но источник не зовёт — "
                    f"{источник} из {где}")
    return беды


def _selftest() -> int:
    проба = КОРЕНЬ / "scripts" / "test_priznaki.py"
    if not проба.exists():
        print(f"[признаки] пробы нет: {проба}")
        return 1
    return subprocess.run([sys.executable, str(проба)], timeout=300).returncode


def главная(argv: list) -> int:
    if "--selftest" in argv:
        return _selftest()
    корень = Path(argv[argv.index("--корень") + 1]) if "--корень" in argv else КОРЕНЬ
    путь_данных = argv[argv.index("--данные") + 1] if "--данные" in argv else ДАННЫЕ
    беды = претензии(корень, данные(путь_данных))
    if беды:
        print(f"[признаки] СУДЯТ БЕЗ ИСТОЧНИКА: {len(беды)}")
        for б in беды:
            print("   ", б)
        print("Починка: позвать источник — или вписать файл в «знают_сами» "
              "с причиной, если он лишь пересказывает чужое решение.")
        return 1
    print(f"[признаки] чисто: у каждого факта один судья "
          f"(признаков {len(данные(путь_данных))})")
    return 0


if __name__ == "__main__":
    sys.exit(главная(sys.argv[1:]))
