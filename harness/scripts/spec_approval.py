#!/usr/bin/env python3
"""Уровень автоматизации: на частичном спека уходит владельцу и работа ждёт его слова.

Откуда взят. Владелец 23.09.2026, дословно: «Это надо сделать не правилом
записаным в памяти, а кнопкой в панели, это уровень автоматизации - либо
полный, либо частичный где скидывается сначала спека, и пока полтзователь не
одобрит, работа не начинается». И он же отдельно: «Прежде чем приступишь к
выполнению спеки, скинь ее мне, после ревью и правок».

Носитель — РУЧКА, а не запись в памяти: ключ `AUTOMATION_LEVEL` в harness.conf,
строка в реестре `harness/config/switches.yaml`, читатель — этот файл.
Правило, которое держится моим вниманием, носителя не имеет
([[a-rule-the-agent-enforces-on-itself]]).

Три решения, каждое — против пережитого случая:

* **След отправки — ответ Telegram, а не моё слово.** Запись «отправлена»
  появляется ТОЛЬКО когда tg_send.sh вернул ноль, то есть Bot API подтвердил
  message_id. «Я отправил» без следа проверяется лишь моей памятью, а 23.09
  ровно так и вышло: спека ушла, а доказать это было нечем.
* **Одобрение ищется в СЛОВАХ владельца, а не в распознавателе согласий.**
  Распознаватель диспетчера знает формы про выкат и push; «Выполняй спеку
  после текущей задачи» в confirmations.jsonl не попало вовсе. Читаем ту же
  первичную запись, что и ворота выката, — файлы очереди $LOG_DIR/inbox.
* **Чужое «да» не считается одобрением.** Голое согласие без названного
  предмета годится, только если после отправки спеки никто не спросил
  владельца о другом: ворота выката помечают свой вопрос в согласие.json, и
  более свежая пометка перевешивает. Иначе «да» про выкат открывало бы работу
  по неодобренной спеке — та же дыра, что ворота закрыли у себя 11.09.2026.

Прогон:
    spec_approval.py --уровень
    spec_approval.py --отправить <id задачи> --описание "о чём спека"
    spec_approval.py --состояние [<id задачи>]
    spec_approval.py --selftest
Код возврата: 0 — сделано либо одобрено; 1 — не сделано либо одобрения нет.
"""
import datetime
import json
import os
import re
import subprocess
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "scripts" / "lib"))
import patterns as формы                          # noqa: E402
import config as конф                                     # noqa: E402

# Ключ ручки. Значения ЛАТИНИЦЕЙ: вход единственного писателя настроек узкий
# нарочно (буквы, цифры и «_ . % -») — то же правило, что у LANG_LEVEL.
КЛЮЧ_УРОВНЯ = "AUTOMATION_LEVEL"
ЧАСТИЧНЫЙ = "partial"
ПОЛНЫЙ = "full"


def _журнал_каталог() -> Path:
    """Каталог журналов ПРИ ВЫЗОВЕ, а не при импорте: проба подменяет
    HARNESS_LOG_DIR после импорта, и вычисленный заранее путь увёл бы её на
    боевой журнал ([[the-probe-played-on-production]])."""
    return Path(os.environ.get("HARNESS_LOG_DIR") or конф.log_dir())


def журнал() -> Path:
    """Журнал отправок и одобрений: одна строка — одно событие."""
    return _журнал_каталог() / "спеки-владельцу.jsonl"


def уровень() -> str:
    """Уровень автоматизации из harness.conf. Ключа нет — ЧАСТИЧНЫЙ.

    Умолчание в сторону «спросить»: конфиг старой установки не смеет молча
    разрешить работу по неодобренной спеке — то же правило, что у
    `нужно_согласие` в воротах выката.
    """
    значение = (os.environ.get(КЛЮЧ_УРОВНЯ)
                or конф.из_файла(конф.путь_harness_conf()).get(КЛЮЧ_УРОВНЯ) or "")
    значение = значение.strip().strip('"').lower()
    return ПОЛНЫЙ if значение == ПОЛНЫЙ else ЧАСТИЧНЫЙ


def записи() -> list:
    """Все события журнала по порядку. Нечитаемый журнал — пустой список:
    отсутствие записи и так означает «не отправлено», строже быть нечему."""
    try:
        строки = журнал().read_text(encoding="utf-8").splitlines()
    except OSError:
        return []
    итог = []
    for строка in строки:
        try:
            запись = json.loads(строка)
        except ValueError:
            continue
        if isinstance(запись, dict):
            итог.append(запись)
    return итог


def дописать(запись: dict) -> None:
    путь = журнал()
    путь.parent.mkdir(parents=True, exist_ok=True)
    with open(путь, "a", encoding="utf-8") as fh:
        fh.write(json.dumps(запись, ensure_ascii=False) + "\n")


def _секунды(ts) -> float:
    try:
        return datetime.datetime.fromisoformat(str(ts)).timestamp()
    except ValueError:
        return 0.0


def отправлена(id_задачи: str, все=None) -> dict | None:
    """Последняя запись «спека отправлена» этой задачи, либо None."""
    найдено = None
    for запись in (все if все is not None else записи()):
        if запись.get("событие") == "отправлена" and запись.get("задача") == id_задачи:
            найдено = запись
    return найдено


def одобрена(id_задачи: str, все=None) -> dict | None:
    """Запись одобрения ПОСЛЕ последней отправки, либо None.

    Одобрение старше отправки не считается: спека переписана — значит владелец
    одобрял другой текст. Это тот же счёт, что у согласия на выкат: разрешение
    привязано к вопросу, а не к задаче вообще.
    """
    все = записи() if все is None else все
    от = отправлена(id_задачи, все)
    if от is None:
        return None
    порог = _секунды(от.get("ts"))
    for запись in все:
        # Считается КОГДА СКАЗАНО, а не когда записано: запись появляется в
        # момент проверки гейтом, и по времени записи одобрение старой редакции
        # выглядело бы свежее новой отправки (поймано самотестом).
        сказано = _секунды(запись.get("сказано") or запись.get("ts"))
        if (запись.get("событие") == "одобрена"
                and запись.get("задача") == id_задачи
                and сказано >= порог):
            return запись
    return None


# ── слова владельца ─────────────────────────────────────────────────────────
# Признак, а не список форм. Перечислять формы — тупик, доказанный трижды на
# согласиях выката: «Да для выката», «По выкату пишу да», «на гит отправляй,
# да» — каждый раз согласие БЫЛО, а механизм его не признавал.
ПРЕДМЕТ = re.compile(r"спек|задач|работ|приступ|выполн|делай|начин")
# Корень ищется с НАЧАЛА СЛОВА, а не подстрокой. Ревью кода 26.09.2026: без
# границы «делай» сидит внутри «сделай» и «переделай», и любое рабочее задание
# владельца («сделай панель зелёной») засчитывалось одобрением ждущей спеки.
ОДОБРЕНИЕ = re.compile(формы.ГРАНИЦА_СЛЕВА +
                       r"(?:одобр|утвержд|согласен|выполняй|приступ|начинай|"
                       r"работай|поехали|делай|годится|принято|довод)")
# Базовый набор общего судьи плюс названное расширение для спеки: свободные
# формы ответа владельца («согласен», «давай») открывают работу по спеке, но
# НЕ выкат — разница объявлена в данных судьи (ревизия §4.3).
ГОЛОЕ_СОГЛАСИЕ = set(формы.СОГЛАСИЕ_БАЗОВОЕ) | set(формы.СОГЛАСИЕ_СПЕКА_ДОП)
# Тот же судья, что у сторожа выката: слово отказа, добавленное в одном
# месте, обязано действовать в обоих (ревизия §4.3).
ОТРИЦАНИЕ = формы.ОТРИЦАНИЕ
# «Все спеки» — ОБЪЕМЛЮЩЕЕ одобрение: оно про каждую ждущую, а не про одну.
# Между «все» и «спек» пускается только короткая вставка (числительное,
# «мои»): дальше начинается другое предложение, и «все сделал, спеку пришли»
# объемлющим не является.
ОБЪЕМЛЕТ_ВСЕ = re.compile(формы.ГРАНИЦА_СЛЕВА + r"вс[еёюя]\w*\s+(?:\S+\s+){0,2}?спек")


def слова_темы(карточка: dict) -> set:
    """Значимые слова задачи: по ним владелец её и называет.

    Берутся из `title` и `id`, усечённые до корня в пять букв: «сотрудников»,
    «сотрудники» и «сотрудника» должны опознаваться одинаково, а падежи
    русского языка иначе не сходятся.
    """
    сырьё = f"{(карточка or {}).get('title', '')} {(карточка or {}).get('id', '')}"
    слова = re.findall(r"[А-Яа-яЁё]{5,}", сырьё.lower())
    return {слово[:5] for слово in слова}


def назвал_эту_задачу(текст: str, карточка: dict, соседи: list) -> bool:
    """Владелец назвал ИМЕННО эту задачу, а не какую-то из ждущих?

    ЗАЧЕМ ЭТО НУЖНО. Окно поиска одобрения кончается отправкой следующей спеки
    — правило верное для ГОЛОГО «да»: иначе согласие по соседней задаче
    засчиталось бы этой. Но оно режет и ответ с НАЗВАННЫМ предметом: 04.10.2026
    владелец написал «Спека сотрудников одобрено» в 15:09, а окно закрылось в
    14:48, когда ему ушла вторая спека. Решение состоялось, механизм его не
    видел, и работа стояла. В очереди у него бывает три спеки, и отвечает он в
    своём порядке — то есть случай повторялся бы с каждой.

    СУДИМ РАЗЛИЧАЮЩИМИ СЛОВАМИ, а не любым совпадением. «клиент», «первая»,
    «может» есть в заголовках сразу нескольких задач, и по ним ответ достался
    бы не той: различающие — это слова ЭТОЙ задачи, которых нет у соседей по
    очереди ожидания.
    """
    мои = слова_темы(карточка)
    чужие = set().union(*(слова_темы(с) for с in соседи)) if соседи else set()
    различающие = мои - чужие
    if not различающие:
        return False
    сказано = {слово[:5] for слово in re.findall(r"[А-Яа-яЁё]{5,}", текст.lower())}
    return bool(различающие & сказано)


def объемлет_все(текст: str) -> bool:
    """Владелец одобрил СРАЗУ ВСЕ ждущие спеки — «все спеки одобряю, делай»?

    ЗАЧЕМ. Правило окна и правило названной задачи оба считают, что владелец
    отвечает ПРО ОДНУ спеку. 04.10.2026 он ответил про все: слово пришло в
    17:50, а окно самой старой ждущей спеки (копия и восстановление) закрылось
    в 13:55 следующей отправкой — её одобрение потерялось, и работа по ней
    осталась незаконной при состоявшемся решении владельца. Названной эту
    задачу он тоже не считал: различающих слов в «все спеки одобряю» нет.

    СУДИМ ПАРОЙ «все» + «спеки» рядом, а не словом «все»: «все сделал», «все
    проверил», «во всех заказах» одобрением не являются и обязаны остаться
    голым согласием, которое ловит общее правило. Числительное между ними
    законно — «все три спеки».
    """
    строка = " ".join(текст.lower().split())
    return bool(ОБЪЕМЛЕТ_ВСЕ.search(строка))


def это_одобрение(текст: str, чужой_вопрос_позже: bool = False) -> bool:
    """Слова владельца означают «работай по этой спеке»?

    Два пути, и второй уже́: с НАЗВАННЫМ предметом одобрение считается всегда,
    голое «да» — только если после отправки спеки его не спросили о другом.
    Иначе «да» про выкат открывало бы работу по неодобренной спеке.
    """
    строка = " ".join(текст.lower().split())
    if not строка or ОТРИЦАНИЕ.search(f" {строка} "):
        return False
    # «да» с НАЗВАННЫМ предметом — тоже одобрение, и это живая форма: 13.10.2026
    # на просьбу ответить «спека безопасности — да» владелец так и ответил, а
    # список слов одобрения «да» не знал вовсе — узкий список форм был тупиком
    # уже трижды на согласиях выката. Судья один на оба механизма: СЛОВО_ДА из
    # scripts/lib/patterns.py (он же знает, что «дай данные» согласием не считается).
    if (ОДОБРЕНИЕ.search(строка) or формы.СЛОВО_ДА.search(строка)) \
            and ПРЕДМЕТ.search(строка):
        return True
    return строка.rstrip(".!") in ГОЛОЕ_СОГЛАСИЕ and not чужой_вопрос_позже


def слова_владельца(после: float, до: float = float("inf")) -> list:
    """Сообщения владельца из очереди $LOG_DIR/inbox в окне (после, до].

    Первичная запись — файл очереди, а не confirmations.jsonl: распознаватель
    диспетчера знает только формы про выкат и push, и «Выполняй спеку после
    текущей задачи» в журнал согласий не попало вовсе.
    """
    каталог = _журнал_каталог() / "inbox"
    найдено = []
    for подкаталог in (каталог, каталог / "обработано"):
        try:
            файлы = sorted(подкаталог.glob("*.txt"))
        except OSError:
            continue
        for файл in файлы:
            try:
                когда = файл.stat().st_mtime
                текст = файл.read_text(encoding="utf-8", errors="replace").strip()
            except OSError:
                continue
            if текст and после < когда <= до:
                найдено.append({"когда": когда, "текст": текст, "файл": файл.name})
    найдено.sort(key=lambda з: з["когда"])
    return найдено


def _чужой_вопрос_позже(порог: float) -> bool:
    """Ворота выката спросили владельца о ДРУГОМ уже после отправки спеки.

    Пометка живёт в согласие.json (ключ «ожидание»): ворота помнят предмет
    последнего отказа, чтобы засчитать голое «да» именно ему. Читаем ту же
    пометку — два механизма не вправе считать одно «да» каждый своим.
    """
    try:
        состояние = json.loads(
            (_журнал_каталог() / "согласие.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return False
    ожидание = (состояние or {}).get("ожидание") or {}
    try:
        когда = float(ожидание.get("ts") or 0)
    except (TypeError, ValueError):
        return False
    return когда > порог


def найти_одобрение(id_задачи: str, корень=None) -> dict | None:
    """Ищет одобрение в словах владельца и ЗАПИСЫВАЕТ его. → запись или None.

    Пишет КОД в момент проверки, а не я по памяти: одобрение, о котором надо
    вспомнить, лимита не переживает ([[a-mechanism-that-needs-a-human-is-dead]]).
    """
    все = записи()
    уже = одобрена(id_задачи, все)
    if уже:
        return уже
    от = отправлена(id_задачи, все)
    if от is None:
        return None
    порог = _секунды(от.get("ts"))
    # Окно кончается следующей отправкой ЛЮБОЙ задачи: иначе «да», сказанное
    # про соседнюю спеку, засчиталось бы и этой.
    до = min((_секунды(з.get("ts")) for з in все
              if з.get("событие") == "отправлена" and _секунды(з.get("ts")) > порог),
             default=float("inf"))
    # НАЗВАННАЯ ЗАДАЧА СИЛЬНЕЕ ОКНА — и в обе стороны. Правило окна защищает от
    # голого «да» по соседней спеке, но названный предмет ни с чем не путается:
    # 04.10.2026 «Спека сотрудников одобрено» пришло после отправки второй
    # спеки, и работа встала при состоявшемся решении владельца.
    #
    # Обратная сторона того же правила важнее: если владелец назвал ДРУГУЮ
    # ждущую задачу, его слово этой НЕ достаётся, даже когда окно открыто. Без
    # этой половины первая же редакция правки зачла «Спека сотрудников
    # одобрено» ЗАОДНО задаче про каталог — у неё окно было открыто, а общего
    # слова «спека» правилу хватало. Дыра была и до правки: любое «одобряю …
    # спеку» открывало работу по всем ждущим.
    карточка = карточка_задачи(id_задачи, корень) or {"id": id_задачи}
    ждущие = карточки_отправленных(все, корень)
    соседи = [к for к in ждущие if (к or {}).get("id") != id_задачи]
    for слово in слова_владельца(порог):
        назвал_мою = назвал_эту_задачу(слово["текст"], карточка, соседи)
        назвал_чужую = any(назвал_эту_задачу(слово["текст"], сосед,
                                             [к for к in ждущие
                                              if (к or {}).get("id") != (сосед or {}).get("id")])
                           for сосед in соседи)
        # ОБЪЕМЛЮЩЕЕ «все спеки» старше обоих правил: оно названо про каждую
        # ждущую, поэтому ни чужое имя рядом, ни закрытое окно его не отменяют.
        объемлет = объемлет_все(слово["текст"])
        if назвал_чужую and not назвал_мою and not объемлет:
            continue
        за_окном = слово["когда"] > до
        if за_окном and not назвал_мою and not объемлет:
            continue
        if это_одобрение(слово["текст"], _чужой_вопрос_позже(порог) and not за_окном):
            запись = {"ts": datetime.datetime.now().isoformat(timespec="seconds"),
                      "событие": "одобрена", "задача": id_задачи,
                      "слово": слово["текст"][:300],
                      "источник": f"inbox:{слово['файл']}",
                      "названа_явно": назвал_мою,
                      "сказано": datetime.datetime.fromtimestamp(
                          слово["когда"]).isoformat(timespec="seconds")}
            дописать(запись)
            return запись
    return None


def карточки_отправленных(все: list, корень=None) -> list:
    """Карточки ВСЕХ задач, чьи спеки владельцу отправлялись.

    Нужны как СОСЕДИ: различающее слово считается против них, а не против всей
    карты — иначе «сотрудников» перестало бы различать, едва в карте появится
    вторая задача со словом «сотрудник» в заголовке.

    Почему ВСЕ отправленные, а не только ждущие одобрения: набор ждущих меняется
    в момент записи одобрения, и первая редакция этой правки получила порочный
    круг — едва запись появлялась, задача выпадала из соседей, слово перестало
    «называть чужую», и то же слово засчитывалось следующей спеке. Набор
    соседей обязан не зависеть от порядка записей в журнале.
    """
    отправленные = {з.get("задача") for з in все if з.get("событие") == "отправлена"}
    итог = []
    for задача in sorted(x for x in отправленные if x):
        карточка = карточка_задачи(задача, корень)
        if карточка:
            итог.append(карточка)
    return итог


def путь_спеки(спека: str, корень=None) -> Path | None:
    """Файл спеки: у харнеса или у ПРОДУКТА. None — файла нет нигде.

    Путь в карточке относительный, а корней два: спеки задач продукта лежат в
    его репозитории (PRODUCT_REPO в harness.conf). Пока корень был только
    наш, механизм отвечал «файла спеки нет» на существующий файл — и отправка
    владельцу была невозможна, а гейт требовал её вечно (замер 13.10.2026).
    """
    if not спека:
        return None
    места = [Path(корень)] if корень else []
    места.append(КОРЕНЬ)
    продукт = (конф.из_файла(конф.путь_harness_conf()).get("PRODUCT_REPO") or "").strip()
    if продукт:
        места.append(Path(продукт))
    for место in места:
        файл = место / спека
        if файл.exists():
            return файл
    return None


def одобрение_по_факту(id_задачи: str, карточка: dict,
                      корень=None) -> dict | None:
    """Слово владельца об этой спеке, сказанное ПОСЛЕ её последней правки.

    Нужна, когда записи об отправке нет, а слово есть: механизм обязан принимать
    состоявшееся решение владельца, иначе его «Приступай» ничего не значит и
    работа идёт честной дверью (28.09.2026 — пять записей обходов за смену).

    Строгость та же, что у обычного одобрения: нужен ФАЙЛ спеки, слово должно
    быть сказано ПОЗЖЕ его правки и содержать названный предмет. Найденное
    записывается в журнал парой «отправлена по факту» + «одобрена», чтобы второй
    раз это не пересчитывалось и было видно, на чём основано.
    """
    корень = корень or КОРЕНЬ
    спека = (карточка or {}).get("spec")
    if not спека:
        return None
    файл = путь_спеки(спека, корень)
    if файл is None:
        return None
    try:
        правлена = файл.stat().st_mtime
    except OSError:
        return None
    for запись in reversed(слова_владельца(правлена)):
        if это_одобрение(запись["текст"], чужой_вопрос_позже=True):
            # Время отправки — момент ПРАВКИ спеки, а не «сейчас»: иначе слово
            # владельца окажется старше отправки, и одобрение не засчитается
            # (проверка одобрена() судит по порядку, и это верно).
            дописать({"ts": datetime.datetime.fromtimestamp(правлена).isoformat(
                          timespec="seconds"),
                      "событие": "отправлена", "задача": id_задачи,
                      "файл": спека, "кем": "по факту: слово владельца после правки спеки"})
            дописать({"ts": datetime.datetime.now().isoformat(timespec="seconds"),
                      "событие": "одобрена", "задача": id_задачи,
                      "слово": запись["текст"][:200],
                      "источник": f"inbox:{запись['файл']}",
                      "сказано": datetime.datetime.fromtimestamp(
                          запись["когда"]).isoformat(timespec="seconds")})
            return запись
    return None


# ── что видит гейт ──────────────────────────────────────────────────────────
def беды_одобрения(id_задачи: str, карточка: dict, корень=None) -> list:
    """Чего не хватает задаче на ЧАСТИЧНОМ уровне автоматизации. Чистая часть.

    Судится только задача, у которой спека уже есть: требовать одобрения
    ненаписанной спеки бессмысленно, а порядок владельца — «спека → ревью →
    правки → отправка → его слово → работа».
    """
    if уровень() != ЧАСТИЧНЫЙ:
        return []
    if not (карточка or {}).get("spec"):
        return []
    от = отправлена(id_задачи)
    if от is None:
        # СОСТОЯВШЕЕСЯ одобрение: файл спеки существует, и ПОСЛЕ его последней
        # правки владелец сказал слово одобрения с названным предметом. Так было
        # 28.09.2026 с ревизией: «Приступай» сказано, а записи об отправке нет —
        # и пять коммитов смены прошли честной дверью, хотя его слово было.
        # Замок при этом не слабеет: без файла спеки и без ЕГО слова после её
        # правки ответ прежний — «не отправлена».
        по_факту = одобрение_по_факту(id_задачи, карточка, корень)
        if по_факту is None:
            return [f"спека владельцу НЕ ОТПРАВЛЕНА, а уровень автоматизации «частичный»: "
                    f"python3 scripts/spec_approval.py --отправить {id_задачи}"]
        return []
    if найти_одобрение(id_задачи) is None:
        return [f"спека отправлена {str(от.get('ts'))[:16]}, одобрения владельца нет — "
                f"по его слову работа начинается после одобрения"]
    return []


# ── отправка ────────────────────────────────────────────────────────────────
def карточка_задачи(id_задачи: str, корень=None) -> dict | None:
    """Карточка из карты. Корень — параметр, чтобы самотест играл на СВОЕЙ карте,
    а не на боевой ([[the-probe-played-on-production]])."""
    import yaml
    корень = корень or КОРЕНЬ
    try:
        данные = yaml.safe_load((Path(корень) / "dev-map.yaml").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None

    def обход(узел):
        if isinstance(узел, dict):
            if узел.get("id") == id_задачи and "status" in узел:
                yield узел
            for значение in узел.values():
                yield from обход(значение)
        elif isinstance(узел, list):
            for значение in узел:
                yield from обход(значение)

    return next(обход(данные), None)


ОПИСАНИЕ_МИНИМУМ = 80


def отправить(id_задачи: str, описание: str = "") -> int:
    """Отправить спеку владельцу — ОПИСАНИЕМ и файлом — и оставить след.

    След пишется ТОЛЬКО после нулевого кода tg_send.sh: он возвращает успех
    лишь при ok:true И подтверждённом message_id. Запись без доказанной
    доставки была бы ровно тем «я отправил», ради которого всё и делается.

    Описание ОБЯЗАТЕЛЬНО. Владелец 26.09.2026 на вопрос о разрешении ответил
    «1. присылать спеку описанием, а не голым файлом»: файл без слов — это работа, переложенная на него,
    он должен открыть документ, чтобы понять, о чём его спрашивают. Его же
    правило 27.08: «отчёт текстом, файлом — только документ» — отчёт ТЕКСТОМ,
    вложение только для документа.

    Пустое или короткое описание — ОТКАЗ, а не отправка молчком: иначе правило
    держалось бы моим вниманием, а не кодом.
    """
    описание = " ".join((описание or "").split())
    if len(описание) < ОПИСАНИЕ_МИНИМУМ:
        print(f"{id_задачи}: спека НЕ отправлена — нет описания «о чём она» "
              f"(нужно хотя бы {ОПИСАНИЕ_МИНИМУМ} знаков, дано {len(описание)}).")
        print("    Владелец 26.09: «присылать спеку описанием, а не голым файлом». Файл без слов не считается.")
        print(f"    python3 scripts/spec_approval.py --отправить {id_задачи} "
              f"--описание «что за задача, что меняем и чем это проверяется»")
        return 1
    карточка = карточка_задачи(id_задачи)
    if карточка is None:
        print(f"нет такой задачи в карте: {id_задачи}")
        return 1
    спека = карточка.get("spec")
    if not спека:
        print(f"{id_задачи}: в карточке нет поля spec: — отправлять нечего")
        return 1
    путь = путь_спеки(спека)
    if путь is None:
        print(f"{id_задачи}: файла спеки нет ни у харнеса, ни у продукта — {спека}")
        return 1
    # Сначала СЛОВА, потом документ: он читает текст в канале, а файл
    # открывает, только если нужны подробности.
    словами = (f"Спека задачи {id_задачи} — {карточка.get('title') or ''}.\n\n"
               f"{описание}\n\n"
               f"Ревью сделано, правки внесены. Работа начнётся после твоего "
               f"слова — ответь «да» или напиши правки.")
    subprocess.run(["bash", str(КОРЕНЬ / "scripts" / "tg_send.sh"), словами[:1700]],
                   capture_output=True, text=True, errors="replace", timeout=180)
    готово = subprocess.run(
        ["bash", str(КОРЕНЬ / "scripts" / "tg_send.sh"), "--file", str(путь),
         "--caption", f"Спека задачи {id_задачи} целиком"],
        capture_output=True, text=True, errors="replace", timeout=180)
    print((готово.stdout or "").strip() or (готово.stderr or "").strip())
    if готово.returncode != 0:
        print(f"{id_задачи}: спека НЕ отправлена (tg_send вернул {готово.returncode}) — "
              f"следа нет, и гейт по-прежнему красный")
        return 1
    дописать({"ts": datetime.datetime.now().isoformat(timespec="seconds"),
              "событие": "отправлена", "задача": id_задачи, "файл": спека,
              "описание": описание[:500], "кем": "scripts/spec_approval.py"})
    print(f"{id_задачи}: спека отправлена владельцу, след в {журнал()}")
    return 0


def состояние(id_задачи: str | None) -> int:
    все = записи()
    print(f"уровень автоматизации: {уровень()} "
          f"({'спека уходит владельцу, работа ждёт одобрения' if уровень() == ЧАСТИЧНЫЙ else 'работа идёт без одобрения'})")
    задачи = [id_задачи] if id_задачи else sorted(
        {з.get("задача") for з in все if з.get("задача")})
    if not задачи:
        print("ни одной спеки владельцу ещё не отправлено")
        return 1
    плохо = 0
    for задача in задачи:
        от = отправлена(задача, все)
        # Тем же вызовом, что и гейт: показ, читающий только журнал, говорил
        # «одобрения НЕТ» там, где боевой путь его находил и засчитывал
        # ([[the-probe-calls-it-differently]]).
        од = найти_одобрение(задача)
        print(f"  {задача}: отправлена {str((от or {}).get('ts', '—'))[:16]} · "
              f"одобрение {('«' + str(од.get('слово'))[:40] + '»') if од else 'НЕТ'}")
        плохо |= 0 if од else 1
    return плохо


# ── самотест ────────────────────────────────────────────────────────────────
def самотест() -> int:
    """Проверка обязана СОЗДАТЬ своё условие: свой каталог журналов, свои слова."""
    import tempfile
    ok = True
    путей = 0

    def сказал(двор: Path, текст: str, когда: float) -> None:
        каталог = двор / "inbox"
        каталог.mkdir(parents=True, exist_ok=True)
        файл = каталог / f"{когда:.0f}.txt"
        файл.write_text(текст, encoding="utf-8")
        os.utime(файл, (когда, когда))

    def итог(зачем: str, вышло, ждём) -> None:
        nonlocal ok, путей
        путей += 1
        if вышло == ждём:
            print(f"  ок    {зачем}")
        else:
            ok = False
            print(f"  ПЛОХО {зачем}: вышло {вышло!r}, ждали {ждём!r}")

    # Разбор слов — без файлов: чистая функция, её и судим.
    итог("БОЛЬНОЙ СЛУЧАЙ 23.09: «доводить текущую задачу прежде спеки» — одобрение",
         это_одобрение("доводить текущую задачу прежде спеки"), True)
    итог("«одобряю» одним словом — одобрение", это_одобрение("одобряю"), True)
    итог("«да» — одобрение, когда о другом не спрашивали",
         это_одобрение("да"), True)
    итог("«да» НЕ одобрение, когда ворота выката спросили позже",
         это_одобрение("да", чужой_вопрос_позже=True), False)
    итог("«спеку не делай пока» — отрицание перевешивает",
         это_одобрение("спеку не делай пока"), False)
    итог("«не одобряю» — не одобрение", это_одобрение("не одобряю"), False)
    # ЖИВАЯ ФОРМА 13.10.2026: на просьбу ответить «спека безопасности — да» он
    # так и ответил, а список слов одобрения «да» не знал. Форма с НАЗВАННЫМ
    # предметом считается даже тогда, когда его спрашивали о другом: предмет в
    # ответе и есть доказательство, о чём он говорит.
    итог("живая форма «спека безопасности - да» — одобрение",
         это_одобрение("спека безопасности - да", чужой_вопрос_позже=True), True)
    итог("БОЛЬНОЙ СЛУЧАЙ: «дай данные по спеке» — не одобрение",
         это_одобрение("дай данные по спеке"), False)

    # Состоявшееся одобрение: слово ПОСЛЕ правки файла спеки принимается, слово
    # ДО правки — нет (владелец одобрял другой текст). Условие создаём сами.
