#!/usr/bin/env python3
"""Все, кто ищет главы, знают ОБЕ раскладки — пакета и публичной сборки.

ЗАЧЕМ ЭТОТ ГЕЙТ. Публикация переносит `UNIFIED/` в `sluzhebnoe/UNIFIED`
(данные `harness/config/public-build.yaml`, ключ «перенести»): 1,1 МБ глав
в корне человек читает как груз. Переносить — решение владельца, и оно
безобидно ровно до тех пор, пока КАЖДЫЙ, кто ищет главы, знает новое место.

13.10.2026 владелец ставил харнес на свой сервер из публичного гита, и
установка умерла на первом шаге: `USTANOVIT.sh` искал главы в `../UNIFIED`,
`./UNIFIED`, `../../UNIFIED` — и отказал словами «каталог UNIFIED не найден».
Раскладчик (`razlozhit-harnes.sh`) и генератор скилов (`BUILD-SKILLS.py`) обе
раскладки знали; тот, кого человек запускает ПЕРВЫМ, — нет. Знание о третьем
искателе жило КОММЕНТАРИЕМ в файле данных («кто ищет UNIFIED после переноса:
раскладчик и генератор»), а комментарий ничего не держит.

ЧТО СУДИТСЯ. Искатели находятся ПОИСКОМ по дереву, а не списком в коде: список
ослепнет на новом искателе в тот день, когда его напишут.

Судится не всякий, кто поминает главы, а тот, кто ищет их ОТ СВОЕГО
МЕСТОПОЛОЖЕНИЯ (`$SCRIPT_DIR`, `$HERE`, `__file__`): именно его место и
переезжает вместе со сборкой. Кто берёт `UNIFIED` от корня проекта
(`check-extensions.py`, `check-who-calls.py`, `test_panel_install.py`) — работает
ПОСЛЕ раскладки, а раскладчик кладёт главы в `$PROJECT_DIR/UNIFIED`, то есть в
старое место; требовать от них нового пути значит красить здоровый код, а
красящий гейт выключают ([[a-rule-covering-one-path-of-two]]).

Прогон:
    python3 scripts/check-unified-seekers.py            # проект и пакет
    python3 scripts/check-unified-seekers.py --selftest # на больном случае
"""
from __future__ import annotations

import re
import subprocess
import sys
import tempfile
from pathlib import Path

import importlib.util


def _сосед():
    """Модуль, который УЖЕ умеет искать каталог пакета.

    Вторая копия этого поиска (STARTER_DIR из harness.conf, иначе конвенция по
    AGENT_USER) разошлась бы с первой на первой правке. Имя файла с дефисом
    обычным импортом не берётся, отсюда загрузка по пути.
    """
    путь = Path(__file__).resolve().parent / "compare-with-package.py"
    spec = importlib.util.spec_from_file_location("sverka_s_paketom", путь)
    if spec is None or spec.loader is None:
        return None
    модуль = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(модуль)
    return модуль

def корни() -> list[Path]:
    """Где искать искателей: проект (от git) и каталог пакета (из данных).

    ЛИТЕРАЛОВ ЗДЕСЬ НЕ БЫВАЕТ. Путь установки, зашитый в код, уезжает в
    публичную сборку — обезличивание идёт только по документам, и замок «в
    сборке нет следов установки» отказал бы публикации; на чужой машине тот же
    литерал красит ворота «судимых 0, бед 2». Находка ревью кода 13.10.2026.
    """
    найдено = []
    свой = subprocess.run(["git", "rev-parse", "--show-toplevel"],
                          capture_output=True, text=True, cwd=Path(__file__).resolve().parent)
    if свой.returncode == 0 and свой.stdout.strip():
        найдено.append(Path(свой.stdout.strip()))
    модуль = _сосед()
    if модуль is not None:
        пакет, почему = модуль.найти_пакет()
        if пакет is not None:
            найдено.append(пакет)
        else:
            # «Пакета нет» говорится словами: молчание тут читалось бы как
            # «искателей в пакете не бывает».
            print(f"  ПЛОХО каталог пакета не найден: {почему}")
    return найдено

# Чем кандидат опознаётся. ДВА НАПИСАНИЯ, и второе я сперва пропустил: путь
# строкой (`"$HERE/../UNIFIED"`) и путь, собранный по частям
# (`here.parent / "sluzhebnoe" / "UNIFIED"`). Считать только первое — значит
# ослепнуть на генераторе скилов, то есть на одном искателе из двух способов
# написать одно и то же ([[a-measure-counting-one-spelling-of-two]]).
КАНДИДАТ = re.compile(r'["\']([^"\'\n]*?/UNIFIED)["\']|(?<=["\'])(UNIFIED)(?=["\'])')

# Что НЕ судится: сами главы, документы и этот гейт.
ПРОПУСК = ("sluzhebnoe/UNIFIED/", "UNIFIED/", "/.git/", "check-unified-seekers.py")

# Чем судятся файлы. `.mjs` добавлен находкой ревью: приборы продукта на нём
# тоже читают каталоги, и слепота по расширению не видна ничем.
СУДИМЫЕ_РАСШИРЕНИЯ = (".sh", ".py", ".mjs")

# Файлы, которые не удалось прочитать: они беда, а не тишина.
НЕПРОЧИТАННЫЕ: list[str] = []


# Чем путь привязан к МЕСТУ САМОГО ФАЙЛА. Только такой путь переезжает вместе
# со сборкой; `"UNIFIED"` от корня проекта — другой вопрос и другой ответ.
#
# ПРИЗНАКИ ТОЧНЫЕ, А НЕ ПОХОЖИЕ. Прежняя редакция держала `here` и `parent` —
# и ловила `mkdir(parents=True)` и английское слово `where`: три ложных находки
# из трёх на здоровом коде, а красящий гейт выключают (находка ревью 13.10).
ЯКОРЯ = ("SCRIPT_DIR", "BASH_SOURCE", "$HERE", "HERE/", "__file__", "$0", "dirname")

# Путь, собранный по частям: `… / "UNIFIED"` у Path или os.path.join. Такая
# сборка тоже привязана к месту файла, и без неё гейт слеп на генераторе скилов.
СБОРКА = re.compile(r'(?:/\s*|join\s*\([^)]*?)["\']UNIFIED["\']')


def кандидаты(текст: str) -> list[str]:
    """Строки-кандидаты: путь к главам, привязанный к месту самого файла.

    Отдаются СТРОКИ, а не куски пути: знание о новой раскладке судится по той
    же строке, где стоит кандидат. Прежняя редакция искала слово `sluzhebnoe`
    по всему файлу — и была сыта КОММЕНТАРИЕМ о нём (находка ревью: снял оба
    настоящих кандидата у генератора скилов, оставил комментарий — находок 0).
    """
    собрано = []
    for строка in текст.splitlines():
        прямой = КАНДИДАТ.search(строка)
        сборный = СБОРКА.search(строка)
        if прямой is None and сборный is None:
            continue
        if прямой is not None and "/UNIFIED" in (прямой.group(1) or ""):
            собрано.append(строка.strip())
            continue
        if any(якорь in строка for якорь in ЯКОРЯ) or сборный is not None:
            собрано.append(строка.strip())
    return собрано


def искатели(корень: Path) -> list[Path]:
    """Файлы кода, которые ищут главы от своего местоположения."""
    найдено = []
    for путь in корень.rglob("*"):
        if not путь.is_file() or путь.suffix not in СУДИМЫЕ_РАСШИРЕНИЯ:
            continue
        строка = str(путь)
        if any(мимо in строка for мимо in ПРОПУСК):
            continue
        try:
            текст = путь.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            # «Не прочитали» и «нет кандидатов» — разные ответы, и первый обязан
            # быть НАХОДКОЙ, а не печатью: прежняя редакция печатала «ПЛОХО» и
            # отвечала кодом 0 (находка ревью 13.10).
            НЕПРОЧИТАННЫЕ.append(f"{путь}: файл не прочитан — судить нечем")
            continue
        if кандидаты(текст):
            найдено.append(путь)
    return найдено


def судить(путь: Path) -> list[str]:
    """Находки по одному искателю: словами, с именем файла."""
    текст = путь.read_text(encoding="utf-8")
    свои = кандидаты(текст)
    беды: list[str] = []
    # Привязанных к своему месту путей нет — файл вообще не искатель, и
    # требовать от него нового пути значит красить здоровый код (поймано
    # четвёртым случаем самотеста).
    if not свои:
        return беды
    # ЗНАНИЕ — ЛИБО В СТРОКЕ КАНДИДАТА, ЛИБО В КОДЕ РЯДОМ, НО НЕ В КОММЕНТАРИИ.
    # Строка кандидата — главный случай (`$HERE/../sluzhebnoe/UNIFIED`), но
    # сосед держит обе раскладки СПИСКОМ в константе (`check-seed-templates.py`:
    # МЕСТА = ("UNIFIED/templates", "sluzhebnoe/UNIFIED/templates")), и это
    # законно. А комментарий о переносе знанием НЕ считается: ревью сняло у
    # генератора скилов оба настоящих пути, оставило комментарий — и прежняя
    # редакция была этим сыта.
    живые = [одна for одна in текст.splitlines()
             if not одна.strip().startswith(("#", "//"))]
    знает = any("sluzhebnoe" in одна for одна in свои) or any(
        "sluzhebnoe/UNIFIED" in одна for одна in живые
    )
    if not знает:
        беды.append(
            f"{путь}: ищет главы в {len(свои)} местах, и ни одно не ведёт в "
            "sluzhebnoe/UNIFIED — в публичной сборке главы лежат ТАМ, и этот "
            f"файл их не найдёт (строки: {' | '.join(свои)})"
        )
    return беды


def больной_случай() -> int:
    """Самотест: искатель без нового кандидата обязан стать находкой."""
    неудач = 0
    with tempfile.TemporaryDirectory(prefix="проба-искателей-") as врем:
        двор = Path(врем)
        слепой = двор / "slepoj.sh"
        слепой.write_text(
            'for cand in "$HERE/../UNIFIED" "$HERE/UNIFIED"; do :; done\n',
            encoding="utf-8",
        )
        зрячий = двор / "zryachij.sh"
        зрячий.write_text(
            'for cand in "$HERE/../UNIFIED" "$HERE/../sluzhebnoe/UNIFIED"; do :; done\n',
            encoding="utf-8",
        )

        беды = судить(слепой)
        ок = len(беды) == 1 and "sluzhebnoe/UNIFIED" in беды[0]
        print(("  ок    " if ок else "  ПЛОХО ") + "БОЛЬНОЙ: искатель без нового пути — находка")
        неудач += 0 if ок else 1

        беды = судить(зрячий)
        ок = беды == []
        print(("  ок    " if ок else "  ПЛОХО ") + "ОБРАТНЫЙ: искатель с новым путём чист")
        неудач += 0 if ок else 1

        # Третий случай: файл без кандидатов вообще не искатель.
        мимо = двор / "mimo.sh"
        мимо.write_text("# слово UNIFIED в тексте, без пути\n", encoding="utf-8")
        ок = мимо not in искатели(двор)
        print(("  ок    " if ок else "  ПЛОХО ") + "слово UNIFIED без пути искателем не считается")
        неудач += 0 if ок else 1

        # ЧЕТВЁРТЫЙ, из-за которого гейт едва не покрасил здоровый код: путь от
        # КОРНЯ ПРОЕКТА. Такой читатель работает после раскладки, а раскладчик
        # кладёт главы в $PROJECT_DIR/UNIFIED — старого пути ему достаточно.
        от_корня = двор / "ot_kornya.py"
        от_корня.write_text('ГДЕ = ["harness/skills", "UNIFIED", "docs"]\n', encoding="utf-8")
        ок = от_корня not in искатели(двор) and судить(от_корня) == []
        print(("  ок    " if ок else "  ПЛОХО ") + "путь от корня проекта не судится")
        неудач += 0 if ок else 1

        # ПЯТЫЙ: комментарий о переносе знанием не считается. Ревью сняло у
        # генератора скилов оба настоящих пути и оставило о них комментарий —
        # прежняя редакция была этим сыта, то есть удовлетворялась ровно тем
        # носителем, который коммит объявляет негодным.
        болтун = двор / "boltun.py"
        болтун.write_text(
            '# главы переехали в sluzhebnoe/UNIFIED, помним\n'
            'главы = Path(__file__).parent / "UNIFIED"\n',
            encoding="utf-8",
        )
        беды = судить(болтун)
        ок = len(беды) == 1
        print(("  ок    " if ок else "  ПЛОХО ") + "комментарий о переносе знанием НЕ считается")
        неудач += 0 if ок else 1

        # ШЕСТОЙ: путь, собранный по частям, — тоже искатель. Без него гейт слеп
        # на генераторе скилов, то есть на одном из двух способов написать путь.
        сборный = двор / "sbornyj.py"
        сборный.write_text(
            'главы = [here.parent / "sluzhebnoe" / "UNIFIED", here / "UNIFIED"]\n',
            encoding="utf-8",
        )
        ок = сборный in искатели(двор) and судить(сборный) == []
        print(("  ок    " if ок else "  ПЛОХО ") + "путь, собранный по частям, опознан и чист")
        неудач += 0 if ок else 1

        # СЕДЬМОЙ: `dirname "$0"` — тот же якорь, что SCRIPT_DIR, и он встречался
        # в живых скриптах чаще.
        нулевой = двор / "nulevoj.sh"
        нулевой.write_text('главы="$(dirname "$0")/UNIFIED"\n', encoding="utf-8")
        ок = len(судить(нулевой)) == 1
        print(("  ок    " if ок else "  ПЛОХО ") + 'путь от `dirname "$0"` судится')
        неудач += 0 if ок else 1

        # ВОСЬМОЙ, бывшая ложная находка: `parents=True` рядом с путём от корня
        # проекта. Якорь `parent` ловил его и красил здоровый код.
        здоровый = двор / "zdorovyj.py"
        здоровый.write_text(
            'Path("docs").mkdir(parents=True)\nГДЕ = ["UNIFIED", "docs"]\n',
            encoding="utf-8",
        )
        ок = здоровый not in искатели(двор) and судить(здоровый) == []
        print(("  ок    " if ок else "  ПЛОХО ") + "parents=True рядом с путём от корня — не находка")
        неудач += 0 if ок else 1

        # ДЕВЯТЫЙ: закрытый файл — БЕДА, а не тишина. Прежняя редакция печатала
        # «ПЛОХО» и отвечала кодом 0.
        НЕПРОЧИТАННЫЕ.clear()
        закрытый = двор / "zakrytyj.sh"
        закрытый.write_text('главы="$HERE/../UNIFIED"\n', encoding="utf-8")
        закрытый.chmod(0o000)
        искатели(двор)
        ок = len(НЕПРОЧИТАННЫЕ) == 1 and "не прочитан" in НЕПРОЧИТАННЫЕ[0]
        закрытый.chmod(0o644)
        НЕПРОЧИТАННЫЕ.clear()
        print(("  ок    " if ок else "  ПЛОХО ") + "закрытый файл — находка, а не тишина")
        неудач += 0 if ок else 1

    print(f"ИСКАТЕЛИ ГЛАВ (самотест): путей 9, неудач {неудач}")
    return 0 if неудач == 0 else 1


def main() -> int:
    if "--selftest" in sys.argv:
        return больной_случай()

    беды: list[str] = []
    сколько = 0
    for корень in корни():
        if not корень.is_dir():
            print(f"  ПЛОХО корня {корень} нет — судить нечем")
            беды.append(f"корень {корень} не прочитан")
            continue
        for путь in искатели(корень):
            сколько += 1
            беды.extend(судить(путь))

    беды.extend(НЕПРОЧИТАННЫЕ)
    for одна in беды:
        print(f"  ПЛОХО {одна}")
    print(f"ИСКАТЕЛИ ГЛАВ: судимых файлов {сколько}, бед {len(беды)}")
    return 0 if not беды else 1


if __name__ == "__main__":
    raise SystemExit(main())
