#!/usr/bin/env python3
"""Гейт: функция оболочки, званная выше своего определения, молчит.

Откуда взят. Улика 12.09.2026: в scripts/hooks/session_state.sh функция
«обрезать» вызывалась на строке 62, а определялась на 154. Каждый старт сессии
владелец видел «line 62: обрезать: command not found» и ПУСТОЕ поле «последний
коммит» — так с 11.08.2026, месяц. Ни один сторож не сработал: `bash -n` такой
файл считает законным, а у shellcheck правила на это нет вовсе (проверено на
образце — выдал только SC2005 про лишний echo).

Почему молчит. Оболочка читает файл сверху вниз: на момент вызова имени ещё
нет, вызов уходит в PATH, не находится и печатает ОДНУ строку в stderr.
Подстановка `$(…)` при этом не роняет скрипт — результат просто пустой, и
отказ выглядит как «данных нет», а не как «сломано».

Что ловим: вызов функции ВНЕ тела функций (на верхнем уровне) выше строки, где
она определена. Вызов из тела другой функции законен — тело исполняется
позже, когда определены уже все.

Прогон: python3 scripts/check-function-before-definition.py [--selftest]
"""
import io
import os
import re
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
КАТАЛОГИ = ('scripts', 'harness')

# Отступ допускается: определение ВНУТРИ блока (например, заглушка канала в
# самотесте — `    tg_send() { … }`) — законный bash и именно то, что автор
# хотел: подменить настоящую функцию, определённую ниже. Прежняя редакция
# требовала начала строки и объявляла такую заглушку «вызовом выше
# определения» — краснела на честном коде (12.09.2026).
ОПРЕДЕЛЕНИЕ = re.compile(r'^\s*(?:function\s+)?([^\s()=]+)\s*\(\s*\)\s*\{')
КОНЕЦ_ТЕЛА = re.compile(r'^\s*\}')


def В_ПОЗИЦИИ_КОМАНДЫ(имя):
    """Имя запускается, а не упоминается: слово стоит там, где ждут команду.

    Без этого гейт краснел на здоровом коде — в pre-commit-gate.sh слово «гейт»
    девять раз встречается ВНУТРИ текста сообщений («прошло гейт»), а функция
    с тем же именем определена ниже. Краснящий зря гейт отключают.
    """
    return re.compile(r'(?:^|[;|&(){]|\$\(|`|\bthen\b|\bdo\b|\belse\b)\s*'
                      + re.escape(имя) + r'(?![\w./-])')


def разбор(текст):
    """(определения {имя: строка}, вызовы верхнего уровня, вызовы В ТЕЛАХ).

    Третий ответ появился 26.09.2026. Правило «вызов из тела другой функции
    законен — тело исполняется позже» верно, только если тело и вправду
    исполняется позже. У скрипта с ранним выходом (блок `--selftest`) это не
    так: проба зовёт помощника, помощник зовёт имя, определённое НИЖЕ выхода,
    и оболочка отдаёт 127. В ту ночь проба сторожа сессий зеленела именно от
    127 — «команды нет» она читала как законный ответ «не будить».
    """
    определения, вызовы, в_телах = {}, [], []
    в_теле, чьё_тело = False, None
    for номер, строка in enumerate(текст.split('\n'), 1):
        без_отступа = строка.lstrip()
        if без_отступа.startswith('#'):
            continue
        начало = ОПРЕДЕЛЕНИЕ.match(строка)
        if начало:
            определения.setdefault(начало.group(1), номер)
            # Однострочное определение `f() { …; }` тело не открывает.
            в_теле = not строка.rstrip().endswith('}')
            чьё_тело = начало.group(1) if в_теле else None
            continue
        if в_теле:
            if КОНЕЦ_ТЕЛА.match(строка):
                в_теле, чьё_тело = False, None
            else:
                в_телах.append((чьё_тело, номер, строка))
            continue
        вызовы.append((номер, строка))
    return определения, вызовы, в_телах


# Подключение библиотеки: `source <путь>` или `. <путь>`. Путь часто собран
# через $(dirname "$(readlink -f "${BASH_SOURCE[0]}")") — берём ХВОСТ после
# последней закрывающей скобки, остальное подставляет оболочка.
# Берётся ВЕСЬ хвост строки: путь почти всегда собран подстановкой с
# пробелами внутри ($(dirname "$(readlink -f …)")), и класс «без пробелов»
# обрезал бы его на первом же слове.
ПОДКЛЮЧЕНИЕ = re.compile(r'^\s*(?:source|\.)\s+(\S.*)$')


# Присваивание пути переменной: `KONF_SH="$DIR/../../scripts/lib/config.sh"`.
# Так пишут, когда путь ищут в двух раскладках, и тогда в строке подключения
# стоит только имя переменной.
ПРИСВАИВАНИЕ = re.compile(r'^\s*(\w+)=(.+)$')


def _хвост_пути(строка: str) -> str:
    """Литеральный хвост пути: подстановки оболочки отбрасываются."""
    s = строка.strip().strip('"\'')
    if ')/' in s:                      # $(dirname …)/lib/pane.sh
        s = s.rsplit(')/', 1)[-1]
    совпало = re.match(r'^\$\{?\w+\}?/(.+)$', s)
    if совпало:                        # $WARDEN_DIR/../scripts/lib/config.sh
        s = совпало.group(1)
    return s.strip('"\'')


def _имена_библиотеки(путь_строки: str, откуда: str | None,
                      текст: str = "") -> list:
    """Имена функций подключаемого файла, или [] — путь не разобрать/не прочесть."""
    хвост = _хвост_пути(путь_строки)
    # В строке подключения одно имя переменной — ищем её присваивание выше.
    только_имя = re.match(r'^\$\{?(\w+)\}?$', хвост)
    if только_имя and текст:
        for строка in текст.split('\n'):
            совпало = ПРИСВАИВАНИЕ.match(строка)
            if совпало and совпало.group(1) == только_имя.group(1):
                имена = _имена_библиотеки(совпало.group(2), откуда)
                if имена:
                    return имена
        return []
    if not хвост.endswith('.sh'):
        return []
    кандидаты = []
    if откуда:
        кандидаты.append(os.path.join(os.path.dirname(os.path.abspath(откуда)), хвост))
    кандидаты += [os.path.join(КОРЕНЬ, хвост),
                  os.path.join(КОРЕНЬ, 'scripts', хвост)]
    for кандидат in (os.path.normpath(к) for к in кандидаты):
        if os.path.isfile(кандидат):
            текст = io.open(кандидат, encoding='utf-8', errors='replace').read()
            return [ОПРЕДЕЛЕНИЕ.match(с).group(1) for с in текст.split('\n')
                    if ОПРЕДЕЛЕНИЕ.match(с)]
    return []


def находки_в(текст, путь=None):
    определения, вызовы, в_телах = разбор(текст)
    # БОЛЬНОЙ СЛУЧАЙ 17.10.2026: семь строк нажатий в панель переехали в общую
    # библиотеку (scripts/lib/pane.sh), диспетчер канала стал её подключать — и
    # гейт назвал его вызовы «выше определения», потому что в файле осталась
    # только ЗАГЛУШКА самотеста. Имя, пришедшее подключением, определено на
    # строке подключения.
    for номер, строка in вызовы:
        подключение = ПОДКЛЮЧЕНИЕ.match(строка)
        if подключение:
            for имя in _имена_библиотеки(подключение.group(1), путь, текст):
                # Не setdefault: заглушка самотеста НИЖЕ уже заняла имя, а
                # настоящее определение пришло подключением ВЫШЕ — побеждает
                # раннее, иначе вызов между ними читается как «выше определения».
                if определения.get(имя, len(текст)) > номер:
                    определения[имя] = номер
    если_нет = []
    for номер, строка in вызовы:
        for имя, где in определения.items():
            if где <= номер:
                continue
            if В_ПОЗИЦИИ_КОМАНДЫ(имя).search(строка):
                если_нет.append((номер, имя, где, строка.strip()[:120]))
                break
    # Когда ТЕЛО исполняется раньше определения. Функция, позванная на верхнем
    # уровне в строке N, исполняет своё тело именно там; всё, что она зовёт и
    # что определено НИЖЕ N, на момент вызова не существует.
    позвана_на = {}
    for номер, строка in вызовы:
        for имя in определения:
            if В_ПОЗИЦИИ_КОМАНДЫ(имя).search(строка):
                позвана_на.setdefault(имя, номер)
    for хозяин, номер, строка in в_телах:
        когда = позвана_на.get(хозяин)
        if когда is None:
            continue                      # тело не исполняется раньше — правило прежнее
        for имя, где in определения.items():
            if где <= когда or имя == хозяин:
                continue
            if В_ПОЗИЦИИ_КОМАНДЫ(имя).search(строка):
                если_нет.append((номер, имя, где, строка.strip()[:120]))
                break
    return если_нет


def файлы_репозитория():
    for каталог in КАТАЛОГИ:
        корень = os.path.join(КОРЕНЬ, каталог)
        if not os.path.isdir(корень):
            continue
        for путь, каталоги, имена in os.walk(корень):
            каталоги[:] = [d for d in каталоги if d not in ('.git', '__pycache__')]
            for имя in sorted(имена):
                if имя.endswith('.sh'):
                    yield os.path.join(путь, имя)


def самотест():
    случаи = [
        ('echo "$(обрезать 80)"\nобрезать() {\n  cat\n}\n', 1,
         'БОЛЬНОЙ СЛУЧАЙ: ровно session_state.sh — вызов на 1-й строке, определение на 2-й'),
        ('обрезать() {\n  cat\n}\necho "$(обрезать 80)"\n', 0,
         'определение выше вызова — здоровый код'),
        ('внешняя() {\n  поздняя 1\n}\nпоздняя() {\n  echo 1\n}\nвнешняя\n', 0,
         'вызов из ТЕЛА другой функции законен: тело исполняется позже'),
        ('say "привет"\nsay() { echo "$1"; }\n', 1,
         'однострочное определение ниже вызова — тот же отказ'),
        ('echo "функция обрезать описана ниже"\nобрезать() {\n  cat\n}\n', 0,
         'БОЛЬНОЙ СЛУЧАЙ 2: имя внутри ТЕКСТА сообщения — не вызов (девять таких в pre-commit-gate.sh)'),
        ('echo "$(git log -1 | обрезать 80)"\nобрезать() {\n  cat\n}\n', 1,
         'вызов за конвейером внутри подстановки — настоящий, ловим'),
        ('гейт "имена" python3 x.py\nгейт() { \"$@\"; }\n', 1,
         'вызов первым словом строки — настоящий'),
        ('вызов_потом() { echo 1; }\nвызов_потом\n', 0,
         'вызов сразу после определения — здоровый код'),
        ('if true; then\n    tg_send() { echo "$1"; }\n    tg_send "проба"\nfi\ntg_send() { curl -s x; }\n', 0,
         'ЛОЖНОЕ СРАБАТЫВАНИЕ: заглушка с отступом внутри блока — подмена, а не вызов выше определения'),
        # БОЛЬНОЙ СЛУЧАЙ 26.09.2026: тело исполняется РАНЬШЕ определения.
        ('проба() {\n  поздняя 1\n}\nпроба\nпоздняя() { echo 1; }\n', 1,
         'БОЛЬНОЙ СЛУЧАЙ 26.09: тело позвано выше определения того, что оно зовёт'),
        ('проба() {\n  поздняя 1\n}\nпоздняя() { echo 1; }\nпроба\n', 0,
         'то же тело, но позвано НИЖЕ определения — здоровый код'),
        # БОЛЬНОЙ СЛУЧАЙ 17.10.2026: функция пришла ПОДКЛЮЧЕНИЕМ библиотеки, а
        # в файле осталась только заглушка самотеста ниже вызовов.
        ('source "$(dirname "$0")/lib/pane.sh"\nsend_to_pane "проба"\n'
         'if true; then\n    send_to_pane() { echo "$1"; }\nfi\n', 0,
         'БОЛЬНОЙ СЛУЧАЙ 17.10: имя пришло подключением библиотеки — не отказ'),
        ('source "$(dirname "$0")/lib/net-takoj-biblioteki.sh"\nне_та "проба"\n'
         'не_та() { echo 1; }\n', 1,
         'подключение НЕ той библиотеки имя не оправдывает — отказ прежний'),
        # Путь к библиотеке лежит в ПЕРЕМЕННОЙ: так пишут, когда её ищут в двух
        # раскладках (пакет и разложенный проект).
        ('KONF_SH="$(dirname "$0")/lib/pane.sh"\nsource "$KONF_SH"\n'
         'send_to_pane "проба"\nsend_to_pane() { echo "$1"; }\n', 0,
         'БОЛЬНОЙ СЛУЧАЙ 17.10: путь библиотеки в переменной — имя всё равно найдено'),
    ]
    ok = True
    for текст, ждём, зачем in случаи:
        было = len(находки_в(текст))
        if было != ждём:
            ok = False
        print('  %s %s (находок %d, ждали %d)' % ('ок   ' if было == ждём else 'ПЛОХО', зачем, было, ждём))
    print('САМОТЕСТ %s: %d путей, первым — больной случай'
          % ('ПРОЙДЕН' if ok else 'ПРОВАЛЕН', len(случаи)))
    return 0 if ok else 1


def main():
    if '--selftest' in sys.argv:
        return самотест()
    всего = 0
    for путь in файлы_репозитория():
        текст = io.open(путь, encoding='utf-8', errors='replace').read()
        for номер, имя, где, строка in находки_в(текст, путь):
            всего += 1
            print('%s:%d  «%s» определена ниже, на строке %d:  %s'
                  % (os.path.relpath(путь, КОРЕНЬ), номер, имя, где, строка))
    if всего:
        print('[функция до определения] КРАСНЫЙ: %d вызов(ов) выше определения — оболочка '
              'напечатает «command not found» в stderr и вернёт ПУСТО, отказ выглядит как '
              '«данных нет». Перенесите определение выше первого вызова' % всего)
        return 1
    print('[функция до определения] чисто: функции определены выше своих вызовов')
    return 0


if __name__ == '__main__':
    sys.exit(main())
