ЮНИТЫ = _путь("HARNESS_LIVE_CHECK_UNITS", "harness", "config", "live-check-units.yaml")

# Сколько знаков делают цитату из следа ДОКАЗАТЕЛЬСТВОМ. Короче — это общее
# слово («ок», «отказов»), какое найдётся в любом выводе (спека §3.2 п.2).
ЦИТАТА_ЗНАКОВ = 12

ИСХОДЫ = ("ок", "косяк", "не-проверяемо", "ждёт")

# Классы живой проверки — спека §3.1. Список ЗАКРЫТ: опечатка в имени («A1»
