#!/usr/bin/env python3
"""Собирает список живой проверки механизмов: реестр + состояние проверки.

Владелец 15.10.2026: «проверить каждый механизм, каждого демона, каждый хук,
каждый скрипт, проверить не просто тестами, а именно наживую, в практике.
Тщательно, достоверно. Сейчас очень много косяков и недоработок».

Откуда берутся строки. Список механизмов — ТОЛЬКО из реестра
(`harness/config/mechanisms.yaml`): свой список в приборе разошёлся бы с
реестром молча, и «проверено всё» означало бы «проверено всё, что я помню»
(та же беда, что у гейтов, чья область перечислена именем —
[[gate-scope-listed-by-name-goes-blind]]). Состояние живой проверки — из
`harness/config/live-check-state.yaml`, который правит проверяющий.

Чем живая проверка отличается от самотеста. Самотест проверяет то, о чём
догадался автор; живая — работу механизма в настоящей системе. Поэтому в
документе ДВЕ разные графы: «проверяется» из реестра (команда автора) и
«живьём» из состояния (что сделали руками и что увидели).

Прогон:
    python3 scripts/build-live-check-list.py            # собрать документ
    python3 scripts/build-live-check-list.py --проверить  # документ сходится?
    python3 scripts/build-live-check-list.py --числа     # числа и разрез по классам
    python3 scripts/build-live-check-list.py --проба     # счёт закрыт работой?
    python3 scripts/build-live-check-list.py --данные    # то же, что --проверить, но без сверки документа
Код возврата: 0 — собран (или сходится), 1 — документ разошёлся с данными.
"""
from __future__ import annotations

import os
import pathlib
import re
import sys

import yaml

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent


def _путь(ключ: str, *куски: str) -> pathlib.Path:
    """Путь из окружения, иначе боевой. Окружение СТАРШЕ файла: без этого
    проба судит производство, а не свой двор (улика 12.09.2026 — подстановка
    переменных поверх живого конфига увела «/model» в рабочую панель)."""
    задано = os.environ.get(ключ)
    return pathlib.Path(задано) if задано else КОРЕНЬ.joinpath(*куски)


РЕЕСТР = _путь("HARNESS_MECHANISMS", "harness", "config", "mechanisms.yaml")
СОСТОЯНИЕ = _путь("HARNESS_LIVE_CHECK_STATE", "harness", "config", "live-check-state.yaml")
КЛАССЫ = _путь("HARNESS_LIVE_CHECK_CLASSES", "harness", "config", "live-check-classes.yaml")
ДОКУМЕНТ = _путь("HARNESS_LIVE_CHECK_DOC", "docs", "живая-проверка-механизмов.md")
# Карта нужна, чтобы судить ссылку на карточку косяка: «найдено и заведено»
# без существующего id — это обещание, а не находка.
КАРТА = _путь("HARNESS_DEVMAP", "dev-map.yaml")
# Связь «проба → механизм» класса D: прогон пробы доказывает, что проба
# РАБОТАЕТ, но не что она ловит поломку. Носитель назван в данных.
МУТАЦИИ_ПРОБ = _путь("HARNESS_PROBE_MUTATIONS", "harness", "config",
                     "probe-mutations.yaml")
# Второй носитель той же связи: у инварианта мутация стоит в МЕХАНИЗМЕ, а
