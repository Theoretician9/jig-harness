#!/usr/bin/env python3
"""Собирает список живой проверки механизмов: реестр + состояние проверки.

Владелец 15.10.2026: «проверить каждый механизм, каждого демона, каждый хук,
каждый скрипт, проверить не просто тестами, а именно наживую, в практике.
Тщательно, достоверно. Сейчас очень много косяков и недоработок».

Откуда берутся строки. Список механизмов — ТОЛЬКО из реестра
(`harness/config/mechanisms.yaml`): свой список в приборе разошёлся бы с
реестром молча, и «проверено всё» означало бы «проверено всё, что я помню»
(та же беда, что у гейтов, чья область перечислена именем —
[[gate-scope-listed-by-name-goes-blind]]). Состояние живой проверки — из
`harness/config/live-check-state.yaml`, который правит проверяющий.

Чем живая проверка отличается от самотеста. Самотест проверяет то, о чём
догадался автор; живая — работу механизма в настоящей системе. Поэтому в
документе ДВЕ разные графы: «проверяется» из реестра (команда автора) и
«живьём» из состояния (что сделали руками и что увидели).

Прогон:
    python3 scripts/build-live-check-list.py            # собрать документ
    python3 scripts/build-live-check-list.py --проверить  # документ сходится?
    python3 scripts/build-live-check-list.py --числа     # числа и разрез по классам
Код возврата: 0 — собран (или сходится), 1 — документ разошёлся с данными.
"""
from __future__ import annotations

import os
import pathlib
import sys

import yaml

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent


def _путь(ключ: str, *куски: str) -> pathlib.Path:
    """Путь из окружения, иначе боевой. Окружение СТАРШЕ файла: без этого
    проба судит производство, а не свой двор (улика 12.09.2026 — подстановка
    переменных поверх живого конфига увела «/model» в рабочую панель)."""
    задано = os.environ.get(ключ)
    return pathlib.Path(задано) if задано else КОРЕНЬ.joinpath(*куски)


РЕЕСТР = _путь("HARNESS_MECHANISMS", "harness", "config", "mechanisms.yaml")
СОСТОЯНИЕ = _путь("HARNESS_LIVE_CHECK_STATE", "harness", "config", "live-check-state.yaml")
КЛАССЫ = _путь("HARNESS_LIVE_CHECK_CLASSES", "harness", "config", "live-check-classes.yaml")
ДОКУМЕНТ = _путь("HARNESS_LIVE_CHECK_DOC", "docs", "живая-проверка-механизмов.md")

ИСХОДЫ = ("ок", "косяк", "не-проверяемо", "ждёт")

# Классы живой проверки — спека §3.1. Список ЗАКРЫТ: опечатка в имени («A1»
# латиницей против «А1» кириллицей) на глаз неотличима, а разрез по ней молча
# завёл бы восьмой класс.
КЛАССЫ_ДОПУСТИМЫЕ = ("A1", "A2", "B1", "B2", "C1", "C2", "C3", "D", "E")
# Класс, который обязан называть причину: ярлык «опасный» без причины ничего
# не запрещает, а проверяющему нужно знать, ЧЕМ он опасен.
КЛАССЫ_С_ПРИЧИНОЙ = ("C3",)


def механизмы() -> list[dict]:
    данные = yaml.safe_load(РЕЕСТР.read_text())
    return данные if isinstance(данные, list) else данные.get("механизмы", [])


def состояние() -> dict:
    данные = yaml.safe_load(СОСТОЯНИЕ.read_text()) or {}
    return данные.get("проверено") or {}


def неизвестные_ключи(меха: list[dict], сост: dict) -> list[str]:
    """Ключи состояния, которых НЕТ в реестре. Молчать о них нельзя: имя файла
    механизма в этом проекте меняется часто, и счётчик по имени при
    переименовании слепнет — живая проверка превращается в «не трогал» без
    единого слова (находка ревью 15.10.2026). Соседний build-watch-periods.py
    называет расхождение поимённо, и здесь то же правило."""
    известные = {м.get("файл") for м in меха}
    return sorted(k for k in сост if k not in известные)


def классы() -> dict:
    """Класс каждого механизма. Нет файла — пустой словарь: прибор тогда
    назовёт поимённо ВСЕ механизмы без класса, а не промолчит."""
    if not КЛАССЫ.exists():
        return {}
    данные = yaml.safe_load(КЛАССЫ.read_text()) or {}
    return данные.get("классы") or {}


def беды_классов(меха: list[dict], кл: dict) -> list[str]:
    """Что не так с классами — поимённо и по-русски.

    Пустая строка и None считаются ОТСУТСТВИЕМ класса: «ключ есть» проходит
    проверку наличия и даёт зелёный счёт без работы — так уже краснел гейт
    чистоты с пустыми данными."""
    беды = []
    известные = {м.get("файл") for м in меха}
    for м in меха:
        файл = м.get("файл")
        запись = кл.get(файл) or {}
        имя = (запись.get("класс") or "").strip()
        if not имя:
            беды.append(f"класса нет: {файл}")
        elif имя not in КЛАССЫ_ДОПУСТИМЫЕ:
            беды.append(f"класс «{имя}» неизвестен: {файл}")
        elif имя in КЛАССЫ_С_ПРИЧИНОЙ and not (запись.get("причина") or "").strip():
            беды.append(f"класс {имя} без причины: {файл}")
    for файл in sorted(кл):
        if файл not in известные:
            беды.append(f"класс у ключа вне реестра (переименовали?): {файл}")
    return беды


def разрез(меха: list[dict], кл: dict) -> dict:
    """Сколько механизмов в каждом классе. Сумма обязана равняться числу
    механизмов — иначе фазы спеки считаются по одному списку, а работа идёт
    по другому."""
    итог = {и: 0 for и in КЛАССЫ_ДОПУСТИМЫЕ}
    итог["без класса"] = 0
    for м in меха:
        имя = ((кл.get(м.get("файл")) or {}).get("класс") or "").strip()
        итог[имя if имя in итог else "без класса"] += 1
    return итог


def числа(меха: list[dict], сост: dict) -> dict:
    итог = {и: 0 for и in ИСХОДЫ}
    итог["не трогал"] = 0
    for м in меха:
        запись = сост.get(м.get("файл"))
        исход = (запись or {}).get("исход")
        if исход in итог:
            итог[исход] += 1
        else:
            итог["не трогал"] += 1
    итог["всего"] = len(меха)
    return итог


def строка_таблицы(м: dict, сост: dict) -> str:
    запись = сост.get(м.get("файл")) or {}
    исход = запись.get("исход") or "—"
    живьём = (запись.get("живьём") or "").replace("|", "\\|").strip()
    увидели = (запись.get("увидели") or "").replace("|", "\\|").strip()
    находка = (запись.get("находка") or "").replace("|", "\\|").strip()
    когда = запись.get("когда") or ""
    проверяется = str(м.get("проверяется") or "—").replace("|", "\\|").strip()
    клетка = " · ".join(ч for ч in (живьём, увидели) if ч) or "—"
    if находка:
        клетка += f" · НАХОДКА: {находка}"
    return (f"| `{м.get('файл')}` | {м.get('имя')} | {проверяется} "
            f"| {клетка} | {исход} | {когда} |\n")


def собрать() -> str:
    меха = механизмы()
    сост = состояние()
    ч = числа(меха, сост)
    куски = [
        "# Живая проверка механизмов харнеса\n\n",
        "> Документ СОБИРАЕТСЯ прибором `scripts/build-live-check-list.py` из\n"
        "> реестра механизмов и `harness/config/live-check-state.yaml`.\n"
        "> Руками не править: следующая сборка перезапишет, а\n"
        "> `--проверить` краснеет меж тем.\n\n",
        "Владелец 15.10.2026: «проверить каждый механизм, каждого демона, каждый\n"
        "хук, каждый скрипт, проверить не просто тестами, а именно наживую, в\n"
        "практике. Тщательно, достоверно. Сейчас очень много косяков и\n"
        "недоработок».\n\n",
        "## Чем живая проверка отличается от самотеста\n\n",
        "Самотест проверяет то, о чём догадался его автор. Живая проверка —\n"
        "работу механизма в настоящей системе: его позвали так, как его зовёт\n"
        "жизнь, и посмотрели, что он СДЕЛАЛ. Поэтому в таблице две разные\n"
        "графы: «проверяется» — команда из реестра, «живьём» — что сделали\n"
        "руками и что увидели.\n\n",
        "## Числа\n\n",
        f"| всего | ок | косяк | не-проверяемо | ждёт | не трогал |\n",
        "|---|---|---|---|---|---|\n",
        f"| {ч['всего']} | {ч['ок']} | {ч['косяк']} | {ч['не-проверяемо']} "
        f"| {ч['ждёт']} | {ч['не трогал']} |\n\n",
    ]
    по_видам: dict[str, list[dict]] = {}
    for м in меха:
        по_видам.setdefault(м.get("вид") or "без вида", []).append(м)
    for вид in sorted(по_видам, key=lambda в: (-len(по_видам[в]), в)):
        группа = по_видам[вид]
        проверено = sum(1 for м in группа
                        if (сост.get(м.get("файл")) or {}).get("исход"))
        куски.append(f"## {вид} — {len(группа)}, живьём проверено {проверено}\n\n")
        куски.append("| файл | имя | проверяется (самотест) | живьём: что сделали и что увидели | исход | когда |\n")
        куски.append("|---|---|---|---|---|---|\n")
        for м in sorted(группа, key=lambda м: str(м.get("файл"))):
            куски.append(строка_таблицы(м, сост))
        куски.append("\n")
    return "".join(куски)


def main() -> int:
    чужие = неизвестные_ключи(механизмы(), состояние())
    if чужие:
        print("[живая проверка] ✗ в состоянии есть механизмы, которых нет в "
              "реестре — переименовали файл? живая проверка по этим ключам "
              "никем не считается:", file=sys.stderr)
        for k in чужие:
            print(f"    {k}", file=sys.stderr)
        return 1
    собранный = собрать()
    if "--числа" in sys.argv:
        меха = механизмы()
        ч = числа(меха, состояние())
        print(f"[живая проверка] всего {ч['всего']}: ок {ч['ок']}, "
              f"косяк {ч['косяк']}, не-проверяемо {ч['не-проверяемо']}, "
              f"ждёт {ч['ждёт']}, не трогал {ч['не трогал']}")
        кл = классы()
        р = разрез(меха, кл)
        print("[живая проверка] классы: " + ", ".join(
            f"{к}: {р[к]}" for к in (*КЛАССЫ_ДОПУСТИМЫЕ, "без класса")))
        беды = беды_классов(меха, кл)
        if беды:
            print(f"[живая проверка] ✗ класс решает, ЧТО считать живой "
                  f"проверкой; бед {len(беды)}:", file=sys.stderr)
            for б in беды[:20]:
                print(f"    {б}", file=sys.stderr)
            if len(беды) > 20:
                print(f"    …и ещё {len(беды) - 20}", file=sys.stderr)
            return 1
        return 0
    if "--проверить" in sys.argv:
        если_есть = ДОКУМЕНТ.read_text() if ДОКУМЕНТ.exists() else ""
        if если_есть == собранный:
            ч = числа(механизмы(), состояние())
            print(f"[живая проверка] документ сходится с данными: механизмов "
                  f"{ч['всего']}, живьём проверено "
                  f"{ч['всего'] - ч['не трогал']}")
            return 0
        print("[живая проверка] ✗ документ разошёлся с реестром или состоянием "
              "(правили руками?) — пересобрать: "
              "python3 scripts/build-live-check-list.py", file=sys.stderr)
        return 1
    ДОКУМЕНТ.write_text(собранный)
    ч = числа(механизмы(), состояние())
    # Путь печатается коротким, если он внутри дерева, и целиком, если нет:
    # relative_to на чужом пути БРОСАЕТ, и прибор падал трассой ПОСЛЕ успешной
    # записи документа — то есть работа сделана, а ответ выглядит поломкой
    # (ревью 17.10, F-gen-10; своя же проба Task 2 на этом и встала).
    где = ДОКУМЕНТ.relative_to(КОРЕНЬ) if ДОКУМЕНТ.is_relative_to(КОРЕНЬ) else ДОКУМЕНТ
    print(f"{где}: собран, механизмов {ч['всего']}, "
          f"живьём проверено {ч['всего'] - ч['не трогал']}, косяков {ч['косяк']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
