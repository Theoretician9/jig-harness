# не запрещает, а проверяющему нужно знать, ЧЕМ он опасен.
КЛАССЫ_С_ПРИЧИНОЙ = ("C3",)


def механизмы() -> list[dict]:
    данные = yaml.safe_load(РЕЕСТР.read_text())
    return данные if isinstance(данные, list) else данные.get("механизмы", [])


def состояние() -> dict:
    данные = yaml.safe_load(СОСТОЯНИЕ.read_text()) or {}
    return данные.get("проверено") or {}


def неизвестные_ключи(меха: list[dict], сост: dict) -> list[str]:
    """Ключи состояния, которых НЕТ в реестре. Молчать о них нельзя: имя файла
    механизма в этом проекте меняется часто, и счётчик по имени при
    переименовании слепнет — живая проверка превращается в «не трогал» без
    единого слова (находка ревью 15.10.2026). Соседний build-watch-periods.py
    называет расхождение поимённо, и здесь то же правило."""
    известные = {м.get("файл") for м in меха}
    return sorted(k for k in сост if k not in известные)


def классы() -> dict:
    """Класс каждого механизма. Нет файла — пустой словарь: прибор тогда
    назовёт поимённо ВСЕ механизмы без класса, а не промолчит."""
    if not КЛАССЫ.exists():
        return {}
    данные = yaml.safe_load(КЛАССЫ.read_text()) or {}
    return данные.get("классы") or {}


def беды_классов(меха: list[dict], кл: dict) -> list[str]:
    """Что не так с классами — поимённо и по-русски.

    Пустая строка и None считаются ОТСУТСТВИЕМ класса: «ключ есть» проходит
    проверку наличия и даёт зелёный счёт без работы — так уже краснел гейт
    чистоты с пустыми данными."""
    беды = []
    известные = {м.get("файл") for м in меха}
    for м in меха:
        файл = м.get("файл")
        запись = кл.get(файл) or {}
        имя = (запись.get("класс") or "").strip()
        if not имя:
            беды.append(f"класса нет: {файл}")
        elif имя not in КЛАССЫ_ДОПУСТИМЫЕ:
            беды.append(f"класс «{имя}» неизвестен: {файл}")
        elif имя in КЛАССЫ_С_ПРИЧИНОЙ and not (запись.get("причина") or "").strip():
            беды.append(f"класс {имя} без причины: {файл}")
    for файл in sorted(кл):
        if файл not in известные:
            беды.append(f"класс у ключа вне реестра (переименовали?): {файл}")
    return беды


def разрез(меха: list[dict], кл: dict) -> dict:
    """Сколько механизмов в каждом классе. Сумма обязана равняться числу
    механизмов — иначе фазы спеки считаются по одному списку, а работа идёт
    по другому."""
    итог = {и: 0 for и in КЛАССЫ_ДОПУСТИМЫЕ}
    итог["без класса"] = 0
    for м in меха:
        имя = ((кл.get(м.get("файл")) or {}).get("класс") or "").strip()
        итог[имя if имя in итог else "без класса"] += 1
    return итог


def числа(меха: list[dict], сост: dict) -> dict:
    итог = {и: 0 for и in ИСХОДЫ}
    итог["не трогал"] = 0
    for м in меха:
        запись = сост.get(м.get("файл"))
        исход = (запись or {}).get("исход")
        if исход in итог:
            итог[исход] += 1
        else:
            итог["не трогал"] += 1
    итог["всего"] = len(меха)
    return итог


def беды_счёта(меха: list[dict], сост: dict) -> list[str]:
    """Что мешает закрыть счёт живой проверки — поимённо и по-русски.

    Это `проверка:` карточки задачи (спека §5, Ф4): счёт нельзя закрыть, пока
    есть нетронутые механизмы. Три беды, и каждая называет СВОЮ причину —
    отказ по одному коду возврата неотличим от отказа по другому.

    ПОЧЕМУ «ждёт» НЕ ПРОВЕРЕН. `числа()` кладёт его в свой исход, а документ
    печатает «живьём проверено» как «всего минус не трогал» — то есть счёт
    закрывался бы чужим словом, которого никто не сказал, и работы за ним нет
    никакой. Для счёта «ждёт» — это долг, а не проверка.

    ПОЧЕМУ «косяк» ПРОВЕРЕН. Механизм позвали, увидели поломку и завели
    карточку: работа сделана, а то, что механизм плох, счёт живой проверки не
    отменяет.
    """
    беды = []
    причины = причины_непроверяемого()
    for м in меха:
        файл = м.get("файл")
        запись = сост.get(файл) or {}
        исход = (запись.get("исход") or "").strip()
        if not исход:
            беды.append(f"не трогал: {файл}")
        elif исход == "ждёт":
            беды.append(f"ждёт чужого слова, проверкой не считается: {файл}")
        elif исход == "не-проверяемо":
            # Причина судится ТЕМ ЖЕ списком из данных, что у «--проверить»:
            # два предиката на один вопрос расходятся молча.
            if not причины:
                беды.append(f"не-проверяемо, а списка причин в данных нет: {файл}")
            elif not any(п in (запись.get("увидели") or "") for п in причины):
                беды.append(f"не-проверяемо по причине вне списка: {файл}")
    return беды


def строка_таблицы(м: dict, сост: dict) -> str:
    запись = сост.get(м.get("файл")) or {}
    исход = запись.get("исход") or "—"
    живьём = (запись.get("живьём") or "").replace("|", "\\|").strip()
    увидели = (запись.get("увидели") or "").replace("|", "\\|").strip()
    находка = (запись.get("находка") or "").replace("|", "\\|").strip()
    когда = запись.get("когда") or ""
    проверяется = str(м.get("проверяется") or "—").replace("|", "\\|").strip()
    клетка = " · ".join(ч for ч in (живьём, увидели) if ч) or "—"
    if находка:
        клетка += f" · НАХОДКА: {находка}"
    return (f"| `{м.get('файл')}` | {м.get('имя')} | {проверяется} "
            f"| {клетка} | {исход} | {когда} |\n")


def причины_непроверяемого() -> list:
    """Закрытый список причин «не-проверяемо» — ИЗ ДАННЫХ рядом с классами.

    Пустой список означает «судить нечем», а не «всё законно»: именно пустые
    данные однажды сделали гейт чистоты зелёным на месяц.
    """
    if not КЛАССЫ.exists():
        return []
    данные = yaml.safe_load(КЛАССЫ.read_text()) or {}
    return [str(п).strip() for п in (данные.get("причины_непроверяемого") or [])
            if str(п).strip()]


def пробы_с_мутацией() -> set | None:
    """Файлы проб, у которых мутация НАЗВАНА в данных, — из обоих носителей.

    None и пустое множество — РАЗНЫЕ факты: None значит «ни одного носителя нет
    на диске, судить нечем», и молчать об этом нельзя
    ([[unreadable-source-turns-check-green]]).

    Из invariants.yaml пробу называет команда «доказательство»: мутация стоит в
    механизме (`файл`), а покраснеть обязана та команда. Имя пробы берётся
    ОТДЕЛЬНЫМ словом команды, не подстрокой: подстрока зачла бы `test_a.py` за
    доказанную по команде, зовущей `test_a.py.bak`.
    """
    sys.path.insert(0, str(КОРЕНЬ / "scripts" / "lib"))
    import probe_coverage                                 # noqa: PLC0415
    return probe_coverage.covered_probes(МУТАЦИИ_ПРОБ, ИНВАРИАНТЫ)


def _слово_владельца(имя: str) -> pathlib.Path:
    """Файл записанного сообщения владельца. Каталог журналов — из окружения
    (HARNESS_LOG_DIR старше конфига), иначе боевой."""
    журналы = os.environ.get("HARNESS_LOG_DIR")
    if not журналы:
        sys.path.insert(0, str(КОРЕНЬ / "scripts" / "lib"))
        import config as конф                             # noqa: PLC0415
        журналы = конф.log_dir()
    return pathlib.Path(журналы) / "inbox" / "обработано" / имя


def _названы_зовущие() -> set:
    """Механизмы, чей приговор читается в журнале ЗОВУЩЕГО. Данных нет —
    пустое множество: тогда об этом говорится отказом, а не молчанием."""
    if not ЮНИТЫ.is_file():
        return set()
    прочтено = yaml.safe_load(ЮНИТЫ.read_text(encoding="utf-8")) or {}
    юниты = прочтено.get("юниты") or {}
    return {м for м, з in юниты.items() if isinstance(з, dict) and з.get("зовёт")}


def беды_предиката_b2(файл: str, запись: dict) -> list[str]:
    """Класс B2 (спека §3.1): прогнан на ЗАПИСАННОМ слове владельца.

    ЗАЧЕМ. Предикат класса B2 не судил никто: запись «прогон на живых
    формулировках владельца» проходила общий след §3.2, а чьи это слова —
    проверяющего или владельца — не спрашивалось. Подделать входящее нельзя
    только пока улику ищут в каталоге диспетчера, а не в словах записи.
    """
    входящее = (запись.get("входящее") or "").strip()
    if not входящее:
        if файл in _названы_зовущие():
            return []
        return [f"{файл}: обработчик входящих, а записанного слова владельца "
                f"запись не называет — нужно поле «входящее» (файл из "
                f"inbox/обработано) либо имя механизма в {ЮНИТЫ.name} с полем "
                f"«зовёт» (спека §3.1, класс B2)"]
    слово = _слово_владельца(входящее)
    if not слово.is_file():
        return [f"{файл}: названного входящего «{входящее}» нет в "
                f"{слово.parent} — слово владельца не подтверждается"]
    путь_следа = (запись.get("след") or "").strip()
    if путь_следа:
        текст = _файл_следа(путь_следа)
        if текст.is_file() and f"входящее: {входящее}" not in текст.read_text(errors="replace"):
            return [f"{файл}: след {путь_следа} не называет входящее "
                    f"«{входящее}» — имя приписано к следу, а не взято из прогона"]
    return []


def беды_предиката_класса(файл: str, класс: str, запись: dict,
                          мутации: set | None) -> list[str]:
    """Требования §3.1 — предикат СВОЕГО класса, а не общий след §3.2.

    ЗАЧЕМ. Класс лежал в данных, а предикат класса не судил НИКТО: 17.10.2026
    за одну смену 48 гейтов-судей были записаны по ОДНОМУ зелёному прогону,
    хотя спека говорит «одного зелёного мало», и 55 проб — по факту своего
    прогона, который доказывает лишь, что проба работает. Запись выглядела
    доказанной, потому что доказан был ДРУГОЙ, слабейший предикат.

    Судятся классы, у которых есть машинный признак: C1 — больной случай со
    своим следом, D — мутация в данных, B2 — записанное слово владельца.
    Остальные (A1 — журнал кронового прогона, B1 — перехваченное действие,
    E — запись журнала скилов) ждут своих носителей и названы в спеке §3.1.
    """
    # Требование КЛАССА — про притязание «ок». Исход «косяк» доказывает ДЕФЕКТ,
    # и больной случай в нём — сам живой вызов: «одного зелёного мало» сказано
    # о зелёном, а не о находке. Без этого различения пересуд 17.10 снял бы и
    # две настоящие находки той же смены.
    if (запись.get("исход") or "").strip() != "ок":
        return []
    беды = []
    if класс == "C1":
        больной = (запись.get("больной") or "").strip()
        путь_больного = (запись.get("след_больного") or "").strip()
        if not больной:
            беды.append(f"{файл}: гейт-судья, а больного случая нет — одного "
                        f"зелёного мало (спека §3.1, класс C1)")
        elif not путь_больного:
            беды.append(f"{файл}: больной случай назван, а след больного случая "
                        f"не указан — своё слово доказательством не считается")
        else:
            файл_следа = _файл_следа(путь_больного)
            if not файл_следа.is_file():
                беды.append(f"{файл}: следа больного случая нет на диске: "
                            f"{путь_больного}")
            else:
                текст = файл_следа.read_text(errors="replace")
                if not _есть_шапка(текст):
                    беды.append(f"{файл}: в следе больного случая {путь_больного} "
                                f"нет шапки обёртки — он написан не scripts/live-check.sh")
                elif not _цитата_из_следа(больной, текст):
                    беды.append(f"{файл}: «больной» не цитирует след больного случая "
                                f"ДОСЛОВНО (нужна подстрока от {ЦИТАТА_ЗНАКОВ} знаков)")
    elif класс == "B2":
        беды += беды_предиката_b2(файл, запись)
    elif класс == "D":
        if мутации is None:
            беды.append(f"{файл}: носителя мутаций проб нет "
                        f"({МУТАЦИИ_ПРОБ.name}, {ИНВАРИАНТЫ.name}) — "
                        f"судить предикат класса D нечем")
        elif файл not in мутации:
            беды.append(f"{файл}: мутация пробы не названа в данных — прогон пробы "
                        f"доказывает, что она работает, а не что ловит поломку")
    return беды


def id_карты() -> set:
    """Все id карточек карты и её архива. Карты нет — пустое множество: тогда
    требование к ссылке на карточку не судится, и об этом говорится вслух, а не
    молчанием. Архив читается потому, что самоисправление карты уносит туда
    закрытые направления, а находка на унесённую карточку остаётся находкой."""
    if not КАРТА.exists():
        return set()
    архив = КАРТА.parent / "docs" / "dev-map-archive.yaml"
    тексты = [КАРТА.read_text()] + ([архив.read_text()] if архив.exists() else [])
    return {ид for текст in тексты
            for ид in re.findall(r"^\s+- id:\s*(\S+)\s*$", текст, re.M)}


def _цитата_из_следа(увидели: str, след_текст: str) -> bool:
    """Есть ли в «увидели» подстрока ≥ ЦИТАТА_ЗНАКОВ, встречающаяся в следе.

    Сравниваются ПЛОТНЫЕ строки (пробелы сжаты): перенос строки в журнале
    механизма не должен отменять дословность.
    """
    плотно = lambda с: " ".join(с.split())           # noqa: E731 — одна строка
    цель = плотно(след_текст)
    видно = плотно(увидели)
    return any(видно[н:н + ЦИТАТА_ЗНАКОВ] in цель
               for н in range(max(0, len(видно) - ЦИТАТА_ЗНАКОВ + 1)))


def _файл_следа(путь: str) -> pathlib.Path:
    """Путь следа: относительный — от корня дерева, абсолютный — как есть."""
    return pathlib.Path(путь) if путь.startswith("/") else КАРТА.parent / путь


def _есть_шапка(текст_следа: str) -> bool:
    """След написан ПРИБОРОМ, а не рукой: шапка и разделитель чужого текста.

    Законных видов следа три, и названы они все. Обёртка `scripts/live-check.sh`
    кладёт вывод механизма, которого позвали. Прибор живой проверки демонов
    (`scripts/live-check-daemon.py`) кладёт хвост журнала кронового прогона: у
    демона класса A1 доказательством служит именно этот журнал, его пишет сам
    демон под кроном. Прибор живой проверки скилов
    (`scripts/live-check-skill.py`) кладёт машинную запись журнала вызовов — её
    пишет ХУК оболочки, а скил зовёт оболочка, не проверяющий. Прибор живой
    проверки перехватчиков (`scripts/live-check-hook.py`) кладёт РЕШЕНИЕ хука,
    которому подали событие той же формы, какую шлёт оболочка. Требование одно
    и то же: в следе лежит ЧУЖОЙ текст, а не слова проверяющего.
    """
    разделители = ("--- вывод механизма ---", "--- хвост журнала демона ---",
                   "--- строка журнала скилов, написанная хуком ---",
                   "--- решение хука ---")
    return (any(р in текст_следа for р in разделители)
            and "механизм:" in текст_следа)


def беды_записей(меха: list, сост: dict, кл: dict) -> list:
    """Шесть требований §3.2 к записи живой проверки — поимённо и по-русски.

    Отдаёт ДВА списка: беды (отказ) и долг пересуда — записи без поля «след»,
    сделанные до того, как обёртка появилась. Смешивать их нельзя: гейт стоит
    в воротах, и покрасневший на всём старом он был бы отключён.

    Каждая беда называет СВОЮ причину: шесть требований — шесть разных бед, и
    отказ по одному коду возврата неотличим от отказа по другому (проба,
    судящая только код, зелена от любой второй беды).
    """
    беды = []
    долг = []
    причины = причины_непроверяемого()
    карточки = id_карты()
    мутации = пробы_с_мутацией()
    по_файлу = {м.get("файл"): м for м in меха}
    for файл, запись in сост.items():
        if not isinstance(запись, dict):
            continue
        исход = (запись.get("исход") or "").strip()
        if not исход:
            continue
        живьём = (запись.get("живьём") or "").strip()
        увидели = (запись.get("увидели") or "").strip()
        класс = ((кл.get(файл) or {}).get("класс") or "").strip()
        механизм = по_файлу.get(файл) or {}
        проверяется = str(механизм.get("проверяется") or "").strip()

        # 3. Пересказ самотеста — не живая проверка. Класс D исключён: там
        #    прогон пробы и ЕСТЬ инструмент (спека §3.1).
        if класс != "D" and живьём and проверяется:
            if " ".join(живьём.split()) == " ".join(проверяется.split()):
                беды.append(f"{файл}: «живьём» — пересказ команды самотеста из "
                            f"реестра, а не живая работа")
                continue

        # 5. «не-проверяемо» обязано называть причину из закрытого списка.
        if исход == "не-проверяемо":
            if not причины:
                беды.append(f"{файл}: исход «не-проверяемо», а списка "
                            f"«причины_непроверяемого» в данных нет — судить нечем")
            elif not any(п in увидели for п in причины):
                беды.append(f"{файл}: причина «не-проверяемо» не из списка в данных "
                            f"(их {len(причины)})")
            continue

        # 6. «ждёт» обязано называть, чьего слова или какого условия ждёт.
        if исход == "ждёт":
            чего = (запись.get("ждёт") or "").strip()
            if not чего:
                беды.append(f"{файл}: исход «ждёт», а поле «ждёт» не говорит, "
                            f"чьего слова или какого условия")
            continue

        # 4. Косяк называет существующую карточку либо закрытие с уликой.
        if исход == "косяк":
            находка = (запись.get("находка") or "").strip()
            if not находка:
                беды.append(f"{файл}: исход «косяк», а «находка» пуста — куда он заведён?")
            elif карточки and "закрыто" not in находка.lower():
                названные = re.findall(r"[a-zа-я]{2}\.[\w.-]+", находка)
                if not any(и in карточки for и in названные):
                    беды.append(f"{файл}: «находка» называет карточку, которой нет в "
                                f"карте: {находка[:60]}")

        # 1 и 2. След и дословная цитата из него — для всех исходов, которые
        #        означают сделанную работу.
        путь_следа = (запись.get("след") or "").strip()
        if not путь_следа:
            # Запись БЕЗ поля «след» — долг пересуда (спека §5, Task 5 плана), а
            # не отказ: гейт стоит в воротах, и покрасневший на 65 прежних
            # записях он был бы отключён в тот же день. Долг называется числом
            # отдельно — молчать о нём тоже нельзя.
            долг.append(файл)
            continue
        файл_следа = _файл_следа(путь_следа)
        if not файл_следа.is_file():
            беды.append(f"{файл}: следа нет на диске: {путь_следа}")
            continue
        текст_следа = файл_следа.read_text(errors="replace")
        if not _есть_шапка(текст_следа):
            беды.append(f"{файл}: в следе {путь_следа} нет шапки обёртки — "
                        f"он написан не scripts/live-check.sh")
            continue
        if not _цитата_из_следа(увидели, текст_следа):
            беды.append(f"{файл}: «увидели» не цитирует след ДОСЛОВНО "
                        f"(нужна подстрока от {ЦИТАТА_ЗНАКОВ} знаков)")
            continue
        # §3.1: предикат СВОЕГО класса. Проверяется ПОСЛЕ общего следа: пока
        # следа нет, говорить о половинах не о чем.
        беды += беды_предиката_класса(файл, класс, запись, мутации)
    return беды, долг


def собрать() -> str:
    меха = механизмы()
    сост = состояние()
    ч = числа(меха, сост)
    куски = [
        "# Живая проверка механизмов харнеса\n\n",
        "> Документ СОБИРАЕТСЯ прибором `scripts/build-live-check-list.py` из\n"
        "> реестра механизмов и `harness/config/live-check-state.yaml`.\n"
        "> Руками не править: следующая сборка перезапишет, а\n"
        "> `--проверить` краснеет меж тем.\n\n",
        "Владелец 15.10.2026: «проверить каждый механизм, каждого демона, каждый\n"
        "хук, каждый скрипт, проверить не просто тестами, а именно наживую, в\n"
        "практике. Тщательно, достоверно. Сейчас очень много косяков и\n"
        "недоработок».\n\n",
        "## Чем живая проверка отличается от самотеста\n\n",
        "Самотест проверяет то, о чём догадался его автор. Живая проверка —\n"
        "работу механизма в настоящей системе: его позвали так, как его зовёт\n"
        "жизнь, и посмотрели, что он СДЕЛАЛ. Поэтому в таблице две разные\n"
        "графы: «проверяется» — команда из реестра, «живьём» — что сделали\n"
        "руками и что увидели.\n\n",
        "## Числа\n\n",
        f"| всего | ок | косяк | не-проверяемо | ждёт | не трогал |\n",
        "|---|---|---|---|---|---|\n",
        f"| {ч['всего']} | {ч['ок']} | {ч['косяк']} | {ч['не-проверяемо']} "
        f"| {ч['ждёт']} | {ч['не трогал']} |\n\n",
    ]
    по_видам: dict[str, list[dict]] = {}
    for м in меха:
        по_видам.setdefault(м.get("вид") or "без вида", []).append(м)
    for вид in sorted(по_видам, key=lambda в: (-len(по_видам[в]), в)):
        группа = по_видам[вид]
        проверено = sum(1 for м in группа
                        if (сост.get(м.get("файл")) or {}).get("исход"))
        куски.append(f"## {вид} — {len(группа)}, живьём проверено {проверено}\n\n")
        куски.append("| файл | имя | проверяется (самотест) | живьём: что сделали и что увидели | исход | когда |\n")
        куски.append("|---|---|---|---|---|---|\n")
        for м in sorted(группа, key=lambda м: str(м.get("файл"))):
            куски.append(строка_таблицы(м, сост))
        куски.append("\n")
    return "".join(куски)


def main() -> int:
    чужие = неизвестные_ключи(механизмы(), состояние())
    if чужие:
        print("[живая проверка] ✗ в состоянии есть механизмы, которых нет в "
              "реестре — переименовали файл? живая проверка по этим ключам "
              "никем не считается:", file=sys.stderr)
        for k in чужие:
            print(f"    {k}", file=sys.stderr)
        return 1
    собранный = собрать()
    if "--числа" in sys.argv:
        меха = механизмы()
        ч = числа(меха, состояние())
        print(f"[живая проверка] всего {ч['всего']}: ок {ч['ок']}, "
              f"косяк {ч['косяк']}, не-проверяемо {ч['не-проверяемо']}, "
              f"ждёт {ч['ждёт']}, не трогал {ч['не трогал']}")
        кл = классы()
        р = разрез(меха, кл)
        print("[живая проверка] классы: " + ", ".join(
            f"{к}: {р[к]}" for к in (*КЛАССЫ_ДОПУСТИМЫЕ, "без класса")))
        беды = беды_классов(меха, кл)
        if беды:
            print(f"[живая проверка] ✗ класс решает, ЧТО считать живой "
                  f"проверкой; бед {len(беды)}:", file=sys.stderr)
            for б in беды[:20]:
                print(f"    {б}", file=sys.stderr)
            if len(беды) > 20:
                print(f"    …и ещё {len(беды) - 20}", file=sys.stderr)
            return 1
        return 0
    if "--проба" in sys.argv:
        меха = механизмы()
        сост = состояние()
        ч = числа(меха, сост)
        print(f"[живая проверка] счёт: всего {ч['всего']}, ок {ч['ок']}, "
              f"косяк {ч['косяк']}, не-проверяемо {ч['не-проверяемо']}, "
              f"ждёт {ч['ждёт']}, не трогал {ч['не трогал']}", flush=True)
        беды = беды_счёта(меха, сост)
        if беды:
            print(f"[живая проверка] ✗ счёт живой проверки не закрыт: "
                  f"{len(беды)} механизмов ждут работы", file=sys.stderr)
            for б in беды[:10]:
                print(f"    {б}", file=sys.stderr)
            if len(беды) > 10:
                print(f"    …и ещё {len(беды) - 10}", file=sys.stderr)
            return 1
        print(f"[живая проверка] счёт закрыт: все {ч['всего']} механизмов "
              f"проверены живьём")
        return 0
    if "--проверить" in sys.argv or "--данные" in sys.argv:
        # «--данные» судит только записи: pre-commit читает их из снимка индекса, а документ
        # в снимке бывает старше правки данных, и свежесть документа судят ворота.
        сверять_документ = "--данные" not in sys.argv
        если_есть = ДОКУМЕНТ.read_text() if ДОКУМЕНТ.exists() else ""
        if сверять_документ and если_есть != собранный:
            print("[живая проверка] ✗ документ разошёлся с реестром или состоянием "
                  "(правили руками?) — пересобрать: "
                  "python3 scripts/build-live-check-list.py", file=sys.stderr)
            return 1
        # Прежний смысл сохранён, новый ДОБАВЛЕН: документ сходится с данными —
        # и каждая запись доказана СЛЕДОМ, а не формой (спека §3.2). Прежний
        # предикат судил форму: «2026-10-15: работает» и пересказ самотеста
        # проходили (ревью спеки 15.10, CRITICAL 5).
        беды, долг = беды_записей(механизмы(), состояние(), классы())
        if долг:
            print(f"[живая проверка] записей без следа (долг пересуда, спека §5): "
                  f"{len(долг)}")
        if беды:
            print(f"[живая проверка] ✗ записей без доказательства: {len(беды)}",
                  file=sys.stderr)
            for б in беды[:20]:
                print(f"    {б}", file=sys.stderr)
            if len(беды) > 20:
                print(f"    …и ещё {len(беды) - 20}", file=sys.stderr)
            return 1
        ч = числа(механизмы(), состояние())
        итог = "документ сходится с данными" if сверять_документ else "данные"
        print(f"[живая проверка] {итог}: механизмов "
              f"{ч['всего']}, живьём проверено "
              f"{ч['всего'] - ч['не трогал']}, и каждая запись доказана следом")
        return 0
    ДОКУМЕНТ.parent.mkdir(parents=True, exist_ok=True)
    # Не тронутый документ не переписывается: повтор раскладки той же версии не должен менять mtime.
    if not ДОКУМЕНТ.exists() or ДОКУМЕНТ.read_text() != собранный:
        ДОКУМЕНТ.write_text(собранный)
    ч = числа(механизмы(), состояние())
    # Путь печатается коротким, если он внутри дерева, и целиком, если нет:
    # relative_to на чужом пути БРОСАЕТ, и прибор падал трассой ПОСЛЕ успешной
    # записи документа — то есть работа сделана, а ответ выглядит поломкой
    # (ревью 17.10, F-gen-10; своя же проба Task 2 на этом и встала).
    где = ДОКУМЕНТ.relative_to(КОРЕНЬ) if ДОКУМЕНТ.is_relative_to(КОРЕНЬ) else ДОКУМЕНТ
    print(f"{где}: собран, механизмов {ч['всего']}, "
          f"живьём проверено {ч['всего'] - ч['не трогал']}, косяков {ч['косяк']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
