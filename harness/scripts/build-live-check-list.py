ИНВАРИАНТЫ = _путь("HARNESS_INVARIANTS", "harness", "config", "invariants.yaml")
# Класс B2: обработчик входящих доказывается ЗАПИСАННЫМ словом владельца. Два
# законных доказательства, и оба машинные: запись называет файл из
