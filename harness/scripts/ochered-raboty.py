    # сумма 0 — «порядок считает код» вырождается в «порядок строк в файле».
    карта = {"queue": [], "lines": [{"id": "h", "tasks": [
        {"id": "старая", "status": "plan", "источник": "inbox:1000.0"},
        {"id": "свежая", "status": "plan", "источник": "inbox:9000.0"},
        {"id": "ничья", "status": "plan"}]}]}
