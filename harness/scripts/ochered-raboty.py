# Веса и слова — ДАННЫЕ (harness/config/очередь.yaml). Умолчания здесь нужны не
# «на всякий случай», а для свежей установки: файла данных ещё нет, а прибор
# уже зовут из осмотра сессии.
НАСТРОЙКИ_ПО_УМОЛЧАНИЮ = {
    "веса": {"внимание_владельца": 100, "провал_проверки": 40,
             "wip": 30, "queue": 20, "plan": 0, "почти_закончена": 10},
    "внимание_суток": 3,
    "почти_закончена_с_доли": 0.5,
    "свежесть_максимум": 9,
    "потолок_строк": 10,
}


def настройки(путь: str | Path | None = None) -> dict:
    """Данные порядка. Нет файла — умолчания, а не отказ: прибор не гейт."""
    файл = Path(путь) if путь else (Path(__file__).resolve().parent.parent
                                    / "harness" / "config" / "очередь.yaml")
    итог = dict(НАСТРОЙКИ_ПО_УМОЛЧАНИЮ)
    try:
        свои = yaml.safe_load(файл.read_text(encoding="utf-8")) or {}
    except (OSError, yaml.YAMLError):
        return итог
    итог.update({к: v for к, v in свои.items() if v is not None})
    итог["веса"] = {**НАСТРОЙКИ_ПО_УМОЛЧАНИЮ["веса"], **(свои.get("веса") or {})}
    return итог


def внимание_владельца(журнал: str | Path | None = None, суток: int = 3,
                       сейчас: float | None = None) -> dict:
    """{id сообщения: слово} по журналу, который ведёт ДИСПЕТЧЕР канала.

    Признак срочности ставит тот, чьи это слова, а не тот, кому он выгоден:
    агент этот файл только читает (находка ревью C-10 — та же, по которой
    отвергнуто поле priority в карточке).

    Просроченное не возвращается: у пометки обязан быть срок, иначе через
    неделю она поднимает наверх то, что владелец давно забыл.
    """
    import json
    import time
    файл = Path(журнал) if журнал else Path(
        os.environ.get("LOG_DIR", "/var/log/harness")) / "внимание.jsonl"
    сейчас = time.time() if сейчас is None else сейчас
    итог = {}
    try:
        строки = файл.read_text(encoding="utf-8").splitlines()
    except OSError:
        return итог
    for строка in строки:
        try:
            запись = json.loads(строка)
            ид = str(запись["id"])
            когда = float(запись.get("метка") or ид)
        except (ValueError, KeyError, TypeError):
            continue          # битую строку журнала пропускаем, но не падаем
        if сейчас - когда <= суток * 86400:
            итог[ид] = запись.get("слово") or "прямое слово владельца"
    return итог


def _источник_метка(задача: dict) -> float:
    """Метка времени сообщения, из которого заведена задача. Нет — 0."""
    сырое = str(задача.get("источник") or "")
    метки = re.findall(r"inbox:([0-9.]+)", сырое)
    значения = []
    for м in метки:
        try:
            значения.append(float(м))
        except ValueError:
            continue
    return max(значения) if значения else 0.0


def порядок(data: dict, направление: str | None = None, настройки: dict | None = None,
            внимание: dict | None = None) -> list[dict]:
    """Задачи в порядке работы: [{id, вес, почему}], первая — что делать сейчас.

    Правило источников то же, что у разобрать(), плюс хвост `plan`. Статус
    `test` в порядок не идёт: работа сделана и ждёт владельца, а не меня.
    Прямое слово владельца снимает ЛЮБОЕ исключение, кроме закрытых статусов:
    иначе «могу направить внимание на любую задачу» не выполняется.
    """
    напр = активное_направление() if направление is None else направление
    наст = настройки or НАСТРОЙКИ_ПО_УМОЛЧАНИЮ
    веса = dict(НАСТРОЙКИ_ПО_УМОЛЧАНИЮ["веса"], **(наст.get("веса") or {}))
    внимание = внимание or {}
    задачи = {t.get("id"): t
              for line in data.get("lines") or []
              if not напр or line.get("id") == напр
              for t in line.get("tasks") or []}
    # Задачи ВСЕЙ карты — чтобы отличить «карточки нет вовсе» (битая очередь,
    # её надо заметить) от «карточка в другом направлении» (над ним сейчас не
    # работаем). Живой случай 12.09.2026: в queue висели три задачи продукта,
    # и первой строкой «сейчас делаем» шла чужая задача без карточки.
    все_задачи = {t.get("id") for line in data.get("lines") or []
                  for t in line.get("tasks") or []}
    очередь = list(data.get("queue") or [])

    места = []
    for ид in dict.fromkeys(очередь + list(задачи)):
        задача = задачи.get(ид)
        if задача is None:
            if ид in все_задачи:
                continue      # карточка есть, но в другом направлении — не наше
            # Карточки нет НИГДЕ: битую очередь прибор не прощает — так же, как
            # разобрать(), иначе два вывода одного прибора разошлись бы.
            места.append({"id": ид, "вес": веса["queue"],
                          "почему": "в очереди, а карточки в карте нет"})
            continue
        слово = _слово_внимания(задача, внимание)
        статус = задача.get("status")
        блокер = задача.get("blocked")
        провал = задача.get("провал_проверки")
        if статус in ("done", "принято"):
            continue
        if not слово and (блокер or статус == "test" and not провал):
            continue
        вес, почему = 0, []
        if слово:
            вес += веса["внимание_владельца"]
            почему.append(f"внимание владельца: «{слово}»")
        if провал:
            вес += веса["провал_проверки"]
            почему.append("провалила проверку")
        if статус == "wip":
            вес += веса["wip"]
            почему.append("начата")
        if ид in очередь:
            вес += веса["queue"]
            почему.append("в очереди")
        доля = доля_закрытого(задача)
        if доля >= наст["почти_закончена_с_доли"]:
            вес += веса["почти_закончена"]
            почему.append(f"закрыто {int(доля * 100)} % пунктов")
        if not почему:
            почему.append("план")
        if блокер:
            почему.append(f"блокер: {блокер}")
        места.append({"id": ид, "вес": вес, "почему": ", ".join(почему),
                      "метка": _источник_метка(задача)})

    # Свежесть источника разводит хвост: без неё девять задач из десяти
    # получают 0, и порядок вырождается в порядок строк в файле.
    с_меткой = sorted({м["метка"] for м in места if м.get("метка")})
    шаг = наст["свежесть_максимум"]
    for м in места:
        метка = м.pop("метка", 0.0)
        if метка and len(с_меткой) > 1:
            м["вес"] += round(шаг * с_меткой.index(метка) / (len(с_меткой) - 1))
        elif метка:
            м["вес"] += шаг
    места.sort(key=lambda м: -м["вес"])
    return места if напр else места[:наст["потолок_строк"]]


def доля_закрытого(задача: dict) -> float:
    """Какая часть чеклиста закрыта. Нет чеклиста — 0, судить не по чему.

    Владелец 13.09.2026: порядок задаёт «эффективность и логичность
    разработки», а не свежесть его сообщений. Признаков эффективности в карте
    оказалось меньше, чем хотелось: поля зависимостей («что разблокирует
    другие») нет вовсе — 147 карточек, ни одной связи, — и придумывать его
    здесь значило бы считать по пустоте. Что есть честно: доведение начатого
    до конца дешевле начала нового, и это видно по чеклисту.
    """
    пункты = задача.get("checklist") or []
    if not пункты:
        return 0.0
    закрыто = sum(1 for п in пункты if п.get("done"))
    return закрыто / len(пункты)


def _слово_внимания(задача: dict, внимание: dict) -> str:
    """Слово владельца по любому из источников задачи (их бывает несколько)."""
    for ид in re.findall(r"inbox:([0-9.]+)", str(задача.get("источник") or "")):
        if ид in внимание:
            return внимание[ид]
    return ""


def разобрать(data: dict, направление: str | None = None) -> tuple[int, list[str]]:
    """→ (сколько задач можно делать самому, список «id=причина» по остальным)."""
    направление = активное_направление() if направление is None else направление
    tasks = {
        t.get("id"): t
        for line in data.get("lines") or []
        if not направление or line.get("id") == направление
        for t in line.get("tasks") or []
    }
    работа, ждут = 0, []
    # Одним списком: очередь, начатое и ПРОВАЛИВШАЯ ПРОВЕРКУ. Провал — это
    # работа: приёмка его нашла, а починка за мной. Без этого провал виден
    # только в карточке, и я узнаю о нём, случайно открыв карту (вопрос
    # владельца 12.09.2026: «С провалом что? Куда уходит и как причина»).
    начатые = [и for и, з in tasks.items()
               if з.get("status") == "wip" or з.get("провал_проверки")]
    for qid in dict.fromkeys(list(data.get("queue") or []) + начатые):
        задача = tasks.get(qid)
        # Задачи нет в карте — это ловит валидатор pre-commit. Здесь считаем её
        # работой: прибор не должен молчаливо прощать битую очередь.
        if задача is None:
            работа += 1
            continue
        причина = задача.get("blocked")
        провал = задача.get("провал_проверки")
        if провал and not причина:
            # Провал не блокирует: его можно брать в работу прямо сейчас.
            работа += 1
            continue
        if причина:
            ждут.append(f"{qid}={причина}")
        else:
            работа += 1
    return работа, ждут


def _коротко(задача: dict, предел: int = 58) -> str:
    """Заголовок задачи человеческими словами: id владельцу ничего не говорит."""
    имя = str(задача.get("title") or задача.get("id") or "").strip()
    return имя if len(имя) <= предел else имя[:предел - 1].rstrip() + "…"


def _сделано(часов: int = 12, сколько: int = 1) -> list[str]:
    """Заголовки коммитов смены. «Что сделал» — это git, а не моя память."""
    try:
        вывод = subprocess.run(
            ["git", "-C", str(Path(__file__).resolve().parent.parent),
             "log", f"--since={часов} hours ago", "--format=%s", f"-{сколько}"],
            capture_output=True, text=True, timeout=20).stdout
    except (OSError, subprocess.SubprocessError):
        return []
    return [с.strip() for с in вывод.splitlines() if с.strip()]


def для_владельца(data: dict) -> list[str]:
    """Ответ на /status: что сделал, что делаю, что дальше — и ничего сверх.

    Владелец 13.09.2026, увидев прежний ответ: «ерунда какая то ответ. мне
    нужен понимать что ты делаешь, что сделал, что дальше». До этого ответ был
    дампом прибора (id, вес числом, первая задача дважды), а после первой
    правки «Делаю» показало ЕГО ЖЕ фразу: автомат карточек называет задачу
    первой строкой сообщения, и свежая карточка встаёт первой в очереди.

    Поэтому «делаю» берётся с ДОСКИ — там я пишу о себе своими словами
    (doska.py, у записи обязательный срок). Очередь остаётся запасным ответом
    и честно помечается как план, а не как работа.
    """
    строки = []
    сделал = _сделано()
    if сделал:
        строки.append("Сделал: " + _обрезать(сделал[0], 90))

    наст = настройки()
    места = порядок(data, направление=активное_направление(), настройки=наст,
                    внимание=внимание_владельца(суток=наст["внимание_суток"]))
    задачи = {t.get("id"): t
              for line in data.get("lines") or []
              for t in line.get("tasks") or []}
    доска = _доска_смены()
    if доска:
        строки.append("Делаю: " + _обрезать(доска, 90))
    elif места:
        строки.append("В плане следующей: "
                      + _коротко(задачи.get(места[0]["id"], {}), 70))
    else:
        строки.append("Делаю: очередь пуста — работы в карте нет.")

    дальше = [_коротко(задачи.get(м["id"], {}), 60) for м in места[1:2]]
    if доска and места:
        дальше = [_коротко(задачи.get(места[0]["id"], {}), 60)]
    if дальше:
        строки.append("Дальше: " + дальше[0])
    return строки


def _обрезать(текст: str, предел: int) -> str:
    текст = str(текст or "").strip()
    return текст if len(текст) <= предел else текст[:предел - 1].rstrip() + "…"


def _доска_смены() -> str:
    """Что смена сказала о себе сама. Протухшую запись доска не отдаёт."""
    try:
        вышло = subprocess.run(
            [sys.executable,
             str(Path(__file__).resolve().parent / "doska.py"), "--читать", "смена"],
            capture_output=True, text=True, timeout=20)
    except (OSError, subprocess.SubprocessError):
        return ""
    return вышло.stdout.strip() if вышло.returncode == 0 else ""


def напечатать(data: dict, с_порядком: bool = False) -> None:
    работа, ждут = разобрать(data)
    print(f"работа: {работа}")
    print("ждут: " + "; ".join(ждут))
    if not с_порядком:
        return
    # Старые две строки печатаются ВСЕГДА и первыми: их читают сторож сессий и
    # осмотр сессии. Порядок идёт следом одним и тем же разбором карты — иначе
    # осмотр разбирал бы файл в 390 КБ дважды.
    наст = настройки()
    напр = активное_направление()
    if not напр:
        print("порядок: направление не выбрано (ACTIVE_LINE пуст) — считаю по всей карте")
    места = порядок(data, направление=напр, настройки=наст,
                    внимание=внимание_владельца(суток=наст["внимание_суток"]))
    if not места:
        print("сейчас делаем: очередь пуста")
        return
    print(f"сейчас делаем: {места[0]['id']} — {места[0]['почему']}")
    for номер, м in enumerate(места[:наст["потолок_строк"]], 1):
        print(f"  {номер}. {м['id']} · {м['вес']} · {м['почему']}")


