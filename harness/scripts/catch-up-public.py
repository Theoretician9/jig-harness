def _стенд(двор: Path) -> tuple[Path, Path, Path]:
    """Проект, пакет и каталог публикации с публичной веткой впереди."""
    проект = двор / "проект"
    (проект / "память").mkdir(parents=True)
    (проект / "память" / "УКАЗАНИЯ.md").write_text("# указания\n", encoding="utf-8")
    (проект / "память" / "ORDERS.md").write_text("# указания\n", encoding="utf-8")
    пакет = _пакет_стенда(двор, проект)

    паспорт = двор / "install.conf"
    паспорт.write_text(
        f'PROJECT_DIR="{проект}"\nPROJECT_NAME="Стенд"\nAGENT_USER="agent"\n',
        encoding="utf-8")

    # Публичный репозиторий: сначала наша публикация, потом ЕГО правки.
    голый = двор / "публичный.git"
    subprocess.run(["git", "init", "-q", "--bare", str(голый)], capture_output=True)
    сборка = двор / "сборка"
    собрать(пакет, сборка, паспорт)
    subprocess.run(["git", "init", "-q", "-b", "master", str(сборка)], capture_output=True)
    гит(сборка, "remote", "add", "jig", str(голый))
    гит(сборка, "add", "-A")
    гит(сборка, "-c", "user.name=p", "-c", "user.email=p@l", "commit", "-q", "-m", "публикация")
    # Файлы публикатора: их рождает не пакет, и переноситься они не должны.
    (сборка / "VERSION").write_text("1.0.0\n", encoding="utf-8")
    гит(сборка, "add", "-A")
    гит(сборка, "-c", "user.name=p", "-c", "user.email=p@l", "commit", "-q", "-m", "версия")
    гит(сборка, "push", "-q", "jig", "master")
    return проект, пакет, сборка


def _его_правки(двор: Path, голый: Path, правки) -> None:
    """Правки ВТОРОЙ машины: отдельный клон публичного репозитория."""
    чужой = двор / "чужой"
    subprocess.run(["git", "clone", "-q", str(голый), str(чужой)], capture_output=True)
    правки(чужой)
    гит(чужой, "add", "-A")
    гит(чужой, "-c", "user.name=o", "-c", "user.email=o@l", "commit", "-q", "-m", "его правки")
    гит(чужой, "push", "-q", "origin", "master")
    shutil.rmtree(чужой)


