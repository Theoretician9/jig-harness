def main() -> int:
    только_проверка = "--проверка" in sys.argv
    значения = настройки()
    пакет = Path(os.environ.get("HARNESS_STARTER")
                 or значения.get("STARTER_DIR", "").strip()
                 or f"/home/{значения.get('AGENT_USER', 'agent')}"
                    f"/starter/STARTER-PACKAGE")
    сборка = Path(значения.get("PUBLIC_BUILD_DIR", "").strip())
    удалённый = значения.get("PUBLIC_REMOTE", "").strip()
    ветка = значения.get("PUBLIC_BRANCH", "").strip()
    for имя, значение in (("PUBLIC_BUILD_DIR", str(сборка)),
                          ("PUBLIC_REMOTE", удалённый), ("PUBLIC_BRANCH", ветка)):
        if not значение:
            print(f"[догнать] не настроено: пуст {имя}", file=sys.stderr)
            return 2
    if not (сборка / ".git").is_dir():
        print(f"[догнать] не настроено: в {сборка} нет публичной сборки — "
              f"её создаёт publish.sh", file=sys.stderr)
        return 2
    try:
        if "--продолжить" in sys.argv:
            место = sys.argv[sys.argv.index("--продолжить") + 1]
            return продолжить(пакет, Path(место), Path(путь_install_conf()),
                              сборка, удалённый, ветка)
        return догнать(пакет, сборка, удалённый, ветка,
                       Path(путь_install_conf()), только_проверка)
    except Отказ as отказ:
        print(f"[догнать] ОТКАЗ: {отказ}", file=sys.stderr)
        return отказ.код


