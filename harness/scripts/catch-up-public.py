#!/usr/bin/env python3
"""Догнать публичную ветку: пакет = публичная ветка + наши правки.

ЗАЧЕМ. 13.10.2026 владелец поставил харнес на второй сервер, и агент ТОЙ
машины начал править тот же публичный репозиторий: 25 коммитов, 161 файл, 45
переименований кириллических имён в английские. Наша публикация честно
отказала («расхождение с публичной веткой»), и правильно: сборка из нашего
пакета вернула бы старые имена и снесла бы его работу. Слово владельца:
«надо чтобы конфликтов не было».

Отказ двери говорил «разбирает человек» — а человека у терминала нет
([[a-mechanism-that-needs-a-human-is-dead]]). Поэтому догоняние — КОМАНДА:
пока публичный репозиторий правят две машины, расхождение будет повторяться.

КАК ЭТО РАБОТАЕТ. Наружу уезжает не пакет, а СБОРКА (build-public.py:
обезличенные документы, перенос глав, подмена двух файлов заготовками), и
обратного преобразования у сборки нет. Поэтому слияние идёт в ПРОСТРАНСТВЕ
СБОРКИ, где обе стороны сравнимы (его публикует такая же сборка), а в пакет
переносится трёхсторонним слиянием каждого файла:

    ours   = файл ПАКЕТА (с нашими литералами и живыми замерами)
    base   = тот же файл в СВЕЖЕЙ сборке нашего пакета
    theirs = тот же файл в слитом дереве

base → theirs — это ровно ЕГО правки, и git merge-file кладёт их на наш файл,
не трогая того, что преобразование сборки заменило. Переименования берёт git
(он же их и распознаёт), поэтому новое имя получает содержимое ПАКЕТА, а не
сборки.

ЧТО НЕ ПЕРЕНОСИТСЯ, и почему списки МЕРЯЮТСЯ, а не вписаны сюда:
* файлы, которые рождает публикатор, а не пакет (VERSION, CHANGELOG.md) —
  это разность «дерево последней публикации минус наша сборка»;
* файлы, подменяемые заготовкой (замер речи владельца, пары цитат) — это
  ключи «заменить_шаблоном» из данных сборки, нашей И его: в сборке там лежит
  содержимое заготовки, и перенос его в пакет убил бы живой файл.

ЧЕМ ДОКАЗЫВАЕТСЯ. Догнавший пакет собирается снова, и его сборка обязана
совпасть со слитым деревом файл в файл. Не совпала — отказ со списком путей:
это единственная проверка, которая ловит ошибку переноса в обе стороны.

Прогон:
    python3 scripts/catch-up-public.py --проверка  # только померить расхождение
    python3 scripts/catch-up-public.py             # догнать пакет
    python3 scripts/catch-up-public.py --selftest  # на больном случае

Код возврата: 0 — догнали (или догонять нечего), 1 — отказ (конфликт, грязный
пакет, непройденная сверка), 2 — не настроено.
"""
from __future__ import annotations

import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "scripts" / "lib"))
from config import из_файла, путь_harness_conf, путь_install_conf  # noqa: E402

# Имена файла данных сборки: публичная ветка переименовала его, а догонять
# придётся и ДО, и ПОСЛЕ этого перехода — поэтому список имён, а не одно.
ИМЕНА_ДАННЫХ = ("public-build.yaml", "публичная-сборка.yaml")
# Метка каталога публикации — та же, по которой его узнаёт build-public.py.
МЕТКА_СБОРКИ = ".публичная-сборка"


class Отказ(Exception):
    def __init__(self, текст: str, код: int = 1):
        super().__init__(текст)
        self.код = код


def гит(каталог: Path | str, *доводы: str, можно_упасть: bool = False) -> str:
    """git в каталоге. Отказ git — это отказ, а не пустой ответ
    ([[command-failure-read-as-empty]])."""
    # core.quotepath=false ВСЕГДА: иначе git печатает кириллическое имя
    # C-экранированным ("\320\277..."), оно не совпадает ни с одним путём
    # дерева, и файл молча считается чужим ([[a-measure-counting-one-spelling-of-two]]).
    готово = subprocess.run(["git", "-C", str(каталог),
                             "-c", "core.quotepath=false", *доводы],
                            capture_output=True, text=True)
    if готово.returncode != 0 and not можно_упасть:
        raise Отказ(f"git {' '.join(доводы)} в {каталог}: "
                    f"{готово.stderr.strip() or готово.stdout.strip()}")
    return готово.stdout


def данные_сборки(пакет: Path) -> tuple[Path, dict]:
    """Файл данных публичной сборки в пакете и его содержимое."""
    for имя in ИМЕНА_ДАННЫХ:
        путь = пакет / "harness" / "config" / имя
        if путь.is_file():
            return путь, (yaml.safe_load(путь.read_text(encoding="utf-8")) or {})
    raise Отказ(f"в пакете нет данных сборки (искал: {', '.join(ИМЕНА_ДАННЫХ)})", 2)


def собрать(пакет: Path, куда: Path, паспорт: Path) -> None:
    """Свежая сборка пакета в каталог. Данные берутся у ПАКЕТА: его состояние
    и решает, что в сборку не едет."""
    путь_данных, _ = данные_сборки(пакет)
    куда.mkdir(parents=True, exist_ok=True)
    (куда / МЕТКА_СБОРКИ).write_text("", encoding="utf-8")
    готово = subprocess.run(
        [sys.executable, str(КОРЕНЬ / "scripts" / "build-public.py"),
         "--пакет", str(пакет), "--куда", str(куда),
         "--паспорт", str(паспорт), "--данные", str(путь_данных)],
        capture_output=True, text=True)
    if готово.returncode != 0:
        raise Отказ(f"сборка пакета не прошла: "
                    f"{готово.stderr.strip() or готово.stdout.strip()}")


def файлы_дерева(корень: Path) -> set[str]:
    """Пути всех файлов относительно корня. Метка каталога сборки и .git —
    не содержимое дерева."""
    return {str(п.relative_to(корень)) for п in корень.rglob("*")
            if п.is_file() and ".git" not in п.parts
            and п.name != МЕТКА_СБОРКИ}


def обратный_перенос(данные: dict) -> list[tuple[str, str]]:
    """Пары «путь сборки → путь пакета» из ключа «перенести»."""
    return [(куда.strip("/"), откуда.strip("/"))
            for откуда, куда in (данные.get("перенести") or {}).items()]


def путь_в_пакете(путь: str, переносы: list[tuple[str, str]]) -> str:
    for куда, откуда in переносы:
        if путь == куда or путь.startswith(куда + "/"):
            return откуда + путь[len(куда):]
    return путь


def перевести_сборку(сборка: Path, удалённый: str, ветка: str) -> int:
    """Перевести ветку каталога публикации на публичную — ТОЛЬКО вперёд.

    Пакет догнать мало: публикуется СБОРКА, и замок publish.sh «только вперёд»
    судит `merge-base --is-ancestor <удалённый>/<ветка> HEAD`. Пока локальная
    ветка каталога публикации стоит на нашей прошлой публикации, замок отказывает
    словами «расхождение… разбирает человек» — то есть публикация после догоняния
    не исполнима НИ ОДНОЙ командой (находка ревью F-nb-01 14.10.2026, замер: 28
    коммитов отставания).

    Рабочее дерево каталога публикации — ПРОИЗВОДНОЕ: его заново раскладывает
    build-public.py при каждой публикации, поэтому прошлая сборка в нём — не
    данные. Но цель разрушительной команды узнаётся ЯВНО, по метке каталога:
    довод может указывать куда угодно ([[the-probes-secret-was-a-real-one]]).
    """
    if not (сборка / МЕТКА_СБОРКИ).is_file():
        raise Отказ(f"{сборка} не похож на каталог публикации (нет {МЕТКА_СБОРКИ}) — "
                    f"ветку там не трогаю")
    свои = гит(сборка, "rev-list", "--count",
               f"{удалённый}/{ветка}..HEAD").strip() or "0"
    if свои != "0":
        raise Отказ(f"в каталоге публикации {свои} коммитов, которых нет в "
                    f"публичной ветке: перевод вперёд невозможен, разбирать по месту")
    отставание = гит(сборка, "rev-list", "--count",
                     f"HEAD..{удалённый}/{ветка}").strip() or "0"
    if отставание == "0":
        return 0
    гит(сборка, "reset", "--hard", f"{удалённый}/{ветка}")
    return int(отставание)


def слить(сборка: Path, наша: Path, удалённый: str, ветка: str,
          работа: Path) -> tuple[Path, str, list[tuple[str, str]],
                                 list[str], set[str]]:
    """Слить свежую сборку с публичной веткой в ОТДЕЛЬНОМ репозитории.

    Каталог публикации не трогается: его хозяин — publish.sh, и писать в него
    отсюда значит сводить два механизма в одном месте.

    Возвращает (репозиторий слияния, коммит нашей стороны, переименования,
    конфликты, файлы публикатора).
    """
    # Отказ fetch НЕ проглатывается: прибор судил бы по устаревшей ссылке и
    # печатал «догонять нечего» с кодом 0, пока вторая машина впереди — ровно
    # та ложь, от которой написан docstring функции «гит»
    # ([[command-failure-read-as-empty]], находка ревью F-gen-01 14.10.2026).
    # «Удалённого нет вовсе» судится отдельно, строкой ниже, через rev-parse.
    гит(сборка, "fetch", "--quiet", удалённый)
    ссылка = f"refs/remotes/{удалённый}/{ветка}"
    if not гит(сборка, "rev-parse", "--verify", "-q", ссылка, можно_упасть=True).strip():
        raise Отказ(f"у сборки нет {удалённый}/{ветка} — догонять нечего", 2)

    репо = работа / "слияние"
    готово = subprocess.run(["git", "clone", "--quiet", str(сборка), str(репо)],
                            capture_output=True, text=True)
    if готово.returncode != 0:
        raise Отказ(f"клон сборки не прошёл: {готово.stderr.strip()}")
    гит(репо, "fetch", "-q", str(сборка), f"{ссылка}:refs/heads/его")

    # Наша сторона: свежая сборка пакета поверх последней публикации. Общего
    # предка ищет git сам — отсюда и трёхстороннее слияние.
    гит(репо, "checkout", "-q", "-b", "наша")
    for путь in файлы_дерева(репо):
        (репо / путь).unlink()
    for путь in файлы_дерева(наша):
        цель = репо / путь
        цель.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(наша / путь, цель)
    # Файлы, которые пишет публикатор поверх собранного (VERSION, CHANGELOG.md),
    # возвращаются из опубликованного дерева. Иначе наша сторона «удаляет» их,
    # git честно принимает удаление, и слитое дерево выходит не тем, что живёт в
    # каталоге публикации: там rsync сборки их не трогает.
    общий = гит(репо, "merge-base", "HEAD", "его", можно_упасть=True).strip()
    от_публикатора: set[str] = set()
    if общий:
        в_базе = {с for с in гит(репо, "ls-tree", "-r", "--name-only",
                                 общий).splitlines() if с}
        от_публикатора = в_базе - файлы_дерева(наша)
        if от_публикатора:
            гит(репо, "checkout", общий, "--", *sorted(от_публикатора))
    гит(репо, "add", "-A")
    гит(репо, "-c", "user.name=harness", "-c", "user.email=harness@local",
        "commit", "-q", "--allow-empty", "-m", "наша сборка")
    наш_коммит = гит(репо, "rev-parse", "HEAD").strip()

    слито = subprocess.run(
        ["git", "-C", str(репо), "-c", "user.name=harness",
         "-c", "user.email=harness@local", "merge", "--no-edit", "его"],
        capture_output=True, text=True)
    конфликты = sorted({с for с in
                        гит(репо, "diff", "--name-only",
                            "--diff-filter=U").splitlines() if с})
    if слито.returncode != 0 and not конфликты:
        raise Отказ(f"слияние не прошло: "
                    f"{слито.stdout.strip() or слито.stderr.strip()}")

    переименования: list[tuple[str, str]] = []
    if not конфликты:
        поля = гит(репо, "-c", "core.quotepath=false", "diff", "-M", "-z",
                   "--name-status", наш_коммит, "HEAD").split("\0")
        i = 0
        while i < len(поля) and поля[i]:
            if поля[i][0] in "RC":
                переименования.append((поля[i + 1], поля[i + 2])); i += 3
            else:
                i += 2
    return репо, наш_коммит, переименования, конфликты, от_публикатора


def подменяемые_заготовкой(данные: dict, репо: Path) -> set[str]:
    """Пути, где в сборке лежит заготовка. Берутся из данных НАШЕГО пакета и
    из данных его дерева: имя файла данных могло переехать вместе с переводом."""
    ключи = set(данные.get("заменить_шаблоном") or {})
    for имя in ИМЕНА_ДАННЫХ:
        файл = репо / "harness" / "config" / имя
        if файл.is_file():
            его = yaml.safe_load(файл.read_text(encoding="utf-8")) or {}
            ключи |= set(его.get("заменить_шаблоном") or {})
    return ключи


def спланировать(репо: Path, наша: Path, пакет: Path, переименования: list,
                 пропуск: set[str], переносы: list) -> tuple[list, list, set]:
    """Посчитать перенос, НЕ трогая пакет: (план, конфликтные, задетые пути).

    Два такта, а не один: прежняя редакция переносила файл за файлом и на
    первом конфликте поднимала отказ со словами «файлы оставлены как есть» —
    неправдой для всех, кроме конфликтного: переименования уже сделаны, соседи
    перезаписаны, а повторный прогон отказывал «пакет не чист» (находка ревью
    F-gen-02 14.10.2026). Теперь пакет не трогается, пока не посчитан весь
    перенос.

    План — список действий: («переименовать», старое, новое),
    («записать», путь, байты), («удалить», путь).
    """
    план: list[tuple] = []
    конфликтные: list[str] = []
    сделано: set[str] = set()
    переименованные: dict[str, str] = {}

    def содержимое(в_базе: str, в_слиянии: str, в_пакете: str) -> None:
        """Чем станет файл пакета. Пишет в план, либо называет конфликт."""
        их = репо / в_слиянии
        баз = наша / в_базе
        наш = пакет / переименованные.get(в_пакете, в_пакете)
        if not наш.is_file():
            план.append(("записать", в_пакете, их.read_bytes(), "новых"))
            return
        наши_байты = наш.read_bytes()
        if not баз.is_file():
            # База неизвестна: наложить его правку нечем. Берём его файл и
            # говорим об этом числом, а не молчим.
            if наши_байты != их.read_bytes():
                план.append(("записать", в_пакете, их.read_bytes(), "без_базы"))
            return
        if наши_байты == баз.read_bytes():
            if наши_байты != их.read_bytes():       # преобразование файл не коснулось
                план.append(("записать", в_пакете, их.read_bytes(), "правлено"))
            return
        with tempfile.TemporaryDirectory(prefix="слияние-файла-") as двор:
            копия = Path(двор) / "ours"
            копия.write_bytes(наши_байты)
            готово = subprocess.run(
                ["git", "merge-file", "--diff3", str(копия), str(баз), str(их)],
                capture_output=True, text=True)
            if готово.returncode != 0:
                конфликтные.append(в_пакете)
                return
            слито = копия.read_bytes()
        if слито != наши_байты:
            план.append(("записать", в_пакете, слито, "правлено"))

    for старое, новое in переименования:
        сделано.update({старое, новое})
        п_старое, п_новое = (путь_в_пакете(старое, переносы),
                             путь_в_пакете(новое, переносы))
        if (пакет / п_старое).is_file():
            план.append(("переименовать", п_старое, п_новое))
            переименованные[п_новое] = п_старое
        # Пропуск — про СОДЕРЖИМОЕ (там лежит заготовка или файл публикатора),
        # но имя обязано переехать: данные сборки называют новое, и под старым
        # именем подмена заготовкой перестаёт срабатывать МОЛЧА. Сверка этого не
        # видит — пропущенные пути она не сравнивает по определению.
        if старое in пропуск or новое in пропуск:
            continue
        содержимое(старое, новое, п_новое)

    в_слиянии, в_нашей = файлы_дерева(репо), файлы_дерева(наша)
    for путь in sorted(в_слиянии - сделано):
        if путь in пропуск:
            continue
        содержимое(путь, путь, путь_в_пакете(путь, переносы))
    for путь in sorted(в_нашей - в_слиянии - сделано):
        if путь in пропуск:
            continue
        в_пакете = путь_в_пакете(путь, переносы)
        if (пакет / в_пакете).is_file():
            план.append(("удалить", в_пакете))
    return план, конфликтные, сделано


def перенести(репо: Path, наша: Path, пакет: Path, переименования: list,
              пропуск: set[str], переносы: list) -> dict:
    """Перенести его правки в пакет по посчитанному плану. Числа — вслух."""
    план, конфликтные, _ = спланировать(репо, наша, пакет, переименования,
                                        пропуск, переносы)
    if конфликтные:
        raise Отказ("конфликт при переносе в пакет (пакет НЕ тронут, "
                    f"разбирать по месту): {', '.join(конфликтные)}")

    счёт = {"переименовано": 0, "правлено": 0, "новых": 0, "удалено": 0,
            "пропущено": len(пропуск), "без_базы": 0}
    for действие in план:
        вид = действие[0]
        if вид == "переименовать":
            _, п_старое, п_новое = действие
            (пакет / п_новое).parent.mkdir(parents=True, exist_ok=True)
            гит(пакет, "mv", "-f", "--", п_старое, п_новое)
            счёт["переименовано"] += 1
        elif вид == "записать":
            _, в_пакете, байты, какой = действие
            цель = пакет / в_пакете
            цель.parent.mkdir(parents=True, exist_ok=True)
            цель.write_bytes(байты)
            счёт[какой] += 1
        else:
            _, в_пакете = действие
            гит(пакет, "rm", "-q", "-f", "--", в_пакете)
            счёт["удалено"] += 1
    return счёт


def слепок(пакет: Path, куда: Path) -> Path:
    """Копия РАБОЧЕГО дерева пакета со своей историей из одного коммита.

    Сборка берёт источник из `git archive HEAD` — и это правильно: каталог ≠
    коммит, и незакоммиченная правка уехала бы наружу мимо замков публикации.
    Но догоняние оставляет свои правки НЕЗАКОММИЧЕННЫМИ (сообщение коммита и
    трейлер карты пишет смена), поэтому сверять надо рабочее дерево — на копии,
    чтобы история настоящего пакета осталась его.
    """
    куда.mkdir(parents=True, exist_ok=True)   # rsync не создаёт вложенный путь сам
    готово = subprocess.run(
        ["rsync", "-a", "--exclude", ".git/", f"{пакет}/", f"{куда}/"],
        capture_output=True, text=True)
    if готово.returncode != 0:
        raise Отказ(f"копия пакета не снята: {готово.stderr.strip()}")
    subprocess.run(["git", "init", "-q", "-b", "master", str(куда)],
                   capture_output=True, text=True)
    гит(куда, "add", "-A")
    гит(куда, "-c", "user.name=harness", "-c", "user.email=harness@local",
        "commit", "-q", "--allow-empty", "-m", "слепок рабочего дерева")
    return куда


def сверить(пакет: Path, репо: Path, паспорт: Path, пропуск: set[str],
            работа: Path) -> tuple[int, list[str]]:
    """Собрать догнавший пакет и сверить со слитым деревом: это и есть довод."""
    снова = работа / "сверка"
    собрать(слепок(пакет, работа / "слепок"), снова, паспорт)
    расхождения = []
    for путь in sorted(файлы_дерева(снова) | файлы_дерева(репо)):
        if путь in пропуск:
            continue
        а, б = снова / путь, репо / путь
        if not а.is_file():
            расхождения.append(f"нет в сборке пакета: {путь}")
        elif not б.is_file():
            расхождения.append(f"нет в слитом дереве: {путь}")
        elif а.read_bytes() != б.read_bytes():
            расхождения.append(f"разное содержимое: {путь}")
    return len(файлы_дерева(снова)), расхождения


def догнать(пакет: Path, сборка: Path, удалённый: str, ветка: str,
            паспорт: Path, только_проверка: bool) -> int:
    _, данные = данные_сборки(пакет)
    грязь = гит(пакет, "status", "--porcelain").strip()
    if грязь and not только_проверка:
        raise Отказ("пакет не чист — догоняние началось бы с чужой правки:\n"
                    + "\n".join(грязь.splitlines()[:10]))

    работа = Path(tempfile.mkdtemp(prefix="dognat-"))
    убрать = True
    try:
        наша = работа / "наша"
        собрать(пакет, наша, паспорт)
        репо, наш_коммит, переименования, конфликты, от_публикатора = слить(
            сборка, наша, удалённый, ветка, работа)
        if конфликты:
            убрать = False
            print(f"ОТКАЗ: конфликт в слиянии ({len(конфликты)}): "
                  f"{', '.join(конфликты)}")
            print(f"дерево слияния оставлено для разбора: {репо}")
            print(f"разобрать, закоммитить там же — и продолжить: "
                  f"python3 scripts/catch-up-public.py --продолжить {репо}")
            return 1

        пропуск = от_публикатора | подменяемые_заготовкой(данные, репо)
        переносы = обратный_перенос(данные)
        # Пропущенное из меры ИСКЛЮЧЕНО: VERSION он перезаписывает каждой
        # публикацией, и с ним число никогда не вернулось бы к нулю — дверь
        # «догонять нечего» была бы мертва (находка ревью F-gen-09).
        его_правок = len([с for с in гит(репо, "diff", "--name-only",
                                         наш_коммит, "HEAD").splitlines()
                          if с and с not in пропуск])
        print(f"расхождение: его правок файлов {его_правок}, "
              f"переименований {len(переименования)}, "
              f"не переносится {len(пропуск)}: {', '.join(sorted(пропуск))}")
        if только_проверка:
            return 0
        if not его_правок:
            print("догонять нечего: публичная ветка не ушла вперёд")
            return 0

        счёт = перенести(репо, наша, пакет, переименования, пропуск, переносы)
        print("перенесено в пакет: " + ", ".join(f"{к} {з}" for к, з in счёт.items()))
        файлов, расхождения = сверить(пакет, репо, паспорт, пропуск, работа)
        if расхождения:
            print(f"ОТКАЗ сверки: сборка догнавшего пакета не совпала со слитым "
                  f"деревом, расхождений {len(расхождения)}")
            for строка in расхождения[:20]:
                print("  " + строка)
            return 1
        print(f"СВЕРКА ЗЕЛЁНАЯ: сборка пакета совпала со слитым деревом, "
              f"файлов {файлов}, расхождений 0")
        догнали = перевести_сборку(сборка, удалённый, ветка)
        print(f"ветка каталога публикации переведена вперёд на {догнали} коммитов "
              f"— замок «только вперёд» в publish.sh больше не откажет")
        return 0
    finally:
        if убрать:
            shutil.rmtree(работа, ignore_errors=True)


def продолжить(пакет: Path, репо: Path, паспорт: Path, сборка: Path,
               удалённый: str, ветка: str) -> int:
    """Перенести в пакет УЖЕ РАЗОБРАННОЕ человеком слияние.

    Отказ по конфликту без этой двери делал прибор бесполезным ровно в том
    случае, ради которого он написан: оба агента правили один файл
    ([[a-guard-without-a-legal-door]]). Разбор идёт в оставленном каталоге
    (git mergetool, правка руками, `git commit`), а перенос и сверку делает
    та же механика, что в здоровом случае.
    """
    if не_разобрано := [с for с in гит(репо, "diff", "--name-only",
                                       "--diff-filter=U").splitlines() if с]:
        raise Отказ(f"в слиянии остались неразобранные файлы: "
                    f"{', '.join(не_разобрано)}")
    if гит(репо, "status", "--porcelain").strip():
        raise Отказ("слияние разобрано, но не закоммичено — `git -C "
                    f"{репо} commit` и позови снова")
    родители = гит(репо, "rev-parse", "HEAD^@").split()
    if len(родители) != 2:
        raise Отказ(f"в {репо} верхний коммит не слияние (родителей "
                    f"{len(родители)}) — это не разобранное догоняние")
    наш_коммит = родители[0]
    if "наша сборка" not in гит(репо, "log", "-1", "--format=%s", наш_коммит):
        raise Отказ("первый родитель слияния — не «наша сборка»: каталог не от "
                    "этого прибора")
    грязь = гит(пакет, "status", "--porcelain").strip()
    if грязь:
        raise Отказ("пакет не чист — перенос лёг бы на чужую правку:\n"
                    + "\n".join(грязь.splitlines()[:10]))

    _, данные = данные_сборки(пакет)
    работа = Path(tempfile.mkdtemp(prefix="dognat-dalshe-"))
    try:
        наша = работа / "наша"
        собрать(пакет, наша, паспорт)
        # Пакет мог уехать, пока человек разбирал конфликт: тогда перенос лёг бы
        # на другую базу и соврал бы молча.
        было = работа / "было"
        было.mkdir()
        архив = subprocess.run(["git", "-C", str(репо), "archive", наш_коммит],
                               capture_output=True)
        subprocess.run(["tar", "-x", "-C", str(было)], input=архив.stdout,
                       capture_output=True)
        от_публикатора = файлы_дерева(было) - файлы_дерева(наша)
        разошлось = [п for п in файлы_дерева(наша)
                     if not (было / п).is_file()
                     or (было / п).read_bytes() != (наша / п).read_bytes()]
        if разошлось:
            raise Отказ(f"пакет изменился после слияния ({len(разошлось)} файлов, "
                        f"например {разошлось[0]}) — догоняй заново")

        поля = гит(репо, "diff", "-M", "-z", "--name-status",
                   наш_коммит, "HEAD").split("\0")
        переименования, i = [], 0
        while i < len(поля) and поля[i]:
            if поля[i][0] in "RC":
                переименования.append((поля[i + 1], поля[i + 2])); i += 3
            else:
                i += 2
        пропуск = от_публикатора | подменяемые_заготовкой(данные, репо)
        счёт = перенести(репо, наша, пакет, переименования, пропуск,
                         обратный_перенос(данные))
        print("перенесено в пакет: " + ", ".join(f"{к} {з}" for к, з in счёт.items()))
        файлов, расхождения = сверить(пакет, репо, паспорт, пропуск, работа)
        if расхождения:
            print(f"ОТКАЗ сверки: сборка догнавшего пакета не совпала со слитым "
                  f"деревом, расхождений {len(расхождения)}")
            for строка in расхождения[:20]:
                print("  " + строка)
            return 1
        print(f"СВЕРКА ЗЕЛЁНАЯ: сборка пакета совпала со слитым деревом, "
              f"файлов {файлов}, расхождений 0")
        догнали = перевести_сборку(сборка, удалённый, ветка)
        print(f"ветка каталога публикации переведена вперёд на {догнали} коммитов "
              f"— замок «только вперёд» в publish.sh больше не откажет")
        return 0
    finally:
        shutil.rmtree(работа, ignore_errors=True)


