def найти_пакет(конф: str = "/etc/harness/harness.conf") -> tuple[Path | None, str]:
    """(каталог пакета, причина отсутствия). STARTER_DIR → поиск по домам."""
    значение = ""
    try:
        for line in Path(конф).read_text(encoding="utf-8").splitlines():
            m = re.match(r'\s*STARTER_DIR\s*=\s*"?([^"#\s]*)"?', line)
            if m:
                значение = m.group(1)
    except OSError:
        pass
    if значение:
        p = Path(значение)
        if p.is_dir():
            return p, ""
        return None, f"STARTER_DIR={значение} в {конф} указывает на несуществующий каталог"
    # STARTER_DIR пуст — ищем по конвенции установки, у АГЕНТА.
    # Не перебором /home/*: чужие домашние каталоги закрыты на чтение, и обход
    # падал PermissionError на первом же соседе (поймано первым прогоном).
    агент = ""
    try:
        for line in Path("/etc/harness/install.conf").read_text(encoding="utf-8").splitlines():
            m = re.match(r'\s*AGENT_USER\s*=\s*"?([^"#\s]*)"?', line)
            if m:
                агент = m.group(1)
    except OSError:
        pass
    if агент:
        p = Path("/home") / агент / "starter" / "STARTER-PACKAGE"
        if p.is_dir():
            return p, ""
        return None, f"каталог пакета не найден: STARTER_DIR пуст, и {p} не существует"
    return None, ("каталог пакета не найден: STARTER_DIR в /etc/harness/harness.conf пуст, "
                  "AGENT_USER в /etc/harness/install.conf тоже")


def место_в_пакете(путь: str) -> str | None:
    """Проектный путь → путь внутри пакета. None — файл не из пакета."""
    # Длинные префиксы раньше коротких — иначе scripts/hooks/ уедет в scripts/.
    for проектное in sorted(СООТВЕТСТВИЯ, key=len, reverse=True):
        if проектное.endswith("/"):
            if путь.startswith(проектное):
                return СООТВЕТСТВИЯ[проектное] + путь[len(проектное):]
        elif путь == проектное:
            return СООТВЕТСТВИЯ[проектное]
    return None


def скилы_наборов(пакет: Path) -> set[str]:
    """Имена скилов, которые рождает установка набора возможностей.

    В пакете таких скилов нет и быть не должно: пока набор не установлен, его
    скилы не собираются и контекст сессии чист (МАНИФЕСТ.conf, ключ SKILLS).
    Требовать их в пакете — требовать того, что противоречит замыслу набора.
    """
    имена: set[str] = set()
    for манифест in (пакет / "harness/vozmozhnosti").glob("*/МАНИФЕСТ.conf"):
        for line in манифест.read_text(encoding="utf-8").splitlines():
            m = re.match(r'\s*SKILLS\s*=\s*"([^"]*)"', line)
            if m:
                имена.update(m.group(1).split())
    return имена


def живой(путь: str, скилы: set[str] = frozenset()) -> bool:
    # Метка установки набора — свойство ЭТОГО сервера, не пакета: раскладка
    # снимает её и возвращает, а не копирует (razlozhit-harnes.sh).
    if путь.endswith("/.установлено"):
        return True
    части = путь.split("/")
    if len(части) > 2 and части[0] == "harness" and части[1] == "skills" and части[2] in скилы:
        return True
    return any(путь == ж or путь.startswith(ж) for ж in ЖИВЫЕ)


def из_индекса(путь: str, корень: Path) -> bytes | None:
    """Содержимое файла В ИНДЕКСЕ. None — файла в индексе нет (удалён).

    cwd=корень обязателен: без него git спрашивает тот репозиторий, в котором
    запущен процесс, не находит файла и молча возвращает None — гейт зеленел
    бы на любом расхождении (поймано первым прогоном селфтеста).
    """
    готово = subprocess.run(["git", "show", f":{путь}"], capture_output=True, cwd=корень)
    return готово.stdout if готово.returncode == 0 else None


def пары_раскладчика(текст: str) -> set[tuple[str, str]]:
    """(источник в пакете, назначение в проекте) из cp-строк razlozhit-harnes.sh.

    Второй источник истины запрещён: таблица выше и раскладчик обязаны
    описывать одно и то же. Разъедутся — краснеет селфтест, а не сервер
    через месяц.
    """
    пары: set[tuple[str, str]] = set()
    # Источник бывает не в самой строке укладки, а в заголовке цикла над ней:
    #     for f in "$HERE"/config/*.yaml; do … polozhit_fajl "$f" "$PROJECT_DIR/…"
    # Так сделана укладка настроек, которые нельзя затирать (живые данные
    # владельца). До 12.09.2026 проверка такую пару не видела и краснела на
    # исправной раскладке — а краснеющий без причины сторож отключают.
    из_цикла: list[str] = []
    for строка in текст.splitlines():
        заголовок = re.match(r'\s*for\s+\w+\s+in\s+(.+);\s*do', строка)
        if заголовок and "$HERE" in заголовок.group(1):
            куски = re.findall(r'"\$HERE"/([^\s"]+)|"\$HERE/([^"]+)"', заголовок.group(1))
            из_цикла = [a or b for a, b in куски]
            continue
        if "$HERE" not in строка and not из_цикла:
            continue
        # Раскладчик кладёт файлы двумя способами: cp (источник → назначение) и
        # polozhit_v/polozhit_fajl (назначение первым доводом — запись через
        # временный файл и mv, чтобы не писать в inode работающего процесса).
        # Проверка обязана понимать оба: 11.09.2026 перевод на mv сделал её
        # слепой к пяти правилам сразу, и самотест честно покраснел.
        if строка.lstrip().startswith(("polozhit_v", "polozhit_fajl")):
            назначение = re.search(r'"\$PROJECT_DIR/([^"]*)"', строка)
            куски = re.findall(r'"\$HERE"/([^\s"]+)|"\$HERE/([^"]+)"', строка)
            источники = [a or b for a, b in куски] or из_цикла
            if not (назначение and источники):
                continue
            цель = назначение.group(1)
            if not цель.endswith("/"):
                цель += "/"
            for и in источники:
                и = re.sub(r"/\*[^/]*$", "/", и)
                конец = цель if и.endswith("/") else назначение.group(1)
                # Имя файла подставляется переменной («…/config/$name») — это
                # укладка ЦЕЛОГО каталога, а не одного файла: хвост убираем,
                # иначе пара не совпадёт с таблицей ни при каком составе.
                конец = re.sub(r"\$\{?\w+\}?/?$", "", конец)
                пары.add((и, конец))
            continue
        if "cp " not in строка:
            continue
        куски = re.findall(r'"\$HERE"/([^\s"]+)|"\$HERE/([^"]+)"', строка)
        источники = [a or b for a, b in куски]
        m = re.search(r'"\$PROJECT_DIR/([^"]*)"', строка)
        if not (источники and m):
            continue
        назначение = m.group(1)
        for и in источники:
            # cp -f "$HERE"/hooks/*.py … "$PROJECT_DIR/scripts/hooks/" — маска
            # означает «весь каталог», а не конкретный файл.
            и = re.sub(r"/\*[^/]*$", "/", и)
            если_каталог = и.endswith("/")
            цель = назначение if назначение.endswith("/") else назначение
            if если_каталог and not цель.endswith("/"):
                цель += "/"
            пары.add((и, цель))
    return пары


def незакоммиченное_в_пакете(пакет: Path) -> list[str]:
    """Файлы пакета, не попавшие в его СОБСТВЕННУЮ историю.

    Гейт сверки сторожил содержимое: файл в проекте обязан совпасть с файлом в
    пакете. Сохранность он не сторожил вовсе — и 10.09.2026 замер показал 38
    незакоммиченных правок в пакете при последнем коммите от 27.08: содержимое
    сходилось, а история за две недели не велась. Потеря каталога пакета
    означала бы потерю харнеса как отдельного инструмента. Правило одно, путей
    два — второй теперь тоже перекрыт.

    Пустой список — пакет чист либо не является репозиторием (тогда сторожить
    нечего, и молчание честнее отказа).
    """
    итог = subprocess.run(["git", "-C", str(пакет), "-c", "core.quotepath=false",
         "status", "--porcelain"],
                          capture_output=True)
    if итог.returncode != 0:
        return []
    return [с for с in итог.stdout.decode("utf-8", "replace").splitlines() if с.strip()]


def сверить_таблицу_с_раскладчиком(раскладчик: Path) -> list[str]:
    """Беды рассинхрона таблицы и cp-строк. Пустой список — сходится."""
    try:
        текст = раскладчик.read_text(encoding="utf-8")
    except OSError as e:
        return [f"раскладчик не прочитан ({раскладчик}): {e}"]
    пары = пары_раскладчика(текст)
    беды = []
    for проектное, пакетное in СООТВЕТСТВИЯ.items():
        # Путь внутри пакета в cp-строках отсчитывается от каталога harness/.
        источник = пакетное[len("harness/"):]
        цель = проектное
        # cp -rf "$HERE"/skills … "$PROJECT_DIR/harness/" — каталог кладётся
        # ВНУТРЬ назначения под своим именем.
        варианты = {(источник, цель),
                    (источник.rstrip("/"), цель.rsplit(источник.rstrip("/"), 1)[0]),
                    (источник.rstrip("/"), "harness/"),
                    (источник, цель.rsplit("/", 2)[0] + "/" if "/" in цель else цель)}
        if not (пары & варианты):
            беды.append(f"в таблице есть «{проектное} → {пакетное}», а cp-строки в "
                        f"{раскладчик.name} такого не копируют")
    return беды


def проверить(файлы: list[str], пакет: Path, корень: Path) -> tuple[int, list[str]]:
    """rc и строки отчёта."""
    беды: list[str] = []
    расходящиеся: list[tuple[str, str]] = []
    харнесных = 0
    скилы = скилы_наборов(пакет)
    for путь in файлы:
        if живой(путь, скилы):
            continue
        пакетный = место_в_пакете(путь)
        if пакетный is None:
            continue                      # не файл харнеса — не наше дело
        харнесных += 1
        содержимое = из_индекса(путь, корень)
        if содержимое is None:
            continue                      # файл удаляется — сверять нечего
        цель = пакет / пакетный
        if not цель.exists():
            беды.append(f"  {путь}\n      в пакете НЕТ файла {цель}")
            расходящиеся.append((путь, str(цель)))
        elif цель.read_bytes() != содержимое:
            беды.append(f"  {путь}\n      расходится с {цель}")
            расходящиеся.append((путь, str(цель)))

    if беды:
        отчёт = ["РАСХОЖДЕНИЕ С ПАКЕТОМ: раскладка копирует пакет → проект,",
                 "правка только здесь умрёт при следующем razlozhit-harnes.sh.",
                 ""]
        отчёт += беды
        отчёт += ["", "Скопируйте в пакет и повторите коммит:"]
        отчёт += [f"  cp {корень / п} {ц}" for п, ц in расходящиеся]
        return 1, отчёт

    if харнесных:
        грязь = незакоммиченное_в_пакете(пакет)
        if грязь:
            отчёт = [f"В пакете {len(грязь)} незакоммиченных файл(ов): у него своя "
                     f"история, и она отстаёт.",
                     "Раскладка копирует пакет → проект; потеря каталога пакета —",
                     "потеря харнеса как отдельного инструмента.", ""]
            отчёт += [f"  {с}" for с in грязь[:10]]
            if len(грязь) > 10:
                отчёт.append(f"  … и ещё {len(грязь) - 10}")
            отчёт += ["", f"Закоммить пакет и повтори: git -C {пакет} add -A && "
                          f"git -C {пакет} commit"]
            return 1, отчёт
        журнал = корень / ЖУРНАЛ_В_ПРОЕКТЕ
        сегодня = date.today().strftime("%d.%m")
        текст = журнал.read_text(encoding="utf-8") if журнал.exists() else ""
        if f"| {сегодня} |" not in текст:
            return 1, [f"Файлы харнеса изменены ({харнесных}), а записи за {сегодня} "
                       f"в журнале нет.",
                       f"Допишите строку со статусом доказанности: {журнал}",
                       "Статусы: «доказано здесь» · «доказано селфтестом» · «ждёт чистого VPS»."]
    return 0, [f"[сверка с пакетом] файлов харнеса в коммите: {харнесных} — совпадают с пакетом"]


def main() -> int:
    if len(sys.argv) > 1 and sys.argv[1] == "--selftest":
        return селфтест()
    файлы = [s.strip() for s in sys.stdin.read().splitlines() if s.strip()]
    пакет, причина = найти_пакет()
    if пакет is None:
        # Не молчать и не валить коммит: сверка невозможна — сказать, где чинить.
        print(f"[сверка с пакетом] НЕВОЗМОЖНА: {причина}")
        print("[сверка с пакетом] задайте STARTER_DIR в /etc/harness/harness.conf")
        return 0
    корень = Path(subprocess.run(["git", "rev-parse", "--show-toplevel"],
                                 capture_output=True, text=True).stdout.strip() or ".")
    rc, строки = проверить(файлы, пакет, корень)
    print("\n".join(строки))
    return rc


# ─────────────────────────────── селфтест ───────────────────────────────────
def селфтест() -> int:
    import shutil
    import tempfile

    ok = True

    def проба(имя: str, ждём, факт) -> None:
        nonlocal ok
        if факт == ждём:
            print(f"  ок    {имя}")
        else:
            print(f"  ПЛОХО {имя}: ждали {ждём!r}, получили {факт!r}")
            ok = False

    # ── разбор путей: длинный префикс раньше короткого ──────────────────────
    проба("scripts/hooks/ не уезжает в правило scripts/",
          "harness/hooks/guard_bash.py", место_в_пакете("scripts/hooks/guard_bash.py"))
    проба("scripts/", "harness/scripts/deploy.sh", место_в_пакете("scripts/deploy.sh"))
