БЕЗ_ПРИСМОТРА = "с расписанием, но без присмотра:"

ОК, УПАЛО = [], []


def проба(имя: str, условие: bool, подробность: str = "") -> None:
    (ОК if условие else УПАЛО).append(имя)
    знак = "✓" if условие else "✗"
    print(f"  {знак} {имя}" + (f" — {подробность}" if подробность and not условие else ""))


def _md5(путь: Path) -> str:
    return hashlib.md5(путь.read_bytes()).hexdigest() if путь.exists() else "нет файла"


def _слепок_боевых() -> dict:
    """md5 всего, что сборщик читает или мог бы задеть."""
    слепок = {f"config/{п.name}": _md5(п)
              for п in sorted((КОРЕНЬ / "harness" / "config").glob("*.yaml"))}
    слепок["/etc/harness/harness.conf"] = _md5(КОНФИГ_БОЕВОЙ)
    return слепок


def имена_и_сроки(текст: str) -> dict:
    """HEARTBEAT_PERIODS из текста harness.conf → {имя: минуты}.

    Свой разбор, не чужой: число, прочитанное из вывода сборщика, было бы
    пересказом сборщика самому себе ([[проверка-создаёт-условие]]).
    """
    строка = None
    for s in текст.splitlines():
        m = re.match(r'\s*HEARTBEAT_PERIODS="([^"]*)"', s)
        if m:
            строка = m.group(1)
    if строка is None:
        return {}
    return {п.split(":")[0]: int(п.split(":")[1]) for п in строка.split()}


СЛЕПОК_ДО = _слепок_боевых()
ЖИВЫЕ_СРОКИ = имена_и_сроки(КОНФИГ_БОЕВОЙ.read_text(encoding="utf-8"))


# ─── подставной вход: свои паспорта, свои имена, свои числа ────────────────
def метка(имя: str, минут: int) -> dict:
    return {"имя": имя, "молчание_считать_поломкой": минут}


def повод(источник: str, расписание: str, *метки) -> dict:
    """Структура `повод` паспорта. `метки` — ВСЕГДА список, даже одна."""
    return {"источник": источник, "расписание": расписание, "метки": list(метки)}


def паспорт(файл: str, имя: str, повод_=None) -> dict:
    """Паспорт v1 (девять обязательных полей) плюс необязательный `повод`."""
    п = {
        "файл": файл,
        "вид": "демон",
        "тема": "присмотр за собой",
        "имя": имя,
        "роль": "Делает свою работу по расписанию.",
        "когда": "по расписанию",
        "без_него": "Работа не делается, и этого никто не замечает.",
        "проверяется": f"bash {файл} --selftest",
        "пишет": "метку в HEARTBEAT_DIR",
    }
    if повод_ is not None:
        п["повод"] = повод_
    return п


