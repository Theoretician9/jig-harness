проба("HEARTBEAT_PERIODS из комментария не читается — сверка всё равно сошлась",
      rc_к == 0 and "призрак" not in вывод_к,
      f"rc={rc_к}, вывод: {вывод_к[:300]!r}")

print("── расхождение названо ПОИМЁННО в обе стороны ──")
# Главное требование Task 6. «Множества не равны» — не ответ: по такому
# сообщению чинить нечего, и оно неотличимо от «расхождение в одну сторону».
rc_нк, вывод_нк, _ = проверить(ДВА_ДЕМОНА, {"alpha": 10})
красный_с_причиной("имя из реестра, которого нет в конфиге, названо и красит",
                   rc_нк, вывод_нк, НЕТ_В_КОНФИГЕ, "beta")
СТРОКА_НК = строка_с(вывод_нк, НЕТ_В_КОНФИГЕ)
# Сошедшееся имя в списке расхождений — сборщик, печатающий весь реестр вместо
# разницы: отчёт выглядит подробным и не говорит, что чинить.
проба("имя, которое сошлось, в список расхождений не попало",
      "beta" in СТРОКА_НК and "alpha" not in СТРОКА_НК,
      f"строка расхождения: {СТРОКА_НК!r}")

rc_нр, вывод_нр, _ = проверить(ДВА_ДЕМОНА,
                               {"alpha": 10, "beta": 1440, "gamma": 60})
красный_с_причиной("имя из конфига, которого нет в реестре, названо и красит",
                   rc_нр, вывод_нр, НЕТ_В_РЕЕСТРЕ, "gamma")

# Ловушка «печатает первую разницу и выходит»: расхождение бывает двусторонним,
# и половина, напечатанная без второй, читается как полный ответ.
rc_об, вывод_об, _ = проверить(ДВА_ДЕМОНА, {"alpha": 10, "gamma": 60})
красный_с_причиной("двустороннее расхождение печатает ОБЕ стороны разом",
                   rc_об, вывод_об, НЕТ_В_КОНФИГЕ, "beta", НЕТ_В_РЕЕСТРЕ, "gamma")

print("── sentinel: таймер systemd берётся наравне с кроном ──")
# Первый из двух законных случаев «без крона» (спека §0). Сборщик, отбирающий
# паспорта по расписанию крона, потеряет sentinel — и сверка объявит его
# ЛИШНИМ в конфиге, то есть предложит снять присмотр за подъёмом после
# падения. Двор нарочно состоит из одного sentinel: на смешанном дворе потеря
# утонула бы среди совпавших имён.
ТОЛЬКО_SENTINEL = [паспорт("harness/demons/sentinel.sh", "Подъём после падения",
                           повод("таймер", "harness-sentinel.timer",
                                 метка("sentinel", 5)))]
rc_с, вывод_с, _ = проверить(ТОЛЬКО_SENTINEL, {"sentinel": 5})
сошлось("паспорт с источником «таймер» попал в сборку — сверка сошлась",
        rc_с, вывод_с, СОШЛОСЬ, "имён 1")
проба("sentinel не объявлен лишним в конфиге",
      rc_с == 0 and НЕТ_В_РЕЕСТРЕ not in вывод_с,
      f"rc={rc_с}, вывод: {вывод_с[:300]!r}")
# Обратная сторона того же: если убрать sentinel из конфига, сборщик обязан
# назвать его — иначе «сошлось» выше могло получиться от пустой сборки.
rc_сб, вывод_сб, _ = проверить(ТОЛЬКО_SENTINEL, {})
красный_с_причиной("без строки в конфиге sentinel назван поимённо",
                   rc_сб, вывод_сб, НЕТ_В_КОНФИГЕ, "sentinel")

print("── session-warden.запуск: вторая метка одного демона ──")
# Второй законный случай. Паспорт у файла ровно один, а меток у демона две:
# `session-warden` ставится прогоном сторожа, `session-warden.запуск` —
# подъёмом смены (session-warden.sh:1317, читает sentinel.sh:249). Сборщик,
# берущий одну метку на паспорт, потеряет вторую молча.
ДВЕ_МЕТКИ = [паспорт("harness/demons/session-warden.sh", "Надзиратель рабочих окон",
                     повод("крон", "*/10 * * * *",
                           метка("session-warden", 10),
                           метка("session-warden.запуск", 10)))]
rc_дм, вывод_дм, _ = проверить(ДВЕ_МЕТКИ,
                               {"session-warden": 10, "session-warden.запуск": 10})
сошлось("один паспорт дал ДВА имени — сверка сошлась, «имён 2»",
        rc_дм, вывод_дм, СОШЛОСЬ, "имён 2")
# Доказательство, что вторая метка действительно собрана, а не совпала
# случайно: снимаем её из конфига — сборщик обязан назвать именно её.
rc_вм, вывод_вм, _ = проверить(ДВЕ_МЕТКИ, {"session-warden": 10})
красный_с_причиной("вторая метка, снятая из конфига, названа поимённо",
                   rc_вм, вывод_вм, НЕТ_В_КОНФИГЕ, "session-warden.запуск")

print("── имя метки берётся из данных, а не из имени файла ──")
# Улика §0: сирота `check-srok-vhoda` жил в scripts/ и звался в кроне через
# python3 — имя, выведенное из пути, дало бы `check-srok-vhoda.py` и не
# сошлось бы с конфигом никогда. Метод замера сам создал слепое пятно.
ИМЯ_НЕ_ИЗ_ПУТИ = [паспорт("scripts/check-srok-vhoda.py", "Сторож срока входа",
                          повод("крон", "*/30 * * * *",
                                метка("check-srok-vhoda", 30)))]
rc_ип, вывод_ип, _ = проверить(ИМЯ_НЕ_ИЗ_ПУТИ, {"check-srok-vhoda": 30})
сошлось("имя метки взято из поля, а не из basename файла",
        rc_ип, вывод_ип, СОШЛОСЬ)
проба("в выводе нет выдуманного имени метки с расширением",
      rc_ип == 0 and "check-srok-vhoda.py:" not in вывод_ип,
      f"rc={rc_ип}, вывод: {вывод_ип[:300]!r}")

print("── срок числом (сверх буквы плана: «совпадает как множество») ──")
# Множества имён равны, а сторож пульса ждёт протухшую метку вшестеро дольше.
# Расхождение числом молчит ровно так же, как расхождение именем.
rc_сч, вывод_сч, _ = проверить(ДВА_ДЕМОНА, {"alpha": 60, "beta": 1440})
красный_с_причиной("разошедшийся срок назван с именем и ОБОИМИ числами",
                   rc_сч, вывод_сч, СРОК_РАЗОШЁЛСЯ, "alpha",
                   "в реестре 10", "в конфиге 60")
проба("имена при этом лишними не объявлены — разница именно в числе",
      _красный_годен(rc_сч, вывод_сч, [СРОК_РАЗОШЁЛСЯ])
      and НЕТ_В_КОНФИГЕ not in вывод_сч and НЕТ_В_РЕЕСТРЕ not in вывод_сч,
      f"rc={rc_сч}, вывод: {вывод_сч[:300]!r}")

print("── расписание есть, присмотра нет (сверх буквы плана: болезнь §0) ──")
# Механизм с расписанием и пустым списком меток не попадает НИ В ОДНО
# множество: сверка сошлась бы, а демон остался бы без присмотра — ровно то,
# чем 13.09 оказался check-srok-vhoda. Сборщик обязан назвать его поимённо.
БЕЗНАДЗОРНЫЙ = [паспорт("harness/demons/alpha.sh", "Альфа",
                        повод("крон", "*/10 * * * *", метка("alpha", 10))),
                паспорт("harness/demons/omega.sh", "Омега",
                        повод("крон", "*/5 * * * *"))]
rc_бн, вывод_бн, _ = проверить(БЕЗНАДЗОРНЫЙ, {"alpha": 10})
красный_с_причиной("механизм с расписанием и без меток назван поимённо",
                   rc_бн, вывод_бн, БЕЗ_ПРИСМОТРА, "Омега")
проба("безнадзорный не выдан за «лишнее имя в конфиге»",
      _красный_годен(rc_бн, вывод_бн, [БЕЗ_ПРИСМОТРА])
      and "omega" not in строка_с(вывод_бн, НЕТ_В_РЕЕСТРЕ)
      and "omega" not in строка_с(вывод_бн, НЕТ_В_КОНФИГЕ),
      f"rc={rc_бн}, строки расхождений: "
      f"{строка_с(вывод_бн, НЕТ_В_РЕЕСТРЕ)!r} / {строка_с(вывод_бн, НЕТ_В_КОНФИГЕ)!r}")

print("── сборщик НИЧЕГО не пишет ──")
# Правило Шага 5 Task 6: писателем настроек остаётся scripts/zapisat-klyuch.py.
# Сборщик, дописавший недостающее сам, чинил бы расхождение вместо того, чтобы
# его показать, — и делал бы это молча, из-под крона.
# Прогон обязан СОСТОЯТЬСЯ: «файлы целы, потому что сборщика нет» — это путь,
# совпавший с машиной, а не проба ([[проверка-создаёт-условие]]).
проба("на сошедшемся дворе реестр и конфиг побайтово те же",
      rc_ок != НЕТ_СБОРЩИКА and целы_ок,
      f"rc={rc_ок}, целы={целы_ок}")
rc_расх, _, целы_расх = проверить(ДВА_ДЕМОНА, {"alpha": 10})
проба("на РАСХОДЯЩЕМСЯ дворе конфиг тоже не дописан",
      rc_расх != НЕТ_СБОРЩИКА and целы_расх,
      f"rc={rc_расх}, целы={целы_расх}")

print("── живые данные: 22 имени, расхождений нет (Шаг 4 Task 6) ──")
# Свой замер по /etc/harness/harness.conf, а не число из плана: имён в
# таблице станет больше в тот день, когда заведут новый демон.
print(f"     свой замер конфига: имён {len(ЖИВЫЕ_СРОКИ)}, "
      f"сроки от {min(ЖИВЫЕ_СРОКИ.values())} до {max(ЖИВЫЕ_СРОКИ.values())} мин")
проба("в боевом конфиге есть оба законных случая без крона",
      {"sentinel", "session-warden.запуск"} <= set(ЖИВЫЕ_СРОКИ),
      f"нет: {sorted({'sentinel', 'session-warden.запуск'} - set(ЖИВЫЕ_СРОКИ))}")
rc_ж, вывод_ж = прогон(("--проверить",))
# Останется красным, пока фаза 6 не заведёт `повод` живым паспортам: сегодня
