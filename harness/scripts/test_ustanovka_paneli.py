#!/usr/bin/env python3
"""Гейт: установщик поднимает панель, а не «ставит юнит».

СЛУЧАЙ (13.09.2026). Замер на живой чистой установке — контейнер
`harness-proba-ustanovki`: службы панели нет, пользователя `harness-panel`
нет, каталога состояния нет, прав нет. Всё это на рабочей машине заведено
РУКАМИ, а установщик про панель не знал вовсе (`grep` по `USTANOVIT.sh`: ноль
совпадений). Панель — единственное окно владельца в харнес кроме канала.

ПОЧЕМУ ГЕЙТ ЧИТАЕТ ПАКЕТ. `USTANOVIT.sh` живёт только в стартовом пакете: в
репозитории проекта его нет и в таблице соответствий `sverit-s-paketom.py` он
не значится — ни один гейт проекта на него не смотрел (ревью спеки, S-11).
Поэтому судим файл по `STARTER_DIR` из harness.conf, как это делает сверка с
пакетом.

Судятся не слова, а требования ревью спеки: группа заводится отдельно от
пользователя, агент попадает в группу панели, права sudoers ставятся 0440 и
проверяются по смыслу, порт проверяется свободным ДО запуска, юнит
перезапускается, а живая проверка идёт ВХОДОМ (`klient.py --ссылка`), потому
что `curl /` отдаёт 200 гостю и при невозможности войти.

Запуск:
    python3 scripts/test_ustanovka_paneli.py
    python3 scripts/test_ustanovka_paneli.py --selftest
Код возврата: 0 — шаг на месте, 1 — установщик не поднимает панель, 77 —
пакета нет (жёлтый: судить нечего).
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

_ЗДЕСЬ = Path(__file__).resolve().parent
sys.path.insert(0, str(_ЗДЕСЬ / "lib"))
from konf import из_файла, корень_дерева  # noqa: E402

КОРЕНЬ = Path(корень_дерева(__file__))
КОНФИГ = "/etc/harness/harness.conf"
ЖЁЛТЫЙ = 77

# Требование → как оно выглядит в тексте шага. Слева то, ради чего требование
# заведено: если строка исчезнет, пропадёт названный отказ, а не «стиль».
ТРЕБОВАНИЯ = {
    "группа заводится отдельно от пользователя (иначе юнит падает 216/GROUP)":
        r"groupadd\s+--system\s+harness-panel",
    "пользователь системный, с этой группой":
        r"useradd\s+--system\s+-g\s+harness-panel",
    "агент в группе панели (иначе ссылка входа не выдаётся молча)":
        r"usermod\s+-aG\s+harness-panel",
    "каталог состояния с setgid 2770":
        r"install\s+-d[^\n]*-m\s+2770",
    "права sudoers ставятся 0440 root:root (иначе sudo молча их игнорирует)":
        r"install\s+-o\s+root\s+-g\s+root\s+-m\s+0440",
    "синтаксис sudoers проверяется до установки файла":
        r"visudo\s+-c\s+-f",
    "право проверяется ПО СМЫСЛУ, а не по факту файла":
        r"sudo\s+-n\s+-l\s+-U\s+harness-panel",
    "порт проверяется свободным до запуска службы":
        r"connect_ex\(\('127\.0\.0\.1'",
    "юнит собирается сборщиком, а не пишется здесь":
        r"unit-paneli\.sh",
    "служба перезапускается, а не только включается":
        r"systemctl\s+restart\s+harness-panel",
    "запасной код входа выдаётся (страница обещает его словами)":
        r"vhod\.py[^\n]*--запасной-код",
    "запасной код уходит в КАНАЛ, а не в файл логов с правами 644":
        r"tg_send\.sh(.|\n){0,120}Запасной код",
    "живая проверка идёт ВХОДОМ, а не страницей":
        r"klient\.py.*--ссылка",
    "в правах подставляется и имя агента (иначе команда «панель наружу» мертва)":
        r"s\|@AGENT_USER@\|",
    "root-скрипт вывода наружу кладётся вне дерева агента":
        r"/usr/local/lib/harness",
    "диспетчер перезапускается после смены групп (живой процесс их не подхватит)":
        r"try-restart[^\n]*harness-dispatcher",
    "ненулевой код «код уже есть» погашен: под set -e он обрывал установку до отметки шага":
        r"\|\| true; \} 2>/dev/null",
    "занятый порт называет ПРОЦЕСС, а не слово «занят»":
        r"kto-na-portu\.py",
}


def файл_установщика(конфиг: str = КОНФИГ) -> Path | None:
    """USTANOVIT.sh из пакета: STARTER_DIR, иначе поиск по дому агента."""
    каталог = из_файла(конфиг).get("STARTER_DIR", "").strip()
    кандидаты = [Path(каталог)] if каталог else []
    пользователь = из_файла("/etc/harness/install.conf").get("AGENT_USER", "").strip()
    if пользователь:
        дом = Path(f"/home/{пользователь}")
        кандидаты += [дом / "starter" / "STARTER-PACKAGE", дом / "STARTER-PACKAGE"]
    for путь in кандидаты:
        if (путь / "USTANOVIT.sh").is_file():
            return путь / "USTANOVIT.sh"
    return None


def недостающее(текст: str) -> list[str]:
    """Требования, следов которых в шаге нет."""
    шаг = вырезать_шаг(текст)
    if шаг is None:
        return ["шага панели нет вовсе: функция шаг_10 не найдена"]
    пропало = [зачем for зачем, образец in ТРЕБОВАНИЙ_ПАР(ТРЕБОВАНИЯ)
               if not re.search(образец, шаг)]
    if not re.search(r"^\s*шаг_10\s*$", текст, re.M):
        пропало.append("шаг_10 определён, но не вызван в прогоне установки")
    return пропало


def ТРЕБОВАНИЙ_ПАР(таблица: dict[str, str]):
    return list(таблица.items())


def вырезать_шаг(текст: str) -> str | None:
    """Тело функции шаг_10 — от заголовка до строки «}» в начале строки."""
    начало = текст.find("шаг_10() {")
    if начало < 0:
        return None
    конец = текст.find("\n}\n", начало)
    return текст[начало:конец if конец > 0 else len(текст)]


def проверить(конфиг: str = КОНФИГ) -> int:
    путь = файл_установщика(конфиг)
    if путь is None:
        print("[установка панели] пакета нет — судить нечего (жёлтый)")
        return ЖЁЛТЫЙ
    пропало = недостающее(путь.read_text(encoding="utf-8"))
    пропало += путь_состояния_везде_один(путь)
    if not пропало:
        print(f"[установка панели] шаг панели на месте: {len(ТРЕБОВАНИЯ)} "
              f"требований, все выполнены ({путь})")
        return 0
    print(f"[установка панели] УСТАНОВКА НЕ ПОДНИМАЕТ ПАНЕЛЬ: пропало {len(пропало)}")
    for строка in пропало:
        print(f"  ✗ {строка}")
    print(f"  Файл: {путь}")
    return 1


def путь_состояния_везде_один(установщик: Path) -> list[str]:
    """Каталог состояния панели в шаге установки, в коде панели и в юните.

    Путь был записан в четырёх местах разными строками (ревью безопасности
    13.09.2026, F-sec-08): разойдясь, они дают службу, которая пишет не туда,
    куда смотрит диспетчер, — вход молча перестаёт работать.
    """
    import re as _re
    беды = []
    шаг = вырезать_шаг(установщик.read_text(encoding="utf-8")) or ""
    найдено = _re.search(r'PANEL_STATE="([^"]+)"', шаг)
    из_шага = найдено.group(1) if найдено else ""
    из_кода = ""
    настройки = КОРЕНЬ / "harness" / "panel" / "nastrojki.py"
    найдено = _re.search(r'СОСТОЯНИЕ_ПАНЕЛИ = Path\("([^"]+)"\)',
                         настройки.read_text(encoding="utf-8"))
    из_кода = найдено.group(1) if найдено else ""
    юнит = КОРЕНЬ / "harness" / "panel" / "harness-panel.service.in"
    из_юнита = set(_re.findall(r"PANEL_SECRETS_DIR=(\S+)", юнит.read_text(encoding="utf-8")))
    if not из_шага:
        беды.append("в шаге установки не найден PANEL_STATE")
    if not из_кода:
        беды.append("в nastrojki.py не найдена СОСТОЯНИЕ_ПАНЕЛИ")
    for имя, значение in (("код панели", из_кода), *(("юнит", п) for п in из_юнита)):
        if из_шага and значение and значение != из_шага:
            беды.append(f"{имя} называет {значение}, а шаг установки — {из_шага}")
    return беды


def прогон_с_отказом(установщик: Path) -> tuple[int, str]:
    """Копия установщика с нарочным `стоп` на первом шаге: код и вывод.

    --dry-run: ни одна команда не исполняется, трогается только вывод. Копия,
    а не живой файл: мутировать боевой установщик ради пробы нельзя.
    """
    import subprocess
    import tempfile
    текст = установщик.read_text(encoding="utf-8")
    битый = текст.replace("шаг_0\nшаг_1",
                          'стоп "проба" "нарочный отказ" "нет"\nшаг_0\nшаг_1', 1)
    with tempfile.TemporaryDirectory() as врем:
        копия = Path(врем) / "USTANOVIT.sh"
        копия.write_text(битый, encoding="utf-8")
        # Соседи пакета — симлинками: установщик отказывается работать без
        # harness/ рядом с собой (проверка первой же строкой), и без них проба
        # мерила бы не ловушку, а этот отказ.
        for сосед in ("harness", "UNIFIED", "razrabotka"):
            рядом = установщик.parent / сосед
            if рядом.exists():
                (Path(врем) / сосед).symlink_to(рядом)
        вышло = subprocess.run(["bash", str(копия), "--dry-run"],
                               capture_output=True, text=True, timeout=300,
                               cwd=врем)
    return вышло.returncode, вышло.stdout + вышло.stderr


def самотест() -> int:
    """Больные случаи на подставном тексте: живой пакет зелен всегда."""
    ok = True
    путей = 0

    def проба(имя: str, ждём, факт):
        nonlocal ok, путей
        путей += 1
        if факт == ждём:
            print(f"  ок    {имя}")
        else:
            print(f"  ПЛОХО {имя}: ждали «{ждём}», вышло «{факт}»")
            ok = False

    целый = файл_установщика()
    текст = целый.read_text(encoding="utf-8") if целый else ""

    # БОЛЬНОЙ СЛУЧАЙ 13.09.2026: установщик про панель не знал вовсе.
    проба("БОЛЬНОЙ: шага панели нет — претензия названа", 1,
          len(недостающее("шаг_9() {\n  :\n}\n")))
    if not текст:
        # Пакета нет — это не вина кода: на втором способе установки («дать
        # репозиторий работающему Клоду») пакета рядом не бывает, и красный
        # самотест красил бы ворота ни за что (ревью кода 13.09.2026, F-14).
        # Больной случай выше прогнан и на подставном тексте — его вердикт
        # уже учтён; жёлтый говорит ровно то, что есть: судить нечего.
        print(f"SELFTEST: ЖЁЛТЫЙ — пакета нет, больные случаи на живом "
              f"установщике не прогнаны (путей {путей}, неудач "
              f"{0 if ok else 1})")
        return ЖЁЛТЫЙ if ok else 1
    проба("живой установщик требований не нарушает", 0, len(недостающее(текст)))
    # Каждое требование проверяется СВОИМ больным случаем: снимаем строку и
    # ждём ровно одну претензию — иначе проверка держится на соседях.
    for зачем, образец in ТРЕБОВАНИЯ.items():
        шаг = вырезать_шаг(текст)
        битый = текст.replace(шаг, re.sub(образец, "ЗАМЕНЕНО", шаг))
        проба(f"БОЛЬНОЙ: пропало «{зачем[:44]}…»", 1, len(недостающее(битый)))
    # Шаг определён, но не вызван — установка молча пройдёт мимо панели.
    без_вызова = re.sub(r"^\s*шаг_10\s*$", "", текст, flags=re.M)
    проба("БОЛЬНОЙ: шаг_10 определён, но не вызван", 1, len(недостающее(без_вызова)))
    # ЖИВОЙ путь, а не текст: отказ шага не имеет права уносить с собой блок
    # подсказок и сводку (ревью кода 13.09.2026, F-10). Проверяется прогоном
    # копии установщика с нарочным `стоп` — судить текст ловушки бесполезно,
    # она работает или нет только на запуске.
    расхождения_путей = путь_состояния_везде_один(целый)
    проба("каталог состояния везде один (шаг, код панели, юнит)", [], расхождения_путей)
    вышло, вывод = прогон_с_отказом(целый)
    проба("БОЛЬНОЙ: стоп на шаге — код отказа", 1, вышло)
    проба("при отказе блок «ОСТАЛОСЬ РУКАМИ» всё равно напечатан", True,
          "ОСТАЛОСЬ РУКАМИ (только" in вывод)
    проба("при отказе сводка всё равно напечатана", True,
          "ИТОГОВАЯ СВОДКА" in вывод)
    print(f"SELFTEST: зелёный ({путей} путей; первым — больной случай "
          "«установщик про панель не знает»)" if ok
          else f"SELFTEST: КРАСНЫЙ (путей {путей})")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(самотест() if "--selftest" in sys.argv else проверить())
