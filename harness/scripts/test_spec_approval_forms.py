#!/usr/bin/env python3
"""Проба судьи одобрения спеки: «ок», «окей», «подтверждаю» с предметом.

БОЛЬНОЙ СЛУЧАЙ: голые «ок» и «подтверждаю» одобряли спеку, а «спека ок», «спека окей»,
«подтверждаю спеку» — нет: этих слов нет в признаке ОДОБРЕНИЕ, и ответ
владельца с названным предметом работу не открывал.

Граница слова — с ОБЕИХ сторон: «около», «окно», «подтверди» одобрением не
становятся. Отказ перевешивает, как и прежде.

Модуль берётся РЯДОМ с пробой: из копии дерева она судит испорченную копию.
"""
import importlib.util
import sys
from pathlib import Path

ЗДЕСЬ = Path(__file__).resolve().parent
sys.path.insert(0, str(ЗДЕСЬ / "lib"))
_спец = importlib.util.spec_from_file_location("spec_approval", ЗДЕСЬ / "spec_approval.py")
судья = importlib.util.module_from_spec(_спец)
_спец.loader.exec_module(судья)

СЛУЧАИ = (
    # (слова владельца, чужой вопрос позже, ждём одобрения, почему)
    ("спека ок", False, True, "БОЛЬНОЙ СЛУЧАЙ: «ок» с предметом"),
    ("спека окей", False, True, "БОЛЬНОЙ СЛУЧАЙ: «окей» с предметом"),
    ("подтверждаю спеку", False, True, "БОЛЬНОЙ СЛУЧАЙ: «подтверждаю» с предметом"),
    ("спеку подтверждаю", False, True, "БОЛЬНОЙ СЛУЧАЙ: обратный порядок"),
    ("спека ок", True, True, "предмет назван — чужой вопрос не мешает"),
    ("ок, но не выкатывай", False, False, "отказ перевешивает"),
    ("спека около готова", False, False, "«ок» внутри «около» — граница справа"),
    ("окно задачи закрой", False, False, "«ок» внутри «окно»"),
    ("спека не ок", False, False, "отказ перед «ок»"),
    ("подтверди спеку", False, False, "просьба подтвердить — не одобрение"),
    # Квитанция и вопрос с названным предметом одобрением НЕ становятся: предмет
    # открывает работу мимо окна и чужого вопроса, и «ок» в начале квитанции
    # запускал бы её без решения владельца.
    ("ок, получил спеку", False, False, "БОЛЬНОЙ СЛУЧАЙ: «ок» — квитанция о получении"),
    ("ок, спеку прочитаю", False, False, "БОЛЬНОЙ СЛУЧАЙ: «ок» — обещание прочитать"),
    ("спека ок?", False, False, "БОЛЬНОЙ СЛУЧАЙ: вопрос, а не одобрение"),
    ("пришли спеку на подтверждение", False, False, "БОЛЬНОЙ СЛУЧАЙ: существительное «подтверждение»"),
    ("подтверждаешь спеку?", False, False, "БОЛЬНОЙ СЛУЧАЙ: вопрос «подтверждаешь»"),
    ("жду подтверждения задачи от заказчика", False, False, "БОЛЬНОЙ СЛУЧАЙ: «подтверждения» о чужом"),
    ("ок", False, True, "контроль: голое «ок» одобряет, как прежде"),
    ("ок", True, False, "контроль: голое «ок» после чужого вопроса — нет"),
)


def main() -> int:
    неудач = 0
    for текст, чужой, ждём, почему in СЛУЧАИ:
        вышло = судья.это_одобрение(текст, чужой_вопрос_позже=чужой)
        if вышло is ждём:
            print(f"  ок    «{текст}» (чужой вопрос: {чужой}) → {вышло} · {почему}")
        else:
            неудач += 1
            print(f"  ПЛОХО «{текст}» (чужой вопрос: {чужой}) → {вышло}, ждали {ждём} · {почему}")
    print(f"ОДОБРЕНИЕ-СПЕКИ: путей {len(СЛУЧАИ)}, неудач {неудач}")
    return 1 if неудач else 0


if __name__ == "__main__":
    sys.exit(main())
