#!/usr/bin/env python3
"""Проверка класса живой проверки — ДО того, как класс появился в приборе.

Откуда взято. Спека `docs/specs/2026-10-15-живая-проверка-механизмов.md` §3.1
и план `docs/plans/2026-10-16-носители-живой-проверки.md`, Task 0.

Зачем класс нужен. «Проверено живьём» сегодня значит «я посмотрел»: предикат
живёт в голове смены и меняется от смены к смене. Ревью спеки 15.10 измерило
цену этого: «повод = крон» покрывает 15 демонов из 19, а 158 «гейтов» включают
11 библиотек `scripts/lib`, 4 сборщика и 7 опасных инструментов (`deploy.sh`,
`drop-database.sh`, `publish.sh`, `emergency-send.sh`, `gates.sh`,
`install-docker.sh`, `start-agent.sh`) — предикат судьи к ним неприменим.
Поэтому класс берётся ИЗ ДАННЫХ (`harness/config/live-check-classes.yaml`), а
прибор обязан краснеть, когда класса нет: иначе файл можно просто не заполнить
и закрыть счёт работой, которой не было.

── Что охраняется сверх буквы плана ───────────────────────────────────────
1. **Пустой класс — не класс.** `класс: ""` и `класс: null` обязаны считаться
   отсутствием: пустая строка проходит проверку «ключ есть» и даёт зелёный
   счёт без работы — ровно та же беда, что у ключа чистоты с пустыми данными
   ([[a-gate-alive-with-empty-data]]).
2. **Опечатка в имени класса** («A1» латиницей против «А1» кириллицей, «F»)
   обязана быть НАЗВАНА, а не принята: кириллическая «А» в имени класса
   неотличима на глаз, а разрез по ней молча заведёт восьмой класс.
3. **Класс у ключа, которого нет в реестре** — имя файла механизма меняется
   часто, и счётчик по имени при переименовании слепнет; у соседней функции
   `неизвестные_ключи` это правило уже есть, и здесь оно то же.
4. **Причина обязательна для C3** (опасный) — без неё «опасный» это ярлык,
   который ничего не запрещает.

5. **Каждый случай требует СВОЮ причину дословно, а не просто красный код.**
   Первая редакция этой пробы требовала «код 1 и имя файла в выводе» — и
   мутация «механизм без класса больше не называется» не покраснила НИ ОДНОГО
   случая: пустой класс ловила вторая ветка («класс «» неизвестен»), код был
   тот же, имя то же. Одна дорога — один случай; у каждой своя подстрока.

Каждый случай СОЗДАЁТ своё условие: свой временный двор со своим реестром,
состоянием и файлом классов. Боевые файлы сверяются по md5 до и после — проба,
которая играет на производстве, уже была (12.09.2026, «/model» уехала в рабочую
панель агента).

Прогон: python3 scripts/test_live_check_classes.py
Код возврата: 0 — все случаи зелёные, 1 — хоть один плохой.
"""
from __future__ import annotations

import hashlib
import os
import pathlib
import subprocess
import sys
import tempfile

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
ПРИБОР = КОРЕНЬ / "scripts" / "build-live-check-list.py"
БОЕВЫЕ = (
    КОРЕНЬ / "harness" / "config" / "mechanisms.yaml",
    КОРЕНЬ / "harness" / "config" / "live-check-state.yaml",
    КОРЕНЬ / "docs" / "живая-проверка-механизмов.md",
)

хорошо = 0
плохо = 0


def случай(имя: str, условие: bool, пояснение: str = "") -> None:
    global хорошо, плохо
    if условие:
        хорошо += 1
        print(f"  ок    {имя}")
    else:
        плохо += 1
        print(f"  ПЛОХО {имя}{(': ' + пояснение) if пояснение else ''}")


def двор(механизмы: list[dict], классы: dict, состояние: dict | None = None) -> pathlib.Path:
    """Свой двор: реестр, классы и состояние, которых нет на производстве."""
    import yaml

    путь = pathlib.Path(tempfile.mkdtemp(prefix="класс-"))
    (путь / "mechanisms.yaml").write_text(
        yaml.dump(механизмы, allow_unicode=True), encoding="utf-8")
    (путь / "classes.yaml").write_text(
        yaml.dump({"классы": классы}, allow_unicode=True), encoding="utf-8")
    (путь / "state.yaml").write_text(
        yaml.dump({"проверено": состояние or {}}, allow_unicode=True), encoding="utf-8")
    return путь


def прогон(путь: pathlib.Path, *доводы: str) -> tuple[int, str]:
    среда = dict(os.environ)
    среда.update({
        "HARNESS_MECHANISMS": str(путь / "mechanisms.yaml"),
        "HARNESS_LIVE_CHECK_CLASSES": str(путь / "classes.yaml"),
        "HARNESS_LIVE_CHECK_STATE": str(путь / "state.yaml"),
        "HARNESS_LIVE_CHECK_DOC": str(путь / "документ.md"),
    })
    готово = subprocess.run([sys.executable, str(ПРИБОР), *доводы],
                            capture_output=True, text=True, env=среда, timeout=120)
    return готово.returncode, готово.stdout + готово.stderr


МЕХАНИЗМ = {"файл": "a.sh", "вид": "демон", "имя": "А", "проверяется": "-"}
СОСЕД = {"файл": "b.sh", "вид": "гейт", "имя": "Б", "проверяется": "-"}


def main() -> int:
    было = {п: hashlib.md5(п.read_bytes()).hexdigest() for п in БОЕВЫЕ if п.exists()}

    # БОЛЬНОЙ СЛУЧАЙ ПЕРВЫМ: механизм без класса обязан краснить прибор.
    д = двор([МЕХАНИЗМ, СОСЕД], {"a.sh": {"класс": "A1"}})
    код, вывод = прогон(д, "--числа")
    случай("БОЛЬНОЙ СЛУЧАЙ: механизм без класса краснит и назван поимённо",
           код == 1 and "класса нет: b.sh" in вывод, f"код {код}, вывод {вывод[:200]!r}")

    # Пустой класс — не класс.
    д = двор([МЕХАНИЗМ, СОСЕД], {"a.sh": {"класс": "A1"}, "b.sh": {"класс": ""}})
    код, вывод = прогон(д, "--числа")
    случай("пустой класс считается отсутствием",
           код == 1 and "класса нет: b.sh" in вывод, f"код {код}, вывод {вывод[:200]!r}")

    # Опечатка в имени класса названа, а не принята молча.
    д = двор([МЕХАНИЗМ, СОСЕД], {"a.sh": {"класс": "A1"}, "b.sh": {"класс": "F"}})
    код, вывод = прогон(д, "--числа")
    случай("неизвестный класс назван",
           код == 1 and "класс «F» неизвестен: b.sh" in вывод,
           f"код {код}, вывод {вывод[:200]!r}")

    # Класс у ключа, которого нет в реестре: переименовали файл.
    д = двор([МЕХАНИЗМ], {"a.sh": {"класс": "A1"}, "старое-имя.sh": {"класс": "C1"}})
    код, вывод = прогон(д, "--числа")
    случай("класс у ключа вне реестра назван",
           код == 1 and "вне реестра" in вывод and "старое-имя.sh" in вывод,
           f"код {код}, вывод {вывод[:200]!r}")

    # C3 без причины — ярлык, который ничего не запрещает.
    д = двор([МЕХАНИЗМ, СОСЕД], {"a.sh": {"класс": "A1"}, "b.sh": {"класс": "C3"}})
    код, вывод = прогон(д, "--числа")
    случай("опасный класс без причины краснит",
           код == 1 and "без причины: b.sh" in вывод, f"код {код}, вывод {вывод[:200]!r}")

    # Здоровый двор: разрез печатается, сумма классов равна числу механизмов.
    д = двор([МЕХАНИЗМ, СОСЕД],
             {"a.sh": {"класс": "A1"},
              "b.sh": {"класс": "C3", "причина": "шлёт сообщение владельцу"}})
    код, вывод = прогон(д, "--числа")
    случай("здоровый двор: код 0", код == 0, f"код {код}, вывод {вывод[:200]!r}")
    случай("разрез по классам напечатан и сходится",
           "A1: 1" in вывод and "C3: 1" in вывод, вывод[:200])

    стало = {п: hashlib.md5(п.read_bytes()).hexdigest() for п in БОЕВЫЕ if п.exists()}
    случай("боевые файлы не тронуты", было == стало,
           "проба сыграла на производстве")

    print(f"ИТОГ: хороших {хорошо}, плохих {плохо}")
    return 1 if плохо else 0


if __name__ == "__main__":
    sys.exit(main())
