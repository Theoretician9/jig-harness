#!/usr/bin/env python3
"""Собирает документ «как устроен харнес» из реестра устройства.

Владелец 11.09.2026: «Нужно прописать как работает всё в харнесе, отдельно
детально что делает каждый демон хук и тд».

Документ и пояснения на панели растут из ОДНОГО файла данных
(`harness/config/устройство.yaml`). Второй носитель, который правят руками,
через месяц расходится с первым — и никто не знает, какой из них правда.
Поэтому документ собирается, а не пишется; правку руками ловит гейт
`scripts/check-ustrojstvo.py`.

Прогон:
    python3 scripts/sobrat-ustrojstvo.py            # пересобрать документ
    python3 scripts/sobrat-ustrojstvo.py --печать   # вывести, не записывая
"""
import sys
from pathlib import Path

import yaml

КОРЕНЬ = Path(__file__).resolve().parent.parent
РЕЕСТР = КОРЕНЬ / "harness" / "config" / "устройство.yaml"
ДОКУМЕНТ = КОРЕНЬ / "docs" / "УСТРОЙСТВО-ХАРНЕСА.md"

ЗАГОЛОВКИ = {
    "демон": ("Сторожа, которые работают сами",
              "Запускаются по расписанию без моего участия: следят за машиной, "
              "памятью, сессиями и копиями данных."),
    "хук": ("Перехватчики внутри моей работы",
            "Срабатывают в момент, когда я что-то делаю: запускаю команду, "
            "пишу файл, завершаю ход. Отменяют опасное до того, как оно случится."),
    "гейт": ("Проверки перед коммитом и выкатом",
             "Все вместе запускаются одной командой `bash scripts/vorota.sh`. "
             "Красная проверка останавливает работу — это и есть смысл ворот."),
    "скил": ("Правила шагов работы",
             "Пошаговые инструкции для меня: как принимать задачу, писать спеку, "
             "разбирать падение, выкатывать. Вызов каждого пишется в журнал."),
}
ПОРЯДОК = ("демон", "хук", "гейт", "скил")


def по_видам(записи: list) -> dict:
    """Записи, сгруппированные по виду механизма, в порядке показа."""
    группы = {}
    for запись in записи:
        группы.setdefault(запись.get("вид", "прочее"), []).append(запись)
    for группа in группы.values():
        группа.sort(key=lambda з: з.get("имя", ""))
    return {вид: группы[вид] for вид in ПОРЯДОК if вид in группы} | {
        вид: группа for вид, группа in группы.items() if вид not in ПОРЯДОК}


def _абзац(текст: str) -> str:
    return " ".join(str(текст).split())


def собрать(записи: list) -> str:
    """Документ целиком. Чистая функция: то же на входе — то же на выходе."""
    группы = по_видам(записи)
    строки = [
        "# Как устроен харнес",
        "",
        "> Этот файл СОБИРАЕТСЯ из `harness/config/устройство.yaml` и руками не правится:",
        "> правка попадёт под гейт `scripts/check-ustrojstvo.py` и исчезнет при",
        "> следующей сборке. Менять нужно реестр, потом выполнить",
        "> `python3 scripts/sobrat-ustrojstvo.py`.",
        "",
        "Харнес — это обвязка вокруг работы: она сама следит за машиной, "
        "отменяет опасные команды, не даёт выкатить непроверенное и помнит "
        "правила между сессиями. Ниже перечислено всё, из чего она состоит: "
        f"механизмов — {len(записи)}.",
        "",
        "## Что здесь есть",
        "",
    ]
    for вид, группа in группы.items():
        заголовок = ЗАГОЛОВКИ.get(вид, (вид.capitalize(), ""))[0]
        строки.append(f"- **{заголовок}** — {len(группа)}")
    строки.append("")

    for вид, группа in группы.items():
        заголовок, пояснение = ЗАГОЛОВКИ.get(вид, (вид.capitalize(), ""))
        строки += [f"## {заголовок}", ""]
        if пояснение:
            строки += [пояснение, ""]
        for запись in группа:
            строки += [
                f"### {запись['имя']}",
                "",
                f"`{запись['файл']}`",
                "",
                _абзац(запись["роль"]),
                "",
                f"- **Когда работает:** {_абзац(запись['когда'])}",
                f"- **Что будет без него:** {_абзац(запись['без_него'])}",
                f"- **Чем проверяется:** {_абзац(запись['проверяется'])}",
                f"- **Что пишет:** {_абзац(запись['пишет'])}",
                "",
            ]
    return "\n".join(строки).rstrip() + "\n"


def main() -> int:
    записи = yaml.safe_load(РЕЕСТР.read_text(encoding="utf-8"))["механизмы"]
    текст = собрать(записи)
    if "--печать" in sys.argv:
        sys.stdout.write(текст)
        return 0
    ДОКУМЕНТ.parent.mkdir(parents=True, exist_ok=True)
    было = ДОКУМЕНТ.read_text(encoding="utf-8") if ДОКУМЕНТ.exists() else None
    ДОКУМЕНТ.write_text(текст, encoding="utf-8")
    состояние = "без изменений" if было == текст else "обновлён"
    print(f"{ДОКУМЕНТ.relative_to(КОРЕНЬ)}: {состояние}, механизмов {len(записи)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
