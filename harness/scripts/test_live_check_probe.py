#!/usr/bin/env python3
"""Проверка носителя класса D — живой проверки ПРОБЫ (scripts/live-check-probe.py).

Откуда взято. Спека `docs/specs/2026-10-15-живая-проверка-механизмов.md` §3.1,
класс D: «мутация в судимом механизме → проба краснеет; зелёная мутация —
находка о ПРОБЕ». Пробу портят и ждут красного. У класса D единственного в
семье не было прибора с `--записать`: 145 записей писались руками из полного
журнала мутаций, и 123 оставшиеся ждали тех же ручных вставок — правило без
носителя (план задачи hr.zhivaya-proverka-vseh-mehanizmov, часть 5).

Сначала проба судит СВОЙ двор: прибор мутаций, позванный напрямую, обязан
сказать о каждой игрушечной пробе то, что ей приписано (ловит 2 из 2, дыра,
не встала, красна на чистой). Без этого красное ниже судило бы двор, а не
прибор.

Что охраняется — по случаю на каждую беду, больные первыми:

1. **Зелёная мутация — не «ок», а дыра в пробе.** Проба, которую мутация не
   красит, ничего не охраняет; записать её «проверено» — ложь И-4.
2. **Мутация, которая не встала** (sed не нашёл текст), — тоже не «ок»: иначе
   проба зачтена ловящей по мутации, которой не было (failure_modes контракта).
3. **Чистая копия красная — отказ.** Красное на испорченном тогда ничего не
   доказывает: оно было и до порчи.
4. **Нет мутаций и нет причины — отказ.** Пустой список мутаций (в том числе
   записанный пустым) — тоже отказ, а не «0 из 0».
5. **В `без_мутаций` с причиной — «не-проверяемо» с этой причиной**, а не «ок».
6. **Живая мутация — «ок» с цитатой красного**: число покрасневших названо,
   журнал мутаций лежит в каталоге следов, запись ссылается на него, а след
   пробы написан ОБЁРТКОЙ live-check.sh (её шапка), не прибором.
7. **Сухой прогон (без `--записать`) не пишет ничего**: ни состояния, ни следов
   — сравнение двора до и после. Иначе сухой прогон переписывает живой след
   записи «ок», и `--проверить` краснеет на чужой записи (edge_cases контракта).
8. **Два прогона рядом не теряют записей** (замок, как у семьи).
9. **«--всё» берёт пробы класса D без исхода**, и ни одну с исходом.

Двери (как у семьи): путь прибора — HARNESS_LIVE_CHECK_PROBE_TOOL; корень —
HARNESS_LIVE_CHECK_REPO; реестр, классы, состояние, мутации проб, инварианты —
HARNESS_MECHANISMS, HARNESS_LIVE_CHECK_CLASSES, HARNESS_LIVE_CHECK_STATE,
HARNESS_PROBE_MUTATIONS, HARNESS_INVARIANTS; каталог следов —
HARNESS_LIVE_CHECK_PROBE_TRACE_DIR. Прибор зовёт `scripts/live-check.sh` и
`scripts/mutation-probe.sh` своего корня — во двор кладутся настоящие копии.

Каждый случай строит СВОЙ двор под общим каталогом с префиксом harness-run-
(его же получают TMPDIR и mktemp прибора мутаций — уборка /tmp его опознаёт):
игрушечный механизм, игрушечные пробы, свой реестр мутаций. Боевые данные не
трогаются — это судит последний случай.

Прогон: python3 scripts/test_live_check_probe.py
Код возврата: 0 — все случаи зелёные, 1 — хоть один плохой.
"""
from __future__ import annotations

import hashlib
import os
