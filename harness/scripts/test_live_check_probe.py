import yaml

СКРИПТЫ = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(СКРИПТЫ / "lib"))
import config as _конфиг  # noqa: E402

# Корень установки, а не parent.parent: в пакете скрипты лежат в harness/scripts.
КОРЕНЬ = pathlib.Path(_конфиг.корень_дерева(__file__))
# Путь прибора — из окружения: мутационный прогон подсовывает ИСПОРЧЕННУЮ копию
# и требует красного ([[probe-loads-the-live-mechanism]]).
ПРИБОР = pathlib.Path(os.environ.get("HARNESS_LIVE_CHECK_PROBE_TOOL")
                      or СКРИПТЫ / "live-check-probe.py")
БОЕВЫЕ = ("harness/config/live-check-state.yaml",
          "harness/config/probe-mutations.yaml")
# Всё, что прибор берёт из своего корня: настоящие копии, не заглушки — след
# пишет обёртка, мутации ставит прибор мутаций, и проба судит их работу.
ЧУЖИЕ_ПРИБОРЫ = ("live-check.sh", "mutation-probe.sh", "run-in-checks-slice.sh")

хорошо = 0
плохо = 0


def случай(имя: str, условие: bool, пояснение: str = "") -> None:
    global хорошо, плохо
    if условие:
        хорошо += 1
        print(f"  ок    {имя}", flush=True)
    else:
        плохо += 1
        print(f"  ПЛОХО {имя}{(': ' + пояснение) if пояснение else ''}", flush=True)


# Механизм: две судимые функции и одна, которую ни одна проба не судит, —
# место для зелёной мутации.
МЕХАНИЗМ = '''import sys


def udvoit(x):
    return x * 2


def utroit(x):
    return x * 3


def privetstvie():
    return "privet"


if __name__ == "__main__":
    n = int(sys.argv[1])
    print(udvoit(n), utroit(n), privetstvie())
'''

# Проба находит механизм через дверь среды MEH_UNDER_TEST (подмена в данных),
# иначе — рядом с собой. Модулей не импортирует: байткод во дворе исказил бы
# сравнение «до/после» сухого прогона.
ПРОБА = '''import os, pathlib, subprocess, sys

мех = os.environ.get("MEH_UNDER_TEST") or str(pathlib.Path(__file__).resolve().parent / "meh.py")
слова = subprocess.run([sys.executable, мех, "5"], capture_output=True, text=True).stdout.split()
плохих = 0
for имя, номер, ждём in (("удвоение пяти даёт десять", 0, "10"),
                         ("утроение пяти даёт пятнадцать", 1, "15")):
    есть = слова[номер] if len(слова) > номер else "нет"
    if есть == ждём:
        print(f"  ок    {имя}")
    else:
        плохих += 1
        print(f"  ПЛОХО {имя}: вышло {есть}")
print(f"ИТОГ: хороших {2 - плохих}, плохих {плохих}")
sys.exit(1 if плохих else 0)
'''

# Проба, красная на ЧИСТОМ механизме: ждёт от удвоения пяти одиннадцать.
ПРОБА_КРАСНАЯ = ПРОБА.replace('"удвоение пяти даёт десять", 0, "10"',
                              '"удвоение пяти даёт одиннадцать", 0, "11"')

ЛОВИТ_УДВОЕНИЕ = r"s/^    return x \* 2$/    return x + 2/"
ЛОВИТ_УТРОЕНИЕ = r"s/^    return x \* 3$/    return x + 3/"
# Строку приветствия ни одна проба не судит — мутация в ней зелёная.
ЗЕЛЁНАЯ = r's/^    return "privet"$/    return "poka"/'
# Текста нет в механизме: sed ничего не меняет — мутация «не встала».
НЕ_ВСТАЁТ = r"s/^    return x \* 7$/    return x + 7/"

ПРИЧИНА = "повода на этой машине нет: проба судит продукт, которого во дворе нет"
# Причина не с пункта закрытого списка: свободный текст освобождал бы любую пробу.
ПРИЧИНА_СВОБОДНАЯ = "некогда было: проба судит продукт, которого во дворе нет"


def запись_мутаций(проба: str, выражения: list[str]) -> dict:
    return {"механизм": "scripts/meh.py",
            "доказательство": f"python3 {проба}",
            "подмена": "MEH_UNDER_TEST",
            "мутация": выражения,
            "мутация_случай": [f"случай {н + 1} пробы {проба}"
                               for н in range(len(выражения))]}


# Пробы двора: имя файла → (текст, запись мутаций или None). None — записи в
# «пробы» нет вовсе; без_мутаций задаётся отдельно.
ПРОБЫ_ДВОРА = {
    "scripts/test_meh.py": (ПРОБА, [ЛОВИТ_УДВОЕНИЕ, ЛОВИТ_УТРОЕНИЕ]),
    "scripts/test_meh2.py": (ПРОБА, [ЛОВИТ_УДВОЕНИЕ, ЛОВИТ_УТРОЕНИЕ]),
    "scripts/test_meh3.py": (ПРОБА, [ЛОВИТ_УДВОЕНИЕ, ЛОВИТ_УТРОЕНИЕ]),
    "scripts/test_meh4.py": (ПРОБА, [ЛОВИТ_УДВОЕНИЕ, ЛОВИТ_УТРОЕНИЕ]),
    "scripts/test_holey.py": (ПРОБА, [ЛОВИТ_УДВОЕНИЕ, ЗЕЛЁНАЯ]),
    "scripts/test_unset.py": (ПРОБА, [ЛОВИТ_УДВОЕНИЕ, НЕ_ВСТАЁТ]),
    "scripts/test_red.py": (ПРОБА_КРАСНАЯ, [ЛОВИТ_УДВОЕНИЕ, ЛОВИТ_УТРОЕНИЕ]),
    "scripts/test_empty.py": (ПРОБА, []),
    "scripts/test_bare.py": (ПРОБА, None),
    "scripts/test_nomut.py": (ПРОБА, None),
    "scripts/test_freetext.py": (ПРОБА, None),
}


def двор(общий: pathlib.Path, *, состояние: dict | None = None) -> pathlib.Path:
    """Свой двор случая: корень с scripts/ и harness/config/, как у установки."""
    путь = pathlib.Path(tempfile.mkdtemp(prefix="dvor-", dir=общий))
    скрипты = путь / "scripts"
    конфиг = путь / "harness" / "config"
    скрипты.mkdir()
    конфиг.mkdir(parents=True)
    (путь / "log").mkdir()
    (скрипты / "meh.py").write_text(МЕХАНИЗМ, encoding="utf-8")
    for имя, (текст, _) in ПРОБЫ_ДВОРА.items():
        (путь / имя).write_text(текст, encoding="utf-8")
    for имя in ЧУЖИЕ_ПРИБОРЫ:
        shutil.copy2(СКРИПТЫ / имя, скрипты / имя)
    shutil.copytree(СКРИПТЫ / "lib", скрипты / "lib",
                    ignore=shutil.ignore_patterns("__pycache__"))
    пробы = {имя: запись_мутаций(имя, выражения)
             for имя, (_, выражения) in ПРОБЫ_ДВОРА.items() if выражения is not None}
    данные = {
        "mechanisms.yaml": {"механизмы": [{"файл": "scripts/meh.py", "вид": "прибор",
                                           "проверяется": "python3 scripts/test_meh.py"}]
                            + [{"файл": имя, "вид": "проба", "проверяется": f"python3 {имя}"}
                               for имя in ПРОБЫ_ДВОРА]},
        "live-check-classes.yaml": {
            "причины_непроверяемого": ["повода на этой машине нет"],
            "классы": {"scripts/meh.py": {"класс": "C2"},
                       **{имя: {"класс": "D"} for имя in ПРОБЫ_ДВОРА}}},
        "probe-mutations.yaml": {"пробы": пробы,
                                 "без_мутаций": {"scripts/test_nomut.py": ПРИЧИНА,
                                                 "scripts/test_freetext.py": ПРИЧИНА_СВОБОДНАЯ}},
        "invariants.yaml": {"инварианты": []},
        "live-check-state.yaml": {"версия": 1, "проверено": состояние or {}},
    }
    for имя, содержимое in данные.items():
        (конфиг / имя).write_text(yaml.safe_dump(содержимое, allow_unicode=True,
                                                 sort_keys=False), encoding="utf-8")
    return путь


def среда_двора(путь: pathlib.Path) -> dict:
    конфиг = путь / "harness" / "config"
    среда = dict(os.environ)
    среда.update({
        "HARNESS_LIVE_CHECK_REPO": str(путь),
        "HARNESS_MECHANISMS": str(конфиг / "mechanisms.yaml"),
        "HARNESS_LIVE_CHECK_CLASSES": str(конфиг / "live-check-classes.yaml"),
        "HARNESS_LIVE_CHECK_STATE": str(конфиг / "live-check-state.yaml"),
        "HARNESS_PROBE_MUTATIONS": str(конфиг / "probe-mutations.yaml"),
        "HARNESS_INVARIANTS": str(конфиг / "invariants.yaml"),
        "HARNESS_LIVE_CHECK_PROBE_TRACE_DIR": str(путь / "следы"),
        # Журнал и кэш прибора мутаций — во дворе: боевой мутации.log читает
        # ночной демон, и строка итога выборки стала бы его вердиктом.
        "LOG_DIR": str(путь / "log"),
        "HARNESS_LOG_DIR": str(путь / "log"),
        "MUT_CACHE_DAYS": "0",
        # Двор лёгкий: очередь среза проверок занята часами, и проба ждала бы её.
        "HARNESS_IN_CHECKS_SLICE": "1",
    })
    return среда


def прогон(путь: pathlib.Path, *доводы: str) -> tuple[int, str]:
    готово = subprocess.run([sys.executable, str(ПРИБОР), *доводы],
                            capture_output=True, text=True, env=среда_двора(путь),
                            timeout=600)
    return готово.returncode, готово.stdout + готово.stderr


def запустить(путь: pathlib.Path, *доводы: str) -> subprocess.Popen:
    return subprocess.Popen([sys.executable, str(ПРИБОР), *доводы],
                            stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                            text=True, env=среда_двора(путь))


def состояние(путь: pathlib.Path) -> dict:
    данные = yaml.safe_load((путь / "harness" / "config" / "live-check-state.yaml")
                            .read_text(encoding="utf-8")) or {}
    return данные.get("проверено") or {}


def исход(путь: pathlib.Path, проба: str) -> str:
    return str((состояние(путь).get(проба) or {}).get("исход") or "")


def снимок(путь: pathlib.Path) -> dict:
    """Хэш каждого файла двора, кроме журнала прибора мутаций (log/)."""
    return {str(ф.relative_to(путь)): hashlib.sha256(ф.read_bytes()).hexdigest()
            for ф in sorted(путь.rglob("*"))
            if ф.is_file() and ф.relative_to(путь).parts[0] != "log"}


def файл_следа(путь: pathlib.Path, след: str) -> pathlib.Path:
    п = pathlib.Path(след)
    return п if п.is_absolute() else путь / п


def журнал_с(путь: pathlib.Path, текст: str) -> pathlib.Path | None:
    """Файл в каталоге следов, где стоит дословный текст, — или None."""
    for ф in sorted((путь / "следы").rglob("*")):
        if ф.is_file() and текст in ф.read_text(encoding="utf-8", errors="replace"):
            return ф
    return None


def пробы_d_без_исхода(путь: pathlib.Path) -> list[str]:
    """Список, который судит «--всё», — РАЗБОРОМ данных двора, а не из головы."""
    конфиг = путь / "harness" / "config"
    кл = (yaml.safe_load((конфиг / "live-check-classes.yaml").read_text(encoding="utf-8"))
          or {}).get("классы") or {}
    сост = состояние(путь)
    return [ф for ф, з in кл.items()
            if (з or {}).get("класс") == "D" and not (сост.get(ф) or {}).get("исход")]


def main() -> int:
    боевые = {п: (КОРЕНЬ / п).read_bytes() for п in БОЕВЫЕ if (КОРЕНЬ / п).is_file()}
    общий = pathlib.Path(tempfile.mkdtemp(prefix="harness-run-lcprobe-"))
    # Дети (прибор мутаций, пробы) берут временное место отсюда: префикс
    # harness-run- наследуется, и уборка /tmp опознаёт хвост упавшего прогона.
    os.environ["TMPDIR"] = str(общий)
    try:
        случай("прибор есть по своему пути", ПРИБОР.is_file(), f"нет файла {ПРИБОР}")
        прогнать_случаи(общий)
    finally:
        shutil.rmtree(общий, ignore_errors=True)

    тронуты = [п for п, байты in боевые.items() if (КОРЕНЬ / п).read_bytes() != байты]
    случай("боевые файлы не тронуты", not тронуты and len(боевые) == len(БОЕВЫЕ),
           f"тронуты {тронуты}, прочитано {len(боевые)} из {len(БОЕВЫЕ)}")
    print(f"ИТОГ: хороших {хорошо}, плохих {плохо}")
    return 1 if плохо else 0


def мутации_напрямую(путь: pathlib.Path, проба: str) -> str:
    """Итог прибора мутаций по одной пробе двора, без судимого прибора."""
    выборка = путь / "выборка.yaml"
    пробы = yaml.safe_load((путь / "harness" / "config" / "probe-mutations.yaml")
                           .read_text(encoding="utf-8"))["пробы"]
    выборка.write_text(yaml.safe_dump({"пробы": {проба: пробы[проба]}}, allow_unicode=True),
                       encoding="utf-8")
    среда = среда_двора(путь)
    среда["HARNESS_PROBE_MUTATIONS"] = str(выборка)
    готово = subprocess.run(["bash", str(путь / "scripts" / "mutation-probe.sh")],
                            capture_output=True, text=True, env=среда, timeout=300)
    выборка.unlink()
    return готово.stdout + готово.stderr


def прогнать_случаи(общий: pathlib.Path) -> None:
    # ── Двор честен: без него красное ниже судило бы двор, а не прибор ─────
    # Прибор мутаций зовётся напрямую: ловящая проба ловит 2 из 2, дырявая
    # оставляет одну дыру, у невставшей мутации файл не меняется, красная
    # проба красна на чистой копии.
    д = двор(общий)
    ждём = {"scripts/test_meh.py": "покраснели как надо 2, дыр 0",
            "scripts/test_holey.py": "покраснели как надо 1, дыр 1",
            "scripts/test_unset.py": "мутация не изменила файл",
            "scripts/test_red.py": "чистая копия уже красная"}
    for проба, слово in ждём.items():
        итог = мутации_напрямую(д, проба)
        случай(f"двор честен: прибор мутаций на {проба} говорит «{слово}»",
               слово in итог, f"итог {итог[-300:]!r}")

    # ── БОЛЬНЫЕ СЛУЧАИ ПЕРВЫМИ ──────────────────────────────────────────────
    # Зелёная мутация: проба её не видит. Одна из двух мутаций поймана — и
    # всё равно не «ок»: охрана с дырой называется дырой, а не «почти».
    д = двор(общий)
    код, вывод = прогон(д, "scripts/test_holey.py", "--записать")
    случай("БОЛЬНОЙ СЛУЧАЙ: мутация не покрасила пробу — отказ «дыра», не «ок»",
           код == 1 and "дыра" in вывод and исход(д, "scripts/test_holey.py") != "ок",
           f"код {код}, исход {исход(д, 'scripts/test_holey.py')!r}, вывод {вывод[-300:]!r}")

    # Мутация не встала: проба «поймала» то, чего не было.
    д = двор(общий)
    код, вывод = прогон(д, "scripts/test_unset.py", "--записать")
    случай("БОЛЬНОЙ СЛУЧАЙ: мутация не встала в механизм — не «ок»",
           код == 1 and исход(д, "scripts/test_unset.py") != "ок",
           f"код {код}, исход {исход(д, 'scripts/test_unset.py')!r}, вывод {вывод[-300:]!r}")

    # Чистая копия красная: красное на порче ничего не доказывает.
    д = двор(общий)
    код, вывод = прогон(д, "scripts/test_red.py", "--записать")
    случай("БОЛЬНОЙ СЛУЧАЙ: проба красна на чистом механизме — отказ, записи нет",
           код == 1 and "красн" in вывод.lower() and "scripts/test_red.py" not in состояние(д),
           f"код {код}, состояние {list(состояние(д))}, вывод {вывод[-300:]!r}")

    # Ни мутаций, ни причины.
    д = двор(общий)
    код, вывод = прогон(д, "scripts/test_bare.py", "--записать")
    случай("БОЛЬНОЙ СЛУЧАЙ: у пробы нет мутаций и нет причины — отказ, записи нет",
           код == 1 and "мутаци" in вывод and "scripts/test_bare.py" not in состояние(д),
           f"код {код}, состояние {list(состояние(д))}, вывод {вывод[-300:]!r}")

    # Запись есть, а список мутаций пуст: «0 из 0» — не проверка.
    д = двор(общий)
    код, вывод = прогон(д, "scripts/test_empty.py", "--записать")
    случай("БОЛЬНОЙ СЛУЧАЙ: разобранный список мутаций пуст — провал, не «ок»",
           код == 1 and исход(д, "scripts/test_empty.py") != "ок",
           f"код {код}, исход {исход(д, 'scripts/test_empty.py')!r}, вывод {вывод[-300:]!r}")

    # Пустой список и у самого прибора: назвать некого — отказ, а не «все 0 доказаны».
    д = двор(общий)
    код, вывод = прогон(д, "--записать")
    случай("БОЛЬНОЙ СЛУЧАЙ: ни одной пробы не названо — провал",
           код == 1 and состояние(д) == {},
           f"код {код}, состояние {list(состояние(д))}, вывод {вывод[-300:]!r}")

    # ── Освобождение с причиной: не «ок», а «не-проверяемо» с причиной ──────
    д = двор(общий)
    код, вывод = прогон(д, "scripts/test_nomut.py", "--записать")
    запись = состояние(д).get("scripts/test_nomut.py") or {}
    случай("проба в без_мутаций с причиной — «не-проверяемо» с этой причиной",
           "не-проверяемо" in вывод and ПРИЧИНА in вывод
           and запись.get("исход") == "не-проверяемо" and ПРИЧИНА in str(запись),
           f"код {код}, запись {запись}, вывод {вывод[-300:]!r}")

    д = двор(общий)
    код, вывод = прогон(д, "scripts/test_freetext.py", "--записать")
    случай("БОЛЬНОЙ СЛУЧАЙ: причина без_мутаций не из закрытого списка — отказ, записи нет",
           код == 1 and "scripts/test_freetext.py" not in состояние(д),
           f"код {код}, состояние {list(состояние(д))}, вывод {вывод[-300:]!r}")

    # ── Здоровый случай: «ок» с цитатой красного ───────────────────────────
    д = двор(общий)
    код, вывод = прогон(д, "scripts/test_meh.py", "--записать")
    запись = состояние(д).get("scripts/test_meh.py") or {}
    след = файл_следа(д, str(запись.get("след") or "-"))
    текст = след.read_text(encoding="utf-8") if след.is_file() else ""
    вывод_пробы = текст.split("--- вывод механизма ---", 1)[-1] if текст else ""
    увидели = str(запись.get("увидели") or "")
    случай("живая мутация: код 0, «ок», названо «2 из 2»",
           код == 0 and "ок" in вывод and re.search(r"\b2 из 2\b", вывод) is not None,
           f"код {код}, вывод {вывод[-300:]!r}")
    случай("живая мутация: запись «ок», цитата пробы из следа от 12 знаков",
           запись.get("исход") == "ок" and len(увидели) >= 12 and увидели in вывод_пробы,
           f"запись {запись}, следа знаков {len(текст)}")
    случай("след пробы написан обёрткой live-check.sh (её шапка), не прибором",
           "--- вывод механизма ---" in текст and "механизм: scripts/test_meh.py" in текст
           and "пользователь:" in текст and "код возврата: 0" in текст,
           f"след {след}, начало {текст[:200]!r}")
    журнал = журнал_с(д, "покраснели как надо 2, дыр 0")
    случай("цитата красного: журнал мутаций в каталоге следов, запись его называет",
           журнал is not None and журнал.name in str(запись.get("мутация") or ""),
           f"журнал {журнал}, мутация {запись.get('мутация')!r}")
    # LOG_DIR вызывающего — место ночного вердикта (мутации.log): выборка пишет
    # свой журнал во временный каталог, а не туда.
    чужой = д / "log" / "мутации.log"
    случай("выборка не пишет в мутации.log вызывающего — свой LOG_DIR",
           код == 0 and not чужой.exists(), f"код {код}, {чужой} есть: {чужой.exists()}")

    # ── Сухой прогон: ни состояния, ни следов ──────────────────────────────
    д = двор(общий)
    до = снимок(д)
    код, вывод = прогон(д, "scripts/test_meh.py")
    после = снимок(д)
    новое = sorted(set(после) - set(до))
    изменено = sorted(п for п in до if после.get(п) != до[п])
    случай("сухой прогон: «ок», а во дворе ни одного нового или изменённого файла",
           код == 0 and "ок" in вывод and len(до) > 0 and not новое and not изменено,
           f"код {код}, файлов до {len(до)}, новые {новое[:5]}, изменены {изменено[:5]}")

    # ── Два прогона рядом не теряют записей ────────────────────────────────
    д = двор(общий)
    первый = запустить(д, "scripts/test_meh.py", "scripts/test_meh2.py", "--записать")
    второй = запустить(д, "scripts/test_meh3.py", "scripts/test_meh4.py", "--записать")
    вывод1, _ = первый.communicate(timeout=600)
    вывод2, _ = второй.communicate(timeout=600)
    четыре = ("scripts/test_meh.py", "scripts/test_meh2.py",
              "scripts/test_meh3.py", "scripts/test_meh4.py")
    случай("два прогона рядом: все четыре записи «ок» на месте",
           первый.returncode == 0 and второй.returncode == 0
           and all(исход(д, п) == "ок" for п in четыре),
           f"коды {первый.returncode}/{второй.returncode}, "
           f"исходы {[исход(д, п) for п in четыре]}, хвосты {вывод1[-150:]!r} {вывод2[-150:]!r}")

    # ── «--всё»: пробы класса D без исхода, и ни одной с исходом ───────────
    готовая = {"scripts/test_meh2.py": {"исход": "ок", "живьём": "прошлая работа"}}
    д = двор(общий, состояние=готовая)
    ждём = пробы_d_без_исхода(д)
    код, вывод = прогон(д, "--всё")
    случай("«--всё» называет каждую пробу D без исхода и не зовёт готовую",
           len(ждём) > 0 and all(п in вывод for п in ждём)
           and "scripts/test_meh2.py" not in вывод,
           f"ждём {len(ждём)}, нет в выводе {[п for п in ждём if п not in вывод]}, "
           f"вывод {вывод[-300:]!r}")


