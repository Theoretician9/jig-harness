#!/usr/bin/env python3
"""Проверка: `--проверить` судит СЛЕД живой проверки, а не форму записи.

Откуда взято. Спека `docs/specs/2026-10-15-живая-проверка-механизмов.md` §3.2
(шесть требований к записи) и план `docs/plans/2026-10-16-носители-живой-проверки.md`,
Task 2.

Зачем. Прежний предикат судил ФОРМУ: «в записи есть цифра, кавычка или
двоеточие». Его проходили и «2026-10-15: работает», и пересказ самотеста
(ревью спеки 15.10, CRITICAL 5). Мерой может быть только ЧУЖОЙ текст — вывод
самого механизма, сохранённый обёрткой `scripts/live-check.sh`. Поэтому
больной случай ПЕРВЫЙ: запись, пересказывающая команду самотеста из реестра,
обязана краснить.

Что охраняется сверх буквы плана:
1. **Отказ называет ПРИЧИНУ, а не только код.** Шесть требований §3.2 — шесть
   разных бед, и «код 1» у них общий: проба, судящая по коду, зелена от любой
   второй беды (память: «проба, ждущая ненулевого кода, зеленеет от 127»).
   Поэтому каждый случай требует свою дословную причину в выводе.
2. **Прежний смысл `--проверить` сохраняется**: документ обязан сходиться с
   данными. Новое требование ДОБАВЛЯЕТСЯ, иначе ворота начнут краснеть на том,
   что раньше проверяли (ограничение плана).
3. **Свой двор, не производство.** Реестр, классы, состояние, документ и карта
   берутся из окружения: иначе проба судит живой реестр этой машины и её числа
   («всего 249») вместо своих.

Прогон: python3 scripts/test_live_check_trace.py
Код возврата: 0 — все случаи зелёные, 1 — хоть один плохой.
"""
import os
import pathlib
import subprocess
import sys
import tempfile

import yaml

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
# Путь прибора берётся из окружения, если задан: так мутационная проба
# подсовывает ИСПОРЧЕННУЮ копию и требует красного. Без этой двери живость
# требований пришлось бы доказывать правкой боевого файла.
ПРИБОР = pathlib.Path(os.environ.get("HARNESS_LIVE_CHECK_PRIBOR")
                      or КОРЕНЬ / "scripts" / "build-live-check-list.py")

хорошо = 0
плохо = 0


def случай(имя: str, условие: bool, пояснение: str = "") -> None:
    global хорошо, плохо
    if условие:
        хорошо += 1
        print(f"  ок    {имя}")
    else:
        плохо += 1
        print(f"  ПЛОХО {имя}{(': ' + пояснение) if пояснение else ''}")


МЕХАНИЗМ = {"файл": "a.sh", "вид": "демон", "имя": "А",
            "проверяется": "bash a.sh --selftest"}
ПРОБА_D = {"файл": "test_a.py", "вид": "гейт", "имя": "Проба А",
           "проверяется": "python3 test_a.py"}
# Третий механизм двора — ГЕЙТ-СУДЬЯ: его предикат §3.1 требует ДВУХ половин,
# больной и здоровой, и без своего класса в дворе это требование не судится.
ГЕЙТ_C1 = {"файл": "gate_a.py", "вид": "гейт", "имя": "Судья А",
           "проверяется": "python3 gate_a.py --selftest"}
# Четвёртый механизм двора — ОБРАБОТЧИК ВХОДЯЩИХ: его предикат §3.1 требует
# назвать ЗАПИСАННОЕ слово владельца, и без своего класса в дворе это
# требование не судится.
ОБРАБОТЧИК_B2 = {"файл": "inbox_a.py", "вид": "гейт", "имя": "Разбор входящих",
                 "проверяется": "python3 inbox_a.py --selftest"}
КЛАССЫ = {"a.sh": {"класс": "A1"}, "test_a.py": {"класс": "D"},
          "gate_a.py": {"класс": "C1"}, "inbox_a.py": {"класс": "B2"}}
СЛОВО_ВЛАДЕЛЬЦА = "1792010768.757779872.txt"
ПРИЧИНЫ = ["первая установка: механизм ставится на чистой машине",
           "опасный: трогать на боевой машине нельзя"]

ШАПКА = ("время: 2026-10-17T01:00:00+05:00\n"
         "механизм: a.sh\n"
         "команда: bash a.sh --живьём\n"
         "пользователь: agent\n"
         "--- вывод механизма ---\n")


# Носитель мутаций класса D двор несёт ПО УМОЛЧАНИЮ: случаи про §3.2 написаны
# не о нём, и краснеть им по чужой причине нельзя. Его отсутствие и пустота
# задаются случаями явно.
МУТАЦИИ_ПО_УМОЛЧАНИЮ = {"test_a.py": {"механизм": "a.sh", "мутация": "s/x/y/",
                                      "мутация_случай": "судимый случай"}}

ШАПКА_БОЛЬНОГО = ("время: 2026-10-17T01:05:00+05:00\n"
                  "механизм: a.sh\n"
                  "команда: bash a.sh --живьём (в копии дерева, строка сломана)\n"
                  "пользователь: agent\n"
                  "--- вывод механизма ---\n")


def двор(состояние: dict, *, след: str | None = ШАПКА + "отказов шагов: 0\n",
         карта: str = "lines:\n  - id: harness\n    tasks:\n      - id: hr.есть\n",
         причины: list | None = None,
         больной_след: str | None = ШАПКА_БОЛЬНОГО + "шаг без своей модели: контракт\n",
         мутации_проб: dict | None = МУТАЦИИ_ПО_УМОЛЧАНИЮ,
         инварианты: list | None = None,
         слова_владельца: list | None = None,
         юниты: dict | None = None) -> pathlib.Path:
    """Свой двор: реестр, классы, состояние, карта, два следа и ДВА носителя мутаций."""
    путь = pathlib.Path(tempfile.mkdtemp(prefix="след-"))
    (путь / "mechanisms.yaml").write_text(
        yaml.dump([МЕХАНИЗМ, ПРОБА_D, ГЕЙТ_C1, ОБРАБОТЧИК_B2],
                  allow_unicode=True), encoding="utf-8")
    данные_классов = {"классы": КЛАССЫ}
    if причины is not None:
        данные_классов["причины_непроверяемого"] = причины
    (путь / "classes.yaml").write_text(
        yaml.dump(данные_классов, allow_unicode=True), encoding="utf-8")
    (путь / "state.yaml").write_text(
        yaml.dump({"проверено": состояние}, allow_unicode=True), encoding="utf-8")
    (путь / "dev-map.yaml").write_text(карта, encoding="utf-8")
    if след is not None:
        (путь / "след.log").write_text(след, encoding="utf-8")
    if больной_след is not None:
        (путь / "больной.log").write_text(больной_след, encoding="utf-8")
    if мутации_проб is not None:
        (путь / "probe-mutations.yaml").write_text(
            yaml.dump({"пробы": мутации_проб}, allow_unicode=True), encoding="utf-8")
    if инварианты is not None:
        (путь / "invariants.yaml").write_text(
            yaml.dump({"инварианты": инварианты}, allow_unicode=True), encoding="utf-8")
    # Слова владельца лежат там, где их кладёт диспетчер: гейт ищет улику в
    # каталоге, а не в словах записи.
    обработано = путь / "log" / "inbox" / "обработано"
    обработано.mkdir(parents=True)
    for имя in (слова_владельца if слова_владельца is not None else [СЛОВО_ВЛАДЕЛЬЦА]):
        (обработано / имя).write_text("прямо сейчас займись харнесом", encoding="utf-8")
    if юниты is not None:
        (путь / "units.yaml").write_text(
            yaml.dump({"юниты": юниты}, allow_unicode=True), encoding="utf-8")
    return путь


def прогон(путь: pathlib.Path, *доводы: str) -> tuple[int, str]:
    среда = dict(os.environ)
    среда.update({
        "HARNESS_MECHANISMS": str(путь / "mechanisms.yaml"),
        "HARNESS_LIVE_CHECK_CLASSES": str(путь / "classes.yaml"),
        "HARNESS_LIVE_CHECK_STATE": str(путь / "state.yaml"),
        "HARNESS_LIVE_CHECK_DOC": str(путь / "документ.md"),
        "HARNESS_DEVMAP": str(путь / "dev-map.yaml"),
        "HARNESS_PROBE_MUTATIONS": str(путь / "probe-mutations.yaml"),
        "HARNESS_INVARIANTS": str(путь / "invariants.yaml"),
        "HARNESS_LIVE_CHECK_UNITS": str(путь / "units.yaml"),
        "HARNESS_LOG_DIR": str(путь / "log"),
    })
    готово = subprocess.run([sys.executable, str(ПРИБОР), *доводы],
                            capture_output=True, text=True, env=среда, timeout=120)
    return готово.returncode, готово.stdout + готово.stderr


def проверить(двор_путь: pathlib.Path) -> tuple[int, str]:
    """Документ собирается ПЕРВЫМ: прежний смысл `--проверить` — сверка
    документа с данными, и без сборки любой случай краснел бы по ней, а не по
    следу (тогда проба мерила бы не то, что обещает)."""
    код, вывод = прогон(двор_путь)
    if код != 0:
        return код, "сборка документа отказала: " + вывод
    return прогон(двор_путь, "--проверить")


def main() -> int:
    # ── БОЛЬНОЙ СЛУЧАЙ ПЕРВЫЙ: пересказ самотеста вместо живой проверки ────
    # Ровно это пропускал прежний гейт формы: «проверяется» из реестра,
    # переписанное в графу «живьём», выглядит работой и ею не является.
    д = двор({"a.sh": {"живьём": "bash a.sh --selftest", "увидели": "отказов шагов: 0",
                       "исход": "ок", "когда": "2026-10-17",
                       "след": "след.log"}},
             причины=ПРИЧИНЫ)
    код, вывод = проверить(д)
    случай("БОЛЬНОЙ СЛУЧАЙ: запись пересказывает самотест — отказ с причиной",
           код == 1 and "пересказ" in вывод.lower() and "a.sh" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    # ── Класс D: самотест и ЕСТЬ инструмент, и это законно ─────────────────
    д = двор({"test_a.py": {"живьём": "python3 test_a.py с мутацией в a.sh",
                            "увидели": "отказов шагов: 0", "исход": "ок",
                            "когда": "2026-10-17", "след": "след.log"}},
             причины=ПРИЧИНЫ)
    код, вывод = проверить(д)
    случай("класс D: запись о прогоне пробы законна",
           код == 0, f"код {код}, вывод {вывод[:300]!r}")

    # ── След обязан существовать и нести шапку обёртки ─────────────────────
    д = двор({"a.sh": {"живьём": "позвал в среде крона", "увидели": "отказов шагов: 0",
                       "исход": "ок", "когда": "2026-10-17", "след": "след.log"}},
             след=None, причины=ПРИЧИНЫ)
    код, вывод = проверить(д)
    случай("БОЛЬНОЙ: следа нет на диске — отказ называет путь",
           код == 1 and "Traceback" not in вывод
           and "следа нет на диске" in вывод and "след.log" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    д = двор({"a.sh": {"живьём": "позвал в среде крона", "увидели": "отказов шагов: 0",
                       "исход": "ок", "когда": "2026-10-17", "след": "след.log"}},
             след="отказов шагов: 0\n", причины=ПРИЧИНЫ)
    код, вывод = проверить(д)
    случай("БОЛЬНОЙ: в следе нет шапки обёртки — отказ",
           код == 1 and "шапк" in вывод.lower(),
           f"код {код}, вывод {вывод[:300]!r}")

    # ── Второй законный вид следа: его пишет прибор живой проверки ДЕМОНОВ ─
    # У демона класса A1 доказательством служит журнал его кронового прогона, и
    # копирует его хвост scripts/live-check-daemon.py, а не обёртка. Требовать
    # от такого следа шапку обёртки значило бы требовать того, чего в этом виде
    # доказательства не бывает (живой случай 17.10.2026: 20 демонов разом).
    ШАПКА_ДЕМОНА = ("время: 2026-10-17T07:30:00+05:00\n"
                    "механизм: a.sh\n"
                    "строка расписания: */10 * * * * /путь/a.sh >>/лог/a.log 2>&1\n"
                    "журнал кронового прогона: /лог/a.log\n"
                    "--- хвост журнала демона ---\n")
    д = двор({"a.sh": {"живьём": "прочитан журнал кронового прогона",
                       "увидели": "отказов шагов: 0",
                       "исход": "ок", "когда": "2026-10-17", "след": "след.log"}},
             след=ШАПКА_ДЕМОНА + "отказов шагов: 0\n", причины=ПРИЧИНЫ)
    код, вывод = проверить(д)
    случай("след прибора демонов принят: хвост журнала — тоже чужой текст",
           код == 0, f"код {код}, вывод {вывод[:300]!r}")

    # ── Третий законный вид следа: строка журнала скилов, её пишет ХУК ─────
    # У скила класса E доказательством служит машинная запись журнала вызовов
    # («источник»:«хук»), и копирует её scripts/live-check-skill.py. Обёртки в
    # этом виде доказательства не бывает: скил зовёт оболочка, а не я.
    ШАПКА_СКИЛА = ("время: 2026-10-17T07:55:00+05:00\n"
                   "механизм: a.sh\n"
                   "задача: задача-двора (начата 2026-10-15)\n"
                   "артефакт: docs/specs/спека.md\n"
                   "--- строка журнала скилов, написанная хуком ---\n")
    д = двор({"a.sh": {"живьём": "позван в этой задаче, запись журнала машинная",
                       "увидели": "отказов шагов: 0",
                       "исход": "ок", "когда": "2026-10-17", "след": "след.log"}},
             след=ШАПКА_СКИЛА + "отказов шагов: 0\n", причины=ПРИЧИНЫ)
    код, вывод = проверить(д)
    случай("след прибора скилов принят: строку журнала написал хук",
           код == 0, f"код {код}, вывод {вывод[:300]!r}")

    # ── «увидели» обязано цитировать след ДОСЛОВНО ─────────────────────────
    д = двор({"a.sh": {"живьём": "позвал в среде крона", "увидели": "всё работает",
                       "исход": "ок", "когда": "2026-10-17", "след": "след.log"}},
             причины=ПРИЧИНЫ)
    код, вывод = проверить(д)
    случай("БОЛЬНОЙ: «увидели» не цитирует след — отказ",
           код == 1 and "дословно" in вывод.lower(),
           f"код {код}, вывод {вывод[:300]!r}")

    # Короткая цитата не считается: «ок» найдётся в любом выводе.
    д = двор({"a.sh": {"живьём": "позвал в среде крона", "увидели": "отказов",
                       "исход": "ок", "когда": "2026-10-17", "след": "след.log"}},
             причины=ПРИЧИНЫ)
    код, вывод = проверить(д)
    случай("БОЛЬНОЙ: цитата короче 12 знаков не считается",
           код == 1 and "дословно" in вывод.lower(),
           f"код {код}, вывод {вывод[:300]!r}")

    # ── «косяк» называет существующую карточку карты ───────────────────────
    д = двор({"a.sh": {"живьём": "позвал в среде крона", "увидели": "отказов шагов: 0",
                       "исход": "косяк", "находка": "hr.нет-такой-карточки",
                       "когда": "2026-10-17", "след": "след.log"}},
             причины=ПРИЧИНЫ)
    код, вывод = проверить(д)
    случай("БОЛЬНОЙ: косяк ссылается на карточку, которой нет в карте",
           код == 1 and "hr.нет-такой-карточки" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    д = двор({"a.sh": {"живьём": "позвал в среде крона", "увидели": "отказов шагов: 0",
                       "исход": "косяк", "находка": "hr.есть",
                       "когда": "2026-10-17", "след": "след.log"}},
             причины=ПРИЧИНЫ)
    код, вывод = проверить(д)
    случай("косяк со существующей карточкой — законен",
           код == 0, f"код {код}, вывод {вывод[:300]!r}")

    # ── «не-проверяемо» называет причину из закрытого списка ───────────────
    д = двор({"a.sh": {"живьём": "трогать нельзя", "увидели": "руки прочь",
                       "исход": "не-проверяемо", "когда": "2026-10-17"}},
             причины=ПРИЧИНЫ)
    код, вывод = проверить(д)
    случай("БОЛЬНОЙ: «не-проверяемо» с причиной вне списка — отказ",
           код == 1 and "причина «не-проверяемо» не из списка" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    д = двор({"a.sh": {"живьём": "трогать нельзя", "увидели": ПРИЧИНЫ[1],
                       "исход": "не-проверяемо", "когда": "2026-10-17"}},
             причины=ПРИЧИНЫ)
    код, вывод = проверить(д)
    случай("«не-проверяемо» с причиной из списка — законно",
           код == 0, f"код {код}, вывод {вывод[:300]!r}")

    # Список причин в данных ОБЯЗАН быть: пустые данные делали бы это
    # требование зелёным без работы — так уже краснел гейт чистоты.
    д = двор({"a.sh": {"живьём": "трогать нельзя", "увидели": ПРИЧИНЫ[1],
                       "исход": "не-проверяемо", "когда": "2026-10-17"}},
             причины=None)
    код, вывод = проверить(д)
    случай("БОЛЬНОЙ: списка причин нет в данных — отказ, а не зелень",
           код == 1 and "списка «причины_непроверяемого» в данных нет" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    # ── «ждёт» называет, чьего слова ждёт ──────────────────────────────────
    д = двор({"a.sh": {"живьём": "проверить нельзя сейчас", "увидели": "отказов шагов: 0",
                       "исход": "ждёт", "когда": "2026-10-17", "след": "след.log"}},
             причины=ПРИЧИНЫ)
    код, вывод = проверить(д)
    случай("БОЛЬНОЙ: «ждёт» не называет, чьего слова — отказ",
           код == 1 and "ждёт" in вывод.lower(),
           f"код {код}, вывод {вывод[:300]!r}")

    # ── Прежний смысл сохранён: документ, правленный руками, краснит ───────
    д = двор({"a.sh": {"живьём": "позвал в среде крона", "увидели": "отказов шагов: 0",
                       "исход": "ок", "когда": "2026-10-17", "след": "след.log"}},
             причины=ПРИЧИНЫ)
    код, _ = прогон(д)
    (д / "документ.md").write_text("правка руками\n", encoding="utf-8")
    код, вывод = прогон(д, "--проверить")
    случай("прежний смысл цел: документ правлен руками — отказ",
           код == 1 and "документ" in вывод.lower(),
           f"код {код}, вывод {вывод[:300]!r}")

    # ── Здоровый случай целиком ────────────────────────────────────────────
    д = двор({"a.sh": {"живьём": "позвал в среде крона (env -i) и прочёл журнал",
                       "увидели": "отказов шагов: 0", "исход": "ок",
                       "когда": "2026-10-17", "след": "след.log"}},
             причины=ПРИЧИНЫ)
    код, вывод = проверить(д)
    случай("здоровая запись со следом и дословной цитатой — зелено",
           код == 0, f"код {код}, вывод {вывод[:300]!r}")

    # ── §3.1: КЛАСС СУДИТСЯ КОДОМ, а не обещанием проверяющего ───────────
    # БОЛЬНОЙ СЛУЧАЙ 17.10.2026: этой проверки не было вовсе, и за одну смену
    # я записал 48 гейтов-судей по ОДНОМУ зелёному прогону — спека же говорит
    # «одного зелёного мало». Класс лежал в данных, а предикат класса не судил
    # никто: запись выглядела доказанной, потому что доказан был ДРУГОЙ,
    # слабейший предикат (§3.2 про след).
    ЗДОРОВО_C1 = {"живьём": "позван так, как его зовёт прогон ворот",
                  "увидели": "отказов шагов: 0", "след": "след.log",
                  "исход": "ок", "когда": "2026-10-17"}
    БОЛЬНАЯ_ПОЛОВИНА = {"больной": "в копии дерева снята строка модели шага: "
                                   "шаг без своей модели: контракт",
                        "след_больного": "больной.log"}

    д = двор({"gate_a.py": dict(ЗДОРОВО_C1)})
    код, вывод = проверить(д)
    случай("БОЛЬНОЙ СЛУЧАЙ: гейт-судья с одним зелёным прогоном — отказ",
           код == 1 and "одного зелёного мало" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    д = двор({"gate_a.py": dict(ЗДОРОВО_C1, больной="сломал строку модели")})
    код, вывод = проверить(д)
    случай("больной случай назван, а следа его нет — отказ",
           код == 1 and "след больного случая" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    д = двор({"gate_a.py": dict(ЗДОРОВО_C1, **БОЛЬНАЯ_ПОЛОВИНА)},
             больной_след=None)
    код, вывод = проверить(д)
    случай("след больного случая назван, а на диске его нет — отказ",
           код == 1 and "следа больного случая нет на диске" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    д = двор({"gate_a.py": dict(ЗДОРОВО_C1, **БОЛЬНАЯ_ПОЛОВИНА)},
             больной_след="я сам написал, что гейт покраснел\n")
    код, вывод = проверить(д)
    случай("след больного случая без шапки обёртки — отказ",
           код == 1 and "нет шапки обёртки" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    д = двор({"gate_a.py": dict(ЗДОРОВО_C1,
                                больной="гейт сказал, что всё плохо",
                                след_больного="больной.log")})
    код, вывод = проверить(д)
    случай("«больной» не цитирует свой след ДОСЛОВНО — отказ",
           код == 1 and "не цитирует след больного случая" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    д = двор({"gate_a.py": dict(ЗДОРОВО_C1, **БОЛЬНАЯ_ПОЛОВИНА)})
    код, вывод = проверить(д)
    случай("обе половины на месте — гейт-судья проверен",
           код == 0, f"код {код}, вывод {вывод[:300]!r}")

    # Исход «косяк» доказывает ДЕФЕКТ: больной случай в нём — сам живой вызов,
    # и требовать второй половины значит снять настоящую находку.
    д = двор({"gate_a.py": dict(ЗДОРОВО_C1, исход="косяк",
                                находка="закрыто: гейт читал форму, которой нет")})
    код, вывод = проверить(д)
    случай("косяк у гейта-судьи больной половины не требует",
           код == 0, f"код {код}, вывод {вывод[:300]!r}")

    # ── §3.1, класс B2: ЧЬИ это слова ────────────────────────────────────
    # Предикат класса B2 не судил никто: запись «прогон на живых формулировках
    # владельца» проходила общий след §3.2, а чьи это слова — проверяющего или
    # владельца — не спрашивалось. Улика ищется в каталоге диспетчера.
    СЛЕД_B2 = (ШАПКА.replace("механизм: a.sh", "механизм: inbox_a.py")
               + "прямо сейчас\n"
               + f"входящее: {СЛОВО_ВЛАДЕЛЬЦА}\n")
    ЗДОРОВО_B2 = {"живьём": "прогнан на записанном слове владельца",
                  "увидели": "прямо сейчас займись", "след": "след.log",
                  "исход": "ок", "когда": "2026-10-18"}

    д = двор({"inbox_a.py": dict(ЗДОРОВО_B2)}, след=СЛЕД_B2, юниты={})
    код, вывод = проверить(д)
    случай("БОЛЬНОЙ СЛУЧАЙ: обработчик входящих не называет слова владельца — отказ",
           код == 1 and "записанного слова владельца" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    д = двор({"inbox_a.py": dict(ЗДОРОВО_B2, входящее="1700000000.000000000.txt")},
             след=СЛЕД_B2, юниты={})
    код, вывод = проверить(д)
    случай("названного входящего нет в каталоге диспетчера — отказ",
           код == 1 and "не подтверждается" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    д = двор({"inbox_a.py": dict(ЗДОРОВО_B2, входящее=СЛОВО_ВЛАДЕЛЬЦА)},
             след=ШАПКА.replace("механизм: a.sh", "механизм: inbox_a.py")
                  + "прямо сейчас займись\n",
             юниты={})
    код, вывод = проверить(д)
    случай("имя входящего приписано к записи, а не взято из прогона — отказ",
           код == 1 and "не называет входящее" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    д = двор({"inbox_a.py": dict(ЗДОРОВО_B2, входящее=СЛОВО_ВЛАДЕЛЬЦА)},
             след=СЛЕД_B2, юниты={})
    код, вывод = проверить(д)
    случай("слово владельца названо и стоит в следе — обработчик проверен",
           код == 0, f"код {код}, вывод {вывод[:300]!r}")

    # Второе законное доказательство: приговор механизма прочитан в журнале
    # ЗОВУЩЕГО на настоящем сообщении владельца (носитель живой проверки
    # демонов). Поля «входящее» у такой записи нет и быть не должно.
    д = двор({"inbox_a.py": dict(ЗДОРОВО_B2)}, след=СЛЕД_B2,
             юниты={"inbox_a.py": {"зовёт": "диспетчер на каждое сообщение"}})
    код, вывод = проверить(д)
    случай("приговор, прочитанный в журнале зовущего, — законное доказательство",
           код == 0, f"код {код}, вывод {вывод[:300]!r}")

    # Данных зовущих нет вовсе: тогда прибор отказывает СЛОВАМИ, а не считает
    # предикат выполненным молча.
    д = двор({"inbox_a.py": dict(ЗДОРОВО_B2)}, след=СЛЕД_B2)
    код, вывод = проверить(д)
    случай("без данных зовущих и без входящего — отказ, а не молчание",
           код == 1 and "записанного слова владельца" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    # Класс D: прогон пробы доказывает, что проба РАБОТАЕТ, но не что она
    # ловит поломку. Связь «проба → механизм» обязана быть в данных.
    ЗДОРОВО_D = {"живьём": "проба прогнана целиком своей командой",
                 "увидели": "отказов шагов: 0", "след": "след.log",
                 "исход": "ок", "когда": "2026-10-17"}
    д = двор({"test_a.py": dict(ЗДОРОВО_D)}, мутации_проб={})
    код, вывод = проверить(д)
    случай("БОЛЬНОЙ СЛУЧАЙ: проба без названной мутации — отказ",
           код == 1 and "мутация пробы не названа в данных" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    д = двор({"test_a.py": dict(ЗДОРОВО_D)},
             мутации_проб={"test_a.py": {"механизм": "a.sh",
                                         "мутация": "s/x/y/",
                                         "мутация_случай": "случай"}})
    код, вывод = проверить(д)
    случай("мутация пробы названа в данных — зелено",
           код == 0, f"код {код}, вывод {вывод[:300]!r}")

    д = двор({"test_a.py": dict(ЗДОРОВО_D)}, мутации_проб=None)
    код, вывод = проверить(д)
    случай("носителя мутаций нет вовсе — отказ со своей причиной",
           код == 1 and "носителя мутаций проб нет" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    # Второй носитель мутаций — invariants.yaml: мутация там стоит В МЕХАНИЗМЕ,
    # а краснеть обязана команда «доказательство», то есть сама проба. Требовать
    # вторую запись в probe-mutations.yaml значит требовать дублировать данные:
    # мутационный прогон (scripts/mutation-probe.sh) читает ОБА носителя, и
    # предикат класса D обязан читать те же оба.
    ИНВАРИАНТ = {"id": "И-тест", "правило": "правило",
                 "механизм": "механизм", "файл": "a.sh",
                 "доказательство": "python3 test_a.py",
                 "мутация": "s/x/y/", "мутация_случай": "случай"}
    д = двор({"test_a.py": dict(ЗДОРОВО_D)}, мутации_проб={},
             инварианты=[ИНВАРИАНТ])
    код, вывод = проверить(д)
    случай("мутация названа у инварианта, чьё доказательство — эта проба: зелено",
           код == 0, f"код {код}, вывод {вывод[:300]!r}")

    д = двор({"test_a.py": dict(ЗДОРОВО_D)}, мутации_проб=None,
             инварианты=[ИНВАРИАНТ])
    код, вывод = проверить(д)
    случай("probe-mutations.yaml нет, а инвариант мутацию назвал — зелено",
           код == 0, f"код {код}, вывод {вывод[:300]!r}")

    д = двор({"test_a.py": dict(ЗДОРОВО_D)}, мутации_проб={},
             инварианты=[dict(ИНВАРИАНТ, мутация=None, мутация_случай=None)])
    код, вывод = проверить(д)
    случай("БОЛЬНОЙ СЛУЧАЙ: инвариант зовёт пробу, но мутации не назвал — отказ",
           код == 1 and "мутация пробы не названа в данных" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    д = двор({"test_a.py": dict(ЗДОРОВО_D)}, мутации_проб={},
             инварианты=[dict(ИНВАРИАНТ, доказательство="python3 gate_a.py --selftest")])
    код, вывод = проверить(д)
    случай("БОЛЬНОЙ СЛУЧАЙ: мутация у инварианта ЧУЖОЙ пробы — отказ",
           код == 1 and "мутация пробы не названа в данных" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    д = двор({"test_a.py": dict(ЗДОРОВО_D)}, мутации_проб={},
             инварианты=[dict(ИНВАРИАНТ, доказательство="python3 test_a.py.bak")])
    код, вывод = проверить(д)
    случай("БОЛЬНОЙ СЛУЧАЙ: доказательство зовёт файл, чьё имя лишь начинается"
           " с имени пробы — отказ",
           код == 1 and "мутация пробы не названа в данных" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    print(f"ИТОГ: хороших {хорошо}, плохих {плохо}")
    return 1 if плохо else 0


