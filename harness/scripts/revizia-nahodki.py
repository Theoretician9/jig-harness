#!/usr/bin/env python3
"""Что агент ревизии сделал с картой: разность двух карт, а не вера в промпт.

Откуда взят. Три улики ревью спеки ежемесячной ревизии:

* «число задач не уменьшилось» у ДОБАВЛЯЮЩЕГО демона не значит ничего: удалил
  пять, завёл двенадцать — счёт вырос, а пять задач исчезли молча (C-10).
  Поэтому сверяется МНОЖЕСТВО id.
* Потолок находок, записанный словами в промпте, держится ровно до первого
  раза, когда агент решит иначе (I-14). Поэтому потолок — арифметика здесь.
* Дубли находок агент по промпту не ловит (I-11): месяц спустя та же дыра
  описывается другими словами. Поэтому у находки есть КЛЮЧ, и сверку по ключу
  делает скрипт, а не внимание.

Разбор карточек берётся ИМПОРТОМ из `arhiv-karty.py`: второй разбор блоков
карты разъехался бы с первым при первой же правке формата.

Запуск:
    revizia-nahodki.py --до <файл> --после <файл> --максимум N --максимум-знаков M [--применить]
    revizia-nahodki.py --устаревшие <карта> --срок 90
Код возврата: 0 — разобрано, 3 — из карты ПРОПАЛИ задачи (ничего не записано).
"""
from __future__ import annotations

import datetime
import importlib.util
import json
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
_спец = importlib.util.spec_from_file_location("архив", КОРЕНЬ / "scripts" / "arhiv-karty.py")
_архив = importlib.util.module_from_spec(_спец)
_спец.loader.exec_module(_архив)

КЛЮЧ_НАХОДКИ = re.compile(r"^\s+источник:\s*(ревизия:\S.*)$", re.M)
ЗАВЕДЕНО = re.compile(r'^\s+заведено:\s*"?(\d{4}-\d{2}-\d{2})"?', re.M)
СТАТУС = re.compile(r"^(\s+)status:\s*\S+\s*$", re.M)


def ключ_находки(блок: str) -> str | None:
    """Ключ вида `ревизия:<область>:<файл>:<заголовок>` либо None."""
    совпало = КЛЮЧ_НАХОДКИ.search(блок)
    return совпало.group(1).strip() if совпало else None


def область_ключа(ключ: str) -> str:
    части = ключ.split(":")
    return части[1] if len(части) > 1 else ""


def _карточки(текст: str) -> dict[str, str]:
    """{id: блок} только по ЛИСТЬЯМ дерева карты.

    `блоки()` отдаёт и направление (`- id: harness`), чей блок содержит все
    свои задачи: без фильтра «изменённой» считалась бы вся ветка, а возврат
    её блока из «до» затирал бы новые карточки разом.
    """
    все = _архив.блоки(текст)
    листья = {}
    for ид, блок, начало, конец in все:
        если_внутри = [и for и, _, н, _ in все if и != ид and начало < н < конец]
        if not если_внутри:
            листья[ид] = блок
    return листья


def сверить(до: str, после: str, максимум: int, максимум_знаков: int) -> dict:
    """Разность двух карт: что пропало, что изменено, что заведено сверх правил."""
    было, стало = _карточки(до), _карточки(после)
    итог = {"текст": после, "новых": 0, "пропавшие": sorted(set(было) - set(стало)),
            "изменённые": [], "без_ключа": [], "дубли": [], "длинные": [],
            "сверх_потолка": [], "по_областям": {}, "заголовки": []}
    # Пропажа — стоп: карта возвращается целиком, разбираться будет человек.
    if итог["пропавшие"]:
        return итог

    текст = после
    # Чужая карточка, которую агент переписал, возвращается из «до»: ему велено
    # ТОЛЬКО добавлять, и молчаливая правка чужого — это потеря работы.
    for ид, блок in было.items():
        if стало[ид] != блок:
            итог["изменённые"].append(ид)
            текст = текст.replace(стало[ид], блок, 1)

    ключи_до = {ключ_находки(б) for б in было.values()} - {None}
    видели: set[str] = set()
    принятые: list[str] = []
    # Порядок сита важен: карточка попадает в ОДИН список причин, не в два.
    for ид, блок in стало.items():
        if ид in было:
            continue
        ключ = ключ_находки(блок)
        if ключ is None:
            итог["без_ключа"].append(ид)
        elif ключ in ключи_до or ключ in видели:
            итог["дубли"].append(ид)
        elif len(блок) > максимум_знаков:
            итог["длинные"].append(ид)
        else:
            видели.add(ключ)
            принятые.append(ид)

    # Потолок — арифметикой по порядку в файле, а не просьбой в промпте.
    сверх = принятые[максимум:]
    принятые = принятые[:максимум]
    итог["сверх_потолка"] = сверх  # порядок файла, а не алфавита

    for список in ("без_ключа", "дубли", "длинные"):
        итог[список] = sorted(итог[список])
    for ид in sorted(set(итог["без_ключа"] + итог["дубли"] + итог["длинные"] + сверх)):
        текст = текст.replace(стало[ид], "", 1)

    for ид in принятые:
        блок = стало[ид]
        # Находка — предложение, а не работа: статус всегда plan.
        новый = СТАТУС.sub(lambda м: f"{м.group(1)}status: plan", блок, count=1)
        if новый != блок:
            текст = текст.replace(блок, новый, 1)
        область = область_ключа(ключ_находки(блок) or "")
        итог["по_областям"][область] = итог["по_областям"].get(область, 0) + 1
        совпало = re.search(r'^\s+title:\s*"(.*)"\s*$', блок, re.M)
        if совпало and len(итог["заголовки"]) < 3:
            итог["заголовки"].append(совпало.group(1))

    текст = re.sub(r"\n{3,}", "\n\n", текст)
    итог["текст"] = текст
    итог["новых"] = len(принятые)
    return итог


def устаревшие(текст: str, срок_суток: int, сегодня: datetime.date) -> list[str]:
    """id находок ревизии в статусе plan, заведённых раньше срока."""
    старые = []
    for ид, блок, _, _ in _архив.блоки(текст):
        if not ключ_находки(блок) or _архив.статус(блок) != "plan":
            continue
        когда = ЗАВЕДЕНО.search(блок)
        if когда and (сегодня - datetime.date.fromisoformat(когда.group(1))).days > срок_суток:
            старые.append(ид)
    return старые


def _довод(имя: str, умолчание=None):
    return sys.argv[sys.argv.index(имя) + 1] if имя in sys.argv else умолчание


def main() -> int:
    if "--устаревшие" in sys.argv:
        карта = Path(_довод("--устаревшие"))
        срок = int(_довод("--срок", "90"))
        for ид in устаревшие(карта.read_text(encoding="utf-8"), срок, datetime.date.today()):
            print(ид)
        return 0

    до, после = Path(_довод("--до")), Path(_довод("--после"))
    итог = сверить(до.read_text(encoding="utf-8"), после.read_text(encoding="utf-8"),
                   int(_довод("--максимум", "12")), int(_довод("--максимум-знаков", "1500")))
    текст = итог.pop("текст")
    print(json.dumps(итог, ensure_ascii=False))
    if итог["пропавшие"]:
        return 3
    if "--применить" in sys.argv:
        после.write_text(текст, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
