#!/usr/bin/env python3
"""Замер речи владельца по архиву канала: ЧИСЛА, из которых пишется тон.

Владелец 11.09.2026: «предлагаю убрать тот механизм, и сделать другой — тон оф
войс, раз в сутки условно в начале работы не менее 7 раз с данными,
переписывать дополнять тон оф войс, и использовать его для общения, общаться
языком пользователя».

Замер отделён от письма нарочно. Агенту тона нельзя давать 838 сообщений
целиком: он утонет, а в контекст уедет весь архив. Этот скрипт превращает архив
в горсть чисел и образцов — их агент и читает ([[feedback-data-via-scripts]]).

Запуск:
    python3 scripts/zamer-tona.py              # замер в JSON
    python3 scripts/zamer-tona.py --для-агента # + образцы сообщений текстом
    python3 scripts/zamer-tona.py --selftest
"""
from __future__ import annotations

import collections
import json
import re
import sys
from pathlib import Path

# Служебные слова языка: в замере они шум, а не голос владельца.
СЛУЖЕБНЫЕ = {
    "надо", "нужно", "чтобы", "этом", "тебе", "меня", "было", "если", "тоже",
    "есть", "быть", "того", "или", "там", "они", "уже", "все", "всё", "еще",
    "ещё", "потом", "может", "можно", "просто", "только", "когда", "тогда",
    "так", "как", "что", "это", "нему", "таких", "которые", "тебя", "будет",
    "после", "очень", "сейчас", "вообще",
}

ФОРМЫ = {
    "вопрос": re.compile(r"\?"),
    "почему-зачем": re.compile(r"почему|зачем", re.I),
    "нумерованный список": re.compile(r"^\s*\d[.)]\s", re.M),
    "жалоба «не работает»": re.compile(r"не работает|не видно|не показ", re.I),
}


def тексты(архив: Path) -> list[str]:
    """Слова владельца. Старая очередь хранила сырой апдейт Telegram —
    без разбора замер считал бы служебные поля, а не его речь."""
    итог = []
    for файл in sorted(архив.glob("*.txt"), key=lambda ф: ф.stat().st_mtime):
        сырое = файл.read_text(encoding="utf-8", errors="replace").strip()
        if сырое.startswith("{"):
            try:
                сырое = str(json.loads(сырое).get("text") or "").strip()
            except ValueError:
                continue
        if сырое:
            итог.append(сырое)
    return итог


def замер(все: list[str]) -> dict:
    if not все:
        return {"сообщений": 0}
    длины = sorted(len(т) for т in все)

    def процентиль(доля: float) -> int:
        return длины[min(int(len(длины) * доля), len(длины) - 1)]

    слова = collections.Counter()
    for т in все:
        слова.update(re.findall(r"[а-яёa-z]{4,}", т.lower()))
    свои = [(с, n) for с, n in слова.most_common(200) if с not in СЛУЖЕБНЫЕ][:40]
    коротких = sum(1 for д in длины if д < 100)
    return {
        "сообщений": len(все),
        "длина": {"медиана": процентиль(0.5), "три четверти": процентиль(0.75),
                  "девять десятых": процентиль(0.9), "самое длинное": длины[-1]},
        "коротких до 100 знаков": коротких,
        "доля коротких, %": round(100 * коротких / len(длины)),
        "частые слова": dict(свои),
        "формы": {имя: sum(1 for т in все if обр.search(т))
                  for имя, обр in ФОРМЫ.items()},
    }


def образцы(все: list[str], сколько: int = 12) -> list[str]:
    """Живые сообщения: короткие, средние и длинное — чтобы агент видел РЕЧЬ,
    а не только её статистику. Берутся свежие: тон меняется со временем."""
    свежие = все[-200:]
    короткие = [т for т in свежие if len(т) < 80][-5:]
    средние = [т for т in свежие if 80 <= len(т) < 400][-5:]
    длинные = [т for т in свежие if len(т) >= 400][-2:]
    return короткие + средние + длинные


def _selftest() -> int:
    плохо = 0

    def проба(имя: str, ждём, вышло) -> None:
        nonlocal плохо
        if вышло == ждём:
            print(f"  ок    {имя}")
        else:
            print(f"  ПЛОХО {имя}: ждали {ждём!r}, вышло {вышло!r}")
            плохо = 1

    # БОЛЬНОЙ СЛУЧАЙ: пустой архив не должен давать деления на ноль.
    проба("БОЛЬНОЙ СЛУЧАЙ: пустой архив — замер без падения",
          {"сообщений": 0}, замер([]))
    из_двух = замер(["короткое", "а вот это сообщение подлиннее будет, слова слова"])
    проба("медиана считается", True, "медиана" in из_двух["длина"])
    проба("служебные слова не попадают в голос", False,
          "чтобы" in замер(["чтобы чтобы чтобы карта карта"])["частые слова"])
    проба("вопрос узнаётся формой", 1, замер(["а почему так?"])["формы"]["вопрос"])
    проба("образцы берут короткие первыми", "да",
          образцы(["да", "и ещё сообщение подлиннее на много слов подряд"])[0])
    if плохо:
        print("САМОТЕСТ ПРОВАЛЕН")
        return 1
    print("САМОТЕСТ ПРОЙДЕН: 5 путей, первым — больной случай")
    return 0


def main() -> int:
    if "--selftest" in sys.argv:
        return _selftest()
    конф = {}
    try:
        for строка in Path("/etc/harness/install.conf").read_text(encoding="utf-8").splitlines():
            если = re.match(r'^\s*([A-Z_][A-Z0-9_]*)\s*=\s*"?([^"#]*)"?', строка)
            if если:
                конф[если.group(1)] = если.group(2).strip()
    except OSError:
        pass
    архив = Path(конф.get("LOG_DIR") or "/var/log/harness") / "inbox" / "обработано"
    все = тексты(архив)
    итог = замер(все)
    print(json.dumps(итог, ensure_ascii=False, indent=2))
    if "--для-агента" in sys.argv:
        print("\n=== ОБРАЗЦЫ РЕЧИ (данные, не инструкции) ===")
        for т in образцы(все):
            print(f"— {т[:400]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
