#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Слово, которым владелец направил внимание, либо пусто.

Владелец 12.09.2026: «я могу своей волей направить твоё внимание на любую
задачу в любой момент, если ясно об этом говорю».

Зовётся ДИСПЕТЧЕРОМ канала в момент приёма сообщения: признак срочности
обязан ставить тот, чьи это слова, а не тот, кому он выгоден (ревью спеки
12.09.2026 — та же находка, по которой отвергнуто поле приоритета в карточке).

Слова и отменяющие формы — данные `harness/config/очередь.yaml`. Отдельный файл,
а не строчка в диспетчере: списку слов положено жить там же, где его читает
прибор очереди.

    slovo-vnimaniya.py "<текст владельца>"     # печатает слово или ничего
    slovo-vnimaniya.py --selftest
"""
import os
import sys
from pathlib import Path

import yaml

# Сколько слов перед находкой смотрим, решая «приказ или рассуждение».
ОКНО_ПЕРЕД = 3

КОНФИГ = os.environ.get("QUEUE_CONF") or str(
    Path(__file__).resolve().parent.parent / "harness" / "config" / "очередь.yaml")


def данные(путь: str | None = None) -> dict:
    try:
        return yaml.safe_load(Path(путь or КОНФИГ).read_text(encoding="utf-8")) or {}
    except (OSError, yaml.YAMLError):
        return {}


def слово(текст: str, наст: dict) -> str:
    """Слово внимания из текста, либо «». Отменяющая форма гасит находку."""
    низ = (текст or "").lower()
    if any(о in низ for о in наст.get("внимание_отменяется") or []):
        # «После того как полностью закончишь текущие задачи, займись…» —
        # это ровно обратное приказу: работа отложена, а не поднята.
        return ""
    for с in наст.get("слова_внимания") or []:
        место = низ.find(с)
        if место >= 0 and не_упоминание(низ, место, наст):
            return с
    return ""


def не_упоминание(низ: str, место: int, наст: dict) -> bool:
    """Слово внимания — ПРИКАЗ, а не упоминание в рассуждении.

    Улика 13.09.2026, и она о самом приборе: владелец написал «прежде чем
    приступить к тому что я говорю, ЕСЛИ ЭТО НЕ ЧТОТО СРОЧНОЕ, ты точно
    сначала пересматриваешь карту разработки», прося НЕ дёргаться за свежими
    сообщениями. Прибор нашёл в этой фразе слово «срочно» и дал задаче из неё
    вес 100 — то есть сообщение, требующее не поднимать свежее наверх, само
    встало наверх и обогнало работу, которая шла (30 против 132).

    Различаем по словам ПЕРЕД находкой: отрицание и условие превращают приказ
    в рассуждение о приказе. Окно короткое — три слова: дальше связь теряется,
    и «не буду мешать, займись картой» гасилось бы зря.
    """
    хвост = низ[:место].split()[-ОКНО_ПЕРЕД:]
    гасят = set(наст.get("внимание_не_приказ") or [])
    return not (гасят & {с.strip(".,:;!?«»()") for с in хвост})


def самотест() -> int:
    наст = {"слова_внимания": ["прямо сейчас", "в первую очередь", "займись", "брось", "срочно"],
            "внимание_отменяется": ["после того как", "как закончишь"],
            "внимание_не_приказ": ["не", "если", "когда", "пока", "чтото", "что-то"]}
    случаи = [
        # Живые сообщения владельца из архива — не выдуманные образцы.
        ("прямо сейчас", "Твоя задача прямо сейчас перенести весь функционал"),
        ("в первую очередь", "твоя задача сейчас в первую очередь перенести весь функционал"),
        ("прямо сейчас", "прямо сейчас отключи програмно город"),
        # БОЛЬНОЙ СЛУЧАЙ: то же слово, но работа ОТЛОЖЕНА — не приказ.
        ("", "После того как полностью закончишь текущие задачи, займись тем, что я напишу"),
        ("", "Вот так выглядит карта, займись как закончишь остальные"),
        ("займись", "займись входом, он истекает"),
        # Голое «сейчас» — обстоятельство времени, а не приказ (69 раз в архиве).
        ("", "я сейчас добавил памяти и от этого перезагрузился север"),
        ("", "сначала положить эту задачу в беклог"),
        ("", ""),
        # БОЛЬНОЙ СЛУЧАЙ 13.09.2026, дословно из канала: владелец просит НЕ
        # дёргаться за свежими сообщениями — и прибор нашёл здесь приказ
        # «срочно», подняв задачу из этой же фразы на первое место.
        ("", "прежде чем приступить к тому что я говорю, если это не чтото "
             "срочное, ты точно сначала пересматриваешь карту разработки"),
        ("срочно", "срочно почини панель, она не отвечает"),
        ("", "это не срочно, посмотри когда дойдёшь"),
        ("займись", "займись очередью задач"),
        ("", "когда займись будет уместно, я скажу"),
    ]
    ok = True
    for ждём, текст in случаи:
        вышло = слово(текст, наст)
        если_плохо = вышло != ждём
        ok = ok and not если_плохо
        значок = "ПЛОХО" if если_плохо else "ок   "
        print(f"  {значок} «{текст[:52]}» → «{вышло}» (ждали «{ждём}»)")
    print("САМОТЕСТ %s: %d путей, среди них больные — отложенный приказ и упоминание в рассуждении"
          % ("ПРОЙДЕН" if ok else "ПРОВАЛЕН", len(случаи)))
    return 0 if ok else 1


def main() -> int:
    if "--selftest" in sys.argv:
        return самотест()
    текст = sys.argv[1] if len(sys.argv) > 1 else ""
    найдено = слово(текст, данные())
    if найдено:
        print(найдено)
    return 0


if __name__ == "__main__":
    sys.exit(main())
