#!/usr/bin/env python3
"""Гейт: файл секрета читает ТОЛЬКО его владелец.

Улика 27.09.2026 (замер для ревизии харнеса). В `SECRETS_DIR` лежали два файла с
правами шире `600`: снимок боевого окружения продукта (`644`, 1 306 байт) и
пустой файл `имя` (`664`). На этой машине есть ещё три домашних каталога других
людей и `www-data` — то есть токен и креды мог прочитать любой, кто на неё зашёл.

Почему нужен ОТДЕЛЬНЫЙ гейт: И-3 держат два прибора, и оба смотрят не туда.
`check-secrets.sh` стережёт РЕПОЗИТОРИЙ (чтобы секрет не уехал в git),
`check-secret-in-logs.py` — ЖУРНАЛЫ. Права внутри каталога секретов не проверял
никто, и дыра прожила там с 10.09.2026 незамеченной.

Судится ФОРМА права, а не имя файла: `600` (или строже) для файла, `700` для
каталога. Судить по имени нельзя — оба измерения имени уже проверялись и лгали
([[a-secret-is-known-by-its-shape]]).

Запуск:
    python3 scripts/check-secrets-perms.py            # гейт: 0 — чисто
    python3 scripts/check-secrets-perms.py --selftest
Код возврата: 0 — чисто, 1 — есть файл шире 600, 2 — каталог не прочитан.
"""
from __future__ import annotations

import os
import stat
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))
import config as конф                                    # noqa: E402

# Права, при которых файл виден не только владельцу: любой бит группы и мира.
ЛИШНИЕ_БИТЫ_ФАЙЛА = (stat.S_IRWXG | stat.S_IRWXO)
# У каталога секретов тот же счёт: группа и мир не должны видеть даже список.
ЛИШНИЕ_БИТЫ_КАТАЛОГА = (stat.S_IRWXG | stat.S_IRWXO)


def находки(каталог: Path) -> list[tuple[str, int]]:
    """Файлы и подкаталоги с лишними правами: [(путь, права)]."""
    итог: list[tuple[str, int]] = []
    свой = os.stat(каталог).st_mode
    if свой & ЛИШНИЕ_БИТЫ_КАТАЛОГА:
        итог.append((str(каталог), stat.S_IMODE(свой)))
    for путь in sorted(каталог.rglob("*")):
        режим = путь.lstat().st_mode
        лишние = (ЛИШНИЕ_БИТЫ_КАТАЛОГА if путь.is_dir() else ЛИШНИЕ_БИТЫ_ФАЙЛА)
        if режим & лишние:
            итог.append((str(путь), stat.S_IMODE(режим)))
    return итог


def _selftest() -> int:
    import tempfile
    плохо = 0

    def проба(имя: str, хорошо: bool) -> None:
        nonlocal плохо
        print(f"  {'ок   ' if хорошо else 'ПЛОХО'} {имя}")
        плохо = плохо or not хорошо

    with tempfile.TemporaryDirectory() as врем:
        двор = Path(врем) / "секреты"
        двор.mkdir(mode=0o700)
        (двор / "токен").write_text("s3cret", encoding="utf-8")
        (двор / "токен").chmod(0o600)
        проба("каталог 700 и файл 600 — чисто", находки(двор) == [])

        # БОЛЬНОЙ СЛУЧАЙ 27.09.2026: ровно этот файл и лежал в боевом каталоге.
        (двор / "снимок.bak").write_text("DB_PASSWORD=...", encoding="utf-8")
        (двор / "снимок.bak").chmod(0o644)
        найдено = находки(двор)
        проба("БОЛЬНОЙ СЛУЧАЙ: файл 644 назван",
              any(п.endswith("снимок.bak") and р == 0o644 for п, р in найдено))
        проба("и файл 600 при этом не назван",
              not any(п.endswith("токен") for п, _ in найдено))

        # Второй из того же замера: пустой файл с правом записи для группы.
        (двор / "снимок.bak").chmod(0o600)
        (двор / "пустой").write_text("", encoding="utf-8")
        (двор / "пустой").chmod(0o664)
        проба("БОЛЬНОЙ СЛУЧАЙ: пустой файл 664 назван — пустота не оправдание",
              any(п.endswith("пустой") for п, _ in находки(двор)))

        # Подкаталог: в боевом каталоге лежит «панель-токены/».
        (двор / "пустой").chmod(0o600)
        (двор / "подкаталог").mkdir(mode=0o755)
        проба("БОЛЬНОЙ СЛУЧАЙ: подкаталог 755 назван",
              any(п.endswith("подкаталог") for п, _ in находки(двор)))

        (двор / "подкаталог").chmod(0o700)
        проба("после сужения прав — снова чисто", находки(двор) == [])

        # Сам каталог секретов: 750 значит, что список файлов видит группа.
        двор.chmod(0o750)
        проба("БОЛЬНОЙ СЛУЧАЙ: каталог 750 назван",
              any(п == str(двор) for п, _ in находки(двор)))
        двор.chmod(0o700)

        # Символическая ссылка судится по СЕБЕ (lstat), а не по цели: иначе
        # ссылка 777 на секрет прошла бы молча.
        (двор / "ссылка").symlink_to(двор / "токен")
        режим = (двор / "ссылка").lstat().st_mode
        проба("ссылка не роняет разбор", isinstance(режим, int))

    if плохо:
        print("САМОТЕСТ ПРОВАЛЕН")
        return 1
    print("САМОТЕСТ ПРОЙДЕН: 8 путей, второй — больной случай 27.09.2026")
    return 0


def main(argv: list[str]) -> int:
    if "--selftest" in argv:
        return _selftest()
    каталог = Path(конф.secrets_dir())
    if not каталог.is_dir():
        # «Не нашли» и «не смогли прочитать» — разные ответы: закрытый источник
        # не имеет права зеленить проверку ([[unreadable-source-turns-check-green]]).
        print(f"[права секретов] каталог секретов не прочитан: {каталог}")
        return 2
    try:
        найдено = находки(каталог)
    except OSError as беда:
        print(f"[права секретов] каталог не обойдён: {беда}")
        return 2
    if not найдено:
        print("[права секретов] чисто: секреты читает только их владелец")
        return 0
    print(f"[права секретов] КРАСНЫЙ: {len(найдено)} шире 600 — "
          "их может прочитать любой, кто зашёл на машину")
    for путь, режим in найдено:
        print(f"    {режим:o} {путь}")
    print("    Лечение: chmod 600 для файлов, chmod 700 для каталогов.")
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
