#!/usr/bin/env python3
"""Проверка счёта версии релиза: что versiya.py считает и чего НЕ считает.

Откуда взято. Владелец 12.09.2026: «Какие есть стандарты для релизов в гит».
План — .tasks/hr.relizy-po-standartu/план.md.

Проверять приходится на подставных репозиториях: у живой публичной сборки один
коммит и ноль тегов, и «сегодня зелёно» на ней не отличает патч от минора.
Отдельный путь — переименование: на прошлом релизе реестр механизмов лежал по
кириллическому пути, и признак «новый файл» обязан отличать R от A.

Прогон:
    python3 scripts/test_versiya.py
Код возврата: 0 — все пути прошли, 1 — есть упавший.
"""
import importlib.util
import subprocess
import sys
import tempfile
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
путей = неудач = 0


def путь_ок(текст: str) -> None:
    global путей
    путей += 1
    print("ок  · " + текст)


def путь_плохо(текст: str) -> None:
    global путей, неудач
    путей += 1
    неудач += 1
    print("ПЛОХО · " + текст)


спец = importlib.util.spec_from_file_location(
    "версия", КОРЕНЬ / "scripts" / "versiya.py")
версия = importlib.util.module_from_spec(спец)
спец.loader.exec_module(версия)


def гит(*доводы, где=None):
    return subprocess.run(["git", *доводы], cwd=где, capture_output=True,
                          text=True, timeout=30)


def коммит(репо: Path, текст: str) -> str:
    гит("add", "-A", где=репо)
    гит("commit", "-q", "-m", текст, где=репо)
    return гит("rev-parse", "--short", "HEAD", где=репо).stdout.strip()


def двор() -> tuple:
    """Подставные пакет и сборка: в пакете механизмы, в сборке — релизы."""
    врем = Path(tempfile.mkdtemp(prefix="версия-"))
    пакет, сборка = врем / "пакет", врем / "сборка"
    for репо in (пакет, сборка):
        репо.mkdir()
        гит("init", "-q", "-b", "master", str(репо))
        гит("config", "user.email", "проба@харнес", где=репо)
        гит("config", "user.name", "проба", где=репо)
    (пакет / "harness" / "demons").mkdir(parents=True)
    (пакет / "harness" / "demons" / "backup.sh").write_text("#!/bin/sh\n", encoding="utf-8")
    коммит(пакет, "первый механизм")
    return врем, пакет, сборка


ДАННЫЕ = версия.данные(КОРЕНЬ / "harness" / "config" / "релиз.yaml")
врем, пакет, сборка = двор()

try:
    print("── первый релиз: тегов нет ──")
    ответ = версия.следующая(пакет, сборка, ДАННЫЕ)
    if ответ["следующая"] == ДАННЫЕ["начальная_версия"]:
        путь_ок(f"тегов нет → начальная версия {ответ['следующая']}")
    else:
        путь_плохо(f"без тегов выдана версия {ответ['следующая']}")
    if ответ["заметки"] == ["первый механизм"]:
        путь_ок("заметки первого релиза — вся история пакета")
    else:
        путь_плохо(f"заметки первого релиза: {ответ['заметки']}")

    # Сборка получает релиз: коммит с ТЕМ ЖЕ заголовком, что пишет
    # publikaciya.sh (его же читает obnovlenie.py), и тег.
    хэш = гит("rev-parse", "--short", "HEAD", где=пакет).stdout.strip()
    (сборка / "VERSION").write_text("0.1.0\n", encoding="utf-8")
    коммит(сборка, f"версия от 2026-09-01, пакет {хэш}")
    гит("tag", "-a", "v0.1.0", "-m", "релиз", где=сборка)

    print("── минор: появился новый механизм ──")
    (пакет / "harness" / "demons" / "новый.sh").write_text("#!/bin/sh\n", encoding="utf-8")
    коммит(пакет, "новый демон присмотра")
    ответ = версия.следующая(пакет, сборка, ДАННЫЕ)
    if ответ["следующая"] == "0.2.0":
        путь_ок(f"новый файл демона → минор 0.2.0 ({ответ['почему']})")
    else:
        путь_плохо(f"новый демон дал {ответ['следующая']}: {ответ['почему']}")
    if ответ["заметки"] == ["новый демон присмотра"]:
        путь_ок("заметки — только коммиты после прошлого релиза")
    else:
        путь_плохо(f"заметки вышли за диапазон: {ответ['заметки']}")

    print("── патч: правка существующего ──")
    (сборка / "VERSION").write_text("0.2.0\n", encoding="utf-8")
    хэш = гит("rev-parse", "--short", "HEAD", где=пакет).stdout.strip()
    коммит(сборка, f"версия от 2026-09-02, пакет {хэш}")
    гит("tag", "-a", "v0.2.0", "-m", "релиз", где=сборка)
    (пакет / "harness" / "demons" / "backup.sh").write_text("#!/bin/sh\necho\n", encoding="utf-8")
    коммит(пакет, "копия считает свой возраст")
    ответ = версия.следующая(пакет, сборка, ДАННЫЕ)
    if ответ["следующая"] == "0.2.1":
        путь_ок(f"правка файла → патч 0.2.1 ({ответ['почему']})")
    else:
        путь_плохо(f"правка дала {ответ['следующая']}: {ответ['почему']}")

    print("── переименование не возможность ──")
    гит("mv", "harness/demons", "harness/demoni", где=пакет)
    коммит(пакет, "каталог демонов переименован")
    ответ = версия.следующая(пакет, сборка, ДАННЫЕ)
    if ответ["следующая"] == "0.2.1":
        путь_ок("переименование каталога → патч, а не минор")
    else:
        путь_плохо(f"переименование дало {ответ['следующая']}: {ответ['почему']}")

    print("── мажор только доводом ──")
    ответ = версия.следующая(пакет, сборка, ДАННЫЕ, мажор=True)
    if ответ["следующая"] == "1.0.0":
        путь_ок("довод --мажор → 1.0.0")
    else:
        путь_плохо(f"довод --мажор дал {ответ['следующая']}")

    print("── потолок заметок: лишнее названо, а не выброшено ──")
    # Условие создаём сами: без лишних коммитов «снято 0» зеленеет впустую.
    for н in range(3):
        (пакет / f"мелочь-{н}.txt").write_text("x\n", encoding="utf-8")
        коммит(пакет, f"мелкая правка {н}")
    для_потолка = dict(ДАННЫЕ, потолок_заметок=2)
    ответ = версия.следующая(пакет, сборка, для_потолка)
    if (len(ответ["заметки"]) == 2 and ответ["снято"] > 0
            and ответ["снято"] == ответ["коммитов"] - 2):
        путь_ок(f"заметок {len(ответ['заметки'])}, снято {ответ['снято']} — число названо")
    else:
        путь_плохо(f"потолок не сработал: заметок {len(ответ['заметки'])}, "
                   f"снято {ответ.get('снято')}, коммитов {ответ['коммитов']}")

    print("── оформление: VERSION и CHANGELOG в сборке ──")
    итог = версия.оформить(пакет, сборка, dict(ДАННЫЕ, потолок_заметок=2))
    журнал = (сборка / "CHANGELOG.md").read_text(encoding="utf-8")
    if (сборка / "VERSION").read_text(encoding="utf-8").strip() == итог["следующая"]:
        путь_ок(f"VERSION написан: {итог['следующая']}")
    else:
        путь_плохо("VERSION не совпал с посчитанной версией")
    if f"## [{итог['следующая']}]" in журнал and итог["пакет"] in журнал:
        путь_ок("в журнале есть секция версии и хэш пакета")
    else:
        путь_плохо(f"секции версии в журнале нет: {журнал[:200]}")
    if "и ещё" in журнал:
        путь_ок("снятое потолком названо числом в журнале")
    else:
        путь_плохо("потолок срезал заметки молча")
    версия.оформить(пакет, сборка, dict(ДАННЫЕ, потолок_заметок=2))
    если_дважды = (сборка / "CHANGELOG.md").read_text(encoding="utf-8")
    if если_дважды.count(f"## [{итог['следующая']}]") == 1:
        путь_ок("повторное оформление не двоит секцию")
    else:
        путь_плохо("вторая секция той же версии в журнале")

    print("── журнал переживает rsync --delete сборщика ──")
    # Условие создаём боевым способом: сборщик зовёт именно rsync -a --delete,
    # и артефакты релиза, которых нет в пакете, он сносит.
    гит("add", "-A", где=сборка)
    гит("commit", "-q", "-m", "версия от 2026-09-03, пакет ноль", где=сборка)
    subprocess.run(["rsync", "-a", "--delete", "--exclude", ".git",
                    str(пакет) + "/", str(сборка) + "/"], timeout=60)
    if (сборка / "CHANGELOG.md").exists():
        путь_плохо("стенд не воспроизвёл снос: журнал уцелел после rsync --delete")
    else:
        # Новая версия обязана ДОПИСАТЬСЯ к прежней, а не заменить её: иначе
        # «восстановлен» означало бы «журнал из одной секции».
        # Каталог demons выше по пробе переименован в demoni — возвращаем имя,
        # которое знают ДАННЫЕ: шаблон минора смотрит на harness/demons/*.sh.
        (пакет / "harness" / "demons").mkdir(parents=True, exist_ok=True)
        # Содержимое уникальное: при одинаковом git с -M признал бы новый файл
        # переименованием ранее переехавшего и минор бы не сработал.
        (пакет / "harness" / "demons" / "ещё.sh").write_text(
            "#!/bin/sh\necho второй демон присмотра\n", encoding="utf-8")
        коммит(пакет, "ещё один демон")
        снова = версия.оформить(пакет, сборка, dict(ДАННЫЕ, потолок_заметок=2))
        журнал = (сборка / "CHANGELOG.md").read_text(encoding="utf-8")
        if ("## [0.2.1]" in журнал and f"## [{снова['следующая']}]" in журнал
                and журнал.count("## [") == 2):
            путь_ок(f"после сноса журнал дописан к прежнему: секций 2, "
                    f"новая {снова['следующая']}")
        else:
            путь_плохо(f"история версий потеряна: секций {журнал.count('## [')}, "
                       f"новая {снова['следующая']}, {снова['почему']}")

    print("── прошлая версия берётся из ТЕГА, а не из файла ──")
    (сборка / "VERSION").write_text("9.9.9\n", encoding="utf-8")
    коммит(сборка, "кто-то правил VERSION руками")
    ответ = версия.следующая(пакет, сборка, ДАННЫЕ)
    if ответ["прошлая"] == "0.2.0":
        путь_ок("подложный VERSION не сбил счёт: прошлая 0.2.0 из тега")
    else:
        путь_плохо(f"прошлая версия взята не из тега: {ответ['прошлая']}")
finally:
    subprocess.run(["rm", "-rf", str(врем)], timeout=30)

print(f"\nитого путей {путей}, неудач {неудач}")
sys.exit(1 if неудач else 0)
