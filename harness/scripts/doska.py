#!/usr/bin/env python3
"""Доска состояния смены: я пишу факт словами, код читает и действует.

Владелец 12.09.2026: «Нужен какое то место для обмена данными, чтобы код умел
туда обращаться».

Откуда задача. Код видит меня только по КОСВЕННЫМ признакам: возраст записи в
журнале сессии, текст на экране панели, наличие процесса. Отсюда весь класс
сегодняшних отказов — сторож считал отказ 429 работой; в ту же минуту одна его
ветка видела лимит, а другая говорила владельцу «с лимитом не связано»; я три
часа «работал», не отчитываясь, и никто не мог отличить это от зависания.

Доска — прямой канал в обратную сторону: я СООБЩАЮ факт, код его ЧИТАЕТ.
Не заменяет косвенные признаки, а даёт им опору: запись с доски старше своего
срока перестаёт быть правдой сама (поле «годно_до»), иначе «жду ответа»,
написанное однажды, оправдывало бы молчание вечно —
см. [[пометка-снятия-не-снимается-сама]].

Формат — одна запись на ключ, JSON:
    {"ключ": "лимит", "что": "упёрся в лимит, сброс в 22:50",
     "поставил": "смена", "ts": ..., "годно_до": ...}

Прогон:
    python3 scripts/doska.py --сказать лимит "упёрся в лимит, сброс в 22:50" [--на 180]
    python3 scripts/doska.py --снять лимит
    python3 scripts/doska.py --читать лимит        # код 0 — запись жива, 1 — нет
    python3 scripts/doska.py --всё                 # что на доске сейчас
    python3 scripts/doska.py --selftest
"""
import json
import os
import subprocess
import sys
import time
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
# Доска живёт в журнале харнеса: её пишет смена, читают демоны и панель.
ДОСКА = Path(os.environ.get("HARNESS_DOSKA")
             or Path(os.environ.get("LOG_DIR", "/var/log/harness")) / "доска.json")
# Сколько живёт запись, если срок не назван. Не «вечно»: несвежая правда —
# это ложь, а доску пишет тот, кто может замолчать на три часа.
СРОК_МИН = 60


def прочитать() -> dict:
    try:
        дано = json.loads(ДОСКА.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return дано if isinstance(дано, dict) else {}


def _записать(всё: dict) -> None:
    ДОСКА.parent.mkdir(parents=True, exist_ok=True)
    врем = ДОСКА.with_suffix(".tmp")
    врем.write_text(json.dumps(всё, ensure_ascii=False, indent=1), encoding="utf-8")
    os.replace(врем, ДОСКА)          # атомарно: доску читают демоны по расписанию


def сказать(ключ: str, что: str, минут: int = СРОК_МИН, кто: str = "смена") -> dict:
    всё = прочитать()
    сейчас = time.time()
    запись = {"что": что, "поставил": кто, "ts": сейчас,
              "годно_до": сейчас + минут * 60}
    всё[ключ] = запись
    _записать(всё)
    return запись


def снять(ключ: str) -> bool:
    всё = прочитать()
    если_был = ключ in всё
    всё.pop(ключ, None)
    _записать(всё)
    return если_был


def читать(ключ: str) -> dict | None:
    """Живая запись или None. Протухшая молча снимается: срок — часть факта."""
    всё = прочитать()
    запись = всё.get(ключ)
    if not запись:
        return None
    if запись.get("годно_до", 0) < time.time():
        снять(ключ)
        return None
    return запись


def живые() -> dict:
    return {к: з for к, з in прочитать().items()
            if з.get("годно_до", 0) >= time.time()}


def _selftest() -> int:
    проба = КОРЕНЬ / "scripts" / "test_doska.py"
    if not проба.exists():
        print(f"[доска] пробы нет: {проба}")
        return 1
    return subprocess.run([sys.executable, str(проба)], timeout=300).returncode


def главная(argv: list) -> int:
    if "--selftest" in argv:
        return _selftest()

    def довод(имя):
        return argv[argv.index(имя) + 1] if имя in argv else None

    if "--всё" in argv:
        сейчас = живые()
        if not сейчас:
            print("доска пуста")
            return 1
        for ключ, з in сорт(сейчас):
            осталось = int((з["годно_до"] - time.time()) // 60)
            print(f"{ключ}: {з['что']}  (поставил {з['поставил']}, ещё {осталось} мин)")
        return 0

    ключ = довод("--сказать") or довод("--снять") or довод("--читать")
    if not ключ:
        print("нужен --сказать КЛЮЧ ТЕКСТ, --снять КЛЮЧ, --читать КЛЮЧ или --всё",
              file=sys.stderr)
        return 2

    if "--снять" in argv:
        print(f"{ключ}: снято" if снять(ключ) else f"{ключ}: на доске не было")
        return 0
    if "--читать" in argv:
        запись = читать(ключ)
        if запись is None:
            print(f"{ключ}: записи нет")
            return 1
        print(запись["что"])
        return 0

    # --сказать: текст идёт следующим доводом после ключа
    место = argv.index("--сказать") + 2
    что = argv[место] if len(argv) > место else ""
    if not что.strip():
        print("нечего говорить: после ключа нужен текст", file=sys.stderr)
        return 2
    минут = int(довод("--на") or СРОК_МИН)
    запись = сказать(ключ, что, минут, довод("--кто") or "смена")
    print(f"{ключ}: записано на {минут} мин — {запись['что']}")
    return 0


def сорт(всё: dict):
    return sorted(всё.items(), key=lambda п: п[1].get("ts", 0), reverse=True)


if __name__ == "__main__":
    sys.exit(главная(sys.argv[1:]))
