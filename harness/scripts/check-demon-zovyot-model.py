#!/usr/bin/env python3
"""Гейт: фоновый прогон зовёт модель ТОЛЬКО через обёртку claude-demon.sh.

СЛУЧАЙ 13.09.2026. Демоны звали `claude -p` напрямую и отказ по лимиту
принимали за обычную неудачу: «попробую в следующий раз», «повторим завтра».
Недельный лимит держался трое суток, карта разработки не чинилась двое, и
владелец не услышал ни слова. Видимость сделана в одном месте — обёртке
`scripts/claude-demon.sh`; правило «звать через неё» без сторожа живёт до
первого нового демона.

Гейт судит файлы демонов (`harness/demons/*.sh`): прямой вызов `claude -p`
там больше не законен. Сама обёртка зовёт CLI — она и есть единственное место,
где это разрешено.

    python3 scripts/check-demon-zovyot-model.py
    python3 scripts/check-demon-zovyot-model.py --selftest
Код возврата: 0 — чисто, 1 — есть прямой вызов.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
ДЕМОНЫ = КОРЕНЬ / "harness" / "demons"
ОБЁРТКА = "claude-demon.sh"

# Вызов команды, а не упоминание: строка начинается с claude (возможно после
# timeout/переменных/подстановки), дальше -p. Комментарии не судим — в них
# разбор случая, и запрет на слово превратил бы пояснение в нарушение.
ПРЯМОЙ_ВЫЗОВ = re.compile(
    r"^(?!\s*#)[^#\n]*?(?<![\w/-])claude\s+(?:--?[\w-]+\s+)*-p(?![\w-])")


def находки(текст: str) -> list[int]:
    """Номера строк с прямым вызовом модели."""
    итог = []
    for номер, строка in enumerate(текст.splitlines(), 1):
        if ОБЁРТКА in строка:
            continue          # строка зовёт обёртку — это и есть правильный путь
        if ПРЯМОЙ_ВЫЗОВ.search(строка):
            итог.append(номер)
    return итог


def проверить(каталог: Path = ДЕМОНЫ) -> int:
    беды = []
    файлы = sorted(каталог.glob("*.sh"))
    for файл in файлы:
        for номер in находки(файл.read_text(encoding="utf-8")):
            беды.append(f"{файл.relative_to(КОРЕНЬ)}:{номер}")
    if беды:
        print(f"[вызов модели демоном] ПРЯМОЙ ВЫЗОВ МИМО ОБЁРТКИ: {len(беды)}")
        for место in беды:
            print(f"  ✗ {место}")
        print(f"  Починка: bash {ОБЁРТКА} <имя-демона> -p … — она распознаёт "
              "отказ по лимиту и говорит владельцу один раз на период")
        return 1
    print(f"[вызов модели демоном] чисто: демонов {len(файлы)}, "
          "модель зовут только через обёртку")
    return 0


def самотест() -> int:
    путей = неудач = 0

    def проба(имя: str, ждём, факт):
        nonlocal путей, неудач
        путей += 1
        if факт == ждём:
            print(f"  ок    {имя}")
        else:
            неудач += 1
            print(f"  ПЛОХО {имя}: ждали «{ждём}», вышло «{факт}»")

    # БОЛЬНОЙ СЛУЧАЙ 13.09.2026 — ровно те строки, что были в трёх демонах.
    проба("БОЛЬНОЙ: прямой вызов дежурного", [1],
          находки('claude -p --strict-mcp-config --model "$(model_dlya дежурный)" "Ты дежурный"'))
    проба("БОЛЬНОЙ: вызов под timeout", [1],
          находки('timeout "$6" claude -p --model "$M" "$promt"'))
    проба("БОЛЬНОЙ: вызов в подстановке", [1],
          находки('answer=$(cd "$D" && timeout 300 claude -p --model "$M" "$t")'))
    проба("вызов через обёртку — законен", [],
          находки('bash "$PROJECT_DIR/scripts/claude-demon.sh" ton-watch -p --model "$M" "$t"'))
    проба("комментарий про claude -p — не нарушение", [],
          находки('# раньше здесь стоял claude -p --model haiku'))
    проба("pgrep по имени процесса — не вызов", [],
          находки("if pgrep -u \"$AGENT_USER\" -x claude >/dev/null 2>&1; then"))
    проба("живые демоны чисты", 0, проверить())
    print(f"SELFTEST: {'зелёный' if not неудач else 'КРАСНЫЙ'} ({путей} путей; "
          "первым — больной случай «демон зовёт модель сам»)")
    return 1 if неудач else 0


if __name__ == "__main__":
    sys.exit(самотест() if "--selftest" in sys.argv else проверить())
