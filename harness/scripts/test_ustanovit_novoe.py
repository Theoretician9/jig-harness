#!/usr/bin/env python3
"""Проверка доустановки нового: что скрипт добавляет и чего НЕ трогает.

Откуда взято. Находка C7 разбора спеки обновления (11.09.2026): обновление
привозит новый демон, а он без строки cron и без периода метки мёртв и
незаметен — сторож меток не знает, что его ждать. Раньше такие строки
добавлялись руками, то есть правило держалось на памяти.

Главное требование — идемпотентность и безвредность: повторный прогон ничего
не дублирует, чужие строки расписания остаются нетронутыми.

Прогон:
    python3 scripts/test_ustanovit_novoe.py
"""
import importlib.util
import json
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
путей = неудач = 0


def путь_ок(текст: str) -> None:
    global путей
    путей += 1
    print("ок  · " + текст)


def путь_плохо(текст: str) -> None:
    global путей, неудач
    путей += 1
    неудач += 1
    print("ПЛОХО · " + текст)


спец = importlib.util.spec_from_file_location(
    "доустановка", КОРЕНЬ / "scripts" / "ustanovit-novoe.py")
доустановка = importlib.util.module_from_spec(спец)
спец.loader.exec_module(доустановка)

ЗАДАНИЯ = [
    {"имя": "старый", "расписание": "0 3 * * *",
     "команда": "harness/demons/старый.sh", "журнал": "старый.log"},
    {"имя": "новый", "расписание": "45 4 * * *",
     "команда": "harness/demons/новый.sh", "журнал": "новый.log"},
]
ЧУЖОЕ = "0 1 * * *  /home/владелец/своё-личное.sh   # поставил владелец"

было = (f"{ЧУЖОЕ}\n"
        f"0 3 * * *  /srv/проба/harness/demons/старый.sh "
        f">>/var/log/harness/старый.log 2>&1\n")

print("── расписание ──")
стало = доустановка.дополнить_расписание(было, ЗАДАНИЯ, "/srv/проба",
                                         "/var/log/harness")
if "новый.sh" in стало:
    путь_ок("новое задание добавлено")
else:
    путь_плохо("новое задание не добавлено")

if ЧУЖОЕ in стало:
    путь_ок("БОЛЬНОЙ СЛУЧАЙ: чужая строка расписания цела")
else:
    путь_плохо("чужая строка расписания пропала — это чужое имущество")

if стало.count("старый.sh") == 1:
    путь_ок("уже стоящее задание не продублировано")
else:
    путь_плохо(f"дубль задания: {стало.count('старый.sh')} раз")

ещё_раз = доустановка.дополнить_расписание(стало, ЗАДАНИЯ,
                                           "/srv/проба", "/var/log/harness")
if ещё_раз == стало:
    путь_ок("повторный прогон ничего не меняет (идемпотентность)")
else:
    путь_плохо("повторный прогон изменил расписание")

print("── периоды меток ──")
конфиг = 'PROJECT_DIR="/x"\nHEARTBEAT_PERIODS="sentinel:5 старый:1440"\nДРУГОЕ="1"\n'
метки = {"sentinel": 5, "старый": 1440, "новый": 1440}
новый_конфиг = доустановка.дополнить_периоды(конфиг, метки)
if "новый:1440" in новый_конфиг:
    путь_ок("период новой метки дописан")
else:
    путь_плохо(f"период не дописан: {новый_конфиг!r}")

if "sentinel:5" in новый_конфиг and 'ДРУГОЕ="1"' in новый_конфиг:
    путь_ок("прежние значения и соседние ключи целы")
else:
    путь_плохо("правка задела чужое в конфиге")

изменённый = доустановка.дополнить_периоды(
    'HEARTBEAT_PERIODS="sentinel:99"\n', {"sentinel": 5})
if "sentinel:99" in изменённый:
    путь_ок("БОЛЬНОЙ СЛУЧАЙ: значение, выставленное владельцем, не перетирается")
else:
    путь_плохо("чужое значение периода перетёрто умолчанием")

ещё = доустановка.дополнить_периоды(новый_конфиг, метки)
if ещё == новый_конфиг:
    путь_ок("повторный прогон периодов ничего не меняет")
else:
    путь_плохо("повторный прогон переписал периоды")

print("── ключи harness.conf ──")
# Почему: ручка панели требует, чтобы ключ СТОЯЛ в конфиге (гейт переключателей),
# а на чужой установке после обновления его туда никто не писал (I-9² ревью
# спеки ревизии). Правило то же, что у периодов: только добавляем.
конфиг_ключей = 'PROJECT_DIR="/x"\nREVIZIA_MODEL="fable"\n'
с_ключами = доустановка.дополнить_ключи(конфиг_ключей, {"REVIZIA_ENABLED": "1", "REVIZIA_MODEL": "opus"})
if 'REVIZIA_ENABLED="1"' in с_ключами:
    путь_ок("недостающий ключ дописан с умолчанием")
else:
    путь_плохо(f"ключ не дописан: {с_ключами!r}")
if 'REVIZIA_MODEL="fable"' in с_ключами and 'REVIZIA_MODEL="opus"' not in с_ключами:
    путь_ок("БОЛЬНОЙ СЛУЧАЙ: выбор владельца (fable) не перетёрт умолчанием")
else:
    путь_плохо("значение владельца перетёрто или продублировано")
if доустановка.дополнить_ключи(с_ключами, {"REVIZIA_ENABLED": "1", "REVIZIA_MODEL": "opus"}) == с_ключами:
    путь_ок("повторный прогон ключей ничего не меняет")
else:
    путь_плохо("повторный прогон переписал ключи")
if доустановка.дополнить_ключи('# REVIZIA_ENABLED="0" — комментарий\n', {"REVIZIA_ENABLED": "1"}).count("REVIZIA_ENABLED=") == 2:
    путь_ок("закомментированный ключ за стоящий не считается")
else:
    путь_плохо("комментарий принят за ключ — ключа в конфиге не будет")

print("── данные читаются ──")
задания, метки_из_данных, ключи_из_данных, снять_из_данных = доустановка.прочитать_данные(
    КОРЕНЬ / "harness" / "config" / "системные-задания.yaml")
if "REVIZIA_ENABLED" in ключи_из_данных and "REVIZIA_MODEL" in ключи_из_данных:
    путь_ок("в данных объявлены ключи ревизии")
else:
    путь_плохо(f"ключей ревизии в данных нет: {sorted(ключи_из_данных)}")
if len(задания) >= 10 and "obnovlenie-watch" in метки_из_данных:
    путь_ок(f"в данных {len(задания)} заданий и {len(метки_из_данных)} меток")
else:
    путь_плохо(f"данные прочитаны не так: {len(задания)} заданий")

живые = {з["команда"] for з in задания}
нет_файла = [к for к in живые if not (КОРЕНЬ / к.split()[0]).exists()]
if not нет_файла:
    путь_ок("каждое задание указывает на существующий файл")
else:
    путь_плохо(f"задание ведёт в никуда: {нет_файла}")

print("── снятие отработавших ключей ──")
# БОЛЬНОЙ СЛУЧАЙ первым: ключ стоит — обязан исчезнуть, соседи целы. Правило
# «только добавляем» про ЧУЖИЕ строки; ключ, который харнес завёл сам и сам
# же признал отработавшим, снимается по списку в ДАННЫХ.
было_к = ('PUBLIC_BRANCH="master"\nWORK_BRANCH="master"\n'
          '# WORK_BRANCH="старое"\nUPDATE_MODE="manual"\n')
стало_к = доустановка.снять_ключи(было_к, ["WORK_BRANCH"])
if ("\nWORK_BRANCH=" not in "\n" + стало_к and 'PUBLIC_BRANCH="master"' in стало_к
        and 'UPDATE_MODE="manual"' in стало_к):
    путь_ок("WORK_BRANCH снят, соседние ключи целы")
else:
    путь_плохо(f"снятие ключа сломало конфиг: {стало_к!r}")
if '# WORK_BRANCH="старое"' in стало_к:
    путь_ок("закомментированная строка не тронута")
else:
    путь_плохо("снятие ключа выкосило комментарий")
if доустановка.снять_ключи(стало_к, ["WORK_BRANCH"]) == стало_к:
    путь_ок("повторное снятие ничего не меняет")
else:
    путь_плохо("повторное снятие меняет конфиг")
if ("PUBLIC_BUILD_DIR" in ключи_из_данных and "PUBLIC_COMMIT_EMAIL" in ключи_из_данных
        and "WORK_BRANCH" in снять_из_данных):
    путь_ок("в данных объявлены ключи публикации и снятие WORK_BRANCH")
else:
    путь_плохо(f"данных публикации нет: {sorted(ключи_из_данных)} / {снять_из_данных}")

print(f"ДОУСТАНОВКА: путей {путей}, неудач {неудач}")
if неудач:
    sys.exit(1)
print(json.dumps({"проверка": "доустановка", "путей": путей, "неудач": 0},
                 ensure_ascii=False))
