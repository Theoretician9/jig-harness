# ── чтение сообщения и его исхода ──────────────────────────────────────────

def файл_сообщения(инбокс: Path, ид: str) -> Path | None:
    for кандидат in (инбокс / f"{ид}.txt", инбокс / "обработано" / f"{ид}.txt"):
        if кандидат.exists():
            return кандидат
    return None


def исход_есть(карта: Path, ид: str) -> bool:
    """Исход — карточка со ссылкой на сообщение либо пометка «не задача»."""
    куски = []
    if карта.exists():
        куски.append(карта.read_text(encoding="utf-8"))
    спутник = карта.parent / "память" / ".задачи-разобрано"
    if спутник.exists():
        куски.append(спутник.read_text(encoding="utf-8"))
    return f"inbox:{ид}" in "\n".join(куски) or any(
        строка.startswith(ид + " ") for кусок in куски for строка in кусок.splitlines())


# ── разбор смысла: модель отдаёт данные, решает код ────────────────────────

def спросить_модель(текст: str) -> tuple[dict | None, str]:
    """Данные о сообщении от модели или (None, причина). Единственный вход —
    scripts/sprosit-model.py: схема ответа, журнал вызова и потолок в сутки
    живут там, а не у каждого зовущего (владелец 12.09.2026)."""
    вход = os.environ.get("HARNESS_SPROSIT_MODEL") or str(
        Path(__file__).resolve().parent / "sprosit-model.py")
    вопрос = ("Вот сообщение владельца проекта. Перечисли, какие ЗАДАЧИ в нём "
              "названы (каждая — одной строкой, словами владельца), какие "
              "УКАЗАНИЯ (правила на будущее) и какие ВОПРОСЫ он задал.\n\n"
              "СООБЩЕНИЕ:\n" + текст)
    with tempfile.NamedTemporaryFile("w", suffix=".txt", delete=False,
                                     encoding="utf-8") as ф:
        ф.write(вопрос)
        путь_вопроса = ф.name
    try:
        готово = subprocess.run(["python3", вход, "--повод", ПОВОД,
                                 "--вопрос-файл", путь_вопроса],
                                capture_output=True, text=True, timeout=420)
    except (subprocess.TimeoutExpired, OSError) as беда:
        return None, f"модель не ответила: {беда}"
    finally:
        os.unlink(путь_вопроса)
    if готово.returncode != 0:
        return None, (готово.stderr or готово.stdout).strip()[:200] or "отказ модели"
    try:
        return json.loads(готово.stdout), ""
    except ValueError:
        return None, "ответ модели не разобран как JSON"


# ── карточка ───────────────────────────────────────────────────────────────

# Пересланная переписка: «[12.09.2026 23:54] Бот: …» — это МОИ же
# слова, вернувшиеся от владельца. Он пересылает их, чтобы показать дефект, а
# своё говорит следом. Заголовком обязана стать ЕГО строка: 13.09.2026 задача
# получила имя «[12.09.2026 23:54] Бот: принял: /status», и бот
# докладывал владельцу, что «делает» его собственную цитату.
ЦИТАТА = re.compile(r"^\[\d{2}\.\d{2}\.\d{4}[^\]]*\]\s*\S+:")


def заголовок_из(текст: str) -> str:
    """Первая осмысленная строка ВЛАДЕЛЬЦА — заголовок, когда модели нет."""
    свои = [с for с in текст.splitlines() if not ЦИТАТА.match(с.strip())]
    for строка in (свои or текст.splitlines()):
        строка = строка.strip(" -–—•\t")
        if len(строка) >= 8:
            return строка[:110]
    return (текст.strip() or "задача из сообщения владельца")[:110]


def идентификатор(приставка: str, заголовок: str, занятые: set) -> str:
    слова = re.findall(r"[а-яёa-z0-9]+", заголовок.lower())
    основа = "-".join(слова[:5]) or "задача"
    ид = f"{приставка}.{основа}"
    номер = 2
    while ид in занятые:
        ид = f"{приставка}.{основа}-{номер}"
        номер += 1
    return ид


def карточка(ид: str, заголовок: str, сообщение: str, ид_сообщения: str,
             разбор: dict | None, отказ_модели: str) -> str:
    """Текст карточки. Поля — те, что требует гейт манифеста: id, status,
    title, summary; плюс источник, по которому гейт канала видит исход."""
    сегодня = datetime.date.today().isoformat()
    слова = сообщение.strip().replace("\n", " ")[:ПОТОЛОК_SUMMARY]
    хвост = "…" if len(сообщение.strip()) > ПОТОЛОК_SUMMARY else ""
    если_модель = (f"Разбор модели: задач {len(разбор.get('задачи') or [])}, "
                   f"указаний {len(разбор.get('указания') or [])}, "
                   f"вопросов {len(разбор.get('вопросы') or [])}."
                   if разбор else f"Модель не разобрала сообщение ({отказ_модели}) — "
                                  f"заголовок взят по первой строке.")
    указания = (разбор or {}).get("указания") or []
    если_указания = (" Названы указания (занести в память/УКАЗАНИЯ.md): "
                     + "; ".join(str(у)[:120] for у in указания[:3]) if указания else "")
    summary = (f"Владелец {сегодня} в канал: «{слова}{хвост}». Карточка заведена "
               f"КОДОМ (scripts/karta-iz-soobshcheniya.py) в момент приёма "
               f"сообщения — не вниманием сессии. {если_модель}{если_указания} "
               f"Разобрать замысел и уточнить объём — при взятии задачи в работу.")
    return "\n".join([
        f"      - id: {ид}",
        "        status: plan",
        "        owner_testable: true",
        f"        источник: inbox:{ид_сообщения}",
        f"        заведено: \"{сегодня}\"",
        "        завёл: scripts/karta-iz-soobshcheniya.py",
        f"        глубина: {глубина_строкой(заголовок + ' ' + слова, сегодня)}",
        f"        title: {json.dumps(заголовок, ensure_ascii=False)}",
        f"        summary: {json.dumps(summary, ensure_ascii=False)}",
        "        volume: { loc: 100, complexity: 3, tokens_k: 50, estimated: true }",
        "        when: { started: null, done: null, tested: null, estimated: true }",
        "",
    ])


def глубина_строкой(текст: str, сегодня: str) -> str:
    """Заготовка глубины для новой карточки — одной строкой YAML.

    Владелец 13.09.2026: «это должно быть не просто памятью, должен работать
    чёткий механизм». Правило «пересмотр сразу ставит задаче статус и глубину»
    держалось вниманием смены: замер того дня — 15 карточек из 21, заведённых
    отсюда, поля «глубина» не имели вовсе, и 12 из них уже дошли до статуса
    test. Поле дописывалось руками, когда краснел гейт.

    Судья один — pajplajn.py: своя копия правил здесь стала бы четвёртой и
    разошлась бы с остальными молча.
    """
    import importlib.util
    спец = importlib.util.spec_from_file_location(
        "пайплайн", Path(__file__).resolve().parent / "pajplajn.py")
    модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(модуль)
    поля = модуль.глубина_для_карточки(текст, сегодня)
    внутри = ", ".join(f"{к}: {в}" for к, в in поля.items())
    return "{ " + внутри + " }"


# ── правка карты: под локом, с проверкой результата ────────────────────────

def направление(данные: dict, имя: str | None) -> dict:
    линии = данные.get("lines") or []
    if имя:
        for л in линии:
            if л.get("id") == имя:
                return л
    return линии[0] if линии else {}


def приставка_линии(линия: dict) -> str:
    """Приставка id берётся у соседей той же линии: в «hr.*» новая задача не
    имеет права называться «pr.*»."""
    for з in линия.get("tasks") or []:
        ид = str(з.get("id") or "")
        if "." in ид:
            return ид.split(".", 1)[0]
    return str(линия.get("id") or "task")[:2]


def место_вставки(строки: list, линия_ид: str) -> int:
    """Номер строки, ПЕРЕД которой встаёт новая карточка: первая задача своей
    линии. Вставка перед якорем не трогает ни одной существующей строки —
    правка структурного файла регулярками съедала соседей (09.09.2026)."""
    в_линии = False
    for номер, строка in enumerate(строки):
        if re.match(rf"^\s*-\s+id:\s*{re.escape(линия_ид)}\s*$", строка):
            в_линии = True
            continue
        if в_линии and re.match(r"^\s{6}-\s+id:\s", строка):
            return номер
        if в_линии and re.match(r"^\s{0,4}-\s+id:\s", строка):
            break          # началась следующая линия, задач в нашей нет
    raise SystemExit(f"в карте не нашлось места для задачи линии «{линия_ид}»")


def записать(карта: Path, лок: Path, линия_ид: str, карточки: list,
             ид_сообщения: str | None = None) -> bool:
    """Пишет карту под ОБЩИМ локом $LOG_DIR/locks/services/dev-map.lock: её
    правят пять сторон, и два писателя наперегонки затирают друг друга.

    Исход сверяется ЕЩЁ РАЗ под локом: между проверкой и записью карточку мог
    завести агент, разбуженный тем же сообщением. Возвращает False, если
    писать уже нечего."""
    лок.parent.mkdir(parents=True, exist_ok=True)
    with open(лок, "a", encoding="utf-8") as замок:
        fcntl.flock(замок, fcntl.LOCK_EX)
        if ид_сообщения and исход_есть(карта, ид_сообщения):
            return False
        было_текст = карта.read_text(encoding="utf-8")
        было = yaml.safe_load(было_текст) or {}
        было_ид = {з.get("id") for л in было.get("lines") or []
                   for з in л.get("tasks") or []}
        строки = было_текст.splitlines(keepends=True)
        куда = место_вставки(строки, линия_ид)
        строки[куда:куда] = ["".join(к) for к in карточки]
        стало_текст = "".join(строки)
        стало = yaml.safe_load(стало_текст) or {}
        стало_ид = {з.get("id") for л in стало.get("lines") or []
                    for з in л.get("tasks") or []}
        пропало = было_ид - стало_ид
        if пропало:
            raise SystemExit(f"ОТКАЗ: правка потеряла задачи: {sorted(пропало)}")
        if len(стало_ид) != len(было_ид) + len(карточки):
            raise SystemExit(f"ОТКАЗ: задач было {len(было_ид)}, стало "
                             f"{len(стало_ид)}, добавляли {len(карточки)}")
        карта.write_text(стало_текст, encoding="utf-8")
        return True


# ── главный ход ────────────────────────────────────────────────────────────

def завести(ид_сообщения: str, карта: Path, инбокс: Path, лок: Path,
            линия: str | None, сухой: bool) -> int:
    файл = файл_сообщения(инбокс, ид_сообщения)
    if файл is None:
        print(f"сообщения {ид_сообщения} нет ни в {инбокс}, ни в обработано/")
        return 1
    гейт = модуль("zadachi-iz-kanala")
    текст = гейт.текст_сообщения(файл)
    if not текст.strip():
        print(f"{ид_сообщения}: слов владельца нет (вложение без подписи) — карточки нет")
        return 0
    if not гейт.рабочее(текст):
        print(f"{ид_сообщения}: признака работы нет — карточки нет "
              f"(тот же признак, что у гейта задач из канала)")
        return 0
    # Вопрос — не задача, даже когда в нём стоит глагол работы. Прибор
    # срочности уже умеет это различать («не работа (ответ, реакция)»), и
    # спрашивать надо ЕГО, а не заводить второй признак: 12.09.2026 два
    # механизма рассудили по-разному, и вопросы владельца «объясни в чём
    # смысл» и «доделывай всё и проверяй» стали карточками, которые пришлось
    # снимать руками и переносить в архив.
    срочность = модуль("srochnost")
    это_срочно, почему = срочность.срочно(текст)
    if это_срочно and "не работа" in почему:
        print(f"{ид_сообщения}: это {почему} — карточки нет")
        return 0
    if исход_есть(карта, ид_сообщения):
        print(f"{ид_сообщения}: исход уже есть — не трогаю")
        return 0

    разбор, отказ = спросить_модель(текст)
    задачи = [str(з).strip() for з in (разбор or {}).get("задачи") or [] if str(з).strip()]
    заголовки = задачи[:МАКСИМУМ_ЗАДАЧ] or [заголовок_из(текст)]

    данные = yaml.safe_load(карта.read_text(encoding="utf-8")) or {}
    линия_данные = направление(данные, линия)
    линия_ид = линия_данные.get("id")
    занятые = {з.get("id") for л in данные.get("lines") or [] for з in л.get("tasks") or []}
    приставка = приставка_линии(линия_данные)

    блоки = []
    для_печати = []
    for з in заголовки:
        ид = идентификатор(приставка, з, занятые)
        занятые.add(ид)
        блоки.append(карточка(ид, з[:110], текст, ид_сообщения, разбор, отказ))
        для_печати.append(ид)

    if сухой:
        print(f"сухой прогон: завёл бы {len(блоки)} карточк(и) в линии {линия_ид}")
        for б in блоки:
            print(б)
        if отказ:
            print(f"(модель не ответила: {отказ})")
        return 0

    if not записать(карта, лок, линия_ид, блоки, ид_сообщения):
        print(f"{ид_сообщения}: исход появился, пока я разбирал сообщение — не трогаю")
        return 0
    источник = "разбор модели" if разбор else f"без модели ({отказ})"
    print(f"{ид_сообщения}: заведено {len(блоки)} — {', '.join(для_печати)} "
          f"[{источник}]")
    return 0


def накопленные(инбокс: Path, карта: Path) -> list:
    """Сообщения очереди без исхода — и лежащие, и уже перенесённые агентом."""
    гейт = модуль("zadachi-iz-kanala")
    итог = []
    for ф in sorted(list(инбокс.glob("*.txt"))
                    + list((инбокс / "обработано").glob("*.txt"))):
        ид = ф.stem
        текст = гейт.текст_сообщения(ф)
        if текст.strip() and гейт.рабочее(текст) and not исход_есть(карта, ид):
            итог.append(ид)
    return итог


