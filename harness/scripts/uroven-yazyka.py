#!/usr/bin/env python3
"""Каким языком писать владельцу: считается по ЕГО сообщениям, а не по моему вкусу.

Откуда взят. Владелец 11.09.2026: «то как ты мне пишешь должно быть не
косноязычным только тебе понятным языком, а доступным для меня, с гибким
уровнем технического языка. Твой язык должен подстраиваться к моему поведению,
от очень простого на пальцах, до технического. Это нужно чтобы харнесом могли
пользоваться люди с разной подготовкой и язык был адаптивным».

Признак — доля технических слов в последних сообщениях владельца. Человек,
который сам пишет «детерминированно», «пайплайн», «кэш», читает термины без
труда; человек, который пишет «почему не работает, сделай чтобы», получит от
них только раздражение.

Три уровня и что они означают для МЕНЯ:
  простой      — без терминов вовсе; вместо «гейт» — «проверка, которая не
                 пропускает», вместо «ротация» — «смена рабочего окна»;
  обычный      — термин можно, но при первом появлении в сообщении объясняется
                 в скобках одним оборотом;
  технический  — термины как есть, без пояснений.

Уровень пересчитывается при каждом входящем (диспетчер) и лежит в
$LOG_DIR/уровень-языка. Смена уровня не мгновенная: нужно, чтобы новый уровень
подтвердился дважды подряд — иначе одно короткое «да» роняло бы язык до
простого ([[сигнал-без-различения]]).

Прогон:
    python3 scripts/uroven-yazyka.py                 # текущий уровень
    python3 scripts/uroven-yazyka.py --пересчитать   # по входящим владельца
    python3 scripts/uroven-yazyka.py --selftest
"""
import glob
import io
import os
import re
import sys

LOG_DIR = os.environ.get("LOG_DIR", "/var/log/harness")
ФАЙЛ_УРОВНЯ = os.path.join(LOG_DIR, "уровень-языка")
INBOX = os.path.join(LOG_DIR, "inbox", "обработано")

# Словарь в ДВА слоя: доля слов различает плохо — замер 11.09 дал почти
# одинаковую долю (0,088 против 0,087) у сообщения владельца про SaaS и у
# простой просьбы «проверь деплой и тесты». Различает не количество терминов,
# а их ГЛУБИНА: «тест» и «сервер» знает любой заказчик, «детерминированно» и
# «инвариант» — тот, кто сам строит системы.
ОБИХОДНЫЕ = re.compile(
    r'\b(тест\w*|сервер\w*|лог\w*|гит\b|git\b|деплой\w*|сайт\w*|программ\w*'
    r'|код\w*|файл\w*|база\b|бот\w*|ошибк\w*|скрипт\w*)\b', re.I)

ГЛУБОКИЕ = re.compile(
    r'\b(пайплайн\w*|гейт\w*|детерминирован\w*|инвариант\w*|кэш\w*|токен\w*'
    r'|репозитори\w*|ротаци\w*|хук\w*|миграци\w*|рефактор\w*|архитектур\w*'
    r'|бэкенд\w*|фронтенд\w*|конфиг\w*|валидац\w*|демон\w*|дамп\w*|бэкап\w*'
    r'|контекстн\w*|саас\b|saas\b|стек\b|индекс\w*|коммит\w*|апи\b|api\b)\b',
    re.I)

УРОВНИ = ("простой", "обычный", "технический")
# Технический — когда человек сам свободно берёт ГЛУБОКИЕ слова, и не одно.
ГЛУБОКИХ_ДЛЯ_ТЕХНИЧЕСКОГО = 2


def уровень_текста(текст):
    слова = re.findall(r'\w+', текст, re.U)
    if len(слова) < 5:
        return None              # слишком коротко, чтобы судить («да», «ок»)
    глубоких = len({м.lower() for м in ГЛУБОКИЕ.findall(текст)})
    if глубоких >= ГЛУБОКИХ_ДЛЯ_ТЕХНИЧЕСКОГО:
        return "технический"
    if глубоких or ОБИХОДНЫЕ.search(текст):
        return "обычный"
    return "простой"


def прочитать_уровень():
    try:
        значение = io.open(ФАЙЛ_УРОВНЯ, encoding="utf-8").read().strip()
    except OSError:
        return "обычный"          # не знаем — середина, а не крайность
    return значение if значение in УРОВНИ else "обычный"


# Разговор О ТОМ, КАК я пишу, ведётся простыми словами всегда и о подготовке
# человека не говорит. 11.09 два таких сообщения подряд уронили уровень до
# «простого» у владельца, который писал «Пилю SaaS Вайбкодингом» (находка I-8).
МЕТА_О_СТИЛЕ = re.compile(
    r'\bпишешь\b|\bпереписк\w*|\bотчетност\w*|\bотчётност\w*|\bязык\b'
    r'|\bкосноязыч\w*|\bформулиру\w*|\bобъясня\w*\s+проще', re.I)

ОКНО = 20


def пересчитать(сообщения=None, прежний=None, окно=ОКНО):
    """Уровень по ОКНУ сообщений владельца — по максимуму, а не по последним двум.

    Человек, однажды написавший «детерминированно», не разучился к следующему
    сообщению: уровень должен падать только тогда, когда ВСЁ окно обиходное.
    Прежнее правило «две оценки подряд» роняло регистр после двух коротких
    реплик о стиле — и сторож начинал метить слово «гейт» в моих отчётах.
    """
    прежний = прежний or прочитать_уровень()
    if сообщения is None:
        пути = sorted(glob.glob(os.path.join(INBOX, "*.txt")),
                      key=os.path.getmtime, reverse=True)[:окно]
        сообщения = []
        for п in пути:
            try:
                сообщения.append(io.open(п, encoding="utf-8", errors="replace").read())
            except OSError:
                pass
    по_делу = [т for т in сообщения if not МЕТА_О_СТИЛЕ.search(т)]
    оценки = [у for у in (уровень_текста(т) for т in по_делу) if у]
    if len(оценки) < 2:
        return прежний, "судить не по чему — уровень прежний"
    # Высший уровень засчитывается, если встретился НЕ МЕНЬШЕ двух раз: одно
    # случайное слово не делает человека инженером, а два — уже привычка.
    подтверждённые = [у for у in УРОВНИ if оценки.count(у) >= 2]
    высший = подтверждённые[-1] if подтверждённые else max(оценки, key=УРОВНИ.index)
    if высший != прежний:
        return высший, (f"в окне из {len(оценки)} сообщений уровень «{высший}» "
                        f"({оценки.count(высший)} раз)")
    return прежний, f"в окне из {len(оценки)} сообщений уровень прежний"


def самотест():
    случаи = [
        ("Смотри я ранее писал посты в телегу. Пилю SaaS Вайбкодингом: специально "
         "вывел количество вызовов за шаг. В целом то что кэш довольно монолитен "
         "я этого и добивался. Память проекта обновляется очень детерминировано.",
         "технический", "БОЛЬНОЙ СЛУЧАЙ: сообщение самого владельца 11.09"),
        ("Почему не работает? Сделай чтобы всё было хорошо и покажи мне что "
         "получилось на картинке, я хочу посмотреть своими глазами вечером.",
         "простой", "человек без терминов — язык на пальцах"),
        ("Проверь пожалуйста деплой и скажи что там с тестами, когда закончишь "
         "работу вечером, я посмотрю утром и отвечу тебе по результатам сразу.",
         "обычный", "термины есть, но редко — середина"),
        ("да", None, "короткое «да» судить нельзя — уровень не меняется"),
    ]
    ok = True
    for текст, ждём, зачем in случаи:
        вышло = уровень_текста(текст)
        if вышло != ждём:
            ok = False
            print(f"  ПЛОХО {зачем}: получили «{вышло}», ждали «{ждём}»")
        else:
            print(f"  ок    {зачем}")
    # Одно короткое сообщение не роняет уровень.
    новый, почему = пересчитать(["да", "ок"], прежний="технический")
    if новый == "технический":
        print("  ок    БОЛЬНОЙ СЛУЧАЙ: два коротких «да» не роняют уровень")
    else:
        ok = False
        print(f"  ПЛОХО короткие ответы уронили уровень до «{новый}» ({почему})")
    # Две подряд простых — уровень падает.
    новый, _ = пересчитать(["Почему не работает, сделай чтобы всё было хорошо сразу",
                            "Покажи мне картинку как это выглядит у людей сейчас"],
                           прежний="технический")
    if новый == "простой":
        print("  ок    два простых сообщения подряд опускают уровень")
    else:
        ok = False
        print(f"  ПЛОХО уровень не опустился: «{новый}»")
    # Мета-сообщения о стиле из выборки исключаются: 11.09 два таких подряд
    # уронили уровень до «простого» у владельца, писавшего «Пилю SaaS» (I-8).
    новый, _ = пересчитать(
        ["Мне не нравится как ты пишешь, нужна лаконичная отчетность без рассуждений",
         "И язык твой должен подстраиваться под меня, не косноязычный а понятный",
         "Пилю SaaS Вайбкодингом: кэш монолитен, память обновляется детерминировано",
         "Репозиторий и коммиты смотри сам, инвариант держи в конфиге деплоя"],
        прежний="технический")
    if новый == "технический":
        print("  ок    БОЛЬНОЙ СЛУЧАЙ: разговор о стиле не роняет уровень")
    else:
        ok = False
        print(f"  ПЛОХО мета-сообщения уронили уровень до «{новый}»")

    # Одно техническое сообщение в окне — ещё не привычка.
    новый, _ = пересчитать(
        ["Проверь деплой и тесты, скажи что с логами сервера вечером сразу",
         "Посмотри сайт и скажи что там с базой данных после обновления кода",
         "Репозиторий с кэшем и инвариантами держи в конфиге, коммиты смотри сам"],
        прежний="обычный")
    if новый == "обычный":
        print("  ок    одно техническое сообщение в окне не поднимает уровень")
    else:
        ok = False
        print(f"  ПЛОХО уровень подскочил до «{новый}» по одному сообщению")

    print("САМОТЕСТ %s: %d путей, первым — больной случай"
          % ("ПРОЙДЕН" if ok else "ПРОВАЛЕН", len(случаи) + 4))
    return 0 if ok else 1


def main():
    if "--selftest" in sys.argv:
        return самотест()
    if "--пересчитать" in sys.argv:
        новый, почему = пересчитать()
        try:
            os.makedirs(LOG_DIR, exist_ok=True)
            io.open(ФАЙЛ_УРОВНЯ, "w", encoding="utf-8").write(новый + "\n")
        except OSError:
            pass
        print(f"[язык] уровень: {новый} ({почему})")
        return 0
    print(прочитать_уровень())
    return 0


if __name__ == "__main__":
    sys.exit(main())
