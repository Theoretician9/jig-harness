def _слепок_боевых_настроек() -> dict:
    """md5 всех боевых harness/config/*.yaml: проба не играет на боевом."""
    каталог = КОРЕНЬ / "harness" / "config"
    return {п.name: hashlib.md5(п.read_bytes()).hexdigest()
            for п in sorted(каталог.glob("*.yaml"))}


СЛЕПОК_ДО = _слепок_боевых_настроек()


def схема_файлом(данные, текстом: str | None = None) -> Path:
    """Подставная схема отдельным файлом во временном каталоге."""
    каталог = Path(tempfile.mkdtemp(prefix="схема-"))
    путь = каталог / "паспорт.yaml"
    путь.write_text(
        текстом if текстом is not None
        else гейт.yaml.safe_dump(данные, allow_unicode=True),
        encoding="utf-8")
    return путь


def попытка(действие):
    """Вызов ручки, которой может не быть: (получилось, значение_или_беда).

    Нужна затем, чтобы красный прогон ДО реализации печатал имена упавших
    путей, а не обрывался трассировкой на первой отсутствующей функции.
    """
    try:
        return True, действие()
    except BaseException as беда:  # noqa: BLE001 — ручки ещё нет, это ожидаемо
        return False, беда


def под_схемой(путь_схемы, действие):
    """Выполнить действие, подставив путь схемы переменной окружения."""
    было = os.environ.get(РУЧКА)
    os.environ[РУЧКА] = str(путь_схемы)
    try:
        return попытка(действие)
    finally:
        if было is None:
            os.environ.pop(РУЧКА, None)
        else:
            os.environ[РУЧКА] = было


def претензии_по_схеме(схема, записи, найденные=None,
                       файлы=("harness/demons/backup.sh",), текстом=None):
    """Претензии гейта при подставной схеме. Беда гейта — строкой в списке."""
    путь_схемы = схема_файлом(схема, текстом)
    корень = двор(записи, файлы)
    try:
        получилось, итог = под_схемой(
            путь_схемы,
            lambda: гейт.проверить(гейт.прочитать_реестр(корень),
                                   найденные or {}, корень))
        return итог if получилось else [f"БЕДА ГЕЙТА: {итог!r}"]
    finally:
        shutil.rmtree(корень, ignore_errors=True)
        shutil.rmtree(путь_схемы.parent, ignore_errors=True)


def прогон_гейта(путь_схемы=None, предел: int = 180):
    """Боевой гейт отдельным процессом: так его зовут ворота. (rc, вывод)."""
    окружение = dict(os.environ)
    if путь_схемы is None:
        окружение.pop(РУЧКА, None)
    else:
        окружение[РУЧКА] = str(путь_схемы)
    итог = subprocess.run([sys.executable, str(ГЕЙТ_ФАЙЛ)], cwd=str(КОРЕНЬ),
                          env=окружение, capture_output=True, text=True,
                          timeout=предел)
    return итог.returncode, (итог.stdout or "") + (итог.stderr or "")


