    try:
        получилось, итог = под_судьёй(
            соответствия,
            lambda: гейт.проверить(гейт.прочитать_реестр(корень),
                                   гейт.механизмы_репозитория(корень), корень),
            живые)
        return итог if получилось else [f"БЕДА ГЕЙТА: {итог!r}"]
    finally:
        shutil.rmtree(корень, ignore_errors=True)


