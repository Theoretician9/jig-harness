    судья = _модуль("sverit-s-paketom.py", "судья_домена_пробы")
    файлы = set()
    for ключ in судья.СООТВЕТСТВИЯ:
        путь = КОРЕНЬ / ключ
        кандидаты = путь.rglob("*") if ключ.endswith("/") else [путь]
