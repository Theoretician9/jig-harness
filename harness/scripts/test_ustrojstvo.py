    if СУДЬЯ is None:
        return False, "модуля-судьи нет — подменять нечего"
    было_с, было_ж = СУДЬЯ.СООТВЕТСТВИЯ, СУДЬЯ.ЖИВЫЕ
    СУДЬЯ.СООТВЕТСТВИЯ = соответствия
    if живые is not None:
        СУДЬЯ.ЖИВЫЕ = живые
    try:
        return попытка(действие)
    finally:
        СУДЬЯ.СООТВЕТСТВИЯ, СУДЬЯ.ЖИВЫЕ = было_с, было_ж


