#!/usr/bin/env python3
"""Закрытые задачи уезжают из карты в архив — кодом, а не вниманием.

Владелец 11.09.2026 спросил: «Что в этих файлах которые постоянно упираются в
лимит». Замер ответил: в `dev-map.yaml` 263 798 знаков, 105 задач, и 77 % из
них — уже закрытая работа. Карта едет в контекст каждой сессии, а чистило её
только моё внимание — то есть не чистило.

Что уезжает: задачи в статусах `done` (проверено владельцем) и `принято`
(доказано машиной). `test`, `wip`, `plan` остаются — это живая работа.

Как уезжает: блок задачи переносится ТЕКСТОМ, а не через yaml.dump. Карту
читают люди, и перезапись сломала бы порядок, комментарии и длинные строки;
заодно это ограничивает власть скрипта — он умеет ровно то, что умеет его
разбор блоков.

И-1 держится тем же приёмом, что у гейта потери задач: id обязан оказаться в
архиве в ТОМ ЖЕ коммите. Скрипт пишет оба файла сразу или не пишет ничего.

Запуск:
    python3 scripts/arhiv-karty.py            # что уехало бы (ничего не меняет)
    python3 scripts/arhiv-karty.py --перенести
    python3 scripts/arhiv-karty.py --selftest
Код возврата: 0 — прогон состоялся.
"""
from __future__ import annotations

import datetime
import re
import sys
from pathlib import Path

import sys as _sys
_sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))
import kartochki as карточки                            # noqa: E402

КОРЕНЬ = Path(__file__).resolve().parent.parent
КАРТА = КОРЕНЬ / "dev-map.yaml"
АРХИВ = КОРЕНЬ / "docs" / "dev-map-archive.yaml"
ЗАКРЫТЫЕ = ("done", "принято")
# Находка ревизии, которую никто не взял в работу за срок, уходит из карты
# тем же путём, что закрытая задача: статуса «снято» в проекте нет, а
# удаление без архива красит гейт потери задач (спека ревизии, I-12).
ПРИЧИНА_СНЯТИЯ = "срок находки истёк"

# Блок задачи: от «      - id: X» до следующего «      - id:» того же отступа
# либо до строки меньшего отступа (конец направления).
#
# Границы карточки — ОБЩИЙ разбор (scripts/lib/kartochki.py): у каждого
# писателя карты он был свой, и починка в одной копии оставляла беду в
# остальных. Две аварии этого класса за четыре дня: 88 задач 09.09, 15 — 12.09.
блоки = карточки.блоки


def статус(блок: str) -> str:
    """Статус САМОГО блока: первый `status:` на уровне полей этой карточки.

    Искать `status:` где угодно внутри блока нельзя — блок направления
    содержит все свои задачи, и первый попавшийся `status: done` делал
    направление «закрытой задачей» (самотест поймал это первой пробой).
    Но и требовать, чтобы `status` стоял ВТОРОЙ строкой, нельзя: карточка, у
    которой перед ним появился `spec:`, получала пустой статус и не
    архивировалась НИКОГДА — молча (находка I7 ревью кода 11.09.2026).
    Поэтому: уровень полей берём у первой строки после id, и на этом уровне
    ищем `status`.
    """
    строки = блок.splitlines()
    # Блок может начинаться с пустых строк — тогда «вторая строка» это ещё id,
    # и уровень полей считался по ней: статус не находился НИ У ОДНОЙ карточки
    # (поймано живым прогоном 12.09.2026, самотест был зелёным, потому что его
    # образцы пустых строк не имели).
    начало = next((i for i, с in enumerate(строки) if "- id:" in с), None)
    if начало is None or начало + 1 >= len(строки):
        return ""
    поле = строки[начало + 1]
    уровень = len(поле) - len(поле.lstrip())
    for строка in строки[начало + 1:]:
        отступ = len(строка) - len(строка.lstrip())
        if строка.strip() and отступ < уровень:
            break                       # вышли из полей этой карточки
        if отступ == уровень:
            совпало = re.match(r"status:\s*(\S+)\s*$", строка.strip())
            if совпало:
                return совпало.group(1)
    return ""


def направление(текст: str, позиция: int) -> str:
    """Имя направления, внутри которого лежит задача: в архиве она ляжет туда же."""
    кусок = текст[:позиция]
    совпало = None
    for м in re.finditer(r"^\s*- id:\s*(\S+)\s*\n\s*layer:", кусок, re.M):
        совпало = м
    return совпало.group(1) if совпало else "harness"


def отобрать(текст: str) -> list[tuple[str, str, str]]:
    """[(id, блок, направление)] — что подлежит переносу."""
    return [(ид, блок, направление(текст, начало))
            for ид, блок, начало, _ in блоки(текст)
            if статус(блок) in ЗАКРЫТЫЕ]


def вложить_в_архив(архив: str, добавить: list[tuple[str, str, str]]) -> str:
    """Блоки кладутся в своё направление архива; нет такого — заводится."""
    for ид, блок, напр in добавить:
        м = re.search(rf"^(\s*)- id:\s*{re.escape(напр)}\s*$", архив, re.M)
        if м:
            # Конец направления: следующая строка того же отступа «- id:».
            конец = len(архив)
            for следующее in re.finditer(r"^(\s*)- id:\s*(\S+)\s*$", архив, re.M):
                if следующее.start() > м.start() and len(следующее.group(1)) <= len(м.group(1)):
                    конец = следующее.start()
                    break
            архив = архив[:конец].rstrip("\n") + "\n\n" + блок.rstrip("\n") + "\n\n" + архив[конец:]
        else:
            архив = архив.rstrip("\n") + (
                f"\n\n  - id: {напр}\n    name: \"{напр}\"\n    tasks:\n"
                + блок.rstrip("\n") + "\n")
    return архив


def перенести(карта_путь: Path, архив_путь: Path, применить: bool) -> dict:
    текст = карта_путь.read_text(encoding="utf-8")
    добавить = отобрать(текст)
    if not добавить:
        return {"перенесено": 0, "знаков освобождено": 0}
    освобождено = sum(len(блок) for _, блок, _ in добавить)
    if применить:
        новая = текст
        for _, блок, _ in добавить:
            новая = новая.replace(блок, "", 1)
        новая = re.sub(r"\n{3,}", "\n\n", новая)

        # СЧЁТ ДО И ПОСЛЕ. Улика 12.09.2026: из-за `\s` в разборе отступа блок
        # одной закрытой задачи поглотил одиннадцать соседних, девять из них
        # живых, — и перенос прошёл молча, отчитавшись «перенесено 6». Данные
        # уцелели в архиве, но карта потеряла работу, и очередь опустела.
        # Считаем id, а не знаки: пропажа обязана остановить запись (И-1).
        было = {ид for ид, _, _, _ in блоки(текст)}
        осталось = {ид for ид, _, _, _ in блоки(новая)}
        уносим = {ид for ид, _, _ in добавить}
        лишние = было - осталось - уносим
        if лишние:
            raise SystemExit(
                "[архив карты] ОТКАЗ: перенос унёс бы ЧУЖИЕ задачи (%s) — "
                "ничего не записано (И-1). Границы блоков разъехались: проверь "
                "отступы карточек" % ", ".join(sorted(лишние)))
        архив = архив_путь.read_text(encoding="utf-8") if архив_путь.exists() else \
            "# Архив карты разработки: закрытые задачи.\nversion: 1\nlines:\n"
        архив = вложить_в_архив(архив, добавить)
        # Пишем ОБА файла и только вместе: id обязан оказаться в архиве в том
        # же коммите, иначе гейт потери задач (И-1) справедливо покраснеет.
        архив_путь.write_text(архив, encoding="utf-8")
        карта_путь.write_text(новая, encoding="utf-8")
    return {"перенесено": len(добавить), "знаков освобождено": освобождено,
            "задачи": [ид for ид, _, _ in добавить]}


def снять(карта_путь: Path, архив_путь: Path, ids: list[str],
          причина: str = ПРИЧИНА_СНЯТИЯ) -> dict:
    """Перенести названные задачи ЛЮБОГО статуса в архив с причиной снятия.

    Всё или ничего: неизвестный id — файлы не пишутся вовсе (И-1). Это не
    удаление: карточка остаётся читаемой в архиве, и гейт потери задач видит
    её на месте.
    """
    текст = карта_путь.read_text(encoding="utf-8")
    известные = {ид: (блок, направление(текст, начало))
                 for ид, блок, начало, _ in блоки(текст)}
    не_найдены = [ид for ид in ids if ид not in известные]
    if не_найдены:
        return {"снято": 0, "задачи": [], "не найдены": не_найдены}

    сегодня = datetime.date.today().isoformat()
    добавить, новая = [], текст
    for ид in ids:
        блок, напр = известные[ид]
        добавить.append((ид, с_причиной(блок, причина, сегодня), напр))
        новая = новая.replace(блок, "", 1)
    новая = re.sub(r"\n{3,}", "\n\n", новая)

    архив = архив_путь.read_text(encoding="utf-8") if архив_путь.exists() else \
        "# Архив карты разработки: закрытые задачи.\nversion: 1\nlines:\n"
    архив = вложить_в_архив(архив, добавить)
    архив_путь.write_text(архив, encoding="utf-8")
    карта_путь.write_text(новая, encoding="utf-8")
    return {"снято": len(ids), "задачи": list(ids), "не найдены": []}


def с_причиной(блок: str, причина: str, когда: str) -> str:
    """Блок карточки с дописанными причиной снятия и датой — после `status:`.

    Уровень полей берётся так же, как в `статус()`: по первой строке после
    `- id:`. Ставить строки в конец блока нельзя — в конце лежит чек-лист, и
    поле уехало бы внутрь его последнего пункта.
    """
    строки = блок.splitlines(keepends=True)
    начало = next((i for i, с in enumerate(строки) if "- id:" in с), 0)
    поле = строки[начало + 1] if начало + 1 < len(строки) else "        x"
    отступ = " " * (len(поле) - len(поле.lstrip()))
    for i in range(начало + 1, len(строки)):
        голая = строки[i].strip()
        if голая.startswith("status:") and len(строки[i]) - len(строки[i].lstrip()) == len(отступ):
            строки.insert(i + 1, f'{отступ}closed_reason: "{причина}"\n')
            строки.insert(i + 2, f'{отступ}снято_когда: "{когда}"\n')
            break
    return "".join(строки)


def _selftest() -> int:
    import tempfile
    плохо = 0

    def проба(имя: str, ждём, вышло) -> None:
        nonlocal плохо
        if вышло == ждём:
            print(f"  ок    {имя}")
        else:
            print(f"  ПЛОХО {имя}: ждали {ждём!r}, вышло {вышло!r}")
            плохо = 1

    образец = """version: 1
lines:
  - id: harness
    layer: infra
    name: "Ядро"
    tasks:
      - id: t.закрыта
        status: done
        title: "Закрытая"
        summary: "текст"

      - id: t.живая
        status: test
        title: "Живая"
        summary: "текст"
      - id: t.принята
        status: принято
        принято_когда: "2026-09-11"
        title: "Доказана машиной"
        summary: "текст"

      - id: t.вторая-живая
        status: plan
        title: "Тоже живая"
        summary: "текст"
"""
    # ПУСТЫЕ СТРОКИ В ОБРАЗЦЕ — часть больного случая 12.09.2026: разбор считал
    # отступ классом `\s`, который включает перевод строки, и у карточки с
    # пустой строкой перед ней отступ выходил на единицу больше. Карточка без
    # пустой строки поглощала всех соседей до конца направления — одиннадцать
    # задач, девять живых. Прежний образец шёл сплошняком, и дефект в нём не
    # проявлялся ни разу.
    with tempfile.TemporaryDirectory() as врем:
        к = Path(врем) / "dev-map.yaml"
        а = Path(врем) / "archive.yaml"
        к.write_text(образец, encoding="utf-8")
        # БОЛЬНОЙ СЛУЧАЙ: живая задача уезжать не должна — иначе работа пропадёт.
        отобрано = [ид for ид, _, _ in отобрать(образец)]
        проба("БОЛЬНОЙ СЛУЧАЙ: живая задача остаётся в карте",
              ["t.закрыта", "t.принята"], отобрано)
        блок_закрытой = next(б for и, б, _, _ in блоки(образец) if и == "t.закрыта")
        проба("БОЛЬНОЙ СЛУЧАЙ 12.09: блок закрытой не поглощает соседей",
              [], [и for и, *_ in блоки(блок_закрытой) if и != "t.закрыта"])
        итог = перенести(к, а, применить=True)
        проба("перенесено две", 2, итог["перенесено"])
        новая = к.read_text(encoding="utf-8")
        проба("живая осталась", True, "t.живая" in новая)
        проба("закрытая ушла из карты", False, "t.закрыта" in новая)
        проба("закрытая есть в архиве", True, "t.закрыта" in а.read_text(encoding="utf-8"))
        import yaml
        проба("карта осталась валидным YAML", True,
              isinstance(yaml.safe_load(новая), dict))
        проба("архив остался валидным YAML", True,
              isinstance(yaml.safe_load(а.read_text(encoding="utf-8")), dict))
    # БОЛЬНОЙ СЛУЧАЙ ревью (I7): карточка, у которой перед `status` появилось
    # любое поле, получала пустой статус и не архивировалась НИКОГДА — молча.
    с_полем_выше = """      - id: t.закрыта
        spec: docs/specs/что-то.md
        status: done
        title: "Закрытая"
"""
    проба("БОЛЬНОЙ СЛУЧАЙ: статус найден, даже если он не второй строкой",
          "done", статус(с_полем_выше))
    # БОЛЬНОЙ СЛУЧАЙ 12.09.2026: блок пришёл с пустой строкой в начале, и
    # уровень полей считался по строке id — статуса не было ни у одной задачи,
    # архив молча не уносил ничего.
    проба("БОЛЬНОЙ СЛУЧАЙ: пустая строка перед карточкой не сбивает статус",
          "принято",
          статус("\n      - id: t.x\n        status: принято\n        title: \"T\"\n"))
    проба("блок направления закрытой задачей не становится", "",
          статус("  - id: harness\n    layer: infra\n    tasks:\n"
                 "      - id: t.x\n        status: done\n"))

    # БОЛЬНОЙ СЛУЧАЙ ревью 11.09.2026: блок последней закрытой задачи тянулся
    # ДО КОНЦА ФАЙЛА и уносил всё, что стоит после секции lines:. Карта при
    # этом оставалась валидным YAML — то есть пропажу не поймал бы никто.
    хвостатый = """version: 1
lines:
  - id: harness
    layer: infra
    name: "Ядро"
    tasks:
      - id: t.живая
        status: test
        title: "Живая"
        summary: "текст"
      - id: t.закрыта
        status: done
        title: "Закрытая"
        summary: "текст"
queue: []
layers:
  - { id: infra, label: "Инфра", color: "#5aa06a" }
"""
    with tempfile.TemporaryDirectory() as врем:
        к = Path(врем) / "dev-map.yaml"
        а = Path(врем) / "archive.yaml"
        к.write_text(хвостатый, encoding="utf-8")
        import yaml as _yaml
        ключи_до = set(_yaml.safe_load(хвостатый))
        перенести(к, а, применить=True)
        ключи_после = set(_yaml.safe_load(к.read_text(encoding="utf-8")))
        проба("БОЛЬНОЙ СЛУЧАЙ: секции после lines: не уносятся в архив",
              ключи_до, ключи_после)

    # ── --снять: находка ревизии уходит в архив с причиной (спека ревизии, I-12²)
    # Почему: статуса «снято» в проекте нет, удаление без архива красит гейт
    # потери задач. Снятие обязано пройти тем же путём, что и закрытие, —
    # карта и архив пишутся вместе.
    with tempfile.TemporaryDirectory() as врем:
        к = Path(врем) / "dev-map.yaml"
        а = Path(врем) / "archive.yaml"
        к.write_text(образец, encoding="utf-8")
        итог = снять(к, а, ["t.живая"], "срок находки истёк")
        проба("снято одна", 1, итог["снято"])
        новая = к.read_text(encoding="utf-8")
        архив = а.read_text(encoding="utf-8")
        проба("снятая ушла из карты", False, "t.живая" in новая)
        проба("снятая в архиве с причиной", True,
              "t.живая" in архив and 'closed_reason: "срок находки истёк"' in архив)
        проба("у снятой есть дата снятия", True, "снято_когда:" in архив)
        проба("соседи целы", True, "t.закрыта" in новая and "t.принята" in новая)
        # БОЛЬНОЙ СЛУЧАЙ: неизвестный id — ничего не пишем (всё или ничего, И-1).
        было = к.read_text(encoding="utf-8")
        итог = снять(к, а, ["t.нет-такой"], "срок находки истёк")
        проба("БОЛЬНОЙ СЛУЧАЙ: неизвестный id — карта не тронута",
              (["t.нет-такой"], было), (итог["не найдены"], к.read_text(encoding="utf-8")))

    if плохо:
        print("САМОТЕСТ ПРОВАЛЕН")
        return 1
    print("САМОТЕСТ ПРОЙДЕН: 17 путей, первым — больной случай")
    return 0


def main() -> int:
    if "--selftest" in sys.argv:
        return _selftest()
    if "--снять" in sys.argv:
        ids = sys.argv[sys.argv.index("--снять") + 1:]
        if not ids:
            print("[архив карты] --снять: назови хотя бы один id задачи")
            return 1
        итог = снять(КАРТА, АРХИВ, ids)
        if итог["не найдены"]:
            print("[архив карты] ОТКАЗ: в карте нет задач: "
                  + ", ".join(итог["не найдены"]) + " — ничего не записано")
            return 1
        print(f"[архив карты] снято: {итог['снято']}")
        for ид in итог["задачи"]:
            print(f"    {ид}")
        return 0
    итог = перенести(КАРТА, АРХИВ, применить="--перенести" in sys.argv)
    было = len(КАРТА.read_text(encoding="utf-8"))
    print(f"[архив карты] закрытых задач: {итог['перенесено']}, "
          f"это {итог['знаков освобождено']} знаков; в карте сейчас {было}")
