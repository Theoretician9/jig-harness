#!/usr/bin/env python3
"""Дверь записи профилей и запуска смены на аккаунте по ключу setup-token.

Единственное место, которое пишет profiles.json и state.json (под замком
`.lock`, tmp+rename). Каждая запись идёт после ЖИВОГО вызова ключом: смена,
поднятая на мёртвом ключе, не сможет даже откатить себя сама.

    --профиль-добавить <имя> --подпись S --орг O --ключ <файл в SECRETS_DIR> [--почта E]
    --запуск <имя|login>     профиль, на котором поднимется СЛЕДУЮЩИЙ процесс смены
    --проверить              процесс смены несёт ключ профиля `запуск` и орг сошлась
    --хочу <имя|login>       выбор владельца из бота: запись `запуск` и `переключение`, затем будит сторожа
                             (он дожидается тишины помощников и передачи дел, ротирует сам)
    --ждёт                   для сторожа: 0 + цель — ротировать; 3 — процесс уже на цели; 1 — переключения нет
    --итог                   для сторожа после подъёма: судит процесс, шлёт ОДНУ весть; неудача → откат

Печатает имя, отпечаток, организацию — ни ключа, ни пути файла ключа.
Коды: 0 — сделано, 1 — отказ или расхождение, 2 — проверить нечем (у --ждёт: 3 — подтвердить, не ротировать).
Ключ и имя файла ключа не попадают ни в вывод, ни в весть владельцу.
"""
import argparse
import datetime
import hashlib
import importlib.util
import os
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "lib"))
import accounts  # noqa: E402
from config import из_файла, путь_harness_conf  # noqa: E402

ВХОД = "login"
ПОДПИСЬ_ВХОДА = "вход /login"
ОЖИДАНИЕ_ПРОЦЕССА_СЕК = 120
ШАГ_ОЖИДАНИЯ_СЕК = 2


def _сторож():
    """check-login-expiry.py — тот же код, не копия: процесс смены, ключ процесса, организация."""
    spec = importlib.util.spec_from_file_location("check_login_expiry", os.path.join(HERE, "check-login-expiry.py"))
    модуль = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(модуль)
    return модуль


def отказ(текст: str) -> int:
    print(f"ОТКАЗ: {текст}", file=sys.stderr)
    return 1


def _отпечаток(ключ: str) -> str:
    return hashlib.sha256(ключ.encode()).hexdigest()[:8]


def _сейчас() -> str:
    return datetime.datetime.now().astimezone().isoformat(timespec="seconds")


def _каталог_есть():
    if os.path.isdir(accounts.каталог()):
        return None
    return отказ(f"каталога аккаунтов нет; создать: sudo install -d -o agent -g agent -m 750 {accounts.каталог()}")


def _живой_ключ(имя_файла: str, сторож):
    """(ключ, орг, "") или ("", "", причина): файл годен и живой вызов принят."""
    путь, причина = accounts.путь_ключа(имя_файла)
    if причина:
        return "", "", причина
    ключ = accounts.ключ(путь)
    орг, повод = сторож.организация(ключ)
    return (ключ, орг, "") if орг else ("", "", f"ключ не принят: {повод}")


def добавить(арг) -> int:
    if not accounts.ИМЯ.fullmatch(арг.профиль_добавить):
        return отказ("имя профиля — [a-z0-9-], 1-20 знаков")
    if (r := _каталог_есть()) is not None:
        return r
    if accounts.профиль(арг.профиль_добавить):
        return отказ(f"профиль {арг.профиль_добавить} уже заведён: имя неизменно")
    if not арг.орг or not арг.подпись:
        return отказ("нужны --подпись и --орг")
    сторож = _сторож()
    ключ, орг, причина = _живой_ключ(арг.ключ, сторож)
    if причина:
        return отказ(причина)
    ожидаемые = сторож.ожидаемые_орг()
    if орг != арг.орг:
        return отказ(f"живой вызов назвал организацию {орг}, а не {арг.орг}")
    if орг not in ожидаемые:
        return отказ(f"организация {орг} не в LOGIN_EXPECTED_ORG")
    запись = {"имя": арг.профиль_добавить, "подпись": арг.подпись, "орг": орг, "почта": арг.почта or "",
              "ключ": арг.ключ, "отпечаток": _отпечаток(ключ)}

    def вставить(данные):
        if any(p.get("имя") == запись["имя"] for p in данные.setdefault("профили", [])):
            raise ValueError("профиль уже заведён")
        данные["профили"].append(запись)
    accounts.записать_профили(вставить)
    accounts.записать_состояние(lambda s: s.setdefault("запуск", "login"))
    print(f"профиль {запись['имя']} заведён: отпечаток {запись['отпечаток']}, организация {орг}")
    return 0


def запуск(арг) -> int:
    цель = арг.запуск
    if цель != "login" and not accounts.ИМЯ.fullmatch(цель):
        return отказ("цель — login или имя [a-z0-9-]")
    if (r := _каталог_есть()) is not None:
        return r
    if цель != "login":
        проф = accounts.профиль(цель)
        if проф is None:
            return отказ(f"профиль {цель} не заведён")
        _, орг, причина = _живой_ключ(проф.get("ключ"), _сторож())
        if причина:
            return отказ(f"профиль {цель}: {причина}")
        if орг != проф.get("орг"):
            return отказ(f"профиль {цель}: организация ключа {орг} не та, что у профиля")

    def записать(s):
        откуда = s.get("запуск", "")
        s["запуск"] = цель
        s.setdefault("переключения", []).append(
            {"время": _сейчас(), "откуда": откуда, "куда": цель, "что": "запуск"})
    try:
        accounts.записать_состояние(записать)
    except ValueError:
        return отказ("state.json битый — не затираю")
    print(f"запуск следующей смены: {цель}")
    return 0


def проверить(_арг) -> int:
    стат = accounts.состояние()
    if стат is None:
        print("state.json не читается", file=sys.stderr)
        return 2
    цель = стат.get("запуск")
    код, текст = судить_процесс(цель, 0)
    if код == 2:
        print(текст, file=sys.stderr)
        return 2
    if код == 1:
        return отказ(текст)
    accounts.записать_состояние(lambda s: s.__setitem__("идёт", цель))
    print(f"смена идёт на {текст}")
    return 0


def _настройка(ключ: str, умолчание: int) -> int:
    """Число из окружения, затем harness.conf; нет или не число — умолчание."""
    значение = os.environ.get(ключ) or из_файла(путь_harness_conf()).get(ключ, "")
    return int(значение) if str(значение).isdigit() else умолчание


def _подпись(имя: str) -> str:
    """Что называть владельцу: подпись профиля; ни ключа, ни имени файла ключа."""
    if имя == ВХОД:
        return ПОДПИСЬ_ВХОДА
    return str((accounts.профиль(имя) or {}).get("подпись") or имя)


def весть(текст: str) -> None:
    """Одно сообщение владельцу. Недоставленное — в stderr: смена от него не зависит."""
    отправка = os.environ.get("TG_SEND") or os.path.join(HERE, "tg_send.sh")
    try:
        subprocess.run(["bash", отправка, текст], check=True, stdout=subprocess.DEVNULL)
    except (subprocess.CalledProcessError, OSError) as беда:
        print(f"весть не ушла: {беда}", file=sys.stderr)


def путь_сторожа() -> str:
    return os.environ.get("ACCOUNT_WARDEN") or os.path.normpath(
        os.path.join(HERE, "..", "harness", "demons", "session-warden.sh"))


def разбудить_сторожа() -> int:
    """Сторож сам отвяжется и дождётся тишины; здесь только толчок."""
    return subprocess.run(["bash", путь_сторожа(), "--account-switch"], check=False).returncode


def _переключение(s: dict, откуда: str, куда: str, откат: bool, причина: str = "") -> None:
    s["переключение"] = {"откуда": откуда, "куда": куда, "начало": _сейчас(), "откат": откат,
                         **({"причина": причина} if причина else {})}


def _журнал(s: dict, что: str, откуда: str, куда: str, исход: str = "") -> None:
    s.setdefault("переключения", []).append(
        {"время": _сейчас(), "откуда": откуда, "куда": куда, "что": что, **({"исход": исход} if исход else {})})


def _отказ_выбора(цель: str, причина: str) -> int:
    """Отказ по выбору владельца: он нажал кнопку и ждёт слова. Профиль неизвестен — молчим."""
    if цель == ВХОД or accounts.профиль(цель):
        весть(f"Не перешёл на {_подпись(цель)}: {причина}")
    return отказ(причина)


def _вошла_в_сессии(сторож) -> bool:
    """Смена несёт ключ в окружении, но «/login» внутри сессии сменил вход: state ей не верит."""
    pid = сторож.процесс_смены()
    return bool(pid and сторож.ключ_процесса(pid) and сторож.вход_после_старта(pid))


def хочу(арг) -> int:
    цель = арг.хочу
    if цель != ВХОД and not accounts.ИМЯ.fullmatch(цель):
        return отказ("цель — login или имя [a-z0-9-]")
    if (r := _каталог_есть()) is not None:
        return r
    if цель != ВХОД and accounts.профиль(цель) is None:
        return отказ(f"профиль {цель} не заведён")
    стат = accounts.состояние()
    if стат is None:
        return _отказ_выбора(цель, "state.json нет или не читается")
    идёт = стат.get("идёт") or стат.get("запуск", "")
    переключение = стат.get("переключение") or {}
    if переключение.get("откат"):
        return _отказ_выбора(цель, "сейчас идёт возврат на прежний аккаунт, выбор не принимаю")
    if цель == идёт and not переключение and not _вошла_в_сессии(_сторож()):
        весть(f"Уже работаю на {_подпись(цель)}")
        return 0
    if цель != ВХОД:
        проф = accounts.профиль(цель)
        _, орг, причина = _живой_ключ(проф.get("ключ"), _сторож())
        if причина:
            return _отказ_выбора(цель, причина)
        if орг != проф.get("орг"):
            return _отказ_выбора(цель, f"организация ключа {орг} не та, что у профиля")

    def записать(s):
        откуда = s.get("идёт") or s.get("запуск", "")
        s["запуск"] = цель
        _переключение(s, откуда, цель, False)
        _журнал(s, "хочу", откуда, цель)
    try:
        accounts.записать_состояние(записать)
    except ValueError:
        return _отказ_выбора(цель, "state.json битый — не затираю")
    print(f"выбор записан: {цель}")
    if разбудить_сторожа() != 0:
        весть(f"Выбор {_подпись(цель)} записан, но сторож сессий не запустился: перейду со следующей сменой.")
        return 1
    return 0


def _ключ_цели(цель: str):
    """Ключ профиля цели; "" — у login носителя нет; None — ключ профиля прочесть нельзя."""
    if цель == ВХОД:
        return ""
    путь, причина = accounts.файл_ключа(accounts.профиль(цель))
    return None if причина else accounts.ключ(путь)


def ждёт(_арг) -> int:
    стат = accounts.состояние() or {}
    переключение = стат.get("переключение") or {}
    if not переключение:
        return 1
    цель = переключение.get("куда", "")
    вход = _сторож()
    pid = вход.процесс_смены()
    ключ = вход.ключ_процесса(pid) if pid else None
    if ключ is not None and ключ == _ключ_цели(цель) and not (ключ and вход.вход_после_старта(pid)):
        return 3
    print(цель)
    return 0


def судить_процесс(цель: str, ждать_сек: int):
    """(код, текст): 0 — процесс смены на аккаунте цели; 1 — не на нём; 2 — судить нечем."""
    сторож_ = _сторож()
    срок = time.monotonic() + ждать_сек
    pid = сторож_.процесс_смены()
    while pid is None and time.monotonic() < срок:
        time.sleep(ШАГ_ОЖИДАНИЯ_СЕК)
        pid = сторож_.процесс_смены()
    if pid is None:
        return 2, "процесса смены в панели нет — проверять нечего"
    ключ = сторож_.ключ_процесса(pid)
    if ключ is None:
        return 2, "окружение процесса смены не прочесть"
    if ключ and сторож_.вход_после_старта(pid):
        return 2, сторож_.ВХОД_В_СЕССИИ
    if цель == ВХОД:
        if ключ:
            return 1, "запуск=login, а процесс смены несёт ключ"
        return 0, "login: ключа в процессе нет"
    проф = accounts.профиль(цель) if isinstance(цель, str) else None
    путь, причина = accounts.файл_ключа(проф) if проф else ("", "профиль запуска не заведён")
    if причина:
        return 1, причина
    if not ключ or ключ != accounts.ключ(путь):
        return 1, f"процесс смены несёт не ключ профиля {цель} (смена не переподнята?)"
    орг, повод = сторож_.организация(ключ)
    if not орг:
        return 2, f"организацию узнать не удалось: {повод}"
    if орг != проф.get("орг"):
        return 1, f"организация ключа процесса {орг} не та, что у профиля {цель}"
    return 0, f"{цель}: отпечаток {_отпечаток(ключ)}, организация {орг}"


def _принять_итог(переключение: dict) -> int:
    цель, откат = переключение.get("куда", ""), bool(переключение.get("откат"))

    def записать(s):
        s["идёт"] = цель
        s.pop("переключение", None)
        _журнал(s, "откат" if откат else "итог", переключение.get("откуда", ""), цель, "ок")
    accounts.записать_состояние(записать)
    if not откат:  # о неудаче уже сказано, возврат подтверждается молча
        весть(f"Перешёл на аккаунт {_подпись(цель)}")
    return 0


def _вернуть_прежний(переключение: dict, причина: str) -> int:
    цель, прежний = переключение.get("куда", ""), переключение.get("откуда", "")

    def записать(s):
        s["запуск"] = прежний
        _переключение(s, цель, прежний, True, причина)
        _журнал(s, "итог", прежний, цель, "не перешёл")
    accounts.записать_состояние(записать)
    весть(f"Не перешёл на {_подпись(цель)}: {причина}. Возвращаю {_подпись(прежний)}.")
    разбудить_сторожа()
    return 1


def _снять_откат(переключение: dict, причина: str) -> int:
    def записать(s):
        s.pop("переключение", None)
        _журнал(s, "откат", переключение.get("откуда", ""), переключение.get("куда", ""), "не удался")
    accounts.записать_состояние(записать)
    весть(f"Вернуть на {_подпись(переключение.get('куда', ''))} тоже не вышло: {причина}")
    return 1


def итог(_арг) -> int:
    стат = accounts.состояние() or {}
    переключение = стат.get("переключение") or {}
    if not переключение:
        return 2
    код, текст = судить_процесс(переключение.get("куда", ""), _настройка("ACCOUNT_VERIFY_WAIT_SEC", ОЖИДАНИЕ_ПРОЦЕССА_СЕК))
    if код == 0:
        return _принять_итог(переключение)
    if переключение.get("откат"):
        return _снять_откат(переключение, текст)
    return _вернуть_прежний(переключение, текст)


def main() -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("--профиль-добавить", dest="профиль_добавить")
    р.add_argument("--подпись")
    р.add_argument("--орг")
    р.add_argument("--ключ")
    р.add_argument("--почта")
    р.add_argument("--запуск")
    р.add_argument("--проверить", action="store_true")
    р.add_argument("--хочу")
    р.add_argument("--ждёт", action="store_true")
    р.add_argument("--итог", action="store_true")
    арг = р.parse_args()
    if арг.профиль_добавить:
        return добавить(арг)
    if арг.запуск:
        return запуск(арг)
    if арг.проверить:
        return проверить(арг)
    if арг.хочу:
        return хочу(арг)
    if арг.ждёт:
        return ждёт(арг)
    if арг.итог:
        return итог(арг)
    р.print_usage(sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main())
