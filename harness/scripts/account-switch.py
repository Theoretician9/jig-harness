def main() -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("--профиль-добавить", dest="профиль_добавить")
    р.add_argument("--подпись")
    р.add_argument("--орг")
    р.add_argument("--ключ")
    р.add_argument("--почта")
    р.add_argument("--запуск")
    р.add_argument("--проверить", action="store_true")
    р.add_argument("--хочу")
    р.add_argument("--ждёт", action="store_true")
    р.add_argument("--итог", action="store_true")
    р.add_argument("--авто", action="store_true")
    р.add_argument("--от", choices=("смена", "демоны"), default="смена")
    р.add_argument("--сухо", action="store_true")
    р.add_argument("--в-лимите", dest="в_лимите", action="store_true")
    р.add_argument("--после-ротации", dest="после_ротации", action="store_true")
    р.add_argument("--остановлено", type=int, default=0)
    арг = р.parse_args()
    if арг.профиль_добавить:
        return добавить(арг)
    if арг.запуск:
        return запуск(арг)
    if арг.проверить:
        return проверить(арг)
    if арг.хочу:
        return _с_журналом("хочу", lambda: хочу(арг))
    if арг.ждёт:
        return ждёт(арг)
    if арг.итог:
        return _с_журналом("итог", lambda: итог(арг))
    if арг.авто:
        return _с_журналом("авто", lambda: авто(арг.от, арг.сухо))
    if арг.в_лимите:
        return _с_журналом("в-лимите", lambda: в_лимите(арг))
    р.print_usage(sys.stderr)
    return 2


