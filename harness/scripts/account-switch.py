#!/usr/bin/env python3
"""Дверь записи профилей и запуска смены на аккаунте по ключу setup-token.

Единственное место, которое пишет profiles.json и state.json (под замком
`.lock`, tmp+rename). Каждая запись идёт после ЖИВОГО вызова ключом: смена,
поднятая на мёртвом ключе, не сможет даже откатить себя сама.

    --профиль-добавить <имя> --подпись S --орг O --ключ <файл в SECRETS_DIR> [--почта E]
    --запуск <имя|login>     профиль, на котором поднимется СЛЕДУЮЩИЙ процесс смены
    --проверить              процесс смены несёт ключ профиля `запуск` и орг сошлась
    --хочу <имя|login>       выбор владельца из бота: запись `запуск` и `переключение`, затем будит сторожа
                             (он дожидается тишины помощников и передачи дел, ротирует сам)
    --ждёт                   для сторожа: 0 + цель — ротировать; 3 — процесс уже на цели; 4 — после ротации
                             судить нечем, только итог; 1 — переключения нет
    --итог [--после-ротации] [--остановлено N]
                             для сторожа после подъёма: судит процесс, шлёт ОДНУ весть; неудача ручного → откат,
                             автоперехода → следующий кандидат
    --авто --от смена|демоны [--сухо]
                             аккаунт в лимите по ЖИВОМУ вызову → переход на свободный (зовут limit-watch и claude-demon)
    --в-лимите               для сторожа: живой вызов ключом смены, 0 — rejected

Печатает имя, отпечаток, организацию — ни ключа, ни пути файла ключа.
Коды: 0 — сделано, 1 — отказ или расхождение, 2 — проверить нечем (у --ждёт: 3 — подтвердить, не ротировать).
У --авто: 0 переход начат, 1 текущий не в лимите, 2 не время или судить нечем (в т. ч. все в лимите, а часа сброса
никто не назвал), 4 все в лимите, 5 переход уже идёт, 6 предел неудач.
Код 9 — дверь упала: 1 здесь значит «текущий не в лимите», упавшая дверь не вправе его изображать.
Ключ и имя файла ключа не попадают ни в вывод, ни в весть владельцу, ни в журнал двери.
"""
