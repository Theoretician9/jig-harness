#!/usr/bin/env bash
#
# live-check.sh — зовёт механизм и кладёт ЕГО вывод в след.
#
# Откуда взято: спека `docs/specs/2026-10-15-живая-проверка-механизмов.md` §3.2,
# план `docs/plans/2026-10-16-носители-живой-проверки.md` Task 1.
#
# Зачем. Запись «проверено живьём» доказывалась моими же словами, и гейт судил
# ФОРМУ записи — «2026-10-15: работает» и пересказ самотеста проходили (ревью
# спеки 15.10, CRITICAL 5). Мерой может быть только ЧУЖОЙ текст: вывод самого
# механизма. Обёртка его сохраняет, а гейт `--проверить` потом требует из следа
# дословную подстроку.
#
# Запуск:
#   bash scripts/live-check.sh <путь-механизма> -- <команда…>
# Код возврата — КОД МЕХАНИЗМА как есть: проглоченный код превратил бы поломку
# в «проверено». Свои отказы обёртка отдаёт кодом 2 и своим словом.
#
# Чем доказано: scripts/test_live_check_sh.sh (больной случай первым — упавший
# механизм отдаёт 7, и обёртка обязана вернуть 7).
set -uo pipefail
cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/.." || exit 1

# Каталог следа — из окружения, иначе проба писала бы в рабочую задачу.
# Умолчание нейтральное: id карточки ЭТОЙ установки в коде был её следом, а
# в заготовке карты пакета такой карточки нет вовсе (ревью 17.10, F-gen-07).
# Свой каталог задачи задаётся переменной при вызове.
TRACE_DIR="${HARNESS_LIVE_CHECK_TRACE_DIR:-.tasks/живая-проверка/живьём}"
# Предел времени и закрытый stdin. Механизм, читающий ввод, висел ВЕЧНО, и в
# следе уже лежала шапка — со стороны это выглядело начатой проверкой (ревью
# 17.10, F-gen-03). Живая проверка зовёт механизм так, как его зовёт жизнь:
# из крона и из демона stdin закрыт, а время не бесконечно.
TIMEOUT_SEC="${HARNESS_LIVE_CHECK_TIMEOUT:-300}"

refuse() { echo "live-check: $1" >&2; exit 2; }

[ $# -ge 1 ] || refuse "нечего звать: нужен путь механизма, затем «--» и команда"
mechanism="$1"; shift
[ $# -ge 1 ] || refuse "нечего звать: после механизма нет разделителя «--» и команды"
[ "$1" = "--" ] || refuse "нет разделителя «--» между механизмом и командой: «$1»"
shift
[ $# -ge 1 ] || refuse "нечего звать: после разделителя «--» пусто"

# Косая черта в имени файла создала бы каталоги вне следа — и могла бы записать
# файл чужому механизму.
trace="$TRACE_DIR/${mechanism//\//-}.log"
mkdir -p "$TRACE_DIR" || refuse "не создать каталог следа: $TRACE_DIR"

{
    echo "время: $(date -Is)"
    echo "механизм: $mechanism"
    echo "команда: $*"
    echo "пользователь: $(id -un)"
    echo "--- вывод механизма ---"
} > "$trace" || refuse "не записать след: $trace"

# stderr идёт в след наравне с stdout: именно там механизм ругается, и без него
# ровно ту проверку нечем было бы доказать.
timeout "$TIMEOUT_SEC" "$@" < /dev/null 2>&1 | tee -a "$trace"
code=${PIPESTATUS[0]}
# 124 — слово самого timeout: механизм не кончился за предел. Пишем это в след
# СВОИМИ словами, иначе «проверено» получилось бы из оборванного ожидания.
if [ "$code" = 124 ]; then
    echo "ОБОРВАНО ОБЁРТКОЙ: механизм не кончился за предел ${TIMEOUT_SEC} с" >> "$trace"
fi
echo "код возврата: $code" >> "$trace"
exit "$code"
