def по_темам(записи: list, порядок: tuple) -> list:
    """[(тема, пояснение, [записи])] в заданном порядке; хвост — в конце."""
    группы = {}
    for запись in записи:
        группы.setdefault(запись.get("тема") or "прочее", []).append(запись)
    for группа in группы.values():
        группа.sort(key=lambda з: з.get("имя", ""))
    названные = [(т, п, группы.pop(т)) for т, п in порядок if т in группы]
    return названные + [(т, "", г) for т, г in sorted(группы.items())]


ДНИ_НЕДЕЛИ = {"0": "воскресеньям", "1": "понедельникам", "2": "вторникам",
              "3": "средам", "4": "четвергам", "5": "пятницам", "6": "субботам",
              "7": "воскресеньям"}


def крон_словами(крон: str) -> str:
    """Cron-строка задания — словами владельца. Незнакомая форма остаётся как
    есть: лучше сырой cron, чем выдуманная фраза."""
    поля = крон.split()
    if len(поля) != 5:
        return крон                    # @daily и прочие формы — как есть
    мин, час, день, месяц, неделя = поля
    if (мин, час, день, месяц, неделя) == ("*",) * 5:
        return "каждую минуту"
    if мин.startswith("*/") and (час, день, месяц, неделя) == ("*",) * 4:
        return f"каждые {мин[2:]} мин"
    if мин.isdigit() and (час, день, месяц, неделя) == ("*",) * 4:
        return "каждый час" if int(мин) == 0 else f"каждый час в :{int(мин):02d}"
    if not (мин.isdigit() and all(ч.isdigit() for ч in час.split(",")) and месяц == "*"):
        return крон
    время = " и ".join(f"{int(ч):02d}:{int(мин):02d}" for ч in час.split(","))
    if день.isdigit() and неделя == "*":
        return f"{день}-го числа каждого месяца в {время}"
    if день == "*" and неделя in ДНИ_НЕДЕЛИ:
        return f"по {ДНИ_НЕДЕЛИ[неделя]} в {время}"
    if день == "*" and неделя == "*":
        return f"каждые сутки в {время}"
    return крон


def путь_задания(задание: dict) -> str:
    """Файл, который запускает задание: первое слово команды."""
    return (str(задание.get("команда") or "").split() or [""])[0]


def _абзац(текст: str) -> str:
    return " ".join(str(текст).split())


def _механизм(запись: dict, расписания: dict) -> list:
    когда = _абзац(запись["когда"])
    if запись["файл"] in расписания:
        # Время — из system-jobs.yaml, откуда ставится живой cron; «когда» в
        # реестре держит только смысл, иначе две копии расходятся.
        время = "; ".join(расписания[запись["файл"]])
        когда = время if когда == "по расписанию" else f"{время} — {когда}"
    return [
        f"#### {запись['имя']}",
        "",
        f"`{запись['файл']}`",
        "",
        _абзац(запись["роль"]),
        "",
        f"- **Когда работает:** {когда}",
        f"- **Что будет без него:** {_абзац(запись['без_него'])}",
        f"- **Чем проверяется:** {_абзац(запись['проверяется'])}",
        f"- **Что пишет:** {_абзац(запись['пишет'])}",
        "",
    ]


def _раздел(название: str, вступление: list, темы: list, расписания: dict) -> list:
    строки = [f"## {название}", ""] + вступление + [""]
    for тема, пояснение, группа in темы:
        строки.append(f"- **{тема}** — {len(группа)}")
    строки.append("")
    for тема, пояснение, группа in темы:
        строки += [f"### {тема.capitalize()}", ""]
        if пояснение:
            строки += [_абзац(пояснение), ""]
        for запись in группа:
            строки += _механизм(запись, расписания)
    return строки


def собрать(записи: list, задания: list) -> str:
    """Документ целиком. Чистая функция: то же на входе — то же на выходе."""
    расписания: dict = {}
    for задание in задания:
        if задание.get("расписание"):
            расписания.setdefault(путь_задания(задание), []).append(
                крон_словами(задание["расписание"]))
    код = [з for з in записи if з.get("вид") in ВИДЫ_КОДА]
    скилы = [з for з in записи if з.get("вид") == "скил"]
    прочее = [з for з in записи if з not in код and з not in скилы]

    строки = [
        "# Как устроен харнес",
        "",
        "> Этот файл СОБИРАЕТСЯ из `harness/config/mechanisms.yaml` и руками не правится:",
        "> правка попадёт под гейт `scripts/check-registry.py` и исчезнет при",
        "> следующей сборке. Менять нужно реестр, потом выполнить",
        "> `python3 scripts/build-registry-doc.py`.",
        "",
        "Харнес — это обвязка вокруг работы: она сама следит за машиной, "
        "отменяет опасные команды, не даёт выкатить непроверенное и помнит "
        f"правила между сессиями. Всего механизмов — {len(записи)}, и они "
        "делятся надвое.",
        "",
        f"**Код — {len(код)}.** Работает сам: по расписанию, в момент моей "
        "команды или перед записью в репозиторий. Меня не спрашивает.",
        "",
        f"**Скилы — {len(скилы)}.** Это не программы, а инструкции мне: текст "
        "правил, который подгружается в работу, когда наступает его шаг. "
        "Собираются из глав правил, руками не пишутся, вызов каждого "
        "записывается в журнал.",
        "",
    ]
    строки += _раздел(
        f"Код ({len(код)})",
        ["Механизмы, которые работают без меня. Внутри — по темам: от того, что "
         "касается вас напрямую, к внутренней кухне."],
        по_темам(код, ТЕМЫ_КОДА), расписания)
    строки += _раздел(
        f"Скилы ({len(скилы)})",
        ["Инструкции шагов работы. Каждая подгружается в тот момент, когда "
         "наступает её шаг, и её вызов виден в журнале."],
        по_темам(скилы, ТЕМЫ_СКИЛОВ), расписания)
    if прочее:
        строки += _раздел(f"Прочее ({len(прочее)})", [], по_темам(прочее, ()), расписания)
    return "\n".join(строки).rstrip() + "\n"


def main() -> int:
    записи = yaml.safe_load(РЕЕСТР.read_text(encoding="utf-8"))["механизмы"]
    задания = yaml.safe_load(ЗАДАНИЯ.read_text(encoding="utf-8"))["задания"]
    текст = собрать(записи, задания)
    if "--печать" in sys.argv:
        sys.stdout.write(текст)
        return 0
    ДОКУМЕНТ.parent.mkdir(parents=True, exist_ok=True)
    было = ДОКУМЕНТ.read_text(encoding="utf-8") if ДОКУМЕНТ.exists() else None
    ДОКУМЕНТ.write_text(текст, encoding="utf-8")
    состояние = "без изменений" if было == текст else "обновлён"
    print(f"{ДОКУМЕНТ.relative_to(КОРЕНЬ)}: {состояние}, механизмов {len(записи)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
