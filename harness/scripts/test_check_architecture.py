def красный(имя: str, данные: dict, режим: tuple, *предметы: str) -> None:
    """Код ≠ 0, предмет назван, не трейсбек: красный от правила, а не от падения."""
    def судья(код, вывод, _кат):
        нет = [п for п in предметы if п not in вывод]
        итог(имя, код != 0 and not нет and "Traceback" not in вывод,
             f"код {код}, не названо {нет}; {вывод}")
    отложить(данные, режим, судья)


def зелёный(имя: str, данные: dict, режим: tuple, *образцы: str,
            не_в_выводе: tuple = ()) -> None:
    """Код 0, в выводе каждый образец (регэксп), запрещённых имён нет."""
    def судья(код, вывод, _кат):
        нет = [о for о in образцы if not re.search(о, вывод)]
        лишние = [и for и in не_в_выводе if и in вывод]
        итог(имя, код == 0 and not нет and not лишние,
             f"код {код}, нет {нет}, лишние {лишние}; {вывод}")
    отложить(данные, режим, судья)


