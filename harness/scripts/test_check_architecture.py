# Прогонщик: копия сторожа грузится один раз, `main` зовётся на каждый случай.
# Древесный harness.conf у случаев свой, а файл один — пишется перед случаем.
ПРОГОНЩИК = r'''
import contextlib, importlib.util, io, json, os, sys, traceback
from pathlib import Path
м = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
спец = importlib.util.spec_from_file_location("check_architecture", м["сторож"])
сторож = importlib.util.module_from_spec(спец)
спец.loader.exec_module(сторож)
итоги = []
for с in м["случаи"]:
    os.environ.clear()
    os.environ.update(с["окружение"])
    Path(м["древесный"]).write_text(с["древесный"], encoding="utf-8")
    вывод = io.StringIO()
    with contextlib.redirect_stdout(вывод), contextlib.redirect_stderr(вывод):
        try:
            код = сторож.main(с["режим"])
        except сторож.architecture.RegistryError as ошибка:
            print(f"ПРЕТЕНЗИЯ {ошибка}")
            код = 1
        except Exception:
            traceback.print_exc()
            код = 99
    итоги.append([код, вывод.getvalue()])
Path(м["итог"]).write_text(json.dumps(итоги, ensure_ascii=False), encoding="utf-8")
'''

СЛУЧАИ = []        # по порядку записи: раздел (строка) или случай (словарь)


def раздел(название: str) -> None:
    СЛУЧАИ.append(название)


def отложить(данные: dict, режим: tuple, судья) -> None:
    """Случай выкладывается сразу, судится после пакетного прогона."""
    кат, окружение = выложить(данные)
    СЛУЧАИ.append({"кат": кат, "окружение": окружение, "режим": list(режим),
                   "древесный": conf_текст(данные["древесный"]), "судья": судья})


def прогнать_пакетом() -> None:
    """Один процесс на режим; код и вывод — в случай."""
    случаи = [с for с in СЛУЧАИ if isinstance(с, dict)]
    for режим in dict.fromkeys(tuple(с["режим"]) for с in случаи):
        группа = [с for с in случаи if tuple(с["режим"]) == режим]
        манифест, итог_ = ВЕРХ / "манифест.json", ВЕРХ / "итог.json"
        итог_.unlink(missing_ok=True)
        манифест.write_text(json.dumps({
            "сторож": str(ЗАПУСК), "древесный": str(ДРЕВЕСНЫЙ), "итог": str(итог_),
            "случаи": [{к: с[к] for к in ("окружение", "режим", "древесный")} for с in группа],
        }, ensure_ascii=False), encoding="utf-8")
        try:
            ход = subprocess.run([sys.executable, "-c", ПРОГОНЩИК, str(манифест)], env=ЧИСТОЕ,
                                 capture_output=True, text=True, timeout=120, cwd=str(ВЕРХ))
            сбой = f"прогонщик {ход.returncode}: {ход.stdout}{ход.stderr}"
        except subprocess.TimeoutExpired:
            сбой = "предел 120 с"
        итоги = json.loads(итог_.read_text(encoding="utf-8")) if итог_.is_file() else []
        for с, (код, вывод) in zip(группа, итоги or [[125, сбой]] * len(группа)):
            с["код"], с["вывод"] = код, вывод


