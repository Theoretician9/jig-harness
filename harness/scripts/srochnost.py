#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Срочно ли входящее: прервать шаг агента или скопить до рубежа.

Владелец 12.09.2026: «когда идет активная разработка у агента, накидывать ему
задач в разных направлениях не самая лучшая идея, это сбивает процесс <…> llm
видит мои сообщения как факт входящего и первые слова, но не читает содержание
целиком, что снижает влияние на внимание, пока не закончится текущая задача или
если её пнёт хук по ключевому слову».

Правило ОДНО, без частных случаев: **шаг прерывает то, что не работа.**
Вопрос, ответ, согласие, реакция — их ждут, они коротки, они доезжают сразу,
как раньше. Сообщение, несущее РАБОТУ, копится и подаётся одним сортированным
списком на рубеже — если в нём нет слова срочности.

Порядок разбора (первое совпадение решает):
  1. слово срочности из данных     → срочно
  2. прямое слово внимания         → срочно (тот же список, что у очереди)
  3. прямой вопрос «?»             → срочно (ТОН.md: вопрос ждёт ответа)
  4. есть слова работы             → НЕСРОЧНО, копится до рубежа
  5. всё остальное                 → срочно

Слова и переключатели — ДАННЫЕ `harness/config/очередь.yaml` (ключ
«срочность»). Списки слов работы и внимания НЕ дублируются здесь: их читают
`zadachi-iz-kanala.py` и `slovo-vnimaniya.py`, и второй носитель разошёлся бы
с первым молча.

    srochnost.py "<текст владельца>"      # печатает причину, если СРОЧНО
    srochnost.py --разбор "<текст>"       # «срочно|несрочно<таб>причина»
    srochnost.py --замер <каталог>        # доля срочных по архиву сообщений
    srochnost.py --selftest
Код возврата 0 всегда: это прибор, а не гейт.
"""
import os
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))
from konf import корень_дерева  # noqa: E402
from sosed import модуль  # noqa: E402

КОНФИГ = os.environ.get("QUEUE_CONF") or str(
    корень_дерева(__file__) / "harness" / "config" / "очередь.yaml")

# Умолчания — для свежей установки, где файла данных ещё нет: прибор не гейт и
# отказывать ему нечем. Значения те же, что в файле.
ПО_УМОЛЧАНИЮ = {"слова": ["срочно", "останови", "стоп", "сломал", "не работает",
                          "упал", "авария", "не грузится", "отвалил", "горит",
                          "умер", "молчит", "завис"],
                "вопрос_срочен": True, "внимание_срочно": True}


def данные(путь: str | Path | None = None) -> dict:
    """Настройки срочности из данных; нет файла или ключа — умолчания."""
    try:
        всё = yaml.safe_load(Path(путь or КОНФИГ).read_text(encoding="utf-8")) or {}
    except (OSError, yaml.YAMLError):
        всё = {}
    итог = dict(ПО_УМОЛЧАНИЮ)
    итог.update({к: v for к, v in (всё.get("срочность") or {}).items() if v is not None})
    итог["_всё"] = всё
    return итог


def срочно(текст: str, наст: dict | None = None) -> tuple[bool, str]:
    """(срочно ли, причина словами). Причина печатается в журнал канала."""
    наст = наст if наст is not None else данные()
    низ = (текст or "").lower()
    всё = наст.get("_всё") or {}

    for с in наст.get("слова") or []:
        if с in низ:
            return True, f"слово срочности «{с}»"

    if наст.get("внимание_срочно"):
        сл = модуль("slovo-vnimaniya").слово(текст, всё)
        if сл:
            return True, f"прямое слово владельца «{сл}»"

    if наст.get("вопрос_срочен") and "?" in (текст or ""):
        return True, "прямой вопрос — ответа ждут"

    работа = модуль("zadachi-iz-kanala")
    if работа.рабочее(текст or ""):
        return False, "несёт работу — копится до рубежа"

    return True, "не работа (ответ, реакция) — доезжает сразу"


def замер(каталог: str) -> int:
    """Сколько копилось бы, а сколько пинало бы сессию. Судит НАСТОЯЩИЙ архив:
    порог, выбранный без замера, либо молчит всегда, либо пинает всегда."""
    работа = модуль("zadachi-iz-kanala")
    наст = данные()
    тексты = []
    for ф in sorted(Path(каталог).glob("*.txt")):
        т = работа.текст_сообщения(ф)
        if т.strip():
            тексты.append(т)
    копится = [т for т in тексты if not срочно(т, наст)[0]]
    всего = len(тексты) or 1
    print(f"сообщений с текстом: {len(тексты)}")
    print(f"копилось бы до рубежа: {len(копится)} ({100 * len(копится) / всего:.1f}%)")
    print(f"пинало бы сессию сразу: {len(тексты) - len(копится)} "
          f"({100 * (len(тексты) - len(копится)) / всего:.1f}%)")
    return 0


def _selftest() -> int:
    плохо = 0
    наст = данные()

    def проба(имя: str, ждём: bool, текст: str) -> None:
        nonlocal плохо
        вышло, почему = срочно(текст, наст)
        if вышло == ждём:
            print(f"  ок    {имя} → {почему}")
        else:
            print(f"  ПЛОХО {имя}: ждали срочно={ждём}, вышло {вышло} ({почему})")
            плохо = 1

    # БОЛЬНОЙ СЛУЧАЙ, ради которого всё писано: владелец накидывает задачу
    # посреди работы. 12.09.2026 такое сообщение пинало сессию в тот же миг.
    проба("БОЛЬНОЙ СЛУЧАЙ: задача посреди работы НЕ прерывает шаг", False,
          "Надо сделать глубокое исследование и выписать весь список какие "
          "механизмы надо проверить, прежде чем отдавать в пользование")
    проба("вторая задача тем же способом — тоже копится", False,
          "нужно и то и другое, сначала 2, потом 1. добавь в карту")
    # Слово срочности перебивает признак работы: иначе «срочно» нечем сказать.
    проба("слово срочности перебивает работу", True,
          "срочно надо починить карту, она не открывается")
    проба("«останови» будит сразу", True, "останови выкат, я передумал")
    проба("«завис» будит сразу", True, "у тебя завис прогон, сделай заново")
    # Прямое слово владельца — тот же список, что у очереди работ.
    проба("прямое слово «брось» будит сразу", True, "брось это и сделай карту")
    # А отложенная форма приказом не считается — и работой остаётся.
    проба("отложенный приказ остаётся работой", False,
          "после того как закончишь, займись картой, надо её переделать")
    # Не работа — доезжает сразу, как раньше: ответы, согласия, реакции.
    проба("согласие доезжает сразу", True, "да")
    проба("ответ цифрой доезжает сразу", True, "1")
    проба("вопрос доезжает сразу", True, "Всё сделано?")
    проба("реакция доезжает сразу", True, "дошло")
    # Вопрос внутри задачи: ключ данных «вопрос_срочен» включён.
    проба("вопрос внутри задачи будит (ключ вопрос_срочен)", True,
          "надо переделать карту, или ты уже начал?")
    без_вопроса = dict(наст, вопрос_срочен=False)
    вышло, _ = срочно("надо переделать карту, или ты уже начал?", без_вопроса)
    if вышло is False:
        print("  ок    ключ вопрос_срочен=false выключает это правило — данные, не код")
    else:
        print("  ПЛОХО ключ вопрос_срочен=false ничего не изменил")
        плохо = 1
    # Пустое сообщение (снимок без подписи) работой не является.
    проба("пусто — не работа, доезжает сразу", True, "")

    if плохо:
        print("САМОТЕСТ ПРОВАЛЕН")
        return 1
    print("САМОТЕСТ ПРОЙДЕН: 14 путей, первым — больной случай "
          "(задача посреди работы не прерывает шаг)")
    return 0


def main() -> int:
    аргументы = sys.argv[1:]
    if "--selftest" in аргументы:
        return _selftest()
    if "--замер" in аргументы:
        return замер(аргументы[аргументы.index("--замер") + 1])
    разбор = "--разбор" in аргументы
    текст = [а for а in аргументы if not а.startswith("--")]
    текст = текст[0] if текст else ""
    вышло, почему = срочно(текст)
    if разбор:
        print(("срочно" if вышло else "несрочно") + "\t" + почему)
    elif вышло:
        print(почему)
    return 0


if __name__ == "__main__":
    sys.exit(main())
