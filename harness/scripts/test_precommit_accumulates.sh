#!/usr/bin/env bash
# Проба: pre-commit-gate.sh собирает ВСЕ красные гейты прогона и печатает их списком.
#
# Откуда взята. Первый коммит каркаса на новой установке занял пять кругов по ~8 минут:
# хук останавливался на первом провале, провалы шли по одному. Функции хука достаются
# ПАРСИНГОМ его исходника (пустое извлечение — провал), а не копируются сюда.
# Дверь мутаций: PRECOMMIT_UNDER_TEST — хук, который судит проба.
set -u
here=$(cd "$(dirname "$0")" && pwd)
src=${PRECOMMIT_UNDER_TEST:-$here/pre-commit-gate.sh}
fail=0
ok()  { echo "ok:   $1"; }
bad() { echo "FAIL: $1"; fail=1; }
extract() { awk -v f="$1" 'index($0, f "() {")==1 {on=1} on {print} on && /^}$/ {exit}' "$src"; }
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
{
  echo 'set -euo pipefail'
  echo 'LOG_DIR="$1"; GATES_LOG="$1/gates.jsonl"; HEAD_SHA=probe; CHANGED="a"; YELLOW_CODE=77'
  grep -m1 '^GATE_FAILURES=' "$src"
  for f in journal fail подвести гейт; do
    body=$(extract "$f"); [ -n "$body" ] || { echo "FAIL: функция $f не найдена в хуке" >&2; exit 1; }
    echo "$body"
  done
} > "$tmp/lib.sh" || exit 1
grep -q '^GATE_FAILURES=' "$tmp/lib.sh" || { echo "FAIL: накопитель провалов не найден"; exit 1; }

run() { # тело сценария → вывод; код возврата в $RC
  RC=0; OUT=$(bash -c ". '$tmp/lib.sh' '$tmp/log'; $1; echo ДОШЛИ_ДО_КОНЦА" 2>&1) || RC=$?
}
# БОЛЬНОЙ СЛУЧАЙ: два заведомо красных условия подряд, под set -e и через `|| fail`
run 'false || fail "первый_гейт"; false || fail "второй_гейт"; гейт "третий_гейт" bash -c "exit 2"; подвести'
[ "$RC" != 0 ] && ok "два красных: код ненулевой ($RC)" || bad "красные гейты, а код 0"
for g in первый_гейт второй_гейт третий_гейт; do
  grep -q "^  - $g\$" <<<"$OUT" && ok "в итоговом списке есть $g" || bad "в итоговом списке нет $g"
done
grep -q 'красных гейтов 3' <<<"$OUT" && ok "число красных названо" || bad "число красных не названо"
grep -q '"failed":"первый_гейт,второй_гейт,третий_гейт"' "$tmp/log/gates.jsonl" 2>/dev/null \
  && ok "журнал: одна строка fail со всеми именами" || bad "журнал не содержит всех провалов"
# провал не обрывает прогон до итога: после первого fail выполнение шло дальше
grep -q 'ДОШЛИ_ДО_КОНЦА' <<<"$OUT" && bad "после подвести код 0 не должен был дойти до конца" || ok "после красного итога прогон остановлен подвести"
# ЗДОРОВЫЙ: без красных — код 0 и тишина про провалы
run 'гейт "зелёный" true; подвести'
[ "$RC" = 0 ] && ok "без красных код 0" || bad "зелёный прогон дал код $RC"
grep -q 'КОММИТ ОСТАНОВЛЕН' <<<"$OUT" && bad "зелёный прогон печатает остановку" || ok "зелёный прогон без остановки"
# жёлтый (77) — не провал
run 'гейт "жёлтый" bash -c "exit 77"; подвести'
[ "$RC" = 0 ] && ok "жёлтый гейт не краснит" || bad "жёлтый дал код $RC"
[ "$fail" = 0 ] && echo "ВСЁ ЗЕЛЁНОЕ" || echo "КРАСНОЕ"
exit $fail
