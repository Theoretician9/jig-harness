#!/usr/bin/env python3
"""Гейт: задача не исчезает из dev-map.yaml молча.

09.09.2026 я сжимал разросшееся поле `progress` регулярным выражением с флагом
DOTALL. Жадная точка съела всё до последней кавычки в файле — вместе с 88
задачами. Карта осталась валидным YAML, все семь ворот были ЗЕЛЁНЫМИ, и
пропажу поймала только ручная проверка числа id. Это прямое нарушение И-1: не
терять данные.

Перенос задачи в архив законен и обычен (карта упирается в потолок). Поэтому
гейт не запрещает уменьшение, а требует, чтобы каждый исчезнувший id нашёлся в
`docs/dev-map-archive.yaml` — там же, в коммите. Пропал бесследно — красный со
списком имён.

Сравнивается ИНДЕКС с HEAD (К-4): коммитится индекс.

Запуск: список staged-файлов на stdin (как прочие гейты pre-commit).
Самотест — `--selftest`.
"""
from __future__ import annotations

import collections
import pathlib
import re
import subprocess
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
КАРТА = "dev-map.yaml"
АРХИВ = "docs/dev-map-archive.yaml"
# Задача карты: «      - id: <имя>» на своём уровне отступа. Регулярное
# выражение, а не yaml.safe_load: гейт обязан работать и на файле, который
# правка сломала, — именно тогда он и нужен.
ЗАДАЧА = re.compile(r"^\s+- id:\s*(\S+)\s*$", re.MULTILINE)


def _git(*аргументы: str) -> str | None:
    """Вывод git — или None, если git не ответил.

    «Не прочитали» и «пусто» — разные ответы: до 14.09.2026 отказ отдавался
    пустой строкой, прежняя карта выглядела отсутствующей, и гейт печатал
    «сверять не с чем» с кодом 0 — то есть сторож И-1 зеленел на сбое.
    """
    из_git = subprocess.run(["git", "-C", str(КОРЕНЬ), *аргументы],
                            capture_output=True)
    return из_git.stdout.decode("utf-8", "replace") if из_git.returncode == 0 else None


def перечень(текст: str) -> list[str]:
    """Все id по порядку — с повторами: дубль id тоже порча карты."""
    return ЗАДАЧА.findall(текст)


def задачи(текст: str) -> set[str]:
    return set(перечень(текст))


def дубли(текст: str) -> list[str]:
    счёт = collections.Counter(перечень(текст))
    return sorted(ид for ид, n in счёт.items() if n > 1)


def _не_прочитано(что: str) -> int:
    print(f"\n[карта] ✗ НЕ ПРОЧИТАНО: git не отдал {что}")
    print("Сверять нечем, а «нечем судить» это не «нарушений нет»: сторож И-1")
    print("молчал бы ровно там, где карта могла потерять задачи.")
    return 1


def проверить(изменённые: list[str]) -> int:
    if КАРТА not in изменённые:
        print("[карта] dev-map.yaml не в коммите — сверять нечего")
        return 0
    текст = _git("show", f":{КАРТА}")
    if текст is None:
        return _не_прочитано(f":{КАРТА}")
    повторы = дубли(текст)
    if повторы:
        print(f"\n[карта] ✗ ОДИН id ВСТРЕЧАЕТСЯ ДВАЖДЫ: {len(повторы)}")
        for ид in повторы[:20]:
            print(f"    {ид}")
        print("\nДва блока с одним id — не удвоение задачи, а её РАСЩЕПЛЕНИЕ:")
        print("статусы у них разные, и кто читает карту, тот берёт свой экземпляр.")
        print("11.09.2026 так разошлась hr.память-по-областям: один блок test с")
        print("тремя закрытыми пунктами, второй — plan с пустым списком; пропажи")
        print("не было, и этот же гейт молчал, потому что считал id множеством.")
        return 1
    прежняя = _git("show", f"HEAD:{КАРТА}")
    if прежняя is None and _git("rev-parse", "--git-dir") is not None:
        # git жив, а прежней карты нет: либо это первый коммит карты, либо
        # коммитов нет вовсе (свежая установка). И то и другое законно —
        # красным должен быть только сбой самого git.
        прежняя = ""
    if прежняя is None:
        return _не_прочитано(f"HEAD:{КАРТА}")
    было = задачи(прежняя)
    стало = задачи(текст)
    if not было:
        print("[карта] прежней версии нет (первый коммит карты) — сверять не с чем")
        return 0
    пропали = было - стало
    if not пропали:
        print(f"[карта] задач {len(стало)}, ни одна не потерялась")
        return 0
    в_архиве = (задачи(_git("show", f":{АРХИВ}") or "")
                | задачи(_git("show", f"HEAD:{АРХИВ}") or ""))
    бесследно = sorted(пропали - в_архиве)
    перенесены = sorted(пропали & в_архиве)
    if перенесены:
        print(f"[карта] перенесены в архив ({len(перенесены)}): "
              + ", ".join(перенесены[:5]) + ("…" if len(перенесены) > 5 else ""))
    if not бесследно:
        print(f"[карта] задач {len(стало)}, все исчезнувшие нашлись в архиве")
        return 0
    print(f"\n[карта] ✗ ЗАДАЧИ ИСЧЕЗЛИ БЕССЛЕДНО: {len(бесследно)}")
    for ид in бесследно[:20]:
        print(f"    {ид}")
    if len(бесследно) > 20:
        print(f"    … и ещё {len(бесследно) - 20}")
    print("\nПеренос в docs/dev-map-archive.yaml законен — тогда id обязан быть")
    print("ТАМ, в этом же коммите. Пропажа без переноса — потеря данных (И-1).")
    print("09.09.2026 так исчезли 88 задач: жадное регулярное выражение съело")
    print("кусок файла, YAML остался валидным, и все ворота были зелёными.")
    return 1


def _selftest() -> int:
    плохо = 0

    def проба(имя: str, ждём: set[str], текст: str) -> None:
        nonlocal плохо
        было = задачи(текст)
        if было == ждём:
            print(f"  ок    {имя}")
        else:
            print(f"  ПЛОХО {имя}: ждали {ждём}, нашли {было}")
            плохо = 1

    # БОЛЬНОЙ СЛУЧАЙ 09.09.2026: после жадной правки в файле осталась горстка.
    # Направление тоже считается: его пропажа уносит все задачи под ним.
    проба("БОЛЬНОЙ СЛУЧАЙ: карта после жадной правки — задач почти нет",
          {"harness", "pr.один"},
          "lines:\n  - id: harness\n    tasks:\n      - id: pr.один\n")
    проба("обычная карта: задачи и направление считаются все",
          {"harness", "pr.один", "pr.два"},
          "lines:\n  - id: harness\n    tasks:\n"
          "      - id: pr.один\n        status: test\n"
          "      - id: pr.два\n        status: plan\n")
    проба("id внутри текста поля — не задача", set(),
          '        summary: "перенос задачи - id: pr.лишний внутри текста"\n')
    проба("пустой файл", set(), "")

    def проба_дублей(имя: str, ждём: list[str], текст: str) -> None:
        nonlocal плохо
        нашли = дубли(текст)
        if нашли == ждём:
            print(f"  ок    {имя}")
        else:
            print(f"  ПЛОХО {имя}: ждали {ждём}, нашли {нашли}")
            плохо = 1

    # БОЛЬНОЙ СЛУЧАЙ 11.09.2026: блок задачи вставлен вторым разом, статусы
    # разошлись (test с закрытыми пунктами против plan с пустыми), и гейт
    # молчал — он считал id множеством.
    проба_дублей("БОЛЬНОЙ СЛУЧАЙ: задача записана дважды с разными статусами",
                 ["hr.память"],
                 "lines:\n  - id: harness\n    tasks:\n"
                 "      - id: hr.память\n        status: test\n"
                 "      - id: pr.один\n        status: plan\n"
                 "      - id: hr.память\n        status: plan\n")
    проба_дублей("здоровая карта дублей не даёт", [],
                 "lines:\n  - id: harness\n    tasks:\n"
                 "      - id: pr.один\n      - id: pr.два\n")
    if плохо:
        print("САМОТЕСТ ПРОВАЛЕН")
        return 1
    if _проба_отказа_git() != 0:
        return 1
    if _проба_свежей_установки() != 0:
        return 1
    print("САМОТЕСТ ПРОЙДЕН: 8 путей, больной случай первым в каждой паре")
    return 0


def _проба_свежей_установки() -> int:
    """На свежей установке гейт молчит: коммитов нет — это не сбой git.

    Здоровый случай рядом с больным обязателен: отличать «git умер» от «в
    HEAD ещё ничего нет» гейт обязан сам, иначе первый же коммит новой машины
    встанет, а краснеющий без причины сторож отключают.
    """
    import subprocess as подпроцесс
    import tempfile
    with tempfile.TemporaryDirectory() as тмп:
        дерево = pathlib.Path(тмп)
        (дерево / "scripts").mkdir()
        (дерево / "scripts" / pathlib.Path(__file__).name).write_bytes(
            pathlib.Path(__file__).read_bytes())
        (дерево / КАРТА).write_text(
            "lines:\n  - id: harness\n    tasks:\n"
            "      - id: hr.проба\n        status: plan\n", encoding="utf-8")
        подпроцесс.run(["git", "init", "-q", "."], cwd=дерево, check=True)
        подпроцесс.run(["git", "add", КАРТА], cwd=дерево, check=True)
        итог = подпроцесс.run(
            [sys.executable, str(дерево / "scripts" / pathlib.Path(__file__).name)],
            input=f"{КАРТА}\n", capture_output=True, text=True, cwd=дерево)
    if итог.returncode == 0 and "первый коммит карты" in итог.stdout:
        print("  ок    свежая установка: коммитов ещё нет — гейт молчит")
        return 0
    print(f"  ПЛОХО свежая установка покраснела: код {итог.returncode}, "
          f"вывод «{итог.stdout.strip()[:120]}»")
    return 1


def _проба_отказа_git() -> int:
    """Гейт краснеет, когда git не отдал карту, и называет ПРИЧИНУ."""
    sys.path.insert(0, str(КОРЕНЬ / "scripts" / "lib"))
    from proba_git import гейт_краснеет_без_git
    return гейт_краснеет_без_git(__file__, f"{КАРТА}\n", "НЕ ПРОЧИТАНО")


def main() -> int:
    if "--selftest" in sys.argv[1:]:
        return _selftest()
    return проверить([с.strip() for с in sys.stdin if с.strip()])


if __name__ == "__main__":
    sys.exit(main())
