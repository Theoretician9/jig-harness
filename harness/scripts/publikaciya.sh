say "замок 1 · ворота зелёные"

# ── Замок 2: согласие владельца ИМЕННО на публикацию ───────────────────────
REFUSAL=$(python3 "$PROJECT_DIR/scripts/deploy_guard.py" --действие публикация --только-согласие $([ "$CHECK_ONLY" = 1 ] && echo --не-тратить) 2>&1) || true
