def _зов(действие: str, *ключи: str) -> tuple[object, str]:
    """main() ворот (в этом процессе): (код, вывод). Исключение — тоже ответ."""
    прежний_argv, sys.argv = sys.argv, ["deploy_guard.py", "--действие", действие, *ключи]
    g._ПРЕДМЕТ.clear()
    g.ПУШ = g.ВЫКАТ = g.ПУБЛИКАЦИЯ = None
    g.МОМЕНТ_СВЕЖЕСТИ = None
    вывод = io.StringIO()
    try:
        with contextlib.redirect_stdout(вывод), contextlib.redirect_stderr(вывод):
            try:
                код = g.main()
            except SystemExit as выход:
                код = выход.code if isinstance(выход.code, int) else 1
            except Exception as беда:               # noqa: BLE001
                код = f"исключение {type(беда).__name__}: {беда}"
    finally:
        sys.argv = прежний_argv
    return код, вывод.getvalue()


