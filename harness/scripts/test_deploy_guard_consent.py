# ── Кого спрашивать: своя ручка на каждое действие ─────────────────────────
# Владелец 11.09.2026: «вообще я хочу чтобы это автоматически происходило» —
# про отправку в репозиторий. Находки ревью C1/C2 того же дня: решал ОДИН ключ
# AUTONOMY, и «автомат» снимал согласие разом с выката, отправки, публикации И
# СНОСА БАЗЫ — то есть переключатель на панели стал бы веб-выключателем И-1.
# Теперь ключ свой у каждого действия, а снос базы ручки не имеет вовсе.
КЛЮЧ_ДЕЙСТВИЯ_ИМЕНА = set(g.КЛЮЧ_ДЕЙСТВИЯ.values())
КЛЮЧИ = [
    # (ключи механики, действие, ждём ли вопрос владельцу, чем случай важен)
    ({"PUSH_NEEDS_OWNER": "0"}, "push", False,
     'отправка идёт сама — прямое слово владельца'),
    ({"PUSH_NEEDS_OWNER": "1"}, "push", True,
     'владелец вернул вопрос про отправку'),
    ({"PUSH_NEEDS_OWNER": "0"}, "deploy", True,
     'БОЛЬНОЙ СЛУЧАЙ: свободная отправка НЕ открывает выкат'),
    ({"DEPLOY_NEEDS_OWNER": "0"}, "deploy", False,
     'выкат отпущен отдельной ручкой'),
    ({"DEPLOY_NEEDS_OWNER": "0"}, "dropdb", True,
     'БОЛЬНОЙ СЛУЧАЙ: отпущенный выкат НЕ открывает снос базы (И-1)'),
    ({"DEPLOY_NEEDS_OWNER": "0", "PUSH_NEEDS_OWNER": "0",
      "PUBLISH_NEEDS_OWNER": "0"}, "dropdb", True,
     'БОЛЬНОЙ СЛУЧАЙ: снос базы спрашивает всегда, ручки у него нет'),
    ({"PUBLISH_NEEDS_OWNER": "0"}, "публикация", False,
     'публикация отпущена своей ручкой'),
    ({}, "push", True, 'ключа нет — спрашиваем: старый конфиг не смеет открывать молча'),
    ({}, "deploy", True, 'ключа нет — спрашиваем'),
    ({}, "публикация", True, 'ключа нет — спрашиваем'),
]
for ключи, действие, ждём, почему in КЛЮЧИ:
    # Пустой словарь означает «ключа в конфиге НЕТ» — значит его надо убрать, а
    # не наложить пустоту поверх боевого конфига, где ключ уже прописан
    # (иначе путь «ключа нет» молча проверял бы обратное).
    основа = {к: з for к, з in g.МЕХАНИКА.items() if к not in КЛЮЧ_ДЕЙСТВИЯ_ИМЕНА}
    прежние, g.МЕХАНИКА = g.МЕХАНИКА, dict(основа, **ключи)
    try:
        вышло = g.нужно_согласие(действие)
    finally:
        g.МЕХАНИКА = прежние
    if вышло is ждём:
        путь_ок(f'ключи {ключи or "пусто"} · {действие} → спрашивать={вышло} · {почему}')
    else:
        путь_плохо(f'ключи {ключи or "пусто"} · {действие} → спрашивать={вышло}, '
                   f'ждали {ждём} · {почему}')

# AUTONOMY больше НЕ снимает согласие со сноса базы: улика C1 — проверка режима
# стояла первой строкой и выходила до разбора действия.
прежние, g.КОНФИГ = g.КОНФИГ, dict(g.КОНФИГ, AUTONOMY="full")
try:
    вышло = g.нужно_согласие("dropdb")
finally:
    g.КОНФИГ = прежние
if вышло is True:
    путь_ок('БОЛЬНОЙ СЛУЧАЙ: AUTONOMY=full не открывает снос базы')
else:
    путь_плохо('AUTONOMY=full открыл снос базы — это веб-выключатель И-1')

# Отпущенное действие не спрашивает согласия, но ворота продолжают смотреть
# занятость: ключ отменяет ВОПРОС владельцу, а не защиту от чужого выката.
прежние, g.МЕХАНИКА = g.МЕХАНИКА, dict(g.МЕХАНИКА, PUSH_NEEDS_OWNER="0")
try:
    if g.нет_согласия("push") is None:
        путь_ок('отпущенная отправка не требует записи согласия')
    else:
        путь_плохо('отпущенная отправка всё равно потребовала «да»')
finally:
    g.МЕХАНИКА = прежние

# Порог обязан быть осмысленным ЧИСЛОМ, а не «когда-нибудь»: мутация в
# 99999999 минут — это отсутствие правила, записанное цифрой.
