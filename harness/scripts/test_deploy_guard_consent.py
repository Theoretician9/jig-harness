# ── Свежесть согласия: одно «да» действует час, а не вечно ──────────────────
# Мутационная проба 10.09.2026: срок CONFIRM_MAX_AGE_MIN подняли до
# 99999999 — и ни один путь этого не заметил. Признак согласия проверялся
# подробно, а ПРОТУХАНИЕ — единственное, что отделяет «владелец разрешил
# сейчас» от «владелец разрешал когда-то», — не проверял никто.
import json
import tempfile
import time
from pathlib import Path


def _с_журналом(записи, действие="deploy", спрашивали="сам", повторов=1):
    """Ответ ворот при заданном журнале. `спрашивали` — что ворота ждали:
    «сам» значит смоделировать отказ до того (так и бывает в жизни).
    `повторов` — сколько раз подряд спросить: одно «да» обязано сработать раз."""
    with tempfile.TemporaryDirectory() as tmp:
        (Path(tmp) / "confirmations.jsonl").write_text(
            "".join(json.dumps(з, ensure_ascii=False) + "\n" for з in записи),
            encoding="utf-8")
        прежний, g.LOG_DIR = g.LOG_DIR, Path(tmp)
        try:
            предмет = действие if спрашивали == "сам" else спрашивали
            if предмет:
                (Path(tmp) / "согласие.json").write_text(json.dumps(
                    {"ожидание": {"действие": предмет, "ts": time.time()}}),
                    encoding="utf-8")
            ответ = None
            for _ in range(повторов):
                ответ = g.нет_согласия(действие)
            return ответ
        finally:
            g.LOG_DIR = прежний


