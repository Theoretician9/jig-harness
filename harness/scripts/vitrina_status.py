#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Кто из названных задач НЕ готов к витрине — один разбор на замок и пробу.

Замок 3 публикации (`scripts/publikaciya.sh`) держит И-4: в публичную ветку
уходит только то, что подтверждено. Подтверждений два, и оба законны:

* `done` — слово владельца;
* `принято` — доказательство МАШИНЫ: приёмка (`scripts/priyomka.py`) выполнила
  команду из карточки и увидела в выводе то, что карточка обещала.

Пока замок знал одно «done», машинно доказанная задача всё равно держала
витрину: два механизма говорили об одном разными словами, и сильнее оказывался
тот, что о доказательстве не знает (живой отказ публикации 14.09.2026).
Владелец 11.09.2026: «Я не хочу лично все проверять, в этом и смысл, надо
только то, что не может проверить система».

Разбор живёт отдельным файлом, потому что его зовут двое: замок в бою и проба
в самотесте. Вписанный в оболочку, он был бы доступен только замку, а проба
судила бы свою копию — и починка в одной копии не дошла бы до второй.

Вход — окружение: DEVMAP (карта), DEVMAP_ARCHIVE (архив, необязателен),
IDS (id через пробел). Выход — по строке на задачу, которая витрину держит.
Самотест — `--selftest`.
"""
from __future__ import annotations

import os
import sys

ЗАКРЫТЫЕ = {"done", "принято"}


def задачи(узел):
    """Все карточки дерева карты: у карточки есть и id, и статус."""
    if isinstance(узел, dict):
        if "id" in узел and "status" in узел:
            yield узел
        for значение in узел.values():
            yield from задачи(значение)
    elif isinstance(узел, list):
        for значение in узел:
            yield from задачи(значение)


def держат_витрину(карты: list, ид: list[str]) -> list[str]:
    """Строки про задачи, которые публиковать нельзя, — в порядке запроса."""
    по_id = {з["id"]: з for карта in карты for з in задачи(карта)}
    беды = []
    for ид_задачи in ид:
        задача = по_id.get(ид_задачи)
        if задача is None:
            беды.append(f"{ид_задачи} (в карте нет)")
        elif (задача.get("status") not in ЗАКРЫТЫЕ
                and задача.get("owner_testable") is not False):
            беды.append(f"{ид_задачи} (статус {задача.get('status')} — "
                        f"ждёт проверки владельцем)")
    return беды


def _карты() -> list:
    import yaml
    пути = [os.environ["DEVMAP"]]
    # Карта И архив: задачи уезжают в архив по мере роста карты, статус от
    # этого не меняется. Искать только в карте — отказывать зря на всём старом.
    архив = os.environ.get("DEVMAP_ARCHIVE")
    if архив and os.path.exists(архив):
        пути.append(архив)
    return [yaml.safe_load(open(п, encoding="utf-8")) for п in пути]


def _selftest() -> int:
    плохо = 0
    карта = {"lines": [{"id": "harness", "tasks": [
        {"id": "hr.принято", "status": "принято"},
        {"id": "hr.done", "status": "done"},
        {"id": "hr.test", "status": "test"},
        {"id": "hr.test-без-владельца", "status": "test", "owner_testable": False},
    ]}]}
    случаи = [
        # БОЛЬНОЙ СЛУЧАЙ первым: до 14.09.2026 машинно доказанная задача
        # держала витрину наравне с непроверенной.
        ("БОЛЬНОЙ СЛУЧАЙ: «принято» витрину не держит", ["hr.принято"], 0),
        ("«test» держит — его никто не доказал", ["hr.test"], 1),
        ("«done» не держит — слово владельца", ["hr.done"], 0),
        ("«test» с owner_testable: false не держит", ["hr.test-без-владельца"], 0),
        ("задачи нет в карте — держит, это не молчание", ["hr.нет-такой"], 1),
    ]
    for зачем, ид, ждём in случаи:
        вышло = len(держат_витрину([карта], ид))
        if вышло == ждём:
            print(f"  ок    {зачем}")
        else:
            print(f"  ПЛОХО {зачем}: держат {вышло}, ждали {ждём}")
            плохо = 1
    if плохо:
        print("САМОТЕСТ ПРОВАЛЕН")
        return 1
    print(f"САМОТЕСТ ПРОЙДЕН: {len(случаи)} путей, больной случай первым")
    return 0


def main() -> int:
    if "--selftest" in sys.argv[1:]:
        return _selftest()
    for строка in держат_витрину(_карты(), os.environ.get("IDS", "").split()):
        print(строка)
    return 0


if __name__ == "__main__":
    sys.exit(main())
