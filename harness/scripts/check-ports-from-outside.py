#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Какие порты машины ОТКРЫТЫ из интернета — замер с ЧУЖИХ адресов.

СЛУЧАЙ (03.10.2026). «Порт открыт снаружи» проверялся с ЭТОЙ ЖЕ машины на её
внешний адрес. Такой пакет в интернет не выходит: ядро заворачивает его
локально, и ответ не доказывает ни «открыто», ни «закрыто». На этом замере
держался вывод о дыре в соседнем проекте — вывод оказался верным, но замер
был негодный, и это важнее самой дыры.

Чужой адрес взять неоткуда — машина одна. Поэтому спрашиваются узлы
check-host.net: три страны, каждая делает TCP-подключение со своего адреса.
Один дозвонившийся узел значит ОТКРЫТО; «закрыто» — только когда не дозвонился
НИ ОДИН, и при этом каждый узел ответил. Молчание узлов — третий исход
«не смог измерить», а не зелень ([[unreadable-source-turns-check-green]]).

Что судится: порт, слушающий НЕ на 127.0.0.1 (их список берётся у ядра —
функция `слушатели` соседнего прибора), плюс порты, объявленные открытыми.
Открытый необъявленный — находка. Объявленный, но закрытый — тоже находка:
значит сайт снаружи не отвечает.

Объявленное — ДАННЫЕ: ключ PORTS_EXPECTED_OPEN в harness.conf.

    check-ports-from-outside.py            # замер по машине
    check-ports-from-outside.py --selftest # пробы, сеть не трогается
Код возврата: 0 — наружу открыто ровно объявленное; 1 — есть находка;
77 — измерить не удалось (узлы молчат, нет адреса, нет списка слушателей).
"""
from __future__ import annotations

import json
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))
import config as конф                                    # noqa: E402

НЕ_ПРИМЕНИМО = 77
УЗЛОВ = 3
СЛУЖБА = "https://check-host.net"
ЖДАТЬ_СЕКУНД = 40
ИМЯ_ПРИБОРА = "harness-port-check/1.0"


def _слушатели_наружу() -> list[int]:
    """Порты, слушающие не на локальном адресе. Соседний прибор — источник.

    Импорт по пути, а не `import`: в имени файла дефис, и обычный импорт его
    не возьмёт. Переписывать соседа ради этого значило бы завести вторую копию
    разбора /proc/net/tcp — две копии одного правила расходятся молча.
    """
    import importlib.util
    путь = Path(__file__).resolve().parent / "check-external-surface.py"
    спец = importlib.util.spec_from_file_location("внешняя_поверхность", путь)
    if спец is None or спец.loader is None:
        return []
    модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(модуль)
    return sorted({з["порт"] for з in модуль.слушатели() if модуль.наружу(з)})


def внешний_адрес() -> str:
    """IPv4-адрес, с которого машина выходит в сеть. Пусто — спросить некого."""
    try:
        вывод = subprocess.run(["ip", "-o", "route", "get", "1.1.1.1"],
                               capture_output=True, text=True, timeout=5)
    except (OSError, subprocess.SubprocessError):
        return ""
    if вывод.returncode != 0:
        return ""
    поля = вывод.stdout.split()
    return поля[поля.index("src") + 1] if "src" in поля else ""


def _запрос(адрес: str) -> dict | None:
    """JSON службы или None. «Не ответила» ≠ «ответила пусто».

    Имя у запроса своё: без заголовка User-Agent питон ходит как «Python-urllib»,
    и Cloudflare службы отвечает 403 «доступ по подписи браузера». Первый живой
    прогон 03.10.2026 получил «не измерен» по всем семи портам — отказ был
    честным, но причина молчала, поэтому она теперь печатается.
    """
    запрос = urllib.request.Request(адрес, headers={
        "Accept": "application/json", "User-Agent": ИМЯ_ПРИБОРА})
    try:
        with urllib.request.urlopen(запрос, timeout=20) as ответ:
            return json.loads(ответ.read().decode("utf-8"))
    except (urllib.error.URLError, OSError, ValueError, TimeoutError) as беда:
        print(f"  служба не ответила: {type(беда).__name__}: {беда}")
        return None


def приговор_порта(ответы: dict) -> str:
    """«открыт» / «закрыт» / «не измерен» по ответам узлов.

    Один дозвонившийся узел значит ОТКРЫТ: дыра есть, даже если двое других
    не дошли. «Закрыт» требует ответа от КАЖДОГО узла — иначе это молчание,
    а молчание в замере безопасности выдавать за «закрыто» нельзя.
    """
    if not ответы:
        return "не измерен"
    отвечено = 0
    for итоги in ответы.values():
        if итоги is None:
            continue
        отвечено += 1
        for итог in итоги:
            if isinstance(итог, dict) and "time" in итог:
                return "открыт"
    return "закрыт" if отвечено == len(ответы) else "не измерен"


def дозвонившиеся(ответы: dict) -> list[str]:
    """Узлы, у которых подключение удалось, — с именем и временем.

    Нужны в отчёте, а не только внутри приговора: один узел из трёх объявляет
    порт открытым, и это правильно для безопасности, но проверить такой
    приговор можно только зная, КТО дозвонился. Живой прогон 03.10.2026 дал
    «6380 открыт» по одному узлу, а повтор с четырёх узлов — «закрыт»: без
    имени узла разницу не разобрать.
    """
    итог = []
    for узел, итоги in (ответы or {}).items():
        for итог_узла in итоги or []:
            if isinstance(итог_узла, dict) and "time" in итог_узла:
                итог.append(f"{узел} за {итог_узла['time']} с")
    return итог


def находки(измерено: dict[int, str], объявлено: set[int]) -> list[str]:
    """Расхождения между замером и объявленным. Обе стороны названы отдельно:
    «открыт лишний» и «объявленный не отвечает» — разные беды, и сливать их в
    одно число значит потерять одну из них ([[inequality-merges-two-opposite-cases]])."""
    итог = []
    for порт, состояние in sorted(измерено.items()):
        if состояние == "открыт" and порт not in объявлено:
            итог.append(f"порт {порт} ОТКРЫТ из интернета, а наружу не объявлен")
        elif состояние == "закрыт" and порт in объявлено:
            итог.append(f"порт {порт} объявлен открытым, но снаружи НЕ отвечает")
    return итог


def измерить(адрес: str, порт: int) -> dict:
    """Ответы узлов по одному порту. Пустой словарь — служба не ответила."""
    пуск = _запрос(f"{СЛУЖБА}/check-tcp?host={адрес}%3A{порт}&max_nodes={УЗЛОВ}")
    if not пуск or not пуск.get("request_id"):
        return {}
    ссылка = f"{СЛУЖБА}/check-result/{пуск['request_id']}"
    узлов = len(пуск.get("nodes") or {}) or УЗЛОВ
    край = time.monotonic() + ЖДАТЬ_СЕКУНД
    ответы: dict = {}
    while time.monotonic() < край:
        time.sleep(4)
        ответы = _запрос(ссылка) or {}
        if ответы and sum(1 for з in ответы.values() if з is not None) >= узлов:
            break
    return ответы


# ── самотест: сеть не трогается, судятся разбор и приговор ────────────────
def _самотест() -> int:
    плохо = 0

    def проба(имя, ждём, вышло):
        nonlocal плохо
        if ждём == вышло:
            print(f"  ок    {имя}")
        else:
            print(f"  ПЛОХО {имя}: ждали «{ждём}», вышло «{вышло}»")
            плохо += 1

    проба("три отказа — закрыт", "закрыт", приговор_порта(
        {"de": [{"error": "Connection timed out"}],
         "ru": [{"error": "Connection timed out"}],
         "se": [{"error": "Connection timed out"}]}))
    # БОЛЬНОЙ: один дозвонившийся — это ОТКРЫТО. Требовать единогласия значило
    # бы объявить дыру закрытой из-за двух недошедших узлов.
    проба("БОЛЬНОЙ: дозвонился один узел из трёх — открыт", "открыт", приговор_порта(
        {"de": [{"error": "Connection timed out"}],
         "ru": [{"time": 0.07, "address": "193.0.0.1"}],
         "se": [{"error": "Connection timed out"}]}))
    # БОЛЬНОЙ: узел ещё не ответил (null). Это «не измерен», а не «закрыт» —
    # иначе замер безопасности зеленеет от медленной службы.
    проба("БОЛЬНОЙ: узел молчит — не измерен, а не закрыт", "не измерен", приговор_порта(
        {"de": [{"error": "Connection timed out"}], "ru": None, "se": None}))
    проба("БОЛЬНОЙ: служба не ответила вовсе — не измерен", "не измерен",
          приговор_порта({}))

    проба("открытый необъявленный — находка", 1,
          len(находки({6380: "открыт"}, {22, 80, 443})))
    # БОЛЬНОЙ: объявленный, но закрытый — тоже находка, другой стороной.
    # Прибор, который молчит об этом, не заметил бы упавший снаружи сайт.
    проба("БОЛЬНОЙ: объявленный не отвечает — находка", "не отвечает",
          "не отвечает" if "НЕ отвечает" in (находки({443: "закрыт"}, {443}) or [""])[0]
          else "промолчал")
    проба("объявленный и открытый — тишина", 0,
          len(находки({443: "открыт", 22: "открыт"}, {22, 443})))
    # БОЛЬНОЙ: «не измерен» не находка и не зелень — он обязан дойти до
    # исхода 77 выше по течению, а не раствориться здесь.
    проба("БОЛЬНОЙ: неизмеренный порт находкой не считается", 0,
          len(находки({6380: "не измерен"}, set())))
    # БОЛЬНОЙ: приговор «открыт» обязан называть узел. Без имени проверить
    # его нечем, а один узел из трёх решает приговор.
    проба("дозвонившийся узел назван в отчёте", ["ru за 0.07 с"], дозвонившиеся(
        {"de": [{"error": "Connection timed out"}],
         "ru": [{"time": 0.07, "address": "193.0.0.1"}]}))
    проба("никто не дозвонился — список пуст", [], дозвонившиеся(
        {"de": [{"error": "Connection timed out"}]}))

    print("самотест: всё зелено" if not плохо else f"самотест: красных {плохо}")
    return 1 if плохо else 0


def главное() -> int:
    конфиг = конф.из_файла(конф.путь_harness_conf())
    объявлено = {int(ч) for ч in
                 (конфиг.get("PORTS_EXPECTED_OPEN", "") or "").replace(" ", "").split(",") if ч}

    адрес = внешний_адрес()
    if not адрес:
        print("не применимо: не узнал внешний IPv4-адрес машины")
        return НЕ_ПРИМЕНИМО
    порты = sorted(set(_слушатели_наружу()) | объявлено)
    if not порты:
        print("не применимо: ни одного слушателя наружу и ничего не объявлено")
        return НЕ_ПРИМЕНИМО

    print(f"адрес {адрес}; спрашиваю {УЗЛОВ} чужих узла по {len(порты)} портам")
    измерено: dict[int, str] = {}
    for порт in порты:
        ответы = измерить(адрес, порт)
        измерено[порт] = приговор_порта(ответы)
        кто = дозвонившиеся(ответы)
        print(f"  {порт}: {измерено[порт]}" + (f" — дозвонились: {', '.join(кто)}" if кто else ""))

    немые = [п for п, с in измерено.items() if с == "не измерен"]
    если_находки = находки(измерено, объявлено)
    for строка in если_находки:
        print(f"НАХОДКА: {строка}")
    if немые:
        print(f"не применимо: узлы не ответили по портам {немые} — замер неполон")
        return НЕ_ПРИМЕНИМО
    if если_находки:
        return 1
    print(f"наружу открыто ровно объявленное: {sorted(объявлено)}")
    return 0


if __name__ == "__main__":
    sys.exit(_самотест() if "--selftest" in sys.argv else главное())
