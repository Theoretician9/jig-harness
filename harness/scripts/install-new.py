#!/usr/bin/env python3
"""Доустановка нового после обновления: расписания и периоды меток.

Откуда взято. Находка C7 разбора спеки обновления (11.09.2026): обновление
привозит НОВЫЙ демон, а он без строки cron и без периода метки мёртв и
незаметен — сторож меток не знает, что его ждать. До этого такие строки
дописывались руками, то есть правило держалось на том, что кто-то помнит.

Два правила, из которых всё остальное следует:

* **только добавляем.** Чужие строки расписания принадлежат машине, а не
  харнесу; значение периода, выставленное владельцем, не перетирается
  умолчанием из данных;
* **повторный прогон ничего не меняет.** Доустановка идёт после каждого
  обновления, и «добавить ещё раз» означало бы дубли в cron.

Что ставить — ДАННЫЕ: `harness/config/system-jobs.yaml`.

Прогон:
    python3 scripts/install-new.py            # доустановить недостающее
    python3 scripts/install-new.py --показать # что не хватает, ничего не менять
"""
