def перенести_файлы(корень: Path, карта: dict, только_счёт: bool = False) -> list:
    """Переселить файлы проекта на новые имена; вернуть старые имена переселённых.

    Переселяются журналы, куда только дописывают: если новый файл уже завёлся,
    недостающие строки старого дописываются в него, а не теряются.
    """
    перенесено = []
    for старое, новое in карта.items():
        старый, новый = Path(корень) / старое, Path(корень) / новое
        if not старый.is_file():
            continue
        перенесено.append(старое)
        if только_счёт:
            continue
        if not новый.exists():
            старый.rename(новый)
            continue
        текст_нового = новый.read_text(encoding="utf-8")
        есть = текст_нового.splitlines()
        недостаёт = [с for с in старый.read_text(encoding="utf-8").splitlines() if с not in есть]
        if недостаёт:
            with новый.open("a", encoding="utf-8") as fh:
                # Цель без завершающего перевода строки склеила бы свою
                # последнюю строку с первой переезжающей, и построчный читатель
                # потерял бы ОБЕ записи молча (ревью F-gen-07 14.10.2026).
                if текст_нового and not текст_нового.endswith("\n"):
                    fh.write("\n")
                fh.write("".join(с + "\n" for с in недостаёт))
        старый.unlink()
    return перенесено


def переименовать_метки(конфиг: str, карта: dict) -> str:
    """HEARTBEAT_PERIODS со старыми именами меток, заменёнными на новые.

    Демон, сменивший имя метки, пишет новую, а период в конфиге остаётся под
    старой: сторож меток зовёт мёртвой метку, которую больше никто не пишет,
    и не ждёт новую. Период владельца переезжает вместе с именем; если новое
    имя уже стоит, старое просто уходит.
    """
    было = конф_модуль.из_текста(конфиг).get("HEARTBEAT_PERIODS", "").split()
    if not было or not карта:
        return конфиг
    пары = [с.split(":", 1) for с in было if ":" in с]
    стоят = {имя for имя, _ in пары}
    новые = []
    for имя, период in пары:
        if имя in карта:
            if карта[имя] in стоят:
                continue
            имя = карта[имя]
            стоят.add(имя)
        новые.append(f"{имя}:{период}")
    образец = re.compile(r'^(HEARTBEAT_PERIODS=")([^"]*)(")', re.MULTILINE)
    return образец.sub(lambda m: m.group(1) + " ".join(новые) + m.group(3), конфиг, count=1)


def переселить_метки(каталог: Path, карта: dict, только_счёт: bool = False) -> list:
    """Переселить файлы меток на новые имена; вернуть переселённые имена.

    Переименование конфига переносит период, но файл старой метки остаётся
    лежать: гейт сроков присмотра читает его как «метку пишут, а срока нет».

    ПЕРЕИМЕНОВАНИЕ, А НЕ УДАЛЕНИЕ. Прежняя редакция файл удаляла, рассудив,
    что «живая метка под новым именем пишется заново на ближайшем запуске».
    Для демона с периодом 10 минут это так, а для месячного — нет: 14.10.2026
    доустановка на нашей машине сняла 9 меток, и у трёх период от суток до
    31 дня (project-revision, restore-probe). Метки нет → сторож пульса судит
    МЁРТВ (маркер установки давно стар) и будит владельца тревогой о демоне,
    который здоров. Mtime переезжает вместе с файлом, и ЧАС ПОСЛЕДНЕГО ПРОГОНА
    остаётся настоящим ([[freshness-by-mtime-is-false]] — обратная сторона:
    выдуманная свежесть так же лжёт, как выдуманная смерть).
    """
    переселённые = [имя for имя in карта if (Path(каталог) / имя).is_file()]
    if только_счёт:
        return переселённые
    for имя in переселённые:
        старый, новый = Path(каталог) / имя, Path(каталог) / карта[имя]
        if новый.exists():
            # Новый демон уже отметился: оставляем СВЕЖЕЕ из двух времён —
            # метка отвечает на «когда работа шла», а не «какой файл новее».
            if старый.stat().st_mtime > новый.stat().st_mtime:
                os.utime(новый, (старый.stat().st_mtime, старый.stat().st_mtime))
            старый.unlink()
        else:
            старый.rename(новый)
    return переселённые


ЗАГОТОВКИ_ПАМЯТИ = {"MEMORY.md", "ORDERS.md", "TONE.md"}
ЗАГЛУШКА_ПАМЯТИ = "Полная запись с уликами в этот харнес не приехала"
РАЗДЕЛ_ДОНЕСЁННОГО = "## Донесено обновлением"


def _не_заглушка(запись: Path) -> bool:
    # Читается как у гейта (errors="ignore"): битая кодировка записи не делает её заглушкой.
    return ЗАГЛУШКА_ПАМЯТИ not in запись.read_text(encoding="utf-8", errors="ignore")


def _место_занято(место: Path) -> bool:
    # Висячая ссылка местом не считается: на её месте запись ляжет обычным файлом.
    return место.is_file() or место.is_dir()


def _была_в_истории(проект: Path, имя: str) -> bool:
    """Проект эту запись уже имел и убрал — воскрешать её нельзя."""
    try:
        готово = subprocess.run(
            ["git", "-C", str(проект), "log", "--all", "--format=%H", "-n1",
             "--", f"память/{имя}"],
            capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.SubprocessError):
        return False
    return готово.returncode == 0 and bool(готово.stdout.strip())


def разобрать_память(пакет: Path, проект: Path):
    """(к доноске, задержанные историей) или None, если каталога пакета нет."""
    источник, цель = Path(пакет) / "harness" / "память", Path(проект) / "память"
    if not источник.is_dir():
        return None
    новые = [п for п in sorted(источник.glob("*.md"), key=lambda п: п.name)
             if п.is_file() and п.name not in ЗАГОТОВКИ_ПАМЯТИ and _не_заглушка(п)
             and not _место_занято(цель / п.name)]
    задержанные = [п.name for п in новые if _была_в_истории(Path(проект), п.name)]
    return [п for п in новые if п.name not in задержанные], задержанные


def _дописать_указатель(указатель: Path, имена: list) -> None:
    """Ссылки на донесённые записи — в указатель проекта, иначе гейт гигиены зовёт их сиротами."""
    байты = указатель.read_bytes() if указатель.is_file() else b""
    текст = байты.decode("utf-8", errors="surrogateescape")
    недостающие = [и for и in имена if f"[[{и.removesuffix('.md')}]]" not in текст]
    if not недостающие:
        return
    if текст and not текст.endswith("\n"):
        текст += "\n"
    if РАЗДЕЛ_ДОНЕСЁННОГО not in текст:
        текст += f"\n{РАЗДЕЛ_ДОНЕСЁННОГО}\n\n"
    текст += "".join(f"- [[{и.removesuffix('.md')}]]\n" for и in недостающие)
    временный = указатель.with_name(f".{указатель.name}.{os.getpid()}.tmp")
    try:
        временный.write_bytes(текст.encode("utf-8", errors="surrogateescape"))
        if указатель.is_file():
            shutil.copymode(указатель, временный)
        os.replace(временный, указатель)
    except OSError:
        временный.unlink(missing_ok=True)
        raise


def донести_память(пакет: Path, проект: Path, только_счёт: bool = False):
    """Записи памяти пакета, которых нет в памяти проекта; вернуть их имена.

    Раскладка кладёт записи в пакет, а в память проекта их не кладёт никто,
    и гейт остатков пакета на потребителе краснеет «нет в памяти проекта».
    «Есть» судится ТОЧНЫМ именем на верхнем уровне, как у гейта; заготовки
    и заглушки не доносятся — это не содержание, а место под него.
    None — каталога пакета нет: «ничего не донесено» и «пакет не прочитан» разные ответы.
    """
    разбор = разобрать_память(пакет, проект)
    if разбор is None:
        return None
    нужные, _ = разбор
    имена = [п.name for п in нужные]
    if имена and not только_счёт:
        цель = Path(проект) / "память"
        цель.mkdir(parents=True, exist_ok=True)
        for п in нужные:
            место = цель / п.name
            if место.is_symlink():
                место.unlink()  # писать сквозь ссылку значит писать вне проекта
            место.write_bytes(п.read_bytes())
        _дописать_указатель(цель / "MEMORY.md", имена)
    return имена


def stale_artifacts_report() -> str:
    """Строка отчёта, если в живой models.yaml остался раздел «артефакты:»;
    пусто — раздела нет. Только печать: файл владельца не правится."""
    live = КОРЕНЬ / "harness" / "config" / "models.yaml"
    try:
        import yaml
    except ImportError:
        return ""
    try:
        table = yaml.safe_load(live.read_text(encoding="utf-8")) or {}
    except (OSError, yaml.YAMLError):
        return ""
    if isinstance(table, dict) and "артефакты" in table:
        return "раздел артефакты в models.yaml устарел и не читается"
    return ""


def _расписание_сейчас() -> str:
    готово = subprocess.run(["crontab", "-l"], capture_output=True, text=True,
                            timeout=30)
    return готово.stdout if готово.returncode == 0 else ""


def _назвать_память(глагол: str, имена) -> int:
    """Печатает число и имена; None (пакета нет) — отказ, код 2."""
    if имена is None:
        print(f"[доустановка] пакет не прочитан: {конф_модуль.katalog_paketa()}",
              file=sys.stderr)
        return 2
    print(f"[доустановка] {глагол} записей памяти: {len(имена)}")
    for имя in имена:
        print(f"[доустановка]   {имя}")
    return 0


def _назвать_задержанные(пакет: Path, проект: Path) -> None:
    разбор = разобрать_память(пакет, проект)
    задержанные = разбор[1] if разбор else []
    if not задержанные:
        return
    print(f"[доустановка] не донесено записей памяти (были в истории проекта): {len(задержанные)}")
    for имя in задержанные:
        print(f"[доустановка]   {имя}")


GIT_HOOKS = {"pre-commit": "../../scripts/pre-commit-gate.sh",
             "commit-msg": "../../scripts/commit-msg-gate.sh"}


def install_git_hooks(root: Path) -> list:
    """Хуки git проекта: обновление идёт без раскладчика, и хук, заведённый после установки, иначе не доедет.

    Стоящий на месте хук (свой файл владельца или другой симлинк) не заменяется.
    """
    hooks = root / ".git" / "hooks"
    if not (root / ".git").is_dir():
        return []
    placed = []
    for name, target in GIT_HOOKS.items():
        link = hooks / name
        if link.is_symlink() or link.exists():
            continue
        hooks.mkdir(exist_ok=True)
        link.symlink_to(target)
        placed.append(name)
    return placed


def main(argv: list) -> int:
    задания, метки, ключи, снимаемые = прочитать_данные()
    проект = os.environ.get("PROJECT_DIR") or str(КОРЕНЬ)
    журналы = конф_модуль.log_dir()

    конфиг = Path(HARNESS_CONF).read_text(encoding="utf-8") if Path(HARNESS_CONF).exists() else ""
    # Выключенное ключом не ставится, но и не снимается: правило «только
    # добавляем» — стоящую строку убирает владелец.
    off = конф_модуль.switched_off_marks(задания, конф_модуль.из_текста(конфиг))
    задания = [job for job in задания if конф_модуль.job_mark(job) not in off]
    метки = {name: period for name, period in метки.items() if name not in off}
    было = _расписание_сейчас()
    стало = дополнить_расписание(было, задания, проект, журналы)
    # Переименование ДО дополнения: иначе новое имя дописалось бы умолчанием,
    # а старое с периодом владельца осталось бы висеть.
    карта_имён = прочитать_переименования()
    стоящие_метки = {с.split(":")[0] for с in
                     конф_модуль.из_текста(конфиг).get("HEARTBEAT_PERIODS", "").split()}
    # Переименование слов не прибавляет — счёт по словам его не видит.
    переименовано = len(стоящие_метки & set(карта_имён))
    # ПОСЧИТАТЬ переезды, но НЕ двигать: файлы меток и журналов переезжают
    # ПОСЛЕ успешной записи расписания и конфига. Прежний порядок двигал их
    # первыми, и отказ записи (crontab вернул не ноль, sudo -n tee отказал на
    # чужой машине) оставлял метки под НОВЫМИ именами при HEARTBEAT_PERIODS со
    # СТАРЫМИ — сторож пульса называл здоровые демоны МЁРТВЫМИ
    # (ревью F-gen-05 14.10.2026).
    карта_файлов = прочитать_переименования("переименовать_файлы")
    старые_файлы = переселить_метки(конф_модуль.heartbeat_dir(), карта_имён,
                                    только_счёт=True)
    переселено = перенести_файлы(Path(проект), карта_файлов, только_счёт=True)
    новый_конфиг = (дополнить_периоды(переименовать_метки(конфиг, карта_имён), метки)
                    if конфиг else конфиг)
    # Метки считаются ЗДЕСЬ, до правок ключей: счёт идёт по словам, и снятие
    # отжившего ключа убавило бы слова — прибор показал бы минус там, где меток
    # не прибавилось вовсе.
    новых_меток = len(новый_конфиг.split()) - len(конфиг.split()) if конфиг else 0
    новых_ключей = снято = 0
    if конфиг:
        с_ключами = дополнить_ключи(новый_конфиг, ключи)
        новых_ключей = len(с_ключами.splitlines()) - len(новый_конфиг.splitlines())
        новый_конфиг = с_ключами
        без_отживших = снять_ключи(новый_конфиг, снимаемые)
        снято = len(новый_конфиг.splitlines()) - len(без_отживших.splitlines())
        новый_конфиг = без_отживших

    новых_заданий = len(стало.splitlines()) - len(было.splitlines())
    пакет_памяти = конф_модуль.katalog_paketa()

    if "--показать" in argv:
        ждут, _ = применить_живые_правки(
            прочитать_живые_правки(), Path(проект),
            Path(конф_модуль.log_dir()) / "install-new-доставлено.json", только_счёт=True)
        print(f"[доустановка] живых правок ждёт: {len(ждут)}")
        print(f"[доустановка] заданий не хватает: {новых_заданий}, "
              f"периодов меток: {новых_меток}, переименовать меток: {переименовано}, "
              f"переселить меток: {len(старые_файлы)}, переселить файлов: {len(переселено)}, "
              f"ключей: {новых_ключей}, снять: {снято}")
        устарело = stale_artifacts_report()
        if устарело:
            print("[доустановка] " + устарело)
        код = _назвать_память("донести", донести_память(пакет_памяти, Path(проект), True))
        _назвать_задержанные(пакет_памяти, Path(проект))
        return код

    if стало != было:
        готово = subprocess.run(["crontab", "-"], input=стало, text=True,
                                capture_output=True, timeout=30)
        if готово.returncode != 0:
            print(f"[доустановка] расписание не записано: {готово.stderr.strip()}",
                  file=sys.stderr)
            return 1
    if конфиг and новый_конфиг != конфиг and not писатель.надо_поднять_права([Path(HARNESS_CONF)]):
        # Конфиг агента (каталог /etc/harness/agent, решение владельца
        # 13.10.2026): пишем сами, атомарно, с копией прежнего — как панель.
        писатель.снять_копию(Path(HARNESS_CONF))
        писатель.записать_атомарно(Path(HARNESS_CONF), новый_конфиг)
    elif конфиг and новый_конфиг != конфиг:
        # Установка прежнего вида: конфиг у root — пишем через того, кто ставил.
        готово = subprocess.run(["sudo", "-n", "tee", HARNESS_CONF],
                                input=новый_конфиг, text=True,
                                capture_output=True, timeout=30)
        if готово.returncode != 0:
            print(f"[доустановка] конфиг не записан: {готово.stderr.strip()}",
                  file=sys.stderr)
            return 1
    # Правки живых файлов (пульт, модели) — после конфига: упавшая команда не
    # должна оставить установку с полузаписанным расписанием.
    применены, отказы = применить_живые_правки(
        прочитать_живые_правки(), Path(проект),
        Path(конф_модуль.log_dir()) / "install-new-доставлено.json")
    for причина in отказы:
        print(f"[доустановка] живая правка не применена: {причина}", file=sys.stderr)
    # Расписание и конфиг записаны — теперь переезд файлов. Порядок именно
    # такой: метка без своего периода выглядит мёртвой, период без метки — нет.
    if "--показать" not in argv:
        переселить_метки(конф_модуль.heartbeat_dir(), карта_имён)
        перенести_файлы(Path(проект), карта_файлов)
    донесено = донести_память(пакет_памяти, Path(проект))
    for name in install_git_hooks(Path(проект)):
        print(f"[доустановка] хук git {name} подключён симлинком")
    # Снятое называется вслух наравне с добавленным: строка, убранная из
    # конфига молча, неотличима от строки, которой там и не было.
    print(f"[доустановка] добавлено заданий {новых_заданий}, "
          f"периодов меток {новых_меток}, переименовано меток {переименовано}, "
          f"переселено меток {len(старые_файлы)}, переселено файлов {len(переселено)}, "
          f"ключей {новых_ключей}, снято ключей {снято}, живых правок {len(применены)}")
    устарело = stale_artifacts_report()
    if устарело:
        print("[доустановка] " + устарело)
    код = _назвать_память("донесено", донесено)
    _назвать_задержанные(пакет_памяти, Path(проект))
    return код


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
