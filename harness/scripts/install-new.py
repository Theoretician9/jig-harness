#!/usr/bin/env python3
"""Доустановка нового после обновления: расписания и периоды меток.

Откуда взято. Находка C7 разбора спеки обновления (11.09.2026): обновление
привозит НОВЫЙ демон, а он без строки cron и без периода метки мёртв и
незаметен — сторож меток не знает, что его ждать. До этого такие строки
дописывались руками, то есть правило держалось на том, что кто-то помнит.

Два правила, из которых всё остальное следует:

* **только добавляем.** Чужие строки расписания принадлежат машине, а не
  харнесу; значение периода, выставленное владельцем, не перетирается
  умолчанием из данных;
* **повторный прогон ничего не меняет.** Доустановка идёт после каждого
  обновления, и «добавить ещё раз» означало бы дубли в cron.

Что ставить — ДАННЫЕ: `harness/config/system-jobs.yaml`.

Прогон:
    python3 scripts/install-new.py            # доустановить недостающее
    python3 scripts/install-new.py --показать # что не хватает, ничего не менять
"""
import os
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))
import config as конф_модуль                             # noqa: E402
import panel_writer as писатель                           # noqa: E402

КОРЕНЬ = Path(__file__).resolve().parent.parent
ДАННЫЕ = КОРЕНЬ / "harness" / "config" / "system-jobs.yaml"
HARNESS_CONF = конф_модуль.путь_harness_conf()


def прочитать_данные(путь: Path = ДАННЫЕ) -> tuple:
    import yaml
    данные = yaml.safe_load(Path(путь).read_text(encoding="utf-8")) or {}
    return (данные.get("задания") or [], данные.get("метки") or {},
            данные.get("ключи") or {}, данные.get("снять_ключи") or [])


def строка_задания(задание: dict, проект: str, журналы: str) -> str:
    команда = f"{проект}/{задание['команда']}"
    return (f"{задание['расписание']}  {команда} "
            f">>{журналы}/{задание['журнал']} 2>&1")


def команда_строки(строка: str) -> str:
    """Команда из строки расписания: без времени и без перенаправления.

    Признак «уже стоит» — КОМАНДА ЦЕЛИКОМ, вместе с ключами. Прежде им был
    только файл задания, и два задания одного скрипта с разными ключами
    считались одним: строка со вторым не ставилась НИКОГДА и молча. У харнеса
    таких пар две (`memory-revision` с `--по-порогу`, `disk-cleanup` с
    `--по-давлению`), и на чистой установке оба ключа не завелись бы вовсе.

    Время и перенаправление в признак не входят: владелец мог подвинуть час
    или увести вывод в другой файл, и дубль был бы хуже.
    """
    строка = строка.strip()
    if not строка or строка.startswith("#"):
        return ""
    # Особые расписания cron («@daily cmd») — одно поле времени вместо пяти.
    поля = строка.split(None, 1) if строка.startswith("@") else строка.split(None, 5)
    if len(поля) < 2:
        return ""
    команда = re.split(r"\s*>>?", поля[-1], maxsplit=1)[0]
    return " ".join(команда.split())


def дополнить_расписание(было: str, задания: list, проект: str,
                         журналы: str) -> str:
    """Расписание с дописанными недостающими заданиями. Чужое не трогаем."""
    стоящие = {команда_строки(с) for с in было.splitlines()} - {""}
    добавить = []
    for задание in задания:
        ожидаемая = " ".join(f"{проект}/{задание['команда']}".split())
        if ожидаемая in стоящие:
            continue
        добавить.append(строка_задания(задание, проект, журналы))
    if not добавить:
        return было
    хвост = "\n".join(добавить)
    return (было.rstrip("\n") + "\n" + хвост + "\n") if было.strip() else хвост + "\n"


def дополнить_периоды(конфиг: str, метки: dict) -> str:
    """HEARTBEAT_PERIODS с дописанными недостающими метками."""
    # Значение читает общий загрузчик: своя регулярка здесь была одной из
    # десяти копий разбора конфига (ревизия лаконичности 12.09.2026).
    если_было = конф_модуль.из_текста(конфиг).get("HEARTBEAT_PERIODS", "").split()
    имена = {с.split(":")[0] for с in если_было}
    добавка = [f"{имя}:{период}" for имя, период in метки.items()
               if имя not in имена]
    if not добавка:
        return конфиг
    строка = " ".join(если_было + добавка)
    # Подменяем ЗНАЧЕНИЕ на месте, а не строку целиком: рядом могут стоять
    # комментарии, и переписать их нельзя. Строки нет вовсе — дописываем.
    образец = re.compile(r'^(HEARTBEAT_PERIODS=")([^"]*)(")', re.MULTILINE)
    if образец.search(конфиг):
        return образец.sub(lambda m: m.group(1) + строка + m.group(3), конфиг, count=1)
    return конфиг.rstrip("\n") + f'\nHEARTBEAT_PERIODS="{строка}"\n'


def дополнить_ключи(конфиг: str, ключи: dict) -> str:
    """Конфиг с дописанными недостающими ключами. Стоящий не трогаем НИКОГДА.

    Ручка панели требует, чтобы ключ СТОЯЛ в конфиге (гейт переключателей), а
    на чужой установке после обновления его туда не писал никто: обновление
    привозит новый механизм, а его ключ — нет (ревью спеки ревизии, I-9).

    Значение владельца старше умолчания пакета: «только добавляем» — то же
    правило, что у расписания и периодов меток.
    """
    добавка = []
    for имя, значение in ключи.items():
        # Закомментированный ключ за стоящий не считается: иначе ключа в
        # конфиге не появится, а панель будет обещать ручку.
        if re.search(rf'^\s*{re.escape(имя)}=', конфиг, re.MULTILINE):
            continue
        добавка.append(f'{имя}="{значение}"')
    if not добавка:
        return конфиг
    return конфиг.rstrip("\n") + "\n" + "\n".join(добавка) + "\n"


def снять_ключи(конфиг: str, имена: list) -> str:
    """Убрать строки ключей, которые харнес завёл сам и сам признал отжившими.

    Правило «только добавляем» (см. шапку) — про ЧУЖИЕ строки и значения
    владельца. Свой отработавший ключ, оставленный в конфиге, живёт как
    настройка, которой ничто не управляет: в ней написано одно, а делается
    другое. Список снимаемых — ДАННЫЕ, здесь только механика.
    Закомментированные строки не трогаем: комментарий — след решения.
    """
    for имя in имена:
        конфиг = re.sub(rf'^[ \t]*{re.escape(имя)}=.*\n?', "", конфиг, flags=re.MULTILINE)
    return конфиг


def прочитать_переименования(путь: Path = ДАННЫЕ) -> dict:
    import yaml
    данные = yaml.safe_load(Path(путь).read_text(encoding="utf-8")) or {}
    return данные.get("переименовать_метки") or {}


def переименовать_метки(конфиг: str, карта: dict) -> str:
    """HEARTBEAT_PERIODS со старыми именами меток, заменёнными на новые.

    Демон, сменивший имя метки, пишет новую, а период в конфиге остаётся под
    старой: сторож меток зовёт мёртвой метку, которую больше никто не пишет,
    и не ждёт новую. Период владельца переезжает вместе с именем; если новое
    имя уже стоит, старое просто уходит.
    """
    было = конф_модуль.из_текста(конфиг).get("HEARTBEAT_PERIODS", "").split()
    if not было or not карта:
        return конфиг
    пары = [с.split(":", 1) for с in было if ":" in с]
    стоят = {имя for имя, _ in пары}
    новые = []
    for имя, период in пары:
        if имя in карта:
            if карта[имя] in стоят:
                continue
            имя = карта[имя]
            стоят.add(имя)
        новые.append(f"{имя}:{период}")
    образец = re.compile(r'^(HEARTBEAT_PERIODS=")([^"]*)(")', re.MULTILINE)
    return образец.sub(lambda m: m.group(1) + " ".join(новые) + m.group(3), конфиг, count=1)


def убрать_старые_метки(каталог: Path, карта: dict, только_счёт: bool = False) -> list:
    """Удалить файлы меток под старыми именами; вернуть их имена.

    Переименование конфига переносит период, но файл старой метки остаётся
    лежать: гейт сроков присмотра читает его как «метку пишут, а срока нет».
    Старый файл — отметка демона, который так больше не называется; живая
    метка под новым именем пишется заново на ближайшем запуске.
    """
    старые = [имя for имя in карта if (Path(каталог) / имя).is_file()]
    if not только_счёт:
        for имя in старые:
            (Path(каталог) / имя).unlink()
    return старые


def _расписание_сейчас() -> str:
    готово = subprocess.run(["crontab", "-l"], capture_output=True, text=True,
                            timeout=30)
    return готово.stdout if готово.returncode == 0 else ""


def main(argv: list) -> int:
    задания, метки, ключи, снимаемые = прочитать_данные()
    проект = os.environ.get("PROJECT_DIR") or str(КОРЕНЬ)
    журналы = конф_модуль.log_dir()

    было = _расписание_сейчас()
    стало = дополнить_расписание(было, задания, проект, журналы)
    конфиг = Path(HARNESS_CONF).read_text(encoding="utf-8") if Path(HARNESS_CONF).exists() else ""
    # Переименование ДО дополнения: иначе новое имя дописалось бы умолчанием,
    # а старое с периодом владельца осталось бы висеть.
    карта_имён = прочитать_переименования()
    стоящие_метки = {с.split(":")[0] for с in
                     конф_модуль.из_текста(конфиг).get("HEARTBEAT_PERIODS", "").split()}
    # Переименование слов не прибавляет — счёт по словам его не видит.
    переименовано = len(стоящие_метки & set(карта_имён))
    старые_файлы = убрать_старые_метки(конф_модуль.heartbeat_dir(), карта_имён,
                                       только_счёт="--показать" in argv)
    новый_конфиг = (дополнить_периоды(переименовать_метки(конфиг, карта_имён), метки)
                    if конфиг else конфиг)
    # Метки считаются ЗДЕСЬ, до правок ключей: счёт идёт по словам, и снятие
    # отжившего ключа убавило бы слова — прибор показал бы минус там, где меток
    # не прибавилось вовсе.
    новых_меток = len(новый_конфиг.split()) - len(конфиг.split()) if конфиг else 0
    новых_ключей = снято = 0
    if конфиг:
        с_ключами = дополнить_ключи(новый_конфиг, ключи)
        новых_ключей = len(с_ключами.splitlines()) - len(новый_конфиг.splitlines())
        новый_конфиг = с_ключами
        без_отживших = снять_ключи(новый_конфиг, снимаемые)
        снято = len(новый_конфиг.splitlines()) - len(без_отживших.splitlines())
        новый_конфиг = без_отживших

    новых_заданий = len(стало.splitlines()) - len(было.splitlines())

    if "--показать" in argv:
        print(f"[доустановка] заданий не хватает: {новых_заданий}, "
              f"периодов меток: {новых_меток}, переименовать меток: {переименовано}, "
              f"старых файлов меток: {len(старые_файлы)}, "
              f"ключей: {новых_ключей}, снять: {снято}")
        return 0

    if стало != было:
        готово = subprocess.run(["crontab", "-"], input=стало, text=True,
                                capture_output=True, timeout=30)
        if готово.returncode != 0:
            print(f"[доустановка] расписание не записано: {готово.stderr.strip()}",
                  file=sys.stderr)
            return 1
    if конфиг and новый_конфиг != конфиг and not писатель.надо_поднять_права([Path(HARNESS_CONF)]):
        # Конфиг агента (каталог /etc/harness/agent, решение владельца
        # 13.10.2026): пишем сами, атомарно, с копией прежнего — как панель.
        писатель.снять_копию(Path(HARNESS_CONF))
        писатель.записать_атомарно(Path(HARNESS_CONF), новый_конфиг)
    elif конфиг and новый_конфиг != конфиг:
        # Установка прежнего вида: конфиг у root — пишем через того, кто ставил.
        готово = subprocess.run(["sudo", "-n", "tee", HARNESS_CONF],
                                input=новый_конфиг, text=True,
                                capture_output=True, timeout=30)
        if готово.returncode != 0:
            print(f"[доустановка] конфиг не записан: {готово.stderr.strip()}",
                  file=sys.stderr)
            return 1
    # Снятое называется вслух наравне с добавленным: строка, убранная из
    # конфига молча, неотличима от строки, которой там и не было.
    print(f"[доустановка] добавлено заданий {новых_заданий}, "
          f"периодов меток {новых_меток}, переименовано меток {переименовано}, "
          f"убрано старых файлов меток {len(старые_файлы)}, "
          f"ключей {новых_ключей}, снято ключей {снято}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
