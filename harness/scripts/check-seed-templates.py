#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Гейт: семена в UNIFIED/templates не выдают себя за живой код.

Больной случай 27.09.2026 (находка ревью minor-5, проверенная замером).
`UNIFIED/templates/check-context-hygiene.py` — 118 строк против 706 у живого
гейта: в семени ещё потолок STATE в ЗНАКАХ и память в `~/.claude/projects`.
Замер показал, что расходятся ВСЕ двенадцать кодовых семян — от 113 до 754
изменённых строк, и ни одно не обновлялось с первого коммита.

Опасность не в самом расхождении: установка берёт файлы из `harness/scripts`
пакета (`razlozhit-harnes.sh`), а не отсюда, — а в том, что главы называют
семя местом, где «живёт» механизм (например 06-ГЕЙТЫ-КАЧЕСТВА.md про
`templates/pre-commit-gate.sh`), и живые файлы ссылаются на него строкой
«Откуда взят». Указатель, который врёт, хуже отсутствующего: правку понесут в
семя, она нигде не проявится, и потерю заметят через месяц.

Поэтому правило простое: каждое кодовое семя обязано ПЕРВЫМИ строками называть
свой живой файл. Тогда читатель, пришедший из главы, видит правду сразу.

Прогон:
    check-seed-templates.py            # 0 — чисто, 1 — есть семя без указателя
    check-seed-templates.py --selftest
"""
from __future__ import annotations

import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
СЕМЕНА = "UNIFIED/templates"
МЕТКА = "СЕМЯ ПЕРВОЙ УСТАНОВКИ"
# Сколько первых строк смотрим: метка стоит сразу после shebang и кодировки.
ГОЛОВА = 6
КОД = (".py", ".sh", ".yaml", ".json", ".md")
# Опись — про семена, а не семя: у неё живого двойника нет.
НЕ_СЕМЕНА = ("README.md",)
# Имя подставного семени в самотесте.
SEED_NAME = f"{СЕМЕНА}/проба-семени.py"


# Где каталог семян может лежать — В СВОЁМ дереве: рядом с кодом либо в
# служебном подкаталоге (так в публичной сборке 12.09). Выше по дереву не
# ходим: из пакета гейт увидел бы семена ПАКЕТА, а живые файлы там лежат по
# другой раскладке (harness/hooks вместо scripts/hooks) — и честная метка
# выглядела бы ложью. Судит проект, ставший из пакета, а не сам пакет.
МЕСТА = ("UNIFIED/templates", "sluzhebnoe/UNIFIED/templates")


def дом_семян(корень: Path) -> Path | None:
    for место in МЕСТА:
        если_есть = (корень / место)
        if если_есть.is_dir():
            return если_есть
    return None


def есть_каталог(корень: Path) -> bool:
    return дом_семян(корень) is not None


def семена(корень: Path) -> list[Path]:
    дом = дом_семян(корень)
    if дом is None:
        return []
    return sorted(п for п in дом.rglob("*")
                  if п.is_file() and п.suffix in КОД and п.name not in НЕ_СЕМЕНА)


# Форматы, куда комментарий не вписать: у них метка живёт в файле-соседе.
# Это не особый случай ради красоты, а свойство формата: JSON комментариев не
# держит, а молча оставить одно семя без указателя — вернуть ту же беду.
БЕЗ_КОММЕНТАРИЕВ = (".json",)
СОСЕД = ".ЧИТАЙ-МЕНЯ.md"


def голова_семени(семя: Path) -> str:
    """Где у этого семени может стоять метка: в нём самом или в файле-соседе."""
    если_json = семя.suffix in БЕЗ_КОММЕНТАРИЕВ
    источник = семя.with_name(семя.name + СОСЕД) if если_json else семя
    if not источник.exists():
        return ""
    строки = источник.read_text(encoding="utf-8", errors="replace").splitlines()
    return "\n".join(строки[:ГОЛОВА])


# Обёртки, которыми путь окружают в тексте. Снимаются с обеих сторон, а точка
# слева — часть пути (`.claude/settings.json`), и общий strip съедал её.
ОБЁРТКИ_СЛЕВА = " #'\"`(<«[«"
ОБЁРТКИ_СПРАВА = " #'\"`.,;:)>»]»"


def _путь(слово: str) -> str:
    return слово.lstrip(ОБЁРТКИ_СЛЕВА).rstrip(ОБЁРТКИ_СПРАВА)


def названный_живой(голова: str) -> list[str]:
    """Пути, названные ИМЕННО в строке метки, после слов «Живой файл:».

    Прежняя редакция брала любой существующий путь из головы — и метка,
    указывающая сама на себя, считалась честной (ревью 27.09, сем-3).
    """
    for строка in голова.splitlines():
        if МЕТКА not in строка and "Живой файл" not in строка:
            continue
        хвост = строка.split("Живой файл", 1)[-1]
        пути = [_путь(сл) for сл in хвост.split()
                if _путь(сл).endswith(КОД) or _путь(сл).endswith("/")]
        if пути:
            return пути
    return []


ВЫГРУЗКА = "UNIFIED/ХАРНЕС-ОДНИМ-ФАЙЛОМ.md"


def выгрузка_отстала(корень: Path) -> str:
    """Пусто — выгрузка свежа; иначе строка беды.

    Выгрузку «одним файлом» читают ЛЮДИ, и в ней лежат тела семян целиком.
    27.09.2026 метки «не живой код» уже стояли в семенах, а в выгрузке их не
    было ни одной: её сборщика не звал никто (ревью, сем-4). Судит эту
    свежесть гейт семян, а не отдельная строка ворот: сборщик живёт в UNIFIED,
    то есть в «живом» дереве проекта, и паспорта механизма ему не положено.
    """
    сборщик = корень / "UNIFIED" / "BUILD.py"
    файл = корень / ВЫГРУЗКА
    if not сборщик.exists() or not файл.exists():
        return ""        # нечего сверять: установка без глав
    import importlib.util                                  # noqa: PLC0415
    спец = importlib.util.spec_from_file_location("сборщик_выгрузки", сборщик)
    модуль = importlib.util.module_from_spec(спец)
    try:
        спец.loader.exec_module(модуль)
        ожидается = модуль.собрать()
    except Exception as беда:                              # noqa: BLE001
        return f"{ВЫГРУЗКА}: сборщик не отработал ({беда}) — судить нечем"
    if файл.read_text(encoding="utf-8") == ожидается:
        return ""
    return (f"{ВЫГРУЗКА}: отстала от глав и семян — в ней лежат старые тела. "
            f"Починка: python3 UNIFIED/BUILD.py")


def беды(корень: Path) -> list[str]:
    найдено = []
    for семя in семена(корень):
        имя = семя.relative_to(корень) if семя.is_relative_to(корень) else семя
        try:
            голова = голова_семени(семя)
        except OSError as беда:
            # Нечитаемое семя — это «нечем судить», а не «чисто»: падение гейта
            # выглядит поломкой прогона, а не находкой (ревью 27.09, сем-8).
            найдено.append(f"{имя}: семя не прочитано ({беда}) — судить нечем")
            continue
        где = f"в соседе {семя.name}{СОСЕД}" if семя.suffix in БЕЗ_КОММЕНТАРИЕВ \
            else f"в первых {ГОЛОВА} строках"
        if МЕТКА not in голова:
            найдено.append(f"{имя}: нет метки «{МЕТКА}» {где} — "
                           f"семя выглядит живым кодом")
            continue
        живые = названный_живой(голова)
        свои = {str(имя), семя.name}
        если_есть = [ж for ж in живые
                     if (корень / ж).exists() and ж not in свои and not ж.startswith("/")]
        if not если_есть:
            найдено.append(f"{имя}: метка есть, а живой файл не назван, не найден или "
                           f"указывает на себя (в метке: {живые or 'ничего'})")
    если_отстала = выгрузка_отстала(корень)
    if если_отстала:
        найдено.append(если_отстала)
    return найдено


def _selftest() -> int:
    import tempfile
    плохо = путей = 0

    def проба(имя: str, вышло, ждём) -> None:
        nonlocal плохо, путей
        путей += 1
        if вышло == ждём:
            print(f"  ок    {имя}")
        else:
            print(f"  ПЛОХО {имя}: вышло {вышло!r}, ждали {ждём!r}")
            плохо = 1

    with tempfile.TemporaryDirectory() as двор:
        корень = Path(двор)
        (корень / СЕМЕНА).mkdir(parents=True)
        (корень / "scripts").mkdir()
        (корень / "scripts" / "живой.py").write_text("живой\n", encoding="utf-8")

        проба("семян нет — чисто", беды(корень), [])
        # БОЛЬНОЙ СЛУЧАЙ: семя молчит о том, что оно семя.
        семя = корень / SEED_NAME
        семя.write_text("#!/usr/bin/env python3\nprint('я как живой')\n", encoding="utf-8")
        проба("БОЛЬНОЙ СЛУЧАЙ: семя без метки — находка", len(беды(корень)), 1)
        семя.write_text(f"#!/usr/bin/env python3\n# {МЕТКА}. Живой файл: scripts/живой.py\n",
                        encoding="utf-8")
        проба("метка с существующим живым файлом — чисто", беды(корень), [])
        семя.write_text(f"#!/usr/bin/env python3\n# {МЕТКА}. Живой файл: scripts/нет-такого.py\n",
                        encoding="utf-8")
        проба("метка называет несуществующий файл — находка", len(беды(корень)), 1)
        семя.write_text(f"#!/usr/bin/env python3\n# {МЕТКА} и больше ничего\n",
                        encoding="utf-8")
        проба("метка без имени живого файла — находка", len(беды(корень)), 1)
        # Метка ниже головы не считается: читатель её не увидит.
        семя.write_text("#!/usr/bin/env python3\n" + "\n" * 20
                        + f"# {МЕТКА}. Живой файл: scripts/живой.py\n", encoding="utf-8")
        проба("метка в подвале файла не считается", len(беды(корень)), 1)
        # Стенд возвращаем в здоровое состояние: предыдущая проба нарочно
        # испортила семя, и следующая мерила бы ЕГО, а не то, что называет.
        семя.write_text(f"#!/usr/bin/env python3\n# {МЕТКА}. Живой файл: scripts/живой.py\n",
                        encoding="utf-8")
        # JSON комментариев не держит: метка живёт в файле-соседе.
        json_семя = корень / СЕМЕНА / "настройки.json"
        json_семя.write_text("{}\n", encoding="utf-8")
        проба("БОЛЬНОЙ СЛУЧАЙ: json-семя без соседа — находка", len(беды(корень)), 1)
        json_семя.with_name(json_семя.name + СОСЕД).write_text(
            f"# {МЕТКА}\n\nЖивой файл: scripts/живой.py\n", encoding="utf-8")
        проба("json-семя с соседом — чисто", беды(корень), [])
        # Не код — не судим: README и примеры памяти живут своей жизнью.
        (корень / СЕМЕНА / "README.md").write_text("опись\n", encoding="utf-8")
        семя.write_text(f"#!/usr/bin/env python3\n# {МЕТКА}. Живой файл: scripts/живой.py\n",
                        encoding="utf-8")
        проба("markdown рядом гейту не мешает", беды(корень), [])
        # БОЛЬНОЙ СЛУЧАЙ (ревью 27.09, сем-3): метка, указывающая САМА НА СЕБЯ,
        # считалась честной — гейт искал в голове любой существующий путь.
        семя.write_text(f"#!/usr/bin/env python3\n# {МЕТКА}. Живой файл: {SEED_NAME}\n",
                        encoding="utf-8")
        проба("метка, указывающая на себя, — находка", len(беды(корень)), 1)
        # И абсолютный путь этой машины живым файлом не считается: у другой
        # установки его нет.
        семя.write_text(f"#!/usr/bin/env python3\n# {МЕТКА}. Живой файл: /etc/passwd.py\n",
                        encoding="utf-8")
        проба("абсолютный путь живым файлом не считается", len(беды(корень)), 1)
        # Путь в скобках и кавычках — тот же путь: ложная находка на верной
        # метке стоит доверия к гейту (сем-9).
        семя.write_text(f"#!/usr/bin/env python3\n# {МЕТКА}. Живой файл: «scripts/живой.py», правки туда.\n",
                        encoding="utf-8")
        проба("путь в кавычках и с запятой читается верно", беды(корень), [])
        # БОЛЬНОЙ СЛУЧАЙ (сем-2): каталог семян переименован — «нечем судить»,
        # а не «нарушений нет».
        (корень / СЕМЕНА).rename(корень / "UNIFIED" / "семена-уехали")
        проба("каталога семян нет — гейт говорит об этом, а не молчит",
              есть_каталог(корень), False)

    print(f"САМОТЕСТ {'ПРОЙДЕН' if not плохо else 'ПРОВАЛЕН'}: {путей} путей, "
          "больной первым — семя без метки")
    return 1 if плохо else 0


def main() -> int:
    if "--selftest" in sys.argv:
        return _selftest()
    if not есть_каталог(КОРЕНЬ):
        # «Каталога нет» и «нарушений нет» — РАЗНЫЕ ответы, и говорятся они
        # разными словами (ревью 27.09, сем-2). Но это не отказ: установка без
        # глав законна, и красный гейт на ней просто отключили бы.
        print(f"[семена] каталога семян нет ни в одном из мест {МЕСТА} — "
              f"судить нечего, это установка без глав")
        return 0
    найдено = беды(КОРЕНЬ)
    if not найдено:
        print(f"[семена] чисто: каждое семя в {СЕМЕНА} называет свой живой файл "
              f"({len(семена(КОРЕНЬ))} шт.)")
        return 0
    print(f"[семена] ✗ семя выдаёт себя за живой код ({len(найдено)}):")
    for беда in найдено:
        print(f"    {беда}")
    print("    Правка семени нигде не проявится: живой код ставится раскладкой из"
          " harness/scripts пакета. Назови живой файл первыми строками семени.")
    return 1


if __name__ == "__main__":
    sys.exit(main())
