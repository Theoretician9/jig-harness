#!/usr/bin/env bash
#
# tg-dispatcher.sh — ЕДИНСТВЕННЫЙ потребитель getUpdates на токен бота.
#
# Откуда взят: написан для стартового пакета, шаблона в UNIFIED нет; норма —
# улика из devmap-selfheal.sh: Telegram допускает ровно одного потребителя
# getUpdates на токен, второй убивает «устаревшего держателя» — то есть живой
# канал владельца. Поэтому потребитель здесь один, под локом, а все остальные
# (хуки, демоны, агент) только ШЛЮТ через tg_send.sh/sendMessage — это
# getUpdates не трогает.
#
# Что делает цикл long-poll:
#   - входящие ТОЛЬКО от TG_CHAT_ID; чужие — игнор с записью в лог,
#     «добавь меня» — вежливый отказ (02-КАРТА: доступ меняет только владелец
#     извне канала, правка — только конфигом с сервера);
#   - каждое входящее получает ack ≤30 секунд: sendMessage «принял: <кратко>»
#     (CLAUDE.md §11 — отзывчивость держится механикой, не вниманием агента);
#   - текст пишется в очередь $LOG_DIR/inbox/<ts>.txt — оттуда его берёт агент;
#   - ответы «да/подтверждаю/ротация ок/ок» — подтверждения полуавтомата —
#     дополнительно пишутся в $LOG_DIR/confirmations.jsonl (их читают ворота
#     deploy_guard.py перед выкатом в semi; агент — перед завершением/ротацией);
#   - сеть упала → retry с нарастающей паузой, не смерть: канал владельца не
#     имеет права умирать от минутного обрыва сети.
#
# Запуск: systemd-юнит или tmux, от имени $AGENT_USER. Второй экземпляр
# отказывается стартовать с внятным сообщением (лок-файл).
# Чем доказывается на живом: тестовое входящее получает ack; запуск второго
# экземпляра руками → отказ; «добавь меня» с чужого аккаунта → вежливый отказ;
# доставка текста в панель — `--selftest` на живом tmux (4 пути, первый больной).
set -euo pipefail

# Без UTF-8-локали ${текст,,} не приводит кириллицу к нижнему регистру и
# «Подтверждаю» проходит мимо журнала подтверждений. Поймано прогоном при
# сборке пакета 08.08.2026 (та же грабля, что и резка текста в tg_send.sh).
export LC_ALL=C.UTF-8

# ── слова владельца: текст или подпись ──────────────────────────────────────
# Слова владельца приходят ДВУМЯ полями: у обычного сообщения это .text, у
# фото/файла/видео — .caption. Улика 11.08.2026: владелец прислал снимок с
# подписью «высылаю пустое изображение для теста» — снимок доехал, подпись
# исчезла, и он увидел, что его не читают. Поле одно для всех видов входящих:
# ветвиться должен вид вложения, а не место, где лежат слова.
слова_владельца() {  # JSON .message → текст или подпись
    printf '%s' "$1" | jq -r '.text // .caption // empty'
}

# Слова, которыми владелец направляет внимание, и формы, где приказ отложен, —
# ДАННЫЕ (harness/config/очередь.yaml). Тот же файл читает прибор очереди: два
# списка в двух носителях разъезжаются молча (так разошлись формы команд
# приёмки, и цикл крутился впустую пять кругов).
otmetit_vnimanie() {  # $1=метка времени сообщения, $2=слова владельца
    [ -n "${2:-}" ] || return 0
    # Путь считается ВНУТРИ: PROJECT_DIR и HERE задаются ниже по файлу, и
    # объявление наверху раскрылось бы в пустоту (проба до правки это и дала).
    local QUEUE_CONF="${QUEUE_CONF:-$PROJECT_DIR/harness/config/очередь.yaml}"
    [ -r "$QUEUE_CONF" ] || return 0
    local slovo
    slovo=$(QUEUE_CONF="$QUEUE_CONF" python3 "$HERE/slovo-vnimaniya.py" "$2" 2>/dev/null || true)
    [ -n "$slovo" ] || return 0
    printf '{"id": "%s", "метка": %s, "слово": "%s", "когда": "%s"}\n' \
        "$1" "$1" "$slovo" "$(date -Iseconds)" >> "$LOG_DIR/внимание.jsonl"
    say "прямое слово владельца: «$slovo» — задача из этого сообщения пойдёт первой"
}

# Улика 20.08.2026: владелец ответил сразу на два вопроса одним сообщением —
# «1 - но не надо подписи» первой строкой и «да» второй. Шаблон сравнивал
# сообщение ЦЕЛИКОМ, согласие в журнал не попало, и выкат встал, хотя
# разрешение было дано. Это был второй такой случай за сутки (первым «1» тоже
# не легло — но там слова согласия не было вовсе, и это правильно).
# Строка сравнивается целиком: «да и вообще не надо» согласием не станет.
# Печатает ВСЕ найденные согласия — по одному в строке, а не первое попавшееся.
# Улика 04.09.2026: «Да, отправляй на гит\nда, выкатывай на прод» одним
# сообщением. Первая строка дала согласие на push, `return 0` оборвал разбор, и
# согласие на ВЫКАТ не попало в журнал вовсе — ворота отказали при данном
# разрешении, а владельца пришлось бы просить написать то же второй раз.
# Форма ответа панели: слово и код. Сообщение такого вида в общий журнал
# согласий не попадает НИКОГДА — даже если панель его не применила (служба
# лежит, код просрочен). Иначе «да 7391» про переключатель открывало бы
# анонсированный ВЫКАТ: ворота засчитывают любое «да» (ревью 11.09, F-gen-01).
# Имя переменной ЛАТИНИЦЕЙ: кириллические bash не берёт вовсе.
PANEL_ANSWER_RE='^(да|нет|ок|стоп)[^0-9]{0,12}[0-9]{4,6}$'

это_ответ_панели() {  # $1=нормализованный текст → 0 если форма совпала
    printf '%s' "$1" | grep -Eqi "$PANEL_ANSWER_RE"
}

согласие_владельца() {  # текст сообщения → строки согласия (по одной)
    local line
    while IFS= read -r line; do
        line="${line,,}"
        line=$(printf '%s' "$line" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')
        case "$line" in
            да|ок|окей|подтверждаю|"ротация ок"|"ротация да"|выкатывай)
                printf '%s\n' "$line"; continue ;;
        esac
        # Прямое распоряжение — согласие, даже без слова «да» и любой длины.
        # 11.09.2026 на вопрос с нумерованными вариантами («ответь цифрой»)
        # владелец ответил «1 публикуй как есть, проверю - обновим если чтото
        # не так»: слова «да» нет, строка длиннее трёх слов — распознаватель
        # промолчал, и распоряжение владельца осталось неисполненным. Предмет
        # сторож разберёт сам; отрицание прямо перед глаголом («не публикуй»)
        # снимает согласие.
        if printf '%s' "$line" | grep -qE '(публикуй|опубликуй|выкатывай|выкати|отправляй|отправь)' \
           && ! printf '%s' "$line" | grep -qE '(не|нет|стоп|отмена|погоди|подожди|позже|рано) ?(публикуй|опубликуй|выкатывай|выкати|отправляй|отправь)'; then
            printf '%s\n' "$line"; continue
        fi
        # Согласие БЕЗ названного предмета — ответ на заданный мной вопрос.
        # Улика 09.09.2026: прод лежал после ребута, я спросил разрешения
        # поднять его, владелец ответил «Моё да / Делай как лучше» — записи в
        # журнале не появилось, и ворота отказали бы при данном разрешении.
        # Предмет назван в ВОПРОСЕ, а не в ответе, поэтому признак «да + слово
        # про предмет» такую строку не берёт, а список точных форм её не знал.
        # Мера — КОРОТКАЯ строка: не больше трёх слов, отдельное «да», ни
        # одного отрицания. «да и вообще не надо» (пять слов) согласием не
        # станет, «да нет» — тоже: отрицание перевешивает.
        if [ "$(printf '%s' "$line" | wc -w)" -le 3 ] \
           && printf '%s' " $line " | grep -qE '[ ,.;:!?()"-]да[ ,.;:!?()"-]' \
           && ! printf '%s' " $line " | grep -qE '[ ,.;:!?()"-](не|нет|стоп|отмена|погоди|подожди|позже|рано)[ ,.;:!?()"-]'; then
            printf '%s\n' "$line"; continue
        fi
        # Согласие с НАЗВАННЫМ ПРЕДМЕТОМ. Перечислять точные формы оказалось
        # тупиком: за одни сутки владелец написал «Да для выката» и «По выкату
        # пишу да» — обе не совпали со списком, и выкат встал при данном
        # разрешении. Признак вместо списка: в строке есть отдельное слово
        # «да» И слово про выкат, и нет ни одного отрицания. «да выкатывать не
        # надо» согласием не станет — отрицание перевешивает.
        # Границы слова — по пробелам и знакам препинания, а НЕ через
        # диапазон [а-яё]: под локалью C такой диапазон даёт «Invalid
        # collation character», и всё условие молча падает вместе с grep.
        # Границы слова — по пробелам и знакам препинания, класс подставлен
        # ВНУТРЬ шаблона: имя переменной кириллицей bash не принимает и печатает
        # ЗНАЧЕНИЕ в ошибку ([[кириллица-в-именах-bash]] — так однажды утёк токен).
        if printf '%s' " $line " | grep -qE '[ ,.;:!?()"-]да[ ,.;:!?()"-]' \
           && printf '%s' "$line" | grep -qE 'выкат|деплой|deploy' \
           && ! printf '%s' " $line " | grep -qE '[ ,.;:!?()"-](не|нет|стоп|отмена|погоди|подожди|позже|рано)[ ,.;:!?()"-]'; then
            printf '%s\n' "$line"; continue
        fi
        # Отправка в чужой репозиторий — тоже наружу, и ворота требуют согласия
        # так же, как на выкат. Улика 03.09.2026: владелец написал «на гит
        # отправляй, да» — согласие названо словом и предмет назван, а запись не
        # появилась: «да» без слова про ВЫКАТ ни под одно правило не подходило,
        # и push встал при данном разрешении. Признак тот же, что у выката:
        # отдельное «да» И слово про отправку, и ни одного отрицания.
        if printf '%s' " $line " | grep -qE '[ ,.;:!?()"-]да[ ,.;:!?()"-]' \
           && printf '%s' "$line" | grep -qE 'гит|git|пуш|push|отправляй|отправь|отправить' \
           && ! printf '%s' " $line " | grep -qE '[ ,.;:!?()"-](не|нет|стоп|отмена|погоди|подожди|позже|рано)[ ,.;:!?()"-]'; then
            printf '%s\n' "$line"; continue
        fi
    done <<< "$1"
    # Ответ функции — НАПЕЧАТАННЫЕ строки, а не код возврата: вызывающий берёт
    # её подстановкой (AGREE=$(...)), и ненулевой код здесь ронял под set -e
    # ВЕСЬ диспетчер на любом сообщении без согласия. Улика 04.09.2026: канал
    # падал и рестартовал каждые 10 с, на каждом старте заново шля владельцу
    # «принял» на одно и то же сообщение — offset не успевал лечь на диск.
    return 0
}

# ── доставка текста в панель агента ─────────────────────────────────────────
# Улика 11.08.2026: `tmux send-keys -t сессия "$текст" Enter` теряет сообщения
# владельца двумя разными способами, и оба воспроизводятся руками.
#   1. Без -l tmux разбирает аргумент как ИМЯ КЛАВИШИ, если оно совпало с
#      именем: сообщение «Enter» стало нажатием Enter (в приёмнике — «\n\n»,
#      слова нет вовсе), а «C-c» оборвал бы сессию агента.
#   2. Одним вызовом (текст и Enter вместе) финальный Enter теряется: TUI ещё
#      разбирает вставку и не видит нажатия — текст висит в строке ввода
#      непосланным. Поэтому Enter — ОТДЕЛЬНЫМ вызовом после паузы.
# Перевод строки и возврат каретки внутри текста — в пробел: в TUI каждый \n
# это отправка, и длинное сообщение владельца ушло бы рваными кусками.
send_to_pane() {  # текст
    local flat="${1//$'\n'/ }"
    flat="${flat//$'\r'/ }"
    tmux send-keys -t "$TMUX_SESSION" -l -- "$flat" || return 1
    sleep "${PANE_ENTER_DELAY:-0.7}"
    tmux send-keys -t "$TMUX_SESSION" Enter || return 1
}

# ── селфтест доставки: ЖИВОЙ tmux, свои одноразовые сессии ──────────────────
# Прибор доказывается на больном случае (UNIFIED/08), а больной случай здесь —
# потеря сообщения владельца. Поэтому первый путь гоняет СТАРЫЙ способ и ждёт
# провала: зазеленей он — чинить было нечего. Сессии свои, с `cat > файл` в
# приёмнике: в сессию агента селфтест не пишет ни байта.
if [ "${1:-}" = "--selftest" ]; then
    command -v tmux >/dev/null 2>&1 || { echo "SELFTEST: tmux не установлен — доставку в панель проверить нечем"; exit 1; }
    T=$(mktemp -d); ok_flag=1

    # ── Распознаватель согласий: вторая половина механизма, и до 11.09.2026
    # её не проверял никто. Формы взяты из живого канала, включая те, что
    # согласием быть НЕ должны.
    соглас_проба() {  # текст, ждём-согласие(1/0), зачем
        local vyshlo=0
        [ -n "$(согласие_владельца "$1")" ] && vyshlo=1
        if [ "$vyshlo" = "$2" ]; then printf '  ок    %s\n' "$3"
        else printf '  ПЛОХО %s: текст «%s» → согласие=%s, ждали %s\n' "$3" "$1" "$vyshlo" "$2"; ok_flag=0; fi
    }
    # БОЛЬНОЙ СЛУЧАЙ 11.09.2026: ответ цифрой на вопрос с вариантами.
    соглас_проба "1 публикуй как есть, проверю - обновим если чтото не так" 1 \
        "БОЛЬНОЙ СЛУЧАЙ: ответ цифрой с распоряжением «публикуй»"
    соглас_проба "да" 1 "голое «да» — ответ на заданный вопрос"
    соглас_проба "не публикуй пока" 0 "отрицание прямо перед глаголом — не согласие"
    соглас_проба "публиковать пока рано" 0 "обсуждение без распоряжения — не согласие"
    соглас_проба "а что будет если опубликовать?" 0 "вопрос владельца — не согласие"
    соглас_проба "да и вообще не надо" 0 "отрицание перевешивает"
    приёмник() {  # имя сессии, файл — поднять одноразовую панель с `cat > файл`
        tmux new-session -d -s "$1" "cat > '$2'"
        sleep 0.5
    }
    закрыть() { tmux kill-session -t "$1" 2>/dev/null || true; }
    забрать() {  # имя сессии, файл — закрыть stdin приёмника и вернуть текст
        tmux send-keys -t "$1" C-d 2>/dev/null || true
        sleep 0.5
        cat "$2" 2>/dev/null || true
    }
    итог() {  # ожидание, факт, имя случая
        if [ "$2" = "$1" ]; then printf '  ок    %s\n' "$3"
        else printf '  ПЛОХО %s: ждали «%s», получили «%s»\n' "$3" "$1" "$2"; ok_flag=0; fi
    }

    # 1. БОЛЬНОЙ СЛУЧАЙ: старый способ на тексте «Enter». tmux принимает
    #    аргумент за имя клавиши — в приёмник попадают переводы строки, а
    #    слова владельца нет вовсе. Ждём именно провала.
    TMUX_SESSION="harness-selftest-1-$$"
    приёмник "$TMUX_SESSION" "$T/1"
    tmux send-keys -t "$TMUX_SESSION" "Enter" Enter
    sleep 0.5
    got=$(забрать "$TMUX_SESSION" "$T/1"); закрыть "$TMUX_SESSION"
    if printf '%s' "$got" | grep -q 'Enter'; then
        printf '  ПЛОХО больной случай не воспроизвёлся: старый способ доставил «Enter» — проверка ничего не доказывает\n'; ok_flag=0
    else
        # od по ФАЙЛУ, не по $got: подстановка уже срезала переводы строки, и
        # улика «в приёмнике \n \n» из переменной не видна.
        printf '  ок    БОЛЬНОЙ СЛУЧАЙ: старый способ на тексте «Enter» кладёт в приёмник%s — слово потеряно целиком\n' "$(od -An -c "$T/1" | tr -s ' ' | head -1)"
    fi

    # 2. Тот же текст через send_to_pane — слово доезжает.
    TMUX_SESSION="harness-selftest-2-$$"
    приёмник "$TMUX_SESSION" "$T/2"
    send_to_pane "Enter"
    got=$(забрать "$TMUX_SESSION" "$T/2"); закрыть "$TMUX_SESSION"
    итог "Enter" "$got" "send_to_pane доставляет слово «Enter» как текст, а не как клавишу"

    # 3. Многострочный текст: \n и \r становятся пробелами, приходит одной строкой.
    TMUX_SESSION="harness-selftest-3-$$"
    приёмник "$TMUX_SESSION" "$T/3"
    # $'\n', а не $(printf '\n'): подстановка съедает хвостовые переводы строки,
    # и проверка многострочности гонялась бы на однострочном тексте (поймано
    # первым же прогоном — прибор доказал себя на себе).
    send_to_pane "первая"$'\n'"вторая"$'\r'"третья"
    got=$(забрать "$TMUX_SESSION" "$T/3"); закрыть "$TMUX_SESSION"
    итог "первая вторая третья" "$got" "перевод строки и возврат каретки заменены пробелом — сообщение одно, не три"

    # 5. Ответ панели формой «да 7391» не может стать согласием на выкат.
    if это_ответ_панели "да 7391" && это_ответ_панели "нет 481920" \
       && ! это_ответ_панели "да" && ! это_ответ_панели "да, выкатывай"; then
        printf '  ок    БОЛЬНОЙ СЛУЧАЙ: «да 7391» распознаётся как ответ панели, а голое «да» — нет\n'
    else
        printf '  ПЛОХО форма ответа панели распознаётся неверно\n'; ok_flag=0
    fi

    # 4. «C-c»: старым способом это сигнал, убивающий приёмник (и убил бы
    #    сессию агента); через send_to_pane — обычный текст, панель жива.
    TMUX_SESSION="harness-selftest-4-$$"
    приёмник "$TMUX_SESSION" "$T/4"
    tmux send-keys -t "$TMUX_SESSION" "C-c" Enter
    sleep 1
    if tmux has-session -t "$TMUX_SESSION" 2>/dev/null; then
        printf '  ПЛОХО больной случай «C-c» не воспроизвёлся: приёмник пережил старый способ\n'; ok_flag=0
    else
        printf '  ок    БОЛЬНОЙ СЛУЧАЙ: старый способ на тексте «C-c» оборвал приёмник сигналом (в бою — сессию агента)\n'
    fi
    закрыть "$TMUX_SESSION"
    TMUX_SESSION="harness-selftest-4b-$$"
    приёмник "$TMUX_SESSION" "$T/4b"
    send_to_pane "C-c"
