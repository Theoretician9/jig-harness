            # Через python3, а не прямым запуском: exec-бит теряется при
            # копировании (та же улика, что в razlozhit-harnes.sh про scp с
            # Windows), и вложения молча перестали бы качаться.
            DL=$(python3 "$HERE/skachat_vlozhenie.py" "$INBOX/$TS.txt" 2>&1) || DL_RC=$?
            if [ "$DL_RC" = 0 ]; then
                say "вложение скачано: $DL"
                KICK="Владелец прислал вложение ($KIND)${WORDS:+ с подписью: ${WORDS:0:600}}, файл скачан: $DL — посмотри его; сопроводительный JSON в $INBOX/$TS.txt, перенеси в $INBOX/обработано/."
                # Голосовое — РАСШИФРОВАТЬ и положить в очередь текстом: слушать
                # агент не умеет, а «посмотри файл» на аудио — тупик. Улика
                # 11.09.2026: голосовое в 79 секунд с заказом работы осталось
                # непрочитанным. Расшифровка локальная (faster-whisper), замер:
                # 79 с аудио → 24 с. Потолок 600 с в самом скрипте; ack владельцу
                # уже ушёл выше, так что эта пауза его не задерживает.
                if [ "$KIND" = "голосовое" ]; then
                    VOICE_RC=0
                    VOICE_TEXT=$(python3 "$HERE/rasshifrovat_golos.py" "$DL" 2>&1) || VOICE_RC=$?
                    if [ "$VOICE_RC" = 0 ] && [ -n "$VOICE_TEXT" ]; then
                        printf '%s\n' "$VOICE_TEXT" > "$INBOX/$TS.txt"
                        say "голосовое расшифровано: ${VOICE_TEXT:0:120}"
                        # Владельцу — что услышано: распознано криво, поправит сразу.
                        ack "$CHAT" "расшифровал голосовое: «${VOICE_TEXT:0:600}»"
                        KICK_TEXT="${VOICE_TEXT:0:600}"
                        [ ${#VOICE_TEXT} -gt 600 ] && KICK_TEXT="$KICK_TEXT… (обрезано, полностью — в файле)"
                        KICK="Владелец прислал ГОЛОСОВОЕ, расшифровка: $KICK_TEXT — полная версия в $INBOX/$TS.txt, прочитай и перенеси в $INBOX/обработано/. Аудио: $DL"
                    else
                        say "голосовое НЕ расшифровано (rc=$VOICE_RC): ${VOICE_TEXT:0:200}"
                        ack "$CHAT" "голосовое скачал, но расшифровать не смог: ${VOICE_TEXT:0:300}. Продиктуйте текстом или я разберусь с контуром."
                        KICK="Владелец прислал голосовое, но расшифровать не удалось: ${VOICE_TEXT:0:300}. Файл: $DL — разберись с контуром голосовых (scripts/rasshifrovat_golos.py --selftest) и ответь владельцу."
                    fi
                fi
            else
                say "вложение НЕ скачано (rc=$DL_RC): $DL"
                KICK="Владелец прислал вложение ($KIND)${WORDS:+ с подписью: ${WORDS:0:600}}, но скачать его не удалось: ${DL:0:300}. Координаты в $INBOX/$TS.txt — разберись и перенеси в $INBOX/обработано/."
                # Владельцу — СРАЗУ, не дожидаясь агента. Пережито 12.08.2026:
                # он прислал архив 92 МБ с первой задачей, получил обычное
                # «принял» и ждал, пока агент проснётся и объяснит. Кто узнал о
                # неудаче — тот и говорит; молчать о недоставленном нельзя.
                case "$DL" in
                    *"file is too big"*)
                        REASON="файл больше 20 МБ — Telegram не отдаёт ботам такие. Пришли ссылку на облако или разбей на части меньше 20 МБ." ;;
                    *)
                        REASON="${DL:0:200}" ;;
                esac
                ack "$CHAT" "Файл до меня НЕ дошёл: $REASON"
            fi
        fi
        # ── подтверждения полуавтомата ──────────────────────────────────────
        # «да/подтверждаю/ротация ок/ок» — ответ на анонс (выкат, ротация,
        # необратимое). Пишется отдельным журналом: его читают ворота
        # deploy_guard.py — разбирать всю очередь им не по чину.
        # СТРОГО ДО persist_offset (П-8): смерть в окне «offset сдвинут,
        # подтверждение не записано» теряла бы «да» владельца навсегда —
        # update уже не перечитается. Дубль записи при рестарте безопаснее
        # потери — тот же приём «дубль безопаснее потери», что и для inbox.
        # ${TEXT,,} — а не tr: tr не понимает многобайтную кириллицу, «ДА» бы прошло мимо.
        NORM="${WORDS,,}"
        NORM=$(printf '%s' "$NORM" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')
        # ── веб-панель: ссылка входа и ответ на её вопрос ───────────────────
        # Разбирается ДО согласий полуавтомата (M2, C3): ответ «да 7391» — это
        # согласие на ПЕРЕКЛЮЧАТЕЛЬ, и попади он в общий журнал согласий, тем же
        # словом открылись бы ворота выката. Ветка лёгкая и стоит первой.
        PANEL_DIR="$PROJECT_DIR/harness/панель"
        if [ -f "$PANEL_DIR/klient.py" ]; then
            # Диспетчер СПРАШИВАЕТ службу, а не пишет в её файлы: состояние
            # панели держит одна сторона, иначе права молча расходятся.
            PANEL_ANSWER=$(python3 "$PANEL_DIR/klient.py" --ответ "$WORDS" 2>/dev/null || echo "не ответ панели")
        else
            PANEL_ANSWER="не ответ панели"
        fi
        if [ "$PANEL_ANSWER" != "не ответ панели" ]; then
            say "ответ веб-панели: $PANEL_ANSWER (владельцу отвечает сама панель)"
            persist_offset "$UPDATE_ID"
            continue
        fi
        if это_ответ_панели "$NORM"; then
            # Форма совпала, а панель не применила: служба молчит или код
            # просрочен. Сказать владельцу прямо и ОСТАНОВИТЬСЯ — в согласия
            # такое слово не идёт (F-gen-01).
            ack "$CHAT" "Код не подошёл или устарел — переключение не применено. Открой панель и нажми ещё раз."
            say "ответ с кодом панели не применён (служба молчит или код просрочен) — в согласия не пишем"
            persist_offset "$UPDATE_ID"
            continue
        fi
        case "$NORM" in
            "панель выйти"|"выйти из панели")
                python3 "$PANEL_DIR/klient.py" --выйти "$CHAT" >/dev/null 2>&1 || true
                ack "$CHAT" "Вышел со всех устройств: прежние ссылки и пропуска панели больше не работают."
                persist_offset "$UPDATE_ID"
                continue ;;
            "обновить"|"обнови"|"обнови харнес"|"обновить харнес")
                # Обновление откатываемое (копия, самопроверка, возврат), но
                # долгое: запускаем фоном и сразу отвечаем — молчащий бот на
                # десять минут выглядит как сломанный.
                ack "$CHAT" "Принял: ставлю обновление харнеса. Сниму копию, проверю себя воротами и, если что-то не так, вернусь на прежнюю версию. Отчитаюсь итогом."
                setsid nohup python3 "$PROJECT_DIR/scripts/obnovlenie.py" --поставить \
                    >>"$LOG_DIR/obnovlenie-watch.log" 2>&1 < /dev/null &
                say "владелец попросил обновление — запущено фоном"
                persist_offset "$UPDATE_ID"
                continue ;;
            "panel")
                PANEL_LINK=$(python3 "$PANEL_DIR/klient.py" --ссылка "$CHAT" 2>&1)
                # disable_web_page_preview обязателен: предпросмотр Telegram
                # открывает ссылку сам, и вход сгорел бы до владельца (C4).
                отправить_без_предпросмотра "$CHAT" "$PANEL_LINK"
                say "ссылка на панель выдана: ${PANEL_LINK:0:60}"
                persist_offset "$UPDATE_ID"
                continue ;;
        esac
        AGREE=$(согласие_владельца "$WORDS")
        if [ -n "$AGREE" ]; then
            # ПРЕДМЕТ согласия проставляет тот, кто его распознал. Иначе знание
            # «что считать согласием на выкат» живёт в двух местах — здесь и в
            # списке форм внутри deploy_guard.py — и они расходятся: 20.08 ночи
            # диспетчер согласие принял, а ворота его же записи не признали,
            # потому что формы «по выкату пишу да» не было в ИХ списке.
            #
            # Строк может быть НЕСКОЛЬКО: «да, отправляй на гит» и «да,
            # выкатывай на прод» приходят одним сообщением, и каждая обязана
            # стать своей записью — иначе второе разрешение теряется молча
            # (улика 04.09.2026).
            while IFS= read -r AGREE_LINE; do
                [ -n "$AGREE_LINE" ] || continue
                KIND=""
                case "$AGREE_LINE" in *выкат*) KIND="deploy" ;; esac
                # Согласие БЕЗ названного предмета — «моё да», «да, конечно».
                # Предмет назван в ВОПРОСЕ агента, и распознаватель здесь его
                # не знает. Такая запись метится `any`: ворота принимают её за
                # согласие на анонсированное действие ровно так же, как они уже
                # принимают голое «да». Метка нужна, чтобы ворота НЕ разбирали
                # текст своим списком форм: 09.09.2026 «Моё да» диспетчер
                # признал, а ворота — нет, потому что их список знал только
                # «да/ок/подтверждаю». Знание о формах живёт здесь одно.
                if [ -z "$KIND" ] && [ "$(printf '%s' "$AGREE_LINE" | wc -w)" -le 3 ] \
                   && ! printf '%s' "$AGREE_LINE" | grep -qE 'гит|git|пуш|push|отправ'; then
                    KIND="any"
                fi
                jq -cn --arg ts "$(date -Is)" --arg text "$AGREE_LINE" --arg mid "$MSG_ID" \
                    --arg kind "$KIND" \
                    '{ts:$ts, text:$text, message_id:$mid} + (if $kind == "" then {} else {kind:$kind} end)' \
                    >> "$CONFIRM_LOG"
                say "подтверждение: «$AGREE_LINE» → $CONFIRM_LOG"
            done <<< "$AGREE"
        fi

        # ── «модель» и «модель <имя>»: переключатель, не зависящий от агента ──
        # Задача владельца 15.08.2026. Разбирает ДИСПЕТЧЕР, а не агент: смысл
        # инструмента в том, чтобы модель переключалась и тогда, когда агент
        # занят длинной работой, залип или не поднялся вовсе — именно в этих
        # случаях за переключателем и тянутся. Агент об этом всё равно узнает:
        # сообщение уже легло в inbox выше по коду.
        case "$NORM" in
            модель|"модель "*)
                MODEL_ARG="${NORM#модель}"
                MODEL_ARG="${MODEL_ARG## }"
                MODEL_SH="$HERE/model.sh"
                if [ ! -x "$MODEL_SH" ]; then
                    ack "$CHAT" "Переключатель моделей не найден: $MODEL_SH"
                elif [ -z "$MODEL_ARG" ]; then
                    ack "$CHAT" "$("$MODEL_SH" 2>&1)"
                else
                    # Отвязка обязательна: переключение уводит сессию в ротацию,
                    # а ротация убивает агента — диспетчер обязан пережить это и
                    # продолжать слушать канал.
                    ack "$CHAT" "Переключаю модель на «$MODEL_ARG» и ухожу в ротацию — вернусь уже на ней."
                    setsid nohup "$MODEL_SH" "$MODEL_ARG" \
                        >> "$LOG_DIR/model-switch.log" 2>&1 < /dev/null &
                fi
                ;;
        esac

        # Входящее НА ДИСКЕ (и в inbox, и в confirmations) — только теперь
        # двигаем offset (К-1а, П-8): упади мы до этой строки, рестарт
        # перечитает update и положит его заново.
        persist_offset
        say "в очередь: $INBOX/$TS.txt (message_id=$MSG_ID)"
        dostavit_agentu "$TS" "$WORDS" "$KICK" "${AGREE:-}"
    done
done
