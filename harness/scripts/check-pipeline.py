#!/usr/bin/env python3
"""Гейт середины пайплайна: у крупной задачи есть спека и ревью спеки.

Откуда взят. Владелец 11.09.2026: «пайплайн контролируется по концам. Вход и
выход. Середина на честном слове <…> Всё, что можно сделать кодом, делается
кодом». Первый из трёх названных им пунктов: «Задачу крупного тира не коммитить
без файла спеки, привязанного к её id».

Три решения, каждое — находка adversarial-ревью спеки:

* **Якорь — поле `spec:` в карточке задачи** `dev-map.yaml`, а не имя файла и не
  строка в тексте. Замер 11.09: файлов `спека.md` в `.tasks/` — ноль, строку
  «Задача карты» несут 2 файла из 63, а глоб `спека*.md` ловил `спека-REVIEW.md`
  и зачёл бы ревью за спеку (ложный зелёный).
* **Водораздел по дате.** Судятся задачи, начатые не раньше даты в конфиге.
  Переписывать 63 старых файла под новую конвенцию — работа без пользы, а
  краснеющий на истории гейт отключают.
* **Честная дверь.** `HARNESS_PIPELINE_FORCE=1` вместе с причиной в
  `HARNESS_PIPELINE_WHY` пропускает гейт и оставляет строку в журнале обходов.
  Гейт без двери обходят `--no-verify`, и следа не остаётся вовсе.

Прогон:
    python3 scripts/check-pipeline.py            # судит текущий индекс
    python3 scripts/check-pipeline.py --selftest
Код возврата: 0 — чисто, 1 — нарушение, 77 — жёлтый (обкатка, коммит идёт).
"""
