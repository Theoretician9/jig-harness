def задачи_в_rabote(карта=None) -> list:
    """Все карточки в статусе wip. Отдельно от `задача_карты`, потому что
    отказу нужно НАЗВАТЬ ЧИСЛО: «нужна одна» без «а у тебя три» заставляет
    искать их глазами."""
    import yaml
    путь = карта or (КОРЕНЬ / "dev-map.yaml")
    try:
        with open(путь, encoding="utf-8") as fh:
            данные = yaml.safe_load(fh)
    except (OSError, ValueError, ImportError):
        return []

    def обход(узел):
        if isinstance(узел, dict):
            if "id" in узел and узел.get("status") == "wip":
                yield узел
            for значение in узел.values():
                yield from обход(значение)
        elif isinstance(узел, list):
            for значение in узел:
                yield from обход(значение)

    return list(обход(данные))


