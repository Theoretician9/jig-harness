def _модуль_цены():
    """Импорт модуля цены: имя файла кириллицей, обычным import не берётся."""
    import importlib.util
    путь = КОРЕНЬ / "scripts" / "pajplajn.py"
    спец = importlib.util.spec_from_file_location("пайплайн", путь)
    модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(модуль)
    return модуль


def задача_карты(карта=None):
    """(id, карточка) единственной задачи в работе. Неоднозначно — (None, None)."""
    import yaml
    путь = карта or (КОРЕНЬ / "dev-map.yaml")
    try:
        with open(путь, encoding="utf-8") as fh:
            данные = yaml.safe_load(fh)
    except (OSError, ValueError, ImportError):
        return None, None

    def обход(узел):
        if isinstance(узел, dict):
            if "id" in узел and узел.get("status") == "wip":
                yield узел
            for значение in узел.values():
                yield from обход(значение)
        elif isinstance(узел, list):
            for значение in узел:
                yield from обход(значение)

    задачи = list(обход(данные))
    if len(задачи) != 1:
        return None, None
    return задачи[0]["id"], задачи[0]


def старше_водораздела(карточка, водораздел):
    """Задача начата раньше включения гейта — её правила не касаются."""
    начата = ((карточка.get("when") or {}).get("started")) if карточка else None
    if not начата or not водораздел:
        return False
    return str(начата) < str(водораздел)


# Где живёт артефакт каждого шага. Вопрос владельца 11.09: «По поводу договора
# о задаче, почему машина не может?» — может: у договора и плана есть файл.
# Машинно непроверяемым остаётся только то, у чего артефакта нет вовсе.
def _где_артефакт(шаг, id_задачи, спека, корень):
    """(путь, человеческое имя) либо (None, имя) — если шага мы судить не умеем."""
    основа = (Path(корень) / спека) if спека else None
    if шаг == "спека":
        return основа, "спека"
    if шаг == "ревью_спеки" and основа:
        return основа.with_name(основа.stem + "-REVIEW" + основа.suffix), "ревью спеки"
    if шаг == "ревью_кода" and основа:
        return основа.with_name(основа.stem + "-CODE-REVIEW" + основа.suffix), "ревью кода"
    if шаг == "контракт":
        return Path(корень) / ".tasks" / id_задачи / "pretask.yaml", "контракт задачи"
    if шаг == "план":
        return Path(корень) / ".tasks" / id_задачи / "план.md", "план"
    return None, шаг


def проверить(карточка, корень=КОРЕНЬ, шаги=None):
    """Чего не хватает задаче. Чистая функция — её и проверяет самотест.

    Список шагов — из пульта владельца: какие бумаги требовать, решает он, а не
    код. Шаг «тесты» здесь не проверяется: его судит отдельный гейт по каждому
    коммиту, а не по наличию файла.
    """
    шаги = шаги or ["спека", "ревью_спеки"]
    id_задачи = (карточка or {}).get("id") or "-"
    спека = (карточка or {}).get("spec")
    беды = []
    if not спека and any(ш in шаги for ш in ("спека", "ревью_спеки", "ревью_кода")):
        беды.append("в карточке задачи нет поля spec: — спека не привязана к задаче")
        return беды
    for шаг in шаги:
        if шаг == "тесты":
            continue           # судится гейтом тестов по коммитам, не файлом
        путь, имя = _где_артефакт(шаг, id_задачи, спека, корень)
        if путь is None:
            continue           # шаг без артефакта судить нечем — и мы этого не делаем
        if not путь.exists():
            беды.append(f"нет шага «{имя}»: ожидается {путь.relative_to(Path(корень))}")
    return беды


def _карта_из(ревизия):
    """dev-map.yaml из индекса (':') или из HEAD — чтобы увидеть СМЕНУ статуса.

    None — «не прочитали». До 14.09.2026 любой отказ git отдавался пустым
    словарём: переходов в test в нём не находилось, и гейт закрытия молчал
    ровно там, где судить было нечем.
    """
    import yaml
    try:
        готово = subprocess.run(
            ["git", "-C", str(КОРЕНЬ), "show", f"{ревизия}dev-map.yaml"],
            capture_output=True, text=True, errors="replace", timeout=30)
    except (OSError, subprocess.SubprocessError):
        return None
    if готово.returncode != 0:
        return None
    try:
        return yaml.safe_load(готово.stdout) or {}
    except (ValueError, yaml.YAMLError):
        return None


def карты_коммита():
    """Статусы (HEAD, индекс) — или None, если git не отдал карту.

    Пустой HEAD — не сбой: на свежей установке коммитов ещё нет, и первый
    коммит новой машины не должен упираться в гейт (тот же случай уже ловил
    check-imports 13.09.2026). Красным остаётся только отказ самого git.
    """
    было, стало = _карта_из("HEAD:"), _карта_из(":")
    if было is None and _git_жив():
        было = {}
    if было is None or стало is None:
        return None
    return _статусы(было), _статусы(стало)


def _git_жив():
    """git отвечает и мы в репозитории — значит пустой ответ означает пустоту."""
    try:
        return subprocess.run(["git", "-C", str(КОРЕНЬ), "rev-parse", "--git-dir"],
                              capture_output=True, timeout=30).returncode == 0
    except (OSError, subprocess.SubprocessError):
        return False


def _статусы(дерево):
    """id → карточка. При повторе id побеждает УЖЕ ЗАКРЫТАЯ карточка.

    11.09.2026 карта две недели несла один id дважды (test с закрытыми
    пунктами и plan с пустым списком). Словарь брал последнюю, гейт считал
    задачу незакрытой, и уборка дубля выглядела для него закрытием без
    пайплайна. Повтор ловит гейт карты; здесь важно не судить по случайному
    из двух экземпляров.
    """
    статусы = {}
    порядок = {"plan": 0, "wip": 1, "test": 2, "done": 3}

    def обход(узел):
        if isinstance(узел, dict):
            if "id" in узел and "status" in узел:
                прежняя = статусы.get(узел["id"])
                if (прежняя is None
                        or порядок.get(узел["status"], 0)
                        >= порядок.get(прежняя.get("status"), 0)):
                    статусы[узел["id"]] = узел
            for значение in узел.values():
                обход(значение)
        elif isinstance(узел, list):
            for значение in узел:
                обход(значение)

    обход(дерево)
    return статусы


def переходы_в_test(было, стало):
    """Чистая часть М5: какие задачи СМЕНИЛИ статус на test. Её и проверяем."""
    переходы = []
    for id_задачи, карточка in стало.items():
        если_было = (было.get(id_задачи) or {}).get("status")
        if карточка.get("status") == "test" and если_было != "test":
            переходы.append((id_задачи, карточка))
    return переходы


def взятые_в_работу(было, стало):
    """Задачи, которые этим коммитом ВЗЯТЫ в работу: plan → wip или plan → test.

    Момент «взятие задачи в работу» в коде не существовал вовсе (находка
    adversarial-ревью C-2 от 13.09.2026): `when.started` не пишет никто, и
    оценка глубины повисла бы на внимании смены. Переход статуса — тот же
    приём, которым уже ловится закрытие: сравнение индекса с HEAD.

    plan → test берётся наравне с plan → wip: работа, сделанная одним махом,
    минует wip, и без этой ветки она обходила бы правило целиком.
    """
    переходы = []
    for id_задачи, карточка in стало.items():
        было_ст = (было.get(id_задачи) or {}).get("status")
        стало_ст = карточка.get("status")
        if стало_ст in ("wip", "test") and было_ст == "plan":
            переходы.append((id_задачи, карточка))
    return переходы


def проверить_взятие(взятые):
    """У задачи, взятой в работу, глубина обязана быть назначена.

    Судятся ТОЛЬКО карточки, чей статус меняется в этом коммите: у 114 из 143
    карточек нет `when.started`, и водораздел их не защищает (находка C-3) —
    опираться на пустое поле значит краснеть на всей карте разом.
    """
    беды = []
    for id_задачи, карточка in взятые:
        глубина = карточка.get("глубина")
        # Не словарь — это тоже «глубины нет»: гейт взятия стоит РАНЬШЕ
        # схемного валидатора карты (ревью кода 13.09, C-4), и падать здесь
        # значило бы уронить весь pre-commit вместо внятной находки.
        if not isinstance(глубина, dict):
            глубина = {}
        if not (глубина.get("уровень") and глубина.get("характер")):
            беды.append(
                f"{id_задачи} взята в работу без назначенной глубины: впиши поле "
                f"«глубина» (уровень и характер). Подсказка: "
                f"python3 scripts/pajplajn.py --подсказать {id_задачи}")
        elif глубина.get("кем") == "автомат":
            # Заготовку ставит автомат карточек, чтобы поле не приходило пустым,
            # но РЕШЕНИЕ остаётся за сменой: ревью спеки 13.09 (C-2, C-5)
            # запретило выводить глубину формулой — volume самоотчётен. Автомат
            # не знает ни объёма работы, ни того, что владелец имел в виду.
            беды.append(
                f"{id_задачи} уходит в работу с заготовкой автомата: глубина не "
                f"подтверждена сменой. Проверь уровень и характер и переподпиши "
                f"поле «кем» словом «смена». Подсказка: "
                f"python3 scripts/pajplajn.py --подсказать {id_задачи}")
    return беды


ПОРЯДОК_УРОВНЕЙ = ("мелкая", "обычная", "крупная")


def сверить_глубину(карточка, имя_уровня_факта):
    """Объявленная глубина против замера диффа. → (цвет, строка) либо None.

    Сверка, а не вторая шкала: замер коммита остаётся единственным судьёй
    ФАКТА, объявление — единственным судьёй ЗАМЫСЛА. Расхождение на один
    уровень обычное дело (работа выросла), на два — значит работа была названа
    мелкой, а оказалась крупной, и спеку никто не писал.
    """
    объявлено = ((карточка or {}).get("глубина") or {}).get("уровень")
    if объявлено not in ПОРЯДОК_УРОВНЕЙ or имя_уровня_факта not in ПОРЯДОК_УРОВНЕЙ:
        return None
    разрыв = ПОРЯДОК_УРОВНЕЙ.index(имя_уровня_факта) - ПОРЯДОК_УРОВНЕЙ.index(объявлено)
    if разрыв <= 0:
        return None                      # факт не крупнее замысла — вопросов нет
    строка = (f"объявлена «{объявлено}», по коммитам вышла «{имя_уровня_факта}»")
    return ("красный", строка) if разрыв >= 2 else ("жёлтый", строка)


def закрываемые():
    """Задачи, которые этим коммитом переводятся в test.

    Гейт закрытия висит на переходе в `test`, а не в `done`: замер 11.09 —
    done стоит у 1 задачи из 94, потому что done по правилам проекта ставит
    владелец после своей проверки. Момент, когда работу объявляю сделанной я, —
    это test (находка ревью I-4).
    """
    карты = карты_коммита()
    return переходы_в_test(*карты) if карты else None


def записать_обход(причина, задача):
    строка = json.dumps({"ts": str(date.today()), "гейт": "пайплайн",
                         "задача": задача or "-", "почему": причина},
                        ensure_ascii=False)
    try:
        ЖУРНАЛ_ОБХОДОВ.parent.mkdir(parents=True, exist_ok=True)
        with open(ЖУРНАЛ_ОБХОДОВ, "a", encoding="utf-8") as fh:
            fh.write(строка + "\n")
    except OSError:
        pass


def самотест():
    случаи = [
        ({}, 1, "БОЛЬНОЙ СЛУЧАЙ: крупная задача без поля spec — находка"),
        ({"spec": "docs/specs/нет-такой.md"}, 2,
         "спека указана, а файла нет — находки и на спеку, и на её ревью"),
        ({"spec": "docs/specs/2026-09-11-пайплайн-под-код.md"}, 0,
         "спека и ревью на месте — чисто"),
    ]
    ok = True
    for карточка, ждём, зачем in случаи:
        вышло = len(проверить(карточка))
        if вышло != ждём:
            ok = False
            print(f"  ПЛОХО {зачем}: бед {вышло}, ждали {ждём}")
        else:
            print(f"  ок    {зачем}")

    # БОЛЬНОЙ СЛУЧАЙ 11.09.2026: один id в карте дважды — test и plan. Словарь
    # брал последнюю карточку, и уборка дубля читалась как закрытие задачи без
    # пайплайна: коммит встал, хотя закрытие прошло неделей раньше.
    дерево_с_дублем = {"lines": [{"id": "harness", "tasks": [
        {"id": "hr.проба", "status": "test"},
        {"id": "hr.проба", "status": "plan"}]}]}
    дерево_без = {"lines": [{"id": "harness", "tasks": [
        {"id": "hr.проба", "status": "test"}]}]}
    if not переходы_в_test(_статусы(дерево_с_дублем), _статусы(дерево_без)):
        print("  ок    БОЛЬНОЙ СЛУЧАЙ: уборка дубля id не считается закрытием")
    else:
        ok = False
        print("  ПЛОХО уборка дубля id зачлась переходом в test")

    # Настоящий переход виден по-прежнему.
    if переходы_в_test(_статусы({"lines": [{"id": "harness", "tasks": [
            {"id": "hr.проба", "status": "wip"}]}]}), _статусы(дерево_без)):
        print("  ок    настоящий переход wip → test виден")
    else:
        ok = False
        print("  ПЛОХО переход wip → test потерян")

    # Задача в работе не обязана нести бумаги будущих шагов (улика 11.09.2026:
    # коммит спеки требовал плана, контракта и ревью кода).
    в_работе = {"id": "hr.проба", "status": "wip",
                "spec": "docs/specs/2026-09-11-пайплайн-под-код.md"}
    полные = ["спека", "ревью_спеки", "контракт", "план", "ревью_кода"]
    урезанные = [ш for ш in полные if ш in ("спека", "ревью_спеки")]
    if проверить(в_работе, шаги=урезанные) == [] and проверить(в_работе, шаги=полные):
        print("  ок    БОЛЬНОЙ СЛУЧАЙ: задача в работе судится по пройденному пути")
    else:
        ok = False
        print("  ПЛОХО задача в работе судится по всему списку шагов")

    # Ревью спеки НЕ засчитывается за спеку: прежний глоб «спека*.md» ловил
    # именно этот файл и красил гейт зелёным там, где спеки нет.
    ревью_как_спека = проверить({"spec": "docs/specs/2026-09-11-пайплайн-под-код-REVIEW.md"})
    if ревью_как_спека:
        print("  ок    БОЛЬНОЙ СЛУЧАЙ: файл ревью за спеку не засчитан")
    else:
        ok = False
        print("  ПЛОХО ревью спеки зачлось за спеку")

    # Шаг, включённый ПОЗЖЕ старта задачи, эту задачу не судит (вопрос
    # владельца 11.09.2026: «А что будет с текущими задачами, когда пользователь
    # переключает правила пайплайна?»). Иначе включение шага красит работу,
    # которая была почти закончена, и требует бумаг, которых на её старте
    # никто не просил.
    пульт = {"шаги": {"крупная": ["спека", "план"]},
             "шаги_включены": {"крупная": {"план": "2026-09-11"}}}
    старая = {"id": "a", "when": {"started": "2026-09-01"}}
    новая = {"id": "b", "when": {"started": "2026-09-12"}}
    если_старая = шаги_для_задачи(пульт, "крупная", старая)
    если_новая = шаги_для_задачи(пульт, "крупная", новая)
    сегодняшняя = шаги_для_задачи(пульт, "крупная", {"id": "d", "when": {"started": "2026-09-11"}})
    if "план" not in если_старая and "план" in если_новая and "план" not in сегодняшняя:
        print("  ок    БОЛЬНОЙ СЛУЧАЙ: шаг включён позже старта — старую задачу не судит")
        print("  ок    задачу того же дня новое правило тоже не судит")
    else:
        ok = False
