def _проба_отказа_git() -> int:
    """Гейт краснеет, когда git молчит, и называет ПРИЧИНУ.

    Два чтения git подряд — состав коммита и карта, — поэтому боевой путь
    упирается в первое же; слово ищется общее. Отказ ИМЕННО на карте
    проверяется вторым путём: несуществующая ревизия — настоящий отказ git,
    подмены не требует.
    """
    sys.path.insert(0, str(КОРЕНЬ / "scripts" / "lib"))
    from proba_git import гейт_краснеет_без_git
    # Честная дверь гасится явно: иначе проба судила бы обход, а не гейт.
    плохо = гейт_краснеет_без_git(__file__, "", "не прочитан",
                                  {"HARNESS_PIPELINE_FORCE": ""})
    if _карта_из("НЕТ-ТАКОЙ-РЕВИЗИИ:") is None:
        print("  ок    карта из несуществующей ревизии — «не прочитали», а не пустая карта")
    else:
        print("  ПЛОХО отказ git на карте вернул пустую карту вместо None")
        плохо = 1
    return плохо


def шаги_уровня(настройки, имя_уровня):
    """Какие бумаги требует этот уровень — из пульта, с разумным умолчанием."""
    из_пульта = (настройки.get("шаги") or {}).get(имя_уровня)
    if из_пульта is not None:
        return list(из_пульта)
    return {"мелкая": [], "обычная": ["тесты"],
            "крупная": ["спека", "ревью_спеки", "контракт", "тесты"]}[имя_уровня]


def сузить_характером(настройки, шаги, карточка):
    """Шаги уровня, суженные ХАРАКТЕРОМ работы. Пустой характер ничего не режет.

    Ревью кода 13.09.2026 (C-1): характер читался только подсказкой
    `pajplajn.py --подсказать`, а гейт закрытия судил по одному уровню — то
    есть центральная часть задачи не действовала, а выглядела рабочей.
    Аварийной починке по-прежнему требовалась спека, и единственным выходом
    оставалась честная дверь.

    Сужение, а не замена: характер может УБРАТЬ шаг уровня, но не добавить
    новый. Иначе «починка» у мелкой задачи потребовала бы ревью кода, которого
    её уровень не просит.
    """
    характер = ((карточка or {}).get("глубина") or {}).get("характер")
    если_дано = (настройки.get("характеры") or {}).get(характер) or {}
    разрешено = если_дано.get("шаги")
    if not характер or разрешено in (None, "все"):
        return list(шаги)
    разрешено = set(разрешено)
    return [ш for ш in шаги if ш in разрешено]


def шаги_для_задачи(настройки, имя_уровня, карточка):
    """Шаги уровня МИНУС те, что включены позже, чем задача начата.

    Вопрос владельца 11.09.2026 (голосом): «что будет с текущими задачами,
    когда пользователь переключает правила пайплайна, если задача уже доведена
    до какого-то этапа, а пользователь включил предыдущий этап?» Правильный
    ответ — ничего: новое правило судит новые задачи. Иначе включение шага
    краснит почти законченную работу и требует бумаг, которых на её старте
    никто не просил (живой случай в тот же вечер: панель управления).

    Шаг без даты включения (был всегда) требуется, как и прежде. Сравнение
    СТРОГОЕ: у задач дата начала без времени, и «включил сегодня» не должно
    задним числом судить работу, начатую сегодня же утром — правило вступает
    в силу со следующего дня.
    """
    шаги = сузить_характером(настройки, шаги_уровня(настройки, имя_уровня), карточка)
    включены = ((настройки.get("шаги_включены") or {}).get(имя_уровня) or {})
    начата = str(((карточка or {}).get("when") or {}).get("started") or "")
    if not начата:
        return шаги          # неизвестно, когда начата — судим по полным правилам
    return [ш for ш in шаги
            if not включены.get(ш) or начата > str(включены[ш])]


def проверить_закрытие(цена, настройки):
    """М5: задача уходит в test — значит середина её пайплайна пройдена."""
    водораздел = (настройки.get("строгость") or {}).get("водораздел")
    беды = []
    переходы = закрываемые()
    if переходы is None:
        return ["карта не прочитана: git не отдал dev-map.yaml — судить нечем"]
    for id_задачи, карточка in переходы:
        if старше_водораздела(карточка, водораздел):
            continue
        признаки = цена.признаки_задачи(id_задачи)
        if признаки is None:
            continue           # коммитов с трейлером ещё нет — судить нечего
        значение = цена.цена(признаки, настройки["веса"])
        if цена.уровень(значение, настройки["пороги"]) != "крупная":
            continue
        for беда in проверить(карточка,
                              шаги=шаги_для_задачи(настройки, "крупная", карточка)):
            беды.append(f"{id_задачи} уходит в test (цена задачи {значение}): {беда}")
    return беды


def дверь_открыта(id_задачи: str) -> bool:
    """Честная дверь: обход с НАЗВАННОЙ причиной, записанной в журнал.

    Дверь общая для всех отказов гейта. Пока она стояла у одной ветки из двух,
    закрытие задачи ниже порога «крупная» обойти было нечем, и оставался лишь
    --no-verify, после которого следа не остаётся вовсе (13.09.2026).
    """
    if not os.environ.get("HARNESS_PIPELINE_FORCE"):
        return False
    причина = (os.environ.get("HARNESS_PIPELINE_WHY") or "").strip()
    if not причина:
        print("[пайплайн] обход без причины не открывает дверь: "
              "задай HARNESS_PIPELINE_WHY")
        return False
    записать_обход(причина, id_задачи)
    print(f"[пайплайн] обход разрешён и записан в журнал: {причина}")
    return True


