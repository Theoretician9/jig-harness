#!/usr/bin/env python3
"""Живая проверка обработчика входящих (класс B2): прогон на ЗАПИСАННОМ слове.

Откуда взято: спека `docs/specs/2026-10-15-живая-проверка-механизмов.md` §3.1,
класс B2 — «прогнан на ЗАПИСАННОМ живом сообщении владельца из
inbox/обработано/; подделать входящее нельзя: проверяемый написал бы себе
улику». Носителя этому предикату не было: `inbox-digest.py` так и стоял в
исходе «ждёт — стенда класса B2», а `attention-word.py` и `secret-intake.py`
были возвращены в непроверенные пересудом 17.10.

Чем это отличается от самотеста. Вход берётся не из головы прибора, а из
каталога, куда его положил ДИСПЕТЧЕР, и авторство слова доказывается ЕГО
машинным журналом `inbox.jsonl` (message_id там ставит телеграм). Сообщение
старше этого журнала принимается с оговоркой вслух: журнала тогда не вели.

Два предиката ответа, потому что механизмы делают с сообщением РАЗНОЕ: один
достаёт из него кусок (эхо-входа), другой заменяет в нём значение
(не-как-вход). Третьего вида в данных нет — его бы и судить было нечем.

Запуск:
    python3 scripts/live-check-inbox.py <механизм> [<механизм>…] [--записать]
    python3 scripts/live-check-inbox.py --всё [--записать]
Код возврата: 0 — доказаны все названные, 1 — хоть один нет.

Чем доказано: scripts/test_live_check_inbox.py (больным случаем первым —
механизм, который вернул слова владельца как есть).
"""
from __future__ import annotations

import datetime
import difflib
import json
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile

import yaml

КОРЕНЬ = pathlib.Path(os.environ.get("HARNESS_LIVE_CHECK_REPO")
                      or pathlib.Path(__file__).resolve().parent.parent)
СОСТОЯНИЕ = pathlib.Path(os.environ.get("HARNESS_LIVE_CHECK_STATE")
                         or КОРЕНЬ / "harness" / "config" / "live-check-state.yaml")
ДАННЫЕ = pathlib.Path(os.environ.get("HARNESS_LIVE_CHECK_INBOX")
                      or КОРЕНЬ / "harness" / "config" / "live-check-inbox.yaml")
def _корень_следов() -> pathlib.Path:
    """Корень следов — у общего загрузчика: умолчание внутри репозитория
    отдавало весь вывод произвольной команды гиту."""
    sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent / "lib"))
    import config as конф                                 # noqa: PLC0415
    return pathlib.Path(конф.live_check_trace_root())


СЛЕДЫ = pathlib.Path(os.environ.get("HARNESS_LIVE_CHECK_INBOX_TRACE_DIR")
                     or _корень_следов() / "hr.zhivaya-proverka-vseh-mehanizmov"
                     / "живьём-входящие")
ЦИТАТА_ЗНАКОВ = 12
ЭХО_ЗНАКОВ = 6
ПРЕДЕЛ_СЕК = 120
# Сколько записанных сообщений перебираем, идя от свежих. Перебор по всем 1300
# стоил бы прогон механизма на каждом; подходящее находится среди свежих.
ПЕРЕБОР = 400


def плотно(текст: str) -> str:
    return " ".join(текст.split())


def log_dir() -> str:
    """Каталог журналов. Своя переменная старше конфига: без неё проба играла
    бы на БОЕВЫХ журналах ([[the-probe-played-on-production]])."""
    свой = os.environ.get("HARNESS_LOG_DIR")
    if свой:
        return свой
    sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent / "lib"))
    import config as конф                                 # noqa: PLC0415
    return конф.log_dir()


def данные() -> dict:
    if not ДАННЫЕ.is_file():
        print(f"[живая проверка входящих] нет данных {ДАННЫЕ} — судить нечем",
              file=sys.stderr)
        return {}
    прочтено = yaml.safe_load(ДАННЫЕ.read_text(encoding="utf-8")) or {}
    return прочтено.get("входящие") or {}


def журнал_диспетчера() -> tuple[str, float | None]:
    """(все слова владельца из inbox.jsonl одним текстом, ts первой записи).

    Журнал пишет ДИСПЕТЧЕР, message_id в нём ставит телеграм — это и делает его
    уликой об авторстве. Журнала нет или он не читается — ts None: тогда прибор
    не выдаёт авторство за доказанное, а говорит это в записи вслух."""
    файл = pathlib.Path(log_dir()) / "inbox.jsonl"
    try:
        строки = [с for с in файл.read_text(encoding="utf-8",
                                            errors="replace").splitlines() if с.strip()]
    except OSError:
        return "", None
    тексты, первый = [], None
    for с in строки:
        try:
            запись = json.loads(с)
        except json.JSONDecodeError:
            continue
        тексты.append(плотно(запись.get("text") or ""))
        if первый is None and запись.get("ts"):
            try:
                первый = datetime.datetime.fromisoformat(запись["ts"]).timestamp()
            except ValueError:
                первый = None
    return "\n".join(тексты), первый


def записанные_сообщения() -> list[pathlib.Path]:
    """Файлы слов владельца, которые положил диспетчер, от свежих к старым.

    Сырое update (JSON вместо текста) пропускается: это не слова, а конверт."""
    каталог = pathlib.Path(log_dir()) / "inbox" / "обработано"
    файлы = sorted(каталог.glob("*.txt"), key=lambda ф: ф.name, reverse=True)
    годные = []
    for ф in файлы[:ПЕРЕБОР]:
        try:
            текст = ф.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        if текст.lstrip().startswith("{") or not текст.strip():
            continue
        годные.append(ф)
    return годные


def авторство(файл: pathlib.Path, журнал: str, начало: float | None) -> str | None:
    """Чем доказано, что это слова владельца, либо None — доказательства нет."""
    текст = плотно(файл.read_text(encoding="utf-8", errors="replace"))
    if текст[:60] and текст[:60] in журнал:
        return f"есть в машинном журнале диспетчера inbox.jsonl (message_id ставит телеграм)"
    try:
        метка = float(файл.stem)
    except ValueError:
        return None
    if начало is not None and метка < начало:
        когда = datetime.datetime.fromtimestamp(метка).date().isoformat()
        return (f"записано {когда} — раньше первой строки журнала входящих, "
                f"машинного журнала тогда не вели")
    return None


def команда(механизм: str, запись: dict, входящее: pathlib.Path,
            стенд: pathlib.Path) -> list[str]:
    """Команда, которой механизм зовут в жизни, с подстановкой слов владельца."""
    зов = (запись.get("зов") or "").strip()
    файл = str(КОРЕНЬ / механизм)
    подстановка = {"стенд": str(стенд), "метка": входящее.stem,
                   "входящее": str(входящее)}
    доводы = [str(д).format(**подстановка) for д in (запись.get("доводы") or [])]
    if зов == "довод":
        текст = входящее.read_text(encoding="utf-8", errors="replace")
        return [sys.executable, файл, *доводы, текст]
    if зов == "stdin":
        # Обёртка следа закрывает stdin, и слово владельца подаётся файлом —
        # ровно тем, который положил диспетчер.
        внутри = " ".join([sys.executable, файл, *доводы])
        return ["bash", "-c", f'{внутри} < "$1"', "--", str(входящее)]
    if зов == "очередь":
        (стенд / "inbox").mkdir(parents=True, exist_ok=True)
        shutil.copy2(входящее, стенд / "inbox" / входящее.name)
        return [sys.executable, файл, *доводы]
    return []


def позвать(механизм: str, запись: dict, входящее: pathlib.Path,
            стенд: pathlib.Path, обёрткой: bool) -> tuple[str, int, list[str]]:
    """(ответ механизма, код, команда). Обёрткой — когда пишем след.

    Каждый зов получает ЧИСТЫЙ стенд: механизм, которому прибор подложил свой
    же прошлый файл, честно отказал («хранилище не записано (File exists)»), и
    отказ выглядел работой — ответ ведь отличался от слов владельца."""
    свой = pathlib.Path(tempfile.mkdtemp(dir=стенд))
    зовём = команда(механизм, запись, входящее, свой)
    if not зовём:
        return "", 2, []
    среда = dict(os.environ)
    for имя, значение in (запись.get("среда") or {}).items():
        путь = КОРЕНЬ / str(значение)
        среда[имя] = str(путь) if путь.exists() else str(значение)
    if обёрткой:
        среда["HARNESS_LIVE_CHECK_TRACE_DIR"] = str(СЛЕДЫ)
        зовём = ["bash", str(КОРЕНЬ / "scripts" / "live-check.sh"),
                 механизм, "--", *зовём]
    готово = subprocess.run(зовём, capture_output=True, text=True,
                            timeout=ПРЕДЕЛ_СЕК, cwd=str(КОРЕНЬ), env=среда)
    return (готово.stdout or "") + (готово.stderr or ""), готово.returncode, зовём


def значения_в_речи(текст: str) -> list[str]:
    """Что судья форм считает значением ключа в этих словах. Тот же судья, что
    у механизма: судится не правило, а ИСХОД — значение в ответ не попало."""
    sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent / "lib"))
    import patterns as формы                              # noqa: PLC0415
    try:
        найдено = формы.секреты_в_речи(текст)
    except Exception:                                      # noqa: BLE001
        return []
    значения = []
    for н in найдено:
        значения.append(н if isinstance(н, str) else str((н or [""])[0]))
    return [з for з in значения if з]


def ответ_годен(ждём: str, вход: str, ответ: str, признак: str = "") -> tuple[bool, str]:
    """Выполнен ли предикат ОТВЕТА этого механизма, и что сказать, если нет.

    Признак успеха обязателен там, где у механизма есть СВОЙ отказ: приёмник
    секретов на отказ хранилища печатает «секрет не принят», и это «не как
    вход» ровно так же, как удача. Прибор принял такой отказ за доказательство
    на первом же прогоне 17.10.2026."""
    плотный_ответ, плотный_вход = плотно(ответ), плотно(вход)
    if not плотный_ответ:
        return False, "ответ пуст"
    if признак and признак not in ответ:
        return False, (f"в ответе нет признака удачи «{признак}» — "
                       f"механизм отказал или сделал не своё дело")
    if ждём == "эхо-входа":
        низ_вход = плотный_вход.lower()
        куски = [к for к in плотный_ответ.lower().split("\n") if к]
        for строка in [плотный_ответ.lower(), *куски]:
            if any(строка[н:н + ЭХО_ЗНАКОВ] in низ_вход
                   for н in range(max(0, len(строка) - ЭХО_ЗНАКОВ + 1))):
                return True, ""
        return False, "в ответе нет ни куска слов владельца"
    if ждём == "не-как-вход":
        if плотный_ответ == плотный_вход:
            return False, "ответ дословно равен словам владельца — механизм ничего не сделал"
        утекло = [з for з in значения_в_речи(вход) if з in ответ]
        if утекло:
            return False, f"значение из сообщения осталось в ответе ({len(утекло)} шт.)"
        return True, ""
    return False, f"предикат ответа «{ждём}» прибору неизвестен"


def цитата(ответ: str, вход: str, ждём: str, признак: str = "") -> str:
    """Строка ответа от ЦИТАТА_ЗНАКОВ: ею гейт проверит след дословно.

    У механизма, который ЗАМЕНЯЕТ значение в словах владельца, цитатой берётся
    строка, которой во входе НЕТ: эхо чужих слов доказывало бы, что сообщение
    прошло насквозь, а запись осела бы в гите вместе со словами владельца."""
    if ждём == "не-как-вход":
        # Признак удачи написан САМИМ механизмом: от него и читается цитата —
        # разность знаков иначе начинается с хвоста соседней пометки
        # («<куда>]#[секрет из канала: …»), а цитату читает человек.
        if признак and признак in ответ:
            строка = next(с for с in ответ.splitlines() if признак in с)
            с_признака = плотно(строка[строка.index(признак):])
            if len(с_признака) >= ЦИТАТА_ЗНАКОВ:
                return с_признака
        return _вставка_механизма(вход, ответ)
    for строка in ответ.splitlines():
        сжато = плотно(строка)
        if len(сжато) >= ЦИТАТА_ЗНАКОВ:
            return сжато
    return ""


def _по_словам(текст: str, начало: int, конец: int) -> str:
    """Кусок текста, сжатый ВНУТРЬ до границ слов: разность считается по знакам,
    и её край рассекает слово («t; переложить: …»), а цитату читает человек."""
    while начало < конец and начало > 0 and не_пробел(текст, начало - 1):
        начало += 1
    while конец > начало and конец < len(текст) and не_пробел(текст, конец):
        конец -= 1
    return текст[начало:конец].strip()


def не_пробел(текст: str, где: int) -> bool:
    return not текст[где].isspace()


def _вставка_механизма(вход: str, ответ: str) -> str:
    """Самая длинная ВСТАВКА механизма в слова владельца, от ЦИТАТА_ЗНАКОВ.

    Цитатой не годится ни строка ответа, ни окно слов: механизм вставляет
    пометку ВНУТРЬ слов владельца, и строка «<слова владельца> [пометка]» во
    входе не встречается целиком — такая цитата уносила слова владельца в
    состояние, а оно лежит в гите (поймано пробой 17.10.2026). Вставка
    считается разностью двух текстов, то есть ровно тем, что написал механизм."""
    левый, правый = плотно(вход), плотно(ответ)
    сверка = difflib.SequenceMatcher(None, левый, правый, autojunk=False)
    вставки = [_по_словам(правый, ю1, ю2)
               for тег, _, _, ю1, ю2 in сверка.get_opcodes()
               if тег in ("insert", "replace")]
    вставки.sort(key=len, reverse=True)
    for вставка in вставки:
        if len(вставка) >= ЦИТАТА_ЗНАКОВ:
            return вставка
    return ""


def судить(механизм: str, запись: dict) -> tuple[bool, str, dict]:
    """(доказано, что сказать, поля записи) для одного обработчика входящих."""
    if not запись or not (запись.get("зов") and запись.get("ждём")):
        return False, (f"{механизм}: в данных не названы зов или предикат "
                       f"ответа — придумывать их прибор не вправе"), {}
    сообщения = записанные_сообщения()
    if not сообщения:
        return False, (f"{механизм}: записанных слов владельца нет в "
                       f"{log_dir()}/inbox/обработано — прогонять не на чем"), {}
    журнал, начало = журнал_диспетчера()
    признак = (запись.get("признак") or "").strip()

    стенд = pathlib.Path(tempfile.mkdtemp(prefix="живая-проверка-B2-"))
    try:
        последняя_беда = ""
        for входящее in сообщения:
            чем_авторство = авторство(входящее, журнал, начало)
            if not чем_авторство:
                continue
            вход = входящее.read_text(encoding="utf-8", errors="replace")
            ответ, код, _ = позвать(механизм, запись, входящее, стенд, обёрткой=False)
            годен, беда = ответ_годен(запись["ждём"], вход, ответ, признак)
            if not годен:
                последняя_беда = беда
                continue
            if not цитата(ответ, вход, запись["ждём"], признак):
                последняя_беда = (f"ответ короче {ЦИТАТА_ЗНАКОВ} знаков — "
                                  f"цитировать нечего")
                continue
            # Нашли живое сообщение, на котором механизм делает своё дело.
            # Повторяем ТЕМ ЖЕ зовом через обёртку: след пишет только она.
            ответ, код, зовём = позвать(механизм, запись, входящее, стенд, обёрткой=True)
            годен, беда = ответ_годен(запись["ждём"], вход, ответ, признак)
            if not годен:
                return False, (f"{механизм}: под обёрткой ответ другой — {беда} "
                               f"(код {код})"), {}
            видно = цитата(ответ, вход, запись["ждём"], признак)
            след = СЛЕДЫ / (механизм.replace("/", "-") + ".log")
            with след.open("a", encoding="utf-8") as ф:
                ф.write(f"входящее: {входящее.name}\n"
                        f"авторство: {чем_авторство}\n")
            путь_следа = (str(след.relative_to(КОРЕНЬ))
                          if след.is_relative_to(КОРЕНЬ) else str(след))
            поля = {
                "живьём": (f"прогнан на ЗАПИСАННОМ слове владельца "
                           f"{входящее.name} ({чем_авторство}); в жизни "
                           f"{плотно(запись.get('чем_жив') or '')}"),
                "увидели": видно,
                "входящее": входящее.name,
                "след": путь_следа,
                "когда": datetime.date.today().isoformat(),
                "исход": "ок",
            }
            return True, f"{механизм}: доказан на {входящее.name} — {видно[:70]}", поля
        return False, (f"{механизм}: среди {len(сообщения)} записанных слов "
                       f"владельца нет ни одного, на котором он делает своё "
                       f"дело" + (f"; последняя попытка: {последняя_беда}"
                                  if последняя_беда else
                                  "; ни одно слово не подтверждено журналом "
                                  "диспетчера")), {}
    finally:
        # Стенд уносит с собой копии значений, которые механизм отделил от слов
        # владельца: оставить его значило бы размножить ключ по машине.
        shutil.rmtree(стенд, ignore_errors=True)


def записать(исходы: dict) -> None:
    данные_сост = yaml.safe_load(СОСТОЯНИЕ.read_text(encoding="utf-8")) or {}
    сост = данные_сост.setdefault("проверено", {})
    for механизм, поля in исходы.items():
        запись = сост.setdefault(механизм, {})
        # Поля ПРЕЖНЕГО исхода снимаются: запись «ждёт стенда класса B2»
        # осталась бы рядом с исходом «ок» и читалась бы как живой долг.
        for чужое in ("ждёт", "причина"):
            запись.pop(чужое, None)
        запись.update(поля)
    СОСТОЯНИЕ.write_text(
        yaml.dump(данные_сост, allow_unicode=True, sort_keys=False, width=100),
        encoding="utf-8")
    print(f"[живая проверка входящих] записано механизмов: {len(исходы)}")


def main() -> int:
    писать = "--записать" in sys.argv
    названные = [д for д in sys.argv[1:] if not д.startswith("--")]
    входящие = данные()
    if "--всё" in sys.argv:
        названные = sorted(входящие)
    if not названные:
        print("[живая проверка входящих] нечего судить: назовите механизм "
              "или «--всё»", file=sys.stderr)
        return 1

