ГЕЙТ_ДОВОДА = '''#!/usr/bin/env python3
import sys
текст = " ".join(sys.argv[1:])
if "запретное" in текст:
    print("[довод] запретное слово в доводе: запретное")
    sys.exit(1)
print("[довод] чисто: довод без запретного слова")
sys.exit(0)
'''


def случай(имя: str, условие: bool, пояснение: str = "") -> None:
    global хорошо, плохо
    if условие:
        хорошо += 1
        print(f"  ок    {имя}")
    else:
        плохо += 1
        print(f"  ПЛОХО {имя}{(': ' + пояснение) if пояснение else ''}")


def двор(случаи: dict) -> pathlib.Path:
    """Свой git-репозиторий с «гейтом», обёрткой и данными больных случаев."""
    путь = pathlib.Path(tempfile.mkdtemp(prefix="проба-больной-"))
    (путь / "scripts").mkdir()
    (путь / "src").mkdir()
    # git не хранит ПУСТЫЕ каталоги: без этого файла «src/» до клона не доезжает,
    # и команда поломки падает «No such file or directory» — дефект стенда, а не
    # механизма (поймано первым прогоном пробы).
    (путь / "src" / "хранитель.txt").write_text("двор\n", encoding="utf-8")
    (путь / "harness" / "config").mkdir(parents=True)
    (путь / "scripts" / "gate_dvor.py").write_text(ГЕЙТ, encoding="utf-8")
    (путь / "scripts" / "gate_arg.py").write_text(ГЕЙТ_ДОВОДА, encoding="utf-8")
    # Обёртка — ТА ЖЕ, что в бою: свою копию писать нельзя, иначе проба судит
    # выдумку, а не механизм ([[comparing-two-implementations-turns-tautological]]).
    (путь / "scripts" / "live-check.sh").write_text(
        (СКРИПТЫ / "live-check.sh").read_text(), encoding="utf-8")
    # Обёртка читает корень следов через загрузчик конфига — ему нужна lib.
    shutil.copytree(СКРИПТЫ / "lib", путь / "scripts" / "lib",
                    ignore=shutil.ignore_patterns("__pycache__"))
    (путь / "harness" / "config" / "live-check-sick-cases.yaml").write_text(
        yaml.dump({"больные_случаи": случаи}, allow_unicode=True), encoding="utf-8")
    (путь / "harness" / "config" / "live-check-state.yaml").write_text(
        "версия: 1\nпроверено: {}\n", encoding="utf-8")
    тихо = {"capture_output": True, "cwd": путь}
    subprocess.run(["git", "init", "-q"], **тихо)
    subprocess.run(["git", "config", "user.email", "d@d"], **тихо)
    subprocess.run(["git", "config", "user.name", "d"], **тихо)
    subprocess.run(["git", "add", "-A"], **тихо)
    subprocess.run(["git", "commit", "-q", "-m", "двор"], **тихо)
    return путь


def прогон(путь: pathlib.Path, *доводы: str,
           среда_сверх: dict | None = None) -> tuple[int, str]:
    """`среда_сверх`: значение None УБИРАЕТ переменную — так судится умолчание."""
    среда = dict(os.environ)
    среда.update({
        "HARNESS_LIVE_CHECK_SICK_CASES":
            str(путь / "harness" / "config" / "live-check-sick-cases.yaml"),
        "HARNESS_LIVE_CHECK_STATE":
            str(путь / "harness" / "config" / "live-check-state.yaml"),
        "HARNESS_LIVE_CHECK_SICK_TRACE_DIR": str(путь / "следы"),
        "HARNESS_LIVE_CHECK_SICK_TRACE_OUT": str(путь / "следы-наружу"),
        "HARNESS_LIVE_CHECK_REPO": str(путь),
        "HARNESS_LIVE_CHECK_SICK_LIVE_TRACE_DIR": str(путь / "следы-живьём"),
    })
    for ключ, значение in (среда_сверх or {}).items():
        if значение is None:
            среда.pop(ключ, None)
        else:
            среда[ключ] = значение
    готово = subprocess.run([sys.executable, str(ПРОГОН), *доводы],
                            capture_output=True, text=True, env=среда, timeout=300)
    return готово.returncode, готово.stdout + готово.stderr


