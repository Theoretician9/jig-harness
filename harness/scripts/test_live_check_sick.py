#!/usr/bin/env python3
"""Проверка прогона больной половины живой проверки (scripts/live-check-sick.py).

Откуда взято. Спека `docs/specs/2026-10-15-живая-проверка-механизмов.md` §3.1,
класс C1: «Больной случай в КОПИИ дерева → красный с названной причиной; затем
здоровый → зелёный. **Одного зелёного мало**».

Зачем прогон нужен. 17.10.2026 за одну смену я записал 48 гейтов-судей по
ОДНОМУ зелёному прогону: предикат класса не судил никто, и запись выглядела
доказанной. Делать больную половину руками по гейту — решение, которое требует
помнить, то есть не решение.

── Что охраняется сверх буквы спеки ───────────────────────────────────────
1. **Чистая копия обязана быть ЗЕЛЁНОЙ.** Красное на сломанном дереве ничего
   не доказывает, если то же красное даёт и целое: оно могло прийти от
   сломанного окружения копии, а не от пойманной поломки. Ровно это правило
   спасло мутационную пробу 12.09.2026.
2. **Отказ судится СЛОВОМ, а не кодом.** Код 1 даёт и «ошибка разбора», и
   «файла нет», и 127 «нет такой команды»: ждём подстроку, которую может
   напечатать ТОЛЬКО судимое правило.
3. **Поломка обязана изменить дерево.** Команда, не изменившая ни одного
   файла, — промах данных, а не успех: иначе «гейт покраснел» означало бы
   «гейт краснеет всегда».
4. **Каждый случай судит СВОЮ причину дословно.** Отказ по одному коду
   неотличим от отказа по другому.

Проба создаёт свой двор: маленький git-репозиторий со своим «гейтом», своими
данными больных случаев и своим каталогом следов. Боевые файлы не трогаются.

Прогон: python3 scripts/test_live_check_sick.py
Код возврата: 0 — все случаи зелёные, 1 — хоть один плохой.
"""
from __future__ import annotations

import hashlib
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile

import yaml

СКРИПТЫ = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(СКРИПТЫ / "lib"))
import config as _конфиг  # noqa: E402

# Корень установки, а не parent.parent: в пакете скрипты лежат в harness/scripts.
КОРЕНЬ = pathlib.Path(_конфиг.корень_дерева(__file__))
# Путь прибора — через окружение: мутационная проба подсовывает КОПИЮ
# испорченного прибора, и без этой двери проба судила бы боевой файл, то
# есть оставалась зелёной на любой мутации (поймано прогоном 17.10.2026:
# три мутации из трёх не покраснели).
ПРОГОН = pathlib.Path(os.environ.get("HARNESS_LIVE_CHECK_SICK_TOOL")
                      or СКРИПТЫ / "live-check-sick.py")
БОЕВЫЕ = (КОРЕНЬ / "harness" / "config" / "live-check-state.yaml",
          КОРЕНЬ / "harness" / "config" / "live-check-sick-cases.yaml")

хорошо = 0
плохо = 0

# «Гейт» двора: краснеет СВОИМ словом, если в дереве есть запретный файл.
ГЕЙТ = '''#!/usr/bin/env python3
import pathlib, sys
плохие = sorted(p.name for p in pathlib.Path("src").glob("*.bad"))
if плохие:
    print("[двор] запретных файлов: " + ", ".join(плохие))
    sys.exit(1)
print("[двор] чисто: запретных файлов нет")
sys.exit(0)
'''


# «Гейт» двора второго рода: предмет приходит ДОВОДОМ, а не лежит в дереве.
# Таких среди гейтов-судей 24 из 63 непроверенных (замер 17.10.2026): сторож
# канала судит текст сообщения, guard_bash — команду, limit-in-log — путь
# журнала. Поломкой дерева их не покрасить, и прибор обязан звать их больным
# ДОВОДОМ.
ГЕЙТ_ДОВОДА = '''#!/usr/bin/env python3
import sys
текст = " ".join(sys.argv[1:])
if "запретное" in текст:
    print("[довод] запретное слово в доводе: запретное")
    sys.exit(1)
print("[довод] чисто: довод без запретного слова")
sys.exit(0)
'''


def случай(имя: str, условие: bool, пояснение: str = "") -> None:
    global хорошо, плохо
    if условие:
        хорошо += 1
        print(f"  ок    {имя}")
    else:
        плохо += 1
        print(f"  ПЛОХО {имя}{(': ' + пояснение) if пояснение else ''}")


def двор(случаи: dict) -> pathlib.Path:
    """Свой git-репозиторий с «гейтом», обёрткой и данными больных случаев."""
    путь = pathlib.Path(tempfile.mkdtemp(prefix="проба-больной-"))
    (путь / "scripts").mkdir()
    (путь / "src").mkdir()
    # git не хранит ПУСТЫЕ каталоги: без этого файла «src/» до клона не доезжает,
    # и команда поломки падает «No such file or directory» — дефект стенда, а не
    # механизма (поймано первым прогоном пробы).
    (путь / "src" / "хранитель.txt").write_text("двор\n", encoding="utf-8")
    (путь / "harness" / "config").mkdir(parents=True)
    (путь / "scripts" / "gate_dvor.py").write_text(ГЕЙТ, encoding="utf-8")
    (путь / "scripts" / "gate_arg.py").write_text(ГЕЙТ_ДОВОДА, encoding="utf-8")
    # Обёртка — ТА ЖЕ, что в бою: свою копию писать нельзя, иначе проба судит
    # выдумку, а не механизм ([[comparing-two-implementations-turns-tautological]]).
    (путь / "scripts" / "live-check.sh").write_text(
        (СКРИПТЫ / "live-check.sh").read_text(), encoding="utf-8")
    # Обёртка читает корень следов через загрузчик конфига — ему нужна lib.
    shutil.copytree(СКРИПТЫ / "lib", путь / "scripts" / "lib",
                    ignore=shutil.ignore_patterns("__pycache__"))
    (путь / "harness" / "config" / "live-check-sick-cases.yaml").write_text(
        yaml.dump({"больные_случаи": случаи}, allow_unicode=True), encoding="utf-8")
    (путь / "harness" / "config" / "live-check-state.yaml").write_text(
        "версия: 1\nпроверено: {}\n", encoding="utf-8")
    тихо = {"capture_output": True, "cwd": путь}
    subprocess.run(["git", "init", "-q"], **тихо)
    subprocess.run(["git", "config", "user.email", "d@d"], **тихо)
    subprocess.run(["git", "config", "user.name", "d"], **тихо)
    subprocess.run(["git", "add", "-A"], **тихо)
    subprocess.run(["git", "commit", "-q", "-m", "двор"], **тихо)
    return путь


def прогон(путь: pathlib.Path, *доводы: str) -> tuple[int, str]:
    среда = dict(os.environ)
    среда.update({
        "HARNESS_LIVE_CHECK_SICK_CASES":
            str(путь / "harness" / "config" / "live-check-sick-cases.yaml"),
        "HARNESS_LIVE_CHECK_STATE":
            str(путь / "harness" / "config" / "live-check-state.yaml"),
        "HARNESS_LIVE_CHECK_SICK_TRACE_DIR": str(путь / "следы"),
        "HARNESS_LIVE_CHECK_SICK_TRACE_OUT": str(путь / "следы-наружу"),
        "HARNESS_LIVE_CHECK_REPO": str(путь),
    })
    готово = subprocess.run([sys.executable, str(ПРОГОН), *доводы],
                            capture_output=True, text=True, env=среда, timeout=300)
    return готово.returncode, готово.stdout + готово.stderr


ЗДОРОВЫЙ = {
    "scripts/gate_dvor.py": {
        "чем_ломать": "touch src/плохой.bad",
        "команда": "python3 scripts/gate_dvor.py",
        "ждём_в_отказе": "запретных файлов: плохой.bad",
    }
}


ЗДОРОВЫЙ_ДОВОД = {
    "scripts/gate_arg.py": {
        "команда": "python3 scripts/gate_arg.py obychnyj-dovod",
        "больной_довод": "python3 scripts/gate_arg.py запретное",
        "ждём_в_отказе": "запретное слово в доводе",
    }
}


def main() -> int:
    было = {п: hashlib.md5(п.read_bytes()).hexdigest() for п in БОЕВЫЕ if п.exists()}

    # ── БОЛЬНОЙ СЛУЧАЙ ПЕРВЫМ: гейт НЕ краснеет на сломанном дереве ───────
    # Это и есть дыра, ради которой прогон написан: гейт, который не ловит
    # нарушение, выглядел «проверенным» по одному зелёному прогону.
    слепой = {"scripts/gate_dvor.py": dict(
        ЗДОРОВЫЙ["scripts/gate_dvor.py"],
        чем_ломать="touch src/безобидный.txt")}
    д = двор(слепой)
    код, вывод = прогон(д, "scripts/gate_dvor.py")
    случай("БОЛЬНОЙ СЛУЧАЙ: гейт зелен на сломанном дереве — отказ",
           код == 1 and "гейт ЗЕЛЁН на сломанном дереве" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    # Поломка не изменила дерево — промах данных, а не успех.
    пустая = {"scripts/gate_dvor.py": dict(
        ЗДОРОВЫЙ["scripts/gate_dvor.py"], чем_ломать="true")}
    д = двор(пустая)
    код, вывод = прогон(д, "scripts/gate_dvor.py")
    случай("поломка не изменила дерево — названо своей причиной",
           код == 1 and "поломка не изменила дерево" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    # Отказ судится СЛОВОМ: красный по другой причине не считается.
    чужое = {"scripts/gate_dvor.py": dict(
        ЗДОРОВЫЙ["scripts/gate_dvor.py"], ждём_в_отказе="совсем другое слово")}
    д = двор(чужое)
    код, вывод = прогон(д, "scripts/gate_dvor.py")
    случай("отказ без ожидаемого слова — не доказательство",
           код == 1 and "в отказе нет ожидаемого слова" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    # Чистая копия уже красная — доказывать нечем.
    д = двор(ЗДОРОВЫЙ)
    (д / "src" / "заранее.bad").touch()
    subprocess.run(["git", "add", "-A"], capture_output=True, cwd=д)
    subprocess.run(["git", "commit", "-q", "-m", "уже плохо"], capture_output=True, cwd=д)
    код, вывод = прогон(д, "scripts/gate_dvor.py")
    случай("чистая копия уже красная — отказ, а не зачёт",
           код == 1 and "чистая копия уже красная" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    # Механизма нет в данных — молчать нельзя.
    д = двор(ЗДОРОВЫЙ)
    код, вывод = прогон(д, "scripts/нет-такого.py")
    случай("механизма нет в данных больных случаев — назван",
           код == 1 and "больного случая нет в данных" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    # БОЛЬНОЙ СЛУЧАЙ 17.10.2026: поломка в ИНДЕКСЕ. `git checkout -- .`
    # восстанавливает дерево ИЗ индекса, то есть не восстанавливает ничего, и
    # грязь предыдущего случая проходит за поломку следующего — «гейт зелён на
    # сломанном дереве» говорится о дереве, сломанном не тем случаем.
    д = двор({
        "scripts/gate_dvor.py": dict(ЗДОРОВЫЙ["scripts/gate_dvor.py"]),
        # Первый случай убирает файл ИЗ ИНДЕКСА; второй обязан увидеть чистую
        # копию и пожаловаться на СВОЮ поломку, а не пройти по чужой грязи.
        # Этот случай НАРОЧНО негоден: он сносит сам гейт из индекса И с диска.
        # Его собственный приговор неважен — важно, что СОСЕД после него видит
        # целую копию. Без `reset --hard` файл не вернётся, и у соседа чистая
        # копия окажется красной.
        "scripts/gate_vtoroj.py": {
            "команда": "python3 scripts/gate_dvor.py",
            "чем_ломать": "git rm -q --cached scripts/gate_dvor.py && rm -f scripts/gate_dvor.py",
            "ждём_в_отказе": "ничего такого гейт не печатает",
        },
    })
    код, вывод = прогон(д, "scripts/gate_vtoroj.py", "scripts/gate_dvor.py")
    случай("после поломки ИНДЕКСА сосед видит ЦЕЛУЮ копию",
           "scripts/gate_dvor.py: больная половина доказана" in вывод,
           f"код {код}, вывод {вывод[:400]!r}")

    # ── ЗДОРОВЫЙ ПУТЬ: обе проверки сошлись, запись заполнена ─────────────
    д = двор(ЗДОРОВЫЙ)
    код, вывод = прогон(д, "scripts/gate_dvor.py", "--записать")
    случай("здоровый путь: больная половина доказана, код 0",
           код == 0 and "больная половина доказана" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")
    состояние = yaml.safe_load(
        (д / "harness" / "config" / "live-check-state.yaml").read_text()) or {}
    запись = (состояние.get("проверено") or {}).get("scripts/gate_dvor.py") or {}
    случай("в запись легли «больной» и «след_больного»",
           bool(запись.get("больной")) and bool(запись.get("след_больного")),
           str(запись))
    случай("«больной» цитирует след ДОСЛОВНО",
           "запретных файлов: плохой.bad" in (запись.get("больной") or ""),
           str(запись.get("больной")))
    след = д / "следы" / "scripts-gate_dvor.py.log"
    случай("след написан обёрткой: шапка на месте",
           след.is_file() and "--- вывод механизма ---" in след.read_text(),
           str(след))
    # Без «--записать» состояние не трогается: прогон, который пишет всегда,
    # нельзя позвать «просто посмотреть».
    д = двор(ЗДОРОВЫЙ)
    прогон(д, "scripts/gate_dvor.py")
    состояние = yaml.safe_load(
        (д / "harness" / "config" / "live-check-state.yaml").read_text()) or {}
    случай("без «--записать» состояние не меняется",
           not (состояние.get("проверено") or {}), str(состояние))

    # След, которому в гите не место (гейты секретов доказываются ТЕМ, что они
    # запрещают), уходит в каталог вне дерева. Случай судит, что путь записи
    # ведёт именно туда: иначе запись отправит следующую смену искать файл,
    # которого в дереве нет.
    д = двор({"scripts/gate_dvor.py": dict(ЗДОРОВЫЙ["scripts/gate_dvor.py"],
                                           след_наружу=True)})
    код, вывод = прогон(д, "scripts/gate_dvor.py", "--записать")
    состояние = yaml.safe_load(
        (д / "harness" / "config" / "live-check-state.yaml").read_text()) or {}
    запись = (состояние.get("проверено") or {}).get("scripts/gate_dvor.py") or {}
    # Путь записи ведёт в каталог следов НАРУЖУ. Абсолютности требовать нельзя:
    # во дворе пробы этот каталог лежит внутри корня, и прогон честно пишет
    # относительный путь — в бою каталог вне корня, и путь остаётся полным.
    случай("след_наружу: след лежит вне дерева и путь записи ведёт туда",
           код == 0 and (д / "следы-наружу" / "scripts-gate_dvor.py.log").is_file()
           and (запись.get("след_больного") or "").endswith(
               "следы-наружу/scripts-gate_dvor.py.log"),
           f"код {код}, запись {запись.get('след_больного')!r}")
    случай("след_наружу: в каталоге следов дерева его НЕТ",
           not (д / "следы" / "scripts-gate_dvor.py.log").exists(),
           str(list((д / "следы").glob("*")) if (д / "следы").is_dir() else "каталога нет"))

    # ── ВТОРОЙ РОД: предмет приходит ДОВОДОМ (поле «больной_довод») ───────
    # БОЛЬНЫМ СЛУЧАЕМ ПЕРВЫМ: гейт зелен и на больном доводе — это дыра того же
    # рода, что и «зелён на сломанном дереве».
    д = двор({"scripts/gate_arg.py": dict(
        ЗДОРОВЫЙ_ДОВОД["scripts/gate_arg.py"],
        больной_довод="python3 scripts/gate_arg.py bezobidnyj")})
    код, вывод = прогон(д, "scripts/gate_arg.py")
    случай("БОЛЬНОЙ СЛУЧАЙ: гейт зелен на больном ДОВОДЕ — отказ",
           код == 1 and "ЗЕЛЁН на больном доводе" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    д = двор({"scripts/gate_arg.py": dict(
        ЗДОРОВЫЙ_ДОВОД["scripts/gate_arg.py"],
        ждём_в_отказе="совсем другое слово")})
    код, вывод = прогон(д, "scripts/gate_arg.py")
    случай("больной довод краснеет НЕ своим словом — не доказательство",
           код == 1 and "нет ожидаемого слова" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    д = двор({"scripts/gate_arg.py": dict(
        ЗДОРОВЫЙ_ДОВОД["scripts/gate_arg.py"], чем_ломать="touch src/плохой.bad")})
    код, вывод = прогон(д, "scripts/gate_arg.py")
    случай("оба способа сразу — отказ: прибор не выбирает за данные",
           код == 1 and "одно из двух" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    д = двор(ЗДОРОВЫЙ_ДОВОД)
    код, вывод = прогон(д, "scripts/gate_arg.py", "--записать")
    случай("здоровый путь второго рода: больная половина доказана, код 0",
           код == 0 and "больная половина доказана" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")
    случай("дерево при этом НЕ ломается: требования поломки нет",
           "поломка не изменила дерево" not in вывод, вывод[:300])
    состояние = yaml.safe_load(
        (д / "harness" / "config" / "live-check-state.yaml").read_text()) or {}
    запись = (состояние.get("проверено") or {}).get("scripts/gate_arg.py") or {}
    случай("в запись легли «больной» и «след_больного»",
           bool(запись.get("больной")) and bool(запись.get("след_больного")),
           str(запись))
    случай("«больной» называет больной ДОВОД и цитирует след дословно",
           "больным доводом" in (запись.get("больной") or "")
           and "запретное слово в доводе" in (запись.get("больной") or ""),
           str(запись.get("больной")))

    стало = {п: hashlib.md5(п.read_bytes()).hexdigest() for п in БОЕВЫЕ if п.exists()}
    случай("боевые файлы не тронуты", было == стало, "проба сыграла на производстве")

    print(f"ИТОГ: хороших {хорошо}, плохих {плохо}")
    return 1 if плохо else 0


if __name__ == "__main__":
    sys.exit(main())
