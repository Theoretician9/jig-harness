    д = двор({"scripts/gate_arg.py": dict(
        ЗДОРОВЫЙ_ДОВОД["scripts/gate_arg.py"],
        больной_довод="python3 scripts/gate_arg.py bezobidnyj")})
    код, вывод = прогон(д, "scripts/gate_arg.py")
    случай("БОЛЬНОЙ СЛУЧАЙ: гейт зелен на больном ДОВОДЕ — отказ",
           код == 1 and "ЗЕЛЁН на больном доводе" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    д = двор({"scripts/gate_arg.py": dict(
        ЗДОРОВЫЙ_ДОВОД["scripts/gate_arg.py"],
        ждём_в_отказе="совсем другое слово")})
    код, вывод = прогон(д, "scripts/gate_arg.py")
    случай("больной довод краснеет НЕ своим словом — не доказательство",
           код == 1 and "нет ожидаемого слова" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    д = двор({"scripts/gate_arg.py": dict(
        ЗДОРОВЫЙ_ДОВОД["scripts/gate_arg.py"], чем_ломать="touch src/плохой.bad")})
    код, вывод = прогон(д, "scripts/gate_arg.py")
    случай("оба способа сразу — отказ: прибор не выбирает за данные",
           код == 1 and "одно из двух" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")

    д = двор(ЗДОРОВЫЙ_ДОВОД)
    код, вывод = прогон(д, "scripts/gate_arg.py", "--записать")
    случай("здоровый путь второго рода: больная половина доказана, код 0",
           код == 0 and "больная половина доказана" in вывод,
           f"код {код}, вывод {вывод[:300]!r}")
    случай("дерево при этом НЕ ломается: требования поломки нет",
           "поломка не изменила дерево" not in вывод, вывод[:300])
    состояние = yaml.safe_load(
        (д / "harness" / "config" / "live-check-state.yaml").read_text()) or {}
    запись = (состояние.get("проверено") or {}).get("scripts/gate_arg.py") or {}
    случай("в запись легли «больной» и «след_больного»",
           bool(запись.get("больной")) and bool(запись.get("след_больного")),
           str(запись))
    случай("«больной» называет больной ДОВОД и цитирует след дословно",
           "больным доводом" in (запись.get("больной") or "")
           and "запретное слово в доводе" in (запись.get("больной") or ""),
           str(запись.get("больной")))

    # ── ЗДОРОВАЯ ПОЛОВИНА: прибор сам ставит «ок», когда доказаны обе ────
    # БОЛЬНЫМ СЛУЧАЕМ ПЕРВЫМ: живое дерево красное, а копия — зелёная. Прибор,
    # позвавший здоровую половину ИЗ КОПИИ, увидит зелёный и поставит «ок»
    # механизму, который в живом дереве красен. Грязь кладётся в КОРЕНЬ без
    # коммита: клон её не несёт, и больная половина доказывается как обычно.
    д = двор(ЗДОРОВЫЙ_ОК)
    (д / "src" / "живой.bad").touch()
    код, вывод = прогон(д, "scripts/gate_dvor.py", "--записать")
    запись = запись_двора(д, "scripts/gate_dvor.py")
    след_живьём = д / "следы-живьём" / "scripts-gate_dvor.py.log"
    случай("БОЛЬНОЙ СЛУЧАЙ: здоровая красная на живом дереве — «ок» нет, код 1",
           код == 1 and not запись.get("исход") and "здоров" in вывод.lower(),
           f"код {код}, исход {запись.get('исход')!r}, вывод {вывод[-300:]!r}")
    случай("здоровая красная: здоровая всё же ЗВАЛАСЬ обёрткой, след на месте",
           след_живьём.is_file()
           and "запретных файлов: живой.bad" in вывод_механизма(след_живьём.read_text()),
           str(след_живьём))

    # Слово только в ШАПКЕ следа: команда несёт его комментарием, гейт — нет.
    # Поиск по всему следу нашёл бы его в строке «команда: …» и закрыл бы
    # здоровую половину эхом её же команды.
    в_шапке = "slovo-tolko-v-shapke"
    д = двор({"scripts/gate_dvor.py": dict(
        ЗДОРОВЫЙ["scripts/gate_dvor.py"],
        команда=f"python3 scripts/gate_dvor.py # {в_шапке}",
        ждём_в_здоровом=в_шапке)})
    код, вывод = прогон(д, "scripts/gate_dvor.py", "--записать")
    запись = запись_двора(д, "scripts/gate_dvor.py")
    случай("слово только в шапке следа — «ок» нет, код 1, слово названо",
           код == 1 and not запись.get("исход") and в_шапке in вывод,
           f"код {код}, исход {запись.get('исход')!r}, вывод {вывод[-300:]!r}")

    # Нет поля «ждём_в_здоровом» — пишется ТОЛЬКО больная половина, и прибор
    # говорит об этом вслух: молчание выглядело бы как «здоровая не нужна».
    д = двор(ЗДОРОВЫЙ)
    код, вывод = прогон(д, "scripts/gate_dvor.py", "--записать")
    запись = запись_двора(д, "scripts/gate_dvor.py")
    случай("нет «ждём_в_здоровом»: больная записана, исхода нет, сказано вслух",
           код == 0 and bool(запись.get("больной")) and not запись.get("исход")
           and "ждём_в_здоровом" in вывод,
           f"код {код}, запись {запись}, вывод {вывод[-300:]!r}")
    случай("нет «ждём_в_здоровом»: здоровая не звалась — следа живьём нет",
           not (д / "следы-живьём" / "scripts-gate_dvor.py.log").exists(),
           "след здоровой есть, хотя звать её было не с чем")

    # Больная не доказана — здоровая не зовётся: «ок» по одной зелёной
    # половине и есть та дыра, ради которой прибор написан.
    д = двор({"scripts/gate_dvor.py": dict(ЗДОРОВЫЙ_ОК["scripts/gate_dvor.py"],
                                           чем_ломать="touch src/безобидный.txt")})
    код, вывод = прогон(д, "scripts/gate_dvor.py", "--записать")
    запись = запись_двора(д, "scripts/gate_dvor.py")
    случай("больная не доказана: здоровая не зовётся, исхода нет",
           код == 1 and not запись.get("исход")
           and not (д / "следы-живьём" / "scripts-gate_dvor.py.log").exists(),
           f"код {код}, запись {запись}")

    # ЗДОРОВЫЙ ПУТЬ обеих половин. Метка — НЕЗАКОММИЧЕННАЯ правка корня: её
    # видит только живое дерево, клон её не несёт. Метка в выводе здоровой
    # доказывает, что та звалась из корня, а не из копии.
    метка = "metka-zhivogo-dereva"
    команда_ок = "python3 scripts/gate_dvor.py && cat src/хранитель.txt"
    д = двор({"scripts/gate_dvor.py": dict(ЗДОРОВЫЙ_ОК["scripts/gate_dvor.py"],
                                           команда=команда_ок)})
    (д / "src" / "хранитель.txt").write_text(метка + "\n", encoding="utf-8")
    было_дня = сегодня()
    код, вывод = прогон(д, "scripts/gate_dvor.py", "--записать")
    стало_дня = сегодня()
    запись = запись_двора(д, "scripts/gate_dvor.py")
    след_живьём = д / "следы-живьём" / "scripts-gate_dvor.py.log"
    след_живьём_текст = след_живьём.read_text() if след_живьём.is_file() else ""
    текст_живьём = вывод_механизма(след_живьём_текст)
    случай("обе половины: код 0 и исход «ок»",
           код == 0 and запись.get("исход") == "ок",
           f"код {код}, исход {запись.get('исход')!r}, вывод {вывод[-300:]!r}")
    случай("здоровая звалась обёрткой из КОРНЯ: в выводе метка живого дерева",
           метка in текст_живьём
           and f"команда: bash -c {команда_ок}" in след_живьём_текст
           and "механизм: scripts/gate_dvor.py" in след_живьём_текст,
           f"след {след_живьём}: {след_живьём_текст[-300:]!r}")
    след_больного = д / "следы" / "scripts-gate_dvor.py.log"
    текст_больного = след_больного.read_text() if след_больного.is_file() else ""
    случай("больная звалась из КОПИИ: метки в её следе нет, след не затёрт",
           "запретных файлов: плохой.bad" in текст_больного
           and метка not in текст_больного,
           f"{след_больного}: {текст_больного[-200:]!r}")
    случай("«живьём» — «позван здоровым: <команда случая>»",
           запись.get("живьём") == f"позван здоровым: {команда_ок}",
           repr(запись.get("живьём")))
    увидели = запись.get("увидели") or ""
    случай("«увидели» — плотная строка со словом из ВЫВОДА здоровой",
           ЗДОРОВОЕ_СЛОВО in увидели
           and увидели == " ".join(увидели.split())
           and увидели in " ".join(текст_живьём.split()),
           f"увидели {увидели!r}")
    случай("«след» ведёт в каталог HARNESS_LIVE_CHECK_SICK_LIVE_TRACE_DIR",
           bool(запись.get("след")) and след_живьём.is_file()
           and файл_записи(д, запись["след"]).resolve() == след_живьём.resolve(),
           f"след {запись.get('след')!r}")
    случай("«когда» — сегодняшняя дата по часам, ГГГГ-ММ-ДД",
           str(запись.get("когда")) in (было_дня, стало_дня),
           f"когда {запись.get('когда')!r}, часы {было_дня}")
    случай("больная половина при «ок» записана как прежде",
           "запретных файлов: плохой.bad" in (запись.get("больной") or "")
           and bool(запись.get("след_больного")),
           str(запись))

    # Записанное проходит ТОГО судью, что стоит в воротах: запись, которую
    # прибор пишет, а гейт отвергает, сломала бы ворота первой же записью.
    # «исход ок» требуется явно: запись без исхода судья пропускает молча.
    беды, долг = судья(д, "scripts/gate_dvor.py", запись)
    случай("ок-запись прибора проходит судью C1 (build-live-check-list.py)",
           запись.get("исход") == "ок" and not беды and not долг,
           f"исход {запись.get('исход')!r}, беды {беды}, долг {долг}")
    # Судья на этом стенде не пуст: та же запись с выдуманным «увидели»
    # отвергается. Без этого «проходит судью» было бы зелено и от судьи,
    # который на стенде ничего не читает.
    беды, _ = судья(д, "scripts/gate_dvor.py",
                    dict(запись, увидели="выдумка проверяющего, в следе её нет"))
    случай("судья на стенде не пуст: выдуманное «увидели» отвергнуто",
           запись.get("исход") == "ок" and any("увидели" in б for б in беды),
           f"беды {беды}")

    # Умолчание каталога следов живьём: <корень следов>/<задача>/живьём.
    # Корень следов уводится во двор ключом загрузчика — живые следы целы.
    д = двор(ЗДОРОВЫЙ_ОК)
    код, вывод = прогон(д, "scripts/gate_dvor.py", "--записать", среда_сверх={
        "HARNESS_LIVE_CHECK_SICK_LIVE_TRACE_DIR": None,
        "LIVE_CHECK_TRACE_ROOT": str(д / "корень-следов")})
    # Имя каталога задачи не судим: это id карточки ЭТОЙ установки, в пробу сборки он не едет.
    по_умолчанию = next((д / "корень-следов").glob("*/живьём/scripts-gate_dvor.py.log"),
                        д / "корень-следов" / "следа-нет")
    запись = запись_двора(д, "scripts/gate_dvor.py")
    случай("без переменной след здоровой — в <корень следов>/<задача>/живьём",
           код == 0 and по_умолчанию.is_file() and bool(запись.get("след"))
           and файл_записи(д, запись["след"]).resolve() == по_умолчанию.resolve(),
           f"код {код}, след {запись.get('след')!r}, ждали {по_умолчанию}")

    # БОЛЬНОЙ СЛУЧАЙ: у механизма уже лежит прежняя ок-запись, живое дерево
    # с тех пор покраснело. Больная доказана заново, здоровая красная — и
    # прежние «исход ок», «увидели», «след» остаются рядом с новым «больным»:
    # запись говорит «ок» о механизме, который сегодня красен. Беда здоровой
    # обязана снять поля здоровой половины.
    д = двор(ЗДОРОВЫЙ_ОК)
    код, вывод = прогон(д, "scripts/gate_dvor.py", "--записать")
    прежняя = запись_двора(д, "scripts/gate_dvor.py")
    данные_случаев = д / "harness" / "config" / "live-check-sick-cases.yaml"
    данные_случаев.write_text(yaml.dump({"больные_случаи": {"scripts/gate_dvor.py": dict(
        ЗДОРОВЫЙ_ОК["scripts/gate_dvor.py"], чем_ломать="touch src/второй.bad",
        ждём_в_отказе="запретных файлов: второй.bad")}}, allow_unicode=True),
        encoding="utf-8")
    (д / "src" / "живой.bad").touch()
    код, вывод = прогон(д, "scripts/gate_dvor.py", "--записать")
    запись = запись_двора(д, "scripts/gate_dvor.py")
    поля_здоровой = ("исход", "живьём", "увидели", "след", "когда")
    остались = [п for п in поля_здоровой if п in запись]
    случай("прежняя ок-запись, здоровая красная — поля здоровой сняты, больная новая",
           прежняя.get("исход") == "ок" and код == 1 and not остались
           and "второй.bad" in (запись.get("больной") or "")
           and bool(запись.get("след_больного")),
           f"прежний исход {прежняя.get('исход')!r}, код {код}, остались {остались}, "
           f"больной {запись.get('больной')!r}")

    # БОЛЬНОЙ СЛУЧАЙ: обёртка в копии не дошла до следа (поломка снесла её
    # саму), а в каталоге следов лежит след ПРОШЛОГО прогона со словом отказа.
    # Красный код + слово в старом файле — и больная «доказана» чужим днём.
    д = двор(ЗДОРОВЫЙ)
    прогон(д, "scripts/gate_dvor.py")
    старый = д / "следы" / "scripts-gate_dvor.py.log"
    было_старого = старый.is_file() and "запретных файлов: плохой.bad" in старый.read_text()
    данные_случаев = д / "harness" / "config" / "live-check-sick-cases.yaml"
    данные_случаев.write_text(yaml.dump({"больные_случаи": {"scripts/gate_dvor.py": dict(
        ЗДОРОВЫЙ["scripts/gate_dvor.py"], чем_ломать="rm scripts/live-check.sh")}},
        allow_unicode=True), encoding="utf-8")
    код, вывод = прогон(д, "scripts/gate_dvor.py", "--записать")
    запись = запись_двора(д, "scripts/gate_dvor.py")
    случай("след прошлого прогона не доказывает больную: обёртка не писала — отказ",
           было_старого and код == 1 and "больная половина доказана" not in вывод
           and not запись.get("больной"),
           f"старый след {было_старого}, код {код}, запись {запись}, вывод {вывод[:300]!r}")

    # БОЛЬНОЙ СЛУЧАЙ: слово отказа — в самом больном ДОВОДЕ, а довод упал по
    # другой причине (файла нет). Шапка следа несёт «команда: …» с доводом, и
    # поиск по всему следу находит слово эхом своей же команды. Та же дыра,
    # что закрыта у здоровой половины разделителем, но у больной.
    д = двор({"scripts/gate_arg.py": dict(
        ЗДОРОВЫЙ_ДОВОД["scripts/gate_arg.py"],
        больной_довод="python3 scripts/net-takogo.py запретное слово в доводе")})
    код, вывод = прогон(д, "scripts/gate_arg.py", "--записать")
    запись = запись_двора(д, "scripts/gate_arg.py")
    случай("слово отказа только в шапке (эхо довода) — больная не доказана",
           код == 1 and "больная половина доказана" not in вывод
           and not запись.get("больной"),
           f"код {код}, запись {запись}, вывод {вывод[:300]!r}")

    # БОЛЬНОЙ СЛУЧАЙ: слово здоровой есть ТОЛЬКО в хвосте обёртки («код
    # возврата: 0»). Хвост пишет обёртка, а не механизм: слово из него
    # закрыло бы здоровую половину кодом, который бывает у любой команды.
    в_хвосте = "код возврата: 0"
    д = двор({"scripts/gate_dvor.py": dict(ЗДОРОВЫЙ["scripts/gate_dvor.py"],
                                           ждём_в_здоровом=в_хвосте)})
    код, вывод = прогон(д, "scripts/gate_dvor.py", "--записать")
    запись = запись_двора(д, "scripts/gate_dvor.py")
    след_живьём = д / "следы-живьём" / "scripts-gate_dvor.py.log"
    случай("слово только в хвосте обёртки «код возврата:» — «ок» нет, код 1",
           код == 1 and not запись.get("исход")
           and след_живьём.is_file() and в_хвосте in след_живьём.read_text()
           and "слова" in вывод and в_хвосте in вывод,
           f"код {код}, исход {запись.get('исход')!r}, вывод {вывод[-300:]!r}")

    # БОЛЬНОЙ СЛУЧАЙ: здоровая печатает своё слово и всё же КРАСНАЯ на живом
    # дереве. Флаг — незакоммиченный файл корня: клон его не несёт, и чистая
    # копия зелёная; в корне команда падает уже ПОСЛЕ слова гейта. Слово без
    # кода поставило бы «ок» красному механизму.
    команда_красная = "python3 scripts/gate_dvor.py && test ! -e src/flag-krasnyj"
    д = двор({"scripts/gate_dvor.py": dict(ЗДОРОВЫЙ_ОК["scripts/gate_dvor.py"],
                                           команда=команда_красная)})
    (д / "src" / "flag-krasnyj").touch()
    код, вывод = прогон(д, "scripts/gate_dvor.py", "--записать")
    запись = запись_двора(д, "scripts/gate_dvor.py")
    след_живьём = д / "следы-живьём" / "scripts-gate_dvor.py.log"
    случай("здоровая красная, хоть и печатает слово — «ок» нет, код 1, код назван",
           код == 1 and not запись.get("исход") and bool(запись.get("больной"))
           and след_живьём.is_file()
           and ЗДОРОВОЕ_СЛОВО in вывод_механизма(след_живьём.read_text())
           and "здоровая половина красная" in вывод,
           f"код {код}, исход {запись.get('исход')!r}, вывод {вывод[-300:]!r}")

    # ── ЗДОРОВАЯ_КОМАНДА: здоровая половина зовётся СВОЕЙ командой ─────────
    # Больная команда бывает самотестом (check-host-independence --selftest), а
    # здоровую надо звать узко на настоящих воротах: полный прогон идёт часы.
    # БОЛЬНОЙ СЛУЧАЙ: «команда» красна на живом дереве (флаг корня, клон его не
    # несёт), «здоровая_команда» зелена и печатает свою метку. Прибор, зовущий
    # здоровую половину «командой», покраснеет и метки не увидит.
    метка_здоровой = "metka-zdorovoj-komandy"
    команда_больной = "python3 scripts/gate_dvor.py && test ! -e src/flag-krasnyj"
    здоровая = f"python3 scripts/gate_dvor.py && echo {метка_здоровой}"
    д = двор({"scripts/gate_dvor.py": dict(
        ЗДОРОВЫЙ["scripts/gate_dvor.py"], команда=команда_больной,
        здоровая_команда=здоровая, ждём_в_здоровом=метка_здоровой)})
    (д / "src" / "flag-krasnyj").touch()
    код, вывод = прогон(д, "scripts/gate_dvor.py", "--записать")
    запись = запись_двора(д, "scripts/gate_dvor.py")
    след_живьём = д / "следы-живьём" / "scripts-gate_dvor.py.log"
    след_живьём_текст = след_живьём.read_text() if след_живьём.is_file() else ""
    след_больного = д / "следы" / "scripts-gate_dvor.py.log"
    текст_больного = след_больного.read_text() if след_больного.is_file() else ""
    случай("здоровая_команда: обе половины, код 0, исход «ок»",
           код == 0 and запись.get("исход") == "ок",
           f"код {код}, исход {запись.get('исход')!r}, вывод {вывод[-300:]!r}")
    случай("здоровая_команда: след здоровой несёт ИМЕННО её, метка в выводе",
           f"команда: bash -c {здоровая}" in след_живьём_текст
           and метка_здоровой in вывод_механизма(след_живьём_текст)
           and "механизм: scripts/gate_dvor.py" in след_живьём_текст,
           f"след {след_живьём}: {след_живьём_текст[-300:]!r}")
    случай("здоровая_команда: «живьём» — «позван здоровым: <здоровая_команда>»",
           запись.get("живьём") == f"позван здоровым: {здоровая}"
           and метка_здоровой in (запись.get("увидели") or ""),
           f"живьём {запись.get('живьём')!r}, увидели {запись.get('увидели')!r}")
    случай("здоровая_команда: больная звана по-прежнему «командой»",
           f"команда: bash -c {команда_больной}" in текст_больного
           and метка_здоровой not in текст_больного
           and "запретных файлов: плохой.bad" in (запись.get("больной") or ""),
           f"{след_больного}: {текст_больного[:300]!r}")
    беды, долг = судья(д, "scripts/gate_dvor.py", запись)
    случай("здоровая_команда: ок-запись проходит судью C1",
           запись.get("исход") == "ок" and not беды and not долг,
           f"исход {запись.get('исход')!r}, беды {беды}, долг {долг}")

    # «здоровая_команда» без «ждём_в_здоровом» — здоровую нечем судить: отказ
    # своим словом, и НИЧЕГО не пишется, даже больная (ошибка данных случая,
    # а не беда механизма). Нынешний прибор поле не знает и пишет одну больную.
    д = двор({"scripts/gate_dvor.py": dict(
        ЗДОРОВЫЙ["scripts/gate_dvor.py"], здоровая_команда=здоровая)})
    код, вывод = прогон(д, "scripts/gate_dvor.py", "--записать")
    запись = запись_двора(д, "scripts/gate_dvor.py")
    случай("здоровая_команда без ждём_в_здоровом — отказ словом, ничего не записано",
           код == 1 and "«здоровая_команда» без «ждём_в_здоровом»" in вывод
           and not запись
           and not (д / "следы" / "scripts-gate_dvor.py.log").exists()
           and not (д / "следы-живьём" / "scripts-gate_dvor.py.log").exists(),
           f"код {код}, запись {запись}, вывод {вывод[-300:]!r}")

    # Пустая «здоровая_команда» — не «поля нет»: молча упасть на «команду»
    # значило бы судить не то, что названо в данных.
    for пустая_здоровая in ("   ", None):
        д = двор({"scripts/gate_dvor.py": dict(
            ЗДОРОВЫЙ_ОК["scripts/gate_dvor.py"], здоровая_команда=пустая_здоровая)})
        код, вывод = прогон(д, "scripts/gate_dvor.py", "--записать")
        запись = запись_двора(д, "scripts/gate_dvor.py")
        случай(f"пустая здоровая_команда ({пустая_здоровая!r}) — отказ, ничего не записано",
               код == 1 and "«здоровая_команда» пуста" in вывод and not запись
               and not (д / "следы-живьём" / "scripts-gate_dvor.py.log").exists(),
               f"код {код}, запись {запись}, вывод {вывод[-300:]!r}")

    стало = {п: hashlib.md5(п.read_bytes()).hexdigest() for п in БОЕВЫЕ if п.exists()}
    случай("боевые файлы не тронуты", было == стало, "проба сыграла на производстве")

    print(f"ИТОГ: хороших {хорошо}, плохих {плохо}")
    return 1 if плохо else 0


