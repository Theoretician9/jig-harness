    # ── ВТОРОЙ РОД: предмет приходит ДОВОДОМ (поле «больной_довод») ───────
    # БОЛЬНЫМ СЛУЧАЕМ ПЕРВЫМ: гейт зелен и на больном доводе — это дыра того же
