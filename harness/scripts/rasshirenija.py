#!/usr/bin/env python3
"""Единственная точка установки расширений Claude Code (плагины и MCP).

Откуда взят: 12.09.2026. Владелец — «установка/удаление скилов как будто бы по
моим ощущениям ни разу не сработала». Замер подтвердил ощущение числом:
плагинов установлено 0, MCP 0, следов установки в истории и журналах за месяц
0. Причина оказалась не в поломке, а в устройстве: список расширений жил
ТЕКСТОМ скила, а командами в нём стояли слэш-формы (`/plugin install …`).
Слэш-команду вводит человек в терминале; агент её выполнить не может, а
владелец терминала не видит никогда. Механизм был мёртв с рождения.

Здесь он живой: список — данные (`harness/config/расширения.yaml`), установка —
CLI-форма `claude plugin install`, проверенная живьём в тот же день (поставил
context7, снял, реестр до 0 → 1 → 0).

    python3 scripts/rasshirenija.py состояние
    python3 scripts/rasshirenija.py поставить-базовый
    python3 scripts/rasshirenija.py поставить <id>
    python3 scripts/rasshirenija.py снять <id>

Коды возврата: 0 — сделано или уже так; 1 — базовый набор неполон (для гейта);
2 — отказ с причиной (нет данных, нет claude, отказ установки).
"""
import json
import os
import subprocess
import sys
from pathlib import Path

import yaml

def найти_данные() -> Path:
    """Файл данных ищется ВВЕРХ по дереву, а не считается от `scripts/`: в
    пакете этот скрипт лежит в `harness/scripts/`, а после раскладки — в
    `scripts/` корня проекта. Жёсткое `parent.parent` давало в пакете путь
    `harness/harness/config/…`, и две пробы самотеста молча пропускались
    (поймано 12.09.2026 на первом же прогоне)."""
    for каталог in Path(__file__).resolve().parents:
        кандидат = каталог / "harness" / "config" / "расширения.yaml"
        if кандидат.exists():
            return кандидат
    return Path(__file__).resolve().parent.parent / "harness" / "config" / "расширения.yaml"


ДАННЫЕ = найти_данные()


def конфиг_claude() -> Path:
    """Каталог настроек Claude Code. Установщик работает под root и задаёт
    HOME агента — поэтому путь берётся из окружения, а не из ~ процесса."""
    задан = os.environ.get("CLAUDE_CONFIG_DIR")
    if задан:
        return Path(задан)
    return Path(os.path.expanduser("~")) / ".claude"


def читать_данные(путь: Path = ДАННЫЕ) -> dict:
    if not путь.exists():
        raise SystemExit(f"нет данных расширений: {путь}")
    return yaml.safe_load(путь.read_text(encoding="utf-8")) or {}


def установленные() -> set:
    """Что стоит НА САМОМ ДЕЛЕ — реестр самого Claude Code, а не свой журнал.
    Свой журнал разъезжается с машиной молча; этот файл пишет установщик
    плагинов, и по нему же оболочка решает, что грузить."""
    реестр = конфиг_claude() / "plugins" / "installed_plugins.json"
    if not реестр.exists():
        return set()
    try:
        содержимое = json.loads(реестр.read_text(encoding="utf-8"))
    except json.JSONDecodeError as ошибка:
        raise SystemExit(f"реестр плагинов испорчен ({реестр}): {ошибка}")
    return set((содержимое.get("plugins") or {}).keys())


def выполнить(аргументы: list) -> tuple:
    """Зов claude. Отдаёт (код, вывод) — причина отказа нужна целиком: проба с
    ожиданием «код не ноль» зеленеет и от 127 «команды нет»."""
    try:
        готово = subprocess.run(["claude", *аргументы], capture_output=True,
                                text=True, timeout=300)
    except FileNotFoundError:
        return 127, "claude не найден в PATH"
    except subprocess.TimeoutExpired:
        return 124, f"claude {' '.join(аргументы)} не ответил за 300 с"
    return готово.returncode, (готово.stdout + готово.stderr).strip()


def подключить_маркетплейсы(данные: dict) -> int:
    """Идемпотентно: уже подключённый маркетплейс не ошибка."""
    подключены = (конфиг_claude() / "plugins" / "known_marketplaces.json")
    известные = {}
    if подключены.exists():
        известные = json.loads(подключены.read_text(encoding="utf-8"))
    отказов = 0
    for рынок in данные.get("маркетплейсы") or []:
        if рынок["имя"] in известные:
            print(f"  маркетплейс {рынок['имя']}: уже подключён")
            continue
        код, вывод = выполнить(["plugin", "marketplace", "add", рынок["источник"]])
        print(f"  маркетплейс {рынок['имя']}: {'подключён' if код == 0 else вывод}")
        отказов += код != 0
    return отказов


def поставить(идентификатор: str) -> int:
    if идентификатор in установленные():
        print(f"  {идентификатор}: уже стоит")
        return 0
    код, вывод = выполнить(["plugin", "install", идентификатор, "-y"])
    print(f"  {идентификатор}: {'поставлен' if код == 0 else 'ОТКАЗ — ' + вывод}")
    return код


def снять(идентификатор: str) -> int:
    if идентификатор not in установленные():
        print(f"  {идентификатор}: не стоял — снимать нечего")
        return 2
    код, вывод = выполнить(["plugin", "uninstall", идентификатор])
    print(f"  {идентификатор}: {'снят' if код == 0 else 'ОТКАЗ — ' + вывод}")
    return код


def поставить_базовый(данные: dict) -> int:
    отказов = подключить_маркетплейсы(данные)
    for строка in данные.get("базовый_набор") or []:
        отказов += поставить(строка["id"]) != 0
    return 2 if отказов else 0


def свести(данные: dict) -> dict:
    """Довести факт до данных: поставить недостающее из базового набора, снять
    стоящее из «не ставить». Это работа ДЕМОНА, а не рук: владелец 12.09.2026 —
    «Команды установки/удаления плагинов и скилов не для человека, а для
    демонов и хуков». Отдаёт числа, чтобы демон молчал, когда менять нечего.
    """
    итог = {"поставлено": 0, "снято": 0, "отказов": 0}
    итог["отказов"] += подключить_маркетплейсы(данные)
    стоят = установленные()
    for строка in данные.get("базовый_набор") or []:
        if строка["id"] in стоят:
            continue
        код = поставить(строка["id"])
        итог["поставлено"] += код == 0
        итог["отказов"] += код != 0
    # Снимается ТОЛЬКО то, что стоит и прямо запрещено вердиктом: «сверх
    # набора» не трогается — расширение по условию ставится сознательно.
    запрещены = {с["id"] for с in данные.get("не_ставить") or []}
    for идентификатор in установленные():
        короткое = идентификатор.split("@")[0]
        if идентификатор in запрещены or короткое in запрещены:
            код = снять(идентификатор)
            итог["снято"] += код == 0
            итог["отказов"] += код != 0
    return итог


def состояние(данные: dict) -> int:
    стоят = установленные()
    базовые = [с["id"] for с in данные.get("базовый_набор") or []]
    нет = [и for и in базовые if и not in стоят]
    лишние = sorted(стоят - set(базовые))
    print(f"базовый набор: {len(базовые) - len(нет)} из {len(базовые)}")
    for идентификатор in нет:
        print(f"  НЕТ: {идентификатор}")
    for идентификатор in лишние:
        print(f"  сверх набора: {идентификатор}")
    print(f"по условию ждут: {len(данные.get('по_условию') or [])} · "
          f"вердиктов «не ставить»: {len(данные.get('не_ставить') or [])}")
    return 1 if нет else 0


def selftest() -> int:
    """Пробы зовут те же функции, что и боевой путь: разница между пробой и
    работой — только подменённый каталог настроек (12.09.2026,
    [[проба-зовёт-не-так-как-боевой-путь]])."""
    import tempfile
    неудач = 0

    def проба(имя, ожидалось, получено):
        nonlocal неудач
        ок = ожидалось == получено
        неудач += not ок
        print(f"  {'ok  ' if ок else 'FAIL'} {имя}"
              + ("" if ок else f": ждали {ожидалось!r}, получили {получено!r}"))

    with tempfile.TemporaryDirectory() as каталог:
        os.environ["CLAUDE_CONFIG_DIR"] = каталог
        проба("пустой каталог настроек: установлено ничего", set(), установленные())

        реестр = Path(каталог) / "plugins"
        реестр.mkdir()
        (реестр / "installed_plugins.json").write_text(
            json.dumps({"version": 2, "plugins": {"a@m": [{"scope": "user"}]}}),
            encoding="utf-8")
        проба("реестр прочитан", {"a@m"}, установленные())

        # БОЛЬНОЙ СЛУЧАЙ: снять то, чего нет, — честный отказ, а не тихий 0.
        проба("снятие несуществующего — код 2", 2, снять("нет@такого"))

        данные = {"базовый_набор": [{"id": "a@m"}, {"id": "b@m"}]}
        проба("состояние неполного набора — код 1", 1, состояние(данные))
        проба("состояние полного набора — код 0", 0,
              состояние({"базовый_набор": [{"id": "a@m"}]}))

        (реестр / "installed_plugins.json").write_text("{сломано", encoding="utf-8")
        try:
            установленные()
            проба("испорченный реестр называет причину", "SystemExit", "молча прошло")
        except SystemExit as ошибка:
            проба("испорченный реестр называет причину", True,
                  "испорчен" in str(ошибка))

        # БОЛЬНОЙ СЛУЧАЙ: запрещённое вердиктом стоит — демон обязан его
        # снять, а «сверх набора» без вердикта не трогать.
        (реестр / "installed_plugins.json").write_text(
            json.dumps({"version": 2, "plugins": {
                "a@m": [{"scope": "user"}], "dream-skill@m": [{"scope": "user"}]}}),
            encoding="utf-8")
        снятые = []
        настоящее_снять = globals()["снять"]
        globals()["снять"] = lambda и: (снятые.append(и), 0)[1]
        итог = свести({"базовый_набор": [{"id": "a@m"}],
                       "не_ставить": [{"id": "dream-skill"}]})
        globals()["снять"] = настоящее_снять
        проба("свести: снят запрещённый вердиктом", ["dream-skill@m"], снятые)
        проба("свести: ставить было нечего", 0, итог["поставлено"])

    # Данные обязаны БЫТЬ и иметь непустой набор. Условие `if ДАННЫЕ.exists()`
    # здесь стояло ровно один прогон и сделало обе пробы невидимыми: проверка
    # обязана создавать своё условие, а не совпадать с машиной.
    проба("данные найдены", True, ДАННЫЕ.exists())
    данные = читать_данные()
    проба("данные: базовый набор непуст", True,
          len(данные.get("базовый_набор") or []) > 0)
    проба("данные: у каждой строки по условию есть условие", True,
          all(с.get("условие") for с in данные.get("по_условию") or []))
    print(f"самотест rasshirenija: неудач {неудач}")
    return 1 if неудач else 0


def главная(аргументы: list) -> int:
    if not аргументы or аргументы[0] in ("-h", "--help"):
        print(__doc__)
        return 0
    if аргументы[0] == "--selftest":
        return selftest()
    команда = аргументы[0]
    if команда == "состояние":
        return состояние(читать_данные())
    if команда == "поставить-базовый":
        return поставить_базовый(читать_данные())
    if команда == "свести":
        итог = свести(читать_данные())
        print(f"свёл: поставлено {итог['поставлено']} · снято {итог['снято']} "
              f"· отказов {итог['отказов']}")
        return 2 if итог["отказов"] else 0
    if команда in ("поставить", "снять"):
        if len(аргументы) < 2:
            print(f"нужен id: {команда} <plugin@marketplace>", file=sys.stderr)
            return 2
        return (поставить if команда == "поставить" else снять)(аргументы[1])
    print(f"неизвестная команда: {команда}", file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(главная(sys.argv[1:]))
