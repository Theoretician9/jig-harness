# Root-часть установки: обновление её не ставит — у него нет root. Чего нет на
# машине, то довозит повтор установщика, и владельцу называется одна команда.
# Каталог sudoers.d агенту закрыт (0750): правила читаются по копии, которую
# установщик кладёт для гейтов (шаг 12).
def timer_enabled(unit: str) -> bool:
    try:
        return subprocess.run(["systemctl", "is-enabled", "--quiet", unit],
                              capture_output=True, timeout=20).returncode == 0
    except (OSError, subprocess.SubprocessError):
        return False


# Единственный перечень рестартуемых обновлением юнитов: из него и цикл
# _перезапустить_службы, и суд прав в root_part_gaps. Диспетчер последним: он
# держит канал с владельцем, и его перезапуск обрывает разговор (находка C4).
RESTARTED_UNITS = ("harness-panel.service", "harness-sentinel.timer", "harness-dispatcher.service")
RIGHTS_FILES = ("harness-agent-readonly", "harness-agent-units")


def _rights_gaps(rights: Path) -> list[str]:
    """Что не так в копии прав агента: файлы прав и право restart на каждый юнит.
    Право даёт любой файл копии, поэтому правило ищется по всей копии, а имя
    юнита — целым словом (за ним запятая, пробел или конец строки)."""
    try:
        text = rights.read_text(encoding="utf-8")
    except OSError:
        return [f"нет копии прав {rights}"]
    absent = [f"/etc/sudoers.d/{name}" for name in RIGHTS_FILES
              if f"# файл: /etc/sudoers.d/{name}" not in text]
    unruled = [unit for unit in RESTARTED_UNITS
               if not re.search(rf"systemctl restart {re.escape(unit)}(?![\w.-])", text)]
    parts = ([f"файлы {', '.join(absent)}"] if absent else []) + \
            ([f"restart юнитов: {', '.join(unruled)}"] if unruled else [])
    return [f"нет прав агента: {'; '.join(parts)}"] if parts else []


def root_part_gaps(etc: Path = Path("/etc"), enabled=timer_enabled) -> list[str]:
    """Чего из root-части установки нет — по пункту на пробел."""
    gaps = _rights_gaps(etc / "harness" / "sudo-rights.txt")
    if not (etc / "logrotate.d" / "harness").is_file():
        gaps.append(f"нет {etc / 'logrotate.d' / 'harness'}")
    timers = [f"harness-{i}.timer" for i in process_library.checks_ids()] + ["harness-sentinel.timer"]
    off = [unit for unit in timers if not enabled(unit)]
    if off:
        gaps.append(f"не включены таймеры: {', '.join(off)}")
    return gaps


def root_part_command(каталог: Path) -> str:
    return f"sudo bash {каталог}/USTANOVIT.sh --resume"


def каталог_копий() -> Path:
    return конф_модуль.backup_dir()


def _снять_копию(каталог: Path) -> Path | None:
    """Копия пакета ДО установки. Без неё установка не начинается (И-1).

    Имя с датой И временем: два обновления за сутки затирали бы копию друг
    друга (находка I10 разбора спеки).
    """
    try:
        основа = каталог_копий() / time.strftime("обновление-%Y%m%d-%H%M%S")
    except LookupError as беда:
        # Копия некуда — установка не начинается; причину видно в журнале, владельцу
        # уходит прежний текст отказа.
        print(f"[обновление] {беда}", file=sys.stderr)
        return None
    # Два обновления в одну секунду — не выдумка: так идут проверки, и второе
    # падало на «каталог уже есть», то есть отказывалось ставиться молча.
    цель, номер = основа, 1
    while цель.exists():
        номер += 1
        цель = основа.with_name(f"{основа.name}-{номер}")
    try:
        цель.parent.mkdir(parents=True, exist_ok=True)
        shutil.copytree(каталог, цель, symlinks=True,
                        ignore=shutil.ignore_patterns("__pycache__"))
        return цель
    except (OSError, shutil.Error):
        return None


def _вернуть_из_копии(копия: Path, каталог: Path, пути: list) -> None:
    """Правки владельца переживают обновление: их возвращают из копии.

    Владелец 11.09.2026 (карточка задачи): «расхождение должно показываться,
    а не затираться молча». Показ — это отчёт; здесь — вторая половина: файл
    остаётся тем, каким его сделали здесь.
    """
    for путь in пути:
        откуда, куда = копия / путь, каталог / путь
        try:
            if откуда.is_file():
                куда.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(откуда, куда)
        except (OSError, shutil.Error):
            continue


def _занят_выкат() -> bool:
    """Идёт ли выкат. Спрашиваем ЛОК, а не возраст файла: deploy.lock не метка
    свежести и после выката остаётся лежать (находка I6)."""
    лок = Path(конф_модуль.log_dir()) / "locks" / "deploy.lock"
    if not лок.exists():
        return False
    готово = subprocess.run(["flock", "-n", str(лок), "-c", "true"],
                            capture_output=True, timeout=30)
    return готово.returncode != 0


def красные_из_вывода(текст: str) -> Counter | None:
    """Красные ворота из вывода gates.sh: имя → сколько строк; None — итог не
    прочитан.

    Красная — строка ровно с двумя пробелами отступа: вывод красного гейта
    идёт глубже, и его строки красными не считаются. Счёт, а не множество: две
    разные проверки носят одно имя, и вторая красная того же имени — новая."""
    if "=== итог:" not in текст:
        return None
    красные = Counter()
    for строка in текст.splitlines():
        if строка.startswith("  ПЛОХО · "):
            имя = строка[len("  ПЛОХО · "):]
            красные[re.split(r" \(код | — ", имя, maxsplit=1)[0]] += 1
    return красные


