# Дверь печатает путь архива в той же строке итога, что и числа; итог без архива — шум.
ЗНАК_АРХИВА_В_СТРОКЕ_ДВЕРИ = ", архив "


def _строка_описи(строка: str) -> bool:
    return строка.startswith(ПРЕФИКСЫ_СТРОК_ОПИСИ) or (
        строка.startswith("дверь укладки") and ЗНАК_АРХИВА_В_СТРОКЕ_ДВЕРИ in строка)


def _напечатать_строки_описи(вывод: str) -> None:
    """Строки описи раскладки в журнал обновления (stdout уходит в update-watch.log).

    Кортеж итога не трогаем: на нём стоят вызывающие; владельцу в канал строки
    описи не идут.
    """
    for строка in вывод.splitlines():
        if _строка_описи(строка):
            print(f"[обновление] {строка}")


# Бюджет §3.5: ожидание замка раскладки (300 с) и сама раскладка. Постоянная модуля,
# а не литерал: проба подменяет предел, а не спит его целиком.
LAYOUT_TIMEOUT_SEC = 900
ROLLBACK_SUFFIX = "-откат"


def _layout_root() -> Path:
    return конф_модуль.backup_dir() / "раскладка"


def _layout_archives() -> tuple[Path, Path]:
    """Пути архивов прямой и откатной раскладки; только выбирает.

    Каталоги создаёт дверь укладки: запись в архив — её граница §0, и update.py
    мимо неё не пишет. Имя занято (два обновления в одну секунду одним процессом) —
    время сдвигается вперёд: имя обязано держать форму, по которой журналы ищет
    читатель оборванных."""
    project = конф_модуль.конфиг().get("PROJECT_NAME", "")
    for shift in itertools.count():
        stamp = time.strftime("%Y%m%d-%H%M%S", time.localtime(time.time() + shift))
        forward = _layout_root() / f"{project}-{stamp}-{os.getpid()}"
        rollback = forward.with_name(forward.name + ROLLBACK_SUFFIX)
        if not (os.path.lexists(forward) or os.path.lexists(rollback)):
            return forward, rollback


def _run_layout(command: list, env: dict, timeout: float) -> subprocess.CompletedProcess:
    """Раскладчик своей группой процессов. По пределу убивается вся группа: прежний
    `subprocess.run` убивал одного ребёнка, а внук (генератор) продолжал писать в
    проект. Код по пределу — -9 всегда: лидер мог выйти сам, и 0 прочёлся бы успехом."""
    with subprocess.Popen(command, env=env, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                          text=True, start_new_session=True) as proc:
        try:
            out, err = proc.communicate(timeout=timeout)
            timed_out = False
        except subprocess.TimeoutExpired:
            with contextlib.suppress(ProcessLookupError):
                os.killpg(proc.pid, signal.SIGKILL)
            out, err = proc.communicate()
            timed_out = True
    done = subprocess.CompletedProcess(command, -9 if timed_out else proc.returncode, out, err)
    done.timed_out = timed_out
    return done


# Список вопроса берёт тот же судья, что снимает: дверь прямого прогона. Итог прогона
# ложится в LOG_DIR: `--затравка` показывает его без новой раскладки.
_SEED_LINE = re.compile(r"^по истории пакета снял бы \d+: .+; ждёт «да, убрать»$", re.M)
_SEED_LIST = re.compile(r"^список затравки: (\[.*\])$", re.M)
QUESTION_CEILING = 600
LISTED_CEILING = 400


def _save_seed_view(stdout: str) -> None:
    line = _SEED_LINE.search(stdout)
    listed = _SEED_LIST.search(stdout)
    paths = json.loads(listed.group(1)) if listed else []
    try:
        layout_history.record_seed_view(конф_модуль.log_dir(), datetime.now().astimezone(),
                                        paths, line.group(0) if line else "")
    except OSError as trouble:
        print(f"[обновление] итог затравки не записан: {trouble.strerror or trouble}")


def _seed_paths_since(moment) -> list:
    """Пути последнего итога, если он записан этим прогоном, а не прежним."""
    view = layout_history.last_seed_view(конф_модуль.log_dir())
    if isinstance(view, layout_history.SeedView) and view.ts >= moment:
        return view.paths
    return []


def _ask_about_seed(paths: list, спросить) -> None:
    """Вопрос о файлах от прежних версий: тот же набор моложе 7 суток не повторяется.
    Время берётся до отправки, носитель пишется только при коде 0: неотправленный
    вопрос не должен глушить следующий."""
    if not paths:
        return
    log_dir = конф_модуль.log_dir()
    previous = layout_history.last_question(log_dir)
    if isinstance(previous, layout_history.Unreadable):
        print(f"[обновление] вопрос о затравке не задан: {previous.reason}")
        return
    text, asked = layout_history.question_text(paths, QUESTION_CEILING)
    asked_at = datetime.now().astimezone()
    window = timedelta(days=layout_history.CONSENT_MAX_AGE_DAYS)
    if previous and asked_at - previous.ts < window and set(previous.paths) == set(asked):
        return
    if спросить(text) == 0:
        layout_history.record_question(log_dir, asked_at, asked, text)


def _files_words(count: int) -> str:
    return f"{count} {_plural_ru(count, 'файл', 'файла', 'файлов')}"


def _named(paths: list, ceiling: int = LISTED_CEILING) -> str:
    """Пути через «, » под потолок знаков; остальные — числом: отчёт об успехе
    длиннее жёсткого предела канала не дойдёт до владельца вовсе."""
    shown = []
    for path in paths:
        if shown and len(", ".join(shown + [path])) > ceiling:
            break
        shown.append(path)
    rest = len(paths) - len(shown)
    return ", ".join(shown) + (f" и ещё {rest}" if rest else "")


# Сообщение об обновлении несёт строку заметок простым языком, только пока
# остаётся заметно ниже отказа сторожа канала (900/1800): вылететь из канала
# целиком из-за выдержки оно не должно.
RELEASE_NOTE_CEILING = 800


def _with_release_note(message: str, package_dir) -> str:
    """Сообщение плюс «Что нового: …» из заметок пакета, если влезает в потолок."""
    notes = Path(package_dir) / release_notes.ИМЯ_ФАЙЛА
    note = release_notes.кратко(notes.read_text(encoding="utf-8")) if notes.is_file() else ""
    longer = f"{message} Что нового: {note}" if note else message
    return longer if len(longer) <= RELEASE_NOTE_CEILING else message


def _removed_words(archive) -> str:
    """Что убрала раскладка, словами владельцу; по пометке журнала история и опись раздельно.
    Журнал, который не прочитался, — не «ничего не убрано»."""
    if not archive:
        return ""
    journal, reason = layout_journal.read_journal(archive)
    if journal is None:
        return f" Что убрано, не прочитал: {reason}." if reason else ""
    removed = [a.path for a in journal.actions if a.kind == "снят" and a.done]
    seeded = [p for p in removed if p in journal.seed_paths]
    listed = len(removed) - len(seeded)
    words = ""
    if seeded:
        pronoun = "он" if len(seeded) == 1 else "они"
        words += (f" Убрал по истории пакета {_files_words(len(seeded))}: "
                  f"{_named(seeded)} — {pronoun} в архиве копий.")
    if listed:
        pronoun = "он" if listed == 1 else "они"
        words += f" Убрал {_files_words(listed)} прежней версии — {pronoun} в архиве копий."
    return words


def _launch_layout(archive=None, rollback_of=None, timeout=LAYOUT_TIMEOUT_SEC):
    """Только раскладчик → True | False | LayoutNotStarted | LayoutTimedOut.

    Без пересборки и доустановки: они пишут живой crontab и harness.conf, поэтому
    пробы зовут эту половину. Архив и откат идут доводами, а не окружением процесса
    update.py: переменная утекла бы в ворота и вложенные раскладки самотестов."""
    command = ["bash", str(пакет() / "harness" / "razlozhit-harnes.sh")]
    if rollback_of is not None:
        command += ["--откат", str(rollback_of)]
    env = {k: v for k, v in os.environ.items() if k != "HARNESS_LAYOUT_ARCHIVE"}
    if archive is not None:
        env["HARNESS_LAYOUT_ARCHIVE"] = str(archive)
    done = _run_layout(command, env, timeout)
    if getattr(done, "timed_out", False):
        return LayoutTimedOut()
    if done.returncode == КОД_РАСКЛАДКА_НЕ_НАЧАТА:
        return LayoutNotStarted(_причина_отказа_раскладки(done.stderr))
    if done.returncode != 0:
        return False
    _напечатать_строки_описи(done.stdout)
    if rollback_of is None:
        _save_seed_view(done.stdout)
    return True


def _напечатать_эталон() -> None:
    """Просит у root печать эталона личности по только что разложенному пакету.

    Отказ (права нет, печать упала) оставляет эталон прежним: модели получают
    старую личность, а обновление выглядело бы успешным. Поэтому отказ — сигнал
    писателю тревог (карточка), а не тишина. Вывод sudo владельцу не показываем."""
    try:
        done = subprocess.run(["sudo", "-n", "/usr/local/lib/harness/self-seal", str(пакет())],
                              capture_output=True, text=True, timeout=60)
        refused = done.returncode != 0
        detail = f"код {done.returncode}: {(done.stderr or done.stdout).strip()[-300:]}"
    except (OSError, subprocess.SubprocessError) as error:
        refused, detail = True, f"не запущено: {error}"
    if refused:
        _сигнал_отказа_печати(detail)


def _пересобрать_карточки() -> bool:
    """Карточки несут слой 1: после печати эталона они пересобираются по нему.

    Код 3 — эталона нет, карточки собраны из дерева (не сбой). Любой иной код, таймаут и
    ошибка запуска — сбой: True, если пересборка не удалась. Исключение наружу не выходит."""
    try:
        done = subprocess.run([sys.executable, str(КОРЕНЬ / "scripts" / "self-prompt.py"), "--карточки", "--в",
                               str(КОРЕНЬ / ".claude" / "agents")], capture_output=True, text=True, timeout=120)
    except (OSError, subprocess.SubprocessError):
        return True
    return done.returncode not in (0, 3)


def _эталон_личности() -> str:
    """Каталог эталона из того же источника, что читает self-prompt.py."""
    return os.environ.get("SELF_ETALON_DIR") or конф_модуль.корень_машины() + "/self"


def _сигнал_отказа_печати(detail: str) -> None:
    writer = os.environ.get("HARNESS_ALERT_TASK") or str(КОРЕНЬ / "scripts" / "alert-task.py")
    command = [writer] if os.environ.get("HARNESS_ALERT_TASK") else [sys.executable, writer]
    command += ["--key", "update:self-seal-refused", "--watcher", "update",
                "--title", "Обновление: эталон личности не напечатан (self-seal отказал)",
                "--text", f"После раскладки sudo self-seal отказал ({detail}). Модели читают прежний "
                          f"эталон {_эталон_личности()}. Напечатать эталон по кнопке согласия или "
                          "выдать право sudo на self-seal."]
    try:
        subprocess.run(command, capture_output=True, text=True, timeout=60, stdin=subprocess.DEVNULL)
    except (OSError, subprocess.SubprocessError):
        pass


def _разложить_пакет(archive=None, rollback_of=None) -> tuple:
    """Раскладка пакета в проект И пересборка производных → (раскладка_ок, упавшие).

    Пересборка обязательна: документ устройства собирается из реестра, и без
    неё гейт `check-registry.py` краснеет побайтно — то есть КАЖДОЕ
    обновление откатывалось бы самопроверкой. Упавшие сборщики отдаются
    отдельно от успеха раскладки: см. `_разложить_и_проверить`.
    """
    launched = _launch_layout(archive, rollback_of)
    if not launched and not _rollback_finished(launched, archive, rollback_of):
        return launched, []
    if launched:   # откат с кодом 1 не печатает: эталон ставит только удавшаяся раскладка
        _напечатать_эталон()
        карточки_упали = _пересобрать_карточки()
    else:
        карточки_упали = False
    упавшие = пересобрать_производные()
    if карточки_упали:
        упавшие = [*упавшие, ("карточки помощников", "self-prompt.py --карточки не собрал карточки")]
    # Новый демон без строки cron и без периода метки мёртв и незаметен
    # (находка C7): доустановка добавляет недостающее и ничего не удаляет.
    снимать_расписание = launched and archive is not None and rollback_of is None
    if снимать_расписание:
        _записать_снимок(archive / "crontab.до", _crontab_сейчас())
        _записать_снимок(archive / "harness.conf.до", _конфиг_сейчас())
        _записать_юниты_до(archive)
    доставлено = subprocess.run(
        [sys.executable, str(КОРЕНЬ / "scripts" / "install-new.py")],
        capture_output=True, text=True, timeout=300)
    if снимать_расписание:
        _записать_снимок(archive / "crontab.после", _crontab_сейчас())
        _записать_снимок(archive / "harness.conf.после", _конфиг_сейчас())
    elif rollback_of is not None and archive is not None:
        снято, не_снято = _снять_строки_новой_версии(rollback_of)
        _записать_снимок(archive / "crontab.снято", "".join(с + "\n" for с in снято))
        if не_снято:
            _записать_снимок(archive / "crontab.не-снято", не_снято)
        _записать_снимок(archive / "harness.conf.перед-откатом", _конфиг_сейчас())
        снято_к, не_снято_к = _снять_строки_конфига_новой_версии(rollback_of)
        _записать_снимок(archive / "harness.conf.снято", "".join(с + "\n" for с in снято_к))
        if не_снято_к:
            _записать_снимок(archive / "harness.conf.не-снято", не_снято_к)
        снято_ю, не_снято_ю = _снять_юниты_новой_версии(rollback_of)
        _записать_снимок(archive / "юниты.снято", "".join(ю + "\n" for ю in снято_ю))
        if не_снято_ю:
            _записать_снимок(archive / "юниты.не-снято", не_снято_ю)
    if launched and archive is not None and rollback_of is None:
        _записать_шаги_после_двери(archive)
    return bool(launched) and доставлено.returncode == 0, упавшие


def _каталог_юнитов() -> Path:
    return Path(os.environ.get("HARNESS_SYSTEMD_DIR") or "/etc/systemd/system")


def _юниты_харнеса() -> list:
    """Имена harness-* в каталоге юнитов; каталог не читается — OSError."""
    return sorted(п.name for п in _каталог_юнитов().iterdir() if п.name.startswith("harness-"))


def _записать_юниты_до(архив: Path) -> None:
    """Снимок «до» для отката: юниты ставит root-часть после прямого прогона, и без него
    не отличить новые от прежних. Не прочитан — файл `юниты.до.сбой`."""
    try:
        имена = _юниты_харнеса()
    except OSError:
        _записать_снимок(архив / "юниты.до", None)
        return
    _записать_снимок(архив / "юниты.до", "".join(и + "\n" for и in имена))


def _команда_systemctl() -> list:
    return shlex.split(os.environ.get("HARNESS_SYSTEMCTL") or "sudo -n systemctl")


def _снять_юниты_новой_версии(прямой_архив) -> tuple:
    """Откат: harness-юниты «сейчас − до» выключить и убрать → (снятые, слова о не снятых).

    Прав может не быть (юниты root): тогда ничего не падает, а владельцу уходит точная
    команда. Нет снимка «до» — не снимается ничего: разность без него снесла бы прежние юниты."""
    if (прямой_архив / "юниты.до.сбой").exists():
        return [], "снимок юнитов до прямого прогона не прочитан — ничего не снято"
    try:
        до = set((прямой_архив / "юниты.до").read_text(encoding="utf-8").split())
    except OSError:
        return [], ""
    try:
        новые = [ю for ю in _юниты_харнеса() if ю not in до]
    except OSError as беда:
        return [], f"каталог юнитов не прочитан ({беда})"
    снято, беды = [], []
    for юнит in новые:
        файл = _каталог_юнитов() / юнит
        команда_root = (f"sudo systemctl disable --now {юнит} && sudo rm {файл} "
                        f"&& sudo systemctl daemon-reload")
        try:
            готово = subprocess.run([*_команда_systemctl(), "disable", "--now", юнит],
                                    capture_output=True, text=True, timeout=60)
        except (OSError, subprocess.SubprocessError):
            беды.append(f"{юнит} — запустите: {команда_root}")
            continue
        if готово.returncode != 0:
            беды.append(f"{юнит} — запустите: {команда_root}")
            continue
        try:
            файл.unlink()
        except OSError:
            беды.append(f"{юнит} выключен, файл остался — запустите: sudo rm {файл} && sudo systemctl daemon-reload")
            continue
        снято.append(юнит)
    if снято:
        try:
            subprocess.run([*_команда_systemctl(), "daemon-reload"], capture_output=True,
                           text=True, timeout=60)
        except (OSError, subprocess.SubprocessError):
            беды.append("daemon-reload не выполнен — запустите: sudo systemctl daemon-reload")
    return снято, "; ".join(беды)


def _слова_о_снятых_юнитах(архив_отката) -> str:
    слова = ""
    try:
        снято = (архив_отката / "юниты.снято").read_text(encoding="utf-8").split()
        слова = f" Снято из systemd (юниты новой версии): {'; '.join(снято)}." if снято else ""
    except OSError:
        pass
    try:
        не_снято = (архив_отката / "юниты.не-снято").read_text(encoding="utf-8").strip()
    except OSError:
        return слова
    return f"{слова} юниты не сняты: {не_снято}." if не_снято else слова


def _crontab_сейчас() -> str | None:
    """Текст crontab; «no crontab for» — пусто законно; None — снять не удалось.

    Сбой, принятый за пустой crontab, делает «после − до» равным всему crontab, и откат
    снял бы строки владельца."""
    try:
        готово = subprocess.run(["crontab", "-l"], capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.SubprocessError):
        return None
    if готово.returncode == 0:
        return готово.stdout
    return "" if "no crontab for" in готово.stderr else None


def _записать_снимок(путь: Path, текст: str | None) -> None:
    """Снимок crontab или harness.conf; не снятый — файл `<имя>.сбой`: откат отличит сбой от раскладки без расписания."""
    try:
        if текст is None:
            (путь.parent / f"{путь.name}.сбой").write_text("снимок не прочитан\n", encoding="utf-8")
        else:
            путь.write_text(текст, encoding="utf-8")
    except OSError as беда:
        print(f"[обновление] снимок {путь.name} не записан: {беда}")


def _снять_строки_новой_версии(прямой_архив) -> tuple:
    """Откат: из нынешнего crontab снять строки, которые добавила доустановка прямого
    прогона (после − до), по точному совпадению строки → (снятые строки, почему не снято).

    Доустановка только добавляет, и без снятия прежняя версия держит задания новой.
    Прочие строки, в том числе владельца с тем же именем задания, не трогаются. Нет
    снимка «до» или «после» — не снимается ничего: разность без них снесла бы чужое."""
    if any((прямой_архив / f"crontab.{снимок}.сбой").exists() for снимок in ("до", "после")):
        return [], "снимок crontab до доустановки не прочитан"
    try:
        до = (прямой_архив / "crontab.до").read_text(encoding="utf-8").splitlines()
        после = (прямой_архив / "crontab.после").read_text(encoding="utf-8").splitlines()
    except OSError:
        return [], ""
    добавлено = set(после) - set(до)
    нынешний = _crontab_сейчас()
    if нынешний is None:
        return [], "crontab не прочитан"
    строки = нынешний.splitlines()
    снято = [с for с in строки if с in добавлено]
    if not снято:
        return [], ""
    остаток = "".join(с + "\n" for с in строки if с not in добавлено)
    try:
        подмена = subprocess.run(["crontab", "-"], input=остаток, text=True,
                                 capture_output=True, timeout=30)
    except (OSError, subprocess.SubprocessError) as беда:
        return [], str(беда)
    if подмена.returncode != 0:
        return [], подмена.stderr.strip() or f"crontab - вернул код {подмена.returncode}"
    return снято, ""


def _конфиг_сейчас() -> str | None:
    """Текст живого harness.conf; нет файла — пусто законно; None — прочитать не удалось.

    Тот же договор, что у crontab: сбой, принятый за пустой конфиг, сделал бы «после − до»
    равным всему конфигу, и откат снёс бы ключи владельца."""
    try:
        return Path(конф_модуль.путь_harness_conf()).read_text(encoding="utf-8")
    except FileNotFoundError:
        return ""
    except (OSError, UnicodeDecodeError):
        return None


def _строки_конфига_после_отката(нынешние, до, после) -> list:
    """Строки «после − до» убрать, строки «до − после» вернуть на прежнее место.

    Дописанное владельцем после укладки в обе разности не входит и остаётся. Изменённая
    доустановкой строка (метки HEARTBEAT_PERIODS) — это пара: новая уходит, прежняя
    встаёт на место новой, а не в конец файла."""
    добавлено, было_после = set(после) - set(до), set(после)
    прежние = iter([с for с in до if с not in было_после])
    итог = []
    for строка in нынешние:
        if строка not in добавлено:
            итог.append(строка)
        elif (вернуть := next(прежние, None)) is not None:
            итог.append(вернуть)
    return итог + list(прежние)


def _снять_строки_конфига_новой_версии(прямой_архив) -> tuple:
    """Откат: вернуть harness.conf к состоянию до доустановки прямого прогона →
    (снятые строки, почему не снято).

    Доустановка дописывает метки и ключи новой версии, и без возврата сторож пульса
    объявляет демоны новой версии мёртвыми (копия сети 20.11). Нет снимка
    «до» или «после» — не снимается ничего. Ничего не изменилось — файл не пишется."""
    if any((прямой_архив / f"harness.conf.{снимок}.сбой").exists() for снимок in ("до", "после")):
        return [], "снимок harness.conf до доустановки не прочитан"
    try:
        до = (прямой_архив / "harness.conf.до").read_text(encoding="utf-8").splitlines()
        после = (прямой_архив / "harness.conf.после").read_text(encoding="utf-8").splitlines()
    except OSError:
        return [], ""
    нынешний = _конфиг_сейчас()
    if нынешний is None:
        return [], "harness.conf не прочитан"
    строки = нынешний.splitlines()
    добавлено = set(после) - set(до)
    снято = [с for с in строки if с in добавлено]
    новые = _строки_конфига_после_отката(строки, до, после)
    if новые == строки:
        return [], ""
    файл = Path(конф_модуль.путь_harness_conf())
    try:
        # Копия до записи (И-1) — снимок «перед-откатом» в архиве отката, его пишет вызывающий:
        # копия панели легла бы в живой LOG_DIR и из пробы.
        писатель.записать_атомарно(файл, "".join(с + "\n" for с in новые))
    except OSError as беда:
        return [], str(беда)
    return снято, ""


