def замок_раскладки() -> str:
    """Причина не ставить обновление или пусто (эталонный выкат §6.2 п. 2).

    Копия, катившая своим выкатом с развилкой STACK_ROLLOUT=server, держала в нём тесты
    продукта на стенде. Эталон пакета развилки не знает и без STACK_CHECKS_FILE выкатил бы её
    продукт без тестов. Судится конфиг копии; копию без STACK_ROLLOUT замок не касается.
    """
    путь = конф_модуль.путь_harness_conf()
    ключи = конф_модуль.конфиг(путь)
    moved = [f"{old} → {new}" for old, new in RETIRED_KEYS
               if ключи.get(old) and not ключи.get(new)]
    if moved:
        return (f"в {путь} заданы ключи прежнего выката, а их места в эталоне пусты: "
                f"{', '.join(moved)} — эталон прежних не читает; перенеси значения (прежние можно "
                f"оставить) и обнови снова; раскладка не начата, пакет и проект не тронуты")
    if ключи.get("STACK_ROLLOUT") != "server" or ключи.get("STACK_CHECKS_FILE"):
        return ""
    return (f"в {путь} STACK_ROLLOUT=server, а STACK_CHECKS_FILE пуст: новый выкат продукта идёт "
            f"одним путём и берёт тесты на стенде из файла проверок — задай STACK_CHECKS_FILE "
            f"(с ним STACK_CHECK_MIN_FREE_MB и STACK_CHECK_UID) и обнови снова; раскладка не начата, "
            f"пакет и проект не тронуты")


КРАСНАЯ = "  ПЛОХО · "
# Слова владельца для отката; те же слова — в bot-commands.yaml (update_rollback).
СЛОВА_ОТКАТА = "откати обновление"
СТРОК_ПРИЧИНЫ = 5


class Красные(Counter):
    """Счёт красных имён и рядом — .причины: имя → хвост её вывода."""


def _имя_красной(строка: str) -> str:
    return re.split(r" \(код | — ", строка[len(КРАСНАЯ):], maxsplit=1)[0]


def красные_из_вывода(текст: str) -> Counter | None:
    """Красные ворота из вывода gates.sh: имя → сколько строк; None — итог не
    прочитан.

    Красная — строка ровно с двумя пробелами отступа: вывод красного гейта
    идёт глубже, и его строки красными не считаются. Счёт, а не множество: две
    разные проверки носят одно имя, и вторая красная того же имени — новая."""
    if "=== итог:" not in текст:
        return None
    красные = Красные(_имя_красной(строка) for строка in текст.splitlines()
                      if строка.startswith(КРАСНАЯ))
    красные.причины = причины_красных(текст)
    return красные


# Зелёная строка пробы внутри красного блока: «ок · …», «ok - …».
ЗЕЛЁНАЯ_СТРОКА = re.compile(r"^(ок|ok)\b", re.IGNORECASE)


def причины_красных(текст: str) -> dict:
    """Имя красной → до пяти первых строк её блока (строки глубже двух пробелов),
    без зелёных строк пробы: гейт сперва называет находку, итог — в хвосте.

    Находка копии сети 14.11.2026: вывод назвал пять имён и ни одной причины —
    чинится ли это данными копии или нужен пакет, судить было нечем."""
    причины, блок = {}, None
    for строка in текст.splitlines():
        if строка.startswith(КРАСНАЯ):
            блок = причины.setdefault(_имя_красной(строка), [])
        elif строка.startswith("   ") and блок is not None:
            if строка.strip() and not ЗЕЛЁНАЯ_СТРОКА.match(строка.strip()):
                блок.append(строка.strip())
        else:
            блок = None
    return {имя: строки[:СТРОК_ПРИЧИНЫ] for имя, строки in причины.items()}


# Главные проверки — данные установки: только их новая красная откатывает обновление.
# Прочая красная судит код и среду самой копии, откат пакета её не снимает.
ПРОВЕРКИ_ГЛАВНЫЕ = "update-rollback.yaml"
# В сообщение владельцу — по две строки причины на красную, строка не длиннее этого.
СТРОК_В_СЛОВАХ, ЗНАКОВ_СТРОКИ = 2, 200


def главные_проверки(корень: Path = None) -> set | None:
    """Имена главных проверок из update-rollback.yaml установки; None — файла нет или
    в нём нет ни одного имени (копия старше): тогда откатывает любая новая красная,
    проверка не мягчает."""
    корень = корень or КОРЕНЬ
    for каталог in (корень / "harness" / "config", корень / "config"):
        путь = каталог / ПРОВЕРКИ_ГЛАВНЫЕ
        if путь.is_file():
            записи = (yaml.safe_load(путь.read_text(encoding="utf-8")) or {}).get("главные") or []
            return {запись["имя"] for запись in записи} or None
    return None


def слова_о_причинах(причины: dict) -> str:
    """«имя — строка | строка; …»: гейт и первые строки причины, коротко."""
    return "; ".join(
        f"{имя} — " + (" | ".join(строка[:ЗНАКОВ_СТРОКИ] for строка in строки[:СТРОК_В_СЛОВАХ]) or "вывода нет")
        for имя, строки in причины.items())


# Срок карантина — предел суда карантина (gates-quarantine.py MAX_DAYS).
СРОК_КАРАНТИНА_ДНЕЙ = 7


# Первая строка вывода писателя тревог: «заведена|повтор|беклог <id>»; следом бывают строки notice.
КАРТОЧКА_ИЗ_ВЫВОДА = re.compile(r"^(заведена|повтор|беклог) (\S+)$")
# Код писателя тревог на зов из сессии: карточки заводит только демон.
ПИСАТЕЛЬ_ТОЛЬКО_ДЕМОН = 6


def _завести_карточку(коммит: str, красные: dict) -> str:
    """Одна карточка на обновление через писатель тревог → её id.

    Ключ по версии, а не по имени красной: писатель держит потолок открытых карточек на
    сторожа, и карточка на каждое имя оставила бы часть красных без неё."""
    писатель = os.environ.get("HARNESS_ALERT_TASK")
    команда = [писатель] if писатель else [sys.executable, str(КОРЕНЬ / "scripts" / "alert-task.py")]
    версия = коммит[:7]
    готово = subprocess.run(
        [*команда, "--key", f"update:quarantine:{версия}", "--watcher", "update",
         "--title", f"Обновление {версия}: новые красные стоят в карантине копии ({len(красные)})",
         "--text", f"После обновления до {версия} красны проверки, они не главные: обновление встало, "
                   f"карантин на {СРОК_КАРАНТИНА_ДНЕЙ} дней. Причины: {слова_о_причинах(красные)}. "
                   "Починить до конца срока."],
        capture_output=True, text=True, timeout=60, stdin=subprocess.DEVNULL)
    if готово.returncode == ПИСАТЕЛЬ_ТОЛЬКО_ДЕМОН:
        raise OSError("карточки заводит только демон: обновление запущено из сессии, "
                      "запусти командой бота «обнови»")
    первая = готово.stdout.splitlines()[0].strip() if готово.stdout.strip() else ""
    найдено = КАРТОЧКА_ИЗ_ВЫВОДА.match(первая)
    if готово.returncode != 0 or not найдено:
        raise OSError(f"писатель тревог не завёл карточку (код {готово.returncode}): {первая or 'вывода нет'}")
    return найдено.group(2)


def _запись_карантина(имя: str, карточка: str, причины: list) -> str:
    сегодня = datetime.now().date()
    причина = (причины[0] if причины else "вывода нет")[:ЗНАКОВ_СТРОКИ]
    return (f"  - гейт: {json.dumps(имя, ensure_ascii=False)}\n    карточка: {карточка}\n"
            f"    заведено: \"{сегодня}\"\n    срок: \"{сегодня + timedelta(days=СРОК_КАРАНТИНА_ДНЕЙ)}\"\n"
            f"    причина: {json.dumps(причина, ensure_ascii=False)}\n")


# Якорь списка: «карантин:» с пустым списком или без него, комментарий в конце строки допустим.
ЯКОРЬ_КАРАНТИНА = re.compile(r"^карантин:\s*(\[\])?\s*(#.*)?$", re.MULTILINE)


def _вставить_в_карантин(текст: str, вставка: str) -> str:
    """Вставка сразу после блока списка под `карантин:`: комментарии и записи копии — на местах.
    Нет якоря — ключ дописывается в конец."""
    якорь = ЯКОРЬ_КАРАНТИНА.search(текст)
    if not якорь:
        return текст.rstrip("\n") + ("\n" if текст.strip() else "") + "карантин:\n" + вставка
    строки = текст.splitlines(keepends=True)
    номер = текст.count("\n", 0, якорь.start())
    if якорь.group(1):   # пустой список `[]` становится блоком
        строки[номер] = "карантин:" + (f" {якорь.group(2)}" if якорь.group(2) else "") + "\n"
    конец = номер + 1
    for след in range(номер + 1, len(строки)):
        if строки[след][:1] in (" ", "\t", "-") and строки[след].strip():
            конец = след + 1
        elif строки[след].strip() and not строки[след].startswith("#"):
            break
    if not строки[конец - 1].endswith("\n"):
        строки[конец - 1] += "\n"
    return "".join(строки[:конец]) + вставка + "".join(строки[конец:])


def _просрочка(запись: dict) -> str:
    """Почему старая запись карантина больше не прикрывает гейт (пусто — прикрывает): суд
    карантина — gates-quarantine.py defect, свой набор правил здесь разошёлся бы с ним."""
    спека = importlib.util.spec_from_file_location("gates_quarantine", КОРЕНЬ / "scripts" / "gates-quarantine.py")
    суд = importlib.util.module_from_spec(спека)
    спека.loader.exec_module(суд)
    return суд.defect(запись, datetime.now().date(), {str(запись.get("карточка"))}, [])


def _в_карантин_копии(прочие: dict, коммит: str) -> tuple:
    """Прочие новые красные → записи в карантин копии на одну карточку → ({имя: карточка}, беды).

    Файл — живая настройка копии: записи вставляются текстом после списка, комментарии и
    свои записи копии остаются. Нет карточки — нет записи: карантин без карточки суд
    карантина всё равно назвал бы бедой. Нечитаемый файл не переписывается."""
    путь = Path(os.environ.get("HARNESS_GATES_QUARANTINE")
                or КОРЕНЬ / "harness" / "config" / "gates-quarantine.yaml")
    try:
        текст = путь.read_text(encoding="utf-8") if путь.is_file() else "карантин:\n"
        записи = (yaml.safe_load(текст) or {}).get("карантин") or []
    except (yaml.YAMLError, OSError) as беда:
        return {}, [f"{путь.name} — {str(беда).splitlines()[0]}"]
    есть = {з.get("гейт"): з for з in записи}
    карточки, беды, новые = {}, [], {}
    for имя, причины in прочие.items():
        старая = есть.get(имя)
        просрочка = _просрочка(старая) if старая else ""
        if просрочка:
            беды.append(f"{имя} — запись карантина просрочена ({просрочка}): прикрытия нет")
        elif старая:
            карточки[имя] = str(старая.get("карточка"))
        else:
            новые[имя] = причины
    if not новые:
        return карточки, беды
    try:
        карточка = _завести_карточку(коммит, новые)
        вставка = "".join(_запись_карантина(имя, карточка, причины) for имя, причины in новые.items())
        итог = _вставить_в_карантин(текст, вставка)
        после = (yaml.safe_load(итог) or {}).get("карантин") or []
        if len(после) != len(записи) + len(новые):
            raise OSError(f"счёт записей {len(записи)} → {len(после)}, ждали {len(записи) + len(новые)}")
        путь.write_text(итог, encoding="utf-8")
    except (OSError, subprocess.SubprocessError, yaml.YAMLError) as беда:
        return карточки, [*беды, *(f"{имя} — {str(беда).splitlines()[0]}" for имя in новые)]
    return {**карточки, **{имя: карточка for имя in новые}}, беды


# Код отказа разбора доводов у evolution-net.py: у копии режима отправки находок нет.
НЕТ_РЕЖИМА_ОТПРАВКИ = 2


def _послать_находку(текст: str, коммит: str, архив: Path) -> str:
    """Находка о новых красных в сеть эволюции → пусто при успехе, иначе слово об отказе.

    Текст ложится в архив прямого прогона до отправки: отказ двери не теряет находку.
    Отправителя находок у копии пока нет (evolution-net.py — только хозяин): отказ
    двери — слово владельцу, обновлению и откату он не мешает."""
    дверь = os.environ.get("HARNESS_EVOLUTION_FINDING")
    команда = [дверь] if дверь else [sys.executable, str(КОРЕНЬ / "scripts" / "evolution-net.py")]
    файл = архив / "находка.md"
    try:
        архив.mkdir(parents=True, exist_ok=True)   # отказ до первой записи раскладчика оставляет архив без каталога
        файл.write_text(текст, encoding="utf-8")
        готово = subprocess.run(
            [*команда, "--находка-копии", "--суть", f"update-{коммит[:7]}-reds", "--файл", str(файл)],
            capture_output=True, text=True, timeout=120, stdin=subprocess.DEVNULL)
    except (OSError, subprocess.SubprocessError) as беда:
        return f"находка не отправлена: {беда}"
    if готово.returncode == 0:
        return ""
    if готово.returncode == НЕТ_РЕЖИМА_ОТПРАВКИ:
        return f"находка не отправлена: у копии нет отправителя находок; текст — {файл}"
    строки = [с.strip() for с in (готово.stderr or готово.stdout).splitlines() if с.strip()]
    return f"находка не отправлена: {строки[-1] if строки else 'вывода нет'}"


def _текст_находки(прежний: str, коммит: str, исход: str, красные: dict) -> str:
    """Находка: версии, исход, каждая красная и до пяти строк её причины."""
    блоки = [f"## {имя}\n" + "".join(f"- {с}\n" for с in строки[:СТРОК_ПРИЧИНЫ] or ["вывода нет"])
             for имя, строки in красные.items()]
    return (f"# Обновление {прежний[:7]} → {коммит[:7]}: новые красные\n\nИсход: {исход}.\n\n"
            + "\n".join(блоки))


# Обычные ворота (без --всё) на свежей 4-ядерной машине шли 44–58 мин: предел —
# данные установки, а не число в коде.
ПРЕДЕЛ_ВОРОТ_УМОЛЧАНИЕ = 5400
# Ключ — пол, а не потолок: у копии сети 15.11.2026 полный прогон шёл 1,5–2,5 ч, и
# 5400 с образца обрывали ворота после обновления — откат. Ворота новой версии бывают
# длиннее прежних: запас к стене прошлого законченного полного прогона этой установки.
ЗАПАС_ПРЕДЕЛА = 1.5


def предел_ворот() -> int:
    значение = конф_модуль.конфиг(конф_модуль.путь_harness_conf()).get("UPDATE_GATES_TIMEOUT_SEC", "")
    ключ = int(значение) if str(значение).isdigit() else ПРЕДЕЛ_ВОРОТ_УМОЛЧАНИЕ
    прошлый = _последний_полный_прогон()
    стена = 0 if прошлый is None else (прошлый[1] - прошлый[0]).total_seconds()
    return max(ключ, math.ceil(ЗАПАС_ПРЕДЕЛА * стена))


def слова_о_пределе_ворот() -> str:
    return (f"предел {предел_ворот()} с — ключ UPDATE_GATES_TIMEOUT_SEC в harness.conf "
            f"или {ЗАПАС_ПРЕДЕЛА:g} × прошлый полный прогон ворот, что больше")


def журнал_ворот() -> Path:
    """Ход ворот постановки: «до» и «после» идут по очереди под замком постановки."""
    журнал = Path(конф_модуль.log_dir()) / "update-gates.log"
    журнал.parent.mkdir(parents=True, exist_ok=True)
    return журнал


def _ворота_в_журнал(журнал: Path, предел: int) -> bool:
    """gates.sh своей группой, вывод в журнал по мере хода → дошли ли в срок.

    Вывод в файл, а не в память: копия сети 14.11.2026 ждала ворота
    30 мин и не видела ни строки. По пределу убивается вся группа: проверки,
    пережившие ворота, жгли бы процессор и писали бы в журнал следующего прогона."""
    свой_журнал = журнал.parent / "update-gates-timing"
    свой_журнал.mkdir(exist_ok=True)
    with open(журнал, "w", encoding="utf-8") as вывод, subprocess.Popen(
            ["bash", str(КОРЕНЬ / "scripts" / "gates.sh")], stdout=вывод, stderr=subprocess.STDOUT,
            stdin=subprocess.DEVNULL, start_new_session=True,
            env={**os.environ, "GATES_TIMING_DIR": str(свой_журнал),
                 # Свой сторож gates.sh (GATES_RUN_TIMEOUT_SEC) иначе оборвал бы прогон раньше.
                 "GATES_RUN_TIMEOUT_SEC": str(предел)}) as proc:
        try:
            proc.wait(timeout=предел)
            return True
        except subprocess.TimeoutExpired:
            with contextlib.suppress(ProcessLookupError):
                os.killpg(proc.pid, signal.SIGKILL)
            return False


def прогнать_ворота() -> Counter | None:
    """Самопроверка харнеса: счёт красных имён. Код возврата не судим: жёлтые
    проверки в него не входят. Оборванный пределом прогон — не прочитанный
    итог, то есть None."""
    журнал = журнал_ворот()
    print(f"[обновление] ворота идут ({слова_о_пределе_ворот()}); ход — в {журнал}")
    if not _ворота_в_журнал(журнал, предел_ворот()):
        return None
    return красные_из_вывода(журнал.read_text(encoding="utf-8", errors="replace"))


# Основа «красных до» — прошлый полный прогон ворот этой установки (ночной или
# ручной), а не свой прогон перед постановкой: владелец 14.11.2026 на копии сети —
# «пару часов была проверка, потом раскатка, а потом самопроверка». Релиз уже
# прошёл полные ворота у хозяина перед публикацией. Прогоны самой постановки
# пишут свой журнал (update-gates-timing): красные откаченной версии иначе стали
# бы основой следующей попытки, и битый релиз встал бы со второго раза.
СВЕЖЕСТЬ_ОСНОВЫ = timedelta(days=7)
# Итог ворот пишется сразу за последней проверкой прогона: так прогон
# узнаётся законченным, а не оборванным.
ЗАЗОР_ИТОГА = timedelta(minutes=5)
ПОЛНЫЕ_РЕЖИМЫ = ("обычный", "всё")


def _строки_jsonl(путь: Path) -> list:
    try:
        текст = путь.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return []
    строки = []
    for строка in текст.splitlines():
        with contextlib.suppress(ValueError):
            строки.append(json.loads(строка))
    return [с for с in строки if isinstance(с, dict)]


def _время(запись: dict):
    """Время записи журнала с поясом; без пояса или битое — None: записи
    без пояса с поясными не сравнить."""
    try:
        когда = datetime.fromisoformat(str(запись.get("ts")))
    except ValueError:
        return None
    return когда if когда.tzinfo else None


def _начало_прогона(прогон: str):
    """Метка прогона gates.sh — «<время начала> <pid>»; без пояса или битая — None."""
    return _время({"ts": str(прогон).split(" ")[0]})


def _прогоны_проверок(записи: list) -> dict:
    """Прогон → (начало, время последней проверки, счёт красных имён). Соло-перепрогон
    красной не считается: имя уже сосчитано общим прогоном."""
    прогоны = {}
    for запись in записи:
        данные = запись.get("data") or {}
        когда = _время(запись)
        if (запись.get("event") != "gate.check" or not данные.get("run") or когда is None
                or данные.get("solo")):
            continue
        начало, последняя, красные = прогоны.get(
            данные["run"], (_начало_прогона(данные["run"]) or когда, когда, Counter()))
        if запись.get("outcome") != "ok":
            красные[данные.get("name")] += 1
        прогоны[данные["run"]] = (min(начало, когда), max(последняя, когда), красные)
    return прогоны


def _последний_полный_прогон(сейчас=None) -> tuple | None:
    """(начало, конец, красные) последнего законченного полного прогона ворот не старше
    СВЕЖЕСТЬ_ОСНОВЫ; None — такого нет."""
    журналы = Path(конф_модуль.log_dir())
    сейчас = сейчас or datetime.now().astimezone()
    итоги = [_время(и) for и in _строки_jsonl(журналы / "ворота-итог.jsonl")
             if и.get("режим", "обычный") in ПОЛНЫЕ_РЕЖИМЫ and _время(и)]
    законченные = [прогон for прогон
                   in _прогоны_проверок(_строки_jsonl(журналы / "gates-timing.jsonl")).values()
                   if сейчас - прогон[1] <= СВЕЖЕСТЬ_ОСНОВЫ
                   and any(timedelta(0) <= итог - прогон[1] <= ЗАЗОР_ИТОГА for итог in итоги)]
    return max(законченные, key=lambda прогон: прогон[1]) if законченные else None


def красные_прошлых_ворот(сейчас=None) -> Красные | None:
    """Красные последнего законченного полного прогона ворот; None — такого нет
    (тогда ворота идут перед постановкой)."""
    прошлый = _последний_полный_прогон(сейчас)
    if прошлый is None:
        return None
    _, когда, красные = прошлый
    основа = Красные(красные)
    основа.причины, основа.когда = {}, когда
    return основа


@contextlib.contextmanager
def _замок_постановки():
    """Одна постановка за раз: два прогона ворот разом откатывают друг друга
    под запись версии. Держится до конца постановки; дочерние процессы его не
    наследуют (close_fds)."""
    лок = Path(конф_модуль.log_dir()) / "locks" / "update.lock"
    лок.parent.mkdir(parents=True, exist_ok=True)
    with open(лок, "a+") as файл:
        try:
            fcntl.flock(файл, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            yield False
            return
        try:
            yield True
        finally:
            fcntl.flock(файл, fcntl.LOCK_UN)


def поставить(*, разложить=None, перезапустить=None, проверить=None,
              сказать=None, спросить=None, reset_own=False, host=None,
              сверить_корень=None, despite_reds=False) -> dict:
    """Поставить обновление под замком постановки; занят — отказ словами.

    `despite_reds` — слово владельца: новые красные главных проверок не откатывают,
    а уходят в карантин копии вместе с прочими."""
    сказать = сказать or (lambda текст: None)
    with _замок_постановки() as взят:
        if not взят:
            причина = "уже идёт другая постановка обновления"
            сказать(f"Обновление не поставлено: {причина}")
            return {"поставлено": False, "беда": причина}
        return _поставить_под_замком(разложить=разложить, перезапустить=перезапустить,
                                     проверить=проверить, сказать=сказать, спросить=спросить,
                                     reset_own=reset_own, host=host,
                                     сверить_корень=сверить_корень, despite_reds=despite_reds)


def _записать_постановку(архив: Path, прежний: str, коммит: str, красные: dict, по_слову: bool) -> None:
    """`постановка.json` в архиве прямого прогона: по нему откатывает команда отката.

    Не записана — обновление уже стоит, весть об этом не смеет стать исключением."""
    запись = {"прежний": прежний, "коммит": коммит,
              "причина": "по слову владельца" if по_слову else "проверки",
              "новые красные": красные}
    try:
        архив.mkdir(parents=True, exist_ok=True)
        (архив / "постановка.json").write_text(
            json.dumps(запись, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    except OSError as беда:
        print(f"[обновление] постановка.json не записана: {беда}")


def _последняя_постановка() -> tuple:
    """(архив, запись) последней постановки по времени файла; нет — (None, None)."""
    лучшая = None
    for файл in _layout_root().glob("*/постановка.json"):
        try:
            метка = файл.stat().st_mtime_ns
            запись = json.loads(файл.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        if isinstance(запись, dict) and (лучшая is None or метка > лучшая[0]):
            лучшая = (метка, файл.parent, запись)
    return (лучшая[1], лучшая[2]) if лучшая else (None, None)


def откатить_последнюю(*, разложить=None, перезапустить=None, сказать=None) -> dict:
    """Откатить последнюю постановку по записи в её архиве, под замком постановки.

    Пакет должен стоять на её коммите: иначе откат ударил бы по чужим правкам.
    Не вышло — отказ словами, пакет не тронут."""
    сказать = сказать or (lambda текст: None)
    with _замок_постановки() as взят:
        if not взят:
            return _отказ_отката("уже идёт другая постановка обновления", сказать)
        return _откатить_под_замком(разложить or _разложить_пакет,
                                    перезапустить or _перезапустить_службы, сказать)


def _отказ_отката(причина: str, сказать) -> dict:
    сказать(f"Откат не сделан: {причина}")
    return {"откат удался": False, "беда": причина}


def _откатить_под_замком(разложить, перезапустить, сказать) -> dict:
    каталог = пакет()
    архив, запись = _последняя_постановка()
    if архив is None:
        return _отказ_отката("записи о постановке обновления нет — откатывать нечего", сказать)
    прежний, коммит = str(запись.get("прежний") or ""), str(запись.get("коммит") or "")
    стоит = _гит("rev-parse", "HEAD", где=каталог).stdout.strip()
    откатный = архив.with_name(архив.name + ROLLBACK_SUFFIX)
    if not прежний or not коммит:
        return _отказ_отката(f"запись постановки {архив.name} без версий", сказать)
    if стоит != коммит or os.path.lexists(откатный):
        return _отказ_отката(f"последняя постановка ({коммит[:7]}) уже не стоит: пакет на {стоит[:7]}", сказать)
    if _занят_выкат():
        return _отказ_отката("идёт выкат — откат подождёт", сказать)
    копия = _снять_копию(каталог)
    if копия is None:
        return _отказ_отката("копия не снята — пакет не тронут", сказать)
    сброшен = _гит("reset", "--hard", прежний, где=каталог)
    if сброшен.returncode != 0:
        return _отказ_отката(f"пакет не вернулся на {прежний[:7]}: "
                             f"{(сброшен.stderr or сброшен.stdout).strip()}", сказать)
    записать_версию(прежний)
    откат_разложен, _ = разложить(archive=откатный, rollback_of=архив)
    перезапустить()
    слова, исход = _rollback_report(архив, откатный, откат_разложен)
    сказать(f"Обновление {коммит[:7]} откачено: откат на {прежний[:7]}. Копия до отката: {копия}."
            f"{слова}{_слова_о_снятом_crontab(откатный)}{_слова_о_снятом_конфиге(откатный)}{_слова_о_снятых_юнитах(откатный)}")
    return {"откат удался": True, "откат": прежний, "откачено": коммит, "копия": str(копия),
            "архив отката": str(откатный), "откат разложен": bool(откат_разложен),
            "откат по журналу": исход}


def _count_own_commits(каталог: Path, public: str) -> int | None:
    """Сколько коммитов пакета нет в публичном; 0 — пакет просто позади.
    None — git не ответил: считать «своих нет» значило бы стереть их сбросом."""
    ancestor = _гит("merge-base", "--is-ancestor", "HEAD", public, где=каталог)
    if ancestor.returncode == 0:
        return 0
    if ancestor.returncode != 1:
        return None
    count = _гит("rev-list", "--count", "HEAD", f"^{public}", где=каталог)
    if count.returncode != 0 or not count.stdout.strip().isdigit():
        return None
    return int(count.stdout.strip())


# Отказ уходит владельцу в канал: двадцать своих коммитов длиннее экрана.
OWN_COMMITS_LISTED = 10


def _own_commits_lines(каталог: Path, public: str) -> list:
    """«sha тема» своих коммитов пакета — тех, которых нет в публичном."""
    вышло = _гит("log", "--format=%h %s", "HEAD", f"^{public}", где=каталог)
    return [с for с in вышло.stdout.splitlines() if с.strip()] if вышло.returncode == 0 else []


def _own_commits_words(каталог: Path, public: str) -> str:
    строки = _own_commits_lines(каталог, public)
    if not строки:
        return ""
    остаток = len(строки) - OWN_COMMITS_LISTED
    хвост = f"; и ещё {остаток}" if остаток > 0 else ""
    return f" Свои коммиты: {'; '.join(строки[:OWN_COMMITS_LISTED])}{хвост}."


def _branch_exists(каталог: Path, name: str) -> bool:
    return _гит("show-ref", "--verify", "--quiet", f"refs/heads/{name}",
                где=каталог).returncode == 0


def _save_own_and_reset(каталог: Path, прежний: str, public: str,
                        host: str | None) -> tuple[str | None, int | None, str | None]:
    """Свои коммиты пакета → ветка-страховка, и только затем пакет встаёт на
    публичный коммит. → (имя | None, число своих | None, причина отказа | None):
    при отказе пакет остался на своём коммите (И-1).

    Число считается здесь, прямо перед веткой: коммит, лёгший за время ворот
    «до», уезжает в ветку вместе с прочими.
    Занятое имя не затирается: `git branch` без -f не перезаписывает ветку,
    поэтому гонка за имя кончается отказом git, а не потерей чужой ветки."""
    own_count = _count_own_commits(каталог, public)
    if own_count is None:
        return None, None, "не удалось сосчитать свои коммиты пакета — пакет не тронут"
    base_name = (f"server-{host or socket.gethostname()}-local-"
                 f"{time.strftime('%Y%m%d-%H%M')}")
    name = base_name
    for suffix in range(2, 102):
        if not _branch_exists(каталог, name):
            created = _гит("branch", name, прежний, где=каталог)
            if created.returncode == 0:
                break
            if not _branch_exists(каталог, name):
                return None, own_count, (f"ветка-страховка {name} не создалась: "
                                         f"{(created.stderr or created.stdout).strip()}")
        name = f"{base_name}-{suffix}"
    else:
        return None, own_count, f"не нашлось свободного имени ветки-страховки от {base_name}"
    count = _гит("rev-list", "--count", name, f"^{public}", где=каталог)
    if count.returncode != 0 or count.stdout.strip() != str(own_count):
        return name, own_count, (f"в ветке-страховке {name} число своих коммитов не сошлось: "
                                 f"{count.stdout.strip() or '?'} вместо {own_count}")
    reset = _гит("reset", "--hard", public, где=каталог)
    if reset.returncode != 0:
        # Отвергнутый на обновлении ссылки reset уже переписал индекс и дерево.
        restored = _гит("read-tree", "--reset", "-u", прежний, где=каталог)
        restore_note = ("" if restored.returncode == 0 else
                        f"; дерево на свой коммит вернуть не удалось: "
                        f"{(restored.stderr or restored.stdout).strip()}")
        return name, own_count, (f"пакет не встал на публичный коммит: "
                                 f"{(reset.stderr or reset.stdout).strip()}{restore_note}")
    return name, own_count, None


def _reset_phrase() -> str | None:
    """Слова владельца для команды сброса — из данных команд бота; None, если
    команды в данных нет (отказ тогда идёт без подсказки, но идёт)."""
    data = yaml.safe_load((КОРЕНЬ / "harness" / "config" / "bot-commands.yaml")
                          .read_text(encoding="utf-8"))
    command = next((к for к in data["команды"] if к["имя"] == "update_reset"), None)
    return command["слова"][0] if command else None


def _plural_ru(count: int, one: str, few: str, many: str) -> str:
    if count % 100 in range(11, 15) or count % 10 not in (1, 2, 3, 4):
        return many
    return one if count % 10 == 1 else few


def _commits_word(count: int) -> str:
    return _plural_ru(count, "коммит", "коммита", "коммитов")


def _branch_words(own_count: int, name: str) -> str:
    return (f" Свои правки пакета ({own_count} {_commits_word(own_count)}) сохранены "
            f"в ветке {name}. Они не потеряны, но в новую версию не перенесены.")


def _группа_без_ключа_владельца() -> str:
    """Причина отказа, если канал — группа, а паспорт не знает id владельца.

    Слово владельца в группе судится по from.id против TG_OWNER_ID. id из данных
    установки не выводим: from.id в них мог оставить любой участник группы, и
    вывод сделал бы владельцем первого написавшего. Поэтому — отказ до копии и
    перезапуска, пока владелец не впишет id сам."""
    паспорт = конф_модуль.из_файла(конф_модуль.путь_install_conf())
    канал = str(паспорт.get("TG_CHAT_ID") or "").strip()
    владелец = str(паспорт.get("TG_OWNER_ID") or "").strip()
    if not канал.startswith("-") or (владелец and not владелец.startswith("-")):
        return ""
    return ("канал — группа (TG_CHAT_ID начинается с «-»), а в install.conf нет TG_OWNER_ID: "
            "без него слово владельца в группе не отличить от слова других участников. "
            "Впиши в install.conf строку TG_OWNER_ID=\"<твой id>\" — свой from.id "
            "(числовой id, не отрицательный id группы; его видно в личке с ботом) — "
            "и повтори обновление. Ничего не тронуто")


def _поставить_под_замком(*, разложить, перезапустить, проверить, сказать,
                          спросить=None, reset_own=False, host=None,
                          сверить_корень=None, despite_reds=False) -> dict:
    """Поставить обновление: ворота до → копия → пакет вперёд → раскладка → проверка.

    Не прошло — откат на прежний коммит, версия НЕ меняется, владельцу сказано
    словами. Внешние действия приходят доводами: так их подменяет проверка, а
    живая установка получает умолчания.
    """
    разложить = разложить or _разложить_пакет
    перезапустить = перезапустить or _перезапустить_службы
    проверить = проверить or прогнать_ворота
    спросить = спросить or _спросить_владельца
    сверить_корень = сверить_корень or root_part_gaps
    начало = datetime.now().astimezone()

    каталог = пакет()

    def отказ(причина: str, **ещё) -> dict:
        """Любой отказ доходит до владельца: молчаливо не поставленное
        обновление выглядит как «всё хорошо» (И-4)."""
        сказать(f"Обновление не поставлено: {причина}")
        return {"поставлено": False, "беда": причина, **ещё}

    ответ = спросить_обновления()
    if ответ.get("беда"):
        return отказ(ответ["беда"])
    if not ответ["есть новое"]:
        return {"поставлено": False, "беда": "нового нет"}   # это не беда, молчим
    if _занят_выкат():
        return отказ("идёт выкат — обновление подождёт")
    замок = замок_раскладки()
    if замок:
        return отказ(замок)
    беда_ключа = _группа_без_ключа_владельца()
    if беда_ключа:
        return отказ(беда_ключа)

    own = _count_own_commits(каталог, ответ["коммит"])
    if own is None:
        return отказ("не удалось сосчитать свои коммиты пакета — пакет не тронут")
    if own and not reset_own:
        phrase = _reset_phrase()
        hint = (f" Чтобы сберечь их в отдельной ветке и поставить обновление, "
                f"напиши: «{phrase}»") if phrase else ""
        return отказ(f"пакет разошёлся с публичной веткой: в нём {own} "
                     f"{_commits_word(own)}, которых нет в публичной."
                     f"{_own_commits_words(каталог, ответ['коммит'])}{hint}")

    # Судим РАЗНИЦУ красных: среда живой установки (срок входа, nginx,
    # журналы) даёт красные всегда, «красных 0» не бывает. Основа — последний
    # полный прогон ворот этой установки; только когда его нет, ворота идут
    # здесь, РАНЬШЕ копии: правка пакета, сделанная за их минуты, обязана в неё попасть.
    красные_до = красные_прошлых_ворот()
    if красные_до is not None:
        print(f"[обновление] основа — ворота {красные_до.когда:%Y-%m-%d %H:%M}: красных "
              f"{sum(красные_до.values())}; полного прогона до обновления нет")
    else:
        print("[обновление] свежего полного прогона ворот нет — ворота до обновления")
        красные_до = проверить()
    if красные_до is None:
        return отказ(f"ворота до обновления не дали итога ({слова_о_пределе_ворот()}) — пакет не тронут")
    # Выкат мог начаться за время прогона, а первая проверка его не видела.
    if _занят_выкат():
        return отказ("идёт выкат — обновление подождёт")

    копия = _снять_копию(каталог)
    if копия is None:
        return отказ("копия не снята — установка не начата")

    forward_archive, rollback_archive = _layout_archives()
    прежний = _гит("rev-parse", "HEAD", где=каталог).stdout.strip()
    # Что здесь правили — знаем ДО слияния: после него отличить правку
    # владельца от пришедшей строки уже нечем.
    исходы = разбор(прежний, ответ["коммит"])
    сберечь = исходы["не трогать"] + исходы["расхождения"]
    свой_код = [п for п in исходы["расхождения"] if п.startswith(ПУТИ_КОДА_ХАРНЕСА)]
    if свой_код:
        # Файл пары (ворота и реестр механизмов едут вместе) после слияния вернулся бы
        # прежним, а сосед по паре — новым: «кто зовёт» краснеет до раскладки.
        return отказ(
            f"в пакете правлены на этой машине и изменены в обновлении файлы харнеса: "
            f"{', '.join(свой_код)}. Обновление их не затирает, а поставить их половину "
            f"нельзя — пара файлов разъехалась бы. Свою правку сохраните (скопируйте "
            f"файл в сторону или закоммитьте её в отдельную ветку пакета), верните файлы "
            f"в прежний вид и повторите обновление; правку потом перенесите на новую "
            f"версию. Пакет не тронут")

    branch_text, branch_info = "", {}
    if own:
        safety_branch, own, reset_failure = _save_own_and_reset(
            каталог, прежний, ответ["коммит"], host)
        if reset_failure:
            _вернуть_из_копии(копия, каталог, сберечь)
            return отказ(f"{reset_failure}; пакет остался на своём коммите",
                         **({"ветка-страховка": safety_branch} if safety_branch else {}))
        branch_text = _branch_words(own, safety_branch)
        branch_info = {"ветка-страховка": safety_branch, "своих коммитов": own}
    # Слияние не смеет спотыкаться о правки владельца: дерево сбрасывается до
    # HEAD (копия уже снята), а сбережённые файлы возвращаются из копии после.
    # Живая проверка 11.09.2026: без этого merge --ff-only отказывался словами
    # «your local changes would be overwritten», и обновление не шло вовсе.
    _гит("checkout", "--", ".", где=каталог)
    вперёд = _гит("merge", "--ff-only", ответ["коммит"], где=каталог)
    if вперёд.returncode != 0:
        причина = (вперёд.stderr or вперёд.stdout).strip().splitlines()
        _вернуть_из_копии(копия, каталог, сберечь)
        return отказ(f"пакет разошёлся с публичной веткой: "
                     f"{причина[0] if причина else '?'}.{_own_commits_words(каталог, ответ['коммит'])}")
    _вернуть_из_копии(копия, каталог, сберечь)

    раскладка_ок, упавшие, причина, новые, прочие = _разложить_и_проверить(
        разложить, перезапустить, проверить, красные_до, forward_archive, despite_reds)
    # По слову владельца главные новые красные лежат среди «прочих»: судьба у них одна — карантин.
    главные = главные_проверки()
    по_слову = ({имя: строки for имя, строки in прочие.items() if главные is None or имя in главные}
                if despite_reds else {})
    красные_находки = {**((новые if причина else None) or {}), **прочие}
    находка = (_послать_находку(
        _текст_находки(прежний, ответ["коммит"], "откат" if причина else "поставлено", красные_находки),
        ответ["коммит"], forward_archive) if красные_находки else "")
    о_прочих = f" Прочие новые красные: {слова_о_причинах(прочие)}." if прочие else ""
    о_находке = f" {находка}." if находка else ""
    карточки = {}
    if причина is None:
        orphans_text, orphans = _orphan_report((forward_archive, rollback_archive))
        строка = f"красных {sum(новые.values())}, все были до обновления"
        # Беда записи версии не смеет съесть весть об уже поставленном обновлении.
        try:
            записать_версию(ответ["коммит"])
            версия_беда = ""
        except OSError as беда:
            версия_беда = f" Версию записать не удалось ({беда}): панель покажет прежнюю."
        хвост = ("" if not исходы["расхождения"] else
                 f" Не тронуто (правлено здесь и в обновлении): "
                 f"{', '.join(исходы['расхождения'][:5])}")
        хвост += _слова_об_упавших(упавшие) + branch_text + orphans_text
        хвост += _removed_words(forward_archive) + версия_беда
        if по_слову:
            о_прочих = (f" Поставлено по слову владельца, несмотря на новые красные: {слова_о_причинах(прочие)}. "
                        f"Вернуть прежнюю версию: «{СЛОВА_ОТКАТА}».")
        _записать_постановку(forward_archive, прежний, ответ["коммит"], прочие, bool(по_слову))
        if прочие:
            карточки, беды = _в_карантин_копии(прочие, ответ["коммит"])
            о_прочих += (f" В карантине копии на {СРОК_КАРАНТИНА_ДНЕЙ} дней: "
                         + "; ".join(f"{имя} — {карт}" for имя, карт in карточки.items()) + "."
                         if карточки else "")
            о_прочих += f" Карантин не заведён: {'; '.join(беды)}." if беды else ""
        хвост += о_прочих + о_находке
        сказать(_with_release_note(
            f"Харнес обновлён до {ответ['коммит'][:7]}. Проверки: {строка}.{хвост}", каталог))
        # Отдельным сообщением: потолок заметок выпуска не смеет срезать команду.
        пробелы = сверить_корень()
        довезти = root_part_command(каталог) if пробелы else None
        if довезти:
            сказать(f"Часть установки, которую ставит только root, не доехала: {'; '.join(пробелы)}. "
                    f"Обновление её не ставит — запустите одну команду: {довезти}")
        _ask_about_seed(_seed_paths_since(начало), спросить)
        return {"поставлено": True, "коммит": ответ["коммит"], "проверки": строка, "довезти": довезти,
                "версия записана": not версия_беда,
                "копия": str(копия), "расхождения": исходы["расхождения"],
                "упавшие сборщики": упавшие, "архив раскладки": str(forward_archive),
                "оборванные": orphans, "прочие новые красные": {и: с for и, с in прочие.items() if и not in по_слову},
                "несмотря на красные": bool(по_слову), "причины новых красных": по_слову,
                "карантин копии": карточки, "находка": находка, **branch_info}

    # Правка пакета за прогон «после» иначе стирается reset --hard без следа (И-1).
    копия_до_отката = _снять_копию(каталог)
    rolled_back = _гит("reset", "--hard", прежний, где=каталог)
    rollback_failure = ""
    if rolled_back.returncode != 0:
        saved = (f" Свои коммиты целы в ветке {branch_info['ветка-страховка']}."
                 if branch_info else "")
        rollback_failure = (f" ВНИМАНИЕ: откат не удался — пакет стоит на НОВОЙ версии: "
                            f"{(rolled_back.stderr or rolled_back.stdout).strip()}.{saved}")
    elif branch_info:
        # Пакет снова на своих коммитах: ветка-страховка им не нужна.
        deleted = _гит("branch", "-d", branch_info["ветка-страховка"], где=каталог)
        if deleted.returncode == 0:
            branch_text, branch_info = "", {}
    # Раскладка читает пакет: правки владельца должны лежать в нём до неё.
    _вернуть_из_копии(копия, каталог, сберечь)
    if isinstance(раскладка_ок, LayoutNotStarted):
        # Проект не тронут: раскладывать прежнюю версию незачем, а перезапуск
        # диспетчера рвёт канал с владельцем (C4).
        return _отказ_раскладки_не_начата(
            раскладка_ок.reason, прежний, rollback_failure, branch_text, branch_info, сказать,
            copy=копия, copy_before_rollback=копия_до_отката, archive=forward_archive)
    откат_разложен, _ = разложить(archive=rollback_archive, rollback_of=forward_archive)
    перезапустить()
    clear_rotation_request()
    где_копия = (f"Копия до отката: {копия_до_отката}" if копия_до_отката
                 else "Второй копии нет — снять не удалось")
    rollback_words, rollback_outcome = _rollback_report(forward_archive, rollback_archive, откат_разложен)
    orphans_text, orphans = _orphan_report((forward_archive, rollback_archive))
    слова_о_crontab = (_слова_о_снятом_crontab(rollback_archive) + _слова_о_снятом_конфиге(rollback_archive)
                       + _слова_о_снятых_юнитах(rollback_archive))
    итог_отката = (f"сделан откат на {прежний[:7]}" if not rollback_failure
                   else "откат не сделан")
    о_причинах = f" Причины: {слова_о_причинах(новые)}." if новые else ""
    о_расхождениях = ("" if not исходы["расхождения"] else
                      f" Не тронуто (правлено здесь и в обновлении): {', '.join(исходы['расхождения'][:5])}.")
    сказать(f"Обновление не прошло проверку ({причина}) — {итог_отката}.{о_причинах}{о_прочих}{о_находке}{слова_о_crontab}{о_расхождениях} "
            f"Копия: {копия}. {где_копия}.{rollback_words}{rollback_failure}{branch_text}{orphans_text}")
    return {"поставлено": False, "беда": f"самопроверка не прошла: {причина}", **branch_info,
            "откат": прежний, "откат удался": not rollback_failure, "копия": str(копия),
            "копия до отката": str(копия_до_отката) if копия_до_отката else None,
            "новые красные": list(новые or []), "причины новых красных": новые or {},
            "прочие новые красные": прочие, "находка": находка,
            "откат разложен": bool(откат_разложен),
            "архив раскладки": str(forward_archive), "архив отката": str(rollback_archive),
            "откат по журналу": rollback_outcome, "оборванные": orphans}


def _отказ_раскладки_не_начата(reason, прежний, rollback_failure, branch_text, branch_info, сказать,
                               *, copy, copy_before_rollback, archive):
    """Итог отката, когда раскладчик отказал до первой записи."""
    вернули = "" if rollback_failure else f", пакет возвращён на {прежний[:7]}"
    сказать(f"Обновление не встало: {reason}. Проект не тронут{вернули}."
            f"{rollback_failure}{branch_text}")
    return {"поставлено": False, "беда": f"раскладка не начата: {reason}", **branch_info,
            "откат": прежний, "откат удался": not rollback_failure,
            "раскладка не начата": reason, "откат разложен": None,
            "копия": str(copy), "копия до отката": str(copy_before_rollback) if copy_before_rollback else None,
            "архив раскладки": str(archive)}


