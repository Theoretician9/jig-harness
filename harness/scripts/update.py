        if archive_line:
            print(archive_line)
        if итог.get("поставлено"):
            print(f"[обновление] поставлено: {итог['коммит'][:7]}; "
                  f"проверки: {итог['проверки']}")
            if итог.get("довезти"):
                print(f"[обновление] root-часть установки не доехала — запустите: {итог['довезти']}")
