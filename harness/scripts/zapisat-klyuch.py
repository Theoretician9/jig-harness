#!/usr/bin/env python3
"""Единственный писатель настроек харнеса: ключ из реестра, значение из перечня.

Откуда взят. Спека панели (11.09.2026) даёт владельцу менять развилки харнеса
из браузера. Adversarial-ревью назвало два условия, без которых это опасно:

  • **писатель обязан быть один** (находка I8): сегодня конфиг правят и скрипты
    установки (`sed -i`), и агент руками. Два писателя одного файла рано или
    поздно затирают друг друга, и потерянная правка выглядит как «настройка не
    сработала»;
  • **панель не смеет быть root** (находка C5): писать в `/etc/harness` может
    только root, а служба панели идёт под пользователем без прав. Единственное
    её право — одна строка sudoers на ЭТОТ скрипт, поэтому его вход обязан быть
    узким: имя ключа из реестра и значение из перечня, и ничего больше. Нет
    путей файлов, нет команд, нет подстановки в оболочку — инъектировать нечего.

Что делает: проверяет ключ по реестру `harness/config/переключатели.yaml`,
проверяет значение по виду (перечень или границы), снимает копию прежнего
файла (И-1), пишет атомарно, дописывает строку в журнал панели.

Прогон:
    zapisat-klyuch.py <ключ> <значение>
Код возврата: 0 — записано; 2 — ключа нет в реестре или он запрещён;
3 — значение не по реестру; 4 — копия не удалась; 5 — конфиг не прочитан.
"""
import datetime
import fnmatch
import json
import os
import re
import subprocess
import sys
from pathlib import Path

import yaml

КОРЕНЬ = Path(__file__).resolve().parent.parent
РЕЕСТР = Path(os.environ.get("HARNESS_PERECLUCHATELI")
              or КОРЕНЬ / "harness" / "config" / "переключатели.yaml")
КОНФИГИ = {
    "install.conf": os.environ.get("HARNESS_INSTALL_CONF", "/etc/harness/install.conf"),
    "harness.conf": os.environ.get("HARNESS_CONF", "/etc/harness/harness.conf"),
}
LOG_DIR = Path(os.environ.get("LOG_DIR", "/var/log/harness"))
# Значение конфига — простое слово, число или доля процента. Всё остальное
# (кавычки, точка с запятой, пробел, кириллица) отвергается: строка уезжает в
# shell-конфиг, который потом читают исполняемые скрипты.
РАЗРЕШЁННЫЕ = re.compile(r"^[A-Za-z0-9_.%-]{1,64}$")


def отказ(код: int, причина: str) -> int:
    print(f"[запись-ключа] отказ: {причина}", file=sys.stderr)
    return код


def строка_реестра(реестр: dict, ключ: str):
    """(строка переключателя, причина запрета). Одно из двух — None."""
    for запрет in reestr_list(реестр, "чёрный_список"):
        if fnmatch.fnmatch(ключ, запрет.get("ключ", "")):
            return None, (запрет.get("причина") or "ключ в чёрном списке").strip()
    for строка in reestr_list(реестр, "переключатели"):
        if строка.get("ключ") == ключ:
            return строка, None
    return None, None


def reestr_list(реестр: dict, имя: str) -> list:
    значение = реестр.get(имя)
    return значение if isinstance(значение, list) else []


def значение_годится(строка: dict, значение: str) -> str | None:
    """Причина отказа или None."""
    if not РАЗРЕШЁННЫЕ.match(значение):
        return (f"значение «{значение}» содержит недопустимые символы — "
                f"разрешены буквы, цифры и «_ . % -»")
    if строка["вид"] == "выбор":
        можно = [str(з.get("значение")) for з in (строка.get("значения") or [])]
        if значение not in можно:
            return f"значение «{значение}» не из перечня {можно}"
    elif строка["вид"] == "число":
        try:
            число = float(значение)
        except ValueError:
            return f"«{значение}» не число, а реестр обещает число"
        if not (float(строка["от"]) <= число <= float(строка["до"])):
            return (f"число {значение} вне границ {строка['от']}..{строка['до']}")
    else:
        return f"неизвестный вид «{строка['вид']}» в реестре"
    return None


def прежнее(текст: str, ключ: str) -> str | None:
    найдено = re.search(rf'^\s*{re.escape(ключ)}=["\']?([^"\'\n#]*)',
                        текст, re.MULTILINE)
    return найдено.group(1).strip() if найдено else None


def заменить(текст: str, ключ: str, значение: str) -> str:
    """Заменить строку ключа или дописать её в конец. Комментарии не трогаем."""
    образец = re.compile(rf'^(\s*){re.escape(ключ)}=.*$', re.MULTILINE)
    if образец.search(текст):
        return образец.sub(rf'\g<1>{ключ}={значение}', текст, count=1)
    хвост = "" if текст.endswith("\n") else "\n"
    return f"{текст}{хвост}{ключ}={значение}\n"


def снять_копию(файл: Path) -> Path:
    """Копия прежнего файла ДО записи (И-1). Без неё запись не начинается."""
    каталог = LOG_DIR / "панель-копии"
    каталог.mkdir(parents=True, exist_ok=True)
    метка = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
    копия = каталог / f"{файл.name}.{метка}"
    копия.write_bytes(файл.read_bytes())
    return копия


def записать_журнал(ключ: str, было, стало: str, файл: str) -> None:
    """Кто, когда, что и из чего во что. Единственный ответ на вопрос
    «почему харнес вдруг ведёт себя иначе»."""
    запись = {"ts": datetime.datetime.now().isoformat(timespec="seconds"),
              "ключ": ключ, "было": было, "стало": стало, "файл": файл,
              "кто": os.environ.get("SUDO_USER") or os.environ.get("USER") or "?"}
    try:
        LOG_DIR.mkdir(parents=True, exist_ok=True)
        with open(LOG_DIR / "панель.jsonl", "a", encoding="utf-8") as fh:
            fh.write(json.dumps(запись, ensure_ascii=False) + "\n")
    except OSError as беда:
        print(f"[запись-ключа] журнал не записан: {беда}", file=sys.stderr)


def _вернуть_хозяина(новый_файл: Path, прежний: os.stat_result) -> None:
    """Оставить файлу прежних владельца и группу. Не наш файл — молчим."""
    try:
        os.chown(новый_файл, прежний.st_uid, прежний.st_gid)
    except (PermissionError, OSError):
        pass


def main(argv: list[str]) -> int:
    argv = [а for а in argv if а != "--под-sudo"]
    if len(argv) != 2:
        return отказ(2, "нужно ровно два довода: <ключ> <значение>")
    ключ, значение = argv
    try:
        реестр = yaml.safe_load(РЕЕСТР.read_text(encoding="utf-8"))
    except (OSError, yaml.YAMLError) as беда:
        return отказ(2, f"реестр переключателей не прочитан: {беда}")

    строка, запрет = строка_реестра(реестр, ключ)
    if запрет:
        return отказ(2, f"ключ «{ключ}» менять нельзя — {запрет}")
    if строка is None:
        return отказ(2, f"ключа «{ключ}» нет в реестре переключателей")

    беда = значение_годится(строка, значение)
    if беда:
        return отказ(3, беда)

    путь = КОНФИГИ.get(строка["файл"])
    if путь is None:
        return отказ(2, f"неизвестный файл конфига «{строка['файл']}»")
    файл = Path(путь)
    # Конфиги харнеса принадлежат root, а служба панели идёт под пользователем
    # без прав (находка C5). Не можем писать сами — переисполняемся через sudo
    # по единственной разрешённой строке sudoers. Флаг PANEL_NO_SUDO нужен
    # проверкам: там файл свой, и лишний sudo сбросил бы подменённые пути.
    if (not os.access(файл, os.W_OK) and not os.environ.get("PANEL_NO_SUDO")
            and "--под-sudo" not in sys.argv):
        # Флаг «--под-sudo» — защита от бесконечного круга: sudo сбрасывает
        # окружение, поэтому признак «уже поднимались» обязан ехать доводом.
        # Улика 11.09.2026: служба панели под ProtectSystem=strict не могла
        # писать в /etc даже как root, и попытки шли лавиной, пока запрос не
        # отвалился по таймауту.
        готово = subprocess.run(
            ["sudo", "-n", "/usr/bin/python3", str(Path(__file__).resolve()),
             ключ, значение, "--под-sudo"],
            capture_output=True, text=True, timeout=60)
        sys.stdout.write(готово.stdout)
        sys.stderr.write(готово.stderr)
        return готово.returncode
    if not os.access(файл, os.W_OK):
        return отказ(5, f"нет права записи в {файл} даже после попытки поднять "
                        f"права — проверь ProtectSystem у службы и sudoers")
    try:
        текст = файл.read_text(encoding="utf-8")
    except OSError as беда:
        return отказ(5, f"конфиг не прочитан: {беда}")

    try:
        копия = снять_копию(файл)
    except OSError as беда:
        return отказ(4, f"копия прежнего конфига не снята: {беда}")

    было = прежнее(текст, ключ)
    новый = заменить(текст, ключ, значение)
    прежний = os.stat(файл)
    врем = файл.with_suffix(файл.suffix + ".tmp")
    врем.write_text(новый, encoding="utf-8")
    os.chmod(врем, прежний.st_mode & 0o7777)
    # Хозяин прежний: запись идёт через sudo, и иначе конфиг молча переходит к
    # root — следующая правка тем же путём ещё пройдёт, а раскладка пакета и
    # обычные инструменты уже нет.
    _вернуть_хозяина(врем, прежний)
    os.replace(врем, файл)

    записать_журнал(ключ, было, значение, строка["файл"])
    print(f"[запись-ключа] {ключ}: {было} → {значение} "
          f"({строка['файл']}, применяется {строка['применяется']}); "
          f"копия: {копия}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
