#!/usr/bin/env python3
"""Мера Ф3: какие скилы срабатывали УСПЕШНО, а какие — ни разу.

СЛУЧАЙ (ревизия харнеса, §5, замер 28.09.2026). Мера «сколько раз запускался» не
годится: прогон, кончившийся ошибкой, ставит метку и выглядит работой
([[a-sign-true-while-work-stands-still]]). Считаем УСПЕШНЫЕ машинные записи
журнала `$LOG_DIR/skills.jsonl` — их пишет хук `scripts/hooks/skill_log.sh`
(`"источник":"хук"`, `"успех":true`); записи старой схемы (до 11.09.2026) и
любые записи рукой в счёт не идут.

Замер, из которого мера и выросла: из 19 скилов `harness/skills/` три не были
позваны НИ РАЗУ за всё время — `работа-субагентами`, `агенты-параллельно`,
`добыча-улик`. Первые два закрыты носителем: хук `agent_skill_guard.py` отменяет
запуск помощника, если скил не позван в этой смене.

Исход для скила особый (спека §5): гейт не может заставить модель позвать скил,
поэтому либо скил зовёт КОД (хук, демон, гейт по данным), либо он сливается с
соседним, либо удаляется. «Назвать условие» исходом не считается.

    python3 scripts/check-skill-usage.py            # список и итог
    python3 scripts/check-skill-usage.py --selftest
Код возврата: 0 — у каждого скила есть носитель или успешные вызовы;
1 — есть скил без вызовов и без носителя.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "scripts" / "lib"))
import config as конф                                    # noqa: E402

СКИЛЫ = КОРЕНЬ / "harness" / "skills"
# Скилы, у которых носитель — КОД: их зовёт не память смены, а механизм. Данные,
# потому что список растёт по мере появления носителей (Ф3 ревизии).
С_НОСИТЕЛЕМ = {
    "работа-субагентами": "scripts/hooks/agent_skill_guard.py (PreToolUse на Agent)",
    "агенты-параллельно": "scripts/hooks/agent_skill_guard.py (два помощника и больше)",
}
# Скилы, которые ждут СОБЫТИЯ, а не смены: мобильная работа и установка
# расширений наступают не каждую смену, и ноль вызовов у них не дефект.
# Каждому — причина, по которой ноль успешных вызовов не дефект.
ПО_СОБЫТИЮ = {
    "android-env": "эмулятор поднимают, когда он не поднялся сам",
    "mobile-release": "релиз мобильного приложения владелец просит отдельно",
    "mobile-testing": "петля проверки нужна после правки экрана",
    "установка-расширений": "условие расширения наступает по данным, не каждую смену",
    "выкат-и-смоук": "продукт погашен владельцем с 21.09.2026 — выкатов не было",
    "падение-тестов": "разбор нужен, когда тест упал; 15 записей старой схемы до 11.09",
    "разбор-аварии": "разбор нужен, когда прод сломался или владелец увидел дефект",
}


def потолок_молчащих() -> int:
    """Сколько скилов без носителя и без события пока законно молчат.

    Данные (SKILL_SILENT_MAX в harness.conf), а не число в коде: потолок — мера
    обкатки, он уменьшается по мере выбора исходов и обязан быть виден владельцу
    в настройках, а не спрятан в проверке.
    """
    try:
        значение = конф.конфиг(конф.путь_harness_conf()).get("SKILL_SILENT_MAX")
        return max(0, int(str(значение).strip()))
    except (AttributeError, TypeError, ValueError):
        # Ключа нет — требуем ноль: молчаливое умолчание «можно сколько угодно»
        # превратило бы гейт в украшение.
        return 0


def журнал(путь: Path | None = None) -> list[dict]:
    """Машинные записи журнала скилов. Нечитаемый журнал — пустой список."""
    путь = путь or Path(конф.log_dir()) / "skills.jsonl"
    итог = []
    try:
        строки = путь.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return итог
    for строка in строки:
        строка = строка.strip()
        if not строка:
            continue
        try:
            итог.append(json.loads(строка))
        except ValueError:
            continue
    return итог


def успешные_вызовы(записи: list[dict]) -> dict[str, int]:
    """скил → число УСПЕШНЫХ машинных вызовов."""
    счёт: dict[str, int] = {}
    for запись in записи:
        if запись.get("источник") != "хук":
            continue        # старая схема и записи рукой не считаются
        if запись.get("успех") not in (True, "да", 1):
            continue        # запуск, кончившийся отказом, работой не считается
        имя = str(запись.get("skill") or "")
        if имя:
            счёт[имя] = счёт.get(имя, 0) + 1
    return счёт


def все_вызовы(записи: list[dict]) -> dict[str, int]:
    """скил → число любых записей: показывает, что скил жил хотя бы когда-то."""
    счёт: dict[str, int] = {}
    for запись in записи:
        имя = str(запись.get("skill") or "")
        if имя:
            счёт[имя] = счёт.get(имя, 0) + 1
    return счёт


def скилы(каталог: Path | None = None) -> list[str]:
    основа = каталог or СКИЛЫ
    try:
        return sorted(п.name for п in основа.iterdir() if п.is_dir())
    except OSError:
        return []


def осмотр(каталог: Path | None = None, путь_журнала: Path | None = None
           ) -> dict[str, list]:
    записи = журнал(путь_журнала)
    успех = успешные_вызовы(записи)
    любые = все_вызовы(записи)
    молчат, по_событию, носители = [], [], []
    for скил in скилы(каталог):
        if успех.get(скил):
            continue
        if скил in С_НОСИТЕЛЕМ:
            носители.append((скил, С_НОСИТЕЛЕМ[скил], любые.get(скил, 0)))
        elif скил in ПО_СОБЫТИЮ:
            по_событию.append((скил, любые.get(скил, 0), ПО_СОБЫТИЮ[скил]))
        else:
            молчат.append((скил, любые.get(скил, 0)))
    return {"молчат": молчат, "по_событию": по_событию, "носители": носители,
            "успех": успех}


def проверить() -> int:
    итог = осмотр()
    всего = len(скилы())
    живых = len(итог["успех"])
    for скил, носитель, было in итог["носители"]:
        print(f"[скилы] носитель у «{скил}»: {носитель} (успешных вызовов пока "
              f"нет, записей всего {было})")
    for скил, было, причина in итог["по_событию"]:
        print(f"[скилы] ждёт события: «{скил}» — {причина} (записей всего {было})")
    потолок = потолок_молчащих()
    if len(итог["молчат"]) > потолок:
        print(f"[скилы] БЕЗ УСПЕШНЫХ ВЫЗОВОВ И БЕЗ НОСИТЕЛЯ: "
              f"{len(итог['молчат'])} (потолок {потолок})")
        for скил, было in итог["молчат"]:
            print(f"  ✗ {скил} — успешных машинных вызовов 0, записей всего {было}")
        print("  Исходы (спека ревизии §5): скил зовёт КОД (хук, демон, гейт по "
              "данным) · сливается с соседним · удаляется. «Назвать условие» "
              "исходом не считается — это мёртвая запись.")
        return 1
    if итог["молчат"]:
        for скил, было in итог["молчат"]:
            print(f"[скилы] молчит в пределах потолка: {скил} (записей {было}) — "
                  f"исход ещё не выбран, карточка в карте")
    print(f"[скилы] чисто: из {всего} скилов успешно вызывались {живых}, "
          f"у остальных есть носитель, событие или место под потолком "
          f"(молчащих {len(итог['молчат'])} из {потолок})")
    return 0


def самотест() -> int:
    import tempfile
    путей = неудач = 0

    def проба(имя: str, ждём, факт):
        nonlocal путей, неудач
        путей += 1
        if факт == ждём:
            print(f"  ок    {имя}")
        else:
            неудач += 1
            print(f"  ПЛОХО {имя}: ждали «{ждём}», вышло «{факт}»")

    with tempfile.TemporaryDirectory() as врем:
        двор = Path(врем)
        (двор / "скилы" / "молчит").mkdir(parents=True)
        (двор / "скилы" / "живой").mkdir()
        (двор / "скилы" / "работа-субагентами").mkdir()
        (двор / "скилы" / "mobile-testing").mkdir()
        журнал_путь = двор / "skills.jsonl"

        def запись(скил, источник="хук", успех=True):
            return json.dumps({"skill": скил, "источник": источник,
                               "успех": успех}, ensure_ascii=False)

        журнал_путь.write_text("\n".join([
            запись("живой"),
            # БОЛЬНОЙ СЛУЧАЙ: запуск с отказом работой не считается.
            запись("молчит", успех=False),
            # Старая схема (без «источник») тоже не считается.
            json.dumps({"skill": "молчит"}, ensure_ascii=False),
        ]) + "\n", encoding="utf-8")

        итог = осмотр(двор / "скилы", журнал_путь)
        проба("БОЛЬНОЙ СЛУЧАЙ: неудачный запуск успехом не считается",
              ["молчит"], [с for с, _ in итог["молчат"]])
        проба("успешный вызов снимает претензию", True,
              "живой" not in [с for с, _ in итог["молчат"]])
        проба("скил с носителем назван отдельно", ["работа-субагентами"],
              [с for с, _, _ in итог["носители"]])
        проба("скил, ждущий события, назван отдельно с причиной",
              [("mobile-testing", ПО_СОБЫТИЮ["mobile-testing"])],
              [(с, п) for с, _, п in итог["по_событию"]])
        проба("число записей у молчащего скила названо", 2,
              dict(итог["молчат"])["молчит"])
        # Успех появился — молчащих нет. Журнал ДОПИСЫВАЕТСЯ: перезапись отняла бы
        # успех у «живого», и проба судила бы не то, что обещает.
        с_успехом = журнал_путь.read_text(encoding="utf-8") + запись("молчит") + "\n"
        журнал_путь.write_text(с_успехом, encoding="utf-8")
        итог = осмотр(двор / "скилы", журнал_путь)
        проба("после успешного вызова скил перестаёт быть молчащим", [],
              [с for с, _ in итог["молчат"]])
        # Потолок — ДАННЫЕ: мутация «взять его из кода» обязана краснеть, иначе
        # рост числа молчащих скилов перестаёт замечаться (мутационный прогон 28.09).
        конф_путь = двор / "harness.conf"
        конф_путь.write_text("SKILL_SILENT_MAX=3\n", encoding="utf-8")
        прежний = os.environ.get("HARNESS_CONF")
        os.environ["HARNESS_CONF"] = str(конф_путь)
        проба("потолок берётся из данных", 3, потолок_молчащих())
        конф_путь.write_text("ДРУГОЙ_КЛЮЧ=1\n", encoding="utf-8")
        проба("БОЛЬНОЙ СЛУЧАЙ: без ключа потолок НОЛЬ, а не «сколько угодно»",
              0, потолок_молчащих())
        if прежний is None:
            del os.environ["HARNESS_CONF"]
        else:
            os.environ["HARNESS_CONF"] = прежний

        # Нечитаемый журнал: молчат все, кроме носителей и ждущих события.
        итог = осмотр(двор / "скилы", двор / "нет-такого.jsonl")
        проба("нечитаемый журнал не выглядит успехом", ["живой", "молчит"],
              sorted(с for с, _ in итог["молчат"]))

    print(f"SELFTEST: {'зелёный' if not неудач else 'КРАСНЫЙ'} ({путей} путей; "
          "больной первый — «неудачный запуск успехом не считается»)")
    return 1 if неудач else 0


if __name__ == "__main__":
    sys.exit(самотест() if "--selftest" in sys.argv else проверить())
