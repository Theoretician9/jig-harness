#!/usr/bin/env bash
# Проба: смена сессии невозможна, пока передача дел не написана.
#
# Откуда взята. Владелец 18.10.2026 прислал беду с ДРУГОГО своего сервера:
# «Лимит подписки. И смена сессии. Но без полноценной передачи, потому, что
# возник лимит и модель не может сделать передачу. Соответственно ротация
# сессии надо чтобы была невозможна если передача не состоялась».
#
# Что делало это возможным. rotate_clear подаёт в панель поручение регламента
# («перепиши STATE.md, допиши передачу, отчитайся») и ждёт двух признаков:
# ход завершён И панель молчит. Под лимитом ход не НАЧИНАЕТСЯ вовсе, и оба
# признака читаются так же, как после честно отработанного регламента.
# Молчание смены под лимитом и молчание смены, доделавшей дела, для сторожа
# выглядели одинаково — после чего он подавал «/clear».
#
# Судятся две двери, обе из ЖИВЫХ файлов (пути берутся из окружения, иначе
# испорченная мутацией копия до пробы не доходит — [[probe-loads-the-live-mechanism]]):
#   1. ротация_разрешена — чистая функция сторожа, решающая «менять ли сессию»;
#   2. handover-check.sh --после <миг> — судья «передача обновлена ПОСЛЕ мига».
#
# Имена переменных ЛАТИНИЦЕЙ: bash не берёт кириллические идентификаторы
# ([[cyrillic-in-bash-names]]).
set -uo pipefail
export LC_ALL=C.UTF-8

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$HERE/lib/selftest_cases.sh"

WARDEN="${HARNESS_SESSION_WARDEN:-$HERE/../harness/demons/session-warden.sh}"
HANDOVER_CHECK="${HARNESS_HANDOVER_CHECK:-$HERE/handover-check.sh}"
STAND=$(mktemp -d)
trap 'rm -rf "$STAND"' EXIT

# ── дверь 1: чистая функция сторожа ────────────────────────────────────────
FUNC="$STAND/reshenie.sh"
sed -n '/^ротация_разрешена() {$/,/^}$/p' "$WARDEN" > "$FUNC"
case_check "решающая функция вынута из файла сторожа" \
    "да" "$([ -s "$FUNC" ] && echo да || echo нет)"

reshenie() {  # $1=передача свежа $2=лимит держится $3=принуждение $4=причина; печатает текст
    bash -c 'set -uo pipefail; source "$1"; ротация_разрешена "$2" "$3" "$4" "$5"' \
        _ "$FUNC" "$1" "$2" "$3" "${4:-}" 2>&1
}

# Слово И код возврата одной строкой «слово;код»: вызывающий в сторожe смотрит
# на КОД, журнал печатает СЛОВО, и мутация, разведшая их, обязана краснить.
verdikt() {  # те же доводы; печатает «да;0» или «нет;1»
    local out rc=0
    out=$(reshenie "$@") || rc=$?
    printf '%s;%s\n' "${out%%:*}" "$rc"
}

echo "── БОЛЬНОЙ СЛУЧАЙ 18.10.2026: передачи нет, а сессию меняют ──"
case_check "передача НЕ обновлялась после поручения — ротации нет" \
    "нет;1" "$(verdikt 0 0 0)"
OTKAZ_PEREDACHA=$(reshenie 0 0 0)
case_check "отказ называет причину словом «передача»" \
    "да" "$(grep -qi "передач" <<< "$OTKAZ_PEREDACHA" && echo да || echo нет)"
# Лимит объясняет, ПОЧЕМУ передачи нет, а не запрещает смену при её наличии:
# подавленная ротация доводит окно до автосжатия (улика сторожа 11.08.2026).
case_check "передачи нет и держится лимит — ротации нет" \
    "нет;1" "$(verdikt 0 1 0)"
OTKAZ_LIMIT=$(reshenie 0 1 0)
case_check "отказ по лимиту называет причиной лимит, а не передачу" \
    "да" "$(grep -qi "лимит" <<< "$OTKAZ_LIMIT" && echo да || echo нет)"
case_check "передача есть, но держится лимит — меняем: терять уже нечего" \
    "да;0" "$(verdikt 1 1 0)"

echo "── ЗДОРОВАЯ ПОЛОВИНА: работа смены не остановлена ──"
case_check "передача написана, лимита нет — ротация идёт" \
    "да;0" "$(verdikt 1 0 0)"

echo "── ЗАКОННАЯ ДВЕРЬ: принуждение с названной причиной ──"
case_check "принуждение БЕЗ причины — отказ (дверь без причины не дверь)" \
    "нет;1" "$(verdikt 0 0 1 "")"
case_check "принуждение С причиной — ротация идёт" \
    "да;0" "$(verdikt 0 0 1 "смена модели по слову владельца")"
case_check "принуждение не отменяет лимит: писать передачу всё равно нечем" \
    "нет;1" "$(verdikt 0 1 1 "смена модели")"

# ── дверь ВСТАВЛЕНА в разрушительный путь, а не просто написана ────────────
# Находка ревью F1-gen-06: прежняя редакция пробы судила только чистую функцию,
# и удаление ЗОВА двери из rotate_clear/rotate_full оставляло пробу зелёной —
# «функция написана» и «функция позвана» разные факты
# ([[a-port-written-but-never-wired]]).
telo() {  # $1 = имя функции сторожа; печатает её тело
    sed -n "/^$1() {\$/,/^}\$/p" "$WARDEN"
}

dver_vyshe() {  # $1 = тело функции, $2 = образец разрушительной строки
    local dver razrush
    dver=$(grep -n 'дверь_ротации' <<< "$1" | head -1 | cut -d: -f1 || true)
    razrush=$(grep -n -- "$2" <<< "$1" | head -1 | cut -d: -f1 || true)
    if [ -n "$dver" ] && [ -n "$razrush" ] && [ "$dver" -lt "$razrush" ]; then
        echo да
    else
        echo "нет (дверь: ${dver:-нет}, разрушение: ${razrush:-нет})"
    fi
}

TELO_CLEAR=$(telo rotate_clear)
TELO_FULL=$(telo rotate_full)
case_check "тела обоих путей ротации вынуты из файла сторожа" \
    "да;да" "$([ -n "$TELO_CLEAR" ] && echo -n "да" || echo -n "нет");$([ -n "$TELO_FULL" ] && echo да || echo нет)"
case_check "быстрый путь: дверь спрошена ДО «/clear»" \
    "да" "$(dver_vyshe "$TELO_CLEAR" 'pane_command text "/clear"')"
case_check "тяжёлый путь: дверь спрошена ДО подачи выхода в панель" \
    "да" "$(dver_vyshe "$TELO_FULL" '"$send_fn" "$PROMPT"')"

# ── дверь 2: судья свежести передачи ОТНОСИТЕЛЬНО мига поручения ────────────
echo "── СУДЬЯ ПЕРЕДАЧИ: сравнение с мигом поручения, а не с порогом возраста ──"
PROEKT="$STAND/proekt"
mkdir -p "$PROEKT/docs/handover"
git -C "$PROEKT" init -q
git -C "$PROEKT" -c user.email=t@t -c user.name=t commit -q --allow-empty -m "работа смены"

# Печатает «код;свои ли слова». Второе поле обязательно: сломанный судья
# (копия без своих библиотек, нет конфига) тоже отвечает ненулевым кодом, и
# «не смог спросить» читалось бы как «отказал по делу»
# ([[unreadable-source-turns-check-green]]). Своё слово судьи — «handover:».
sudit() {  # $1 = миг поручения; печатает «код;да|нет»
    local rc=0 out
    out=$(PROJECT_DIR="$PROEKT" LOG_DIR="$STAND/log" bash "$HANDOVER_CHECK" --после "$1" 2>&1) || rc=$?
    printf '%s;%s\n' "$rc" "$(grep -q "handover:" <<< "$out" && echo да || echo нет)"
}

PORUCHENIE=$(date +%s)
case_check "передачи нет вовсе — отказ своими словами" "1;да" "$(sudit "$PORUCHENIE")"

# Передача ЕСТЬ и свежая по порогу возраста (минута назад), но написана ДО
# поручения — ровно случай владельца: порог сказал бы «свежо».
touch -d "@$((PORUCHENIE - 60))" "$PROEKT/docs/handover/SESSION-HANDOFF-2026-10-18.md"
case_check "передача написана ДО поручения — отказ (порог возраста сказал бы «свежо»)" \
    "1;да" "$(sudit "$PORUCHENIE")"

touch -d "@$((PORUCHENIE + 5))" "$PROEKT/docs/handover/SESSION-HANDOFF-2026-10-18.md"
case_check "передача дописана ПОСЛЕ поручения — пропускает" "0;да" "$(sudit "$PORUCHENIE")"

printf '\nДВЕРЬ РОТАЦИИ: путей %d, неудач %d\n' "$CASES_PATHS" "$CASES_FAILED"
[ "$CASES_FAILED" -eq 0 ]
