#!/usr/bin/env python3
"""Живая проверка ПРОБЫ (класс D): пробу портят мутацией и ждут красного.

Откуда взято: спека `docs/specs/2026-10-15-живая-проверка-механизмов.md` §3.1,
класс D — «мутация в судимом механизме → проба краснеет; зелёная мутация —
находка о ПРОБЕ». У класса D единственного в семье не было прибора с
`--записать`: записи писались руками из полного журнала мутаций (правило без
носителя).

Почему порчу ставит `mutation-probe.sh`, а не этот прибор. Копия дерева,
подмена механизма и проверка «чистая копия зелёная» там уже есть и доказаны;
второй исполнитель мутаций разошёлся бы с первым молча. Прибор отдаёт ему
выборку из ОДНОЙ пробы и читает итог.

Что считается доказательством:
  * «ок» — все названные мутации покрасили пробу (дыр 0, число красных равно
    числу мутаций). Зелёная мутация — дыра в пробе, а не «почти»; мутация, не
    изменившая файл, и красная чистая копия тоже не «ок».
  * «не-проверяемо» — проба в `без_мутаций`, а причина НАЧИНАЕТСЯ с пункта
    закрытого списка `причины_непроверяемого`: свободный текст отказ.
  * Нет мутаций и нет причины — отказ, как и пустой список мутаций.

Почему журнал мутаций прибор ставит СВОЙ (LOG_DIR во временном каталоге): прибор
мутаций пишет итог выборки в `мутации.log`, который читает ночной демон, и итог
«мутаций 1» стал бы его вердиктом.

Почему след пробы пишет обёртка `scripts/live-check.sh`: доказательство,
написанное проверяемым, доказательством не является. Сухой прогон (без
`--записать`) пишет и след, и журнал во временный каталог и стирает: иначе он
переписывал бы живой след чужой записи «ок».

Запуск:
    python3 scripts/live-check-probe.py <проба> [<проба>…] [--записать]
    python3 scripts/live-check-probe.py --всё [--записать]
Код возврата: 0 — все названные «ок» или «не-проверяемо», 1 — хоть одна нет.

Чем доказан: scripts/test_live_check_probe.py (больным случаем первым — мутация,
которую проба не заметила).
"""
from __future__ import annotations

import datetime
import fcntl
import os
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

import yaml

СКРИПТЫ = pathlib.Path(__file__).resolve().parent
# Байткод в дворе исказил бы сравнение «до/после» сухого прогона.
sys.dont_write_bytecode = True
sys.path.insert(0, str(СКРИПТЫ / "lib"))
import config as _конфиг  # noqa: E402

КОРЕНЬ = pathlib.Path(os.environ.get("HARNESS_LIVE_CHECK_REPO")
                      or _конфиг.корень_дерева(__file__))
КЛАССЫ = pathlib.Path(os.environ.get("HARNESS_LIVE_CHECK_CLASSES")
                      or КОРЕНЬ / "harness" / "config" / "live-check-classes.yaml")
СОСТОЯНИЕ = pathlib.Path(os.environ.get("HARNESS_LIVE_CHECK_STATE")
                         or КОРЕНЬ / "harness" / "config" / "live-check-state.yaml")
МУТАЦИИ = pathlib.Path(os.environ.get("HARNESS_PROBE_MUTATIONS")
                       or КОРЕНЬ / "harness" / "config" / "probe-mutations.yaml")
# Нейтральное умолчание вне репозитория: в след уходит весь вывод пробы.
СЛЕДЫ = pathlib.Path(os.environ.get("HARNESS_LIVE_CHECK_PROBE_TRACE_DIR")
                     or pathlib.Path(_конфиг.live_check_trace_root())
                     / "живая-проверка" / "пробы")

КЛАСС = "D"
ЦИТАТА_ЗНАКОВ = 12
ШАПКА_КОНЕЦ = "--- вывод механизма ---"
# Предел на одну мутацию: прибор мутаций сам держит 180 с на запуск, а запусков
# на мутацию два (чистая копия и испорченная).
ПРЕДЕЛ_НА_МУТАЦИЮ_СЕК = 600
ИТОГ_МУТАЦИЙ = re.compile(r"покраснели как надо (\d+), дыр (\d+)")


def данные(путь: pathlib.Path, ключ: str) -> dict:
    if not путь.exists():
        return {}
    return (yaml.safe_load(путь.read_text(encoding="utf-8")) or {}).get(ключ) or {}


def пробы_без_исхода() -> list[str]:
    сост = данные(СОСТОЯНИЕ, "проверено")
    return [ф for ф, з in данные(КЛАССЫ, "классы").items()
            if (з or {}).get("класс") == КЛАСС
            and not str((сост.get(ф) or {}).get("исход") or "").strip()]


def относительный(путь: pathlib.Path) -> str:
    return str(путь.relative_to(КОРЕНЬ)) if путь.is_relative_to(КОРЕНЬ) else str(путь)


def имя_файла(проба: str, суффикс: str) -> str:
    return проба.replace("/", "-") + суффикс


def причина_освобождения(проба: str) -> str:
    """Причина из `без_мутаций`, если она начинается с пункта закрытого списка."""
    причина = str(данные(МУТАЦИИ, "без_мутаций").get(проба) or "").strip()
    допустимые = данные(КЛАССЫ, "причины_непроверяемого") or []
    return причина if any(причина.startswith(п) for п in допустимые) else ""


def выборка_мутаций(проба: str, запись: dict, куда: pathlib.Path) -> dict:
    """Среда прибора мутаций: одна проба, свой журнал, инвариантов нет.

    Инварианты обнулены: иначе выборка из одной пробы тащила бы за собой все
    мутации инвариантов и итог принадлежал бы не ей.
    """
    выбор = куда / "выборка.yaml"
    выбор.write_text(yaml.safe_dump({"пробы": {проба: запись}}, allow_unicode=True),
                     encoding="utf-8")
    пустые = куда / "инварианты.yaml"
    пустые.write_text("инварианты: []\n", encoding="utf-8")
    журнал = куда / "log"
    журнал.mkdir()
    среда = dict(os.environ)
    # Прибор мутаций узнаёт каталог пакета питоном под -I, а тот игнорирует
    # PYTHONDONTWRITEBYTECODE и пишет байткод во двор: ответ даём заранее.
    среда.setdefault("MECH_STARTER", str(_конфиг.katalog_paketa()))
    среда.update({"PYTHONDONTWRITEBYTECODE": "1",
                  "HARNESS_PROBE_MUTATIONS": str(выбор),
                  "HARNESS_INVARIANTS": str(пустые),
                  "LOG_DIR": str(журнал)})
    # events.py берёт HARNESS_LOG_DIR раньше LOG_DIR стенда: каталог журнала
    # прибора (свой или унаследованный) не должен утекать в проверяемые пробы.
    среда.pop("HARNESS_LOG_DIR", None)
    return среда


def прогнать_мутации(проба: str, запись: dict, среда: dict, число: int) -> tuple[int, str]:
    try:
        готово = subprocess.run(["bash", "scripts/mutation-probe.sh"], cwd=КОРЕНЬ,
                                capture_output=True, text=True, env=среда,
                                timeout=900 + ПРЕДЕЛ_НА_МУТАЦИЮ_СЕК * число)
    except subprocess.TimeoutExpired:
        return -1, "прибор мутаций оборван пределом времени прибора"
    return готово.returncode, готово.stdout + готово.stderr


def слово_об_отказе(проба: str, число: int, код: int, вывод: str) -> str:
    """Отказ своими словами и строки «ПЛОХО» прибора мутаций дословно."""
    плохие = [с.strip() for с in вывод.splitlines() if с.lstrip().startswith("ПЛОХО")]
    итог = ИТОГ_МУТАЦИЙ.search(вывод)
    if итог is None:
        суть = f"прибор мутаций не дал итога (код {код}): {вывод.strip()[-200:]}"
    else:
        красных, дыр = int(итог.group(1)), int(итог.group(2))
        суть = (f"дыра в пробе: покраснели {красных} из {число}, дыр {дыр} — "
                f"проба с дырой ничего не охраняет")
    return " · ".join([f"{проба}: {суть}"] + плохие)


def позвать_обёртку(проба: str, команда: str, куда: pathlib.Path) -> tuple[int, str]:
    """Чистую пробу зовёт ОБЁРТКА: след пишет она, а не прибор."""
    среда = dict(os.environ, HARNESS_LIVE_CHECK_TRACE_DIR=str(куда),
                 PYTHONDONTWRITEBYTECODE="1")
    предел = int(os.environ.get("HARNESS_LIVE_CHECK_TIMEOUT", "300")) + 60
    готово = subprocess.run(["bash", "scripts/live-check.sh", проба, "--",
                             "bash", "-o", "pipefail", "-e", "-c", команда],
                            cwd=КОРЕНЬ, capture_output=True, text=True, env=среда,
                            timeout=предел)
    след = куда / имя_файла(проба, ".log")
    return готово.returncode, след.read_text(errors="replace") if след.is_file() else ""


def цитата(след: str) -> str:
    """Первая строка вывода пробы от ЦИТАТА_ЗНАКОВ, дословно (шапка — мои слова)."""
    части = след.split(ШАПКА_КОНЕЦ, 1)
    for строка in (части[1] if len(части) == 2 else "").splitlines():
        чистая = строка.strip()
        if len(чистая) >= ЦИТАТА_ЗНАКОВ and not чистая.startswith("код возврата:"):
            return чистая
    return ""


def освобождена(проба: str, причина: str) -> tuple[bool, str, dict]:
    поля = {"живьём": "живой проверки мутацией нет: проба названа в без_мутаций "
                      "(harness/config/probe-mutations.yaml)",
            "увидели": причина,
            "когда": datetime.date.today().isoformat(),
            "исход": "не-проверяемо"}
    return True, f"{проба}: не-проверяемо — {причина}", поля


def доказана_мутацией(проба: str, запись: dict, рабочий: pathlib.Path) -> tuple[bool, str, dict]:
    число = len(запись.get("мутация") or [])
    среда = выборка_мутаций(проба, запись, рабочий)
    код, вывод = прогнать_мутации(проба, запись, среда, число)
    итог = ИТОГ_МУТАЦИЙ.search(вывод)
    if код != 0 or итог is None or int(итог.group(2)) != 0 or int(итог.group(1)) != число:
        return False, слово_об_отказе(проба, число, код, вывод), {}
    журнал = рабочий / имя_файла(проба, ".мутации.log")
    журнал.write_text(вывод, encoding="utf-8")
    команда = str(запись.get("доказательство") or "")
    код, след = позвать_обёртку(проба, команда, рабочий)
    видно = цитата(след)
    if код != 0 or not видно:
        return False, (f"{проба}: чистая проба при зове обёрткой: код {код}, "
                       f"цитировать {'нечего' if код == 0 else 'не с чего'}"), {}
    поля = {"живьём": f"пробу портили мутациями и звали обёрткой: {команда}",
            "увидели": видно,
            "мутация": (f"мутаций {число} из probe-mutations.yaml, покраснели "
                        f"{число} из {число}, дыр 0; журнал {журнал.name}"),
            "когда": datetime.date.today().isoformat(),
            "исход": "ок"}
    return True, f"{проба}: ок — покраснели {число} из {число} — {видно[:80]}", \
        dict(поля, _файлы=(журнал, рабочий / имя_файла(проба, ".log")))


def судить(проба: str) -> tuple[bool, str, dict]:
    класс = (данные(КЛАССЫ, "классы").get(проба) or {}).get("класс") or "не назван"
    if класс != КЛАСС:
        return False, (f"{проба}: класс {класс}, а не {КЛАСС} — у каждого класса "
                       f"свой предикат, этим носителем он не доказывается"), {}
    запись = данные(МУТАЦИИ, "пробы").get(проба)
    причина = причина_освобождения(проба)
    if запись is None and причина:
        return освобождена(проба, причина)
    if запись is None:
        return False, (f"{проба}: мутаций нет и допустимой причины нет — "
                       f"ни записи в пробы, ни пункта закрытого списка в без_мутаций"), {}
    if not запись.get("мутация"):
        return False, f"{проба}: список мутаций пуст — «0 из 0» не проверка", {}
    with tempfile.TemporaryDirectory(prefix="live-check-probe-") as врем:
        рабочий = pathlib.Path(врем)
        удача, слово, поля = доказана_мутацией(проба, запись, рабочий)
        if удача and ПИШЕМ:
            поля = унести_следы(поля)
        return удача, слово, поля


ПИШЕМ = False


def унести_следы(поля: dict) -> dict:
    """Журнал мутаций и след обёртки — в каталог следов, пока рабочий жив."""
    журнал, след = поля.pop("_файлы")
    СЛЕДЫ.mkdir(parents=True, exist_ok=True)
    shutil.copy2(журнал, СЛЕДЫ / журнал.name)
    shutil.copy2(след, СЛЕДЫ / след.name)
    поля["мутация"] += f" в {относительный(СЛЕДЫ / журнал.name)}"
    поля["след"] = относительный(СЛЕДЫ / след.name)
    return поля


def записать(проба: str, поля: dict) -> None:
    """Чтение-правка-запись состояния ПОД ЗАМКОМ и атомарно (как у семьи)."""
    with open(СОСТОЯНИЕ.with_name(СОСТОЯНИЕ.name + ".lock"), "w") as замок:
        fcntl.flock(замок, fcntl.LOCK_EX)
        прочитано = yaml.safe_load(СОСТОЯНИЕ.read_text(encoding="utf-8")) or {}
        прочитано.setdefault("проверено", {}).setdefault(проба, {}).update(
            {к: з for к, з in поля.items() if not к.startswith("_")})
        рядом = СОСТОЯНИЕ.with_name(f"{СОСТОЯНИЕ.name}.{os.getpid()}.tmp")
        рядом.write_text(yaml.dump(прочитано, allow_unicode=True, sort_keys=False,
                                   width=100), encoding="utf-8")
        os.replace(рядом, СОСТОЯНИЕ)


def main() -> int:
    global ПИШЕМ
    ПИШЕМ = "--записать" in sys.argv
    названные = [д for д in sys.argv[1:] if not д.startswith("--")]
    кого = пробы_без_исхода() if "--всё" in sys.argv else названные
    if not кого:
        print("[живая проверка проб] нечего судить: назови пробу или дай «--всё»",
              file=sys.stderr)
        return 1
    отказов = 0
    for проба in кого:
        удача, слово, поля = судить(проба)
        print(f"  {'ок   ' if удача else 'ПЛОХО'} {слово}", flush=True)
        if not удача:
            отказов += 1
        elif ПИШЕМ:
            записать(проба, поля)
    print(f"[живая проверка проб] названо {len(кого)}, отказов {отказов}")
    return 1 if отказов else 0


if __name__ == "__main__":
    sys.exit(main())
