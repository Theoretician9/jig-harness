#!/usr/bin/env python3
"""Гейт: панель говорит словами владельца, а не своими.

Откуда взят. Владелец 12.09.2026: «в панеле тоже должен использоваться тон оф
войс для текстов объяснений всех описаний». Его язык замерен и записан в
`память/ТОН.md` — там раздел «Его слова — не наши»: пары «наше слово — а не
такие-то». Документ пишет агент по живой речи (демон `ton-watch.sh`), поэтому
СЛОВАРЬ ГЕЙТА — этот файл, а не список внутри кода: второй список разошёлся бы
с первым молча, как уже было со сроками присмотра и с ручками панели.

Судятся не все пары, а только те, чьё «наше» слово вообще звучит в панели.
Замер 13.09.2026: из 12 пар половина про ПРОДУКТ («дома», «трубы»), и слово
«записи» в панели законно — это записи памяти, а не дома. Пара, чьего слова
в текстах панели нет, к панели и не относится: гейт её пропускает, и никакого
второго списка исключений заводить не нужно.

Прогон:
    python3 scripts/check-ton-paneli.py
    python3 scripts/check-ton-paneli.py --selftest
Код возврата: 0 — чисто, 1 — панель говорит не его словом, 77 — судить нечем
(нет документа тона).
"""
import os
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
ТОН = Path(os.environ.get("HARNESS_TON") or КОРЕНЬ / "память" / "ТОН.md")
# Тексты, которые видит владелец: вид панели целиком и сообщения службы.
ТЕКСТЫ_ПАНЕЛИ = ("harness/panel/vid.py", "harness/panel/server.py")
# Строка, видимая владельцу: в кавычках и длиннее слова. Имена ключей, пути и
# css сюда не попадают — у них нет пробелов и кириллицы.
ВИДИМАЯ = re.compile(r'["\']([^"\'\n]*[а-яё][^"\'\n]*\s[^"\'\n]*)["\']', re.I)
# Начала docstring — собраны из кодов, чтобы сам этот файл не спотыкался
# о тройные кавычки внутри литерала.
ТРОЙНЫЕ = chr(34) * 3
ТРОЙНЫЕ_ОДИНАРНЫЕ = chr(39) * 3


def словарь(текст_тона: str) -> list[tuple[list[str], list[str]]]:
    """[(наши слова, слова-замены)] из раздела «Его слова — не наши»."""
    пары = []
    for наше, хвост in re.findall(r'^- \*\*(.+?)\*\* — (.+)$', текст_тона, re.M):
        наши = [с.strip().lower() for с in наше.replace("**", "").split("/") if с.strip()]
        чужие = [с.lower() for с in re.findall(r'«([^»]+)»', хвост)]
        if наши and чужие:
            пары.append((наши, чужие))
    return пары


def видимые_строки(корень: Path, файлы=ТЕКСТЫ_ПАНЕЛИ):
    for имя in файлы:
        путь = корень / имя
        if not путь.exists():
            continue
        for номер, строка in enumerate(путь.read_text(encoding="utf-8").splitlines(), 1):
            # Комментарий и docstring — речь к разработчику, а не к владельцу:
            # судить их тоном значило бы править пояснения кода ради гейта.
            голая = строка.lstrip()
            if голая.startswith("#") or голая[:3] in (ТРОЙНЫЕ, ТРОЙНЫЕ_ОДИНАРНЫЕ):
                continue
            for найдено in ВИДИМАЯ.findall(строка):
                yield имя, номер, найдено


def находки(корень: Path, пары) -> list[str]:
    тексты = list(видимые_строки(корень))
    весь = " ".join(т for _, _, т in тексты).lower()
    беды = []
    for наши, чужие in пары:
        # Пара относится к панели, только если ЕЁ слово здесь вообще звучит.
        if not any(re.search(rf"\b{re.escape(с)}", весь) for с in наши):
            continue
        for имя, номер, текст in тексты:
            for чужое in чужие:
                if re.search(rf"\b{re.escape(чужое)}\b", текст.lower()):
                    беды.append(f"{имя}:{номер}: «{чужое}» — его слово "
                                f"«{наши[0]}»: {текст.strip()[:60]}")
    return беды


def самотест() -> int:
    неудач = 0

    def проба(имя, условие, подробность=""):
        nonlocal неудач
        неудач += not условие
        print(("  ок    " if условие else "  ПЛОХО ") + имя
              + ("" if условие else f" — {подробность}"))

    пары = словарь("""## Его слова — не наши

- **карта** — не «задачи», не «тикет»
- **дома** / **домов** — не «объекты», не «записи»
""")
    проба("словарь разобран из документа тона", len(пары) == 2, str(пары))

    import tempfile
    двор = Path(tempfile.mkdtemp(prefix="тон-панели-"))
    (двор / "harness" / "panel").mkdir(parents=True)
    (двор / "harness" / "panel" / "vid.py").write_text(
        'x = "Карта работы: задачи и их состояния"\n'
        '# комментарий: задачи тут не судятся\n'
        'y = "Здесь записи памяти, а не объекты"\n', encoding="utf-8")
    (двор / "harness" / "panel" / "server.py").write_text("", encoding="utf-8")
    беды = находки(двор, пары)
    проба("БОЛЬНОЙ СЛУЧАЙ: «задачи» при живом слове «карта» — находка",
          any("«задачи»" in б for б in беды), str(беды))
    # Пара про дома к панели не относится: слова «дома» в ней нет, значит и
    # «записи» здесь законны — иначе пришлось бы заводить список исключений.
    проба("слово чужой пары («записи») находкой не считается",
          not any("«записи»" in б for б in беды), str(беды))
    проба("текст из КОММЕНТАРИЯ не судится",
          not any(":2:" in б for б in беды), str(беды))

    # БОЛЬНОЙ СЛУЧАЙ: docstring — речь к разработчику. Судя его тоном, гейт
    # заставлял бы переписывать пояснения кода ради слов владельца.
    (двор / "harness" / "panel" / "server.py").write_text(
        "    " + ТРОЙНЫЕ + "Включить шаг работы на уровне задачи." + ТРОЙНЫЕ + "\n",
        encoding="utf-8")
    (двор / "harness" / "panel" / "vid.py").write_text(
        'x = "Карта работы"\n', encoding="utf-8")
    проба("docstring не судится", not находки(двор, пары), str(находки(двор, пары)))
    import shutil
    shutil.rmtree(двор, ignore_errors=True)
    print(f"САМОТЕСТ check-ton-paneli: неудач {неудач}")
    return 1 if неудач else 0


def main() -> int:
    if "--selftest" in sys.argv:
        return самотест()
    if not ТОН.exists():
        print(f"[тон панели] судить нечем: документа тона нет ({ТОН})")
        return 77
    пары = словарь(ТОН.read_text(encoding="utf-8"))
    if not пары:
        print("[тон панели] судить нечем: в документе тона нет раздела «Его слова»")
        return 77
    беды = находки(КОРЕНЬ, пары)
    if беды:
        print(f"[тон панели] панель говорит не его словами: {len(беды)}")
        for строка in беды:
            print("   ", строка)
        return 1
    print(f"[тон панели] чисто: судимых пар слов {len(пары)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
