#!/usr/bin/env python3
"""Единый вход: код спрашивает модель и получает АНАЛИТИКУ ДАННЫХ, а решает сам.

Откуда взят: владелец 12.09.2026 — «Когда коду нужна какая то информация о
ситуации которую он не может получить напрямую, запускать сессию с конкретным
запросом получать конкретный ответ, действовать исходя из него, но безопасно,
не доверяя только модели, тоесть ответ модели должен быть в виде аналитики
данных, а не выводов. Ответ от модели может быть в нужном виде для скрипта,
который считает и принимает решение».

Замер того же дня: модель звали ЧЕТЫРЕ демона, каждый своим способом — свой
таймаут, свой разбор ответа, ни у одного журнала вызова, потолка расхода и
схемы ответа. Модель могла вернуть прозу вместо данных, и демон принял бы это
молча.

Здесь один способ и четыре правила:

1. **Ответ — данные по СХЕМЕ**, а не текст. Схема — файл JSON: {ключ: тип}.
   Не разобралось или ключа нет — отказ (код 2), а не «как-нибудь поймём».
2. **Выводов не спрашиваем.** Имя поля вроде «решение», «рекомендация»,
   «вывод», «оценка» запрещено схемой: решение принимает ВЫЗВАВШИЙ КОД.
3. **Каждый вызов в журнале** `$LOG_DIR/модель-вызовы.jsonl`: зачем, модель,
   секунды, прошла ли схема, стоимость по данным CLI.
4. **Потолок в сутки на «зачем»** (ключ MODEL_CALLS_PER_DAY): исчерпан — отказ
   с кодом 3, чтобы цикл демона не съел подписку.

    python3 scripts/sprosit-model.py --повод состояние-другой-смены \\
        --вопрос-файл /tmp/вопрос.txt
    python3 scripts/sprosit-model.py --зачем разовый-замер \\
        --вопрос-файл /tmp/вопрос.txt --схема /tmp/схема.json [--вид дежурное]

Поводы — данные (`harness/config/поводы-вызова-модели.yaml`): там сказано, КТО
зовёт, ПРИ КАКОМ условии, о чём спрашивает, какая схема ответа и что делает с
ним код. Там же список «когда НЕ звать».

Печатает в stdout ТОЛЬКО разобранный JSON ответа — его читает вызвавший скрипт.
"""
import json
import os
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))
from konf import из_файла, конфиг, корень_дерева  # noqa: E402

# Поля-выводы: их у модели не спрашивают. Решение — работа кода, который знает
# пороги, историю и последствия; модель знает только текст, который ей дали.
ЗАПРЕЩЁННЫЕ_ПОЛЯ = ("решение", "рекомендация", "вывод", "оценка", "советую",
                    "decision", "recommendation", "verdict", "should")
ТИПЫ = {"число": (int, float), "строка": str, "перечень": list,
        "правда-ложь": bool, "словарь": dict}


def журнал() -> Path:
    каталог = Path(конфиг().get("LOG_DIR") or "/var/log/harness")
    return каталог / "модель-вызовы.jsonl"


def записать(запись: dict) -> None:
    путь = журнал()
    путь.parent.mkdir(parents=True, exist_ok=True)
    with open(путь, "a", encoding="utf-8") as fh:
        fh.write(json.dumps(запись, ensure_ascii=False) + "\n")


def вызовов_за_сутки(зачем: str) -> int:
    путь = журнал()
    if not путь.exists():
        return 0
    рубеж = time.time() - 86400
    счёт = 0
    for строка in путь.read_text(encoding="utf-8", errors="replace").splitlines():
        try:
            запись = json.loads(строка)
        except ValueError:
            continue
        if запись.get("зачем") == зачем and запись.get("время", 0) >= рубеж:
            счёт += 1
    return счёт


def проверить_схему(схема: dict) -> str | None:
    """Схема запрещает спрашивать выводы и знает только описанные типы."""
    for ключ, тип in схема.items():
        низкий = ключ.lower()
        for запрет in ЗАПРЕЩЁННЫЕ_ПОЛЯ:
            if запрет in низкий:
                return (f"поле «{ключ}» просит у модели ВЫВОД. Спрашивайте данные, "
                        f"решение принимает код")
        if тип not in ТИПЫ:
            return f"тип «{тип}» неизвестен; известны: {', '.join(ТИПЫ)}"
    return None


def сверить_ответ(ответ: dict, схема: dict) -> str | None:
    for ключ, тип in схема.items():
        if ключ not in ответ:
            return f"в ответе нет поля «{ключ}»"
        if not isinstance(ответ[ключ], ТИПЫ[тип]):
            return (f"поле «{ключ}» пришло как {type(ответ[ключ]).__name__}, "
                    f"а схема просит «{тип}»")
    return None


def модель_для(вид: str, корень: Path) -> str:
    готово = subprocess.run(["bash", str(корень / "scripts" / "model-dlya.sh"), вид],
                            capture_output=True, text=True, timeout=30)
    return готово.stdout.strip() or "haiku"


def вынуть_json(текст: str) -> dict | None:
    """Модель может обрамить JSON пояснением — берём первый разбирающийся блок."""
    текст = текст.strip()
    for начало in range(len(текст)):
        if текст[начало] not in "{[":
            continue
        for конец in range(len(текст), начало, -1):
            try:
                значение = json.loads(текст[начало:конец])
            except ValueError:
                continue
            return значение if isinstance(значение, dict) else None
    return None


def спросить(вопрос: str, схема: dict, вид: str, таймаут: int, корень: Path) -> tuple:
    модель = модель_для(вид, корень)
    подсказка = ("Ответь ТОЛЬКО одним объектом JSON без пояснений. "
                 "Инструменты не нужны: все данные уже в вопросе. "
                 "Поля и их типы: "
                 + ", ".join(f"{к} — {т}" for к, т in схема.items())
                 + ". Это ДАННЫЕ, а не совет: выводов не делай.\n\n" + вопрос)
    начало = time.monotonic()
    try:
        готово = subprocess.run(
            # Замок инструментов обязателен: первый живой вызов 12.09.2026 ушёл
            # ИССЛЕДОВАТЬ файлы — 23 хода, 146 секунд, 0,26 $ и ответ прозой
            # вместо данных. Аналитический вопрос несёт данные В СЕБЕ; ходить
            # по машине незачем. Замок держит --permission-mode manual
            # (--allowedTools его не заменяет, память: флаг-инструментов-не-замок).
            ["claude", "-p", "--model", модель, "--strict-mcp-config",
             "--permission-mode", "manual",
             "--output-format", "json", подсказка],
            capture_output=True, text=True, timeout=таймаут)
    except subprocess.TimeoutExpired:
        return None, модель, round(time.monotonic() - начало, 1), f"нет ответа за {таймаут} с", {}
    секунды = round(time.monotonic() - начало, 1)
    if готово.returncode != 0:
        return None, модель, секунды, (готово.stderr or готово.stdout).strip()[:200], {}
    try:
        оболочка = json.loads(готово.stdout)
        текст = оболочка.get("result", "")
        цена = {"usd": оболочка.get("total_cost_usd"),
                "ходов": оболочка.get("num_turns")}
    except ValueError:
        текст, цена = готово.stdout, {}
    ответ = вынуть_json(текст)
    if ответ is None:
        return None, модель, секунды, "ответ не разобран как JSON", цена
    return ответ, модель, секунды, None, цена


def selftest() -> int:
    неудач = 0

    def проба(имя, ок):
        nonlocal неудач
        неудач += not ок
        print(f"  {'ok  ' if ок else 'FAIL'} {имя}")

    # БОЛЬНОЙ СЛУЧАЙ: у модели просят вывод — схема обязана отказать.
    проба("схема с «решением» отвергнута",
          проверить_схему({"решение": "строка"}) is not None)
    проба("схема с «recommendation» отвергнута",
          проверить_схему({"recommendation": "строка"}) is not None)
    проба("схема данных принята",
          проверить_схему({"файлов": "число", "имена": "перечень"}) is None)
    проба("неизвестный тип назван",
          проверить_схему({"x": "монада"}) is not None)

    проба("ответ без поля — отказ",
          сверить_ответ({"файлов": 3}, {"файлов": "число", "имена": "перечень"}) is not None)
    проба("ответ не того типа — отказ",
          сверить_ответ({"файлов": "три"}, {"файлов": "число"}) is not None)
    проба("ответ по схеме — принят",
          сверить_ответ({"файлов": 3, "имена": ["a"]},
                        {"файлов": "число", "имена": "перечень"}) is None)

    # Модель часто обрамляет JSON словами — вынимаем первый разбирающийся блок.
    проба("JSON в обрамлении вынут",
          вынуть_json('Вот данные:\n{"файлов": 2}\nГотово') == {"файлов": 2})
    проба("прозу за JSON не принимаем", вынуть_json("данных нет") is None)

    # Поводы — данные: каждый описанный повод обязан нести схему, и схема
    # обязана проходить тот же запрет на выводы, что и схема из файла.
    корень = корень_дерева(__file__)
    файл_поводов = корень / "harness" / "config" / "поводы-вызова-модели.yaml"
    проба("файл поводов на месте", файл_поводов.exists())
    if файл_поводов.exists():
        import yaml
        данные = yaml.safe_load(файл_поводов.read_text(encoding="utf-8")) or {}
        поводы = данные.get("поводы") or []
        проба("поводы описаны", len(поводы) > 0)
        проба("у каждого повода есть схема, и она без выводов",
              all(з.get("схема") and проверить_схему(з["схема"]) is None for з in поводы))
        проба("у каждого повода сказано, что делает код",
              all(з.get("делает_код") for з in поводы))
        проба("список «когда не звать» непуст", len(данные.get("не_звать") or []) > 0)
        # БОЛЬНОЙ СЛУЧАЙ: повода нет в данных — отказ с перечнем известных.
        try:
            повод("нет-такого-повода", корень)
            проба("неизвестный повод — отказ", False)
        except SystemExit as отказ:
            проба("неизвестный повод — отказ с перечнем известных",
                  "Известные" in str(отказ))
    print(f"самотест sprosit-model: неудач {неудач}")
    return 1 if неудач else 0


def повод(идентификатор: str, корень: Path) -> dict:
    """Повод — ДАННЫЕ (harness/config/поводы-вызова-модели.yaml): кто зовёт,
    при каком условии, о чём спрашивает, какая схема ответа и что код делает с
    ответом. Вызывающему коду остаётся передать текст вопроса.

    Зачем данными. Владелец 12.09.2026 спросил: «Зачем для чего могут
    запускаться сессии и в какой момент». Ответ не должен жить в голове автора
    каждого демона: повод, схема и потолок лежат в одном файле, который можно
    прочитать и пересмотреть, не читая четыре демона.
    """
    import yaml
    файл = корень / "harness" / "config" / "поводы-вызова-модели.yaml"
    данные = yaml.safe_load(файл.read_text(encoding="utf-8")) or {}
    for запись in данные.get("поводы") or []:
        if запись.get("id") == идентификатор:
            return запись
    известные = ", ".join(з.get("id", "?") for з in данные.get("поводы") or [])
    raise SystemExit(f"повод «{идентификатор}» не описан в данных. Известные: {известные}")


def довод(имя: str, умолчание: str | None = None) -> str | None:
    аргументы = sys.argv[1:]
    return аргументы[аргументы.index(имя) + 1] if имя in аргументы else умолчание


def главная() -> int:
    if "--selftest" in sys.argv[1:]:
        return selftest()
    корень = корень_дерева(__file__)
    имя_повода = довод("--повод")
    файл_вопроса = довод("--вопрос-файл")
    общий_потолок = int(из_файла("/etc/harness/harness.conf").get("MODEL_CALLS_PER_DAY")
                        or os.environ.get("MODEL_CALLS_PER_DAY") or 50)

    if имя_повода:
        # Схема, вид работы и потолок берутся из данных повода: демон не
        # переписывает их у себя и не расходится с реестром.
        запись = повод(имя_повода, корень)
        зачем = имя_повода
        схема_из_данных = запись.get("схема") or {}
        вид = довод("--вид", запись.get("вид", "дежурное"))
        потолок = int(довод("--потолок", str(запись.get("потолок", общий_потолок))))
        файл_схемы = None
    else:
        зачем = довод("--зачем")
        файл_схемы = довод("--схема")
        схема_из_данных = None
        вид = довод("--вид", "дежурное")
        потолок = общий_потолок

    if not (зачем and файл_вопроса and (файл_схемы or схема_из_данных is not None)):
        print(__doc__, file=sys.stderr)
        return 2
    таймаут = int(довод("--таймаут", "300"))

    было = вызовов_за_сутки(зачем)
    if было >= потолок:
        print(f"отказ: «{зачем}» уже спрашивали {было} раз за сутки при потолке "
              f"{потолок}", file=sys.stderr)
        return 3

    схема = (схема_из_данных if схема_из_данных is not None
             else json.loads(Path(файл_схемы).read_text(encoding="utf-8")))
    беда = проверить_схему(схема)
    if беда:
        print(f"отказ схемы: {беда}", file=sys.stderr)
        return 2

    вопрос = Path(файл_вопроса).read_text(encoding="utf-8")
    ответ, модель, секунды, отказ, цена = спросить(вопрос, схема, вид, таймаут, корень)
    if ответ is not None:
        отказ = сверить_ответ(ответ, схема)

    записать({"время": time.time(), "зачем": зачем, "модель": модель,
              "секунд": секунды, "по_схеме": отказ is None,
              "отказ": отказ, "цена": цена})
    if отказ:
        print(f"отказ: {отказ}", file=sys.stderr)
        return 2
    print(json.dumps(ответ, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(главная())
