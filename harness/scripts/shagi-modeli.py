#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Каждый шаг пайплайна имеет свою модель в таблице.

Откуда взят: ревью спеки «модель под задачу» 12.09.2026, находка C-7. Первая
редакция таблицы перечисляла виды работы «на глаз», и половина шагов пайплайна
(контракт, план, тесты) в неё не попала. Шаг без строки уходит в умолчание —
значит тесты до кода и контракт молча писала бы самая дешёвая модель.

Требование ОДНО: шаг есть в пайплайне — обязан быть и в таблице. Формулировка
«либо строка, либо честное умолчание» (первая редакция риска) делала проверку
зелёной при любом составе таблицы — это проверка, совпадающая с машиной.

    MODELS_CONF=… PIPELINE_CONF=… shagi-modeli.py
Код возврата: 0 — все шаги покрыты, 1 — есть непокрытые.
"""
import os
import sys

import yaml


def читать(путь: str) -> dict:
    try:
        with open(путь, encoding="utf-8") as fh:
            return yaml.safe_load(fh) or {}
    except (OSError, yaml.YAMLError):
        return {}


def непокрытые(таблица: dict, шаги: dict) -> list:
    """Шаги пайплайна, у которых нет своей модели."""
    нужны = {ш for уровень in (шаги or {}).values() for ш in (уровень or [])}
    return sorted(нужны - set(таблица or {}))


КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main() -> int:
    # Пути по умолчанию — боевые: гейт ворот зовёт скрипт без окружения, и без
    # умолчаний он проверял бы пустоту, оставаясь зелёным (та же беда, что с
    # самотестом на синтетических файлах).
    таблица = читать(os.environ.get("MODELS_CONF")
                     or os.path.join(КОРЕНЬ, "harness", "config", "модели.yaml")).get("модели") or {}
    шаги = читать(os.environ.get("PIPELINE_CONF")
                  or os.path.join(КОРЕНЬ, "harness", "config", "пайплайн.yaml")).get("шаги") or {}
    if not шаги:
        print("шагов пайплайна не прочитать — проверять нечего", file=sys.stderr)
        return 1
    if not таблица:
        print("таблицы моделей не прочитать", file=sys.stderr)
        return 1
    нет = непокрытые(таблица, шаги)
    if нет:
        print("шаги пайплайна без своей модели: " + ", ".join(нет), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
