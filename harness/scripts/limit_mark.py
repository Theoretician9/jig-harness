            проба("снятая метка называет повод", повод, "limit")
            проба("весть про лимит говорит про лимит", "Лимит обновился" in весть, True)
            проба("метки после снятия нет", файл().exists(), False)

            поставить("nemota")
            _, _, весть = снять()
            проба("немота называется немотой",
                  "Признака лимита не было" in весть, True)

            # Метка ПРЕЖНЕГО образца — одно поле. Так её писал limit-watch.sh,
            # и читатель печатал по ней положительное утверждение.
            файл().write_text(f"{int(time.time()) - 600}\n", encoding="utf-8")
            простой, повод, весть = снять()
            проба("у метки старого образца повода нет", повод, "")
            проба("и весть НЕ утверждает, что лимита не было",
                  "Признака лимита не было" in весть, False)
            проба("а говорит, что причину назвать нечем",
                  "причину назвать не могу" in весть, True)
            проба("простой считается и по такой метке", простой, 10)

            файл().write_text("мусор без времени\n", encoding="utf-8")
            простой, повод, весть = снять()
            проба("битая метка: простой 0, повода нет", (простой, повод), (0, ""))
            проба("пустой повод даёт нейтральную весть",
                  "причину назвать не могу" in весть, True)
            проба("неизвестный повод не принимается", поставить("выдумка"), 2)
            # Путь CLI, а не только функций: демоны зовут судью КОМАНДОЙ и
            # режут вывод по ТАБу — разделитель обязан быть пробой, а не
            # обещанием в docstring (ревью 27.09, F-lim-07).
            import subprocess                              # noqa: PLC0415
            свой = [sys.executable, str(Path(__file__).resolve())]
            среда = dict(os.environ, LOG_DIR=двор)
            пусто = subprocess.run(свой + ["--снять"], capture_output=True,
                                   text=True, env=среда)
            проба("CLI: снятие без метки — код 1 и молчание",
                  (пусто.returncode, пусто.stdout.strip()), (1, ""))
            subprocess.run(свой + ["--поставить", "limit"], env=среда, check=False)
            снято = subprocess.run(свой + ["--снять"], capture_output=True,
                                   text=True, env=среда)
            поля = снято.stdout.rstrip("\n").split("\t")
            проба("CLI: вывод режется ТАБом на три поля", len(поля), 3)
            проба("CLI: повод в поле два", поля[1], "limit")
            проба("CLI: весть в поле три", "Лимит обновился" in поля[2], True)

            # БОЛЬНОЙ СЛУЧАЙ 14.10.2026: работы не было, смена стояла у
            # приглашения, а владелец получил «смена просто молчала».
            subprocess.run(свой + ["--снять"], capture_output=True, env=среда)
            проба("«работы нет, смена у приглашения» — допустимый повод",
                  subprocess.run(свой + ["--поставить", "blocked"], env=среда,
                                 check=False).returncode, 0)
            повод_cli = subprocess.run(свой + ["--повод"], capture_output=True,
                                       text=True, env=среда)
            проба("CLI: --повод называет повод стоящей метки",
                  (повод_cli.returncode, повод_cli.stdout.strip()), (0, "blocked"))
            простой_вл, повод_вл, весть_вл = снять()
            проба("БОЛЬНОЙ СЛУЧАЙ: стояли у приглашения — вести о возобновлении НЕ даёт",
                  (повод_вл, весть_вл), ("blocked", ""))
            # Тихая метка не занимает места громкой: лимит, пришедший поверх
            # «blocked», ставит свою метку, и о нём говорят.
            поставить("blocked")
            проба("БОЛЬНОЙ СЛУЧАЙ: лимит поверх «blocked» ставится (код 0)",
                  поставить("limit"), 0)
            проба("и повод метки теперь «limit»", прочитать()[1], "limit")
            проба("а лимит поверх лимита — по-прежнему «уже стояла» (код 1)",
                  поставить("limit"), 1)
            проба("и «blocked» громкую метку не вытесняет", поставить("blocked"), 1)
            снять()
            без_метки = subprocess.run(свой + ["--повод"], capture_output=True,
                                       text=True, env=среда)
            проба("CLI: --повод без метки — код 1 и молчание",
                  (без_метки.returncode, без_метки.stdout.strip()), (1, ""))

            # БОЛЬНОЙ СЛУЧАЙ (ревью 27.09, F-04): метка от УМЕРШЕЙ смены.
            # Снимает её первая минута следующей, и владелец получал
            # «работа возобновилась сама, простой составил 5194 мин» про
            # лимит, кончившийся три дня назад (limit-watch.log 26.09 18:18).
            (каталог() / ИМЯ).write_text(
                f"{int(time.time()) - (УСТАРЕЛА_МИН + 1) * 60} limit",
                encoding="utf-8")
            простой_ст, повод_ст, весть_ст = снять()
            проба("устаревшая метка: простой всё равно назван",
                  простой_ст > УСТАРЕЛА_МИН, True)
            проба("устаревшая метка: повод не потерян", повод_ст, "limit")
            проба("БОЛЬНОЙ СЛУЧАЙ: устаревшая метка вести владельцу НЕ даёт",
                  весть_ст, "")

            (каталог() / ИМЯ).write_text(
                f"{int(time.time()) - (УСТАРЕЛА_МИН - 5) * 60} limit",
                encoding="utf-8")
            _, _, весть_св = снять()
            проба("метка моложе порога весть по-прежнему даёт",
                  "Лимит обновился" in весть_св, True)

            # БОЛЬНОЙ СЛУЧАЙ 17.10.2026 (снимок владельца): первое сообщение о
            # лимите пришло БЕЗ времени обновления — его слал тот из двух
            # сторожей, кто проснулся раньше, и слова у них были разные.
            снять()
            сброс = int(time.time()) + 7200
            поставить("limit", сброс)
            проба("метка помнит время сброса", прочитать()[2], сброс)
            час = datetime.datetime.fromtimestamp(сброс).strftime("%H:%M")
            проба("БОЛЬНОЙ СЛУЧАЙ: весть о лимите называет час обновления",
                  f"в {час}" in весть_о_лимите(), True)
            проба("и обещает продолжить после обновления",
                  "продолжу" in весть_о_лимите(), True)
            снять()
            # БОЛЬНОЙ СЛУЧАЙ (ревью 17.10.2026, F-01): дверь канала молчала
            # владельцу при ЛЮБОЙ метке. Повод «blocked» — работы нет, смена у
            # приглашения; «nemota» — смена молчит, а лимита НЕТ. Молчать
            # можно только из-за лимита.
            проба("метки нет — лимит не держится", лимит_держится(), False)
            поставить("limit")
            проба("повод limit — держится", лимит_держится(), True)
            снять(); поставить("blocked")
            проба("БОЛЬНОЙ СЛУЧАЙ: «работы нет» лимитом не считается",
                  лимит_держится(), False)
            снять(); поставить("nemota")
            проба("БОЛЬНОЙ СЛУЧАЙ: немота без признака лимита — не лимит",
                  лимит_держится(), False)
            снять()
            # Метка, пережившая смерть смены: снять её может только живая, и
            # без порога она закрывала бы канал НАВСЕГДА.
            файл().write_text(f"{int(time.time()) - (УСТАРЕЛА_МИН + 1) * 60} limit 0",
                              encoding="utf-8")
            проба("БОЛЬНОЙ СЛУЧАЙ: устаревшая метка канал не закрывает",
                  лимит_держится(), False)
            файл().write_text("мусор\n", encoding="utf-8")
            проба("БОЛЬНОЙ СЛУЧАЙ: битая метка канал не закрывает",
                  лимит_держится(), False)
            файл().write_text("", encoding="utf-8")
            проба("БОЛЬНОЙ СЛУЧАЙ: пустая метка (диск полон при постановке) — не лимит",
                  лимит_держится(), False)
            снять()
            # Час ДОВОДОМ: чтение обратно из файла было гонкой (F-10).
            сброс_доводом = int(time.time()) + 3600
            час_доводом = datetime.datetime.fromtimestamp(сброс_доводом).strftime("%H:%M")
