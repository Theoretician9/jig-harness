#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Метка «работа встала»: один формат, один текст вести.

Больной случай 27.09.2026 — его прислал владелец снимком. Прибор сказал ему
подряд две вещи: «Упёрся в лимит подписки. Признак: отказ 429 в журнале сессии
3 мин назад» и через 12 минут «Признака лимита не было — смена просто молчала».
Один прибор объявил лимит и сам же его опроверг.

Причина не в суждении, а в ФОРМАТЕ МЕТКИ. В ней два поля — когда встала и
повод (`limit` | `nemota`). Так её писал `session-warden.sh`
(`printf '%s %s'`), и так её читали ОБА демона. А `limit-watch.sh` писал
`date +%s` — одно поле. Повод терялся ровно в том случае, где доказательство
было самым крепким (свежий отказ 429), и читатель, не найдя повода, печатал
ПОЛОЖИТЕЛЬНОЕ утверждение «признака лимита не было».

Улика из журнала: `работа пошла снова (простой 33 мин, повод неизвестен)` —
после `лимит доказан: отказ 429 3 мин назад`.

Поэтому формат метки и текст вести живут ЗДЕСЬ, у одного судьи: знание о двух
полях, разъехавшееся по двум демонам, — это та же беда, что «два судьи одного
факта» ([[a-check-creates-its-own-condition]], [[the-check-fell-behind-the-code]]).

Прогон:
    limit_mark.py --поставить limit|nemota|blocked   # 0 — поставил, 1 — уже стояла
    limit_mark.py --стоит-ли                 # 0 — метка есть (ЛЮБАЯ)
    limit_mark.py --лимит-держится           # 0 — держится ЛИМИТ (вопрос двери канала)
    limit_mark.py --повод                    # печатает повод стоящей метки; 1 — метки нет
    limit_mark.py --снять                    # печатает: <простой_мин> <повод> <весть>
    limit_mark.py --selftest
"""
from __future__ import annotations

import datetime
import os
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))
import config as конф                                     # noqa: E402

# Пояс ВЛАДЕЛЬЦА, а не машины. Час обновления печатается ему, и на этой машине
# пояса совпали случайно: ревью 17.10.2026 замерило, что на свежем VPS пояс
# обычно UTC — владелец прочёл бы «обновится в 10:10», часа, которого у него
# нет. Пусто — пояс машины (так и стоит на этой установке).
def пояс_владельца() -> str:
    """Имя часового пояса владельца из настроек; пусто — пояс машины.

    Читается через общий загрузчик (окружение старше файла), а не из
    os.environ: `source harness.conf` в демоне НЕ экспортирует ключи, и
    питоновский помощник их просто не увидел бы
    ([[default-above-loader-kills-setting]]).
    """
    try:
        return str(конф.конфиг(конф.путь_harness_conf()).get("OWNER_TZ") or "").strip()
    except Exception:
        return ""

ИМЯ = "лимит-подписки.состояние"
ПИНОК = "лимит-подписки.пинок"
ПОВОДЫ = ("limit", "nemota", "blocked")
ТИХИЕ = ("blocked",)

# Весть владельцу на каждый повод. Неизвестный повод — НЕ «лимита не было»:
# утверждать по отсутствующему полю значит врать там, где нечем судить.
# «blocked» — работы, которую смена может делать сама, нет, и она стоит у
# приглашения: работа не вставала, возобновляться нечему, весть пуста.
# Такая метка ТИХАЯ: громкий повод (лимит, немота) её вытесняет, иначе она
# заняла бы место метки, о которой владельцу обязаны сказать.
# Весть о НАЧАЛЕ простоя. Жила в двух демонах разными словами, и владелец
# получал ту, чей сторож проснулся первым: ежеминутный limit-watch.sh писал
# «Признак: отказ 429 в журнале сессии N мин назад» БЕЗ времени обновления, а
# десятиминутный session-warden.sh — с временем. 17.10.2026 первым пришёл
# быстрый, и владелец сказал: «сообщение о том, что лимит подписки первое
# самое должно сразу иметь инфорсацию о времени, и время должно быть в 24
# часовом формате, написано все должно быть человеческим языком».
ВЕСТЬ_О_ЛИМИТЕ = "Упёрся в лимит подписки. Лимит обновится в {час}, после обновления продолжу."
# Часа нет — не выдумывать: время сброса приходит ЧИСЛОМ от CLI, и его
# отсутствие само по себе новость («скажу, когда пойдёт»), а не повод врать.
ВЕСТЬ_О_ЛИМИТЕ_БЕЗ_ЧАСА = ("Упёрся в лимит подписки. Времени обновления подписка не назвала — "
                            "скажу, как только работа пойдёт.")

ВЕСТИ = {
    "limit": "Лимит обновился — работа возобновилась сама, простой составил {мин} мин.",
    "nemota": ("Работа возобновилась сама, простой составил {мин} мин. "
               "Признака лимита не было — смена просто молчала."),
    "blocked": "",
    "": ("Работа возобновилась сама, простой составил {мин} мин. "
         "Почему стояла — метка не записала, причину назвать не могу."),
}


# Сколько минут простоя означают, что метку ставила УЖЕ ДРУГАЯ смена.
#
# Ревью 27.09.2026 (F-04): метка переживает смерть сессии, а снять её может
# только живая — значит её снимет первая минута СЛЕДУЮЩЕЙ смены, и владелец
# получит «Лимит обновился — работа возобновилась сама, простой составил
# 5194 мин» про лимит, кончившийся три дня назад (limit-watch.log, 26.09 18:18).
# Шесть часов взяты не на глаз: окно лимита подписки сбрасывается каждые пять
# часов, поэтому простой длиннее лимитом уже не объясняется.
УСТАРЕЛА_МИН = int(os.environ.get("LIMIT_STALE_MIN") or 360)


def каталог() -> Path:
    return Path(os.environ.get("LOG_DIR") or конф.log_dir())


def файл() -> Path:
    return каталог() / ИМЯ


def поставить(повод: str, сброс: int = 0) -> int:
    """0 — метка поставлена, 1 — уже стояла (о ней сказано, повторять нечего).

    `сброс` — unix-время обновления лимита, как его назвал САМ CLI
    (`limit-in-log.py --сброс`). Ноль означает «не назвал»: угадывать час по
    человеческой строке нельзя, а по его отсутствию нельзя утверждать время.
    Поле третье и необязательное — метка прежнего образца (два поля) читается
    по-прежнему.
    """
    if повод not in ПОВОДЫ:
        print(f"повод должен быть одним из {ПОВОДЫ}, а не «{повод}»", file=sys.stderr)
        return 2
    цель = файл()
    цель.parent.mkdir(parents=True, exist_ok=True)
    try:
        # Атомарно: два сторожа стартуют по cron в одну секунду (ежеминутный и
        # десятиминутный), и «проверил → записал» давало ДВУХ поставивших —
        # значит два сообщения владельцу (ревью 27.09, F-lim-04).
        дескриптор = os.open(цель, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o644)
    except FileExistsError:
        if повод in ТИХИЕ or прочитать()[1] not in ТИХИЕ:
            return 1
        # Тихую метку убирает ОДИН: rename атомарен, второй получит отказ и
        # уступит, как при обычной гонке постановки.
        вытеснена = цель.with_name(f"{цель.name}.вытеснена-{os.getpid()}")
        try:
            os.rename(цель, вытеснена)
        except OSError:
            return 1
        # Между чтением и rename соседний сторож мог уже вытеснить тихую метку
        # своей громкой — тогда унесена ЕГО метка: вернуть и уступить.
        поля = вытеснена.read_text(encoding="utf-8").split()
        if len(поля) < 2 or поля[1] not in ТИХИЕ:
            os.replace(вытеснена, цель)
            return 1
        вытеснена.unlink()
        return поставить(повод, сброс)
    except OSError as беда:
        print(f"метку не поставить: {беда}", file=sys.stderr)
        return 3
    with os.fdopen(дескриптор, "w", encoding="utf-8") as поток:
        поток.write(f"{int(time.time())} {повод} {int(сброс)}\n")
    return 0


def прочитать() -> tuple[int, str, int]:
    """(когда встала, повод, время сброса). Нет метки или мусор — (сейчас, «», 0)."""
    try:
        поля = файл().read_text(encoding="utf-8").split()
    except OSError:
        return int(time.time()), "", 0
    когда = int(поля[0]) if поля and поля[0].isdigit() else int(time.time())
    повод = поля[1] if len(поля) > 1 and поля[1] in ПОВОДЫ else ""
    сброс = int(поля[2]) if len(поля) > 2 and поля[2].isdigit() else 0
    return когда, повод, сброс


def лимит_держится() -> bool:
    """Держится ли ЛИМИТ прямо сейчас — вопрос двери канала, не «есть ли файл».

    Три различения, каждое куплено находкой ревью 17.10.2026 (F-01):

    * ПОВОД. У метки их три, и молчать владельцу можно только из-за лимита.
      «blocked» — работы в очереди нет, смена стоит у приглашения: штатное
      состояние, метка ТИХАЯ по замыслу. «nemota» — смена молчит, а признака
      лимита НЕТ. Закрывать канал в этих двух значит оставить владельца без
      единого сообщения там, где лимита не было вовсе.
    * ВОЗРАСТ. Снять метку может только ЖИВАЯ смена (возобновление требует
      свежего ответа в журнале). Умерла панель в лимите — метка стоит вечно, и
      порог УСТАРЕЛА_МИН здесь тот же, что у снятия: простой длиннее шести
      часов лимитом уже не объясняется.
    * РАЗБОРЧИВОСТЬ. Пустая или битая метка — не основание молчать: пустой
      файл получается ровно в беде (постановка открывает его O_EXCL и пишет
      вторым шагом — диск полон, процесс убит), а беда обязана дойти.
    """
    if not файл().exists():
        return False
    когда, повод, _ = прочитать()
    if повод != "limit":
        return False
    return int((time.time() - когда) // 60) < УСТАРЕЛА_МИН


def _час(сброс: int) -> str:
    """Час обновления в 24-часовом формате и в поясе ВЛАДЕЛЬЦА."""
    момент = datetime.datetime.fromtimestamp(сброс, datetime.UTC)
    пояс = пояс_владельца()
    if пояс:
        try:
            from zoneinfo import ZoneInfo                # noqa: PLC0415
            return момент.astimezone(ZoneInfo(пояс)).strftime("%H:%M")
        except Exception:
            # Неизвестное имя пояса — не повод соврать часом: пояс машины
            # хотя бы назван в паспорте установки.
            pass
    return момент.astimezone().strftime("%H:%M")


def час_сброса() -> str:
    """Час обновления стоящей метки в 24-часовом формате, или «» — неизвестен.

    Спрашивает дверь канала, чтобы назвать час в своём отказе. Формат считает
    ТОТ ЖЕ судья: `date -d "@unix"` есть только у GNU date, и второй формат
    часа в другом файле разъехался бы молча (ревью 17.10.2026, F-16).
    """
    _, _, сброс = прочитать()
    if сброс <= 0:
        return ""
    return _час(сброс)


def весть_о_лимите(сброс: int = 0) -> str:
    """Что сказать владельцу в НАЧАЛЕ простоя: час обновления или честное «нет часа».

    Час берётся ДОВОДОМ, если звонящий его уже знает (он же кладёт его в
    метку), иначе — из метки. Чтение обратно из файла отдельным процессом было
    гонкой: соседний сторож успевал снять метку, и владелец получал весть БЕЗ
    часа — ровно то, на что он пожаловался (ревью 17.10.2026, F-10).
    Печатается в 24-часовом формате местного времени машины.
    """
    if сброс <= 0:
        _, _, сброс = прочитать()
    if сброс <= 0:
        return ВЕСТЬ_О_ЛИМИТЕ_БЕЗ_ЧАСА
    return ВЕСТЬ_О_ЛИМИТЕ.format(час=_час(сброс))


def снять() -> tuple[int, str, str]:
    """(простой в минутах, повод, весть владельцу). Метка и пинок удаляются.

    Весть ПУСТА, когда метка устарела: звонящий тогда молчит владельцу и пишет
    только в свой журнал.
    """
    когда, повод, _ = прочитать()
    for имя in (ИМЯ, ПИНОК):
        try:
            (каталог() / имя).unlink()
        except OSError:
            pass
    простой = max(0, int((time.time() - когда) // 60))
    if простой >= УСТАРЕЛА_МИН:
        return простой, повод, ""
    return простой, повод, ВЕСТИ[повод].format(мин=простой)


def _selftest() -> int:
    import tempfile
    плохо = путей = 0

    def проба(имя: str, вышло, ждём) -> None:
        nonlocal плохо, путей
        путей += 1
        if вышло == ждём:
            print(f"  ок    {имя}")
        else:
            print(f"  ПЛОХО {имя}: вышло {вышло!r}, ждали {ждём!r}")
            плохо = 1

    прежний = os.environ.get("LOG_DIR")
    with tempfile.TemporaryDirectory() as двор:
        os.environ["LOG_DIR"] = двор
        try:
            проба("метки нет — ставится", поставить("limit"), 0)
            проба("вторая постановка не перетирает первую", поставить("nemota"), 1)
            проба("повод прочитан", прочитать()[1], "limit")
            # БОЛЬНОЙ СЛУЧАЙ 27.09.2026: повод терялся, и владелец получал
            # «Признака лимита не было» сразу после «Упёрся в лимит».
            простой, повод, весть = снять()
            проба("снятая метка называет повод", повод, "limit")
            проба("весть про лимит говорит про лимит", "Лимит обновился" in весть, True)
            проба("метки после снятия нет", файл().exists(), False)

            поставить("nemota")
            _, _, весть = снять()
            проба("немота называется немотой",
                  "Признака лимита не было" in весть, True)

            # Метка ПРЕЖНЕГО образца — одно поле. Так её писал limit-watch.sh,
            # и читатель печатал по ней положительное утверждение.
            файл().write_text(f"{int(time.time()) - 600}\n", encoding="utf-8")
            простой, повод, весть = снять()
            проба("у метки старого образца повода нет", повод, "")
            проба("и весть НЕ утверждает, что лимита не было",
                  "Признака лимита не было" in весть, False)
            проба("а говорит, что причину назвать нечем",
                  "причину назвать не могу" in весть, True)
            проба("простой считается и по такой метке", простой, 10)

            файл().write_text("мусор без времени\n", encoding="utf-8")
            простой, повод, весть = снять()
            проба("битая метка: простой 0, повода нет", (простой, повод), (0, ""))
            проба("пустой повод даёт нейтральную весть",
                  "причину назвать не могу" in весть, True)
            проба("неизвестный повод не принимается", поставить("выдумка"), 2)
            # Путь CLI, а не только функций: демоны зовут судью КОМАНДОЙ и
            # режут вывод по ТАБу — разделитель обязан быть пробой, а не
            # обещанием в docstring (ревью 27.09, F-lim-07).
            import subprocess                              # noqa: PLC0415
            свой = [sys.executable, str(Path(__file__).resolve())]
            среда = dict(os.environ, LOG_DIR=двор)
            пусто = subprocess.run(свой + ["--снять"], capture_output=True,
                                   text=True, env=среда)
            проба("CLI: снятие без метки — код 1 и молчание",
                  (пусто.returncode, пусто.stdout.strip()), (1, ""))
            subprocess.run(свой + ["--поставить", "limit"], env=среда, check=False)
            снято = subprocess.run(свой + ["--снять"], capture_output=True,
                                   text=True, env=среда)
            поля = снято.stdout.rstrip("\n").split("\t")
            проба("CLI: вывод режется ТАБом на три поля", len(поля), 3)
            проба("CLI: повод в поле два", поля[1], "limit")
            проба("CLI: весть в поле три", "Лимит обновился" in поля[2], True)

            # БОЛЬНОЙ СЛУЧАЙ 14.10.2026: работы не было, смена стояла у
            # приглашения, а владелец получил «смена просто молчала».
            subprocess.run(свой + ["--снять"], capture_output=True, env=среда)
            проба("«работы нет, смена у приглашения» — допустимый повод",
                  subprocess.run(свой + ["--поставить", "blocked"], env=среда,
                                 check=False).returncode, 0)
            повод_cli = subprocess.run(свой + ["--повод"], capture_output=True,
                                       text=True, env=среда)
            проба("CLI: --повод называет повод стоящей метки",
                  (повод_cli.returncode, повод_cli.stdout.strip()), (0, "blocked"))
            простой_вл, повод_вл, весть_вл = снять()
            проба("БОЛЬНОЙ СЛУЧАЙ: стояли у приглашения — вести о возобновлении НЕ даёт",
                  (повод_вл, весть_вл), ("blocked", ""))
            # Тихая метка не занимает места громкой: лимит, пришедший поверх
            # «blocked», ставит свою метку, и о нём говорят.
            поставить("blocked")
            проба("БОЛЬНОЙ СЛУЧАЙ: лимит поверх «blocked» ставится (код 0)",
                  поставить("limit"), 0)
            проба("и повод метки теперь «limit»", прочитать()[1], "limit")
            проба("а лимит поверх лимита — по-прежнему «уже стояла» (код 1)",
                  поставить("limit"), 1)
            проба("и «blocked» громкую метку не вытесняет", поставить("blocked"), 1)
            снять()
            без_метки = subprocess.run(свой + ["--повод"], capture_output=True,
                                       text=True, env=среда)
            проба("CLI: --повод без метки — код 1 и молчание",
                  (без_метки.returncode, без_метки.stdout.strip()), (1, ""))

            # БОЛЬНОЙ СЛУЧАЙ (ревью 27.09, F-04): метка от УМЕРШЕЙ смены.
            # Снимает её первая минута следующей, и владелец получал
            # «работа возобновилась сама, простой составил 5194 мин» про
            # лимит, кончившийся три дня назад (limit-watch.log 26.09 18:18).
            (каталог() / ИМЯ).write_text(
                f"{int(time.time()) - (УСТАРЕЛА_МИН + 1) * 60} limit",
                encoding="utf-8")
            простой_ст, повод_ст, весть_ст = снять()
            проба("устаревшая метка: простой всё равно назван",
                  простой_ст > УСТАРЕЛА_МИН, True)
            проба("устаревшая метка: повод не потерян", повод_ст, "limit")
            проба("БОЛЬНОЙ СЛУЧАЙ: устаревшая метка вести владельцу НЕ даёт",
                  весть_ст, "")

            (каталог() / ИМЯ).write_text(
                f"{int(time.time()) - (УСТАРЕЛА_МИН - 5) * 60} limit",
                encoding="utf-8")
            _, _, весть_св = снять()
            проба("метка моложе порога весть по-прежнему даёт",
                  "Лимит обновился" in весть_св, True)

            # БОЛЬНОЙ СЛУЧАЙ 17.10.2026 (снимок владельца): первое сообщение о
            # лимите пришло БЕЗ времени обновления — его слал тот из двух
            # сторожей, кто проснулся раньше, и слова у них были разные.
            снять()
            сброс = int(time.time()) + 7200
            поставить("limit", сброс)
            проба("метка помнит время сброса", прочитать()[2], сброс)
            час = datetime.datetime.fromtimestamp(сброс).strftime("%H:%M")
            проба("БОЛЬНОЙ СЛУЧАЙ: весть о лимите называет час обновления",
                  f"в {час}" in весть_о_лимите(), True)
            проба("и обещает продолжить после обновления",
                  "продолжу" in весть_о_лимите(), True)
            снять()
            # БОЛЬНОЙ СЛУЧАЙ (ревью 17.10.2026, F-01): дверь канала молчала
            # владельцу при ЛЮБОЙ метке. Повод «blocked» — работы нет, смена у
            # приглашения; «nemota» — смена молчит, а лимита НЕТ. Молчать
            # можно только из-за лимита.
            проба("метки нет — лимит не держится", лимит_держится(), False)
            поставить("limit")
            проба("повод limit — держится", лимит_держится(), True)
            снять(); поставить("blocked")
            проба("БОЛЬНОЙ СЛУЧАЙ: «работы нет» лимитом не считается",
                  лимит_держится(), False)
            снять(); поставить("nemota")
            проба("БОЛЬНОЙ СЛУЧАЙ: немота без признака лимита — не лимит",
                  лимит_держится(), False)
            снять()
            # Метка, пережившая смерть смены: снять её может только живая, и
            # без порога она закрывала бы канал НАВСЕГДА.
            файл().write_text(f"{int(time.time()) - (УСТАРЕЛА_МИН + 1) * 60} limit 0",
                              encoding="utf-8")
            проба("БОЛЬНОЙ СЛУЧАЙ: устаревшая метка канал не закрывает",
                  лимит_держится(), False)
            файл().write_text("мусор\n", encoding="utf-8")
            проба("БОЛЬНОЙ СЛУЧАЙ: битая метка канал не закрывает",
                  лимит_держится(), False)
            файл().write_text("", encoding="utf-8")
            проба("БОЛЬНОЙ СЛУЧАЙ: пустая метка (диск полон при постановке) — не лимит",
                  лимит_держится(), False)
            снять()
            # Час ДОВОДОМ: чтение обратно из файла было гонкой (F-10).
            сброс_доводом = int(time.time()) + 3600
            час_доводом = datetime.datetime.fromtimestamp(сброс_доводом).strftime("%H:%M")
            проба("весть берёт час доводом, когда метки уже нет",
                  f"в {час_доводом}" in весть_о_лимите(сброс_доводом), True)
            поставить("limit")
            проба("без времени сброса час НЕ выдумывается",
                  "не назвала" in весть_о_лимите(), True)
            проба("и поле сброса у такой метки нулевое", прочитать()[2], 0)
            снять()
        finally:
            os.environ.pop("LOG_DIR", None)
            if прежний is not None:
                os.environ["LOG_DIR"] = прежний

    print(f"САМОТЕСТ {'ПРОЙДЕН' if not плохо else 'ПРОВАЛЕН'}: {путей} путей, "
          "больной первым — потерянный повод")
    return 1 if плохо else 0


def main() -> int:
    доводы = sys.argv[1:]
    if "--selftest" in доводы:
        return _selftest()
    if "--поставить" in доводы:
        место = доводы.index("--поставить") + 1
        сброс = 0
        if "--сброс" in доводы:
            где = доводы.index("--сброс") + 1
            значение = доводы[где] if где < len(доводы) else ""
            сброс = int(значение) if значение.isdigit() else 0
        return поставить(доводы[место] if место < len(доводы) else "", сброс)
    if "--весть-о-лимите" in доводы:
        сброс = 0
        if "--сброс" in доводы:
            где = доводы.index("--сброс") + 1
            значение = доводы[где] if где < len(доводы) else ""
            сброс = int(значение) if значение.isdigit() else 0
        print(весть_о_лимите(сброс))
        return 0
    if "--час-сброса" in доводы:
        час = час_сброса()
        if not час:
            return 1
        print(час)
        return 0
    if "--лимит-держится" in доводы:
        # Вопрос двери канала: 0 — лимит держится, владельцу молчим.
        return 0 if лимит_держится() else 1
    if "--сброс-стоящей" in доводы:
        if not файл().exists():
            return 1
        сброс = прочитать()[2]
        if сброс <= 0:
            return 1
        print(сброс)
        return 0
    if "--стоит-ли" in доводы:
        return 0 if файл().exists() else 1
    if "--повод" in доводы:
        if not файл().exists():
            return 1
        print(прочитать()[1])
        return 0
    if "--снять" in доводы:
        # Нет метки — нечего и снимать: работа не «возобновилась», просто её
        # никто не объявлял вставшей. Прежде здесь печаталось «возобновилась
        # сама, простой 0 мин», и второй сторож слал владельцу дубль с ложным
        # нулём (ревью 27.09, F-lim-03).
        if not файл().exists():
            return 1
        простой, повод, весть = снять()
        print(f"{простой}\t{повод}\t{весть}")
        return 0
    print(__doc__.strip().splitlines()[-1], file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main())
