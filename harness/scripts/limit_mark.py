#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Метка «работа встала»: один формат, один текст вести.

Больной случай 27.09.2026 — его прислал владелец снимком. Прибор сказал ему
подряд две вещи: «Упёрся в лимит подписки. Признак: отказ 429 в журнале сессии
3 мин назад» и через 12 минут «Признака лимита не было — смена просто молчала».
Один прибор объявил лимит и сам же его опроверг.

Причина не в суждении, а в ФОРМАТЕ МЕТКИ. В ней два поля — когда встала и
повод (`limit` | `nemota`). Так её писал `session-warden.sh`
(`printf '%s %s'`), и так её читали ОБА демона. А `limit-watch.sh` писал
`date +%s` — одно поле. Повод терялся ровно в том случае, где доказательство
было самым крепким (свежий отказ 429), и читатель, не найдя повода, печатал
ПОЛОЖИТЕЛЬНОЕ утверждение «признака лимита не было».

Улика из журнала: `работа пошла снова (простой 33 мин, повод неизвестен)` —
после `лимит доказан: отказ 429 3 мин назад`.

Поэтому формат метки и текст вести живут ЗДЕСЬ, у одного судьи: знание о двух
полях, разъехавшееся по двум демонам, — это та же беда, что «два судьи одного
факта» ([[a-check-creates-its-own-condition]], [[the-check-fell-behind-the-code]]).

Прогон:
    limit_mark.py --поставить limit|nemota   # 0 — поставил, 1 — уже стояла
    limit_mark.py --стоит-ли                 # 0 — метка есть
    limit_mark.py --снять                    # печатает: <простой_мин> <повод> <весть>
    limit_mark.py --selftest
"""
from __future__ import annotations

import os
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))
import config as конф                                     # noqa: E402

ИМЯ = "лимит-подписки.состояние"
ПИНОК = "лимит-подписки.пинок"
ПОВОДЫ = ("limit", "nemota")

# Весть владельцу на каждый повод. Неизвестный повод — НЕ «лимита не было»:
# утверждать по отсутствующему полю значит врать там, где нечем судить.
ВЕСТИ = {
    "limit": "Лимит обновился — работа возобновилась сама, простой составил {мин} мин.",
    "nemota": ("Работа возобновилась сама, простой составил {мин} мин. "
               "Признака лимита не было — смена просто молчала."),
    "": ("Работа возобновилась сама, простой составил {мин} мин. "
         "Почему стояла — метка не записала, причину назвать не могу."),
}


# Сколько минут простоя означают, что метку ставила УЖЕ ДРУГАЯ смена.
#
# Ревью 27.09.2026 (F-04): метка переживает смерть сессии, а снять её может
# только живая — значит её снимет первая минута СЛЕДУЮЩЕЙ смены, и владелец
# получит «Лимит обновился — работа возобновилась сама, простой составил
# 5194 мин» про лимит, кончившийся три дня назад (limit-watch.log, 26.09 18:18).
# Шесть часов взяты не на глаз: окно лимита подписки сбрасывается каждые пять
# часов, поэтому простой длиннее лимитом уже не объясняется.
УСТАРЕЛА_МИН = int(os.environ.get("LIMIT_STALE_MIN") or 360)


def каталог() -> Path:
    return Path(os.environ.get("LOG_DIR") or конф.log_dir())


def файл() -> Path:
    return каталог() / ИМЯ


def поставить(повод: str) -> int:
    """0 — метка поставлена, 1 — уже стояла (о ней сказано, повторять нечего)."""
    if повод not in ПОВОДЫ:
        print(f"повод должен быть одним из {ПОВОДЫ}, а не «{повод}»", file=sys.stderr)
        return 2
    цель = файл()
    цель.parent.mkdir(parents=True, exist_ok=True)
    try:
        # Атомарно: два сторожа стартуют по cron в одну секунду (ежеминутный и
        # десятиминутный), и «проверил → записал» давало ДВУХ поставивших —
        # значит два сообщения владельцу (ревью 27.09, F-lim-04).
        дескриптор = os.open(цель, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o644)
    except FileExistsError:
        return 1
    except OSError as беда:
        print(f"метку не поставить: {беда}", file=sys.stderr)
        return 3
    with os.fdopen(дескриптор, "w", encoding="utf-8") as поток:
        поток.write(f"{int(time.time())} {повод}\n")
    return 0


def прочитать() -> tuple[int, str]:
    """(когда встала, повод). Нет метки или мусор — (сейчас, «»)."""
    try:
        поля = файл().read_text(encoding="utf-8").split()
    except OSError:
        return int(time.time()), ""
    когда = int(поля[0]) if поля and поля[0].isdigit() else int(time.time())
    повод = поля[1] if len(поля) > 1 and поля[1] in ПОВОДЫ else ""
    return когда, повод


def снять() -> tuple[int, str, str]:
    """(простой в минутах, повод, весть владельцу). Метка и пинок удаляются.

    Весть ПУСТА, когда метка устарела: звонящий тогда молчит владельцу и пишет
    только в свой журнал.
    """
    когда, повод = прочитать()
    for имя in (ИМЯ, ПИНОК):
        try:
            (каталог() / имя).unlink()
        except OSError:
            pass
    простой = max(0, int((time.time() - когда) // 60))
    if простой >= УСТАРЕЛА_МИН:
        return простой, повод, ""
    return простой, повод, ВЕСТИ[повод].format(мин=простой)


def _selftest() -> int:
    import tempfile
    плохо = путей = 0

    def проба(имя: str, вышло, ждём) -> None:
        nonlocal плохо, путей
        путей += 1
        if вышло == ждём:
            print(f"  ок    {имя}")
        else:
            print(f"  ПЛОХО {имя}: вышло {вышло!r}, ждали {ждём!r}")
            плохо = 1

    прежний = os.environ.get("LOG_DIR")
    with tempfile.TemporaryDirectory() as двор:
        os.environ["LOG_DIR"] = двор
        try:
            проба("метки нет — ставится", поставить("limit"), 0)
            проба("вторая постановка не перетирает первую", поставить("nemota"), 1)
            проба("повод прочитан", прочитать()[1], "limit")
            # БОЛЬНОЙ СЛУЧАЙ 27.09.2026: повод терялся, и владелец получал
            # «Признака лимита не было» сразу после «Упёрся в лимит».
            простой, повод, весть = снять()
            проба("снятая метка называет повод", повод, "limit")
            проба("весть про лимит говорит про лимит", "Лимит обновился" in весть, True)
            проба("метки после снятия нет", файл().exists(), False)

            поставить("nemota")
            _, _, весть = снять()
            проба("немота называется немотой",
                  "Признака лимита не было" in весть, True)

            # Метка ПРЕЖНЕГО образца — одно поле. Так её писал limit-watch.sh,
            # и читатель печатал по ней положительное утверждение.
            файл().write_text(f"{int(time.time()) - 600}\n", encoding="utf-8")
            простой, повод, весть = снять()
            проба("у метки старого образца повода нет", повод, "")
            проба("и весть НЕ утверждает, что лимита не было",
                  "Признака лимита не было" in весть, False)
            проба("а говорит, что причину назвать нечем",
                  "причину назвать не могу" in весть, True)
            проба("простой считается и по такой метке", простой, 10)

            файл().write_text("мусор без времени\n", encoding="utf-8")
            простой, повод, весть = снять()
            проба("битая метка: простой 0, повода нет", (простой, повод), (0, ""))
            проба("пустой повод даёт нейтральную весть",
                  "причину назвать не могу" in весть, True)
            проба("неизвестный повод не принимается", поставить("выдумка"), 2)
            # Путь CLI, а не только функций: демоны зовут судью КОМАНДОЙ и
            # режут вывод по ТАБу — разделитель обязан быть пробой, а не
            # обещанием в docstring (ревью 27.09, F-lim-07).
            import subprocess                              # noqa: PLC0415
            свой = [sys.executable, str(Path(__file__).resolve())]
            среда = dict(os.environ, LOG_DIR=двор)
            пусто = subprocess.run(свой + ["--снять"], capture_output=True,
                                   text=True, env=среда)
            проба("CLI: снятие без метки — код 1 и молчание",
                  (пусто.returncode, пусто.stdout.strip()), (1, ""))
            subprocess.run(свой + ["--поставить", "limit"], env=среда, check=False)
            снято = subprocess.run(свой + ["--снять"], capture_output=True,
                                   text=True, env=среда)
            поля = снято.stdout.rstrip("\n").split("\t")
            проба("CLI: вывод режется ТАБом на три поля", len(поля), 3)
            проба("CLI: повод в поле два", поля[1], "limit")
            проба("CLI: весть в поле три", "Лимит обновился" in поля[2], True)

            # БОЛЬНОЙ СЛУЧАЙ (ревью 27.09, F-04): метка от УМЕРШЕЙ смены.
            # Снимает её первая минута следующей, и владелец получал
            # «работа возобновилась сама, простой составил 5194 мин» про
            # лимит, кончившийся три дня назад (limit-watch.log 26.09 18:18).
            (каталог() / ИМЯ).write_text(
                f"{int(time.time()) - (УСТАРЕЛА_МИН + 1) * 60} limit",
                encoding="utf-8")
            простой_ст, повод_ст, весть_ст = снять()
            проба("устаревшая метка: простой всё равно назван",
                  простой_ст > УСТАРЕЛА_МИН, True)
            проба("устаревшая метка: повод не потерян", повод_ст, "limit")
            проба("БОЛЬНОЙ СЛУЧАЙ: устаревшая метка вести владельцу НЕ даёт",
                  весть_ст, "")

            (каталог() / ИМЯ).write_text(
                f"{int(time.time()) - (УСТАРЕЛА_МИН - 5) * 60} limit",
                encoding="utf-8")
            _, _, весть_св = снять()
            проба("метка моложе порога весть по-прежнему даёт",
                  "Лимит обновился" in весть_св, True)
        finally:
            os.environ.pop("LOG_DIR", None)
            if прежний is not None:
                os.environ["LOG_DIR"] = прежний

    print(f"САМОТЕСТ {'ПРОЙДЕН' if not плохо else 'ПРОВАЛЕН'}: {путей} путей, "
          "больной первым — потерянный повод")
    return 1 if плохо else 0


def main() -> int:
    доводы = sys.argv[1:]
    if "--selftest" in доводы:
        return _selftest()
    if "--поставить" in доводы:
        место = доводы.index("--поставить") + 1
        return поставить(доводы[место] if место < len(доводы) else "")
    if "--стоит-ли" in доводы:
        return 0 if файл().exists() else 1
    if "--снять" in доводы:
        # Нет метки — нечего и снимать: работа не «возобновилась», просто её
        # никто не объявлял вставшей. Прежде здесь печаталось «возобновилась
        # сама, простой 0 мин», и второй сторож слал владельцу дубль с ложным
        # нулём (ревью 27.09, F-lim-03).
        if not файл().exists():
            return 1
        простой, повод, весть = снять()
        print(f"{простой}\t{повод}\t{весть}")
        return 0
    print(__doc__.strip().splitlines()[-1], file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main())
