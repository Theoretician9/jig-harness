#!/usr/bin/env python3
"""Черновик реестра устройства v2: разбор владельца + живые паспорта.

Откуда взят. Владелец 13.09.2026 прислал архив РАЗБОР-УСТРОЙСТВА-2026-09-12 и
велел взять его «как большую задачу». Шаг З-2 задания: собрать черновик нового
реестра, ничего не потеряв по дороге, и доказать это приёмкой
`127 = 55 + 31 + 19 + 22`.

Почему приёмка именно такая. Разбор делит 127 записей на четыре группы, и
границы групп не совпадают с именами семейств: `promote` — это механизмы,
которые разбор предложил поднять из проверок, а `skill-dom` — скилы своего
хозяйства. Формулировка «механизмы + правила + скилы + слитые», взятая на
глаз, даёт 121: шесть `promote` исчезают молча. Так и случилось в первой
редакции плана — поэтому семейства перечислены здесь данными, а незнакомое
семейство красит сверку поимённо, вместо того чтобы тихо выпасть из суммы.

Сборщик НИЧЕГО не перезаписывает: живой реестр он только читает, а черновик
кладёт отдельным файлом в рабочий каталог задачи. В `harness/config/` черновику
не место — этот каталог гейт сверки обязывает держать в пакете, и промежуточный
артефакт уехал бы в чужую установку.

Прогон:
    python3 scripts/sobrat-reestr-v2.py --сверка   # приёмка, ничего не пишет
    python3 scripts/sobrat-reestr-v2.py            # + черновик
Ручки (пути — данные, а не знание кода о дереве): HARNESS_KARTA_DATA,
HARNESS_USTROJSTVO, HARNESS_CHERNOVIK.
Код возврата: 0 — разбивка сошлась, 1 — расхождение названо поимённо.
"""
import json
import os
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))
from konf import корень_дерева  # noqa: E402

КОРЕНЬ = корень_дерева(__file__)
КАРТА = "docs/РАЗБОР-УСТРОЙСТВА-2026-09-12/karta-data.json"
РЕЕСТР = "harness/config/устройство.yaml"
ЧЕРНОВИК = ".tasks/hr.reestr-v2/устройство-v2.draft.yaml"

# Группы приёмки задания владельца (З-2) — ДАННЫЕ, а не разбор по месту.
# Семейство, которого здесь нет, не молчит: оно красит сверку по имени.
ГРУППЫ = {
    "механизмы": ("mech", "promote"),
    "правила": ("rule",),
    "скилы": ("skill", "skill-dom"),
    "слитые": ("proof", "wrap", "part"),
}
# Поля записи разбора: имя, семейство, контур, цель слияния, путь файла.
ИМЯ, СЕМЕЙСТВО, КОНТУР, ЦЕЛЬ, ПУТЬ = "n", "f", "c", "t", "p"


def путь(ручка: str, умолчание: str) -> Path:
    """Путь из окружения либо от корня установки. Окружение старше файла."""
    return Path(os.environ.get(ручка) or (КОРЕНЬ / умолчание))


def прочитать_разбор(источник: Path) -> list:
    try:
        записи = json.loads(источник.read_text(encoding="utf-8"))
    except OSError as беда:
        raise SystemExit(f"разбор не прочитан: {источник} — {беда}")
    except ValueError as беда:
        raise SystemExit(f"разбор не разобран: {источник} — {беда}")
    return записи if isinstance(записи, list) else записи.get("записи", [])


def прочитать_паспорта(источник: Path) -> list:
    try:
        реестр = yaml.safe_load(источник.read_text(encoding="utf-8")) or {}
    except OSError as беда:
        raise SystemExit(f"реестр не прочитан: {источник} — {беда}")
    return реестр.get("механизмы") or []


def разбивка(записи: list) -> tuple[dict, list]:
    """(сколько в каждой группе, записи незнакомых семейств)."""
    счёт = {группа: 0 for группа in ГРУППЫ}
    чужие = []
    for запись in записи:
        группа = next((имя for имя, семейства in ГРУППЫ.items()
                       if запись.get(СЕМЕЙСТВО) in семейства), None)
        if группа is None:
            чужие.append(запись)
        else:
            счёт[группа] += 1
    return счёт, чужие


def в_никуда(записи: list) -> list:
    """Записи, чья цель слияния не существует как запись разбора.

    Это НЕ дефект сборщика: цели живут среди механизмов, у которых ещё нет
    паспорта (спека фаза 2). Поэтому печатается честный список, а сверку он не
    красит — ноль здесь требуется после того, как паспорта заведены.
    """
    имена = {з.get(ИМЯ) for з in записи}
    return [з for з in записи if з.get(ЦЕЛЬ) and з.get(ЦЕЛЬ) not in имена]


def паспорт_из_записи(запись: dict) -> dict:
    """Черновой паспорт по записи разбора. Поля v1 — те, из которых печатается
    документ устройства; структурные добавит человек при вычитке черновика."""
    return {
        "файл": запись.get(ПУТЬ, ""),
        "вид": запись.get("k") or "гейт",
        "тема": запись.get(КОНТУР, ""),
        "имя": запись.get(ИМЯ, ""),
        "роль": запись.get("d", ""),
        "когда": запись.get("kog", ""),
        "без_него": запись.get("bez", ""),
        "проверяется": запись.get("pr", ""),
        "пишет": "",
    }


def черновик(записи: list, паспорта: list) -> dict:
    """Живые паспорта плюс механизмы разбора, которых в реестре ещё нет.

    Живой паспорт всегда старше черновика: его писали по уликам, а запись
    разбора — по описанию. Поэтому путь, уже описанный в реестре, повторно не
    заводится: два паспорта на один файл ломают инвариант ещё до заведения.
    """
    собрано = list(паспорта)
    занято = {з.get("файл") for з in паспорта}
    for запись in записи:
        if запись.get(СЕМЕЙСТВО) not in ГРУППЫ["механизмы"]:
            continue
        файл = запись.get(ПУТЬ)
        if not файл or файл in занято:
            continue
        собрано.append(паспорт_из_записи(запись))
        занято.add(файл)
    return {"механизмы": собрано}


def главная() -> int:
    только_сверка = "--сверка" in sys.argv[1:]
    записи = прочитать_разбор(путь("HARNESS_KARTA_DATA", КАРТА))
    паспорта = прочитать_паспорта(путь("HARNESS_USTROJSTVO", РЕЕСТР))

    счёт, чужие = разбивка(записи)
    сумма = sum(счёт.values())
    беды = []

    print(f"приёмка З-2: {len(записи)} = {счёт['механизмы']} + {счёт['правила']}"
          f" + {счёт['скилы']} + {счёт['слитые']}")
    print(f"  механизмы {счёт['механизмы']} · правила {счёт['правила']}"
          f" · скилы {счёт['скилы']} · слитые {счёт['слитые']}")
    if сумма != len(записи):
        беды.append(f"сумма групп {сумма} не равна числу записей {len(записи)}")
    for запись in чужие:
        беды.append(f"семейство «{запись.get(СЕМЕЙСТВО)}» вне перечня групп: "
                    f"запись «{запись.get(ИМЯ)}»")

    безродные = [з for з in записи if not з.get(КОНТУР)]
    print(f"без контура: {len(безродные)}")
    for запись in безродные:
        беды.append(f"без контура: 1 — запись «{запись.get(ИМЯ)}» "
                    f"не отнесена ни к одному контуру")

    потерянные = в_никуда(записи)
    цели = sorted({з.get(ЦЕЛЬ) for з in потерянные})
    print(f"слитых в никуда: {len(потерянные)} (целей {len(цели)})")
    for запись in потерянные:
        print(f"  «{запись.get(ИМЯ)}» → «{запись.get(ЦЕЛЬ)}» — цели нет среди записей")

    if беды:
        print("\nчерновик не собран: разбор не сошёлся")
        for строка in беды:
            print(f"  ✗ {строка}")
        return 1

    if только_сверка:
        return 0

    цель = путь("HARNESS_CHERNOVIK", ЧЕРНОВИК)
    цель.parent.mkdir(parents=True, exist_ok=True)
    цель.write_text(yaml.safe_dump(черновик(записи, паспорта), allow_unicode=True,
                                   sort_keys=False), encoding="utf-8")
    print(f"черновик собран: {цель}")
    return 0


if __name__ == "__main__":
    sys.exit(главная())
