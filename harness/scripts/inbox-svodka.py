#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Свод накопленных входящих: ОДИН сортированный список на рубеже.

Владелец 12.09.2026: «По завершению текущей задачи модель получает
сортированный скриптом по важности список, из которого принимает решения о
текущих действиях, изменениях в карте разработки и следующих действий».

Несрочное сообщение больше не пинает сессию (диспетчер решает это прибором
`srochnost.py`) — оно лежит в очереди канала, и его карточку заводит код
(`karta-iz-soobshcheniya.py`). Здесь эти накопленные сообщения собираются в
один список: что пришло, чем закончилось (карточка) и КАКОЕ МЕСТО эта работа
занимает в порядке.

Порядок не считается заново: его считает `ochered-raboty.py` по данным
`harness/config/очередь.yaml`. Второй сортировщик разошёлся бы с первым молча.

    inbox-svodka.py                # свод для рубежа (хук Stop)
    inbox-svodka.py --сколько      # одно число: сколько накоплено
    inbox-svodka.py --selftest
Код возврата 0 всегда: это прибор, а не гейт.
"""
import argparse
import sys
import time
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))
from konf import конфиг, корень_дерева  # noqa: E402
from sosed import модуль  # noqa: E402

ПОТОЛОК_СТРОК = 10          # длинный свод на рубеже никто не дочитает
ДЛИНА_КУСКА = 90


def накопленное(инбокс: Path, карта: Path, сейчас: float | None = None) -> list[dict]:
    """Что лежит в очереди канала непрочитанным, с исходом каждого."""
    сейчас = сейчас or time.time()
    гейт = модуль("zadachi-iz-kanala")
    сроч = модуль("srochnost")
    наст_срочности = сроч.данные()
    текст_карты = карта.read_text(encoding="utf-8") if карта.exists() else ""
    итог = []
    for ф in sorted(инбокс.glob("*.txt")):
        текст = гейт.текст_сообщения(ф)
        срочно, почему = сроч.срочно(текст, наст_срочности)
        итог.append({
            "id": ф.stem,
            "минут": int((сейчас - ф.stat().st_mtime) / 60),
            "срочно": срочно,
            "почему": почему,
            "работа": гейт.рабочее(текст),
            "кусок": (текст.replace("\n", " ")[:ДЛИНА_КУСКА] or "(без слов: вложение)"),
            "карточка": карточка_сообщения(текст_карты, ф.stem),
        })
    return итог


def карточка_сообщения(текст_карты: str, ид: str) -> str:
    """id карточки, заведённой из этого сообщения, либо пусто."""
    последний = ""
    for строка in текст_карты.splitlines():
        обрезка = строка.strip()
        if обрезка.startswith("- id:"):
            последний = обрезка.split(":", 1)[1].strip()
        if f"inbox:{ид}" in обрезка:
            return последний
    return ""


def места(карта: Path) -> dict:
    """{id задачи: её номер в порядке работы} — счёт ведёт ochered-raboty.py."""
    if not карта.exists():
        return {}
    очередь = модуль("ochered-raboty")
    данные = yaml.safe_load(карта.read_text(encoding="utf-8")) or {}
    наст = очередь.настройки()
    внимание = очередь.внимание_владельца(суток=наст.get("внимание_суток", 3))
    порядок = очередь.порядок(данные, настройки=наст, внимание=внимание)
    return {м["id"]: номер for номер, м in enumerate(порядок, 1)}


def свод(инбокс: Path, карта: Path, потолок: int = ПОТОЛОК_СТРОК,
         сейчас: float | None = None) -> list[str]:
    записи = накопленное(инбокс, карта, сейчас)
    if not записи:
        return []
    номера = места(карта)
    записи.sort(key=lambda з: (not з["срочно"],
                               номера.get(з["карточка"], 10 ** 6),
                               -float(з["id"] or 0)))
    срочных = sum(1 for з in записи if з["срочно"])
    строки = [f"входящие владельца: {len(записи)} не разобрано "
              f"(срочных {срочных}) — по важности:"]
    for номер, з in enumerate(записи[:потолок], 1):
        место = номера.get(з["карточка"])
        исход = (f"карточка {з['карточка']}"
                 + (f", №{место} в порядке работы" if место else "")
                 ) if з["карточка"] else (
                     "карточки нет" if з["работа"] else "работы в нём нет")
        метка = "СРОЧНО · " if з["срочно"] else ""
        строки.append(f"  {номер}. {метка}{з['минут']} мин назад · {з['id']} · "
                      f"«{з['кусок']}» — {исход}")
    if len(записи) > потолок:
        строки.append(f"  … и ещё {len(записи) - потолок}")
    строки.append(f"  прочитанное перенести в {инбокс}/обработано/")
    return строки


def _selftest() -> int:
    import tempfile
    плохо = 0

    def проба(имя: str, хорошо: bool) -> None:
        nonlocal плохо
        print(("  ок    " if хорошо else "  ПЛОХО ") + имя)
        плохо = плохо or not хорошо

    with tempfile.TemporaryDirectory() as врем:
        т = Path(врем)
        инбокс = т / "inbox"
        инбокс.mkdir()
        карта = т / "dev-map.yaml"
        карта.write_text(
            "version: 1\nqueue: []\nlayers:\n  - { id: infra, label: И, color: \"#1\" }\n"
            "lines:\n  - id: core\n    layer: infra\n    name: Ядро\n    tasks:\n"
            "      - id: hr.из-сообщения\n        status: plan\n"
            "        источник: inbox:100.0\n        title: Т\n        summary: с\n",
            encoding="utf-8")
        (инбокс / "100.0.txt").write_text("надо переделать экран карты", encoding="utf-8")
        (инбокс / "200.0.txt").write_text("срочно останови выкат", encoding="utf-8")
        (инбокс / "300.0.txt").write_text("спасибо", encoding="utf-8")

        строки = свод(инбокс, карта, сейчас=time.time())
        весь = "\n".join(строки)
        print("\n".join("      " + с for с in строки))
        # БОЛЬНОЙ СЛУЧАЙ: на рубеже агент видел «в inbox 3 файла» и шёл читать
        # их по одному, тратя ход. Свод обязан дать список, а не число.
        проба("БОЛЬНОЙ СЛУЧАЙ: свод показывает сами сообщения, а не счётчик",
              "переделать экран карты" in весь and "останови выкат" in весь)
        проба("срочное стоит первым", строки[1].startswith("  1. СРОЧНО"))
        проба("у сообщения с карточкой назван её id", "hr.из-сообщения" in весь)
        проба("у сообщения с работой без карточки сказано «карточки нет»",
              "карточки нет" not in весь)     # карточка есть у единственной работы
        проба("сообщение без работы названо таким", "работы в нём нет" in весь)
        проба("сказано, куда переносить прочитанное", "обработано" in весь)

        (инбокс / "100.0.txt").unlink()
        (инбокс / "200.0.txt").unlink()
        (инбокс / "300.0.txt").unlink()
        проба("пустая очередь — пустой свод (рубеж молчит)",
              свод(инбокс, карта) == [])

    if плохо:
        print("САМОТЕСТ ПРОВАЛЕН")
        return 1
    print("САМОТЕСТ ПРОЙДЕН: 7 путей, первым — больной случай")
    return 0


def main() -> int:
    разбор = argparse.ArgumentParser(add_help=True)
    разбор.add_argument("--инбокс")
    разбор.add_argument("--карта")
    разбор.add_argument("--сколько", action="store_true")
    разбор.add_argument("--сколько-срочных", dest="срочных", action="store_true")
    разбор.add_argument("--selftest", action="store_true")
    аргументы = разбор.parse_args()
    if аргументы.selftest:
        return _selftest()

    наст = конфиг()
    инбокс = Path(аргументы.инбокс or (Path(наст.get("LOG_DIR") or "/var/log/harness") / "inbox"))
    карта = Path(аргументы.карта or (Path(наст.get("PROJECT_DIR")
                                          or корень_дерева(__file__)) / "dev-map.yaml"))
    if not инбокс.is_dir() or not any(инбокс.glob("*.txt")):
        # Пустая очередь — ни чтения карты, ни счёта очереди: этот путь зовётся
        # в конце КАЖДОГО хода, и молчать он обязан дёшево.
        if аргументы.сколько or аргументы.срочных:
            print(0)
        return 0
    if аргументы.сколько:
        print(len(list(инбокс.glob("*.txt"))))
        return 0
    if аргументы.срочных:
        # Спрашивает сторож сессий: срочное будит смену, несрочное ждёт рубежа.
        print(sum(1 for з in накопленное(инбокс, карта) if з["срочно"]))
        return 0
    for строка in свод(инбокс, карта):
        print(строка)
    return 0


if __name__ == "__main__":
    sys.exit(main())
