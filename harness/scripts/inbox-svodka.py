def main() -> int:
    разбор = argparse.ArgumentParser(add_help=True)
    разбор.add_argument("--инбокс")
    разбор.add_argument("--карта")
    разбор.add_argument("--сколько", action="store_true")
    разбор.add_argument("--сколько-срочных", dest="срочных", action="store_true")
    разбор.add_argument("--selftest", action="store_true")
    разбор.add_argument("--деталь", nargs=2, metavar=("ИД-СООБЩЕНИЯ", "РОДИТЕЛЬ"),
                        help="прицепить сообщение пунктом к задаче-родителю")
    разбор.add_argument("--не-деталь", dest="не_деталь", metavar="РОДИТЕЛЬ",
                        help="запомнить, что эта задача родителем не является")
    аргументы = разбор.parse_args()
    if аргументы.selftest:
        return _selftest()

    наст = конфиг()
    инбокс = Path(аргументы.инбокс or (Path(наст.get("LOG_DIR") or "/var/log/harness") / "inbox"))
    карта = Path(аргументы.карта or (Path(наст.get("PROJECT_DIR")
                                          or корень_дерева(__file__)) / "dev-map.yaml"))
    корень = Path(наст.get("PROJECT_DIR") or корень_дерева(__file__))
    if аргументы.не_деталь:
        return отказать_в_родстве(аргументы.не_деталь, корень)
    if аргументы.деталь:
        ид_сообщения, родитель = аргументы.деталь
        файлы = list(инбокс.glob(f"{ид_сообщения}.txt")) + \
            list((инбокс / "обработано").glob(f"{ид_сообщения}.txt"))
        if not файлы:
            print(f"сообщения {ид_сообщения} нет ни в очереди, ни в обработано/")
            return 1
        текст = файлы[0].read_text(encoding="utf-8", errors="replace")
        return прицепить_деталь(ид_сообщения, родитель, текст, карта, корень)

    if not инбокс.is_dir() or not any(инбокс.glob("*.txt")):
        # Пустая очередь — ни чтения карты, ни счёта очереди: этот путь зовётся
        # в конце КАЖДОГО хода, и молчать он обязан дёшево.
        if аргументы.сколько or аргументы.срочных:
            print(0)
        return 0
    if аргументы.сколько:
        print(len(list(инбокс.glob("*.txt"))))
        return 0
    if аргументы.срочных:
        # Спрашивает сторож сессий: срочное будит смену, несрочное ждёт рубежа.
        print(sum(1 for з in накопленное(инбокс, карта) if з["срочно"]))
        return 0
    for строка in свод(инбокс, карта):
        print(строка)
    return 0


if __name__ == "__main__":
    sys.exit(main())
