ПОТОЛОК_СТРОК = 10          # длинный свод на рубеже никто не дочитает
ДЛИНА_КУСКА = 90


def накопленное(инбокс: Path, карта: Path, сейчас: float | None = None) -> list[dict]:
    """Что лежит в очереди канала непрочитанным, с исходом каждого."""
    сейчас = сейчас or time.time()
    гейт = модуль("zadachi-iz-kanala")
    сроч = модуль("srochnost")
    наст_срочности = сроч.данные()
    текст_карты = карта.read_text(encoding="utf-8") if карта.exists() else ""
    итог = []
    for ф in sorted(инбокс.glob("*.txt")):
        текст = гейт.текст_сообщения(ф)
        срочно, почему = сроч.срочно(текст, наст_срочности)
        итог.append({
            "id": ф.stem,
            "минут": int((сейчас - ф.stat().st_mtime) / 60),
            "срочно": срочно,
            "почему": почему,
            "работа": гейт.рабочее(текст),
            "кусок": (текст.replace("\n", " ")[:ДЛИНА_КУСКА] or "(без слов: вложение)"),
            # Полный текст нужен поиску родителя: по обрезке в 90 знаков
            # совпадение слов считалось бы по началу сообщения, а суть
            # владелец часто дописывает в конце.
            "полный": текст,
            "карточка": карточка_сообщения(текст_карты, ф.stem),
        })
    return итог


def карточка_сообщения(текст_карты: str, ид: str) -> str:
    """id карточки, заведённой из этого сообщения, либо пусто."""
    последний = ""
    for строка in текст_карты.splitlines():
        обрезка = строка.strip()
        if обрезка.startswith("- id:"):
            последний = обрезка.split(":", 1)[1].strip()
        if f"inbox:{ид}" in обрезка:
            return последний
    return ""


# Слова короче пяти букв не различают темы: «карта», «панель», «задача» —
# каждое второе сообщение. Считаем пересечение по значимым словам.
ДЛИНА_ЗНАЧИМОГО = 5
ПОРОГ_РОДСТВА = 2           # меньше двух общих слов — совпадение случайно
СПУТНИК_ОТКАЗОВ = "память/.детали-разобрано"


def _значимые(текст: str) -> set:
    return {с.strip(".,:;!?»«()—-").lower()
            for с in str(текст or "").split()
            if len(с.strip(".,:;!?»«()—-")) >= ДЛИНА_ЗНАЧИМОГО}


def родитель_кандидат(текст: str, карта: Path, отказы: set = frozenset()) -> tuple:
    """Чья это деталь → (id задачи, сколько общих слов) либо ("", 0).

    Владелец 13.09.2026: «всякие задачи которые я пишу они мелкие могут быть по
    сути, но являться частью большой разработки <…> вместо того чтобы
    объеденить в большую задачу как комментарий к ней». Улика той же ночи: из
    пяти карточек, заведённых автоматом, три были деталями идущих задач и
    сливались РУКАМИ — то есть держались на памяти смены.

    Кандидат ищется среди задач в работе и в плане; идущая работа (`wip`)
    получает преимущество при равном числе общих слов, потому что деталь чаще
    всего относится к тому, что делается прямо сейчас.
    """
    if not карта.exists():
        return "", 0
    данные = yaml.safe_load(карта.read_text(encoding="utf-8")) or {}
    слова = _значимые(текст)
    лучший, счёт, лучший_wip = "", 0, False
    for линия in данные.get("lines") or []:
        for задача in линия.get("tasks") or []:
            если_статус = задача.get("status")
            if если_статус not in ("wip", "plan"):
                continue
            ид = задача.get("id") or ""
            if ид in отказы:
                continue
            общие = слова & _значимые(f"{задача.get('title')} {задача.get('summary')}")
            это_wip = если_статус == "wip"
            лучше = len(общие) > счёт or (len(общие) == счёт and это_wip and not лучший_wip)
            if общие and лучше:
                лучший, счёт, лучший_wip = ид, len(общие), это_wip
    return (лучший, счёт) if счёт >= ПОРОГ_РОДСТВА else ("", 0)


def отказы_родства(корень: Path) -> set:
    """Кого уже решили НЕ цеплять: иначе свод предлагает одно и то же вечно."""
    путь = корень / СПУТНИК_ОТКАЗОВ
    try:
        return {с.strip() for с in путь.read_text(encoding="utf-8").splitlines() if с.strip()}
    except OSError:
        return set()


def _лок(корень: Path) -> Path:
    """Тот же общий лок, что берут остальные писатели карты (гейт следит)."""
    из_конфига = конфиг()
    журнал = Path(из_конфига.get("LOG_DIR") or "/var/log/harness")
    под = из_конфига.get("SERVICE_LOCKS_SUBDIR") or "services"
    return журнал / "locks" / под / "dev-map.lock"


def прицепить_деталь(ид_сообщения: str, родитель: str, текст: str,
                     карта: Path, корень: Path) -> int:
    """Пункт в чеклист родителя вместо отдельной карточки.

    Карта правится под ОБЩИМ локом dev-map.lock и сверяется разбором YAML:
    число задач обязано остаться прежним, а у родителя — вырасти чеклист.
    Улика жанра 09.09.2026: жадное регулярное выражение съело 88 задач, и
    YAML остался валидным.
    """
    import fcntl
    лок = _лок(корень)
    лок.parent.mkdir(parents=True, exist_ok=True)
    with open(лок, "a", encoding="utf-8") as замок:
        fcntl.flock(замок, fcntl.LOCK_EX)
        было_текст = карта.read_text(encoding="utf-8")
        было = yaml.safe_load(было_текст) or {}
        задачи_было = {з.get("id") for л in было.get("lines") or []
                       for з in л.get("tasks") or []}
        if родитель not in задачи_было:
            print(f"родителя «{родитель}» нет в карте")
            return 1
        # Экранируется и обратный слэш: YAML в двойных кавычках понимает \n,
        # и путь вида C:\\users или регулярка \\s роняли разбор необработанным
        # ScannerError (ревью кода 13.09, C-3).
        кусок = (текст.strip()
                 .replace("\\", "/")
                 .replace('"', "'")
                 .replace("\n", " ")[:300])
        пункт = (f'          - {{ label: "Владелец 13.09: «{кусок}»", done: false, '
                 f'источник: "inbox:{ид_сообщения}" }}\n')
        строки = было_текст.splitlines(keepends=True)
        куда, отступ_карточки = None, None
        for номер, строка in enumerate(строки):
            if строка.strip().startswith("- id:") and строка.split(":", 1)[1].strip() == родитель:
                отступ_карточки = len(строка) - len(строка.lstrip())
                continue
            if отступ_карточки is None:
                continue
            отступ = len(строка) - len(строка.lstrip())
            if строка.strip().startswith("checklist:") and отступ == отступ_карточки + 2:
                куда = номер + 1
                break
            # Дошли до следующей карточки — у родителя чеклиста не было.
            if строка.strip().startswith("- id:") and отступ <= отступ_карточки:
                строки[номер:номер] = [" " * (отступ_карточки + 2) + "checklist:\n"]
                куда = номер + 1
                break
        # Родитель оказался ПОСЛЕДНЕЙ карточкой файла и чеклиста не имел:
        # цикл кончился, следующей карточки не встретив. Дописываем в конец —
        # без этой ветки деталь было некуда прицепить (ревью кода 13.09, C-2).
        if куда is None and отступ_карточки is not None:
            строки.append(" " * (отступ_карточки + 2) + "checklist:\n")
            куда = len(строки)
        if куда is None:
            print(f"не нашёл, куда вписать пункт у «{родитель}»")
            return 1
        строки[куда:куда] = [пункт]
        стало_текст = "".join(строки)
        стало = yaml.safe_load(стало_текст) or {}
        задачи_стало = {з.get("id") for л in стало.get("lines") or []
                        for з in л.get("tasks") or []}
        if задачи_стало != задачи_было:
            print(f"ОТКАЗ: правка изменила состав задач "
                  f"({len(задачи_было)} → {len(задачи_стало)}) — карта не тронута")
            return 1
        карта.write_text(стало_текст, encoding="utf-8")
    print(f"деталь прицеплена к «{родитель}»: пункт в чеклисте, карточка не заведена")
    return 0


def отказать_в_родстве(родитель: str, корень: Path) -> int:
    """Запомнить отказ: иначе свод предложит того же родителя завтра снова."""
    путь = корень / СПУТНИК_ОТКАЗОВ
    путь.parent.mkdir(parents=True, exist_ok=True)
    с_отказами = отказы_родства(корень) | {родитель}
    путь.write_text("\n".join(sorted(с_отказами)) + "\n", encoding="utf-8")
    print(f"«{родитель}» больше не предлагается родителем")
    return 0


def места(карта: Path) -> dict:
    """{id задачи: её номер в порядке работы} — счёт ведёт ochered-raboty.py."""
    if not карта.exists():
        return {}
    очередь = модуль("ochered-raboty")
    данные = yaml.safe_load(карта.read_text(encoding="utf-8")) or {}
    наст = очередь.настройки()
    внимание = очередь.внимание_владельца(суток=наст.get("внимание_суток", 3))
    порядок = очередь.порядок(данные, настройки=наст, внимание=внимание)
    return {м["id"]: номер for номер, м in enumerate(порядок, 1)}


def свод(инбокс: Path, карта: Path, потолок: int = ПОТОЛОК_СТРОК,
         сейчас: float | None = None) -> list[str]:
    записи = накопленное(инбокс, карта, сейчас)
    if not записи:
        return []
    номера = места(карта)
    отказы = отказы_родства(Path(конфиг().get("PROJECT_DIR") or корень_дерева(__file__)))
    записи.sort(key=lambda з: (not з["срочно"],
                               номера.get(з["карточка"], 10 ** 6),
                               -float(з["id"] or 0)))
    срочных = sum(1 for з in записи if з["срочно"])
    строки = [f"входящие владельца: {len(записи)} не разобрано "
              f"(срочных {срочных}) — по важности:"]
    for номер, з in enumerate(записи[:потолок], 1):
        место = номера.get(з["карточка"])
        исход = (f"карточка {з['карточка']}"
                 + (f", №{место} в порядке работы" if место else "")
                 ) if з["карточка"] else (
                     "карточки нет" if з["работа"] else "работы в нём нет")
        метка = "СРОЧНО · " if з["срочно"] else ""
        строки.append(f"  {номер}. {метка}{з['минут']} мин назад · {з['id']} · "
                      f"«{з['кусок']}» — {исход}")
        # Деталь большой работы вместо отдельной мелкой задачи (владелец
        # 13.09.2026). Предлагается, а не решается: цеплять или нет — решает
        # смена, но ЗАБЫТЬ об этом больше нельзя, предложение стоит в своде.
        родитель, общих = родитель_кандидат(з.get("полный") or з["кусок"], карта, отказы)
        if родитель and родитель != з["карточка"]:
            строки.append(f"       похоже на деталь «{родитель}» ({общих} общих слов): "
                          f"inbox-svodka.py --деталь {з['id']} {родитель} "
                          f"| --не-деталь {родитель}")
    if len(записи) > потолок:
        строки.append(f"  … и ещё {len(записи) - потолок}")
    строки.append(f"  прочитанное перенести в {инбокс}/обработано/")
    return строки


