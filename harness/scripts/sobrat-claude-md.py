#!/usr/bin/env python3
"""Собирает CLAUDE.md пакета — правила для ЛЮБОГО проекта, по-английски.

Откуда взят: 12.09.2026. Владелец о файле, который едет каждому, кто ставит
харнес: «убрать всё лишнее, иметь ввиду что это чистый фаил для случайного
пользователя для любого проекта <…> перевести на английский для экономии
токенов, сделать более актуальным, сделать его тоже автоматически
актуализирующимся, но оставить все основные принципы».

Отсюда устройство: неизменные принципы живут в шаблоне
(harness/шаблоны-задач/CLAUDE-EN.md.in), а то, что стареет — чем держится
каждый инвариант и сколько в системе механизмов, — подставляется ИЗ ДАННЫХ
(harness/config/инварианты.yaml, harness/config/устройство.yaml) при каждой
сборке. Руками файл не правят: правка уедет при следующей сборке, и гейт
check-claude-md.py её увидит.

Английский — не вкус, а цена: файл грузится в КАЖДУЮ сессию, а русский текст
стоит примерно вдвое больше токенов на тот же смысл.

    python3 scripts/sobrat-claude-md.py            # собрать
    python3 scripts/sobrat-claude-md.py --проверить  # собранное совпадает? (гейт)
"""
import sys
from pathlib import Path

import yaml

НАЧАЛО = "<!-- AUTO:{имя} -->"
КОНЕЦ = "<!-- /AUTO -->"


def корень() -> Path:
    """Пакет держит шаблон в harness/шаблоны-задач, проект — там же; сам скрипт
    лежит в harness/scripts (пакет) или scripts (проект)."""
    for каталог in Path(__file__).resolve().parents:
        if (каталог / "harness" / "шаблоны-задач" / "CLAUDE-EN.md.in").exists():
            return каталог / "harness"
        if (каталог / "шаблоны-задач" / "CLAUDE-EN.md.in").exists():
            return каталог
    sys.exit("sobrat-claude-md: шаблон CLAUDE-EN.md.in не найден")


ВИДЫ_EN = {"гейт": "gates", "демон": "daemons", "скил": "skills", "хук": "hooks"}


def без_повторов(значения) -> list:
    """Порядок сохраняется: set() перетасовал бы строки, и файл менялся бы от
    сборки к сборке — гейт сравнения стал бы случайным."""
    видели, итог = set(), []
    for значение in значения:
        if значение not in видели:
            видели.add(значение)
            итог.append(значение)
    return итог


def таблица_инвариантов(данные: dict) -> str:
    """Строка на инвариант: чем держится и чем проверяется — из данных покрытия.
    Формулировка по-английски лежит рядом с русской, в том же файле."""
    названия = данные.get("названия_en") or {}
    группы: dict = {}
    for запись in данные.get("инварианты") or []:
        ключ = "-".join(запись["id"].split("-")[:2])
        if not ключ.startswith("И-"):
            continue
        группы.setdefault(ключ, []).append(запись)

    строки = ["| # | invariant | held by | how to check the guard |",
              "|---|---|---|---|"]
    for ключ in sorted(группы):
        # Один сторож держит несколько строк покрытия — в таблице он нужен
        # один раз: повтор читается как два разных носителя.
        файлы = " · ".join(f"`{ф}`" for ф in без_повторов(
            з["файл"] for з in группы[ключ]))
        проверки = " · ".join(f"`{к}`" for к in без_повторов(
            з["доказательство"] for з in группы[ключ] if з.get("доказательство")))
        строки.append(f"| {ключ} | {названия.get(ключ, '—')} | {файлы} | "
                      f"{проверки or '—'} |")
    return "\n".join(строки)


def счёт_механизмов(реестр: dict) -> str:
    виды: dict = {}
    for запись in реестр.get("механизмы") or []:
        виды[запись.get("вид", "?")] = виды.get(запись.get("вид", "?"), 0) + 1
    всего = sum(виды.values())
    порядок = ", ".join(f"{ВИДЫ_EN.get(вид, вид)} — {число}"
                        for вид, число in sorted(виды.items()))
    return (f"{всего} mechanisms are registered in `harness/config/устройство.yaml` "
            f"({порядок}). Each one names what it does, when it runs, what breaks "
            f"without it and the command that proves it works. The registry is "
            f"data: `python3 scripts/check-ustrojstvo.py` fails when the code and "
            f"the registry disagree.")


def подставить(текст: str, имя: str, содержимое: str) -> str:
    начало, конец = НАЧАЛО.format(имя=имя), КОНЕЦ
    i = текст.index(начало) + len(начало)
    j = текст.index(конец, i)
    return текст[:i] + "\n" + содержимое + "\n" + текст[j:]


def собрать(база: Path) -> str:
    шаблон = (база / "шаблоны-задач" / "CLAUDE-EN.md.in").read_text(encoding="utf-8")
    инварианты = yaml.safe_load(
        (база / "config" / "инварианты.yaml").read_text(encoding="utf-8")) or {}
    реестр = yaml.safe_load(
        (база / "config" / "устройство.yaml").read_text(encoding="utf-8")) or {}
    текст = подставить(шаблон, "invariants", таблица_инвариантов(инварианты))
    return подставить(текст, "mechanisms", счёт_механизмов(реестр))


def главная() -> int:
    база = корень()
    цель = база / "CLAUDE.md"
    собранное = собрать(база)
    if "--проверить" in sys.argv[1:]:
        сейчас = цель.read_text(encoding="utf-8") if цель.exists() else ""
        if сейчас == собранное:
            print(f"[claude.md] собранный файл совпадает с данными ({len(собранное)} знаков)")
            return 0
        print("[claude.md] ✗ файл разошёлся с данными: правили руками или данные "
              "изменились. Починка: python3 scripts/sobrat-claude-md.py")
        return 1
    цель.write_text(собранное, encoding="utf-8")
    print(f"{цель}: собран, {len(собранное)} знаков")
    return 0


if __name__ == "__main__":
    sys.exit(главная())
