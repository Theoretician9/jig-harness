#!/usr/bin/env python3
"""Проверка сверки скилов с главами: ловит ли она отставшую копию.

Откуда взято. Владелец 12.09.2026 спросил, как и когда генерируются скилы, —
и вопрос вскрыл дыру: генератор зовут КОМАНДОЙ, а гейта «скил отстал от
главы» не было. Поправил главу, забыл перегенерировать — агент работает по
устаревшему правилу и уверен, что прав.

Проверять приходится на подставном дереве: портить живые скилы нельзя, а
«сегодня совпадает» ничего не доказывает — нужно, чтобы механизм КРАСНЕЛ на
испорченной копии.

Прогон:
    python3 scripts/test_sborka_skilov.py
Код возврата: 0 — все пути прошли, 1 — есть упавший.
"""
import importlib.util
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
путей = неудач = 0


def путь_ок(текст: str) -> None:
    global путей
    путей += 1
    print("ок  · " + текст)


def путь_плохо(текст: str) -> None:
    global путей, неудач
    путей += 1
    неудач += 1
    print("ПЛОХО · " + текст)


спец = importlib.util.spec_from_file_location(
    "сборка_скилов", КОРЕНЬ / "harness" / "SBORKA-SKILOV.py")
сборка = importlib.util.module_from_spec(спец)
спец.loader.exec_module(сборка)

главы = сборка.find_chapters_dir()
собрано = сборка.render(главы)
двор = Path(tempfile.mkdtemp(prefix="скилы-"))

try:
    print("── здоровый: диск совпадает с главами ──")
    сборка.write_atomic(собрано, двор / "skills")
    if сборка.sverit(собрано, двор / "skills") == []:
        путь_ок(f"свежесобранные {len(собрано)} скилов расхождений не дают")
    else:
        путь_плохо(f"свежая сборка уже разошлась: {сборка.sverit(собрано, двор / 'skills')[:2]}")

    print("── БОЛЬНОЙ: скил на диске отстал от главы ──")
    имя = sorted(собрано)[0]
    файл = двор / "skills" / имя / "SKILL.md"
    файл.write_text(файл.read_text(encoding="utf-8").replace("Когда", "КОГДА", 1),
                    encoding="utf-8")
    беды = сборка.sverit(собрано, двор / "skills")
    if any(имя in б and "не то" in б for б in беды):
        путь_ок(f"правка одного знака в «{имя}» поймана")
    else:
        путь_плохо(f"отставший скил не пойман: {беды}")

    print("── БОЛЬНОЙ: скила нет на диске вовсе ──")
    shutil.rmtree(двор / "skills" / имя)
    беды = сборка.sverit(собрано, двор / "skills")
    if any(имя in б and "нет" in б for б in беды):
        путь_ок(f"пропавший «{имя}» пойман")
    else:
        путь_плохо(f"пропажа скила не поймана: {беды}")

    print("── БОЛЬНОЙ: лишний каталог, которого нет ни в одной главе ──")
    сборка.write_atomic(собрано, двор / "skills")
    (двор / "skills" / "самодельный").mkdir()
    (двор / "skills" / "самодельный" / "SKILL.md").write_text("---\nname: x\n---\n",
                                                              encoding="utf-8")
    беды = сборка.sverit(собрано, двор / "skills")
    if any("самодельный" in б for б in беды):
        путь_ок("скил, написанный руками мимо глав, пойман")
    else:
        путь_плохо(f"самодельный скил не пойман: {беды}")

    print("── боевой путь: команда гейта на живом дереве ──")
    # Зовём ТАК ЖЕ, как ворота: отдельным процессом, по коду возврата.
    готово = subprocess.run([sys.executable, str(КОРЕНЬ / "harness" / "SBORKA-SKILOV.py"),
                             "--сверить"], capture_output=True, text=True, timeout=120)
    if готово.returncode == 0 and "совпадают с главами" in готово.stdout:
        путь_ок("на живом дереве гейт зелёный и говорит это словами")
    else:
        путь_плохо(f"живой прогон: код {готово.returncode}, {готово.stdout[-200:]}")
finally:
    shutil.rmtree(двор, ignore_errors=True)

print(f"\nитого путей {путей}, неудач {неудач}")
sys.exit(1 if неудач else 0)
