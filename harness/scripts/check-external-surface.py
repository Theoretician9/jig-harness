#!/usr/bin/env python3
"""Что у нас торчит наружу: слушатели + прокси + разбор Host.

СЛУЧАЙ (ревью спеки ревизии, 28.09.2026, находка 4). Мера «кто слушает наружу»
слепа к главному пути: панель слушает `127.0.0.1:8787` — снаружи её как будто
нет, — а nginx отдаёт её в мир строкой `proxy_pass`. И второе: если ни один
блок `sites-enabled` не объявлен `default_server`, nginx отвечает ПЕРВЫМ по
алфавиту блоком на ЛЮБОЙ `Host:` ([[the-first-nginx-block-answers-for-all]]).
То есть внешняя поверхность = слушатели ПЛЮС прокси, и судить их надо вместе.

Что прибор говорит:

* **наш порт наружу** — слушатель на `0.0.0.0`/`[::]`, чей процесс наш
  (по корню проекта в командной строке): это находка, её надо объяснить;
* **чужой порт** — сосед по машине: НАЗЫВАЕМ и не правим (решение владельца);
* **прокси на наш порт** — какой `server_name` и есть ли `default_server`;
* **нет разбора Host** — ни одного `default_server` в `sites-enabled`.

Машинная зависимость названа, а не спрятана: нет `/proc/net/tcp` или каталога
nginx — исход «не применимо» с честной строкой, а не молчаливая зелень
(харнес уходит в публичный гит, спека §1 и §3.1).

    python3 scripts/check-external-surface.py            # отчёт по машине
    python3 scripts/check-external-surface.py --selftest # пробы на стенде
    python3 scripts/check-external-surface.py --убрать-мусор-смены  # снять порты, оставленные сменой
        [--корень-proc DIR] [--только-назвать]   # подмена /proc; ничего не убивать
Код возврата: 0 — наружу ничего нашего без объяснения; 1 — есть находка;
77 — ни одного источника данных нет (не применимо).
"""
from __future__ import annotations

import contextlib
import io
import ipaddress
import os
import re
import signal
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))
import config as конф                                    # noqa: E402

СЛУШАЕТ = "0A"                      # TCP_LISTEN в /proc/net/tcp
НЕ_ПРИМЕНИМО = 77                   # третье состояние гейта (обкатка, §3.2)
ВОЗРАСТ_МУСОРА_МИН = 120            # запасное значение SHIFT_LEFTOVER_MIN_AGE_MIN
МЕТКИ_НЕ_ТРОГАТЬ = "/дерево/,/tmp/proba-"   # запасное значение SHIFT_LEFTOVER_KEEP
ПУТИ_NGINX = ("/etc/nginx/sites-enabled",)
# Местный адрес судится РАЗБОРОМ, а не списком из двух строк: systemd-resolved
# слушает 127.0.0.53, а 127.0.0.54 — это другая строка, и список называл их
# «видно снаружи». Петля — вся сеть 127.0.0.0/8 и ::1 (улика 03.10.2026:
# замер с чужих адресов пошёл спрашивать интернет про порт 53).


def слушатели(корень_proc: Path = Path("/proc")) -> list[dict]:
    """Слушающие сокеты: адрес, порт, inode. Пусто, если таблиц нет."""
    итог = []
    for имя in ("net/tcp", "net/tcp6"):
        try:
            строки = (корень_proc / имя).read_text(encoding="utf-8").splitlines()[1:]
        except OSError:
            continue
        for строка in строки:
            поля = строка.split()
            if len(поля) < 10 or поля[3] != СЛУШАЕТ:
                continue
            адрес, порт = поля[1].split(":")
            итог.append({"адрес": адрес.upper(), "порт": int(порт, 16),
                         "inode": поля[9], "uid": int(поля[7]), "таблица": имя})
    return итог


def адрес_сокета(шестнадцатеричный: str):
    """Адрес из /proc/net/tcp: байты идут словами по 4, внутри слова — задом
    наперёд. Непонятную строку возвращаем как None: «не разобрали» ≠ «местный»."""
    try:
        байты = bytes.fromhex(шестнадцатеричный)
    except ValueError:
        return None
    if len(байты) == 4:
        return ipaddress.ip_address(байты[::-1])
    if len(байты) == 16:
        return ipaddress.ip_address(
            b"".join(байты[и:и + 4][::-1] for и in range(0, 16, 4)))
    return None


def наружу(запись: dict) -> bool:
    """Слушатель виден снаружи? Петля (127.0.0.0/8, ::1) не видна."""
    адрес = адрес_сокета(запись["адрес"])
    return адрес is None or not адрес.is_loopback


def хозяин_сокета(inode: str, корень_proc: Path = Path("/proc")) -> dict | None:
    """(pid, команда) процесса, держащего сокет, либо None — прав не хватило.

    «Не видно» и «никого нет» — разные ответы: под обычным пользователем чужие
    /proc/<pid>/fd закрыты, и молчание здесь означало бы «порт бесхозный»
    ([[unreadable-source-turns-check-green]]).
    """
    цель = f"socket:[{inode}]"
    for каталог in корень_proc.iterdir():
        if not каталог.name.isdigit():
            continue
        try:
            ссылки = [os.readlink(файл) for файл in (каталог / "fd").iterdir()]
        except OSError:
            continue
        if цель in ссылки:
            try:
                строка = (каталог / "cmdline").read_bytes().replace(b"\0", b" ")
            except OSError:
                строка = b""
            return {"pid": int(каталог.name),
                    "команда": строка.decode("utf-8", "replace").strip()}
    return None


def наш_процесс(команда: str, корень_проекта: str) -> bool:
    """Процесс наш, если его командная строка ведёт в дерево проекта."""
    return bool(корень_проекта) and корень_проекта in команда


def мусор_смены(запись: dict, хозяин: dict, корень_проекта: str,
                объявлено: dict[int, str]) -> bool:
    """Кандидат: слушатель наружу от нашего пользователя, без корня проекта и не
    объявленный. Одного этого мало для беды: под тем же uid идут чужие пробы и
    прогоны мутаций, поэтому возраст и сиротство судит разбор_смены/цель_уборки.
    Владельца судим по uid из таблицы сокетов, а не по stat() каталога /proc —
    на стенде stat врёт."""
    return (запись["uid"] == os.getuid()
            and запись["порт"] not in объявлено
            and not наш_процесс(хозяин["команда"], корень_проекта))


def такты_старта(корень_proc: Path, pid: int) -> int | None:
    """Поле 22 /proc/<pid>/stat. Имя процесса в скобках может содержать пробелы
    и скобки, поэтому режем по ПОСЛЕДНЕЙ «)»."""
    try:
        текст = (корень_proc / str(pid) / "stat").read_text(encoding="utf-8")
        return int(текст.rpartition(")")[2].split()[19])
    except (OSError, ValueError, IndexError):
        return None


def возраст_сек(корень_proc: Path, pid: int) -> float | None:
    """Возраст процесса; None — не прочитан (не «ноль» и не «старый»)."""
    старт = такты_старта(корень_proc, pid)
    try:
        работает = float((корень_proc / "uptime").read_text().split()[0])
        return работает - старт / os.sysconf("SC_CLK_TCK") if старт is not None else None
    except (OSError, ValueError, IndexError):
        return None


def родитель(корень_proc: Path, pid: int) -> int | None:
    """PPid из /proc/<pid>/status; None — не прочитан."""
    try:
        for строка in (корень_proc / str(pid) / "status").read_text(
                encoding="utf-8").splitlines():
            if строка.startswith("PPid:"):
                return int(строка.split()[1])
    except (OSError, ValueError, IndexError):
        pass
    return None


def сирота(корень_proc: Path, pid: int) -> tuple[bool, int | None]:
    """(сирота ли, pid родителя). Сирота — родитель init, systemd-пользователя
    или уже мёртв: за процессом никто не следит. Родитель не прочитан — не сирота:
    без улики не убиваем."""
    ppid = родитель(корень_proc, pid)
    if ppid is None:
        return False, None
    if ppid == 1 or not (корень_proc / str(ppid)).exists():
        return True, ppid
    try:
        имя = (корень_proc / str(ppid) / "comm").read_text(encoding="utf-8").strip()
    except OSError:
        имя = ""
    return имя == "systemd", ppid


def разбор_смены(запись: dict, хозяин: dict, корень_проекта: str,
                 объявлено: dict[int, str], корень_proc: Path,
                 мин_возраст_мин: float) -> dict | None:
    """None — не кандидат. Иначе вид: «мусор» (старше порога или равен),
    «свежий» (идёт проба или работа исполнителя), «не_виден» (возраст не прочитан)."""
    if not мусор_смены(запись, хозяин, корень_проекта, объявлено):
        return None
    возраст = возраст_сек(корень_proc, хозяин["pid"])
    if возраст is None:
        return {"вид": "не_виден", "возраст_мин": None}
    вид = "мусор" if возраст >= мин_возраст_мин * 60 else "свежий"
    return {"вид": вид, "возраст_мин": int(возраст // 60)}


def хозяева_наружу(корень_proc: Path):
    """(запись, хозяин или None) по слушателям наружу; один сокет — один раз.
    Сливаем по inode, а не по порту: иначе нечитаемая или чужая запись порта
    прятала бы нашего слушателя на том же порту."""
    видели: set[str] = set()
    for запись in слушатели(корень_proc):
        if not наружу(запись) or запись["inode"] in видели:
            continue
        видели.add(запись["inode"])
        yield запись, хозяин_сокета(запись["inode"], корень_proc)


