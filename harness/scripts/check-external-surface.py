#!/usr/bin/env python3
"""Что у нас торчит наружу: слушатели + прокси + разбор Host.

СЛУЧАЙ (ревью спеки ревизии, 28.09.2026, находка 4). Мера «кто слушает наружу»
слепа к главному пути: панель слушает `127.0.0.1:8787` — снаружи её как будто
нет, — а nginx отдаёт её в мир строкой `proxy_pass`. И второе: если ни один
блок `sites-enabled` не объявлен `default_server`, nginx отвечает ПЕРВЫМ по
алфавиту блоком на ЛЮБОЙ `Host:` ([[the-first-nginx-block-answers-for-all]]).
То есть внешняя поверхность = слушатели ПЛЮС прокси, и судить их надо вместе.

Что прибор говорит:

* **наш порт наружу** — слушатель на `0.0.0.0`/`[::]`, чей процесс наш
  (по корню проекта в командной строке): это находка, её надо объяснить;
* **чужой порт** — сосед по машине: НАЗЫВАЕМ и не правим (решение владельца);
* **прокси на наш порт** — какой `server_name` и есть ли `default_server`;
* **нет разбора Host** — ни одного `default_server` в `sites-enabled`.

Машинная зависимость названа, а не спрятана: нет `/proc/net/tcp` или каталога
nginx — исход «не применимо» с честной строкой, а не молчаливая зелень
(харнес уходит в публичный гит, спека §1 и §3.1).

    python3 scripts/check-external-surface.py            # отчёт по машине
    python3 scripts/check-external-surface.py --selftest # пробы на стенде
Код возврата: 0 — наружу ничего нашего без объяснения; 1 — есть находка;
77 — ни одного источника данных нет (не применимо).
"""
from __future__ import annotations

import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))
import config as конф                                    # noqa: E402

СЛУШАЕТ = "0A"                      # TCP_LISTEN в /proc/net/tcp
НЕ_ПРИМЕНИМО = 77                   # третье состояние гейта (обкатка, §3.2)
ПУТИ_NGINX = ("/etc/nginx/sites-enabled",)
# Локальные адреса в шестнадцатеричном виде /proc/net/tcp: 127.0.0.1 и ::1.
МЕСТНЫЕ = {"0100007F", "00000000000000000000000001000000"}


def слушатели(корень_proc: Path = Path("/proc")) -> list[dict]:
    """Слушающие сокеты: адрес, порт, inode. Пусто, если таблиц нет."""
    итог = []
    for имя in ("net/tcp", "net/tcp6"):
        try:
            строки = (корень_proc / имя).read_text(encoding="utf-8").splitlines()[1:]
        except OSError:
            continue
        for строка in строки:
            поля = строка.split()
            if len(поля) < 10 or поля[3] != СЛУШАЕТ:
                continue
            адрес, порт = поля[1].split(":")
            итог.append({"адрес": адрес.upper(), "порт": int(порт, 16),
                         "inode": поля[9], "таблица": имя})
    return итог


def наружу(запись: dict) -> bool:
    """Слушатель виден снаружи? Локальные адреса не видны."""
    return запись["адрес"] not in МЕСТНЫЕ


def хозяин_сокета(inode: str, корень_proc: Path = Path("/proc")) -> dict | None:
    """(pid, команда) процесса, держащего сокет, либо None — прав не хватило.

    «Не видно» и «никого нет» — разные ответы: под обычным пользователем чужие
    /proc/<pid>/fd закрыты, и молчание здесь означало бы «порт бесхозный»
    ([[unreadable-source-turns-check-green]]).
    """
    цель = f"socket:[{inode}]"
    for каталог in корень_proc.iterdir():
        if not каталог.name.isdigit():
            continue
        try:
            ссылки = [os.readlink(файл) for файл in (каталог / "fd").iterdir()]
        except OSError:
            continue
        if цель in ссылки:
            try:
                строка = (каталог / "cmdline").read_bytes().replace(b"\0", b" ")
            except OSError:
                строка = b""
            return {"pid": int(каталог.name),
                    "команда": строка.decode("utf-8", "replace").strip()}
    return None


def наш_процесс(команда: str, корень_проекта: str) -> bool:
    """Процесс наш, если его командная строка ведёт в дерево проекта."""
    return bool(корень_проекта) and корень_проекта in команда


def блоки_nginx(каталог: Path) -> list[dict]:
    """Блоки server из файлов каталога: server_name, listen, proxy_pass.

    Разбор простой нарочно: нужен не полный парсер nginx, а три признака.
    Файл, который не читается, назван отдельно — «не прочли» ≠ «пусто».
    """
    итог = []
    try:
        файлы = sorted(п for п in каталог.iterdir() if п.is_file() or п.is_symlink())
    except OSError:
        return итог
    for файл in файлы:
        try:
            текст = файл.read_text(encoding="utf-8", errors="replace")
        except OSError:
            итог.append({"файл": файл.name, "не_прочли": True})
            continue
        for кусок in re.split(r"\bserver\s*\{", текст)[1:]:
            тело = кусок.split("\n}")[0]
            итог.append({
                "файл": файл.name,
                "server_name": [и for и in re.findall(
                    r"^\s*server_name\s+([^;]+);", тело, re.M)],
                "listen": [и.strip() for и in re.findall(
                    r"^\s*listen\s+([^;]+);", тело, re.M)],
                # Без привязки к началу строки: `location / { proxy_pass …; }`
                # — обычная форма, и первая редакция пробы её не видела.
                "proxy_pass": [и.strip() for и in re.findall(
                    r"proxy_pass\s+([^;]+);", тело)],
            })
    return итог


def порты_проксирования(блоки: list[dict]) -> dict[int, list[str]]:
    """Порт → файлы блоков, которые на него проксируют."""
    итог: dict[int, list[str]] = {}
    for блок in блоки:
        for цель in блок.get("proxy_pass", []):
            найдено = re.search(r":(\d+)", цель)
            if найдено:
                итог.setdefault(int(найдено.group(1)), []).append(блок["файл"])
    return итог


def порт_из_listen(строка: str) -> int | None:
    """Порт из строки listen: «443 ssl», «[::]:80 default_server», «8080»."""
    найдено = re.search(r"(?:^|:)(\d+)", строка.strip())
    return int(найдено.group(1)) if найдено else None


def порты_без_default_server(блоки: list[dict]) -> list[int]:
    """Порты, на которых nginx слушает, но ни один блок не назван default_server.

    Судим по ПОРТУ, а не по всему каталогу: на 443 default_server объявлен
    (`000-default-ssl`), а на любом новом порту его может не быть — и там снова
    ответит первый блок по алфавиту.
    """
    слушают: dict[int, bool] = {}
    for блок in блоки:
        for строка in блок.get("listen", []):
            порт = порт_из_listen(строка)
            if порт is None:
                continue
            слушают[порт] = слушают.get(порт, False) or "default_server" in строка
    return sorted(порт for порт, объявлен in слушают.items() if not объявлен)


def объявленные_порты(конфиг: dict | None = None) -> dict[int, str]:
    """Порты, отданные наружу НАМЕРЕННО: данные, а не список в коде.

    Ключ harness.conf: EXTERNAL_SURFACE_DECLARED="8787=harness-panel,…".
    """
    значение = (конфиг or {}).get("EXTERNAL_SURFACE_DECLARED", "") or ""
    итог = {}
    for кусок in значение.replace(";", ",").split(","):
        кусок = кусок.strip()
        if not кусок:
            continue
        порт, _, зачем = кусок.partition("=")
        if порт.strip().isdigit():
            итог[int(порт.strip())] = зачем.strip() or "объявлено без пояснения"
    return итог


def находки(корень_proc: Path, каталог_nginx: Path | None,
            корень_проекта: str,
            объявлено: dict[int, str] | None = None
            ) -> tuple[list[str], list[str], bool]:
    """(находки, описанное чужое, был ли хоть один источник данных)."""
    беды: list[str] = []
    чужое: list[str] = []
    объявлено = объявлено or {}
    источник = False

    слушают = слушатели(корень_proc)
    if (корень_proc / "net/tcp").exists() or (корень_proc / "net/tcp6").exists():
        источник = True
    наши_порты_наружу = set()
    # Один порт слушается и по IPv4, и по IPv6: без слияния живой прогон печатал
    # 14 строк про 7 портов, и читатель тонул в повторах.
    видели: set[int] = set()
    for запись in слушают:
        if not наружу(запись) or запись["порт"] in видели:
            continue
        видели.add(запись["порт"])
        хозяин = хозяин_сокета(запись["inode"], корень_proc)
        if хозяин is None:
            чужое.append(f"порт {запись['порт']}: слушает наружу, хозяин не виден "
                         f"(нужен root) — чей это процесс, решает владелец")
            continue
        if наш_процесс(хозяин["команда"], корень_проекта):
            наши_порты_наружу.add(запись["порт"])
            строка = (f"порт {запись['порт']} слушает НАРУЖУ наш процесс "
                      f"(pid {хозяин['pid']}): {хозяин['команда'][:80]}")
            if запись["порт"] in объявлено:
                чужое.append(f"наше объявленное: {строка} — "
                             f"{объявлено[запись['порт']]}")
            else:
                беды.append(строка)
        else:
            чужое.append(f"порт {запись['порт']}: чужой процесс "
                         f"{хозяин['команда'][:60]} — называем, не правим")

    if каталог_nginx is not None and каталог_nginx.is_dir():
        источник = True
        блоки = блоки_nginx(каталог_nginx)
        for блок in блоки:
            if блок.get("не_прочли"):
                беды.append(f"nginx: файл {блок['файл']} не прочитан — "
                            f"внешняя поверхность измерена не полностью")
        прокси = порты_проксирования(блоки)
        местные_наши = {з["порт"] for з in слушают if not наружу(з)}
        for порт, файлы in sorted(прокси.items()):
            if порт not in местные_наши and порт not in наши_порты_наружу:
                continue
            строка = (f"порт {порт} отдан наружу через nginx "
                      f"({', '.join(sorted(set(файлы)))})")
            if порт in объявлено:
                чужое.append(f"наше объявленное: {строка} — {объявлено[порт]}")
            else:
                беды.append(f"{строка} — проверь, что так и задумано")
        for порт in порты_без_default_server(блоки):
            беды.append(f"nginx: на порту {порт} ни один блок не объявлен "
                        f"default_server — на чужой Host отвечает первый "
                        f"по алфавиту")
    return беды, чужое, источник


def отчёт(корень_proc: Path, каталог_nginx: Path | None, корень_проекта: str,
          объявлено: dict[int, str] | None = None) -> int:
    беды, чужое, источник = находки(корень_proc, каталог_nginx, корень_проекта,
                                    объявлено)
    if not источник:
        print("[внешняя поверхность] не применимо: нет ни /proc/net/tcp, "
              "ни каталога nginx — мерить нечем")
        return НЕ_ПРИМЕНИМО
    for строка in чужое:
        print(f"[внешняя поверхность] чужое: {строка}")
    if not беды:
        print("[внешняя поверхность] чисто: наших портов наружу нет, "
              f"разбор Host объявлен (чужих слушателей: {len(чужое)})")
        return 0
    for строка in беды:
        print(f"[внешняя поверхность] ✗ {строка}")
    print(f"[внешняя поверхность] находок: {len(беды)}")
    return 1


# ── самотест: стенд, а не боевая машина ─────────────────────────────────────
def _стенд(каталог: Path, адрес: str, порт: int, inode: str = "111",
           хозяин: str | None = None) -> Path:
    """Поддельный /proc: таблица слушателей и, если задан, хозяин сокета.

    Хозяин нужен затем, что «кто держит порт» прибор читает из /proc/<pid>/fd;
    стенд без него доказывал бы только ветку «хозяин не виден».
    """
    сеть = каталог / "net"
    сеть.mkdir(parents=True, exist_ok=True)
    if хозяин is not None:
        fd = каталог / "4242" / "fd"
        fd.mkdir(parents=True, exist_ok=True)
        ссылка = fd / "0"
        if not ссылка.is_symlink():
            os.symlink(f"socket:[{inode}]", ссылка)
        (каталог / "4242" / "cmdline").write_bytes(хозяин.encode("utf-8") + b"\0")
    (сеть / "tcp").write_text(
        "  sl  local_address rem_address   st tx_queue rx_queue tr tm->when "
        "retrnsmt   uid  timeout inode\n"
        f"   0: {адрес}:{порт:04X} 00000000:0000 {СЛУШАЕТ} 00000000:00000000 "
        f"00:00000000 00000000     0        0 {inode} 1 0000 100 0 0 10 0\n",
        encoding="utf-8")
    return каталог


def селфтест() -> int:
    import tempfile
    ok = True

    def проба(условие: bool, имя: str):
        nonlocal ok
        print(f"  {'ок   ' if условие else 'ПЛОХО'} {имя}")
        ok = ok and условие

    with tempfile.TemporaryDirectory() as врем:
        врем = Path(врем)

        # БОЛЬНОЙ СЛУЧАЙ 1: панель слушает только localhost, а nginx отдаёт её
        # наружу — прежняя мера «кто слушает 0.0.0.0» этого не видела вовсе.
        proc = _стенд(врем / "proc-местный", "0100007F", 8787)
        nginx = врем / "nginx-прокси"
        nginx.mkdir()
        (nginx / "panel").write_text(
            "server {\n  listen 443 ssl;\n  server_name panel.example;\n"
            "  location / { proxy_pass http://127.0.0.1:8787; }\n}\n",
            encoding="utf-8")
        беды, _, источник = находки(proc, nginx, "/нет-такого-корня")
        проба(источник, "источник данных найден")
        проба(any("8787 отдан наружу через nginx" in б for б in беды),
              "БОЛЬНОЙ СЛУЧАЙ: местный порт, отданный наружу прокси, назван")
        проба(any("default_server" in б for б in беды),
              "БОЛЬНОЙ СЛУЧАЙ: нет разбора Host — сказано вслух")

        # Тот же прокси, но default_server объявлен — про Host молчим.
        (nginx / "panel").write_text(
            "server {\n  listen 443 ssl default_server;\n"
            "  server_name panel.example;\n"
            "  location / { proxy_pass http://127.0.0.1:8787; }\n}\n",
            encoding="utf-8")
        беды, _, _ = находки(proc, nginx, "/нет-такого-корня")
        проба(not any("default_server" in б for б in беды),
              "объявленный default_server претензии снимает")

        # Чужой слушатель наружу: называем, но это НЕ находка.
        proc_чужой = _стенд(врем / "proc-чужой", "00000000", 6380, inode="222")
        беды, чужое, _ = находки(proc_чужой, None, "/нет-такого-корня")
        проба(беды == [], "чужой порт наружу не считается нашей находкой")
        проба(len(чужое) == 1 and "6380" in чужое[0],
              "чужой порт НАЗВАН, а не пропущен молча")

        # Ни одного источника данных — «не применимо», а не зелень.
        пусто = врем / "proc-пустой"
        (пусто / "net").mkdir(parents=True)
        беды, _, источник = находки(пусто, None, "/нет-такого-корня")
        проба(not источник, "БОЛЬНОЙ СЛУЧАЙ: мерить нечем — это «не применимо»")
        проба(отчёт(пусто, None, "/нет-такого-корня") == НЕ_ПРИМЕНИМО,
              "код возврата «не применимо» — 77, а не 0")

        # Нечитаемый файл nginx: «не прочли» ≠ «пусто».
        закрытый = врем / "nginx-закрытый"
        закрытый.mkdir()
        (закрытый / "site").write_text("server {\n  listen 80;\n}\n", encoding="utf-8")
        (закрытый / "site").chmod(0)
        беды, _, _ = находки(proc, закрытый, "/нет-такого-корня")
        (закрытый / "site").chmod(0o644)
        if os.geteuid() == 0:
            print("  —     ПРОПУСК 1 путь: от root chmod 0 не держит")
        else:
            проба(any("не прочитан" in б for б in беды),
                  "БОЛЬНОЙ СЛУЧАЙ: нечитаемый файл nginx — находка, а не тишина")

        # БОЛЬНОЙ СЛУЧАЙ: default_server объявлен на 443, а на 8080 — нет.
        смешанный = врем / "nginx-смешанный"
        смешанный.mkdir()
        (смешанный / "000-default").write_text(
            "server {\n  listen 443 ssl default_server;\n  server_name _;\n}\n",
            encoding="utf-8")
        (смешанный / "new-port").write_text(
            "server {\n  listen 8080;\n  server_name new.example;\n"
            "  location / { proxy_pass http://127.0.0.1:8787; }\n}\n",
            encoding="utf-8")
        беды, _, _ = находки(proc, смешанный, "/нет-такого-корня")
        проба(any("на порту 8080 ни один блок не объявлен" in б for б in беды),
              "БОЛЬНОЙ СЛУЧАЙ: разбор Host судится ПО ПОРТУ, а не по каталогу")
        проба(not any("на порту 443" in б for б in беды),
              "порт с объявленным default_server претензии не получает")

        # Объявленное в данных: панель отдана наружу намеренно — не находка,
        # но и не молчание: строка «наше объявленное» остаётся в отчёте.
        беды, чужое, _ = находки(proc, nginx, "/нет-такого-корня",
                                 {8787: "harness-panel, так задумано"})
        проба(беды == [] and any("наше объявленное" in с for с in чужое),
              "объявленный в данных порт назван, но ворота не красит")
        проба(объявленные_порты({"EXTERNAL_SURFACE_DECLARED": "8787=панель, 9090"})
              == {8787: "панель", 9090: "объявлено без пояснения"},
              "разбор объявленных портов из данных")

        # БОЛЬНОЙ СЛУЧАЙ: наш процесс слушает 0.0.0.0 — находка с pid и командой.
        proc_наш = _стенд(врем / "proc-наш", "00000000", 9999, inode="333",
                          хозяин="python3 /корень-стенда/scripts/panel.py")
        беды, чужое, _ = находки(proc_наш, None, "/корень-стенда")
        проба(any("порт 9999 слушает НАРУЖУ наш процесс" in б for б in беды),
              "БОЛЬНОЙ СЛУЧАЙ: наш процесс на 0.0.0.0 — находка с pid")
        проба(any("pid 4242" in б for б in беды),
              "в находке назван pid — чинить есть что")
        # Тот же сокет, но процесс чужой: называем, находкой не считаем.
        proc_сосед = _стенд(врем / "proc-сосед", "00000000", 9999, inode="444",
                            хозяин="/usr/sbin/pure-ftpd")
        беды, чужое, _ = находки(proc_сосед, None, "/корень-стенда")
        проба(беды == [] and any("чужой процесс" in с for с in чужое),
              "сосед на 0.0.0.0 назван чужим, а не нашей бедой")

    if ok:
        print("SELFTEST: зелёный (15 путей, первым — больной случай "
              "«местный порт отдан наружу прокси»)")
        return 0
    print("SELFTEST: КРАСНЫЙ")
    return 1


def главная(аргументы: list[str]) -> int:
    if аргументы[:1] == ["--selftest"]:
        return селфтест()
    корень_проекта = str(Path(__file__).resolve().parent.parent)
    каталог = next((Path(п) for п in ПУТИ_NGINX if Path(п).is_dir()), None)
    # Ключ живёт в harness.conf (пороги механики), а конфиг() без пути читает
    # install.conf (паспорт установки) — и объявленные порты остались бы пустыми.
    try:
        настройки = конф.конфиг(конф.путь_harness_conf())
    except Exception:                       # noqa: BLE001 — нет конфига: судим без него
        настройки = {}
    return отчёт(Path("/proc"), каталог, корень_проекта,
                 объявленные_порты(настройки))


