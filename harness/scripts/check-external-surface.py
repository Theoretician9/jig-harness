def порог_возраста_мин(настройки: dict) -> float:
    try:
        return float(настройки.get("SHIFT_LEFTOVER_MIN_AGE_MIN") or ВОЗРАСТ_МУСОРА_МИН)
    except ValueError:
        return ВОЗРАСТ_МУСОРА_МИН


def не_трогать_метки(настройки: dict) -> list[str]:
    значение = настройки.get("SHIFT_LEFTOVER_KEEP") or МЕТКИ_НЕ_ТРОГАТЬ
    return [м.strip() for м in значение.split(",") if м.strip()]


def блоки_nginx(каталог: Path) -> list[dict]:
    """Блоки server из файлов каталога: server_name, listen, proxy_pass.

    Разбор простой нарочно: нужен не полный парсер nginx, а три признака.
    Файл, который не читается, назван отдельно — «не прочли» ≠ «пусто».
    """
    итог = []
    try:
        файлы = sorted(п for п in каталог.iterdir() if п.is_file() or п.is_symlink())
    except OSError:
        return итог
    for файл in файлы:
        try:
            текст = файл.read_text(encoding="utf-8", errors="replace")
        except OSError:
            итог.append({"файл": файл.name, "не_прочли": True})
            continue
        for кусок in re.split(r"\bserver\s*\{", текст)[1:]:
            тело = кусок.split("\n}")[0]
            итог.append({
                "файл": файл.name,
                "server_name": [и for и in re.findall(
                    r"^\s*server_name\s+([^;]+);", тело, re.M)],
                "listen": [и.strip() for и in re.findall(
                    r"^\s*listen\s+([^;]+);", тело, re.M)],
                # Без привязки к началу строки: `location / { proxy_pass …; }`
                # — обычная форма, и первая редакция пробы её не видела.
                "proxy_pass": [и.strip() for и in re.findall(
                    r"proxy_pass\s+([^;]+);", тело)],
            })
    return итог


def порты_проксирования(блоки: list[dict]) -> dict[int, list[str]]:
    """Порт → файлы блоков, которые на него проксируют."""
    итог: dict[int, list[str]] = {}
    for блок in блоки:
        for цель in блок.get("proxy_pass", []):
            найдено = re.search(r":(\d+)", цель)
            if найдено:
                итог.setdefault(int(найдено.group(1)), []).append(блок["файл"])
    return итог


def порт_из_listen(строка: str) -> int | None:
    """Порт из строки listen: «443 ssl», «[::]:80 default_server», «8080»."""
    найдено = re.search(r"(?:^|:)(\d+)", строка.strip())
    return int(найдено.group(1)) if найдено else None


def порты_без_default_server(блоки: list[dict]) -> list[int]:
    """Порты, на которых nginx слушает, но ни один блок не назван default_server.

    Судим по ПОРТУ, а не по всему каталогу: на 443 default_server объявлен
    (`000-default-ssl`), а на любом новом порту его может не быть — и там снова
    ответит первый блок по алфавиту.
    """
    слушают: dict[int, bool] = {}
    for блок in блоки:
        for строка in блок.get("listen", []):
            порт = порт_из_listen(строка)
            if порт is None:
                continue
            слушают[порт] = слушают.get(порт, False) or "default_server" in строка
    return sorted(порт for порт, объявлен in слушают.items() if not объявлен)


def объявленные_порты(конфиг: dict | None = None) -> dict[int, str]:
    """Порты, отданные наружу НАМЕРЕННО: данные, а не список в коде.

    Ключ harness.conf: EXTERNAL_SURFACE_DECLARED="8787=harness-panel,…".
    """
    значение = (конфиг or {}).get("EXTERNAL_SURFACE_DECLARED", "") or ""
    итог = {}
    for кусок in значение.replace(";", ",").split(","):
        кусок = кусок.strip()
        if not кусок:
            continue
        порт, _, зачем = кусок.partition("=")
        if порт.strip().isdigit():
            итог[int(порт.strip())] = зачем.strip() or "объявлено без пояснения"
    return итог


def находки(корень_proc: Path, каталог_nginx: Path | None,
            корень_проекта: str,
            объявлено: dict[int, str] | None = None,
            мин_возраст_мин: float = ВОЗРАСТ_МУСОРА_МИН
            ) -> tuple[list[str], list[str], bool]:
    """(находки, описанное чужое, был ли хоть один источник данных)."""
    беды: list[str] = []
    чужое: list[str] = []
    объявлено = объявлено or {}
    источник = False

    слушают = слушатели(корень_proc)
    if (корень_proc / "net/tcp").exists() or (корень_proc / "net/tcp6").exists():
        источник = True
    наши_порты_наружу = set()
    # Один процесс слушает и по IPv4, и по IPv6: без слияния живой прогон печатал
    # 14 строк про 7 портов. Слияние только для печати: судим каждый сокет.
    видели: set[tuple] = set()
    for запись, хозяин in хозяева_наружу(корень_proc):
        порт = запись["порт"]
        if хозяин is None:
            if ("?", порт) not in видели:
                видели.add(("?", порт))
                чужое.append(f"порт {порт}: слушает наружу, хозяин не виден "
                             f"(нужен root) — чей это процесс, решает владелец")
            continue
        pid = хозяин["pid"]
        if наш_процесс(хозяин["команда"], корень_проекта):
            наши_порты_наружу.add(порт)
            if ("наш", pid, порт) in видели:
                continue
            видели.add(("наш", pid, порт))
            строка = (f"порт {порт} слушает НАРУЖУ наш процесс "
                      f"(pid {pid}): {хозяин['команда'][:80]}")
            if порт in объявлено:
                чужое.append(f"наше объявленное: {строка} — {объявлено[порт]}")
            else:
                беды.append(строка)
            continue
        if ("чужой", pid) in видели:
            continue
        видели.add(("чужой", pid))
        разбор = разбор_смены(запись, хозяин, корень_проекта, объявлено,
                              корень_proc, мин_возраст_мин)
        if разбор is None:
            чужое.append(f"порт {порт}: чужой процесс "
                         f"{хозяин['команда'][:60]} — называем, не правим")
        elif разбор["вид"] == "не_виден":
            чужое.append(f"порт {порт}: слушатель нашего пользователя вне проекта "
                         f"(pid {pid}), возраст не виден — не мусор и не цель уборки")
        elif разбор["вид"] == "свежий":
            чужое.append(f"порт {порт}: свежий слушатель смены (pid {pid}, "
                         f"возраст {разбор['возраст_мин']} мин) — не беда")
        else:
            беды.append(f"порт {порт}: мусор смены — {хозяин['команда'][:80]} "
                        f"(pid {pid}, возраст {разбор['возраст_мин']} мин)")

    if каталог_nginx is not None and каталог_nginx.is_dir():
        источник = True
        блоки = блоки_nginx(каталог_nginx)
        for блок in блоки:
            if блок.get("не_прочли"):
                беды.append(f"nginx: файл {блок['файл']} не прочитан — "
                            f"внешняя поверхность измерена не полностью")
        прокси = порты_проксирования(блоки)
        местные_наши = {з["порт"] for з in слушают if not наружу(з)}
        for порт, файлы in sorted(прокси.items()):
            if порт not in местные_наши and порт not in наши_порты_наружу:
                continue
            строка = (f"порт {порт} отдан наружу через nginx "
                      f"({', '.join(sorted(set(файлы)))})")
            if порт in объявлено:
                чужое.append(f"наше объявленное: {строка} — {объявлено[порт]}")
            else:
                беды.append(f"{строка} — проверь, что так и задумано")
        for порт in порты_без_default_server(блоки):
            беды.append(f"nginx: на порту {порт} ни один блок не объявлен "
                        f"default_server — на чужой Host отвечает первый "
                        f"по алфавиту")
    return беды, чужое, источник


def отчёт(корень_proc: Path, каталог_nginx: Path | None, корень_проекта: str,
          объявлено: dict[int, str] | None = None,
          мин_возраст_мин: float = ВОЗРАСТ_МУСОРА_МИН) -> int:
    беды, чужое, источник = находки(корень_proc, каталог_nginx, корень_проекта,
                                    объявлено, мин_возраст_мин)
    if not источник:
        print("[внешняя поверхность] не применимо: нет ни /proc/net/tcp, "
              "ни каталога nginx — мерить нечем")
        return НЕ_ПРИМЕНИМО
    for строка in чужое:
        print(f"[внешняя поверхность] чужое: {строка}")
    if not беды:
        print("[внешняя поверхность] чисто: наших портов наружу нет, "
              f"разбор Host объявлен (чужих слушателей: {len(чужое)})")
        return 0
    for строка in беды:
        print(f"[внешняя поверхность] ✗ {строка}")
    print(f"[внешняя поверхность] находок: {len(беды)}")
    return 1


def _снять(pid: int) -> bool:
    """SIGTERM: True — сигнал послан. KILL не шлём: это решение владельца."""
    try:
        os.kill(pid, signal.SIGTERM)
    except OSError:
        return False
    return True


def _ушёл(корень_proc: Path, pid: int, ждать_сек: float) -> bool:
    """Сигнал ≠ смерть: снятым считаем только процесс, чей каталог исчез."""
    конец = time.monotonic() + ждать_сек
    while (корень_proc / str(pid)).exists():
        if time.monotonic() >= конец:
            return False
        time.sleep(0.1)
    return True


def убрать_мусор_смены(корень_proc: Path, корень_проекта: str,
                       объявлено: dict[int, str] | None = None,
                       убийца=None, мин_возраст_мин: float | None = None,
                       не_трогать: list[str] | None = None,
                       ждать_сек: float = 5.0,
                       только_назвать: bool = False,
                       наш_uid: int | None = None) -> int:
    """Снять процессы-«мусор смены»: старый (порог), сирота, без меток
    SHIFT_LEFTOVER_KEEP в команде. Число ушедших; остальных называем по pid.
    Параметры по умолчанию берутся из harness.conf."""
    # От root «наш uid» — это все системные службы: сирота uid 0 бывает nginx или sshd.
    if (os.getuid() if наш_uid is None else наш_uid) == 0:
        print("уборка от root не снимает ничего: наш uid 0 — это системные службы")
        return 0
    объявлено = объявлено or {}
    if мин_возраст_мин is None or не_трогать is None:
        настройки = настройки_харнеса()
        мин_возраст_мин = (порог_возраста_мин(настройки)
                           if мин_возраст_мин is None else мин_возраст_мин)
        не_трогать = не_трогать_метки(настройки) if не_трогать is None else не_трогать
    убийца = убийца or _снять
    снято = целей = 0
    видели: set[int] = set()
    for запись, хозяин in хозяева_наружу(корень_proc):
        if хозяин is None or хозяин["pid"] in видели:
            continue
        pid, порт = хозяин["pid"], запись["порт"]
        старт = такты_старта(корень_proc, pid)
        разбор = разбор_смены(запись, хозяин, корень_проекта, объявлено,
                              корень_proc, мин_возраст_мин)
        if разбор is None or разбор["вид"] != "мусор":
            continue
        видели.add(pid)
        осиротел, ppid = сирота(корень_proc, pid)
        метка = next((м for м in не_трогать if м in хозяин["команда"]), None)
        if not осиротел:
            print(f"мусор смены не снят: родитель жив (pid {ppid if ppid is not None else '?'})"
                  f" — порт {порт}, pid {pid}")
            continue
        if метка is not None:
            print(f"мусор смены не снят: метка «{метка}» из SHIFT_LEFTOVER_KEEP"
                  f" — порт {порт}, pid {pid}")
            continue
        целей += 1
        if только_назвать:
            print(f"снял бы: pid {pid} порт {порт}")
            continue
        if старт is None or старт != такты_старта(корень_proc, pid):
            print(f"мусор смены не снят: pid {pid} сменил хозяина — порт {порт}")
            continue
        if not убийца(pid):
            print(f"мусор смены не снят: сигнал pid {pid} не послан — порт {порт}")
            continue
        if not _ушёл(корень_proc, pid, ждать_сек):
            print(f"мусор смены не снят: pid {pid} не ушёл за {ждать_сек:g} с — порт {порт}")
            continue
        снято += 1
    итог = (f"снято мусора смены: 0 (только назвать, целей {целей})"
            if только_назвать else f"снято мусора смены: {снято}")
    print(итог)
    return снято


# ── самотест: стенд, а не боевая машина ─────────────────────────────────────
def _стенд(каталог: Path, адрес: str, порт: int, inode: str = "111",
           хозяин: str | None = None, uid: int = 0, ppid: int = 1,
           возраст_сек: float | None = None) -> Path:
    """Поддельный /proc: таблица слушателей и, если задан, хозяин сокета.

    Хозяин нужен затем, что «кто держит порт» прибор читает из /proc/<pid>/fd;
    стенд без него доказывал бы только ветку «хозяин не виден». Возраст не задан —
    stat и uptime не пишутся: так проверяется ветка «возраст не виден».
    ppid больше 1 — живой родитель (каталог с comm bash).
    """
    сеть = каталог / "net"
    сеть.mkdir(parents=True, exist_ok=True)
    if хозяин is not None:
        fd = каталог / "4242" / "fd"
        fd.mkdir(parents=True, exist_ok=True)
        ссылка = fd / "0"
        if not ссылка.is_symlink():
            os.symlink(f"socket:[{inode}]", ссылка)
        (каталог / "4242" / "cmdline").write_bytes(хозяин.encode("utf-8") + b"\0")
        (каталог / "4242" / "status").write_text(
            f"Name:\tpython3\nUid:\t{uid}\t{uid}\t{uid}\t{uid}\nPPid:\t{ppid}\n",
            encoding="utf-8")
        if ppid > 1:
            (каталог / str(ppid)).mkdir(exist_ok=True)
            (каталог / str(ppid) / "comm").write_text("bash\n", encoding="utf-8")
        if возраст_сек is not None:
            работает = 100000.0
            такты = int((работает - возраст_сек) * os.sysconf("SC_CLK_TCK"))
            (каталог / "uptime").write_text(f"{работает:.2f} 0.00\n", encoding="utf-8")
            (каталог / "4242" / "stat").write_text(
                f"4242 (python3 (x)) S {ppid} " + " ".join(["0"] * 17) + f" {такты} 0\n",
                encoding="utf-8")
    (сеть / "tcp").write_text(
        "  sl  local_address rem_address   st tx_queue rx_queue tr tm->when "
        "retrnsmt   uid  timeout inode\n"
        f"   0: {адрес}:{порт:04X} 00000000:0000 {СЛУШАЕТ} 00000000:00000000 "
        f"00:00000000 00000000 {uid:5d}        0 {inode} 1 0000 100 0 0 10 0\n",
        encoding="utf-8")
    return каталог


def селфтест() -> int:
    import shutil
    import tempfile
    ok = True
    путей = 0

    def проба(условие: bool, имя: str):
        nonlocal ok, путей
        путей += 1
        print(f"  {'ок   ' if условие else 'ПЛОХО'} {имя}")
        ok = ok and условие

    with tempfile.TemporaryDirectory() as врем:
        врем = Path(врем)

        # БОЛЬНОЙ СЛУЧАЙ 1: панель слушает только localhost, а nginx отдаёт её
        # наружу — прежняя мера «кто слушает 0.0.0.0» этого не видела вовсе.
        proc = _стенд(врем / "proc-местный", "0100007F", 8787)
        nginx = врем / "nginx-прокси"
        nginx.mkdir()
