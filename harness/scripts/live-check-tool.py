#!/usr/bin/env python3
"""Живая проверка инструмента или библиотеки: позван с настоящим входом.

Откуда взято: спека `docs/specs/2026-10-15-живая-проверка-механизмов.md` §3.1,
класс C2 — «вызван с настоящим входом, вывод прочитан и записан». Носителя этому
предикату в коде не было, и 24 механизма класса оставались непроверенными:
доказательством служило бы слово проверяющего.

Почему команда берётся ИЗ ДАННЫХ, а не из паспорта механизма. В реестре поле
«проверяется» смешано с прозой («python3 x.py (12 путей, первым больной)»), и
разбор прозы однажды позвал бы не то — у соседа по семье (`live-check-sick.py`)
команда тоже лежит в своих данных. Нет команды в данных — отказ со своим словом.

Почему отказ механизма не записывается как «ок». Инструмент, который на
здоровой машине отвечает ненулевым кодом, — это косяк: его называет сам прибор,
а исход ставит проверяющий, разобравшись (И-4).

Почему нужна цитата от 12 знаков. У молчащего механизма цитировать нечего, и
запись доказывалась бы моим эхом вместо чужого текста (находка 17.10.2026,
карточка `hr.mehanizm-otvechaet-tolko-kodom`).

Запуск:
    python3 scripts/live-check-tool.py <механизм> [<механизм>…] [--записать]
    python3 scripts/live-check-tool.py --всё [--записать]
Код возврата: 0 — живой вызов доказан у всех названных, 1 — хоть у одного нет.

Чем доказан: scripts/test_live_check_tool.py (больным случаем первым — механизм,
отказавший на здоровой машине).
"""
from __future__ import annotations

import datetime
import fcntl
import json
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile

import yaml

КОРЕНЬ = pathlib.Path(os.environ.get("HARNESS_LIVE_CHECK_REPO")
                      or pathlib.Path(__file__).resolve().parent.parent)
РЕЕСТР = pathlib.Path(os.environ.get("HARNESS_MECHANISMS")
                      or КОРЕНЬ / "harness" / "config" / "mechanisms.yaml")
КЛАССЫ = pathlib.Path(os.environ.get("HARNESS_LIVE_CHECK_CLASSES")
                      or КОРЕНЬ / "harness" / "config" / "live-check-classes.yaml")
СОСТОЯНИЕ = pathlib.Path(os.environ.get("HARNESS_LIVE_CHECK_STATE")
                         or КОРЕНЬ / "harness" / "config" / "live-check-state.yaml")
КОМАНДЫ = pathlib.Path(os.environ.get("HARNESS_LIVE_CHECK_COMMANDS")
                       or КОРЕНЬ / "harness" / "config" / "live-check-commands.yaml")
# Умолчание каталога следов НЕЙТРАЛЬНОЕ: id карточки этой установки в коде был
# её следом, а в заготовке карты пакета такой карточки нет вовсе (та же находка
# у обёртки, ревью 17.10). Свой каталог задачи задаётся переменной при зове.
СЛЕДЫ = pathlib.Path(os.environ.get("HARNESS_LIVE_CHECK_TOOL_TRACE_DIR")
                     or КОРЕНЬ / ".tasks" / "живая-проверка" / "живьём")

КЛАСС = "C2"
# Приставка поля «живьём» у записей ЭТОГО прибора: по ней он отличает своё
# прежнее доказательство от чужого и не затирает чужое.
ПРИСТАВКА = "позван своей командой из данных живой проверки"
# Столько знаков делают цитату доказательством: короче — это общее слово
# («ок», «чисто»), какое найдётся в любом выводе (спека §3.2 п. 2).
ЦИТАТА_ЗНАКОВ = 12
ШАПКА_КОНЕЦ = "--- вывод механизма ---"


def данные(путь: pathlib.Path, ключ: str) -> dict:
    """Содержимое носителя. Нет файла — ПУСТО с именем ключа у вызывающего:
    «не прочитали» он отличает сам, потому что отказывает поимённо."""
    if not путь.exists():
        return {}
    прочитано = yaml.safe_load(путь.read_text(encoding="utf-8")) or {}
    return прочитано.get(ключ) or {}


def классы() -> dict:
    return данные(КЛАССЫ, "классы")


def команды() -> dict:
    return данные(КОМАНДЫ, "команды")


def состояние() -> dict:
    return данные(СОСТОЯНИЕ, "проверено")


def реестр() -> dict:
    """Файл механизма → его поле «проверяется» (строка паспорта)."""
    прочитано = yaml.safe_load(РЕЕСТР.read_text(encoding="utf-8"))
    список = прочитано if isinstance(прочитано, list) else прочитано.get("механизмы", [])
    return {м.get("файл"): str(м.get("проверяется") or "") for м in список}


def механизмы_класса() -> list[str]:
    """Механизмы класса C2 из реестра — по порядку реестра, не по моей памяти."""
    кл = классы()
    return [ф for ф in реестр()
            if (кл.get(ф) or {}).get("класс") == КЛАСС]


def пересказ_самотеста(команда: str, паспорт: str) -> bool:
    """Команда — повтор поля «проверяется» из паспорта?

    Владелец 15.10.2026: «проверить не просто тестами, а именно наживую, в
    практике». Ревью 17.10 замерило: все 35 команд живого вызова побуквенно
    (или с точностью до приписки в скобках) равнялись паспорту, то есть живая
    проверка доказывалась ПЕРЕСКАЗОМ САМОТЕСТА.
    """
    плотно = lambda с: " ".join(с.split())              # noqa: E731 — одна строка
    к = плотно(команда)
    # Проза паспорта отрезается: сравнивать надо команду с командой, а не с
    # «python3 x.py --selftest (12 путей, первым больной)».
    п = плотно(паспорт.split(" (")[0])
    # Судится ОДНА сторона: команда равна паспортной или начинается с неё. Если
    # команда КОРОЧЕ («bash x.sh» против «bash x.sh --selftest») — это другой
    # вызов, и отказ ему закрыл бы законную дверь: помощник 17.10 обошёл такой
    # отказ ветвью --help, то есть правило без двери обходят, а не соблюдают.
    return bool(к) and bool(п) and к.startswith(п)


# Сторож берётся от СВОЕГО пути, а не от КОРНЯ: корень подменяется пробой на
# её двор, а сторож — механизм харнеса, он лежит рядом с этим файлом.
СТОРОЖ = pathlib.Path(__file__).resolve().parent / "hooks" / "guard_bash.py"
# Предел прибора БОЛЬШЕ предела обёртки: иначе оборванным оказывается прибор, а
# не механизм, и в следе нет ни слова о причине (находка ревью F-sec-05).
ЗАПАС_СЕКУНД = 60


def сторож_отменяет(команда: str) -> str:
    """Слово сторожа команд, если он эту команду отменяет, иначе пустая строка.

    Команда приходит ИЗ ДАННЫХ и уходила в `bash -c` мимо сторожа: ни одно
    правило И-1/И-2 к ней не применялось, и `dropdb` исполнился бы (находка
    ревью безопасности F-sec-01, 17.10.2026). Судит САМ сторож своей дверью —
    свой запретный список разошёлся бы с его правилами молча.
    """
    полезное = json.dumps({"tool_name": "Bash", "session_id": "живая-проверка",
                           "tool_input": {"command": команда}})
    готово = subprocess.run([sys.executable, str(СТОРОЖ)], input=полезное,
                            capture_output=True, text=True, timeout=120)
    if готово.returncode == 0:
        return ""
    первая = (готово.stderr or готово.stdout or "").strip().splitlines()
    return первая[0][:200] if первая else f"код {готово.returncode} без слова"


def позвать(механизм: str, команда: str) -> tuple[int, str, pathlib.Path, str]:
    """Механизм зовётся ОБЁРТКОЙ: след пишет она, и в следе чужой текст.

    След пишется в СВОЙ каталог прогона, а не в общий: соседний прогон того же
    механизма успевал подменить файл во время зова, и цитатой «проверено
    живьём» становился чужой текст (находка ревью F-sec-03). После чтения след
    переносится под своё постоянное имя — шапку обёртки перенос сохраняет.
    """
    предел = int(os.environ.get("HARNESS_LIVE_CHECK_TIMEOUT", "300")) + ЗАПАС_СЕКУНД
    # Свой каталог — ВНУТРИ каталога следов: файл потом ПЕРЕИМЕНОВЫВАЕТСЯ
    # (os.replace на одной файловой системе), а не перезаписывается мною. След
    # обязан быть написан ОБЁРТКОЙ: доказательство, написанное проверяемым,
    # доказательством не является ([[a-trace-is-evidence-only-if-someone-else-wrote-it]]).
    try:
        СЛЕДЫ.mkdir(parents=True, exist_ok=True)
        свой = pathlib.Path(tempfile.mkdtemp(prefix=".прогон-", dir=СЛЕДЫ))
    except OSError as беда:
        # Своими словами, а не трассировкой: каталог следов задаётся
        # окружением, и «не могу писать» — обычный ответ машины, а не дефект.
        # Префикс обязателен: свой отказ прибора и код 2 САМОГО механизма
        # различаются только словом (случай 18.10.2026 — клиент панели).
        return 2, "", СЛЕДЫ / (механизм.replace("/", "-") + ".log"), \
               f"прибор: не создать каталог следов {СЛЕДЫ}: {беда}"
    среда = dict(os.environ)
    среда["HARNESS_LIVE_CHECK_TRACE_DIR"] = str(свой)
    имя = механизм.replace("/", "-") + ".log"
    try:
        готово = subprocess.run(["bash", "scripts/live-check.sh", механизм, "--",
                                 "bash", "-c", команда],
                                cwd=КОРЕНЬ, capture_output=True, text=True,
                                env=среда, timeout=предел)
        код = готово.returncode
        слово = (готово.stderr or "").strip().splitlines()
        слово_обёртки = слово[-1][:200] if слово else ""
    except subprocess.TimeoutExpired:
        # Предел прибора сработал раньше предела обёртки — это косяк ПРИБОРА,
        # и говорить о нём надо вслух, а не падать трассировкой.
        код, слово_обёртки = -1, ""
    текст = (свой / имя).read_text(errors="replace") if (свой / имя).is_file() else ""
    след = СЛЕДЫ / имя
    if текст:
        os.replace(свой / имя, след)
    shutil.rmtree(свой, ignore_errors=True)
    return код, текст, след, слово_обёртки


def цитата(текст_следа: str) -> str:
    """Первая строка ВЫВОДА МЕХАНИЗМА длиной от ЦИТАТА_ЗНАКОВ.

    Шапка обёртки пропускается: в ней стоят время, путь и команда — мои слова,
    а не чужой текст.
    """
    если_есть = текст_следа.split(ШАПКА_КОНЕЦ, 1)
    вывод = если_есть[1] if len(если_есть) == 2 else ""
    for строка in вывод.splitlines():
        плотно = " ".join(строка.split())
        if len(плотно) >= ЦИТАТА_ЗНАКОВ and not плотно.startswith("код возврата:"):
            return плотно
    return ""


def проверить(механизм: str, кл: dict, кмд: dict, пасп: dict) -> tuple[bool, str, dict]:
    """(доказано, что сказать, поля записи)."""
    имя_класса = (кл.get(механизм) or {}).get("класс") or "не назван"
    if имя_класса != КЛАСС:
        return False, (f"{механизм}: класс {имя_класса}, а не {КЛАСС} — у каждого "
                       f"класса свой предикат, этим носителем он не доказывается"), {}
    команда = (кмд.get(механизм) or "").strip()
    if not команда:
        return False, (f"{механизм}: команды в данных нет ({КОМАНДЫ.name}) — "
                       f"паспорт механизма смешан с прозой, разбирать его нельзя"), {}
    if пересказ_самотеста(команда, пасп.get(механизм, "")):
        return False, (f"{механизм}: команда повторяет паспортный самотест "
                       f"«{пасп.get(механизм, '')[:60]}» — это пересказ самотеста, "
                       f"а не живой вызов с настоящим входом"), {}
    слово_сторожа = сторож_отменяет(команда)
    if слово_сторожа:
        return False, (f"{механизм}: команду отменяет сторож команд — "
                       f"{слово_сторожа}"), {}
    код, текст, след, слово_обёртки = позвать(механизм, команда)
    # Три разных отказа, а не один: обёртка отдаёт СВОИ отказы кодом 2 и свой
    # обрыв по времени кодом 124 (live-check.sh), и выдавать их за отказ
    # механизма значит отправить проверяющего заводить карточку на невиновного
    # (находка ревью F-gen-05).
    # Код 2 носят ДВЕ разные беды: свой отказ обёртки и код самого механизма
    # (живой случай 18.10.2026 — клиент панели отвечает 2 на чужой номер, и
    # прибор отправлял проверяющего искать дефект в невиновной обёртке).
    # Различает их СЛОВО: свои отказы обёртка печатает с префиксом «live-check:».
    if код == 2 and слово_обёртки.startswith(("live-check:", "прибор:")):
        return False, (f"{механизм}: отказала ОБЁРТКА следа, механизм не звался "
                       f"— {слово_обёртки}"), {}
    if код == 124:
        return False, (f"{механизм}: механизм оборван ПРЕДЕЛОМ обёртки "
                       f"({os.environ.get('HARNESS_LIVE_CHECK_TIMEOUT', '300')} с) "
                       f"— поднимай HARNESS_LIVE_CHECK_TIMEOUT; след: {след}"), {}
    if код == -1:
        return False, (f"{механизм}: предел самого прибора сработал раньше предела "
                       f"обёртки — это косяк прибора, а не механизма"), {}
    if код != 0:
        return False, (f"{механизм}: механизм отказал на здоровой машине "
                       f"(код {код}) — это косяк, а не доказательство; след: "
                       f"{след}"), {}
    видно = цитата(текст)
    if not видно:
        return False, (f"{механизм}: цитировать нечего — в выводе нет строки от "
                       f"{ЦИТАТА_ЗНАКОВ} знаков; молчащий механизм доказывался бы "
                       f"моим эхом"), {}
    поля = {
        "живьём": f"{ПРИСТАВКА}: {команда}",
        "увидели": видно,
        "след": str(след.relative_to(КОРЕНЬ)) if след.is_relative_to(КОРЕНЬ) else str(след),
        "когда": datetime.date.today().isoformat(),
        "исход": "ок",
    }
    return True, f"{механизм}: живой вызов доказан — {видно[:80]}", поля


def записать(поля_по_механизму: dict) -> None:
    """Чтение-правка-запись состояния ПОД ЗАМКОМ и атомарно.

    Без замка два прогона рядом теряли записи молча: замер ревью 17.10.2026 —
    три прогона из трёх, каждый раз ровно 30 доказанных записей из 60 исчезали,
    а прибор печатал «записано: 30» и отдавал 0 (находка F-sec-04). Замок — на
    отдельном файле рядом, а не на самом состоянии: замок на файле, который
    переписывается через os.replace, не держит ничего.
    """
    замок = СОСТОЯНИЕ.with_suffix(СОСТОЯНИЕ.suffix + ".lock")
    замок.parent.mkdir(parents=True, exist_ok=True)
    with open(замок, "w") as дверь:
        fcntl.flock(дверь, fcntl.LOCK_EX)
        прочитано = yaml.safe_load(СОСТОЯНИЕ.read_text(encoding="utf-8")) or {}
        сост = прочитано.setdefault("проверено", {})
        for механизм, поля in поля_по_механизму.items():
            запись = сост.setdefault(механизм, {})
            прежде = str(запись.get("живьём") or "")
            # Запись ПОВЕРХ чужого доказательства уносила его молча: за смену
            # 17.10 так снесено четыре записи, у owner_word.py — живое
            # наблюдение владельца (находка ревью F-gen-03). Чужое переносится
            # полем «прежде», а не исчезает (И-1 о потере данных).
            if прежде and not прежде.startswith(ПРИСТАВКА):
                запись["прежде"] = (f"{прежде} · увидели: "
                                    f"{запись.get('увидели') or '—'}")
            запись.update(поля)
        рядом = СОСТОЯНИЕ.with_suffix(СОСТОЯНИЕ.suffix + f".новое-{os.getpid()}")
        рядом.write_text(
            yaml.dump(прочитано, allow_unicode=True, sort_keys=False, width=100),
            encoding="utf-8")
        os.replace(рядом, СОСТОЯНИЕ)


def main() -> int:
    писать = "--записать" in sys.argv
    названные = [д for д in sys.argv[1:] if not д.startswith("--")]
    кл, кмд, сост, пасп = классы(), команды(), состояние(), реестр()
    # «--всё» — про НЕПРОВЕРЕННЫХ: у кого исход уже стоит, звать незачем.
    кого = ([м for м in механизмы_класса()
             if not ((сост.get(м) or {}).get("исход") or "").strip()]
            if "--всё" in sys.argv else названные)
    if not кого:
        if "--всё" in sys.argv:
            print(f"[живой вызов] непроверенных механизмов класса {КЛАСС} нет")
            return 0
        print("[живой вызов] нечего звать: назови механизм или дай «--всё»",
              file=sys.stderr)
        return 1

    доказано = 0
    for механизм in кого:
        удача, слово, поля = проверить(механизм, кл, кмд, пасп)
        # flush: под перенаправлением питон буферизует вывод блоками, и долгий
        # прогон выглядит мёртвым — за ним перестают ждать (замер 17.10.2026:
        # 23 механизма, журнал пустой до самого конца).
        print(f"  {'ок   ' if удача else 'ПЛОХО'} {слово}", flush=True)
        if not удача:
            continue
        доказано += 1
        # Запись СРАЗУ, а не одним разом в конце: обрыв прогона (лимит
        # подписки, ротация, Ctrl-C) уносил всё доказанное, хотя журнал уже
        # напечатал «доказан» по каждому (находка ревью F-sec-05).
        if писать:
            записать({механизм: поля})
    if писать:
        print(f"[живой вызов] записано механизмов: {доказано}")
    if доказано == len(кого):
        print(f"[живой вызов] доказано все {len(кого)}")
        return 0
    print(f"[живой вызов] ✗ не доказано: {len(кого) - доказано} из {len(кого)}")
    return 1


if __name__ == "__main__":
    sys.exit(main())
