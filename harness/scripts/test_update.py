    def asker(code: int = 0, hold: float = 0.0):
        """Заглушка отправки вопроса: помнит текст и миг получения, отвечает кодом случая.
        hold — задержка ответа: время, взятое ПОСЛЕ отправки, выйдет позже мига получения."""
        calls = []

