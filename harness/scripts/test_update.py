def inside(path, root) -> bool:
    real, base = os.path.realpath(path), os.path.realpath(root)
    return real == base or real.startswith(base + os.sep)


def live_backups_snapshot():
    """(имя, mtime, размер, inode) записей живого каталога копий + mtime самого
    каталога; None — не прочитан. Имена не печатаются (имя бывает ключом)."""
    live = обновление.конф_модуль.из_файла("/etc/harness/harness.conf").get("BACKUP_DIR", "")
    if not live:
        return None
    try:
        own = os.stat(live)
        with os.scandir(live) as entries:
            rows = sorted((e.name, e.stat(follow_symlinks=False).st_mtime_ns,
                           e.stat(follow_symlinks=False).st_size, e.inode()) for e in entries)
    except OSError:
        return None
    return own.st_mtime_ns, rows


