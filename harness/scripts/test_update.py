def поставить_без_падения(**доводы) -> dict:
    """Падение `поставить` — это неудача пути, а не конец всего прогона.

    Отправка вопроса Ф-д подменяется в КАЖДОМ зове (К9): иначе default-путь
    update.py шлёт из пробы через живой scripts/tg_send.sh. Пока довода нет в
    `поставить`, подмены нет — прежние случаи идут прежним путём."""
    if ("спросить" not in доводы
            and "спросить" in inspect.signature(обновление.поставить).parameters):
        доводы["спросить"] = question_guard
    if ("сверить_корень" not in доводы
            and "сверить_корень" in inspect.signature(обновление.поставить).parameters):
        доводы["сверить_корень"] = lambda: []
    try:
        return обновление.поставить(**доводы)
    except Exception as беда:  # noqa: BLE001 — любой сбой здесь и есть находка
        return {"поставлено": False, "исключение": f"{type(беда).__name__}: {беда}"}


