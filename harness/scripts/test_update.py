    # обновление, а владелец не знал бы почему.
    # Договор, под который пишется код:
    #   * Реестр `harness/config/mechanisms.yaml`: у записи сборщика поле
    #     `собирает: <путь от корня проекта>` (например docs/УСТРОЙСТВО-ХАРНЕСА.md).
    #     Сборщик пересобирает документ ГОЛЫМ вызовом `python3 <файл>`.
    #   * `обновление.сборщики_производных(реестр: dict) -> list[str]` — чисто:
    #     `файл` каждой записи с `собирает`, в порядке реестра; нет таких — [].
    #   * `обновление._запустить_сборщик(путь: Path) -> (код: int, хвост: str)` —
    #     умолчание запуска: subprocess с sys.executable; хвост — последняя
    #     НЕПУСТАЯ строка stderr без пробелов по краям; пустой stderr — "".
    #   * `обновление.пересобрать_производные(реестр=None, запустить=None)
    #     -> list[(файл, хвост)]`: реестр None — живой mechanisms.yaml от КОРЕНЬ;
    #     `запустить(путь: Path) -> (код, хвост)`, путь = КОРЕНЬ / файл. Зовёт
    #     КАЖДОГО сборщика из реестра; отдаёт упавших (код ≠ 0) по порядку
    #     реестра: файл — как записан в реестре, хвост — из `запустить`; [] —
    #     все прошли. Исключение запуска (TimeoutExpired, OSError) — тоже
    #     упавший, хвост — str(исключения), и остальные всё равно зовутся.
    #   * `_разложить_пакет() -> (раскладка_ок: bool, упавшие: list)`:
    #     razlozhit-harnes.sh или доустановка (install-new.py) с ненулевым кодом
    #     → раскладка_ок False. `пересобрать_производные()` зовётся как
    #     глобальное имя модуля (в момент вызова); её упавшие — второй элемент,
    #     раскладка_ок от них НЕ зависит.
    #   * `поставить()`: раскладка_ок False → откат СРАЗУ: ворота «после» не
