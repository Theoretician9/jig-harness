# ── договор самопроверки обновления (hr.update-judges-new-reds) ──────────────
# На живой установке красные ворота есть всегда — из-за среды (срок входа,
# nginx, журналы), — поэтому «пропускать только при красных 0» откатывало
# каждое обновление. Договор, под который пишется код:
#   * `обновление.красные_из_вывода(текст) -> Counter[str] | None` — чистый разбор
#     вывода gates.sh: имена из строк «  ПЛОХО · <имя> (код N)» и
#     «  ПЛОХО · <имя> — гейт объявлен БЕЗ КОМАНДЫ…» (ровно два пробела отступа;
#     строки вывода гейта под ней отступлены глубже и красными не считаются),
#     жёлтые не красные; нет строки «=== итог:» — None (итог не прочитан).
#     Счёт, а не множество: в воротах две разные проверки носят одно имя
#     («скилы-самотест»), и вторая красная того же имени — тоже новая красная.
#     Имя → сколько строк «ПЛОХО» с ним; пустые ворота — пустой Counter.
#   * `проверить()` (довод `поставить`, умолчание — `прогнать_ворота`) зовётся
#     ДВАЖДЫ: прогон «до» — РАНЬШЕ снятия копии (правка пакета, сделанная за
#     минуты прогона, обязана попасть в копию), второй — после раскладки;
#     отдаёт Counter имён красных либо None, если итог прочитать не удалось.
#   * Проходит, если разность счётов «после − до» пуста. Новая красная —
#     откат, в сказанном её имя, в ответе `"новые красные"` — список их имён.
#     Успех говорит владельцу «красных N» — сколько осталось, с кратностью.
#   * None до — отказ, пакет не тронут; None после — откат. Прогон, оборванный
#     пределом времени (`TimeoutExpired`), — тоже None, а не исключение.
#   * Откат возвращает из копии правки владельца («не трогать», «расхождения»).
#   * Перед `reset --hard` отката снимается ВТОРАЯ копия: ключ ответа
#     `"копия до отката"` — её путь, и он назван в сказанном. Не снялась —
#     откат всё равно, ключ None, в сказанном «копии нет».
#   * Выкат, начавшийся за время прогона «до», — отказ до слияния.
#   * Свой замок `$LOG_DIR/locks/update.lock` (flock) держится всё время
#     постановки; занят — отказ словами, ворота не гоняются. Дверь пробы —
#     переменная окружения LOG_DIR (загрузчик конфига: окружение старше файла).


def ворота_проба(*ответы):
    """Подмена `проверить`: отдаёт ответы по очереди и помнит, на каком
    коммите пакета её позвали — так видно, что первый прогон был ДО слияния."""
    очередь = list(ответы)
    зовы = []

    def проверить():
        зовы.append(гит("rev-parse", "HEAD", где=пакет).stdout.strip())
        return очередь.pop(0) if очередь else None
    проверить.зовы = зовы
    return проверить


