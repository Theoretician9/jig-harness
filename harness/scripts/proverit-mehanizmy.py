#!/usr/bin/env python3
"""Прогоняет ЖИВЬЁМ команду проверки каждого механизма из реестра.

Откуда взят: владелец 12.09.2026 — «Потом перепроверить еще раз на практике
каждый механизм, удостовериться что все работает». Самотест доказывает, что
код делает задуманное; живой прогон — что задуманное верно и что механизм
вообще запускается на ЭТОЙ машине. За смену 11.09 живой прогон нашёл четыре
дефекта, которых не было ни в одной проверке.

Реестр (`harness/config/устройство.yaml`) у каждого механизма несёт строку
«проверяется». У 95 из 113 это исполняемая команда, у остальных — слова
(«отметка вызова в журнале»): их прибор честно относит к непроверяемым кодом,
а не выдаёт за пройденные.

Запрещённое к прогону — данные, не догадка: выкат, публикация и отправка в
удалённый репозиторий не запускаются НИКОГДА, даже если попадут в строку.

    python3 scripts/proverit-mehanizmy.py            # прогон, отчёт в stdout
    python3 scripts/proverit-mehanizmy.py --список   # что будет запущено
    python3 scripts/proverit-mehanizmy.py --selftest
"""
import json
import re
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))
from konf import корень_дерева  # noqa: E402

КОМАНДА = re.compile(r'^(python3|bash|sh)\s')
# Опасное не запускается никогда: прогон механизмов не имеет права выкатывать,
# публиковать и отправлять. Это данные правила, а не осторожность на глаз.
ЗАПРЕЩЕНО = ("deploy.sh", "git push", "--опубликовать", "docker compose", "rm -rf")


def боевая_публикация(команда: str) -> bool:
    """publikaciya.sh запускать нельзя — кроме её же самотеста: он ничего не
    публикует и как раз доказывает замки. Прежний образец «publikaciya.sh --»
    запрещал и самотест: механизм, который нельзя проверить, остаётся
    непроверенным (замер 12.09.2026: 1 механизм в списке «запрещено»)."""
    return "publikaciya.sh" in команда and "--selftest" not in команда
ТАЙМАУТ = 180


def команда_механизма(запись: dict) -> str | None:
    """Первая исполняемая команда строки «проверяется». Хвост в скобках и
    после «;» — пояснение автора, а не вторая команда."""
    строка = (запись.get("проверяется") or "").strip()
    if not КОМАНДА.match(строка):
        return None
    строка = строка.split(";")[0]
    строка = re.sub(r"\s*\(.*$", "", строка).strip()
    return строка or None


def опасна(команда: str) -> str | None:
    for образец in ЗАПРЕЩЕНО:
        if образец in команда:
            return образец
    return "публикация без --selftest" if боевая_публикация(команда) else None


def прогнать(команда: str, корень: Path) -> dict:
    начало = time.monotonic()
    try:
        готово = subprocess.run(команда, shell=True, cwd=корень, capture_output=True,
                                text=True, timeout=ТАЙМАУТ)
        код, вывод = готово.returncode, (готово.stdout + готово.stderr)
    except subprocess.TimeoutExpired:
        код, вывод = 124, f"не ответила за {ТАЙМАУТ} с"
    return {"код": код, "секунд": round(time.monotonic() - начало, 1),
            "хвост": вывод.strip().splitlines()[-1][:200] if вывод.strip() else ""}


def разобрать(корень: Path) -> tuple:
    import yaml
    реестр = yaml.safe_load(
        (корень / "harness" / "config" / "устройство.yaml").read_text(encoding="utf-8")) or {}
    к_прогону, словом, опасные = [], [], []
    for запись in реестр.get("механизмы") or []:
        команда = команда_механизма(запись)
        if not команда:
            словом.append(запись["файл"])
        elif опасна(команда):
            опасные.append((запись["файл"], команда, опасна(команда)))
        else:
            к_прогону.append((запись["файл"], команда, запись.get("вид", "")))
    return к_прогону, словом, опасные


def selftest() -> int:
    неудач = 0

    def проба(имя, ожидалось, получено):
        nonlocal неудач
        ок = ожидалось == получено
        неудач += not ок
        print(f"  {'ok  ' if ок else 'FAIL'} {имя}"
              + ("" if ок else f": ждали {ожидалось!r}, получили {получено!r}"))

    проба("команда без пояснения", "python3 scripts/x.py --selftest",
          команда_механизма({"проверяется": "python3 scripts/x.py --selftest (8 путей)"}))
    проба("хвост после ; отрезан", "bash harness/demons/backup.sh --selftest",
          команда_механизма({"проверяется": "bash harness/demons/backup.sh --selftest; возраст копии"}))
    проба("слово командой не считается", None,
          команда_механизма({"проверяется": "отметка вызова в журнале"}))
    # БОЛЬНОЙ СЛУЧАЙ: выкат не запускается, даже если попал в строку реестра.
    проба("выкат опознан как запрещённый", "deploy.sh", опасна("bash ./scripts/deploy.sh"))
    проба("самотест не запрещён", None, опасна("python3 scripts/check-secrets.py --selftest"))
    проба("самотест публикации разрешён", None, опасна("bash scripts/publikaciya.sh --selftest"))
    проба("боевая публикация запрещена", "публикация без --selftest",
          опасна("bash scripts/publikaciya.sh"))
    print(f"самотест proverit-mehanizmy: неудач {неудач}")
    return 1 if неудач else 0


def главная() -> int:
    if "--selftest" in sys.argv[1:]:
        return selftest()
    корень = корень_дерева(__file__)
    к_прогону, словом, опасные = разобрать(корень)

    if "--список" in sys.argv[1:]:
        for файл, команда, _вид in к_прогону:
            print(f"  {файл}: {команда}")
        print(f"\nк прогону {len(к_прогону)} · словом {len(словом)} · "
              f"запрещено {len(опасные)}")
        return 0

    итоги, упало, сигналы = [], [], []
    for файл, команда, вид in к_прогону:
        итог = прогнать(команда, корень)
        итоги.append({"механизм": файл, "команда": команда, "вид": вид, **итог})
        # У ХУКА ненулевой код — способ сказать агенту «есть о чём подумать», а
        # не поломка: stop_reminder честно вернул 2 на четырёх незакоммиченных
        # файлах, и прибор объявил его упавшим (первый прогон 12.09.2026).
        # Смешивать сигнал с отказом значит приучать себя к красному.
        if итог["код"] == 0:
            знак = "ок  "
        elif вид == "хук":
            знак = "сигнал"
            сигналы.append(файл)
        else:
            знак = "ПЛОХО"
            упало.append(файл)
        print(f"  {знак} {файл} ({итог['секунд']} с) {итог['хвост'][:90]}")

    отчёт = корень / "docs" / "проверка-механизмов.json"
    отчёт.parent.mkdir(exist_ok=True)
    отчёт.write_text(json.dumps(
        {"прогнано": len(итоги), "упало": упало, "сигналы": сигналы, "словом": словом,
         "запрещено": [{"механизм": ф, "команда": к, "образец": о} for ф, к, о in опасные],
         "механизмы": итоги}, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"\nпрогнано {len(итоги)} · упало {len(упало)} · сигналов хуков {len(сигналы)} · "
          f"проверяется словом {len(словом)} · запрещено к прогону {len(опасные)}")
    print(f"отчёт: {отчёт}")
    return 1 if упало else 0


if __name__ == "__main__":
    sys.exit(главная())
