#!/usr/bin/env python3
"""Проверка команд бота: сверка меню с данными и разбор слов владельца.

Откуда взято. Владелец 13.09.2026: «надо сделать вызов панели кнопкой прям в
меню бота». Механизм обязан не только поставить кнопки, но и заметить, что их
затёрли: меню живёт на стороне Telegram, и «поставили один раз» — не гарантия.

Сеть здесь не нужна: сверка — чистая функция от двух списков, и проверяется
именно она.

Прогон:
    python3 scripts/test_komandy_bota.py
Код возврата: 0 — все пути прошли, 1 — есть упавший.
"""
import importlib.util
import re
import subprocess
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
путей = неудач = 0


def путь_ок(текст: str) -> None:
    global путей
    путей += 1
    print("ок  · " + текст)


def путь_плохо(текст: str) -> None:
    global путей, неудач
    путей += 1
    неудач += 1
    print("ПЛОХО · " + текст)


спец = importlib.util.spec_from_file_location(
    "команды", КОРЕНЬ / "scripts" / "komandy-bota.py")
команды = importlib.util.module_from_spec(спец)
спец.loader.exec_module(команды)

ДАНО = [
    {"имя": "panel", "описание": "Открыть панель", "слова": ["панель", "открой панель"]},
    {"имя": "status", "описание": "Что делается сейчас", "слова": ["статус"]},
]

print("── здоровый: меню совпадает с данными ──")
стоит = [{"command": "panel", "description": "Открыть панель"},
         {"command": "status", "description": "Что делается сейчас"}]
if команды.расхождения(ДАНО, стоит) == []:
    путь_ок("совпадающее меню претензий не даёт")
else:
    путь_плохо(f"ложная тревога: {команды.расхождения(ДАНО, стоит)}")

print("── БОЛЬНОЙ: меню пустое (так и было до 13.09) ──")
беды = команды.расхождения(ДАНО, [])
if len(беды) == 2 and all("кнопки нет" in б for б in беды):
    путь_ок("пустое меню названо поимённо: обе кнопки пропали")
else:
    путь_плохо(f"пустое меню разобрано не так: {беды}")

print("── БОЛЬНОЙ: подпись затёрта чужим клиентом ──")
чужое = [{"command": "panel", "description": "Panel"},
         {"command": "status", "description": "Что делается сейчас"}]
беды = команды.расхождения(ДАНО, чужое)
if len(беды) == 1 and "вместо" in беды[0]:
    путь_ок(f"подмена подписи поймана: {беды[0]}")
else:
    путь_плохо(f"подмена подписи не поймана: {беды}")

print("── БОЛЬНОЙ: лишняя кнопка, которой нет в данных ──")
лишнее = стоит + [{"command": "debug", "description": "Отладка"}]
беды = команды.расхождения(ДАНО, лишнее)
if len(беды) == 1 and "лишняя" in беды[0]:
    путь_ок("лишняя кнопка названа")
else:
    путь_плохо(f"лишняя кнопка не поймана: {беды}")

print("── слово владельца и кнопка ведут в одно место ──")
слова = команды.слова_команд(ДАНО)
проверки = [
    ("панель", "panel", "русское слово"),
    ("panel", "panel", "имя команды латиницей"),
    ("открой панель", "panel", "форма из двух слов"),
    ("статус", "status", "слово другой команды"),
]
for слово, ждём, зачем in проверки:
    if слова.get(слово) == ждём:
        путь_ок(f"{зачем}: «{слово}» → /{ждём}")
    else:
        путь_плохо(f"{зачем}: «{слово}» → {слова.get(слово)}, ждали /{ждём}")
if "что-то постороннее" not in слова:
    путь_ок("постороннее слово командой не становится")
else:
    путь_плохо("посторонний текст разобран как команда")

print("── боевой путь: диспетчер зовёт --какая ПОДПРОЦЕССОМ ──")
# Диспетчер не импортирует модуль, а зовёт скрипт строкой (tg-dispatcher.sh:
# CMD=$(python3 .../komandy-bota.py --какая "$NORM")). Проба, дёргающая
# функцию напрямую, слепа к разбору аргументов, регистру и ведущему «/» —
# а именно ими слово владельца «панель» и уходило мимо команды.
СКРИПТ = str(КОРЕНЬ / "scripts" / "komandy-bota.py")
for слово, ждём in [("панель", "panel"), ("/panel", "panel"),
                    ("Статус", "status"), ("обнови харнес", "update")]:
    вышло = subprocess.run([sys.executable, СКРИПТ, "--какая", слово],
                           capture_output=True, text=True, timeout=60)
    если_имя = вышло.stdout.strip()
    if вышло.returncode == 0 and если_имя == ждём:
        путь_ок(f"боевым вызовом «{слово}» → /{ждём}")
    else:
        путь_плохо(f"боевым вызовом «{слово}» → «{если_имя}» (код {вышло.returncode}), ждали /{ждём}")
пусто = subprocess.run([sys.executable, СКРИПТ, "--какая", "что там по картам"],
                       capture_output=True, text=True, timeout=60)
if пусто.returncode == 1 and not пусто.stdout.strip():
    путь_ок("обычное сообщение командой не становится: код 1, имя пустое")
else:
    путь_плохо(f"постороннее слово разобрано как команда: «{пусто.stdout.strip()}» (код {пусто.returncode})")

ДИСПЕТЧЕР = (КОРЕНЬ / "scripts" / "tg-dispatcher.sh").read_text(encoding="utf-8")
print("── команда с ИМЕНЕМ в сообщении ──")
# БОЛЬНОЙ СЛУЧАЙ 13.09.2026 (ревью кода, F-06): «панель наружу my.example.com»
# сверялось точным совпадением строки и командой не считалось — имя уходило в
# inbox, а ветка разбора имени внутри panel-naruzhu.sh была недостижима.
# Разбор по префиксу разрешён ТОЛЬКО когда хвост целиком совпал с формой
# аргумента из данных: иначе командой стал бы и рассказ «панель упала».
С_АРГУМЕНТОМ = [
    {"имя": "panel", "описание": "Панель", "слова": ["панель"]},
    {"имя": "panel_out", "описание": "Наружу", "слова": ["панель наружу"],
     "аргумент": r"[a-z0-9][a-z0-9.-]*\.[a-z]{2,}"},
]
разбор = [
    ("панель наружу my.example.com", ("panel_out", "my.example.com"), "имя названо словом"),
    ("Панель наружу MY.Example.COM", ("panel_out", "my.example.com"), "регистр не мешает"),
    ("панель наружу", ("panel_out", ""), "без имени — та же команда, имя выведет код"),
    ("панель упала, посмотри", ("", ""), "рассказ о панели командой не становится"),
    ("панель наружу завтра сделай", ("", ""), "хвост не по форме — не команда"),
    ("панель", ("panel", ""), "соседняя команда не перехватывается"),
]
for текст, ждём, зачем in разбор:
    вышло = команды.разобрать(С_АРГУМЕНТОМ, текст)
    if вышло == ждём:
        путь_ок(f"{зачем}: «{текст}» → {вышло}")
    else:
        путь_плохо(f"{зачем}: «{текст}» → {вышло}, ждали {ждём}")

print("── боевой путь: аргумент приходит ВТОРОЙ строкой ──")
живое = subprocess.run([sys.executable, СКРИПТ, "--какая", "панель наружу my.example.com"],
                       capture_output=True, text=True, timeout=60)
строки = живое.stdout.split("\n")
if живое.returncode == 0 and строки[:2] == ["panel_out", "my.example.com"]:
    путь_ок("боевым вызовом: имя команды и аргумент двумя строками")
else:
    путь_плохо(f"боевой вызов отдал {строки[:2]} (код {живое.returncode})")

print("── форма имени хоста описана ОДИН раз — в данных ──")
# Диспетчер выделял имя хоста своей регуляркой: два списка форм расходятся
# молча, и разошедшаяся половина молчит ровно тогда, когда нужна.
if re.search(r"grep -oE '\[a-z0-9\]", ДИСПЕТЧЕР):
    путь_плохо("tg-dispatcher.sh выделяет имя хоста своей регуляркой — форма живёт в двух местах")
else:
    путь_ок("диспетчер берёт аргумент из разбора, своей формы имени не держит")

print("── вывод наружу не держит канал ──")
# apt и certbot занимают минуты, а диспетчер — единственный потребитель
# getUpdates: синхронный вызов делает бота мёртвым на всё это время (F-16).
# Граница ветки — начало СЛЕДУЮЩЕЙ ветки case (свой отступ), а не первый
# «;;»: внутри ветки стоит свой case, и разбор по «;;» обрывался на нём.
ветка = ДИСПЕТЧЕР.split('"panel_out")', 1)[-1].split('\n            "', 1)[0]
if "setsid nohup" in ветка:
    путь_ок("панель наружу запускается фоном — канал продолжает принимать")
else:
    путь_плохо("ветка panel_out ждёт вывода наружу синхронно: канал молчит минуты")

print("── у каждой кнопки есть ветка в диспетчере ──")
# Кнопка, которой нет в case диспетчера, выглядит живой: Telegram её рисует,
# владелец нажимает, бот молчит. Данные и потребитель данных обязаны сойтись
# ЗДЕСЬ, иначе расхождение обнаружит только владелец.
for к in команды.данные():
    имя = str(к["имя"])
    if f'"{имя}")' in ДИСПЕТЧЕР or f'"{имя}"|' in ДИСПЕТЧЕР:
        путь_ок(f"/{имя} разбирается диспетчером")
    else:
        путь_плохо(f"/{имя} стоит в меню, но ветки в tg-dispatcher.sh нет — бот промолчит")

print("── всё, что диспетчер ЗОВЁТ по пути, лежит на месте ──")
# Живой случай 13.09.2026: каталог панели переименовали в harness/panel, а
# диспетчер остался единственным, кто звал harness/панель. Кнопка /panel
# стояла в меню и молчала — «сейчас кстати перестало работать». Гейты сюда не
# смотрят: путь внутри строки bash, и никакой линтер его не проверяет.
ОКРУЖЕНИЕ = {"$PROJECT_DIR": str(КОРЕНЬ),
             "$HERE": str(КОРЕНЬ / "scripts"),           # tg-dispatcher.sh:374
             "$PANEL_DIR": str(КОРЕНЬ / "harness" / "panel")}
зовёт = re.findall(r'python3 "(\$[A-Z_]+/[^"]+)"', ДИСПЕТЧЕР)
if not зовёт:
    путь_плохо("в диспетчере не найдено ни одного вызова python3 по пути — проба ослепла")
for шаблон in sorted(set(зовёт)):
    путь = шаблон
    for имя, значение in ОКРУЖЕНИЕ.items():
        путь = путь.replace(имя, значение)
    if путь.startswith("/") and Path(путь).exists():
        путь_ок(f"диспетчер зовёт {шаблон} — файл на месте")
    elif not путь.startswith("/"):
        путь_плохо(f"путь {шаблон} не разобран пробой: подставь переменную в ОКРУЖЕНИЕ")
    else:
        путь_плохо(f"диспетчер зовёт {шаблон}, а файла нет: {путь}")

print("── данные живого харнеса разбираются ──")
живые = команды.данные()
имена = [к["имя"] for к in живые]
if "panel" in имена and all(и.isascii() and и.islower() for и in имена):
    путь_ок(f"команд в данных {len(живые)}, все имена латиницей: {', '.join(имена)}")
else:
    путь_плохо(f"имена команд не по правилам Telegram: {имена}")

print(f"\nитого путей {путей}, неудач {неудач}")
sys.exit(1 if неудач else 0)
