#!/usr/bin/env python3
"""Больной случай 15.10.2026: чужой агент на той же машине держит наши ворота.

На машине стоит ВТОРОЙ харнес под другим пользователем, и
велел его не трогать. Его агент работает постоянно — и ворота выката, обходя
весь `/proc` по имени бинаря, назвали его работу нашей занятостью: «занято:
процесс 280436: claude --dangerously-skip-permissions (131 мин)», отправка в гит
отменена. Чужой агент не перезапустит наш стек и не потеряет нашу работу, а
вечный отказ учит ходить «--силой» — ровно то, от чего замок и ставился.

Проба СОЗДАЁТ условие сама: поднимает процесс с именем `claude`, который ворота
обязаны опознать как долгую работу, и спрашивает их дважды — своим владельцем и
чужим. Двери для этого две, обе ДАННЫЕ: порог долготы (`DEPLOY_BUSY_MIN_SEC`,
иначе пробе пришлось бы ждать две минуты) и свой владелец (`HARNESS_OWN_UID`,
иначе чужого пользователя пришлось бы заводить через sudo, которого на машине
заказчика может не быть). Третья дверь — дерево смен (`AGENT_PROC_ROOT`,
`AGENT_MAINPID`): ворота отказывают «работают два агента» раньше занятости, и
без своего дерева ОДНОЙ смены проба судила число живых сессий машины.
"""
import os
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile
import time

# Корень — рядом с самим файлом: проба обязана судить ТОТ прибор, с которым
# лежит, иначе раскладка пакета оставит её судить чужую копию.
КОРЕНЬ = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path(__file__).resolve().parent.parent
ПРИБОР = КОРЕНЬ / "scripts" / "deploy_guard.py"

плохо = 0


def судить(зачем: str, вышло, ждём) -> None:
    global плохо
    if вышло == ждём:
        print(f"  ок    {зачем}")
    else:
        плохо += 1
        print(f"  ПЛОХО {зачем}: вышло {вышло!r}, ждали {ждём!r}")


def назван_занятым(pid: int, ответ: str) -> bool:
    """Назвали ли ворота процесс pid среди держателей в отказе «занято: …».
    Не «первым»: на машине параллельные прогоны ворот держат свои процессы
    claude, и первым в списке бывает чужой pid — проба судит только своё
    условие. Двоеточие после номера — чтобы pid 123 не находился в 1234."""
    return re.search(rf"(?:занято: |; )процесс {pid}:", ответ) is not None


def стендовый_конфиг(двор: pathlib.Path) -> pathlib.Path:
    """Живой harness.conf плюс обе ручки согласия в 0 последними строками (последняя
    побеждает): ответ ворот «можно» иначе зависит от ручки согласия машины, и
    проба на установке с PUSH/DEPLOY_NEEDS_OWNER=1 краснела бы не от своего правила."""
    sys.path.insert(0, str(КОРЕНЬ / "scripts" / "lib"))
    import config as конф
    живой = pathlib.Path(конф.путь_harness_conf())
    текст = живой.read_text(encoding="utf-8") if живой.is_file() else ""
    свой = двор / "harness.conf"
    свой.write_text(текст + "\nPUSH_NEEDS_OWNER=0\nDEPLOY_NEEDS_OWNER=0\n", encoding="utf-8")
    return свой


# Pid стенда — за pid_max ядра: живого процесса с таким номером быть не может.
PID_СТЕНДА = int(pathlib.Path("/proc/sys/kernel/pid_max").read_text().strip()) + 1000


def дерево_одной_смены(корень: pathlib.Path) -> dict:
    """Корень /proc стенда для подсчёта смен: точка запуска юнита и ОДИН claude под ней.

    Две смены ворота считают по дереву процессов (agent_processes), а занятость —
    по живому /proc. Без своего дерева две живые сессии на машине (24.11.2026)
    давали «работают два агента» раньше занятости, и все четыре случая краснели
    не по своей логике. Образец — дерево_смен в scripts/hooks/test_guard_bash.py.
    """
    uid = os.getuid()
    процессы = [(PID_СТЕНДА, 0, "bash", "/bin/bash", ["bash", "scripts/start-agent.sh"]),
                (PID_СТЕНДА + 1, PID_СТЕНДА, "claude",
                 "/usr/lib/node_modules/@anthropic-ai/claude-code/bin/claude.exe", ["claude"])]
    for pid, ppid, comm, exe, argv in процессы:
        d = корень / str(pid)
        d.mkdir(parents=True, exist_ok=True)
        if not (d / "exe").is_symlink():
            (d / "exe").symlink_to(exe)
        (d / "comm").write_text(comm + "\n")
        (d / "status").write_text(f"PPid:\t{ppid}\nUid:\t{uid}\t{uid}\t{uid}\t{uid}\n")
        (d / "cmdline").write_bytes(b"\0".join(a.encode() for a in argv) + b"\0")
    return {"AGENT_PROC_ROOT": str(корень), "AGENT_MAINPID": str(PID_СТЕНДА)}


def ворота(двор: pathlib.Path, свой_uid: str | None = None, действие: str = "deploy") -> tuple[int, str]:
    """(код, ответ) ворот. Код судится вместе со словом: незнакомый ключ
    отвечает rc 2 без слова «занято», и случай «чужой не держит» зеленел на
    отказе разбора."""
    среда = dict(os.environ, HARNESS_LOG_DIR=str(двор), DEPLOY_BUSY_MIN_SEC="0",
                 HARNESS_CONF=str(стендовый_конфиг(двор)),
                 **дерево_одной_смены(двор / "proc"))
    if свой_uid is not None:
        среда["HARNESS_OWN_UID"] = свой_uid
    готово = subprocess.run([sys.executable, str(ПРИБОР), "--действие", действие],
                            capture_output=True, text=True, env=среда, check=False)
    return готово.returncode, готово.stdout + готово.stderr


with tempfile.TemporaryDirectory() as врем:
    двор = pathlib.Path(врем)
    (двор / "locks").mkdir(parents=True)

    # Процесс с ИМЕНЕМ claude: ворота опознают работу по имени бинаря, поэтому
    # имя даёт не аргумент, а сам файл. `setsid` отвязывает его от дерева смены —
    # иначе ворота законно сочтут его своим предком и пропустят по другой ветке.
    самозванец = двор / "claude"
    самозванец.write_bytes(pathlib.Path(shutil.which("sleep")).read_bytes())
    самозванец.chmod(0o755)
    # Рабочий каталог — СВОЙ, вне дерева проекта: ворота считают своим и
    # процесс, работающий под PROJECT_DIR (ревью безопасности 15.10.2026 — одного
    # uid не хватило, работа в контейнере и под sudo идёт не под нашим
    # пользователем). Запуск из каталога проекта делал самозванца «нашим» по
    # второму признаку, и проба судила бы не то, что проверяет.
    чужой = subprocess.Popen(["setsid", str(самозванец), "60"], cwd=врем,
                             stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    time.sleep(0.4)

    # БОЛЬНОЙ СЛУЧАЙ ПЕРВЫМ: под СВОИМ владельцем такая работа — занятость.
    # Без этого зелень второго случая не стоит ничего: ворота могли не увидеть
    # процесс вовсе (не то имя, не тот порог), и «чужой не мешает» вышло бы
    # само собой.
    код, свой = ворота(двор)
    судить("БОЛЬНОЙ СЛУЧАЙ: своя долгая работа claude — это занятость (rc 1)",
           (код, назван_занятым(чужой.pid, свой)), (1, True))

    # БОЛЬНОЙ СЛУЧАЙ 15.11.2026: та же своя долгая работа (демон claude, 29 мин)
    # отказала пушу в origin master словами «Выкат перезапускает стек…» — шесть
    # коммитов и автопуш стояли час. Пуш стек не перезапускает и чужую работу не
    # убивает: занятость судит только выкат.
    код, пушу = ворота(двор, действие="push")
    судить("БОЛЬНОЙ СЛУЧАЙ: пуш при своей занятости демоном пропущен (rc 0, без отказа «занято:»)",
           (код, "занято:" in пушу, назван_занятым(чужой.pid, пушу)), (0, False, False))

    # Тот же живой процесс, но ворота считают своим ДРУГОГО владельца — значит
    # этот процесс для них чужой, как агент второй установки.
    код, чужому = ворота(двор, свой_uid=str(os.getuid() + 1))
    # Судим только СВОЙ процесс: ворота ответили по делу (rc 0 «идущих работ нет»
    # или rc 1 «занято» — параллельные прогоны в дереве проекта законно держат
    # ворота и под чужим uid) и нашего самозванца не назвали. Отказ разбора
    # (rc 2) сюда не проходит.
    по_делу = (код == 0 and "идущих работ нет" in чужому) or (код == 1 and "занято: " in чужому)
    судить("чужой пользователь не держит наши ворота (ответ по делу, наш процесс не назван)",
           (по_делу, f"процесс {чужой.pid}:" in чужому), (True, False))

    # ВТОРОЙ ПРИЗНАК своим случаем: работа чужого ПОЛЬЗОВАТЕЛЯ, но в НАШЕМ
    # дереве — занятость. Иначе прогон и сборка в контейнере (uid 0/70/999) и
    # работа под sudo воротам не видны, и выкат пойдёт поверх идущей работы
    # (ревью безопасности 15.10.2026, major).
    # «Наше дерево» — то, что судят ворота (PROJECT_DIR установки), а не место
    # пробы: из копии дерева мутационного прогона КОРЕНЬ лежит в /tmp.
    import config as конф
    наше_дерево = конф.из_файла(конф.путь_install_conf()).get("PROJECT_DIR") or КОРЕНЬ
    в_дереве = subprocess.Popen(["setsid", str(самозванец), "60"], cwd=наше_дерево,
                                stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    time.sleep(0.4)
    код, ответ = ворота(двор, свой_uid=str(os.getuid() + 1))
    судить("чужой пользователь, но работа в НАШЕМ дереве — занятость (rc 1)",
           (код, назван_занятым(в_дереве.pid, ответ)), (1, True))
    в_дереве.terminate()
    в_дереве.wait(timeout=5)

    чужой.terminate()
    чужой.wait(timeout=5)

print(f"ИТОГ: плохих {плохо}")
sys.exit(1 if плохо else 0)
