#!/usr/bin/env python3
"""Больной случай 15.10.2026: чужой агент на той же машине держит наши ворота.

На машине стоит ВТОРОЙ харнес под другим пользователем, и
велел его не трогать. Его агент работает постоянно — и ворота выката, обходя
весь `/proc` по имени бинаря, назвали его работу нашей занятостью: «занято:
процесс 280436: claude --dangerously-skip-permissions (131 мин)», отправка в гит
отменена. Чужой агент не перезапустит наш стек и не потеряет нашу работу, а
вечный отказ учит ходить «--силой» — ровно то, от чего замок и ставился.

Проба СОЗДАЁТ условие сама: поднимает процесс с именем `claude`, который ворота
обязаны опознать как долгую работу, и спрашивает их дважды — своим владельцем и
чужим. Двери для этого две, обе ДАННЫЕ: порог долготы (`DEPLOY_BUSY_MIN_SEC`,
иначе пробе пришлось бы ждать две минуты) и свой владелец (`HARNESS_OWN_UID`,
иначе чужого пользователя пришлось бы заводить через sudo, которого на машине
заказчика может не быть).
"""
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile
import time

# Корень — рядом с самим файлом: проба обязана судить ТОТ прибор, с которым
# лежит, иначе раскладка пакета оставит её судить чужую копию.
КОРЕНЬ = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path(__file__).resolve().parent.parent
ПРИБОР = КОРЕНЬ / "scripts" / "deploy_guard.py"

плохо = 0


def судить(зачем: str, вышло, ждём) -> None:
    global плохо
    if вышло == ждём:
        print(f"  ок    {зачем}")
    else:
        плохо += 1
        print(f"  ПЛОХО {зачем}: вышло {вышло!r}, ждали {ждём!r}")


def ворота(двор: pathlib.Path, свой_uid: str | None = None) -> str:
    среда = dict(os.environ, HARNESS_LOG_DIR=str(двор), DEPLOY_BUSY_MIN_SEC="0")
    if свой_uid is not None:
        среда["HARNESS_OWN_UID"] = свой_uid
    готово = subprocess.run([sys.executable, str(ПРИБОР), "push"],
                            capture_output=True, text=True, env=среда, check=False)
    return готово.stdout + готово.stderr


with tempfile.TemporaryDirectory() as врем:
    двор = pathlib.Path(врем)
    (двор / "locks").mkdir(parents=True)

    # Процесс с ИМЕНЕМ claude: ворота опознают работу по имени бинаря, поэтому
    # имя даёт не аргумент, а сам файл. `setsid` отвязывает его от дерева смены —
    # иначе ворота законно сочтут его своим предком и пропустят по другой ветке.
    самозванец = двор / "claude"
    самозванец.write_bytes(pathlib.Path(shutil.which("sleep")).read_bytes())
    самозванец.chmod(0o755)
    # Рабочий каталог — СВОЙ, вне дерева проекта: ворота считают своим и
    # процесс, работающий под PROJECT_DIR (ревью безопасности 15.10.2026 — одного
    # uid не хватило, работа в контейнере и под sudo идёт не под нашим
    # пользователем). Запуск из каталога проекта делал самозванца «нашим» по
    # второму признаку, и проба судила бы не то, что проверяет.
    чужой = subprocess.Popen(["setsid", str(самозванец), "60"], cwd=врем,
                             stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    time.sleep(0.4)

    # БОЛЬНОЙ СЛУЧАЙ ПЕРВЫМ: под СВОИМ владельцем такая работа — занятость.
    # Без этого зелень второго случая не стоит ничего: ворота могли не увидеть
    # процесс вовсе (не то имя, не тот порог), и «чужой не мешает» вышло бы
    # само собой.
    свой = ворота(двор)
    судить("БОЛЬНОЙ СЛУЧАЙ: своя долгая работа claude — это занятость",
           f"процесс {чужой.pid}" in свой, True)

    # Тот же живой процесс, но ворота считают своим ДРУГОГО владельца — значит
    # этот процесс для них чужой, как агент второй установки.
    чужому = ворота(двор, свой_uid=str(os.getuid() + 1))
    судить("чужой пользователь не держит наши ворота",
           f"процесс {чужой.pid}" in чужому, False)

    # ВТОРОЙ ПРИЗНАК своим случаем: работа чужого ПОЛЬЗОВАТЕЛЯ, но в НАШЕМ
    # дереве — занятость. Иначе прогон и сборка в контейнере (uid 0/70/999) и
    # работа под sudo воротам не видны, и выкат пойдёт поверх идущей работы
    # (ревью безопасности 15.10.2026, major).
    в_дереве = subprocess.Popen(["setsid", str(самозванец), "60"], cwd=КОРЕНЬ,
                                stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    time.sleep(0.4)
    ответ = ворота(двор, свой_uid=str(os.getuid() + 1))
    судить("чужой пользователь, но работа в НАШЕМ дереве — занятость",
           f"процесс {в_дереве.pid}" in ответ, True)
    в_дереве.terminate()
    в_дереве.wait(timeout=5)

    чужой.terminate()
    чужой.wait(timeout=5)

print(f"ИТОГ: плохих {плохо}")
sys.exit(1 if плохо else 0)
