def _загрузить(имя: str, путь: Path):
    """Модуль по пути. Грузится ПРИ СТАРТЕ службы, а не при первом запросе:
    ленивая загрузка с кэшем давала гонку (второй поток видел полупустой
    модуль) и заклинивала запись навсегда, если файл на миг был битым
    (ревью кода 13.09.2026, F3-sec-01)."""
    спец = importlib.util.spec_from_file_location(имя, путь)
    модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(модуль)
    return модуль


