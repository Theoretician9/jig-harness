def переключатели() -> list[dict]:
    """Ручки и ТРИ состояния каждой (спека §10.1.4, фаза 4).

    Нечитаемый конфиг раньше выглядел как «значение пустое»: владелец видел
    ручку в умолчании и считал, что так и настроено. Теперь состояние названо:

      значение   — конфиг прочитан, ключ найден;
      умолчание  — конфиг прочитан, ключа в нём нет;
      неизвестно — конфиг не прочитан, и вид рисует ручку серой с причиной.
    """
    готово = []
    for строка in реестр().get("переключатели") or []:
        файл = строка.get("файл", "")
        значение, почему = nastrojki.значение(строка["ключ"], файл)
        if значение is not None:
            состояние = "значение"
        elif "не прочитан" in почему:
            состояние = "неизвестно"
        else:
            состояние = "умолчание"
        готово.append(dict(строка, сейчас=значение,
                           состояние=состояние, почему=почему))
    return готово


class Частота:
    """Сколько запросов пришло с адреса за минуту. Забывает само."""

    def __init__(self):
        self.следы: dict[str, deque] = {}

    def можно(self, адрес: str, потолок: int) -> bool:
        сейчас = time.time()
        след = self.следы.setdefault(адрес, deque())
        while след and сейчас - след[0] > 60:
            след.popleft()
        if len(след) >= потолок:
            return False
        след.append(сейчас)
        return True


