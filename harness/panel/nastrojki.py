#!/usr/bin/env python3
"""Откуда панель узнаёт настройки и куда пишет. Один разбор на всю панель.

Ревью кода 11.09.2026: разборов shell-конфига в панели было три, а «каталог
состояния» считался в четырёх местах разными цепочками окружения. Копия
расходится с оригиналом молча — и панель показывает одно, а служба пишет
другое. Спека `docs/specs/2026-09-11-панель-порядок-в-коде.md`, фаза 2.

Два решения:

* **Пути берутся ПРИ ВЫЗОВЕ, а не при импорте.** Прежняя редакция читала
  окружение на модульном уровне, и проба, выставившая переменные после
  импорта, судила БОЕВЫЕ файлы ([[проба-играет-на-боевом]]).
* **«Панель не знает» — это ответ, а не пустая строка.** `значение()` отдаёт
  пару (значение, причина): None означает, что показывать нечего, и вид рисует
  ручку серой с причиной сверху, вместо того чтобы врать умолчанием.
"""
import os
from pathlib import Path

# Каким файлам панель верит. Имя → переменная окружения и путь по умолчанию.
ФАЙЛЫ = {
    "install.conf": ("HARNESS_INSTALL_CONF", "/etc/harness/install.conf"),
    "harness.conf": ("HARNESS_CONF", "/etc/harness/harness.conf"),
}

# Боевые пути. Здесь, а не в трёх файлах: каталог состояния был записан
# отдельно в vhod.py, klient.py и в CLI — четыре копии одной строки, которые
# расходятся молча (ревью безопасности 13.09.2026, F-sec-08). Паспорт нужен
# тем, кто решает «кто владелец», и для них переменная окружения — не источник:
# путь задаёт тот, кто ЗОВЁТ (F-sec-01 той же ревизии).
СОСТОЯНИЕ_ПАНЕЛИ = Path("/var/lib/harness/panel-state")
ПАСПОРТ_УСТАНОВКИ = Path(ФАЙЛЫ["install.conf"][1])


def пути() -> dict:
    """Пути к конфигам. Читаются при КАЖДОМ вызове: служба и проба вправе
    выставить окружение до первого запроса, а импорт случается раньше."""
    return {имя: Path(os.environ.get(ключ) or умолчание)
            for имя, (ключ, умолчание) in ФАЙЛЫ.items()}


def читать(путь) -> dict:
    """Разбор shell-конфига без исполнения: панели нельзя исполнять чужое.

    Нечитаемый файл — пустой словарь, а не исключение: отличить «нет файла» от
    «нет ключа» умеет `значение()`, и это его работа, а не разбора.
    """
    значения = {}
    try:
        текст = Path(путь).read_text(encoding="utf-8", errors="replace")
    except OSError:
        return значения
    for строка in текст.splitlines():
        строка = строка.strip()
        if not строка or строка.startswith("#") or "=" not in строка:
            continue
        ключ, _, значение_строки = строка.partition("=")
        значения[ключ.strip()] = значение_строки.split("#")[0].strip().strip('"\'')
    return значения


def значение(ключ: str, файл: str = "harness.conf") -> tuple:
    """(значение | None, причина словами). None — панель не знает, и это видно."""
    путь = пути().get(файл)
    if путь is None:
        return None, f"файл «{файл}» панели неизвестен"
    if not Path(путь).exists():
        return None, f"конфиг не прочитан: {путь} не найден"
    значения = читать(путь)
    if not значения:
        return None, f"конфиг не прочитан: {путь} пуст или недоступен"
    if ключ not in значения:
        return None, f"в {Path(путь).name} нет ключа {ключ}"
    return значения[ключ], f"из {Path(путь).name}"


def состояние_дир() -> Path:
    """Приватное состояние панели: её журнал и ожидания подтверждения.

    Отдельный ключ нужен пробам: они поднимают службу на своём каталоге и не
    должны писать в боевой журнал харнеса. Без него — общий журнал.
    """
    return Path(os.environ.get("PANEL_STATE_DIR") or журнал_дир())


def журнал_дир() -> Path:
    """Общий журнал харнеса: его пишут демоны, панель только читает."""
    return Path(os.environ.get("LOG_DIR", "/var/log/harness"))
