#!/usr/bin/env python3
"""Второй рубеж панели: опасное переключение подтверждается кодом в канале.

Владелец 11.09.2026: «Панель должна быть очень безопасной, что хрен взломаешь».
Пропуск в браузере можно украсть вместе с телефоном; доступ к чату владельца —
это второй, независимый ключ. Поэтому опасный переключатель панель не применяет
сама: она заводит ожидание и присылает владельцу вопрос с одноразовым кодом.

Почему у рубежа СВОЙ журнал (находка C3 ревью спеки): диспетчер метит короткое
«да» как согласие «на то, о чём спрашивали», а ворота выката такую метку
засчитывают. Пиши панель в общий `confirmations.jsonl` — её «да» открывало бы
выкат и снос базы. Здесь ответы живут в `панель-ожидания.json`, и слово без
кода не применяет ничего.

Зовётся из диспетчера на каждое входящее:
    python3 harness/panel/podtverzhdenie.py --ответ "да 7391"
"""
import json
import os
import random
import re
import subprocess
import sys
import time
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent.parent
ПИСАТЕЛЬ = КОРЕНЬ / "scripts" / "zapisat-klyuch.py"
ОТПРАВКА = КОРЕНЬ / "scripts" / "tg_send.sh"
ЖИВЁТ_СЕК = 10 * 60
# Шесть знаков, а не четыре: разбор ответа доступен внутренним маршрутом, и
# 9000 попыток по петле перебирались за секунды (ревью безопасности 11.09.2026,
# F-sec-05). Диктовать шесть цифр не тяжелее, а пространство больше в сто раз.
ОТВЕТ = re.compile(r"\b(да|нет|ок|стоп)\b[^\d]{0,12}(\d{4,6})\b", re.IGNORECASE)
# Сколько промахов подряд гасят ВСЕ ожидания: перебор не должен стоить дёшево.
ПРОМАХОВ_ДО_ГАШЕНИЯ = 3
СОГЛАСИЕ = ("да", "ок")


def _лог_дир() -> Path:
    """Каталог состояния панели. PANEL_STATE_DIR — общий для службы и
    диспетчера: ожидание заводит служба, а ответ владельца разбирает
    диспетчер, и смотреть они обязаны в одно место."""
    return Path(os.environ.get("PANEL_STATE_DIR")
                or os.environ.get("LOG_DIR", "/var/log/harness"))


def _файл() -> Path:
    return _лог_дир() / "панель-ожидания.json"


def _ожидания() -> dict:
    try:
        return json.loads(_файл().read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def _сохранить(данные: dict) -> None:
    врем = _файл().with_suffix(".tmp")
    врем.parent.mkdir(parents=True, exist_ok=True)
    врем.write_text(json.dumps(данные, ensure_ascii=False), encoding="utf-8")
    os.replace(врем, _файл())


def _записать_в_журнал(событие: dict) -> None:
    событие = dict(событие, ts=time.strftime("%Y-%m-%dT%H:%M:%S"))
    try:
        with open(_лог_дир() / "панель.jsonl", "a", encoding="utf-8") as fh:
            fh.write(json.dumps(событие, ensure_ascii=False) + "\n")
    except OSError:
        pass


def _сказать(текст: str) -> None:
    """Сообщение владельцу. Пустой PANEL_TG_SEND — проверка, молчим."""
    если_молчим = os.environ.get("PANEL_TG_SEND") == ""
    if если_молчим or not ОТПРАВКА.exists():
        return
    try:
        subprocess.run(["bash", str(ОТПРАВКА), текст], timeout=30,
                       capture_output=True)
    except (OSError, subprocess.SubprocessError):
        pass


def _файл_промахов():
    return _лог_дир() / "панель-промахи"


def _промах() -> int:
    """Счётчик неудачных кодов подряд. Живёт файлом: разбор идёт процессом на
    сообщение, и переменная в памяти не пережила бы ни одной попытки."""
    было = 0
    try:
        было = int(_файл_промахов().read_text(encoding="utf-8").strip() or 0)
    except (OSError, ValueError):
        было = 0
    стало = было + 1
    try:
        _файл_промахов().write_text(str(стало), encoding="utf-8")
    except OSError:
        pass
    return стало


def _сбросить_промахи() -> None:
    try:
        _файл_промахов().unlink(missing_ok=True)
    except OSError:
        pass


def завести(ключ: str, значение: str, имя: str = "") -> str:
    """Завести ожидание и спросить владельца. Возвращает код подтверждения."""
    ожидания = {к: з for к, з in _ожидания().items()
                if time.time() - з.get("ts", 0) <= ЖИВЁТ_СЕК}
    код = f"{random.SystemRandom().randrange(100000, 1000000)}"
    ожидания[код] = {"ключ": ключ, "значение": значение, "ts": time.time()}
    _сохранить(ожидания)
    _сказать(f"Переключить «{имя or ключ}» на «{значение}»? "
             f"Ответь: да {код}. Если это не ты — ответь: нет {код}.")
    _записать_в_журнал({"событие": "ожидание", "ключ": ключ, "значение": значение})
    return код


def ответ(текст: str):
    """Разобрать ответ владельца.

    Возвращает True — применено, False — отказ снят, None — это не ответ
    панели (и тогда сообщение идёт своим обычным путём).
    """
    найдено = ОТВЕТ.search(текст or "")
    if not найдено:
        return None
    слово, код = найдено.group(1).lower(), найдено.group(2)
    ожидания = _ожидания()
    запись = ожидания.get(код)
    if not запись:
        # Промах: код не из наших ожиданий. Три подряд — гасим всё и говорим
        # владельцу: значит кто-то подбирает (F-sec-05).
        промахов = _промах()
        if промахов >= ПРОМАХОВ_ДО_ГАШЕНИЯ and ожидания:
            _сохранить({})
            _сбросить_промахи()
            _сказать("Кто-то подбирал код подтверждения — все вопросы сняты. "
                     "Если это были вы, переключите ещё раз на панели.")
            _записать_в_журнал({"событие": "гашение по промахам",
                                "промахов": промахов})
        return None
    _сбросить_промахи()
    ожидания.pop(код, None)
    _сохранить(ожидания)                      # код расходуется в любом случае
    if time.time() - запись.get("ts", 0) > ЖИВЁТ_СЕК:
        _сказать("Вопрос устарел — переключи ещё раз на панели.")
        _записать_в_журнал({"событие": "ожидание просрочено", **запись})
        return None
    if слово not in СОГЛАСИЕ:
        _сказать(f"Понял, «{запись['ключ']}» оставляю как было.")
        _записать_в_журнал({"событие": "отказ владельца", **запись})
        return False
    готово = subprocess.run(
        [sys.executable, str(ПИСАТЕЛЬ), запись["ключ"], запись["значение"]],
        capture_output=True, text=True, timeout=30)
    if готово.returncode != 0:
        причина = (готово.stderr or готово.stdout).strip()
        _сказать(f"Переключить не вышло: {причина}")
        _записать_в_журнал({"событие": "переключение не удалось", **запись,
                            "причина": причина})
        return None
    _сказать(f"Готово: «{запись['ключ']}» теперь «{запись['значение']}».")
    _записать_в_журнал({"событие": "переключено по подтверждению", **запись})
    return True


def main(argv: list[str]) -> int:
    if "--ответ" in argv:
        итог = ответ(argv[argv.index("--ответ") + 1])
        print({True: "применено", False: "отказ", None: "не ответ панели"}[итог])
        return 0
    print(__doc__)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
