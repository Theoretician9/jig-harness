#!/usr/bin/env python3
"""Проверка входа в панель: что пускает и, главное, чего НЕ пускает.

Каждый путь — из находки adversarial-ревью спеки панели (11.09.2026):

  C4 — «использованием» ссылки считается ОБМЕН токена на сессию, а не открытие
       страницы: предпросмотр Telegram открывает ссылку сам и сжёг бы вход до
       владельца;
  I13 — обмен атомарен: два параллельных запроса (браузер плюс предзагрузка)
       обязаны дать ровно одну сессию, а не две и не ноль;
  I10 — сессии переживают перезапуск службы, а смена ключа подписи отзывает их
       все разом;
  C6 — подделанная подпись cookie не пускает;
  5.15 — файлы входа лежат правами 600: в них ключи.

Прогон:
    python3 harness/panel/test_vhod.py
"""
import concurrent.futures
import os
import sys
import tempfile
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

путей = 0
неудач = 0


def путь_ок(текст):
    global путей
    путей += 1
    print("ок  · " + текст)


def путь_плохо(текст):
    global путей, неудач
    путей += 1
    неудач += 1
    print("ПЛОХО · " + текст)


try:
    import vhod
except ImportError as беда:
    путь_плохо(f"модуля входа нет: {беда}")
    print(f"ВХОД-ПАНЕЛИ: путей {путей}, неудач {неудач}")
    sys.exit(1)


def стенд(врем: Path) -> "vhod.Вход":
    return vhod.Вход(каталог=врем, chat_id="100000001")


with tempfile.TemporaryDirectory() as tmp:
    врем = Path(tmp)
    вход = стенд(врем)

    # Выдача: ссылка только владельцу, чужому чату — ничего.
    токен = вход.выдать_токен("100000001")
    if токен and len(токен) >= 32:
        путь_ок(f"токен владельцу выдан ({len(токен)} знаков)")
    else:
        путь_плохо(f"токен не выдан: {токен!r}")

    if вход.выдать_токен("999000111") is None:
        путь_ок("БОЛЬНОЙ СЛУЧАЙ: чужому чату ссылка не выдаётся")
    else:
        путь_плохо("чужому чату выдана ссылка входа")

    # Открытие страницы токен НЕ гасит: иначе предпросмотр Telegram сжигает вход.
    if вход.жив(токен):
        путь_ок("БОЛЬНОЙ СЛУЧАЙ: токен жив после простого взгляда (предпросмотр)")
    else:
        путь_плохо("токен погас до обмена — предпросмотр сожжёт вход")

    # Обмен атомарен: десять одновременных попыток дают РОВНО одну сессию.
    with concurrent.futures.ThreadPoolExecutor(max_workers=10) as пул:
        итоги = list(пул.map(lambda _: вход.обменять(токен, "127.0.0.1"), range(10)))
    удачи = [и for и in итоги if и]
    if len(удачи) == 1:
        путь_ок("БОЛЬНОЙ СЛУЧАЙ: десять одновременных обменов — ровно одна сессия")
    else:
        путь_плохо(f"одновременные обмены дали {len(удачи)} сессий — гонка")

    сессия = удачи[0] if удачи else None
    if сессия and вход.проверить(сессия):
        путь_ок("сессия после обмена действительна")
    else:
        путь_плохо("сессия после обмена не признана")

    if вход.обменять(токен, "127.0.0.1") is None:
        путь_ок("повторный обмен того же токена отвергнут")
    else:
        путь_плохо("тот же токен обменян дважды")

    # Подделка подписи.
    if сессия:
        подделка = сессия[:-3] + ("abc" if not сессия.endswith("abc") else "xyz")
        if not вход.проверить(подделка):
            путь_ок("БОЛЬНОЙ СЛУЧАЙ: подделанная подпись не пускает")
        else:
            путь_плохо("подделанная подпись признана действительной")

    # Перезапуск службы: сессии лежат на диске и переживают его.
    вход2 = стенд(врем)
    if сессия and вход2.проверить(сессия):
        путь_ок("сессия пережила перезапуск службы")
    else:
        путь_плохо("перезапуск обнулил пропуска — владельца выкинуло без причины")

    # Права файлов: в них ключи.
    # Посторонним — ничего. Группа нужна: токен пишет одна сторона, читает
    # другая, и обе живут в закрытом каталоге с общей группой.
    плохие = [п.name for п in врем.rglob("*") if п.is_file()
              and os.stat(п).st_mode & 0o007]
    if not плохие:
        путь_ок("файлы входа закрыты от посторонних")
    else:
        путь_плохо(f"файлы входа читаемы посторонним: {плохие}")

    # Отзыв: «выйти со всех устройств».
    вход2.отозвать_всё()
    if сессия and not вход2.проверить(сессия):
        путь_ок("отзыв гасит все сессии разом")
    else:
        путь_плохо("после отзыва сессия всё ещё действует")

    # Просроченный токен.
    токен2 = вход.выдать_токен("100000001")
    вход.ТОКЕН_ЖИВЁТ_СЕК = 0
    time.sleep(0.01)
    if вход.обменять(токен2, "127.0.0.1") is None:
        путь_ок("БОЛЬНОЙ СЛУЧАЙ: просроченный токен не пускает")
    else:
        путь_плохо("просроченный токен пустил в панель")

    # Выдуманный токен.
    if вход.обменять("выдуманный-токен-которого-не-было", "127.0.0.1") is None:
        путь_ок("выдуманный токен не пускает")
    else:
        путь_плохо("выдуманный токен пустил в панель")

# ── запасной вход долгим кодом: когда канал мёртв (I9 ревью спеки) ──────────
with tempfile.TemporaryDirectory() as tmp:
    врем = Path(tmp)
    вход = стенд(врем)

    код = вход.завести_запасной_код()
    if код and len(код) >= 20:
        путь_ок(f"запасной код заведён, длина {len(код)}")
    else:
        путь_плохо(f"запасной код не заведён: {код!r}")

    файл_кода = врем / "запасной-код"
    хранимое = файл_кода.read_text(encoding="utf-8") if файл_кода.exists() else ""
    if файл_кода.exists() and код not in хранимое:
        путь_ок("БОЛЬНОЙ СЛУЧАЙ: сам код на диске не хранится — только его отпечаток")
    else:
        путь_плохо("код лежит на диске открытым текстом")

    права = oct(файл_кода.stat().st_mode)[-3:] if файл_кода.exists() else "---"
    if права.endswith("0"):
        путь_ок(f"файл запасного кода закрыт от посторонних (права {права})")
    else:
        путь_плохо(f"файл кода открыт посторонним: права {права}")

    первая = вход.войти_запасным(код, "127.0.0.1")
    if первая.get("ждать") and not первая.get("пропуск"):
        путь_ок(f"верный код сразу НЕ пускает: ждать {первая['ждать']} с")
    else:
        путь_плохо(f"верный код пустил мгновенно: {первая}")

    сразу = вход.войти_запасным(код, "127.0.0.1")
    if not сразу.get("пропуск"):
        путь_ок("БОЛЬНОЙ СЛУЧАЙ: повтор до конца задержки тоже не пускает")
    else:
        путь_плохо("повтор до конца задержки выдал пропуск")

    чужой = вход.войти_запасным("СОВСЕМ-ДРУГОЙ-КОД-1234", "127.0.0.1")
    if not чужой.get("пропуск") and not чужой.get("ждать"):
        путь_ок("БОЛЬНОЙ СЛУЧАЙ: неверный код не пускает и не заводит ожидания")
    else:
        путь_плохо(f"неверный код принят: {чужой}")

    # Задержка прошла: подделываем время заявки, а не спим минуту.
    вход.сдвинуть_заявку(-vhod.ЗАПАСНОЙ_ЖДЁТ_СЕК - 1)
    после = вход.войти_запасным(код, "127.0.0.1")
    пропуск = после.get("пропуск")
    if пропуск and вход.проверить(пропуск):
        путь_ок("после задержки тот же код пускает")
    else:
        путь_плохо(f"после задержки код не пустил: {после}")

    if вход.запасная(пропуск):
        путь_ок("сессия помечена запасной — опасное ей недоступно")
    else:
        путь_плохо("сессия запасного входа неотличима от обычной")

    # Обычная сессия запасной НЕ считается.
    токен = вход.выдать_токен("100000001")
    обычный = вход.обменять(токен, "127.0.0.1")
    if обычный and not вход.запасная(обычный):
        путь_ок("сессия из канала запасной не считается")
    else:
        путь_плохо("сессия из канала помечена запасной")

    # Заявка одноразовая: после входа она погашена.
    вход.сдвинуть_заявку(-vhod.ЗАПАСНОЙ_ЖДЁТ_СЕК - 1)
    повтор = вход.войти_запасным(код, "127.0.0.1")
    if not повтор.get("пропуск"):
        путь_ок("БОЛЬНОЙ СЛУЧАЙ: погашенная заявка второй сессии не даёт")
    else:
        путь_плохо("погашенная заявка выдала вторую сессию")

    # Каждая попытка оставляет след: владелец узнает о входе, даже проспав его.
    события = вход.события_запасного()
    if len(события) >= 3 and any(с.get("исход") == "отказ" for с in события):
        путь_ок(f"каждая попытка записана: событий {len(события)}")
    else:
        путь_плохо(f"следа попыток нет: {события}")

    # Повторная установка НЕ имеет права выпустить второй код молча: владелец
    # хранит тот, который получил при первой (ревью кода 13.09.2026, F-21).
    if вход.запасной_код_заведён():
        путь_ок("выпущенный код виден: повторный прогон шага его не затрёт")
    else:
        путь_плохо("признак «код уже заведён» ложен — установка выпустит второй")

    # Смена кода отменяет прежний.
    новый = вход.завести_запасной_код()
    вход.сдвинуть_заявку(-vhod.ЗАПАСНОЙ_ЖДЁТ_СЕК - 1)
    старым = вход.войти_запасным(код, "127.0.0.1")
    if not старым.get("пропуск") and новый != код:
        путь_ок("новый код отменяет прежний")
    else:
        путь_плохо("прежний код работает после смены")

print("── CLI: право не берётся из окружения ──")
# БОЛЬНОЙ СЛУЧАЙ (ревизия безопасности 12.09.2026, находка 3): `--ссылка`
# сверяла chat_id с файлом, путь к которому назвал сам вызывающий
# (HARNESS_INSTALL_CONF), а токен клала в НАСТОЯЩИЙ каталог — годная ссылка
# входа доставалась любому, кто может запустить файл. Путь убран: вход выдаёт
# служба, она доказывает право внутренним ключом.
import subprocess          # noqa: E402  (проба CLI — боевым вызовом, не импортом)
import tempfile            # noqa: E402

CLI = str(Path(__file__).resolve().parent / "vhod.py")
with tempfile.TemporaryDirectory() as врем_cli:
    чужой = Path(врем_cli) / "install.conf"
    чужой.write_text('TG_CHAT_ID="999999999"\n', encoding="utf-8")
    окружение = dict(os.environ,
                     HARNESS_INSTALL_CONF=str(чужой),
                     PANEL_SECRETS_DIR=врем_cli)
    for довод in ("--ссылка", "--выйти"):
        вышло = subprocess.run([sys.executable, CLI, довод, "999999999"],
                               capture_output=True, text=True, env=окружение,
                               timeout=60)
        сказано = (вышло.stdout + вышло.stderr)
        if вышло.returncode == 2 and "служба" in сказано and "vhod?t=" not in сказано:
            путь_ок(f"{довод} с подставленным паспортом ссылки не даёт: код 2")
        else:
            путь_плохо(f"{довод} отдал «{сказано.strip()[:80]}» (код {вышло.returncode})")

# Второй носитель: ПУТИ, которыми пользуется единственная оставшаяся команда
# CLI. Проба зовёт `--пути` подпроцессом с подставленным окружением — так
# ловится возврат `os.environ.get` и в константу, и внутрь `--запасной-код`
# (ревью безопасности 13.09.2026, F-sec-01: прежняя редакция сверяла значения
# констант после reload и мутацию в самой команде не видела).
with tempfile.TemporaryDirectory() as врем_путей:
    окружение_путей = dict(os.environ,
                           HARNESS_INSTALL_CONF=f"{врем_путей}/install.conf",
                           SECRETS_DIR=врем_путей, PANEL_SECRETS_DIR=врем_путей)
    вышло = subprocess.run([sys.executable, CLI, "--пути"], capture_output=True,
                           text=True, env=окружение_путей, timeout=60)
    сказано = вышло.stdout
    боевые = ("паспорт: /etc/harness/install.conf" in сказано
              and "состояние: /var/lib/harness/panel-state" in сказано)
    if вышло.returncode == 0 and боевые and врем_путей not in сказано:
        путь_ок("пути CLI боевые при любом окружении: право задаёт машина, не вызывающий")
    else:
        путь_плохо(f"окружение переставило пути CLI: «{сказано.strip()[:90]}» "
                   f"(код {вышло.returncode})")

    # Та же команда с подставленным окружением НЕ создаёт состояние в чужом
    # каталоге: если бы каталог брался из переменной, здесь появились бы файлы.
    if not list(Path(врем_путей).iterdir()):
        путь_ок("CLI ничего не пишет в подставленный каталог")
    else:
        путь_плохо(f"CLI записал в подставленный каталог: {list(Path(врем_путей).iterdir())}")

# Поведение ЕДИНСТВЕННОЙ оставшейся команды — на КОПИИ модуля с отведёнными
# константами: живой `--запасной-код` тронул бы секрет владельца (И-1), а
# судить эту команду надо — прежние пробы её не касались вовсе, и мутация
# «взять каталог из окружения» оставалась зелёной (F-sec-01, F-sec-02).
with tempfile.TemporaryDirectory() as свой, tempfile.TemporaryDirectory() as ловушка:
    дерево = Path(свой) / "код"
    дерево.mkdir()
    for имя in ("vhod.py", "nastrojki.py"):
        (дерево / имя).write_text(
            (Path(CLI).parent / имя).read_text(encoding="utf-8"), encoding="utf-8")
    состояние = Path(свой) / "состояние"
    состояние.mkdir()
    копия = дерево / "vhod.py"
    копия.write_text(копия.read_text(encoding="utf-8").replace(
        "СОСТОЯНИЕ_ПАНЕЛИ = nastrojki.СОСТОЯНИЕ_ПАНЕЛИ",
        f'СОСТОЯНИЕ_ПАНЕЛИ = Path("{состояние}")', 1), encoding="utf-8")
    # Окружение ведёт в ЛОВУШКУ: если команда возьмёт каталог оттуда, файл
    # ляжет не туда, где его ищет проба, — и это увидят все три пути ниже.
    окружение_кода = dict(os.environ, PANEL_SECRETS_DIR=ловушка, SECRETS_DIR=ловушка,
                          HARNESS_INSTALL_CONF=f"{ловушка}/install.conf")

    def позвать_код(*доводы):
        return subprocess.run([sys.executable, str(копия), "--запасной-код", *доводы],
                              capture_output=True, text=True, env=окружение_кода,
                              timeout=60)

    первый = позвать_код()
    файл_кода = состояние / "запасной-код"
    if первый.returncode == 0 and файл_кода.exists() and not list(Path(ловушка).iterdir()):
        путь_ок("запасной код заводится в своём каталоге, окружение его не уводит")
    else:
        путь_плохо(f"первый выпуск: код {первый.returncode}, свой файл "
                   f"{файл_кода.exists()}, в ловушке {list(Path(ловушка).iterdir())}")

    def содержимое() -> str:
        """Пусто, если файла нет: проба обязана сказать «ПЛОХО», а не оборваться
        трассировкой — упавшая в подготовке проверка не проверяет ничего
        (память: [[проверка-падает-в-setup]], ревью 13.09.2026 F-sec-07)."""
        try:
            return файл_кода.read_text(encoding="utf-8")
        except OSError:
            return ""

    было = содержимое()
    второй = позвать_код()
    стало = содержимое()
    if второй.returncode == 4 and стало == было:
        путь_ок("повторный прогон прежний код НЕ отменяет: отказ кодом 4")
    else:
        путь_плохо(f"повторный прогон перевыпустил код молча (код {второй.returncode})")

    третий = позвать_код("--перевыпустить")
    if третий.returncode == 0 and содержимое() not in ("", было):
        путь_ок("явное --перевыпустить код меняет")
    else:
        путь_плохо(f"--перевыпустить код не сменил (код {третий.returncode})")

print(f"ВХОД-ПАНЕЛИ: путей {путей}, неудач {неудач}")
sys.exit(1 if неудач else 0)
