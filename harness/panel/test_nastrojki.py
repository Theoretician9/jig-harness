#!/usr/bin/env python3
"""Проверка единственного разбора настроек панели.

Откуда взято. Ревью кода панели 11.09.2026: разборов shell-конфига в панели
три, «каталог состояния» считается в четырёх местах разными цепочками
окружения. Спека `docs/specs/2026-09-11-панель-порядок-в-коде.md`, фаза 2.

Главное, что проверяется: пути читаются ПРИ ВЫЗОВЕ, а не при импорте модуля.
Прежняя редакция брала их в момент import, и проба, выставившая окружение
после импорта, судила боевые файлы.

Прогон:
    python3 harness/panel/test_nastrojki.py
Код возврата: 0 — все пути прошли, 1 — есть упавший.
"""
import importlib.util
import os
import shutil
import sys
import tempfile
from pathlib import Path

ЗДЕСЬ = Path(__file__).resolve().parent
путей = неудач = 0


def путь_ок(текст: str) -> None:
    global путей
    путей += 1
    print("ок  · " + текст)


def путь_плохо(текст: str) -> None:
    global путей, неудач
    путей += 1
    неудач += 1
    print("ПЛОХО · " + текст)


спец = importlib.util.spec_from_file_location("настройки", ЗДЕСЬ / "nastrojki.py")
настройки = importlib.util.module_from_spec(спец)
спец.loader.exec_module(настройки)

двор = Path(tempfile.mkdtemp(prefix="настройки-"))
try:
    конф = двор / "harness.conf"
    конф.write_text(
        '# комментарий\n'
        'ROTATE_AT=75            # с хвостом-комментарием\n'
        'PANEL_URL="https://пример"\n'
        "AGENT_LEVEL='минимум'\n"
        'ПУСТО=\n'
        'кривая строка без равно\n', encoding="utf-8")

    print("── разбор ──")
    значения = настройки.читать(конф)
    проверки = [
        ("число с хвостовым комментарием", значения.get("ROTATE_AT") == "75"),
        ("двойные кавычки сняты", значения.get("PANEL_URL") == "https://пример"),
        ("одинарные кавычки сняты", значения.get("AGENT_LEVEL") == "минимум"),
        ("пустое значение — пустая строка, а не пропажа", значения.get("ПУСТО") == ""),
        ("строка без «=» не ломает разбор", "кривая строка без равно" not in значения),
    ]
    for имя, ок in проверки:
        (путь_ок if ок else путь_плохо)(имя)

    print("── нечитаемый файл: пусто, а не исключение ──")
    пусто = настройки.читать(двор / "нет-такого.conf")
    (путь_ок if пусто == {} else путь_плохо)("файла нет — пустой словарь")

    print("── пути берутся ПРИ ВЫЗОВЕ ──")
    os.environ["HARNESS_CONF"] = str(конф)
    os.environ["HARNESS_INSTALL_CONF"] = str(двор / "install.conf")
    пути = настройки.пути()
    if str(пути.get("harness.conf")) == str(конф):
        путь_ок("окружение, выставленное ПОСЛЕ импорта, учтено")
    else:
        путь_плохо(f"путь взят при импорте: {пути}")

    print("── значение ключа: три состояния ──")
    зн, почему = настройки.значение("ROTATE_AT", "harness.conf")
    (путь_ок if зн == "75" else путь_плохо)(f"ключ найден: {зн} ({почему})")

    зн, почему = настройки.значение("НЕТ_ТАКОГО", "harness.conf")
    if зн is None and "нет" in почему.lower():
        путь_ок(f"ключа нет — None и причина словами: {почему}")
    else:
        путь_плохо(f"отсутствующий ключ: {зн}, {почему}")

    os.environ["HARNESS_CONF"] = str(двор / "пропал.conf")
    зн, почему = настройки.значение("ROTATE_AT", "harness.conf")
    if зн is None and "проч" in почему.lower():
        путь_ок(f"конфиг не прочитан — None и причина: {почему}")
    else:
        путь_плохо(f"нечитаемый конфиг: {зн}, {почему}")

    print("── каталоги: состояние панели и общий журнал — РАЗНЫЕ ──")
    os.environ["PANEL_STATE_DIR"] = str(двор / "своё")
    os.environ["LOG_DIR"] = str(двор / "общее")
    if настройки.состояние_дир() != настройки.журнал_дир():
        путь_ок(f"состояние {настройки.состояние_дир().name} ≠ журнал {настройки.журнал_дир().name}")
    else:
        путь_плохо("каталог состояния совпал с общим журналом")

    del os.environ["PANEL_STATE_DIR"]
    if настройки.состояние_дир() == настройки.журнал_дир():
        путь_ок("без своей настройки состояние падает на общий журнал")
    else:
        путь_плохо("без PANEL_STATE_DIR каталоги разъехались")
finally:
    shutil.rmtree(двор, ignore_errors=True)

print(f"\nитого путей {путей}, неудач {неудач}")
sys.exit(1 if неудач else 0)
