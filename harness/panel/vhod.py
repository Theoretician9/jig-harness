#!/usr/bin/env python3
"""Вход в панель: доказательство через канал, а не пароль.

Владелец 11.09.2026: «Панель должна быть очень безопасной, что хрен взломаешь».
Пароля у панели нет намеренно — его подбирают, крадут и переиспользуют.
Владелец доказывает себя тем же, чем каждый день: пишет боту в СВОЙ чат. Бот
отвечает одноразовой ссылкой, ссылка меняется на сессию, сессия живёт неделю.

Четыре решения, каждое под находку adversarial-ревью спеки (11.09.2026):

  • **токен гасит ОБМЕН, а не взгляд** (C4). Telegram открывает присланные
    ссылки сам, чтобы показать предпросмотр, — вход, сгорающий от открытия
    страницы, не сработал бы ни разу. Поэтому GET ничего не тратит, а сессию
    создаёт отдельный шаг;
  • **обмен атомарен** (I13): токен — файл, обмен — `os.rename` этого файла.
    Переименование удаётся ровно одному из параллельных запросов, остальные
    получают отказ. Два клика (или клик плюс предзагрузка) не дадут двух сессий;
  • **сессии лежат на диске** (I10): перезапуск службы не выкидывает владельца,
    а смена ключа подписи отзывает все пропуска разом — это и есть «выйти со
    всех устройств»;
  • **подпись проверяется постоянным по времени сравнением** (C6): cookie
    подписана HMAC-SHA256, ключ — в каталоге секретов правами 600.
"""
import hashlib
import hmac
import json
import os
import secrets
import sys
import time
from pathlib import Path

import nastrojki

# Сколько живёт ссылка из бота и сколько — сессия в браузере.
ТОКЕН_ЖИВЁТ_СЕК = 10 * 60
СЕССИЯ_ЖИВЁТ_СЕК = 7 * 24 * 3600
# Запасной вход: код длинный, а вход по нему — с выдержкой. Выдержка нужна не
# от подбора (код длиннее любого перебора), а чтобы владелец успел увидеть
# сообщение о чужой попытке ДО того, как она чем-то кончится.
ЗАПАСНОЙ_ЖДЁТ_СЕК = 60
ЗАЯВКА_ЖИВЁТ_СЕК = 15 * 60
# Азбука без похожих знаков: код диктуют голосом и переписывают с бумаги.
АЗБУКА = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"

# Боевые пути — из общего модуля настроек. Для CLI они единственные: путь из
# переменной окружения задаёт тот, кто ЗОВЁТ, а в CLI решается «кто владелец» —
# проверка «chat_id совпал с паспортом» вырождалась в тавтологию: кто подставил
# файл, тот и владелец (ревизия безопасности 12.09.2026, находка 3). Окружение
# осталось у СЛУЖБЫ и у проб: они создают `Вход` со своим каталогом прямо.
ПАСПОРТ_УСТАНОВКИ = nastrojki.ПАСПОРТ_УСТАНОВКИ
СОСТОЯНИЕ_ПАНЕЛИ = nastrojki.СОСТОЯНИЕ_ПАНЕЛИ


def каталог_секретов() -> Path:
    """Где лежат токены входа, сессии и ключ подписи.

    Каталог ОБЩИЙ для службы панели и для диспетчера: ссылку выдаёт диспетчер
    (от своего пользователя), а обменивает её служба (от своего). Смотри они в
    разные каталоги — выданная ссылка не открывала бы ничего.
    """
    return Path(os.environ.get("PANEL_SECRETS_DIR")
                or os.environ.get("SECRETS_DIR")
                or СОСТОЯНИЕ_ПАНЕЛИ)


def _записать_тайно(путь: Path, данные: str) -> None:
    """Атомарная запись файла без прав для посторонних.

    Права 660, а не 600: файлы входа пишут ДВЕ стороны — диспетчер выдаёт
    токен от своего пользователя, служба обменивает его от своего. Общая
    группа задана каталогом с setgid, а посторонним не видно ничего: сам
    каталог закрыт (2770).
    """
    врем = путь.with_suffix(путь.suffix + ".tmp")
    дескриптор = os.open(врем, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o660)
    with os.fdopen(дескриптор, "w", encoding="utf-8") as fh:
        fh.write(данные)
    os.replace(врем, путь)


class Вход:
    """Токены входа и сессии панели. Каталог — из SECRETS_DIR."""

    def __init__(self, каталог: Path, chat_id: str):
        self.каталог = Path(каталог)
        self.токены = self.каталог / "панель-токены"
        self.сессии_файл = self.каталог / "панель-сессии.json"
        self.ключ_файл = self.каталог / "панель-ключ-подписи"
        self.внутренний_файл = self.каталог / "панель-внутренний-ключ"
        self.запасной_файл = self.каталог / "запасной-код"
        self.заявка_файл = self.каталог / "запасная-заявка.json"
        self.события_файл = self.каталог / "запасной-вход.jsonl"
        self.chat_id = str(chat_id)
        self.ТОКЕН_ЖИВЁТ_СЕК = ТОКЕН_ЖИВЁТ_СЕК
        self.токены.mkdir(parents=True, exist_ok=True)
        try:
            os.chmod(self.токены, 0o2770)
        except PermissionError:
            pass          # каталог завела другая сторона — права уже её
        if not self.ключ_файл.exists():
            _записать_тайно(self.ключ_файл, secrets.token_urlsafe(32))

    # ── ключ подписи ────────────────────────────────────────────────────────
    @property
    def ключ(self) -> bytes:
        return self.ключ_файл.read_text(encoding="utf-8").strip().encode()

    def сменить_ключ(self) -> None:
        """Отзывает ВСЕ выданные пропуска: их подписи перестают сходиться."""
        _записать_тайно(self.ключ_файл, secrets.token_urlsafe(32))

    def внутренний_ключ(self) -> str:
        """Общий секрет службы и диспетчера для маршрутов /vnutr/.

        Ревью безопасности 11.09.2026 (F-sec-01): признак «запрос с петли и без
        X-Real-IP» различает «мимо nginx» и «через nginx», а НЕ «своя сторона»
        и «чужой процесс». Любая учётка машины брала одноразовую ссылку входа
        и получала сессию владельца. Доказательство права — ключ; петля
        осталась дополнением, а не доказательством.
        """
        if not self.внутренний_файл.exists():
            _записать_тайно(self.внутренний_файл, secrets.token_urlsafe(32))
        return self.внутренний_файл.read_text(encoding="utf-8").strip()

    # ── токены входа ────────────────────────────────────────────────────────
    def выдать_токен(self, chat_id: str) -> str | None:
        """Одноразовый токен владельцу. Чужому чату — None, и это не ошибка."""
        if str(chat_id) != self.chat_id:
            return None
        токен = secrets.token_urlsafe(32)
        _записать_тайно(self.токены / токен, json.dumps({"ts": time.time()}))
        return токен

    def жив(self, токен: str) -> bool:
        """Токен ещё можно обменять. Взгляд ничего не тратит (C4)."""
        файл = self.токены / токен
        if not self._свой(файл) or not файл.exists():
            return False
        return time.time() - self._выдан(файл) <= self.ТОКЕН_ЖИВЁТ_СЕК

    def обменять(self, токен: str, откуда: str) -> str | None:
        """Токен → подписанная сессия. Ровно один раз, даже при гонке (I13)."""
        файл = self.токены / токен
        if not self._свой(файл):
            return None
        забрано = файл.with_name(файл.name + ".обменян")
        try:
            os.rename(файл, забрано)          # атомарно: успевает ровно один
        except OSError:
            return None
        try:
            выдан = json.loads(забрано.read_text(encoding="utf-8")).get("ts", 0)
        except (OSError, ValueError):
            выдан = 0
        забрано.unlink(missing_ok=True)
        if time.time() - выдан > self.ТОКЕН_ЖИВЁТ_СЕК:
            return None
        return self._завести_сессию(откуда)

    def _свой(self, файл: Path) -> bool:
        """Имя токена не выводит за каталог: путей на входе панели нет."""
        try:
            return файл.resolve().parent == self.токены.resolve()
        except OSError:
            return False

    def _выдан(self, файл: Path) -> float:
        try:
            return json.loads(файл.read_text(encoding="utf-8")).get("ts", 0)
        except (OSError, ValueError):
            return 0

    # ── запасной вход: канал мёртв, а панель нужна ──────────────────────────
    def запасной_код_заведён(self) -> bool:
        """Код уже выпущен. Новый отменил бы прежний — и молча."""
        return self.запасной_файл.exists()

    def завести_запасной_код(self) -> str:
        """Новый долгий код. Возвращается ОДИН раз, на диск ложится отпечаток.

        Файл секретов читает тот, кто попал на машину; код, лежащий там
        открытым, был бы вторым паролем без второго рубежа.
        """
        код = "-".join("".join(secrets.choice(АЗБУКА) for _ in range(5))
                       for _ in range(5))
        соль = secrets.token_hex(16)
        _записать_тайно(self.запасной_файл, json.dumps(
            {"соль": соль, "отпечаток": self._отпечаток(код, соль),
             "заведён": time.time()}))
        self.заявка_файл.unlink(missing_ok=True)
        return код

    @staticmethod
    def _отпечаток(код: str, соль: str) -> str:
        return hashlib.scrypt(код.encode(), salt=соль.encode(),
                              n=2 ** 14, r=8, p=1, dklen=32).hex()

    def _код_сходится(self, код: str) -> bool:
        try:
            хранимое = json.loads(self.запасной_файл.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return False
        свой = self._отпечаток(код.strip().upper(), хранимое.get("соль", ""))
        return hmac.compare_digest(свой, хранимое.get("отпечаток", ""))

    def войти_запасным(self, код: str, откуда: str) -> dict:
        """Две попытки с выдержкой: первая заводит заявку, вторая пускает.

        Ответ — словарь: «ждать» (сколько секунд), «пропуск» (когда пустили)
        или «беда» (когда не пустили и не будут).
        """
        if not self._код_сходится(код):
            self._записать_событие(откуда, "отказ")
            return {"беда": "код не подходит"}
        заявка = self._заявка()
        сейчас = time.time()
        если_свежая = заявка and сейчас - заявка.get("ts", 0) <= ЗАЯВКА_ЖИВЁТ_СЕК
        if not если_свежая:
            _записать_тайно(self.заявка_файл,
                            json.dumps({"ts": сейчас, "откуда": откуда}))
            self._записать_событие(откуда, "заявка")
            return {"ждать": ЗАПАСНОЙ_ЖДЁТ_СЕК}
        ждать = ЗАПАСНОЙ_ЖДЁТ_СЕК - (сейчас - заявка["ts"])
        if ждать > 0:
            return {"ждать": int(ждать) + 1}
        self.заявка_файл.unlink(missing_ok=True)
        self._записать_событие(откуда, "вход")
        return {"пропуск": self._завести_сессию(откуда, запасная=True)}

    def _заявка(self) -> dict:
        try:
            return json.loads(self.заявка_файл.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return {}

    def сдвинуть_заявку(self, секунд: float) -> None:
        """Сдвиг времени заявки — только для проверок: минуту никто не ждёт."""
        заявка = self._заявка()
        if заявка:
            заявка["ts"] = заявка.get("ts", 0) + секунд
            _записать_тайно(self.заявка_файл, json.dumps(заявка))

    def _записать_событие(self, откуда: str, исход: str) -> None:
        """След остаётся ВСЕГДА: владелец узнает о попытке, даже проспав её."""
        строка = json.dumps({"ts": time.time(), "откуда": откуда,
                             "исход": исход}, ensure_ascii=False)
        try:
            with open(self.события_файл, "a", encoding="utf-8") as файл:
                файл.write(строка + "\n")
            os.chmod(self.события_файл, 0o600)
        except OSError:
            pass

    def события_запасного(self) -> list:
        try:
            строки = self.события_файл.read_text(encoding="utf-8").splitlines()
        except OSError:
            return []
        события = []
        for строка in строки:
            try:
                события.append(json.loads(строка))
            except ValueError:
                continue
        return события

    def запасная(self, пропуск: str | None) -> bool:
        """Сессия заведена запасным кодом: опасное ей недоступно."""
        if not пропуск:
            return False
        запись = self._сессии().get(пропуск.rpartition(".")[0]) or {}
        return bool(запись.get("запасная"))

    # ── сессии ──────────────────────────────────────────────────────────────
    def _сессии(self) -> dict:
        try:
            return json.loads(self.сессии_файл.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return {}

    def _сохранить(self, сессии: dict) -> None:
        _записать_тайно(self.сессии_файл, json.dumps(сессии, ensure_ascii=False))

    def _завести_сессию(self, откуда: str, запасная: bool = False) -> str:
        имя = secrets.token_urlsafe(24)
        сессии = self._сессии()
        сейчас = time.time()
        сессии = {и: з for и, з in сессии.items()
                  if сейчас - з.get("ts", 0) <= СЕССИЯ_ЖИВЁТ_СЕК}
        сессии[имя] = {"ts": сейчас, "откуда": откуда, "запасная": запасная}
        self._сохранить(сессии)
        return f"{имя}.{self._подпись(имя)}"

    def _подпись(self, имя: str) -> str:
        return hmac.new(self.ключ, имя.encode(), hashlib.sha256).hexdigest()[:32]

    def проверить(self, пропуск: str | None) -> bool:
        """Cookie действительна: подпись сходится и сессия не истекла."""
        if not пропуск or "." not in пропуск:
            return False
        имя, _, подпись = пропуск.rpartition(".")
        if not hmac.compare_digest(подпись, self._подпись(имя)):
            return False
        запись = self._сессии().get(имя)
        return bool(запись) and time.time() - запись.get("ts", 0) <= СЕССИЯ_ЖИВЁТ_СЕК

    def продлить(self, пропуск: str) -> None:
        имя = пропуск.rpartition(".")[0]
        сессии = self._сессии()
        if имя in сессии:
            сессии[имя]["ts"] = time.time()
            self._сохранить(сессии)

    def отозвать_всё(self) -> None:
        """«Выйти со всех устройств»: и записи стёрты, и подписи не сходятся."""
        self._сохранить({})
        self.сменить_ключ()


# Разбор конфига — общий для всей панели: своя копия расходится молча
# (ревью 11.09.2026, фаза 2 спеки).
_конфиг = nastrojki.читать


def main(argv: list[str]) -> int:
    """Запасной код входа: `vhod.py --запасной-код [--перевыпустить]`.

    Ссылку входа и выход со всех устройств выдаёт СЛУЖБА (`klient.py`), а не
    этот файл. Два пути к одному праву — две правды: служба доказывает право
    внутренним ключом (F-sec-01), а здешний CLI доказывал его конфигом, путь
    к которому назвал сам вызывающий. Путь убран, а не обвешан проверками.

    `--пути` печатает, какими файлами CLI пользуется, и НИЧЕГО не пишет: это
    носитель правила «право задаёт машина, не вызывающий» — проба зовёт его с
    подставленным окружением и требует боевых путей.
    """
    if "--ссылка" in argv or "--выйти" in argv:
        print("вход в панель выдаёт служба, а не этот файл: "
              "klient.py --ссылка <chat_id> | klient.py --выйти <chat_id>",
              file=sys.stderr)
        return 2
    if "--пути" in argv:
        print(f"паспорт: {ПАСПОРТ_УСТАНОВКИ}")
        print(f"состояние: {СОСТОЯНИЕ_ПАНЕЛИ}")
        return 0
    if "--запасной-код" in argv:
        # chat_id здесь пустой НАРОЧНО: право на этом пути даёт запись в
        # каталог состояния (2770) и ничто другое, а паспорт в конструкторе
        # создавал бы вид доказательства, которого нет (F-sec-06).
        вход = Вход(каталог=СОСТОЯНИЕ_ПАНЕЛИ, chat_id="")
        # Перевыпуск — по ЯВНОМУ слову. Прежняя редакция выпускала новый код
        # при каждом прогоне, а старый умирал молча: на диске только отпечаток,
        # восстановить нечем, в канал из CLI ничего не уходит (И-1, F-sec-02).
        if вход.запасной_код_заведён() and "--перевыпустить" not in argv:
            print("запасной код уже заведён — не перевыпускаю: новый отменил бы "
                  "прежний, а владелец хранит именно его. Нужен новый — "
                  "--перевыпустить", file=sys.stderr)
            return 4
        print(вход.завести_запасной_код())
        print("Это единственный показ: на диске остаётся только отпечаток.",
              file=sys.stderr)
        return 0
    print(__doc__)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
