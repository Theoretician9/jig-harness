os.environ["HARNESS_USTROJSTVO"] = "/нет/такого/файла.yaml"
пусто = sostoyanie.устройство()
os.environ.pop("HARNESS_USTROJSTVO")
if пусто.get("нет данных"):
    путь_ок("БОЛЬНОЙ СЛУЧАЙ: нечитаемый реестр назван словами, а не нулём")
