    # БОЛЬНОЙ СЛУЧАЙ 13.09.2026 (второй на том же экране): «устарели 12 из 19»
    # при здоровых демонах. Витрина мерила ВСЕ метки одним порогом в три часа,
    # а backup ходит раз в сутки, memory-revision — раз в месяц. Порог у
    # каждого свой, и он уже записан: HEARTBEAT_PERIODS, та же таблица, по
