# Реестр v2, Task 3: ни один механизм не пропадает с ЭКРАНА ВЛАДЕЛЬЦА.
#
# Больной случай, ради которого эти пути написаны. Группы на экране устройства
# строятся по жёсткому кортежу видов («демон», «хук», «гейт», «скил»)
# в _разобрать_устройство. Механизм, чей носитель в этот кортеж не входит
# (служба, сборщик, библиотека, витрина), попадает в счётчик «найдено», но не
# попадает ни в одну группу: владелец видит ВЕРНОЕ число и не видит механизм.
# Реестр v2 заводит паспорта 39 файлам, среди которых службы и библиотеки, —
# то есть дефект срабатывает ровно тогда, когда дыра закрывается.
#
# Сверяется НАЙДЕНО, а не ВСЕГО: при непустом поиске «всего» остаётся длиной
# всего реестра, а группы пусты — путь на «всего» краснел бы на здоровой
# жизни (замер 13.09: всего 134, найдено 0, сумма 0).
#
# Отображение носитель → вид берётся из СХЕМЫ (harness/config/паспорт.yaml),
# а не из второго списка в коде экрана: два списка разойдутся молча.
# ════════════════════════════════════════════════════════════════════════════
import hashlib
import yaml

КОРЕНЬ_ПРОЕКТА = Path(__file__).resolve().parent.parent.parent
СХЕМА_ПАСПОРТА = КОРЕНЬ_ПРОЕКТА / "harness" / "config" / "паспорт.yaml"


def _слепок_настроек():
    """md5 боевых harness/config/*.yaml: проба не играет на боевом."""
    каталог = КОРЕНЬ_ПРОЕКТА / "harness" / "config"
    return {п.name: hashlib.md5(п.read_bytes()).hexdigest()
            for п in sorted(каталог.glob("*.yaml"))}


СЛЕПОК_ДО_ПАНЕЛИ = _слепок_настроек()


def сумма_групп(ответ):
    """Сколько строк показано владельцу суммарно по всем группам."""
    return sum(len(г["строки"]) for г in ответ.get("группы", []))


