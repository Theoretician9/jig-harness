#!/usr/bin/env python3
"""Проверка витрины состояния: пустое называется пустым, а не нулём.

Правило, ради которого эта проверка существует: величина, которой НЕТ, обязана
называть причину, а не показывать ноль ([[движок-состояние-участка]]). Демон,
ни разу не отметившийся, и демон, отметившийся час назад, — разные вещи, и на
экране владельца они не должны выглядеть одинаково.

Прогон:
    python3 harness/panel/test_sostoyanie.py
"""
import os
import sys
import tempfile
import time
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

путей = 0
неудач = 0


def путь_ок(текст):
    global путей
    путей += 1
    print("ок  · " + текст)


def путь_плохо(текст):
    global путей, неудач
    путей += 1
    неудач += 1
    print("ПЛОХО · " + текст)


try:
    import sostoyanie
except ImportError as беда:
    путь_плохо(f"модуля витрины нет: {беда}")
    print(f"ВИТРИНА-ПАНЕЛИ: путей {путей}, неудач {неудач}")
    sys.exit(1)

