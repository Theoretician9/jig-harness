# здесь сторожем против правки групп — механизм не имеет права исчезнуть.
живое = sostoyanie.устройство()
if живое.get("найдено") == сумма_групп(живое):
    путь_ок(f"живой реестр: найдено {живое['найдено']} == сумме длин групп")
else:
    путь_плохо(f"часть механизмов не попала ни в одну группу: "
               f"найдено {живое.get('найдено')}, в группах {сумма_групп(живое)}")

живое_поиском = sostoyanie.устройство("сторож команд")
if живое_поиском.get("найдено") == сумма_групп(живое_поиском):
    путь_ок(f"поиск: найдено {живое_поиском['найдено']} == сумме длин групп")
else:
    путь_плохо(f"поиск теряет механизмы: найдено {живое_поиском.get('найдено')}, "
               f"в группах {сумма_групп(живое_поиском)}")

# Схема — источник отображения носитель → вид. Без неё путь ниже проверял бы
