#!/usr/bin/env python3
"""Витрина состояния: что с харнесом прямо сейчас, без единой команды.

Ничего нового здесь не замеряется — всё это харнес уже собирает сам: метки
демонов, очередь входящих, суточный расход, итог ворот, карта задач. Витрина
только складывает готовое в один снимок.

Главное правило экрана: величина, которой НЕТ, называет причину, а не
показывает ноль. «Сторожей нет данных» и «сторожа не отмечались» — разные
вещи, и на экране владельца они не должны выглядеть одинаково
([[движок-состояние-участка]]).
"""
import json
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent.parent


def _лог() -> Path:
    return Path(os.environ.get("PANEL_STATE_DIR_LOGS")
                or os.environ.get("LOG_DIR", "/var/log/harness"))


def _метки() -> Path:
    return Path(os.environ.get("HEARTBEAT_DIR", "/var/lib/harness/heartbeat"))


def _карта() -> Path:
    return Path(os.environ.get("PANEL_DEVMAP") or КОРЕНЬ / "dev-map.yaml")


def _минут(путь: Path) -> int:
    return int((time.time() - путь.stat().st_mtime) / 60)


def работа() -> dict:
    """Задача, которая идёт сейчас. Поля берутся те, что в карте ЕСТЬ."""
    try:
        import yaml
        карта = yaml.safe_load(_карта().read_text(encoding="utf-8"))
    except Exception as беда:                       # noqa: BLE001 — витрина не падает
        return {"нет данных": f"карта не прочитана: {беда}"}
    задачи = []

    def обход(узел):
        if isinstance(узел, dict):
            if "id" in узел and "status" in узел:
                задачи.append(узел)
            for значение in узел.values():
                обход(значение)
        elif isinstance(узел, list):
            for элемент in узел:
                обход(элемент)

    обход(карта)
    идут = [з for з in задачи if з.get("status") == "wip"]
    if not идут:
        return {"нет данных": "задач в работе нет"}
    задача = идут[0]
    начата = (задача.get("when") or {}).get("started")
    return {"id": задача["id"], "название": задача.get("title", ""),
            "начата": начата, "блокер": задача.get("blocked"),
            "всего задач": len(задачи)}


def _активное_направление() -> str:
    """Над каким направлением карты работаем. Данные, не догадка."""
    import re as _re
    из_окружения = os.environ.get("HARNESS_ACTIVE_LINE")
    if из_окружения is not None:
        return из_окружения
    try:
        текст = Path("/etc/harness/harness.conf").read_text(encoding="utf-8")
    except OSError:
        return ""
    найдено = _re.search(r'^\s*ACTIVE_LINE\s*=\s*"?([^"#\s]*)"?', текст, _re.M)
    return найдено.group(1) if найдено else ""


def karta() -> dict:
    """Карта разработки для экрана: сводка по статусам и что где стоит.

    Владелец 11.09.2026 спросил: «Карта где используется? Где предполагается
    быть использованной?» — ответ был честным: её читают двадцать механизмов и
    ни один экран. Источник, по которому машина принимает решения, владелец
    обязан видеть.

    Полных описаний задач здесь НЕ отдаём: карта весит четверть миллиона знаков,
    и экран из неё грузился бы минуту. Отдаём имя, состояние и чем доказана.
    """
    try:
        import yaml
        карта = yaml.safe_load(_карта().read_text(encoding="utf-8"))
    except Exception as беда:                       # noqa: BLE001 — витрина не падает
        return {"нет данных": f"карта не прочитана: {беда}"}
    задачи = []

    def обход(узел):
        if isinstance(узел, dict):
            if "id" in узел and "status" in узел:
                задачи.append(узел)
            for значение in узел.values():
                обход(значение)
        elif isinstance(узел, list):
            for элемент in узел:
                обход(элемент)

    обход(карта)
    # Направления: над одним работаем, остальные отложены. Владелец 12.09.2026
    # просил, чтобы отложенное не мешало, — но и не пропадало из виду.
    активное = _активное_направление()
    по_направлениям = {л.get("id"): len(л.get("tasks") or [])
                       for л in (карта.get("lines") or [])}
    if активное:
        свои = {з["id"] for л in (карта.get("lines") or [])
                if л.get("id") == активное
                for з in (л.get("tasks") or [])}
        задачи = [з for з in задачи if з["id"] in свои]
    по_статусам = {}
    for з in задачи:
        по_статусам[з["status"]] = по_статусам.get(з["status"], 0) + 1
    порядок = {"wip": 0, "test": 1, "plan": 2, "принято": 3, "done": 4}
    строки = []
    for з in sorted(задачи, key=lambda з: (порядок.get(з["status"], 9), з["id"])):
        проверка = з.get("проверка") or {}
        строки.append({
            "id": з["id"],
            "название": str(з.get("title", ""))[:110],
            "состояние": з["status"],
            "чем доказана": (проверка.get("команда") if isinstance(проверка, dict) else None)
                            or з.get("проверить_владельцу") or "",
            "блокер": з.get("blocked"),
        })
    отложено = sum(n for имя, n in по_направлениям.items() if имя != активное) \
        if активное else 0
    return {"по состояниям": по_статусам, "всего": len(задачи), "задачи": строки,
            "рабочее направление": активное or "все",
            "отложено задач": отложено}


def сторожа() -> dict:
    """Метки демонов с возрастом. Пусто — так и говорим."""
    каталог = _метки()
    try:
        файлы = sorted(п for п in каталог.iterdir() if п.is_file())
    except OSError as беда:
        return {"нет данных": f"каталог меток недоступен: {беда}"}
    if not файлы:
        return {"нет данных": f"в {каталог} ни одной метки — демоны не отмечались"}
    return {"строки": [{"имя": п.name, "минут": _минут(п)} for п in файлы]}


def канал() -> dict:
    очередь = list((_лог() / "inbox").glob("*.txt")) if (_лог() / "inbox").exists() else []
    обработано = _лог() / "inbox" / "обработано"
    последнее = None
    if обработано.exists():
        файлы = sorted(обработано.glob("*.txt"), key=lambda п: п.stat().st_mtime)
        if файлы:
            последнее = _минут(файлы[-1])
    return {"в очереди": len(очередь), "последнее сообщение, минут назад": последнее}


def расход() -> dict:
    отчёт = _лог() / "tokens-daily.report"
    try:
        текст = отчёт.read_text(encoding="utf-8")
    except OSError as беда:
        return {"нет данных": f"суточный отчёт не прочитан: {беда}"}
    значения = {}
    for строка in текст.splitlines():
        куски = строка.split()
        if len(куски) >= 2 and куски[-1].replace(",", "").replace("%", "").replace(
                "k", "").replace("M", "").replace(".", "").isdigit():
            значения[" ".join(куски[:-1]).strip()] = куски[-1]
    return {"строки": значения, "обновлён минут назад": _минут(отчёт)}


def проверки() -> dict:
    """Итог последнего прогона ворот — его пишут сами ворота."""
    журнал = _лог() / "ворота-итог.jsonl"
    try:
        строки = [с for с in журнал.read_text(encoding="utf-8").splitlines() if с.strip()]
    except OSError:
        return {"нет данных": "ворота ещё не писали итога — прогона не было"}
    if not строки:
        return {"нет данных": "журнал ворот пуст"}
    try:
        запись = json.loads(строки[-1])
    except ValueError:
        return {"нет данных": "последняя запись журнала ворот не разбирается"}
    запись["минут назад"] = _минут(журнал)
    return запись


def машина() -> dict:
    всего, занято, _ = shutil.disk_usage("/")
    итог = {"диск занято %": round(занято / всего * 100)}
    try:
        готово = subprocess.run(["systemctl", "is-system-running"],
                                capture_output=True, text=True, timeout=10)
        итог["системные службы"] = готово.stdout.strip() or "неизвестно"
    except (OSError, subprocess.SubprocessError):
        итог["системные службы"] = "спросить не удалось"
    return итог


# Что делает каждый шаг — словами человека без подготовки. Владелец:
