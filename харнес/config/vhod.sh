# Вход агента: долгий токен Claude Code — ОДИН носитель на все пути запуска.
#
# Откуда взят. Владелец 12.09.2026: «твоя прошлая правка "на год" не сработала,
# был логаут и я вручную логинился, а сейчас опять». Замер того же часа:
#
#   * токен `claude setup-token` получен 11.09 16:05 и лежит в секретах;
#   * файл окружения ~/.harness-env.sh создан 11.09 16:06;
#   * работающая сессия запущена 11.09 06:49 — на девять часов РАНЬШЕ файла.
#     Окружение живого процесса задним числом не меняется, поэтому она так и
#     осталась на входе из `/login`, и CLI предупредил о его сроке;
#   * cron профиль оболочки не читает вовсе (проверка: `env -i /bin/sh -c`
#     не видит переменной), поэтому ночные демоны, зовущие `claude -p`,
#     долгого токена не получали НИКОГДА.
#
# Почему именно переменная. Документация Claude Code (Authentication →
# Generate a long-lived token): токен `setup-token` действует ТОЛЬКО через
# `CLAUDE_CODE_OAUTH_TOKEN`; сам файл ничего не включает. В порядке выбора
# учётки эта переменная стоит выше подписочного `/login`, поэтому пока она
# выставлена, срок входа из `/login` работе не мешает.
#
# Почему файл в /etc, а не в домашнем каталоге: его подключает и конфиг
# демонов (harness.conf), и оболочки владельца, и sudo-вызовы — у них разный
# $HOME, и путь в домашнем каталоге доходил не до всех.
#
# Значение секрета здесь НЕ хранится (И-3): только путь к файлу 0600.

HARNESS_OAUTH_TOKEN_FILE="${HARNESS_OAUTH_TOKEN_FILE:-/var/lib/harness/secrets/claude-oauth-token}"

# `if`, а не `[ … ] && …`: под `set -e` ложное условие последней строкой
# уронило бы ВЕСЬ подключающий скрипт — грабли «падение под set -e молчит».
if [ -r "$HARNESS_OAUTH_TOKEN_FILE" ] && [ -s "$HARNESS_OAUTH_TOKEN_FILE" ]; then
    CLAUDE_CODE_OAUTH_TOKEN="$(cat "$HARNESS_OAUTH_TOKEN_FILE")"
    export CLAUDE_CODE_OAUTH_TOKEN
fi
