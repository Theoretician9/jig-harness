#!/usr/bin/env python3
"""Проверка второго рубежа: опасное переключение подтверждается кодом в канале.

Зачем рубеж (спека панели §5.3): даже украденный пропуск в браузере не меняет
поведение боевого сервера, пока у вора нет доступа к чату владельца.

Находка C3 ревью, ради которой у рубежа СВОЙ журнал: диспетчер метит короткое
«да» как согласие «на что спрашивали», а ворота выката засчитывают такую метку.
Пиши панель в общий confirmations.jsonl — её «да» открывало бы выкат и снос
базы. Поэтому здесь проверяется не только «код работает», но и «общий журнал
согласий не тронут».

Прогон:
    python3 харнес/панель/test_podtverzhdenie.py
"""
import json
import os
import sys
import tempfile
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

путей = 0
неудач = 0


def путь_ок(текст):
    global путей
    путей += 1
    print("ок  · " + текст)


def путь_плохо(текст):
    global путей, неудач
    путей += 1
    неудач += 1
    print("ПЛОХО · " + текст)


КОНФИГ = "PUSH_NEEDS_OWNER=0\nCTX_ROTATE_PCT=75\n"

with tempfile.TemporaryDirectory() as tmp:
    врем = Path(tmp)
    (врем / "harness.conf").write_text(КОНФИГ, encoding="utf-8")
    (врем / "install.conf").write_text('TG_CHAT_ID="100000001"\n', encoding="utf-8")
    (врем / "логи").mkdir()
    os.environ.update(HARNESS_CONF=str(врем / "harness.conf"),
                      HARNESS_INSTALL_CONF=str(врем / "install.conf"),
                      LOG_DIR=str(врем / "логи"),
                      PANEL_TG_SEND="")            # в проверке ничего не шлём
    try:
        import podtverzhdenie as п
    except ImportError as беда:
        путь_плохо(f"модуля подтверждения нет: {беда}")
        print(f"ПОДТВЕРЖДЕНИЕ-ПАНЕЛИ: путей {путей}, неудач {неудач}")
        sys.exit(1)

    журнал_ворот = врем / "логи" / "confirmations.jsonl"
    журнал_ворот.write_text("", encoding="utf-8")
    было_ворот = журнал_ворот.read_text(encoding="utf-8")

    код = п.завести("PUSH_NEEDS_OWNER", "1")
    if код and код.isdigit() and len(код) >= 6:
        путь_ок(f"ожидание заведено, код из {len(код)} цифр ({код})")
    else:
        путь_плохо(f"код ожидания не тот: {код!r}")

    конфиг = врем / "harness.conf"
    # Чужой код ничего не применяет.
    было = конфиг.read_text(encoding="utf-8")
    if not п.ответ(f"да {int(код) % 9000 + 1000 if код else 1234}") and \
            было == конфиг.read_text(encoding="utf-8"):
        путь_ок("БОЛЬНОЙ СЛУЧАЙ: чужой код ничего не переключает")
    else:
        путь_плохо("чужой код применил переключение")

    # Голое «да» без кода — тоже ничего: иначе общее согласие владельца в канале
    # применяло бы то, чего он в этот момент не видел.
    if not п.ответ("да") and было == конфиг.read_text(encoding="utf-8"):
        путь_ок("БОЛЬНОЙ СЛУЧАЙ: «да» без кода не переключает")
    else:
        путь_плохо("«да» без кода применило переключение")

    # Верный код применяет.
    готово = п.ответ(f"да {код}")
    if готово and "PUSH_NEEDS_OWNER=1" in конфиг.read_text(encoding="utf-8"):
        путь_ок("верный код применяет переключение")
    else:
        путь_плохо(f"верный код не применил: {готово}")

    # Код расходуется.
    конфиг.write_text(КОНФИГ, encoding="utf-8")
    if not п.ответ(f"да {код}") and "PUSH_NEEDS_OWNER=0" in конфиг.read_text(
            encoding="utf-8"):
        путь_ок("код расходуется: второй раз не срабатывает")
    else:
        путь_плохо("тот же код применён дважды")

    # Общий журнал согласий не тронут — иначе «да» панели открыло бы выкат.
    if журнал_ворот.read_text(encoding="utf-8") == было_ворот:
        путь_ок("БОЛЬНОЙ СЛУЧАЙ: общий журнал согласий панель не пишет (C3)")
    else:
        путь_плохо("панель написала в журнал ворот выката")

    # Просроченное ожидание.
    код2 = п.завести("PUSH_NEEDS_OWNER", "1")
    ожидания = json.loads((врем / "логи" / "панель-ожидания.json").read_text(
        encoding="utf-8"))
    ожидания[код2]["ts"] = time.time() - п.ЖИВЁТ_СЕК - 5
    (врем / "логи" / "панель-ожидания.json").write_text(
        json.dumps(ожидания), encoding="utf-8")
    конфиг.write_text(КОНФИГ, encoding="utf-8")
    if not п.ответ(f"да {код2}") and "PUSH_NEEDS_OWNER=0" in конфиг.read_text(
            encoding="utf-8"):
        путь_ок("БОЛЬНОЙ СЛУЧАЙ: просроченное ожидание не применяется")
    else:
        путь_плохо("просроченное ожидание применилось")

    # Отказ владельца снимает ожидание.
    код3 = п.завести("PUSH_NEEDS_OWNER", "1")
    if п.ответ(f"нет {код3}") is False and not п.ответ(f"да {код3}"):
        путь_ок("отказ снимает ожидание: следом «да» уже не применяет")
    else:
        путь_плохо("после отказа ожидание осталось живым")

    # Своя запись в журнал панели — чтобы было видно, кто и что переключил.
    записи = (врем / "логи" / "панель.jsonl")
    if записи.exists() and "PUSH_NEEDS_OWNER" in записи.read_text(encoding="utf-8"):
        путь_ок("подтверждённое переключение записано в журнал панели")
    else:
        путь_плохо("переключение не записано в журнал панели")

    # ── F-sec-05: перебор кода по петле ────────────────────────────────────────
    # Ревью безопасности 11.09.2026: код был четырёхзначный, а разбор ответа
    # доступен внутренним маршрутом без счёта промахов — 9000 попыток применяют
    # опасный переключатель. Код удлинён, промахи считаются.
    код6 = п.завести("PUSH_NEEDS_OWNER", "1", "проба")
    if len(код6) >= 6:
        путь_ок(f"код второго рубежа длиной {len(код6)}")
    else:
        путь_плохо(f"код короткий: {код6}")

    for попытка in range(3):
        п.ответ("да " + "9" * len(код6))
    if not п._ожидания():
        путь_ок("БОЛЬНОЙ СЛУЧАЙ: три промаха подряд гасят все ожидания")
    else:
        путь_плохо(f"после трёх промахов ожидания живы: {п._ожидания()}")

    if п.ответ(f"да {код6}") is not True:
        путь_ок("погашенное ожидание верным кодом уже не применяется")
    else:
        путь_плохо("код применился после гашения ожиданий")

print(f"ПОДТВЕРЖДЕНИЕ-ПАНЕЛИ: путей {путей}, неудач {неудач}")
sys.exit(1 if неудач else 0)
