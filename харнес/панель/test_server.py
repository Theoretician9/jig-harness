def запрос(url, данные=None, заголовки=None, метод=None, форма=None):
    """(код, тело). Отказ сервера — это ответ, а не исключение.

    `форма` шлёт тело так, как его шлёт браузер обычной кнопкой: это отдельный
    путь, и он однажды не работал, пока проверялся только JSON."""
    if форма is not None:
        тело = urllib.parse.urlencode(форма).encode()
    else:
        тело = json.dumps(данные).encode() if данные is not None else None
    req = urllib.request.Request(url, data=тело, method=метод,
                                 headers=заголовки or {})
    if форма is not None:
        req.add_header("Content-Type", "application/x-www-form-urlencoded")
    elif тело is not None:
        req.add_header("Content-Type", "application/json")
    try:
        with urllib.request.urlopen(req, timeout=10) as ответ:
            return ответ.status, ответ.read().decode("utf-8", "replace")
    except urllib.error.HTTPError as беда:
        return беда.code, беда.read().decode("utf-8", "replace")


class _БезПереходов(urllib.request.HTTPRedirectHandler):
    """Редирект после входа несёт cookie: следовать за ним — потерять её."""

    def redirect_request(self, *аргументы, **именованные):
        return None


def запрос_сырой(url, форма=None, заголовки=None) -> dict:
    """Заголовки ответа. Переход по 303 не выполняется — нужен Set-Cookie."""
    тело = urllib.parse.urlencode(форма or {}).encode()
    req = urllib.request.Request(url, data=тело, headers=заголовки or {})
    req.add_header("Content-Type", "application/x-www-form-urlencoded")
    открыватель = urllib.request.build_opener(_БезПереходов)
    try:
        with открыватель.open(req, timeout=10) as ответ:
            return dict(ответ.headers)
    except urllib.error.HTTPError as беда:
        return dict(беда.headers)


