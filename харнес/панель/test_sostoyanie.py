#!/usr/bin/env python3
"""Проверка витрины состояния: пустое называется пустым, а не нулём.

Правило, ради которого эта проверка существует: величина, которой НЕТ, обязана
называть причину, а не показывать ноль ([[движок-состояние-участка]]). Демон,
ни разу не отметившийся, и демон, отметившийся час назад, — разные вещи, и на
экране владельца они не должны выглядеть одинаково.

Прогон:
    python3 харнес/панель/test_sostoyanie.py
"""
import os
import sys
import tempfile
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

путей = 0
неудач = 0


def путь_ок(текст):
    global путей
    путей += 1
    print("ок  · " + текст)


def путь_плохо(текст):
    global путей, неудач
    путей += 1
    неудач += 1
    print("ПЛОХО · " + текст)


try:
    import sostoyanie
except ImportError as беда:
    путь_плохо(f"модуля витрины нет: {беда}")
    print(f"ВИТРИНА-ПАНЕЛИ: путей {путей}, неудач {неудач}")
    sys.exit(1)

КАРТА = """epics:
  - id: e1
    tasks:
      - id: hr.проба
        status: wip
        title: "Проба пера"
        blocked: "ждёт слова владельца"
        when: { started: "2026-09-11" }
"""

with tempfile.TemporaryDirectory() as tmp:
    врем = Path(tmp)
    (врем / "логи").mkdir()
    (врем / "логи" / "inbox").mkdir()
    (врем / "метки").mkdir()
    (врем / "dev-map.yaml").write_text(КАРТА, encoding="utf-8")
    os.environ.update(LOG_DIR=str(врем / "логи"),
                      HEARTBEAT_DIR=str(врем / "метки"),
                      PANEL_DEVMAP=str(врем / "dev-map.yaml"))

    # Пустой стенд: ничего ещё не случилось.
    снимок = sostoyanie.снять()
    сторожа = снимок["сторожа"]
    if сторожа.get("нет данных") or сторожа.get("строки") == []:
        путь_ок("сторожей ещё нет — витрина говорит «нет данных», а не «0 живых»")
    else:
        путь_плохо(f"пустые сторожа показаны как данные: {сторожа}")

    if снимок["расход"].get("нет данных"):
        путь_ок("расход не собран — витрина честно говорит об этом")
    else:
        путь_плохо(f"расход выдуман из ничего: {снимок['расход']}")

    if снимок["проверки"].get("нет данных"):
        путь_ок("ворота ещё не гонялись — «нет данных», а не «0 красных»")
    else:
        путь_плохо(f"итог ворот выдуман: {снимок['проверки']}")

    # Задача из карты.
    if снимок["работа"].get("id") == "hr.проба" and \
            "ждёт слова" in (снимок["работа"].get("блокер") or ""):
        путь_ок("текущая задача и её блокер взяты из карты")
    else:
        путь_плохо(f"задача не прочитана: {снимок['работа']}")

    # Метки: свежая и протухшая.
    (врем / "метки" / "backup").write_text("", encoding="utf-8")
    старая = врем / "метки" / "session-warden"
    старая.write_text("", encoding="utf-8")
    давно = time.time() - 5 * 3600
    os.utime(старая, (давно, давно))
    снимок = sostoyanie.снять()
    по_имени = {с["имя"]: с for с in снимок["сторожа"]["строки"]}
    if по_имени.get("backup", {}).get("минут") == 0:
        путь_ок("свежая метка показана с возрастом 0 минут")
    else:
        путь_плохо(f"свежая метка не та: {по_имени.get('backup')}")
    if по_имени.get("session-warden", {}).get("минут", 0) >= 299:
        путь_ок("протухшая метка показана своим настоящим возрастом")
    else:
        путь_плохо(f"протухшая метка не та: {по_имени.get('session-warden')}")

    # Очередь входящих.
    (врем / "логи" / "inbox" / "1.txt").write_text("привет", encoding="utf-8")
    снимок = sostoyanie.снять()
    if снимок["канал"]["в очереди"] == 1:
        путь_ок("очередь входящих считается")
    else:
        путь_плохо(f"очередь посчитана неверно: {снимок['канал']}")

    # Итог ворот — из журнала, который пишут сами ворота.
    (врем / "логи" / "ворота-итог.jsonl").write_text(
        '{"ts": "2026-09-11T17:00:00", "зелёных": 27, "красных": 0}\n',
        encoding="utf-8")
    снимок = sostoyanie.снять()
    if снимок["проверки"].get("зелёных") == 27 and снимок["проверки"].get("красных") == 0:
        путь_ок("итог последних ворот прочитан")
    else:
        путь_плохо(f"итог ворот не прочитан: {снимок['проверки']}")

    # Машина: диск считается всегда — он есть у любой машины.
    if 0 < снимок["машина"]["диск занято %"] <= 100:
        путь_ок("занятость диска показана числом")
    else:
        путь_плохо(f"диск не посчитан: {снимок['машина']}")

# Устройство: панель читает ТОТ ЖЕ реестр, из которого собран документ.
из_реестра = sostoyanie.устройство()
if из_реестра.get("всего", 0) >= 60 and из_реестра["группы"]:
    путь_ок(f"устройство прочитано: частей {из_реестра['всего']}")
else:
    путь_плохо(f"устройство не прочитано: {str(из_реестра)[:120]}")

по_слову = sostoyanie.устройство("сторож команд")
if 0 < по_слову["найдено"] < из_реестра["всего"]:
    путь_ок("поиск по устройству сужает список")
else:
    путь_плохо(f"поиск не сузил: {по_слову.get('найдено')}")

os.environ["HARNESS_USTROJSTVO"] = "/нет/такого/файла.yaml"
пусто = sostoyanie.устройство()
os.environ.pop("HARNESS_USTROJSTVO")
if пусто.get("нет данных"):
    путь_ок("БОЛЬНОЙ СЛУЧАЙ: нечитаемый реестр назван словами, а не нулём")
else:
    путь_плохо(f"нечитаемый реестр показан как данные: {str(пусто)[:100]}")

# F-gen-02: битый реестр устройства обязан давать «нет данных», а не падение
# внутри обработчика (ревью корректности 11.09.2026: страница отвечала
# закрытым соединением, а журнал оставался пуст).
битый = Path(tempfile.mkdtemp(prefix="битое-")) / "устройство.yaml"
битый.write_text("механизмы:\n  - файл: [не\n", encoding="utf-8")
os.environ["HARNESS_USTROJSTVO"] = str(битый)
ответ = sostoyanie.устройство()
os.environ.pop("HARNESS_USTROJSTVO")
if ответ.get("нет данных"):
    путь_ок("БОЛЬНОЙ СЛУЧАЙ: битый реестр устройства назван словами")
else:
    путь_плохо(f"битый реестр не пойман: {str(ответ)[:100]}")

# Состояние обновлений: «проверок ещё не было» и «есть новая версия» — разные
# строки, а не одинаковая пустота (§4 спеки обновления).
import os as _os2
_врем_обн = Path(tempfile.mkdtemp(prefix="обновления-"))
_os2.environ["LOG_DIR"] = str(_врем_обн)
_os2.environ["PANEL_STATE_DIR_LOGS"] = str(_врем_обн)
_лог_обн = _врем_обн / "obnovlenie-watch.log"
пусто_обн = sostoyanie.обновления()
if пусто_обн.get("нет данных") == "проверок ещё не было":
    путь_ок("обновления: проверок ещё не было — сказано словами")
else:
    путь_плохо(f"пустое состояние обновлений не то: {пусто_обн}")

_лог_обн.write_text("2026-09-11 04:45:00  [обновление] есть новая версия: abc1234\n",
                    encoding="utf-8")
есть_обн = sostoyanie.обновления()
if есть_обн.get("состояние") == "есть новая версия":
    путь_ок("обновления: новая версия видна на экране")
else:
    путь_плохо(f"новая версия не распознана: {есть_обн}")

_лог_обн.write_text("2026-09-11 04:45:00  [обновление] спросить не удалось: сети нет\n",
                    encoding="utf-8")
беда_обн = sostoyanie.обновления()
if беда_обн.get("состояние") == "спросить не удалось":
    путь_ок("обновления: недоступное хранилище отличается от «всё свежо»")
else:
    путь_плохо(f"недоступность не распознана: {беда_обн}")

print(f"ВИТРИНА-ПАНЕЛИ: путей {путей}, неудач {неудач}")
sys.exit(1 if неудач else 0)
