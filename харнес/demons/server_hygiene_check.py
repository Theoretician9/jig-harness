#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Правила гигиены сервера — проверкой, а не памятью.

Что держит: потолки машины и сервисов. Владелец 08.08: «эти правила должны
распространяться на весь сервер и для любых других сервисов, которые будут
создаваться». Правило, записанное словами, распространяется ровно до первого
забывшего — поэтому здесь оно записано проверкой, которая падает.

Откуда взят: UNIFIED/templates/server_hygiene_check.py (живой скрипт боевого
сервера). Плейсхолдеры заменены на чтение /etc/harness/install.conf и
/etc/harness/harness.conf (мини-парсер ниже — формат KEY="value" разбирается
без библиотек). Компоуз разбирается через yaml: python3-yaml гарантирован
установкой (01-SPEC §2) — самодельный отступный парсер молча слеп на файлах
с нестандартными отступами (fail-open), это дороже зависимости.

Коды выхода: 0 — чисто; 1 — нарушения; 2 — проверка сама сломана (traceback
в stderr; обёртка server-hygiene.sh на 2 метку НЕ ставит и зовёт владельца).

Чем доказывается: запуском при установке (нулевая машина обязана пройти
чисто) и больным случаем — временно поставить vm.swappiness=60 или порт
наружу в compose → проверка обязана покраснеть. Пороги — в harness.conf,
данные, не код.

Что проверяется:

1. **Потолок памяти у каждого сервиса.** Без него утечка одного контейнера
   выпихивает в своп всю машину: 08.08 своп дошёл до 91%, и виноват был
   единственный процесс. С потолком умирает один контейнер, а не сервер.
   Базам данных потолок ставится с большим запасом или не ставится вовсе —
   у них всплески законны (тяжёлый запрос, вакуум); такие исключения должны
   быть НАЗВАНЫ здесь, а не подразумеваться.

2. **Политика перезапуска.** Сервис без неё не встаёт после перезагрузки
   машины: 05.07 стек поднялся наполовину, и восемь часов никто не работал.

3. **Порты только на 127.0.0.1.** Правило появилось 03.08, когда наружу
   слушали MySQL, Redis, RabbitMQ и Vault. Наружу имеют право 80, 443, 22.

4. **Границы не устарели.** Владелец 08.08: «если ведётся работа над сервисом,
   он может быть изменён, масштабирован — эти границы нужно пересматривать».
   Пересмотр не должен зависеть от памяти: потолок сравнивается с ПИКОМ за
   неделю из Prometheus. Пик выше 80% потолка — сервис вырос, потолок поднять;
   ниже 20% — потолок ни от чего не защищает.

5. **Место на диске и своп** — пороги те же, что у оповещений.

Продукта на сервере ещё нет: отсутствие docker-compose.yml — не нарушение,
а честная строка «продукт ещё не начат»; проверяется только машина.

    server_hygiene_check.py            # проверить, вернуть 0/1
    server_hygiene_check.py --кратко   # только итог
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

# ── конфиги: install.conf + harness.conf, без внешних библиотек ─────────────
import os

INSTALL_CONF = Path(os.environ.get("INSTALL_CONF", "/etc/harness/install.conf"))
HARNESS_CONF = Path(os.environ.get("HARNESS_CONF", "/etc/harness/harness.conf"))


def _read_conf(path: Path, conf: dict) -> None:
    """KEY="value" / KEY=число; комментарии и пустые строки мимо.

    Подстановки $VAR разворачиваются по уже прочитанному — install.conf
    ссылается на $SECRETS_DIR в TG_TOKEN_FILE.

    Комментарий режется только ВНЕ кавычек (Д-3): прежняя резка по первому #
    обрубала значение вида KEY="пароль#42" посередине.
    """
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, raw = line.partition("=")
        raw = raw.strip()
        m = re.match(r'"([^"]*)"|\'([^\']*)\'', raw)
        if m:  # значение в кавычках — берём до закрывающей, # внутри законен
            value = m.group(1) if m.group(1) is not None else m.group(2)
        else:  # без кавычек # значению принадлежать не может — это комментарий
            value = raw.split("#", 1)[0].strip()
        for name, seen in conf.items():
            value = value.replace("${%s}" % name, seen).replace("$" + name, seen)
        conf[key.strip()] = value


def _сломана(причина: Exception) -> "SystemExit":
    """Проверка сломана ≠ нарушения найдены: traceback в stderr, код 2.

    Обёртка server-hygiene.sh различает по коду: 1 — нарушения (метка
    ставится), 2 — сломана сама проверка (метки НЕТ, сигнал владельцу).
    Без этого любой traceback выходил кодом 1 и сходил за «нарушения».
    """
    import traceback
    traceback.print_exc(file=sys.stderr)
    return SystemExit(2)


КОНФИГ: dict = {}
try:
    for _f in (INSTALL_CONF, HARNESS_CONF):
        if not _f.exists():
            print(f"гигиена: нет конфига {_f} — установка не завершена (01-SPEC §0)")
            raise SystemExit(2)
        _read_conf(_f, КОНФИГ)
except SystemExit:
    raise
except Exception as _e:                                     # noqa: BLE001
    raise _сломана(_e) from None

# Компоуз продукта — в каталоге проекта из паспорта установки, не по
# положению скрипта: демоны харнеса лежат отдельно от кода продукта.
КОМПОУЗ = Path(КОНФИГ.get("PROJECT_DIR", "/nonexistent")) / "docker-compose.yml"

# Сервисы, которым потолок памяти НЕ ставится, и почему. Список должен быть
# коротким и объяснённым: молчаливое исключение — это дыра, а не решение.
БЕЗ_ПОТОЛКА = {
    "mysql": "база прода: всплеск памяти при тяжёлом запросе законен, убийство хуже свопа",
    "postgres": "то же, что и mysql",
    "elasticsearch": "своя настройка кучи через ES_JAVA_OPTS — двойной потолок вреден",
    "vault": "хранилище секретов: перезапуск требует распечатывания, цена ошибки выше",
}

# Порты, которым можно слушать наружу.
НАРУЖУ_МОЖНО = {"80", "443", "22"}

# Пороги — из harness.conf; дефолты совпадают с ним (VPS 2 CPU / 4 ГБ / 60 ГБ).
# Битое значение в конфиге (не число) — это сломанная проверка, код 2.
try:
    ПОРОГ_ДИСКА = int(КОНФИГ.get("DISK_MAX_PCT", "85"))
    ПОРОГ_СВОПА = int(КОНФИГ.get("SWAP_MAX_PCT", "85"))

    # Насколько охотно ядру позволено выпихивать живые страницы вместо кеша.
    # По умолчанию в системе 60 — значение для настольной машины: ядро
    # подкачивает заранее, ради большого кеша. Отсюда своп на 91% при живой
    # памяти (08.08). Владелец выбрал 20, а не 10: чуть больше свободы ядру,
    # чем на классическом сервере, но втрое меньше прежнего.
    СВАППИНЕСС = int(КОНФИГ.get("SWAPPINESS_MAX", "20"))

    # Границы устаревают. Владелец 08.08: «если ведётся работа над сервисом, он
    # может быть изменён, масштабирован — эти границы нужно пересматривать».
    # Пересмотр не должен зависеть от того, вспомнит ли кто-то: сравниваем
    # потолок с ПИКОМ за неделю.
    #
    #   пик выше 80% потолка — тесно: сервис вырос, потолок пора поднять,
    #                          иначе ядро убьёт живую работу;
    #   пик ниже 20% потолка — потолок ни от чего не защищает: утечка успеет
    #                          съесть впятеро больше нормы, прежде чем сработает.
    ТЕСНО = float(КОНФИГ.get("MEM_PEAK_TIGHT_RATIO", "0.8"))
    СЛИШКОМ_ШИРОКО = float(КОНФИГ.get("MEM_PEAK_LOOSE_RATIO", "0.2"))
except Exception as _e:                                     # noqa: BLE001
    raise _сломана(_e) from None
# Пустой URL — Prometheus ещё не поставлен, проверка границ честно молчит.
ПРОМЕТЕЙ = КОНФИГ.get("PROMETHEUS_URL", "")

# Имена контейнеров в метриках начинаются с имени compose-проекта; у нас это
# PROJECT_NAME из паспорта установки.
ПРЕФИКС_КОНТЕЙНЕРОВ = КОНФИГ.get("PROJECT_NAME", "")


def _услуги(текст: str) -> dict:
    """Разбор compose через yaml: имя сервиса → его словарь.

    Именно yaml, не самодельный парсер по отступам: файл с отступами не
    ровно-в-2-пробела прежний парсер молча пропускал целиком (fail-open),
    и открытый наружу порт оставался невидимым.
    """
    import yaml  # python3-yaml ставится установщиком (01-SPEC §2)
    данные = yaml.safe_load(текст) or {}
    сервисы = данные.get("services") or {}
    return {имя: (блок or {}) for имя, блок in сервисы.items()
            if isinstance(блок, dict) or блок is None}


def _наружные_порты(порты) -> list[tuple[str, str]]:
    """(адрес, наружный-порт) для каждой публикации. Наружный — HOST-часть.

    Короткий синтаксис "8080:80": наружу смотрит 8080 (host), а не 80
    (container) — прежний разбор путал их и пропускал беду. Длинный синтаксис:
    published — наружный, target — внутренний.
    """
    из: list[tuple[str, str]] = []
    for п in порты or []:
        if isinstance(п, dict):                              # long syntax
            наружу = str(п.get("published", "")).strip()
            адрес = str(п.get("host_ip") or "")
            if наружу:
                из.append((адрес, наружу))
            continue
        s = str(п).split("/")[0].strip()                     # "8080:80/udp" → "8080:80"
        части = s.split(":")
        if len(части) >= 3:                                  # ip:host:container
            адрес, наружу = ":".join(части[:-2]), части[-2]
        elif len(части) == 2:                                # host:container
            адрес, наружу = "", части[0]
        else:                                                # "80" — эфемерный host-порт на 0.0.0.0
            адрес, наружу = "", части[0]
        из.append((адрес, наружу))
    return из


def проверить_компоуз() -> list[str]:
    беды: list[str] = []
    if not КОМПОУЗ.exists():
        # Продукт ещё не начат — это состояние, а не нарушение. Но след
        # обязателен: пропуск без следа неотличим от проверки.
        print(f"  (компоуза {КОМПОУЗ} нет — продукт ещё не начат, проверяю только машину)")
        return []
    услуги = _услуги(КОМПОУЗ.read_text(encoding="utf-8"))
    for имя, блок in услуги.items():
        if "mem_limit" not in блок and имя not in БЕЗ_ПОТОЛКА:
            беды.append(f"{имя}: нет mem_limit — утечка уйдёт в своп всей машины")
        if "restart" not in блок:
            беды.append(f"{имя}: нет restart — не встанет после перезагрузки")
        for адрес, снаружи in _наружные_порты(блок.get("ports")):
            if not адрес.startswith("127.0.0.1") and снаружи not in НАРУЖУ_МОЖНО:
                беды.append(f"{имя}: порт {снаружи} слушает наружу ({адрес or '0.0.0.0'})")
    return беды


def _пики_за_неделю() -> dict:
    """Пик рабочего набора каждого контейнера за 7 дней, МБ. Пусто — если Prometheus молчит."""
    import json
    import urllib.parse
    import urllib.request
    if not ПРОМЕТЕЙ:
        return {}
    запрос = 'max_over_time(container_memory_working_set_bytes{name!=""}[7d])'
    url = f"{ПРОМЕТЕЙ}/api/v1/query?query=" + urllib.parse.quote(запрос)
    try:
        with urllib.request.urlopen(url, timeout=20) as о:
            ряды = json.loads(о.read().decode())["data"]["result"]
    except Exception:                                       # noqa: BLE001
        return {}
    из: dict = {}
    for р in ряды:
        имя = (р.get("metric") or {}).get("name", "")
        if not ПРЕФИКС_КОНТЕЙНЕРОВ or not имя.startswith(ПРЕФИКС_КОНТЕЙНЕРОВ):
            continue
        краткое = re.sub(r"-\d+$", "", re.sub(r"^" + re.escape(ПРЕФИКС_КОНТЕЙНЕРОВ) + r"[-_]", "", имя))
        из[краткое] = max(из.get(краткое, 0.0), float(р["value"][1]) / 1024 / 1024)
    return из


def проверить_границы() -> list[str]:
    """Не устарели ли потолки: сервис мог вырасти или, наоборот, усохнуть."""
    пики = _пики_за_неделю()
    if not пики or not КОМПОУЗ.exists():
        return []
    беды: list[str] = []
    for имя, блок in _услуги(КОМПОУЗ.read_text(encoding="utf-8")).items():
        м = re.search(r"(\d+)\s*([mg])", str(блок.get("mem_limit", "")), re.I)
        пик = пики.get(имя)
        if not м or not пик:
            continue
        потолок = int(м.group(1)) * (1024 if м.group(2).lower() == "g" else 1)
        if пик > потолок * ТЕСНО:
            беды.append(f"{имя}: пик за неделю {пик:.0f} МБ при потолке {потолок} МБ — "
                        "тесно, поднять потолок (сервис вырос)")
        elif пик < потолок * СЛИШКОМ_ШИРОКО and потолок > 512:
            беды.append(f"{имя}: пик за неделю {пик:.0f} МБ при потолке {потолок} МБ — "
                        "потолок ни от чего не защищает, опустить")
    return беды


def проверить_машину() -> list[str]:
    беды: list[str] = []
    try:
        из = subprocess.run(("df", "--output=pcent", "/"), capture_output=True,
                            text=True, timeout=10).stdout.split()
        занято = int(из[-1].rstrip("%"))
        if занято >= ПОРОГ_ДИСКА:
            беды.append(f"диск занят на {занято}% (порог {ПОРОГ_ДИСКА}%)")
    except Exception:                                       # noqa: BLE001
        беды.append("диск: замерить не вышло")
    try:
        строки = Path("/proc/meminfo").read_text(encoding="utf-8")
        всего = int(re.search(r"SwapTotal:\s+(\d+)", строки).group(1))
        свободно = int(re.search(r"SwapFree:\s+(\d+)", строки).group(1))
        if всего:
            занято = round((всего - свободно) * 100 / всего)
            if занято >= ПОРОГ_СВОПА:
                беды.append(f"своп занят на {занято}% (порог {ПОРОГ_СВОПА}%)")
    except Exception:                                       # noqa: BLE001
        беды.append("своп: замерить не вышло")
    try:
        s = int(Path("/proc/sys/vm/swappiness").read_text().strip())
        if s > СВАППИНЕСС:
            беды.append(f"vm.swappiness={s} — ядро охотно выпихивает живые страницы; "
                        f"серверу нужно не выше {СВАППИНЕСС}")
    except Exception:                                       # noqa: BLE001
        pass
    return беды


def main() -> int:
    # `--только-compose` для CI: там другая машина, и её диск со свопом к нашему
    # серверу отношения не имеют — а правила compose проверить надо ДО вливания.
    беды = проверить_компоуз()
    if "--только-compose" not in sys.argv:
        беды += проверить_границы() + проверить_машину()
    if "--кратко" not in sys.argv:
        for б in беды:
            print("  •", б)
    print(f"гигиена сервера: нарушений {len(беды)}")
    return 1 if беды else 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except SystemExit:
        raise
    except Exception as e:                                  # noqa: BLE001
        raise _сломана(e) from None
