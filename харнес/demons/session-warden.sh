# ── Чем менять сессию: «/clear» или полный перезапуск ───────────────────────
# Решение владельца 11.09.2026: «Механизма нужно оба, просто для каждого своя
# роль». Замер того же дня на отдельной сессии: «/clear» освобождает окно
# (117 385 → 34 927 токенов), заводит НОВЫЙ идентификатор сессии и новый файл
# транскрипта — то есть замер заполнения подхватывает его сам, — и при этом
# CLAUDE.md с указаниями остаётся в контексте (проверено секретным словом:
# после «/clear» сессия ответила из контекста, ни разу не заглянув в файл).
#
# Отсюда роли. «/clear» — обычный путь: мгновенно, без выхода из процесса, без
# диалога подтверждения, без подъёма преемника (48 таймаутов из 135 попыток за
# месяц — все родом из тяжёлого пути). Полный перезапуск — там, где «/clear»
# бессилен, потому что процесс остаётся прежним:
#   • правились хуки или настройки — их читают только при старте процесса;
#   • сменилась версия CLI — работает старая, пока процесс жив;
#   • давно не перезапускались — память процесса не освобождается никогда;
#   • «/clear» уже подавали, а окно не упало — значит признак врёт, уходим
#     тяжёлым путём, а не крутимся в лёгком.
# Принудительный выход (`--rotate-now`, смена модели) — тоже полный: агент
# просил именно уйти.
#
# Печатает: clear | full
способ_ротации() { # $1=хуки правились $2=версия сменилась $3=часов с полного $4=потолок часов $5=clear не помог $6=принудительный
    local hooks="$1" version="$2" hours="$3" limit="$4" failed="$5" forced="$6"
    [ "$forced" = 1 ] && { printf 'full\n'; return 0; }
    [ "$failed" = 1 ] && { printf 'full\n'; return 0; }
    [ "$hooks"  = 1 ] && { printf 'full\n'; return 0; }
    [ "$version" = 1 ] && { printf 'full\n'; return 0; }
    [ "$hours" -ge "$limit" ] && { printf 'full\n'; return 0; }
    printf 'clear\n'
}

