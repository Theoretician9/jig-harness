# ── 5. Решение о ротации ────────────────────────────────────────────────────
# -ge, не -gt (Б-4г): обещано «больше одного компакта подряд запрещено» —
# достигнутый потолок MAX_COMPACTS уже означает ротацию.
NEED_ROTATE=0; REASON=""
if [ "$FORCE_ROTATE" = 1 ]; then
    # Ротацию запросил сам агент (`--rotate-now`). Пороги и антиповтор — про
    # то, когда сторож решает САМ; здесь решение уже принято, и подавить его
    # значило бы вернуть агента к единственному оставшемуся способу уйти —
    # выходу без смены (улика 11.08.2026, 22:51: вышел сам, преемника нет).
    NEED_ROTATE=1; REASON="ротацию запросил агент (--rotate-now)"
elif [ "$COMPACTS" -gt 0 ] && [ "$COMPACTS" -ge "$MAX_COMPACTS" ]; then
    NEED_ROTATE=1; REASON="компактов $COMPACTS ≥ потолка $MAX_COMPACTS"
elif [ "$FILL_PCT" -ge "$CTX_ROTATE_PCT" ]; then
    NEED_ROTATE=1; REASON="окно ≈${FILL_PCT}% ≥ ${CTX_ROTATE_PCT}%"
fi

# Защита от спама — РАЗДЕЛЬНО по видам события. Анонс владельцу (semi) и
# поданная в панель команда (full) — разные вещи: первый ждёт чужого решения,
# вторая уже исполняется. Пока оба писались событием rotate_command, анонс,
# на который владелец не ответил, давил ротацию весь ROTATE_COOLDOWN_MIN.
# Улика 11.08.2026: анонс 22:20 → «повтор не подаю» в 22:30 и 22:40 при окне
# 97% и 114% → контекст переполнился и ушёл в автосжатие, то есть ровно в то,
# что ротация обязана предотвращать. Поэтому и окно у анонса своё, короткое:
# неотвеченный вопрос стоит владельцу одного сообщения, а молчание сторожа —
# потерянной сессии.
ROTATE_SUPPRESSED=0
if [ "$NEED_ROTATE" = 1 ] && [ "$FORCE_ROTATE" != 1 ]; then
    read -r VERDICT LAST_EVENT AGE_MIN GAP_MIN <<<"$(подавить_ротацию \
        "$ROTATION_LOG" "$SESSION_ID" "${ROTATE_NEEDS_OWNER:-0}" "$(date +%s)")"
    if [ "$VERDICT" = "да" ]; then
        # Формулировка честная: ротация ТРЕБУЕТСЯ, просто подавлена. Раньше
        # следом печаталось «ротация не требуется» — прибор врал тому, кто
        # придёт читать журнал после отказа.
        say "ротация ТРЕБУЕТСЯ ($REASON), но подавлена антиповтором: $LAST_EVENT был ${AGE_MIN} мин назад (< ${GAP_MIN}); повтор через $(( GAP_MIN - AGE_MIN )) мин"
        NEED_ROTATE=0; ROTATE_SUPPRESSED=1
    fi
fi

