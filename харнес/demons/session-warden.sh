knopka_revizii() {  # $1 = файл-флага, $2 = путь демона ревизии
    # Кнопка панели «ревизия сейчас» — ФЛАГ, а не ключ конфига. Ключ читает
    # месячный cron, а сбрасывать его пришлось бы демону, то есть второму
    # писателю /etc/harness/harness.conf (спека ревизии, C-5). Флаг кладёт
    # панель, снимает сторож — и обещание «в ближайшую проверку» правдиво.
    [ -f "$1" ] || return 0
    rm -f "$1"
    if [ ! -x "$2" ] && [ ! -f "$2" ]; then
        say "кнопка ревизии: демона нет ($2) — флаг снят, запускать нечего"
        return 1
    fi
    say "кнопка ревизии: запускаю $2 --сейчас"
    setsid nohup bash "$2" --сейчас >> "$LOG_DIR/revizia-proekta.log" 2>&1 < /dev/null &
    return 0
}

