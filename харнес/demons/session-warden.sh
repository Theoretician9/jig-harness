    # Три признака порознь: по ним видно, какой именно не сошёлся, а не «просто нет».
    printf '%s\n' "$SCREEN" | grep -qE '^[[:space:]]*Background work is running[[:space:]]*$' \
        && echo "  заголовок: есть" || echo "  заголовок: НЕТ"
