# ── 6. Silence-watchdog: очередь непуста, а агент молчит ────────────────────
DEVMAP="$PROJECT_DIR/dev-map.yaml"
if [ -f "$DEVMAP" ]; then
    # Будить агента можно только под РАБОТУ. Ночью 12.08 в очереди стояла одна
    # задача, чью формулировку даёт владелец: пинки уходили каждые
    # SILENCE_MAX_MIN, агент просыпался, отвечал «блокер тот же» и жёг контекст
    # до утра. Признак «ждёт владельца» — поле blocked у задачи в карте.
    QUEUE_OUT=$(python3 "$PROJECT_DIR/scripts/ochered-raboty.py" "$DEVMAP" 2>/dev/null || true)
    WORK=$(printf '%s\n' "$QUEUE_OUT" | sed -n 's/^работа: //p')
    WAITING=$(printf '%s\n' "$QUEUE_OUT" | sed -n 's/^ждут: //p')
    # Прибор не ответил (нет PyYAML, битая карта) — возвращаемся к прежнему
    # признаку: непустая очередь. Молчать из-за сломанного прибора нельзя.
    if ! [[ "${WORK:-}" =~ ^[0-9]+$ ]]; then
        if grep -qE '^queue:' "$DEVMAP" && ! grep -qE '^queue:\s*\[\s*\]\s*$' "$DEVMAP"; then WORK=1; else WORK=0; fi
        say "прибор очереди не ответил — считаю по прежнему признаку (работа=$WORK)"
    fi
    if [ "$WORK" -gt 0 ]; then
        IDLE_MIN=$(( ( $(date +%s) - $(stat -c '%Y' "$TRANSCRIPT") ) / 60 ))
        if [ "$IDLE_MIN" -gt "$SILENCE_MAX_MIN" ]; then
            say "тишина: очередь непуста, транскрипт молчит ${IDLE_MIN} мин (> ${SILENCE_MAX_MIN}) — пинок в tmux"
            if tmux has-session -t "$TMUX_SESSION" 2>/dev/null; then
                if agent_prompt "Очередь в dev-map.yaml непуста, а работы не видно ${IDLE_MIN} минут. Продолжай текущую задачу или назови блокер."; then
                    jlog "silence_kick" "$SESSION_ID" "тишина ${IDLE_MIN} мин при непустой очереди"
                else
                    tg_send "Очередь непуста, агент молчит ${IDLE_MIN} мин, а в tmux-панели не claude — пинок не отправлен. Похоже, агент выпал в оболочку." || say "и сигнал не ушёл"
                    WARDEN_RC=1
                fi
            else
                say "пинать некого: tmux-сессии '$TMUX_SESSION' нет — сигнал владельцу"
                tg_send "Очередь в dev-map.yaml непуста, агент молчит ${IDLE_MIN} мин, tmux-сессии нет. Запустить агента?" || say "и сигнал не ушёл"
                WARDEN_RC=1
            fi
        fi
    elif [ -n "$WAITING" ]; then
        # Работы нет, но очередь не пуста — вся она ждёт владельца. Агента не
        # трогаем (будить нечем), а тишина не должна стать вечной: раз в
        # BLOCKED_TELL_GAP_MIN напоминаем тому, от кого зависит движение.
        TOLD="$LOG_DIR/blocked-queue.told"
        AGE_MIN=""
        [ -f "$TOLD" ] && AGE_MIN=$(( ( $(date +%s) - $(stat -c '%Y' "$TOLD") ) / 60 ))
        # Второй признак: агент ПРОСТАИВАЕТ. «Очередь целиком ждёт владельца»
        # истинно и когда смена занята работой, пришедшей сообщением в канал, —
        # а её в карте очереди нет. В ночь на 11.09 смена работала всю ночь, и
        # владелец в 01:20 получил «работы, которую я могу делать сам, нет».
        # Занятому агенту сигнал не нужен: упрётся — скажет сам.
        BUSY_MIN=0
        [ -f "$TRANSCRIPT" ] && BUSY_MIN=$(( ( $(date +%s) - $(stat -c '%Y' "$TRANSCRIPT") ) / 60 ))
        if [ "$BUSY_MIN" -lt "${SILENCE_MAX_MIN:-30}" ]; then
            say "очередь целиком ждёт владельца ($WAITING), но агент работает (тишина ${BUSY_MIN} мин < ${SILENCE_MAX_MIN:-30}) — владельца не трогаю"
        elif подавлен_кулдауном "$AGE_MIN" "${BLOCKED_TELL_GAP_MIN:-720}"; then
            say "очередь целиком ждёт владельца ($WAITING); сказано $AGE_MIN мин назад — молчу"
        elif tg_send "Работы, которую я могу делать сам, в очереди нет — она ждёт вашего решения: $WAITING. Как ответите, продолжу сам."; then
            date +%s > "$TOLD"
            say "очередь целиком ждёт владельца ($WAITING) — сказал ему"
        else
            say "очередь ждёт владельца, и сигнал об этом не ушёл"
            WARDEN_RC=1
        fi
    fi
else
    say "dev-map.yaml нет — очередь проверять не по чему (продукт ещё не начат)"
fi

# ── 6в. Пульс отчётности: работа идёт, а владелец не слышит ────────────────
# Владелец 11.09.2026: «мне нужна ёмкая, лаконичная, но регулярная отчетность,
# как пульс по регулярности, и контроль тоже должен быть системный».
# Метку ставит tg_send при КАЖДОЙ доставке — регулярность перестаёт держаться
# моей памятью. Порог — число самого владельца от 21.08.2026: «Пиши статусы в
# процессе работы», молчание дольше получаса он назвал отказом.
PULSE_MARK="$LOG_DIR/last_report"
PULSE_MAX_MIN="${PULSE_MAX_MIN:-${SILENCE_MAX_MIN:-30}}"
if tmux has-session -t "$TMUX_SESSION" 2>/dev/null && [ -f "$TRANSCRIPT" ]; then
    WORK_AGE_MIN=$(( ( $(date +%s) - $(stat -c '%Y' "$TRANSCRIPT") ) / 60 ))
    if [ -f "$PULSE_MARK" ]; then
        REPORT_AGE_MIN=$(( ( $(date +%s) - $(stat -c '%Y' "$PULSE_MARK") ) / 60 ))
    else
        REPORT_AGE_MIN=9999
    fi
    # Работает = транскрипт моложе порога тишины. Молчащему агенту пинок про
    # отчёт не нужен: его будят другие ветки, каждая по своему признаку.
    if [ "$WORK_AGE_MIN" -lt "${SILENCE_MAX_MIN:-30}" ] \
       && [ "$REPORT_AGE_MIN" -ge "$PULSE_MAX_MIN" ]; then
        PULSE_KICK="$LOG_DIR/pulse.kick"
        KICK_AGE=""
        [ -f "$PULSE_KICK" ] && KICK_AGE=$(( ( $(date +%s) - $(stat -c '%Y' "$PULSE_KICK") ) / 60 ))
        if подавлен_кулдауном "$KICK_AGE" "$PULSE_MAX_MIN"; then
            say "пульс: отчёта нет ${REPORT_AGE_MIN} мин, но пинок был $KICK_AGE мин назад — жду"
        else
            date +%s > "$PULSE_KICK"
            say "пульс: работа идёт (${WORK_AGE_MIN} мин), а отчёта владельцу нет ${REPORT_AGE_MIN} мин — прошу статус"
            jlog "pulse_kick" "$SESSION_ID" "отчёта нет ${REPORT_AGE_MIN} мин при идущей работе"
            agent_prompt "[сторож сессий] Владельцу нет отчёта ${REPORT_AGE_MIN} минут, а работа идёт. Дай короткий статус в канал: что сделано числом, что делаешь сейчас. Без разбора своих действий — он идёт в журнал." \
                || say "пинок про пульс не ушёл (в панели: $(pane_cmd))"
        fi
    fi
fi

# ── 6б. Лимит подписки: сказать владельцу и поднять работу самим ───────────
# Задача владельца 11.09.2026. Прежде этого не было вовсе: сторож пинал агента
# ТОЛЬКО при непустой незаблокированной очереди, а при исчерпанном лимите
# очередь обычно уже стоит — будить было некому, и смена молча умирала до
# прихода владельца.
# Механика намеренно простая: пока агент нем — повторять пинок. Лимит кончится
# сам, очередной пинок пройдёт, работа продолжится. Это лечит не только лимит,
# а любую немоту сессии, и не требует угадывать чужой текст.
LIMIT_STATE="$LOG_DIR/лимит-подписки.состояние"
LIMIT_STALL_MIN="${LIMIT_STALL_MIN:-20}"
LIMIT_RETRY_MIN="${LIMIT_RETRY_MIN:-10}"
if tmux has-session -t "$TMUX_SESSION" 2>/dev/null && [ -f "$TRANSCRIPT" ]; then
    STALL_MIN=$(немота_агента_минут "$TRANSCRIPT" || true)
    # Прибор не ответил — не молчать: берём прежний, заведомо заниженный
    # признак, он хуже, но это лучше слепоты.
    [[ "$STALL_MIN" =~ ^[0-9]+$ ]] || \
        STALL_MIN=$(( ( $(date +%s) - $(stat -c '%Y' "$TRANSCRIPT") ) / 60 ))
    PANE_NOW=$(tmux capture-pane -p -t "$TMUX_SESSION" 2>/dev/null || true)
    LIMIT_SEEN=0
    признак_лимита_в "$PANE_NOW" && LIMIT_SEEN=1
    # Будим по НЕМОТЕ, а признак лимита нужен лишь для слов владельцу. Прежде
    # пинок был заперт за признаком лимита — текста CLI при исчерпании я не
    # наблюдал, и «работа поднимется сама» не выполнялось ни разу (задача
    # владельца 11.09: «после обновления лимитов автоматического запуска не
    # произошло»). Немота при живой панели — достаточное основание разбудить:
    # работающий агент пишет в транскрипт постоянно.
    if [ "$STALL_MIN" -ge "$LIMIT_STALL_MIN" ]; then
        if [ ! -f "$LIMIT_STATE" ]; then
            date +%s > "$LIMIT_STATE"
            if [ "$LIMIT_SEEN" = 1 ]; then
                jlog "limit_reached" "$SESSION_ID" "панель: $(строка_лимита_в "$PANE_NOW"); немота ${STALL_MIN} мин"
                RESET_IN=$(через_сколько_сброс "$(строка_лимита_в "$PANE_NOW")")
                [ -n "$RESET_IN" ] && RESET_IN="Обновится $RESET_IN." \
                    || RESET_IN="Времени сброса CLI не назвал — скажу, как только работа пойдёт."
                tg_send "Упёрся в лимит подписки — работа встала. Панель говорит: $(строка_лимита_в "$PANE_NOW"). $RESET_IN Делать ничего не нужно: как лимит обновится, я продолжу сам и скажу вам об этом." \
                    || say "о лимите сказать не удалось"
            else
                jlog "agent_stalled" "$SESSION_ID" "немота ${STALL_MIN} мин, признака лимита на панели нет"
                tg_send "Работа встала: агент молчит ${STALL_MIN} минут. Признака лимита на экране не видно, причина пока не названа. Бужу сам каждые ${LIMIT_RETRY_MIN} минут — если дело в лимите, смена поднимется, как только он обновится." \
                    || say "о немоте сказать не удалось"
            fi
        fi
        # Пинок с редким шагом: пока лимит держится, он не пройдёт, но и не
        # стоит ничего. Как только лимит обновится, ближайший пинок оживит смену.
        LIMIT_KICK="$LOG_DIR/лимит-подписки.пинок"
        KICK_AGE=""
        [ -f "$LIMIT_KICK" ] && KICK_AGE=$(( ( $(date +%s) - $(stat -c '%Y' "$LIMIT_KICK") ) / 60 ))
        if подавлен_кулдауном "$KICK_AGE" "$LIMIT_RETRY_MIN"; then
            say "лимит подписки держится (тишина ${STALL_MIN} мин), пинок был $KICK_AGE мин назад — жду"
        else
            date +%s > "$LIMIT_KICK"
            say "лимит подписки: тишина ${STALL_MIN} мин — пробую разбудить смену"
            agent_prompt "[сторож сессий] Если лимит подписки обновился — продолжай работу с того места, где остановился: сверься с STATE.md и docs/handover/, проверь \$LOG_DIR/inbox/ и скажи владельцу, что работа возобновилась." \
                || say "пинок не ушёл (в панели: $(pane_cmd))"
        fi
    elif [ -f "$LIMIT_STATE" ] && [ "$STALL_MIN" -lt "$LIMIT_STALL_MIN" ]; then
        # Смена ожила: транскрипт снова растёт. Владельцу об этом говорим ровно
        # один раз — молчаливое возобновление он принял бы за продолжение простоя.
        DOWN_MIN=$(( ( $(date +%s) - $(cat "$LIMIT_STATE" 2>/dev/null || date +%s) ) / 60 ))
        rm -f "$LIMIT_STATE" "$LOG_DIR/лимит-подписки.пинок"
        jlog "limit_cleared" "$SESSION_ID" "работа возобновилась, простой ${DOWN_MIN} мин"
        say "лимит подписки снят: работа возобновилась после ${DOWN_MIN} мин простоя"
        tg_send "Лимит обновился — работа возобновилась сама, простой составил ${DOWN_MIN} мин. Продолжаю с того места, где остановился." \
            || say "о возобновлении сказать не удалось"
    fi
fi

# ── 6а. Входящие владельца: непустой inbox не должен лежать молча ───────────
# Диспетчер складывает сообщения владельца в $LOG_DIR/inbox/ файлами; агент
# переносит прочитанное в inbox/обработано/. Свежий необработанный файл старше
# пары минут — пинок в сессию: сообщение владельца не имеет права ждать.
INBOX_DIR="$LOG_DIR/inbox"
OWNER_WAITING=0   # латиницей намеренно: кириллица в имени переменной bash запрещена
if [ -d "$INBOX_DIR" ]; then
    INBOX_N=$(find "$INBOX_DIR" -maxdepth 1 -type f -mmin +2 2>/dev/null | wc -l | tr -d ' ')
    if [ "$INBOX_N" -gt 0 ]; then
        OWNER_WAITING=1
        say "в inbox $INBOX_N необработанных сообщений владельца — пинок в tmux"
        if tmux has-session -t "$TMUX_SESSION" 2>/dev/null; then
            if agent_prompt "В $INBOX_DIR лежат $INBOX_N сообщений владельца — прочитай (ls, cat) и перенеси в $INBOX_DIR/обработано/."; then
                jlog "inbox_kick" "$SESSION_ID" "необработанных: $INBOX_N"
            else
                tg_send "У меня $INBOX_N ваших сообщений в inbox, но в tmux-панели не claude — агент выпал в оболочку. Поднимаю смену сейчас же, ответ будет от неё." || say "и сигнал не ушёл"
                WARDEN_RC=1
            fi
        else
            say "tmux-сессии нет — входящие некому отдать, сигнал владельцу"
            tg_send "У меня $INBOX_N ваших сообщений в очереди, но сессия агента не запущена." || say "и сигнал не ушёл"
            WARDEN_RC=1
        fi
    fi
fi

# ── 6г. Кнопка панели «ревизия сейчас» ─────────────────────────────────────
knopka_revizii "$LOG_DIR/revizia/запуск" "$PROJECT_DIR/харнес/demons/revizia-proekta.sh"

# ── 6б. Агент выпал в оболочку — самостоятельное состояние ──────────────────
# Не «не смогли доставить», а «работать некому». Порядок: засечь время →
# уважить приаттаченного владельца → по порогу поднять агента той же командой,
# что и ротация (AGENT_START_CMD) → сказать владельцу, но не чаще кулдауна.
PANE_STATE="$LOG_DIR/agent-pane.since"
DEAD_STAMP="$LOG_DIR/agent-pane.told"
if tmux has-session -t "$TMUX_SESSION" 2>/dev/null; then
    PANE_NOW=$(pane_cmd)
    CLIENTS=$(tmux list-clients -t "$TMUX_SESSION" 2>/dev/null | grep -c . || true)
    # Часы «агента нет с» заводятся ДО решения. Пока их заводила только ветка
    # «ждём», приаттаченный клиент останавливал и часы: отсчёт начинался заново
    # после его отключения, и порог не наступал никогда.
    case "$PANE_NOW" in claude|node) : ;; *) [ -s "$PANE_STATE" ] || date +%s > "$PANE_STATE" ;; esac
    SINCE=0
    [ -f "$PANE_STATE" ] && SINCE=$(cat "$PANE_STATE" 2>/dev/null || echo 0)
    # Простой панели: tmux помнит время последней активности сессии. Живой
    # человек за клиентом её обновляет, забытый ssh-клиент — нет.
    PANE_ACTIVITY=$(tmux display-message -p -t "$TMUX_SESSION" '#{window_activity}' 2>/dev/null || echo 0)
    PANE_IDLE_MIN=$(( ( $(date +%s) - ${PANE_ACTIVITY:-0} ) / 60 ))
    [ "$PANE_IDLE_MIN" -lt 0 ] && PANE_IDLE_MIN=0
    case "$(решение_по_панели "$PANE_NOW" "${CLIENTS:-0}" "$SINCE" "$(date +%s)" "$PANE_IDLE_MIN" "$OWNER_WAITING")" in
        ok)
            [ -f "$PANE_STATE" ] && rm -f "$PANE_STATE" "$DEAD_STAMP"
            say "в панели '$PANE_NOW' — агент на месте"
            ;;
        человек)
            say "в панели '$PANE_NOW', но к сессии подключён владелец (клиентов: $CLIENTS, простой ${PANE_IDLE_MIN} мин) — не вмешиваюсь"
            ;;
        сказать)
            # Человек в панели работает — команду туда не шлём. Но агента нет
            # дольше порога, и молчать об этом нельзя: харнес стоит.
            MIN_OUT=$(( ( $(date +%s) - SINCE ) / 60 ))
            say "агента нет ${MIN_OUT} мин, но в панели работает человек (простой ${PANE_IDLE_MIN} мин) — не вмешиваюсь, говорю в канал"
            TELL=1
            if [ -f "$DEAD_STAMP" ]; then
                AGE_MIN=$(( ( $(date +%s) - $(stat -c '%Y' "$DEAD_STAMP") ) / 60 ))
                [ "$AGE_MIN" -lt "$AGENT_DEAD_COOLDOWN_MIN" ] && TELL=0
            fi
            if [ "$TELL" = 1 ]; then
                tg_send "Агента нет ${MIN_OUT} мин: в tmux-панели '$PANE_NOW'. Сам не поднимаю — в панели кто-то работает (последняя активность ${PANE_IDLE_MIN} мин назад), команда испортила бы ваш ввод. Запустить: «$AGENT_START_CMD»." \
                    && date +%s > "$DEAD_STAMP" \
                    || say "сигнал о простое агента не ушёл"
            fi
            ;;
        ждём)
            [ -s "$PANE_STATE" ] || date +%s > "$PANE_STATE"
            say "в панели '$PANE_NOW' (не claude) — засёк время, порог ${AGENT_DEAD_MIN} мин"
            ;;
        поднять)
            MIN_OUT=$(( ( $(date +%s) - SINCE ) / 60 ))
            say "агент выпал в оболочку: в панели '$PANE_NOW' уже ${MIN_OUT} мин, клиентов нет — поднимаю"
            if start_agent; then
                jlog "agent_revived" "${SESSION_ID:-?}" "панель '$PANE_NOW' ${MIN_OUT} мин, поднят $AGENT_START_CMD"
                подхватить_работу || true
                rm -f "$PANE_STATE"
                # Сигнал владельцу — с кулдауном: беда та же, спам ни к чему.
                TELL=1
                if [ -f "$DEAD_STAMP" ]; then
                    AGE_MIN=$(( ( $(date +%s) - $(stat -c '%Y' "$DEAD_STAMP") ) / 60 ))
                    [ "$AGE_MIN" -lt "$AGENT_DEAD_COOLDOWN_MIN" ] && TELL=0
                fi
                if [ "$TELL" = 1 ]; then
                    tg_send "Агент выпадал в оболочку (в панели было '$PANE_NOW' ${MIN_OUT} мин) — поднял сам командой «$AGENT_START_CMD». Если это вы выходили из сессии: выход из tmux — Ctrl+B затем D, а Ctrl+C закрывает агента." \
                        && date +%s > "$DEAD_STAMP" \
                        || say "сигнал о выпавшем агенте не ушёл — агент при этом поднят"
                fi
            else
                jlog "agent_revive_failed" "${SESSION_ID:-?}" "команда «$AGENT_START_CMD» не подняла claude"
                tg_send "Агент выпал в оболочку, и поднять его командой «$AGENT_START_CMD» не удалось за ${AGENT_START_TIMEOUT_SEC}с. Нужны ваши руки: sudo -u $AGENT_USER -H tmux attach -t $TMUX_SESSION" \
                    || say "и сигнал не ушёл"
                WARDEN_RC=1
            fi
            ;;
    esac
else
    # Сессии нет вовсе — с тех пор как её создают КОМАНДОЙ, это обычный вид
    # смерти агента: вышел — закрылась панель, а с ней и сессия. Юнит её не
    # вернёт (штатный выход = rc 0, у юнита Restart=on-failure), значит это
    # работа сторожа. Раньше здесь была только строчка в лог — самый глухой
    # вид простоя из возможных.
    say "tmux-сессии '$TMUX_SESSION' нет — агента нет вовсе, поднимаю сессию с агентом"
    if start_agent; then
        jlog "agent_revived" "${SESSION_ID:-?}" "сессии не было — поднята вместе с агентом ($AGENT_START_CMD)"
        подхватить_работу || true
        TELL=1
        if [ -f "$DEAD_STAMP" ]; then
            AGE_MIN=$(( ( $(date +%s) - $(stat -c '%Y' "$DEAD_STAMP") ) / 60 ))
            [ "$AGE_MIN" -lt "$AGENT_DEAD_COOLDOWN_MIN" ] && TELL=0
        fi
        if [ "$TELL" = 1 ]; then
            tg_send "Сессии агента не было совсем (панель закрылась вместе с ним) — поднял заново командой «$AGENT_START_CMD»." \
                && date +%s > "$DEAD_STAMP" || say "сигнал о поднятой сессии не ушёл"
        fi
    else
        jlog "agent_revive_failed" "${SESSION_ID:-?}" "сессии не было, поднять её с агентом не удалось"
        tg_send "Сессии агента нет, и поднять её командой «$AGENT_START_CMD» не удалось. Нужны ваши руки: sudo -u $AGENT_USER -H systemctl restart harness-agent" \
            || say "и сигнал не ушёл"
        WARDEN_RC=1
    fi
fi

# Метка heartbeat — ТОЛЬКО при полном успехе прогона.
if [ "$WARDEN_RC" = 0 ]; then
    touch "$HEARTBEAT_DIR/session-warden"
fi
exit "$WARDEN_RC"
