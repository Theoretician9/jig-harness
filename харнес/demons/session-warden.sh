#!/usr/bin/env bash
#
# session-warden.sh — надзиратель сессий: ротация по заполнению окна и тишине.
#
# Что держит: правило «сессия не доживает до авто-компакта» (UNIFIED/13,
# И-инварианты карты носителей). Контекст, пережатый компактом больше
# MAX_COMPACTS раз, теряет решения владельца; сессия, молчащая при непустой
# очереди, — потерянные часы. Оба отказа должен ловить механизм, не внимание.
#
# Откуда взят: собран для стартового пакета по нормам UNIFIED/13 (ротация)
# и UNIFIED/08 (мягкий отказ оставляет след); приём «фоновый claude -p без
# MCP-серверов» — улика из devmap-selfheal.sh: telegram-плагин допускает
# одного потребителя getUpdates и убивает живой канал, поэтому headless-вызовы
# здесь идут строго со --strict-mcp-config и пустым набором серверов.
#
# Чем доказывается: МЕХАНИКА ЗАМЕРА ОКНА — ЭВРИСТИКА (байты JSONL ≈ окно),
# доказывается принудительной ротацией на этапе приёмки (03-ЗАДАНИЕ §первая
# ротация): порог CTX_WINDOW_BYTES калибруется по живому замеру и вписывается
# в harness.conf. Тишина и режимы semi/full доказываются больными случаями
# при установке (01-SPEC §9).
#
# Запуск: cron, каждые 10 минут, от имени $AGENT_USER. Лог — в stdout,
# cron перенаправляет в $LOG_DIR/session-warden.log.
set -euo pipefail

say() { printf '%s  %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$*"; }

# ── доставка текста в панель агента ─────────────────────────────────────────
# Копия функции из scripts/tg-dispatcher.sh — оба скрипта самодостаточны
# (демон и сервис живут в разных каталогах и не имеют общей библиотеки).
# Улика 11.08.2026: `tmux send-keys -t сессия "$текст" Enter` теряет текст
# двумя способами. Без -l tmux разбирает аргумент как ИМЯ КЛАВИШИ, если оно
# совпало: пинок со словом «Enter» стал нажатием Enter, а «C-c» оборвал бы
# сессию агента. И одним вызовом финальный Enter теряется — TUI ещё разбирает
# вставку и нажатия не видит, текст остаётся в строке ввода непосланным.
# Переводы строки — в пробел: в TUI каждый \n это отправка.
send_to_pane() {  # текст
    local flat="${1//$'\n'/ }"
    flat="${flat//$'\r'/ }"
    tmux send-keys -t "$TMUX_SESSION" -l -- "$flat" || return 1
    sleep "${PANE_ENTER_DELAY:-0.7}"
    tmux send-keys -t "$TMUX_SESSION" Enter || return 1
}

# ── диалог «Background work is running» перехватывает «/exit» ───────────────
# Улика 09.09.2026 (снимок владельца): «/exit» подан, а вместо выхода — вопрос
# с тремя пунктами и «Enter to confirm». Владелец терминала не видит, нажать
# некому: сессия висела, преемник не поднимался, сторож будил владельца зря.
# Пункт 1 («Exit and stop tasks») выбран по умолчанию, и он же верный: НАСТОЯЩАЯ
# долгая работа идёт через `setsid nohup` (этого требует guard_bash) и выходу не
# подчиняется вовсе. Гибнут только задачи самой сессии — ожидания, которые она и
# так не переживёт.
# Признак — ТРИ строки разом, включая приглашение подтвердить: одна строка
# встречается и в отчёте агента про этот самый случай, а слепой Enter в панель
# подтвердил бы чужой вопрос.
# Маркер выбранного пункта в меню Claude Code — «❯», а НЕ «>». Улика
# 11.09.2026: за ротацию 02:00 сторож не распознал диалог ни разу (ноль записей
# rotate_exit_dialog при поданном «/exit»), владелец вышел руками. Причина —
# образец экрана в самотесте был ВЫДУМАН со знаком «>», живой снимок панели дал
# байты e2 9d af. Чередование, а не класс [..]: в локали C класс распался бы на
# отдельные байты и ловил бы любой знак с байтом 0xe2 ([[проверка-создаёт-условие]]).
# «>» оставлен законным: он приходит из ASCII-режима терминала.
PICK_MARK='(>|❯|▶)'
RE_EXIT_ITEM="^[[:space:]]*${PICK_MARK}?[[:space:]]*[0-9]+\\.[[:space:]]+Exit and stop tasks"
RE_PICKED_ITEM="^[[:space:]]*${PICK_MARK}[[:space:]]*[0-9]+\\."

диалог_выхода_в() {  # $1 = текст панели
    # Признак — ТРИ СТРОКИ по своим местам, а не три подстроки где попало.
    # Ревью 10.09.2026: подстрочный признак срабатывал на самом файле сторожа
    # (в нём лежит образец экрана для самотеста) — стоило агенту открыть или
    # сгрепать session-warden.sh во время ротации, и сторож слал Escape в живую
    # сессию, обрывая ход. Пункт ищем как пункт: «N. Exit and stop tasks» в
    # начале строки, возможно под стрелкой выбора.
    printf '%s\n' "$1" | grep -qE '^[[:space:]]*Background work is running[[:space:]]*$' \
        && printf '%s\n' "$1" | grep -qE "$RE_EXIT_ITEM" \
        && printf '%s\n' "$1" | grep -qE '^[[:space:]]*Enter to confirm'
}

# ── лимит подписки исчерпан: работа встала, а панель жива ───────────────────
# Задача владельца 11.09.2026: «Допустим сейчас опять лимиты закончились, я об
# этом не знаю, после их обновления работа сама не запустится».
# Признак НАРОЧНО широкий и двойной. Точного текста CLI при исчерпании лимита я
# не наблюдал — в транскриптах следов нет, — а выдумывать чужой вывод я уже
# пробовал: так родилась слепота к «❯» ([[маркер-меню-cli-не-больше-меньше]]).
# Поэтому: слово limit рядом со словом о сбросе/исчерпании В ПАНЕЛИ — это лишь
# половина; вторая половина (немота транскрипта) проверяется вызывающим. Одна
# без другой ничего не значит: про лимит пишу в отчётах и я сам.
# Когда случай произойдёт, журнал сохранит экран дословно — тогда признак можно
# будет сузить по улике, а не по догадке.
# Грепать ТЕМ ЖЕ выражением, что и признак: по одному слову «limit» в панели
# первой находится строка приглашения оболочки, и владелец получил бы в канал
# свою же команду вместо времени сброса (проба 11.09.2026).
# Образец снят с ЖИВОГО экрана: владелец прислал снимок 11.09.2026, и он
# показал, что прежний признак не сработал бы. Настоящая строка CLI:
#   You've hit your session limit · resets 2:50pm (Asia/Qostanay)
#   /upgrade to increase your usage limit.
# Прежний образец требовал слова «reached» или «resets» СРАЗУ после «limit», а
# там между ними « · ». Теперь ждём: «hit your … limit», «limit» рядом с
# reached/exceeded/resets в пределах строки, «/upgrade …» — и не выдумываем.
LIMIT_RE='(hit|reached|exceeded)[^\n]{0,40}limit|limit[^\n]{0,20}(reached|exceeded|resets?|will reset)|out of (usage|credits)|/upgrade (to|or)|upgrade to continue'
признак_лимита_в() {  # $1 = текст панели
    printf '%s\n' "$1" | grep -qiE "$LIMIT_RE"
}

# Строка про лимит целиком — владельцу нужно ВРЕМЯ сброса, а его печатает CLI.
строка_лимита_в() { # $1 = текст панели
    printf '%s\n' "$1" \
        | grep -m1 -iE "$LIMIT_RE" \
        | sed 's/^[[:space:]]*//' | cut -c1-200 || true
}

# Через сколько лимит обновится — задача владельца 11.09.2026: «сделай чтобы он
# еще сообщал через сколько времени лимиты обновятся». Время сброса печатает
# САМ CLI в строке панели («resets 6pm», «resets at 18:00»); мы его только
# разбираем и считаем остаток. Не назвал — так и говорим, без выдумки: врать
# про срок хуже, чем промолчать.
через_сколько_сброс() { # $1 = строка панели; печатает «в 18:00, через 47 мин»
    printf '%s\n' "$1" | python3 -c '
import datetime, re, sys
строка = sys.stdin.read()
м = re.search(r"resets?(?:\s+at)?\s+(\d{1,2})(?::(\d{2}))?\s*(am|pm)?", строка, re.I)
if not м:
    sys.exit(1)
час = int(м.group(1)); минута = int(м.group(2) or 0); половина = (м.group(3) or "").lower()
if половина == "pm" and час != 12:
    час += 12
elif половина == "am" and час == 12:
    час = 0
if час > 23:
    sys.exit(1)
сейчас = datetime.datetime.now()
сброс = сейчас.replace(hour=час, minute=минута, second=0, microsecond=0)
if сброс <= сейчас:                      # названо время следующих суток
    сброс += datetime.timedelta(days=1)
осталось = int((сброс - сейчас).total_seconds() // 60)
часы, мин = divmod(осталось, 60)
сколько = f"{часы} ч {мин} мин" if часы else f"{мин} мин"
print(f"в {сброс:%H:%M}, через {сколько}")
' 2>/dev/null
}

