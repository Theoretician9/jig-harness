${HANDOVER_NOTE:+$HANDOVER_NOTE
}Скомандуйте агенту завершение: обновить STATE.md, дописать docs/handover/SESSION-HANDOFF-$(date +%Y-%m-%d).md, выйти."
    # jlog — ТОЛЬКО после ok:true (Б-4в): запись до отправки взводит кулдаун,
