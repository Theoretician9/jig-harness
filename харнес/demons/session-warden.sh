# Точный признак даёт хук Stop: он срабатывает ровно тогда, когда ход завершён.
# Хук пишет время в turn-end.stamp, здесь оно сверяется с моментом поручения:
# закончил ход ПОСЛЕ того, как получил задание, — регламент отработан.
#
# Закончил ли агент ход после указанного момента (метку пишет хук Stop).
# Метки нет — печатаем 0: молчание хука толкуем как «ход не закончен», иначе
# отсутствие сигнала работало бы разрешением, а это ровно то, что чинится.
ход_завершён_после() {  # $1=epoch поручения
    local since="$1" stamp
    stamp=$(cat "$LOG_DIR/turn-end.stamp" 2>/dev/null || echo 0)
    [[ "$stamp" =~ ^[0-9]+$ ]] || stamp=0
    if [ "$stamp" -gt "$since" ]; then printf '1'; else printf '0'; fi
}

# Печатает одно слово: смена | ждём | выход | принудительно | тревога
выход_из_ротации() {  # $1=вердикт смены $2=простой панели, сек $3=выход уже подан(1/0) $4=прошло сек $5=таймаут сек $6=ход завершён после поручения(1/0) $7=фоновая задача сессии жива(1/0)
    # Имена переменных латиницей: кириллические bash запрещает (SC2296).
    local verdict="$1" idle="$2" sent="$3" elapsed="$4" limit="$5" turn_done="${6:-0}" tasks_live="${7:-0}"
    [ "$verdict" = "ждём" ] || { printf 'смена\n'; return 0; }
    if [ "$sent" != 1 ]; then
        # Ход закончен И панель молчит — регламент отработан, агент ждёт ввода.
        # Одного молчания мало (см. улику выше), одной метки — тоже: ход мог
        # закончиться и возобновиться, а метка осталась бы прежней.
        [ "$turn_done" = 1 ] && [ "$idle" -ge "${ROTATE_IDLE_SEC:-120}" ] && { printf 'выход\n'; return 0; }
        # Срок вышел, а панель всё говорит: выход всё равно наш — молчание
        # сторожа стоит дороже прерванного хода, работа уже в передаче.
        [ "$elapsed" -ge "$limit" ] && { printf 'принудительно\n'; return 0; }
    elif [ "$elapsed" -ge "$limit" ]; then
        # Фоновая задача сессии держит очередь ввода: «/exit» УЖЕ принят, но
        # исполнится после неё. Сессия при этом жива и работает — будить
        # владельца не за что. Улика 04.09.2026: сторож ввёл «/exit» в 14:13:02,
        # транскрипт принял его («Bye!») в 14:19:34 — 392с спустя, а тревога
        # владельцу ушла в 14:16 напрасно, и следом напрасный дозор.
        [ "$tasks_live" = 1 ] && { printf 'задачи\n'; return 0; }
        printf 'тревога\n'; return 0
    fi
    printf 'ждём\n'
}

# Фоновая задача сессии (Bash с run_in_background) откладывает ВЕСЬ ввод из
# очереди, включая «/exit»: Claude Code исполняет его после хода по завершённой
# задаче. Снаружи это неотличимо от зависания — а различить обязано, иначе
# сторож будит владельца на каждой ротации с живой фоновой работой.
# Признак — свежесть вывода задач: Claude Code пишет его в
# /tmp/claude-<uid>/<проект>/<сессия>/tasks/<id>.output.
# stat, а не `find -newermt`: find здесь bfs, относительных отметок он не берёт.
фоновые_задачи_живы() {  # $1=id сессии $2=порог свежести, сек
    local sid="$1" fresh="${2:-${ROTATE_TASK_FRESH_SEC:-120}}" now d f age
    [ -n "$sid" ] || return 1
    now=$(date +%s)
    for d in "${TASKS_ROOT:-/tmp}"/claude-*/*/"$sid"/tasks; do
        [ -d "$d" ] || continue
        for f in "$d"/*; do
            [ -f "$f" ] || continue
            age=$(( now - $(stat -c %Y "$f" 2>/dev/null || echo 0) ))
            [ "$age" -le "$fresh" ] && return 0
        done
    done
    return 1
}

