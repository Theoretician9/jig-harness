# Что слать диалогу на N-й попытке. Улика 10.09.2026: за ОДНУ ротацию сторож
# послал Enter СОРОК раз (rotate_exit_dialog=40 при rotate_exit_sent=1) и
# двадцать минут ничего не менялось — сессия жила, преемник не поднимался,
# работать было некому. Одна клавиша, повторённая сорок раз, — не попытка, а
# ожидание чуда: если Enter не сработал дважды, он не сработает и в сороковой.
# Лестница: подтвердить как есть → назвать пункт ЯВНО цифрой → сбросить диалог
# и подать «/exit» заново. Клавиши именами tmux, а не текстом (send_to_pane
# шлёт «Enter» буквами -l и в диалоге бесполезен).
клавиши_подтверждения() { # $1 = номер попытки → клавиши через пробел
    case "$1" in
        1|2) printf 'Enter\n' ;;
        3|4) printf 'ПУНКТ Enter\n' ;;   # ПУНКТ подставляется номером с экрана
        *)   printf 'Escape\n' ;;
    esac
}

# Номер пункта «Exit and stop tasks» — С ЭКРАНА, а не вшитый.
# Ревью 10.09.2026: в лестнице стояла литеральная «1», хотя рядом уже был разбор
# пунктов. Сменится порядок в диалоге CLI — сторож нажмёт «Stay», то есть сам
# отменит выход, которого добивается.
номер_пункта_выхода() { # $1 = текст панели → «1» / «2» / пусто
    # «|| true»: пустой ответ — законный случай (диалога нет), а под set -e
    # ненулевой grep уронил бы весь самотест — так и случилось при первом прогоне.
    printf '%s\n' "$1" \
        | grep -E "$RE_EXIT_ITEM" \
        | grep -oE '[0-9]+' | head -1 || true
}

# Какой пункт диалога подсвечен. Без этого в журнале сорок одинаковых строк, по
# которым нельзя сказать, двигался ли выбор вообще ([[сигнал-без-различения]]).
# «> /exit» в той же панели начинается так же — потому и нужен номер пункта.
подсвеченный_пункт_в() { # $1 = текст панели
    printf '%s' "$1" | grep -m1 -E "$RE_PICKED_ITEM" | sed -E "s/^[[:space:]]*${PICK_MARK}[[:space:]]*//" || true
}

# ── Решение по tmux-панели агента — ЧИСТОЙ функцией, чтобы её можно было
# прогнать без tmux, без сервера и без побочных действий (UNIFIED/08: прибор
# доказывается на больном случае, а значит должен быть запускаем).
#
# Улика 11.08.2026: владелец вышел из claude — systemd-юнит остался active,
# heartbeat-метки свежие, харнес рапортовал зелёным, а агента не было.
# Замечалось это ТОЛЬКО когда что-то требовалось доставить (непустой inbox или
# непустая очередь). «Агент мёртв» — самостоятельное состояние, а не побочный
# эффект неудачной доставки, поэтому у него теперь свой сторож.
#
# Улика 11.08.2026 (вторая): подключённый клиент был БЕЗУСЛОВНОЙ блокировкой.
# SSH-клиент владельца висит на сессии постоянно — значит подъём агента был
# запрещён не «пока владелец работает», а НАВСЕГДА; в 22:51 сессия вышла сама,
# и никто её не поднял. Клиент уважается ровно пока в панели есть жизнь:
# простаивает дольше AGENT_ATTACHED_IDLE_MIN — за клиентом никого нет.
# И даже когда человек в панели действительно работает, молчать нельзя:
# работать некому, а владелец узнаёт об этом только из канала.
#
# Печатает одно слово: ok | человек | сказать | ждём | поднять
решение_по_панели() { # $1=команда  $2=клиенты tmux  $3=эпоха «не claude с»  $4=сейчас  $5=простой панели, мин  $6=владелец ждёт ответа
    local cmd="$1" clients="$2" since="$3" now="$4" idle_min="${5:-0}" waiting="${6:-0}" elapsed_min
    case "$cmd" in
        claude|node) printf 'ok\n'; return 0 ;;
    esac
    if [ -n "$since" ] && [ "$since" != 0 ]; then elapsed_min=$(( (now - since) / 60 )); else elapsed_min=-1; fi
    if [ "$AGENT_DEAD_RESPECT_ATTACHED" = 1 ] && [ "${clients:-0}" -gt 0 ] \
       && [ "${idle_min:-0}" -lt "$AGENT_ATTACHED_IDLE_MIN" ]; then
        # За клиентом кто-то печатает: слать туда команды — портить его ввод.
        # Но если агента нет дольше порога — сказать об этом в канал.
        if [ "$elapsed_min" -ge "$AGENT_DEAD_MIN" ]; then printf 'сказать\n'; else printf 'человек\n'; fi
        return 0
    fi
    # БОЛЬНОЙ СЛУЧАЙ 27.08.2026, 13:34–13:53: владелец дважды написал «Статус»,
    # агента в панели не было, а сторож выдерживал порог и вместо подъёма смены
    # дважды ответил ему «передать агенту не могу». Порог существует, чтобы не
    # дёргать сессию на пересборке панели; ждущему владельцу он стоил 19 минут
    # молчания. Ждёт владелец — поднимаем сразу.
    if [ "${waiting:-0}" = 1 ]; then printf 'поднять\n'; return 0; fi
    if [ "$elapsed_min" -lt 0 ]; then printf 'ждём\n'; return 0; fi
    if [ "$elapsed_min" -lt "$AGENT_DEAD_MIN" ]; then printf 'ждём\n'; return 0; fi
    printf 'поднять\n'
}

подавить_ротацию() {  # журнал, сессия, режим (1 = спрашиваем владельца), сейчас-эпоха
    # Печатает «нет» либо «да <событие> <возраст_мин> <окно_мин>». Одно решение,
    # никаких побочных действий — потому и проверяемо селфтестом без живой сессии.
    #
    # Анонс владельцу и поданная в панель команда — РАЗНЫЕ события с разными
    # окнами: первый ждёт чужого решения, вторая уже исполняется. 11.08.2026
    # оба писались как rotate_command, и неотвеченный анонс 22:20 задавил
    # ротацию до 00:20 — окно за это время дошло до 114%, сессия ушла в
    # автосжатие, то есть ровно в то, что ротация обязана предотвращать.
    local log="$1" sess="$2" ask="$3" now="$4" event gap ts age
    if [ "${ask:-0}" = 1 ]; then event="rotate_announced"; gap="${ROTATE_ANNOUNCE_GAP_MIN:-30}"
    else                         event="rotate_command";   gap="${ROTATE_COOLDOWN_MIN:-120}"; fi
    [ -f "$log" ] || { echo "нет"; return 0; }
    ts=$(grep "\"event\":\"$event\".*\"session\":\"$sess\"" "$log" | tail -1 | jq -r '.ts' 2>/dev/null || true)
    [ -n "$ts" ] && [ "$ts" != "null" ] || { echo "нет"; return 0; }
    age=$(( ( now - $(date -d "$ts" +%s) ) / 60 ))
    [ "$age" -lt "$gap" ] && echo "да $event $age $gap" || echo "нет"
    return 0
}

# Единиц у сравнения нет намеренно: возраст и порог приходят в одних и тех же
# единицах — у пинка в секундах, у разговора о блокировке в минутах.
подавлен_кулдауном() {  # возраст ("" — события не было), порог
    [ -n "$1" ] || return 1
    [ "$1" -lt "$2" ]
}

# Пинок «подхвати работу» зовут три руки: сторож после ротации, sentinel после
# загрузки и пусковой скрипт после подъёма юнитом (Restart=always вернёт сессию
# за 10с — раньше её возвращал только сторож, и он же пинал). Решение отдельно
# от действия: внутри самого пинка пауза, ожидание панели и запись в живую
# сессию агента — проверить это селфтестом нельзя, а решение можно.
пинок_подавлен() {  # возраст последнего пинка в секундах ("" — пинка не было)
    подавлен_кулдауном "$1" "${KICK_COOLDOWN_SEC:-120}"
}

