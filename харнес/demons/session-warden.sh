        return 1
    fi
}

# ── Быстрый путь смены сессии: «/clear» без выхода из процесса ──────────────
# Решение владельца 11.09.2026 («механизма нужно оба, для каждого своя роль»)
# и его же принцип: «раз есть команды, надо ими пользоваться». Здесь не нужно
# ничего из тяжёлого пути — ни диалога подтверждения выхода с лестницей
# ответов, ни подъёма преемника, ни дозора позднего выхода: процесс остаётся
# жив. За месяц тяжёлый путь дал 48 таймаутов на 135 попыток; у быстрого
# таймаутиться нечему.
#
# Замер 11.09.2026, отдельная сессия: 117 385 → 34 927 токенов, новый
# идентификатор сессии, новый файл транскрипта, CLAUDE.md и указания в
# контексте остались (проверено секретным словом — ответ пришёл из контекста,
# без чтения файла).
#
# Возвращает 0 — сессия сменена, 1 — не удалось (вызывающий уходит в rotate_full).
rotate_clear() {
    local ordered_at idle turn_done waited=0 was_id new_id was_tokens now_tokens
    if ! tmux has-session -t "$TMUX_SESSION" 2>/dev/null; then
        say "tmux-сессии '$TMUX_SESSION' нет — быстрый путь неприменим"
        return 1
    fi
    was_id="$SESSION_ID"
    was_tokens=$(окно_в_токенах "$TRANSCRIPT")
    # Подпись обязательна: в панель пишут двое, и агент однажды принял слова
    # сторожа за слова владельца (улика 12.08.2026, 18:05).
    if ! agent_prompt "[сторож сессий, автоматическая ротация — это не сообщение владельца] Пора менять контекст: $REASON. Заверши работу по регламенту: перезапиши STATE.md (что верно сейчас), допиши docs/handover/SESSION-HANDOFF-$(date +%Y-%m-%d).md, закоммить и отчитайся владельцу в канал. Выходить НЕ нужно и НЕ вызывай session-warden.sh --rotate-now: как только панель замолчит, я сам подам «/clear» — процесс останется жив, контекст очистится."; then
        say "поручение в панель не ушло — быстрый путь неприменим"
        return 1
    fi
    jlog "rotate_command" "$SESSION_ID" "режим clear: $REASON — поручение подано в tmux"
    ordered_at=$(date +%s)

    # Ждём того же, что и тяжёлый путь: ход закончен И панель молчит. Одного
    # молчания мало — ход мог возобновиться; одной метки мало — она осталась бы
    # прежней (те же улики, что у выход_из_ротации).
    while [ "$waited" -lt "${ROTATE_FINISH_TIMEOUT_SEC:-900}" ]; do
        sleep 15; waited=$((waited + 15))
        idle=$(простой_панели)
        turn_done=$(ход_завершён_после "$ordered_at")
        [ "$turn_done" = 1 ] && [ "$idle" -ge "${ROTATE_IDLE_SEC:-120}" ] && break
    done
    if [ "$waited" -ge "${ROTATE_FINISH_TIMEOUT_SEC:-900}" ]; then
        say "регламент не закончен за ${waited}с — быстрый путь отменяю, решает тяжёлый"
        jlog "clear_timeout" "$SESSION_ID" "регламент не завершён за ${waited}с"
        return 1
    fi
    say "регламент отработан за ${waited}с, панель молчит ${idle}с — подаю «/clear»"

    send_to_pane "/clear" || { say "«/clear» в панель НЕ ушёл"; return 1; }
    # Новый идентификатор — единственное доказательство, что команда принята:
    # «/clear» заводит новую сессию и новый файл транскрипта (замер 11.09).
    waited=0
    while [ "$waited" -lt 90 ]; do
        sleep 5; waited=$((waited + 5))
        new_id=$(свежий_id)
        [ -n "$new_id" ] && [ "$new_id" != "$was_id" ] && break
    done
    if [ -z "$new_id" ] || [ "$new_id" = "$was_id" ]; then
        say "после «/clear» сессия не сменилась за ${waited}с (id прежний: $was_id)"
        jlog "clear_failed" "$was_id" "новый идентификатор сессии не появился за ${waited}с"
        return 1
    fi
    now_tokens=$(окно_в_токенах "$PROJECT_TRANSCRIPTS/$new_id.jsonl")
    say "сессия сменена без перезапуска: $was_id → $new_id (окно ${was_tokens:-?} → ${now_tokens:-?} токенов)"

    # Преемнику — то же задание, что и после полного перезапуска, плюс осмотр:
    # хук старта сессии на «/clear» не срабатывает, а состояние знать нужно.
    agent_prompt "Контекст очищен сторожем сессий (это не сообщение владельца). Прочитай STATE.md, последний docs/handover/SESSION-HANDOFF-*.md и CLAUDE.md, выполни «bash scripts/hooks/session_state.sh» для осмотра, назови владельцу в канал текущую задачу и следующий шаг, проверь $LOG_DIR/inbox/ и продолжай работу." \
        || say "задание преемнику не ушло — сессия чиста, но без поручения"
    jlog "agent_restarted" "$new_id" "режим clear: контекст очищен, процесс жив, задание подано"
    return 0
}

rotate_full() {
    if ! tmux has-session -t "$TMUX_SESSION" 2>/dev/null; then
        say "tmux-сессии '$TMUX_SESSION' нет — ротировать нечего; сигнал владельцу"
        tg_send "Ротация нужна ($REASON), но tmux-сессии '$TMUX_SESSION' нет. Агент не запущен?" || say "и сигнал не ушёл"
        return 1
    fi
    say "шлю команду завершения в tmux '$TMUX_SESSION'"
    # Запросивший ротацию агент регламент уже отработал — ему нужен выход, а не
    # поручение закрываться: второе поручение он начал бы выполнять заново.
    # Имя файла передачи — строго docs/handover/SESSION-HANDOFF-<дата>.md (С-6):
    # по этой маске его ищут handover-check, stop_reminder и session_state.
    if [ "$FORCE_ROTATE" = 1 ]; then PROMPT="/exit"
    # Поручение НЕ требует выхода: выйти агент не может (см. выход_из_ротации),
    # а попытка выйти «как принято в проекте» — через `--rotate-now` — ставит
    # второй сторож в очередь за локом ЭТОГО прогона и вешает обоих (улика
    # 12.08.2026). Подпись в начале обязательна: в панель пишут двое — диспетчер
    # канала и сторож, — и агент, приняв поручение сторожа за слова владельца,
    # процитировал их владельцу как его же указание (улика 12.08.2026, 18:05).
    else PROMPT="[сторож сессий, автоматическая ротация — это не сообщение владельца] Пора менять сессию: $REASON. Заверши работу по регламенту: перезапиши STATE.md (что верно сейчас), допиши docs/handover/SESSION-HANDOFF-$(date +%Y-%m-%d).md, закоммить и отчитайся владельцу в канал. Выходить не нужно и НЕ вызывай session-warden.sh --rotate-now: смену веду я — как только панель замолчит, сам введу «/exit» и подниму преемника."; fi
    if ! agent_prompt "$PROMPT"; then
        tg_send "Ротация нужна ($REASON), но в tmux-панели '$TMUX_SESSION' не агент — команду не отправил (текст в оболочке исполнился бы). Проверьте сессию." || say "и сигнал не ушёл"
        return 1
    fi
    # Команда реально ушла агенту — только теперь событие в журнал (кулдаун).
    jlog "rotate_command" "$SESSION_ID" "режим full: $REASON — команда подана в tmux"

    # Ждём, пока агент отработает регламент, и закрываем сессию сами. Виды
    # завершения перечисляет смена_состоялась, кто вводит «/exit» — решает
    # выход_из_ротации; там же улики, из-за которых каждая ветка появилась.
    local waited=0 pane="" alive=1 verdict="ждём" act="ждём"
    local exit_sent=0 deadline="$ROTATE_FINISH_TIMEOUT_SEC" idle=0 alarm_sent=0
    local alarm_watch="${ROTATE_ALARM_WATCH_SEC:-300}" turn_done=0
    # Ожидание фоновой задачи, держащей очередь ввода: своё, с потолком. Когда
    # потолок выбран, задача перестаёт быть оправданием и путь обычный —
    # тревога. Иначе «жду задачу» стало бы вечным алиби зависшей сессии.
    local tasks_live=0 task_waited=0 tasks_capped=0
    # Счёт попыток по диалогу: он и решает, чем отвечать (клавиши_подтверждения).
    local dialog_tries=0 dialog_rounds=0 dialog_capped=0 pane_text="" picked="" keys="" held=0 sent="" screen="" pick_num=""
    # Момент поручения: ходы, законченные ДО него, к ротации отношения не имеют.
    local ordered_at; ordered_at=$(date +%s)
    while :; do
        sleep 30; waited=$((waited + 30))
        alive=1; tmux has-session -t "$TMUX_SESSION" 2>/dev/null || alive=0
        pane=$(pane_cmd)
        verdict=$(смена_состоялась "$alive" "$pane" "$(свежий_id)" "$SESSION_ID")
        idle=$(простой_панели)
        turn_done=$(ход_завершён_после "$ordered_at")
        # Раньше признака задач: пока диалог не подтверждён, «/exit» не исполнится
        # НИКОГДА, и ожидание задачи было бы ожиданием того, чего никто не ждёт.
        if [ "$exit_sent" = 1 ] && [ "$alive" = 1 ] && [ "$dialog_capped" = 0 ]; then
            pane_text=$(tmux capture-pane -p -t "$TMUX_SESSION" 2>/dev/null || true)
            if диалог_выхода_в "$pane_text"; then
                dialog_tries=$((dialog_tries + 1))
                picked=$(подсвеченный_пункт_в "$pane_text")
                keys=$(клавиши_подтверждения "$dialog_tries")
                # Подставляем НАСТОЯЩИЙ номер пункта; не нашли — подтверждаем
                # подсвеченное, слепая цифра хуже, чем Enter.
                if [ "${keys#ПУНКТ }" != "$keys" ]; then
                    pick_num=$(номер_пункта_выхода "$pane_text")
                    keys="${pick_num:-Enter} ${keys#ПУНКТ }"
                    [ -n "$pick_num" ] || keys="Enter"
                fi
                say "«/exit» перехвачен вопросом о фоновых задачах (попытка $dialog_tries, подсвечено «${picked:-не разобрал}») — шлю «$keys»"
                # Прибор различения (10.09.2026): лечение лестницей выбрано БЕЗ
                # воспроизведённой причины, и по прежнему журналу проверить его
                # нечем — сорок строк были одинаковы. Пишем сырьё: что стоит в
                # диалоге, какие задачи он называет, что ответил tmux на каждую
                # клавишу. Следующая же ротация покажет, помогает лестница или
                # диалог держит что-то другое.
                held=$(printf '%s' "$pane_text" | grep -cE '^\s+(shell|bash|task) ·' || true)
                sent=""
                for k in $keys; do
                    # Снимок мог устареть за 0,7 с предыдущей клавиши: агент сам
                    # подтвердил диалог — и Escape прилетит в работающую сессию,
                    # оборвав ход (ревью 10.09.2026). Перечитываем перед каждой.
                    if ! диалог_выхода_в "$(tmux capture-pane -p -t "$TMUX_SESSION" 2>/dev/null || true)"; then
                        say "диалог закрылся сам — остальные клавиши не шлю"
                        sent="${sent:+$sent,}$k=не нужен"
                        break
                    fi
                    if tmux send-keys -t "$TMUX_SESSION" "$k" 2>/dev/null; then
                        sent="${sent:+$sent,}$k=ок"
                    else
                        sent="${sent:+$sent,}$k=ОТКАЗ"
                        say "клавиша «$k» в панель не ушла"
                    fi
                    sleep "${PANE_ENTER_DELAY:-0.7}"
                done
                # Экран диалога целиком, одной строкой: по нему видно и текст
                # вопроса, и что именно держит выход.
                # «|| true»: под pipefail пустой grep уронил бы ротацию целиком.
                screen=$(printf '%s' "$pane_text" | grep -A 12 -F 'Background work is running' \
                         | tr '\n' '|' | cut -c1-400 || true)
                jlog "rotate_exit_dialog" "$SESSION_ID" "попытка $dialog_tries, подсвечено «${picked:-?}», клавиши «$keys» ($sent), задач в списке: $held, экран: $screen"
                if [ "$keys" = Escape ]; then
                    dialog_rounds=$((dialog_rounds + 1))
                    say "диалог не поддался $dialog_tries раз (круг $dialog_rounds) — сбросил Escape и подаю «/exit» заново"
                    agent_prompt "/exit" || say "«/exit» в панель не ушёл (в панели: $pane)"
                    dialog_tries=0
                fi
                # Потолок кругов: без него ветка делала «continue» ДО решения о
                # сроке, и лестница крутилась вечно с занятым локом — стояли и
                # ротация, и плановые прогоны, а владелец не знал (ревью 10.09).
                if [ "$dialog_rounds" -ge "${ROTATE_DIALOG_ROUNDS:-3}" ]; then
                    say "диалог выхода не поддался за ${dialog_rounds} круга — дальше как обычный отказ, лестницу прекращаю"
                    jlog "rotate_dialog_capped" "$SESSION_ID" "лестница ответов исчерпана: ${dialog_rounds} круга по 5 попыток"
                    tg_send "Ротация: сессия показывает вопрос о фоновых задачах и не закрывается ни Enter, ни выбором пункта, ни Escape — $((dialog_rounds * 5)) попыток. Дальше действую обычным порядком (тревога и досмотр); если увидите панель — нажмите «1» руками." || say "и сигнал не ушёл"
                    dialog_capped=1
                else
                    continue
                fi
            fi
        fi
        tasks_live=0
        [ "$tasks_capped" = 1 ] || { фоновые_задачи_живы "$SESSION_ID" && tasks_live=1; }
        act=$(выход_из_ротации "$verdict" "$idle" "$exit_sent" "$waited" "$deadline" "$turn_done" "$tasks_live")
        case "$act" in
            смена) break ;;
            # «/exit» бывает медленнее срока. 12.08.2026, 19:53: сторож сказал
            # «не закрылась», вышел из ротации — и сессия закрылась через минуту
            # уже без него. Преемника поднял только следующий тик: семь минут
            # без агента, и всё это время сообщение владельца лежало в inbox.
            # Тревога владельцу — не конец смены, а просьба быть наготове.
            тревога)
                [ "$alarm_sent" = 1 ] && break
                say "сессия НЕ закрылась и после «/exit» (в панели: $pane) — сигнал владельцу, смену досматриваю ещё ${alarm_watch}с"
                jlog "rotate_timeout" "$SESSION_ID" "не завершилась за ${waited}с, «/exit» в панель не подействовал — досмотр ${alarm_watch}с"
                tg_send "Ротация: сессия не закрылась за $((waited / 60)) мин даже после «/exit» в панель. Досматриваю ещё $((alarm_watch / 60)) мин: закроется сама — подниму преемника и скажу вам, что вмешательство не нужно." || say "и сигнал не ушёл"
                alarm_sent=1; deadline=$(( waited + alarm_watch )); continue ;;
            задачи)
                task_waited=$((task_waited + 30))
                if [ "$task_waited" -ge "${ROTATE_TASK_WAIT_SEC:-900}" ]; then
                    tasks_capped=1
                    say "фоновая задача сессии держит очередь ввода уже ${task_waited}с — потолок выбран, дальше считаю это зависанием"
                    continue
                fi
                [ $((task_waited % 120)) -eq 0 ] \
                    && say "«/exit» принят, но исполнится после фоновой задачи сессии (ждём ${task_waited}с из ${ROTATE_TASK_WAIT_SEC:-900})"
                deadline=$(( waited + 60 )); continue ;;
            ждём) continue ;;
            выход|принудительно)
                if [ "$act" = принудительно ]; then
                    say "срок ${deadline}с вышел, а агент ещё в ходу (ход завершён: ${turn_done}, простой ${idle}с) — ввожу «/exit» всё равно"
                else
                    say "агент закончил ход после поручения и панель молчит ${idle}с — регламент отработан, ввожу «/exit» за него"
                fi
                jlog "rotate_exit_sent" "$SESSION_ID" "$act: ход завершён=${turn_done}, простой панели ${idle}с, ждали ${waited}с — «/exit» введён в панель"
                agent_prompt "/exit" || say "«/exit» в панель не ушёл (в панели: $pane)"
                exit_sent=1; deadline=$(( waited + ${ROTATE_EXIT_WAIT_SEC:-180} )) ;;
        esac
    done
    if [ "$act" = "тревога" ]; then
        say "смена не состоялась и за досмотр (${waited}с, в панели: $pane) — дальше нужен владелец"
        jlog "rotate_alarm_timeout" "$SESSION_ID" "не завершилась и за досмотр ${alarm_watch}с после «/exit»"
        # Уходя, оставляем дозор: выход бывает позже нашего срока, и тогда
        # преемника ждать до следующего cron — 10 минут без агента (улика
        # 13.08.2026 у ветки `--досмотр-выхода`). `8>&-` обязателен: без него
        # получасовой потомок унаследует лок сторожа и убьёт плановые прогоны.
        WARDEN_DETACHED=1 setsid nohup "$0" --досмотр-выхода "$SESSION_ID" \
            >> "$LOG_DIR/session-warden.log" 2>&1 < /dev/null 8>&- &
        local watch_pid=$!
        if kill -0 "$watch_pid" 2>/dev/null; then
            say "дозор позднего выхода поставлен (pid $watch_pid) — преемника поднимет он"
            jlog "late_exit_watch" "$SESSION_ID" "сдаю смену, но оставил дозор: поднимет преемника, как только панель освободится"
        else
            say "дозор позднего выхода НЕ запустился — преемника поднимет плановый прогон"
        fi
        tg_send "Ротация: сессия жива и после досмотра ($((waited / 60)) мин с начала смены). Сам её не закрою — нужно вмешаться. Дозор оставил: если она закроется позже сама, преемника подниму без вас и скажу отбой." || say "и сигнал не ушёл"
        return 1
    fi
    case "$verdict" in
        ушла)     say "сессия закрылась вместе с агентом — так завершается панель, созданная командой" ;;
        оболочка) say "панель снова оболочка — агент вышел" ;;
        преемник) say "в панели уже другая сессия ($(свежий_id)) — преемника поднял юнит автозапуска"
                  jlog "successor_detected" "$SESSION_ID" "смену завершил юнит: транскрипт сменился за ${waited}с" ;;
    esac
    say "смена состоялась за ${waited}с ($verdict) — обеспечиваю преемника (Б-4а)"

    # Подъём нового агента — обязанность ротации: завершить и не поднять =
    # система умирает молча (воспроизведённый блокер Б-4).
    if ! start_agent; then
        jlog "restart_failed" "$SESSION_ID" "агент не поднялся за ${AGENT_START_TIMEOUT_SEC}с после ротации"
        tg_send "Агент остановлен после ротации, нужен запуск: в tmux '$TMUX_SESSION' команда «$AGENT_START_CMD» не подняла claude за ${AGENT_START_TIMEOUT_SEC}с." || say "и сигнал не ушёл"
        return 1
    fi
    jlog "agent_restarted" "$SESSION_ID" "агент поднят после ротации"
    # Тревогу, которая разрешилась сама, обязан снять тот, кто её поднял:
    # иначе владелец идёт вмешиваться в уже работающую систему.
    [ "$alarm_sent" = 1 ] && { jlog "rotate_alarm_cleared" "$SESSION_ID" "смена состоялась на досмотре за ${waited}с"; \
        tg_send "Отбой по прошлой тревоге: сессия закрылась сама на досмотре (${waited}с от начала смены), преемник поднят. Вмешиваться не нужно." || say "и отбой не ушёл"; }
    подхватить_работу || tg_send "Агент поднят после ротации, но пинок «подхвати работу» не дошёл — сессия стоит у пустого приглашения. Напишите ей что угодно." || say "и сигнал не ушёл"

    # Приёмка передачи. БЕЗ MCP-серверов: telegram-плагин допускает одного
    # потребителя getUpdates на токен и отобрал бы канал у живого диспетчера
    # (улика devmap-selfheal.sh).
    local answer rc=0
    # «ничего не меняй»: проверка приёма — ЗАМЕР, а не работа. Без этой оговорки
    # headless-агент видит устаревшую передачу и чинит её сам (улика приёмки
    # 11.08.2026: пробный прогон переписал SESSION-HANDOFF прямо в проверке).
    # Прибор, меняющий то, что измеряет, врёт дважды: правку никто не ревьюил,
    # а следующий замер уже зелёный по построению.
    # Модель — дешёвая (DEMON_MODEL): чтение трёх файлов не стоит opus-цены,
    # а переключатель модели агента на headless-вызовы не действует.
    answer=$(cd "$PROJECT_DIR" && timeout 300 claude -p --model "$(model_dlya дежурный)" \
        "прочитай CLAUDE.md, STATE.md и последний docs/handover/*; назови текущую задачу и следующий шаг. НИЧЕГО НЕ МЕНЯЙ: это проверка приёма, а не работа — файлы не правь, коммитов не делай" \
        --mcp-config '{"mcpServers":{}}' --strict-mcp-config --output-format text 2>&1) || rc=$?
    jlog "rotation_check" "$SESSION_ID" "rc=$rc: $(printf '%s' "$answer" | head -c 2000)"
    if [ "$rc" -ne 0 ] || [ -z "$(printf '%s' "$answer" | tr -d '[:space:]')" ]; then
        say "проверка приёма ПРОВАЛЕНА (rc=$rc, ответ пуст или ошибка) — сигнал владельцу"
        tg_send "Ротация выполнена, агент поднят, но проверка приёма провалена (rc=$rc): headless-сессия не назвала задачу и шаг. Передача, вероятно, битая." || say "и сигнал не ушёл"
        return 1
    fi
    say "приём подтверждён: новая сессия назвала задачу и шаг (ответ в rotation.jsonl)"
    # Чей это ответ — говорим прямо. Владелец 13.08.2026 прочитал срез как отчёт
    # рабочего агента («не коммичу, указание было ничего не менять») и решил, что
    # кто-то запретил агенту работать. Запрет есть, но он адресован ИЗМЕРИТЕЛЮ.
    tg_send "Ротация выполнена ($REASON), агент поднят. Приём подтверждён — ниже ответ одноразовой сессии-измерителя (ей запрещено править файлы и коммитить, чтобы проверка не чинила то, что измеряет); рабочая сессия этим запретом не связана: $answer" \
        || say "итоговое уведомление не ушло — ротация при этом состоялась, след в rotation.jsonl"
}

# Каждая ветка обязана оставить след — ненадёжную механику не глотаем молча.
WARDEN_RC=0
if [ "$NEED_ROTATE" = 1 ]; then
    # Ротация — механика харнеса, не решение владельца: она ничего не теряет
    # и ничего не выкатывает, она лишь меняет сессию. Раньше её судьбу решал
    # общий ключ AUTONOMY, и в semi владелец получал «скомандуйте агенту
    # завершение» — харнес перекладывал на него свою работу (улика 11.08.2026).
    # Развилки полуавтомата (выкат, необратимое) живут отдельно и этим ключом
    # не затрагиваются.
    if [ "${ROTATE_NEEDS_OWNER:-0}" = 1 ] && [ "$FORCE_ROTATE" != 1 ]; then
        say "нужна ротация: $REASON (ROTATE_NEEDS_OWNER=1 — спрашиваю владельца)"
        rotate_semi || WARDEN_RC=1
    else
        say "нужна ротация: $REASON — выполняю сам (ROTATE_NEEDS_OWNER=0)"
        # Признаки для выбора пути собираются здесь, решение принимает чистая
        # функция способ_ротации (её 8 путей проверяются самотестом без tmux).
        HOOKS_CHANGED=0
        for f in "$PROJECT_DIR/.claude/settings.json" "$PROJECT_DIR/scripts/hooks"/*; do
            [ -e "$f" ] || continue
            [ "$f" -nt "$TRANSCRIPT" ] && { HOOKS_CHANGED=1; break; }
        done
        VERSION_CHANGED=0
        if [ -n "${CC_VERSION:-}" ] && command -v claude >/dev/null 2>&1; then
            # «|| true»: версия без номера — законный случай (иной формат вывода,
            # не тот бинарник), а под pipefail он уронил бы весь прогон сторожа.
            live_ver=$(claude --version 2>/dev/null | grep -oE '[0-9]+\.[0-9]+\.[0-9]+' | head -1 || true)
            [ -n "$live_ver" ] && [ "$live_ver" != "$CC_VERSION" ] && VERSION_CHANGED=1
        fi
        FULL_STAMP="$HEARTBEAT_DIR/полный-перезапуск"
        if [ -f "$FULL_STAMP" ]; then
            HOURS_SINCE_FULL=$(( ( $(date +%s) - $(stat -c '%Y' "$FULL_STAMP") ) / 3600 ))
        else
            # Метки нет — процесс живёт с раскладки или дольше суток: тяжёлый путь.
            HOURS_SINCE_FULL=999
        fi
        MODE=$(способ_ротации "$HOOKS_CHANGED" "$VERSION_CHANGED" "$HOURS_SINCE_FULL" \
                                "${FULL_RESTART_MAX_HOURS:-24}" 0 "$FORCE_ROTATE")
        say "способ смены: $MODE (хуки=$HOOKS_CHANGED версия=$VERSION_CHANGED часов_с_полного=$HOURS_SINCE_FULL принудительно=$FORCE_ROTATE)"
        if [ "$MODE" = clear ]; then
            # Страховка: быстрый путь не удался — тяжёлый доводит смену до конца.
            rotate_clear || { say "быстрый путь не удался — перехожу на полный перезапуск"; rotate_full || WARDEN_RC=1; }
        else
            rotate_full || WARDEN_RC=1
        fi
    fi
