    # держит: свой — молчим, чужой — чиним и говорим владельцу.
    # fuser отдаёт ВСЕ pid одной строкой через пробелы; склеить их в одно
    # число — получить несуществующий процесс, пустое имя и молчаливый выход
    # по ветке «свой прогон». Поймано пробой 12.08.2026 (`flock` + `sleep`
    # дали два pid). Берём первый: любого из держателей довольно, чтобы
    # понять, наш он или чужой.
    # «|| true» обязателен: под `set -euo pipefail` пустой grep роняет ВЕСЬ
    # скрипт кодом 1, и ни одна строка ниже не печатается — сторож мёртв и
    # молчит. Пустой ответ fuser законен: держателя чужого пользователя он без
    # root не покажет ([[настройка-игнорируется-молча]] — молчание не сигнал).
    HOLDER=$(fuser "$SERVICE_LOCK_DIR/session-warden.lock" 2>/dev/null | tr -s ' ' '\n' | grep -m1 '[0-9]' || true)
    HOLDER_CMD=$([ -n "$HOLDER" ] && ps -o comm= -p "$HOLDER" 2>/dev/null || echo "")
    # Пустой держатель — не «свой прогон», а «не разобрал». Разводим: свой
    # выход обычен, неразобранный говорит о себе в лог, иначе разница между
    # здоровой уступкой дороги и мёртвым сторожем видна только человеку.
    if [ -z "$HOLDER" ]; then
        say "лок session-warden занят, а держателя не видно (fuser молчит — обычно чужой пользователь) — выхожу без действий"
        exit 0
    fi
    case "$HOLDER_CMD" in
        ""|*bash*|*session-warden*)
            say "другой прогон session-warden ещё работает (лок занят, держит $HOLDER) — выхожу без действий"
            exit 0 ;;
    esac
    # Чужой держатель лока не отпустит его никогда — он не знает, что держит.
    # Лок пересоздаётся: flock живёт на inode, поэтому новый файл свободен, а
    # старый остаётся у держателя и никому не мешает.
    say "лок session-warden держит ЧУЖОЙ процесс $HOLDER ($HOLDER_CMD) — сторож был бы мёртв навсегда; пересоздаю лок"
    mv -f "$SERVICE_LOCK_DIR/session-warden.lock" \
          "$SERVICE_LOCK_DIR/session-warden.lock.занят-$HOLDER_CMD-$HOLDER" 2>/dev/null || true
    exec 8>> "$SERVICE_LOCK_DIR/session-warden.lock"
    flock -n 8 || { say "новый лок тоже занят — выхожу"; exit 1; }
    LOCK_RECREATED="$HOLDER ($HOLDER_CMD)"
fi

# Запись события в журнал ротаций. jq собирает JSON сам — ручная склейка
# строк ломается на первой же кавычке в тексте.
jlog() {  # событие, сессия, детали
    jq -cn --arg ts "$(date -Is)" --arg ev "$1" --arg s "$2" --arg d "$3" \
        '{ts:$ts, event:$ev, session:$s, detail:$d}' >> "$ROTATION_LOG"
}

# Отправка владельцу. Успех ТОЛЬКО при ok:true (норма 01-SPEC §7) — лог
# «отправлено» без разбора ответа успехом не считается.
tg_send() {
    local text="$1"
    if [ -x "$PROJECT_DIR/scripts/tg_send.sh" ]; then
        if "$PROJECT_DIR/scripts/tg_send.sh" "$text"; then return 0; fi
        say "tg_send.sh отказал — пробую прямой curl"
    fi
    if [ -z "${TG_CHAT_ID:-}" ] || [ ! -s "${TG_TOKEN_FILE:-/nonexistent}" ]; then
        say "КАНАЛ НЕ НАСТРОЕН: TG_CHAT_ID/TG_TOKEN_FILE пусты — сообщение владельцу НЕ ушло"
        return 1
    fi
    # URL с токеном — через stdin (curl -K -), а не в argv: argv виден любому
    # в ps. Образец — scripts/tg_send.sh; здесь была копия с токеном наружу.
    local token; token=$(cat "$TG_TOKEN_FILE")
    printf 'url = "https://api.telegram.org/bot%s/sendMessage"\n' "$token" \
        | curl -s -m 20 -K - -X POST \
        --data-urlencode "chat_id=$TG_CHAT_ID" --data-urlencode "text=$text" \
        | jq -e '.ok == true' >/dev/null
}

# Пересозданный лок — не мелочь механики: до этой минуты сторож не работал, а
# значит не работала и ротация. Владелец узнаёт об этом сразу, а не когда
# сессия дорастёт до автокомпакта.
if [ -n "${LOCK_RECREATED:-}" ]; then
    jlog "lock_recreated" "?" "лок держал чужой процесс $LOCK_RECREATED"
    tg_send "Сторож сессий был заблокирован: лок держал чужой процесс $LOCK_RECREATED (обычно tmux-сервер, унаследовавший дескриптор). Лок пересоздан, сторож снова работает. Ротация всё это время не срабатывала." || true
fi

# Смену уже ведёт другой прогон? Тогда он ждёт РОВНО моего выхода, и вставать
# к нему в очередь за локом — взаимная блокировка: он ждёт агента, агент ждёт
# лок (улика 12.08.2026: сторож заказал ротацию, агент ушёл через --rotate-now,
# оба замерли, владелец написал «ничего не происходит»). Признак берём из
# журнала, а не из «бежит ли процесс»: обычный прогон сторожа тоже виден в
# ps, но преемника он не поднимет — выйти по нему значило бы уйти без смены.
ротация_в_ходу() { # 0 = ротацию ведёт другой прогон и ждёт моего выхода
    python3 - "$LOG_DIR/rotation.jsonl" "${ROTATE_FINISH_TIMEOUT_SEC:-900}" <<'PYEOF' 2>/dev/null
import json, sys, datetime
путь, окно = sys.argv[1], int(sys.argv[2])
последняя = None
try:
    for строка in open(путь, encoding="utf-8"):
        try:
            событие = json.loads(строка)
        except ValueError:
            continue
        if событие.get("event") in ("rotate_command", "agent_restarted",
                                    "rotate_timeout", "restart_failed"):
            последняя = событие
except OSError:
    sys.exit(1)
if not последняя or последняя.get("event") != "rotate_command":
    sys.exit(1)          # ротации нет или она уже завершилась — лок не про меня
момент = datetime.datetime.fromisoformat(последняя["ts"])
прошло = (datetime.datetime.now(момент.tzinfo) - момент).total_seconds()
sys.exit(0 if прошло < окно else 1)
PYEOF
}

# Кто в панели. Отдельным словом «мертва» — панель, переживившая свой процесс
# (remain-on-exit): опыт 13.08.2026 показал, что `pane_current_command` у неё
# продолжает показывать ПРЕЖНЮЮ команду, то есть «claude» уже после выхода
# агента. Всякий, кто спросит «агент на месте?», получил бы ответ про мертвеца.
pane_cmd() {
    local dead
    dead=$(tmux display-message -p -t "$TMUX_SESSION" '#{pane_dead}' 2>/dev/null || echo 0)
    [ "$dead" = 1 ] && { printf 'мертва\n'; return 0; }
    tmux display-message -p -t "$TMUX_SESSION" '#{pane_current_command}' 2>/dev/null || echo "?"
}

# Сессия агента обязана пережить выход агента: пока она умирала вместе с ним,
# ротация выбрасывала из tmux приаттаченного владельца (улика 13.08.2026).
# Новые сессии поднимаются с оболочкой и переживают выход сами; эта опция
# закрывает и те, что уже подняты старым способом — включая живую сейчас.
беречь_сессию() {
    tmux has-session -t "$TMUX_SESSION" 2>/dev/null || return 0
    tmux set-option -t "$TMUX_SESSION" remain-on-exit on 2>/dev/null || true
}

# Сколько секунд панель ничего не выводила. Пока агент работает, TUI
# перерисовывается непрерывно; замолчал — значит ход закончен и ждёт ввода.
# `#{pane_activity}` в tmux 3.4 пуст. `#{session_activity}` тоже НЕ живое: оно
# обновляется при переключении окон, а не при выводе. Замер 11.09.2026 на
# работающем агенте: session_activity дало простой 772 мин, window_activity — 0.
# Ценой этой ошибки было правило «ход закончен И панель молчит»: второе условие
# всегда истинно, и «/exit» подавался по одному признаку — ровно тот обрыв хода
# посреди работы, против которого правило и вводилось 13.08.2026.
простой_панели() {
    local last sec
    last=$(tmux display-message -p -t "$TMUX_SESSION" '#{window_activity}' 2>/dev/null || echo 0)
    [ -n "$last" ] || last=0
    sec=$(( $(date +%s) - last ))
    [ "$sec" -lt 0 ] && sec=0
    printf '%s' "$sec"
}

# Кто пишет прямо сейчас: id свежайшего транскрипта проекта ("" — каталог ещё
# не найден или пуст). Каталог ищет основной поток (PROJECT_TRANSCRIPTS), эта
# функция зовётся уже после него — из ожидания смены.
свежий_id() {
    [ -n "${PROJECT_TRANSCRIPTS:-}" ] || return 0
    local f
    f=$(find "$PROJECT_TRANSCRIPTS" -mindepth 1 -maxdepth 1 -name '*.jsonl' -type f -printf '%T@ %p\n' 2>/dev/null \
        | sort -nr | head -1 | cut -d' ' -f2- || true)
    [ -n "$f" ] && basename "$f" .jsonl
}

# Текст агенту в tmux — ТОЛЬКО при живом claude/node в панели (Б-4б):
# в голой оболочке «Продолжай текущую задачу» исполнился бы как команды bash.
agent_prompt() {  # текст
    local cmd; cmd=$(pane_cmd)
    case "$cmd" in
        claude|node) send_to_pane "$1"; return $? ;;
    esac
    say "в панели '$cmd', не claude/node — текст агенту НЕ шлю (оболочка исполнила бы его как команды)"
    return 1
}

if [ "${LOCK_TAKEN:-1}" = 0 ] && ротация_в_ходу; then
    say "--rotate-now: смену уже ведёт другой прогон — просто выхожу, преемника поднимет он"
    jlog "rotate_already_running" "?" "лок держит идущая ротация — агент выходит, не мешая ей"
    agent_prompt "/exit" || {
        say "команда выхода в панель НЕ ушла — сессия остаётся, смена не состоится"
        tg_send "Смену ведёт сторож, но команда выхода не дошла до панели — сессия жива. Нужно вмешаться." || true
        exit 1
    }
    exit 0
fi

# Лок держит НЕ ротация, а обычный прогон сторожа — смены не будет вовсе.
# Отказ громкий: агент, попросивший смену, ответа уже не увидит — он уходит.
if [ "${LOCK_TAKEN:-1}" = 0 ]; then
    say "--rotate-now: лок занят дольше ${ROTATE_LOCK_WAIT_SEC:-900}с — ротацию не выполняю"
    jlog "rotate_lock_busy" "?" "лок session-warden занят дольше ${ROTATE_LOCK_WAIT_SEC:-900}с"
    tg_send "Агент попросил ротацию, но сторож был занят другим прогоном дольше $(( ${ROTATE_LOCK_WAIT_SEC:-900} / 60 )) мин — смена не состоялась. Сессия работает дальше." || true
    exit 1
fi

# Разбудить свежеподнятую сессию: поднять ПРОЦЕСС — не то же, что вернуть
# РАБОТУ. Улика владельца 11.08.2026: «сессия перезагрузилась, но автозапуска
# не произошло» — claude поднимался и молча ждал у пустого приглашения, потому
# что никто ему ничего не говорил. Проверка приёма после ротации идёт
# ОТДЕЛЬНЫМ headless-вызовом и живой панели не касается.
KICK_STAMP="${KICK_STAMP:-${LOG_DIR:-/var/log/harness}/kick.stamp}"

# Возраст последнего пинка в секундах; пустая строка — пинка ещё не было.
возраст_пинка() {
    [ -f "$KICK_STAMP" ] || return 0
    echo $(( $(date +%s) - $(stat -c '%Y' "$KICK_STAMP") ))
}

подхватить_работу() {
    # Пинок зовут несколько рук сразу: сторож после ротации, sentinel после
    # загрузки, пусковой скрипт после подъёма юнитом. Кулдаун — чтобы свежая
    # сессия не получила три одинаковых поручения подряд и не начала работу
    # трижды. Уже пнули только что — считаем, что работа подхвачена.
    if пинок_подавлен "$(возраст_пинка)"; then
        say "пинок отдан недавно (кулдаун ${KICK_COOLDOWN_SEC:-120}с) — повтор не подаю"
        return 0
    fi
    # Пауза: TUI после запуска ещё рисуется и первые нажатия теряет.
    sleep "${AGENT_WAKE_DELAY:-5}"
    # Ждём именно агента: пусковой скрипт зовёт пинок сразу после создания
    # сессии, а claude в ней поднимается не мгновенно. Без ожидания пинок
    # уходил бы в оболочку, где agent_prompt его законно отвергает, — и
    # сессия оставалась бы у пустого приглашения при исправном коде.
    local waited=0
    while [ "$waited" -lt "${AGENT_START_TIMEOUT_SEC:-60}" ]; do
        case "$(pane_cmd)" in claude|node) break ;; esac
        sleep 5; waited=$((waited + 5))
    done
    if send_to_pane "Ты — новая сессия после перезапуска. Прочитай STATE.md, последний docs/handover/SESSION-HANDOFF-*.md и CLAUDE.md, назови владельцу в канал текущую задачу и следующий шаг, проверь $LOG_DIR/inbox/ и продолжай работу."; then
        date +%s > "$KICK_STAMP"
        jlog "work_resumed" "${SESSION_ID:-?}" "новой сессии отдан пинок «подхвати работу»"
        say "новой сессии отдан пинок подхватить работу"
    else
        say "пинок «подхвати работу» НЕ отдан — сессия поднята, но стоит у пустого приглашения"
        return 1
    fi
}

# `--kick`: отдать пинок «подхвати работу» и выйти. Нужен тому, кто поднял
# агента не через сторожа — прежде всего юниту после перезагрузки сервера:
# сессия там встаёт сама, но у ПУСТОГО приглашения, и работа не начинается,
# пока владелец не напишет первым. Механика пинка живёт в одном месте — выше.
if [ "${1:-}" = "--kick" ]; then
    подхватить_работу && exit 0 || exit 1
fi

# Подъём агента после ротации (Б-4а). Команда запуска — только в оболочку:
# в чужой процесс (редактор, зависший claude) её слать так же опасно.
#
# Улика 11.08.2026 (проба ротации): с тех пор как юнит создаёт сессию КОМАНДОЙ
# (`tmux new-session … "$AGENT_START_CMD"`), выход агента закрывает и панель, и
# всю сессию. Слать команду запуска стало некуда: подъём начинается с самой
# сессии. Юнит её не вернёт — при штатном выходе rc=0, а у него Restart=on-failure.
# `8>&-` у каждого запуска, порождающего tmux-СЕРВЕР, — не украшение.
# Пережито 12.08.2026: лок сторожа взят дескриптором 8 (`exec 8>>` выше),
# затем сторож поднял агента, tmux-сервер унаследовал этот дескриптор и стал
# держать лок ВЕЧНО — он демон и не умирает. Девять плановых прогонов подряд
# вышли «лок занят»; сторож был мёртв 40 минут, а нашлось это случайно.
# Круг замкнутый: ротацию делает сторож, а первая же ротация его и убивает —
# сессия после неё дорастает до автокомпакта, ради избежания которого он есть.
# Улика: `/proc/42014/fd/8 -> …/session-warden.lock`, tmux запущен 13:36:23,
# ровно в момент ротации.
# Проверено пробой: `exec {FD}>>` НЕ спасает (bash не ставит close-on-exec —
# потомок видит дескриптор), спасает только явное закрытие при вызове.
start_agent() {
    local cmd waited=0
    # Подмена конфига живёт одной командой, а не в окружении tmux-сервера:
    # сервер — демон, он не умирает, и всё, что осело в его глобальном
    # окружении, наследует КАЖДАЯ будущая сессия агента. Улика 12.08.2026:
    # HARNESS_CONF со смоук-порогом «ротация при 1% окна» остался в глобале
    # после пробы ротации; поднятая сессия унаследовала его, и первый же
    # ручной прогон сторожа объявил ротацию на 26% окна.
    tmux set-environment -gu HARNESS_CONF 2>/dev/null || true
    tmux set-environment -gu HARNESS_INSTALL_CONF 2>/dev/null || true
    if ! tmux has-session -t "$TMUX_SESSION" 2>/dev/null; then
        say "tmux-сессии '$TMUX_SESSION' нет — поднимаю её вместе с агентом"
        if [ -x "$PROJECT_DIR/scripts/zapustit-agenta.sh" ]; then
            "$PROJECT_DIR/scripts/zapustit-agenta.sh" 8>&- || return 1
        else
            # С оболочкой, а не командой: сессия, созданная командой, умирает
            # вместе с агентом и выбрасывает приаттаченного владельца из tmux
            # (улика 13.08.2026 — та же, что в scripts/zapustit-agenta.sh).
            tmux new-session -d -s "$TMUX_SESSION" -c "$PROJECT_DIR" 8>&- || return 1
            tmux send-keys -t "$TMUX_SESSION" "$AGENT_START_CMD" Enter 8>&- || return 1
        fi
        while [ "$waited" -lt "$AGENT_START_TIMEOUT_SEC" ]; do
            sleep 5; waited=$((waited + 5))
            case "$(pane_cmd)" in claude|node) say "агент поднялся вместе с сессией за ${waited}с"; return 0 ;; esac
        done
        say "сессия поднята, но агента в панели нет за ${AGENT_START_TIMEOUT_SEC}с (там: $(pane_cmd))"
        return 1
    fi
    cmd=$(pane_cmd)
    case "$cmd" in
        claude|node) say "в панели уже claude/node — агент запущен без меня"; return 0 ;;
        # Мёртвой панели ввод не отдать: её оживляют respawn, а не send-keys.
        мертва)
            say "панель пережила выход агента (remain-on-exit) — оживляю её командой запуска"
            tmux respawn-pane -t "$TMUX_SESSION" -c "$PROJECT_DIR" "$AGENT_START_CMD" 8>&- || return 1 ;;
        bash|sh|zsh|dash)
            say "запускаю агента: $AGENT_START_CMD"
            tmux send-keys -t "$TMUX_SESSION" "$AGENT_START_CMD" Enter 8>&- ;;
        *) say "в панели '$cmd' — не оболочка, команду запуска не шлю"; return 1 ;;
    esac
    while [ "$waited" -lt "$AGENT_START_TIMEOUT_SEC" ]; do
        sleep 5; waited=$((waited + 5))
        # Метку ставит ТОЛЬКО тяжёлый путь: по её возрасту решается, не пора ли
        # перезапустить процесс ради памяти, которую «/clear» не освобождает.
        case "$(pane_cmd)" in
            claude|node)
                say "агент поднялся за ${waited}с"
                touch "$HEARTBEAT_DIR/полный-перезапуск" 2>/dev/null || true
                return 0 ;;
        esac
    done
    say "агент НЕ поднялся за ${AGENT_START_TIMEOUT_SEC}с (в панели: $(pane_cmd))"
    return 1
}

# ── `--досмотр-выхода <сессия>`: дозор после сдачи ротации ──────────────────
# Улика 12.08.2026, 23:50–00:10 (снимок владельца). «/exit» подан в 23:50:32,
# сессия не закрылась ни к 23:53, ни к 23:58 — сторож поднял тревогу и вышел.
# А между 23:58 и 00:10 выход ВСЁ-ТАКИ случился: панель, созданная командой,
# закрылась вместе с агентом. Поднять преемника стало некому — cron приходит
# раз в 10 минут, и всё это время сообщение владельца лежало в inbox, а он
# видел «сессии агента не было совсем».
#
# Продлевать досмотр в самой ротации — лечить симптом: любой срок когда-нибудь
# окажется короче. Дыра здесь не в сроке, а в том, что уходя сторож не оставлял
# за собой никого. Теперь оставляет: дозор смотрит каждые 20с и поднимает
# преемника в тот же момент, когда панель освободилась.
агента_нет() {
    tmux has-session -t "$TMUX_SESSION" 2>/dev/null || return 0
    case "$(pane_cmd)" in claude|node) return 1 ;; *) return 0 ;; esac
}

