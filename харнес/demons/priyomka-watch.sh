#!/usr/bin/env bash
#
# priyomka-watch.sh — приёмку задач делает механизм, а не список для владельца.
#
# Владелец 11.09.2026: «Нужен механизм фильтрации <…> там где большая
# уверенность, проверено тобой конкретно что точно работает, то там сам
# закрывай проверку»; «Я не хочу лично все проверять, в этом и смысл, надо
# только то, что не может проверить система».
#
# Модель здесь НЕ ЗОВЁТСЯ. Прогон команд из поля `проверка:` — работа скрипта
# (находка C6 ревью спеки: у харнеса нет способа поднять второго агента, а
# заводить его ради запуска команд — лишняя цена и лишний риск). Агент нужен
# только строителю проверок, и это отдельный демон.
#
# Что делает: зовёт priyomka.py --применить, кладёт отчёт в docs/приёмка/ и
# шлёт владельцу ЧИСЛА — закрыто, провалилось, доказать нечем. Ничего не чинит.
#
# Запуск: cron. Служебное: --selftest, --сухой (посчитать, ничего не менять).
set -uo pipefail

INSTALL_CONF="${HARNESS_INSTALL_CONF:-/etc/harness/install.conf}"
HARNESS_CONF="${HARNESS_CONF:-/etc/harness/harness.conf}"
# Окружение старше конфига: общий загрузчик вместо голого source (улика
# 12.09.2026 — проба с TMUX_SESSION в окружении сменила модель в РАБОЧЕЙ панели).
# shellcheck disable=SC1091
source "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/../../scripts/lib/konf.sh"
konf_zagruzit

PROJECT_DIR="${PROJECT_DIR:?пуст PROJECT_DIR — не прочитан паспорт установки}"
LOG_DIR="${LOG_DIR:-/var/log/harness}"
HEARTBEAT_DIR="${HEARTBEAT_DIR:-/var/lib/harness/heartbeat}"
OTCHET_DIR="$PROJECT_DIR/docs/приёмка"

say() { printf '%s priyomka-watch: %s\n' "$(date -Is)" "$*"; }

# Числа из вывода приёмки: первая строка — JSON со сводом.
chisla() {  # вывод приёмки на stdin → «принято=N провал=M нечем=K»
    # Программа идёт аргументом -c, а НЕ heredoc-ом: «python3 - <<PY» отдаёт
    # стандартный ввод под текст программы, и разбираемый вывод до неё не
    # доходит — самотест поймал это первой же пробой (11.09.2026).
    python3 -c '
import json, sys
свод = {}
for строка in sys.stdin.read().splitlines():
    if строка.startswith("{"):
        try:
            свод = json.loads(строка).get("итог", {})
        except ValueError:
            свод = {}
        break
print("принято=%d провал=%d нечем=%d" % (свод.get("доказано", 0),
                                         свод.get("провал", 0),
                                         свод.get("доказать-нечем", 0)))
'
}

if [ "${1:-}" = "--selftest" ]; then
    ok=1
    # БОЛЬНОЙ СЛУЧАЙ: пустой вывод не должен давать пустых чисел молча — все
    # три числа обязаны быть названы, иначе отчёт владельцу ни о чём.
    got=$(printf '' | chisla)
    if [ "$got" = "принято=0 провал=0 нечем=0" ]; then
        echo "  ок    БОЛЬНОЙ СЛУЧАЙ: пустой вывод даёт три нуля, а не пустоту"
    else echo "  ПЛОХО пустой вывод дал «$got»"; ok=0; fi
    got=$(printf '{"задач в test": 3, "итог": {"доказано": 2, "провал": 1}}\n' | chisla)
    if [ "$got" = "принято=2 провал=1 нечем=0" ]; then
        echo "  ок    числа берутся из свода"
    else echo "  ПЛОХО свод разобран как «$got»"; ok=0; fi
    got=$(printf 'мусор не json\n' | chisla)
    if [ "$got" = "принято=0 провал=0 нечем=0" ]; then
        echo "  ок    битый вывод не валит демона"
    else echo "  ПЛОХО битый вывод дал «$got»"; ok=0; fi
    # Чистка — второй шаг того же действия: закрыл задачу, унеси её из карты.
    # Проба на то, что механизм переноса на месте и зелёный.
    # БОЛЬНОЙ СЛУЧАЙ ревью (I5): метка присмотра писалась даже когда судья
    # падал — сломанный механизм выглядел здоровым и молчал.
    if grep -q 'SUDYA_RC" -gt 1' "$0"; then
        echo "  ок    БОЛЬНОЙ СЛУЧАЙ: падение судьи отличается от «есть провалы»"
    else echo "  ПЛОХО демон не отличает падение судьи от провалов"; ok=0; fi
    # БОЛЬНОЙ СЛУЧАЙ 12.09.2026: лок утекал в агента, тот держал его до 15
    # минут после нашего выхода, и следующий прогон уходил ни с чем — цикл
    # отработал шестнадцать кругов за секунду, все впустую.
    if grep -q '9>&-' "$PROJECT_DIR/харнес/demons/stroitel-proverok.sh"; then
        echo "  ок    БОЛЬНОЙ СЛУЧАЙ: лок закрыт у потомков строителя"
    else echo "  ПЛОХО лок утечёт в агента строителя"; ok=0; fi
    if python3 "$PROJECT_DIR/scripts/arhiv-karty.py" --selftest >/dev/null 2>&1; then
        echo "  ок    перенос в архив на месте и зелёный"
    else echo "  ПЛОХО механизм переноса в архив красный или не найден"; ok=0; fi
    # Валидатор карты доступен демону: без него дубль ключа прошёл бы молча.
    if bash "$PROJECT_DIR/scripts/pre-commit-hook.sh" --devmap-only "$PROJECT_DIR/dev-map.yaml" >/dev/null 2>&1; then
        echo "  ок    валидатор карты доступен демону и карта здорова"
    else echo "  ПЛОХО валидатор карты недоступен или карта больна"; ok=0; fi
    if python3 "$PROJECT_DIR/scripts/priyomka.py" --selftest >/dev/null 2>&1; then
        echo "  ок    судья приёмки на месте и зелёный"
    else echo "  ПЛОХО судья приёмки красный или не найден"; ok=0; fi
    [ "$ok" = 1 ] && { echo "SELFTEST: зелёный (8 путей, первым — больной случай)"; exit 0; }
    echo "SELFTEST: КРАСНЫЙ"; exit 1
fi

# Карту пишут ПЯТЬ сторон: живой агент, devmap-selfheal, проверщик, строитель
# и панель. Лок общий на карту, а не на демона: два писателя наперегонки
# затирают правки друг друга целиком (находка C4 ревью кода 11.09.2026).
LOK="$LOG_DIR/locks/${SERVICE_LOCKS_SUBDIR:-services}/dev-map.lock"
mkdir -p "$(dirname "$LOK")"
exec 9>"$LOK"
# Дескриптор 9 закрывается у КАЖДОГО потомка: иначе агент (он живёт до 15
# минут) наследует его и держит лок после нашего выхода — следующий прогон
# видит «карту правит кто-то другой» и уходит ни с чем. Улика 12.09.2026:
# цикл отработал шестнадцать кругов подряд за одну секунду, все впустую.
# Это те же грабли, что [[лок-утёк-в-потомка]].
if ! flock -n 9; then
    say "карту сейчас правит кто-то другой (лок $LOK) — выхожу, повторю по расписанию"
    exit 0
fi

mkdir -p "$LOG_DIR" "$HEARTBEAT_DIR" "$OTCHET_DIR"

REZHIM="--применить"
[ "${1:-}" = "--сухой" ] && REZHIM=""

VYVOD=$(cd "$PROJECT_DIR" && python3 scripts/priyomka.py $REZHIM 2>&1)
SUDYA_RC=$?
# Код 1 у судьи — это «есть провалы», работа состоялась. Всё, что больше, —
# сам судья упал: битая карта, нет yaml, любая беда. Тогда метку присмотра
# писать НЕЛЬЗЯ: сломанный механизм со свежей меткой неотличим от здорового и
# молчит (находка I5 ревью кода 11.09.2026).
if [ "$SUDYA_RC" -gt 1 ]; then
    say "ОТКАЗ: приёмка упала (код $SUDYA_RC) — метку не ставлю, зову владельца"
    printf '%s\n' "$VYVOD" | tail -5
    bash "$PROJECT_DIR/scripts/tg_send.sh" \
        "Приёмка задач упала и не отработала. Метка присмотра не обновлена — сторож это увидит." \
        >/dev/null 2>&1 || true
    exit "$SUDYA_RC"
fi
ITOG=$(printf '%s\n' "$VYVOD" | chisla)

OTCHET="$OTCHET_DIR/$(date +%Y-%m-%d).md"
{
    printf '# Приёмка задач: %s\n\n' "$(date '+%d.%m.%Y %H:%M')"
    printf 'Итог: %s\n\n' "$ITOG"
    printf 'Проверка идёт по полю `проверка:` в карточке задачи: команда и то,\n'
    printf 'что обязано быть в её выводе. Нет поля — «доказать нечем», и это\n'
    printf 'работа строителю проверок, а не повод закрыть задачу.\n\n'
    printf '```\n%s\n```\n' "$VYVOD"
} > "$OTCHET"

# Закрыл задачу — унеси её из карты. Владелец 11.09.2026: «Один агент пишет
# проверки, другой проверки делает и отмечает что задача проверена, разве он
# не может по логике чистить?» — может и должен: чистка это второй шаг того же
# действия, а не чужая работа. Карта и архив пишутся вместе (И-1).
UBRANO=0
if [ "$REZHIM" = "--применить" ]; then
    UBRANO=$(cd "$PROJECT_DIR" && python3 scripts/arhiv-karty.py --перенести 2>&1 \
             | sed -n 's/.*закрытых задач: \([0-9]*\).*/\1/p')
    UBRANO="${UBRANO:-0}"
    if [ "$UBRANO" != "0" ] \
       && ! bash "$PROJECT_DIR/scripts/pre-commit-hook.sh" --devmap-only "$PROJECT_DIR/dev-map.yaml" >/dev/null 2>&1; then
        say "ТРЕВОГА: после переноса в архив карта не проходит валидатор"
        bash "$PROJECT_DIR/scripts/tg_send.sh" \
            "Приёмка убрала закрытые задачи в архив, и карта перестала проходить проверку. Работа остановлена — нужен разбор." \
            >/dev/null 2>&1 || true
        exit 1
    fi
fi

say "$ITOG убрано-в-архив=$UBRANO · отчёт: $OTCHET"

# Владельцу — числа, а не простыня: сам отчёт лежит файлом.
PROVAL=$(printf '%s' "$ITOG" | sed -n 's/.*провал=\([0-9]*\).*/\1/p')
PRINYATO=$(printf '%s' "$ITOG" | sed -n 's/принято=\([0-9]*\).*/\1/p')
if [ "${PRINYATO:-0}" != "0" ] || [ "${PROVAL:-0}" != "0" ]; then
    bash "$PROJECT_DIR/scripts/tg_send.sh" \
        "Приёмка: $ITOG. Закрытое проверено командой, отчёт в docs/приёмка/." \
        >/dev/null 2>&1 || true
fi

date -Is > "$HEARTBEAT_DIR/priyomka-watch"
exit 0
