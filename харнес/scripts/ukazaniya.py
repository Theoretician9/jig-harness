#!/usr/bin/env python3
"""Гейт указаний: слово владельца не теряется на ротации.

Больной случай 20.08.2026 (дословно): «ты каждый раз пытался дома типа
спорткомплекса искать по названию. Я тебе говорил искать по карте, ты
ротировался и забывал об этом».

Указание было сказано в канал 19.08, разобрано той сессией — и умерло вместе с
ней: сообщения владельца лежат в `$LOG_DIR/inbox/обработано/`, куда новая
сессия не смотрит, а в контекст грузятся только CLAUDE.md, STATE.md и
`память/MEMORY.md`. Память проекта хранила мои выводы, но не слова владельца.

Чинится не памятливостью, а водоразделом: каждое сообщение владельца с
маркером указания обязано быть занесено в `память/УКАЗАНИЯ.md` — файл, который
грузится в КАЖДУЮ сессию через `@` в CLAUDE.md. Занесено = его id есть в файле:
либо действующим указанием, либо в реестре «разобрано, указания нет».

Курсор (`$LOG_DIR/указания/cursor`) — та же механика, что у ревизии карты
разработки: разбор идёт вперёд от последнего занесённого, а не по всем 244
сообщениям с начала времён.

БУХГАЛТЕРИЯ ЖИВЁТ ОТДЕЛЬНО. Занося указание, агент пишет рядом с ним маркер
`<!-- inbox:<id> -->` — так ему удобно, и менять эту привычку нельзя: она и
есть доказательство «занесено». Но сами маркеры в контексте не нужны никому:
03.09.2026 их набралось 58 штук на 2030 знаков — четверть файла, который едет
в КАЖДУЮ сессию, была занята машинными идентификаторами, и файл дважды упёрся
в потолок гигиены. Поэтому при каждой проверке маркеры переезжают в спутник
`память/.указания-разобрано` — файл без `@`-include, который не грузится
никуда. Переезд делает сам гейт, а не «кто-то помнит»: агент пишет как писал.

Запуск:
    ukazaniya.py                 # проверка (и перенос маркеров); 1 = есть долги
    ukazaniya.py --разобрано ID  # занести id в реестр «указания нет»
    ukazaniya.py --selftest      # проверка самого гейта на больном случае
"""
from __future__ import annotations

import os
import pathlib
import re
import sys

# Слова, которыми владелец задаёт правило, а не сообщает факт. Список узкий
# нарочно: ложная тревога стоит одной команды `--разобрано`, а пропущенное
# указание — повторённой ошибки и упрёка в канал.
МАРКЕРЫ = ("правило", "всегда", "никогда", "запомни", "говорил", "больше не",
           "не хочу", "хватит", "прекрати", "категорически", "запрещ",
           "впредь", "требую")

РЕЕСТР = "разобрано-без-указания:"
# Спутник указаний: машинная бухгалтерия «что уже занесено». Точка в начале
# имени — знак того, что читать его человеку незачем.
СПУТНИК = "память/.указания-разобрано"
МАРКЕР = re.compile(r"<!--\s*inbox:([0-9.]+)\s*-->")


def читать_конф(путь: str, куда: dict) -> None:
    """KEY="value" из конфига харнеса. Конфиги не исполняются (И-3)."""
    try:
        текст = pathlib.Path(путь).read_text(encoding="utf-8")
    except OSError:
        return
    for строка in текст.splitlines():
        совпало = re.match(r'^\s*([A-Z_][A-Z0-9_]*)\s*=\s*"?([^"#]*)"?', строка)
        if совпало:
            куда[совпало.group(1)] = совпало.group(2).strip()


def указательное(текст: str) -> bool:
    return any(м in текст.lower() for м in МАРКЕРЫ)


def сообщения(обработано: pathlib.Path) -> list[tuple[float, str, pathlib.Path]]:
    """Разобранные сообщения владельца: (когда, id, файл), от старых к новым."""
    файлы = sorted(обработано.glob("*.txt"), key=lambda ф: ф.stat().st_mtime)
    return [(ф.stat().st_mtime, ф.stem, ф) for ф in файлы]


def водораздел(курсор: pathlib.Path, все: list, указания: str) -> float:
    """С какого момента спрашивать. Первый запуск начинает с последнего id,
    который уже занесён в УКАЗАНИЯ.md: прошлое разбирать поздно, а требовать
    разбора 244 старых сообщений — гейт, который никто не сможет позеленить."""
    try:
        return float(курсор.read_text(encoding="utf-8").strip())
    except (OSError, ValueError):
        занесённые = [когда for когда, ид, _ in все if ид in указания]
        return max(занесённые) if занесённые else 0.0


def неразобранные(все: list, с_какого: float, указания: str) -> list[tuple[str, pathlib.Path]]:
    return [(ид, файл) for когда, ид, файл in все
            if когда > с_какого and ид not in указания
            and указательное(файл.read_text(encoding="utf-8", errors="replace"))]


def перенести_маркеры(корень: pathlib.Path) -> int:
    """Убрать служебные маркеры из УКАЗАНИЙ в спутник. Возвращает число убранных.

    Автопочинка, а не требование к агенту: он заносит указание вместе с
    маркером — это его доказательство, — а место маркера в контексте сессии
    ничем не оправдано.
    """
    файл = корень / "память/УКАЗАНИЯ.md"
    текст = файл.read_text(encoding="utf-8")
    # Старый реестр «указания нет» жил тем же блоком в хвосте файла: он такая
    # же бухгалтерия и едет туда же, иначе правда о занесённом окажется в двух
    # местах сразу.
    блок = re.search(r"<!--[^>]*?" + re.escape(РЕЕСТР) + r"([0-9.\s]*)-->", текст)
    найдены = МАРКЕР.findall(текст) + (блок.group(1).split() if блок else [])
    if not найдены:
        return 0
    if блок:
        текст = текст.replace(блок.group(0), "").rstrip() + "\n"
    спутник = корень / СПУТНИК
    было = спутник.read_text(encoding="utf-8") if спутник.exists() else ""
    новые = [ид for ид in найдены if ид not in было]
    спутник.write_text(было + "".join(f"{ид}\n" for ид in новые), encoding="utf-8")
    # Маркер уходит вместе с пробелом перед ним, если он один: иначе в тексте
    # остаются висячие пробелы там, где маркер стоял после слова.
    файл.write_text(re.sub(r"[ \t]?" + МАРКЕР.pattern, "", текст), encoding="utf-8")
    return len(найдены)


def занесённые(корень: pathlib.Path) -> str:
    """Всё, что считается занесённым: сами указания и спутник с их маркерами."""
    текст = (корень / "память/УКАЗАНИЯ.md").read_text(encoding="utf-8")
    спутник = корень / СПУТНИК
    return текст + (спутник.read_text(encoding="utf-8") if спутник.exists() else "")


def проверить(корень: pathlib.Path, лог: pathlib.Path) -> int:
    файл_указаний = корень / "память/УКАЗАНИЯ.md"
    if not файл_указаний.exists():
        print(f"нет {файл_указаний} — на него смотрит @-include в CLAUDE.md")
        return 1
    обработано = лог / "inbox/обработано"
    if not обработано.is_dir():
        print(f"каталога {обработано} нет — разбирать нечего")
        return 0

    убрано = перенести_маркеры(корень)
    указания = занесённые(корень)
    все = сообщения(обработано)
    курсор = лог / "указания/cursor"
    с_какого = водораздел(курсор, все, указания)
    долги = неразобранные(все, с_какого, указания)

    if долги:
        print(f"НЕ ЗАНЕСЕНО в память/УКАЗАНИЯ.md: {len(долги)} сообщений владельца "
              f"с признаком указания.")
        for ид, файл in долги:
            начало = файл.read_text(encoding="utf-8", errors="replace")[:160]
            print(f"  {ид}: {' '.join(начало.split())}")
        print("Занеси действующее указание строкой с «<!-- inbox:<id> -->», "
              "а если указания в сообщении нет — `ukazaniya.py --разобрано <id>`.")
        return 1

    # Автопочинка: разобрано всё — курсор едет вперёд сам. Иначе гейт требовал
    # бы ещё и «не забыть подвинуть курсор», то есть чтобы кто-то помнил.
    if все:
        курсор.parent.mkdir(parents=True, exist_ok=True)
        курсор.write_text(f"{все[-1][0]:.0f}\n", encoding="utf-8")
    хвост = f", маркеров убрано в спутник: {убрано}" if убрано else ""
    print(f"указания: разобраны все сообщения владельца ({len(все)} в очереди){хвост}")
    return 0


def разобрано(корень: pathlib.Path, ид: str) -> int:
    """Отметить сообщение как разобранное без указания.

    Пишется в спутник, а не в УКАЗАНИЯ.md: «в этом сообщении указания нет» —
    факт для гейта, а не слово владельца, и место ему не в контексте сессии.
    """
    if ид in занесённые(корень):
        print(f"{ид} уже занесён")
        return 0
    спутник = корень / СПУТНИК
    было = спутник.read_text(encoding="utf-8") if спутник.exists() else ""
    спутник.write_text(f"{было}{ид}\n", encoding="utf-8")
    print(f"{ид} занесён в спутник «указания нет»: {СПУТНИК}")
    return 0


def selftest() -> int:
    """Больной случай: сообщение с указанием, которого нет в УКАЗАНИЯ.md."""
    import tempfile

    провалы = []
    with tempfile.TemporaryDirectory() as врем:
        корень, лог = pathlib.Path(врем) / "repo", pathlib.Path(врем) / "log"
        (корень / "память").mkdir(parents=True)
        обработано = лог / "inbox/обработано"
        обработано.mkdir(parents=True)
        указания = корень / "память/УКАЗАНИЯ.md"
        указания.write_text(f"# указания\n<!-- inbox:100 -->\n<!-- {РЕЕСТР} -->\n",
                            encoding="utf-8")

        def сообщение(ид: str, текст: str, когда: int) -> None:
            ф = обработано / f"{ид}.txt"
            ф.write_text(текст, encoding="utf-8")
            os.utime(ф, (когда, когда))

        сообщение("100", "Введи правило проекта", 1000)   # занесено, водораздел
        сообщение("200", "ок, спасибо", 2000)             # не указание
        if проверить(корень, лог) != 0:
            провалы.append("чистое дерево объявлено грязным")

        сообщение("300", "я тебе говорил искать по карте", 3000)
        if проверить(корень, лог) == 0:
            провалы.append("указание без записи в память объявлено разобранным")

        разобрано(корень, "300")
        if проверить(корень, лог) != 0:
            провалы.append("--разобрано не снимает долг")

        # Перенос маркеров прожит: маркер обязан УЙТИ из файла контекста и при
        # этом остаться доказательством — иначе долг вернётся на ровном месте.
        указания.write_text(указания.read_text(encoding="utf-8")
                            + "\nправило: искать по карте <!-- inbox:300 -->\n",
                            encoding="utf-8")
        перенести_маркеры(корень)
        if "inbox:300" in указания.read_text(encoding="utf-8"):
            провалы.append("маркер остался в файле, который едет в контекст")
        if "300" not in занесённые(корень):
            провалы.append("перенос потерял доказательство «занесено»")
        if проверить(корень, лог) != 0:
            провалы.append("после переноса маркеров долг вернулся")

        # Курсор обязан ехать: сообщение СТАРШЕ курсора не спрашивается заново,
        # даже если оно указательное и не занесено.
        сообщение("050", "никогда так не делай", 500)
        if проверить(корень, лог) != 0:
            провалы.append("спрошено сообщение старше водораздела")

    if провалы:
        print("САМОТЕСТ ПРОВАЛЕН:")
        for п in провалы:
            print(f"  {п}")
        return 1
    print("САМОТЕСТ ПРОЙДЕН: 5 путей (чисто, долг, снятие долга, перенос, водораздел)")
    return 0


def main() -> int:
    if "--selftest" in sys.argv:
        return selftest()

    конф: dict = {}
    читать_конф(os.environ.get("HARNESS_INSTALL_CONF", "/etc/harness/install.conf"), конф)
    корень = pathlib.Path(os.environ.get("PROJECT_DIR") or конф.get("PROJECT_DIR")
                          or pathlib.Path(__file__).resolve().parents[1])
    лог = pathlib.Path(os.environ.get("LOG_DIR") or конф.get("LOG_DIR") or "/var/log/harness")

    if "--разобрано" in sys.argv:
        место = sys.argv.index("--разобрано") + 1
        if место >= len(sys.argv):
            print("нужен id сообщения: ukazaniya.py --разобрано 1787173797.119850071")
            return 1
        return разобрано(корень, sys.argv[место])
    return проверить(корень, лог)


if __name__ == "__main__":
    sys.exit(main())
