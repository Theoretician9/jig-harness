#!/usr/bin/env python3
"""Гейт: каждая ручка на панели что-то делает — и делает, когда обещано.

Откуда взят. Спека панели (11.09.2026) выносит развилки харнеса владельцу
переключателями, описанными данными в `харнес/config/переключатели.yaml`.
Adversarial-ревью той же спеки назвало два способа обмануть владельца молча:

  • ручка, которую НИКТО не читает (находка I19): ключ есть, подпись есть,
    переключается — и не делает ничего. Проверить это глазами нельзя: чтение
    ключа живёт в другом файле, а grep по всему репозиторию найдёт упоминание
    в спеке и в памяти;
  • ручка, обещающая «сразу», когда её читают раз в десять минут из cron
    (находка I5): владелец переключил, ничего не изменилось, доверие потеряно.

Плюс третий, самый дорогой: ключ-носитель инварианта, попавший в переключатели
(находка C1 — `AUTONOMY` снимает согласие и со сноса базы). Его ловит чёрный
список, и он тоже данные — с причиной у каждой строки.

Прогон:
    python3 scripts/check-pereklyuchateli.py [--selftest]
Код возврата: 0 — реестр сходится с кодом и конфигом, 1 — расхождение.
"""
import fnmatch
import os
import re
import sys
from pathlib import Path

import yaml

КОРЕНЬ = Path(__file__).resolve().parent.parent
РЕЕСТР = КОРЕНЬ / "харнес" / "config" / "переключатели.yaml"
КОНФИГИ = {
    "install.conf": os.environ.get("HARNESS_INSTALL_CONF", "/etc/harness/install.conf"),
    "harness.conf": os.environ.get("HARNESS_CONF", "/etc/harness/harness.conf"),
}
ОБЯЗАТЕЛЬНЫЕ = ("ключ", "файл", "имя", "вид", "простыми словами",
                "опасный", "читатель", "способ_чтения", "применяется")
# Как часто читают ключ → что панель вправе обещать владельцу.
СРОК_ПО_СПОСОБУ = {
    "при_вызове": {"сразу"},
    "cron_10мин": {"в ближайшую проверку"},
    # Суточная сверка обновлений: обещать «сразу» ключу, который читают раз в
    # день, — тот же обман владельца, что и с десятиминутным (находка I2).
    "cron_сутки": {"в ближайшую проверку"},
    # Раз в месяц или по кнопке панели: обещать больше «в ближайшую проверку»
    # такому ключу нечестно — до планового прогона может быть месяц (ревизия
    # проекта, 12.09.2026).
    "cron_месяц": {"в ближайшую проверку"},
    "служба": {"после перезапуска службы"},
}


def значение_в_конфиге(ключ: str, путь: str) -> str | None:
    """Значение ключа в shell-конфиге. Конфиг не исполняется — разбирается."""
    try:
        текст = Path(путь).read_text(encoding="utf-8", errors="replace")
    except OSError:
        return None
    найдено = re.search(rf'^\s*{re.escape(ключ)}=["\']?([^"\'\n#]*)',
                        текст, re.MULTILINE)
    return найдено.group(1).strip() if найдено else None


def читает_ключ(читатель: str, ключ: str) -> bool:
    """Файл-читатель действительно обращается к ключу.

    Ищем в КОДЕ читателя, а не по всему репозиторию: упоминание ключа в спеке
    или в записи памяти чтением не является.
    """
    файл = КОРЕНЬ / читатель
    try:
        текст = файл.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return False
    строки = [с for с in текст.splitlines() if not с.lstrip().startswith("#")]
    return any(ключ in с for с in строки)


def в_чёрном_списке(ключ: str, чёрный: list) -> str | None:
    """Причина запрета или None. Шаблон «BACKUP_*» закрывает семейство ключей."""
    for строка in чёрный:
        образец = строка.get("ключ", "")
        if fnmatch.fnmatch(ключ, образец):
            return (строка.get("причина") or "").strip()
    return None


def проверить(реестр: dict, конфиги: dict) -> list[str]:
    """Список бед. Пусто — реестр сходится с кодом и конфигом."""
    беды = []
    чёрный = реестр.get("чёрный_список") or []
    ключи = реестр.get("переключатели") or []
    if not ключи:
        return ["реестр пуст: панели нечего показывать"]
    видели = set()
    for строка in ключи:
        ключ = строка.get("ключ", "<без ключа>")
        нет_полей = [п for п in ОБЯЗАТЕЛЬНЫЕ if not строка.get(п) and
                     строка.get(п) is not False]
        if нет_полей:
            беды.append(f"{ключ}: нет обязательных полей: {', '.join(нет_полей)}")
            continue
        if ключ in видели:
            беды.append(f"{ключ}: описан дважды — панель покажет две ручки на один ключ")
        видели.add(ключ)

        причина = в_чёрном_списке(ключ, чёрный)
        if причина:
            беды.append(f"{ключ}: ключ из чёрного списка — {причина}")

        путь = конфиги.get(строка["файл"])
        if путь is None:
            беды.append(f"{ключ}: неизвестный файл конфига «{строка['файл']}»")
        else:
            значение = значение_в_конфиге(ключ, путь)
            if значение is None:
                беды.append(f"{ключ}: в {строка['файл']} такого ключа нет — "
                            f"панель покажет ручку, которой нет в настройках")
            else:
                беды += проверить_значение(строка, значение)

        if not читает_ключ(строка["читатель"], ключ):
            беды.append(f"{ключ}: читатель {строка['читатель']} этот ключ не читает "
                        f"— ручка не делает ничего")

        можно = СРОК_ПО_СПОСОБУ.get(строка["способ_чтения"])
        if можно is None:
            беды.append(f"{ключ}: неизвестный способ_чтения «{строка['способ_чтения']}»")
        elif строка["применяется"] not in можно:
            беды.append(f"{ключ}: обещает «{строка['применяется']}», но читается "
                        f"{строка['способ_чтения']} — обещание не сбудется")
    return беды


def проверить_значение(строка: dict, значение: str) -> list[str]:
    """Текущее значение в конфиге допустимо по реестру."""
    ключ = строка["ключ"]
    if строка["вид"] == "выбор":
        можно = [str(з.get("значение")) for з in (строка.get("значения") or [])]
        if not можно:
            return [f"{ключ}: вид «выбор», но список значений пуст"]
        if значение not in можно:
            return [f"{ключ}: в конфиге «{значение}», а реестр знает только "
                    f"{можно} — панель не сможет показать текущее состояние"]
    elif строка["вид"] == "число":
        try:
            число = float(значение)
        except ValueError:
            return [f"{ключ}: в конфиге «{значение}» — не число, а реестр обещает число"]
        if not (float(строка["от"]) <= число <= float(строка["до"])):
            return [f"{ключ}: значение {значение} вне границ реестра "
                    f"{строка['от']}..{строка['до']}"]
    else:
        return [f"{ключ}: неизвестный вид «{строка['вид']}»"]
    return []


def самотест() -> int:
    """Гейт обязан СОЗДАТЬ своё условие: больная ручка и здоровая рядом."""
    import tempfile
    ok = True

    def проба(имя: str, реестр: dict, конфиг: str, ждём_беду: str | None):
        nonlocal ok
        with tempfile.TemporaryDirectory() as врем:
            путь = Path(врем) / "harness.conf"
            путь.write_text(конфиг, encoding="utf-8")
            беды = проверить(реестр, {"harness.conf": str(путь)})
        нашли = "; ".join(беды)
        если_ждали = ждём_беду is None and not беды
        если_поймали = ждём_беду is not None and ждём_беду in нашли
        if если_ждали or если_поймали:
            print(f"  ок    {имя}")
        else:
            ok = False
            print(f"  ПЛОХО {имя}: получили «{нашли or 'ничего'}»")

    здоровая = {
        "ключ": "PUSH_NEEDS_OWNER", "файл": "harness.conf",
        "имя": "Отправка", "вид": "выбор",
        "значения": [{"значение": "0", "подпись": "сама"},
                     {"значение": "1", "подпись": "спросить"}],
        "простыми словами": "готовый код сам уезжает в хранилище",
        "опасный": True, "читатель": "scripts/deploy_guard.py",
        "способ_чтения": "при_вызове", "применяется": "сразу",
    }
    чёрный = [{"ключ": "AUTONOMY", "причина": "снимает согласие со сноса базы"},
              {"ключ": "BACKUP_*", "причина": "копии держат И-1"}]

    проба("здоровая ручка — чисто",
          {"переключатели": [здоровая], "чёрный_список": чёрный},
          "PUSH_NEEDS_OWNER=0\n", None)

    призрак = dict(здоровая, ключ="ВЫДУМАННЫЙ_КЛЮЧ")
    проба("БОЛЬНОЙ СЛУЧАЙ: ручка, которую никто не читает",
          {"переключатели": [призрак], "чёрный_список": чёрный},
          "ВЫДУМАННЫЙ_КЛЮЧ=1\n", "не читает")

    нет_в_конфиге = dict(здоровая, ключ="DEPLOY_NEEDS_OWNER")
    проба("БОЛЬНОЙ СЛУЧАЙ: ключа нет в настройках",
          {"переключатели": [нет_в_конфиге], "чёрный_список": чёрный},
          "PUSH_NEEDS_OWNER=0\n", "такого ключа нет")

    врёт_срок = dict(здоровая, способ_чтения="cron_10мин", применяется="сразу")
    проба("БОЛЬНОЙ СЛУЧАЙ: обещает «сразу», а читается раз в 10 минут",
          {"переключатели": [врёт_срок], "чёрный_список": чёрный},
          "PUSH_NEEDS_OWNER=0\n", "обещание не сбудется")

    # Ключ, который читают раз в месяц: «в ближайшую проверку» — правда, а
    # «сразу» — обман (ревизия проекта, 12.09.2026).
    месячная = dict(здоровая, способ_чтения="cron_месяц",
                    применяется="в ближайшую проверку")
    проба("месячная ручка обещает «в ближайшую проверку» — чисто",
          {"переключатели": [месячная], "чёрный_список": чёрный},
          "PUSH_NEEDS_OWNER=0\n", None)

    месячная_врёт = dict(здоровая, способ_чтения="cron_месяц", применяется="сразу")
    проба("БОЛЬНОЙ СЛУЧАЙ: месячная ручка обещает «сразу»",
          {"переключатели": [месячная_врёт], "чёрный_список": чёрный},
          "PUSH_NEEDS_OWNER=0\n", "обещание не сбудется")

    запрещённый = dict(здоровая, ключ="AUTONOMY", читатель="scripts/deploy_guard.py")
    проба("БОЛЬНОЙ СЛУЧАЙ: ключ-носитель инварианта в переключателях",
          {"переключатели": [запрещённый], "чёрный_список": чёрный},
          "AUTONOMY=semi\n", "чёрного списка")

    семейство = dict(здоровая, ключ="BACKUP_KEEP_DAYS", вид="число", от=1, до=30)
    семейство.pop("значения", None)
    проба("БОЛЬНОЙ СЛУЧАЙ: шаблон чёрного списка закрывает семейство ключей",
          {"переключатели": [семейство], "чёрный_список": чёрный},
          "BACKUP_KEEP_DAYS=7\n", "чёрного списка")

    вне_границ = dict(здоровая, ключ="CTX_ROTATE_PCT", вид="число", от=50, до=95,
                      читатель="харнес/demons/session-warden.sh",
                      способ_чтения="cron_10мин", применяется="в ближайшую проверку")
    вне_границ.pop("значения", None)
    проба("значение в настройках вне границ реестра",
          {"переключатели": [вне_границ], "чёрный_список": чёрный},
          "CTX_ROTATE_PCT=300\n", "вне границ")

    print("САМОТЕСТ %s: 9 путей, шесть — больные случаи"
          % ("ПРОЙДЕН" if ok else "ПРОВАЛЕН"))
    return 0 if ok else 1


def main() -> int:
    if "--selftest" in sys.argv:
        return самотест()
    try:
        реестр = yaml.safe_load(РЕЕСТР.read_text(encoding="utf-8"))
    except OSError:
        print(f"[переключатели] реестра нет: {РЕЕСТР}")
        return 1
    except yaml.YAMLError as беда:
        print(f"[переключатели] реестр не разбирается: {беда}")
        return 1
    беды = проверить(реестр, КОНФИГИ)
    if беды:
        print(f"[переключатели] РАСХОЖДЕНИЙ: {len(беды)}")
        for строка in беды:
            print("   ", строка)
        return 1
    сколько = len(реестр.get("переключатели") or [])
    print(f"[переключатели] {сколько} ручек: каждая читается и применяется "
          f"тогда, когда обещано")
    return 0


if __name__ == "__main__":
    sys.exit(main())
