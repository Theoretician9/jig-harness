#!/usr/bin/env python3
"""Порции ревизии: свежее первым, порция не больше потолка, курсор помнит место.

Почему. Замер 12.09.2026: код харнеса — 2 070 660 знаков
(find scripts харнес -type f \\( -name '*.py' -o -name '*.sh' \\) -exec wc -c {} + | tail -1),
порция 300 000 — седьмая часть. Без курсора каждый месяц читались бы одни и
те же файлы (C-7² ревью спеки); без правила «крупный файл один и целиком»
session-warden.sh (184 711 зн.) не поместился бы никогда и не читался бы никогда.

Прогон: python3 scripts/test_revizia_porcii.py
"""
import importlib.util
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
спец = importlib.util.spec_from_file_location("порции", КОРЕНЬ / "scripts" / "revizia-porcii.py")
порции = importlib.util.module_from_spec(спец)
спец.loader.exec_module(порции)
путей = неудач = 0


def проба(имя, ждём, вышло):
    global путей, неудач
    путей += 1
    if вышло == ждём:
        print(f"  ок    {имя}")
    else:
        неудач += 1
        print(f"  ПЛОХО {имя}: ждали {ждём!r}, вышло {вышло!r}")


# (путь, знаков, mtime) — mtime растёт: c свежее b свежее a
ФАЙЛЫ = [("a.sh", 100, 1), ("b.sh", 100, 2), ("c.sh", 100, 3), ("d.sh", 100, 4)]

выбрано, курсор = порции.порция(ФАЙЛЫ, None, 250)
проба("свежие первыми, в порцию влезло два", ["d.sh", "c.sh"], выбрано)
проба("курсор — последний взятый", "c.sh", курсор)
выбрано, курсор = порции.порция(ФАЙЛЫ, "c.sh", 250)
проба("БОЛЬНОЙ СЛУЧАЙ: второй прогон продолжает, а не читает те же файлы", ["b.sh", "a.sh"], выбрано)
проба("список исчерпан — курсор снят, следующий раз с начала", None, курсор)
выбрано, _ = порции.порция(ФАЙЛЫ, "нет-такого.sh", 250)
проба("курсор на исчезнувший файл — начинаем с начала", ["d.sh", "c.sh"], выбрано)
выбрано, курсор = порции.порция([("огромный.sh", 900, 5)] + ФАЙЛЫ, None, 250)
проба("БОЛЬНОЙ СЛУЧАЙ: файл крупнее порции идёт один и целиком", ["огромный.sh"], выбрано)
проба("после крупного курсор стоит на нём", "огромный.sh", курсор)
проба("пустой список — пусто и без курсора", ([], None), порции.порция([], None, 250))

# ── CLI на временном проекте: маски, курсор в файле, пороги ──────────────────
with tempfile.TemporaryDirectory() as врем:
    проект = Path(врем) / "проект"
    (проект / "scripts").mkdir(parents=True)
    (проект / "scripts" / "x.sh").write_text("x" * 10, encoding="utf-8")
    (проект / "scripts" / "y.sh").write_text("y" * 10, encoding="utf-8")
    os.utime(проект / "scripts" / "y.sh", (2_000_000_000, 2_000_000_000))
    конф = Path(врем) / "ревизия.yaml"
    конф.write_text(
        "пороги: {знаков_на_порцию: 15, потолок_минут: 9, максимум_находок: 2,\n"
        "         максимум_знаков_карточки: 500, срок_находки_суток: 30}\n"
        "области:\n  - {имя: проба, пути: ['scripts/*.sh'], вопрос: 'что не так'}\n",
        encoding="utf-8")
    окружение = dict(os.environ, PROJECT_DIR=str(проект), LOG_DIR=врем, REVIZIA_CONF=str(конф))

    def cli(*доводы):
        return subprocess.run([sys.executable, str(КОРЕНЬ / "scripts" / "revizia-porcii.py"), *доводы],
                              capture_output=True, text=True, env=окружение)

    проба("--области печатает имена", "проба\n", cli("--области").stdout)
    проба("--пороги печатает строки для eval", True,
          "ZNAKOV_NA_PORCIYU=15" in cli("--пороги").stdout and "POTOLOK_MINUT=9" in cli("--пороги").stdout)
    проба("порция области: свежий y.sh первым, x.sh не влез (10+10 > 15)", "scripts/y.sh\n", cli("проба").stdout)
    проба("без --продвинуть курсора нет", False, (Path(врем) / "revizia" / "курсор.json").exists())
    cli("проба", "--продвинуть")
    курсор = json.loads((Path(врем) / "revizia" / "курсор.json").read_text(encoding="utf-8"))
    проба("--продвинуть записал курсор", {"проба": "scripts/y.sh"}, курсор)
    проба("следующий вызов идёт дальше по курсору", "scripts/x.sh\n", cli("проба").stdout)
    проба("БОЛЬНОЙ СЛУЧАЙ: неизвестная область — отказ, не пустота", 2, cli("нет-такой").returncode)

print(f"ПОРЦИИ РЕВИЗИИ: путей {путей}, неудач {неудач}")
sys.exit(1 if неудач else 0)
