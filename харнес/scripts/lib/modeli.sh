#!/usr/bin/env bash
# shellcheck shell=bash
# Имена моделей — ОДИН источник на все скрипты, которые их проверяют.
#
# Откуда взят: 12.09.2026, задача «модель под задачу». Список допустимых имён
# жил внутри model.sh, а новый выбор модели по виду работы обязан проверять то
# же самое. Два списка в двух файлах разъезжаются молча — так разошлись формы
# команд приёмки, и цикл крутился впустую пять кругов.
#
# Файл только объявляет: его source-ят, исполнять нечего.

# Короткие имена, которые понимает `claude --model`. Список намеренно узкий —
# это то, чем пользуется владелец из канала; полные имена тоже разрешены.
MODEL_ALIASES="fable opus sonnet haiku"

model_imya_dopustimo() {  # имя → 0 годится, 1 нет
    local name="${1:-}" a
    [ -n "$name" ] || return 1
    for a in $MODEL_ALIASES; do
        [ "$name" = "$a" ] && return 0
    done
    # Полное имя: claude-fable-5-1, claude-haiku-4-5-20251001 и подобные.
    printf '%s' "$name" | grep -Eq '^claude-[a-z0-9][a-z0-9.-]*$'
}

# Алиас и полное имя — одна и та же модель: «opus» и «claude-opus-5» сравнивать
# как строки нельзя. Улика 12.09.2026 (ревью кода): хук сравнивал текст вывода
# «модель агента:» (которого model.sh не печатает — он пишет «модель сейчас:»),
# получал пустоту и жал «/model» на каждом вызове скила, хотя менять было нечего.
model_odna_i_ta_zhe() {  # $1, $2 → 0 если это одна модель
    local a="${1:-}" b="${2:-}"
    [ -n "$a" ] && [ -n "$b" ] || return 1
    [ "$a" = "$b" ] && return 0
    # claude-opus-5 → opus; claude-haiku-4-5-20251001 → haiku
    local ka kb
    ka=$(printf '%s' "$a" | sed -n 's/^claude-\([a-z]*\).*/\1/p')
    kb=$(printf '%s' "$b" | sed -n 's/^claude-\([a-z]*\).*/\1/p')
    [ -n "$ka" ] || ka="$a"
    [ -n "$kb" ] || kb="$b"
    [ "$ka" = "$kb" ]
}

# Выбор модели для вызова claude — ОДНА функция на всех демонов. До 12.09.2026
# она лежала четырьмя побайтовыми копиями, и правка выбора потребовала бы
# четырёх синхронных правок (находка ревью кода).
#
# Через `bash`, а не прямым запуском: exec-бит теряется при копировании, и
# живая проба поймала ровно это — механизм молча отдавал умолчание.
# Результат ВСЕГДА непуст: пустое `--model` вернуло бы ненулевой код, и
# session-warden послал бы владельцу ложную тревогу о битой передаче.
model_dlya() {  # $1=вид работы → имя модели
    local kind="${1:-дежурный}" out=""
    out=$(bash "${PROJECT_DIR:?пуст PROJECT_DIR — не прочитан паспорт установки}/scripts/model-dlya.sh" "$kind" 2>/dev/null) || out=""
    [ -n "$out" ] || out="${DEMON_MODEL:-haiku}"
    printf '%s' "$out"
}
