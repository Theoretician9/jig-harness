#!/usr/bin/env python3
"""Сторож срока входа по подписке: предупредить ЗАРАНЕЕ, а не когда всё встало.

Откуда взят. 11.09.2026 CLI напечатал «Your login expires in 1 day · run /login
to renew», и владелец спросил: «А с чего вдруг вообще вход имеет срок? Первый
раз такое вижу». Замер по `~/.claude/.credentials.json` в 06:07: два разных
срока — доступ (`expiresAt`) на 8 часов вперёд и обновляющий ключ
(`refreshTokenExpiresAt`) на 9 часов. Доступ продлевается сам (файл переписан
за полминуты до замера), а вот обновляющий ключ — вопрос: если он истечёт,
работа встанет, и поднять её может только владелец подтверждением в браузере.

Почему сторож, а не память: владелец терминала не видит, а строку «expires in
1 day» вижу только я и только пока смотрю на экран. Правило проекта — решение,
требующее «чтобы кто-то помнил», решением не является.

Значения токенов НЕ печатаются и не логируются: в файле лежат ключи доступа.

Прогон:
    python3 scripts/check-srok-vhoda.py [--selftest] [--часов N]
Код возврата: 0 — запас есть, 1 — пора продлевать, 2 — прочитать нечем.
"""
import datetime
import json
import os
import subprocess
import sys

ФАЙЛ = os.path.expanduser(os.environ.get("CLAUDE_CREDENTIALS")
                          or "~/.claude/.credentials.json")
# Порог: за сколько часов до конца обновляющего ключа звать владельца. Шесть —
# чтобы предупреждение пришло в рабочее время, а не среди ночи перед остановкой.
ПОРОГ_ЧАСОВ = float(os.environ.get("LOGIN_WARN_HOURS", "6"))

# Долгий вход: токен на год (`claude setup-token`), выданный 11.09.2026 по
# слову владельца «делай сразу на долго». Пока он на месте, обновляющий ключ
# подписки роли не играет — работа идёт по нему. Читается ТОЛЬКО дата выдачи
# (mtime), значение не открывается и не печатается.
ТОКЕН_ФАЙЛ = os.environ.get("CLAUDE_OAUTH_TOKEN_FILE",
                            "/var/lib/harness/secrets/claude-oauth-token")
ТОКЕН_ЖИВЁТ_ДНЕЙ = 365
ТОКЕН_ПОРОГ_ДНЕЙ = float(os.environ.get("LOGIN_TOKEN_WARN_DAYS", "14"))


def выдан(путь=ТОКЕН_ФАЙЛ):
    """Когда получен долгий токен, либо None — его нет."""
    try:
        if os.path.getsize(путь) == 0:
            return None
    except OSError:
        return None
    return datetime.datetime.fromtimestamp(os.path.getmtime(путь))


def вердикт_долгого(когда, сейчас=None, порог_дней=ТОКЕН_ПОРОГ_ДНЕЙ):
    """(код, строка) для долгого токена. Чистая функция — её судит самотест."""
    сейчас = сейчас or datetime.datetime.now()
    конец = когда + datetime.timedelta(days=ТОКЕН_ЖИВЁТ_ДНЕЙ)
    осталось = (конец - сейчас).total_seconds() / 86400
    хвост = (f"долгий ключ выдан {когда:%d.%m.%Y}, годен до {конец:%d.%m.%Y} "
             f"({осталось:+.0f} дн)")
    if осталось <= 0:
        return 1, (f"ДОЛГИЙ КЛЮЧ ИСТЁК: {хвост}. Нужен новый: claude setup-token "
                   f"в отдельной панели, ссылку — владельцу")
    if осталось <= порог_дней:
        return 1, (f"долгий ключ кончается меньше чем через {порог_дней:g} дн: "
                   f"{хвост}. Пора выпускать новый: claude setup-token")
    return 0, f"запас есть: {хвост}"


def сроки(путь=ФАЙЛ):
    """(доступ, обновляющий ключ) как datetime, либо None — файла/полей нет."""
    try:
        with open(путь, encoding="utf-8") as fh:
            данные = json.load(fh)
    except (OSError, ValueError):
        return None
    узел = данные.get("claudeAiOauth") or данные
    try:
        доступ = datetime.datetime.fromtimestamp(узел["expiresAt"] / 1000)
        ключ = datetime.datetime.fromtimestamp(узел["refreshTokenExpiresAt"] / 1000)
    except (KeyError, TypeError, ValueError):
        return None
    return доступ, ключ


def вердикт(пара, сейчас=None, порог_часов=ПОРОГ_ЧАСОВ):
    """(код, строка). Чистая функция — её и проверяет самотест."""
    if пара is None:
        return 2, ("срок входа прочитать нечем: нет файла входа или в нём нет "
                   "полей срока — проверить вручную")
    доступ, ключ = пара
    сейчас = сейчас or datetime.datetime.now()
    до_ключа = (ключ - сейчас).total_seconds() / 3600
    до_доступа = (доступ - сейчас).total_seconds() / 3600
    хвост = (f"доступ до {доступ:%d.%m %H:%M} ({до_доступа:+.1f} ч), "
             f"обновляющий ключ до {ключ:%d.%m %H:%M} ({до_ключа:+.1f} ч)")
    if до_ключа <= 0:
        return 1, f"ВХОД ИСТЁК: {хвост}. Нужна команда /login и подтверждение в браузере"
    if до_ключа <= порог_часов:
        return 1, (f"вход истекает меньше чем через {порог_часов:g} ч: {хвост}. "
                   f"Нужна команда /login и подтверждение владельцем в браузере")
    return 0, f"запас есть: {хвост}"


ИСТОРИЯ = os.path.join(os.environ.get("LOG_DIR", "/var/log/harness"),
                       "срок-входа.jsonl")


def записать_историю(пара, путь=ИСТОРИЯ):
    """Дозаписать ЗАМЕР сроков — чтобы узнать фактом, продлевается ли ключ сам.

    Владелец 11.09: «с чего вдруг вообще мне надо перелогиниваться». Ответить
    на это можно только историей замеров: доступ продлевается сам — это видно,
    а про обновляющий ключ известно лишь одно значение. Пишутся ДАТЫ, не токены.
    """
    if пара is None:
        return
    доступ, ключ = пара
    строка = json.dumps({"ts": datetime.datetime.now().isoformat(timespec="seconds"),
                         "доступ_до": доступ.isoformat(timespec="seconds"),
                         "ключ_до": ключ.isoformat(timespec="seconds")},
                        ensure_ascii=False)
    try:
        with open(путь, "a", encoding="utf-8") as fh:
            fh.write(строка + "\n")
    except OSError:
        pass  # журнал наблюдения не вправе ронять сторожа


# Носитель долгого входа: файл, который выставляет переменную, и конфиг
# демонов, который его подключает. Пути — данные установки.
НОСИТЕЛЬ = os.environ.get("HARNESS_VHOD", "/etc/harness/vhod.sh")
КОНФИГ_ДЕМОНОВ = os.environ.get("HARNESS_CONF", "/etc/harness/harness.conf")
ПРОФИЛИ = ("~/.profile", "~/.bashrc")
ПЕРЕМЕННАЯ = "CLAUDE_CODE_OAUTH_TOKEN"


def доносит(конфиг=None):
    """Выставляет ли переменную путь БЕЗ профиля оболочки — то есть у cron.

    Это главная проверка: демоны запускаются из cron, а он профиля не читает.
    Запуск идёт в чистом окружении (`env -i`) — иначе переменная, уже стоящая
    у сторожа, показала бы успех там, где его нет.
    """
    конфиг = конфиг or КОНФИГ_ДЕМОНОВ
    if not os.access(конфиг, os.R_OK):
        return False
    проба = subprocess.run(
        ["env", "-i", "HOME=" + os.path.expanduser("~"), "/bin/sh", "-c",
         f'. {конфиг} >/dev/null 2>&1; [ -n "${{{ПЕРЕМЕННАЯ}:-}}" ]'],
        capture_output=True, timeout=30)
    return проба.returncode == 0


def профили_подключают(имена=ПРОФИЛИ):
    """Какие профили оболочки НЕ подключают носитель (tmux-панель агента)."""
    беда = []
    for имя in имена:
        путь = os.path.expanduser(имя)
        try:
            if os.path.basename(НОСИТЕЛЬ) not in open(путь, encoding="utf-8",
                                                      errors="replace").read():
                беда.append(имя)
        except OSError:
            беда.append(имя)
    return беда


def сессия_на_долгом():
    """(pid, есть ли переменная) у живого процесса claude, либо None.

    Читается окружение процесса, а не его вывод: окружение живого процесса
    задним числом не меняется, и ровно это 12.09.2026 оказалось причиной —
    сессия была старше носителя на девять часов. Значение не печатается.
    """
    найдено = subprocess.run(["pgrep", "-u", str(os.getuid()), "-f", "[c]laude"],
                             capture_output=True, text=True)
    for строка in найдено.stdout.split():
        try:
            with open(f"/proc/{строка}/environ", "rb") as fh:
                окружение = fh.read().split(b"\0")
        except OSError:
            continue
        есть = any(з.startswith(ПЕРЕМЕННАЯ.encode() + b"=") and len(з) > len(ПЕРЕМЕННАЯ) + 1
                   for з in окружение)
        return int(строка), есть
    return None


def вердикт_применения(доносится, профили_без, живая, угроза):
    """(код, строка). Чистая функция — её судит самотест.

    `угроза` — правда, когда подписочный вход близок к концу. Красным делаем
    только то, что чинится: носитель, не доносящий токен. Старая сессия без
    переменной — сообщение, а тревога лишь когда истекает и подписочный вход:
    признак без различения будит владельца на здоровой жизни.
    """
    беды = []
    if not доносится:
        беды.append(f"{КОНФИГ_ДЕМОНОВ} не выставляет {ПЕРЕМЕННАЯ}: "
                    f"ночные вызовы claude идут на входе из /login")
    if профили_без:
        беды.append("профили оболочки не подключают носитель: "
                    + ", ".join(профили_без))
    if беды:
        return 1, "долгий вход НЕ ПРИМЕНЯЕТСЯ — " + "; ".join(беды)
    if живая is not None and not живая[1]:
        хвост = (f"сессия (pid {живая[0]}) запущена раньше носителя и идёт "
                 f"на входе из /login; долгий токен она подхватит при ротации")
        return (1, "ВХОД СЕССИИ ИСТЕКАЕТ: " + хвост) if угроза else (0, хвост)
    return 0, "долгий вход применяется: и демоны, и оболочки, и живая сессия"


def самотест():
    сейчас = datetime.datetime(2026, 9, 11, 6, 0)
    случаи = [
        # (пара сроков, ждём код, чем случай важен)
        ((сейчас + datetime.timedelta(hours=8), сейчас + datetime.timedelta(hours=1)),
         1, "БОЛЬНОЙ СЛУЧАЙ: доступ ещё жив 8 ч, а обновляющий ключ кончается через час"),
        ((сейчас + datetime.timedelta(hours=8), сейчас + datetime.timedelta(hours=30)),
         0, "оба срока далеко — молчим"),
        ((сейчас - datetime.timedelta(hours=1), сейчас - datetime.timedelta(hours=1)),
         1, "срок уже прошёл — это тревога, а не молчание"),
        ((сейчас + datetime.timedelta(hours=1), сейчас + datetime.timedelta(hours=6)),
         1, "ровно на пороге — предупреждаем"),
        (None, 2, "файла или полей нет — отказ, а не выдуманный запас"),
    ]
    ok = True
    for пара, ждём, зачем in случаи:
        код, строка = вердикт(пара, сейчас)
        if код != ждём:
            ok = False
            print(f"  ПЛОХО {зачем}: код {код}, ждали {ждём} — {строка}")
        else:
            print(f"  ок    {зачем}")
    # Долгий ключ: он старше подписочного, и истёкший refresh при нём — не беда.
    долгие = [
        (сейчас - datetime.timedelta(days=1), 0,
         "БОЛЬНОЙ СЛУЧАЙ: долгий ключ выдан вчера — истёкший refresh не тревога"),
        (сейчас - datetime.timedelta(days=360), 1,
         "долгому ключу осталось 5 дней — зовём выпускать новый"),
        (сейчас - datetime.timedelta(days=400), 1,
         "долгий ключ просрочен — тревога, а не молчание"),
    ]
    for когда, ждём, зачем in долгие:
        код, строка = вердикт_долгого(когда, сейчас)
        if код != ждём:
            ok = False
            print(f"  ПЛОХО {зачем}: код {код}, ждали {ждём} — {строка}")
        else:
            print(f"  ок    {зачем}")

    # Токен не должен попасть в вывод НИКОГДА: проверяем на подставном файле.
    import tempfile
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False,
                                     encoding="utf-8") as fh:
        json.dump({"claudeAiOauth": {"accessToken": "СЕКРЕТ-ТОКЕН",
                                     "refreshToken": "СЕКРЕТ-КЛЮЧ",
                                     "expiresAt": 1789117626756,
                                     "refreshTokenExpiresAt": 1789121442756}}, fh)
        путь = fh.name
    _, строка = вердикт(сроки(путь))
    os.unlink(путь)
    if "СЕКРЕТ" in строка:
        ok = False
        print("  ПЛОХО значение токена попало в вывод сторожа")
    else:
        print("  ок    БОЛЬНОЙ СЛУЧАЙ: значения токенов в выводе нет")
    # Применение долгого входа. Первым — больной случай 12.09.2026.
    применение_случаи = [
        ((True, [], (111, False), False), 0,
         "БОЛЬНОЙ СЛУЧАЙ 12.09: носители в порядке, сессия старше их — сообщаем, не красим"),
        ((True, [], (111, False), True), 1,
         "та же сессия, но подписочный вход истекает — это уже тревога"),
        ((False, [], (111, True), False), 1,
         "БОЛЬНОЙ СЛУЧАЙ: конфиг демонов не доносит токен — ночные вызовы без него"),
        ((True, ["~/.bashrc"], (111, True), False), 1,
         "профиль оболочки не подключает носитель — панель агента останется без токена"),
        ((True, [], (111, True), False), 0, "всё на месте — молчим"),
        ((True, [], None, False), 0, "claude не запущен — судить нечего, не выдумываем беду"),
    ]
    for аргументы, ждём, зачем in применение_случаи:
        код, строка = вердикт_применения(*аргументы)
        if код != ждём:
            ok = False
            print(f"  ПЛОХО {зачем}: код {код}, ждали {ждём} — {строка}")
        else:
            print(f"  ок    {зачем}")

    print("САМОТЕСТ %s: %d путей, первым — больной случай"
          % ("ПРОЙДЕН" if ok else "ПРОВАЛЕН",
             len(случаи) + len(долгие) + len(применение_случаи) + 1))
    return 0 if ok else 1


def main():
    if "--selftest" in sys.argv:
        return самотест()
    порог = ПОРОГ_ЧАСОВ
    if "--часов" in sys.argv:
        порог = float(sys.argv[sys.argv.index("--часов") + 1])
    пара = сроки()
    записать_историю(пара)
    # Долгий токен старше подписочного ключа: когда он есть, работа идёт по
    # нему, и истёкший refresh подписки уже ничего не решает.
    когда = выдан()
    if когда is not None:
        код, строка = вердикт_долгого(когда)
    else:
        код, строка = вердикт(пара, порог_часов=порог)
    print(f"[срок-входа] {строка}")

    # Второй вопрос, независимый от первого: ДОХОДИТ ли долгий токен до тех,
    # кто зовёт claude. 12.09.2026 сторож молчал именно здесь: файл токена был
    # на месте, а переменной не было ни у cron, ни у работающей сессии.
    угроза = False
    if пара is not None:
        код_срока, _ = вердикт(пара, порог_часов=порог)
        угроза = код_срока != 0
    код2, строка2 = вердикт_применения(доносит(), профили_подключают(),
                                       сессия_на_долгом(), угроза)
    print(f"[применение] {строка2}")
    return max(код, код2)


if __name__ == "__main__":
    sys.exit(main())
