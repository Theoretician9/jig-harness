#!/usr/bin/env python3
"""Длинные подробности уезжают из карты в отдельный файл — кодом, а не вниманием.

Откуда взят. Замер 12.09.2026: `dev-map.yaml` — 259 458 знаков при потолке
282 500, это 92 %. Карта едет в контекст КАЖДОЙ сессии, то есть её объём —
прямой расход на каждом шаге. Архиватор (`arhiv-karty.py`) уносит только
закрытые задачи, а раздувают карту 31 карточка с `summary` длиннее 1 200
знаков — почти все продуктовые в статусе `test`, то есть живые: архиву они не
подлежат, а читать их целиком каждую сессию незачем.

Что делает. У карточки, чей `summary` длиннее потолка, ПОЛНЫЙ текст уезжает в
`docs/dev-map-подробности.yaml` под тем же id, а в карте остаётся начало по
границе предложения и ссылка. Потолок — ДАННЫЕ (`DEVMAP_SUMMARY_MAX` в
harness.conf, умолчание 1200).

Как уезжает: текстом по блокам, как у архиватора, а не через yaml.dump —
карту читают люди, и перезапись сломала бы порядок, комментарии и длинные
строки. И-1 держится тем же приёмом: оба файла пишутся сразу или не пишется
ничего, а число id в карте до и после обязано совпасть (грабля
[[жадный-regex-съел-полфайла]]: жадная замена съела 88 задач, и YAML остался
валидным).

Запуск:
    python3 scripts/propolka-karty.py            # что уехало бы (ничего не меняет)
    python3 scripts/propolka-karty.py --прополоть
    python3 scripts/propolka-karty.py --проверить  # гейт: сверх потолка нет
    python3 scripts/propolka-karty.py --selftest
"""
from __future__ import annotations

import os
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
КАРТА = КОРЕНЬ / "dev-map.yaml"
ПОДРОБНОСТИ = КОРЕНЬ / "docs" / "dev-map-подробности.yaml"
ССЫЛКА = "Подробности: docs/dev-map-подробности.yaml"

# Отступ — КЛАССОМ [ \t], а не \s (он включает перевод строки): иначе у
# карточки с пустой строкой перед ней отступ на единицу больше, и границы
# блоков разъезжаются — 12.09.2026 так архиватор унёс одиннадцать чужих задач.
НАЧАЛО = re.compile(r"^([ \t]+)- id:\s*(\S+)\s*$", re.M)
СТРОКА_SUMMARY = re.compile(r'^(\s*)summary:\s*"(.*)"\s*$')


def потолок() -> int:
    """DEVMAP_SUMMARY_MAX из harness.conf — данные, не код."""
    путь = os.environ.get("HARNESS_CONF", "/etc/harness/harness.conf")
    try:
        for строка in Path(путь).read_text(encoding="utf-8").splitlines():
            m = re.match(r"\s*DEVMAP_SUMMARY_MAX\s*=\s*\"?(\d+)\"?", строка)
            if m:
                return int(m.group(1))
    except OSError:
        pass
    return 1200


def карточки(текст: str) -> list[tuple[str, int, int]]:
    """[(id, начало блока, конец блока)] — только ЛИСТЬЯ дерева карты.

    Границы блока как у архиватора. Веха (`- id: m1`) тоже подходит под шаблон
    и её блок содержит все свои задачи — первый же `summary:` внутри принадлежал
    бы чужой карточке. Лист — блок, внутри которого других `- id:` нет.
    """
    итог = []
    совпадения = list(НАЧАЛО.finditer(текст))
    for i, совпало in enumerate(совпадения):
        отступ = len(совпало.group(1))
        конец = len(текст)
        for следующее in совпадения[i + 1:]:
            if len(следующее.group(1)) <= отступ:
                конец = следующее.start()
                break
        вложенные = [с for с in совпадения[i + 1:] if с.start() < конец]
        if вложенные:
            continue
        итог.append((совпало.group(2), совпало.start(), конец))
    return итог


def строка_summary(блок: str) -> tuple[int, str, str] | None:
    """(номер строки в блоке, отступ, текст summary) — summary САМОЙ карточки.

    Внутри блока `summary:` встречается ещё и в пунктах чек-листа (там он в
    фигурных скобках, с другим отступом): берём первую строку, целиком
    состоящую из `summary: "…"`, — у пункта чек-листа она частью словаря.
    """
    for номер, строка in enumerate(блок.splitlines()):
        совпало = СТРОКА_SUMMARY.match(строка)
        if совпало:
            return номер, совпало.group(1), совпало.group(2)
    return None


def обрезать(текст: str, предел: int) -> str:
    """Начало текста по границе предложения, не длиннее предела.

    Резать посреди слова нельзя: summary читают люди. Если точки в пределе нет
    вовсе — режем по границе слова, а не по знаку.
    """
    запас = предел - len(ССЫЛКА) - 2
    голова = текст[:запас]
    точка = max(голова.rfind(". "), голова.rfind("! "), голова.rfind("? "))
    if точка > запас // 2:
        return голова[:точка + 1]
    пробел = голова.rfind(" ")
    return (голова[:пробел] if пробел > 0 else голова) + "…"


def находки(текст: str, предел: int) -> list[tuple[str, int]]:
    """[(id, длина summary)] у карточек, чей summary длиннее предела."""
    итог = []
    for id_, начало, конец in карточки(текст):
        найдено = строка_summary(текст[начало:конец])
        if найдено and len(найдено[2]) > предел:
            итог.append((id_, len(найдено[2])))
    return итог


def прополоть(текст: str, предел: int) -> tuple[str, dict[str, str]]:
    """(новая карта, {id: полный summary}) — перенос без потери карточек.

    Один проход по ИСХОДНОМУ тексту: границы карточек посчитаны по нему, и
    склейка идёт кусками между ними. Замена «на месте» с пересчётом смещений —
    тот самый способ, которым правка уезжает в чужой блок.
    """
    вынесено: dict[str, str] = {}
    куски: list[str] = []
    прошлое = 0
    for id_, начало, конец in карточки(текст):
        найдено = строка_summary(текст[начало:конец])
        if not найдено or len(найдено[2]) <= предел:
            continue
        номер, отступ, полный = найдено
        строки = текст[начало:конец].splitlines(keepends=True)
        строки[номер] = f'{отступ}summary: "{обрезать(полный, предел)} {ССЫЛКА}"\n'
        куски.append(текст[прошлое:начало])
        куски.append("".join(строки))
        прошлое = конец
        вынесено[id_] = полный
    куски.append(текст[прошлое:])
    return "".join(куски), вынесено


def записать_подробности(вынесено: dict[str, str]) -> str:
    """Файл подробностей: id → полный текст, дописывается, не перезаписывается."""
    было = {}
    if ПОДРОБНОСТИ.exists():
        import yaml
        было = yaml.safe_load(ПОДРОБНОСТИ.read_text(encoding="utf-8")) or {}
    было.update(вынесено)
    строки = ["# Полные summary карточек, вынесенные из dev-map.yaml.\n",
              "#\n",
              "# Карта едет в контекст каждой сессии, и её объём — расход на каждом шаге.\n",
              "# Здесь лежит то, что нужно при разборе конкретной задачи, а не всегда.\n",
              "# Пишет scripts/propolka-karty.py; руками не править.\n\n"]
    for id_ in sorted(было):
        текст = str(было[id_]).replace("\\\"", "\"")
        строки.append(f"{id_}: |\n")
        for кусок in текст.split("\n"):
            строки.append(f"  {кусок}\n")
        строки.append("\n")
    return "".join(строки)


def самотест() -> int:
    образец = '''milestones:
  - id: m1
    tasks:
      - id: pr.один
        status: test
        summary: "%s"
        checklist:
          - { label: "шаг", done: true, summary: "короткий пункт чек-листа" }
      - id: pr.два
        status: test
        summary: "короткая карточка"
''' % ("Начало текста. " + "х" * 400 + ". Хвост подробностей.")
    ok = True

    def проба(что, было, ждали):
        nonlocal ok
        if было != ждали:
            ok = False
            print(f"  ПЛОХО {что}: ждали «{ждали}», получили «{было}»")
        else:
            print(f"  ок    {что}")

    предел = 200
    проба("БОЛЬНОЙ СЛУЧАЙ: длинная карточка видна, короткая — нет",
          [i for i, _ in находки(образец, предел)], ["pr.один"])
    новый, вынесено = прополоть(образец, предел)
    проба("карточек в карте столько же", len(карточки(новый)), len(карточки(образец)))
    первый = карточки(образец)[0]
    проба("полный текст вынесен целиком, без обрезки",
          вынесено["pr.один"], строка_summary(образец[первый[1]:первый[2]])[2])
    проба("после прополки сверх потолка не осталось", находки(новый, предел), [])
    проба("в карте появилась ссылка на подробности", ССЫЛКА in новый, True)
    проба("короткую карточку не тронули", 'summary: "короткая карточка"' in новый, True)
    проба("summary пункта чек-листа не тронут", "короткий пункт чек-листа" in новый, True)

    import yaml
    try:
        разобрано = yaml.safe_load(новый)
        проба("итог остаётся валидным YAML", isinstance(разобрано, dict), True)
    except yaml.YAMLError as e:
        проба("итог остаётся валидным YAML", f"разбор упал: {e}", True)

    print("САМОТЕСТ %s: 8 путей, первым — больной случай"
          % ("ПРОЙДЕН" if ok else "ПРОВАЛЕН"))
    return 0 if ok else 1


def main() -> int:
    if "--selftest" in sys.argv:
        return самотест()
    предел = потолок()
    текст = КАРТА.read_text(encoding="utf-8")
    длинные = находки(текст, предел)

    if "--проверить" in sys.argv:
        if длинные:
            for id_, длина in длинные:
                print(f"  {id_}: summary {длина} знаков (потолок {предел})")
            print(f"[прополка карты] КРАСНЫЙ: {len(длинные)} карточек сверх потолка — "
                  f"карта едет в контекст каждой сессии. Прополоть: "
                  f"python3 scripts/propolka-karty.py --прополоть")
            return 1
        print(f"[прополка карты] чисто: summary ни одной карточки не длиннее {предел}")
        return 0

    if not длинные:
        print(f"[прополка карты] нечего полоть: потолок {предел}, длиннее нет")
        return 0

    if "--прополоть" not in sys.argv:
        print(f"[прополка карты] уехало бы {len(длинные)} карточек, "
              f"{sum(д - предел for _, д in длинные)} знаков сверх потолка {предел}:")
        for id_, длина in длинные[:10]:
            print(f"  {id_}: {длина}")
        return 0

    новый, вынесено = прополоть(текст, предел)
    было, стало = карточки(текст), карточки(новый)
    if len(было) != len(стало):
        print(f"[прополка карты] ОТКАЗ: карточек было {len(было)}, стало {len(стало)} — "
              f"ничего не записано (И-1)")
        return 1
    import yaml
    try:
        yaml.safe_load(новый)
    except yaml.YAMLError as e:
        print(f"[прополка карты] ОТКАЗ: итог не разбирается как YAML — ничего не записано: {e}")
        return 1

    ПОДРОБНОСТИ.parent.mkdir(parents=True, exist_ok=True)
    ПОДРОБНОСТИ.write_text(записать_подробности(вынесено), encoding="utf-8")
    КАРТА.write_text(новый, encoding="utf-8")
    print(f"[прополка карты] вынесено карточек: {len(вынесено)}; "
          f"карта {len(текст)} → {len(новый)} знаков")
    return 0


if __name__ == "__main__":
    sys.exit(main())
