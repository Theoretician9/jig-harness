#!/usr/bin/env python3
"""Проверка включателя шагов пайплайна: что он меняет и чего не ломает.

Владелец 11.09.2026: «Нужно показать пайплайн, и иметь возможность им управлять
- включать выключать обязательные поля».

Пульт пайплайна — файл, который читают ЛЮДИ: в нём комментарии с уликами,
ради которых каждый порог выбран. Поэтому правка идёт по строке, а не
пересохранением YAML: `yaml.safe_dump` вернул бы валидный файл без единого
комментария, и следующий читатель не узнал бы, почему там эти числа.

Прогон:
    python3 scripts/test_zapisat_shag.py
"""
import os
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

КОРЕНЬ = Path(__file__).resolve().parent.parent
СКРИПТ = КОРЕНЬ / "scripts" / "zapisat-shag.py"

ПУЛЬТ = """# Пульт владельца: чему код заставляет модель следовать.
веса:
  миграция: 5            # необратимое изменение данных — И-1

# Имена шагов: спека · ревью_спеки · контракт · план · ревью_кода · тесты.
шаги:
  мелкая: []
  обычная: [тесты]
  крупная: [спека, ревью_спеки, контракт, тесты]

шаги_включены:
  крупная: {}
  мелкая: {}
  обычная: {}

строгость:
  подъём_после_истинных: 10
"""

путей = 0
неудач = 0


def путь_ок(текст):
    global путей
    путей += 1
    print("ок  · " + текст)


def путь_плохо(текст):
    global путей, неудач
    путей += 1
    неудач += 1
    print("ПЛОХО · " + текст)


def запуск(врем: Path, *доводы):
    среда = dict(os.environ, HARNESS_PAJPLAJN=str(врем / "пайплайн.yaml"),
                 LOG_DIR=str(врем / "логи"))
    готово = subprocess.run([sys.executable, str(СКРИПТ), *доводы],
                            capture_output=True, text=True, env=среда, timeout=30)
    return готово.returncode, (готово.stdout + готово.stderr).strip()


with tempfile.TemporaryDirectory() as tmp:
    врем = Path(tmp)
    (врем / "логи").mkdir()
    пульт = врем / "пайплайн.yaml"
    пульт.write_text(ПУЛЬТ, encoding="utf-8")

    if not СКРИПТ.exists():
        путь_плохо(f"включателя шагов нет: {СКРИПТ}")
    else:
        путь_ок("включатель шагов на месте")

    # Выключить шаг у уровня.
    код, вывод = запуск(врем, "крупная", "контракт", "выключить")
    данные = yaml.safe_load(пульт.read_text(encoding="utf-8"))
    if код == 0 and "контракт" not in данные["шаги"]["крупная"]:
        путь_ок("шаг выключается у своего уровня")
    else:
        путь_плохо(f"шаг не выключился: код {код} · {вывод[:140]}")

    # Комментарии пульта обязаны пережить правку: их читают люди.
    текст = пульт.read_text(encoding="utf-8")
    if "# Пульт владельца" in текст and "# необратимое изменение данных — И-1" in текст \
            and "# Имена шагов" in текст:
        путь_ок("комментарии пульта целы после правки")
    else:
        путь_плохо("комментарии пульта потерялись — пульт читают люди")

    # БОЛЬНОЙ СЛУЧАЙ 11.09.2026: «\s*$» съедал перевод строки и пустую строку
    # за ним — пульт тихо склеивался, и это заметила лишь сверка с пакетом.
    if пульт.read_text(encoding="utf-8").count("\n\n") == ПУЛЬТ.count("\n\n"):
        путь_ок("БОЛЬНОЙ СЛУЧАЙ: пустые строки пульта на месте")
    else:
        путь_плохо("правка съела пустые строки — разделы пульта склеились")

    # Соседние уровни не тронуты.
    if данные["шаги"]["обычная"] == ["тесты"] and данные["шаги"]["мелкая"] == []:
        путь_ок("соседние уровни не тронуты")
    else:
        путь_плохо(f"задеты соседние уровни: {данные['шаги']}")

    # Включить обратно.
    код, вывод = запуск(врем, "крупная", "контракт", "включить")
    данные = yaml.safe_load(пульт.read_text(encoding="utf-8"))
    if код == 0 and "контракт" in данные["шаги"]["крупная"]:
        путь_ок("шаг включается обратно")
    else:
        путь_плохо(f"шаг не включился: код {код} · {вывод[:140]}")

    # Повторное включение не плодит дублей.
    запуск(врем, "крупная", "контракт", "включить")
    данные = yaml.safe_load(пульт.read_text(encoding="utf-8"))
    if данные["шаги"]["крупная"].count("контракт") == 1:
        путь_ок("повторное включение не плодит дублей")
    else:
        путь_плохо(f"дубль шага: {данные['шаги']['крупная']}")

    # Выдуманный шаг и выдуманный уровень.
    было = пульт.read_text(encoding="utf-8")
    код, _ = запуск(врем, "крупная", "выдуманный_шаг", "включить")
    if код != 0 and пульт.read_text(encoding="utf-8") == было:
        путь_ок("БОЛЬНОЙ СЛУЧАЙ: выдуманный шаг отвергнут, файл не тронут")
    else:
        путь_плохо("выдуманный шаг записан в пульт")

    код, _ = запуск(врем, "выдуманный_уровень", "тесты", "включить")
    if код != 0 and пульт.read_text(encoding="utf-8") == было:
        путь_ок("БОЛЬНОЙ СЛУЧАЙ: выдуманный уровень отвергнут")
    else:
        путь_плохо("выдуманный уровень записан в пульт")

    # Копия прежнего пульта — до записи (И-1).
    копии = list((врем / "логи" / "панель-копии").glob("пайплайн.yaml.*"))
    if копии:
        путь_ок("копия прежнего пульта снята до записи")
    else:
        путь_плохо("копии пульта нет")

    # Дата включения шага: без неё правило действует задним числом и красит
    # задачи, начатые раньше (вопрос владельца 11.09.2026).
    import datetime
    запуск(врем, "обычная", "план", "включить")
    данные = yaml.safe_load(пульт.read_text(encoding="utf-8"))
    дата = ((данные.get("шаги_включены") or {}).get("обычная") or {}).get("план")
    сегодня = datetime.date.today().isoformat()
    if дата == сегодня:
        путь_ок(f"включение шага записало дату ({дата})")
    else:
        путь_плохо(f"даты включения нет: {данные.get('шаги_включены')}")

    запуск(врем, "обычная", "план", "выключить")
    данные = yaml.safe_load(пульт.read_text(encoding="utf-8"))
    осталось = ((данные.get("шаги_включены") or {}).get("обычная") or {})
    if "план" not in осталось:
        путь_ок("выключение шага убирает и его дату")
    else:
        путь_плохо(f"дата пережила выключение шага: {осталось}")

    # Повторное включение НЕ сдвигает дату вперёд: иначе любое переключение
    # туда-обратно снимало бы правило с уже идущих задач.
    запуск(врем, "обычная", "план", "включить")
    текст = пульт.read_text(encoding="utf-8").replace(f'план: "{сегодня}"', 'план: "2026-01-01"')
    пульт.write_text(текст, encoding="utf-8")
    запуск(врем, "обычная", "план", "включить")
    данные = yaml.safe_load(пульт.read_text(encoding="utf-8"))
    if данные["шаги_включены"]["обычная"]["план"] == "2026-01-01":
        путь_ок("БОЛЬНОЙ СЛУЧАЙ: повторное включение не сдвигает дату")
    else:
        путь_плохо(f"дата сдвинулась: {данные['шаги_включены']['обычная']}")

print(f"ВКЛЮЧАТЕЛЬ-ШАГОВ: путей {путей}, неудач {неудач}")
sys.exit(1 if неудач else 0)
