#!/usr/bin/env python3
"""Проверка правки памяти с панели: что можно записать и куда нельзя.

Владелец 11.09.2026: «Нужна возможность работать с памятью - вытащить показ и
редактирование файлов памяти и сделать те что будут по умолчанию после
установки».

Память — часть репозитория, а не база: её правки должны выглядеть как обычные
правки файлов. Опасность ровно одна и она понятна: имя файла приходит из
браузера. Поэтому здесь проверяется не «сохранилось ли», а «куда НЕ сохранилось»
— выход за каталог, чужое расширение, пустое имя.

Прогон:
    python3 scripts/test_zapisat_pamyat.py
"""
import os
import subprocess
import sys
import tempfile
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
СКРИПТ = КОРЕНЬ / "scripts" / "zapisat-pamyat.py"

путей = 0
неудач = 0


def путь_ок(текст):
    global путей
    путей += 1
    print("ок  · " + текст)


def путь_плохо(текст):
    global путей, неудач
    путей += 1
    неудач += 1
    print("ПЛОХО · " + текст)


def запуск(врем: Path, имя: str, текст: str):
    среда = dict(os.environ, HARNESS_PAMYAT=str(врем / "память"),
                 LOG_DIR=str(врем / "логи"))
    готово = subprocess.run([sys.executable, str(СКРИПТ), имя],
                            input=текст, capture_output=True, text=True,
                            env=среда, timeout=30)
    return готово.returncode, (готово.stdout + готово.stderr).strip()


ЗАПИСЬ = """---
name: проба-записи
description: проба
metadata:
  type: project
---

Тело записи.
"""

with tempfile.TemporaryDirectory() as tmp:
    врем = Path(tmp)
    (врем / "память").mkdir()
    (врем / "логи").mkdir()
    (врем / "память" / "уже-есть.md").write_text("старое\n", encoding="utf-8")
    чужой = врем / "чужой.md"
    чужой.write_text("не трогать\n", encoding="utf-8")

    if СКРИПТ.exists():
        путь_ок("писатель памяти на месте")
    else:
        путь_плохо(f"писателя памяти нет: {СКРИПТ}")

    код, вывод = запуск(врем, "проба-записи.md", ЗАПИСЬ)
    файл = врем / "память" / "проба-записи.md"
    if код == 0 and файл.exists() and "Тело записи." in файл.read_text(encoding="utf-8"):
        путь_ок("новая запись памяти создаётся")
    else:
        путь_плохо(f"новая запись не создана: код {код} · {вывод[:140]}")

    код, _ = запуск(врем, "уже-есть.md", "новое содержимое\n")
    if код == 0 and (врем / "память" / "уже-есть.md").read_text(
            encoding="utf-8") == "новое содержимое\n":
        путь_ок("существующая запись переписывается")
    else:
        путь_плохо("существующая запись не переписалась")

    # Копия прежнего текста — до перезаписи (И-1): написанное владельцем не
    # исчезает от одной неудачной правки.
    копии = list((врем / "логи" / "панель-копии").glob("уже-есть.md.*"))
    if копии and копии[0].read_text(encoding="utf-8") == "старое\n":
        путь_ок("копия прежней записи снята до перезаписи")
    else:
        путь_плохо(f"копии прежней записи нет: {копии}")

    ОПАСНЫЕ = [
        ("../чужой.md", "выход за каталог памяти"),
        ("/etc/passwd", "абсолютный путь"),
        ("память/../../etc/hosts", "путь с подъёмом"),
        ("запись.py", "чужое расширение — память это .md"),
        ("", "пустое имя"),
        (".md", "имя из одного расширения"),
        ("запись.md.sh", "двойное расширение"),
    ]
    for имя, почему in ОПАСНЫЕ:
        было = чужой.read_text(encoding="utf-8")
        код, вывод = запуск(врем, имя, "взлом\n")
        if код != 0 and чужой.read_text(encoding="utf-8") == было:
            путь_ок(f"БОЛЬНОЙ СЛУЧАЙ: «{имя}» отвергнут · {почему}")
        else:
            путь_плохо(f"«{имя}» принят: код {код} · {почему} · {вывод[:100]}")

    # Пустое содержимое — не правка, а потеря: запись стёрлась бы молча.
    код, _ = запуск(врем, "уже-есть.md", "   \n")
    if код != 0:
        путь_ок("БОЛЬНОЙ СЛУЧАЙ: пустой текст записи отвергнут")
    else:
        путь_плохо("пустой текст стёр запись")

print(f"ПИСАТЕЛЬ-ПАМЯТИ: путей {путей}, неудач {неудач}")
sys.exit(1 if неудач else 0)
