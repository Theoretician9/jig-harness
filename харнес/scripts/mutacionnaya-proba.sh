#!/usr/bin/env bash
#
# mutacionnaya-proba.sh — проверка самих проверок: портим одну строку в КОПИИ
# механизма и требуем, чтобы его самотест покраснел.
#
# Зачем. «Самотест зелёный» доказывает, что код согласован с собственным
# тестом, написанным тем же автором. Оно не доказывает, что тест ловит
# нарушение. Замечание владельца 10.09.2026 (М-2 к ревизии харнеса): ни одна
# проверка ревизии не подсовывала сломанный вход и не показывала красное.
#
# Улика, ради которой инструмент и остался: первая же проба нашла дыру —
# у sentinel пороги приходили в проверяемую функцию АРГУМЕНТАМИ, и мутация
# «WARDEN_STUCK_MIN=999999» оставила самотест зелёным. Сигнал с невозможным
# порогом не сигнал, а самотест этого не видел.
#
# Каждая строка таблицы: файл | выражение sed | команда самотеста | имя случая.
# Команда самотеста задаётся ЯВНО: у guard_bash проверка лежит в отдельном
# файле, и запуск «сам себя с --selftest» покраснел бы от синтаксической
# ошибки, а не от пойманной мутации — ложное доказательство хуже никакого.
#
# Запуск: bash scripts/mutacionnaya-proba.sh (входит в ворота --всё).
set -uo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.." || exit 1
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
OK=0; BAD=0

# Копия механизма проверяется ЕГО ЖЕ доказательством из инвариантов.yaml: путь
# оригинала в команде подменяется путём копии. Где тест берёт файл не из
# аргументов, а из окружения (guard_bash), имя переменной названо в данных
# полем «мутация_подмена» — запуск «сам себя с --selftest» покраснел бы от
# синтаксической ошибки, а не от пойманной мутации, и это ложное доказательство.
#
# Команда разбирается в МАССИВ слов, без eval: первая редакция звала
# eval "${runner//%s/$copy}", и путь с пробелом (TMPDIR) рвался по словам —
# bash отвечал rc=127, а проба печатала «ок, мутация поймана». Пять строк «ок»
# при нулевой проверке — ровно та ложная зелень, ради которой инструмент и
# написан (ревью 10.09.2026).
прогнать() { # $1=команда доказательства (с путём копии) $2=подмена или «-» $3=копия
    local -a words; read -ra words <<< "$1"
    # «Нет подмены» разбирается ЗДЕСЬ, а не у читателя данных: иначе всякий
    # другой вызывающий (самотест) обязан помнить про прочерк — и не помнит.
    local subst="$2"; [ "$subst" = "-" ] && subst=""
    if [ -n "$subst" ]; then
        env "$subst=$3" "${words[@]}" >/dev/null 2>&1
    else
        "${words[@]}" >/dev/null 2>&1
    fi
}

# Копия механизма обязана лежать СРЕДИ СОСЕДЕЙ. Скрипты харнеса сорсят общий
# загрузчик по своему пути (scripts/lib/konf.sh), и одинокая копия в /tmp
# падает на строке source ещё до самотеста: 12.09.2026 пять проверок из
# восемнадцати отвечали «чистая копия уже красная» и не доказывали ничего.
# Копируется КОРНЕВОЙ каталог проверяемого файла — списка каталогов нет.
корень_в_копию() { # $1 = первый сегмент пути (scripts, харнес…)
    [ -e "$TMP/дерево/$1" ] && return 0
    mkdir -p "$TMP/дерево"
    cp -a "$1" "$TMP/дерево/$1"
}

проба() { # $1=файл $2=выражение sed $3=доказательство $4=подмена $5=имя случая
    local src="$1" expr="$2" proof="$3" subst="$4" name="$5"
    local copy
    case "$src" in
        /*) copy="$TMP/$(basename "$src")" ;;   # одинокий файл стенда
        *)  корень_в_копию "${src%%/*}" || { printf '  ПЛОХО не скопировать окружение: %s\n' "$name"; BAD=$((BAD+1)); return; }
            copy="$TMP/дерево/$src" ;;
    esac
    mkdir -p "$(dirname "$copy")"
    cp "$src" "$copy"
    local cmd="${proof//$src/$copy}"
    if [ "$cmd" = "$proof" ] && [ -z "$subst" ]; then
        printf '  ПЛОХО мутацию некуда подставить (в доказательстве нет пути и нет подмены): %s\n' "$name"
        BAD=$((BAD+1)); return
    fi
    # Чистая копия ОБЯЗАНА быть зелёной: без этого «красное» ничего не доказывает —
    # оно могло прийти от сломанного окружения, а не от пойманной мутации.
    if ! прогнать "$cmd" "$subst" "$copy"; then
        printf '  ПЛОХО чистая копия уже красная — проверка ничего не доказывает: %s\n' "$name"
        BAD=$((BAD+1)); return
    fi
    sed -i "$expr" "$copy"
    if cmp -s "$src" "$copy"; then
        printf '  ПЛОХО мутация не изменила файл: %s\n' "$name"; BAD=$((BAD+1)); return
    fi
    if прогнать "$cmd" "$subst" "$copy"; then
        printf '  ПЛОХО самотест ЗЕЛЁН на испорченном коде: %s\n' "$name"; BAD=$((BAD+1))
    else
        printf '  ок    чистая копия зелёная, мутация поймана: %s\n' "$name"; OK=$((OK+1))
    fi
}

# ── Самотест самой пробы ────────────────────────────────────────────────────
# Инструмент, проверяющий чужие проверки, обязан проверяться сам, и не собой же
# на боевых данных: «покраснели 18, дыр 0» доказывает механизмы, а не пробу.
# Стенд — два игрушечных «механизма»: у одного самотест зрячий, у другого
# слепой. Проба обязана похвалить первого и назвать дырой второго.
if [ "${1:-}" = "--selftest" ]; then
    STAND=$(mktemp -d); trap 'rm -rf "$TMP" "$STAND"' EXIT
    seeing="$STAND/зрячий.sh"
    cat > "$seeing" <<'МЕХ'
#!/usr/bin/env bash
PRIZNAK=1
[ "${1:-}" = "--selftest" ] || exit 0
[ "$PRIZNAK" = 1 ] && { echo "SELFTEST: зелёный"; exit 0; }
echo "SELFTEST: КРАСНЫЙ"; exit 1
МЕХ
    blind="$STAND/слепой.sh"
    cat > "$blind" <<'МЕХ'
#!/usr/bin/env bash
PRIZNAK=1
[ "${1:-}" = "--selftest" ] || exit 0
echo "SELFTEST: зелёный"; exit 0
МЕХ
    broken="$STAND/сломанный.sh"
    cat > "$broken" <<'МЕХ'
#!/usr/bin/env bash
PRIZNAK=1
exit 1
МЕХ
    expect() { # $1=имя случая $2=ждём OK $3=ждём BAD $4..=аргументы пробы
        local name="$1" want_ok="$2" want_bad="$3"; shift 3
        OK=0; BAD=0
        проба "$@" >/dev/null 2>&1
        if [ "$OK" = "$want_ok" ] && [ "$BAD" = "$want_bad" ]; then
            printf '  ок    %s\n' "$name"
        else
            printf '  ПЛОХО %s: ждали ок=%s дыр=%s, вышло ок=%s дыр=%s\n' \
                "$name" "$want_ok" "$want_bad" "$OK" "$BAD"
            SELF_BAD=1
        fi
    }
    SELF_BAD=0
    # БОЛЬНОЙ СЛУЧАЙ, ради которого проба и существует: самотест не замечает
    # порчу и остаётся зелёным. Это дыра, и назвать её обязана проба.
    expect "БОЛЬНОЙ СЛУЧАЙ: слепой самотест назван дырой" 0 1 \
        "$blind" "s/^PRIZNAK=1/ПРИЗНАК=0/" "bash $blind --selftest" "-" "слепой"
    expect "зрячий самотест засчитан пойманной мутацией" 1 0 \
        "$seeing" "s/^PRIZNAK=1/ПРИЗНАК=0/" "bash $seeing --selftest" "-" "зрячий"
    expect "чистая копия уже красная — доказывать нечем" 0 1 \
        "$broken" "s/^PRIZNAK=1/ПРИЗНАК=0/" "bash $broken --selftest" "-" "красная копия"
    expect "мутация не изменила файл — это промах данных, а не успех" 0 1 \
        "$seeing" "s/^НЕТ-ТАКОЙ-СТРОКИ/x/" "bash $seeing --selftest" "-" "мимо"
    expect "мутацию некуда подставить — отказ, а не тишина" 0 1 \
        "$seeing" "s/^PRIZNAK=1/ПРИЗНАК=0/" "bash чужой-файл.sh --selftest" "-" "без подстановки"

    # БОЛЬНОЙ СЛУЧАЙ 12.09.2026: механизм читает СОСЕДА по своему пути. Пока
    # копия была одинокой, такой механизм краснел на чистой копии, и проба
    # молча теряла его — ровно так выпали пять боевых проверок из восемнадцати.
    mkdir -p "$STAND/scripts/lib"
    printf 'OBSHEE=1\n' > "$STAND/scripts/lib/общий.sh"
    cat > "$STAND/scripts/зависимый.sh" <<'МЕХ'
#!/usr/bin/env bash
source "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/lib/общий.sh"
PRIZNAK=1
[ "${1:-}" = "--selftest" ] || exit 0
[ "$PRIZNAK" = 1 ] && [ "$OBSHEE" = 1 ] && { echo "SELFTEST: зелёный"; exit 0; }
echo "SELFTEST: КРАСНЫЙ"; exit 1
МЕХ
    # cd без подоболочки: в ( … ) флаг SELF_BAD остался бы у потомка, и
    # проваленная проба не покрасила бы самотест (тот же класс, что чинили
    # сегодня в pre-commit).
    PREZHNIJ="$PWD"
    cd "$STAND" || exit 1
    expect "механизм с соседом: копия несёт окружение" 1 0 \
        "scripts/зависимый.sh" "s/^PRIZNAK=1/ПРИЗНАК=0/" \
        "bash scripts/зависимый.sh --selftest" "-" "с соседом"
    cd "$PREZHNIJ" || exit 1
    if [ "$SELF_BAD" = 0 ]; then
        echo "SELFTEST: зелёный (6 путей, первым — больной случай «самотест слеп»)"
        exit 0
    fi
    echo "SELFTEST: КРАСНЫЙ"; exit 1
fi

# Таблица мутаций — в харнес/config/инварианты.yaml рядом с самими правилами
# (ревью 10.09.2026, q-18): вшитая в скрипт, она не отвечала на главный вопрос
# «какие механизмы мутацией ещё НЕ проверены». Теперь непокрытые названы.
# Имена ЛАТИНИЦЕЙ: `read -r файл` — не идентификатор, bash отвечает ошибкой на
# каждой строке, и проба выходила «0 поймано, 0 дыр» с кодом 0 — зелёная, не
# проверив ничего (поймано прогоном 10.09.2026).
# Пустое поле в середине строки НЕ доживает до read: табуляция — пробельный
# разделитель, и два подряд схлопываются в один, сдвигая имя случая в подмену
# (отчёт печатал «мутация поймана: » без имени). Отсутствие подмены называется
# прочерком — признаком, а не пустотой.
while IFS=$'\t' read -r src expr proof subst name; do
    [ -n "$src" ] || continue
    # Первой строкой идут КОРНИ всех проверяемых файлов: копия механизма
    # должна видеть не только своих соседей, но и чужие каталоги — демон
    # харнес/demons/*.sh сорсит ../../scripts/lib/konf.sh, и без второго
    # корня копия падает на строке source (12.09.2026).
    if [ "$src" = "#КОРНИ" ]; then
        for koren in $expr; do корень_в_копию "$koren"; done
        continue
    fi
    проба "$src" "$expr" "$proof" "$subst" "$name"
done < <(python3 - <<'PYEOF'
import io, sys, yaml
d = yaml.safe_load(io.open("харнес/config/инварианты.yaml", encoding="utf-8"))["инварианты"]
корни = {и["файл"].split("/")[0] for и in d if и.get("мутация")}
sys.stdout.write("\t".join(["#КОРНИ", " ".join(sorted(корни)), "-", "-", "-"]) + "\n")
без = []
for и in d:
    if и.get("мутация"):
        # Доказательство инварианта бывает тяжёлым (поднимает базу) или живым
        # (прогон по боевым логам, зелёный всегда). Тогда мутацию проверяет
        # названный в данных лёгкий самотест — иначе механизм остаётся вовсе
        # без мутации, а это худший исход (10.09.2026).
        sys.stdout.write("\t".join([и["файл"], и["мутация"],
                                    и.get("мутация_доказательство") or и["доказательство"],
                                    и.get("мутация_подмена") or "-",
                                    f"{и['id']}: {и['мутация_случай']}"]) + "\n")
    elif и.get("доказательство"):
        без.append(и["id"])
sys.stderr.write(f"  без мутации ({len(без)}): {', '.join(без)}\n")
PYEOF
)

# Ноль прогнанных мутаций — не успех, а отказ: так выглядит и пустая таблица,
# и сорванное чтение данных (10.09.2026 кириллица в именах read сорвала цикл,
# и проба отчиталась зелёным, не проверив ни одного механизма).
if [ "$((OK + BAD))" -eq 0 ]; then
    echo "$(date '+%Y-%m-%d %H:%M:%S')  === мутационная проба: НИ ОДНОЙ мутации не прогнано — таблица пуста или данные не прочитались ==="
    exit 1
fi
echo "$(date '+%Y-%m-%d %H:%M:%S')  === мутационная проба: покраснели как надо $OK, дыр $BAD ==="
exit "$BAD"
