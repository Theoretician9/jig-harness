def применить(вердикты: list[dict], путь: Path) -> tuple[int, int]:
    """Записать исходы в карту. Правится РОВНО две вещи: статус и дата приёмки.

    Правка текстом, а не перезаписью через yaml: карта — файл, который читают
    люди, и `yaml.dump` переставил бы в ней всё, потеряв порядок, комментарии и
    длинные строки. Заодно это ограничивает власть механизма: он умеет только
    то, что умеет его регулярное выражение.
    """
    import re
    from datetime import date
    текст = путь.read_text(encoding="utf-8")
    принято = сегодня = date.today().isoformat()
    закрыто = вернулось = 0
    for в in вердикты:
        ид = re.escape(в["id"])
        if в["исход"] == "доказано":
            # Поле даты вставляется ТОЛЬКО если его ещё нет. Иначе задача,
            # возвращённая в работу и принятая повторно, получает два
            # `принято_когда`, а YAML берёт последний — то есть прежнюю,
            # неверную дату (известные грабли [[дубль-ключа-yaml-молчит]],
            # находка I3 ревью кода 11.09.2026).
            уже_есть = re.search(
                rf"- id: {ид}\n(?:\s+\w+:.*\n)*?\s+принято_когда:", текст)
            новый = "принято"
            поле = "" if уже_есть else f'\n        принято_когда: "{принято}"'
        elif в["исход"] == "провал":
            # Провал НЕ меняет статус: `task-closer` переводит `wip` старше
            # 48 часов в `plan` с причиной «висела без живого процесса агента»
            # — для задачи, только что возвращённой машиной, это ложь, а 67
            # задач без when.started он не увидит вовсе (находка C4 ревью).
            # Статус — дело разработчика; проверяющий называет провал в самой
            # карточке, чтобы разработчик увидел его вместе с задачей, а не
            # только в отчёте за ту ночь (находка I2 ревью кода).
            строка = (str(в.get("почему", ""))[:120]
                      .replace('"', "'").replace("\n", " "))
            поле_провала = f'\n        провал_проверки: "{сегодня}: {строка}"'
            обр = re.compile(
                rf"(- id: {ид}\n(?:\s+\w+:.*\n)*?\s+status: test)"
                rf"(?!\n\s+провал_проверки)")
            новый_текст, сколько = обр.subn(rf"\g<1>{поле_провала}", текст, count=1)
            if сколько:
                текст = новый_текст
                вернулось += 1
            continue
        else:
            continue
        обр = re.compile(rf"(- id: {ид}\n(?:\s+\w+:.*\n)*?\s+status: )test")
        новый_текст, сколько = обр.subn(rf"\g<1>{новый}{поле}", текст, count=1)
        if сколько:
            # Сырой id, не экранированный: снять_провал экранирует сама.
            текст = снять_провал(новый_текст, в["id"])
            закрыто += в["исход"] == "доказано"
            вернулось += в["исход"] == "провал"
    путь.write_text(текст, encoding="utf-8")
    return закрыто, вернулось


def снять_провал(текст: str, ид: str) -> str:
    """Убрать пометку провала у задачи, которая доказана.

    Улика 12.09.2026: задача `ev.срок-входа-сторож-11-09` провалила проверку,
    была починена, приёмка её доказала — а поле `провал_проверки` осталось в
    карточке. Прибор очереди ставит провал вторым по важности признаком, и
    доказанная задача висела бы первой строкой «что делать сейчас» вечно.
    Та же грабля, что «пометка снятия не снимается сама»: у пометки обязан
    быть тот, кто её снимает.
    """
    обр = re.compile(rf"(- id: {re.escape(ид)}\n(?:\s+\w+:.*\n)*?)"
                     rf"\s+провал_проверки:.*\n")
    return обр.sub(r"\g<1>", текст, count=1)


