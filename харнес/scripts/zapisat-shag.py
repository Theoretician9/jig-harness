#!/usr/bin/env python3
"""Включатель шагов пайплайна: какой шаг обязателен на каком уровне задачи.

Владелец 11.09.2026: «Нужно показать пайплайн, и иметь возможность им управлять
- включать выключать обязательные поля».

Правка идёт ПО СТРОКЕ, а не пересохранением YAML. Пульт `харнес/config/
пайплайн.yaml` читают люди: в нём комментарии с уликами, ради которых выбран
каждый порог. `yaml.safe_dump` вернул бы валидный файл без единого
комментария — и следующий читатель не узнал бы, почему там эти числа.

Чего здесь нет и не будет: концы пайплайна — ворота перед выкатом и живой
смоук — шагами этого пульта не являются вовсе, поэтому и выключить их отсюда
нельзя. Ими держатся И-2 и И-4.

Прогон:
    zapisat-shag.py <уровень> <шаг> включить|выключить
Код возврата: 0 — записано; 2 — неизвестный уровень или шаг; 4 — копия не
удалась; 5 — пульт не прочитан или после правки перестал разбираться.
"""
import datetime
import json
import os
import re
import sys
from pathlib import Path

import yaml

КОРЕНЬ = Path(__file__).resolve().parent.parent
ПУЛЬТ = Path(os.environ.get("HARNESS_PAJPLAJN")
             or КОРЕНЬ / "харнес" / "config" / "пайплайн.yaml")
LOG_DIR = Path(os.environ.get("LOG_DIR", "/var/log/harness"))
УРОВНИ = ("мелкая", "обычная", "крупная")
ШАГИ = ("спека", "ревью_спеки", "контракт", "план", "ревью_кода", "тесты")


def отказ(код: int, причина: str) -> int:
    print(f"[шаг-пайплайна] отказ: {причина}", file=sys.stderr)
    return код


def строка_уровня(текст: str, уровень: str):
    """(строка пульта, список шагов) для уровня или (None, None)."""
    # Пробелы ТОЛЬКО горизонтальные: «\s*$» в многострочном поиске жадно
    # съедает перевод строки и следующую пустую строку — правка тихо склеивала
    # разделы пульта (поймано сверкой с пакетом 11.09.2026).
    найдено = re.search(rf"^([ \t]*){уровень}:[ \t]*\[([^\]]*)\][ \t]*$",
                        текст, re.MULTILINE)
    if not найдено:
        return None, None
    шаги = [ш.strip() for ш in найдено.group(2).split(",") if ш.strip()]
    return найдено.group(0), шаги


def с_датой_включения(текст: str, уровень: str, шаг: str, действие: str) -> str:
    """Помнит, КОГДА шаг включили: правило судит задачи, начатые после этого.

    Вопрос владельца 11.09.2026 (голосом): «что будет с текущими задачами, когда
    пользователь переключает правила пайплайна?» Без даты включение краснит
    работу, которая была почти закончена, и требует бумаг, которых на её старте
    никто не просил. Повторное включение дату НЕ сдвигает — иначе переключение
    туда-обратно снимало бы правило с уже идущих задач.
    """
    данные = yaml.safe_load(текст) or {}
    включены = данные.get("шаги_включены") or {}
    по_уровню = dict(включены.get(уровень) or {})
    if действие == "включить":
        по_уровню.setdefault(шаг, datetime.date.today().isoformat())
    else:
        по_уровню.pop(шаг, None)
    включены = {**включены, уровень: по_уровню}
    строка = "шаги_включены:\n" + "".join(
        f"  {имя}: {{" + ", ".join(f'{ш}: "{д}"' for ш, д in sorted(даты.items()))
        + "}\n"
        for имя, даты in sorted(включены.items()))
    найдено = re.search(r"^шаги_включены:\n(?:[ \t]+.*\n)*", текст, re.MULTILINE)
    if найдено:
        return текст[:найдено.start()] + строка + текст[найдено.end():]
    return текст.rstrip("\n") + "\n\n" + ЗАГОЛОВОК_ДАТ + строка


ЗАГОЛОВОК_ДАТ = (
    "# Когда шаг включили. Правило судит задачи, начатые НЕ РАНЬШЕ этой даты:\n"
    "# иначе включение шага краснит работу, которая уже почти закончена\n"
    "# (вопрос владельца 11.09.2026). Пишет scripts/zapisat-shag.py.\n")


def снять_копию(файл: Path) -> Path:
    каталог = LOG_DIR / "панель-копии"
    каталог.mkdir(parents=True, exist_ok=True)
    метка = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
    копия = каталог / f"{файл.name}.{метка}"
    копия.write_bytes(файл.read_bytes())
    return копия


def записать_журнал(уровень: str, шаг: str, действие: str, стало: list) -> None:
    запись = {"ts": datetime.datetime.now().isoformat(timespec="seconds"),
              "уровень": уровень, "шаг": шаг, "действие": действие,
              "стало": стало,
              "кто": os.environ.get("SUDO_USER") or os.environ.get("USER") or "?"}
    try:
        LOG_DIR.mkdir(parents=True, exist_ok=True)
        with open(LOG_DIR / "панель.jsonl", "a", encoding="utf-8") as fh:
            fh.write(json.dumps(запись, ensure_ascii=False) + "\n")
    except OSError as беда:
        print(f"[шаг-пайплайна] журнал не записан: {беда}", file=sys.stderr)


def _вернуть_хозяина(новый_файл: Path, прежний: os.stat_result) -> None:
    """Оставить файлу прежних владельца и группу. Не наш файл — молчим."""
    try:
        os.chown(новый_файл, прежний.st_uid, прежний.st_gid)
    except (PermissionError, OSError):
        pass


def main(argv: list[str]) -> int:
    argv = [а for а in argv if а != "--под-sudo"]
    if len(argv) != 3:
        return отказ(2, "нужно три довода: <уровень> <шаг> включить|выключить")
    уровень, шаг, действие = argv
    if уровень not in УРОВНИ:
        return отказ(2, f"уровень «{уровень}» неизвестен, есть: {', '.join(УРОВНИ)}")
    if шаг not in ШАГИ:
        return отказ(2, f"шаг «{шаг}» неизвестен, есть: {', '.join(ШАГИ)}")
    if действие not in ("включить", "выключить"):
        return отказ(2, "третий довод — «включить» или «выключить»")

    # Пульт принадлежит репозиторию, а служба панели идёт под пользователем без
    # прав. Не можем писать сами — поднимаемся через свою строку sudoers;
    # признак «уже поднимались» едет доводом, потому что sudo сбрасывает
    # окружение (та же грабля, что у писателя ключей).
    if not os.access(ПУЛЬТ, os.W_OK) and "--под-sudo" not in sys.argv:
        import subprocess
        готово = subprocess.run(
            ["sudo", "-n", "/usr/bin/python3", str(Path(__file__).resolve()),
             уровень, шаг, действие, "--под-sudo"],
            capture_output=True, text=True, timeout=60)
        sys.stdout.write(готово.stdout)
        sys.stderr.write(готово.stderr)
        return готово.returncode

    try:
        текст = ПУЛЬТ.read_text(encoding="utf-8")
    except OSError as беда:
        return отказ(5, f"пульт не прочитан: {беда}")

    прежняя, шаги = строка_уровня(текст, уровень)
    if прежняя is None:
        return отказ(5, f"в пульте нет строки уровня «{уровень}»")

    if действие == "включить" and шаг not in шаги:
        шаги = шаги + [шаг]
    elif действие == "выключить":
        шаги = [ш for ш in шаги if ш != шаг]

    отступ = прежняя[:len(прежняя) - len(прежняя.lstrip())]
    новая = f"{отступ}{уровень}: [{', '.join(шаги)}]"

    try:
        копия = снять_копию(ПУЛЬТ)
    except OSError as беда:
        return отказ(4, f"копия пульта не снята: {беда}")

    новый = с_датой_включения(текст.replace(прежняя, новая, 1),
                              уровень, шаг, действие)
    # После правки пульт обязан остаться разборным И содержать ровно то, что
    # мы написали: иначе строка ушла не туда, и лучше вернуть прежний файл.
    try:
        проверка = yaml.safe_load(новый)
        assert проверка["шаги"][уровень] == шаги
    except Exception as беда:                       # noqa: BLE001
        return отказ(5, f"после правки пульт не сходится ({беда}); "
                        f"прежний целиком лежит в {копия}")

    прежний = os.stat(ПУЛЬТ)
    врем = ПУЛЬТ.with_suffix(".yaml.tmp")
    врем.write_text(новый, encoding="utf-8")
    os.chmod(врем, прежний.st_mode & 0o7777)
    # Хозяин файла обязан остаться прежним: запись идёт через sudo, и без этой
    # строки пульт становился root:root — после первого же переключения с
    # панели его не мог править ни агент, ни раскладка пакета (улика 11.09).
    _вернуть_хозяина(врем, прежний)
    os.replace(врем, ПУЛЬТ)
    записать_журнал(уровень, шаг, действие, шаги)
    print(f"[шаг-пайплайна] {уровень}: {действие} «{шаг}» → "
          f"[{', '.join(шаги)}]; копия: {копия}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
