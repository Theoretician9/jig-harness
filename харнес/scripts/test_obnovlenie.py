#!/usr/bin/env python3
"""Проверка обновления харнеса: что оно видит и чего НЕ делает.

Откуда взято. Владелец 11.09.2026: «А как сделать возможность
ручного-автоматического обновления после изменений в гите публичном где это
будет лежать?» Спека `docs/specs/2026-09-11-обновление-из-гита.md`, итерация 2.

Проверять приходится на подставном репозитории, а не на живом: публичный
репозиторий сегодня анонимно не читается (§0 спеки), да и «сегодня зелёно»
у живого дерева ничего не доказывает.

Прогон:
    python3 scripts/test_obnovlenie.py
Код возврата: 0 — все пути прошли, 1 — есть упавший.
"""
import importlib.util
import json
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
путей = неудач = 0


def путь_ок(текст: str) -> None:
    global путей
    путей += 1
    print("ок  · " + текст)


def путь_плохо(текст: str) -> None:
    global путей, неудач
    путей += 1
    неудач += 1
    print("ПЛОХО · " + текст)


спец = importlib.util.spec_from_file_location(
    "обновление", КОРЕНЬ / "scripts" / "obnovlenie.py")
обновление = importlib.util.module_from_spec(спец)
спец.loader.exec_module(обновление)


def гит(*доводы, где=None):
    return subprocess.run(["git", *доводы], cwd=где, capture_output=True,
                          text=True, timeout=30)


def двор() -> tuple:
    """Подставной «публичный репозиторий» и его рабочая копия — наш пакет."""
    врем = Path(tempfile.mkdtemp(prefix="обновление-"))
    удалённый = врем / "публичный.git"
    гит("init", "--bare", "-b", "master", str(удалённый))
    исток = врем / "исток"
    гит("clone", str(удалённый), str(исток))
    гит("config", "user.email", "проба@харнес", где=исток)
    гит("config", "user.name", "проба", где=исток)
    (исток / "харнес").mkdir(parents=True, exist_ok=True)
    (исток / "харнес" / "правило.txt").write_text("первая версия\n", encoding="utf-8")
    гит("add", "-A", где=исток)
    гит("commit", "-m", "первый", где=исток)
    гит("push", "origin", "master", где=исток)
    пакет = врем / "пакет"
    гит("clone", str(удалённый), str(пакет))
    return врем, удалённый, исток, пакет


врем, удалённый, исток, пакет = двор()
os.environ["HARNESS_STARTER"] = str(пакет)
os.environ["HARNESS_VERSION_FILE"] = str(врем / "версия-харнеса")
os.environ["HARNESS_PUBLIC_BRANCH"] = "master"

try:
    print("── версия установки ──")
    if обновление.версия_установки() == {}:
        путь_ок("версии нет — пустой ответ, а не выдумка")
    else:
        путь_плохо(f"версия взялась ниоткуда: {обновление.версия_установки()}")

    ответ = обновление.спросить_обновления()
    if ответ.get("есть новое") is False and ответ.get("коммит"):
        путь_ок(f"свежая копия: нового нет (коммит {ответ['коммит'][:7]})")
    else:
        путь_плохо(f"на свежей копии найдено новое: {ответ}")

    # Запомнили версию — теперь она известна.
    обновление.записать_версию(ответ["коммит"])
    if обновление.версия_установки().get("коммит") == ответ["коммит"]:
        путь_ок("версия установки записана и читается")
    else:
        путь_плохо(f"версия не записалась: {обновление.версия_установки()}")

    print("── появилось новое ──")
    (исток / "харнес" / "правило.txt").write_text("вторая версия\n", encoding="utf-8")
    гит("add", "-A", где=исток)
    гит("commit", "-m", "второй", где=исток)
    гит("push", "origin", "master", где=исток)

    ответ2 = обновление.спросить_обновления()
    if ответ2.get("есть новое") is True and ответ2.get("коммит") != ответ["коммит"]:
        путь_ок(f"новая версия видна: {ответ2['коммит'][:7]}")
    else:
        путь_плохо(f"новое не замечено: {ответ2}")

    print("── сверка НЕ трогает рабочее дерево ──")
    было = (пакет / "харнес" / "правило.txt").read_text(encoding="utf-8")
    обновление.спросить_обновления()
    стало = (пакет / "харнес" / "правило.txt").read_text(encoding="utf-8")
    if было == стало == "первая версия\n":
        путь_ок("после сверки файлы пакета не изменились (fetch, не pull)")
    else:
        путь_плохо(f"сверка изменила дерево: было {было!r}, стало {стало!r}")

    print("── БОЛЬНОЙ СЛУЧАЙ: наш пакет ВПЕРЕДИ публичной ветки ──")
    # Живая улика 11.09.2026: сверка сравнивала коммиты на «не равны» и на
    # рабочей машине (где в пакет коммитят раньше публикации) кричала «есть
    # новая версия», предлагая откатиться назад.
    # Сперва догоняем публичную ветку, иначе истории разошлись бы, а это
    # другой случай (расхождение, а не опережение).
    гит("reset", "--hard", "FETCH_HEAD", где=пакет)
    (пакет / "своё.txt").write_text("правка, ещё не опубликованная\n", encoding="utf-8")
    гит("config", "user.email", "проба@харнес", где=пакет)
    гит("config", "user.name", "проба", где=пакет)
    гит("add", "-A", где=пакет)
    гит("commit", "-m", "местная правка", где=пакет)
    ответ_в = обновление.спросить_обновления()
    if ответ_в.get("есть новое") is False:
        путь_ок("пакет впереди публичной ветки — обновления нет")
    else:
        путь_плохо(f"опережение принято за обновление: {ответ_в}")
    гит("reset", "--hard", "HEAD~1", где=пакет)

    print("── удалённый называется не origin ──")
    гит("remote", "rename", "origin", "harness", где=пакет)
    ответ_и = обновление.спросить_обновления()
    if ответ_и.get("беда") is None and ответ_и.get("коммит"):
        путь_ок("удалённый с другим именем найден сам (живой пакет зовёт его harness)")
    else:
        путь_плохо(f"чужое имя удалённого сломало сверку: {ответ_и}")
    гит("remote", "rename", "harness", "origin", где=пакет)

    print("── БОЛЬНОЙ СЛУЧАЙ: репозитория не достать ──")
    гит("remote", "set-url", "origin", str(врем / "нет-такого.git"), где=пакет)
    ответ3 = обновление.спросить_обновления()
    if ответ3.get("беда") and not ответ3.get("есть новое"):
        путь_ок(f"недоступный репозиторий назван причиной: {ответ3['беда'][:60]}")
    else:
        путь_плохо(f"недоступный репозиторий выглядит как «нового нет»: {ответ3}")

    if обновление.версия_установки().get("коммит") == ответ["коммит"]:
        путь_ок("неудачная сверка не стёрла известную версию")
    else:
        путь_плохо("после неудачной сверки версия потерялась")

    print("── БОЛЬНОЙ СЛУЧАЙ: пакета нет вовсе ──")
    os.environ["HARNESS_STARTER"] = str(врем / "никакого-пакета")
    ответ4 = обновление.спросить_обновления()
    if ответ4.get("беда"):
        путь_ок("отсутствие пакета названо словами, а не пустотой")
    else:
        путь_плохо(f"без пакета ответ не тот: {ответ4}")
    print("── разбор: три исхода по каждому файлу (§1 спеки) ──")
    # Двор заново: нужна чистая история, где видно и обновление, и местную
    # правку, и файл, который трогали обе стороны.
    shutil.rmtree(врем, ignore_errors=True)
    врем, удалённый, исток, пакет = двор()
    os.environ["HARNESS_STARTER"] = str(пакет)
    os.environ["HARNESS_VERSION_FILE"] = str(врем / "версия-харнеса")
    гит("config", "user.email", "проба@харнес", где=пакет)
    гит("config", "user.name", "проба", где=пакет)

    # Исходное состояние: четыре файла в публичной ветке.
    for имя, текст in (("общий.txt", "было\n"), ("чужой.txt", "было\n"),
                       ("спорный.txt", "было\n"), ("уйдёт.txt", "было\n")):
        (исток / "харнес" / имя).write_text(текст, encoding="utf-8")
    гит("add", "-A", где=исток); гит("commit", "-m", "основа", где=исток)
    гит("push", "origin", "master", где=исток)
    гит("pull", "--ff-only", "origin", "master", где=пакет)
    эталон = гит("rev-parse", "HEAD", где=пакет).stdout.strip()

    # Обновление: общий.txt правлен, спорный.txt правлен, уйдёт.txt удалён,
    # новый.txt добавлен.
    (исток / "харнес" / "общий.txt").write_text("стало\n", encoding="utf-8")
    (исток / "харнес" / "спорный.txt").write_text("стало у них\n", encoding="utf-8")
    (исток / "харнес" / "уйдёт.txt").unlink()
    (исток / "харнес" / "новый.txt").write_text("новьё\n", encoding="utf-8")
    гит("add", "-A", где=исток); гит("commit", "-m", "обновление", где=исток)
    гит("push", "origin", "master", где=исток)
    новый_коммит = гит("rev-parse", "HEAD", где=исток).stdout.strip()
    гит("fetch", "origin", "master", где=пакет)

    # Наши правки на машине: чужой.txt и спорный.txt правлены ЗДЕСЬ.
    (пакет / "харнес" / "чужой.txt").write_text("правил владелец\n", encoding="utf-8")
    (пакет / "харнес" / "спорный.txt").write_text("правил владелец\n", encoding="utf-8")

    итог = обновление.разбор(эталон, новый_коммит)
    ждём = {
        "обновить": "харнес/общий.txt",
        "не трогать": "харнес/чужой.txt",
        "расхождения": "харнес/спорный.txt",
        "добавить": "харнес/новый.txt",
        "удалить": "харнес/уйдёт.txt",
    }
    for исход, файл in ждём.items():
        if файл in итог.get(исход, []):
            путь_ок(f"{файл} → «{исход}»")
        else:
            путь_плохо(f"{файл} не попал в «{исход}»: {итог.get(исход)}")

    # Файл, правленный ЗДЕСЬ, не смеет оказаться в «обновить» — это и есть
    # требование владельца «расхождение показывается, а не затирается».
    if "харнес/спорный.txt" not in итог.get("обновить", []):
        путь_ок("БОЛЬНОЙ СЛУЧАЙ: спорный файл не уходит в молчаливое обновление")
    else:
        путь_плохо("спорный файл затёрли бы молча")

    print("── установка: копия, самопроверка, откат (§3 спеки) ──")
    # Обновление в пакете есть (см. выше). Ставим его подставными действиями:
    # раскладка и перезапуск служб здесь не нужны — проверяется ПОРЯДОК и откат.
    следы = []

    def разложить_проба():
        следы.append("раскладка")
        return True

    def перезапуск_проба():
        следы.append("перезапуск")
        return True

    def сказать_проба(текст):
        следы.append(f"сказал: {текст[:40]}")

    os.environ["HARNESS_BACKUP_DIR"] = str(врем / "копии")
    было_в_пакете = гит("rev-parse", "HEAD", где=пакет).stdout.strip()
    итог_у = обновление.поставить(
        разложить=разложить_проба, перезапустить=перезапуск_проба,
        проверить=lambda: (True, "зелёных 33, красных 0"), сказать=сказать_проба)
    стало_в_пакете = гит("rev-parse", "HEAD", где=пакет).stdout.strip()
    if итог_у.get("поставлено") and стало_в_пакете != было_в_пакете:
        путь_ок(f"обновление поставлено: пакет перешёл на {стало_в_пакете[:7]}")
    else:
        путь_плохо(f"обновление не поставилось: {итог_у}")

    if обновление.версия_установки().get("коммит") == стало_в_пакете:
        путь_ок("версия установки записана после успешной постановки")
    else:
        путь_плохо(f"версия не обновилась: {обновление.версия_установки()}")

    копии = list((врем / "копии").glob("обновление-*")) if (врем / "копии").exists() else []
    if копии:
        путь_ок(f"копия снята до установки ({копии[0].name})")
    else:
        путь_плохо("копии перед установкой нет — И-1 нарушен")

    if следы[:2] == ["раскладка", "перезапуск"] or "раскладка" in следы:
        путь_ок(f"порядок действий: {' → '.join(следы[:3])}")
    else:
        путь_плохо(f"порядок действий не тот: {следы}")

    print("── БОЛЬНОЙ СЛУЧАЙ: самопроверка красная → откат ──")
    # Ещё одно обновление в публичной ветке, но проверка обновлённого харнеса
    # краснеет: дерево обязано вернуться, версия — остаться прежней.
    (исток / "харнес" / "общий.txt").write_text("сломанное\n", encoding="utf-8")
    гит("add", "-A", где=исток); гит("commit", "-m", "сломанное", где=исток)
    гит("push", "origin", "master", где=исток)
    версия_до = обновление.версия_установки().get("коммит")
    коммит_до = гит("rev-parse", "HEAD", где=пакет).stdout.strip()
    файлы_до = гит("ls-files", "-s", где=пакет).stdout

    итог_о = обновление.поставить(
        разложить=разложить_проба, перезапустить=перезапуск_проба,
        проверить=lambda: (False, "зелёных 30, красных 3"), сказать=сказать_проба)

    коммит_после = гит("rev-parse", "HEAD", где=пакет).stdout.strip()
    файлы_после = гит("ls-files", "-s", где=пакет).stdout
    if not итог_о.get("поставлено") and коммит_после == коммит_до:
        путь_ок("красная самопроверка → пакет вернулся на прежний коммит")
    else:
        путь_плохо(f"после красной проверки пакет остался на новом: {итог_о}")
    if файлы_после == файлы_до:
        путь_ок("дерево пакета побайтно прежнее после отката")
    else:
        путь_плохо("дерево после отката отличается")
    if обновление.версия_установки().get("коммит") == версия_до:
        путь_ок("версия установки не изменилась при откате")
    else:
        путь_плохо(f"версия уехала при откате: {обновление.версия_установки()}")
    if any("не прошло" in с or "откат" in с.lower() for с in следы):
        путь_ок("владельцу сказано про откат")
    else:
        путь_плохо(f"про откат владельцу не сказали: {следы[-3:]}")

    print("── раскладка пересобирает производные (C1) ──")
    # Документ устройства собирается из реестра; без пересборки гейт
    # устройства краснеет побайтно, и КАЖДОЕ обновление откатывалось бы.
    исходник = pathlib.Path(КОРЕНЬ / "scripts" / "obnovlenie.py").read_text(encoding="utf-8")
    if "sobrat-ustrojstvo.py" in исходник:
        путь_ок("раскладка зовёт пересборку документа устройства")
    else:
        путь_плохо("пересборки производных нет — самопроверка будет красной всегда")

    print("── публичный коммит собран из этого пакета ──")
    # БОЛЬНОЙ СЛУЧАЙ: на машине-источнике публичная ветка получает коммит-сборку.
    # Он потомок публичной ветки, но НЕ предок HEAD пакета — прежняя сверка
    # отвечала бы «есть новая версия» навсегда, и демон будил бы владельца
    # каждые сутки сообщением о том, что он же сам и опубликовал.
    свой_хэш = гит("rev-parse", "--short", "HEAD", где=пакет).stdout.strip()
    сборка = врем / "сборка"
    гит("clone", "--quiet", str(удалённый), str(сборка))
    гит("config", "user.email", "проба@харнес", где=сборка)
    гит("config", "user.name", "проба", где=сборка)
    (сборка / "собрано.txt").write_text("сборка\n", encoding="utf-8")
    гит("add", "-A", где=сборка)
    гит("commit", "-m", f"версия от 2026-09-12, пакет {свой_хэш}", где=сборка)
    гит("push", "--quiet", "origin", "HEAD:master", где=сборка)
    ответ_св = обновление.спросить_обновления()
    if ответ_св.get("есть новое") is False and ответ_св.get("источник") == "свой пакет":
        путь_ок("сборка из своего пакета — не новая версия")
    else:
        путь_плохо(f"своя сборка принята за новую версию: {ответ_св}")

    # Обратный случай: хэш в сообщении чужой — новое действительно есть.
    (сборка / "собрано.txt").write_text("чужое\n", encoding="utf-8")
    гит("add", "-A", где=сборка)
    гит("commit", "-m", "версия от 2026-09-13, пакет 0123abc", где=сборка)
    гит("push", "--quiet", "origin", "HEAD:master", где=сборка)
    ответ_ч = обновление.спросить_обновления()
    if ответ_ч.get("есть новое") is True:
        путь_ок("сборка из чужого коммита — новая версия")
    else:
        путь_плохо(f"чужая сборка не замечена: {ответ_ч}")

finally:
    shutil.rmtree(врем, ignore_errors=True)

print(f"ОБНОВЛЕНИЕ: путей {путей}, неудач {неудач}")
if неудач:
    sys.exit(1)
print(json.dumps({"проверка": "обновление", "путей": путей, "неудач": 0},
                 ensure_ascii=False))
