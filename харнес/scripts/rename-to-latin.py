def main():
    if "--selftest" in sys.argv:
        return самотест()
    области = [a for a in sys.argv[1:] if not a.startswith("--")]
    if not области:
        print(__doc__)
        return 1
    применять = "--применить" in sys.argv

    пути = []
    for область in области:
        пути.extend(файлы_области(область))
    if not пути:
        print(f"[перевод имён] в области {' '.join(области)} кириллических имён нет")
        return 0
    все_файлы = [п.strip() for п in _git("ls-files").splitlines() if п.strip()]
    карта = карта_переименований(пути, существующие=все_файлы)
    print(f"[перевод имён] область: {' '.join(области)} · файлов к переводу: {len(карта)}")

    по_типам, тронуто, хвосты = Counter(), 0, []
    for файл in файлы_для_правки():
        полный = КОРЕНЬ / файл
        try:
            было = полный.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        стало, замен = правки_в_тексте(было, карта, файл=файл)
        if not замен:
            continue
        по_типам[Path(файл).suffix or Path(файл).name] += замен
        тронуто += 1
        for номер, строка, было_имя, стало_имя in остатки_идентификаторов(стало, карта):
            хвосты.append(f"{файл}:{номер}: «{было_имя}» осталось именем "
                          f"(рядом импорт «{стало_имя}»): {строка}")
        if применять:
            полный.write_text(стало, encoding="utf-8")

    for тип, сколько in по_типам.most_common():
        print(f"    {тип or '(без расширения)'}: {сколько} замен")
    print(f"[перевод имён] ссылок исправлено: {sum(по_типам.values())} "
          f"в {тронуто} файлах")
    if хвосты:
        print(f"[перевод имён] ВНИМАНИЕ: старое имя осталось идентификатором "
              f"в {len(хвосты)} местах — правятся глазами, скриптом опасно:")
        for строка in хвосты[:20]:
            print(f"    {строка}")

    if not применять:
        print("[перевод имён] это ПРОБА — ничего не изменено. Повтори с --применить")
        return 0

    for старый, новый in карта.items():
        Path(КОРЕНЬ / новый).parent.mkdir(parents=True, exist_ok=True)
        _git("mv", старый, новый)
    осталось = len(файлы_области(области[0])) if len(области) == 1 else -1
    print(f"[перевод имён] переименовано: {len(карта)}" +
          (f" · осталось в области: {осталось}" if осталось >= 0 else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
