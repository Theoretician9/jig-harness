def _git(*аргументы, корень=None):
    итог = subprocess.run(
        ["git", "-C", str(корень or КОРЕНЬ), "-c", "core.quotepath=false", *аргументы],
        capture_output=True, text=True, errors="replace", timeout=120)
    return итог.stdout


def файлы_области(область, корень=None):
    """Файлы кода с кириллицей в ИМЕНИ внутри области."""
    найдено = []
    for путь in _git("ls-files", область, корень=корень).splitlines():
        путь = путь.strip()
        if not путь or not путь.endswith(РАСШИРЕНИЯ_КОДА):
            continue
        if re.search(r"[^\x00-\x7F]", Path(путь).name):
            найдено.append(путь)
    return найдено


def карта_переименований(пути, существующие=None):
    """{старый путь: новый путь}. Конфликт — исключение и полная остановка.

    Конфликтом считается не только пара переименовываемых, но и совпадение с
    УЖЕ лежащим рядом латинским файлом: «районы.py» рядом с «rajony.py» — это
    потеря файла при `git mv`, и самотест ловил именно этот случай.
    """
    import importlib.util
    спец = importlib.util.spec_from_file_location("translit", КОРЕНЬ / "scripts" / "translit.py")
    translit = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(translit)

    import builtins
    import keyword
    ЗАНЯТЫЕ_ЯЗЫКОМ = set(dir(builtins)) | set(keyword.kwlist) | {
        "os", "re", "sys", "json", "time", "types", "typing", "string", "math",
        "test", "tests", "copy", "hash", "id", "list", "map", "set", "dict",
    }

    карта, занято = {}, {}
    for путь in (существующие if существующие is not None else пути):
        занято.setdefault(путь, путь)
    for старый in пути:
        новый = translit.перевести_путь(старый)
        if новый == старый:
            continue
        занято.pop(старый, None)      # сам себя не вытесняет
        # Имя модуля, совпавшее со встроенным («сеть.py» → «set.py»), затенило
        # бы его при импорте. Живая находка пробы 11.09 на app/tests.
        основа = Path(новый).stem
        if основа in ЗАНЯТЫЕ_ЯЗЫКОМ and новый.endswith(".py"):
            новый = str(Path(новый).with_name(основа + "_" + Path(новый).suffix))
        ключ = новый
        if ключ in занято:
            raise SystemExit(
                f"ОТКАЗ: «{занято[ключ]}» и «{старый}» дают одно имя «{новый}». "
                f"Переименование остановлено целиком — молчаливая перезапись сносит файл.")
        занято[ключ] = старый
        карта[старый] = новый
    return карта


def файлы_для_правки(корень=None):
    """Файлы, в которых ищем ссылки. Свидетельства и генерируемое пропускаем."""
    отобранные = []
    for путь in _git("ls-files", корень=корень).splitlines():
        путь = путь.strip()
        if not путь or any(путь.startswith(п) for п in НЕ_ТРОГАТЬ):
            continue
        имя = Path(путь).name
        if путь.endswith(ТИПЫ_ССЫЛОК) or имя in БЕЗ_РАСШИРЕНИЯ:
            отобранные.append(путь)
    return отобранные


def _вне_строк_и_комментариев(строка):
    """(код, хвост): часть строки, где имя — это имя, и всё остальное."""
    без_комментария, решётка, комментарий = строка.partition("#")
    куски = re.split(r"""(['"].*?['"])""", без_комментария)
    return куски, решётка + комментарий


