def _связанные_имена(текст):
    """Имена, которые импорт ВВОДИТ в этот файл. None — текст не разобрать."""
    try:
        дерево = ast.parse(текст)
    except (SyntaxError, ValueError):
        return None
    имена = set()
    for узел in ast.walk(дерево):
        if isinstance(узел, (ast.Import, ast.ImportFrom)):
            for что in узел.names:
                имена.add((что.asname or что.name).split(".")[0])
    return имена


def _имя_связано_модулем(текст, основа, файл, старый):
    """Имя основы введено в файл ИМЕННО как модуль — тогда оно модуль везде.

    Различение обязательно: «import гидравлика» делает «гидравлика» модулем и
    в строке «return гидравлика» (без точки), а «from .модель import сеть»
    вводит ФУНКЦИЮ чужого модуля, и трогать её нельзя, хотя рядом лежит файл
    «сеть.py». Живые случаи 11.09.2026 — 106 мест первого рода и 11 наборов,
    сломанных вторым.
    """
    try:
        дерево = ast.parse(текст)
    except (SyntaxError, ValueError):
        return False
    каталог = Path(старый).parent
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Import):
            for что in узел.names:
                if что.asname is None and что.name.split(".")[0] == основа:
                    return True
        elif isinstance(узел, ast.ImportFrom):
            for что in узел.names:
                if что.asname is not None or что.name != основа:
                    continue
                # «from X import основа» — модуль лишь тогда, когда рядом с
                # переименованным файлом и правда лежит такой модуль.
                if (каталог / основа).with_suffix(Path(старый).suffix).exists() \
                        or (каталог / основа).is_dir():
                    return True
    return False


def заменить_использования(текст, основа, новая, питон=False, как_модуль=False):
    """Заменить имя модуля в КОДЕ файла, который его импортирует.

    Живой случай 11.09: «import эталон_destest» заменился, а «return
    эталон_destest» ниже — нет, и ruff поймал F821. Правка безопасна только
    при двух условиях разом: модуль импортирован ЭТИМ файлом и слово стоит вне
    строк и комментариев (в строке «tags=[\"бригады\"]» это текст, не имя).
    """
    # Признак «модуль импортирован этим файлом». Вхождения новой строки мало:
    # в «from .nastrojki import настройки» новое имя стоит в ПУТИ, а вводится
    # имя «настройки» — объект. 11.09 по этому слабому признаку 51 обращение
    # «настройки.ключ» и «тепло.шаг» (локальная переменная рядом с путём
    # «lib/teplo.py» в строке документации) стали неопределёнными (ruff F821).
    связанные = _связанные_имена(текст) if питон else None
    if связанные is not None:
        if новая not in связанные:
            return текст, 0
    elif not re.search(rf"(?<![\w]){re.escape(новая)}(?![\w])", текст):
        return текст, 0
    # Имя занято АЛИАСОМ другого модуля («import risk_uchastka as риск»):
    # трогать его нельзя — 11.09 такая замена сделала «риск.балл» → «risk.балл»
    # в файле, где risk не определён. Поймал линтер (F821).
    if re.search(rf"\bas[ \t]+{re.escape(основа)}(?![\w])", текст):
        return текст, 0
    # ТОЛЬКО обращение к атрибуту модуля: «рамка.коды(...)». Без «(?=\.)» под
    # замену попадали одноимённые функции и параметры — «def риск(...)» стал
    # «def risk(...)» рядом с импортом risk, а «return сейчас()» (функция,
    # импортированная из модуля sejchas) превратился в вызов несуществующего
    # имени. Оба случая поймал линтер 11.09.
    if как_модуль:
        # Имя введено как МОДУЛЬ — значит оно модуль в любом месте файла, а не
        # только перед точкой: «import gidravlika» рядом с «return гидравлика»
        # оставлял неопределённое имя (ruff F821, 106 мест 11.09.2026).
        образец = re.compile(rf"\b{re.escape(основа)}\b")
    else:
        образец = re.compile(
            rf"\b{re.escape(основа)}\b(?=\.)"                      # рамка.коды(...)
            rf"|(?<=reload\(){re.escape(основа)}(?![\w])"           # importlib.reload(имя)
            rf"|(?<=import_module\(['\"]){re.escape(основа)}(?=['\"])")
    # Пропускаем только САМИ строки импорта: проверка «import» подстрокой
    # пропускала и «importlib.reload(свойства_воды)» — имя там осталось
    # непереведённым, поймал линтер (F821) на живом прогоне 11.09.
    строка_импорта = re.compile(r"^\s*(?:from|import)\s")
    строки, всего = [], 0
    for строка in текст.split("\n"):
        if строка_импорта.match(строка):
            строки.append(строка)
            continue
        куски, хвост = _вне_строк_и_комментариев(строка)
        новые = []
        for номер, кусок in enumerate(куски):
            if номер % 2 == 0:          # вне кавычек
                кусок, сколько = образец.subn(новая, кусок)
                всего += сколько
            новые.append(кусок)
        строки.append("".join(новые) + хвост)
    return "\n".join(строки), всего


def остатки_идентификаторов(текст, карта):
    """Где старое имя осталось ИДЕНТИФИКАТОРОМ после правки импорта.

    Живой случай 11.09: «import эталон_destest» заменился, а «return
    эталон_destest» строкой ниже — нет, и линтер поймал F821. Менять такие
    места скриптом опасно (то же слово бывает обычным словом в тексте),
    поэтому они печатаются списком и правятся глазами.
    """
    остатки = []
    for старый, новый in карта.items():
        основа = Path(старый).stem
        новая = Path(новый).stem
        if основа == новая or not re.search(rf"import\s+{re.escape(новая)}\b", текст):
            continue
        for номер, строка in enumerate(текст.splitlines(), 1):
            if "import" in строка:
                continue
            без_комментария = строка.split("#", 1)[0]
            # Слово в кавычках — это текст (тег API, сообщение), а не имя
            # модуля: 11.09 такие места дали 36 ложных предупреждений из 36.
            без_строк = re.sub(r"""(['"]).*?\1""", "", без_комментария)
            if re.search(rf"\b{re.escape(основа)}\b", без_строк):
                остатки.append((номер, строка.strip()[:80], основа, новая))
    return остатки


def _общий_образец(карта):
    """Один regex на все имена: 198 отдельных проходов по 700 файлам считались
    минутами. Кэш на карту — она в пределах шага не меняется."""
    # Ключ — САМИ имена, а не id(карта): id переиспользуется сборщиком мусора,
    # и вторая карта получала образец первой. Поймано самотестом 11.09.
    ключ = frozenset(карта.items())
    если_есть = _ОБРАЗЦЫ.get(ключ)
    if если_есть is not None:
        return если_есть
    имена = {Path(с).name: Path(н).name for с, н in карта.items()}
    if not имена:
        образец = None
    else:
        по_длине = sorted(имена, key=len, reverse=True)   # длинные раньше коротких
        образец = re.compile("|".join(re.escape(и) for и in по_длине))
    _ОБРАЗЦЫ[ключ] = (образец, имена)
    return образец, имена


_ОБРАЗЦЫ = {}


# Строки, которые правка не трогает НИКОГДА. Живой случай 11.09: id задач в
# карте разработки содержат слова, совпадающие с именами модулей, и правка
# сделала «pr.движок» → «pr.dvizhok», «pr.граф-вводов» → «pr.graf-вводов».
# Поймал гейт «карта не теряет задачи»: для него это исчезнувшие задачи (И-1).
НЕПРИКОСНОВЕННЫЕ_СТРОКИ = re.compile(r"^\s*-?\s*id:\s")


def правки_в_тексте(текст, карта, файл=None):
    """(новый текст, число замен). Имя с расширением — всегда; без расширения —
    только в импорте: иначе «район» заменится в человеческом тексте."""
    замен = 0
    # Идентификаторы задач выносим из-под правки целиком и возвращаем как есть.
    защищённые = {}
    if файл and файл.endswith((".yaml", ".yml")):
        строки = текст.split("\n")
        for номер, строка in enumerate(строки):
            if НЕПРИКОСНОВЕННЫЕ_СТРОКИ.match(строка):
                ключ = f"\x00ЗАЩИТА{номер}\x00"
                защищённые[ключ] = строка
                строки[номер] = ключ
        текст = "\n".join(строки)
    исходный_текст = текст
    # 1. Полные имена файлов — ОДНИМ проходом по всем именам сразу.
    образец, имена = _общий_образец(карта)
    if образец is not None:
        текст, сколько = образец.subn(lambda м: имена[м.group(0)], текст)
        замен += сколько
    только_полные_имена = bool(файл) and not файл.endswith(РАСШИРЕНИЯ_ГДЕ_ИМЕНА)
    for старый, новый in карта.items():
        старое_имя, новое_имя = Path(старый).name, Path(новый).name
        if только_полные_имена:
            continue          # в тексте и данных правим ТОЛЬКО «имя.расширение»
        # 2. Имя модуля без расширения — только рядом с import/from.
        если_модуль = старое_имя.rsplit(".", 1)
        if len(если_модуль) != 2 or если_модуль[1] not in ("py", "ts", "tsx", "js", "jsx"):
            continue
        основа, новая_основа = если_модуль[0], новое_имя.rsplit(".", 1)[0]
        # Языки связывают имя модуля по-разному, и от этого зависит, можно ли
        # трогать ИДЕНТИФИКАТОРЫ. В python «import район» делает имя файла
        # именем в коде — выбора нет. Во фронте имя задаётся явно («import
        # Публикации from './Publikacii'»), переезд файла его не требует, а
        # совпадение имени файла с функцией («показать.ts» рядом с «export
        # function показать»), пропсом и переменной («тема») — обычное дело:
        # прогон app/web 11.09 переписал 55 таких мест и уронил сборку типов.
        # Фронту нужен и разрешён ровно один вид правки — путь в кавычках.
        фронт = bool(файл) and файл.endswith((".ts", ".tsx", ".js", ".jsx"))
        if фронт:
            if если_модуль[1] not in ("ts", "tsx", "js", "jsx"):
                continue
            # Относительный импорт: './Карта', '../общее/цвет'. Имя файла тут
            # живёт только внутри кавычек — за ними оно уже идентификатор.
            путь_импорта = re.compile(
                rf"(?P<до>['\"][^'\"]*?/){re.escape(основа)}(?P<после>['\"])")
            текст, сколько = путь_импорта.subn(
                lambda м: м.group("до") + новая_основа + м.group("после"), текст)
            замен += сколько
            continue
        # Дальше — правила python: они трогают ИДЕНТИФИКАТОРЫ, и имя модуля
        # чужого языка под ними становится ловушкой. Прогон web 11.09:
        # переезд фронтового «иконки.ts» переписал в python-тесте локальную
        # переменную «иконки.index(...)» → «ikonki.index(...)», а «дата.ts» —
        # «дата.isoformat()» в hronika.py. Оба поймал ruff (F821). Ссылка на
        # чужой язык живёт полным именем с расширением — правило 1 её и правит.
        if если_модуль[1] != "py":
            continue
        # Дешёвая проверка подстроки перед дорогим regex: без неё на область в
        # 198 имён приходилось по 400 регулярок на каждый из 700 файлов.
        if основа not in текст:
            continue
        # Два условия, оба из живых поломок 11.09:
        # (?<![\w]) — иначе «from conftest import пароль_учётки» превращался в
        #   «пароль_uchetki»: regex подхватывал имя ВНУТРИ чужого идентификатора;
        # проверка пакета — иначе «from .модель import сеть» (ФУНКЦИЯ из другого
        #   модуля) правился по имени файла tests/сеть.py, и 11 наборов
        #   перестали собираться.
        пакет = Path(старый).parent.name

        def _свой_пакет(путь):
            """Импорт ведёт в ТОТ каталог, где лежал файл? Пустой путь — да."""
            if not путь:
                return True
            последний = путь.rstrip(".").rsplit(".", 1)[-1]
            return (not последний) or последний == пакет

        # Форма 1: «from ПАКЕТ import имя» и «import имя».
        # Проверка пакета обязательна: без неё «from .модель import сеть»
        # (ФУНКЦИЯ чужого модуля) правился по имени файла tests/сеть.py, и
        # 11 наборов перестали собираться — поймано живым прогоном 11.09.
        ввоз = re.compile(
            r"(?P<до>(?:^|\n)[ \t]*(?:from[ \t]+(?P<путь>[\w.]+)[ \t]+import|import)"
            r"[ \t]+(?:[\w.]+[ \t]*,[ \t]*)*)"
            rf"(?<![\w])(?P<имя>{re.escape(основа)})(?P<после>[\s.,'\"\)]|$)")
        # Счётчик ведём САМИ: subn считает совпадения, а не изменения — при
        # отказе от замены («чужой пакет») он всё равно прибавлял единицу, и
        # число замен, которым доказывается работа, врало.
        сделано = [0]

        def _ввоз(м):
            if not _свой_пакет(м.group("путь")):
                return м.group(0)
            сделано[0] += 1
            return м.group("до") + новая_основа + м.group("после")

        текст = ввоз.sub(_ввоз, текст)
        замен += сделано[0]

        # Форма 2: имя модуля стоит В ПУТИ импорта — последним сегментом:
        #   «from район import узлы», «from .настройки import настройки»,
        #   «from ..схемы.сеть import Узел», «from collectors.перенос import x».
        # Раньше форм было две, и обе требовали точку ПЕРЕД пакетом: ни
        # «from .модуль import», ни «from пакет.модуль import» под них не
        # попадали. 171 импорт продукта остался указывать на исчезнувшее имя, и
        # ни ruff, ни сборка фронта этого не видят — ловит гейт check-imports.py.
        хвост_пути = re.compile(
            rf"(?P<до>(?:^|\n)[ \t]*from[ \t]+(?P<префикс>\.*(?:[\w.]*\.)?))"
            rf"{re.escape(основа)}(?P<после>[ \t]+import\b)")

        def _годится(префикс):
            """Путь ведёт ИМЕННО в тот каталог, где лежал переименованный файл."""
            точки = len(префикс) - len(префикс.lstrip("."))
            сегменты = [с for с in префикс.strip(".").split(".") if с]
            if сегменты:
                return сегменты[-1] == пакет
            if not точки:
                return True          # «from модуль import» — путь и есть модуль
            if not файл:
                return False         # относительный путь без файла не проверить
            каталог = Path(файл).parent
            for _ in range(точки - 1):
                каталог = каталог.parent
            # Каталог-пакет мог переехать сам («схемы» → «shemy»), и тогда
            # сосед по новому имени — тот же сосед: сверяем оба состояния.
            return каталог in (Path(старый).parent, Path(новый).parent)

        сделано_в_пути = [0]

        def _в_пути(м):
            if not _годится(м.group("префикс")):
                return м.group(0)
            сделано_в_пути[0] += 1
            return м.group("до") + новая_основа + м.group("после")

        текст = хвост_пути.sub(_в_пути, текст)
        замен += сделано_в_пути[0]

        # 1б. МНОГОСТРОЧНЫЙ импорт в скобках:
        #     from ..services import (локализация,
        #                             показ_на_карте, рамка, теплопотери)
        # Однострочный regex его не видел, и 118 имён остались в коде
        # идентификаторами — поймал линтер на живом прогоне api 11.09.
        скобки = re.compile(r"(?m)^[ \t]*from[ \t]+(?P<путь>[\w.]+)[ \t]+import[ \t]*\((?P<тело>[^)]*)\)")

        def _скобки(м):
            if not _свой_пакет(м.group("путь")):
                return м.group(0)
            тело = re.sub(rf"(?<![\w]){re.escape(основа)}(?![\w])", новая_основа, м.group("тело"))
            if тело == м.group("тело"):
                return м.group(0)
            сделано_в_скобках[0] += 1
            return м.group(0).replace(м.group("тело"), тело)

        сделано_в_скобках = [0]
        текст = скобки.sub(_скобки, текст)
        замен += сделано_в_скобках[0]

        # 3б. Имя модуля СПИСКОМ: pyproject.toml:py-modules перечисляет 18
        # модулей lib поимённо, и без правки ломается установка пакета
        # (находка C-6). Правило узкое — только этот файл: иначе оно правит и
        # «tags=[\"район\"]» в коде, где это текст, а не модуль.
        if файл and Path(файл).name == "pyproject.toml":
            в_списке = re.compile(rf"(?P<до>[\[,]\s*\n?\s*[\"'])"
                                  rf"{re.escape(основа)}(?P<после>[\"'])")
            текст, сколько = в_списке.subn(
                lambda м: м.group("до") + новая_основа + м.group("после"), текст)
            замен += сколько

        # 4. Использование модуля в коде того же файла («фабрики.наряд(...)»).
        текст, сколько = заменить_использования(
            текст, основа, новая_основа,
            питон=bool(файл) and файл.endswith(".py"),
            как_модуль=_имя_связано_модулем(исходный_текст, основа, файл, старый))
        замен += сколько
    for ключ, строка in защищённые.items():
        текст = текст.replace(ключ, строка)
    return текст, замен


