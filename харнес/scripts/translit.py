#!/usr/bin/env python3
"""Транслитерация имён файлов: кириллица → латиница, одинаково на любой машине.

Откуда взят. Владелец 11.09.2026 выбрал вариант «2» — перевести имена всех
файлов кода разом. Таблица нужна ОДНА и в коде: разные переводы одного имени
в разных местах дадут два файла вместо одного, а «примерно так же» здесь равно
«сломано». Детерминизм задаётся кодом, а не порядком словаря — запись
[[установка-не-повторяется]].

Правило перевода: ГОСТ 7.79-2000, система Б, упрощённая до ASCII:
«щ» → shch, «ё» → e, «ъ» и «ь» исчезают, «ы» → y, «э» → e, «ю» → yu, «я» → ya.
Разделители (`-`, `_`, `.`, цифры, латиница) остаются как есть, регистр
сохраняется: «Панель.tsx» → «Panel.tsx», «район.py» → «rajon.py».

Прогон:
    python3 scripts/translit.py «имя.py»      # перевести одно имя
    python3 scripts/translit.py --selftest
"""
import sys

ТАБЛИЦА = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "zh", "з": "z", "и": "i", "й": "j", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "h", "ц": "c", "ч": "ch", "ш": "sh", "щ": "shch",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}


def перевести(имя: str) -> str:
    """Имя файла (без каталога) → латиницей. Не-кириллица не трогается."""
    куски = []
    for знак in имя:
        нижний = знак.lower()
        if нижний not in ТАБЛИЦА:
            куски.append(знак)
            continue
        замена = ТАБЛИЦА[нижний]
        if знак.isupper() and замена:
            замена = замена[0].upper() + замена[1:]
        куски.append(замена)
    return "".join(куски)


def перевести_путь(путь: str, переводить_каталоги=False) -> str:
    """Путь целиком. Каталоги переводятся только по явному требованию: имя
    каталога данных идентификатором не становится, и трогать его незачем."""
    части = путь.split("/")
    if переводить_каталоги:
        return "/".join(перевести(ч) for ч in части)
    return "/".join(части[:-1] + [перевести(части[-1])])


def самотест() -> int:
    случаи = [
        ("район.py", "rajon.py", "БОЛЬНОЙ СЛУЧАЙ: модуль продукта («й» → j по ГОСТ)"),
        ("Панель.tsx", "Panel.tsx", "заглавная буква сохраняется"),
        ("ПеремычкаЗон.tsx", "PeremychkaZon.tsx",
         "БОЛЬНОЙ СЛУЧАЙ: «щ» внутри слова и вторая заглавная"),
        ("sverka_formy_s_kartoj.py", "sverka_formy_s_kartoj.py",
         "подчёркивания и «й» на месте"),
        ("check-kirillica-v-imenah.py", "check-kirillica-v-imenah.py",
         "смешанное имя: латиница не трогается"),
        ("объезд.sh", "obezd.sh", "твёрдый знак исчезает, а не становится буквой"),
        ("ёлка.py", "elka.py", "ё → e"),
        ("area.py", "area.py", "чистая латиница не меняется"),
        ("0051_журнал_фоновых_прогонов.py", "0051_zhurnal_fonovyh_progonov.py",
         "цифры и разделители сохраняются"),
    ]
    ok = True
    for вход, ждём, зачем in случаи:
        вышло = перевести(вход)
        if вышло != ждём:
            ok = False
            print(f"  ПЛОХО {зачем}: «{вход}» → «{вышло}», ждали «{ждём}»")
        else:
            print(f"  ок    {зачем}")

    # Путь: каталог по умолчанию не трогаем.
    if перевести_путь("app/lib/район.py") == "app/lib/rajon.py" \
       and перевести_путь("app/api/схемы/узел.py", переводить_каталоги=True) \
           == "app/api/shemy/uzel.py":
        print("  ок    БОЛЬНОЙ СЛУЧАЙ: каталог переводится только по требованию")
    else:
        ok = False
        print("  ПЛОХО перевод пути работает неверно")

    # Одинаковость: два прогона дают одно и то же (детерминизм — в коде).
    if all(перевести(в) == перевести(в) for в, _, _ in случаи):
        print("  ок    перевод повторяем")

    print("САМОТЕСТ %s: %d путей, первым — больной случай"
          % ("ПРОЙДЕН" if ok else "ПРОВАЛЕН", len(случаи) + 2))
    return 0 if ok else 1


def main() -> int:
    if "--selftest" in sys.argv:
        return самотест()
    аргументы = [a for a in sys.argv[1:] if not a.startswith("--")]
    if not аргументы:
        print(__doc__)
        return 0
    for имя in аргументы:
        print(перевести_путь(имя))
    return 0


if __name__ == "__main__":
    sys.exit(main())
