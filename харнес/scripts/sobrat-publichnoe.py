#!/usr/bin/env python3
"""Собрать публичное дерево харнеса из УЧТЁННОГО состояния пакета.

Публикуется не пакет, а сборка: наружу должен уехать инструмент, а не наша
мастерская. Что именно снимается и чем подменяется — ДАННЫЕ
(харнес/config/публичная-сборка.yaml), здесь только механика.

Четыре решения, за каждым живой случай:

* Источник — `git archive HEAD`, а не каталог: каталог ≠ коммит, и
  незакоммиченная правка уехала бы наружу мимо всех замков публикации.
* Обезличиваются только документы (*.md). В коде наш путь стоит УМОЛЧАНИЕМ
  (`${PROJECT_DIR:-/var/www/…}`), и подстановка туда другого литерала даёт
  путь, которого нет ни у кого: это дефект пакета, он лечится причиной.
* Значения паспорта читаются строго из файла (konf.из_файла): тому, кто судит
  установку, окружение не хозяин.
* Каталог сборки ОПОЗНАЁТСЯ по метке .публичная-сборка, и без метки непустой
  каталог не трогается. Улика 12.09.2026: самотест позвал сборку с пустым
  путём, Path("") стал «.», и `rsync -a --delete` снёс рабочее дерево проекта
  целиком (1583 файла; спасло только то, что .git исключён и работа была
  закоммичена). Разрушительная команда обязана узнавать свою цель, а не
  доверять доводу.

Запуск:
  python3 scripts/sobrat-publichnoe.py [--пакет DIR] [--куда DIR]
                                       [--паспорт FILE] [--конфиг FILE] [--данные FILE]
  python3 scripts/sobrat-publichnoe.py --selftest
"""
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "scripts" / "lib"))
from konf import из_файла  # noqa: E402

ПАСПОРТ = "/etc/harness/install.conf"
КОНФИГ = "/etc/harness/harness.conf"
МЕТКА = ".публичная-сборка"


class Отказ(Exception):
    """Сборка не состоялась. Код 1, если не сказано иное."""

    def __init__(self, текст: str, код: int = 1):
        super().__init__(текст)
        self.код = код


def довод(имя: str, умолчание: str | None = None) -> str | None:
    """Значение довода командной строки. Путь конфига НЕ берётся из окружения."""
    if имя in sys.argv:
        место = sys.argv.index(имя) + 1
        if место < len(sys.argv):
            return sys.argv[место]
    return умолчание


def каталог_пакета(паспорт: dict) -> Path:
    """Пакет-источник: ключ STARTER_DIR, иначе конвенция установки."""
    из_ключа = паспорт.get("STARTER_DIR")
    if из_ключа:
        return Path(из_ключа)
    пользователь = паспорт.get("AGENT_USER") or "agent"
    return Path(f"/home/{пользователь}/starter/СТАРТОВЫЙ-ПАКЕТ")


def опознать_цель(куда: str) -> Path:
    """Убедиться, что назначение — каталог сборки, и только потом отдать путь.

    Порядок проверок — от самой дешёвой ошибки к самой дорогой: пустой довод,
    несуществующий каталог, каталог без прав, чужой непустой каталог.
    """
    if not str(куда).strip():
        raise Отказ("пуст PUBLIC_BUILD_DIR — некуда собирать (ключ harness.conf)", код=2)
    цель = Path(куда).resolve()
    if not цель.is_dir():
        raise Отказ(f"каталога сборки нет: {цель}. Создать: "
                    f"sudo install -d -o $(id -un) -g $(id -gn) -m 750 {цель}")
    if not os.access(цель, os.W_OK):
        raise Отказ(f"каталог сборки не пишется: {цель}. Поправить владельца: "
                    f"sudo install -d -o $(id -un) -g $(id -gn) -m 750 {цель}")
    свои = {МЕТКА, ".git"}
    чужое = [п.name for п in цель.iterdir() if п.name not in свои]
    if чужое and not (цель / МЕТКА).exists():
        raise Отказ(
            f"{цель} — непустой каталог без метки {МЕТКА}: это не наша сборка, "
            f"а чьё-то дерево ({len(чужое)} записей, первая «{sorted(чужое)[0]}»). "
            f"Сборка стирает содержимое назначения, поэтому не трогаю. "
            f"Если каталог всё же наш — создать метку: touch {цель}/{МЕТКА}")
    return цель


def архив_пакета(пакет: Path, куда: Path) -> str:
    """Развернуть git archive HEAD пакета в каталог. Отдаёт короткий хэш."""
    if not (пакет / ".git").exists():
        raise Отказ(f"пакет {пакет} — не git-репозиторий, собирать нечего")
    архив = subprocess.run(["git", "-C", str(пакет), "archive", "HEAD"],
                           capture_output=True, timeout=120)
    if архив.returncode != 0:
        raise Отказ("git archive пакета не прошёл: "
                    + архив.stderr.decode("utf-8", "ignore").strip())
    распаковка = subprocess.run(["tar", "-x", "-C", str(куда)], input=архив.stdout,
                                capture_output=True, timeout=120)
    if распаковка.returncode != 0:
        raise Отказ("распаковка архива не прошла: "
                    + распаковка.stderr.decode("utf-8", "ignore").strip())
    хэш = subprocess.run(["git", "-C", str(пакет), "rev-parse", "--short", "HEAD"],
                         capture_output=True, text=True, timeout=30)
    return хэш.stdout.strip()


def замены(данные: dict, паспорт: dict) -> list:
    """Пары «значение установки → имя ключа» для документов.

    От ДЛИННОГО к короткому: PROJECT_DIR (/var/www/Имя) содержит внутри себя
    PROJECT_NAME (Имя), и обратный порядок дал бы «/var/www/${PROJECT_NAME}» —
    половину замены вместо целой.
    """
    пары = []
    for ключ in данные.get("обезличить_ключи") or []:
        значение = паспорт.get(ключ)
        if not значение:
            continue
        if ключ == "AGENT_USER":
            # Имя пользователя само по себе — обычное слово («agent» встречается
            # в текстах сотни раз). След — только домашний путь.
            пары.append((f"/home/{значение}", "/home/${AGENT_USER}"))
        else:
            пары.append((значение, "${%s}" % ключ))
    пары.sort(key=lambda п: len(п[0]), reverse=True)
    return пары


def обезличить(дерево: Path, пары: list) -> int:
    """Заменить значения установки в ДОКУМЕНТАХ. Отдаёт число правленых файлов."""
    правлено = 0
    for файл in sorted(дерево.rglob("*.md")):
        текст = файл.read_text(encoding="utf-8")
        новый = текст
        for значение, замена in пары:
            новый = новый.replace(значение, замена)
        if новый != текст:
            файл.write_text(новый, encoding="utf-8")
            правлено += 1
    return правлено


def собрать(пакет: Path, куда: str, данные: dict, паспорт: dict) -> dict:
    """Собрать дерево. Путь назначения — СТРОКОЙ: Path("") молча становится «.»."""
    цель = опознать_цель(куда)

    with tempfile.TemporaryDirectory(prefix="публичная-сборка-") as врем:
        дерево = Path(врем)
        хэш = архив_пакета(пакет, дерево)

        снято = 0
        for маска in данные.get("исключить") or []:
            for путь in sorted(дерево.glob(маска)):
                (shutil.rmtree(путь) if путь.is_dir() else путь.unlink())
                снято += 1

        заменено = 0
        for цель_замены, шаблон in (данные.get("заменить_шаблоном") or {}).items():
            источник = дерево / шаблон
            if not источник.is_file():
                raise Отказ(f"шаблон {шаблон} не найден в пакете — "
                            f"подменять {цель_замены} нечем")
            (дерево / цель_замены).write_text(источник.read_text(encoding="utf-8"),
                                              encoding="utf-8")
            заменено += 1

        обезличено = обезличить(дерево, замены(данные, паспорт))

        пропало = [ф for ф in (данные.get("оставить") or []) if not (дерево / ф).exists()]
        if пропало:
            raise Отказ("в сборке нет обязательного: " + ", ".join(пропало))

        файлов = sum(1 for п in дерево.rglob("*") if п.is_file())
        (дерево / МЕТКА).write_text(
            "Собрано scripts/sobrat-publichnoe.py. Каталог целиком принадлежит\n"
            "сборке: при пересборке его содержимое заменяется, кроме .git.\n",
            encoding="utf-8")

        # rsync, а не перезапись каталога: .git публичного репозитория —
        # единственное, что обязано пережить пересборку, иначе локальная копия
        # публичной истории исчезает при каждой сборке.
        готово = subprocess.run(
            ["rsync", "-a", "--delete", "--exclude", ".git", f"{дерево}/", f"{цель}/"],
            capture_output=True, text=True, timeout=300)
        if готово.returncode != 0:
            raise Отказ(f"rsync не прошёл: {готово.stderr.strip()}")

    return {"пакет": хэш, "файлов": файлов, "снято": снято,
            "заменено": заменено, "обезличено": обезличено, "куда": str(цель)}


def main() -> int:
    паспорт = из_файла(довод("--паспорт", ПАСПОРТ))
    паспорт.update(из_файла(довод("--конфиг", КОНФИГ)))

    пакет = Path(довод("--пакет") or каталог_пакета(паспорт))
    данные_путь = довод("--данные") or str(пакет / "харнес" / "config" / "публичная-сборка.yaml")
    куда = довод("--куда", паспорт.get("PUBLIC_BUILD_DIR", ""))

    try:
        данные = yaml.safe_load(Path(данные_путь).read_text(encoding="utf-8")) or {}
    except OSError as ошибка:
        print(f"[сборка] ОТКАЗ: данных сборки нет — {ошибка}", file=sys.stderr)
        return 1

    try:
        итог = собрать(пакет, куда, данные, паспорт)
    except Отказ as отказ:
        print(f"[сборка] ОТКАЗ: {отказ}", file=sys.stderr)
        return отказ.код

    print(json.dumps(итог, ensure_ascii=False))
    return 0


# ── самотест: подставной пакет, двенадцать путей ────────────────────────────
def _подставной_пакет(корень: Path) -> Path:
    пакет = корень / "пакет"
    (пакет / "харнес" / "память").mkdir(parents=True)
    (пакет / "харнес" / "шаблоны-задач").mkdir(parents=True)
    (пакет / "док.md").write_text(
        "Ставится в /srv/подставной, живёт у /home/подставной/starter.\n"
        "Проект зовётся Подставной.\n", encoding="utf-8")
    (пакет / "код.py").write_text(
        'ПУТЬ = os.environ.get("PROJECT_DIR", "/srv/подставной")\n', encoding="utf-8")
    (пакет / "харнес" / "память" / "ТОН.md").write_text(
        "# ТОН\n\nЗамер речи владельца: 840 сообщений.\n", encoding="utf-8")
    (пакет / "харнес" / "шаблоны-задач" / "ТОН-заготовка.md").write_text(
        "# ТОН — как говорить с владельцем\n\n<!-- потолки: мягкий=700 жёсткий=1500 -->\n",
        encoding="utf-8")
    (пакет / "мусор.tmp").write_text("временное\n", encoding="utf-8")
    subprocess.run(["git", "-C", str(пакет), "init", "-q", "-b", "master"], check=True)
    subprocess.run(["git", "-C", str(пакет), "add", "-A"], check=True)
    subprocess.run(["git", "-C", str(пакет), "-c", "user.name=t", "-c", "user.email=t@t",
                    "commit", "-qm", "проба"], check=True)
    return пакет


def самотест() -> int:
    """Больные случаи первыми: молчаливая сборка хуже отказа."""
    путей = неудач = 0

    def проба(ок: bool, текст: str) -> None:
        nonlocal путей, неудач
        путей += 1
        неудач += 0 if ок else 1
        print(("  ок    " if ок else "  ПЛОХО ") + текст)

    with tempfile.TemporaryDirectory(prefix="самотест-сборки-") as врем:
        корень = Path(врем)
        пакет = _подставной_пакет(корень)
        куда = корень / "сборка"
        куда.mkdir()
        паспорт = {"PROJECT_DIR": "/srv/подставной", "PROJECT_NAME": "Подставной",
                   "AGENT_USER": "подставной"}
        данные = {
            "исключить": ["мусор.tmp"],
            "заменить_шаблоном": {"харнес/память/ТОН.md": "харнес/шаблоны-задач/ТОН-заготовка.md"},
            "обезличить_ключи": ["PROJECT_DIR", "PROJECT_NAME", "AGENT_USER"],
            "оставить": ["док.md", "харнес/память/ТОН.md"],
        }

        # БОЛЬНОЙ СЛУЧАЙ, ради которого написана защита: пустой довод. Path("")
        # становится «.», и rsync --delete снёс рабочее дерево (12.09.2026).
        # Проба идёт ПЕРВОЙ и из чужого каталога: попади она мимо защиты —
        # пострадал бы подставной пакет, а не проект.
        прежний = os.getcwd()
        os.chdir(пакет)
        try:
            собрать(пакет, "", данные, паспорт)
            проба(False, "БОЛЬНОЙ: пустой PUBLIC_BUILD_DIR должен быть отказом")
        except Отказ as отказ:
            проба(отказ.код == 2 and "PUBLIC_BUILD_DIR" in str(отказ),
                  "БОЛЬНОЙ: пустой PUBLIC_BUILD_DIR — код 2 и имя ключа в тексте")
        os.chdir(прежний)
        проба((пакет / "док.md").exists() and (пакет / ".git").exists(),
              "БОЛЬНОЙ: текущий каталог при пустом доводе не тронут")

        # БОЛЬНОЙ: назначение — чужое непустое дерево (второй рубеж той же беды).
        чужой = корень / "чужой"
        чужой.mkdir()
        (чужой / "важное.txt").write_text("чужая работа\n", encoding="utf-8")
        try:
            собрать(пакет, str(чужой), данные, паспорт)
            проба(False, "БОЛЬНОЙ: чужой непустой каталог должен быть отказом")
        except Отказ as отказ:
            проба(МЕТКА in str(отказ) and (чужой / "важное.txt").exists(),
                  "БОЛЬНОЙ: чужой каталог не тронут, в отказе названа метка")

        итог = собрать(пакет, str(куда), данные, паспорт)

        проба((куда / МЕТКА).exists(), "своя сборка помечена меткой")
        проба(not (куда / "мусор.tmp").exists(),
              "БОЛЬНОЙ: файл из «исключить» в сборку не попал")

        тон = (куда / "харнес" / "память" / "ТОН.md").read_text(encoding="utf-8")
        проба("потолки:" in тон and "840 сообщений" not in тон,
              "БОЛЬНОЙ: замер речи владельца подменён заготовкой с потолками")

        док = (куда / "док.md").read_text(encoding="utf-8")
        проба("${PROJECT_DIR}" in док and "/srv/подставной" not in док,
              "БОЛЬНОЙ: путь установки в документе обезличен")

        код = (куда / "код.py").read_text(encoding="utf-8")
        проба("/srv/подставной" in код,
              "БОЛЬНОЙ ОБРАТНЫЙ: в коде путь ОСТАЛСЯ (обезличивание кода запрещено)")

        проба("/home/${AGENT_USER}" in док and "/home/подставной" not in док,
              "домашний путь заменён именем ключа")
        проба("/var/www/${PROJECT_NAME}" not in док and "${PROJECT_NAME}" in док,
              "порядок замен от длинного к короткому не разорвал путь")

        (пакет / "док.md").write_text("НЕЗАКОММИЧЕНО\n", encoding="utf-8")
        собрать(пакет, str(куда), данные, паспорт)
        проба("НЕЗАКОММИЧЕНО" not in (куда / "док.md").read_text(encoding="utf-8"),
              "БОЛЬНОЙ: незакоммиченная правка пакета в сборку не уехала")

        (куда / ".git").mkdir(exist_ok=True)
        (куда / ".git" / "HEAD").write_text("ref: refs/heads/master\n", encoding="utf-8")
        (куда / "лишний-от-прошлой-сборки.md").write_text("старое\n", encoding="utf-8")
        собрать(пакет, str(куда), данные, паспорт)
        проба((куда / ".git" / "HEAD").exists()
              and not (куда / "лишний-от-прошлой-сборки.md").exists(),
              "пересборка: .git цел, файл прошлой сборки убран")

        try:
            собрать(пакет, str(куда), dict(данные, оставить=["док.md", "нет-такого.md"]), паспорт)
            проба(False, "БОЛЬНОЙ: пропажа обязательного файла должна быть отказом")
        except Отказ as отказ:
            проба("нет-такого.md" in str(отказ),
                  "БОЛЬНОЙ: пропавший файл из «оставить» назван по имени")

        try:
            собрать(пакет, str(корень / "нет-каталога"), данные, паспорт)
            проба(False, "БОЛЬНОЙ: отсутствие каталога сборки должно быть отказом")
        except Отказ as отказ:
            проба("sudo install -d" in str(отказ),
                  "БОЛЬНОЙ: в отказе про каталог названа команда починки")

        проба(итог["файлов"] > 0 and bool(итог["пакет"]),
              f"числа прогона печатаются: файлов {итог['файлов']}, пакет {итог['пакет']}")

        # Строгое чтение паспорта: окружение не хозяин тому, кто судит установку.
        образец = корень / "паспорт.conf"
        образец.write_text('PROJECT_DIR="/из-файла"\n', encoding="utf-8")
        os.environ["PROJECT_DIR"] = "/из-окружения"
        проба(из_файла(str(образец))["PROJECT_DIR"] == "/из-файла",
              "konf.из_файла берёт значение из файла, а не из окружения")
        os.environ.pop("PROJECT_DIR", None)

    if неудач:
        print("САМОТЕСТ ПРОВАЛЕН")
        return 1
    print(f"САМОТЕСТ ПРОЙДЕН: {путей} путей, первым — больной случай")
    return 0


if __name__ == "__main__":
    sys.exit(самотест() if "--selftest" in sys.argv else main())
