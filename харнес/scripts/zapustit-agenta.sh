#!/usr/bin/env bash
#
# zapustit-agenta.sh — поднять tmux-сессию С АГЕНТОМ ВНУТРИ.
#
# Откуда взят: написан 11.08.2026 по улике владельца «сессия перезагрузилась,
# но автозапуска не произошло».
#
# Что было: юнит harness-agent исполнял `tmux new-session -d -s agent` — это
# создаёт сессию с ОБОЛОЧКОЙ. Systemd рапортовал active, tmux жил, а агента в
# панели не было вовсе; работа стояла до тех пор, пока session-warden не
# заметит «в панели не claude» (AGENT_DEAD_MIN=15 мин, cron раз в 10 мин) и не
# поднимет его сам. То есть после каждой перезагрузки сервера — от 15 до 25
# минут мёртвого агента, и это считалось нормой, потому что юнит зелёный.
#
# Команда запуска берётся ТОЛЬКО из AGENT_START_CMD в harness.conf — тем же
# ключом её берёт session-warden при ротации и при подъёме выпавшего агента.
# Вписать её в юнит значило бы завести второй источник истины: после смены
# ключа в конфиге сервер поднимался бы одной командой, а сторож — другой.
#
# Идемпотентен: сессия уже есть — не трогает (в ней может работать агент).
# Чем доказывается: --selftest поднимает СВОЮ одноразовую сессию и проверяет,
# что в панели оказалась заданная команда, а не оболочка.
set -euo pipefail

INSTALL_CONF="${HARNESS_INSTALL_CONF:-/etc/harness/install.conf}"
HARNESS_CONF="${HARNESS_CONF:-/etc/harness/harness.conf}"
# Конфиги грузятся так, чтобы ОКРУЖЕНИЕ было старше файла: иначе проба с
# подставным путём судит БОЕВУЮ установку (улика 12.09.2026 — команда смены
# модели ушла в рабочую панель агента).
# shellcheck disable=SC1091
# Путь берётся по РЕАЛЬНОМУ файлу (readlink -f): pre-commit подключён в
# .git/hooks симлинком, и dirname дал бы .git/hooks, где библиотеки нет.
# Поймано первым же коммитом после правки, 12.09.2026.
source "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/lib/konf.sh"
konf_zagruzit PROJECT_DIR LOG_DIR TMUX_SESSION SECRETS_DIR AGENT_START_CMD

TMUX_SESSION="${TMUX_SESSION:-agent}"
AGENT_START_CMD="${AGENT_START_CMD:-claude --dangerously-skip-permissions}"
PROJECT_DIR="${PROJECT_DIR:-$HOME}"

raised=0

поднять() {  # имя сессии, рабочий каталог, команда
    if tmux has-session -t "$1" 2>/dev/null; then
        echo "сессия '$1' уже есть — не трогаю (в ней может работать агент)"
        return 0
    fi
    raised=1
    # Сессия поднимается С ОБОЛОЧКОЙ, а команда агента идёт в неё вводом.
    #
    # Улика 13.08.2026: владелец сидел в `tmux attach -t agent` и смотрел за
    # работой. Пришла ротация, агент вышел — а вместе с ним закрылась и сессия,
    # созданная командой (tmux убивает сессию, когда завершился её процесс, и
    # отсоединяет всех клиентов). Владельца выбросило в голый терминал посреди
    # смены; выглядело это как падение всего харнеса.
    #
    # С оболочкой выход агента возвращает панель к приглашению: сессия жива,
    # владелец остаётся внутри и видит, что происходит. Признак «агент ушёл»
    # при этом не теряется — session-warden различает оболочку в панели
    # отдельной веткой (смена_состоялась → «оболочка»), она была там всегда.
    tmux new-session -d -s "$1" -c "$2"
    tmux send-keys -t "$1" "$3" Enter
    echo "сессия '$1' поднята с оболочкой, агент запущен вводом: $3"
}

if [ "${1:-}" = "--selftest" ]; then
    command -v tmux >/dev/null 2>&1 || { echo "SELFTEST: нет tmux — поднимать нечем"; exit 1; }
    ok=1
    T=$(mktemp -d)
    S="запуск-selftest-$$"

    # БОЛЬНОЙ СЛУЧАЙ: как делал юнит до починки — сессия без команды.
    # В панели оболочка, агента нет, а systemd считает юнит поднятым.
    tmux new-session -d -s "$S-старый"
    sleep 0.5
    before=$(tmux display-message -p -t "$S-старый" '#{pane_current_command}')
    tmux kill-session -t "$S-старый" 2>/dev/null || true
    case "$before" in
        bash|sh|zsh|dash) printf '  ок    БОЛЬНОЙ СЛУЧАЙ: `tmux new-session -d -s имя` даёт «%s» в панели — агента нет\n' "$before" ;;
        *) printf '  ПЛОХО больной случай не воспроизвёлся: в панели «%s», ждали оболочку\n' "$before"; ok=0 ;;
    esac

    # ЗДОРОВЫЙ: команда доезжает в панель. Вместо claude — заведомо живущий
    # процесс: селфтест обязан проверять МЕХАНИЗМ, а не наличие подписки.
    поднять "$S" "$T" "sleep 30" >/dev/null
    sleep 0.5
    after=$(tmux display-message -p -t "$S" '#{pane_current_command}')
    [ "$after" = "sleep" ] \
        && printf '  ок    команда запуска оказалась в панели («%s»), а не оболочка\n' "$after" \
        || { printf '  ПЛОХО в панели «%s», ждали «sleep»\n' "$after"; ok=0; }

    # БОЛЬНОЙ СЛУЧАЙ 13.08.2026: сессия, СОЗДАННАЯ КОМАНДОЙ, умирает вместе с
    # процессом — и выбрасывает всех приаттаченных клиентов. Так владельца
    # вынесло из tmux в момент ротации.
    tmux new-session -d -s "$S-командой" -c "$T" "sleep 1"
    sleep 2
    if tmux has-session -t "$S-командой" 2>/dev/null; then
        printf '  ПЛОХО больной случай не воспроизвёлся: сессия, созданная командой, пережила её выход\n'; ok=0
        tmux kill-session -t "$S-командой" 2>/dev/null || true
    else
        printf '  ок    БОЛЬНОЙ СЛУЧАЙ: сессия, созданная командой, исчезла вместе с ней — клиентов бы выбросило\n'
    fi

    # ЗДОРОВЫЙ: наш способ — выход агента возвращает оболочку, сессия жива и
    # владелец в ней остаётся.
    поднять "$S-переживёт" "$T" "sleep 1" >/dev/null
    sleep 2
    if tmux has-session -t "$S-переживёт" 2>/dev/null; then
        pane_after=$(tmux display-message -p -t "$S-переживёт" '#{pane_current_command}')
        case "$pane_after" in
            bash|sh|zsh|dash) printf '  ок    выход агента вернул оболочку («%s»), сессия жива — владельца не выбрасывает\n' "$pane_after" ;;
            *) printf '  ПЛОХО сессия жива, но в панели «%s», ждали оболочку\n' "$pane_after"; ok=0 ;;
        esac
        tmux kill-session -t "$S-переживёт" 2>/dev/null || true
    else
        printf '  ПЛОХО сессия умерла вместе с агентом — владельца выбросит из tmux\n'; ok=0
    fi

    # ЗДОРОВЫЙ: рабочий каталог — тот, что заказан.
    pane_path=$(tmux display-message -p -t "$S" '#{pane_current_path}')
    [ "$pane_path" = "$T" ] \
        && printf '  ок    рабочий каталог панели — заданный\n' \
        || { printf '  ПЛОХО каталог панели «%s», ждали «%s»\n' "$pane_path" "$T"; ok=0; }

    # ЗДОРОВЫЙ: идемпотентность — повтор не убивает работающую сессию.
    поднять "$S" "$T" "sleep 30" | grep -q "уже есть" \
        && printf '  ок    повторный запуск не трогает живую сессию\n' \
        || { printf '  ПЛОХО повторный запуск не распознал живую сессию\n'; ok=0; }

    # БОЛЬНОЙ СЛУЧАЙ (12.08.2026): сессия поднята — и молчит. До правки скрипт
    # заканчивался на этом, а пинок отдавал только сторож; после «tmux слетел
    # целиком» юнит возвращал сессию за 10с, сторож заставал живого claude и
    # молчал — агент стоял у пустого приглашения при полностью исправном коде.
    printf 'TMUX_SESSION="%s-пинок"\nPROJECT_DIR="%s"\n' "$S" "$T" > "$T/install.conf"
    printf 'AGENT_START_CMD="sleep 30"\n' > "$T/harness.conf"
    вызвать_себя() {
        HARNESS_INSTALL_CONF="$T/install.conf" HARNESS_CONF="$T/harness.conf" \
            KICK_CMD="touch $T/пинок-заказан" bash "$0" >/dev/null 2>&1
        sleep 1
    }
    вызвать_себя
    [ -f "$T/пинок-заказан" ] \
        && printf '  ок    подъём НОВОЙ сессии заказывает пинок «подхвати работу»\n' \
        || { printf '  ПЛОХО сессия поднята, а пинок не заказан — агент останется у пустого приглашения\n'; ok=0; }

    # ЗДОРОВЫЙ: сессия уже была — никого не поднимали, значит и будить некого.
    rm -f "$T/пинок-заказан"
    вызвать_себя
    [ ! -f "$T/пинок-заказан" ] \
        && printf '  ок    повтор на живой сессии пинка НЕ заказывает\n' \
        || { printf '  ПЛОХО пинок ушёл в сессию, где уже кто-то работает\n'; ok=0; }
    tmux kill-session -t "$S-пинок" 2>/dev/null || true

    tmux kill-session -t "$S" 2>/dev/null || true
    rm -rf "$T"
    (( ok )) && { echo "SELFTEST: зелёный (8 путей, первый, третий и седьмой — больные случаи)"; exit 0; }
    echo "SELFTEST: КРАСНЫЙ"; exit 1
fi

поднять "$TMUX_SESSION" "$PROJECT_DIR" "$AGENT_START_CMD"

# Поднять процесс — не то же, что вернуть работу. Пока юнит перезапускался
# только по сбою, поручение свежей сессии отдавал сторож; с 11.08.2026 у
# harness-agent стоит Restart=always, и после «tmux слетел целиком» сессия
# возвращается за 10 секунд САМА (замерено пробой 12.08). Сторож приходит по
# расписанию через 10 минут, видит в панели живой claude и справедливо
# молчит — а тот стоит у пустого приглашения и не знает, что он на смене.
# Пинок отдаёт тот, кто поднял: механика — в одном месте (--kick), повтор
# гасится кулдауном внутри неё. Отвязанно и в фоне: ExecStart юнита обязан
# завершиться сразу, а пинок ждёт появления агента в панели.
KICK_CMD="${KICK_CMD:-$PROJECT_DIR/харнес/demons/session-warden.sh --kick}"
if [ "$raised" = 1 ]; then
    setsid $KICK_CMD >/dev/null 2>&1 &
    echo "пинок «подхвати работу» заказан: $KICK_CMD"
fi
