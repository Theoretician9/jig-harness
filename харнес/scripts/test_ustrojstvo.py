#!/usr/bin/env python3
"""Проверка реестра устройства: что он ловит и чего не пропускает.

Откуда взят. Владелец 11.09.2026: «Нужно прописать как работает всё в харнесе,
отдельно детально что делает каждый демон хук и тд». Спека панели §9: реестр
`харнес/config/устройство.yaml` — ОДИН источник, из которого растут документ
`docs/УСТРОЙСТВО-ХАРНЕСА.md` и пояснения на экране панели.

Одного реестра мало: список механизмов живёт в репозитории и меняется каждую
неделю (за одну смену 11.09 прибавилось шесть проверок и демон коммита памяти).
Описание, отставшее от кода, хуже отсутствующего — оно врёт с видом истины.
Поэтому сверка двусторонняя, и оба направления проверяются здесь на БОЛЬНЫХ
случаях, а не на живом репозитории: живой сегодня зелёный, а завтра другой.

Прогон:
    python3 scripts/test_ustrojstvo.py
Код возврата: 0 — все пути прошли, 1 — есть упавший.
"""
import importlib.util
import json
import shutil
import sys
import tempfile
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent


def _модуль(имя_файла: str, имя_модуля: str):
    """Импорт по пути: имена с дефисом обычным import не берутся."""
    спец = importlib.util.spec_from_file_location(
        имя_модуля, КОРЕНЬ / "scripts" / имя_файла)
    модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(модуль)
    return модуль


гейт = _модуль("check-ustrojstvo.py", "гейт_устройства")
сборщик = _модуль("sobrat-ustrojstvo.py", "сборщик_устройства")

ОК, УПАЛО = [], []


def проба(имя: str, условие: bool, подробность: str = "") -> None:
    (ОК if условие else УПАЛО).append(имя)
    знак = "✓" if условие else "✗"
    print(f"  {знак} {имя}" + (f" — {подробность}" if подробность and not условие else ""))


# ─── игрушечный репозиторий: свои механизмы, свой реестр ────────────────────
ЗАПИСЬ = {
    "файл": "харнес/demons/backup.sh",
    "вид": "демон",
    "имя": "Резервные копии",
    "роль": "Каждую ночь снимает копию рабочих данных, чтобы их можно было вернуть.",
    "когда": "каждые сутки в 03:10",
    "без_него": "Потерянные данные будет неоткуда вернуть.",
    "проверяется": "bash харнес/demons/backup.sh --selftest",
    "пишет": "копии в /var/backups/harness",
}


def двор(записи, файлы=("харнес/demons/backup.sh",)) -> Path:
    """Временный корень: перечисленные файлы существуют, реестр — из записей."""
    корень = Path(tempfile.mkdtemp(prefix="устройство-"))
    for путь in файлы:
        цель = корень / путь
        цель.parent.mkdir(parents=True, exist_ok=True)
        цель.write_text("# заглушка\n", encoding="utf-8")
    (корень / "харнес" / "config").mkdir(parents=True, exist_ok=True)
    реестр = корень / "харнес" / "config" / "устройство.yaml"
    реестр.write_text(гейт.yaml.safe_dump({"механизмы": записи}, allow_unicode=True),
                      encoding="utf-8")
    return корень


def претензии(записи, найденные, файлы=("харнес/demons/backup.sh",)):
    корень = двор(записи, файлы)
    try:
        return гейт.проверить(гейт.прочитать_реестр(корень), найденные, корень)
    finally:
        shutil.rmtree(корень, ignore_errors=True)


print("── здоровый случай ──")
проба("полная запись на существующий файл — чисто",
      претензии([ЗАПИСЬ], {"харнес/demons/backup.sh": "демон"}) == [])

print("── больные случаи: механизм без описания ──")
без_описания = претензии([ЗАПИСЬ], {
    "харнес/demons/backup.sh": "демон",
    "scripts/hooks/guard_bash.py": "хук",
}, файлы=("харнес/demons/backup.sh", "scripts/hooks/guard_bash.py"))
проба("новый механизм, которого нет в реестре — красный", len(без_описания) == 1,
      f"претензий {len(без_описания)}")
проба("претензия называет файл по имени",
      any("guard_bash.py" in с for с in без_описания))

print("── больные случаи: описание без механизма ──")
призрак = dict(ЗАПИСЬ, файл="харнес/demons/снесённый.sh")
проба("запись на удалённый файл — красная",
      any("снесённый" in с for с in претензии([призрак], {})))

print("── больные случаи: поля ──")
for поле in ("роль", "когда", "без_него", "проверяется", "пишет", "имя"):
    урезанная = {к: v for к, v in ЗАПИСЬ.items() if к != поле}
    проба(f"нет поля «{поле}» — красный",
          any(поле in с for с in претензии([урезанная],
                                           {"харнес/demons/backup.sh": "демон"})))

чужой_вид = dict(ЗАПИСЬ, вид="приблуда")
проба("вид не из перечня — красный",
      any("приблуда" in с for с in претензии([чужой_вид],
                                             {"харнес/demons/backup.sh": "демон"})))

расхождение = dict(ЗАПИСЬ, вид="скил")
проба("вид в реестре разошёлся с видом в репозитории — красный",
      any("демон" in с and "скил" in с
          for с in претензии([расхождение], {"харнес/demons/backup.sh": "демон"})))

дубль = претензии([ЗАПИСЬ, ЗАПИСЬ], {"харнес/demons/backup.sh": "демон"})
проба("один файл описан дважды — красный", any("дважды" in с for с in дубль))

print("── больные случаи: язык пояснений ──")
терминами = dict(ЗАПИСЬ, роль="Кладёт бэкап в отдельное хранилище по расписанию.")
проба("термин без расшифровки в роли — красный",
      any("бэкап" in с.lower() for с in претензии(
          [терминами], {"харнес/demons/backup.sh": "демон"})))

с_расшифровкой = dict(
    ЗАПИСЬ,
    роль="Кладёт бэкап (запасную копию данных) в отдельный каталог.")
проба("тот же термин с расшифровкой в скобках — чисто",
      претензии([с_расшифровкой], {"харнес/demons/backup.sh": "демон"}) == [])

длинная = dict(ЗАПИСЬ, роль="Копирует.")
проба("роль короче внятной фразы — красная",
      any("роль" in с for с in претензии([длинная],
                                         {"харнес/demons/backup.sh": "демон"})))

print("── сбор списка механизмов из репозитория ──")
живые = гейт.механизмы_репозитория(КОРЕНЬ)
проба("демоны найдены", живые.get("харнес/demons/backup.sh") == "демон")
проба("хуки найдены из настроек оболочки",
      живые.get("scripts/hooks/guard_bash.py") == "хук")
проба("гейты найдены из ворот",
      живые.get("scripts/check-secrets.sh") == "гейт")
проба("скилы найдены каталогами",
      живые.get("харнес/skills/приём-задачи/SKILL.md") == "скил")
проба("тестовые файлы хуков не считаются хуками",
      "scripts/hooks/test_guard_bash.py" not in живые
      or живые["scripts/hooks/test_guard_bash.py"] == "гейт")
проба("каждый найденный механизм существует на диске",
      all((КОРЕНЬ / п).exists() for п in живые))

print("── документ собирается из реестра ──")
текст = сборщик.собрать([ЗАПИСЬ])
проба("в документе есть имя механизма", "Резервные копии" in текст)
проба("в документе есть путь к файлу", "харнес/demons/backup.sh" in текст)
проба("в документе есть «что будет без него»", "неоткуда вернуть" in текст)
проба("шапка запрещает править руками", "не правится руками" in текст.lower()
      or "руками не правится" in текст.lower())

print("── документ не расходится с реестром ──")
корень = двор([ЗАПИСЬ])
try:
    (корень / "docs").mkdir(parents=True, exist_ok=True)
    документ = корень / "docs" / "УСТРОЙСТВО-ХАРНЕСА.md"
    документ.write_text(сборщик.собрать([ЗАПИСЬ]), encoding="utf-8")
    проба("собранный документ совпадает сам с собой",
          гейт.документ_разошёлся(корень) is None)
    документ.write_text(документ.read_text(encoding="utf-8") + "\nдописано руками\n",
                        encoding="utf-8")
    проба("правка документа руками — красная",
          гейт.документ_разошёлся(корень) is not None)
    документ.unlink()
    проба("документа нет вовсе — красный",
          гейт.документ_разошёлся(корень) is not None)
finally:
    shutil.rmtree(корень, ignore_errors=True)

print("── панель читает тот же реестр ──")
проба("реестр отдаётся сгруппированным по видам",
      set(сборщик.по_видам([ЗАПИСЬ])) == {"демон"})

print()
print(f"устройство: прошло {len(ОК)}, упало {len(УПАЛО)}")
if УПАЛО:
    print("упавшие: " + ", ".join(УПАЛО))
    sys.exit(1)
print(json.dumps({"проверка": "устройство", "путей": len(ОК), "упало": 0},
                 ensure_ascii=False))
