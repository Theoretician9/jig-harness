def _карточка(id_задачи):
    try:
        import yaml
        with open(КОРЕНЬ / "dev-map.yaml", encoding="utf-8") as fh:
            данные = yaml.safe_load(fh)
    except (OSError, ValueError, ImportError):
        return None

    def обход(узел):
        if isinstance(узел, dict):
            if узел.get("id") == id_задачи:
                yield узел
            for значение in узел.values():
                yield from обход(значение)
        elif isinstance(узел, list):
            for значение in узел:
                yield from обход(значение)

    найдено = list(обход(данные))
    return найдено[0] if найдено else None


def _обходы(id_задачи):
    путь = Path(os.environ.get("LOG_DIR", "/var/log/harness")) / "пайплайн-обходы.jsonl"
    строки = []
    try:
        with open(путь, encoding="utf-8") as fh:
            for строка in fh:
                запись = json.loads(строка)
                if запись.get("задача") == id_задачи:
                    строки.append(запись.get("почему", ""))
    except (OSError, ValueError):
        return []
    return строки


