#!/usr/bin/env python3
"""Цена ошибки задачи и уровень строгости пайплайна.

Откуда взят. Владелец 11.09.2026: «пайплайн контролируется по концам. Вход и
выход. Середина на честном слове <…> Всё, что можно сделать кодом, делается
кодом». И он же про перекос: «Надо походу изобрести подход по проще на задачи
по проще» — поэтому уровней три, а не одиннадцать шагов на всё.

Главное решение (находка ревью C-6). Цена считается ЗАМЕРОМ коммита, а не
полем volume.loc в карте задач: поле заполняю я сам и тем же коммитом, то есть
уровень строгости назначал бы себе тот, кому он добавляет работу. Замеры —
из `git diff --cached`, подделать их нечем.

Второе решение (C-7). Пороги — числа в конфиге, а не перцентили истории: иначе
один и тот же коммит судился бы по-разному в разное время, а доля «крупных»
была бы зафиксирована конструкцией. Пересчёт по истории — отдельная команда,
гейт её не зовёт.

Третье (C-4, C-5). Пути признаков — ДАННЫЕ установки (`MIGRATIONS_GLOB`,
`PROD_PATHS`, `GUARD_PATHS` в harness.conf). В коде харнеса ни «app», ни
«*/migrations/*» не встречается: прежние шаблоны давали ноль совпадений на
живом репозитории, а запасной вариант вшивал продукт в харнес.

Прогон:
    python3 scripts/pajplajn.py --уровень          # по текущему индексу git
    python3 scripts/pajplajn.py --состояние <id>   # что положено задаче
    python3 scripts/pajplajn.py --пересчитать-пороги
    python3 scripts/pajplajn.py --selftest
"""
