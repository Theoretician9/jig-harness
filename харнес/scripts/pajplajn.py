КОРЕНЬ = Path(__file__).resolve().parent.parent
КОНФИГ = КОРЕНЬ / "харнес" / "config" / "пайплайн.yaml"
HARNESS_CONF = os.environ.get("HARNESS_CONF", "/etc/harness/harness.conf")

# Умолчания на случай, когда конфига нет: механизм обязан работать из коробки,
# а не отказывать до настройки.
УМОЛЧАНИЯ = {
    "веса": {"миграция": 5, "код_продукта": 3, "сторож_или_гейт": 3,
             "новый_файл": 1, "за_100_строк": 1, "за_100_строк_потолок": 3,
             "за_5_файлов": 1, "за_5_файлов_потолок": 2},
    "пороги": {"П1": 3, "П2": 6},
    "строгость": {"подъём_после_истинных": 10, "подъём_после_тихих_коммитов": 20,
                  "водораздел": "2026-09-11"},
    "исключения_путей": ["scripts/", "харнес/", "docs/", "память/", ".tasks/"],
}

ШАГИ_УРОВНЯ = {
    "мелкая": (),
    "обычная": ("тесты до кода",),
    "крупная": ("спека", "ревью спеки", "тесты до кода"),
}


def конфиг(путь=КОНФИГ):
    """Пульт владельца. Нет файла или сломан — умолчания, а не отказ."""
    try:
        import yaml
        with open(путь, encoding="utf-8") as fh:
            данные = yaml.safe_load(fh) or {}
    except (OSError, ValueError, ImportError):
        return dict(УМОЛЧАНИЯ)
    слитый = dict(УМОЛЧАНИЯ)
    for ключ, значение in данные.items():
        if isinstance(значение, dict) and isinstance(слитый.get(ключ), dict):
            слитый[ключ] = {**слитый[ключ], **значение}
        else:
            слитый[ключ] = значение
    return слитый


def пути_установки(путь=HARNESS_CONF):
    """(шаблон миграций, пути прода, пути сторожей) — данные, не код."""
    значения = {"MIGRATIONS_GLOB": "", "PROD_PATHS": "", "GUARD_PATHS": ""}
    try:
        текст = Path(путь).read_text(encoding="utf-8")
    except OSError:
        return значения
    for ключ in значения:
        совпадение = re.search(rf'^{ключ}="?([^"#\n]*)"?', текст, re.M)
        if совпадение:
            значения[ключ] = совпадение.group(1).strip()
    return значения


def _под_путями(путь: str, список: str) -> bool:
    """Путь начинается с одного из префиксов (пробел — разделитель)."""
    return any(путь.startswith(префикс) for префикс in список.split() if префикс)


def признаки_коммита(staged=None, пути=None):
    """Что видно в индексе git: строки, файлы, миграция, прод, сторож, новизна."""
    пути = пути if пути is not None else пути_установки()
    if staged is None:
        staged = _индекс()
    строк = sum(запись["добавлено"] for запись in staged)
    имена = [запись["путь"] for запись in staged]
    шаблон = пути.get("MIGRATIONS_GLOB", "")
    return {
        "строк": строк,
        "файлов": len(имена),
        "миграция": bool(шаблон) and any(fnmatch.fnmatch(и, шаблон) for и in имена),
        "код_продукта": _под_путями_любой(имена, пути.get("PROD_PATHS", "")),
        "сторож_или_гейт": _под_путями_любой(имена, пути.get("GUARD_PATHS", "")),
        "новый_файл": any(запись["новый"] for запись in staged),
    }


def _под_путями_любой(имена, список):
    return any(_под_путями(имя, список) for имя in имена)


def _индекс(корень=None):
    """Записи индекса git: путь, добавленные строки, признак нового файла.

    `core.quotepath=false` обязателен: иначе git отдаёт кириллические пути
    экранированными восьмеричными байтами («\\321\\205...»), и признаки по
    путям слепнут ровно там, где половина этого репозитория. Поймано живым
    прогоном 11.09: правка сторожей не дала признака «сторож_или_гейт».
    """
    общее = ["git", "-C", str(корень or КОРЕНЬ), "-c", "core.quotepath=false"]
    try:
        numstat = subprocess.run(
            общее + ["diff", "--cached", "--numstat"],
            capture_output=True, text=True, timeout=30).stdout
        новые = set(subprocess.run(
            общее + ["diff", "--cached", "--name-only", "--diff-filter=A"],
            capture_output=True, text=True, timeout=30).stdout.split("\n"))
    except (OSError, subprocess.SubprocessError):
        return []
    записи = []
    for строка in numstat.splitlines():
        части = строка.split("\t")
        if len(части) != 3:
            continue
        добавлено = int(части[0]) if части[0].isdigit() else 0
        записи.append({"путь": части[2], "добавлено": добавлено,
                       "новый": части[2] in новые})
    return записи


СОСТОЯНИЕ = Path(os.environ.get("LOG_DIR", "/var/log/harness")) / "пайплайн-состояние.json"


def состояние(путь=None):
    """Машинное состояние гейтов: счётчики и строгость. ВНЕ репозитория.

    Конфиг-пульт лежит в харнес/config/ и сторожится сверкой с пакетом — каждая
    машинная запись туда разводила бы проект и пакет (находка ревью I-1).
    Поэтому считанное машиной живёт в LOG_DIR, а человек правит только конфиг.
    """
    try:
        with open(путь or СОСТОЯНИЕ, encoding="utf-8") as fh:
            return json.load(fh)
    except (OSError, ValueError):
        return {}


def отметить_прогон(гейт, находок, путь=None):
    """Прогон жёлтого гейта: копим тихие коммиты и находки.

    Возвращает (строгость, сменилась ли). Подъём — не по молчанию: «ноль
    находок за N коммитов» доказывает, что гейт молчал, а не что он прав
    (находка C-3). Поэтому два пути: N тихих коммитов ПОДРЯД либо N находок,
    признанных истинными при разборе.
    """
    путь = путь or СОСТОЯНИЕ
    данные = состояние(путь)
    свои = данные.setdefault(гейт, {"тихих": 0, "истинных": 0, "строгость": "жёлтый"})
    свои["тихих"] = свои["тихих"] + 1 if not находок else 0
    настройки = конфиг().get("строгость") or {}
    порог_тихих = настройки.get("подъём_после_тихих_коммитов", 20)
    порог_истинных = настройки.get("подъём_после_истинных", 10)
    было = свои["строгость"]
    if было != "красный" and (свои["тихих"] >= порог_тихих
                              or свои["истинных"] >= порог_истинных):
        свои["строгость"] = "красный"
    try:
        путь.parent.mkdir(parents=True, exist_ok=True)
        with open(путь, "w", encoding="utf-8") as fh:
            json.dump(данные, fh, ensure_ascii=False, indent=1)
    except OSError:
        pass
    return свои["строгость"], свои["строгость"] != было


def признаки_задачи(id_задачи, корень=None):
    """Признаки ВСЕХ коммитов задачи — по трейлеру «Dev-Map: <id>».

    Нужны закрытию: уровень задачи нельзя брать из volume.loc (самоотчёт), а
    один коммит показывает только свою часть работы. Здесь складывается то, что
    задача сделала на самом деле.
    """
    корень = корень or КОРЕНЬ
    общее = ["git", "-C", str(корень), "-c", "core.quotepath=false"]
    try:
        шапки = subprocess.run(
            общее + ["log", "--format=%H", f"--grep=^Dev-Map: {id_задачи}$", "--extended-regexp"],
            capture_output=True, text=True, timeout=60).stdout.split()
    except (OSError, subprocess.SubprocessError):
        return None
    if not шапки:
        return None
    записи = []
    for sha in шапки:
        try:
            вывод = subprocess.run(общее + ["show", "--numstat", "--format=", "-r", sha],
                                   capture_output=True, text=True, errors="replace",
                                   timeout=60).stdout
        except (OSError, subprocess.SubprocessError):
            continue
        for строка in вывод.splitlines():
            части = строка.split("\t")
            if len(части) != 3:
                continue
            записи.append({"путь": части[2],
                           "добавлено": int(части[0]) if части[0].isdigit() else 0,
                           "новый": False})
    признаки = признаки_коммита(staged=записи)
    признаки["коммитов"] = len(шапки)
    return признаки


def цена(признаки, веса):
    """Чистая функция: признаки коммита → число. Её и проверяет самотест."""
    итог = 0
    if признаки.get("миграция"):
        итог += веса["миграция"]
    if признаки.get("код_продукта"):
        итог += веса["код_продукта"]
    if признаки.get("сторож_или_гейт"):
        итог += веса["сторож_или_гейт"]
    if признаки.get("новый_файл"):
        итог += веса["новый_файл"]
    итог += min(признаки.get("строк", 0) // 100 * веса["за_100_строк"],
                веса["за_100_строк_потолок"])
    итог += min(признаки.get("файлов", 0) // 5 * веса["за_5_файлов"],
                веса["за_5_файлов_потолок"])
    return итог


def уровень(значение_цены, пороги):
    if значение_цены >= пороги["П2"]:
        return "крупная"
    if значение_цены >= пороги["П1"]:
        return "обычная"
    return "мелкая"


def почему(признаки, веса):
    """Строка «какие признаки дали цену» — для отчёта владельцу и гейта."""
    части = []
    for ключ, подпись in (("миграция", "миграция"),
                          ("код_продукта", "код продукта"),
                          ("сторож_или_гейт", "сторож или гейт"),
                          ("новый_файл", "новый файл")):
        if признаки.get(ключ):
            части.append(f"{подпись} +{веса[ключ]}")
    за_строки = min(признаки.get("строк", 0) // 100 * веса["за_100_строк"],
                    веса["за_100_строк_потолок"])
    if за_строки:
        части.append(f"{признаки['строк']} строк +{за_строки}")
    за_файлы = min(признаки.get("файлов", 0) // 5 * веса["за_5_файлов"],
                   веса["за_5_файлов_потолок"])
    if за_файлы:
        части.append(f"{признаки['файлов']} файлов +{за_файлы}")
    return ", ".join(части) or "признаков риска нет"


# ── Самотест: пороги ВШИТЫ, иначе критерий зависел бы от живой истории ──────
ТЕСТОВЫЕ_ВЕСА = УМОЛЧАНИЯ["веса"]
ТЕСТОВЫЕ_ПОРОГИ = УМОЛЧАНИЯ["пороги"]


def самотест():
    случаи = [
        # (признаки, ждём уровень, чем случай важен)
        ({"строк": 1, "файлов": 1, "миграция": True, "код_продукта": True},
         "крупная",
         "БОЛЬНОЙ СЛУЧАЙ: миграция в одну строку — крупная, объём ни при чём"),
        ({"строк": 40, "файлов": 1, "код_продукта": False},
         "мелкая", "40 строк в одном файле — мелкая, лишних шагов не требуем"),
        ({"строк": 40, "файлов": 1, "сторож_или_гейт": True},
         "обычная", "правка сторожа — обычная: тесты до кода"),
        ({"строк": 0, "файлов": 0},
         "мелкая", "пустой коммит — мелкая, а не отказ"),
        ({"строк": 900, "файлов": 30, "код_продукта": True, "новый_файл": True},
         "крупная", "широкая правка продукта — крупная"),
        ({"строк": 100000, "файлов": 900},
         "обычная",
         "БОЛЬНОЙ СЛУЧАЙ: один объём без риска не делает задачу крупной (потолки)"),
    ]
    ok = True
    for признаки, ждём, зачем in случаи:
        получилось = уровень(цена(признаки, ТЕСТОВЫЕ_ВЕСА), ТЕСТОВЫЕ_ПОРОГИ)
        if получилось != ждём:
            ok = False
            print(f"  ПЛОХО {зачем}: вышло «{получилось}», ждали «{ждём}»")
        else:
            print(f"  ок    {зачем}")

    # Отдельный путь: в коде харнеса не должно быть имени продукта.
    свой_текст = Path(__file__).read_text(encoding="utf-8")
    без_шапки = свой_текст.split('"""', 2)[-1]
    имя_продукта = "kt" + "ek"   # собрано из частей: иначе проверка ловит сама себя
    if имя_продукта in без_шапки.lower():
        ok = False
        print("  ПЛОХО имя продукта попало в код харнеса — пути обязаны быть данными")
    else:
        print("  ок    БОЛЬНОЙ СЛУЧАЙ: имени продукта в коде нет, пути берутся из конфига")

    # БОЛЬНОЙ СЛУЧАЙ, пойманный живым прогоном: путь кириллицей.
    import tempfile
    with tempfile.TemporaryDirectory() as каталог:
        база = Path(каталог)
        (база / "харнес").mkdir()
        (база / "харнес" / "проба.txt").write_text("строка\n", encoding="utf-8")
        тихо = {"capture_output": True, "text": True, "timeout": 30}
        subprocess.run(["git", "-C", каталог, "init", "-q"], **тихо)
        subprocess.run(["git", "-C", каталог, "add", "-A"], **тихо)
        пути_в_индексе = [з["путь"] for з in _индекс(корень=база)]
    if пути_в_индексе == ["харнес/проба.txt"]:
        print("  ок    БОЛЬНОЙ СЛУЧАЙ: путь кириллицей читается, а не байтами \\321\\205")
    else:
        ok = False
        print(f"  ПЛОХО путь кириллицей: получили {пути_в_индексе}")

    # Автоподъём строгости: 20 тихих прогонов подряд поднимают гейт, находка
    # счётчик сбрасывает. Не «молчал N раз — значит прав», а «не мешал N раз —
    # можно доверить»; второй путь подъёма (истинные находки) — в конфиге.
    import tempfile as _tempfile
    with _tempfile.TemporaryDirectory() as каталог_с:
        файл = Path(каталог_с) / "состояние.json"
        подъём_на = None
        for номер in range(1, 25):
            _, сменилась = отметить_прогон("проба", [], файл)
            if сменилась:
                подъём_на = номер
        если_находка, _ = отметить_прогон("проба2", ["модуль.py"], файл)
        сброшено = состояние(файл)["проба2"]["тихих"] == 0
    if подъём_на == 20 and сброшено:
        print("  ок    БОЛЬНОЙ СЛУЧАЙ: гейт взрослеет на 20-м тихом прогоне, "
              "находка счётчик сбрасывает")
    else:
        ok = False
        print(f"  ПЛОХО автоподъём: подъём на {подъём_на}, сброс {сброшено}")

    # Конфига нет — работаем на умолчаниях, а не отказываем.
    пусто = конфиг(путь="/заведомо/нет/такого.yaml")
    if пусто["пороги"] == УМОЛЧАНИЯ["пороги"]:
        print("  ок    без конфига механизм работает на умолчаниях")
    else:
        ok = False
        print("  ПЛОХО без конфига пороги разъехались")

    print("САМОТЕСТ %s: %d путей, первым — больной случай"
          % ("ПРОЙДЕН" if ok else "ПРОВАЛЕН", len(случаи) + 4))
    return 0 if ok else 1


def состояние_задачи(id_задачи):
    """М6: что положено задаче, что пройдено и ЧЕМ доказано.

    Владелец 11.09: «мне нужен какой то слой управления, где я могу управлять
    принципом работы модели, чему код ее заставляет следовать». Пульт —
    конфиг; эта команда — окно в него: видно не мнение, а признаки и файлы.
    """
    настройки = конфиг()
    признаки = признаки_задачи(id_задачи)
    if признаки is None:
        print(f"[пайплайн] у задачи {id_задачи} ещё нет коммитов с трейлером Dev-Map")
        return 0
    значение = цена(признаки, настройки["веса"])
    имя = уровень(значение, настройки["пороги"])
    print(f"задача: {id_задачи}")
    print(f"уровень: {имя} (цена {значение}) — {почему(признаки, настройки['веса'])}")
    print(f"коммитов задачи: {признаки.get('коммитов', 0)}, "
          f"добавлено строк: {признаки['строк']}, файлов: {признаки['файлов']}")
    карточка = _карточка(id_задачи)
    спека = (карточка or {}).get("spec")
    for шаг in ШАГИ_УРОВНЯ[имя]:
        if шаг == "спека":
            есть = bool(спека) and (КОРЕНЬ / спека).exists()
            print(f"  спека: {'есть — ' + спека if есть else 'НЕТ (поле spec: в карточке)'}")
        elif шаг == "ревью спеки":
            путь = (КОРЕНЬ / спека) if спека else None
            ревью = путь.with_name(путь.stem + "-REVIEW" + путь.suffix) if путь else None
            print(f"  ревью спеки: {'есть — ' + str(ревью.relative_to(КОРЕНЬ)) if ревью and ревью.exists() else 'НЕТ'}")
        else:
            print(f"  {шаг}: судит гейт check-tests-first по каждому коммиту")
