#!/usr/bin/env python3
"""Данные публичной сборки означают то, что обещает спека.

Почему тест на файл данных: сборщик верит ему без разбора. Ключ обезличивания,
которого нет в паспорте, — молчаливая пустая замена; путь в «оставить», которого
нет в пакете, — отказ на каждой сборке; литерал нашей установки внутри файла —
красный гейт навсегда (файл сам едет в сборку, ревью спеки №2).

Прогон: python3 scripts/test_publichnaya_sborka.py
"""
import os
import re
import sys
from pathlib import Path

import yaml

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "scripts" / "lib"))
from konf import конфиг  # noqa: E402

ДАННЫЕ = КОРЕНЬ / "харнес" / "config" / "публичная-сборка.yaml"
путей = неудач = 0


def путь(ок: bool, текст: str) -> None:
    global путей, неудач
    путей += 1
    неудач += 0 if ок else 1
    print(("  ок    " if ок else "  ПЛОХО ") + текст)


паспорт = конфиг()
паспорт.update(конфиг("/etc/harness/harness.conf"))
ПАКЕТ = Path(os.environ.get("HARNESS_STARTER")
             or f"/home/{паспорт['AGENT_USER']}/starter/СТАРТОВЫЙ-ПАКЕТ")

if not ДАННЫЕ.is_file():
    print(f"  ПЛОХО файла данных нет: {ДАННЫЕ}")
    print("ДАННЫЕ СБОРКИ: путей 1, неудач 1")
    sys.exit(1)

текст = ДАННЫЕ.read_text(encoding="utf-8")
данные = yaml.safe_load(текст) or {}

# БОЛЬНОЙ СЛУЧАЙ первым: значение любого ключа паспорта внутри файла данных —
# гейт чистоты найдёт его в сборке на каждой публикации, и красным он будет
# всегда, потому что файл данных едет в сборку вместе со сборщиком.
литералы = [к for к in ("PROJECT_DIR", "PROJECT_NAME", "TG_CHAT_ID", "PRODUCT_DIR")
            if паспорт.get(к) and паспорт[к] in текст]
путь(not литералы, f"в файле данных нет значений паспорта {литералы or ''}")

for раздел in ("исключить", "заменить_шаблоном", "обезличить_ключи", "оставить"):
    путь(раздел in данные, f"раздел «{раздел}» объявлен")

for ключ in данные.get("обезличить_ключи") or []:
    путь(bool(паспорт.get(ключ)), f"ключ {ключ} есть в паспорте и непуст")

for файл, шаблон in (данные.get("заменить_шаблоном") or {}).items():
    есть = (ПАКЕТ / шаблон).is_file()
    путь(есть, f"шаблон {шаблон} лежит в пакете")
    потолки = bool(re.search(r"<!--\s*потолки:\s*мягкий=\d+\s+жёсткий=\d+\s*-->",
                             (ПАКЕТ / шаблон).read_text(encoding="utf-8"))) if есть else False
    # Без машинной строки check-perepiska.py берёт запасные числа молча, а
    # @-импорт CLAUDE.md остаётся битым: заменять файл пустышкой нельзя.
    путь(потолки, f"в шаблоне {шаблон} есть машинная строка потолков")
    путь((ПАКЕТ / файл).exists(), f"заменяемый {файл} существует в пакете")

for файл in данные.get("оставить") or []:
    путь((ПАКЕТ / файл).exists(), f"«оставить» {файл} существует в пакете")

# «@STATE.md» и «@./память/ТОН.md» — обе законные формы: regex с обязательной
# точкой терял первую, и битый импорт STATE.md тест бы не заметил.
импорты = re.findall(r"^@(?:\./)?(.+)$",
                     (ПАКЕТ / "харнес" / "CLAUDE.md").read_text(encoding="utf-8"), re.M)
оставить = данные.get("оставить") or []
битые = [и for и in импорты if f"харнес/{и}" not in оставить]
путь(not битые, f"каждый @-импорт CLAUDE.md пакета стоит в «оставить» ({len(импорты)}) {битые or ''}")

print(f"ДАННЫЕ СБОРКИ: путей {путей}, неудач {неудач}")
sys.exit(1 if неудач else 0)
