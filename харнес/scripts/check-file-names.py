#!/usr/bin/env python3
"""Гейт: НОВЫЕ файлы кода называются латиницей.

Откуда взят. Владелец 11.09.2026: «А почему у нас вообще файлы с русскими
именами появляются, мы можем это тотально системно исправить». Правило проекта
всегда говорило то же («Технические термины и имена в коде — в оригинале»), но
носителя у него не было, и за месяц набралось 1118 путей с кириллицей из 1442,
из них 500 — код.

Чем это платится, замер того же дня: git отдаёт такие пути экранированными
байтами («\\321\\205\\320\\260...»), и любая проверка по путям слепнет — так
новый гейт цены задачи не увидел правку сторожей, хотя она была прямо в
индексе. В памяти проекта четыре записи про кириллицу в именах, в журнале
пропусков — две.

Гейт судит ТОЛЬКО добавляемые файлы кода: переименование 500 существующих
трогает прод (импорты по имени, тесты, миграции) и решается владельцем
отдельно. Документы, данные и каталоги задач не касается — там русское имя
уместно и ничего не ломает.

Судятся ДОБАВЛЯЕМЫЕ и ПЕРЕИМЕНОВЫВАЕМЫЕ файлы. Про второе пришлось узнать от
ревьюера: `git mv` отдаёт статус `R`, а гейт смотрел только `A` — 601
переименование прошло бы мимо, и работа по переводу имён осталась бы без
доказательства (находка I-3 ревью спеки 11.09).

Прогон:
    git diff --cached --name-only --diff-filter=AR | python3 scripts/check-file-names.py
    python3 scripts/check-file-names.py --selftest
Код возврата: 0 — чисто, 1 — есть новый файл кода с нелатинским именем.
"""
import json
import os
import re
import sys
from pathlib import Path

# Расширения, где имя файла становится именем модуля или целью импорта.
# Данные, а не код: у проекта на Go или Java список другой, и правило обязано
# работать там без правки харнеса. Ключ CODE_NAME_EXTS в harness.conf.
КОД_ПО_УМОЛЧАНИЮ = (".py", ".sh", ".ts", ".tsx", ".js", ".jsx", ".sql",
                    ".go", ".rs", ".java", ".kt", ".rb", ".php", ".c", ".h",
                    ".cpp", ".cs", ".swift")
НЕ_ЛАТИНИЦА = re.compile(r"[^\x00-\x7F]")
HARNESS_CONF = os.environ.get("HARNESS_CONF", "/etc/harness/harness.conf")


def расширения_кода(путь=HARNESS_CONF):
    """Что на этой установке считается кодом. Нет ключа — вшитый список."""
    try:
        текст = Path(путь).read_text(encoding="utf-8")
    except OSError:
        return КОД_ПО_УМОЛЧАНИЮ
    найдено = re.search(r'^CODE_NAME_EXTS="?([^"#\n]*)"?', текст, re.M)
    если_задано = (найдено.group(1).strip() if найдено else "")
    if not если_задано:
        return КОД_ПО_УМОЛЧАНИЮ
    return tuple(ч if ч.startswith(".") else "." + ч for ч in если_задано.split())


def находки(пути, код=None):
    """Новые файлы кода с нелатинским именем. Чистая функция — её и проверяем."""
    код = код or КОД_ПО_УМОЛЧАНИЮ
    плохие = []
    for путь in пути:
        путь = путь.strip().strip('"')
        if not путь or not путь.endswith(код):
            continue
        if НЕ_ЛАТИНИЦА.search(Path(путь).name):
            плохие.append(путь)
    return плохие


def самотест():
    случаи = [
        # (пути, сколько находок, чем случай важен)
        (["app/lib/район.py"], 1,
         "БОЛЬНОЙ СЛУЧАЙ: новый модуль кириллицей — находка"),
        (["scripts/пайплайн.sh"], 1, "скрипт кириллицей — находка"),
        (["docs/specs/2026-09-11-пайплайн.md"], 0,
         "документ кириллицей — не наше дело, там русское имя уместно"),
        (["app/lib/area.py"], 0, "латинское имя — чисто"),
        (["данные/район.yaml"], 0, "данные кириллицей — не код, молчим"),
        (["app/lib/район/__init__.py"], 0,
         "БОЛЬНОЙ СЛУЧАЙ: кириллица в КАТАЛОГЕ, а не в имени файла — здесь не судим"),
        ([""], 0, "пустая строка списка не роняет гейт"),
    ]
    ok = True
    for пути, ждём, зачем in случаи:
        вышло = len(находки(пути))
        if вышло != ждём:
            ok = False
            print(f"  ПЛОХО {зачем}: находок {вышло}, ждали {ждём}")
        else:
            print(f"  ок    {зачем}")
    # Второй носитель правила: хук на момент создания файла. Проверяется
    # ПОДПРОЦЕССОМ — иначе проверялась бы функция, а не то, что увидит оболочка.
    import subprocess
    хук_случаи = [
        ('{"tool_name":"Write","tool_input":{"file_path":"app/lib/район.py"}}', 2,
         "БОЛЬНОЙ СЛУЧАЙ: хук отказывает при создании модуля кириллицей"),
        ('{"tool_name":"Write","tool_input":{"file_path":"app/lib/area.py"}}', 0,
         "хук пропускает латинское имя"),
        ('{"tool_name":"Write","tool_input":{"file_path":"docs/спека.md"}}', 0,
         "хук не трогает документ кириллицей"),
        ("не json", 0, "битая нагрузка не мешает работать"),
        ('{"tool_name":"Write","tool_input":{}}', 0, "вызов без пути — молчим"),
    ]
    for нагрузка, ждём, зачем in хук_случаи:
        итог = subprocess.run([sys.executable, __file__, "--hook"],
                              input=нагрузка, capture_output=True, text=True)
        if итог.returncode != ждём:
            ok = False
            print(f"  ПЛОХО {зачем}: код {итог.returncode}, ждали {ждём}")
        else:
            print(f"  ок    {зачем}")

    # БОЛЬНОЙ СЛУЧАЙ, найденный ревью (I-3): git mv отдаёт статус R, и гейт со
    # старым фильтром --diff-filter=A переименование НЕ ВИДИТ. Проверяется на
    # настоящем временном репозитории, а не рассуждением.
    import tempfile
    with tempfile.TemporaryDirectory() as каталог:
        тихо = {"capture_output": True, "text": True, "timeout": 30}
        subprocess.run(["git", "-C", каталог, "init", "-q", "."], **тихо)
        subprocess.run(["git", "-C", каталог, "config", "user.email", "a@b"], **тихо)
        subprocess.run(["git", "-C", каталог, "config", "user.name", "a"], **тихо)
        Path(каталог, "module.py").write_text("x = 1\n", encoding="utf-8")
        subprocess.run(["git", "-C", каталог, "add", "-A"], **тихо)
        subprocess.run(["git", "-C", каталог, "commit", "-qm", "init"], **тихо)
        subprocess.run(["git", "-C", каталог, "mv", "module.py", "модуль.py"], **тихо)
        subprocess.run(["git", "-C", каталог, "add", "-A"], **тихо)
        общее = ["git", "-C", каталог, "-c", "core.quotepath=false",
                 "diff", "--cached", "--name-only"]
        только_a = subprocess.run(общее + ["--diff-filter=A"], **тихо).stdout.split()
        и_переимен = subprocess.run(общее + ["--diff-filter=AR"], **тихо).stdout.split()
    if not только_a and находки(и_переимен):
        print("  ок    БОЛЬНОЙ СЛУЧАЙ: переименование в кириллицу видно только с фильтром AR")
    else:
        ok = False
        print(f"  ПЛОХО переименование: A={только_a}, AR={и_переимен}")

    print("САМОТЕСТ %s: %d путей, первым — больной случай"
          % ("ПРОЙДЕН" if ok else "ПРОВАЛЕН", len(случаи) + len(хук_случаи) + 1))
    return 0 if ok else 1


ПОЧЕМУ = ("Имя файла с кодом — латиницей, цифрами и дефисом. Кириллический "
          "путь git отдаёт байтами (\\321\\205...), и любая проверка по путям "
          "слепнет. Русский остаётся ВНУТРИ файла: в тексте, комментариях, данных.")


def режим_хука():
    """PreToolUse на Write/Edit: отказать В МОМЕНТ создания файла, а не на коммите.

    Два носителя у одного правила — не роскошь: гейт видит только коммит, и до
    него успевает появиться модуль с сотней строк и импортами. Правило,
    перекрытое одним путём из двух, обходится вторым — это уже случалось.
    Отказ хука — код 2 и причина в stderr (так же устроен guard_bash).
    """
    try:
        нагрузка = json.loads(sys.stdin.read())
    except ValueError:
        return 0                      # не разобрали — не мешаем работать
    путь = (нагрузка.get("tool_input") or {}).get("file_path") or ""
    if not путь or not находки([путь], расширения_кода()):
        return 0
    print(f"Имя файла кода с нелатинскими знаками: {путь}\n{ПОЧЕМУ}", file=sys.stderr)
    return 2


def main():
    if "--selftest" in sys.argv:
        return самотест()
    if "--hook" in sys.argv:
        return режим_хука()
    плохие = находки(sys.stdin.read().splitlines(), расширения_кода())
    if not плохие:
        print("[имена файлов] новые файлы кода названы латиницей")
        return 0
    print("[имена файлов] новый файл кода с нелатинским именем:")
    for путь in плохие:
        print(f"    {путь}")
    print(f"    {ПОЧЕМУ}")
    return 1


if __name__ == "__main__":
    sys.exit(main())
