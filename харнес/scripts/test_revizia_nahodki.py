#!/usr/bin/env python3
"""Сверка карты после агента ревизии: пропажа, дубль, потолок, устаревшие.

Почему каждый путь: «удалил 5, завёл 12 — счёт зелёный» (C-10 ревью спеки) —
поэтому множество id; агент по промпту дубли не ловит (I-11²) — поэтому ключ и
скрипт; потолок находок словами промпта не держится (I-14) — поэтому арифметика.

Прогон: python3 scripts/test_revizia_nahodki.py
"""
import datetime
import importlib.util
import sys
from pathlib import Path

import yaml

КОРЕНЬ = Path(__file__).resolve().parent.parent
спец = importlib.util.spec_from_file_location("находки", КОРЕНЬ / "scripts" / "revizia-nahodki.py")
находки = importlib.util.module_from_spec(спец)
спец.loader.exec_module(находки)
путей = неудач = 0


def проба(имя, ждём, вышло):
    global путей, неудач
    путей += 1
    if вышло == ждём:
        print(f"  ок    {имя}")
    else:
        неудач += 1
        print(f"  ПЛОХО {имя}: ждали {ждём!r}, вышло {вышло!r}")


def карточка(ид, ключ=None, статус="plan", длина=40, заведено=None):
    поля = [f"      - id: {ид}", f"        status: {статус}",
            f'        title: "{ид}"', f'        summary: "{"x" * длина}"']
    if ключ:
        поля.insert(2, f"        источник: {ключ}")
    if заведено:
        поля.insert(2, f'        заведено: "{заведено}"')
    return "\n".join(поля) + "\n"


ШАПКА = "version: 1\nlines:\n  - id: harness\n    layer: infra\n    name: \"Ядро\"\n    tasks:\n"
СТАРАЯ = карточка("hr.старая", "ревизия:архитектура:scripts/a.sh:дубль механизма", заведено="2026-01-01")
ДО = ШАПКА + карточка("hr.живая", "inbox:1.0") + СТАРАЯ

# ── БОЛЬНОЙ СЛУЧАЙ: пропал id, но новых больше — счёт вырос, а задача исчезла
после = ШАПКА + СТАРАЯ + карточка("hr.н1", "ревизия:а:f:один") + карточка("hr.н2", "ревизия:а:f:два")
итог = находки.сверить(ДО, после, 12, 1500)
проба("БОЛЬНОЙ СЛУЧАЙ: пропавший id назван, хотя карточек стало больше", ["hr.живая"], итог["пропавшие"])
проба("при пропаже карта не переписывается", после, итог["текст"])

# ── дубль по ключу с картой «до» и дубль внутри новых
после = ДО + карточка("hr.н1", "ревизия:архитектура:scripts/a.sh:дубль механизма") \
           + карточка("hr.н2", "ревизия:б:g:новое") + карточка("hr.н3", "ревизия:б:g:новое")
итог = находки.сверить(ДО, после, 12, 1500)
проба("БОЛЬНОЙ СЛУЧАЙ: та же находка второй раз не заводится", ["hr.н1", "hr.н3"], итог["дубли"])
проба("остаётся одна новая", 1, итог["новых"])
проба("вычеркнутых в тексте нет", False, "hr.н1" in итог["текст"] or "hr.н3" in итог["текст"])

# ── потолок находок арифметикой, карточка без ключа, длинная карточка, статус
после = ДО + "".join(карточка(f"hr.н{i}", f"ревизия:в:h:{i}") for i in range(4)) \
           + карточка("hr.безключа") + карточка("hr.длинная", "ревизия:в:h:длинная", длина=2000) \
           + карточка("hr.wip", "ревизия:в:h:wip", статус="wip")
итог = находки.сверить(ДО, после, 3, 500)
проба("сверх потолка 3 — лишние вычеркнуты поимённо", ["hr.н3", "hr.wip"], итог["сверх_потолка"])
проба("карточка без ключа вычеркнута", ["hr.безключа"], итог["без_ключа"])
проба("карточка длиннее потолка вычеркнута", ["hr.длинная"], итог["длинные"])
проба("новых ровно потолок", 3, итог["новых"])
проба("счёт по областям", {"в": 3}, итог["по_областям"])
проба("результат — валидный YAML", True, isinstance(yaml.safe_load(итог["текст"]), dict))

# ── статус новой карточки принудительно plan; изменённая старая возвращается
после = ДО.replace('title: "hr.живая"', 'title: "переписал агент"') + карточка("hr.н1", "ревизия:а:f:x", статус="wip")
итог = находки.сверить(ДО, после, 12, 1500)
проба("изменённая чужая карточка возвращена из «до»", True,
      'title: "hr.живая"' in итог["текст"] and ["hr.живая"] == итог["изменённые"])
проба("новая карточка получает status: plan", True, "status: wip" not in итог["текст"])

# ── устаревшие находки
сегодня = datetime.date(2026, 6, 1)
проба("находка старше срока названа", ["hr.старая"], находки.устаревшие(ДО, 90, сегодня))
проба("свежая находка не трогается", [], находки.устаревшие(ДО, 90, datetime.date(2026, 2, 1)))
проба("карточка не из ревизии сроком не судится", [],
      находки.устаревшие(ШАПКА + карточка("hr.x", "inbox:1.0", заведено="2020-01-01"), 90, сегодня))

print(f"СВЕРКА НАХОДОК: путей {путей}, неудач {неудач}")
sys.exit(1 if неудач else 0)
